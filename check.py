"""Самопроверка прототипа. Запускать после любой правки:

    python check.py                 — всё сразу (около двух минут)
    python check.py --прогонов 40   — глубже
    python check.py --золотой       — перезаписать эталон осознанно

Проверяет шесть вещей:
  1. данные          — balance.json, npcs.json, events.json не противоречат коду;
  2. ручки           — каждая ручка баланса читается кодом, и код не читает
                       того, чего в balance.json нет;
  3. инварианты      — то, что обязано быть верно в конце каждого дня;
     баланс ресурсов — приход минус расход сходится до последней банки;
  4. покрытие        — нет ли действий, которые ни разу не предлагаются;
  5. детерминизм     — одно зерно даёт один и тот же прогон, в том числе
                       в другом процессе с другим PYTHONHASHSEED;
  6. эталон          — поведение не изменилось незаметно (золотой прогон):
                       24 зерна, отпечаток каждого дня, и расхождение
                       называется зерном и днём, а не «где-то в прогоне».

Возвращает код 1, если что-то не так, — чтобы это можно было повесить на хук.

Правило для правок структуры (аудит_архитектуры.md, шаг 0): один шаг —
одна правка, и `python check.py` зелёный без `--золотой`. Если шаг переставляет
вызовы rng или меняет строку журнала, это отдельный коммит с осознанным
`--золотой` и записью в ПЛАН.md о том, почему эталон изменился.
"""
