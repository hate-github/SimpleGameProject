def _канон(x):
    """Одно и то же состояние — одна и та же строка, в любом процессе.

    Множества и словари сортируются: порядок строк в set зависит
    от PYTHONHASHSEED, и без этого отпечаток плыл бы от запуска к запуску.
    Числа с плавающей точкой округляются до шестого знака. Ссылка на жильца
    или кладовую сворачивается в его id: сам он снимается отдельно.
    """
    if isinstance(x, enum.Enum):
        return x.value                  # StrEnum — та же строка, что и была в снимке
    if isinstance(x, bool) or x is None or isinstance(x, (int, str)):
        return x
    if isinstance(x, float):
        v = round(x, 6)
        return 0.0 if v == 0 else v
    if isinstance(x, dict):
        return sorted(((_канон(k), _канон(v)) for k, v in x.items()), key=repr)
    if isinstance(x, (set, frozenset)):
        return sorted((_канон(v) for v in x), key=repr)
    if isinstance(x, (list, tuple)):
        return [_канон(v) for v in x]
    if hasattr(x, "id"):
        return ("#", x.id)
    if dataclasses.is_dataclass(x) and not isinstance(x, type):
        return _канон({f.name: getattr(x, f.name) for f in dataclasses.fields(x)})
    return repr(x)


def снимок(h):
    """Всё состояние дома в конце дня, одной канонической строкой.

    Люди, квартиры и кладовые целиком (dataclass → его поля), мир (погода,
    отключения, снег, богатство мест, stats, хроника), сутки, ожидает
    и календарь — временные модификаторы и очереди на утро. Они снимаются
    нарочно: то, что забыли туда записать, всплыло бы в поведении через
    несколько дней, а здесь видно в тот же день. Не снимаются: rng (это лента,
    а не состояние), B (ручки), journal (текст дня снимается отдельно),
    реплики_быт — это данные из lines.json, а не состояние, — и hooks:
    наблюдатели смотрят на дом, а не составляют его.
    """
    люди = {pid: {k: v for k, v in vars(p).items() if k not in ("_h", "решающий")}
            for pid, p in h.people.items()}
    квартиры = {apt: vars(f) for apt, f in h.flats.items()}
    кладовые = {kid: vars(k) for kid, k in h.кладовые.items()}
    мир = {k: v for k, v in vars(h).items()
           if k not in ("rng", "B", "journal", "people", "flats", "кладовые",
                        "реплики_быт", "hooks")}
    return repr(_канон({"люди": люди, "квартиры": квартиры, "кладовые": кладовые,
                        "мир": мир}))


def _хэш(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


def отпечатки(seed, days=ДНЕЙ_ЭТАЛОНА):
    """Отпечаток прогона по дням: {"итог": …, "дни": ["журнал-состояние", …]}.

    Журнал — текст дня при полной подробности и с секретами; состояние —
    снимок(h) на конец дня. Два хэша на день, а не один: «журнал совпал,
    разошлось только состояние» — это правка, которую в логе глазами
    не увидеть (забытый счётчик, сдвинутое отношение), и эталон должен
    уметь так сказать.
    """
    from house.engine import Simulation
    buf = io.StringIO()
    дни = []
    хвост = [0]

    def день(h):
        текст = buf.getvalue()
        дни.append(_хэш(текст[хвост[0]:]) + "-" + _хэш(снимок(h)))
        хвост[0] = len(текст)

    sim = Simulation(seed=seed, days=days, verbosity=2, secrets=True, stream=buf)
    sim.h.hooks.on_day.append(день)
    sim.run()
    # то, что журнал дописал после последнего дня («не осталось никого»)
    остаток = buf.getvalue()[хвост[0]:]
    return {"итог": _хэш("\n".join(дни) + остаток), "дни": дни}


def _отпечатки_зерна(seed):
    return seed, отпечатки(seed)


def отпечатки_всех(seeds, jobs=None):
    """Отпечатки многих зёрен, параллельно.

    Тот же обход, что в runner.many: на Windows дочерний процесс заново
    импортирует __main__ по файлу, и из `python -c` это не работает —
    тогда считаем в один поток. Дочерние процессы без PYTHONHASHSEED
    получают свой хэш строк каждый, так что это и проверка детерминизма
    заодно.
    """
    seeds = list(seeds)
    главный = getattr(sys.modules.get("__main__"), "__file__", None)
    можно = главный and os.path.exists(главный)
    jobs = jobs if jobs is not None else max(1, min(8, (os.cpu_count() or 2) - 2))
    if jobs <= 1 or len(seeds) < 4 or not можно:
        return {s: отпечатки(s) for s in seeds}
    import multiprocessing as mp
    with mp.Pool(jobs) as pool:
        return dict(pool.map(_отпечатки_зерна, seeds))


def где_разошлись(было, стало):
    """Первый день, где отпечатки разошлись, и что именно: журнал, состояние, оба."""
    a, b = было["дни"], стало["дни"]
    for i, (x, y) in enumerate(zip(a, b), 1):
        if x == y:
            continue
        жx, сx = x.split("-")
        жy, сy = y.split("-")
        if жx == жy:
            return f"с дня {i}: журнал совпадает, разошлось только состояние"
        if сx == сy:
            return f"с дня {i}: разошёлся журнал, состояние совпадает"
        return f"с дня {i}: разошлись и журнал, и состояние"
    if len(a) != len(b):
        return f"дней было {len(a)}, стало {len(b)}"
    if было["итог"] != стало["итог"]:
        return "разошёлся только хвост журнала после последнего дня"
    return "совпадают"


