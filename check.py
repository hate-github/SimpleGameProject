def проверить_решающего(w):
    """Шов решения (задача 8): дом, где один жилец решает скриптом, собирается и живёт.

    Softmax-реализацию держит эталон выше. Здесь — что `Скрипт` и `Человек`
    (с заглушкой вместо консоли) встают на место NPC без правки правил,
    что дом их спрашивает и что решения оставляют разбор — тот самый список
    оценённых вариантов, который и есть объяснение.
    """
    from house.engine import Simulation
    from house.decision import Скрипт, Человек
    bad = []
    sim = Simulation(seed=3, days=6, verbosity=0, stream=io.StringIO())
    скрипт = Скрипт(ответы={"сдаться": "драться"})
    sim.h.people["игорь"].решающий = скрипт
    спрошено = []

    def первый(вопрос, строки):
        спрошено.append(вопрос)
        return 0

    sim.h.people["оксана"].решающий = Человек(спросить=первый)
    h = sim.run()
    if not скрипт.разбор:
        bad.append("скрипт не принял ни одного решения")
    if not спрошено:
        bad.append("человека ни разу не спросили")
    if h.day < 6 and h.alive():
        bad.append(f"дом со скриптом остановился на дне {h.day}")
    вопросы = sorted({в for _, _, в, _, _ in скрипт.разбор})
    w(f"  игорь решает скриптом: {len(скрипт.разбор)} решений за {h.day} дней "
      f"({', '.join(вопросы)})")
    w(f"  оксана — человек с заглушкой вместо консоли: {len(спрошено)} вопросов")
    if скрипт.разбор:
        день, кто, вопрос, строки, выбор = скрипт.разбор[0]
        w(f"  разбор первого решения (день {день}, {вопрос} → {выбор}): "
          + " | ".join(s.strip() for s in строки[:3]))
    return bad


