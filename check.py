# Чем начинается причина в пометке на строке, которой чужое читать можно:
#   # правда: под одной крышей — печка общая
# Причина обязана начинаться с одного из этих слов, чтобы ADR-10 мог их
# перечислить, а фаза 1 плана агента — найти свои
ПРИЧИНЫ = ("исполнение", "под одной крышей", "общее знание", "видно",
           "событие было со мной", "квартира", "решение автора", "фаза 1")
ПОМЕТКА = "# правда:"


def _корень(node):
    """Имя, с которого начинается цепочка вида имя.поле.метод()[ключ], или None."""
    while isinstance(node, (ast.Attribute, ast.Call, ast.Subscript)):
        node = node.func if isinstance(node, ast.Call) else node.value
    return node.id if isinstance(node, ast.Name) else None


def проверить_чтение_правды(w):
    """Решения читают только знание (план агента, фаза 0).

    Граница «NPC не знает правды о соседе» держалась на договорённости:
    решение получает в руки самого соседа и весь дом, а Взгляд и Сведения
    надо было вспомнить применить. Задачи 1–5 плана поведения закрыли
    утечки по одной; эта проверка не даёт им вернуться. В каждой решающей
    функции (РЕШАЮЩИЕ) чтение поля из ПРАВДА у любого имени, кроме
    решающего, — красный check.py с файлом и строкой. Исключение — строка
    с пометкой `# правда: <причина>`, где причина из ПРИЧИНЫ: исполнение,
    под одной крышей, общее знание, видно, событие было со мной, квартира,
    решение автора — или «фаза 1», если утечку закрывает фаза 1 плана.
    """
    bad = []
    функций, пометки, по_причинам, фаза1 = 0, set(), {}, set()
    for имя, таблица in РЕШАЮЩИЕ.items():
        src = open(os.path.join(ROOT, "house", имя), encoding="utf-8").read()
        строки = src.splitlines()
        tree = ast.parse(src)
        определения = {n.name: n for n in tree.body if isinstance(n, ast.FunctionDef)}
        # модули, которые функция зовёт по имени (social.believed_days): это
        # функции знания, а не чужое поле; тело через них ловит ЧИТАЮТ_ТЕЛО
        модули = {a.asname or a.name for n in tree.body
                  if isinstance(n, (ast.Import, ast.ImportFrom)) for a in n.names}
        нарушений = 0
        for функция, свои in таблица.items():
            f = определения.get(функция)
            if f is None:
                bad.append(f"{имя}: в таблице решающих есть {функция}, а в модуле нет")
                continue
            функций += 1
            свои = set(свои) | {"self"} | модули
            for node in ast.walk(f):
                кто = что = None
                if (isinstance(node, ast.Attribute) and node.attr in ПРАВДА
                        and isinstance(node.ctx, ast.Load)):
                    кто, что = _корень(node.value), node.attr
                elif isinstance(node, ast.Call):
                    fn = node.func
                    имя_fn = fn.id if isinstance(fn, ast.Name) else getattr(fn, "attr", None)
                    i = ЧИТАЮТ_ТЕЛО.get(имя_fn)
                    if i is not None and i < len(node.args):
                        кто, что = _корень(node.args[i]), имя_fn + "()"
                if что is None or кто in свои:
                    continue
                # чужое: допустимо только с пометкой и названной причиной
                строка = node.lineno
                if ПОМЕТКА not in строки[строка - 1] and node.end_lineno != строка:
                    строка = node.end_lineno
                текст = строки[строка - 1]
                if ПОМЕТКА in текст:
                    причина = текст.split(ПОМЕТКА, 1)[1].strip()
                    вид = next((п for п in ПРИЧИНЫ if причина.startswith(п)), None)
                    if вид is None:
                        нарушений += 1
                        w(f"  {имя}:{строка} [{функция}]: пометка без причины из списка — «{причина[:50]}»")
                        continue
                    пометки.add((имя, строка))
                    по_причинам[вид] = по_причинам.get(вид, 0) + 1
                    if вид == "фаза 1":
                        фаза1.add((имя, строка))
                    continue
                нарушений += 1
                w(f"  {имя}:{строка} [{функция}]: читает чужое {кто}.{что} — {текст.strip()[:70]}")
        if нарушений:
            bad.append(f"{имя}: {нарушений} чтений чужой правды в решениях без причины")
    if not bad:
        причины = ", ".join(f"{k} {v}" for k, v in sorted(по_причинам.items(), key=lambda kv: -kv[1]))
        w(f"  решения читают только знание: {функций} функций; строк с пометкой "
          f"{len(пометки)} ({причины}); ждут фазы 1: {len(фаза1)}")
    return bad


def проверить_прогоны(w, прогонов, дней):
    from house import checks
    from house.runner import many
    cov = checks.Coverage()
    runs = many(range(1, прогонов + 1), days=дней, hooks=cov.хуки)
    bad = []
    нарушений = [v for r in runs for v in r["нарушения"]]
    if нарушений:
        for v in нарушений[:12]:
            w("  " + v)
        if len(нарушений) > 12:
            w(f"  ... и ещё {len(нарушений) - 12}")
        bad.append(f"нарушений инвариантов и баланса: {len(нарушений)}")
    else:
        w(f"  {прогонов} прогонов: инварианты и баланс ресурсов сходятся")

    мёртвые = cov.dead_branches()
    if мёртвые:
        w("  ни разу не предложены: " + ", ".join(мёртвые))
        if прогонов >= НАДЁЖНАЯ_ВЫБОРКА:
            bad.append(f"мёртвых веток: {len(мёртвые)}")
        else:
            w(f"    (на {прогонов} прогонах это может быть просто редкость — "
              f"чтобы судить, нужно хотя бы {НАДЁЖНАЯ_ВЫБОРКА}: python check.py --прогонов {НАДЁЖНАЯ_ВЫБОРКА})")
    невыбранные = sorted(k for k in cov.offered if not cov.done.get(k) and not cov.сорвано.get(k))
    if невыбранные:
        w("  предлагаются, но никогда не выбираются: " + ", ".join(невыбранные))
    # выбрать выбирали, а до дела не дошло ни разу: засада, пустая кладовая,
    # некуда идти. Это не мёртвая ветка, но и не живая
    несостоявшиеся = sorted(k for k in cov.offered if not cov.done.get(k) and cov.сорвано.get(k))
    if несостоявшиеся:
        w("  выбирались, но ни разу не состоялись: " + ", ".join(несостоявшиеся))
    # текст тоже бывает мёртвым: у реплики есть условие, и оно может
    # не выполниться ни разу за всю жизнь дома
    from house.schema import load_json
    немые = cov.немые_реплики(load_json("lines.json"))
    if немые:
        w(f"  реплик, которые ни разу не прозвучали: {len(немые)}")
        for т in немые[:8]:
            w("    " + т)
        if прогонов >= НАДЁЖНАЯ_ВЫБОРКА:
            bad.append(f"мёртвых реплик: {len(немые)}")
    осады = cov.siege.get("осад", 0)
    исходы = {k[7:] for k in cov.siege if k.startswith("исход: ")}
    ожидаем = {"откупился", "отбился", "ограблен", "изгнан", "убит", "сбежал"}
    if осады:
        w(f"  осад {осады}, средний состав "
          f"{cov.siege.get('состав всего', 0) / осады:.2f} чел.; исходы: "
          + ", ".join(f"{k[7:]} {cov.siege[k]}" for k in sorted(cov.siege) if k.startswith("исход: ")))
        нет = sorted(ожидаем - исходы)
        if нет:
            w("  исходы GDD 16, которые не случились ни разу: " + ", ".join(нет))
    return bad, cov, runs


def проверить_детерминизм(w):
    """Одно зерно = один прогон, в том числе в другом процессе."""
    bad = []
    свой = {s: отпечатки(s) for s in ЗЁРНА_ЭТАЛОНА}
    ещё = {s: отпечатки(s) for s in ЗЁРНА_ЭТАЛОНА}
    if ещё != свой:
        bad.append("прогон не повторяется даже в одном процессе")
        w("  повтор в том же процессе дал другой результат:")
        for s in ЗЁРНА_ЭТАЛОНА:
            if ещё[s] != свой[s]:
                w(f"    зерно {s}: {где_разошлись(свой[s], ещё[s])}")
        return bad, свой
    код = ("import sys, json; sys.path.insert(0, %r); "
           "import check; print(json.dumps({s: check.отпечатки(s) for s in check.ЗЁРНА_ЭТАЛОНА}))" % ROOT)
    for hashseed in ("0", "1", "31337"):
        env = dict(os.environ, PYTHONHASHSEED=hashseed)
        p = subprocess.run([sys.executable, "-c", код], capture_output=True, env=env, cwd=ROOT)
        if p.returncode != 0:
            w("  не удалось запустить подпроцесс: " + p.stderr.decode("utf-8", "replace")[-300:])
            bad.append("проверка детерминизма не отработала")
            return bad, свой
        чужой = json.loads(p.stdout.decode("utf-8"))
        расход = [s for s in свой if свой[s] != чужой[str(s)]]
        if расход:
            w(f"  PYTHONHASHSEED={hashseed}: разошлись зёрна {расход}")
            for s in расход:
                w(f"    зерно {s}: {где_разошлись(свой[s], чужой[str(s)])}")
            bad.append("прогон зависит от PYTHONHASHSEED")
            return bad, свой
    w(f"  {len(ЗЁРНА_ЭТАЛОНА)} зёрен × 3 значения PYTHONHASHSEED — совпадение полное")
    return bad, свой


def проверить_эталон(w, свой, переписать):
    """Отпечатки золотых зёрен по дням против data/эталон.json.

    свой — отпечатки зёрен детерминизма, посчитанные в этом процессе:
    те же зёрна считаются и здесь, в дочерних процессах, и обязаны совпасть.
    """
    bad = []
    все = отпечатки_всех(ЗОЛОТЫЕ_ЗЁРНА)
    расход = [s for s in ЗЁРНА_ЭТАЛОНА if все[s] != свой[s]]
    if расход:
        w(f"  в параллельном процессе прогон другой: зёрна {расход}")
        for s in расход:
            w(f"    зерно {s}: {где_разошлись(свой[s], все[s])}")
        bad.append("прогон в дочернем процессе отличается от прогона в главном")
    if переписать:
        with open(ЭТАЛОН, "w", encoding="utf-8") as f:
            json.dump({
                "формат": "на каждый день: sha256 журнала дня и sha256 состояния дома "
                          "на его конец, по 12 знаков, через дефис; итог — sha256 всех дней "
                          "и хвоста журнала (check.отпечатки)",
                "дней": ДНЕЙ_ЭТАЛОНА,
                "зёрна": {str(s): все[s] for s in ЗОЛОТЫЕ_ЗЁРНА},
            }, f, ensure_ascii=False, indent=1)
        w(f"  эталон перезаписан: {len(ЗОЛОТЫЕ_ЗЁРНА)} зёрен по {ДНЕЙ_ЭТАЛОНА} дней")
        return bad
    if not os.path.exists(ЭТАЛОН):
        w("  эталона ещё нет — создайте его: python check.py --золотой")
        return bad
    было = json.load(open(ЭТАЛОН, encoding="utf-8"))
    if "зёрна" not in было:
        w("  эталон в старом формате (четыре итоговых отпечатка) — "
          "перепишите его: python check.py --золотой")
        return bad + ["эталон в старом формате"]
    if было.get("дней") != ДНЕЙ_ЭТАЛОНА:
        w(f"  эталон снят на {было.get('дней')} дней, а проверяется {ДНЕЙ_ЭТАЛОНА}")
        return bad + ["эталон снят на другое число дней"]
    разошлись = []
    for s in ЗОЛОТЫЕ_ЗЁРНА:
        э = было["зёрна"].get(str(s))
        if э is None:
            w(f"  зерна {s} в эталоне нет")
            разошлись.append(s)
        elif э != все[s]:
            разошлись.append(s)
            w(f"  зерно {s}: {где_разошлись(э, все[s])}")
    if разошлись:
        w(f"  поведение изменилось на {len(разошлись)} зёрнах из {len(ЗОЛОТЫЕ_ЗЁРНА)}")
        w("  если это осознанная правка — обновите эталон: python check.py --золотой")
        return bad + ["прогон разошёлся с эталоном"]
    w(f"  {len(ЗОЛОТЫЕ_ЗЁРНА)} зёрен по {ДНЕЙ_ЭТАЛОНА} дней совпадают с эталоном")
    return bad


