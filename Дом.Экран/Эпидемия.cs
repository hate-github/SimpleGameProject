// Что сосед знает о болезни в доме — для бесед (просьба автора 01.10.2026:
// «диалоги, если началась эпидемия: соседи обеспокоены ситуацией»).
//
// Болезнь — часть мира героя (`Петля/Заражение.cs`), и правда о ней —
// стадии каждого. В разговор идёт не правда, а то, что говорящий мог
// узнать сам:
//   · о себе — только когда уже знобит (болен, тяжело); задетый
//     и заражённый ещё ничего не чувствуют;
//   · о соседе — когда тот болен и живёт с ним под одной крышей или на его
//     этаже (кашель через стенку, на площадке), а тяжёлого слышит весь
//     подъезд;
//   · об умерших от болезни — весь дом: смерть в подъезде не спрячешь;
//   · о герое — видно в дверях: серое лицо и кашель.
// Здесь ничего не меняется и не бросается: только чтение, пока дом спит.

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Что говорящий знает о болезни: своя стадия (как он её чувствует),
/// болен ли на вид герой, кого из соседей он знает больным и кто умер от неё.</summary>
public sealed record ВестиБолезни(Стадия сам, bool герой_болен, IReadOnlyList<NPC> больные,
                                  IReadOnlyList<NPC> умерли)
{
    public static readonly ВестиБолезни НЕТ = new(Стадия.ЗДОРОВ, false, Array.Empty<NPC>(), Array.Empty<NPC>());

    /// <summary>Знает ли он, что в доме болезнь.</summary>
    public bool в_доме => сам is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО || герой_болен
                          || больные.Count > 0 || умерли.Count > 0;
}

public static class Эпидемия
{
    /// <summary>Какой видна болезнь: болен и тяжело — видно и слышно, прочее — нет.</summary>
    private static Стадия Видно(Заражение з, NPC p)
        => з.Стадия(p.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО ? з.Стадия(p.id) : Стадия.ЗДОРОВ;

    /// <summary>Есть ли в доме болезнь, которую слышно: кто-то болен
    /// или от неё уже умирали. Тогда о ней есть тема разговора.</summary>
    public static bool В_доме(House h, Заражение? з)
        => з is not null && (h.alive().Any(p => Видно(з, p) != Стадия.ЗДОРОВ)
                             || h.people.Значения.Any(p => !p.alive && p.cause == Заражение.ПРИЧИНА));

    /// <summary>Что о болезни знает <paramref name="кто"/>, говоря с героем <paramref name="я"/>.</summary>
    public static ВестиБолезни Вести(House h, NPC кто, NPC я, Заражение? з)
    {
        if (з is null)
            return ВестиБолезни.НЕТ;
        int этаж = h.where(кто).floor;
        var больные = h.alive()
            .Where(p => !ReferenceEquals(p, кто) && !ReferenceEquals(p, я) && Видно(з, p) != Стадия.ЗДОРОВ
                        && (Видно(з, p) == Стадия.ТЯЖЕЛО || h.под_одной_крышей(p, кто)
                            || h.where(p).floor == этаж))
            .OrderBy(p => p.id, StringComparer.Ordinal)
            .ToList();
        var умерли = h.people.Значения
            .Where(p => !p.alive && p.cause == Заражение.ПРИЧИНА)
            .OrderBy(p => p.id, StringComparer.Ordinal)
            .ToList();
        return new ВестиБолезни(Видно(з, кто), Видно(з, я) != Стадия.ЗДОРОВ, больные, умерли);
    }

    /// <summary>«одного», «двоих», «троих» … «семерых», дальше — «N человек»:
    /// сколько вынесли.</summary>
    public static string Скольких(int n) => n switch
    {
        1 => "одного",
        2 => "двоих",
        3 => "троих",
        4 => "четверых",
        5 => "пятерых",
        6 => "шестерых",
        7 => "семерых",
        _ => $"{n} человек",
    };
}
