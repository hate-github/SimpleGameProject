// Итог дня (ГДД 4.4): «После сна игрок видит сводку: сколько ресурсов
// потрачено, температура в квартире, что заметили соседи („Кто-то видел, как
// вы носили пакеты“, „Из вашей квартиры был слышен шум“), сообщения в чате,
// изменения состояния. Сводка — главный инструмент обучения: игрок понимает,
// чем живёт дом, до того как это его убьёт».
//
// Считается из двух срезов героя — прошлого утра и этого — и из того, что
// соседи запомнили о нём за эти сутки (`NPC.memory`: слышал, учуял, видел).
// Что заметили — без имён: «кто-то», «двое», «несколько соседей». Кто именно,
// сводка не говорит: это было бы знание, которого у героя нет, — та же
// граница, что у ленты (`ЗнаниеЛенты.cs`) и у плана подъезда.
//
// Читает дом — значит, зовётся, только пока дом спит на вопросе: утром,
// на первом вопросе дня. Срез хранится в сеансе, мимо дома и сейва; после
// загрузки первая сводка не показывается — прошлого утра у неё нет.

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Герой на утро: шкаф, шесть шкал и тепло там, где он живёт.</summary>
public sealed record СрезГероя(
    int день,
    IReadOnlyDictionary<string, double> шкаф,
    double сытость, double вода, double тепло, double сон, double здоровье, double паника,
    double в_квартире,
    int строк_ленты);

/// <summary>Сводка за прошедшие сутки: заголовок и строки по порядку ГДД.</summary>
public sealed record ИтогДня(int день, IReadOnlyList<string> строки);

public sealed partial class Сеанс
{
    private СрезГероя? _утро;

    /// <summary>
