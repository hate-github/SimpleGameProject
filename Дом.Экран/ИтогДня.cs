    /// «слышал») → глагол в единственном и множественном и что дальше.
    /// Шаги нарочно не считаются: «на лестнице шаги» — это весь дом каждый день.
    /// </summary>
    public static readonly IReadOnlyList<(Вид вид, string? шум, string один, string многие, string что)> ЗАМЕТИЛИ = new[]
    {
        (Вид.СЛЫШАЛ, "возвращение", "видел", "видели", ", как ты {вернулся} с улицы с пакетами"),
