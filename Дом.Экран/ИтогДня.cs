    /// <summary>Шкалы: насколько сдвинуться, чтобы сводка это назвала,
    /// и как назвать в обе стороны.</summary>
    private const double ЗАМЕТНО = 8.0;

    /// <summary>
    /// Мысль героя утром — по порогу рассудка (ГДД 11: рассудок «проявляется
    /// через стартовый монолог, реплики героя…»; числом — никогда). Строки
    /// идут по дням, без броска. Тошно (настроение ниже `ТОШНО`) — к мысли
    /// добавляется и это.
    /// </summary>
    public static readonly IReadOnlyDictionary<Порог, string[]> МЫСЛИ_УТРА = new Dictionary<Порог, string[]>
    {
        [Порог.ОБЫЧНО] = new[] { "Ещё один день. Значит, ещё можно что-то успеть.", "Утро. Держись — и других держи." },
        [Порог.ТРЕВОГА] = new[] { "Опять утро. Руки трясутся раньше, чем вспоминаю почему.", "Снова этот свет за окном. Не думать — просто делать." },
        [Порог.ОТСТРАНЕНИЕ] = new[] { "Утро. Какая разница.", "Опять. Всё уже было — и всё будет снова." },
        [Порог.НЕВОЗВРАТ] = new[] { "…" },
    };

    /// <summary>Ниже этого настроения утро ещё и тошное.</summary>
    public const double ТОШНО = 25.0;

    /// <summary>Мысль героя этим утром: <paramref name="день"/> выбирает
    /// строку, <paramref name="настроение"/> — добавить ли, что тошно.</summary>
    public static string Мысль_утра(Порог порог, int день, double настроение)
    {
        var строки = МЫСЛИ_УТРА[порог];
        string мысль = строки[((день % строки.Length) + строки.Length) % строки.Length];
        return настроение < ТОШНО ? мысль + " И тошно так, что не хочется вставать." : мысль;
    }

    /// <summary>
    /// Утро: сводка за сутки с прошлого утра — или null, если прошлого утра
    /// не было (первый день, загрузка) или он не здесь. Срез этого утра
    /// запоминается для завтрашней. Звать только пока дом спит на вопросе.
    /// </summary>
    public ИтогДня? Утро(Порог? порог = null)
    {
        var я_ = я;
        if (!я_.здесь())
            return null;
        var сейчас = Срез();
        var было = _утро;
        if (было is not null && было.день >= сейчас.день)
            return null;                    // то же утро — сводка уже была
        _утро = сейчас;
        if (было is null)
            return null;
        var итог = Сводка(было, сейчас);
        if (порог is not Порог п)
            return итог;
        // первой строкой — что он думает этим утром (ГДД 11)
        var строки = new List<string> { "— " + Мысль_утра(п, сейчас.день, я_.mood) };
        строки.AddRange(итог.строки);
        return итог with { строки = строки };
    }

    private СрезГероя Срез()
    {
        var п = я;
        var шкаф = п.stock.Ключи.ToDictionary(к => к, к => п.stock.Взять(к, 0.0), StringComparer.Ordinal);
        int строк;
        lock (_замок)
            строк = _лента.Count;
        return new СрезГероя(дом.day, шкаф, п.satiety, п.hydration, п.warmth, п.rest, п.health, п.panic,
                             дом.room_temp(п), строк);
    }

    /// <summary>Сводка между двумя утрами — по порядку ГДД 4.4.</summary>
    public ИтогДня Сводка(СрезГероя было, СрезГероя стало)
    {
        var п = я;
        var строки = new List<string>();

        // ---- ресурсы ----
        var сдвиги = было.шкаф.Keys.Union(стало.шкаф.Keys, StringComparer.Ordinal)
            .Select(к => (к, d: стало.шкаф.GetValueOrDefault(к) - было.шкаф.GetValueOrDefault(к)))
            .Where(x => Math.Abs(x.d) >= 0.05)
            .OrderByDescending(x => Math.Abs(x.d)).ThenBy(x => x.к, StringComparer.Ordinal)
            .Take(6).ToList();
        строки.Add(сдвиги.Count == 0
            ? "запасы: всё как вчера"
            : "запасы: " + string.Join(", ", сдвиги.Select(x => $"{x.к} {Текст.Знак(x.d, 1)}")));

        // ---- тепло ----
        string тепло = $"в квартире {Текст.Знак(стало.в_квартире, 0)}°";
        double dt = стало.в_квартире - было.в_квартире;
        if (Math.Abs(dt) >= 1.0)
            тепло += dt > 0 ? $" — теплее, чем вчера ({Текст.Знак(было.в_квартире, 0)}°)"
                            : $" — холоднее, чем вчера ({Текст.Знак(было.в_квартире, 0)}°)";
        строки.Add(тепло);

        // ---- что заметили соседи ----
        строки.AddRange(Заметили(было.день, стало.день));

        // ---- чат ----
        int в_чате;
        lock (_замок)
            в_чате = _лента.Skip(было.строк_ленты).Count(с => с.вид == ВидСтроки.ЧАТ);
        if (в_чате > 0)
            строки.Add($"в чате — {Сообщений(в_чате)}");

        // ---- состояние ----
        var перемены = new List<string>();
        void Шкала(double d, string хуже, string лучше)
        {
            if (d <= -ЗАМЕТНО)
                перемены.Add(хуже);
            else if (d >= ЗАМЕТНО)
                перемены.Add(лучше);
        }
        Шкала(стало.сытость - было.сытость, "голоднее", "сытее");
        Шкала(стало.вода - было.вода, "хочется пить", "{напился}");
        Шкала(стало.тепло - было.тепло, "мёрзнешь сильнее", "{отогрелся}");
        Шкала(стало.сон - было.сон, "{устал}", "{выспался}");
        Шкала(стало.здоровье - было.здоровье, "тебе хуже", "тебе лучше");
        Шкала(было.паника - стало.паника, "тревожнее", "спокойнее");
        if (перемены.Count > 0)
            строки.Add("ты: " + string.Join(", ", перемены.Select(с => Глаголы(с, п.sex))));

        return new ИтогДня(было.день, строки);
    }

    /// <summary>Что соседи запомнили о нём с утра <paramref name="с_дня"/>
    /// по утро <paramref name="по_день"/>: строка на каждое «что», без имён.</summary>
    public IReadOnlyList<string> Заметили(int с_дня, int по_день)
    {
        var п = я;
        var кто_что = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        var порядок = new List<string>();
        foreach (var сосед in дом.others(п))
            foreach (var з in сосед.memory)
            {
                if (з.день < с_дня || з.день >= по_день
                    || !string.Equals(з.кто, п.id, StringComparison.Ordinal))
                    continue;
                var шаблон = ЗАМЕТИЛИ.FirstOrDefault(т => т.вид == з.вид
                    && (т.шум is null || string.Equals(т.шум, з.что, StringComparison.Ordinal)));
                if (шаблон.один is null)
                    continue;
                string ключ = шаблон.что;
                if (!кто_что.TryGetValue(ключ, out var кто))
                {
                    кто_что[ключ] = кто = new HashSet<string>(StringComparer.Ordinal);
                    порядок.Add(ключ);
                }
                кто.Add(сосед.id);
            }
        var @out = new List<string>();
        foreach (var ключ in порядок)
        {
            var т = ЗАМЕТИЛИ.First(x => x.что == ключ);
            int n = кто_что[ключ].Count;
            string подлежащее = n == 1 ? "кто-то" : n == 2 ? "двое" : "несколько соседей";
            string глагол = n == 1 ? т.один : т.многие;
            @out.Add($"{подлежащее} {глагол}{Глаголы(т.что, п.sex)}");
        }
        return @out;
    }

    /// <summary>«{вернулся}» — в роде героя.</summary>
    private static string Глаголы(string s, string? пол)
    {
        int i;
        while ((i = s.IndexOf('{')) >= 0)
        {
            int j = s.IndexOf('}', i);
            s = s[..i] + Util.Vb(пол ?? "м", s[(i + 1)..j]) + s[(j + 1)..];
        }
        return s;
    }

    private static string Сообщений(int n)
    {
        int д = n % 100, е = n % 10;
        string слово = д is >= 11 and <= 14 ? "сообщений" : е == 1 ? "сообщение" : е is >= 2 and <= 4 ? "сообщения" : "сообщений";
        return $"{n} {(е == 1 && д != 11 ? "новое" : "новых")} {слово}";
    }
