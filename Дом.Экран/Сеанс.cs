// Сеанс: один дом, один играющий жилец и всё, что ему показывают.
//
// Это и есть «Вид/Адаптер» из направления зависимостей:
//
//     Сцена Godot → Вид/Адаптер → API симуляции → Дом.Ядро
//
// Сеанс читает дом и складывает записи. В дом он не пишет ничего и `h.rng`
// не трогает — то же правило, что у наблюдателя, и по той же причине:
// иначе интерфейс начал бы влиять на симуляцию, и два прогона с одним
// зерном разошлись бы от того, открыл ли игрок вкладку.
//
// Лента и события копятся подпиской, а не опросом: дом сам зовёт хуки,
// а сеанс их слушает.
//
// Два потока. Это главное, что нужно знать про этот файл.
//
// Ленту и события пополняет поток дома, а читает их поток экрана — в каждом
// кадре. Поэтому оба списка заперты замком: `List<T>` одновременной записи
// и чтения не переживает, и падало бы это раз в сотню запусков, в разных
// местах и без всякой связи с причиной.
//
// А вот сам дом замком не закрыт, и закрывать его нечем: это пятнадцать
// человек, семнадцать квартир и полсотни словарей. Правило вместо замка
// такое: **дом читают только тогда, когда он спит на вопросе.** Пока
// `Партия.Ждёт()` возвращает вопрос, поток дома стоит в `Wait()` и ничего
// не меняет — три экрана в это время безопасны. `Состояние`, `План`
// и `Знание` зовутся оттуда и только оттуда.

using Дом.Ядро;

namespace Дом.Экран;

public sealed class Сеанс
{
    private readonly List<СтрокаЛенты> _лента = new();
    private readonly List<Событие> _события = new();
    private readonly object _замок = new();

    /// <param name="дом">Уже собранный дом; сеанс его не заводит и не гоняет.</param>
    /// <param name="кто">id играющего жильца.</param>
    public Сеанс(House дом, string кто)
    {
        this.дом = дом;
        this.кто = кто;
        if (!дом.people.Есть(кто))
            throw new ArgumentException($"нет такого жильца: {кто}", nameof(кто));
        дом.hooks.on_событие.Add((_, с) =>
        {
            lock (_замок)
                _события.Add(с);
        });
    }

    public House дом { get; }

    public string кто { get; }

    /// <summary>Тот, за кого играют. Читать его поля напрямую — право
    /// играющего: это его собственное тело и его собственный шкаф.</summary>
    public NPC я => дом.people[кто];

    /// <summary>Крупные события дома по порядку — то, из чего движок делает
    /// значки, звуки и подсветку квартир. Отдаётся копией: список пополняет
    /// другой поток.</summary>
    public IReadOnlyList<Событие> события
    {
        get { lock (_замок) return _события.ToList(); }
    }

    /// <summary>Лента дня: строки журнала, как они случились. Тоже копией
    /// и по той же причине.</summary>
    public IReadOnlyList<СтрокаЛенты> лента
    {
        get { lock (_замок) return _лента.ToList(); }
    }

    /// <summary>Сколько строк в ленте сейчас. Дешевле копии — а экрану
    /// в каждом кадре нужно ровно это.</summary>
    public int СтрокВЛенте
    {
        get { lock (_замок) return _лента.Count; }
    }

    /// <summary>
    /// Строки, появившиеся после <paramref name="с"/>-й.
    ///
    /// Затем и заведено: экран дописывает ленту, а не перерисовывает её,
    /// и копировать ради этого семьсот строк в каждом кадре незачем.
    /// </summary>
    public IReadOnlyList<СтрокаЛенты> ЛентаПосле(int с)
    {
        lock (_замок)
            return с >= _лента.Count
                   ? Array.Empty<СтрокаЛенты>()
                   : _лента.GetRange(с, _лента.Count - с);
    }

    /// <summary>Подшить строку журнала в ленту. Зовётся журналом, который
    /// печатает день по ходу; сеанс сам журнала не заводит.</summary>
    public void Строка(string текст, int заметность, bool скрытая, string? час,
                       ВидСтроки вид = ВидСтроки.ХОД)
    {
        var с = new СтрокаЛенты(дом.day, час, текст, заметность, скрытая, вид);
        lock (_замок)
            _лента.Add(с);
    }

    /// <summary>Строки одного вида: журналу — ходы и события, телефону —
    /// чат.</summary>
    public IReadOnlyList<СтрокаЛенты> Вида(params ВидСтроки[] виды)
    {
        lock (_замок)
            return _лента.Where(с => виды.Contains(с.вид)).ToList();
    }

    /// <summary>Строки этого дня — то, что показывается лентой на экране дня.</summary>
    public IReadOnlyList<СтрокаЛенты> ЛентаДня(int день)
    {
        lock (_замок)
            return _лента.Where(с => с.день == день).ToList();
    }

    /// <summary>
    /// Что случилось в этой квартире за последние дни.
    ///
    /// Отсюда берётся «что светится, откуда дым»: налёт, вскрытие, пожар,
    /// смерть — у каждого есть место (`Событие.где` — номер квартиры),
    /// и план подъезда красится по ним, а не по правде мира. События
    /// стареют: три дня — и квартира гаснет обратно.
    /// </summary>
    public IReadOnlyList<Событие> ВКвартире(int квартира, int за_дней = 3)
    {
        lock (_замок)
            return _события
                .Where(с => с.где == квартира && дом.day - с.день < за_дней)
                .ToList();
    }

    /// <summary>Свежие события всего дома, новые сверху: лента значков
    /// рядом с планом.</summary>
    public IReadOnlyList<Событие> Свежие(int за_дней = 3)
    {
        lock (_замок)
            return _события
                .Where(с => дом.day - с.день < за_дней)
                .Reverse()
                .ToList();
    }

    // ---------- три экрана ----------
    //
    // Читают сам дом, а он замком не закрыт. Звать их можно только тогда,
    // когда дом спит на вопросе (`Партия.Ждёт()` вернул вопрос) или уже
    // кончился. В любой другой момент это чтение из-под руки у считающего
    // потока — и увиденное будет не состоянием, а серединой чужого хода.

    /// <summary>Своё состояние: шесть шкал, шкаф и время до ночи.</summary>
    public МоёСостояние Состояние()
    {
        var п = я;
        var шкаф = п.stock.Ключи
            .OrderBy(x => x, StringComparer.Ordinal)
            .Where(р => п.stock.Взять(р, 0.0) != 0)
            .Select(р => new Запас(р, п.stock.Взять(р, 0.0)))
            .ToList();
        return new МоёСостояние(
            кто, п.name, п.apt, п.role,
            п.satiety, п.hydration, п.warmth, п.rest, п.health, п.panic,
            шкаф, п.time_left,
            п.injuries.ToList(),
            !string.IsNullOrEmpty(п.sick),
            string.Equals(п.sex, "ж", StringComparison.Ordinal));
    }

    /// <summary>
    /// План подъезда: кто где живёт, кем считается, жив ли.
    ///
    /// По квартирам, а не по именам: подъезд — это дом, и порядок в нём
    /// пространственный. Умершие остаются на плане — квартира с телом
    /// никуда не девается, и это ровно то, что видит сосед.
    /// </summary>
    public IReadOnlyList<ЖилецНаПлане> План()
    {
        var @out = new List<ЖилецНаПлане>();
        foreach (var п in дом.people.Значения.OrderBy(x => x.apt))
            @out.Add(new ЖилецНаПлане(
                п.apt, п.id, п.@short, п.role, п.здесь(),
                п.здесь() ? null : п.died_day,
                п.здесь() ? null : п.cause,
                !string.IsNullOrEmpty(п.living_with)
                    ? дом.get(п.living_with!)?.@short : null));
        return @out;
    }

    /// <summary>
    /// Подъезд целиком: все квартиры по этажам, жилые и пустые.
    ///
    /// <see cref="План"/> отдаёт жильцов и нужен консоли — она печатает
    /// именно их, знак в знак с прототипом. Экрану нужен дом: пустая
    /// квартира на плане так же важна, как жилая, и «разобрана», «горел»,
    /// «с телом» — это то, за чем в неё ходят.
    /// </summary>
    public IReadOnlyList<КвартираНаПлане> Квартиры()
    {
        var где_кто = new Dictionary<int, ЖилецНаПлане>();
        var гости = new Dictionary<int, List<ЖилецНаПлане>>();
        foreach (var ж in План())
        {
            if (!ж.здесь)
                continue;
            var хозяин = дом.get(ж.id);
            if (хозяин is null)
                continue;
            // Переехавший числится у той двери, к которой ходят за ним, —
            // и решает это `хозяин_жилья`, а не поле `living_with`. Разница
            // видна, когда хозяин умер: поле у гостя остаётся висеть,
            // а `хозяин_жилья` уже возвращает его самого — и он снова
            // у своей двери, где и стоит на самом деле. Сверяться тут
            // с `living_with` значило бы сделать его гостем у собственной
            // квартиры, а квартиру — пустой
            int дверь = дом.хозяин_жилья(хозяин).apt;
            if (дверь == ж.квартира)
                где_кто[дверь] = ж;
            else
            {
                if (!гости.TryGetValue(дверь, out var с))
                    гости[дверь] = с = new List<ЖилецНаПлане>();
                с.Add(ж);
            }
        }

        var @out = new List<КвартираНаПлане>();
        foreach (var f in дом.flats.Значения.OrderBy(x => x.apt))
            @out.Add(new КвартираНаПлане(
                f.apt, f.floor,
                где_кто.TryGetValue(f.apt, out var к) ? к : null,
                гости.TryGetValue(f.apt, out var г) ? г : Array.Empty<ЖилецНаПлане>(),
                f.stripped > 0,
                f.body is not null,
                дом.day - f.костёр < 3,
                f.открыта));
        return @out;
    }

    /// <summary>
    /// Что игрок знает о соседях — через знание, а не через правду.
    ///
    /// Оценка чужого шкафа берётся `believed`, осведомлённость —
    /// `сведения_о(...).aware`. Оба бывают неверными, и это не изъян:
    /// в доме, где никто не видит чужой кастрюли, ошибаться — нормально.
    /// Мёртвые не показываются: о них экран говорит планом подъезда.
    /// </summary>
    public IReadOnlyList<СоседВЗнании> Знание()
    {
        var п = я;
        var @out = new List<СоседВЗнании>();
        foreach (var о in дом.others(п).OrderBy(x => x.apt))
        {
            if (!о.здесь())
                continue;
            @out.Add(new СоседВЗнании(
                о.id, о.@short, о.apt,
                п.believed(о.id, "еда"),
                п.believed(о.id, "топливо"),
                п.сведения_о(о.id).aware,
                п.trust.Взять(о.id, 3.0)));
        }
        return @out;
    }
}
