// Кто спрашивает и о чём: слова к вопросу-ситуации (ГДД 13, 23).
//
// Ядро спрашивает игрока тем же швом, что и соседа, и у вопроса был один
// заголовок — «день 3, Оксана: соврать». Автор так его и увидел: плашка
// с именем героя, под ней «соврать» и «сказать правду» — и ни с кем
// разговор, ни о чём, непонятно. Теперь вместе с вопросом ядро отдаёт,
// с кем разговор (`ВопросИгроку.с_кем`) и о чём (`Суть`), а слова
// собираются здесь: кто перед тобой, что происходит и что значит каждый
// ответ.
//
// Консоль печатает заголовок по-прежнему: стенограмма команды «играть»
// сверена с прототипом знак в знак, и этих слов в ней нет.
//
// Слова — только из того, что герой и так знает: кто стоит у двери,
// чего он просит, что у самого героя в шкафу. Чужого шкафа здесь нет.
//
// Ответы не переставляются и не отбираются: у каждого варианта своя
// подпись в том же порядке, и вес остаётся рядом (навык godot-boundary).

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Слова к вопросу: кто перед тобой, что происходит и подписи
/// к ответам — по одной на вариант, в его порядке.</summary>
public sealed record Сцена(string кто, string что, IReadOnlyList<string> ответы);

public static class Разговор
{
    /// <summary>Вопросы, которые задаёт не сам себе герой, а жизнь: сосед
    /// у двери, вожак, вор, хозяин. У них обязан быть тот, с кем разговор.
    /// Прочие — ночь, день и выбор из своего — идут без собеседника.</summary>
    public static readonly IReadOnlySet<Вопрос> БЕЗ_СОБЕСЕДНИКА = new HashSet<Вопрос>
    {
        Вопрос.ЧТО_ДЕЛАТЬ, Вопрос.ДЕНЬ, Вопрос.НОЧЬ,
        Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ, Вопрос.О_ЧЁМ_ГОВОРИТЬ,
    };

    /// <summary>Темы собрания словами: о чём речь.</summary>
    private static readonly IReadOnlyDictionary<string, string> СОБРАНИЕ =
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["дежурство"] = "о ночных дежурствах: чтобы кто-то в доме не спал",
            ["котёл"] = "о том, чтобы топить одну квартиру на всех",
            ["приговор"] = "о том, что с этим человеком больше жить нельзя",
            ["квартира"] = "о пустой квартире: кому занимать, кому разбирать",
            ["дверь_подъезда"] = "о подъездной двери: заколотить и не пускать чужих",
        };

    /// <summary>Что заказывают у мастера — словами.</summary>
    private static readonly IReadOnlyDictionary<string, string> ЗАКАЗ =
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["буржуйка"] = "собрать буржуйку",
            ["генератор"] = "собрать генератор",
            ["листы"] = "закрыть окна листами",
            ["звукоизоляция"] = "заглушить стены",
            ["стены"] = "укрепить стены арматурой",
        };

    // «просит еды», «просит еду»: родительный и винительный ресурса
    private static readonly IReadOnlyDictionary<string, (string род, string вин)> РЕСУРС =
        new Dictionary<string, (string, string)>(StringComparer.Ordinal)
        {
            ["еда"] = ("еды", "еду"),
            ["вода"] = ("воды", "воду"),
            ["топливо"] = ("топлива", "топливо"),
            ["лекарства"] = ("лекарств", "лекарства"),
            ["материалы"] = ("материалов", "материалы"),
            ["патроны"] = ("патронов", "патроны"),
            ["деньги"] = ("денег", "деньги"),
        };

    /// <summary>Прочитать вопрос. Дом читается, пока он спит на этом вопросе.</summary>
    public static Сцена Прочитать(House h, NPC я, ВопросИгроку в)
    {
        var с = в.с_кем is null ? null : h.get(в.с_кем);
        string кто = с is not null
            ? $"{с.name}, кв.{с.apt}"
            : в.вопрос switch
            {
                Вопрос.НОЧЬ => "Ночь",
                Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ => "Замысел",
                Вопрос.О_ЧЁМ_ГОВОРИТЬ => "Собрание",
                _ => "",
            };
        var ответы = new List<string>(в.варианты.Count);
        foreach (var x in в.варианты)
            ответы.Add(x.что is string ответ && в.вопрос != Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ
                ? $"{Подпись(в.вопрос, в.суть, ответ)}   · {Текст.Ф(x.вес, 2)}"
                : x.строка);
        return new Сцена(кто, Что(h, я, в, с), ответы);
    }

    /// <summary>Что происходит — одной-двумя фразами, с вопросом в конце.</summary>
    public static string Что(House h, NPC я, ВопросИгроку в, NPC? с)
    {
        var суть = в.суть;
        string он = с?.@short ?? "кто-то";
        bool она = string.Equals(с?.sex, "ж", StringComparison.Ordinal);
        bool я_она = string.Equals(я.sex, "ж", StringComparison.Ordinal);
        string Он(string м, string ж) => она ? ж : м;
        string Я(string м, string ж) => я_она ? ж : м;
        NPC? кого = суть?.что as NPC;

        switch (в.вопрос)
        {
            // ---- своё и чужое
            case Вопрос.ОТКРЫТЬ_ДВЕРЬ:
                return $"{он} стучит в твою дверь — {Он("пришёл", "пришла")} просить "
                       + $"{Род(суть?.что)}. Открыть или говорить через дверь?";
            case Вопрос.ДАТЬ_ИЗ_СВОЕГО:
                return $"{он} просит {Вин(суть?.что)}. У тебя в шкафу: "
                       + $"{Сколько(я, суть?.что)}. Дать из своего?";
            case Вопрос.СОВРАТЬ:
                return суть?.тема switch
                {
                    "место" => $"разговор о вылазках: {он} думает, что "
                               + $"{Место(суть.что)} ещё есть чем разжиться. Соврать, что там "
                               + "пусто, — и сходить туда самому?",
                    "человек" => $"разговор о соседях, а ты {Я("зол", "зла")} на "
                                 + $"{кого?.form("acc") ?? "соседа"}. Наговорить {с?.form("dat") ?? он}, "
                                 + $"будто {Род_он(кого)} ворует?",
                    _ => $"ты не даёшь {с?.form("dat") ?? он} {Вин(суть?.что)}. Сказать, "
                         + $"что у тебя {Я("самого", "самой")} нет, — или как есть: "
                         + "есть, но не дашь?",
                };
            case Вопрос.МЕНЯТЬСЯ:
                return $"{он} предлагает мену: {Пара(суть?.что)} у тебя — "
                       + $"за {Пара(суть?.взамен)}. Меняться?";
            case Вопрос.ВЗЯТЬСЯ_ЗА_ЗАКАЗ:
                return $"{он} заказывает у тебя работу — "
                       + $"{(суть?.что is string з && ЗАКАЗ.TryGetValue(з, out var сл) ? сл : суть?.что)}"
                       + (суть?.взамен is double цена
                           ? $", за {Текст.G(Текст.Округлить(цена, 1))} едой и топливом" : "")
                       + ". Взяться?";

            // ---- вдвоём и под одной крышей
            case Вопрос.ВПУСТИТЬ_МЕДИКА:
                return $"{он} {Он("пришёл", "пришла")} перевязать тебя. Впустить?";
            case Вопрос.ПОЙТИ_ВДВОЁМ:
                return $"{он} зовёт вдвоём на вылазку"
                       + (суть?.что is Место м ? $" — {м.куда}" : "") + ". Пойти?";
            case Вопрос.ВЗЯТЬ_РЕБЁНКА_НА_НОЧЬ:
                return $"{он} просит взять "
                       + $"{(суть?.что is Ребёнок р ? р.вин : "ребёнка")} к тебе на ночь: "
                       + "у тебя теплее. Взять?";
            case Вопрос.ПЕРЕЗИМОВАТЬ_ВДВОЁМ:
                return $"{он} предлагает перезимовать вдвоём: держаться друг друга "
                       + "до конца метели. Согласиться?";
            case Вопрос.ПУСТИТЬ_К_СЕБЕ:
                return $"{он} просится жить у тебя: вдвоём теплее и держаться легче. Пустить?";

            // ---- лестница и кражи
            case Вопрос.ОТДАТЬ_НА_ЛЕСТНИЦЕ:
                return $"{он} {Он("остановил", "остановила")} тебя на лестнице и требует "
                       + "отдать, что у тебя есть. Отдать или упереться?";
            case Вопрос.ВЫЙТИ_СО_СТВОЛОМ:
                return $"{он} {Он("залез", "залезла")} к тебе в квартиру, и ты "
                       + $"{Я("застал", "застала")} {Он("вора", "воровку")}. Ствол под рукой — "
                       + "выйти с ним?";
            case Вопрос.ДРАТЬСЯ_С_ВОРОМ:
                return $"ты {Я("застал", "застала")} {с?.form("acc") ?? он} у себя в квартире. "
                       + $"{Он("Он", "Она")} не {Он("убежал", "убежала")} — хватать или отпустить?";
            case Вопрос.БЕЖАТЬ_ОТ_ХОЗЯИНА:
                return суть?.что is Кладовая к
                    ? $"{он} {Он("спустился", "спустилась")} на стук и {Он("застал", "застала")} "
                      + $"тебя у {Чья(к)}: ты ломал{Я("", "а")} замок. Бежать — или остаться "
                      + "и объясниться?"
                    : $"{он} {Он("застал", "застала")} тебя у себя в квартире. Бежать?";

            // ---- налёт
            case Вопрос.ПОЙТИ_В_НАЛЁТ:
                return $"{он} зовёт в налёт на "
                       + $"{(кого is not null ? $"{кого.form("acc")} (кв.{кого.apt})" : "соседа")}. Пойти?";
            case Вопрос.ПРЕДУПРЕДИТЬ_ЖЕРТВУ:
                return $"{кого?.@short ?? "кто-то"} собирает людей на {Он("него", "неё")}. "
                       + $"Предупредить {Он("его", "её")} за спиной у вожака?";
            case Вопрос.ВЫЙТИ_К_ДВЕРИ:
                return $"к {Он("нему", "ней")} ломятся — налёт на квартиру. "
                       + "Выйти на площадку, заступиться?";
            case Вопрос.КРИЧАТЬ:
                return $"у твоей двери налёт — {он} и с {Он("ним", "ней")} люди. "
                       + "Кричать на весь подъезд, звать соседей?";
            case Вопрос.ОТКУПИТЬСЯ:
                return $"у твоей двери налёт — {он} и с {Он("ним", "ней")} люди. "
                       + "Откупиться, отдать часть запасов?";
            case Вопрос.ГОВОРИТЬ_ЧЕРЕЗ_ДВЕРЬ:
                return $"у твоей двери {он} с людьми. Говорить с ними через дверь?";
            case Вопрос.БЕЖАТЬ_ЧЕРЕЗ_ОКНО:
                return $"дверь не держит — {он} с людьми вот-вот ворвутся. Бежать через окно?";
            case Вопрос.ЖДАТЬ_ЗА_ДВЕРЬЮ:
                return $"{он} с людьми ломятся в дверь. Ждать за ней с оружием "
                       + "и встретить первого?";
            case Вопрос.СДАТЬСЯ:
                return $"{он} с людьми ворвались к тебе. Сдаться — или драться?";
            case Вопрос.УЙТИ_НА_КРИК:
                return $"{он} кричит на весь подъезд, по этажам зажигается свет. "
                       + "Уйти, пока не сбежались?";
            case Вопрос.УЙТИ_ОТ_СТВОЛА:
                return $"{он} {Он("вышел", "вышла")} со стволом"
                       + (кого is not null && !ReferenceEquals(кого, с)
                           ? $" за {кого.form("acc")}" : "")
                       + ". Уйти — или лезть дальше?";
            case Вопрос.ДОБИТЬ:
                return $"{он} лежит и не встаёт. Добить?";
            case Вопрос.ЗАНЯТЬ_КВАРТИРУ:
                return $"квартира {с?.form("gen") ?? "соседа"} взята. Занять её себе?";
            case Вопрос.ВЫСТАВИТЬ_НА_МОРОЗ:
                return $"{он} в твоих руках. Выставить {Он("его", "её")} на мороз?";

            // ---- дом как целое
            case Вопрос.ВЫЙТИ_НА_СОБРАНИЕ:
                return $"{он} собирает соседей на площадке — будет собрание. Выйти?";
            case Вопрос.ГОЛОС_НА_СОБРАНИИ:
                return $"собрание на площадке, {Он("созвал", "созвала")} {он}. Речь "
                       + (суть?.тема == "приговор" && кого is not null
                           ? $"о том, что делать с {кого.form("ins")}: так больше жить нельзя"
                           : СОБРАНИЕ.TryGetValue(суть?.тема ?? "", out var речь) ? речь : "о доме")
                       + ". Ты за — или против?";
            case Вопрос.О_ЧЁМ_ГОВОРИТЬ:
                return $"ты {Я("собрал", "собрала")} соседей на площадке. О чём говорить?";
            case Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ:
                return "за что взяться в ближайшие дни — какое дело сделать своим?";
            case Вопрос.НОЧЬ:
                return "как провести ночь?";
            default:
                return Вопросы.Текст(в.вопрос);
        }
    }

    /// <summary>
    /// Подпись ответа. Ответ, которому здесь нет особой подписи, остаётся
    /// своим словом из ядра («пойти», «отказать»): оно и так читается.
    /// </summary>
    public static string Подпись(Вопрос вопрос, Суть? суть, string ответ) => (вопрос, ответ) switch
    {
        (Вопрос.ОТКРЫТЬ_ДВЕРЬ, "открыть") => "открыть дверь",
        (Вопрос.ОТКРЫТЬ_ДВЕРЬ, "через дверь") => "говорить через дверь",
        (Вопрос.СОВРАТЬ, "соврать") => суть?.тема switch
        {
            "место" => "соврать: «там пусто»",
            "человек" => "наговорить",
            _ => "соврать: «у меня нет»",
        },
        (Вопрос.СОВРАТЬ, "сказать правду") => суть?.тема switch
        {
            "место" => "сказать как есть",
            "человек" => "не наговаривать",
            _ => "сказать как есть: «есть, но не дам»",
        },
        (Вопрос.МЕНЯТЬСЯ, "отказать") => "отказаться",
        (Вопрос.ДАТЬ_ИЗ_СВОЕГО, "отказать") => "не давать",
        (Вопрос.ВЫЙТИ_СО_СТВОЛОМ, "выйти") => "выйти со стволом",
        (Вопрос.ВЫЙТИ_СО_СТВОЛОМ, "не выходить") => "не связываться",
        (Вопрос.ДРАТЬСЯ_С_ВОРОМ, "драться") => "хватать",
        (Вопрос.БЕЖАТЬ_ОТ_ХОЗЯИНА, "остаться") => "остаться и объясниться",
        (Вопрос.БЕЖАТЬ_ЧЕРЕЗ_ОКНО, "бежать") => "бежать через окно",
        (Вопрос.ВЫЙТИ_К_ДВЕРИ, "выйти") => "выйти на площадку",
        (Вопрос.КРИЧАТЬ, "кричать") => "звать на помощь",
        (Вопрос.ОТКУПИТЬСЯ, "откупиться") => "откупиться: отдать часть",
        (Вопрос.ЖДАТЬ_ЗА_ДВЕРЬЮ, "ждать") => "ждать с оружием",
        (Вопрос.ВЫСТАВИТЬ_НА_МОРОЗ, "выставить") => "выставить на мороз",
        (Вопрос.О_ЧЁМ_ГОВОРИТЬ, _) => СОБРАНИЕ.TryGetValue(ответ, out var речь)
                                           ? $"{ответ.Replace('_', ' ')} — {речь}" : ответ,
        _ => ответ,
    };

    private static string Род(object? ресурс)
        => ресурс is string р ? (РЕСУРС.TryGetValue(р, out var ф) ? ф.род : р) : "чего-нибудь";

    private static string Вин(object? ресурс)
        => ресурс is string р ? (РЕСУРС.TryGetValue(р, out var ф) ? ф.вин : р) : "что-нибудь";

    private static string Сколько(NPC я, object? ресурс)
        => ресурс is string р ? Текст.G(Текст.Округлить(я.stock.Взять(р, 0.0), 1)) : "—";

    /// <summary>«еда 2» — из пары ресурса и количества.</summary>
    private static string Пара(object? пара)
        => пара is ValueTuple<string, double> п
           ? $"{п.Item1} {Текст.G(Текст.Округлить(п.Item2, 1))}"
           : "что-то";

    private static string Род_он(NPC? кто)
        => string.Equals(кто?.sex, "ж", StringComparison.Ordinal) ? "она" : "он";

    /// <summary>Место вылазки по имени — куда туда идут.</summary>
    private static string Место(object? имя)
    {
        if (имя is not string и)
            return "там";
        var м = Улица.МЕСТА.FirstOrDefault(x => string.Equals(x.имя, и, StringComparison.Ordinal));
        return м is null ? и : $"«{м.куда}»";
    }

    /// <summary>«погреба кв.14», «гаража кв.13».</summary>
    private static string Чья(Кладовая к)
        => $"{(к.вид == ВидКладовой.ПОГРЕБ ? "погреба" : "гаража")} кв.{к.apt}";
}
