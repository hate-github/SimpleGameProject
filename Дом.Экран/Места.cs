// Где делается мысль (ГДД 23): куда подойти, чтобы сделать то, что дом
// предложил.
//
// Вопрос дня больше не висит списком поверх подъезда. Это мысли героя
// о том, что делать, и лежат они в телефоне; нажать мысль — не сделать
// её, а узнать, где она делается. Делается всё ногами, у места: у двери
// соседа, у выхода во двор, у кладовой, у печи или матраса в своей
// квартире, у своей двери — снаружи (собрание, лестница) или изнутри
// (укрепить вход).
//
// Кладовая, что стоит в мире (погреб в подвале, гараж во дворе), — место
// особое: мысль о ней клавишей не отвечается. У кладовой отпирают или
// взламывают замок и обыскивают ящики — руками, за часы дня, и несут
// найденное домой; мысль только говорит, куда идти и что там делать.
// Кладовые, которых в мире нет (гаражи за валом), — улица: их мысли
// отвечаются у выхода, как вылазка.
//
// Отсюда правило, на котором держится игра: **у каждой мысли есть место.**
// Мысль без места ответить нечем, и дом встал бы на вопросе навсегда.
// Поэтому действия справочника разложены закрытыми списками — дома у вещи,
// на площадке, у выхода, у пустых квартир, у квартир с телом, по цели, —
// и раздел «места мыслей» сверяет раскладку со справочником: не разложенное
// и разложенное дважды краснеют, как и вариант, которому места не нашлось.
//
// Места считаются по тому, что герой и так знает: чья дверь где, у какой
// двери кто стоит (хроника — как у фигур на лестнице), какие квартиры
// пусты и в каких остались тела (это видно снаружи: план подъезда
// показывает то же самое).

using Дом.Ядро;

namespace Дом.Экран;

public enum ВидАдреса { ДВЕРЬ, ДВЕРИ, ВЫХОД, КЛАДОВАЯ, ДОМА, ПЛОЩАДКА }

/// <summary>Вещь в своей квартире, у которой делается мысль.</summary>
public enum Вещь { ПЕЧЬ, МАТРАС, ПОЛКА, ОКНО, ДВЕРЬ }

/// <summary>Где делается мысль: у двери (одной или любой из нескольких),
/// у выхода, у кладовой, дома у вещи, на своей площадке. У кладовой —
/// ещё и с чем туда идут: отпереть или взломать.</summary>
public sealed record Адрес(ВидАдреса вид, IReadOnlyList<int> квартиры, string? кладовая,
                           Вещь? вещь, bool взлом = false)
{
    public static Адрес Дверь(int кв) => new(ВидАдреса.ДВЕРЬ, new[] { кв }, null, null);

    public static Адрес Двери(IReadOnlyList<int> квартиры)
        => new(ВидАдреса.ДВЕРИ, квартиры, null, null);

    public static readonly Адрес Выход = new(ВидАдреса.ВЫХОД, Array.Empty<int>(), null, null);

    public static Адрес Кладовая(string id, bool взлом)
        => new(ВидАдреса.КЛАДОВАЯ, Array.Empty<int>(), id, null, взлом);

    public static Адрес Дома(Вещь в) => new(ВидАдреса.ДОМА, Array.Empty<int>(), null, в);

    public static readonly Адрес Площадка = new(ВидАдреса.ПЛОЩАДКА, Array.Empty<int>(), null, null);

    /// <summary>Ведёт ли к двери этой квартиры.</summary>
    public bool К_двери(int кв)
        => вид is ВидАдреса.ДВЕРЬ or ВидАдреса.ДВЕРИ && квартиры.Contains(кв);
}

public static class Места
{
    /// <summary>Что делается дома и у какой вещи.</summary>
    public static readonly IReadOnlyDictionary<string, Вещь> ДОМА =
        new Dictionary<string, Вещь>(StringComparer.Ordinal)
        {
            // у печи — еда, вода и тепло
            ["поесть"] = Вещь.ПЕЧЬ,
            ["поесть_мясо"] = Вещь.ПЕЧЬ,
            ["попить"] = Вещь.ПЕЧЬ,
            ["топить_снег"] = Вещь.ПЕЧЬ,
            ["топить"] = Вещь.ПЕЧЬ,
            ["костёр"] = Вещь.ПЕЧЬ,
            ["буржуйка"] = Вещь.ПЕЧЬ,
            // на матрасе — отдых
            ["отдых"] = Вещь.МАТРАС,
            // у полки — вещи, быт и то, что собирают руками
            ["одежда"] = Вещь.ПОЛКА,
            ["быт"] = Вещь.ПОЛКА,
            ["генератор"] = Вещь.ПОЛКА,
            ["генератор_собрать"] = Вещь.ПОЛКА,
            // у окна — то, что делают с окном и через окно
            ["утепление"] = Вещь.ОКНО,
            ["листы"] = Вещь.ОКНО,
            ["вытяжка"] = Вещь.ОКНО,
            // у своей двери — вход и стены
            ["дверь"] = Вещь.ДВЕРЬ,
            ["стены"] = Вещь.ДВЕРЬ,
            ["звукоизоляция"] = Вещь.ДВЕРЬ,
        };

    /// <summary>Делаются на своей площадке, у своей двери снаружи:
    /// собрание дома и посмотреть, кто на лестнице.</summary>
    public static readonly IReadOnlySet<string> ПЛОЩАДКА =
        new HashSet<string>(StringComparer.Ordinal) { "собрание", "лестница" };

    /// <summary>Делаются за порогом подъезда, но без места в доме.</summary>
    public static readonly IReadOnlySet<string> ВЫХОД =
        new HashSet<string>(StringComparer.Ordinal) { "банкомат", "уйти" };

    /// <summary>Делаются у одной из пустых квартир: какую взять, решает
    /// сам поступок.</summary>
    public static readonly IReadOnlySet<string> ПУСТЫЕ =
        new HashSet<string>(StringComparer.Ordinal) { "разбор" };

    /// <summary>Делаются у квартиры, где осталось тело.</summary>
    public static readonly IReadOnlySet<string> С_ТЕЛОМ =
        new HashSet<string>(StringComparer.Ordinal) { "тело", "вынести" };

    /// <summary>Место задаёт цель: сосед, квартира, кладовая, место вылазки.</summary>
    public static readonly IReadOnlySet<string> ПО_ЦЕЛИ = new HashSet<string>(StringComparer.Ordinal)
    {
        "вылазка", "кладовая", "вскрыть_кладовую",
        "наблюдение", "разговор", "попросить", "поделиться", "вернуть", "обмен",
        "лечить", "переехать", "занять", "съехать", "выгнать", "отнять", "кража_днём",
        "проведать", "шепнуть", "подбросить", "подкараулить", "позвать",
        "отдать_на_ночь", "заказать",
    };

    /// <summary>Все списки разом — для сверки со справочником.</summary>
    public static IEnumerable<(string список, string ключ)> Раскладка()
    {
        foreach (var к in ДОМА.Keys) yield return ("дома", к);
        foreach (var к in ПЛОЩАДКА) yield return ("площадка", к);
        foreach (var к in ВЫХОД) yield return ("выход", к);
        foreach (var к in ПУСТЫЕ) yield return ("пустые", к);
        foreach (var к in С_ТЕЛОМ) yield return ("с телом", к);
        foreach (var к in ПО_ЦЕЛИ) yield return ("по цели", к);
    }

    /// <summary>Кто из вариантов о кладовой идёт ломать чужой замок.</summary>
    public const string ВЗЛОМ = "вскрыть_кладовую";

    /// <summary>
    /// Где делается вариант вопроса дня — или ничего, если места нет
    /// (раздел «места мыслей» такого не пропускает).
    /// <paramref name="у_двери"/> — кто у какой двери стоит сейчас;
    /// <paramref name="в_мире"/> — какие кладовые стоят в мире (это знает
    /// движок: гнёзда его сцены).
    /// </summary>
    public static Адрес? Где(House h, NPC я, ВариантИгроку в,
                             IReadOnlyDictionary<string, int> у_двери,
                             IReadOnlySet<string> в_мире)
    {
        switch (в.цель)
        {
            case NPC p when p.id == я.id:
                return Адрес.Дома(Вещь.МАТРАС);         // полечиться — лёжа
            case NPC p:
                return Адрес.Дверь(у_двери.TryGetValue(p.id, out int д)
                                   ? д : h.хозяин_жилья(p).apt);
            case Flat f:
                return Адрес.Дверь(f.apt);
            case Место:
                return Адрес.Выход;
            case Кладовая к:
                // Стоит в мире — сама себе место: там и делают, руками.
                // Нет в мире — улица: туда ходят через выход, как на вылазку
                return в_мире.Contains(к.id)
                    ? Адрес.Кладовая(к.id, взлом: string.Equals(в.ключ, ВЗЛОМ, StringComparison.Ordinal))
                    : Адрес.Выход;
            case null:
                break;
            default:
                return null;
        }
        string ключ = в.ключ;
        if (ДОМА.TryGetValue(ключ, out var вещь))
            return Адрес.Дома(вещь);
        if (ПЛОЩАДКА.Contains(ключ))
            return Адрес.Площадка;
        if (ВЫХОД.Contains(ключ))
            return Адрес.Выход;
        if (ПУСТЫЕ.Contains(ключ))
        {
            var b = h.B;
            return Адрес.Двери(h.пустые_для(я)
                .Where(f => f.stripped < b["разбор_максимум"] || Ресурсы.Вещи(f.stock) > 0)  // правда: квартира: что лежит в пустой, видно снаружи
                .Select(f => f.apt).OrderBy(x => x).ToList());
        }
        if (С_ТЕЛОМ.Contains(ключ))
            return Адрес.Двери(h.пустые_для(я)
                .Where(f => f.body is not null && f.body.порций > 0)
                .Select(f => f.apt).OrderBy(x => x).ToList());
        return null;
    }

    /// <summary>Места всех вариантов вопроса — в его порядке.</summary>
    public static IReadOnlyList<Адрес?> Адреса(House h, NPC я, ВопросИгроку? в, Хроника х,
                                               IReadOnlySet<string> в_мире)
    {
        var @out = new List<Адрес?>();
        if (в is null)
            return @out;
        var у_двери = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var с in Подача.В_подъезде(h, я, х))
            у_двери[с.id] = с.квартира;
        foreach (var вариант in в.варианты)
            @out.Add(Где(h, я, вариант, у_двери, в_мире));
        return @out;
    }

    /// <summary>
    /// Как туда попасть — словами. Клавишу подсказка не называет:
    /// её назначает игрок, и дописывает её экран.
    /// </summary>
    public static string Как(House h, NPC я, Адрес? а)
    {
        if (а is null)
            return "где это делается — не понять";
        int мой = h.flats.Взять(я.apt, null)?.floor ?? 1;
        string Этаж(int кв)
        {
            var f = h.flats.Взять(кв, null);
            if (f is null)
                return "";
            int d = f.floor - мой;
            return d == 0 ? "на твоём этаже"
                 : d > 0 ? $"{f.floor} этаж, выше на {d}"
                 : $"{f.floor} этаж, ниже на {-d}";
        }
        return а.вид switch
        {
            ВидАдреса.ДВЕРЬ when а.квартиры[0] == я.apt => "у своей двери",
            ВидАдреса.ДВЕРЬ => $"у двери кв.{а.квартиры[0]} — {Этаж(а.квартиры[0])}",
            ВидАдреса.ДВЕРИ when а.квартиры.Count == 0 => "подходящей квартиры не видно",
            ВидАдреса.ДВЕРИ => "у любой из дверей: "
                               + string.Join(", ", а.квартиры.Select(к => $"кв.{к} ({Этаж(к)})")),
            ВидАдреса.ВЫХОД => "у двери во двор — первый этаж, в задней стене",
            ВидАдреса.КЛАДОВАЯ => К_кладовой(h, а),
            ВидАдреса.ДОМА => а.вещь switch
            {
                Вещь.ПЕЧЬ => "дома, у печи",
                Вещь.МАТРАС => "дома, у матраса",
                Вещь.ПОЛКА => "дома, у полки",
                Вещь.ОКНО => "дома, у окна",
                _ => "дома, у своей двери изнутри",
            },
            _ => "на своей площадке, у своей двери снаружи",
        };
    }

    /// <summary>
    /// Как попасть к кладовой и что там делать. Ключ здесь не угадывается
    /// по правде дома: с чем идут, говорит сама мысль — «сходить» ведёт
    /// туда, куда пускают, «вскрыть» — туда, где замок придётся ломать.
    /// </summary>
    private static string К_кладовой(House h, Адрес а)
    {
        if (h.кладовые.Взять(а.кладовая!, null) is not { } к)
            return "у кладовой";
        bool погреб = к.вид == ВидКладовой.ПОГРЕБ;
        string где = погреб
            ? $"в подвале, погреб кв.{к.apt}: вход со двора, приямок в конце дома"
            : $"во дворе, гараж кв.{к.apt}";
        string что = погреб ? "ящики" : "коробки";
        return а.взлом
            ? $"{где} — взломать замок (стук слышно: в первые дни спускаются и ловят), "
              + $"обыскать {что}, унести домой"
            : $"{где} — открыть замок, обыскать {что}, унести домой";
    }
}

public static class Вещи
{
    /// <summary>Как вещь зовётся в подсказке.</summary>
    public static string Текст(this Вещь в) => в switch
    {
        Вещь.ПЕЧЬ => "печь",
        Вещь.МАТРАС => "матрас",
        Вещь.ПОЛКА => "полка",
        Вещь.ОКНО => "окно",
        _ => "своя дверь",
    };
}
