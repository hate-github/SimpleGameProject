// Журнал, который не печатает, а складывает записи.
//
// Обычный журнал копит день и выкладывает его текстом в конце. Для чтения
// потом это правильно, для игры — нет: вопрос приходит посреди дня,
// и до ответа игрок должен знать, что уже случилось. Консольная игра решает
// это тем, что печатает строку сразу; экрану печатать некуда — ему нужна
// запись, которую он положит в ленту, подсветит и, может быть, озвучит.
//
// Отсюда `ЛентаЖурнал`: та же точка `line`, но вместо потока — сеанс.
//
// Заметность и скрытость сохраняются как есть, а не отсеиваются здесь:
// решать, показывать ли строку заметности 0 или секрет, — дело экрана,
// и он может передумать по ходу («показать подробности этого дня»),
// не переигрывая день. Порог остаётся только тот, что уже сидит в самом
// журнале: при `secrets = false` скрытые строки до `line` не доходят вовсе.

using Дом.Ядро;

namespace Дом.Экран;

public sealed class ЛентаЖурнал : Журнал
{
    private readonly Сеанс _сеанс;

    /// <param name="сеанс">Куда складывать строки.</param>
    /// <param name="verbosity">0 — только крупное, 1 — обычно,
    /// 2 — каждое действие. Та же шкала, что у обычного журнала.</param>
    /// <param name="secrets">Показывать ли то, чего дом не знает.</param>
    public ЛентаЖурнал(Сеанс сеанс, int verbosity = 1, bool secrets = false)
        : base(verbosity, secrets, TextWriter.Null)
    {
        _сеанс = сеанс;
    }

    public override void line(string текст, int заметность, bool hidden)
    {
        if (hidden && !secrets)
            return;
        _сеанс.Строка(текст, заметность, hidden, час);
    }

    /// <summary>Событие дня — «◆ Метель. Синоптики говорят…».</summary>
    public override void @event(string текст, bool scripted = false)
        => _сеанс.Строка($"{(scripted ? "◆" : "◇")} {текст}", 2, false, null,
                          ВидСтроки.СОБЫТИЕ);

    /// <summary>То, чего дом не знает. До сюда доходит только при
    /// включённых секретах — так же, как в обычном журнале.</summary>
    public override void secret(string текст)
    {
        if (secrets)
            _сеанс.Строка($"    ⌁ {текст}", 1, true, null, ВидСтроки.СЕКРЕТ);
    }

    /// <summary>Реплика в общем чате жильцов.</summary>
    public override void chat(string кто, string текст)
        => _сеанс.Строка($"  [чат] {кто}: {текст}", 1, false, null, ВидСтроки.ЧАТ);

    /// <summary>
    /// День кончился.
    ///
    /// Печатать нечего: все четыре точки перехвачены, и строки уже в ленте
    /// в том порядке, в каком случились. Буфер поэтому пуст — но чистится
    /// всё равно, потому что «пуст» здесь вывод рассуждения, а не проверенный
    /// факт: стоит в ядре завестись пятой точке, которая пишет в буфер
    /// сама, — и без этой строки она копилась бы до конца метели.
    ///
    /// Заголовок дня в ленту не кладётся: у ленты есть день у каждой строки,
    /// и экран рисует шапку сам — ему нужен не текст с равными знаками,
    /// а число, погода и что в доме отключено.
    /// </summary>
    public override void flush_day(House h) => buf.Clear();
}
