// Хроника: где человек был в каждый час своего дня.
//
// Дом этого не помнил. Он помнил, что было сделано (лента, `h.события`)
// и сколько на это ушло часов, но не «где стоял тот, кто это делал»,
// — и потому в подъезде было пусто: соседи существовали на плане
// и в журнале, а на лестнице их не было.
//
// Ничего нового здесь не решается и не заводится. Хроника **выводится**
// из того, что дом уже посчитал: наблюдатель `on_execute`/`after_execute`
// записывает ход — кто, с какого часа по какой, за какое дело взялся
// и куда это дело его поставило. Договор наблюдателя тот же, что всюду
// (`Дом.Ядро/Хуки.cs`): он смотрит и записывает, ничего не меняет
// и не трогает `h.rng`. Прогон с хроникой и без неё — один и тот же
// до последнего слова, и эталон это проверяет.
//
// Почему час известен. День — лента: ход даётся тому, у кого раньше
// на личных часах (`NPC.час()`). Значит когда игрока спрашивают в час H,
// у всех остальных день уже посчитан по крайней мере до H — и хроника
// на этот час уже написана. Спрашивать «где он сейчас» можно только так;
// заглянуть в будущее нельзя, и не надо.
//
// Куда ставит дело — считается по тому же правилу, по которому дом сам
// решает, вышел человек на площадку или нет (`Действия.засада_ждёт`:
// «выход из справочника, либо цель — сосед или квартира»). Своего правила
// здесь нет нарочно: два разных ответа на вопрос «он на лестнице?»
// разошлись бы молча.

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Где человек находится, пока делает своё дело.</summary>
public enum Где
{
    /// <summary>За своей дверью (или за дверью того, у кого живёт).</summary>
    Дома,

    /// <summary>На площадке у чужой двери: пришёл к соседу или в квартиру.</summary>
    УДвери,

    /// <summary>На площадке без двери: собрание.</summary>
    НаПлощадке,

    /// <summary>Вне подъезда: вылазка, кладовая, банкомат.</summary>
    ЗаПорогом,
}

/// <summary>
/// Один ход одного человека: с какого часа по какой, за что взялся
/// и куда это его поставило. <paramref name="квартира"/> значима
/// для <see cref="Где.УДвери"/> — чья это дверь.
/// </summary>
public sealed record Ход(
    int день, string кто, double от, double до, string ключ, Где где, int квартира);

/// <summary>
/// Наблюдатель: пишет ходы всех жильцов и отвечает, где человек в такой-то
/// час такого-то дня.
/// </summary>
public sealed class Хроника
{
    private readonly object _замок = new();
    private readonly Dictionary<string, List<Ход>> _ходы =
        new(StringComparer.Ordinal);

    // те же ходы, но в том порядке, в каком дом их сделал: по нему видно
    // саму ленту дня — ход даётся тому, у кого раньше на личных часах
    private readonly List<Ход> _подряд = new();

    /// <summary>
    /// Подписаться на дом. Обе точки нужны: `on_execute` знает час начала,
    /// `after_execute` — час конца, а между ними человек и потратил время.
    /// </summary>
    public Хроника(House h)
    {
        var начала = new Dictionary<string, double>(StringComparer.Ordinal);
        h.hooks.on_execute.Add((_, npc, _, _, _) => начала[npc.id] = npc.час());
        h.hooks.after_execute.Add((дом, npc, ключ, цель, _, _) =>
        {
            if (!начала.TryGetValue(npc.id, out double от))
                return;
            начала.Remove(npc.id);
            double до = npc.час();
            if (до <= от)
                return;              // сорвалось, часов не потратил — он дома
            var (где, кв) = Место_дела(дом, npc, ключ, цель);
            lock (_замок)
            {
                if (!_ходы.TryGetValue(npc.id, out var с))
                    _ходы[npc.id] = с = new List<Ход>();
                var ход = new Ход(дом.day, npc.id, от, до, ключ, где, кв);
                с.Add(ход);
                _подряд.Add(ход);
            }
        });
    }

    /// <summary>
    /// Куда дело ставит человека.
    ///
    /// Первое условие — правило дома, а не наше: `засада_ждёт` считает
    /// вышедшим того, у кого действие помечено выходом либо цель — сосед
    /// или квартира. Всё, что не вышло, происходит дома.
    /// </summary>
    private static (Где, int) Место_дела(House h, NPC npc, string ключ, object? цель)
    {
        bool вышел = Каталог.ВЫХОД_НА_ПЛОЩАДКУ.Contains(ключ)
                     || цель is NPC || цель is Flat;
        if (!вышел)
            return (Где.Дома, h.хозяин_жилья(npc).apt);

        // к соседу ходят не по прописке, а к той двери, за которой он живёт
        if (цель is NPC сосед)
            return (Где.УДвери, h.хозяин_жилья(сосед).apt);
        if (цель is Flat f)
            return (Где.УДвери, f.apt);
        if (string.Equals(ключ, "собрание", StringComparison.Ordinal))
            return (Где.НаПлощадке, h.хозяин_жилья(npc).apt);
        // вылазка, кладовая (погреб и гараж во дворе), банкомат
        return (Где.ЗаПорогом, h.хозяин_жилья(npc).apt);
    }

    /// <summary>
    /// Чем человек занят в этот час, или <c>null</c>, если ничем: не встал,
    /// уже отработал свой день или ход сорвался. Ничем — значит дома.
    /// </summary>
    public Ход? Ход_в(string кто, int день, double час)
    {
        lock (_замок)
        {
            if (!_ходы.TryGetValue(кто, out var с))
                return null;
            for (int i = с.Count - 1; i >= 0; i--)
                if (с[i].день == день && с[i].от <= час && час < с[i].до)
                    return с[i];
            return null;
        }
    }

    /// <summary>Все ходы дня подряд, как их сделал дом. День — лента:
    /// ход даётся тому, у кого раньше на личных часах, и потому в этом
    /// списке часы начала не убывают.</summary>
    public IReadOnlyList<Ход> Подряд(int день)
    {
        lock (_замок)
            return _подряд.Where(х => х.день == день).ToList();
    }

    /// <summary>Все ходы человека за день — по порядку. Для проверок
    /// и для того, чтобы посмотреть чужой день целиком.</summary>
    public IReadOnlyList<Ход> День(string кто, int день)
    {
        lock (_замок)
            return _ходы.TryGetValue(кто, out var с)
                ? с.Where(х => х.день == день).ToList()
                : new List<Ход>();
    }
}
