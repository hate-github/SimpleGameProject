// Что показывает камера на пролёт (ГДД 15; ядро — `Дом.Ядро/Петля/Камера.cs`).
//
// Камера видит, а не слышит: кто стоял у какой двери своего этажа, с какого
// часа по какой — и что делал руками. Разговор за дверью ей не слышен, поэтому
// «разговор», «попросить», «обмен» и прочие визиты на записи одно — стучал;
// кража — возился с замком; отъём и налёт — ломился; разбор — выносил доски.
// Соседи названы так, как их знает герой (`Знакомство`): лицо на записи видно,
// а имя — нет, если не знакомились.
//
// Кадры для записи — ходы хроники у дверей (`Снять`): что попадёт на плёнку,
// решает сама камера (свой этаж, после того как повесили, пока есть ток).
// Будущего на записи нет: сегодняшнее — только то, что началось до часа героя,
// а кто ещё стоит — «и сейчас там».

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Строка записи: день, слова и у своей ли двери.</summary>
public sealed record СтрокаКамеры(int день, string текст, bool у_своей);

public static class КамераГероя
{
    /// <summary>Как дело выглядит на записи: глагол (он, она) и где — у чужой
    /// двери (с номером) и у своей.</summary>
    private sealed record Вид(string он, string она, string чужая, string своя);

    private static readonly Вид СТОЯЛ = new("стоял", "стояла", "у кв.{0}", "у твоей двери");

    private static readonly IReadOnlyDictionary<string, Вид> ВИДЫ = Собрать();

    private static Dictionary<string, Вид> Собрать()
    {
        var стучал = new Вид("стучал", "стучала", "в кв.{0}", "в твою дверь");
        var ломился = new Вид("ломился", "ломилась", "в кв.{0}", "в твою дверь");
        var замок = new Вид("возился с замком", "возилась с замком", "кв.{0}", "твоей двери");
        var выносил = new Вид("выносил что-то", "выносила что-то", "из кв.{0}", "из твоей квартиры");
        var д = new Dictionary<string, Вид>(StringComparer.Ordinal);
        foreach (var к in new[] { "разговор", "попросить", "обмен", "поделиться", "лечить", "проведать",
                                  "позвать", "вернуть", "шепнуть", "отдать_на_ночь", "переехать" })
            д[к] = стучал;
        foreach (var к in new[] { "отнять", "налёт", "убить_соседа", "выгнать", "обобрать" })
            д[к] = ломился;
        д["кража_днём"] = замок;
        д["кража"] = замок;
        д["разбор"] = new Вид("выносил доски", "выносила доски", "из кв.{0}", "из твоей квартиры");
        д["тело"] = выносил;
        д["вынести"] = выносил;
        д["занять"] = new Вид("заносил вещи", "заносила вещи", "в кв.{0}", "в твою квартиру");
        д["подбросить"] = new Вид("оставил что-то", "оставила что-то", "у кв.{0}", "у твоей двери");
        д["подкараулить"] = new Вид("ждал", "ждала", "у кв.{0}", "у твоей двери");
        д["наблюдение"] = new Вид("присматривался", "присматривалась", "к кв.{0}", "к твоей двери");
        return д;
    }

    /// <summary>Кадры дня из хроники — ходы у дверей; что из них на плёнку,
    /// решает камера (`Камера.Записать`).</summary>
    public static IEnumerable<КадрКамеры> Снять(Хроника хроника, int день)
        => хроника.Подряд(день).Where(х => х.где == Где.УДвери)
                  .Select(х => new КадрКамеры(х.день, х.от, х.до, х.кто, х.квартира, х.ключ));

    /// <summary>Часы записи: «14:05». Личный час может перевалить за полночь.</summary>
    public static string Время(double час)
    {
        int минут = (int)Math.Round(час * 60) % (24 * 60);
        return $"{минут / 60:00}:{минут % 60:00}";
    }

    /// <summary>
    /// Шапка записи: над чьей дверью, пишет ли сейчас.
    /// </summary>
    public static string Шапка(House h, Камера к)
        => $"Камера над дверью кв.{к.квартира}, площадка {к.этаж}-го этажа. "
           + (к.Работает(h) ? "Пишет." : "Тока нет — не пишет, пока не дадут свет или не заведёшь генератор.");

    /// <summary>
    /// Запись за последние <paramref name="дней"/> дня — свежее сверху. Сегодня —
    /// только то, что началось до <paramref name="сейчас"/> (часа героя); кто
    /// ещё там — «и сейчас там». Своя дверь — с пометкой.
    /// </summary>
    public static IReadOnlyList<СтрокаКамеры> Запись(House h, NPC я, Камера к, double сейчас, int дней = 2)
    {
        var @out = new List<СтрокаКамеры>();
        foreach (var кадр in к.кадры
                     .Where(х => х.день > h.day - дней && х.день <= h.day
                                 && !(х.день == h.day && х.от > сейчас))
                     .OrderByDescending(х => х.день).ThenByDescending(х => х.от))
        {
            if (!h.people.TryGetValue(кадр.кто, out var кто))
                continue;
            var вид = ВИДЫ.TryGetValue(кадр.ключ, out var в) ? в : СТОЯЛ;
            bool своя = кадр.кв == к.квартира;
            bool она = string.Equals(кто.sex, "ж", StringComparison.Ordinal);
            bool идёт = кадр.день == h.day && кадр.до > сейчас;
            string когда = идёт ? $"с {Время(кадр.от)}" : $"{Время(кадр.от)}–{Время(кадр.до)}";
            string где = своя ? вид.своя : string.Format(System.Globalization.CultureInfo.InvariantCulture, вид.чужая, кадр.кв);
            @out.Add(new СтрокаКамеры(кадр.день,
                $"{когда}  {Знакомство.Как_зовут(h, я, кто)} {(она ? вид.она : вид.он)} {где}"
                + (идёт ? " — и сейчас там" : ""),
                своя));
        }
        return @out;
    }
}
