// Выход посреди дня (ГДД 24: «Выход из игры сохраняет прогресс; загрузить
// „раньше“ нельзя»).
//
// Сохраняется жизнь только во сне: дом посреди дня не сложить — его день
// лежит на стеке потока, а не в полях. Раньше выход посреди дня просто
// бросал партию, и «Продолжить» поднимало утро того же дня с тем же
// генератором: день можно было разведать — кто придёт, где пусто, чем кончится
// налёт — выйти и сыграть заново, зная. Это и есть «загрузить раньше».
//
// Теперь ушедший уходит, а день остаётся: дом доживает его без героя —
// как без сознания (`Беспамятство.Ответ`): сам он ничего не делает, к двери
// не выходит, на просьбы отказывает, ночью спит. Во сне жизнь сохраняется,
// как всегда, — и только тогда игра закрывается. Ушёл утром — потерял день
// своих часов; разведать и переиграть его нельзя.
//
// Сразу уходят, когда доживать нечего: с последнего сна герой ничего
// не делал (сохранение и есть «сейчас» — например, «Продолжить» и тут же
// выйти); жизнь уже кончилась (её пишет итог, `Дожить_и_закрыть`).
// До метели дом не идёт и доживать некому: день кончается сном — где стоял.
//
// Здесь — только правило; исполняет его движок (`ДомУзел.Уход`), консоль
// сверяет его живым домом (раздел «уход посреди дня»).

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Как уйти из жизни, которая идёт.</summary>
public enum КакУйти
{
    /// <summary>Сразу: сохранение и есть «сейчас», или жизнь уже кончилась.</summary>
    СРАЗУ,
    /// <summary>До метели: лечь, где стоял, — утро сохранится.</summary>
    СПАТЬ,
    /// <summary>В метель: дом доживает день без героя, во сне — сохранение.</summary>
    ДОЖИТЬ,
}

/// <summary>Что сделать на этом кадре, пока дом доживает день.</summary>
public enum ШагУхода
{
    /// <summary>Дом считает — ждать.</summary>
    ЖДАТЬ,
    /// <summary>Вопрос дня: прожить полчаса и пропустить ход.</summary>
    ПРОЖИТЬ,
    /// <summary>Ответить номером (молчанием, своё — лучшим, ночью — спать).</summary>
    ОТВЕТИТЬ,
    /// <summary>Дом уснул и спрашивает уже о следующем дне — сохранение записано.</summary>
    ГОТОВО,
    /// <summary>Жизнь кончилась (выбыл или метель прошла) — итог, а не сохранение.</summary>
    КОНЧИЛАСЬ,
}

public static class Уход
{
    /// <summary>Шаг дня, которым дом доживает за ушедшего, — как без сознания.</summary>
    public const double ШАГ = 0.5;

    /// <summary>
    /// Как уйти. <paramref name="ходил"/> — тратил ли герой часы или отвечал
    /// дому с последнего сохранения; <paramref name="кончилась"/> — герой
    /// выбыл или метель прошла.
    /// </summary>
    public static КакУйти Как(bool пролог, bool ходил, bool кончилась)
    {
        if (кончилась || !ходил)
            return КакУйти.СРАЗУ;
        return пролог ? КакУйти.СПАТЬ : КакУйти.ДОЖИТЬ;
    }

    /// <summary>
    /// Что сделать сейчас: <paramref name="в"/> — вопрос, на котором дом спит
    /// (null — считает), <paramref name="с_дня"/> — день, в который ушли.
    /// Номер — для <see cref="ШагУхода.ОТВЕТИТЬ"/>.
    /// </summary>
    public static (ШагУхода шаг, int номер) Шаг(ВопросИгроку? в, int с_дня, bool кончилась)
    {
        if (кончилась)
            return (ШагУхода.КОНЧИЛАСЬ, -1);
        if (в is null)
            return (ШагУхода.ЖДАТЬ, -1);
        // день прибавляется утром, после сна и наблюдателей конца дня, —
        // вопрос о следующем дне значит, что сохранение уже лежит
        if (в.день > с_дня)
            return (ШагУхода.ГОТОВО, -1);
        int номер = Беспамятство.Ответ(в);
        return номер < 0 ? (ШагУхода.ПРОЖИТЬ, -1) : (ШагУхода.ОТВЕТИТЬ, номер);
    }
}
