/// <summary>Звук записью: какая запись, у какой двери (null — у самого
/// героя, без места), громкость в дБ, кусок длинной записи в секундах
/// (0 — целиком) и через сколько секунд.</summary>
public sealed record Отзвук(string запись, int? квартира = null, float дб = 0f,
                            float секунд = 0f, double через = 0.0);

