// Что герой слышит — и чем это звучит (записи автора, `Дом.Годот/звуки`).
//
// Слой без движка нарочно, как `Подача`: что слышно, решают дом и то,
// где герой, а движок только ставит запись у нужной двери. Поэтому
// и проверяется это здесь — консоль (раздел «звуки») сверяет выбор записи
// по случаям и то, что каждая названная запись лежит файлом.
//
// Откуда что:
//   · **услышанное** — записи памяти героя «слышал — кто — что» за сегодня.
//     Кто услышал, решил дом (`Социальное.emit`: этажи, стены, буран, спит
//     ли), и громкость за стеной не придумывается второй раз. Звучит у двери
//     того, кто шумел, не больше трёх разом; ночное, пока герой спал,
//     утром не звучит — день у записи уже вчерашний;
//   · **события** — налёт ломится в дверь, прорвались (стекло), переезд
//     (мебель), пожар в квартире; тоже только сегодняшнее;
//   · **крик** — жертва налёта закричала «так, что слышал весь подъезд»
//     (строка ленты: у крика нет ни события, ни записи памяти) — мужским
//     или женским голосом у своей двери; закричал сам герой — без места;
//   · **раны** — героя ранили: ушиб, порез, перелом — удар; огнестрел —
//     выстрел, если его уже не было слышно;
//   · **свои дела** — поел, попил, затопил, строит, разбирает, открыл
//     на стук; съел вещь из кармана;
//   · **фон** — кто кашляет (простуда дома, болезнь с «Вектора») и где
//     плачет ребёнок (голоден, замёрз, болен). Когда — решает движок: раз
//     в полминуты одно из этого, на этаже героя.
// Кого нет в доме (участок, убежище), тот подъезда не слышит: ни шума,
// ни событий, ни крика — только себя.
//
// Дверь деревянная — топор и глухой стук; крепкая (уровень от двух) или
// обитая листами — металл. Молоток по металлу — там, где листы.
//
// Вариант записи (какой из трёх кашлей) выбирает число `n`, которое даёт
// зовущий: случайности здесь нет — слой проверяется, и `h.rng` он не
// трогает никогда.

