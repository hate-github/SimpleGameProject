    // ---- фон: кашель и плач ----

    /// <summary>Ребёнок плачет: голоден, замёрз или болен.</summary>
    public static bool Плачет(Ребёнок р)
        => р.здоровье > 0 && (р.сытость < 45 || р.тепло < 45 || р.болен is not null);

    /// <summary>Кашляет: простуда дома или болезнь с «Вектора» в заразной стадии.</summary>
    public static bool Кашляет(House h, NPC p)
        => p.sick is not null || Округа.У(h) is { } о && о.заражение.Заразен(p.id);

    private static IReadOnlyList<string> Кашли(bool женщина)
        => Enumerable.Range(0, 4).Select(i => Кашель(женщина, i)).ToList();

    /// <summary>
    /// Кто сейчас кашляет и где плачет ребёнок. Герой — без места; соседи —
    /// у своей двери, пока дома; ребёнок — там, где ночует. Кого нет в доме,
    /// тот слышит только себя.
    /// </summary>
    public static IReadOnlyList<Голосок> Фон(House h, NPC я)
    {
        var @out = new List<Голосок>();
        if (!я.alive)
            return @out;
        if (Кашляет(h, я))
            @out.Add(new Голосок(я.id, null, Кашли(Женщина(я)), -6f));
        if (я.нет_в_доме())
            return @out;
        foreach (var p in h.people.Значения)
        {
            if (!p.здесь() || p.нет_в_доме())
                continue;
            if (!ReferenceEquals(p, я) && Кашляет(h, p))
                @out.Add(new Голосок(p.id, h.where(p).apt, Кашли(Женщина(p)), -8f));
            foreach (var р in p.дети)
            {
                if (!Плачет(р))
                    continue;
                int кв = р.у is string у && h.get(у) is NPC t && t.здесь() ? h.where(t).apt : h.where(p).apt;
                @out.Add(new Голосок($"{p.id}/{р.имя}", кв, new[] { "плач" }, -10f));
            }
        }
        return @out;
    }
