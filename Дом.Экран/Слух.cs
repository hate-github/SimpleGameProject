    };

    /// <summary>
    /// Ответ героя на вопрос: дело дня — его звуки (`Дело`); открыл на стук
    /// (впустил медика, пустил к себе, взял ребёнка) — своя дверь открылась
    /// и через четыре секунды закрылась.
    /// </summary>
    public static IReadOnlyList<Отзвук> Ответ(House h, NPC я, ВопросИгроку в, int номер, int n)
    {
        if (номер < 0 || номер >= в.варианты.Count)
            return Array.Empty<Отзвук>();
        string ключ = в.варианты[номер].ключ;
        if (в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
            return Дело(ключ, я.burning, n);
        if (ОТКРЫЛ.TryGetValue(в.вопрос, out var да) && string.Equals(ключ, да, StringComparison.Ordinal))
        {
            int кв = Своя_дверь(h, я);
            return new[] { new Отзвук("дверь_открыть", кв, -2f), new Отзвук("дверь_закрыть", кв, -2f, через: 4.0) };
        }
        return Array.Empty<Отзвук>();
    }

    /// <summary>
    /// Съел вещь из кармана или с полки: закрытую банку сперва открыл;
    /// газировку выпил; овощ порезал; остальное жуют и глотают.
    /// </summary>
    public static IReadOnlyList<Отзвук> Съел(ВидЕды вид, bool была_закрыта, int n)
    {
        var @out = new List<Отзвук>();
        double т = 0;
        if (вид.род == РодЕды.БАНКА && была_закрыта)
        {
            @out.Add(new Отзвук("банка", null, -2f));
            т = 1.4;
        }
        if (вид.воды > 0)
        {
            @out.Add(new Отзвук(Глоток(n), null, -4f, через: т));
            @out.Add(new Отзвук(Глоток(n + 1), null, -4f, через: т + 0.7));
            return @out;
        }
        if (вид.род == РодЕды.ОВОЩ)
        {
            @out.Add(new Отзвук(Резка(n), null, -4f));
            т = 2.4;
        }
        @out.Add(new Отзвук(Жевание(n), null, -4f, через: т));
        @out.Add(new Отзвук(Глоток(n), null, -6f, через: т + 2.4));
        return @out;
    }

