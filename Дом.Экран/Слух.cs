            _ => Array.Empty<Отзвук>(),
        };
    }

    /// <summary>
    /// Что прозвучит на этом вопросе: услышанное с прошлого вопроса
    /// (<paramref name="память"/> — новые записи памяти героя), события
    /// и строки ленты с прошлого вопроса, новые раны героя. Одна дверь
    /// не звучит налётом дважды: налёт слышен и записью памяти («взлом»),
    /// и событием — бьют в дверь один раз.
    /// </summary>
    public static IReadOnlyList<Отзвук> Новое(House h, NPC я, IReadOnlyList<Память> память,
                                              IReadOnlyList<Событие> события,
                                              IReadOnlyList<СтрокаЛенты> строки,
                                              IReadOnlyList<string> раны)
    {
        var @out = new List<Отзвук>();
        if (!я.alive)
            return @out;
        if (!я.нет_в_доме())
        {
            var ломились = new HashSet<int>();
            var было = new HashSet<(string, string)>(); // (что, кто)
            for (int i = 0; i < память.Count && было.Count < РАЗОМ; i++)
            {
                var з = память[i];
                if (з.вид != Вид.СЛЫШАЛ || з.день != h.day || з.что is not string что
                    || !ШУМЫ.Contains(что) || h.get(з.кто) is not NPC кто || !было.Add((что, з.кто)))
                    continue;
                @out.AddRange(Шум(h, что, кто, i));
                if (что == "взлом")
                    ломились.Add(h.where(кто).apt);
            }
            foreach (var с in события)
            {
                if (с.день != h.day || с.где is not int кв)
                    continue;
                switch (с.вид)
                {
                    case ВидСобытия.НАЛЁТ when ломились.Add(кв):
                        @out.AddRange(Ломятся(h, кв, кв));
                        break;
                    case ВидСобытия.ИСХОД when ПРОРВАЛИСЬ.Contains(с.что ?? ""):
                        @out.Add(new Отзвук("стекло", кв, -2f, через: 1.4));
                        break;
                    case ВидСобытия.ПЕРЕЕЗД:
                        @out.Add(new Отзвук("мебель", кв));
                        break;
                    case ВидСобытия.ПОЖАР:
                        @out.Add(new Отзвук("пожар", кв, -2f, 8f));
                        break;
                }
            }
            @out.AddRange(Крики(h, я, строки));
        }
        @out.AddRange(Раны(раны, @out.Any(о => о.запись.StartsWith("выстрел_", StringComparison.Ordinal))));
        return @out;
    }

    /// <summary>Крики из ленты: жертва налёта закричала — у её двери;
    /// закричал сам герой — без места.</summary>
    public static IReadOnlyList<Отзвук> Крики(House h, NPC я, IReadOnlyList<СтрокаЛенты> строки)
    {
        var @out = new List<Отзвук>();
        foreach (var с in строки)
        {
            if (с.день != h.day || !с.текст.EndsWith(КРИК, StringComparison.Ordinal))
                continue;
            foreach (var p in h.people.Значения)
            {
                if (!с.текст.StartsWith($"{p.@short} {Util.Vb(p.sex, "закричал")}{КРИК}", StringComparison.Ordinal))
                    continue;
                @out.Add(new Отзвук(Крик(Женщина(p), p.apt), ReferenceEquals(p, я) ? null : h.where(p).apt, 2f));
                break;
            }
        }
        return @out;
    }

    /// <summary>Новые раны героя: ушиб, порез, перелом — удар; огнестрел —
    /// выстрел, если его уже не было слышно (<paramref name="выстрел_был"/>).
    /// Обморожение и ожог не звучат ничем.</summary>
    public static IReadOnlyList<Отзвук> Раны(IReadOnlyList<string> раны, bool выстрел_был)
    {
        var @out = new List<Отзвук>();
        foreach (var рана in раны)
        {
            if (рана.Contains("огнестрел", StringComparison.Ordinal))
            {
                if (!выстрел_был)
                    @out.Add(new Отзвук("выстрел_пистолет", null, 2f));
                выстрел_был = true;
            }
            else if (рана.Contains("ушиб", StringComparison.Ordinal)
                     || рана.Contains("порез", StringComparison.Ordinal)
                     || рана.Contains("перелом", StringComparison.Ordinal))
                @out.Add(new Отзвук("удар", null, 0f, через: 0.3 * @out.Count));
        }
        return @out;
    }

    /// <summary>Сколько новых сообщений в чате жильцов — не своих.</summary>
    public static int Сообщений(NPC я, IReadOnlyList<СтрокаЛенты> строки)
        => строки.Count(с => с.вид == ВидСтроки.ЧАТ
                             && !с.текст.StartsWith($"  [чат] {я.@short}:", StringComparison.Ordinal));

