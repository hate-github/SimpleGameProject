        int кв = h.where(кто).apt;
        return что switch
        {
            "ссора" => new[] { new Отзвук("ссора", кв, -3f, 6f) },
            "выстрел" => new[] { new Отзвук(Выстрел(кто.weapon), кв, 3f) },
            "разбор" => new[] { new Отзвук("топор_2", кв, -4f, 5f) },
            "взлом" => Ломятся(h, кв, n),
            "пролом" => new[]
            {
                new Отзвук(Лом(n), кв), new Отзвук(Лом(n + 1), кв, через: 0.8),
                new Отзвук(Лом(n + 2), кв, через: 1.7),
            },
            "готовка" => new[] { new Отзвук("жарка", кв, -12f, 5f) },
            "ремонт" => new[] { new Отзвук(Молоток(false, n), кв, -6f, 4f) },
            "дверь" => new[] { new Отзвук(Молоток(Дверь_в_листах(h, кв), n), кв, -6f, 4f) },
            "буржуйка" => new[] { new Отзвук("огонь_1", кв, -12f) },
            "возвращение" => new[]
            {
                new Отзвук("дверь_открыть", кв, -6f), new Отзвук("дверь_закрыть", кв, -6f, через: 1.8),
