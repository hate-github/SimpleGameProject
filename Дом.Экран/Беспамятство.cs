// Без сознания: день для героя кончился (`Дом.Ядро.Положения`, порог
// `без_сознания_ниже`, или избили до беспамятства). Ходить и делать нельзя,
// а дом живёт дальше и спрашивает героя, как спрашивал: к двери пришли,
// в налёт зовут, вор в квартире. Кто без памяти, тот не отвечает — не
// открыл, не впустил, не вышел, молчал, отказал; а с тем, кто на него самого
// напал, не спорит — сдался, отдал, отступил.
//
// Здесь — каким ответом дому звучит молчание, на каждый вопрос: закрытым
// списком, чтобы новый вопрос не проскочил мимо (раздел консоли «без
// сознания» сверяет список с `Вопрос` и с вариантами, которые ядро
// предлагает). Свои вопросы (за что взяться, о чём говорить, соврать) —
// как у распорядка: лучшим; день — пропустить; ночь — спать. Проматывает
// день и отвечает за героя движок (`ДомУзел.Беспамятство`).
//
// Первая версия ничего этого не делала: положение запирало взгляд и ноги,
// а день шёл своим ходом, минута за секунду, — пятнадцать минут взаперти
// до ночи, и при этом мысли дому отвечались, и герой без сознания лечил сам
// себя сколько угодно раз (автор, 28.09.2026).

using Дом.Ядро;

namespace Дом.Экран;

public static class Беспамятство
{
    /// <summary>Ответ без сознания на вопрос «да или нет».</summary>
    public static readonly IReadOnlyDictionary<Вопрос, string> ТИХО = new Dictionary<Вопрос, string>
    {
        // к нему пришли — не открыл, не впустил, не вышел
        [Вопрос.ОТКРЫТЬ_ДВЕРЬ] = "через дверь",
        [Вопрос.ГОВОРИТЬ_ЧЕРЕЗ_ДВЕРЬ] = "молчать",
        [Вопрос.ВПУСТИТЬ_МЕДИКА] = "не впустить",
        [Вопрос.ПУСТИТЬ_К_СЕБЕ] = "отказать",
        [Вопрос.ВЗЯТЬ_РЕБЁНКА_НА_НОЧЬ] = "отказать",
        [Вопрос.ВЫЙТИ_К_ДВЕРИ] = "остаться",
        [Вопрос.ВЫЙТИ_НА_СОБРАНИЕ] = "остаться",
        [Вопрос.ВЫЙТИ_СО_СТВОЛОМ] = "не выходить",
        [Вопрос.ЖДАТЬ_ЗА_ДВЕРЬЮ] = "не ждать",
        // на него напали — не кричал, не платил, не дрался, не бежал
        [Вопрос.КРИЧАТЬ] = "молчать",
        [Вопрос.ОТКУПИТЬСЯ] = "не платить",
        [Вопрос.СДАТЬСЯ] = "сдаться",
        [Вопрос.ДРАТЬСЯ_С_ВОРОМ] = "отпустить",
        [Вопрос.ОТДАТЬ_НА_ЛЕСТНИЦЕ] = "отдать",
        [Вопрос.БЕЖАТЬ_ЧЕРЕЗ_ОКНО] = "остаться",
        [Вопрос.БЕЖАТЬ_ОТ_ХОЗЯИНА] = "остаться",
        // его зовут, у него просят — отказал
        [Вопрос.ПОЙТИ_В_НАЛЁТ] = "отказать",
        [Вопрос.ПОЙТИ_ВДВОЁМ] = "отказать",
        [Вопрос.ПЕРЕЗИМОВАТЬ_ВДВОЁМ] = "отказать",
        [Вопрос.МЕНЯТЬСЯ] = "отказать",
        [Вопрос.ДАТЬ_ИЗ_СВОЕГО] = "отказать",
        [Вопрос.ВЗЯТЬСЯ_ЗА_ЗАКАЗ] = "отказать",
        [Вопрос.ГОЛОС_НА_СОБРАНИИ] = "против",
        // сам ведёт дело — оставил его
        [Вопрос.ПРЕДУПРЕДИТЬ_ЖЕРТВУ] = "смолчать",
        [Вопрос.ДОБИТЬ] = "оставить",
        [Вопрос.ЗАНЯТЬ_КВАРТИРУ] = "уйти",
        [Вопрос.ВЫСТАВИТЬ_НА_МОРОЗ] = "оставить",
        [Вопрос.УЙТИ_НА_КРИК] = "уйти",
        [Вопрос.УЙТИ_ОТ_СТВОЛА] = "уйти",
    };

    /// <summary>Свои вопросы — ответ лучшим, как у распорядка.</summary>
    public static readonly IReadOnlySet<Вопрос> СВОИ = new HashSet<Вопрос>
    {
        Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ, Вопрос.О_ЧЁМ_ГОВОРИТЬ, Вопрос.СОВРАТЬ,
    };

    /// <summary>Вопросы дня и ночи: день пропускается, ночью — спать.
    /// «День» игроку не задаётся (им пишется разбор), но в списке он есть.</summary>
    public static readonly IReadOnlySet<Вопрос> ДЕНЬ_И_НОЧЬ = new HashSet<Вопрос>
    {
        Вопрос.ЧТО_ДЕЛАТЬ, Вопрос.ДЕНЬ, Вопрос.НОЧЬ,
    };

    /// <summary>
    /// Каким вариантом ответить за героя без сознания: своё — лучшим; ночь —
    /// «спать»; «да или нет» — по списку; вопрос дня — −1 (не отвечать,
    /// а прожить шаг). Не нашлось такого варианта — самым слабым (последним:
    /// варианты идут по убыванию веса).
    /// </summary>
    public static int Ответ(ВопросИгроку в)
    {
        if (в.варианты.Count == 0 || в.вопрос is Вопрос.ЧТО_ДЕЛАТЬ or Вопрос.ДЕНЬ)
            return -1;
        if (СВОИ.Contains(в.вопрос))
            return Распорядок.Лучший(в.варианты);
        string? ключ = в.вопрос == Вопрос.НОЧЬ ? "спать" : ТИХО.GetValueOrDefault(в.вопрос);
        for (int i = 0; i < в.варианты.Count; i++)
            if (string.Equals(в.варианты[i].ключ, ключ, StringComparison.Ordinal))
                return i;
        return в.варианты.Count - 1;
    }
}
