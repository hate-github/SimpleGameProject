// Мысль о собеседнике (ГДД 10: «знание меняет диалоги: мысли героя о NPC,
// убившем его, крайне враждебны; можно выбирать реплики, которые „нельзя
// было знать“»).
//
// Сосед этой жизни ничего не помнит (ГДД 3), а герой помнит — заметками
// в телефоне (`Наследие.записи`, пишутся в конце жизни из его же знания).
// Когда разговор идёт с тем, о ком есть такая заметка, окно разговора
// говорит, что герой о нём думает. Без имени: лицо он помнит, а имени этой
// жизни мог ещё не узнать (`Знакомство`) — «это он», «она».
//
// Что громче, то и говорится: убийца, потом вор, кто не открывал, кто
// давал. Тон убийце — от рассудка (ГДД 11): в обычном — помнит и злится,
// в тревоге — руки сжимаются сами, в отстранении — холодно. Заметок этой
// жизни нет: они пишутся смертью, и потому всё, что здесь, — из прошлых.
//
// Только слова: ни дом, ни ответы, ни их порядок мысль не трогает.

using Дом.Ядро;

namespace Дом.Экран;

public static class МысльОСоседе
{
    /// <summary>Порядок громкости: о ком есть несколько заметок — говорится
    /// первая из этого списка.</summary>
    public static readonly IReadOnlyList<ВидЗаписи> ПОРЯДОК = new[]
    {
        ВидЗаписи.УБИЙЦА, ВидЗаписи.ВОР, ВидЗаписи.ОТКАЗАЛ, ВидЗаписи.ПОМОГ,
    };

    /// <summary>Что герой думает о <paramref name="с"/> — или null, если
    /// о нём ничего не помнит.</summary>
    public static string? О(Наследие н, NPC я, NPC с, РучкиПетли ручки)
    {
        foreach (var вид in ПОРЯДОК)
        {
            var з = н.записи.LastOrDefault(x => x.вид == вид
                                                && string.Equals(x.кто, с.id, StringComparison.Ordinal));
            if (з is null)
                continue;
            bool она = string.Equals(с.sex, "ж", StringComparison.Ordinal);
            string он = она ? "она" : "он", его = она ? "её" : "его";
            // заметки этой жизни пишет только смерть: прошлая — та, что кончилась последней
            string когда = з.жизнь >= н.жизней ? "в прошлый раз" : "когда-то, в другой жизни,";
            return вид switch
            {
                ВидЗаписи.УБИЙЦА => Рассудок.Где(н.рассудок, ручки) switch
                {
                    Порог.ОБЫЧНО => $"Это {он}. {Заглавная(когда)} {он} меня {Util.Vb(с.sex, "убил")} — "
                                    + "а сейчас смотрит, как ни в чём не бывало.",
                    Порог.ТРЕВОГА => $"Руки сжимаются сами: это {он} меня {Util.Vb(с.sex, "убил")}.",
                    _ => $"{Заглавная(он)} меня {Util.Vb(с.sex, "убил")}. Пусть попробует ещё раз.",
                },
                ВидЗаписи.ВОР => $"{Заглавная(когда)} {его} называли вором.",
                ВидЗаписи.ОТКАЗАЛ => $"{Заглавная(когда)} {он} мне не {Util.Vb(с.sex, "открывал")}.",
                _ => $"{Заглавная(когда)} {он} мне {Util.Vb(с.sex, "давал")}, "
                     + $"когда я {Util.Vb(я.sex, "просил")}.",
            };
        }
        return null;
    }

    private static string Заглавная(string s) => s.Length == 0 ? s : char.ToUpperInvariant(s[0]) + s[1..];
}
