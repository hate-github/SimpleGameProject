// Что в руках — у героя и у соседа (задание автора, пп. 22–23).
//
// Одна запись на обоих (`Руки`): предмет, как он зовётся у моделей
// и анимаций автора (ассет) и тяжёлый ли. Движок рисует её одним и тем же
// узлом (`Дом.Годот.Руки3D`) — в руке героя у камеры и в руке фигуры
// на лестнице. Две независимые системы задание запрещает прямо, и это
// правильно: разъехались бы в первой же правке.
//
// Откуда берётся, у каждого своё:
//   · у героя — что он достал сам (`Снаряжение.в_руках`); пока идёт
//     долгое дело — инструмент дела: им и ломают;
//   · у соседа — по делу, за которым он стоит на лестнице (`Хроника`):
//     отнять, выгнать, караулить — оружие наголо; разбирать квартиру
//     или ломать дверь днём — монтировка; одичавший носит оружие открыто
//     всегда. Таблица — `data/инструменты.json`, «руки_соседей».
//
// Сосед с оружием в руке — это то, что видно, и только то: что у него
// за пазухой, лестница не показывает.

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Что в руках: предмет, его ассет и тяжёлое ли. Пусто — руки пусты.</summary>
public sealed record Руки(string? предмет, string? ассет, bool тяжёлый)
{
    public static readonly Руки ПУСТЫ = new(null, null, false);

    public bool пусты => предмет is null;
}

public static class Ношение
{
    /// <summary>Предмет каталога — в руках.</summary>
    public static Руки Предмет(Инструменты каталог, string? id, bool тяжёлый = false)
        => id is not null && каталог.в_руках.TryGetValue(id, out var в)
           ? new Руки(в.id, в.ассет, тяжёлый)
           : Руки.ПУСТЫ;

    /// <summary>
    /// Руки героя. Идёт дело — его инструмент: им и ломают, что бы ни было
    /// в руках до того. Иначе — что достал сам; тяжёлое — только взятый
    /// тяжёлый инструмент. Читать, пока дом спит на вопросе или из рук
    /// самого игрока: снаряжение — только его.
    /// </summary>
    public static Руки Героя(NPC я, Инструменты каталог, string? инструмент_дела = null)
    {
        if (инструмент_дела is not null)
            return Предмет(каталог, инструмент_дела,
                           я.снаряжение?.Тяжёлое(инструмент_дела, каталог) ?? false);
        if (я.снаряжение is not { в_руках: string id } с)
            return Руки.ПУСТЫ;
        return Предмет(каталог, id, с.Тяжёлое(id, каталог));
    }

    /// <summary>
    /// Руки соседа на лестнице: по делу, за которым он стоит, и по тому,
    /// одичал ли он. Оружие наголо — если дело из таких или прятать его
    /// он перестал; рабочее — если дело рабочее; иначе руки пусты.
    /// </summary>
    public static Руки Соседа(NPC п, string ключ, Инструменты каталог)
    {
        var р = каталог.соседи;
        if (каталог.Оружие_в_руки(п.weapon) is string оружие
            && (р.оружие_наголо.Contains(ключ) || п.normalcy < р.открыто_ниже))
            return Предмет(каталог, оружие);
        if (р.дело.TryGetValue(ключ, out var id))
            return Предмет(каталог, id);
        return Руки.ПУСТЫ;
    }

    /// <summary>Руки и движение каждого, кто стоит на лестнице. Считать,
    /// пока дом спит на вопросе: читается тело соседа.</summary>
    public static IReadOnlyDictionary<string, (Руки руки, Движение движение)> Соседей(
        House h, IReadOnlyList<ВПодъезде> кто, Инструменты каталог)
    {
        var @out = new Dictionary<string, (Руки, Движение)>(StringComparer.Ordinal);
        foreach (var с in кто)
        {
            if (h.get(с.id) is not { } п)
                continue;
            var руки = Соседа(п, с.ключ, каталог);
            @out[с.id] = (руки, Анимации.Соседа(с.ключ, руки, идёт: false));
        }
        return @out;
    }
}
