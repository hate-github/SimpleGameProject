// Что из ленты дня знает герой (обзор 27.10; ГДД 12: «всё это происходит
// и без участия игрока, и игрок узнаёт об этом из чата, шума и итога дня»).
//
// Журнал дома — рассказчик, который видит всё: кто у кого вынес банки ночью,
// что каждый сосед заметил за день, кто ещё слышал шум, «(а это был не он)».
// Лента J печатала его целиком, и герой читал то, чего не знает ни один жилец.
// Теперь у каждой строки есть отметка `знает`, и ставит её сеанс в ту минуту,
// когда дом строку печатает, — по тому, что в эту минуту происходит:
//
// - событие дня и чат знает весь дом; секрет — никто;
// - строку о себе (начинается с его имени; «Валя и Оксана договорились…»)
//   герой знает — это его жизнь;
// - строку внутри дела — если дело его (или он внутри своего дела), если
//   оно лицом к лицу с ним (разговор, просьба, отъём: `Знакомство.ЛИЦОМ`
//   и `Заражение.ЛИЦОМ_К_ЛИЦУ`), если его делает тот, с кем он живёт под
//   одной крышей, или если за это дело он сам увидел или учуял того, кто
//   его делает (память — единственный след знания: запись `Память` о нём,
//   появившаяся за это дело, `ВИДИТ`), — и только пока он сам в доме;
//   шум за стеной (`СЛЫШАЛ`) строки не открывает: слышно, что шумят,
//   а не что вынесли и у кого — это доносит звук, а не лента;
// - остальное — нет: ночная кража, чужое «за день заметил», «(слышали: …)».
//
// Дело узнаётся по наблюдателям `on_execute`/`after_execute` — стеком: дело
// бывает внутри дела. Вне дел дом печатает утро, ночь, собрание и итог дня;
// такую строку герой знает, только если она о нём.
//
// Знаемая строка пишется его глазами (`СтрокаЛенты.глазами`): соседи,
// которых он не знает по имени, — «сосед из кв.N» (`Знакомство`), а хвост,
// в котором рассказчик договаривает правду («Учуяли: …», «(а это был
// не он)»), срезан. Сам текст строки
// остаётся как есть: его читают звуки и проверки, а галочка отладки
// `ДомУзел.ЛентаЦеликом` показывает ленту целиком, отмечая чужое.
//
// Решает это сеанс на потоке дома, как и всё, что он копит подпиской.

using System.Text.RegularExpressions;
using Дом.Ядро;

namespace Дом.Экран;

public sealed partial class Сеанс
{
    /// <summary>Дела, которые делаются сейчас: кто, что и с кем. Трогает
    /// только поток дома — тот же, что печатает строки.</summary>
    private readonly List<(NPC кто, string ключ, object? цель, int память)> _дела = new();

    /// <summary>Формы имён соседей, которых герой может не знать: регулярка
    /// на каждую форму, по месту в строке — целым словом.</summary>
    private readonly Dictionary<string, Regex> _формы = new(StringComparer.Ordinal);

    /// <summary>Дела лицом к лицу: тот, с кем их делают, стоит рядом и знает,
    /// что было. Два готовых списка ядра — знакомство и встреча при заражении
    /// (второй сверяется с исходниками исполнителей).</summary>
    public static readonly IReadOnlySet<string> ЛИЦОМ =
        new HashSet<string>(Знакомство.ЛИЦОМ.Concat(Заражение.ЛИЦОМ_К_ЛИЦУ), StringComparer.Ordinal);

    /// <summary>Строки, которые знает только рассказчик: кто ещё слышал шум.
    /// Такую строку не знает ни один жилец, даже тот, кто шумел.</summary>
    public static readonly IReadOnlyList<string> ТОЛЬКО_РАССКАЗЧИК = new[] { "(слышали: " };

    /// <summary>Хвосты, в которых рассказчик договаривает правду: строку
    /// человек знает, а хвост — нет («уверена, что это Толик» — его,
    /// «(а это был не он)» — дома; «тянет едой из кв.7» — его, кто ещё
    /// учуял — дома). В строке героя всё от метки до конца срезается.</summary>
    public static readonly IReadOnlyList<string> ХВОСТЫ_РАССКАЗЧИКА = new[] { " (а это был не он)", " Учуяли: " };

    /// <summary>Записи памяти, с которыми человек знает, что было, а не только
    /// что шумели: видел сам, учуял, поймал. `СЛЫШАЛ` сюда нарочно не входит.</summary>
    public static readonly IReadOnlySet<Вид> ВИДИТ = new HashSet<Вид>
    {
        Вид.УЧУЯЛ, Вид.СМОТРЕЛ, Вид.ПОЙМАЛ_ВОРА, Вид.ПОЙМАЛ_НА_ЛЖИ,
        Вид.ВИДЕЛ_УБИЙСТВО, Вид.ВИДЕЛ_ИЗГНАНИЕ,
    };

    /// <summary>Падежи имени, длинные формы — раньше коротких.</summary>
    private static readonly string[] ПАДЕЖИ = { "name", "short", "gen", "dat", "acc", "ins" };

    private void Следить_за_делами()
    {
        дом.hooks.on_execute.Add((_, npc, ключ, цель, _) => _дела.Add((npc, ключ, цель, я.memory.Count)));
        дом.hooks.after_execute.Add((_, _, _, _, _, _) =>
        {
            if (_дела.Count > 0)
                _дела.RemoveAt(_дела.Count - 1);
        });
    }

    /// <summary>Знает ли герой строку, которую дом печатает сейчас.
    /// Зовётся на потоке дома, из <see cref="Строка"/>.</summary>
    public bool Знает_строку(string текст, ВидСтроки вид)
    {
        if (вид is ВидСтроки.СОБЫТИЕ or ВидСтроки.ЧАТ)
            return true;
        if (вид == ВидСтроки.СЕКРЕТ)
            return false;
        if (ТОЛЬКО_РАССКАЗЧИК.Any(с => текст.Contains(с, StringComparison.Ordinal)))
            return false;
        var я_ = я;
        if (Про_меня(текст, я_))
            return true;
        // своё дело — и всё, что случилось внутри него
        if (_дела.Any(д => string.Equals(д.кто.id, я_.id, StringComparison.Ordinal)))
            return true;
        if (_дела.Count == 0 || !я_.здесь() || я_.нет_в_доме())
            return false;
        var (кто, ключ, цель, память) = _дела[^1];
        if (цель is NPC t && string.Equals(t.id, я_.id, StringComparison.Ordinal) && ЛИЦОМ.Contains(ключ))
            return true;
        if (кто.здесь() && дом.под_одной_крышей(я_, кто))
            return true;
        // за это дело он сам увидел или учуял того, кто его делает
        for (int i = Math.Max(0, память); i < я_.memory.Count; i++)
            if (ВИДИТ.Contains(я_.memory[i].вид)
                && string.Equals(я_.memory[i].кто, кто.id, StringComparison.Ordinal))
                return true;
        return false;
    }

    /// <summary>Строка о нём: начинается с его имени — или с пары, где он
    /// второй («Валя и Оксана договорились держаться вместе»).</summary>
    public static bool Про_меня(string текст, NPC я)
    {
        string т = текст.TrimStart();
        string имя = я.@short;
        if (т.Length > имя.Length && т.StartsWith(имя, StringComparison.Ordinal)
            && !char.IsLetter(т[имя.Length]))
            return true;
        int пробел = т.IndexOf(' ');
        return пробел > 0
               && т.AsSpan(пробел).StartsWith(" и " + имя, StringComparison.Ordinal)
               && т.Length > пробел + 3 + имя.Length
               && !char.IsLetter(т[пробел + 3 + имя.Length]);
    }

    /// <summary>Строка его глазами — или null, если она и так его: соседи,
    /// которых он не знает по имени, — «сосед из кв.N», хвост рассказчика
    /// срезан.</summary>
    public string? Его_глазами(string текст)
    {
        string т = текст;
        foreach (var х in ХВОСТЫ_РАССКАЗЧИКА)
        {
            int где = т.IndexOf(х, StringComparison.Ordinal);
            if (где >= 0)
                т = т[..где];
        }
        var я_ = я;
        foreach (var п in дом.people.Значения)
        {
            if (Знакомство.Знает(дом, я_, п))
                continue;
            foreach (var падеж in ПАДЕЖИ)
            {
                string форма = п.form(падеж);
                if (форма.Length == 0 || !т.Contains(форма, StringComparison.Ordinal))
                    continue;
                if (!_формы.TryGetValue(форма, out var r))
                    _формы[форма] = r = new Regex($@"(?<!\p{{L}}){Regex.Escape(форма)}(?!\p{{L}})");
                string вместо = Знакомство.Незнакомый(п, падеж);
                т = r.Replace(т, m => В_начале(т, m.Index) ? char.ToUpperInvariant(вместо[0]) + вместо[1..] : вместо);
            }
        }
        return т == текст ? null : т;
    }

    /// <summary>Совпадение стоит в начале строки (после отступа): слово
    /// с заглавной.</summary>
    private static bool В_начале(string т, int i)
    {
        for (int k = 0; k < i; k++)
            if (!char.IsWhiteSpace(т[k]))
                return false;
        return true;
    }
}
