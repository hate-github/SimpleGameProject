// Новости в телефоне (ГДД 19: «Новости: хроника надвигающейся катастрофы
// и мировой контекст»; «после дня 0 связь деградирует: … новости обрываются,
// к дню 10 сеть исчезает совсем»).
//
// До метели новости — летопись мира (`Летопись.Новости`: что говорят по радио
// в дни перед ней); в метель — события дня, которые дом и так узнаёт
// (◆ в ленте: встала котельная, не работает банк, перекрыли трассу). Телефон
// получает их, пока ловит сеть: после последнего дня со связью новостей нет,
// хотя жизнь в доме идёт дальше, — о ней теперь узнают только в подъезде.
//
// Только сборка того, что уже есть: новостей здесь не пишется.

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Новость: день и что сказали.</summary>
public sealed record Новость(int день, string текст);

public static class Новости
{
    /// <summary>
    /// Лента новостей телефона: <paramref name="до_метели"/> — новости
    /// летописи по дням (уже прошедшим), <paramref name="лента"/> — лента
    /// дня сеанса, из которой берутся события дня метели до
    /// <paramref name="последний_день_сети"/> включительно (null — метели ещё
    /// нет). По дням, в порядке, в каком случились. Сеть пропала раньше
    /// <paramref name="сегодня"/> — последней строкой сказано, что новостей
    /// больше не будет.
    /// </summary>
    public static IReadOnlyList<Новость> Лента(IEnumerable<Новость> до_метели,
                                               IEnumerable<СтрокаЛенты> лента,
                                               int? последний_день_сети, int сегодня)
    {
        var @out = до_метели.OrderBy(н => н.день).ToList();
        if (последний_день_сети is int по)
        {
            @out.AddRange(лента
                .Where(с => с.вид == ВидСтроки.СОБЫТИЕ && с.день <= по)
                .Select(с => new Новость(с.день, с.текст.TrimStart('◆', '◇', ' '))));
            if (по < сегодня)
                @out.Add(new Новость(по + 1, ОБОРВАЛОСЬ));
        }
        return @out;
    }

    /// <summary>Последняя строка, когда сеть пропала.</summary>
    public const string ОБОРВАЛОСЬ = "сети нет — новости кончились; что дальше, узнаешь в подъезде";

    /// <summary>Новости летописи с первого её дня по <paramref name="по_день"/>
    /// (дни пролога отрицательные).</summary>
    public static IEnumerable<Новость> Из_летописи(Летопись летопись, int с_дня, int по_день)
    {
        for (int д = с_дня; д <= по_день; д++)
            if (летопись.Новости(д) is string н)
                yield return new Новость(д, н);
    }
}
