// Записи вида → строки консоли.
//
// Это здесь, а не в консоли, ровно по одной причине: так слой вида
// оказывается доказанным. Консоль печатает не дом, а записи; стенограмма
// при этом обязана остаться знак в знак той же, что у прототипа, — а её
// сверяет и стоячая проверка «консоль», и приёмка на тридцать дней.
// Значит, если запись потеряла поле или соврала числом, это видно сразу
// и без Godot.
//
// Форматирование идёт через `Дом.Ядро.Текст` — тот же единственный путь,
// которым идёт весь вывод порта (ловушка 3 из `docs/ПОРТ.md`).

using Дом.Ядро;

namespace Дом.Экран;

public static class Печать
{
    /// <summary>Своё состояние двумя строками — как их печатала консоль.</summary>
    public static string Состояние(МоёСостояние с)
    {
        string шкаф = string.Join(", ", с.шкаф.Select(з => $"{з.ресурс} {Текст.G(з.сколько)}"));
        string хвост = с.беды.Count > 0 ? $" · {string.Join("; ", с.беды)}" : "";
        return $"  сыт {Текст.Ф(с.сыт, 0)} · вода {Текст.Ф(с.вода, 0)} · "
             + $"тепло {Текст.Ф(с.тепло, 0)} · сон {Текст.Ф(с.сон, 0)} · "
             + $"здоровье {Текст.Ф(с.здоровье, 0)} · паника {Текст.Ф(с.паника, 0)}{хвост}\n"
             + $"  в шкафу: {(шкаф.Length > 0 ? шкаф : "пусто")} · "
             + $"часов до ночи {Текст.Ф(с.часов_до_ночи, 1)}";
    }

    /// <summary>План подъезда строкой на квартиру.</summary>
    public static string План(IReadOnlyList<ЖилецНаПлане> план)
        => string.Join("\n", план.Select(ж =>
        {
            string начало = $"  кв{Текст.Слева(Ч(ж.квартира), 3)} {Текст.Слева(ж.имя, 9)} ";
            if (ж.здесь)
                return начало + ж.роль
                     + (ж.гостит_у is not null ? $", у {ж.гостит_у}" : "");
            string когда = ж.умер_днём is int д ? $"† день {д}" : "†";
            return начало + $"{когда} {ж.причина ?? ""}";
        }));

    /// <summary>Знание о соседях строкой на соседа.</summary>
    public static string Знание(IReadOnlyList<СоседВЗнании> знание)
        => string.Join("\n", знание.Select(с =>
            $"  {Текст.Слева(с.имя, 9)} "
            + $"еда {Текст.Ф(с.еда, 1)} · "
            + $"дрова {Текст.Ф(с.дрова, 1)} · "
            + $"знаю о нём {Текст.Ф(с.знаю_о_нём, 0)} · "
            + $"доверие {Текст.Ф(с.доверие, 1)}"));

    /// <summary>Карта строкой на место.</summary>
    public static string Карта(IReadOnlyList<МестоНаКарте> карта)
    {
        var строки = new List<string>();
        if (карта.Count > 0 && карта[0].закрыто)
            строки.Add($"  на улицу не выйти: мороз ниже предела одежды на "
                       + $"{Текст.Ф(-карта[0].запас_мороза, 0)}°");
        foreach (var м in карта)
            строки.Add($"  {Текст.Слева(м.имя, 20)} "
                       + $"{Текст.Справа(м.часы, 4, 1)} ч · "
                       + $"по-моему там {Текст.Ф(м.знаю * 100, 0)}%"
                       + (м.пусто ? " (пусто)" : "")
                       + $" · дорога {Текст.Ф(м.дорога, 1)}, люди {Текст.Ф(м.угроза, 1)}");
        return string.Join("\n", строки);
    }

    private static string Ч(int v)
        => v.ToString(System.Globalization.CultureInfo.InvariantCulture);
}
