// Что видит игрок — записями, а не строками.
//
// Пять вещей, которые движку нужны первыми (навык godot-boundary): своё
// состояние, план подъезда, знание о соседях, лента дня и поток событий.
// Шестая — вопрос — живёт в ядре (`ВопросИгроку`): вопрос задаёт дом,
// а экран его только показывает.
//
// Зачем записи, если консоль и так печатает строки. Затем, что строку
// нельзя подсветить, нельзя показать полоской и нельзя разобрать обратно.
// Пока вид был текстом, «сыт 85» существовало ровно один раз — в консоли;
// экрану пришлось бы либо разбирать текст, либо считать всё заново своими
// руками — и разойтись с консолью на первом же округлении.
//
// Обратной стрелки нет: ни одна запись отсюда в дом не пишется. Слой читает
// и складывает — и потому его можно звать из наблюдателя.

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Сколько чего лежит в шкафу или на полке.</summary>
public sealed record Запас(string ресурс, double сколько);

/// <summary>
/// Своё состояние: шесть шкал, шкаф и время до ночи.
///
/// Шкалы держатся числами, а не готовым «сыт 85»: экрану нужна полоска,
/// а консоли — та же строка, что была. Округление живёт там, где печатают.
/// </summary>
public sealed record МоёСостояние(
    string кто,
    string имя,
    int квартира,
    string роль,
    double сыт,
    double вода,
    double тепло,
    double сон,
    double здоровье,
    double паника,
    IReadOnlyList<Запас> шкаф,
    double часов_до_ночи,
    IReadOnlyList<string> раны,
    bool болен,
    bool женщина)
{
    /// <summary>Шесть шкал по порядку — тому же, в каком их печатает
    /// консоль и в каком их стоит показывать полосками.</summary>
    public IReadOnlyList<(string имя, double значение)> шкалы => new[]
    {
        ("сыт", сыт), ("вода", вода), ("тепло", тепло),
        ("сон", сон), ("здоровье", здоровье), ("паника", паника),
    };

    /// <summary>Чем ему плохо: раны и болезнь одним списком. Пусто —
    /// значит цел.</summary>
    public IReadOnlyList<string> беды
    {
        get
        {
            var б = new List<string>();
            if (раны.Count > 0)
                б.Add(string.Join(", ", раны));
            if (болен)
                б.Add(женщина ? "больна" : "болен");
            return б;
        }
    }
}

/// <summary>
/// Жилец на плане подъезда: где живёт, кем считается, жив ли.
///
/// Здесь только то, что и так видно соседу: номер квартиры, имя, занятие,
/// к кому переехал, и — если умер — когда и отчего. Шкаф, тело и чувства
/// сюда не попадают: они идут через <see cref="СоседВЗнании"/>, то есть
/// через знание игрока, а не через правду мира.
/// </summary>
public sealed record ЖилецНаПлане(
    int квартира,
    string id,
    string имя,
    string роль,
    bool здесь,
    int? умер_днём,
    string? причина,
    string? гостит_у);

/// <summary>
/// Квартира на плане подъезда — включая пустую.
///
/// План строится по квартирам, а не по жильцам, потому что пустая
/// квартира в этой игре — не дырка, а место: в неё переезжают, её
/// разбирают на доски, в ней жгут костёр, в ней остаётся тело хозяина.
/// Жильцов в доме пятнадцать, квартир больше, и разница видна глазом.
///
/// <c>кто</c> — хозяин, если он ещё здесь; гости идут отдельным списком,
/// потому что к одной двери приходят за всем, что за ней лежит.
/// </summary>
public sealed record КвартираНаПлане(
    int номер,
    int этаж,
    ЖилецНаПлане? кто,
    IReadOnlyList<ЖилецНаПлане> гости,
    bool разобрана,
    bool с_телом,
    bool горел,
    bool открыта);

/// <summary>
/// Что игрок знает о соседе — именно знает, а не что есть на самом деле.
///
/// <c>еда</c> и <c>дрова</c> — оценка чужого шкафа (`believed`), она бывает
/// и неверной. <c>знаю_о_нём</c> — насколько игрок вообще в курсе его дел
/// (`Сведения.aware`). Это тот самый предел, ради которого знание отделено
/// от правды: экран не вправе показать больше.
/// </summary>
public sealed record СоседВЗнании(
    string id,
    string имя,
    int квартира,
    double еда,
    double дрова,
    double знаю_о_нём,
    double доверие);

/// <summary>
/// Откуда взялась строка ленты.
///
/// Различать их приходится потому, что показывают их в разных местах:
/// ход — в журнале дня, чат — в телефоне, секрет — только когда игрок сам
/// попросил показать то, чего дом не знает. По тексту это не определить:
/// «◆» и «[чат]» — украшение консоли, а не признак.
/// </summary>
public enum ВидСтроки
{
    ХОД,            // чей-то ход или то, что он за собой потянул
    СОБЫТИЕ,        // событие дня: метель, отключения, скриптовое
    СЕКРЕТ,         // то, чего дом не знает: кто украл, кто подбросил
    ЧАТ,            // реплика в общем чате жильцов
}

/// <summary>
/// Место на карте (ГДД 20).
///
/// Четыре свойства и одно знание. Свойства — сколько идти, насколько
/// опасна дорога, насколько опасны люди и «дико ли туда идти, пока жизнь
/// ещё похожа на прежнюю»; они одинаковы для всех и известны каждому,
/// кто живёт в этом дворе.
///
/// А <c>знаю</c> — личное: сколько там, по мнению героя, осталось. Он
/// считает, что в магазине всё как до метели, пока сам не сходил или пока
/// ему не рассказали, — и врать об этом законный ход. Правды мира
/// (<c>h.богатство_места</c>) на карте нет и быть не должно: с ней
/// «где ещё что-то есть» перестаёт быть предметом обмена и вранья.
/// </summary>
public sealed record МестоНаКарте(
    string имя,
    string куда,
    double часы,
    double знаю,                // 1.0 — «там всё как было»; 0 — «выгребли»
    double дорога,              // лёд, темнота, расстояние: от неё ломают ногу
    double угроза,              // люди: от них отнимают пакет
    bool магазин,
    bool пусто,                 // по его сведениям там уже нечего брать
    bool закрыто,               // мороз ниже предела одежды — не выйти вовсе
    double запас_мороза);       // сколько градусов до этого предела

/// <summary>
/// Строка ленты дня: время на личных часах, текст и насколько это заметно.
///
/// <c>час</c> — то, что журнал ставит перед строкой («08:30»); у строк
/// без времени его нет. <c>скрытая</c> — то, чего дом не знает: показывать
/// её можно только при включённых секретах.
/// </summary>
public sealed record СтрокаЛенты(
    int день,
    string? час,
    string текст,
    int заметность,
    bool скрытая,
    ВидСтроки вид = ВидСтроки.ХОД);
