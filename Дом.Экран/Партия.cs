// Партия: сыгранная метель, у которой посредине стоит человек.
//
// Задача этого файла одна и она неочевидная. Ядро синхронно и обязано таким
// остаться: оно перенесено с Python дословно, и любая переделка под async
// переставила бы вызовы, а с ними — броски `rng`. Значит, `Решающий.Человек`
// как звал `спросить(вопрос) → номер` и ждал ответа прямо в кадре решения,
// так и зовёт.
//
// А экран ждать не может. `_Process` обязан вернуться, иначе окно замрёт,
// и игрок не то что не ответит — он даже вопроса не увидит.
//
// Развязка: симуляция живёт на своём потоке и на вопросе засыпает, экран
// живёт на своём и её будит. Ни одного изменения в ядре это не потребовало.
//
// Проверяется без движка: то же самое делает консоль в проверке «партия» —
// гоняет дом на потоке, отвечает с главного и сверяет стенограмму. Если мост
// потеряет вопрос, переставит ответ или заклинит — покраснеет там, а не
// на сцене.

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>
/// Метель, которую играет человек: дом на своём потоке, вопросы — сюда.
///
/// Порядок работы у зовущего такой:
/// <code>
///   var партия = new Партия(прогон, "оксана");
///   партия.Начать();
///   // в каждом кадре:
///   if (партия.Ждёт() is ВопросИгроку в) { показать(в); }
///   // по нажатию:
///   партия.Ответить(номер);
/// </code>
/// </summary>
public sealed class Партия : IDisposable
{
    private readonly Прогон _прогон;
    private readonly SemaphoreSlim _ответ_готов = new(0, 1);
    private readonly object _замок = new();

    private ВопросИгроку? _вопрос;
    private int _ответ;
    private Thread? _поток;
    private Exception? _беда;

    /// <param name="прогон">Заведённый, но ещё не пущенный прогон.</param>
    /// <param name="кто">id играющего жильца.</param>
    /// <param name="журнал">Журнал, который кладёт строки в ленту сеанса.
    /// Если не дан — заводится свой.</param>
    public Партия(Прогон прогон, string кто, ЛентаЖурнал? журнал = null)
    {
        _прогон = прогон;
        сеанс = new Сеанс(прогон.h, кто);
        this.журнал = журнал ?? new ЛентаЖурнал(сеанс);
        прогон.h.journal = this.журнал;
        сеанс.я.решающий = new Человек(Спросить);
    }

    /// <summary>Дом и три экрана к нему.</summary>
    public Сеанс сеанс { get; }

    /// <summary>Журнал, складывающий строки в ленту сеанса.</summary>
    public ЛентаЖурнал журнал { get; }

    /// <summary>Метель кончилась (или игрок вышел, или дом упал).</summary>
    public bool кончилась { get; private set; }

    /// <summary>Чем кончилось, если упало. Экран обязан это показать,
    /// а не проглотить: молча погасший дом — худшее, что может случиться
    /// с игроком.</summary>
    public Exception? беда => _беда;

    /// <summary>Пустить дом. Возвращается сразу: считает он на своём потоке.</summary>
    public void Начать()
    {
        if (_поток is not null)
            throw new InvalidOperationException("партия уже идёт");
        _поток = new Thread(Считать)
        {
            IsBackground = true,        // окно закрыли — поток не держит процесс
            Name = "дом",
        };
        _поток.Start();
    }

    private void Считать()
    {
        try
        {
            _прогон.run();
        }
        catch (Exception e)
        {
            _беда = e;
        }
        finally
        {
            lock (_замок)
            {
                _вопрос = null;
                кончилась = true;
            }
        }
    }

    /// <summary>
    /// Есть ли сейчас вопрос. Не блокирует — зовётся хоть каждый кадр.
    /// </summary>
    public ВопросИгроку? Ждёт()
    {
        lock (_замок)
            return _вопрос;
    }

    /// <summary>
    /// Ответить номером варианта и разбудить дом.
    ///
    /// Номер зажимается в границы там же, где зажимался в шве: мимо списка —
    /// ближайший край. Экран, который не даст нажать мимо, до этого
    /// не доведёт, но правило одно и то же и для него, и для консоли.
    /// </summary>
    public void Ответить(int номер)
    {
        lock (_замок)
        {
            if (_вопрос is null)
                return;                 // никто не спрашивал — нечего отвечать
            _ответ = номер;
            _вопрос = null;
        }
        _ответ_готов.Release();
    }

    /// <summary>Дождаться, пока дом задаст вопрос или кончится. Нужно тем,
    /// кто играет не кадрами, а по шагам, — то есть проверке.</summary>
    public ВопросИгроку? Дождаться(int мс = 30_000)
    {
        var срок = DateTime.UtcNow.AddMilliseconds(мс);
        while (DateTime.UtcNow < срок)
        {
            var в = Ждёт();
            if (в is not null || кончилась)
                return в;
            Thread.Sleep(1);
        }
        throw new TimeoutException("дом не задал вопроса и не кончился");
    }

    /// <summary>Дождаться конца метели.</summary>
    public void Досидеть(int мс = 600_000)
    {
        if (_поток is null)
            return;
        if (!_поток.Join(мс))
            throw new TimeoutException("дом не досчитал");
        if (_беда is not null)
            throw new InvalidOperationException("дом упал", _беда);
    }

    /// <summary>Тот самый спрашивающий, которого ждёт `Человек`. Зовётся
    /// на потоке дома и на нём же засыпает.</summary>
    private int Спросить(ВопросИгроку в)
    {
        lock (_замок)
            _вопрос = в;
        _ответ_готов.Wait();
        lock (_замок)
            return _ответ;
    }

    public void Dispose() => _ответ_готов.Dispose();
}
