// Тела людей автора (`Дом.Годот/модели/люди`): файл Mixamo, в котором тело
// и вещи на нём, и чем красить каждую часть (просьба автора 29.09.2026 —
// «вариации людей, верхняя одежда»; уговор с ним — `референсы/люди_нужны.txt`).
//
// Не пятнадцать моделей на пятнадцать соседей, а набор: тело и вещи на одном
// скелете, одна сетка на вещь. Каждого соседа движок собирает из набора сам
// и красит своими цветами (`Дом.Годот.Люди`).
//
// **Зона тела** — материал сетки тела, как его назвал автор: tors, arms, head,
// face zone, hands, legs, foots. Чем её красить — таблица: кожа, кофта, брюки,
// обувь — цветами соседа; цвет зоны в файле не значит ничего. Кофта (торс
// и руки до запястья) под верхней вещью прячется: так тело не протыкает ткань
// на ходу, а дыры не остаётся — куртка закрывает кофту целиком, это сверено
// лучами по сеткам ещё до Mixamo (рукав заходит за границу кисти, низ куртки —
// на 4 см ниже границы торса и ног).
//
// **Вещь** — своя сетка в том же файле, на том же скелете. Её материалы
// краска разбирает по цвету из файла (`Покраска`): серый — без оттенка —
// красится цветом соседа для этой вещи, и чем темнее серый, тем темнее цвет;
// цветной остаётся цветом автора (молния, мех, камуфляж). Эталон серого — 0.8,
// цвет нового материала в Blender: такой серый даёт ровно цвет соседа.
// Цвета — линейные, как их пишет Blender в FBX (движок показывает их в sRGB
// и переводит обратно).
//
// Таблица — не догадка о файле, а закрытый список: раздел консоли «люди»
// читает FBX и сверяет — каждая зона есть в сетке тела, каждый материал тела
// есть в зонах, каждая вещь — сетка файла, и лишних сеток нет: лишняя
// оказалась бы на всех соседях сразу.

namespace Дом.Экран;

/// <summary>Чем красить часть тела или вещи. Номер — тот же, что `role` в шейдере людей.</summary>
public enum Краска
{
    СВОЯ,       // цвет из файла, как покрасил автор
    ВЕРХ,       // верхняя вещь — пальто соседа
    КОФТА,      // торс и руки: под верхней вещью прячутся
    КОЖА,
    БРЮКИ,
    ОБУВЬ,
}

/// <summary>Вещь на теле: сетка в файле тела и чем красить её серые части.</summary>
public sealed record ВещьТела(string сетка, Краска краска);

/// <summary>Тело: файл в `модели/люди` (без .fbx), сетка тела в нём, зоны
/// (материал → краска) и вещи на том же скелете.</summary>
public sealed record Тело(string файл, string сетка, IReadOnlyDictionary<string, Краска> зоны,
                          IReadOnlyList<ВещьТела> вещи)
{
    /// <summary>Зоны, которые под верхней вещью прячутся, — кофта.</summary>
    public IEnumerable<string> под_верхом => зоны.Where(з => з.Value == Краска.КОФТА).Select(з => з.Key);
}

public static class Тела
{
    /// <summary>Разброс каналов, ниже которого цвет — серый.</summary>
    public const double СЕРОЕ = 0.02;

    /// <summary>Серый, дающий ровно цвет соседа: 0.8 — новый материал Blender.</summary>
    public const double ЭТАЛОН = 0.8;

    /// <summary>Мужское тело с курткой уровня 0 («до −19°») — 30.09.2026.</summary>
    public static readonly Тело МУЖЧИНА = new("мужчина", "human",
        new Dictionary<string, Краска>(StringComparer.Ordinal)
        {
            ["tors"] = Краска.КОФТА,
            ["arms"] = Краска.КОФТА,
            ["head"] = Краска.КОЖА,
            ["face zone"] = Краска.КОЖА,
            ["hands"] = Краска.КОЖА,
            ["legs"] = Краска.БРЮКИ,
            ["foots"] = Краска.ОБУВЬ,
        },
        new[] { new ВещьТела("jacket(-19 male)", Краска.ВЕРХ) });

    public static readonly IReadOnlyList<Тело> ВСЕ = new[] { МУЖЧИНА };

    /// <summary>
    /// Чем красить материал вещи с таким цветом из файла (линейный, как
    /// в Blender): серый — краской вещи, с долей яркости от эталона;
    /// цветной — своим цветом.
    /// </summary>
    public static (Краска краска, double доля) Покраска(Краска вещи, double r, double g, double b)
    {
        double разброс = Math.Max(r, Math.Max(g, b)) - Math.Min(r, Math.Min(g, b));
        return разброс < СЕРОЕ ? (вещи, (r + g + b) / 3 / ЭТАЛОН) : (Краска.СВОЯ, 1.0);
    }
}
