// Тела людей автора (`Дом.Годот/модели/люди`): файл Mixamo, в котором тело
// и вещи на нём, и чем красить каждую часть (просьба автора 29.09.2026 —
// «вариации людей, верхняя одежда»; уговор с ним — `референсы/люди_нужны.txt`).
//
// Не пятнадцать моделей на пятнадцать соседей, а набор: тело и вещи на одном
// скелете, одна сетка на вещь. Каждого соседа движок собирает из набора сам
// и красит своими цветами (`Дом.Годот.Люди`).
//
// **Зона тела** — материал сетки тела, как его назвал автор: tors, arms, head,
// face zone, hands, legs, foots. Чем её красить — таблица: кожа, кофта, брюки,
// обувь — цветами соседа; цвет зоны в файле не значит ничего.
//
// **Вещь** — своя сетка в том же файле, на том же скелете. Её материалы
// краска разбирает по цвету из файла (`Покраска`): серый — без оттенка —
// красится цветом соседа для этой вещи, и чем темнее серый, тем темнее цвет;
// цветной остаётся цветом автора (молния, мех, камуфляж). Эталон серого — 0.8,
// цвет нового материала в Blender: такой серый даёт ровно цвет соседа; вещь
// без материала (перчатки 02.10) — тот же эталон. Цвета — линейные, как их
// пишет Blender в FBX (движок показывает их в sRGB и переводит обратно).
//
// **Под вещью зона прячется** (`ВещьТела.прячет`): так тело не протыкает ткань
// на ходу — веса у одежды свои, и колено, локоть, макушка выходят наружу.
// Прятать можно только то, что одежда закрывает целиком, иначе на месте зоны
// дыра; это сверено лучами по сеткам до встройки (`scratchpad/люди_вещи.py`):
// куртка закрывает торс и руки (рукав заходит за границу кисти, низ — на 4 см
// ниже границы торса и ног), штаны с ботинками — ноги, ботинки — ступни,
// перчатки с рукавами — кисти. Шапка не прячет ничего: голова — это и лицо.
// Одна полоска торса у шеи под воротником не закрыта и была такой и с одной
// курткой: при почти чёрной куртке её не видно.
//
// Таблица — не догадка о файле, а закрытый список: раздел консоли «люди»
// читает FBX и сверяет — каждая зона есть в сетке тела, каждый материал тела
// есть в зонах, каждая вещь — сетка файла, и лишних сеток нет: лишняя
// оказалась бы на всех соседях сразу; что вещь прячет — зоны тела, у каждой
// краски есть свой цвет в шейдере.

namespace Дом.Экран;

/// <summary>Чем красить часть тела или вещи. Номер — тот же, что `role` в шейдере людей.</summary>
public enum Краска
{
    СВОЯ,       // цвет из файла, как покрасил автор
    ВЕРХ,       // верхняя вещь — пальто соседа
    КОФТА,      // торс и руки: под верхней вещью прячутся
    КОЖА,
    БРЮКИ,
    ОБУВЬ,
    ШАПКА,
    ПЕРЧАТКИ,
}

/// <summary>Вещь на теле: сетка в файле тела, чем красить её серые части
/// и какие зоны тела под ней прячутся.</summary>
public sealed record ВещьТела(string сетка, Краска краска, IReadOnlyList<string> прячет);

/// <summary>Тело: файл в `модели/люди` (без .fbx), сетка тела в нём, зоны
/// (материал → краска) и вещи на том же скелете.</summary>
public sealed record Тело(string файл, string сетка, IReadOnlyDictionary<string, Краска> зоны,
                          IReadOnlyList<ВещьТела> вещи)
{
    /// <summary>Зоны, которые прячутся под надетыми вещами.</summary>
    public IEnumerable<string> под_вещами => вещи.SelectMany(в => в.прячет).Distinct(StringComparer.Ordinal);
}

public static class Тела
{
    /// <summary>Разброс каналов, ниже которого цвет — серый.</summary>
    public const double СЕРОЕ = 0.02;

    /// <summary>Серый, дающий ровно цвет соседа: 0.8 — новый материал Blender.</summary>
    public const double ЭТАЛОН = 0.8;

    /// <summary>Мужское тело с курткой уровня 0 («до −19°») — 30.09.2026;
    /// штаны, ботинки, перчатки и шапка — 02.10.2026.</summary>
    public static readonly Тело МУЖЧИНА = new("мужчина", "human",
        new Dictionary<string, Краска>(StringComparer.Ordinal)
        {
            ["tors"] = Краска.КОФТА,
            ["arms"] = Краска.КОФТА,
            ["head"] = Краска.КОЖА,
            ["face zone"] = Краска.КОЖА,
            ["hands"] = Краска.КОЖА,
            ["legs"] = Краска.БРЮКИ,
            ["foots"] = Краска.ОБУВЬ,
        },
        new[]
        {
            new ВещьТела("jacket(-19 male)", Краска.ВЕРХ, new[] { "tors", "arms" }),
            new ВещьТела("pants", Краска.БРЮКИ, new[] { "legs" }),          // низ ног — в ботинках
            new ВещьТела("boots", Краска.ОБУВЬ, new[] { "foots" }),
            new ВещьТела("gloves", Краска.ПЕРЧАТКИ, new[] { "hands" }),     // запястье — под рукавом
            new ВещьТела("hat", Краска.ШАПКА, Array.Empty<string>()),
        });

    public static readonly IReadOnlyList<Тело> ВСЕ = new[] { МУЖЧИНА };

    /// <summary>Имя цвета соседа для краски в шейдере людей (`instance uniform`);
    /// у своей краски его нет — цвет из файла.</summary>
    public static string? Униформа(Краска к) => к switch
    {
        Краска.ВЕРХ => "coat",
        Краска.КОФТА => "shirt",
        Краска.КОЖА => "skin",
        Краска.БРЮКИ => "pants",
        Краска.ОБУВЬ => "boots",
        Краска.ШАПКА => "hat",
        Краска.ПЕРЧАТКИ => "gloves",
        _ => null,
    };

    /// <summary>
    /// Чем красить материал вещи с таким цветом из файла (линейный, как
    /// в Blender): серый — краской вещи, с долей яркости от эталона;
    /// цветной — своим цветом.
    /// </summary>
    public static (Краска краска, double доля) Покраска(Краска вещи, double r, double g, double b)
    {
        double разброс = Math.Max(r, Math.Max(g, b)) - Math.Min(r, Math.Min(g, b));
        return разброс < СЕРОЕ ? (вещи, (r + g + b) / 3 / ЭТАЛОН) : (Краска.СВОЯ, 1.0);
    }
}
