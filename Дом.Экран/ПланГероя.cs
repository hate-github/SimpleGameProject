// План подъезда глазами героя (просьба автора: «убери из плана подъезда то,
// чего герой знать не может»).
//
// `Сеанс.План()` и `Квартиры()` — правда дома: ими рисуются двери в мире
// (подойди и увидишь) и печатает консоль. На плане же — только то, что
// герой знает сам:
//
//   · **кто где живёт** — все, кроме умерших, о чьей смерти он знает
//     (`знает_о_смерти`): не знает — сосед для него жив и живёт у себя;
//     имя и занятие — только у знакомых (`Знакомство`), прочие — «сосед»;
//   · **что с дверью** (разобрана, замок сорван, копоть костра) — какой
//     он видел её в последний раз, проходя по этажу (`Увидел_этаж`, зовёт
//     движок); не был на этаже — не знает;
//   · **тело** — только если знает о смерти;
//   · **что случилось за три дня** — то, при чём он был: сделал сам;
//     случилось с ним, пока он был дома (или видно, когда вернулся);
//     громкое (налёт, убийство, пожар, собрание, изгнание), пока он был
//     в доме; тихое чужое — только если в тот день он слышал, видел или
//     ему сказали про того, кто это сделал (его память); смерть — если
//     знает о ней;
//   · **кого нет** — умершие, о чьей смерти он знает, и изгнанные.
//
// Как всё в сеансе, читается только пока дом спит на вопросе.

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Квартира на плане глазами героя. <c>кто</c> null — пусто;
/// <c>роль</c> пустая — занятия не знает.</summary>
public sealed record КвартираГероя(int номер, int этаж, string? кто, string роль,
                                   IReadOnlyList<string> гости, IReadOnlyList<string> метки,
                                   IReadOnlyList<Событие> события);

/// <summary>Кого нет — из того, что герой знает: умер (день, причина) или изгнан.</summary>
public sealed record ВыбылГероя(int квартира, string имя, int? день, string? причина);

/// <summary>Какой герой видел дверь в последний раз: день и что с ней было.</summary>
public sealed record ВиделДверь(int день, bool разобрана, bool открыта, bool костёр);

public sealed partial class Сеанс
{
    /// <summary>Громкое: пока герой в доме, об этом знает весь подъезд.</summary>
    private static readonly HashSet<ВидСобытия> ГРОМКИЕ = new()
    {
        ВидСобытия.НАЛЁТ, ВидСобытия.ИСХОД, ВидСобытия.УБИЙСТВО, ВидСобытия.ПОЖАР,
        ВидСобытия.СОБРАНИЕ, ВидСобытия.ИЗГНАНИЕ,
    };

    private readonly List<bool> _знал = new();                 // рядом с `_события`: знал ли сразу
    private readonly Dictionary<int, ВиделДверь> _видел = new();

    /// <summary>Знал ли герой событие в ту минуту, когда оно случилось
    /// (зовётся подпиской на потоке дома — там же, где пишется событие).</summary>
    private bool Знал_сразу(Событие с)
    {
        if (string.Equals(с.кто, я.id, StringComparison.Ordinal))
            return true;
        if (я.нет_в_доме())
            return false;
        return ГРОМКИЕ.Contains(с.вид) || string.Equals(с.кому, я.id, StringComparison.Ordinal);
    }

    /// <summary>Знает ли герой это событие сейчас.</summary>
    private bool Знает_событие(int i)
    {
        var с = _события[i];
        if (_знал[i])
            return true;
        // случилось с ним, пока его не было, — видно, когда вернулся
        if (string.Equals(с.кому, я.id, StringComparison.Ordinal) && !я.нет_в_доме())
            return true;
        if (с.вид == ВидСобытия.СМЕРТЬ && с.кто is string мёртвый && я.знает_о_смерти.Contains(мёртвый))
            return true;
        // слышал, видел, сказали — в тот же день про того, кто это делал
        return с.кто is string кто
               && я.memory.Any(з => з.день == с.день && string.Equals(з.кто, кто, StringComparison.Ordinal));
    }

    /// <summary>Знает ли герой, что этого человека больше нет: умер — если
    /// знает о смерти; изгнан — всегда (дом решает это на площадке, вслух).</summary>
    private bool Знает_что_нет(NPC п)
        => п.exiled || !п.alive && я.знает_о_смерти.Contains(п.id);

    /// <summary>
    /// Герой на этом этаже (движок зовёт, пока дом спит): видит его двери —
    /// разобрана ли квартира, сорван ли замок, копоть ли от костра.
    /// </summary>
    public void Увидел_этаж(int этаж)
    {
        foreach (var f in дом.flats.Значения)
            if (f.floor == этаж)
                _видел[f.apt] = new ВиделДверь(дом.day, f.stripped > 0, f.открыта, дом.day - f.костёр < 3);
    }

    /// <summary>Какой герой видел эту дверь в последний раз — или null: не видел.</summary>
    public ВиделДверь? Видел_дверь(int квартира) => _видел.TryGetValue(квартира, out var в) ? в : null;

    /// <summary>План подъезда глазами героя — по квартирам, снизу вверх по номерам.</summary>
    public IReadOnlyList<КвартираГероя> План_героя(int за_дней = 3)
    {
        // кто где живёт, как он думает: у своей двери (к хозяину переехал —
        // у хозяйской); кого нет и он это знает — нигде
        var у_двери = new Dictionary<int, List<NPC>>();
        foreach (var п in дом.people.Значения.OrderBy(x => x.apt))
        {
            if (Знает_что_нет(п))
                continue;
            int дверь = п.здесь() ? дом.хозяин_жилья(п).apt : п.apt;
            if (!у_двери.TryGetValue(дверь, out var список))
                у_двери[дверь] = список = new List<NPC>();
            список.Add(п);
        }
        List<Событие> события;
        lock (_замок)
            события = Enumerable.Range(0, _события.Count)
                .Where(i => дом.day - _события[i].день < за_дней && Знает_событие(i))
                .Select(i => _события[i]).ToList();

        var @out = new List<КвартираГероя>();
        foreach (var f in дом.flats.Значения.OrderBy(x => x.apt))
        {
            у_двери.TryGetValue(f.apt, out var живут);
            // хозяин — тот, чья это квартира; прочие — у него в гостях
            var хозяин = живут?.FirstOrDefault(п => п.apt == f.apt) ?? живут?.FirstOrDefault();
            var гости = (живут ?? new List<NPC>()).Where(п => !ReferenceEquals(п, хозяин))
                .Select(Имя_на_плане).ToList();
            var метки = new List<string>();
            if (Видел_дверь(f.apt) is { } в)
            {
                if (в.разобрана)
                    метки.Add("разобрана");
                if (в.костёр)
                    метки.Add("костёр");
                if (в.открыта)
                    метки.Add("открыта");
            }
            if (f.body is not null && f.owner_died is string чьё && я.знает_о_смерти.Contains(чьё))
                метки.Add("тело");
            @out.Add(new КвартираГероя(
                f.apt, f.floor,
                хозяин is null ? null : Имя_на_плане(хозяин),
                хозяин is not null && Знакомство.Знает(дом, я, хозяин) ? хозяин.role : "",
                гости, метки,
                события.Where(с => с.где == f.apt).ToList()));
        }
        return @out;
    }

    /// <summary>Кого нет — из того, что герой знает.</summary>
    public IReadOnlyList<ВыбылГероя> Выбыли_героя()
        => дом.people.Значения.OrderBy(x => x.apt)
            .Where(п => !п.здесь() && Знает_что_нет(п))
            .Select(п => new ВыбылГероя(п.apt, Имя_на_плане(п), п.alive ? null : п.died_day,
                                        п.alive ? "выставлен из дома" : п.cause))
            .ToList();

    /// <summary>Имя на плане: знакомый — по имени, незнакомый — «сосед» (номер квартиры план пишет сам).</summary>
    private string Имя_на_плане(NPC п)
        => ReferenceEquals(п, я) || Знакомство.Знает(дом, я, п) ? п.@short : Знакомство.Сосед(п);
}
