// Еда героя на экране (docs/ЕДА_ПЛАН.md, этап 2): ячейки инвентаря,
// подписи, описание, какой вариант модели показать.
//
// Без движка нарочно, как вся подача: экран Godot только рисует то,
// что здесь посчитано, и потому слой проверяется из консоли. Ячейка —
// **стопка одинаковых вещей в одном месте**: две закрытые свежие банки
// свинины на полке — одна ячейка «×2», а початая третья — своя: её
// и выглядит иначе, и есть её надо раньше.
//
// Имя варианта модели — договор с автором (`модели/ЧИТАЙ.md`): у банок
// «pork unopen fresh», «pork open half expired», у хлеба «full fresh»,
// «half mold». Здесь — список имён по порядку: экран берёт первое,
// которое нашлось в файле. Нужен список, а не одно имя: у сгущёнки нет
// «fresh/expired», у шпрот открытые варианты названы «pork».

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>Стопка одинаковых вещей в одном месте — одна ячейка.</summary>
public sealed record ЯчейкаЕды(
    МестоЕды где,
    string вид,
    string имя,
    int штук,
    IReadOnlyList<int> номера,       // вещи стопки: первой — та, что съедят первой
    Свежесть свежесть,
    string состояние,                // «закрытая», «початая», «половина», «в плесени»…
    double порций,                   // всего в стопке
    string модель,
    IReadOnlyList<string> меши,      // имена варианта, по порядку
    string подпись,                  // при наведении
    string описание);                // в карточке

public static class Инвентарь
{
    /// <summary>«день», «дня», «дней».</summary>
    public static string Дней(double дней)
    {
        int н = (int)Math.Floor(дней);
        int д = н % 100, е = н % 10;
        string слово = д is >= 11 and <= 14 ? "дней" : е == 1 ? "день" : е is >= 2 and <= 4 ? "дня" : "дней";
        return $"{н} {слово}";
    }

    /// <summary>«1 порция», «2 порции», «0.5 порции», «5 порций».</summary>
    public static string Порций(double сколько)
    {
        double округ = Текст.Округлить(сколько, 2);
        if (Math.Abs(округ - Math.Round(округ)) > 1e-9)
            return $"{Текст.G(округ)} порции";
        int н = (int)Math.Round(округ);
        int д = н % 100, е = н % 10;
        string слово = д is >= 11 and <= 14 ? "порций" : е == 1 ? "порция" : е is >= 2 and <= 4 ? "порции" : "порций";
        return $"{н} {слово}";
    }

    /// <summary>Какая часть вещи осталась — словом для подписи и ключом стопки.</summary>
    public static string Часть(ВидЕды в, Продукт п, double доля)
    {
        if (в.род != РодЕды.БАНКА)
            return в.Часть(доля)?.слово ?? "";
        if (!п.открыт)
            return "закрытая";
        return доля >= 0.95 ? "открытая" : "початая";
    }

    public static string Свежесть_словом(ВидЕды в, Свежесть с) => с switch
    {
        Свежесть.СВЕЖАЯ => в.свежий,
        Свежесть.ПРОСРОЧЕНА => "просрочена",
        _ => в.испорчен,
    };

    /// <summary>Имена варианта модели, по порядку: первое найденное в файле
    /// и показывается.</summary>
    public static IReadOnlyList<string> Меши(ВидЕды в, Продукт п, Свежесть с, double доля)
    {
        if (в.род != РодЕды.БАНКА)
        {
            // хлеб и овощ: «{часть} fresh|mold» — «full mold», «1 kg fresh»
            string часть = в.Часть(доля)?.меш ?? "full";
            string вид = с == Свежесть.СВЕЖАЯ ? "fresh" : "mold";
            string целый = в.части.Count > 0 ? в.части[0].меш : "full";
            return new[] { $"{часть} {вид}", $"{часть} fresh", $"{целый} fresh" };
        }
        string как = !п.открыт ? "unopen" : доля >= 0.95 ? "open full" : "open half";
        string срок = с == Свежесть.СВЕЖАЯ ? "fresh" : "expired";
        return new[]
        {
            $"{в.меш} {как} {срок}",
            $"{как} {срок}",            // у шпрот открытые названы «pork»
            $"{в.меш} {как}",           // у сгущёнки свежести нет
            $"{в.меш} unopen fresh",
            $"{в.меш} unopen",
        };
    }

    /// <summary>Ячейки места: стопки по виду, части и свежести; в порядке
    /// «что съедят первым» внутри стопки и по имени между стопками.</summary>
    public static IReadOnlyList<ЯчейкаЕды> Ячейки(Продукты продукты, МестоЕды где, double порция)
    {
        var стопки = new List<ЯчейкаЕды>();
        var вещи = продукты.В(где)
            .OrderBy(п => продукты.Вид(п).имя, StringComparer.Ordinal)
            .ThenByDescending(п => п.открыт)
            .ThenBy(п => продукты.Дней_до_порчи(п))
            .ThenBy(п => п.номер)
            .ToList();
        foreach (var группа in вещи.GroupBy(п =>
                 {
                     var в = продукты.Вид(п);
                     return (п.вид, Часть(в, п, продукты.Доля(п)), продукты.Свежесть(п));
                 }))
        {
            var первая = группа.First();
            var в = продукты.Вид(первая);
            var с = продукты.Свежесть(первая);
            string часть = Часть(в, первая, продукты.Доля(первая));
            int штук = группа.Count();
            double порций = группа.Sum(п => п.единиц);
            string свежесть = Свежесть_словом(в, с);
            string состояние = в.род != РодЕды.БАНКА
                ? (в.части.Count > 0 && часть == в.части[0].слово && в.род == РодЕды.ХЛЕБ ? свежесть : $"{часть}, {свежесть}")
                : часть == "закрытая"
                    ? (с == Свежесть.СВЕЖАЯ ? "целая банка" : $"банка {свежесть}")
                    : $"{часть} банка" + (с == Свежесть.СВЕЖАЯ ? "" : $", {свежесть}");
            string подпись = $"{в.имя}{(штук > 1 ? $" ×{штук}" : "")} — {состояние}";
            стопки.Add(new ЯчейкаЕды(
                где, в.id, в.имя, штук, группа.Select(п => п.номер).ToList(), с, состояние, порций,
                в.модель, Меши(в, первая, с, продукты.Доля(первая)), подпись,
                Описание(продукты, первая, где, порция, штук)));
        }
        return стопки;
    }

    /// <summary>Текст карточки: что это, сколько насыщает, свежесть и срок.</summary>
    public static string Описание(Продукты продукты, Продукт п, МестоЕды где, double порция, int штук = 1)
    {
        var в = продукты.Вид(п);
        var с = продукты.Свежесть(п);
        var строки = new List<string>();
        string часть = Часть(в, п, продукты.Доля(п));
        строки.Add(в.род != РодЕды.БАНКА
            ? $"{часть}, {Свежесть_словом(в, с)}"
            : $"{(часть == "закрытая" ? "закрытая банка" : часть == "открытая" ? "открытая банка" : "початая банка")}, {Свежесть_словом(в, с)}");
        double сытости = п.единиц * порция * в.сырым;
        строки.Add(в.сырым < 1.0
            ? $"сырой насыщает мало: {Текст.G(Math.Round(сытости))} сытости из 100 — "
              + $"сваренный дал бы {Текст.G(Math.Round(п.единиц * порция))}"
            : $"насыщает: {Порций(п.единиц)} — "
              + $"{Текст.G(Math.Round(сытости))} сытости из 100"
              + (в.настроение > 0 && с == Свежесть.СВЕЖАЯ ? ", и настроение получше" : ""));
        double до = продукты.Дней_до_порчи(п);
        строки.Add(с switch
        {
            Свежесть.СВЕЖАЯ when в.род == РодЕды.ХЛЕБ => до < 1 ? "к завтрашнему дню зацветёт" : $"зацветёт через {Дней(до)}",
            Свежесть.СВЕЖАЯ when в.род == РодЕды.ОВОЩ => до > 60 ? "лежит долго" : до < 1 ? "завтра начнёт гнить" : $"начнёт гнить через {Дней(до)}",
            Свежесть.СВЕЖАЯ when п.открыт => до < 1 ? "открыта — завтра испортится" : $"открыта — испортится через {Дней(до)}",
            Свежесть.СВЕЖАЯ => до > 60 ? "годна ещё долго" : $"годна ещё {Дней(до)}",
            Свежесть.ПРОСРОЧЕНА => "срок вышел — есть можно, но можно и отравиться",
            _ => в.род == РодЕды.БАНКА ? "испортилась — отравиться легко" : $"{в.испорчен} — отравиться легко",
        });
        if (где == МестоЕды.КАРМАН)
            строки.Add("в кармане вне времени портится вчетверо медленнее");
        if (штук > 1)
            строки.Add($"таких здесь {штук}");
        строки.Add("");
        строки.Add(в.описание);
        return string.Join("\n", строки);
    }

    /// <summary>«Тушёнка свиная ×2, шпроты» — для окна находки и вестей.</summary>
    public static string Словами(Продукты продукты, IEnumerable<Продукт> что)
        => string.Join(", ", что
            .GroupBy(п => продукты.Вид(п).имя)
            .OrderBy(г => г.Key, StringComparer.Ordinal)
            .Select((г, i) =>
            {
                string имя = i == 0 ? г.Key : г.Key.ToLowerInvariant();
                return г.Count() > 1 ? $"{имя} ×{г.Count()}" : имя;
            }));
}
