// Подача (ГДД 23): что видно и что слышно — данными, а не кодом сцены.
//
// «Звук — основной носитель напряжения: ветер, скрип двери, шаги
// на лестнице, гул генератора за стеной. Музыка минимальна.»
// «Интерфейс диегетический, где возможно: телефон, записки, экран
// без полосок. Состояния читаются через тело (дрожь, дыхание, замедление)
// и экран (красные края, потемнение).»
//
// Отсюда устройство. Подача — не украшение поверх симуляции, а её чтение:
// ни одно число здесь не задаётся вручную, всё выводится из дома и тела.
// Ветер громче в буран, потому что в календаре стоит буран; гул слышен
// тогда, когда у соседа за стеной работает генератор и он не заглушен, —
// и гул поэтому означает достаток, как и сказано в плане.
//
// Считается это **без Godot**, как и всё в `Дом.Экран`: обстановка
// и голоса — обычные записи, и потому их можно проверить прогоном
// в консоли, а не глазами на сцене. Что именно из них рисовать туманом,
// а что играть звуковым файлом — дело узлов.
//
// Полосок здесь нет и быть не должно: экран без полосок — это прямое
// требование ГДД 23, и первая версия состояния его нарушала.

using Дом.Ядро;

namespace Дом.Экран;

/// <summary>
/// Что видно: края, темнота, дрожь, дыхание, туман, снег, свет.
///
/// Все семь — доли от нуля до единицы. Ноль значит «этого не видно
/// вовсе», единица — «сильнее некуда»; узел волен рисовать это чем угодно.
/// </summary>
public sealed record Обстановка(
    double краснота,    // красные края: чем ближе к смерти (ГДД 4)
    double темнота,     // потемнение: то же плюс отсутствие света
    double дрожь,       // тело: холод и паника
    double дыхание,     // тело: усталость и раны
    double туман,       // за окном
    double снег,        // за окном
    double свет);       // сколько света в комнате

/// <summary>Четыре звука ГДД 23 и тишина. Музыки в списке нет
/// нарочно: «музыка минимальна».</summary>
public enum Звук
{
    ВЕТЕР,
    СКРИП_ДВЕРИ,
    ШАГИ_НА_ЛЕСТНИЦЕ,
    ГУЛ_ГЕНЕРАТОРА,
}

/// <summary>
/// Один звук прямо сейчас: что, насколько громко, от кого и откуда.
///
/// <c>квартира</c> — та, из которой звук идёт, и она здесь для того, чтобы
/// узел мог поставить его в пространство. Направление — дело движка,
/// **громкость — дело симуляции**: гул через этаж тише не потому, что
/// дальше от уха, а потому, что через перекрытие. Складывать одно
/// с другим нельзя, иначе тише станет вдвое.
/// </summary>
public sealed record Голос(Звук что, double громкость, string? откуда,
                           int? квартира = null);

/// <summary>
/// Что видно про квартиру **с площадки**, не заходя внутрь.
///
/// Ровно то, что видит любой сосед, поднимаясь по лестнице: горит ли
/// свет под дверью, цела ли дверь, не пахло ли гарью, живёт ли там
/// кто-нибудь ещё. Ни шкафа, ни здоровья, ни настроения — за ними
/// в дверь надо стучать, и в этом вся игра.
/// </summary>
public sealed record ДверьСнаружи(
    int квартира,
    bool живут,       // за дверью кто-то есть — хозяин или переехавшие
    bool свет,        // из-под двери светит
    bool тело,        // хозяин остался внутри
    bool горело,      // недавно горел костёр или пожар
    bool взломана,    // замок сорван, туда теперь ходят все
    bool разобрана);  // квартиру растащили на доски

/// <summary>
/// Что у меня дома — то, что человек знает про своё жильё целиком.
///
/// Здесь границы знания нет и быть не может: это твоя комната, твоя печь
/// и твой шкаф. Ровно поэтому запись отдельная от <see cref="ДверьСнаружи"/>:
/// снаружи видно щель света, изнутри — сколько градусов и сколько банок.
/// Спутать эти два уровня — значит однажды показать чужой шкаф.
/// </summary>
public sealed record Комната(
    double градусов,           // сколько сейчас в комнате
    bool топится,              // печь горит прямо сейчас
    bool печь,                 // буржуйка вообще есть
    bool свет,                 // питание есть
    double утепление,          // 0..3 — сколько слоёв
    int дыр,                   // проломов: окно, стена, пол, потолок
    IReadOnlyList<Запас> шкаф,
    int детей,
    bool тулуп);

/// <summary>
/// Человек, которого сейчас видно в подъезде: на площадке или у двери.
///
/// Видно ровно тех, кто в подъезде и есть. Кто дома — тот за дверью,
/// и его не видно ни через глазок, ни через стену; кто за порогом —
/// того нет в доме вовсе. Это не экономия на фигурах, а то же правило
/// знания, что у <see cref="ДверьСнаружи"/>: чтобы узнать, кто дома,
/// надо постучать, а чтобы увидеть соседа — подняться туда, где он стоит.
/// </summary>
public sealed record ВПодъезде(
    string id,
    string имя,
    Где где,
    int квартира,     // у какой двери стоит (для площадки — своей)
    int этаж,
    string ключ);     // за каким делом — из него берётся поза и подпись

public static class Подача
{
    /// <summary>
    /// Что видно сейчас.
    ///
    /// Красные края и потемнение считаются от **худшей** нужды, а не
    /// от средней: человек умирает от одного, а не от всего сразу,
    /// и экран должен краснеть от того, что его убивает.
    /// </summary>
    public static Обстановка Видно(House h, NPC я)
    {
        // худшая из четырёх шкал, приведённая к «насколько всё плохо»
        double худшая = new[] { я.satiety, я.hydration, я.warmth, я.health }.Min();
        double плохо = Util.Clamp(1.0 - худшая / 40.0, 0.0, 1.0);

        bool свет_есть = h.powered(я) || я.shelter.Взять("буржуйка", 0.0) != 0.0;
        double свет = свет_есть ? 1.0 : 0.25;

        // погода: буран — это стена, затишье — просвет
        (double туман, double снег) = h.режим switch
        {
            Режим.БУРАН => (1.0, 1.0),
            Режим.ЗАТИШЬЕ => (0.25, 0.2),
            _ => (0.6, 0.55),
        };

        return new Обстановка(
            краснота: плохо,
            темнота: Util.Clamp(плохо * 0.6 + (свет_есть ? 0.0 : 0.4), 0.0, 1.0),
            дрожь: Util.Clamp((1.0 - я.warmth / 50.0) * 0.7 + я.panic / 100.0 * 0.5,
                              0.0, 1.0),
            дыхание: Util.Clamp((1.0 - я.rest / 60.0) * 0.6
                                + (1.0 - я.health / 100.0) * 0.6, 0.0, 1.0),
            туман: туман,
            снег: снег,
            свет: свет);
    }

    /// <summary>
    /// Что слышно сейчас.
    ///
    /// Ветер есть всегда — он и есть метель. Гул генератора слышен только
    /// если у кого-то за стеной он работает и не заглушен: гул означает
    /// достаток, и заглушить его стоит материалов. Шаги на лестнице
    /// и скрип двери — не постоянный шум, а событие: они звучат тогда,
    /// когда сегодня кто-то и вправду выходил.
    /// </summary>
    public static IReadOnlyList<Голос> Слышно(House h, NPC я,
                                              IReadOnlyList<СтрокаЛенты> лента)
    {
        var @out = new List<Голос>
        {
            new(Звук.ВЕТЕР, h.режим switch
            {
                Режим.БУРАН => 1.0,
                Режим.ЗАТИШЬЕ => 0.3,
                _ => 0.65,
            }, null),
        };

        // Гул: в квартире стоит генератор, он не заглушен, и там кто-то
        // живой. Считается **по квартирам**, а не по людям, и это не
        // придирка: генератор принадлежит стенам (`NPC.shelter` — это
        // и есть `where(npc).shelter`). Пока считали по людям, двое под
        // одной крышей гудели дважды, а переехавший гудел из своей
        // пустой квартиры — то есть не оттуда, где стоит его генератор.
        int мой = h.where(я).floor;
        foreach (var f in h.flats.Значения.OrderBy(x => x.apt))
        {
            if (f.shelter.Взять("генератор", 0.0) == 0.0)
                continue;
            if (f.shelter.Взять("звукоизоляция", 0.0) != 0.0)
                continue;               // заглушил — гула больше не слышно
            var кто = h.people.Значения
                .Where(о => о.здесь() && h.where(о).apt == f.apt)
                .OrderBy(о => о.id, StringComparer.Ordinal)
                .FirstOrDefault();
            if (кто is null)
                continue;               // у мёртвого генератор не заводят
            // ближе — громче: свой этаж слышно лучше, чем через два
            double далеко = Math.Abs(f.floor - мой);
            @out.Add(new Голос(Звук.ГУЛ_ГЕНЕРАТОРА,
                               Util.Clamp(1.0 - далеко * 0.35, 0.15, 1.0),
                               кто.@short, f.apt));
        }

        // шаги и скрип — по тому, что случилось сегодня
        int сегодня = h.day;
        foreach (var с in лента)
        {
            if (с.день != сегодня)
                continue;
            if (с.текст.Contains("на лестнице", StringComparison.Ordinal))
                @out.Add(new Голос(Звук.ШАГИ_НА_ЛЕСТНИЦЕ, 0.7, null));
            else if (с.текст.Contains("дверь", StringComparison.Ordinal)
                     || с.текст.Contains("постучал", StringComparison.Ordinal))
                @out.Add(new Голос(Звук.СКРИП_ДВЕРИ, 0.5, null));
        }
        return @out;
    }

    /// <summary>
    /// Как читается состояние без полосок (ГДД 23).
    ///
    /// Не «сыт 34», а «сосёт под ложечкой». Порядок — от тела к голове:
    /// человек сначала чувствует, а потом объясняет. Пустой список значит
    /// «ничего не жмёт», и это тоже сообщение.
    /// </summary>
    public static IReadOnlyList<string> Телом(NPC я)
    {
        var @out = new List<string>();

        void Ш(double v, string сильно, string средне, string слабо)
        {
            if (v < 20) @out.Add(сильно);
            else if (v < 40) @out.Add(средне);
            else if (v < 60) @out.Add(слабо);
        }

        Ш(я.satiety, "живот сводит", "сосёт под ложечкой", "не мешало бы поесть");
        Ш(я.hydration, "губы трескаются", "во рту сухо", "хочется пить");
        Ш(я.warmth, "трясёт, пальцы не гнутся", "холодно до костей",
          "зябко");
        Ш(я.rest, "глаза слипаются", "голова тяжёлая", "не выспался");
        Ш(я.health, "внутри всё горит", "мутит", "ломит");
        if (я.panic >= 70)
            @out.Add("сердце колотится");
        else if (я.panic >= 45)
            @out.Add("не по себе");
        foreach (var р in я.injuries)
            @out.Add($"{р} — саднит");
        if (!string.IsNullOrEmpty(я.sick))
            @out.Add("знобит");
        return @out;
    }

    /// <summary>
    /// К какой двери относится вариант — если относится хоть к какой.
    ///
    /// Это то, чем игра от первого лица отличается от списка строк:
    /// «разговор → Валя» перестаёт быть строкой номер три и становится
    /// дверью, к которой можно подойти. Ничего не решается и не
    /// отбирается — считается только адрес.
    ///
    /// Человек числится у той двери, к которой за ним ходят, а не там,
    /// где ночует: решает `хозяин_жилья`, ровно как на плане подъезда.
    /// Разница видна, когда хозяин умер, — поле `living_with` у гостя
    /// остаётся висеть, и без этого правила сосед оказывается у чужой
    /// двери, а своя стоит пустой.
    ///
    /// Квартира — тоже адрес: за пустой квартирой ходят к её двери.
    /// А вот **кладовка адреса в подъезде не имеет**: погреба и гаражи
    /// стоят во дворе, и к ним ходят туда. Пока во двор нельзя было
    /// выйти, в погреб кв.6 «ходили через кв.6» — теперь это неправда,
    /// и адрес у кладовки свой (<see cref="Кладовка"/>).
    ///
    /// Вылазка адреса не имеет тоже: у места нет двери в подъезде,
    /// и делать вид, что есть, — врать.
    /// </summary>
    public static int? Дверь(House h, ВариантИгроку в) => в.цель switch
    {
        NPC p => h.хозяин_жилья(p).apt,
        Flat f => f.apt,
        _ => null,
    };

    /// <summary>
    /// Что у меня дома.
    ///
    /// Читается своя правда, и это единственное место подачи, где так можно:
    /// человек знает свою комнату до банки. Границу держит подпись — сюда
    /// передаётся <c>я</c>, а не любой жилец, и звать это для соседа
    /// нельзя ни при каких обстоятельствах.
    ///
    /// Комната берётся через `where`, а не по номеру квартиры: переехавший
    /// греется хозяйской печкой, и «дома» у него теперь там.
    /// </summary>
    public static Комната Внутри(House h, NPC я)
    {
        var кв = h.where(я);
        var шкаф = я.stock.Ключи
            .OrderBy(x => x, StringComparer.Ordinal)
            .Where(р => я.stock.Взять(р, 0.0) != 0)
            .Select(р => new Запас(р, я.stock.Взять(р, 0.0)))
            .ToList();
        return new Комната(
            градусов: h.room_temp(я, burning: я.burning),
            топится: я.burning,
            печь: кв.shelter.Взять("буржуйка", 0.0) > 0,
            свет: h.powered(я),
            утепление: кв.shelter.Взять("утепление", 0.0),
            дыр: кв.дыр(),
            шкаф: шкаф,
            детей: я.дети.Count,
            тулуп: кв.тулуп);
    }

    /// <summary>
    /// Что видно про каждую квартиру с площадки.
    ///
    /// Всё, кроме света, приходит из плана подъезда — то есть из того,
    /// что экран и так показывает списком. Перенести это в пространство
    /// не значит показать больше: дверь говорит ровно то же, только
    /// глазами, а не строкой.
    ///
    /// Свет — единственное добавленное, и он **не новое знание**: это тот
    /// же факт, которым уже звучит гул генератора (`Слышно`). У соседа
    /// работает генератор — его слышно через стену и видно из-под двери.
    /// Заводить здесь что-то, чего сосед знать не может, нельзя: игра про
    /// догадки перестанет быть игрой ровно в тот день, когда подъезд
    /// начнёт показывать чужой шкаф.
    /// </summary>
    public static IReadOnlyList<ДверьСнаружи> Снаружи(
        House h, IReadOnlyList<КвартираНаПлане> квартиры)
    {
        var @out = new List<ДверьСнаружи>(квартиры.Count);
        foreach (var кв in квартиры)
        {
            // светит тому, кто там живёт: хозяин, а если его нет —
            // тот, кто к нему переехал
            var жилец = кв.кто ?? (кв.гости.Count > 0 ? кв.гости[0] : null);
            var npc = жилец is null ? null : h.get(жилец.id);
            @out.Add(new ДверьСнаружи(
                кв.номер,
                живут: жилец is not null,
                свет: npc is not null && h.powered(npc),
                тело: кв.с_телом,
                горело: кв.горел,
                взломана: кв.открыта,
                разобрана: кв.разобрана));
        }
        return @out;
    }

    /// <summary>
    /// Ведёт ли вариант за порог подъезда.
    ///
    /// Это ровно вылазка и ничего больше: у неё цель — `Место`, то есть
    /// точка **вне дома**. Заказ у мастера, банкомат и разговор через дверь
    /// сюда не попадают, хотя тоже «про улицу»: их делают, не выходя.
    ///
    /// Нужно это затем же, зачем `Дверь`: чтобы у выхода из подъезда
    /// спрашивалось то, что спрашивается у выхода, — а не весь список.
    /// </summary>
    public static bool Наружу(ВариантИгроку в)
        => в.цель is Место
           || (в.цель is Кладовая г && г.вид == ВидКладовой.ГАРАЖ);

    /// <summary>
    /// Адреса всех вариантов вопроса — по тому, **где человек сейчас**.
    ///
    /// <see cref="Дверь"/> считает адрес по жилью: за соседом ходят к его
    /// двери. Это верно, пока сосед дома, — а он может стоять у чужой.
    /// Тогда постучать к нему в пустую квартиру нельзя, и звать его оттуда
    /// игра не вправе: на площадке видно, что его там нет.
    ///
    /// Поэтому здесь адрес берётся из хроники, и совпадает он с фигурой,
    /// которую игрок видит. Один источник на оба ответа — иначе фигура
    /// стоит у одной двери, а разговор с ней идёт у другой.
    /// </summary>
    public static IReadOnlyList<int?> Двери(House h, NPC я, ВопросИгроку? в,
                                            Хроника х)
    {
        var @out = new List<int?>();
        if (в is null)
            return @out;
        // видно только тех, кто в подъезде, и у каждого уже посчитана
        // дверь, у которой он стоит. Отбирать из них ещё и по «где» незачем:
        // на площадке человек числится у своей же двери — то есть там,
        // куда его и так адресует жильё
        var у_двери = new Dictionary<string, int>(StringComparer.Ordinal);
        foreach (var с in В_подъезде(h, я, х))
            у_двери[с.id] = с.квартира;
        foreach (var в_ in в.варианты)
            @out.Add(в_.цель is NPC p && у_двери.TryGetValue(p.id, out int д)
                     ? д : Дверь(h, в_));
        return @out;
    }

    /// <summary>
    /// К какому погребу ведёт вариант — если ведёт.
    ///
    /// **Только к погребу.** Гараж — это улица: в него ходят вылазкой,
    /// и адресуется он двери подъезда (<see cref="Наружу"/>), а не сам
    /// себе. Так говорит не вкус, а данные: `balance.json` — «Погреб
    /// внутри дома… гараж — это улица со всем, что к ней прилагается»,
    /// `Улица.часы_кладовой` множит гараж на погоду, `место_доступно`
    /// закрывает его тем же, чем вылазку, а «гаражи за домом» — место
    /// вылазки с пометкой «гараж» в поле кладовок.
    /// </summary>
    public static string? Кладовка(ВариантИгроку в)
        => в.цель is Кладовая к && к.вид == ВидКладовой.ПОГРЕБ ? к.id : null;

    /// <summary>Что из вопроса ведёт к этой кладовой — номерами, в том же
    /// порядке, в каком их видит игрок.</summary>
    public static IReadOnlyList<int> Кого_к_кладовой(ВопросИгроку? в, string id)
    {
        var @out = new List<int>();
        if (в is null)
            return @out;
        for (int i = 0; i < в.варианты.Count; i++)
            if (string.Equals(Кладовка(в.варианты[i]), id, StringComparison.Ordinal))
                @out.Add(i);
        return @out;
    }

    /// <summary>Что из вопроса ведёт на улицу — номерами, в том же порядке,
    /// в каком их видит игрок.</summary>
    public static IReadOnlyList<int> Кого_наружу(ВопросИгроку? в)
    {
        var @out = new List<int>();
        if (в is null)
            return @out;
        for (int i = 0; i < в.варианты.Count; i++)
            if (Наружу(в.варианты[i]))
                @out.Add(i);
        return @out;
    }

    /// <summary>
    /// Кого сейчас видно в подъезде — всех, кроме себя.
    ///
    /// Час берётся у спрашивающего: день — лента, ход даётся тому, у кого
    /// раньше на личных часах, поэтому когда игрока спрашивают в час H,
    /// у остальных этот час уже прожит и записан. Заглянуть дальше своего
    /// часа нельзя — там у соседей ещё ничего не случилось.
    /// </summary>
    public static IReadOnlyList<ВПодъезде> В_подъезде(House h, NPC я, Хроника х)
    {
        var @out = new List<ВПодъезде>();
        double час = я.час();
        foreach (var п in h.people.Значения.OrderBy(x => x.apt))
        {
            if (п.id == я.id || !п.здесь())
                continue;
            var ход = х.Ход_в(п.id, h.day, час);
            if (ход is null || ход.где is Где.Дома or Где.ЗаПорогом)
                continue;
            int кв = ход.где == Где.НаПлощадке ? h.хозяин_жилья(п).apt : ход.квартира;
            var f = h.flats.Взять(кв, null);
            @out.Add(new ВПодъезде(п.id, п.@short, ход.где, кв,
                                   f?.floor ?? 0, ход.ключ));
        }
        return @out;
    }

    /// <summary>Что из вопроса относится к этой двери — номерами, в том же
    /// порядке, в каком их видит игрок. Пустой список значит «сюда сейчас
    /// незачем», а не «нельзя».</summary>
    public static IReadOnlyList<int> Кого_к_двери(House h, ВопросИгроку? в, int дверь)
    {
        var @out = new List<int>();
        if (в is null)
            return @out;
        for (int i = 0; i < в.варианты.Count; i++)
            if (Дверь(h, в.варианты[i]) == дверь)
                @out.Add(i);
        return @out;
    }
