    /// <summary>
    /// Сосед <paramref name="гость"/> стоит у двери <paramref name="кв"/> по делу
    /// <paramref name="ключ"/> (хроника) — что слышит проходящий мимо: реплику
    /// гостя и ответ хозяина, если тот дома, иначе тишину. Имена — как их
    /// знает герой. null — дело не из тех, что слышно на площадке.
    /// </summary>
    public string? У_двери(House h, NPC я, NPC гость, int кв, string ключ, IReadOnlyList<СоседГде> кто_где,
                           long зерно, int раз)
    {
        if (!У_ДВЕРИ.Contains(ключ))
            return null;
        string Из(string список, string кто) => Одна(_у_двери[список], зерно, "у_двери_" + список, кто, раз + h.day * 23);
        var хозяин = кто_где.Where(с => с.дом == кв && с.где == Где.Дома && с.id != гость.id)
                            .Select(с => h.живой(с.id)).OfType<NPC>()
                            .OrderBy(p => p.apt == кв ? 0 : 1).ThenBy(p => p.id, StringComparer.Ordinal).FirstOrDefault();
        string гость_ = $"{СЗаглавной(Знакомство.Как_зовут(h, я, гость))}: «{Слова(Из(ключ + "_гость", гость.id), гость, я)}»";
        if (хозяин is null)
            return $"{гость_} — {Слова(Из("нет_дома", "кв" + кв), я, я)}";
        return $"{гость_} — {Знакомство.Как_зовут(h, я, хозяин)}: «{Слова(Из(ключ + "_хозяин", хозяин.id), хозяин, я)}»";
    }

    // ------------------------------------------------------------ подслушать

    /// <summary>
    /// Постоять у двери <paramref name="кв"/> тихо: что слышно. Каждый, кто дома,
    /// говорит о том, чем живёт: замысел (уйти, запас, тепло, угол, стравить
    /// двоих, перезимовать вдвоём), злость на героя — и замысел против него,
    /// болезнь, голод или полный шкаф, страх, быт; второй отвечает. Голос
    /// подписан так, как его знает герой: имя — или «мужской голос». О еде
    /// герой узнаёт по-настоящему (<see cref="Подслушано.о_еде"/>): узел кладёт
    /// это в его сведения о соседе, как кладёт сплетня.
    /// </summary>
    public Подслушано Подслушать(House h, NPC я, int кв, IReadOnlyList<СоседГде> кто_где, double час,
                                 Заражение? з, long зерно, int раз)
    {
        string Из(string список, string кто, int ещё = 0)
            => Одна(_подслушать[список], зерно, "слушать_" + список, кто, раз + h.day * 19 + ещё);
        var дома = кто_где.Where(с => с.дом == кв && с.где == Где.Дома).Select(с => h.живой(с.id)).OfType<NPC>()
                          .OrderBy(p => p.apt == кв ? 0 : 1).ThenBy(p => p.id, StringComparer.Ordinal).ToList();
        if (дома.Count == 0)
            return new Подслушано(new[] { Слова(Из("тихо", "кв" + кв), я, я) }, Array.Empty<(string, double)>());
        if (час >= 23 || час < 6.5)
            return new Подслушано(new[] { Слова(Из("спят", "кв" + кв), я, я) }, Array.Empty<(string, double)>());
        var строки = new List<string>();
        var о_еде = new List<(string, double)>();
        foreach (var (p, n) in дома.Take(2).Select((p, n) => (p, n)))
        {
            string голос = Знакомство.Знает(h, я, p) ? $"голос {p.form("gen")}"
                         : p.sex == "ж" ? "женский голос" : "мужской голос";
            var (список, кому) = О_чём(h, я, p, з);
            string слова;
            if (список is null)
                слова = Из("ответ", p.id);
            else
            {
                слова = Из(список, p.id);
                if (кому is not null)
                    слова = слова.Replace("{кто}", кому.@short, StringComparison.Ordinal)
                                 .Replace("{кого}", кому.form("gen"), StringComparison.Ordinal)
                                 .Replace("{кому}", кому.form("dat"), StringComparison.Ordinal)
                                 .Replace("{кем}", кому.form("ins"), StringComparison.Ordinal);
                слова = слова.Replace("{кв}", я.apt.ToString(System.Globalization.CultureInfo.InvariantCulture),
                                      StringComparison.Ordinal);
                if (список is "голод" or "запасы")
                    о_еде.Add((p.id, p.stock.Взять("еда", 0.0)));
            }
            // второй — чаще отвечает первому, чем начинает своё
            if (n == 1 && список is not ("на_героя" or "о_герое") && Округа.Бросок(зерно, "слушать_второй", p.id, раз + h.day * 19) < 0.5)
                слова = Из("ответ", p.id);
            строки.Add($"{СЗаглавной(голос)}: «{Слова(слова, p, я)}»");
        }
        return new Подслушано(строки, о_еде);
    }

    /// <summary>О чём человек говорит у себя дома, если его не видят: имя
    /// списка и о ком (для «{кому}»); null — просто поддакнет.</summary>
    private static (string? список, NPC? кому) О_чём(House h, NPC я, NPC p, Заражение? з)
    {
        if (p.замысел is { } за)
        {
            if (за.вид == "рассорить" && за.враг == я.id)
                return ("на_героя", null);
            var кому = h.живой(за.враг ?? за.друг ?? "");
            if (Замыслы.ВИДЫ.Contains(за.вид) && (за.вид is not ("рассорить" or "вместе") || кому is not null))
                return (за.вид, кому);
        }
        if (p.hate.Взять(я.id, 0.0) > 30)
            return ("о_герое", null);
        if (з is not null && з.Стадия(p.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО)
            return ("болезнь", null);
        double еды = p.stock.Взять("еда", 0.0);
        if (p.satiety < 35 || еды < 2)
            return ("голод", null);
        if (еды >= 12)
            return ("запасы", null);
        if (p.panic > 60)
            return ("страх", null);
        return ("быт", null);
    }

    // ------------------------------------------------------------ записки

    /// <summary>
    /// Что написано на дверях сегодня — то, что жильцы пишут друг другу
    /// и что видит каждый на площадке: мелом крест, где хозяин остался
    /// внутри; «мы у такого-то» — где все съехали к соседу; «болеем, не
    /// стучать» — где больной (болезнь с «Вектора», только в мире героя);
    /// «кому совсем плохо — стучите» — у того, кто последнее отдаст, когда
    /// в доме уже голодно. Пустая, разобранная, без живых — без записки.
    /// </summary>
    public IReadOnlyList<Записка> Записки(House h, NPC я, IReadOnlyList<ДверьСнаружи> двери, Заражение? з, long зерно)
    {
        int свой = h.хозяин_жилья(я).apt;
        string Из(string список, int кв) => Одна(_записки[список], зерно, "записка_" + список, "кв" + кв, h.day);
        var живые = h.alive().ToList();
        // поймали на краже за три дня — или о нём шепчут трое: мелом на двери
        bool Вор(NPC p) => живые.Any(с => с != p && с.memory.Any(м => м.вид == Вид.ПОЙМАЛ_ВОРА && м.кто == p.id && h.day - м.день <= 3))
                        || живые.Count(с => с != p && с.memory.Any(м => м.вид == Вид.НАЗВАЛИ_ВОРОМ && м.кто == p.id && h.day - м.день <= 3)) >= 3;
        var @out = new List<Записка>();
        foreach (var д in двери.OrderBy(д => д.квартира))
        {
            int кв = д.квартира;
            var живут = живые.Where(p => h.хозяин_жилья(p).apt == кв).ToList();
            if (кв == свой)
            {
                // на своей двери герой пишет сам (`ЗапискаГероя`); «вор» мелом — поверх
                string? своя = я.записка is string вид && _записка_героя.TryGetValue(вид, out var т) ? т : null;
                if (живут.Any(Вор))
                    @out.Add(new Записка(кв, Из("вор", кв) + (своя is null ? "" : "\n" + своя), Чем.МЕЛ));
                else if (своя is not null)
                    @out.Add(new Записка(кв, своя, Чем.БУМАГА));
                continue;
            }
            if (д.тело)
            {
                @out.Add(new Записка(кв, Из("тело", кв), Чем.МЕЛ));
                continue;
            }
            var прописаны = h.people.Значения.Where(p => p.apt == кв).ToList();
            // здесь никто не жил и до метели: бумажка, оставшаяся с осени, — не у всех
            if (прописаны.Count == 0 && живут.Count == 0)
            {
                if (!д.разобрана && Округа.Бросок(зерно, "записка_пустая_есть", "кв" + кв, 0) < 0.6)
                    @out.Add(new Записка(кв, Одна(_записки["пустая"], зерно, "записка_пустая", "кв" + кв, 0), Чем.БУМАГА));
                continue;
            }
            // все прописанные живы и живут у соседа — пишут, где искать
            if (живут.Count == 0 && прописаны.Count > 0 && прописаны.All(p => p.alive)
                && прописаны.Select(p => h.хозяин_жилья(p)).FirstOrDefault(f => f.apt != кв) is { } у
                && h.alive().Where(p => p.apt == у.apt).OrderBy(p => p.id, StringComparer.Ordinal).FirstOrDefault() is NPC хозяин)
            {
                @out.Add(new Записка(кв, Из("переехали", кв).Replace("{кого}", хозяин.form("gen").ToUpperInvariant(), StringComparison.Ordinal)
                                                        .Replace("{кв}", у.apt.ToString(System.Globalization.CultureInfo.InvariantCulture), StringComparison.Ordinal),
                                     Чем.БУМАГА));
                continue;
            }
            if (з is not null && живут.Any(p => з.Стадия(p.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО))
            {
                @out.Add(new Записка(кв, Из("болеют", кв), Чем.БУМАГА));
                continue;
            }
            if (живут.Any(Вор))
            {
                @out.Add(new Записка(кв, Из("вор", кв), Чем.МЕЛ));
                continue;
            }
            if (h.day >= 3 && живут.Any(p => p.пунктики.Contains("последнее_отдаст", StringComparer.Ordinal)
                                             && p.stock.Взять("еда", 0.0) > 0))
                @out.Add(new Записка(кв, Из("отдаст", кв), Чем.БУМАГА));
        }
        return @out;
    }

    // ------------------------------------------------------------ из окна

    /// <summary>
    /// Что видно из своего окна: погода дня, снег, мороз, зарево над городом
    /// (летопись), кто во дворе и у гаражей (хроника; в буран и ночью двора
    /// не видно). Строки — по одной на то, что видно. До метели
    /// (<paramref name="до_метели"/>) — обычный двор: метели ещё нет.
    /// </summary>
    public IReadOnlyList<string> Из_окна(House h, NPC я, IReadOnlyList<СоседГде> кто_где, Летопись? л,
                                         double час, long зерно, int раз, bool до_метели = false)
    {
        string Из(string список, int ещё = 0)
            => Одна(_окно[список], зерно, "окно_" + список, я.id, раз + h.day * 13 + ещё);
        var строки = new List<string>();
        if (до_метели)
            return new[] { Слова(Из("до_метели"), я, я) };
        bool ночь = час >= 20 || час < 7;
        bool видно_двор = !ночь && h.режим != Режим.БУРАН;
        строки.Add(ночь ? Из(h.power_on ? "ночь" : "темно")
                        : Из(h.режим switch { Режим.БУРАН => "буран", Режим.ЗАТИШЬЕ => "затишье", _ => "метель" }));
        if (h.снег >= 1.0 && !ночь)
            строки.Add(Из("сугробы"));
        if (h.outside <= -30)
            строки.Add(Из("мороз"));
        if (л is not null)
        {
            var мир = л.На(h.day, зерно);
            foreach (var (место, здание) in мир.здания.OrderBy(п => п.Key, StringComparer.Ordinal))
                if (здание == Здание.ГОРИТ && л.места.TryGetValue(место, out var имя))
                {
                    строки.Add(Из("зарево").Replace("{место}", имя, StringComparison.Ordinal));
                    break;
                }
        }
        if (видно_двор)
        {
            int n = 0;
            foreach (var с in кто_где.Where(с => с.где == Где.ЗаПорогом && с.место is string м
                                                 && (м.StartsWith("двор", StringComparison.Ordinal)
                                                     || м.StartsWith("гараж", StringComparison.Ordinal))))
            {
                // в окно лица не разглядеть: знакомого узнают по фигуре, чужой — «кто-то»
                string кто = h.живой(с.id) is NPC п && Знакомство.Знает(h, я, п) ? п.@short : "кто-то из соседей";
                string список = с.место!.StartsWith("гараж", StringComparison.Ordinal) ? "у_гаражей" : "во_дворе";
                строки.Add(СЗаглавной(Из(список, n++).Replace("{кто}", кто, StringComparison.Ordinal)));
                if (n >= 2)
                    break;
            }
            if (n == 0)
                строки.Add(Из("пусто"));
        }
        return строки.Select(с => Слова(с, я, я)).ToList();
    }
