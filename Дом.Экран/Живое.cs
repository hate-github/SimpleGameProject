    /// <summary>Реплики одного списка раздела «мимоходом», «за_дверью» или «окно» — для проверки.</summary>
    public IReadOnlyList<string> Живое(string раздел, string список) => раздел switch
    {
        "мимоходом" => _мимоходом[список],
        "за_дверью" => _за_дверью[список],
        "окно" => _окно[список],
        "подслушать" => _подслушать[список],
        "записки" => _записки[список],
        _ => throw new ArgumentException($"нет раздела «{раздел}»"),
    };

    private void Прочитать_живое(JsonElement к)
    {
        static List<string> Список(JsonElement э) => э.EnumerateArray().Select(x => x.GetString()!).ToList();
        foreach (var (раздел, имена, куда) in new[]
                 {
                     ("мимоходом", МИМОХОДОМ, _мимоходом),
                     ("за_дверью", ЗА_ДВЕРЬЮ, _за_дверью),
                     ("окно", ОКНО, _окно),
                     ("подслушать", ПОДСЛУШАТЬ, _подслушать),
                     ("записки", ЗАПИСКИ, _записки),
                 })
        {
            var р = к.GetProperty(раздел);
            foreach (var имя in имена)
                куда[имя] = Список(р.GetProperty(имя));
        }
    }

    // ------------------------------------------------------------ на ходу

    /// <summary>
    /// Что сосед <paramref name="с"/> бросит герою, проходящему мимо, — одной
    /// строкой; null — промолчит. <paramref name="где"/> и <paramref name="у_двери"/> —
    /// где он стоит (хроника), <paramref name="час"/> — час героя,
    /// <paramref name="раз"/> — который раз за день он заговорил.
    /// </summary>
    public string? Мимоходом(House h, NPC я, NPC с, Где где, int у_двери, double час, Заражение? з,
                             long зерно, int раз)
    {
        double Бросок(string повод) => Округа.Бросок(зерно, "мимо_" + повод, с.id, раз + h.day * 31);
        string Из(string список) => Одна(_мимоходом[список], зерно, "мимо_" + список, с.id, раз + h.day * 31);
        string отношение = Отношение(я, с);

        // злой — зло или молча отворачивается
        if (отношение == "злой")
            return Бросок("злой") < 0.6 ? Слова(Из("злой"), с, я) : null;
        // болен с «Вектора» — кашляет и держит дистанцию
        if (з is not null && з.Стадия(с.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО)
            return Слова(Из("болен"), с, я);
        // что давит сильнее всего — о том и скажет, чаще всего
        if (Нужда(с) is string нужда && Бросок("нужда") < 0.75)
            return Слова(Из(нужда), с, я);
        // пришёл к соседу — к кому
        if (где == Где.УДвери && Живёт_за(h, у_двери, с) is NPC хозяин && Бросок("дверь") < 0.6)
            return Слова(Из("к_двери").Replace("{кому}", Знакомство.Как_зовут(h, с, хозяин, "dat"),
                                                StringComparison.Ordinal), с, я);
        // в доме умирали — об этом говорят все
        if (Умер_недавно(h) is NPC мёртв && Бросок("смерть") < 0.5)
            return Слова(Из("смерть").Replace("{умер}", мёртв.@short, StringComparison.Ordinal), с, я);
        // время дня и метель
        if (Бросок("время") < 0.35)
            return Слова(Из(час < 10 ? "утро" : час >= 19 ? "вечер" : "метель"), с, я);
        return Слова(Из(отношение), с, я);
    }

    /// <summary>Что давит на человека сильнее всего — имя списка, или null, если ничего.
    /// Пороги — где это слышно в голосе, а не где начинает считать дом.</summary>
    public static string? Нужда(NPC с)
    {
        var давит = new List<(string что, double насколько)>();
        if (с.satiety < 30) давит.Add(("голод", 30 - с.satiety));
        if (с.hydration < 30) давит.Add(("жажда", 30 - с.hydration));
        if (с.warmth < 35) давит.Add(("холод", 35 - с.warmth));
        if (с.rest < 25) давит.Add(("усталость", 25 - с.rest));
        if (с.health < 40) давит.Add(("ранен", 40 - с.health));
        if (с.panic > 60) давит.Add(("страх", с.panic - 60));
        if (с.mood < 25) давит.Add(("тоска", 25 - с.mood));
        return давит.Count == 0 ? null
            : давит.OrderByDescending(д => д.насколько).ThenBy(д => д.что, StringComparer.Ordinal).First().что;
    }

    /// <summary>Кто живёт за дверью <paramref name="кв"/> (кроме <paramref name="кроме"/>):
    /// хозяин — первым, потом переехавшие к нему.</summary>
    private static NPC? Живёт_за(House h, int кв, NPC? кроме)
        => h.alive().Where(p => !ReferenceEquals(p, кроме) && h.хозяин_жилья(p).apt == кв)
                    .OrderBy(p => p.apt == кв ? 0 : 1).ThenBy(p => p.id, StringComparer.Ordinal)
                    .FirstOrDefault();

    /// <summary>Кто в доме умер сегодня или вчера — о нём говорят все.</summary>
    private static NPC? Умер_недавно(House h)
        => h.people.Значения.Where(p => !p.alive && p.died_day is int д && h.day - д <= 1)
                            .OrderByDescending(p => p.died_day).ThenBy(p => p.id, StringComparer.Ordinal)
                            .FirstOrDefault();

    // ------------------------------------------------------------ у двери

    /// <summary>
    /// Стук в дверь <paramref name="кв"/>, к которой дом ничего не положил:
    /// кто за ней и что он скажет. <paramref name="кто_где"/> — где каждый
    /// сосед в час героя (`Подача.Кто_где`), <paramref name="снаружи"/> — что
    /// видно у двери, <paramref name="опять"/> — стучали только что,
    /// <paramref name="раз"/> — который раз за день к этой двери.
    /// </summary>
    public ОтветДвери За_дверью(House h, NPC я, int кв, IReadOnlyList<СоседГде> кто_где, ДверьСнаружи? снаружи,
                                double час, Заражение? з, bool опять, long зерно, int раз)
    {
        string Из(string список, string кто) => Одна(_за_дверью[список], зерно, "дверь_" + список, кто, раз + h.day * 17);
        string повод = "кв" + кв;
        var жильцы = кто_где.Where(с => с.дом == кв).ToList();
        if (жильцы.Count == 0)
        {
            // никто здесь не живёт: хозяин остался внутри, квартиру растащили, пусто
            var что = снаружи?.тело == true ? ЗаДверью.ТЕЛО : снаружи?.разобрана == true ? ЗаДверью.РАЗОБРАНА : ЗаДверью.ПУСТО;
            string список = что switch { ЗаДверью.ТЕЛО => "тело", ЗаДверью.РАЗОБРАНА => "разобрана", _ => "пусто" };
            return new ОтветДвери(что, null, false, Слова(Из(список, повод), я, я), null);
        }
        var дома = жильцы.Where(с => с.где == Где.Дома).Select(с => h.живой(с.id)).OfType<NPC>().ToList();
        if (дома.Count == 0)
            return new ОтветДвери(ЗаДверью.НИКОГО, null, false, Слова(Из("никого", повод), я, я), null);
        var кто = дома.OrderBy(p => p.apt == кв ? 0 : 1).ThenBy(p => p.id, StringComparer.Ordinal).First();
        string? слышно = Слышно(h, кв, дома, з, зерно, раз);
        if (час >= 23 || час < 6.5)
            return new ОтветДвери(ЗаДверью.СПИТ, кто, false, Слова(Из("спит", кто.id), кто, я), слышно);
        var стадия = з?.Стадия(кто.id);
        if (стадия == Стадия.ТЯЖЕЛО)
            return new ОтветДвери(ЗаДверью.ТЯЖЕЛО, кто, false,
                                  Слова(Одна(_болезнь["тяжело"], зерно, "дверь_тяжело", кто.id, раз), кто, я), слышно);
        if (стадия == Стадия.БОЛЕН)
            return new ОтветДвери(ЗаДверью.БОЛЕН, кто, false, Слова(Из("болен", кто.id), кто, я), слышно);
        string отношение = Отношение(я, кто);
        if (отношение == "злой")
            return new ОтветДвери(ЗаДверью.ЗЛОЙ, кто, false, Слова(Из("злой", кто.id), кто, я), слышно);
        if (опять && отношение != "свой")
            return new ОтветДвери(ЗаДверью.ОПЯТЬ, кто, false, Слова(Из("опять", кто.id), кто, я), слышно);
        // у двери уже стоят — хозяину не до героя
        if (кто_где.Any(с => с.где == Где.УДвери && с.квартира == кв && с.id != я.id))
            return new ОтветДвери(ЗаДверью.ЗАНЯТ, кто, false, Слова(Из("занят", кто.id), кто, я), слышно);
        var (вид, список_) = отношение switch
        {
            "свой" => (ЗаДверью.СВОЙ, "свой"),
            "знакомый" => (ЗаДверью.ЗНАКОМЫЙ, "знакомый"),
            _ => (ЗаДверью.ЧУЖОЙ, "чужой"),
        };
        return new ОтветДвери(вид, кто, true, Слова(Из(список_, кто.id), кто, я), слышно);
    }

    /// <summary>Что слышно за дверью: кашель больного, ребёнок, голоса двоих —
    /// то, что и через дверь не спрячешь. null — тихо.</summary>
    private string? Слышно(House h, int кв, IReadOnlyList<NPC> дома, Заражение? з, long зерно, int раз)
    {
        string Из(string список) => Одна(_за_дверью[список], зерно, "слышно_" + список, "кв" + кв, раз + h.day * 17);
        var слышно = new List<string>();
        if (з is not null && дома.Any(p => з.Стадия(p.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО))
            слышно.Add(Из("кашель"));
        if (дома.SelectMany(p => p.дети).Any(р => р.у is null && (р.сытость < 40 || р.тепло < 40 || р.болен is not null))
            || h.alive().SelectMany(p => p.дети).Any(р => р.у is string у && h.живой(у) is NPC где && h.хозяин_жилья(где).apt == кв
                                                         && (р.сытость < 40 || р.тепло < 40)))
            слышно.Add(Из("ребёнок"));
        if (дома.Count >= 2)
            слышно.Add(Из("голоса"));
        return слышно.Count == 0 ? null : string.Join(" ", слышно);
    }

    // ------------------------------------------------------------ подслушать

    /// <summary>
    /// Постоять у двери <paramref name="кв"/> тихо: что слышно. Каждый, кто дома,
    /// говорит о том, чем живёт: замысел (уйти, запас, тепло, угол, стравить
    /// двоих, перезимовать вдвоём), злость на героя — и замысел против него,
    /// болезнь, голод или полный шкаф, страх, быт; второй отвечает. Голос
    /// подписан так, как его знает герой: имя — или «мужской голос». О еде
    /// герой узнаёт по-настоящему (<see cref="Подслушано.о_еде"/>): узел кладёт
    /// это в его сведения о соседе, как кладёт сплетня.
    /// </summary>
    public Подслушано Подслушать(House h, NPC я, int кв, IReadOnlyList<СоседГде> кто_где, double час,
                                 Заражение? з, long зерно, int раз)
    {
        string Из(string список, string кто, int ещё = 0)
            => Одна(_подслушать[список], зерно, "слушать_" + список, кто, раз + h.day * 19 + ещё);
        var дома = кто_где.Where(с => с.дом == кв && с.где == Где.Дома).Select(с => h.живой(с.id)).OfType<NPC>()
                          .OrderBy(p => p.apt == кв ? 0 : 1).ThenBy(p => p.id, StringComparer.Ordinal).ToList();
        if (дома.Count == 0)
            return new Подслушано(new[] { Слова(Из("тихо", "кв" + кв), я, я) }, Array.Empty<(string, double)>());
        if (час >= 23 || час < 6.5)
            return new Подслушано(new[] { Слова(Из("спят", "кв" + кв), я, я) }, Array.Empty<(string, double)>());
        var строки = new List<string>();
        var о_еде = new List<(string, double)>();
        foreach (var (p, n) in дома.Take(2).Select((p, n) => (p, n)))
        {
            string голос = Знакомство.Знает(h, я, p) ? $"голос {p.form("gen")}"
                         : p.sex == "ж" ? "женский голос" : "мужской голос";
            var (список, кому) = О_чём(h, я, p, з);
            string слова;
            if (список is null)
                слова = Из("ответ", p.id);
            else
            {
                слова = Из(список, p.id);
                if (кому is not null)
                    слова = слова.Replace("{кто}", кому.@short, StringComparison.Ordinal)
                                 .Replace("{кого}", кому.form("gen"), StringComparison.Ordinal)
                                 .Replace("{кому}", кому.form("dat"), StringComparison.Ordinal)
                                 .Replace("{кем}", кому.form("ins"), StringComparison.Ordinal);
                слова = слова.Replace("{кв}", я.apt.ToString(System.Globalization.CultureInfo.InvariantCulture),
                                      StringComparison.Ordinal);
                if (список is "голод" or "запасы")
                    о_еде.Add((p.id, p.stock.Взять("еда", 0.0)));
            }
            // второй — чаще отвечает первому, чем начинает своё
            if (n == 1 && список is not ("на_героя" or "о_герое") && Округа.Бросок(зерно, "слушать_второй", p.id, раз + h.day * 19) < 0.5)
                слова = Из("ответ", p.id);
            строки.Add($"{СЗаглавной(голос)}: «{Слова(слова, p, я)}»");
        }
        return new Подслушано(строки, о_еде);
    }

    /// <summary>О чём человек говорит у себя дома, если его не видят: имя
    /// списка и о ком (для «{кому}»); null — просто поддакнет.</summary>
    private static (string? список, NPC? кому) О_чём(House h, NPC я, NPC p, Заражение? з)
    {
        if (p.замысел is { } за)
        {
            if (за.вид == "рассорить" && за.враг == я.id)
                return ("на_героя", null);
            var кому = h.живой(за.враг ?? за.друг ?? "");
            if (Замыслы.ВИДЫ.Contains(за.вид) && (за.вид is not ("рассорить" or "вместе") || кому is not null))
                return (за.вид, кому);
        }
        if (p.hate.Взять(я.id, 0.0) > 30)
            return ("о_герое", null);
        if (з is not null && з.Стадия(p.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО)
            return ("болезнь", null);
        double еды = p.stock.Взять("еда", 0.0);
        if (p.satiety < 35 || еды < 2)
            return ("голод", null);
        if (еды >= 12)
            return ("запасы", null);
        if (p.panic > 60)
            return ("страх", null);
        return ("быт", null);
    }

    // ------------------------------------------------------------ записки

    /// <summary>
    /// Что написано на дверях сегодня — то, что жильцы пишут друг другу
    /// и что видит каждый на площадке: мелом крест, где хозяин остался
    /// внутри; «мы у такого-то» — где все съехали к соседу; «болеем, не
    /// стучать» — где больной (болезнь с «Вектора», только в мире героя);
    /// «кому совсем плохо — стучите» — у того, кто последнее отдаст, когда
    /// в доме уже голодно. Пустая, разобранная, без живых — без записки.
    /// </summary>
    public IReadOnlyList<Записка> Записки(House h, NPC я, IReadOnlyList<ДверьСнаружи> двери, Заражение? з, long зерно)
    {
        int свой = h.хозяин_жилья(я).apt;
        string Из(string список, int кв) => Одна(_записки[список], зерно, "записка_" + список, "кв" + кв, h.day);
        var @out = new List<Записка>();
        foreach (var д in двери.OrderBy(д => д.квартира))
        {
            int кв = д.квартира;
            if (кв == свой)
                continue;                   // на своей двери герой пишет сам — если захочет
            if (д.тело)
            {
                @out.Add(new Записка(кв, Из("тело", кв), Чем.МЕЛ));
                continue;
            }
            var прописаны = h.people.Значения.Where(p => p.apt == кв).ToList();
            var живут = h.alive().Where(p => h.хозяин_жилья(p).apt == кв).ToList();
            // все прописанные живы и живут у соседа — пишут, где искать
            if (живут.Count == 0 && прописаны.Count > 0 && прописаны.All(p => p.alive)
                && прописаны.Select(p => h.хозяин_жилья(p)).FirstOrDefault(f => f.apt != кв) is { } у
                && h.alive().Where(p => p.apt == у.apt).OrderBy(p => p.id, StringComparer.Ordinal).FirstOrDefault() is NPC хозяин)
            {
                @out.Add(new Записка(кв, Из("переехали", кв).Replace("{кого}", хозяин.form("gen").ToUpperInvariant(), StringComparison.Ordinal)
                                                        .Replace("{кв}", у.apt.ToString(System.Globalization.CultureInfo.InvariantCulture), StringComparison.Ordinal),
                                     Чем.БУМАГА));
                continue;
            }
            if (з is not null && живут.Any(p => з.Стадия(p.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО))
            {
                @out.Add(new Записка(кв, Из("болеют", кв), Чем.БУМАГА));
                continue;
            }
            if (h.day >= 3 && живут.Any(p => p.пунктики.Contains("последнее_отдаст", StringComparer.Ordinal)
                                             && p.stock.Взять("еда", 0.0) > 0))
                @out.Add(new Записка(кв, Из("отдаст", кв), Чем.БУМАГА));
        }
        return @out;
    }

    // ------------------------------------------------------------ из окна

    /// <summary>
    /// Что видно из своего окна: погода дня, снег, мороз, зарево над городом
    /// (летопись), кто во дворе и у гаражей (хроника; в буран и ночью двора
    /// не видно). Строки — по одной на то, что видно. До метели
    /// (<paramref name="до_метели"/>) — обычный двор: метели ещё нет.
    /// </summary>
    public IReadOnlyList<string> Из_окна(House h, NPC я, IReadOnlyList<СоседГде> кто_где, Летопись? л,
                                         double час, long зерно, int раз, bool до_метели = false)
    {
        string Из(string список, int ещё = 0)
            => Одна(_окно[список], зерно, "окно_" + список, я.id, раз + h.day * 13 + ещё);
        var строки = new List<string>();
        if (до_метели)
            return new[] { Слова(Из("до_метели"), я, я) };
        bool ночь = час >= 20 || час < 7;
        bool видно_двор = !ночь && h.режим != Режим.БУРАН;
        строки.Add(ночь ? Из(h.power_on ? "ночь" : "темно")
                        : Из(h.режим switch { Режим.БУРАН => "буран", Режим.ЗАТИШЬЕ => "затишье", _ => "метель" }));
        if (h.снег >= 1.0 && !ночь)
            строки.Add(Из("сугробы"));
        if (h.outside <= -30)
            строки.Add(Из("мороз"));
        if (л is not null)
        {
            var мир = л.На(h.day, зерно);
            foreach (var (место, здание) in мир.здания.OrderBy(п => п.Key, StringComparer.Ordinal))
                if (здание == Здание.ГОРИТ && л.места.TryGetValue(место, out var имя))
                {
                    строки.Add(Из("зарево").Replace("{место}", имя, StringComparison.Ordinal));
                    break;
                }
        }
        if (видно_двор)
        {
            int n = 0;
            foreach (var с in кто_где.Where(с => с.где == Где.ЗаПорогом && с.место is string м
                                                 && (м.StartsWith("двор", StringComparison.Ordinal)
                                                     || м.StartsWith("гараж", StringComparison.Ordinal))))
            {
                // в окно лица не разглядеть: знакомого узнают по фигуре, чужой — «кто-то»
                string кто = h.живой(с.id) is NPC п && Знакомство.Знает(h, я, п) ? п.@short : "кто-то из соседей";
                string список = с.место!.StartsWith("гараж", StringComparison.Ordinal) ? "у_гаражей" : "во_дворе";
                строки.Add(СЗаглавной(Из(список, n++).Replace("{кто}", кто, StringComparison.Ordinal)));
                if (n >= 2)
                    break;
            }
            if (n == 0)
                строки.Add(Из("пусто"));
        }
        return строки.Select(с => Слова(с, я, я)).ToList();
    }
