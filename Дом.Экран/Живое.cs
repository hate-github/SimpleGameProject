// Живой подъезд: что соседи говорят на ходу, что отвечает дверь, когда стучат
// просто так, и что видно из окна (импровизация 17.11.2026 по просьбе автора:
// «чтобы игра ощущалась более живой, а тупые моменты максимально исчезли»).
//
// Прежде у двери, к которой дом ничего не положил, стук кончался надписью
// «сейчас сюда незачем» — за дверью живой человек, а мир молчал. Соседи
// в подъезде стояли немыми фигурами, окно и матрас отвечали тем же
// «незачем». Здесь — то, что человек и правда слышит и видит:
//
//   · **на ходу** (`Мимоходом`) — сосед, мимо которого проходят, говорит
//     о том, что его давит сильнее всего: злой — зло или молчит, больной
//     кашляет, голодный, замёрзший, вымотанный, напуганный, раненый —
//     о себе; у чужой двери — к кому пришёл; после смерти в доме — о ней;
//     иначе — по времени и по тому, как он к герою относится;
//   · **у двери** (`За_дверью`) — стук без дела: дома ли кто (тишина, сон,
//     тело, пустая квартира), болен ли, рад ли герою (злой не откроет,
//     чужой — на цепочку, свой — нараспашку), не стучат ли второй раз;
//     и что слышно за дверью — кашель, ребёнок, голоса;
//   · **из окна** (`Из_окна`) — погода дня, снег, мороз, зарево над городом
//     и кто сейчас во дворе или у гаражей.
//
// За ночь к этому добавилось (разделы ниже, по порядку): мысли героя
// у тяжёлой двери, о себе и дома (`Мысль_у_двери`, `Мысль_о_себе`,
// `Мысль_дома`); что слышно у чужой двери (`У_двери`) и из-за двери, не стуча
// (`Слышно_за_дверьми`, с делом из хроники); записки на дверях (`Записки`:
// крест, «болеем», «вор» мелом, бумажки с осени, записки героя — своя
// и соседу, «зайди» герою); былое на ходу (`Прошлое`), сплетни (`Сплетня`),
// «что слышно?» (`Что_слышно`), по трубе (`По_трубе`), доска объявлений
// (`Объявления`), свечи (`Свечи`), подслушать (`Подслушать`).
//
// Почти всё это — только слова и только чтение: дом не меняется, доверие
// не растёт, сплетни не идут (это дело «разговора» дома), бросок —
// `Округа.Бросок` от зерна мимо `h.rng`. Эталон цел. Каждый говорит о себе
// то, что сам про себя знает, а герой видит и слышит то, что видно
// и слышно с площадки и из окна — ни шкафа, ни мыслей. Меняют дом только
// поступки героя через узел: услышанное о чужом шкафе ложится в его знание
// (`note_signal`), записки героя — поля только у игрока (`ЗапискаГероя`).

