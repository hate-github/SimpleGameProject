    /// <summary>
    /// Что сосед <paramref name="с"/> бросит герою, проходящему мимо, — одной
    /// строкой; null — промолчит. <paramref name="где"/> и <paramref name="у_двери"/> —
    /// где он стоит (хроника), <paramref name="час"/> — час героя,
    /// <paramref name="раз"/> — который раз за день он заговорил.
    /// </summary>
    public string? Мимоходом(House h, NPC я, NPC с, Где где, int у_двери, double час, Заражение? з,
                             long зерно, int раз)
    {
        double Бросок(string повод) => Округа.Бросок(зерно, "мимо_" + повод, с.id, раз + h.day * 31);
        string Из(string список) => Одна(_мимоходом[список], зерно, "мимо_" + список, с.id, раз + h.day * 31);
        string отношение = Отношение(я, с);

        bool с_ношей = я.ноша is { пусто: false };
        // знает, что герой ворует (поймал сам или слышал, как назвали за три дня), — в лицо
        if (с.memory.Any(п => п.кто == я.id && п.вид is Вид.ПОЙМАЛ_ВОРА or Вид.НАЗВАЛИ_ВОРОМ && h.day - п.день <= 3)
            && Бросок("вор") < 0.7)
            return Слова(Из("вор_герой"), с, я);
        // в руках топор, монтировка, нож — это видно всем, и каждый скажет по-своему
        if (я.снаряжение?.в_руках is string в_руках && Бросок("в_руках") < 0.5)
            return Слова(Из("в_руках_" + отношение).Replace("{что}", в_руках, StringComparison.Ordinal), с, я);
        // злой — зло или молча отворачивается; ношу заметит и он
        if (отношение == "злой")
            return Бросок("злой") >= 0.6 ? null
                 : Слова(Из(с_ношей && Бросок("ноша") < 0.5 ? "ноша_чужой" : "злой"), с, я);
        // болен с «Вектора» — кашляет и держит дистанцию
        if (з is not null && з.Стадия(с.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО)
            return Слова(Из("болен"), с, я);
        // больную героиню видно — как в дверях, по отношению
        if (з is not null && з.Стадия(я.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО && Бросок("герой_болен") < 0.6)
            return Слова(Одна(_болезнь["герой_болен." + отношение], зерно, "мимо_герой_болен", с.id, раз + h.day * 31), с, я);
        // герой ранен — хромает, кровь на повязке: это видно, и свой предложит помочь
        if ((я.health < 40 || я.injuries.Count > 0) && Бросок("ранен_герой") < 0.5)
            return Слова(Из(отношение is "свой" or "знакомый" ? "ранен_герой_свой" : "ранен_герой_чужой"), с, я);
        // героиня несёт полную тару — это видно всем
        if (с_ношей && Бросок("ноша") < 0.5)
            return Слова(Из(отношение is "свой" or "знакомый" ? "ноша_свой" : "ноша_чужой"), с, я);
        // что было между ними за два дня — сосед был стороной и помнит
        if (Прошлое(h, я, с) is string было && Бросок("прошлое") < 0.6)
            return Слова(Из(было), с, я);
        // ночью на лестнице — свой спросит, не спится ли, чужой насторожится
        if ((час >= 23 || час < 6) && Бросок("ночь") < 0.6)
            return Слова(Из(отношение is "свой" or "знакомый" ? "ночь_свой" : "ночь_чужой"), с, я);
        // записку героя на своей двери он прочёл — и скажет, что зайдёт
        if (я.записки_соседям is { } мои && мои.TryGetValue(с.id, out var мне) && h.day <= мне.до_дня
            && отношение != "злой" && Бросок("прочёл") < 0.7)
            return Слова(Из("прочёл_" + мне.вид), с, я);
        // записку на двери героини читали все — кто-нибудь да скажет
        if (я.записка is string записка && Бросок("записка") < 0.35
            && _мимоходом.ContainsKey("записка_" + записка))
            return Слова(Из("записка_" + записка), с, я);
        // ребёнок голоден, мёрзнет или болен — родитель о нём, а не о себе
        if (с.дети.FirstOrDefault(р => р.у is null && (р.болен is not null || р.сытость < 40 || р.тепло < 40)) is { } дитя
            && Бросок("ребёнок") < 0.7)
            return Слова(Из(дитя.болен is not null ? "ребёнок_болен" : дитя.сытость < 40 ? "ребёнок_голод" : "ребёнок_холод")
                         .Replace("{ребёнок}", дитя.имя, StringComparison.Ordinal)
                         .Replace("{вин}", дитя.вин, StringComparison.Ordinal)
                         .Replace("{род}", дитя.род, StringComparison.Ordinal)
                         .Replace("{твор}", дитя.твор, StringComparison.Ordinal), с, я);
        // что давит сильнее всего — о том и скажет, чаще всего
        if (Нужда(с) is string нужда && Бросок("нужда") < 0.75)
            return Слова(Из(нужда), с, я);
        // что сам видел и слышал за последние дни — пересказывает
        if (Сплетня(h, я, с) is var (список, о_ком) && Бросок("сплетня") < 0.6)
            return Слова(Из(список).Replace("{кто}", о_ком.@short, StringComparison.Ordinal)
                                   .Replace("{кого}", о_ком.form("gen"), StringComparison.Ordinal)
                                   .Replace("{кем}", о_ком.form("ins"), StringComparison.Ordinal)
                                   .Replace("{вин}", о_ком.form("acc"), StringComparison.Ordinal), с, я);
        // пришёл к соседу — к кому
        if (где == Где.УДвери && Живёт_за(h, у_двери, с) is NPC хозяин && Бросок("дверь") < 0.6)
            return Слова(Из("к_двери").Replace("{кому}", Знакомство.Как_зовут(h, с, хозяин, "dat"),
                                                StringComparison.Ordinal), с, я);
        // в доме умирали — об этом говорят все
        if (Умер_недавно(h) is NPC мёртв && Бросок("смерть") < 0.5)
            return Слова(Из("смерть").Replace("{умер}", мёртв.@short, StringComparison.Ordinal), с, я);
        // время дня и погода сегодня: буран, метель, затишье — или «затихло» после бурана
        if (Бросок("время") < 0.35)
            return Слова(Из(час < 10 ? "утро" : час >= 19 ? "вечер" : Погода(h)), с, я);
        return Слова(Из(отношение), с, я);
    }

    /// <summary>О какой погоде говорят сегодня: буран, метель, затишье, а в первый
    /// тихий день после непогоды — «затихло».</summary>
    private static string Погода(House h) => h.режим switch
    {
        Режим.БУРАН => "буран",
        Режим.ЗАТИШЬЕ => h.режим_вчера == Режим.ЗАТИШЬЕ ? "затишье" : "затихло",
        _ => "метель",
    };

    /// <summary>
    /// Что было между соседом и героем за последние два дня — то, что сосед
    /// знает сам, потому что был стороной: герой ему помог, вылечил, отнял,
    /// сосед дал герою или отнял у него, поменялись (`h.события`), герой
    /// обещал вернуть (`NPC.обещал`). Долг — первым, дальше самое свежее.
    /// Имя списка «мимоходом» или null — ничего не было.
    /// </summary>
    public static string? Прошлое(House h, NPC я, NPC с)
    {
        foreach (var о in я.обещал)
            if (о.кому == с.id && о.вид == "отдать")
                return h.day >= о.срок ? "долг_срок" : "долг";     // вечером срока слово уже нарушено
        for (int i = h.события.Count - 1; i >= 0; i--)
        {
            var е = h.события[i];
            if (h.day - е.день > 2)
                break;                      // поток идёт по дням: дальше только старее
            bool от_меня = е.кто == я.id && е.кому == с.id;
            bool мне = е.кто == с.id && е.кому == я.id;
            string? список = е.вид switch
            {
                ВидСобытия.ПОМОЩЬ when от_меня => "спасибо_помощь",
                ВидСобытия.ПОМОЩЬ when мне => "дал_герою",
                ВидСобытия.ЛЕЧЕНИЕ when от_меня => "спасибо_лечение",
                ВидСобытия.ОБМЕН when от_меня || мне => "обмен_герой",
                ВидСобытия.ОТЪЁМ when от_меня => "отнял_герой",
                ВидСобытия.ОТЪЁМ when мне => "отнял_у_героя",
                _ => null,
            };
            if (список is not null)
                return список;
        }
        return null;
    }

    /// <summary>
    /// Что сосед сам видел и слышал вчера и сегодня (`NPC.memory`) и готов
    /// пересказать на ходу — самое громкое: убийство, изгнание, пойманный
    /// вор, своя пропажа, «назвали вором», пойманный на лжи. О самом герое
    /// ему в лицо не говорят. null — нечего.
    /// </summary>
    public static (string список, NPC о_ком)? Сплетня(House h, NPC я, NPC с)
    {
        var по_важности = new[]
        {
            (Вид.ВИДЕЛ_УБИЙСТВО, "убийство"), (Вид.ВИДЕЛ_ИЗГНАНИЕ, "изгнание"), (Вид.ПОЙМАЛ_ВОРА, "вор_пойман"),
            (Вид.ПРОПАЖА, "пропажа"), (Вид.НАЗВАЛИ_ВОРОМ, "назвали_вором"), (Вид.ПОЙМАЛ_НА_ЛЖИ, "на_лжи"),
        };
        foreach (var (вид, список) in по_важности)
            foreach (var п in с.memory.Where(п => п.вид == вид && h.day - п.день <= 1).Reverse())
            {
                if (п.кто == я.id || (п.кто == с.id && вид != Вид.ПРОПАЖА))
                    continue;
                if (h.people.TryGetValue(п.кто, out var о_ком))
                    return (список, о_ком);
            }
        return null;
    }

    /// <summary>Что давит на человека сильнее всего — имя списка, или null, если ничего.
    /// Пороги — где это слышно в голосе, а не где начинает считать дом.</summary>
    public static string? Нужда(NPC с)
    {
        var давит = new List<(string что, double насколько)>();
        if (с.satiety < 30) давит.Add(("голод", 30 - с.satiety));
        if (с.hydration < 30) давит.Add(("жажда", 30 - с.hydration));
        if (с.warmth < 35) давит.Add(("холод", 35 - с.warmth));
        if (с.rest < 25) давит.Add(("усталость", 25 - с.rest));
        if (с.health < 40) давит.Add(("ранен", 40 - с.health));
        if (с.panic > 60) давит.Add(("страх", с.panic - 60));
        if (с.mood < 25) давит.Add(("тоска", 25 - с.mood));
        return давит.Count == 0 ? null
            : давит.OrderByDescending(д => д.насколько).ThenBy(д => д.что, StringComparer.Ordinal).First().что;
    }

    /// <summary>Кто живёт за дверью <paramref name="кв"/> (кроме <paramref name="кроме"/>):
    /// хозяин — первым, потом переехавшие к нему.</summary>
    private static NPC? Живёт_за(House h, int кв, NPC? кроме)
        => h.alive().Where(p => !ReferenceEquals(p, кроме) && h.хозяин_жилья(p).apt == кв)
                    .OrderBy(p => p.apt == кв ? 0 : 1).ThenBy(p => p.id, StringComparer.Ordinal)
                    .FirstOrDefault();

    /// <summary>Кто в доме умер сегодня или вчера — о нём говорят все.</summary>
    private static NPC? Умер_недавно(House h)
        => h.people.Значения.Where(p => !p.alive && p.died_day is int д && h.day - д <= 1)
                            .OrderByDescending(p => p.died_day).ThenBy(p => p.id, StringComparer.Ordinal)
                            .FirstOrDefault();

    // ------------------------------------------------------------ у двери

    /// <summary>
    /// Стук в дверь <paramref name="кв"/>, к которой дом ничего не положил:
    /// кто за ней и что он скажет. <paramref name="кто_где"/> — где каждый
    /// сосед в час героя (`Подача.Кто_где`), <paramref name="снаружи"/> — что
    /// видно у двери, <paramref name="опять"/> — стучали только что,
    /// <paramref name="раз"/> — который раз за день к этой двери.
    /// </summary>
    public ОтветДвери За_дверью(House h, NPC я, int кв, IReadOnlyList<СоседГде> кто_где, ДверьСнаружи? снаружи,
                                double час, Заражение? з, bool опять, long зерно, int раз)
    {
        string Из(string список, string кто) => Одна(_за_дверью[список], зерно, "дверь_" + список, кто, раз + h.day * 17);
        string повод = "кв" + кв;
        var жильцы = кто_где.Where(с => с.дом == кв).ToList();
        if (жильцы.Count == 0)
        {
            // никто здесь не живёт: хозяин остался внутри, квартиру растащили, пусто
            var что = снаружи?.тело == true ? ЗаДверью.ТЕЛО : снаружи?.разобрана == true ? ЗаДверью.РАЗОБРАНА : ЗаДверью.ПУСТО;
            string список = что switch { ЗаДверью.ТЕЛО => "тело", ЗаДверью.РАЗОБРАНА => "разобрана", _ => "пусто" };
            return new ОтветДвери(что, null, false, Слова(Из(список, повод), я, я), null);
        }
        var дома = жильцы.Where(с => с.где == Где.Дома).Select(с => h.живой(с.id)).OfType<NPC>().ToList();
        if (дома.Count == 0)
        {
            // не дома, но здесь же, в подъезде, — у чьей-то двери: так и сказать, где он
            if (жильцы.FirstOrDefault(с => с.где is Где.УДвери or Где.НаПлощадке) is { } рядом && h.живой(рядом.id) is NPC он)
                return new ОтветДвери(ЗаДверью.НИКОГО, null, false,
                    Слова(Из("в_подъезде", повод), он, я)
                        .Replace("{кто}", СЗаглавной(Знакомство.Как_зовут(h, я, он)), StringComparison.Ordinal)
                        .Replace("{кв}", рядом.квартира.ToString(System.Globalization.CultureInfo.InvariantCulture), StringComparison.Ordinal),
                    null);
            return new ОтветДвери(ЗаДверью.НИКОГО, null, false, Слова(Из("никого", повод), я, я), null);
        }
        var кто = дома.OrderBy(p => p.apt == кв ? 0 : 1).ThenBy(p => p.id, StringComparer.Ordinal).First();
        string? слышно = Слышно(h, кв, дома, кто_где, з, зерно, раз);
        if (час >= 23 || час < 6.5)
            return new ОтветДвери(ЗаДверью.СПИТ, кто, false, Слова(Из("спит", кто.id), кто, я), слышно);
        var стадия = з?.Стадия(кто.id);
        if (стадия == Стадия.ТЯЖЕЛО)
            return new ОтветДвери(ЗаДверью.ТЯЖЕЛО, кто, false,
                                  Слова(Одна(_болезнь["тяжело"], зерно, "дверь_тяжело", кто.id, раз), кто, я), слышно);
        if (стадия == Стадия.БОЛЕН)
            return new ОтветДвери(ЗаДверью.БОЛЕН, кто, false, Слова(Из("болен", кто.id), кто, я), слышно);
        string отношение = Отношение(я, кто);
        if (отношение == "злой")
            return new ОтветДвери(ЗаДверью.ЗЛОЙ, кто, false, Слова(Из("злой", кто.id), кто, я), слышно);
        if (опять && отношение != "свой")
            return new ОтветДвери(ЗаДверью.ОПЯТЬ, кто, false, Слова(Из("опять", кто.id), кто, я), слышно);
        // на двери героя «болею» — сам написал; кроме своих, никто не откроет
        if (я.записка == "болею" && отношение != "свой")
            return new ОтветДвери(ЗаДверью.БОИТСЯ, кто, false, Слова(Из("сам_болеешь", кто.id), кто, я), слышно);
        // у двери уже стоят — хозяину не до героя
        if (кто_где.Any(с => с.где == Где.УДвери && с.квартира == кв && с.id != я.id))
            return new ОтветДвери(ЗаДверью.ЗАНЯТ, кто, false, Слова(Из("занят", кто.id), кто, я), слышно);
        // сам звал героя запиской на его двери (замысел «вместе») — рад, что пришёл
        if (кто.замысел is { вид: "вместе" } звал && звал.друг == я.id)
            return new ОтветДвери(отношение == "свой" ? ЗаДверью.СВОЙ : ЗаДверью.ЗНАКОМЫЙ, кто, true,
                                  Слова(Из("звал", кто.id), кто, я), слышно);
        var (вид, список_) = отношение switch
        {
            "свой" => (ЗаДверью.СВОЙ, "свой"),
            "знакомый" => (ЗаДверью.ЗНАКОМЫЙ, "знакомый"),
            _ => (ЗаДверью.ЧУЖОЙ, "чужой"),
        };
        return new ОтветДвери(вид, кто, true, Слова(Из(список_, кто.id), кто, я), слышно);
    }

    /// <summary>Что слышно за дверью: кашель больного, ребёнок, голоса двоих —
    /// то, что и через дверь не спрячешь, — и чем там заняты (хроника): стучит
    /// молоток, тянет варёным или жареным мясом, дымком, гремят посудой, храпят,
    /// гудит генератор. null — тихо.</summary>
    private string? Слышно(House h, int кв, IReadOnlyList<NPC> дома, IReadOnlyList<СоседГде> кто_где, Заражение? з,
                           long зерно, int раз)
    {
        string Из(string список) => Одна(_за_дверью[список], зерно, "слышно_" + список, "кв" + кв, раз + h.day * 17);
        var слышно = new List<string>();
        if (з is not null && дома.Any(p => з.Стадия(p.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО))
            слышно.Add(Из("кашель"));
        if (дома.SelectMany(p => p.дети).Any(р => р.у is null && (р.сытость < 40 || р.тепло < 40 || р.болен is not null))
            || h.alive().SelectMany(p => p.дети).Any(р => р.у is string у && h.живой(у) is NPC где && h.хозяин_жилья(где).apt == кв
                                                         && (р.сытость < 40 || р.тепло < 40)))
            слышно.Add(Из("ребёнок"));
        if (дома.Count >= 2)
            слышно.Add(Из("голоса"));
        // чем заняты — самое заметное: мясо, работа, еда, дым, быт, генератор, сон
        string[] порядок = { "мясо", "работа", "еда", "дым", "быт", "гул", "сон" };
        var заняты = кто_где.Where(с => с.дом == кв && с.где == Где.Дома && ЗАНЯТ_ДОМА.ContainsKey(с.ключ))
                            .Select(с => ЗАНЯТ_ДОМА[с.ключ]).ToHashSet(StringComparer.Ordinal);
        if (порядок.FirstOrDefault(заняты.Contains) is string занят)
            слышно.Add(Из(занят));
        return слышно.Count == 0 ? null : string.Join(" ", слышно);
    }

    /// <summary>
    /// Что слышно у каждой жилой двери сейчас, не стуча (`Слышно`): кашель
    /// больного, плач голодного ребёнка, голоса двоих. Считается на вопросе,
    /// пока дом спит, — подсказка у двери читает готовое. Номер — квартира,
    /// за которой это слышно.
    /// </summary>
    public IReadOnlyDictionary<int, string> Слышно_за_дверьми(House h, IReadOnlyList<СоседГде> кто_где, Заражение? з,
                                                             long зерно)
    {
        var @out = new Dictionary<int, string>();
        foreach (int кв in кто_где.Select(с => с.дом).Distinct().OrderBy(к => к))
        {
            var дома = кто_где.Where(с => с.дом == кв && с.где == Где.Дома)
                              .Select(с => h.живой(с.id)).OfType<NPC>().ToList();
            if (дома.Count > 0 && Слышно(h, кв, дома, кто_где, з, зерно, 0) is string слышно)
                @out[кв] = слышно;
        }
        return @out;
    }

    // ------------------------------------------------------------ мысль героя

    /// <summary>
    /// Что подумает герой, впервые за день увидев эту дверь: крест мелом,
    /// голые доски, копоть, сорванный замок, «болеем», свет из-под двери —
    /// самое тяжёлое из того, что видно. Тон — по рассудку (ГДД 11): обычно —
    /// сочувствие и страх, с тревоги — холодно, расчётом. null — смотреть
    /// не на что.
    /// </summary>
    public string? Мысль_у_двери(NPC я, ДверьСнаружи? д, Записка? записка, Порог порог, long зерно, int день)
    {
        string? что = д is null ? null
                    : д.тело ? "тело" : д.разобрана ? "разобрана" : д.горело ? "горело" : д.взломана ? "взломана"
                    : записка is not null && _записки["болеют"].Contains(записка.текст) ? "болеют"
                    : д.свет ? "свет" : null;
        if (что is null)
            return null;
        string тон = порог == Порог.ОБЫЧНО ? "_обычно" : "_холодно";
        return Слова(Одна(_мысли[что + тон], зерно, "мысль_" + что, "кв" + д!.квартира, день), я, я);
    }

    /// <summary>
    /// Что давит на самого героя сильнее всего — его же словами, строкой
    /// на ходу: болезнь (когда уже знобит), голод, жажда, холод, усталость,
    /// рана, страх, тоска — по тем же порогам, что у соседей (`Нужда`). Тон —
    /// по рассудку, как у мысли у двери. null — ничего не давит.
    /// </summary>
    public string? Мысль_о_себе(NPC я, Заражение? з, Порог порог, long зерно, int день, int раз)
    {
        string? что = з?.Стадия(я.id) is Стадия.БОЛЕН or Стадия.ТЯЖЕЛО ? "болен" : Нужда(я);
        if (что is null)
            return null;
        string тон = порог == Порог.ОБЫЧНО ? "_обычно" : "_холодно";
        return Слова(Одна(_мысли["о_себе_" + что + тон], зерно, "о_себе_" + что, я.id, день * 13 + раз), я, я);
    }

    // ------------------------------------------------------------ свечи

    /// <summary>У каких дверей горит свеча: где жилец умер сегодня или вчера
    /// (план подъезда — то, что видит всякий; квартира — по прописке).</summary>
    public static IReadOnlyList<int> Свечи(IReadOnlyList<ЖилецНаПлане> план, int день)
        => план.Where(ж => !ж.здесь && ж.умер_днём is int д && день - д <= 1)
               .Select(ж => ж.квартира).Distinct().OrderBy(к => к).ToList();

    // ------------------------------------------------------------ доска объявлений

    /// <summary>
    /// Что висит на доске у входа. Каждое объявление пишет тот, кто знает:
    /// мену — сосед о своём шкафе (избыток от шести порций, лекарств — от двух,
    /// нехватка — запаса меньше, чем ему кажется нужным, `NPC.secure`; лекарств —
    /// только когда болит), до трёх
    /// самых щедрых; кражу — у кого за два дня пропало (`Вид.ПРОПАЖА`); смерть —
    /// кто умер за три дня (знает весь дом); медик, когда знает, что в доме болеют,
    /// — совет сидеть дома; и всегда — бумажка с осени, одна на мир. Аркадий
    /// («знал_заранее») ничего не вешает: он ничем не делится.
    /// </summary>
    public IReadOnlyList<Объявление> Объявления(House h, NPC я, Заражение? з, long зерно, bool до_метели = false)
    {
        string Из(string список, string повод) => Одна(_доска[список], зерно, "доска_" + список, повод, h.day);
        static string Кв(int кв) => кв.ToString(System.Globalization.CultureInfo.InvariantCulture);
        var старая = new Объявление(Одна(_доска["старые"], зерно, "доска_старые", "доска", 0), null, null, 0.0);
        if (до_метели)
            return new[] { старая };       // до метели на доске только то, что висело с осени
        var @out = new List<Объявление>();
        var живые = h.alive().Where(p => p != я && p.здесь()).OrderBy(p => p.apt).ThenBy(p => p.id, StringComparer.Ordinal).ToList();
        // смерть — первой: о ней знает весь дом
        foreach (var мёртв in h.people.Значения.Where(p => !p.alive && p.died_day is int д && h.day - д <= 3)
                                                 .OrderByDescending(p => p.died_day).ThenBy(p => p.id, StringComparer.Ordinal))
            @out.Add(new Объявление(Из("смерть", мёртв.id).Replace("{кто}", мёртв.@short.ToUpperInvariant(), StringComparison.Ordinal)
                                                          .Replace("{кв}", Кв(мёртв.apt), StringComparison.Ordinal), null, null, 0.0));
        // медик знает, что в доме болеют, — советует сидеть дома
        if (з is not null && живые.FirstOrDefault(p => p.skills.Contains("медик", StringComparer.Ordinal)
                                                       && Эпидемия.Вести(h, p, я, з).в_доме) is NPC медик)
            @out.Add(new Объявление(Из("медик", медик.id).Replace("{кто}", медик.@short.ToUpperInvariant(), StringComparison.Ordinal)
                                                         .Replace("{кв}", Кв(медик.apt), StringComparison.Ordinal), null, null, 0.0));
        // обокрали — пишет обокраденный
        foreach (var p in живые.Where(p => p.memory.Any(м => м.вид == Вид.ПРОПАЖА && h.day - м.день <= 2)))
            @out.Add(new Объявление(Из("кража", p.id).Replace("{кв}", Кв(h.хозяин_жилья(p).apt), StringComparison.Ordinal), null, null, 0.0));
        // мена: избыток на нехватку — до трёх самых щедрых
        var мена = new List<(NPC p, string что, string на, double сколько)>();
        foreach (var p in живые.Where(p => !p.пунктики.Contains("знал_заранее", StringComparer.Ordinal)))
        {
            var избыток = МЕНА.Select(р => (р, сколько: p.stock.Взять(р, 0.0), порог: р == "лекарства" ? 2.0 : 6.0))
                              .Where(х => х.сколько >= х.порог)
                              .OrderByDescending(х => х.сколько / х.порог).ThenBy(х => х.р, StringComparer.Ordinal).FirstOrDefault();
            if (избыток.р is null)
                continue;
            // лекарств «не хватает» всем, у кого их нет, — просят их, только когда болит
            bool болит = p.health < 50 || !string.IsNullOrEmpty(p.sick);
            var нехватка = МЕНА.Where(р => р != избыток.р && р != "материалы" && (р != "лекарства" || болит) && p.secure(р) < 0.8)
                               .OrderBy(р => p.secure(р)).ThenBy(р => р, StringComparer.Ordinal).FirstOrDefault();
            if (нехватка is not null)
                мена.Add((p, избыток.р, нехватка, избыток.сколько));
        }
        foreach (var (p, что, на, сколько) in мена.OrderByDescending(м => м.сколько).ThenBy(м => м.p.id, StringComparer.Ordinal).Take(3))
            @out.Add(new Объявление(Из("мена", p.id).Replace("{что}", _доска_ресурсы[что], StringComparison.Ordinal)
                                                    .Replace("{на}", _доска_ресурсы[на], StringComparison.Ordinal)
                                                    .Replace("{кв}", Кв(h.хозяин_жилья(p).apt), StringComparison.Ordinal),
                                    p.id, что, сколько));
        // бумажка с осени — одна на мир и не меняется
        @out.Add(старая);
        return @out;
    }

