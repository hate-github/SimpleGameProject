    БЕЖАТЬ_ЧЕРЕЗ_ОКНО = "бежать через окно"
    ЖДАТЬ_ЗА_ДВЕРЬЮ = "ждать за дверью"
    ВЫЙТИ_СО_СТВОЛОМ = "выйти со стволом"
    КРИЧАТЬ = "кричать"
    ВПУСТИТЬ_МЕДИКА = "впустить медика"

