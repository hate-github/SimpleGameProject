# -*- coding: utf-8 -*-
"""Шов решения (GDD 13): кто выбирает за жильца.

Правила дома одни для всех: они собирают оценённые варианты — что делать
днём, что ночью, кричать ли, когда за дверью стоят с ломом, пустить ли соседа
к себе, — а выбирает из них `Решающий` жильца. У NPC это мягкий выбор
(`Софтмакс` — то самое поведение, на котором стоит эталон), у игрока —
`Человек`, в проверках и сценариях — `Скрипт`. Так игрок становится седьмым
жильцом без переписывания правил: ему достаются те же варианты с теми же
оценками. Тот же список — и объяснение решения: структурный разбор вместо
интерфейса (`объяснить`).

Решающий назначается при сборке (assembly; ключ «решает» в npcs.json) и может
быть заменён до первого дня: `sim.h.people["игорь"].решающий = Скрипт()`.
Он не состояние дома и в снимок не входит. Правило одно: решающий получает
готовые варианты и ничего в доме не меняет сам.
"""
from dataclasses import dataclass
from typing import Any, List, Optional, Tuple


@dataclass
class Ситуация:
    """Вопрос к жильцу с готовыми ответами и тем, как ответил бы NPC.

    варианты — [(ответ, вес)], первый — «да» этой ситуации. `склонность` —
    с какой вероятностью NPC берёт первый ответ: монета, как и была
    (`h.rng.chance`). Если склонности нет, NPC отвечает `по_правилу`: правило
    уже решило за него, а человек волен решить иначе.
    """
    вопрос: str
    варианты: List[Tuple[str, float]]
    склонность: Optional[float] = None
    по_правилу: Optional[str] = None


class Решающий:
    """Три вопроса, которые дом задаёт жильцу. Реализации ниже."""

    def день(self, h, npc, варианты):
        """варианты — [((ключ, цель), оценка)] уже выше порога; вернуть (ключ, цель)."""
        raise NotImplementedError

    def ночь(self, h, npc, варианты):
        """варианты — [((Ночь, цель), оценка)]; «спать» среди них есть всегда."""
        raise NotImplementedError

    def ответ(self, h, npc, ситуация):
        """Ответ на `Ситуация`: у своей двери в осаду, у чужой — с просьбой."""
        raise NotImplementedError


def _имя(о):
    if isinstance(о, tuple) and len(о) == 2:
        ключ, цель = о
        кто = getattr(цель, "short", None) or getattr(цель, "имя", None)
        return f"{ключ} → {кто}" if кто else (f"{ключ} → {цель}" if цель is not None else str(ключ))
    return str(о)


def объяснить(варианты, лучших=6):
    """Оценённые варианты строками, от лучшего к худшему: то, что показывают
    человеку и пишут в разбор. Это и есть объяснение решения."""
    top = sorted(варианты, key=lambda v: -v[1])[:лучших]
    return [f"{_имя(о):<30} {s:7.2f}" for о, s in top]


class Софтмакс(Решающий):
    """NPC: обычно лучшее, иногда второе или третье. Страх делает выбор
    безрассуднее, днём — и недосып (actions.choose_and_do, night.решение)."""

    def день(self, h, npc, варианты):
        b = h.B
        temp = b["температура_выбора"] + (npc.panic / 100.0) * b["температура_выбора_паника"]
        temp += (1.0 - npc.rest / 100.0) * 0.4
        return h.rng.softmax_pick(варианты, temp)

    def ночь(self, h, npc, варианты):
        b = h.B
        temp = b["температура_выбора"] + (npc.panic / 100.0) * b["температура_выбора_паника"]
        return h.rng.softmax_pick(варианты, temp)

    def ответ(self, h, npc, с):
        if с.склонность is not None:
            return с.варианты[0][0] if h.rng.chance(с.склонность) else с.варианты[1][0]
        return с.по_правилу


class Скрипт(Решающий):
    """Для проверок и сценариев: без случайности. Всегда лучший вариант,
    монета — по склонности от половины, правило — как есть; отдельные ответы
    можно задать заранее по вопросу. Каждое решение остаётся в `разбор`."""

    def __init__(self, ответы=None):
        self.ответы = dict(ответы or {})       # вопрос -> ответ (для Ситуация)
        self.разбор = []                        # (день, кто, вопрос, строки объяснения, выбор)

    def _записать(self, h, npc, вопрос, варианты, выбор):
        self.разбор.append((h.day, npc.id, вопрос, объяснить(варианты), выбор))

    def _лучший(self, варианты):
        return max(варианты, key=lambda v: v[1])[0] if варианты else None

    def день(self, h, npc, варианты):
        выбор = self._лучший(варианты)
        self._записать(h, npc, "день", варианты, _имя(выбор))
        return выбор

    def ночь(self, h, npc, варианты):
        выбор = self._лучший(варианты)
        self._записать(h, npc, "ночь", варианты, _имя(выбор))
        return выбор

    def ответ(self, h, npc, с):
        if с.вопрос in self.ответы:
            выбор = self.ответы[с.вопрос]
        elif с.склонность is not None:
            выбор = с.варианты[0][0] if с.склонность >= 0.5 else с.варианты[1][0]
        else:
            выбор = с.по_правилу
        self._записать(h, npc, с.вопрос, с.варианты, выбор)
        return выбор


def _консоль(вопрос, строки):
    print(вопрос)
    for i, s in enumerate(строки):
        print(f"  {i}. {s}")
    while True:
        try:
            return int(input("> "))
        except ValueError:
            continue


class Человек(Решающий):
    """Игрок (GDD 13): ему показывают оценённые варианты и спрашивают.

    `спросить(вопрос, строки) -> номер` — по умолчанию консоль; в игре на её
    место встаёт интерфейс. Оценки ему видны те же, что и NPC: это и есть
    «правило одно для всех».
    """

    def __init__(self, спросить=None):
        self.спросить = спросить or _консоль

    def _выбрать(self, h, npc, вопрос, варианты):
        порядок = sorted(варианты, key=lambda v: -v[1])
        i = self.спросить(f"день {h.day}, {npc.short}: {вопрос}", объяснить(варианты, len(варианты)))
        return порядок[max(0, min(int(i), len(порядок) - 1))][0]

    def день(self, h, npc, варианты):
        return self._выбрать(h, npc, "что делать", варианты) if варианты else None

    def ночь(self, h, npc, варианты):
        return self._выбрать(h, npc, "ночь", варианты) if варианты else None

    def ответ(self, h, npc, с):
        строки = [f"{о:<30} {вес:7.2f}" for о, вес in с.варианты]
        i = self.спросить(f"день {h.day}, {npc.short}: {с.вопрос}", строки)
        return с.варианты[max(0, min(int(i), len(с.варианты) - 1))][0]


