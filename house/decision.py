@dataclass
class Ситуация:
    """Вопрос к жильцу с готовыми ответами и тем, как ответил бы NPC.

    варианты — [(ответ, вес)], первый — «да» этой ситуации. `склонность` —
    с какой вероятностью NPC берёт первый ответ: монета, как и была
    (`h.rng.chance`). Если склонности нет, NPC отвечает `по_правилу`: правило
    уже решило за него, а человек волен решить иначе.
    """
    вопрос: Вопрос
    варианты: List[Tuple[str, float]]
    склонность: Optional[float] = None
    по_правилу: Optional[str] = None


class Решающий:
    """Три вопроса, которые дом задаёт жильцу. Реализации ниже."""

    # спрашивает ли этот решающий, из чего сложилась оценка. У мягкого выбора
    # NPC объяснение не читает никто, а копить его — сотни тысяч записей
    # за прогон, поэтому корзина смотрит на этот флаг и молчит по умолчанию
    # (`actions.Корзина.разбирать`)
    разбирает = False

    def день(self, h, npc, варианты, корзина=None):
        """варианты — [((ключ, цель), оценка)] уже выше порога; вернуть (ключ, цель).

        `корзина` — `actions.Корзина` этого хода: в ней слагаемые оценок,
        закрытые двери и самочувствие. Нужна только тому, кто объясняет.
        """
        raise NotImplementedError

    def ночь(self, h, npc, варианты, с=None):
        """варианты — [((Ночь, цель), оценка)]; «спать» среди них есть всегда.
        `с` — самочувствие этой ночи (`model.Самочувствие`)."""
        raise NotImplementedError

    def ответ(self, h, npc, ситуация):
        """Ответ на `Ситуация`: у своей двери в осаду, у чужой — с просьбой."""
        raise NotImplementedError

    def выбор(self, h, npc, вопрос, варианты):
        """Выбрать одно из оценённого там, где выбор жёсткий и без монеты:
        за что взяться (`замысел`), о чём говорить на площадке (`meeting`).

        варианты — [(значение, оценка)]; вернуть значение или None, если
        выбирать не из чего. От `день`/`ночь` отличается тем, что NPC берёт
        лучшее без софтмакса — так и было до появления этого вопроса.
        """
        raise NotImplementedError


def _имя(о):
    if isinstance(о, tuple) and len(о) == 2:
        ключ, цель = о
        кто = getattr(цель, "short", None) or getattr(цель, "имя", None)
        # цель бывает не человеком: пустая квартира — это «кв.11», а не весь
        # её repr со шкафом и убежищем
        if кто is None and getattr(цель, "apt", None) is not None:
            кто = f"кв.{цель.apt}"
        return f"{ключ} → {кто}" if кто else (f"{ключ} → {цель}" if цель is not None else str(ключ))
    return str(о)


def _разложение(сл):
    """Из чего сложилась оценка: `actions.Слагаемые` одной строкой."""
    части = [f"{сл.сырое:.2f} сырое"]
    for имя, v in (("пунктик", сл.пунктик), ("замысел", сл.замысел), ("запрет", -сл.запрет)):
        if abs(v) > 0.005:
            части.append(f"{v:+.2f} {имя}")
    if abs(сл.склонность) > 0.005:
        части.append(f"×{1.0 + сл.склонность:.2f} склонность")
    if abs(сл.ворота - 1.0) > 0.005:
        части.append(f"×{сл.ворота:.2f} нормальность")
    return " ".join(части) + f", {сл.часы:.1f} ч"


def объяснить(варианты, лучших=6, корзина=None):
    """Оценённые варианты строками, от лучшего к худшему: то, что показывают
    человеку и пишут в разбор. Это и есть объяснение решения.

    Строк ровно столько, сколько вариантов: по ним человек и выбирает номером,
    поэтому ни самочувствие, ни закрытые двери сюда не подмешиваются — они
    отдельно (`состояние`, `закрытое`). С корзиной к каждой оценке дописано,
    из чего она сложилась: сырая оценка раздела, пунктик, замысел, запрет,
    склонность и ворота нормальности (`actions.Корзина.слагаемые`).
    """
    top = sorted(варианты, key=lambda v: -v[1])[:лучших]
    слагаемые = getattr(корзина, "слагаемые", None) or {}
    строки = []
    for о, s in top:
        строка = f"{_имя(о):<30} {s:7.2f}"
        сл = слагаемые.get((о[0], id(о[1]))) if isinstance(о, tuple) and len(о) == 2 else None
        if сл is not None:
            строка += "   = " + _разложение(сл)
        строки.append(строка)
    return строки


def состояние(с):
    """С чем человек подошёл к выбору: `model.Самочувствие` одной строкой.

    Половина объяснения решения — вторая половина в оценках вариантов.
    Печатается только то, что не ноль: у сытого и целого строка короткая.
    """
    if с is None:
        return ""
    названо = (("отчаяние", с.отчаяние), ("невмоготу", с.невмоготу), ("зову", с.зову),
               ("голод", с.голод), ("жажда", с.жажда), ("холод", с.холод),
               ("усталость", с.усталость), ("тревога", с.тревога))
    чувства = ", ".join(f"{имя} {v:.2f}" for имя, v in названо if v > 0.005) or "ничего не жмёт"
    return f"самочувствие: {чувства}; в комнате {с.комната:.0f}°, еды {с.еды_дней:.1f} дн"


def закрытое(корзина, сколько=6):
    """Двери, которые сегодня были закрыты, и почему (`Корзина.отказы`).

    Объяснение решения — это не только выбранное и не только оценённое:
    половина вопросов «почему он этого не сделал» упирается в ворота,
    которых в списке вариантов не видно вовсе.
    """
    отказы = getattr(корзина, "отказы", None)
    if not отказы:
        return ""
    # сначала двери, закрытые обстоятельствами — часами, лимитом, разбитой
    # рукой, — и только потом самые частые и самые скучные: «ему этого
    # сейчас не хочется». Иначе первые шесть строк всегда одни и те же
    порядок = sorted(отказы, key=lambda о: о[2].startswith("характер"))
    видно = [f"{_имя((key, target))} ({почему})" for key, target, почему in порядок[:сколько]]
    ещё = len(отказы) - len(видно)
    return "закрыто: " + "; ".join(видно) + (f" и ещё {ещё}" if ещё > 0 else "")


class Софтмакс(Решающий):
    """NPC: обычно лучшее, иногда второе или третье. Страх делает выбор
    безрассуднее, днём — и недосып (actions.choose_and_do, night.решение)."""

    def день(self, h, npc, варианты, корзина=None):
        b = h.B
        temp = b["температура_выбора"] + (npc.panic / 100.0) * b["температура_выбора_паника"]
        temp += (1.0 - npc.rest / 100.0) * 0.4
        return h.rng.softmax_pick(варианты, temp)

    def ночь(self, h, npc, варианты, с=None):
        b = h.B
        temp = b["температура_выбора"] + (npc.panic / 100.0) * b["температура_выбора_паника"]
        return h.rng.softmax_pick(варианты, temp)

    def ответ(self, h, npc, с):
        if с.склонность is not None:
            return с.варианты[0][0] if h.rng.chance(с.склонность) else с.варианты[1][0]
        return с.по_правилу

    def выбор(self, h, npc, вопрос, варианты):
        # лучшее, без монеты: цель и тема площадки выбираются жёстко, и это
        # то самое `max`, что стояло здесь до шва (замысел.выбрать, meeting)
        return max(варианты, key=lambda v: v[1])[0] if варианты else None


class Скрипт(Решающий):
    """Для проверок и сценариев: без случайности. Всегда лучший вариант,
    монета — по склонности от половины, правило — как есть; отдельные ответы
    можно задать заранее по вопросу. Каждое решение остаётся в `разбор`."""

    разбирает = True

    def __init__(self, ответы=None):
        self.ответы = dict(ответы or {})       # вопрос -> ответ (для Ситуация)
        self.разбор = []                        # (день, кто, вопрос, строки объяснения, выбор)

    def _записать(self, h, npc, вопрос, варианты, выбор, корзина=None, чувства=None):
        """Строки разбора: самочувствие, оценённые варианты со слагаемыми,
        закрытые двери. Пустые части не пишутся."""
        чувства = чувства if чувства is not None else getattr(корзина, "с", None)
        строки = ([состояние(чувства)] if чувства is not None else [])
        строки += объяснить(варианты, корзина=корзина)
        хвост = закрытое(корзина)
        if хвост:
            строки.append(хвост)
        self.разбор.append((h.day, npc.id, вопрос, строки, выбор))

    def _лучший(self, варианты):
        return max(варианты, key=lambda v: v[1])[0] if варианты else None

    def день(self, h, npc, варианты, корзина=None):
        выбор = self._лучший(варианты)
        self._записать(h, npc, Вопрос.ДЕНЬ, варианты, _имя(выбор), корзина=корзина)
        return выбор

    def ночь(self, h, npc, варианты, с=None):
        выбор = self._лучший(варианты)
        self._записать(h, npc, Вопрос.НОЧЬ, варианты, _имя(выбор), чувства=с)
        return выбор

    def ответ(self, h, npc, с):
        if с.вопрос in self.ответы:
            выбор = self.ответы[с.вопрос]
        elif с.склонность is not None:
            выбор = с.варианты[0][0] if с.склонность >= 0.5 else с.варианты[1][0]
        else:
            выбор = с.по_правилу
        self._записать(h, npc, с.вопрос, с.варианты, выбор)
        return выбор

    def выбор(self, h, npc, вопрос, варианты):
        если = self.ответы.get(вопрос)
        выбор = если if если is not None else self._лучший(варианты)
        self._записать(h, npc, вопрос, варианты, _имя(выбор))
        return выбор


def _консоль(вопрос, строки):
    print(вопрос)
    for i, s in enumerate(строки):
        print(f"  {i}. {s}")
    while True:
        try:
            return int(input("> "))
        except ValueError:
            continue


class Человек(Решающий):
    """Игрок (GDD 13): ему показывают оценённые варианты и спрашивают.

    `спросить(вопрос, строки) -> номер` — по умолчанию консоль; в игре на её
    место встаёт интерфейс. Оценки ему видны те же, что и NPC: это и есть
    «правило одно для всех».
    """

    разбирает = True

    def __init__(self, спросить=None):
        self.спросить = спросить or _консоль

    def _выбрать(self, h, npc, вопрос, варианты, корзина=None, чувства=None):
        """Строки — ровно варианты, по ним человек и выбирает номером.
        Самочувствие и закрытые двери идут в текст вопроса: подмешать их
        в список значило бы сдвинуть нумерацию под рукой у игрока."""
        порядок = sorted(варианты, key=lambda v: -v[1])
        чувства = чувства if чувства is not None else getattr(корзина, "с", None)
        шапка = f"день {h.day}, {npc.short}: {вопрос}"
        for хвост in (состояние(чувства), закрытое(корзина)):
            if хвост:
                шапка += "\n  " + хвост
        i = self.спросить(шапка, объяснить(варианты, len(варианты), корзина))
        return порядок[max(0, min(int(i), len(порядок) - 1))][0]

    def день(self, h, npc, варианты, корзина=None):
        return self._выбрать(h, npc, Вопрос.ЧТО_ДЕЛАТЬ, варианты, корзина) if варианты else None

    def ночь(self, h, npc, варианты, с=None):
        return self._выбрать(h, npc, Вопрос.НОЧЬ, варианты, чувства=с) if варианты else None

    def ответ(self, h, npc, с):
        строки = [f"{о:<30} {вес:7.2f}" for о, вес in с.варианты]
        i = self.спросить(f"день {h.day}, {npc.short}: {с.вопрос}", строки)
        return с.варианты[max(0, min(int(i), len(с.варианты) - 1))][0]

    def выбор(self, h, npc, вопрос, варианты):
        return self._выбрать(h, npc, вопрос, варианты) if варианты else None


def монета(h, кто, вопрос, да, нет, шанс):
    """Ответ жильца там, где NPC бросал монету: `шанс` — его склонность к «да».

    Для NPC это ровно прежний `h.rng.chance(шанс)`; человеку показывают оба
    ответа с весами. Возвращает True, если ответ — `да`.
    """
    return кто.решающий.ответ(h, кто, Ситуация(
        вопрос, [(да, шанс), (нет, 1.0 - шанс)], склонность=шанс)) == да


def по_правилу(h, кто, вопрос, да, нет, мерка):
    """Ответ жильца там, где решало правило: `мерка` больше нуля — «да».

    NPC следует правилу без броска, человек волен решить иначе; мерка видна
    как вес «да». Возвращает True, если ответ — `да`.
    """
    return кто.решающий.ответ(h, кто, Ситуация(
        вопрос, [(да, мерка), (нет, 0.0)], по_правилу=да if мерка > 0 else нет)) == да


