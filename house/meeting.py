"""Собрание жильцов: то, что заводится в настоящем подъезде на второй день.

В доме были пары (союзы) и шайка на один вечер (налёт). Не было того, ради
чего в ГДД сказано «дом, который не сумел договориться, замерзает»: люди
собираются на площадке и решают что-то вместе.

Устройство:
  · позвать может тот, кому дом в среднем доверяет, и не чаще раза в несколько
    дней. Приходят те, кто не слишком ненавидит зовущего;
  · решается ОДНО дело — голосованием, где вес голоса это доверие к зовущему
    плюс собственная сила;
  · собрание может не собраться и может сорваться в ссору. И у сорванного есть
    цена: дом после него хуже, чем до, потому что все услышали, кто что думает.

Пять дел, и все пять опираются на то, что в игре уже есть: дежурство, общий
котёл (масштабный переезд), приговор, пустая квартира, подъездная дверь.
"""
from .util import clamp, vb
from . import social, conflict, household
from .model import Дежурство
from .decision import Вопрос, по_правилу

ТЕМЫ = ("дежурство", "котёл", "приговор", "квартира", "дверь_подъезда")


# ---------------------------------------------------------------- когда и о чём

def ждут_приговора(h):
    """Тот, про кого дом уже всё узнал и ещё не решил. Момент проходит:
    если за несколько дней не собрались, дальше живут как жили."""
    з = h.приговор_нужен
    if not з:
        return None
    if h.day - з.день > h.B["приговор_срок"]:
        h.приговор_нужен = None
        return None
    кого = h.живой(з.кто)
    if not кого:
        h.приговор_нужен = None
        return None
    return кого


def приговорённый(h, npc):
    """Тот, о ком в доме уже всё известно: людоед или пойманный дважды вор."""
    худший, вес = None, 0.0
    for p in h.others(npc):
        w = 0.0
        if p.раскрыт:
            w += 3.0
        w += max(0.0, p.поймали - 1) * 1.5
        w += p.под_подозрением * 1.5
        if ждут_приговора(h) is p:
            w += 3.0                   # дом уже узнал и ждёт решения
        w += npc.hate.get(p.id, 0.0) / 60.0
        if w > вес:
            худший, вес = p, w
    return (худший, вес) if вес >= h.B["собрание_приговор_порог"] else (None, 0.0)


def холоднее_всех(h, участники):
    """Кому из них хуже всего со своим теплом и у кого лучше всего печка."""
    греет, мёрзнут = None, []
    лучшее = -99.0
    for p in участники:
        своя = h.flat_temp(h.flats[p.apt], burning=True, powered=h.power_on)
        если_топит = h.flat_temp(h.flats[p.apt],
                                 burning=social.своя_топится(h, p), powered=h.power_on)
        if своя > лучшее and h.flats[p.apt].shelter.get("буржуйка"):
            греет, лучшее = p, своя
        мёрзнут.append((p, если_топит))
    return греет, мёрзнут


def темы(h, npc):
    """Что этому человеку есть смысл выносить на площадку. [(тема, острота)]."""
    b = h.B
    out = []
    живые = h.alive()

    # общее дежурство: после того, как в доме уже что-то случилось
    остро = (social.recent_incidents(h, 6) * 1.2 + npc.panic / 30.0
             + npc.обокрали * 1.2 - 1.0)
    out.append(("дежурство", остро))

    # общий котёл: топить одну квартиру вместо шести
    греет, мёрзнут = холоднее_всех(h, живые)
    if греет is not None:
        # смотрят не только на сегодня: метель с каждым днём злее, и это все
        # знают. Иначе дом складывается в один котёл на двадцатый день,
        # когда греть уже некого
        вперёд = b["температура_падение_в_день"] * b["собрание_котёл_вперёд"]
        холод = sum(max(0.0, b["комфортная_температура"] - t + вперёд)
                    for _p, t in мёрзнут)
        out.append(("котёл", холод * b["собрание_котёл_вес"] - 1.0))

    # приговор: выгнать вора или людоеда — решением людей, а не автоматом
    кого, вес = приговорённый(h, npc)
    if кого is not None:
        out.append(("приговор", вес * 1.6))

    # разделить пустую квартиру: кто занимает, кто разбирает
    if h.пустые():
        нужда = 0.0
        своя = h.flats[npc.apt]
        for f in h.пустые():
            нужда = max(нужда, h.ценность_жилья(f, npc) - h.ценность_жилья(своя, npc))
        # у скольких, по его сведениям, нет досок: чужой шкаф он не видит,
        # а оценку имеет (фаза 9б)
        нужда += sum(1.0 for p in живые if npc.believed(p.id, "материалы") < 2)
        out.append(("квартира", нужда * 0.9 - 0.5))

    # не пускать чужих: общее дело, и повод для него приходит с улицы
    порыв = 1.0 if h.day - h.календарь.укрепление_порыв <= 3 else 0.0
    if h.day - h.календарь.подъезд_заколочен > b["дверь_подъезда_дней"]:
        out.append(("дверь_подъезда", порыв * 4.5 + npc.panic / 25.0 - 1.2))
    return out


def жар_ссоры(h, люди):
    """Насколько эти люди готовы сорваться на крик вместо разговора.

    Одна формула на оценку и на исполнение — как у `что_разбирать`: тот, кто
    зовёт, прикидывает её по всему дому (кто выйдет, он заранее не знает),
    а само собрание считает по тем, кто вышел.

    Три слагаемых, и все три человек видит сам: открытая злость друг на друга,
    характер соседей и то, насколько у всех рассыпалось привычное. Злость
    берётся средняя по парам, а не самая громкая: один заклятый враг в доме
    есть всегда, и по нему собрание не судят.
    """
    люди = [p for p in люди if p.здесь()]
    пар = [(a, c) for a in люди for c in люди if a.id != c.id]
    if not пар:
        return 0.0
    злость = sum(a.hate.get(c.id, 0.0) for a, c in пар) / len(пар) / 100.0  # правда: видно: на лестнице кричат, и слышно это всем
    жар = злость * 2.0 + sum(p.t01("вспыльчивость") for p in люди) / len(люди) * 0.7
    return жар * (1.0 + (1.0 - sum(p.normalcy for p in люди) / len(люди)))  # правда: видно: по человеку видно, что он поплыл


def доверие_дома(h, npc):
    """Насколько, по его собственному счёту, дом его послушает.

    Не среднее чужое доверие — чужих мыслей не видно, — а среднее из того,
    что он знает сам о каждом: как отвечали на просьбы, что для него делали,
    свой ли, выходил ли на крик, не нажил ли он этому соседу счёта
    (`NPC.расположение_ко_мне`, фаза 1д). Человек, которого дом не слушает,
    обычно это чувствует; ошибается он в обе стороны, и это правильно —
    собрание может не собраться (план агента, фаза 9б).
    """
    другие = h.others(npc)
    if not другие:
        return 0.0
    return sum(npc.расположение_ко_мне(o.id) for o in другие) / len(другие)


def оценка(h, npc):
    """Насколько этому человеку сейчас хочется собрать дом. 0 — незачем."""
    b = h.B
    if len(h.alive()) < b["собрание_минимум"]:
        return 0.0
    if h.day - h.календарь.последнее_собрание < b["собрание_перерыв"]:
        return 0.0
    порог = b["собрание_доверие"]
    if ждут_приговора(h) is not None:
        # когда дом ждёт решения про своего, зовут не по любви к зовущему
        порог -= b["собрание_доверие_приговор"]
    if доверие_дома(h, npc) < порог:
        return 0.0
    острота = max((о for _т, о in темы(h, npc)), default=0.0)
    if острота <= 0:
        return 0.0
    # и то, чего у зовущего не было вовсе: понимание, что дом на взводе.
    # Замер: 70% собраний срывались в крик, а после срыва дом хуже, чем до, —
    # то есть позвать было ошибкой, которую человек не мог предвидеть, хотя
    # видел ровно то же, что видит `_сорвалось`: кто на кого злится, у кого
    # какой характер и насколько у всех рассыпалось привычное
    рискованно = жар_ссоры(h, h.alive()) * b["собрание_вес_напряжения"]
    # смелый и общительный зовут и на взводе: им кажется, что они справятся,
    # и половину времени они правы
    рискованно *= clamp(1.4 - npc.t01("храбрость") * 0.5
                        - npc.t01("общительность") * 0.3, 0.3, 1.4)
    # общительный зовёт легче, замкнутый — только когда припёрло. И собрать
    # дом — это самому выйти на площадку и заговорить первым: даром это
    # не делается, иначе площадка собирается через день
    return (острота + npc.t01("общительность") * 2.0 - npc.t01("жадность")
            - рискованно - b["собрание_решимость"])


# ---------------------------------------------------------------- голосование

def голос(h, кто, зовущий, тема, цель=None):
    """Как он голосует: больше нуля — за, меньше — против.

    Вес голоса — доверие к зовущему плюс собственная сила: на площадке слушают
    того, кому верят, и того, кого не хочется задевать.
    """
    b = h.B
    вес = 0.4 + кто.trust.get(зовущий.id, 3.0) / 5.0 + кто.power() * 0.3
    за = 0.0
    if тема == "дежурство":
        за = (кто.panic / 35.0 + social.recent_incidents(h, 6) * 0.7
              + кто.обокрали * 1.2
              - (1.0 - кто.rest / 100.0) * 2.0 - кто.t01("жадность") * 0.8)
        if кто.dependents:
            за -= 1.0                      # ему всё равно не выйти на площадку
    elif тема == "котёл":
        своя = h.flat_temp(h.flats[кто.apt], burning=social.своя_топится(h, кто),
                           powered=h.power_on)
        за = ((b["комфортная_температура"] - своя) * b["собрание_котёл_голос"]
              + кто.невмоготу() * 2.5 - кто.t01("жадность") * 2.5)
        if цель is not None and цель.id == кто.id:
            за += 1.0                      # к нему и придут: тепло на всех
            за -= кто.t01("жадность") * 1.5
    elif тема == "приговор":
        за = (кто.hate.get(цель.id, 0.0) / 18.0 - кто.trust.get(цель.id, 3.0) * 0.4
              - (3.0 if цель.id in кто.allies else 0.0)
              - кто.t01("лояльность") * 1.5)
        if цель.раскрыт:
            за += 2.5
        за += социальная_мерка(кто, "табу" if цель.раскрыт else "воровство")
    elif тема == "квартира":
        своя = h.flats[кто.apt]
        лучшая = max((h.ценность_жилья(f, кто) - h.ценность_жилья(своя, кто)
                      for f in h.пустые()), default=0.0)
        за = лучшая * 0.4 + (1.5 if кто.stock.get("материалы", 0) < 2 else 0.0) - 0.5
    elif тема == "дверь_подъезда":
        за = (кто.panic / 30.0 + social.recent_incidents(h, 6) * 0.5
              - (1.0 if кто.stock.get("материалы", 0) < 2 else 0.0))
    # за или против — отвечает сам голосующий (decision.py). Вес голоса
    # остаётся тем же — доверие к зовущему плюс своя сила, — а знак теперь
    # его ответ: NPC за, когда перевесило, игрок волен иначе, и на площадке
    # это видно всем (план агента, фаза 5ж)
    if по_правилу(h, кто, Вопрос.ГОЛОС_НА_СОБРАНИИ, "за", "против", за):
        return вес * abs(за)
    return -вес * abs(за)


def социальная_мерка(кто, tag):
    """Личная мерка поступка (GDD 12.1) — тем же способом, что в social.judge."""
    if кто.не_терпит(tag):
        return 1.5
    if кто.ценит(tag):
        return -1.0
    return 0.0


# ---------------------------------------------------------------- само собрание

def провести(h, зовущий):
    """Собрание от начала до конца. Возвращает строку исхода."""
    b = h.B
    h.календарь.последнее_собрание = h.day
    h.bump("собраний_позвали")

    # кто вышел на площадку
    пришли = [зовущий]
    отказались = []
    for p in h.others(зовущий):
        if p.health < 30:
            continue
        if p.hate.get(зовущий.id, 0.0) > b["собрание_ненависть_предел"]:
            отказались.append(p)
            continue
        охота = (p.trust.get(зовущий.id, 3.0) * 0.5 + p.t01("общительность") * 2.0
                 + social.recent_incidents(h, 6) * 0.5 - p.hate.get(зовущий.id, 0.0) / 25.0
                 - (1.0 - p.normalcy) * b["собрание_нежелание"])
        # выйти на площадку или остаться за дверью — решает сам сосед
        # (decision.py), правило прежнее (план агента, фаза 8)
        if по_правилу(h, p, Вопрос.ВЫЙТИ_НА_СОБРАНИЕ, "выйти", "остаться",
                      охота - b["собрание_порог_прихода"]):
            пришли.append(p)
        else:
            отказались.append(p)

    if len(пришли) < b["собрание_минимум"]:
        h.journal.line(f"{зовущий.short} {vb(зовущий.sex, 'стучал')} по квартирам — "
                       f"вышли не все, и разговора не вышло.", 2)
        h.bump("собраний_не_собралось")
        for p in пришли[1:]:
            social.adjust(p, зовущий.id, trust=-0.3)
        return "не собралось"

    h.bump("собраний")
    имена = ", ".join(p.short for p in пришли)
    h.событие("собрание", кто=зовущий, сколько=len(пришли))
    # о чём говорить, решает позвавший — из того, что ему самому больнее
    # …и решает он сам (decision.py): NPC берёт самое острое, как и брал,
    # а игрок в роли позвавшего выбирает, о чём говорить (план агента, фаза 8)
    тема = зовущий.решающий.выбор(h, зовущий, Вопрос.О_ЧЁМ_ГОВОРИТЬ, темы(h, зовущий))
    if тема is None:
        тема = "дежурство"
    цель = None
    if тема == "приговор":
        цель = приговорённый(h, зовущий)[0]
        if цель is None or цель not in h.alive():
            тема = "дежурство"
    if тема == "котёл":
        цель = холоднее_всех(h, пришли)[0]
        if цель is None:
            тема = "дежурство"
    h.journal.line(f"На площадке собрались: {имена}. {ЗАГОЛОВКИ[тема]}", 2)

    # --- сорваться в ссору можно раньше, чем договориться ---
    if h.rng.chance(clamp(b["собрание_ссора"] * жар_ссоры(h, пришли), 0.0, 0.75)):
        return _сорвалось(h, зовущий, пришли, тема)

    # --- голосование ---
    за = sum(max(0.0, голос(h, p, зовущий, тема, цель)) for p in пришли)
    против = sum(max(0.0, -голос(h, p, зовущий, тема, цель)) for p in пришли)
    if за <= против * b["собрание_нужен_перевес"]:
        h.journal.line(f"   Не договорились. Разошлись по квартирам.", 2)
        h.bump("собраний_без_решения")
        for p in пришли:
            p.mood = clamp(p.mood - 4)
        return "не договорились"

    h.bump("собраний_решили")
    h.bump("собрание_" + тема)
    for p in пришли:
        p.mood = clamp(p.mood + b["собрание_настроение"])
        for c in пришли:
            if c.id != p.id:
                social.adjust(p, c.id, trust=b["собрание_доверие_за_решение"], hate=-4)
    # общее дело — это и обычная жизнь тоже: дом, который договорился,
    # держит нормальность своих (GDD 12.4)
    for p in пришли:
        p.normalcy = clamp(p.normalcy + b["собрание_нормальность"], 0.0, 1.0)
    return _решение(h, зовущий, пришли, тема, цель)


ЗАГОЛОВКИ = {
    "дежурство": "Речь о том, чтобы кто-то ночью не спал.",
    "котёл": "Речь о том, чтобы топить одну квартиру на всех.",
    "приговор": "Речь о том, что с этим больше жить нельзя.",
    "квартира": "Речь о пустой квартире: кому занимать, кому разбирать.",
    "дверь_подъезда": "Речь о подъездной двери: заколотить и не пускать чужих.",
}


def _проверить():
    """Тема описана всюду или не описана нигде — падать при импорте.

    Тем пять, и каждая живёт в четырёх местах: `ТЕМЫ`, острота (`темы`),
    голос (`голос`) и само дело (`_решение`), плюс заголовок для журнала.
    Таблицу с заголовками легко забыть, и тогда собрание пройдёт молча —
    та же мысль, что у `catalog._проверить`: неполнота видна при импорте,
    а не через сорок прогонов (план агента, фаза 8).
    """
    нет = [т for т in ТЕМЫ if т not in ЗАГОЛОВКИ]
    лишние = [т for т in ЗАГОЛОВКИ if т not in ТЕМЫ]
    if нет or лишние:
        raise ValueError("темы собрания не сходятся: "
                         + (f"без заголовка — {', '.join(нет)}; " if нет else "")
                         + (f"заголовок без темы — {', '.join(лишние)}" if лишние else ""))


_проверить()


def _сорвалось(h, зовущий, пришли, тема):
    """Дом после сорванного собрания хуже, чем до него: все услышали, кто что думает."""
    b = h.B
    h.bump("собраний_сорвалось")
    крикун = max(пришли, key=lambda p: p.trait("вспыльчивость") + p.panic / 50.0)
    обиженный = max([p for p in пришли if p.id != крикун.id],
                    key=lambda p: крикун.hate.get(p.id, 0.0), default=None)
    h.journal.line(f"   Начали с дела, кончили криком. {крикун.short} "
                   f"{vb(крикун.sex, 'сказал')} вслух то, что думает"
                   + (f" про {обиженный.form('acc')}." if обиженный else "."), 2)
    for p in пришли:
        for c in пришли:
            if c.id == p.id:
                continue
            # услышанное вслух не забывается и сведения тоже никуда не денутся
            social.adjust(p, c.id, hate=b["собрание_ссора_ненависть"],
                          trust=-b["собрание_ссора_доверие"], aware=10)
    if обиженный is not None:
        social.adjust(обиженный, крикун.id, hate=b["собрание_ссора_ненависть"] * 1.5,
                      trust=-1.5)
    social.emit(h, зовущий, 4, "ссора", night=False)
    social.house_shock(h, panic=b["собрание_ссора_паника"], mood=-8)
    social.register_incident(h, "ссора", None)
    h.note(f"собрание сорвалось ({тема})")
    return "сорвалось"


def _решение(h, зовущий, пришли, тема, цель):
    """Применить принятое. Пять дел, каждое опирается на существующее."""
    b = h.B
    if тема == "дежурство":
        # расписание на неделю: по одному на ночь, по кругу
        очередь = [p.id for p in пришли if not p.dependents and p.health > 45]
        if not очередь:
            h.journal.line("   Договорились, но дежурить оказалось некому.", 2)
            return "решили впустую"
        h.дежурство = Дежурство(очередь=очередь, до=h.day + b["дежурство_дней"], начало=h.day)
        h.journal.line("   Расписали ночи на неделю: "
                       + ", ".join(h.get(i).short for i in очередь) + ".", 2)
        h.note("дом договорился о дежурстве")
        return "дежурство"

    if тема == "котёл":
        хозяин = цель
        сколько = 0
        for p in пришли:
            if p.id == хозяин.id or p.living_with == хозяин.id:
                continue
            if сколько >= b["собрание_котёл_гостей"]:
                break
            своя = h.flat_temp(h.flats[p.apt], burning=social.своя_топится(h, p),
                               powered=h.power_on)
            если_вместе = h.flat_temp(h.flats[хозяин.apt], burning=True, powered=h.power_on)
            if если_вместе <= своя + 2:
                continue
            if p.guests:
                for g in sorted(p.guests):
                    гость = h.get(g)
                    if гость:
                        гость.living_with = None
                        household.occupy_flat(h, гость)
                p.guests.clear()
            if p.living_with:
                прежний = h.get(p.living_with)
                if прежний:
                    прежний.guests.discard(p.id)
            p.living_with = хозяин.id
            p.переехал_день = h.day
            # в котёл человека привело решение дома, а не свой расчёт на шкаф
            p.переезд_умысел = 0.0
            хозяин.guests.add(p.id)
            дрова = p.stock.get("топливо", 0.0)
            хозяин.stock["топливо"] = хозяин.stock.get("топливо", 0.0) + дрова
            p.stock["топливо"] = 0.0
            social.adjust(p, хозяин.id, trust=1.5, hate=-10)
            social.adjust(хозяин, p.id, trust=1.0)
            сколько += 1
        if not сколько:
            h.journal.line("   Договорились, а сходиться не стали: у всех своё.", 2)
            return "решили впустую"
        h.bump("общий_котёл")
        h.journal.line(f"   Сложились и перебрались к {хозяин.form('dat')} в кв."
                       f"{хозяин.apt}: {сколько} чел. Топят одну печку на всех.", 2)
        h.note(f"общий котёл у {хозяин.form('gen')} ({сколько} чел.)")
        return "котёл"

    if тема == "приговор":
        conflict.exile(h, цель, by=зовущий, reason="решение дома")
        h.приговор_нужен = None
        h.bump("приговоров_дома")
        return "приговор"

    if тема == "квартира":
        пустые = h.пустые()
        if not пустые:
            return "решили впустую"
        # кому занимать: тому, кому своя хуже всех
        занимает = min(пришли, key=lambda p: h.ценность_жилья(h.flats[p.apt], p))
        flat = max(пустые, key=lambda f: h.ценность_жилья(f, занимает))
        разбирает = max([p for p in пришли if p.id != занимает.id],
                        key=lambda p: -p.stock.get("материалы", 0.0), default=None)
        if flat.apt != занимает.apt and h.чей(flat) is None:
            старая = h.flats[занимает.apt]
            занимает.apt, занимает.floor = flat.apt, flat.floor
            household.occupy_flat(h, занимает)
            h.bump("занято_квартир")
            h.journal.line(f"   Кв.{flat.apt} отдали {занимает.form('dat')}; "
                           f"{занимает.short} {vb(занимает.sex, 'перебрался')} туда "
                           f"из кв.{старая.apt}.", 2)
        if разбирает is not None:
            доска = b["разбор_материалов"]
            разбирает.stock["материалы"] = разбирает.stock.get("материалы", 0.0) + доска
            h.stats["наразобрано_материалы"] = (h.stats.get("наразобрано_материалы", 0.0)
                                                + доска)
            старая = h.flats[занимает.apt]
            h.journal.line(f"   Разбирать пустую разрешили {разбирает.form('dat')} "
                           f"(+{доска:g} материалов).", 2)
        h.note("дом разделил пустую квартиру")
        return "квартира"

    if тема == "дверь_подъезда":
        собрали = 0.0
        for p in пришли:
            взяли = min(1.0, p.stock.get("материалы", 0.0))
            p.stock["материалы"] = p.stock.get("материалы", 0.0) - взяли
            h.stats["израсходовано_материалы"] = (h.stats.get("израсходовано_материалы", 0.0)
                                                  + взяли)
            собрали += взяли
        if собрали < b["дверь_подъезда_материалы"]:
            h.journal.line("   Досок на дверь не набрали. Так и разошлись.", 2)
            return "решили впустую"
        h.календарь.подъезд_заколочен = h.day
        h.bump("подъезд_заколочен")
        for p in h.alive():
            social.add_panic(p, -b["дверь_подъезда_паника"])
            p.mood = clamp(p.mood + 4)
        h.journal.line("   Заколотили подъездную дверь наглухо, оставили щель "
                       "для своих. Теперь чужой в подъезд не войдёт.", 2)
        h.note("подъезд заколочен общими силами")
        return "дверь_подъезда"
    return "ничего"


