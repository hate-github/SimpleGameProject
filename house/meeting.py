def чья_ночь(h):
    """Кто по расписанию должен не спать этой ночью. None — расписания нет."""
    д = h.mods.get("дежурство")
    if not д or h.day > д["до"]:
        return None
    очередь = [i for i in д["очередь"]
               if (h.get(i) and h.get(i).alive and not h.get(i).exiled
                   and not h.get(i).dependents)]
    if not очередь:
        return None
    return h.get(очередь[(h.day - д["начало"]) % len(очередь)])


def проверить_дежурство(h):
    """Утром: вышел ли вчерашний дежурный. Нарушивший виноват перед всеми.

    Это и есть разница между обещанием одному человеку и обязательством
    перед домом: за сорванную ночь злятся все, а не один сосед.
    """
    b = h.B
    кто_id = h.mods.pop("дежурил_вчера", None)
    if not кто_id:
        return
    кто = h.get(кто_id)
    if not (кто and кто.alive and not кто.exiled):
        return
    if кто.stats.get("дежурил_ночь") == h.day - 1:
        for p in h.others(кто):
            social.adjust(p, кто.id, trust=b["дежурство_доверие"], hate=-3)
        h.bump("дежурств_по_расписанию")
        return
    for p in h.others(кто):
        social.adjust(p, кто.id, trust=-b["дежурство_доверие"] * 1.5,
                      hate=b["дежурство_ненависть"])
    h.bump("дежурство_нарушено")
    h.journal.line(f"{кто.short} {vb(кто.sex, 'проспал')} свою ночь. "
                   f"Об этом сказали все и сразу.", 2)
