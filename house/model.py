@dataclass
class Flat:
    """Квартира — вещь, а не приложение к жильцу (GDD 12, 15).

    Утепление, дверь, буржуйка и арматура принадлежат стенам. Пока они висели
    на человеке, «занять квартиру получше» было нечем выразить: переехавший
    уносил буржуйку на спине, а после смерти хозяина всё, что он построил
    за месяц, исчезало вместе с ним.

    Отсюда же берётся жильё как имущество: его можно занять, за него можно
    прийти с ломом, и его можно испортить, ломая дверь.
    """
    apt: int
    floor: int
    shelter: Dict[str, Any] = field(default_factory=dict)
    stock: Dict[str, float] = field(default_factory=dict)
    stripped: int = 0
    owner_died: Optional[str] = None
    body: Optional[Dict[str, Any]] = None   # тело хозяина, если он умер дома
    вложено: float = 0.0                    # сколько материалов в неё вбито
    костёр: int = -99                       # день, когда в ней жгли костёр
    тулуп: bool = False                     # зимняя одежда хозяина осталась здесь
    # оружие, оставшееся в этих стенах: топор в углу, ружьё над дверью.
    # До сих пор оружие было единственной вещью в модели, которая исчезала
    # вместе с человеком, — тулуп с мёртвого снимали, а винтовку нет, — и оттого
    # расклад сил в доме был заморожен на первом дне метели: за двадцать жизней
    # оружие на тридцатый день ни разу не отличалось от первого
    оружие: List[str] = field(default_factory=list)
    # ключи от кладовых, оставшиеся в этих стенах. Умерший не уносит ключ
    # от своего погреба с собой: он висит на гвозде в прихожей, и тот, кто
    # разбирает квартиру, его находит. Без этого запас в подвале выпадал бы
    # из игры навсегда вместе с хозяином
    ключи: set = field(default_factory=set)
    # чем её ломали: «окно», «стена», «пол», «потолок» -> сколько раз (GDD 16).
    # Пролом остаётся в стенах ровно так же, как утепление: в него выдувает,
    # через него лезут в следующий раз, и заделать его стоит материалов
    дыры: Dict[str, int] = field(default_factory=dict)
    # замок уже сломан. Пока этого не было, «пустая квартира» и «запертая
    # чужая квартира» были для кода одним и тем же: доски из-за целой двери
    # выносили так же буднично, как из открытой
    открыта: bool = False
    # 1.0 — вытяжка тянет, 0.0 — шахта забита льдом наглухо (GDD 15).
    # Люди не идиоты: печку в закрытой комнате не жгут, потому что есть
    # вентиляция. Но вентиляция в панельном доме обрастает льдом изнутри,
    # от собственного пара, и в какой-то день перестаёт тянуть. Об этом
    # никто не думает, потому что об этом никогда не приходилось думать
    вентиляция: float = 1.0

    @property
    def id(self) -> str:
        """Чтобы квартира годилась в цели действия наравне с человеком."""
        return f"кв{self.apt}"

    def door_strength(self) -> float:
        """Прочность двери для стадии осады «Дверь» (GDD 16).

        Стальные листы — уровень 3 убежища, они добавляются к засову.
        """
        return 1.0 + 1.6 * self.shelter.get("дверь", 0) + 1.2 * self.shelter.get("листы", 0)

    def дыр(self) -> int:
        """Сколько в квартире проломов — окно, стена, пол, потолок (GDD 16)."""
        return sum(self.дыры.values())

    def потери_тепла(self, b: Dict[str, Any]) -> float:
        """Сколько градусов уносит в проломы.

        Это и есть цена осады для победителя (GDD 16: «выламывая дверь,
        нападающий портит ровно то, ради чего пришёл»). Выбитое в метель окно
        забирает больше, чем даёт вынесенный шкаф, — и квартира, взятая
        с боем, греет хуже брошенной.
        """
        цены = b["дыра_градусов"]
        return sum(цены.get(вид, цены["стена"]) * n for вид, n in self.дыры.items())

    def защита(self, b: Optional[Dict[str, Any]] = None) -> float:
        """Насколько за этой дверью можно отсидеться (GDD 15, 16).

        Дыра в стене отменяет засов: за ней уже не отсидеться, сколько бы
        листов ни было прибито к двери.
        """
        v = self.door_strength() + 1.2 * self.shelter.get("стены", 0)
        if b is not None:
            v -= b["дыра_защита"] * self.дыр()
        return max(0.0, v)


