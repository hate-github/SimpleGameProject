# родительный падеж вида: «ключ от погреба», «замок с гаража»
ВИД_РОД = {"погреб": "погреба", "гараж": "гаража"}


@dataclass
class Кладовая:
    """Погреб в подвале или гараж за домом — имущество за порогом квартиры.

    До сих пор всё, что не в шкафу, было ничьим в равной мере: и мусорка
    во дворе, и чужой гараж, и чужая площадка. Поэтому «сходить за своим»
    и «залезть в чужое» были для кода одним действием с разной добычей,
    и порядок между ними задавала не совесть, а арифметика часов: в первый
    день метели, при тёплых батареях и работающем магазине, 44% всех вылазок
    уходило в чужие подъезды и гаражи.

    Кладовая — не новый источник еды, а перераспределение того же самого:
    столько же банок в мире, но не у всех, не в шкафу и за отдельным замком.
    Из этого само собой берётся то, чего дому не хватало:

      · законное место на первую неделю — тому, у кого оно есть;
      · асимметрия, которую видно: сосед ходит в подвал и возвращается
        с банками;
      · буран перестаёт быть общим — в погреб спускаются и в минус сорок;
      · цель, которая не человек: сорвать замок с погреба легче, чем прийти
        к двери, за которой хозяин с ружьём.

    Принадлежит она квартире, а не человеку, — по той же причине, по какой
    квартира стала вещью: занял чужой угол — получил и то, что к нему
    приписано.
    """
    id: str
    вид: str                      # «погреб» или «гараж»
    apt: int                      # за какой квартирой закреплена
    stock: Dict[str, float] = field(default_factory=dict)
    оружие: List[str] = field(default_factory=list)
    тулуп: bool = False
    вскрыта: bool = False         # замок сорван — теперь туда ходят все
    ходок: int = 0                # сколько раз оттуда уже носили

    @property
    def имя(self) -> str:
        """Как её называют в журнале: «погреб кв.6»."""
        return f"{self.вид} кв.{self.apt}"

    @property
    def имя_род(self) -> str:
        """Родительный падеж: «ключ от погреба кв.6». Формы лежат рядом
        с самим списком видов — как у имён и у оружия."""
        return f"{ВИД_РОД.get(self.вид, self.вид)} кв.{self.apt}"

    def пусто(self) -> bool:
        return вещи(self.stock) <= 0.01 and not self.оружие and not self.тулуп


@dataclass
class NPC:
    # --- паспорт ---
    id: str
    name: str
    short: str
    apt: int
    floor: int
    age: int
    role: str
    sex: str = "м"
    gen: str = ""      # родительный: «у Лиды»
    dat: str = ""      # дательный: «занёс Лиде»
    acc: str = ""      # винительный: «убил Лиду»
    ins: str = ""      # творительный: «обменял с Лидой»
    skills: List[str] = field(default_factory=list)
    # GDD 12.1: «Ценности: что любит и ненавидит». Метки поступков, на которые
    # этот человек реагирует сильнее прочих — см. social.judge и своя_мерка
    values: Dict[str, Any] = field(default_factory=dict)
    # именованные правила поведения: список строк, как умения (см. пунктик)
    пунктики: List[str] = field(default_factory=list)

    # --- черты 0..10 (GDD 12.1) ---
    traits: Dict[str, float] = field(default_factory=dict)

    # --- имущество ---
    stock: Dict[str, float] = field(default_factory=dict)
    weapon: str = "нет"
    одежда: int = 0            # 0 — обычная куртка, 1 — утеплённая, 2 — тулуп
    # насколько человек свыкся с ЭТИМ оружием: вид -> 0..1. Своё, с которым
    # он вошёл в метель, привычно; чужое, снятое с мёртвого, — нет, и стреляет
    # он из него хуже, пока не привыкнет. Растёт от того, что носишь, от ухода
    # за ним в быту и от того, что пришлось пустить в ход
    рука: Dict[str, float] = field(default_factory=dict)
    счёт: float = 0.0          # цифровые деньги: их нельзя украсть и нельзя спасти
    места: Dict[str, float] = field(default_factory=dict)   # что я думаю о местах
    dependents: int = 0
    dependent_name: str = ""
    dependent_acc: str = ""    # «взял Ваню»
    dependent_ins: str = ""    # «ушла с Ваней»
    # Ребёнок — состояние, а не множитель (GDD 12.6). У него своя сытость,
    # своё тепло и своё здоровье; он мёрзнет и болеет первым и может умереть.
    # `dependents` остаётся числом рук, которые он связывает, — на него смотрят
    # два десятка решений; `дети` — то, что с ним на самом деле происходит.
    дети: List[Dict[str, Any]] = field(default_factory=list)

    # --- состояние (GDD 6.1). 100 = хорошо, 0 = критично ---
    satiety: float = 85.0
    hydration: float = 85.0
    warmth: float = 80.0
    rest: float = 90.0
    mood: float = 65.0
    health: float = 100.0

    panic: float = 10.0
    horizon: float = 10.0     # на сколько дней вперёд человек считает нужным иметь запас
    # 1.0 — «жизнь ещё обычная», 0.0 — «всё, началось». Это состояние, а не
    # формула: оно помнит себя, падает от увиденного и отрастает в тихие дни.
    normalcy: float = 1.0
    # у каждого свой пол и своя скорость — два числа в npcs.json, а не код.
    # Лида не сломается до конца (0.35), Игорь съедет за неделю (0.05)
    нормальность_пол: float = 0.1
    нормальность_скорость: float = 1.0
    injuries: List[str] = field(default_factory=list)
    sick: Optional[str] = None

    # --- отношение к каждому другому жильцу (GDD 12.3) ---
    aware: Dict[str, float] = field(default_factory=dict)
    hate: Dict[str, float] = field(default_factory=dict)
    trust: Dict[str, float] = field(default_factory=dict)
    # четвёртая шкала: насколько человек опасается вот этого соседа (GDD 12.3).
    # К ненависти она не сводится — бояться можно того, на кого не злишься
    # вовсе: он просто вышел на площадку с ружьём или зарубил кого-то топором
    # у тебя на глазах
    страх: Dict[str, float] = field(default_factory=dict)
    # пятая шкала, и она не мнение, а история. Доверие, ненависть, страх
    # и осведомлённость — это то, что человек ДУМАЕТ о соседе, и потому все
    # четверо сходятся у всех к одному: сосед ведёт себя со всеми одинаково,
    # и дом оценивает его одинаково. Близость — то, что между этими двоими
    # на самом деле БЫЛО: сколько раз говорили, носили, возвращали, ночевали
    # под одной крышей. Она у каждого своя и делится на всех, поэтому у того,
    # к кому ходят пятеро, она размазана, а у того, кто ходит к одному, —
    # собрана. Из этого и рождаются пары, которых иначе в доме не заводится
    близость: Dict[str, float] = field(default_factory=dict)
    # Обида: вес неулаженного счёта к этому соседу, 0..100. Не мнение о нём
    # (доверие), не чувство к нему (ненависть и страх) и не история пары
    # (близость), а то, что между нами не улажено.
    #
    # Главное в ней — она не проходит от времени. Ненависть оседает каждый день
    # сама собой, и потому через неделю после осады от неё оставались крохи;
    # обида не оседает вовсе. Гасят её только поступками — и не до нуля:
    # у неё есть дно, ниже которого она не опускается никогда. Человек, к чьей
    # двери приходили с ломом, может снова с тобой разговаривать, но относиться
    # он будет иначе до конца
    счёты: Dict[str, float] = field(default_factory=dict)
    # А это те, кого он не простит ни за что: у него вынесли квартиру, его
    # выставили на мороз из собственных стен. Такое поступками не гасится,
    # и мстят за него любым способом — из засады, наговором, ночью
    не_прощу: set = field(default_factory=set)
    est: Dict[str, Dict[str, float]] = field(default_factory=dict)
    # каким сосед КАЖЕТСЯ: сыт ли, цел ли, не мёрзнет ли. Осведомлённость до
    # сих пор была про чужой шкаф — сколько у него банок, — а про самого
    # человека не знал никто: код читал `t.sick` и `t.health` прямо из правды
    # мира. В подъезде без света видно ровно обратное: шкаф чужой не виден,
    # а лицо видно каждый день. Отсюда и три разных ответа на одно и то же —
    # помочь, добить или подождать, пока квартира освободится
    вид: Dict[str, Dict[str, float]] = field(default_factory=dict)
    # чью смерть человек считает делом дней. Метка на паре, а не на человеке:
    # один сосед может списать со счетов того, кого другой не списал
    не_жилец: set = field(default_factory=set)

    # --- социальное ---
    group: Optional[str] = None
    living_with: Optional[str] = None   # к кому переехал
    guests: set = field(default_factory=set)
    allies: set = field(default_factory=set)
    favors: Dict[str, int] = field(default_factory=dict)
    дал: Dict[str, float] = field(default_factory=dict)   # кому и сколько я отдал
    ключи: set = field(default_factory=set)   # от каких квартир у него ключи
    # от каких кладовых. Отдельным полем, а не вместе с квартирными: там
    # номера квартир числами, и на них смотрит conflict в четырёх местах
    ключи_кладовых: set = field(default_factory=set)
    asking: Dict[str, Dict[str, float]] = field(default_factory=dict)  # память о просьбах
    # --- слово (GDD 14) ---
    врал: List[Dict[str, Any]] = field(default_factory=list)      # что я кому наговорил
    обещал: List[Dict[str, Any]] = field(default_factory=list)    # и что обещал
    не_верю: Dict[str, float] = field(default_factory=dict)        # кто мне уже врал
    # --- о чьей смерти он знает (GDD 12.3, 13) ---
    # Факт и знание о факте — разные вещи, и до сих пор их не различал никто:
    # человек умирал один в своей квартире на пятом этаже, и сосед с первого,
    # не сказавший с ним за месяц двух слов, немедленно пугался и терял
    # привычное. Смерть тихая, во сне, была невозможна не потому, что не бывает,
    # а потому, что её некому было бы не заметить
    знает_о_смерти: set = field(default_factory=set)

    # --- служебное ---
    alive: bool = True
    cause: Optional[str] = None
    died_day: Optional[int] = None
    exiled: bool = False
    # ушёл к пункту обогрева. Отдельный флаг рядом с `exiled`, а не вместо него:
    # для всего кода это одно и то же выбытие — человека в подъезде больше нет,
    # — и различать их нужно ровно в трёх местах: в причине, в отчёте и в счёте
    # выживших. Ушедший не выжил и не погиб: дом не знает, дошёл он или замёрз
    # на объездной, и не узнает никогда
    ушёл: bool = False
    # знает ли он, куда идти. Объявление на двери — вещь, а не знание:
    # его видели не все, и дальше оно расходится разговором (GDD 19, 21)
    знает_пункт: bool = False
    # цель, которая живёт дольше одного дня (house/замысел.py). Не приказ,
    # а перевес: подкрашивает оценки, спит, пока человеку не до неё, и бывает
    # брошена. Пока её не было, дольше дня жили только обещание соседу
    # и заказ мастеру, и дом читался как лента поступков, а не как история
    замысел: Optional[Dict[str, Any]] = None
    time_left: float = 16.0
    slept: float = 8.0
    tonight: str = "спать"
    away: bool = False
    burning: bool = False
    memory: List[str] = field(default_factory=list)
    stats: Dict[str, int] = field(default_factory=dict)
    # ссылка на дом: нужна, чтобы npc.shelter означал «стены, в которых он сейчас».
    # repr=False обязателен — иначе печать жильца утащит за собой весь дом
    _h: Any = field(default=None, repr=False, compare=False)

    # ---------- в каких он стенах ----------
    @property
    def shelter(self) -> Dict[str, Any]:
        """Убежище той квартиры, в которой человек сейчас живёт.

        Своей — или хозяйской, если он переехал. Свойство, а не поле: так все
        сорок мест в коде, которые спрашивают «а есть ли у него буржуйка»,
        сами собой стали спрашивать про правильные стены.
        """
        return self._h.where(self).shelter if self._h is not None else {}

    # ---------- производные величины ----------
    def trait(self, name: str) -> float:
        return float(self.traits.get(name, 5.0))

    def t01(self, name: str) -> float:
        """Черта, приведённая к 0..1."""
        return self.trait(name) / 10.0

    def вес_черт(self, key: str) -> float:
        """Сумма «черта × вес» для этого решения. Веса лежат в balance.json.

        Характер — это и есть эти веса: `лояльность × 4` в щедрости и
        `− лояльность × 4.5` в краже. Пока они были зашиты в код, крутить
        можно было темп и злость дома, но не человека.

        Выносятся только слагаемые вида «черта × число». Там, где черта входит
        множителем (жадность в отъёме, храбрость в бою), она осталась в коде:
        это не вес характера, а устройство самого действия.
        """
        if self._h is None:
            return 0.0
        таблица = self._h.B.get("веса_черт", {}).get(key, {})
        return sum(self.t01(черта) * вес for черта, вес in таблица.items())

    def пунктик(self, key: str) -> float:
        """Сдвиг от личных пунктиков (GDD 12.1: «ценности» как правила).

        Пунктик — это правило, а не сила склонности: «первым не ударит»
        нельзя выразить через храбрость, потому что человек может быть смелым
        и при этом не начинать. Список пунктиков человека лежит в npcs.json,
        сами пунктики — в balance.json; в коде один интерпретатор.
        """
        if not self.пунктики or self._h is None:
            return 0.0
        таблица = self._h.B.get("пунктики", {})
        return sum(float(таблица.get(п, {}).get(key, 0.0)) for п in self.пунктики)

    def eaters(self) -> float:
        """Сколько ртов кормит (GDD 12.1: дневное потребление)."""
        return 1.0 + 0.6 * self.dependents

    def days_of(self, res: str) -> float:
        """На сколько дней хватит ресурса при текущем потреблении."""
        per_day = {"еда": 0.85, "вода": 0.9, "топливо": 1.0}.get(res, 1.0) * self.eaters()
        return self.stock.get(res, 0.0) / max(0.2, per_day)

    def secure(self, res: str) -> float:
        """1.0 = запасов ровно на тот срок, который человек считает нужным.

        Ниже единицы — «мне не хватит», и это главный источник жадности:
        отказывают не злые, а те, кто посчитал.
        """
        return clamp(self.days_of(res) / max(3.0, self.horizon), 0.0, 2.5)

    def топит_сам(self) -> bool:
        """Отвечает ли этот человек за своё отопление.

        Переехавший к соседу — нет: его дрова ушли в общую печку, и топит
        её хозяин. Пока это не спрашивалось, у гостя топлива всегда было ноль,
        и он вечно числился в отчаянии, сидя в тепле и сытости.
        """
        return not self.living_with

    def мороз_предел(self, b: Dict[str, Any]) -> float:
        """Ниже какой температуры этот человек на улицу не выйдет.

        В обычной городской куртке при минус двадцати пяти на улице делать
        нечего — не «опасно», а нельзя: обморожение раньше, чем добыча.
        Каждый уровень одежды отодвигает предел (GDD 20).
        """
        return b["выход_предел"] - self.одежда * b["выход_за_одежду"]

    def могу_топить(self) -> float:
        """Насколько топливо для него вообще ресурс.

        Без буржуйки дрова не сжечь: обогреватель ест электричество, генератор
        надо сперва собрать. Считать их такой же нуждой, как еду, — значит
        заставить человека без печки паниковать из-за мёртвого груза
        и ходить просить дрова у соседей.
        """
        if not self.топит_сам():
            return 0.0
        if self.shelter.get("буржуйка"):
            return 1.0
        if self.stock.get("материалы", 0.0) >= 4.0:
            return 0.5      # есть из чего собрать — запасается не зря
        return 0.15

    def insecurity(self) -> float:
        """0..1 — «мне не хватит».

        Это не голод, а страх: человек считает запас против срока, который сам
        себе назначил, и не знает, когда кончится метель. Отсюда жадность
        и паника — но не преступление.
        """
        части = [1.0 - min(1.0, self.secure("еда")),
                 1.0 - min(1.0, self.secure("вода")),
                 (1.0 - min(1.0, self.secure("топливо"))) * 0.9 * self.могу_топить()]
        return clamp(max(части), 0.0, 1.0)

    def невмоготу(self) -> float:
        """0..1 — «мне сейчас физически плохо».

        Третье чувство, которого не хватало между «мне не хватит» и «я умираю».
        Это не про запасы вообще: холод в комнате, боль от травмы, жар. И лечится
        оно печкой, костром, просьбой, переездом и аптечкой — а не взломом.

        Пока этого не было, холод и ушиб входили слагаемыми в отчаяние, и человек
        с полным шкафом в нетопленой квартире читался как умирающий: у медианного
        ночного вора в первую неделю было еды на десять дней.
        """
        холод = 1.0 - norm(self.warmth, 12, 55)
        боль = 0.0
        if self.injuries:
            боль = min(1.0, 0.35 + 0.2 * (len(self.injuries) - 1))
        if self.sick:
            боль = max(боль, 0.45)
        слабость = 1.0 - norm(self.health, 20, 70)
        return clamp(max(холод, боль, слабость), 0.0, 1.0)

    def desperation(self) -> float:
        """0..1 — «я умираю». Считается по запасам: вот это толкает на кражу и налёт.

        Холод, боль и болезнь сюда не входят — они в `невмоготу`. Травма тоже:
        она уже отнимает силу в драке, скрытность и скорость, и этого довольно.
        """
        food = 1.0 - norm(min(self.days_of("еда"), 10), 0, 6)
        water = 1.0 - norm(min(self.days_of("вода"), 10), 0, 4)
        fuel = (1.0 - norm(min(self.days_of("топливо"), 10), 0, 6)) * self.могу_топить()
        # телесная часть — только настоящее истощение, ниже критического порога:
        # иначе человек «в отчаянии» каждый день перед ужином
        body = 1.0 - norm(min(self.satiety, self.hydration), 5, 30)
        return clamp(max(food * 0.95, water * 0.9, fuel * 0.75, body), 0.0, 1.0)

    def hurt(self, limb: str) -> bool:
        """Повреждена ли конечность (GDD 6.2: «нога снижает скорость, рука — ремонт»).

        Травмы хранятся строками вида «перелом ноги», «порез руки» — тип и место
        в одном тексте, чтобы журнал читался как журнал, а не как структура.
        """
        return any(limb in i for i in self.injuries)

    def speed(self, b: Dict[str, Any]) -> float:
        """Множитель ко времени действия (GDD 6.1).

        Голод, холод и недосып замедляют всё; повреждённая нога — переноску
        и вылазки. Меньше единицы человек не работает быстрее, только медленнее.
        """
        v = 1.0
        v += b["медленнее_за_голод"] * (1.0 - norm(self.satiety, 15, 70))
        v += b["медленнее_за_недосып"] * (1.0 - norm(self.rest, 15, 70))
        v += b["медленнее_за_холод"] * (1.0 - norm(self.warmth, 20, 65))
        if self.sick:
            v += b["медленнее_за_болезнь"]
        if self.hurt("ноги"):
            v += b["медленнее_за_ногу"]
        return v

    def success(self, b: Dict[str, Any]) -> float:
        """Шанс, что работа выйдет с первого раза (GDD 7: у действий есть провал)."""
        p = b["успех_база"]
        p -= b["успех_за_недосып"] * (1.0 - norm(self.rest, 15, 70))
        p -= b["успех_за_голод"] * (1.0 - norm(self.satiety, 15, 70))
        p -= b["успех_за_холод"] * (1.0 - norm(self.warmth, 20, 65))
        if self.hurt("руки"):
            p -= b["успех_за_руку"]
        return clamp(p, 0.15, 0.98)

    def привычка(self, оружие: Optional[str] = None) -> float:
        """Насколько это оружие у него в руке своё: 0 — впервые держит, 1 — своё."""
        w = оружие or self.weapon
        if w == "нет":
            return 1.0
        return clamp(self.рука.get(w, СВОЙСКОЕ.get(w, 0.0)), 0.0, 1.0)

    def power(self) -> float:
        """Боевая сила (GDD 17: оружие и численное превосходство решают почти всё)."""
        p = 0.6 + self.t01("храбрость") * 0.9
        # оружие весит столько, насколько человек с ним свыкся. Пока этого
        # не было, винтовка была одинаково смертельна в любых руках, и вся
        # разница между охотником и кассиром кончалась на том, у кого она
        # сегодня в руках
        p += (WEAPONS.get(self.weapon, 0.0) * 0.8
              * (ЧУЖОЕ_ОРУЖИЕ + (1.0 - ЧУЖОЕ_ОРУЖИЕ) * self.привычка()))
        if self.weapon in FIREARMS and self.stock.get("патроны", 0) <= 0:
            p -= WEAPONS.get(self.weapon, 0.0) * 0.55
        p *= 0.55 + 0.45 * (self.health / 100.0)
        p *= max(0.35, 1.0 - 0.18 * len(self.injuries))
        if self.hurt("руки"):
            p *= 0.8            # оружие в разбитой руке держится плохо (GDD 6.2)
        if self.age > 58:
            p *= 0.88
        if self.sick:
            p *= 0.8
        return max(0.15, p)

    def door_strength(self) -> float:
        """Прочность двери для стадии осады «Дверь» (GDD 16).

        Стальные листы — уровень 3 убежища, они добавляются к засову.
        """
        return 1.0 + 1.6 * self.shelter.get("дверь", 0) + 1.2 * self.shelter.get("листы", 0)

    def знаю_место(self, имя: str) -> float:
        """Что я думаю о месте, пока сам не сходил и никто не рассказал.

        По умолчанию — «наверное, там как всегда»: до метели в магазине была
        еда, и человек идёт туда, пока не узнает обратного. Это и есть
        нормальный порядок вылазок: сначала очевидное, мусорки — потом.
        """
        return self.места.get(имя, 1.0)

    def believed(self, other_id: str, res: str) -> float:
        """Сколько, по мнению этого NPC, у другого есть ресурса."""
        return self.est.get(other_id, {}).get(res, 2.0)

    def обида(self, other_id: str) -> float:
        """Насколько между нами не улажено: 0 — ничего не было, 100 — всё."""
        return self.счёты.get(other_id, 0.0)

    def враждует(self, other_id: str, порог: float) -> bool:
        """Настолько не улажено, что к этой двери он не подойдёт мирно."""
        return self.обида(other_id) >= порог or other_id in self.не_прощу

    def помнит_обиду(self, other_id: str) -> bool:
        """Улеглось, но не забылось: разговаривать станет, прежним не будет."""
        return self.обида(other_id) > 0.0 or other_id in self.не_прощу

    def свой(self, other_id: str) -> float:
        """Насколько этот сосед ему свой: 0 — просто жилец из подъезда, 1 — свой.

        Отдельно от доверия нарочно. Доверять можно и тому, с кем за месяц
        не сказал двух слов, — за репутацию; своим он от этого не станет.
        """
        return clamp(self.близость.get(other_id, 0.0) / 10.0, 0.0, 1.0)

    def предпочтение(self, other_id: str, средний: float) -> float:
        """Насколько этот сосед ближе ПРОЧИХ: −1 (чужее всех) … +1 (свой).

        Решает не близость сама по себе, а разница. Тот, кто одинаково близок
        со всеми пятерыми, не предпочитает никого — и это не сбой, а суть:
        внимания у человека столько же, сколько часов в дне, и «свой» значит
        «этот вместо тех». Пока в выборе стояла абсолютная близость, она
        оказалась положительной обратной связью без тормоза: все разговаривали
        со всеми, близость росла у всех ко всем, и дом стал ещё однороднее,
        чем был на одной репутации.
        """
        return clamp(self.близость.get(other_id, 0.0) / 10.0 - средний, -1.0, 1.0)

    def плох(self, other_id: str) -> float:
        """Насколько сосед, на его взгляд, плох: 0 — здоров, 1 — не жилец.

        По самому провалившемуся из трёх, а не по среднему: человек, который
        сыт и в тепле, но качается и держится за стену, — плох, и никакая
        сытость этого не отменяет.
        """
        v = self.вид.get(other_id)
        if not v:
            return 0.0
        худшее = min(v.get("сыт", 80.0), v.get("цел", 100.0), v.get("тепло", 80.0))
        return clamp(1.0 - худшее / 55.0, 0.0, 1.0)

    def видит_хворь(self, other_id: str) -> bool:
        """Видел ли он на соседе рану или слышал ли кашель."""
        return bool(self.вид.get(other_id, {}).get("хворь"))

    def давно_видел(self, other_id: str, день: int) -> int:
        """Сколько дней назад он в последний раз видел этого соседа вблизи."""
        v = self.вид.get(other_id)
        return 99 if not v else день - int(v.get("день", -99))

    def видимая_сила(self, other) -> float:
        """Каким сильным сосед КАЖЕТСЯ — по лицу, а не по правде мира.

        Оружие и рост видно, а сколько у него на самом деле здоровья — нет.
        Поэтому берётся его настоящая сила, но телесная поправка в ней
        заменяется на ту, которую видит смотрящий: раненый, который держится
        прямо, кажется целым, и к нему не идут; целый, но осунувшийся,
        приглашает.
        """
        сила = other.power()
        v = self.вид.get(other.id)
        if not v:
            return сила
        кажется = clamp(min(v.get("цел", 100.0), v.get("сыт", 80.0) + 25.0), 0.0, 100.0)
        # ту же поправку, что power даёт за здоровье, но по увиденному
        настоящая = 0.55 + 0.45 * (other.health / 100.0)
        видимая = 0.55 + 0.45 * (кажется / 100.0)
        return max(0.15, сила / max(0.2, настоящая) * видимая)

    def confidence(self, other_id: str) -> float:
        """0..1 — насколько он уверен в сведениях. Это и есть осведомлённость."""
        return self.aware.get(other_id, 0.0) / 100.0

    def боится(self, other_id: str) -> float:
        """0..1 — насколько он опасается этого человека (GDD 12.3, 17).

        Страх не толкает, а держит: к тому, кого боятся, не идут ни говорить,
        ни просить, ни красть, ни ломать его дверь, — но ему отдают, когда
        он приходит сам. Ровно то, что GDD 17 называет «угроза оружием часто
        ценнее выстрела»: до сих пор это работало один раз, в момент осады,
        и на следующий день о ружье никто не помнил.
        """
        return clamp(self.страх.get(other_id, 0.0) / 100.0, 0.0, 1.0)

    def самый_страшный(self):
        """(id, страх) того, кого он боится больше всех, или None."""
        if not self.страх:
            return None
        who = max(self.страх, key=lambda k: self.страх[k])
        return (who, self.страх[who]) if self.страх[who] > 0 else None

    def loot_value(self, other_id: str) -> float:
        """Насколько лакомой выглядит чужая квартира: сведения на уверенность."""
        e = self.est.get(other_id, {})
        raw = e.get("еда", 2.0) * 1.0 + e.get("топливо", 2.0) * 0.7 + e.get("лекарства", 0.0) * 1.1
        return raw * (0.35 + 0.65 * self.confidence(other_id))

    def form(self, case: str) -> str:
        """Имя в нужном падеже. Формы лежат в data/npcs.json, а не в коде."""
        return getattr(self, case, "") or self.short

    def слабейший_ребёнок(self):
        """Тот из детей, кому хуже всех. Ему и достаётся лекарство."""
        if not self.дети:
            return None
        return min(self.дети, key=lambda р: min(р["здоровье"], р["тепло"], р["сытость"]))

    def dependents_only_child(self, h=None) -> bool:
        """Заглушка-запрет: ребёнок никогда не может стать едой.

        Тел детей в мире не появляется вовсе (см. conflict._orphan),
        этот метод оставлен как явная точка, чтобы правило было видно в коде.
        """
        return False

    def ask_record(self, other_id: str) -> Dict[str, float]:
        """Что я помню про просьбы к этому человеку."""
        return self.asking.setdefault(other_id, {
            "дали": 0.0, "отказали": 0.0, "подряд": 0.0,
            "последняя": -99.0, "я_дал": -99.0,
        })

    def generosity(self, other_id: str) -> float:
        """0..1 — насколько, по моему опыту, у этого человека можно выпросить.

        Пока опыта нет, оценка около половины: попробовать стоит.
        """
        r = self.asking.get(other_id)
        if not r:
            return 0.5
        return (r["дали"] + 1.0) / (r["дали"] + r["отказали"] + 2.0)

    def label(self) -> str:
        return f"{self.short} (кв.{self.apt})"

    def bump(self, key: str, n: int = 1):
        self.stats[key] = self.stats.get(key, 0) + n


@dataclass
class House:
    """Дом и всё, что в нём происходит. Один подъезд пятиэтажки (GDD 25, «Ядро»)."""
    rng: Any = None
    B: Dict[str, Any] = field(default_factory=dict)
    day: int = 0
    people: Dict[str, NPC] = field(default_factory=dict)
    flats: Dict[int, Flat] = field(default_factory=dict)
    кладовые: Dict[str, Any] = field(default_factory=dict)

    # погода и инфраструктура
    outside: float = -8.0
    heating: bool = True
    power_on: bool = True
    water_on: bool = True
    network: float = 1.0
    банки: bool = True         # работает ли банк и приложение (GDD 18)
    магазины: bool = True      # открыт ли ещё магазин на Заречной
    # Снег — не погода, а количество (GDD 3). Погода бывает и кончается,
    # а снег копится: он и есть причина, по которой улица на двадцатый день
    # не та же самая, что на первый. Три вещи считаются от него и больше
    # ниоткуда: время дороги, шанс сломать ногу и шанс дойти до пункта обогрева.
    снег: float = 0.0          # метры на дворе

    # среда
    scav_richness: float = 1.0
    места: Dict[str, float] = field(default_factory=dict)   # что ещё осталось где
    incidents: int = 0
    first_incident_day: Optional[int] = None
    mods: Dict[str, Any] = field(default_factory=dict)   # временные модификаторы событий

    # вывод
    journal: Any = None
    stats: Dict[str, Any] = field(default_factory=dict)
    chronicle: List[str] = field(default_factory=list)

    def курс(self) -> float:
        """Чего стоят деньги сегодня: 1.0 — как до метели, 0.0 — бумага (GDD 18).

        Пока магазин работает, деньги настоящие: за них дают товар. Дальше они
        держатся только на том, что кто-то у соседа их ещё берёт, и к назначенному
        дню не стоят ничего.

        Документ говорил «после дня 0 деньги бесполезны» — разом. На прототипе
        честнее и интереснее вышло иначе: обесценивание за неделю превращает
        первые дни в гонку успеть потратить, а последнюю тысячу — в вещь,
        которую ещё возьмёт тот, у кого жизнь не рассыпалась.
        """
        b = self.B
        закрытие = b["день_закрытия_магазинов"]
        if self.day <= закрытие:
            return 1.0
        всего = max(1.0, float(b["день_нуля_денег"] - закрытие))
        return clamp(1.0 - (self.day - закрытие) / всего, 0.0, 1.0)

    def богатство_места(self, имя: str) -> float:
        """Сколько ещё осталось в этом месте. 1.0 — как было до метели."""
        return self.места.get(имя, 1.0)

    def alive(self) -> List[NPC]:
        return [p for p in self.people.values() if p.alive and not p.exiled]

    def others(self, npc: NPC) -> List[NPC]:
        return [p for p in self.alive() if p.id != npc.id]

    def get(self, npc_id: str) -> Optional[NPC]:
        return self.people.get(npc_id)

    # ---------- жильё ----------
    def хозяин_жилья(self, npc: NPC) -> NPC:
        """Чья это квартира: своя или того, к кому он переехал."""
        if npc.living_with:
            host = self.people.get(npc.living_with)
            if host and host.alive and not host.exiled:
                return host
        return npc

    def where(self, npc: NPC) -> Flat:
        """В какой квартире человек физически находится."""
        return self.flats[self.хозяин_жилья(npc).apt]

    def занятые(self) -> set:
        """Номера квартир, в которых кто-то живёт прямо сейчас."""
        return {p.apt for p in self.people.values()
                if p.alive and not p.exiled and not p.living_with}

    def пустые(self) -> List[Flat]:
        """Квартиры, в которых никто не живёт.

        Считается, а не хранится: пока список вёлся руками, одна и та же
        квартира успевала попасть в него дважды, а жилая — остаться в нём
        и уйти на доски из-под живого человека.
        """
        занято = self.занятые()
        return [f for f in sorted(self.flats.values(), key=lambda x: x.apt)
                if f.apt not in занято]

    def пустые_для(self, npc: NPC) -> List[Flat]:
        """Квартиры, которые вот ЭТОТ человек считает пустыми (GDD 12.2, 12.3).

        Правда мира — `пустые()`, и на ней стоит геометрия осады и расчёт
        тепла. А занимают и разбирают квартиру по представлению: пока человек
        не знает, что хозяин умер, чужая дверь для него остаётся чужой дверью,
        а не пустым углом с досками. Иначе выходило, что квартира становилась
        общим достоянием в тот же день, когда хозяин перестал дышать, — раньше,
        чем об этом успевал узнать хоть кто-то.
        """
        return [f for f in self.пустые()
                if not f.owner_died or f.owner_died in npc.знает_о_смерти]

    def соседние(self, flat: Flat, где: str) -> List[Flat]:
        """Откуда можно ломать эту квартиру (GDD 16, стадия стен).

        «стена» — соседняя дверь на той же площадке, «потолок» — квартира
        сверху, «пол» — снизу. Геометрия у дома настоящая: у Петра на пятом
        соседняя дверь — пустая кв.20, а к Лиде на третьем спускаются сверху
        через перекрытие. Поэтому одному человеку доступна стена, а другому нет,
        и это видно по номеру квартиры, а не по броску кубика.
        """
        этаж = flat.floor + {"стена": 0, "потолок": 1, "пол": -1}[где]
        return [f for f in sorted(self.flats.values(), key=lambda x: x.apt)
                if f.apt != flat.apt and f.floor == этаж]

    def floor_gap(self, a: NPC, b: NPC) -> int:
        return abs(a.floor - b.floor)

    # ---------- кладовые ----------
    def хозяин_кладовой(self, к) -> Optional[NPC]:
        """Живой человек, за квартирой которого эта кладовая числится."""
        f = self.flats.get(к.apt)
        return self.чей(f) if f is not None else None

    def есть_ключ(self, npc: NPC, к) -> bool:
        """Может ли человек войти сюда, не срывая замка (GDD 12: жильё как имущество).

        Ключом не делятся: он не вещь, которую можно отдать штукой, а доступ
        ко всему сразу и навсегда. Поэтому обычной щедрости здесь нет —
        доступ дают только два положения, в которых хозяйство и так общее:
        человек живёт в этих стенах или связан союзом. Всё остальное — путь
        ключа через имущество (смерть, отъём, осада) или лом.
        """
        if к.вскрыта:
            return True                # замок сорван — заходят все, кто знает
        if к.id in npc.ключи_кладовых:
            return True
        хозяин = self.хозяин_кладовой(к)
        if хозяин is None or хозяин.id == npc.id or к.id not in хозяин.ключи_кладовых:
            return False
        под_крышей = (npc.living_with == хозяин.id or хозяин.living_with == npc.id)
        return под_крышей or хозяин.id in npc.allies

    def мои_кладовые(self, npc: NPC) -> List[Any]:
        """Куда этот человек может сходить за своим — без лома и без вины."""
        return [к for к in sorted(self.кладовые.values(), key=lambda x: x.id)
                if self.есть_ключ(npc, к)]

    def знает_кладовую(self, npc: NPC, к) -> bool:
        """Знает ли он, что эта кладовка вообще есть.

        Подвал один на подъезд, гаражи стоят за домом рядами — что у соседа
        там своя дверь, в доме знают все. Что за ней лежит — не знает никто:
        это идёт обычным путём, через сведения (`est`) и увиденное.
        """
        return к.id in self.кладовые

    def powered(self, npc: NPC) -> bool:
        """Есть ли в этой квартире электричество (GDD 15, уровень 3).

        Либо в доме ещё не отключили свет, либо человек завёл свой генератор —
        ради этого он его и собирал, платя за это шумом на весь подъезд.
        """
        if self.power_on:
            return True
        return self.where(npc).shelter.get("питание") == self.day

    def остаток_отопления(self) -> float:
        """Сколько градусов от бывшего отопления дом ещё держит (GDD 15, 21).

        Панельная пятиэтажка — не палатка: остывшие батареи не выстуживают её
        за одну ночь, дом несколько дней отдаёт накопленное. Пока это было
        двоичным, второе утро отнимало у всех сразу пятнадцать градусов, уже
        на третий день посреди комнат жгли костры, — а событие двенадцатого дня
        («остывает уже не квартира, а дом целиком») не значило ничего, потому
        что базовый прогрев не менялся никогда.

        `остывание_дома_дней = 1` возвращает прежнее поведение: батареи остыли,
        и в тот же день от них не осталось ничего.
        """
        b = self.B
        if self.heating:
            return b["отопление_градусов"]
        прошло = self.day - b["день_отключения_отопления"] + 1
        доля = clamp(1.0 - прошло / max(1.0, b["остывание_дома_дней"]), 0.0, 1.0)
        return b["отопление_градусов"] * доля

    def flat_temp(self, flat: Flat, burning: bool = False, powered: bool = False) -> float:
        """Температура в конкретной квартире. Считает стены, а не жильца —
        поэтому этим же можно оценить чужую и пустую (GDD 15)."""
        b = self.B
        t = self.outside + b["дом_базовый_прогрев"] + self.остаток_отопления()
        t += flat.shelter.get("утепление", 0) * b["утепление_градус_за_уровень"]
        if burning and flat.shelter.get("буржуйка"):
            t += b["буржуйка_градусов"]
        if powered and flat.shelter.get("обогреватель"):
            t += b["обогреватель_градусов"]
        # костёр посреди комнаты: греет хуже печки, дымит и может спалить дом
        if flat.костёр == self.day:
            t += b["костёр_градусов"]
        # и то, что вынесли осадой: в пролом дует, и это уже не отопить
        t -= flat.потери_тепла(b)
        return t

    def чей(self, flat: Flat) -> Optional[NPC]:
        """Живой человек, который считает эту квартиру своей.

        Он может в ней сейчас и не жить — переехал к соседу, — но она его,
        и занять её значит оставить его без угла.
        """
        for p in self.people.values():
            if p.alive and not p.exiled and p.apt == flat.apt:
                return p
        return None

    def ценность_жилья(self, flat: Flat, для: NPC) -> float:
        """Чего эта квартира стоит вот этому человеку.

        Три слагаемых, и все три он может оценить снаружи: сколько она держит
        тепла (видно по окнам и по дыму), крепка ли дверь (видно с площадки)
        и что в ней лежит. Из разницы двух таких чисел растёт всё остальное —
        и мирный переезд, и налёт за квартирой.
        """
        b = self.B
        # свет в доме кончился — значит, обогреватель в расчёт больше не идёт
        тепло = self.flat_temp(flat, burning=True, powered=self.power_on)
        v = (тепло - b["комфортная_температура"]) * b["жильё_вес_тепла"]
        тревога = min(1.5, для.panic / 100.0 + 0.2 * (0 if self.first_incident_day is None else 1))
        v += flat.защита(b) * b["жильё_вес_защиты"] * (0.4 + тревога)
        v += вещи(flat.stock) * b["жильё_вес_запаса"] * (0.5 + для.t01("жадность"))
        # к квартире приписан погреб или гараж, и это часть её цены. Не запас
        # в нём — что там лежит, снаружи не видно, — а сам факт: своя дверь
        # в подвале, до которой можно дойти и в буран
        свои = sum(1 for к in self.кладовые.values()
                   if к.apt == flat.apt and not к.вскрыта and not к.пусто())
        v += свои * b["жильё_вес_кладовой"] * (0.5 + для.t01("жадность"))
        return v

    def room_temp(self, npc: NPC, burning: Optional[bool] = None) -> float:
        """Температура в квартире (GDD 15: утепление, буржуйка, обогреватель)."""
        b = self.B
        # гость греется хозяйской печкой — в этом весь смысл съезжаться
        хозяин = self.хозяин_жилья(npc)
        flat = self.flats[хозяин.apt]
        if burning is None:
            burning = хозяин.burning
        return self.flat_temp(flat, burning=burning, powered=self.powered(npc))

    def bump(self, key: str, n: int = 1):
        self.stats[key] = self.stats.get(key, 0) + n

    def note(self, text: str):
        """Строка в хронику дома — то, что попадёт в финальный отчёт."""
        self.chronicle.append(f"день {self.day:>2}: {text}")
