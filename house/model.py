def вещи(stock: Dict[str, float]) -> float:
    """Сколько на этом складе полезного. Деньги не в счёт.

    Нужно там, где склад оценивают как приз: пустая квартира на разбор, чужие
    стены при переезде. Пачка купюр в тумбочке мертвеца квартиру дороже
    не делает — за неё не согреешься, а к концу метели её и не возьмут.
    """
    return sum(v for k, v in stock.items() if k != "деньги")

