"""За порогом квартиры: подвал, гаражи, двор и магазин (GDD 18, 20).

Места вылазок и их выбор, кладовые и ходки в них, покупка и сама вылазка —
`_outing`: всё, что человек делает, выйдя из подъезда. Отсюда это читают
`world` (`МЕСТА` — район пустеет сам), проверка данных (`КЛАДОВЫЕ_ВИДЫ`)
и линейки (`actions.МЕСТА`, `actions._outing`), и пока всё это жило
в `actions.py`, каждый такой читатель тянул модуль действий по кругу (аудит §7).

`_outing` из `execute` зовётся по имени `actions._outing` нарочно: три линейки
его подменяют, и вызов обязан идти через модуль `actions`, а не отсюда.
"""
import collections

