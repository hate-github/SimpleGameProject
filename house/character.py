# -*- coding: utf-8 -*-
"""Характер как мерка поступка: ценности и нормальность (GDD 12.1, 12.4).

Три функции, которыми человек судит собственную руку. Их спрашивают не только
из `actions`: вербовка в налёт (`conflict.recruit`) и ночные решения
(`night.решение`) задают тот же вопрос, и пока они жили в `actions.py`,
каждый такой вопрос тянул модуль действий по кругу (аудит §7).
`NPC.вес_черт` и `NPC.пунктик` пока остаются в `model.py` (ADR-4).
"""
from .util import clamp
from .catalog import НОРМА, ТЕГИ


def мерка_поступка(npc, key, b):
    """(запрет, склонность) — как ценности человека держат его руку (GDD 12.1).

    Разведены нарочно, потому что действуют они по-разному. Запрет — вычет:
    «не терплю воровство» обязано уметь остановить, даже когда очень хочется.
    Склонность — доля: «ценю работу» делает человека охотнее в том, что он
    и так собрался делать, но не выдумывает ему дела на пустом месте.

    Пока обе входили слагаемыми, склонность работала как нужда: Виктор
    получал +1.5 к любой стройке при нулевом холоде и собирал генератор
    на третий день метели, при горячих розетках.
    """
    теги = ТЕГИ.get(key)
    if not теги:
        return 0.0, 0.0
    запрет = sum(b["своя_мерка"] for tag in теги if npc.не_терпит(tag))
    склонность = sum(b["своя_мерка_склонность"] for tag in теги if npc.ценит(tag))
    return запрет, склонность


def своя_мерка(npc, key, b):
    """Насколько этот поступок противен самому человеку (GDD 12.1).

    Та же метка, которой он судит соседа. «Не терплю воровство» — тормоз
    для своей руки, «ценю щедрость» — прибавка к помощи. Своё осуждается
    сильнее, чем одобряется чужое: запрет весит больше, чем склонность.

    Меток бывает несколько, и они складываются: поступок, в котором человек
    видит и своё, и чужое сразу, тянет его в обе стороны — Игорь одобряет силу
    в отъёме, Костя видит в том же отъёме насилие, и это разные люди.
    """
    теги = ТЕГИ.get(key)
    if not теги:
        return 0.0
    s = 0.0
    for tag in теги:
        if npc.не_терпит(tag):
            s -= b["своя_мерка"]
        if npc.ценит(tag):
            s += b["своя_мерка"] * 0.6
    return s


def norm_gate(npc, key, b):
    """Множитель к оценке: чем нормальнее ещё кажется жизнь, тем немыслимее поступок."""
    w = НОРМА.get(key, 0.0)
    if not w:
        return 1.0
    return clamp(b["нормальность_порог"] - npc.normalcy * w, 0.02, 1.0)
