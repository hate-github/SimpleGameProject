# -*- coding: utf-8 -*-
"""Мелкие утилиты: случайность с зерном, зажимы, взвешенный выбор.

Вся случайность в симуляции идёт через один объект Rng, созданный от зерна.
Это значит: одно и то же зерно = один и тот же прогон, до последнего слова.
(GDD 21: «Распределение случайных событий фиксируется зерном жизни».)
"""
import math
import re
import zlib


def clamp(v, lo=0.0, hi=100.0):
    """Зажать значение в границы."""
    return lo if v < lo else (hi if v > hi else v)


def lerp(a, b, t):
    return a + (b - a) * t


def norm(v, lo, hi):
    """Привести значение к 0..1 внутри диапазона."""
    if hi <= lo:
        return 0.0
    return clamp((v - lo) / (hi - lo), 0.0, 1.0)


class Rng:
    """Свой поток случайности (PCG-XSH-RR): 64 бита состояния, 32 бита выхода.

    Раньше здесь стоял `random.Random` — вихрь Мерсенна из стандартной
    библиотеки Python. Он не воспроизводится побитово ни в GDScript, ни в C#,
    а весь `data/эталон.json` держится ровно на том, что зерно даёт ту же
    жизнь до последнего слова. Значит, при переносе симуляции в движок
    единственная проверка, которая доказывает, что перенос ничего не сломал,
    терялась бы в ту самую минуту, когда она нужна.

    PCG32 — три строки арифметики по 64-битному состоянию; они пишутся
    на любом языке за десять минут и дают тот же поток чисел. Здесь всё
    считается на целых с явной маской, а не на float, — поэтому и результат
    не зависит ни от разрядности, ни от порядка байт.
    """

    _МНОЖИТЕЛЬ = 6364136223846793005
    _ПРИБАВКА = 1442695040888963407
    _МАСКА = (1 << 64) - 1

    def __init__(self, seed):
        self.seed = seed
        # засев как в эталонной реализации PCG: провернуть, добавить зерно,
        # провернуть ещё раз — чтобы соседние зёрна не давали похожие ленты
        self._состояние = 0
        self._бросок()
        self._состояние = (self._состояние + (int(seed) & self._МАСКА)) & self._МАСКА
        self._бросок()

    def _бросок(self):
        """Следующие 32 бита: сдвиг-исключающее-или, потом поворот."""
        было = self._состояние
        self._состояние = (было * self._МНОЖИТЕЛЬ + self._ПРИБАВКА) & self._МАСКА
        сдвинутое = (((было >> 18) ^ было) >> 27) & 0xFFFFFFFF
        поворот = было >> 59
        return ((сдвинутое >> поворот) | (сдвинутое << ((-поворот) & 31))) & 0xFFFFFFFF

    def random(self):
        """0.0 ≤ x < 1.0 — тридцать два бита точности, ровно один бросок."""
        return self._бросок() / 4294967296.0

    def branch(self, tag):
        """Отдельный поток случайности от того же зерна.

        GDD 21: «Распределение случайных событий фиксируется зерном жизни,
        чтобы игрок не чувствовал несправедливости при повторе». С одним общим
        потоком это не выполняется: стоит игроку сделать хоть что-то иначе —
        и весь календарь погоды съезжает, потому что решения жильцов тянут
        числа из той же ленты. Мир получает свою.

        crc32, а не hash(): встроенный хэш строк в Python зависит от
        PYTHONHASHSEED, и зерно перестало бы быть зерном.
        """
        return Rng(zlib.crc32(tag.encode("utf-8")) ^ (self.seed * 2654435761 & 0xFFFFFFFF))

    def chance(self, p):
        return self.random() < p

    def uni(self, a, b):
        return a + (b - a) * self.random()

    def rint(self, a, b):
        """a…b включительно. Остаток от деления, а не отбраковка: диапазоны
        здесь короткие (дни, штуки), перекос меньше миллионной доли, зато
        число бросков на вызов ровно одно — и лента переносится один в один."""
        if b <= a:
            return a
        return a + self._бросок() % (b - a + 1)

    def pick(self, seq):
        seq = list(seq)
        return seq[self._бросок() % len(seq)] if seq else None

    def shuffled(self, seq):
        """Тасовка Фишера — Йетса: тот же порядок в любом языке."""
        s = list(seq)
        for i in range(len(s) - 1, 0, -1):
            j = self._бросок() % (i + 1)
            s[i], s[j] = s[j], s[i]
        return s

    def weighted(self, pairs):
        """pairs: [(объект, вес)] -> объект. Веса не обязаны быть нормированы."""
        pairs = [(o, max(0.0, w)) for o, w in pairs]
        total = sum(w for _, w in pairs)
        if total <= 0:
            return pairs[0][0] if pairs else None
        x = self.random() * total
        acc = 0.0
        for o, w in pairs:
            acc += w
            if x <= acc:
                return o
        return pairs[-1][0]

    def softmax_pick(self, options, temp=1.0):
        """options: [(объект, оценка)] -> объект.

        Мягкий выбор: обычно берётся лучшее, но иногда — второе или третье.
        temp (температура) растёт от паники: чем страшнее, тем безрассуднее выбор.
        """
        if not options:
            return None
        temp = max(0.08, temp)
        best = max(s for _, s in options)
        weights = [(o, math.exp((s - best) / temp)) for o, s in options]
        return self.weighted(weights)


# Согласование глаголов по полу — чтобы в логе не было «Лида ходил».
_IRREGULAR = {"зашёл": "зашла", "ушёл": "ушла", "нашёл": "нашла", "слёг": "слегла",
              "умер": "умерла", "мёртв": "мертва", "уверен": "уверена",
              "вынес": "вынесла", "унёс": "унесла", "принёс": "принесла",
              "занёс": "занесла", "отнёс": "отнесла", "снёс": "снесла",
              "привёл": "привела", "полез": "полезла", "вышел": "вышла",
              "дошёл": "дошла", "замёрз": "замёрзла", "смог": "смогла",
              "обжёг": "обожгла", "пошёл": "пошла"}


_FORM = re.compile(r"\{([^{}|]*)\|([^{}|]*)\}")


def gform(text, sex):
    """Подставить род в строку из данных: «сидел{|а}» -> «сидел» / «сидела».

    Слева мужская форма, справа женская. Так реплики правятся в JSON
    без единой строчки кода.
    """
    return _FORM.sub(lambda m: m.group(2) if sex == "ж" else m.group(1), text)


def vb(sex, word):
    """vb('ж', 'ходил') -> 'ходила', vb('ж', 'проснулся') -> 'проснулась'."""
    if sex != "ж":
        return word
    if word in _IRREGULAR:
        return _IRREGULAR[word]
    if word.endswith("лся"):          # возвратные: -лся -> -лась
        return word[:-2] + "ась"
    return word + "а"
