# -*- coding: utf-8 -*-
"""Сохранение и загрузка дома: снимок, из которого прогон продолжается бит в бит.

`check.снимок` сворачивает состояние в строку для сравнения — из неё дом
не поднять: ссылки уже свёрнуты в id, а лента случайности не снимается вовсе,
потому что для сравнения она не нужна. Здесь наоборот: всё, что нужно, чтобы
продолжить с того же места, и ничего сверх.

Что не сохраняется и почему: ручки (`balance.json`) и реплики (`lines.json`) —
это данные, а не состояние, они читаются с диска; журнал — текст, он уже
напечатан; наблюдатели (`hooks`) — те, кто смотрит на дом, а не часть дома.
Лента случайности сохраняется вся: без неё продолженный прогон разойдётся
с непрерывным на первом же броске (и `check.проверить_сохранение` это ловит).

    из house import сохранение
    данные = сохранение.сохранить(h)          # словарь, годный для json.dump
    h = сохранение.продолжить(данные, до_дня=30)
"""
import dataclasses
import enum

from . import model
from .decision import РЕШАЮЩИЕ

ВЕРСИЯ = 1

# Кем восстанавливать записи и перечисления: имя класса — сам класс. Собирается
# из `model`, а не пишется списком, чтобы новая запись не забылась. Опечатка
# в имени невозможна — имена берутся у самих классов при сохранении.
СПРАВОЧНИК = {имя: значение for имя, значение in vars(model).items()
              if isinstance(значение, type)
              and (dataclasses.is_dataclass(значение) or issubclass(значение, enum.Enum))}

# Поля дома, которые не сохраняются: данные, вывод и наблюдатели. Люди,
# квартиры и кладовые идут своими разделами, потому что восстанавливаются
# в уже собранные объекты.
НЕ_СОСТОЯНИЕ = ("rng", "B", "journal", "people", "flats", "кладовые",
                "реплики_быт", "hooks")


def _в_json(x):
    """Значение любого поля дома — в то, что переживёт json.dump.

    Множества сортируются: их порядок в Python зависит от хэшей, и без
    сортировки один и тот же дом сохранялся бы каждый раз по-разному.
    """
    if isinstance(x, enum.Enum):
        return {"#вид": type(x).__name__, "знач": x.value}
    if isinstance(x, (set, frozenset)):
        return {"#мн": [_в_json(v) for v in sorted(x, key=repr)]}
    if isinstance(x, tuple):
        return {"#кортеж": [_в_json(v) for v in x]}
    if isinstance(x, dict):
        # словарь списком пар: ключом бывает и число, и кортеж, а json знает
        # только строки
        return {"#словарь": [[_в_json(k), _в_json(v)] for k, v in x.items()]}
    if isinstance(x, list):
        return [_в_json(v) for v in x]
    if dataclasses.is_dataclass(x) and not isinstance(x, type):
        return {"#запись": type(x).__name__,
                "поля": {f.name: _в_json(getattr(x, f.name))
                         for f in dataclasses.fields(x)}}
    if isinstance(x, (bool, int, float, str)) or x is None:
        return x
    raise TypeError(f"нечем сохранить {type(x).__name__}: {x!r}")


def _из_json(x):
    """Обратно. Записи и перечисления поднимаются по имени класса."""
    if isinstance(x, list):
        return [_из_json(v) for v in x]
    if not isinstance(x, dict):
        return x
    if "#вид" in x:
        return СПРАВОЧНИК[x["#вид"]](x["знач"])
    if "#мн" in x:
        return {_из_json(v) for v in x["#мн"]}
    if "#кортеж" in x:
        return tuple(_из_json(v) for v in x["#кортеж"])
    if "#словарь" in x:
        return {_из_json(k): _из_json(v) for k, v in x["#словарь"]}
    if "#запись" in x:
        клаcc = СПРАВОЧНИК[x["#запись"]]
        поля = {имя: _из_json(значение) for имя, значение in x["поля"].items()}
        try:
            return клаcc(**поля)
        except TypeError:
            # запись с полем не из конструктора: собираем поимённо.
            # `object.__setattr__` — потому что часть записей заморожена
            # (Событие, Самочувствие), и обычное присваивание им запрещено
            объект = клаcc.__new__(клаcc)
            for имя, значение in поля.items():
                object.__setattr__(объект, имя, значение)
            return объект
    raise ValueError(f"непонятная запись в снимке: {sorted(x)[:3]}")


def _поля(объект, кроме=()):
    return {k: _в_json(v) for k, v in vars(объект).items() if k not in кроме}


def имя_решающего(p):
    """Как зовут того, кто за него решает: softmax, скрипт или человек."""
    for имя, класс in РЕШАЮЩИЕ.items():
        if isinstance(p.решающий, класс):
            return имя
    return "softmax"


def сохранить(h):
    """Весь дом словарём, годным для `json.dump`."""
    return {
        "версия": ВЕРСИЯ,
        "день": h.day,
        # лента случайности: зерно и то, где она сейчас стоит. Без второго
        # продолженный прогон пойдёт другой жизнью с первого же броска
        "случайность": {"зерно": h.rng.seed, "состояние": h.rng._состояние},
        "люди": {pid: dict(_поля(p, кроме=("_h", "решающий")),
                           решающий=имя_решающего(p))
                 for pid, p in h.people.items()},
        "квартиры": {str(apt): _поля(f) for apt, f in h.flats.items()},
        "кладовые": {kid: _поля(k) for kid, k in h.кладовые.items()},
        "мир": _поля(h, кроме=НЕ_СОСТОЯНИЕ),
    }


def загрузить(данные, sim):
    """Заполнить уже собранный дом состоянием из снимка.

    Дом берётся собранным (`Simulation` строит его из тех же данных), а поля
    переписываются: людей, квартир и кладовых в прогоне не прибавляется
    и не убывает — умерший остаётся в `h.people`, — поэтому пересобирать
    объекты незачем, и ссылки на них ниоткуда не рвутся.
    """
    if данные.get("версия") != ВЕРСИЯ:
        raise ValueError(f"снимок версии {данные.get('версия')}, а читаем {ВЕРСИЯ}")
    h = sim.h
    h.rng.seed = данные["случайность"]["зерно"]
    h.rng._состояние = данные["случайность"]["состояние"]
    for pid, поля in данные["люди"].items():
        p = h.people[pid]
        решающий = поля.get("решающий", "softmax")
        for имя, значение in поля.items():
            if имя != "решающий":
                setattr(p, имя, _из_json(значение))
        p._h = h
        p.решающий = РЕШАЮЩИЕ[решающий]()
    for apt, поля in данные["квартиры"].items():
        f = h.flats[int(apt)]
        for имя, значение in поля.items():
            setattr(f, имя, _из_json(значение))
    for kid, поля in данные["кладовые"].items():
        к = h.кладовые[kid]
        for имя, значение in поля.items():
            setattr(к, имя, _из_json(значение))
    for имя, значение in данные["мир"].items():
        setattr(h, имя, _из_json(значение))
    return h


def продолжить(данные, до_дня, verbosity=0, secrets=False, stream=None,
               hooks=None, overrides=None):
    """Поднять дом из снимка и дожить до указанного дня.

    Календарь погоды не пересобирается: он в снимке, и он же — часть того,
    что дом уже прожил. `run()` для этого не годится — он начинает счёт дней
    заново; здесь дни доживаются по одному, как и в нём.
    """
    import io
    from .engine import Simulation
    sim = Simulation(seed=данные["случайность"]["зерно"], days=до_дня,
                     verbosity=verbosity, secrets=secrets,
                     stream=stream if stream is not None else io.StringIO(),
                     hooks=hooks, overrides=overrides)
    h = загрузить(данные, sim)
    while h.day < до_дня and h.alive():
        sim.one_day()
        h.hooks.зов("on_day", h)
    return h
