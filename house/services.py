"""Услуги: что можно заказать у того, у кого руки, почём и как сдаётся работа (GDD 18).

Одно понятие в одном месте: справочник услуг, цена, выбор заказа, решение
мастера взяться, сам уговор (исполнитель `заказать` в actions — тонкий,
он зовёт сюда) и утренняя сдача готовой работы с расчётом. Плата за лечение —
та же мысль «после дня 0 услуги дороже вещей», поэтому она здесь же.
"""
from .util import clamp, vb
from .model import spend, Заказ
from .character import norm_gate
from . import social


# Что можно заказать у того, у кого руки (GDD 18). До сих пор услуга была
# одна — буржуйка, — и всё остальное, что требует умения, мастер строил только
# себе. Поле «умения» здесь двойное: они же и определяют, кто мастер, и то,
# кому заказывать незачем — своими руками дешевле.
УСЛУГИ = {
    "буржуйка":      {"умения": ("слесарь", "электрик"), "мат": "буржуйка_материалы",
                      "поле": "буржуйка", "потолок": 1, "своё": True},
    "генератор":     {"умения": ("электрик",), "мат": "генератор_материалы",
                      "поле": "генератор", "потолок": 1, "своё": False},
    "листы":         {"умения": ("слесарь", "электрик"), "мат": "листы_материалы",
                      "поле": "листы", "потолок": 2, "своё": False},
    "звукоизоляция": {"умения": ("слесарь",), "мат": "звукоизоляция_материалы",
                      "поле": "звукоизоляция", "потолок": 1, "своё": False},
    "стены":         {"умения": ("слесарь",), "мат": "стены_материалы",
                      "поле": "стены", "потолок": 2, "своё": False},
}


# как называется работа, когда о ней договариваются: «сделает буржуйку»
УСЛУГА_ВИН = {"буржуйка": "сделает буржуйку", "генератор": "соберёт генератор",
              "листы": "прибьёт листы на дверь", "звукоизоляция": "заглушит генератор",
              "стены": "протянет арматуру"}

# и как она называется, когда сделана
УСЛУГА_РАБОТА = {"буржуйка": "буржуйку", "генератор": "генератор",
                 "листы": "стальные листы на дверь", "звукоизоляция": "звукоизоляцию",
                 "стены": "арматуру по стенам"}



# ---------------------------------------------------------------- цена и выбор

def кошелёк_за_работу(npc):
    """Чем человек может расплатиться за работу: едой и дровами (GDD 18)."""
    return npc.stock.get("еда", 0.0) + npc.stock.get("топливо", 0.0)


def цена_услуги(h, заказчик, мастер, что, b, материал_заказчика=True):
    """Чего стоит работа. GDD 18: «после дня 0 услуги дороже вещей».

    Цена растёт не от дефицита ресурса, а от беды покупателя — это единственное
    место в модели, где так. У кого вчера ломали дверь, тот заплатит за стальные
    листы вдвое, и это правильно: он платит не за железо, а за то, чтобы дожить
    до утра. Своим при этом дешевле, и жадный берёт больше.

    Доски мастера идут в цену по счёту, а не плоской надбавкой. Пока за них
    доплачивали полторы банки независимо от количества, семь материалов
    на генератор — три с половиной уровня утепления или три дня топки
    мебелью — стоили столько же, сколько три доски на дверь. Отсюда и брался
    генератор за шесть.
    """
    цена = b["услуга_цена"][что]
    цена *= 1.0 + мастер.t01("жадность") * b["услуга_за_жадность"]
    # беда покупателя: паника, происшествия в доме и дыры в его собственных стенах
    беда = clamp(заказчик.panic / 100.0 + 0.15 * h.where(заказчик).дыр(), 0.0, 1.5)
    цена *= 1.0 + беда * b["услуга_за_нужду"]
    цена *= max(0.5, 1.0 - мастер.trust.get(заказчик.id, 3.0) * b["услуга_за_доверие"])
    if not материал_заказчика:
        цена += b[УСЛУГИ[что]["мат"]] * b["услуга_за_доску"]
    return цена


def есть_движок(*кто):
    """Есть ли у кого-нибудь из этих людей то, из чего собирают генератор.

    Из семи досок двигатель не собирается. Генератор в этой игре — вещь,
    а не рецепт: движок один на весь дом, лежит он в погребе у слесаря,
    и всё, что делает электрик, — приводит его в чувство и подключает.

    То же правило, что у оружия: почти всё, что есть в доме, было в доме
    с первого дня. Отсюда же и повод — единственный движок лежит за замком,
    ключ от которого есть у одного человека.
    """
    return any(p is not None and p.stock.get("движок", 0.0) >= 1.0 for p in кто)


def нужен_генератор(h, npc, flat, cold_pressure):
    """Зачем этому человеку генератор — и зачем он ему сегодня (GDD 15, уровень 3).

    Одно место на оценку своей стройки и на оценку заказа: пока их было два,
    они успели разойтись (`cold_pressure * 3.5` в заказе против `cold * 4.0`
    в стройке), и человек хотел от соседа не то же самое, что делал бы сам.

    Считается из того, что генератор на самом деле даст: обогреватель без
    электричества — мёртвый ящик, снег на нём топят, когда топить больше
    не на чем, а свет в окне — это настроение. Пока здесь стояла константа
    «2.0», человек хотел генератор при нулевой нужде — и хотел сильнее,
    чем печку, потому что печка считается от холода, а холода в первые дни
    ещё нет. Замер: 37 из 49 уговоров о генераторе заключались в первые два
    дня, 94% — при работающих розетках, которые гаснут на десятый.
    """
    b = h.B
    s = b["генератор_за_свет"] + cold_pressure * b["генератор_за_холод"]
    if flat.shelter.get("обогреватель"):
        s += b["генератор_за_обогреватель"]
    if not h.water_on and not flat.shelter.get("буржуйка"):
        s += b["генератор_за_снег"]
    if h.power_on:
        # пока розетки живы, генератор — не нужда, а запасливость
        s *= b["генератор_загодя"]
    return s


def что_заказать(h, npc, мастер, b, cold_pressure, fear):
    """Что этот человек заказал бы вот у этого мастера и насколько сильно хочет.

    Одно место на оценку и на исполнение — тот же приём, что у `что_разбирать`:
    пока их было два, человек считал одно, а делал другое.

    Оценки нарочно те же, которыми он решал бы строить это сам (см. gather),
    и через ту же мерку нормальности: заказать арматуру по стенам — такой же
    крайний поступок, как протянуть её самому.
    """
    flat = h.where(npc)
    лучшее, оценка = None, 0.0
    for что, у in УСЛУГИ.items():
        # своими руками дешевле: заказывают то, чего сам не умеешь
        if any(u in npc.skills for u in у["умения"]):
            continue
        if not any(u in мастер.skills for u in у["умения"]):
            continue
        if (flat.shelter.get(у["поле"], 0) or 0) >= у["потолок"]:
            continue
        if что == "буржуйка" and not npc.топит_сам():
            continue          # гость греется хозяйской печкой, своя ему не нужна
        if что == "звукоизоляция" and not flat.shelter.get("генератор"):
            continue          # глушить нечего
        if что == "генератор" and not есть_движок(npc, мастер):
            continue          # из досок двигатель не собрать (см. `есть_движок`)
        s = {"буржуйка": cold_pressure * 7.0,
             "генератор": нужен_генератор(h, npc, flat, cold_pressure),
             "листы": fear * 4.0,
             "звукоизоляция": fear * 2.0,
             "стены": fear * 5.0 - 1.0 + flat.дыр() * b["заказ_за_пролом"],
             }[что]
        # ключ постройки для мерки нормальности: у генератора он свой
        ключ = "генератор_собрать" if что == "генератор" else что
        s *= norm_gate(npc, ключ, b)
        if s > оценка:
            лучшее, оценка = что, s
    return лучшее, оценка



# ---------------------------------------------------------------- уговор и сдача работы

def возьмётся_за_заказ(h, мастер, заказчик, цена, b):
    """Решает мастер: руки у него одни, и работа стоит того, что за неё дают.

    Больше нуля — берётся. Считается из того, что мастер знает о заказчике,
    и из того, что ему предлагают. Как `возьмёт_ребёнка` и `пойдёт_вдвоём`:
    решение ответной стороны названо и лежит рядом с исполнением, а не внутри.
    """
    готов = (мастер.t01("лояльность") * 4.0 + мастер.trust.get(заказчик.id, 3.0) * 0.6
             + мастер.t01("жадность") * 2.0          # это заработок
             + цена * b["услуга_соблазн"]            # и тем больший, чем выше цена
             - мастер.hate.get(заказчик.id, 0.0) / 15.0
             - (1.0 - min(1.0, мастер.secure("еда"))) * 2.0)
    return готов - b["печь_согласие"]


def заказать(h, npc, мастер, cold_pressure, fear):
    """Уговор с мастером: что, почём, чьи доски, и берётся ли он (GDD 18).

    Возвращает строку журнала; None — дело не состоялось («пока он шёл,
    надобность отпала»), и исполнитель в actions отвечает НЕ_СОСТОЯЛОСЬ.
    `cold_pressure` и `fear` считает вызывающий: это взгляд человека
    на свой дом (actions.холод_впереди, actions.тревога), не услуга.
    """
    b = h.B
    said = None
    что, _оц = что_заказать(h, npc, мастер, b, cold_pressure, fear)
    if что is None:
        return None                       # пока он шёл, надобность отпала
    мат = b[УСЛУГИ[что]["мат"]]
    if max(npc.stock.get("материалы", 0.0),
           мастер.stock.get("материалы", 0.0)) < мат:
        return None                       # досок нет ни у того, ни у другого
    # чьи доски — решается здесь, до цены, потому что от этого цена
    # и зависит. Пока доплату за материал прибавляли при сдаче
    # (готовые_заказы), объявленная цена не совпадала с взятой: замер
    # показывал 5.6 против 6.2. В доме, где нарушенное слово судится
    # как предательство, это должно быть одним числом
    чей = npc if npc.stock.get("материалы", 0.0) >= мат else мастер
    цена = цена_услуги(h, npc, мастер, что, b, чей is npc)
    # движок для генератора — та же история, что и доски, только вещь
    # в доме одна. Кто его принёс, тот и не платит за него
    чей_движок = None
    if что == "генератор":
        чей_движок = npc if есть_движок(npc) else мастер
        if not есть_движок(чей_движок):
            return None                   # пока он шёл, движок ушёл из рук
        if чей_движок is мастер:
            цена += b["услуга_за_движок"]
    if h.мастер_занят.get(мастер.id):
        said = (f"{мастер.short} и рад бы, да {vb(мастер.sex, 'занят')}: "
                f"работа уже делается не {npc.form('dat')}")
    elif возьмётся_за_заказ(h, мастер, npc, цена, b) > 0:
        срок = b["печь_срок"] - (1 if "слесарь" in мастер.skills else 0)
        # доски откладывают сразу и в сторону — в угол у мастера. Пока
        # материал ждали до срока, заказы срывались не по злому умыслу,
        # а потому что доски за эти дни уходили в печку или в чужие окна,
        # и мастер оказывался нарушившим слово, не сделав ничего
        склад = h.flats[мастер.apt]
        чей.stock["материалы"] = чей.stock.get("материалы", 0.0) - мат
        склад.stock["материалы"] = склад.stock.get("материалы", 0.0) + мат
        if чей_движок is not None:
            чей_движок.stock["движок"] = чей_движок.stock.get("движок", 0.0) - 1.0
            склад.stock["движок"] = склад.stock.get("движок", 0.0) + 1.0
        h.заказы[npc.id] = Заказ(мастер=мастер.id, что=что, готово=h.day + срок, цена=цена,
                                 материал_заказчика=чей is npc)
        h.мастер_занят[мастер.id] = npc.id
        social.adjust(npc, мастер.id, trust=0.8)
        # это и есть обещание «сделать»: с этого дня у мастера есть срок
        social.обещать(h, мастер, npc, "сделать", что, дней=срок + 1)
        said = (f"{npc.short} {vb(npc.sex, 'сговорился')} с {мастер.form('ins')}: "
                f"{УСЛУГА_ВИН[что]} за {срок} дн., цена {цена:.0f}")
    else:
        social.adjust(npc, мастер.id, trust=-0.4)
        said = (f"{мастер.short} не {vb(мастер.sex, 'взялся')} за работу "
                f"{npc.form('dat')} — руки нужны самому")
    return said


def готовые_заказы(h):
    """Утро: мастер отдаёт готовую работу и берёт своё (GDD 18)."""
    # готовые заказы: мастер отдаёт печь и берёт своё (GDD 18)
    for p in h.alive():
        заказ = h.заказы.get(p.id)
        if not заказ or h.day < заказ.готово:
            continue
        мастер = h.живой(заказ.мастер)
        if not мастер:
            h.заказы.pop(p.id, None)
            h.мастер_занят.pop(заказ.мастер, None)
            continue
        что = заказ.что
        у = УСЛУГИ[что]
        нужно = h.B[у["мат"]]
        # доски отложены в угол у мастера ещё при уговоре: их не сожгли
        # и не пустили в свои окна. Если угол растащили — работает из своего
        склад = h.flats[мастер.apt]
        отложено = min(нужно, склад.stock.get("материалы", 0.0))
        if отложено >= нужно:
            склад.stock["материалы"] -= нужно
            мастер.stock["материалы"] = мастер.stock.get("материалы", 0.0) + нужно
        elif мастер.stock.get("материалы", 0) < нужно:
            continue                       # нет материала — заказ ждёт
        if что == "генератор":
            # движок ждал в том же углу. Если угол растащили — работа
            # стоит: собирать больше не из чего
            if склад.stock.get("движок", 0.0) < 1.0:
                continue
            склад.stock["движок"] -= 1.0
            мастер.stock["движок"] = мастер.stock.get("движок", 0.0) + 1.0
        # цена — та, о которой договорились, включая доски мастера
        # (цена_услуги). Пока доплата за материал прибавлялась
        # здесь, при сдаче, объявленная цена не совпадала с взятой
        цена = заказ.цена
        плата = {}
        for res in ("еда", "топливо"):
            берём = min(цена - sum(плата.values()), p.stock.get(res, 0.0))
            if берём > 0:
                p.stock[res] -= берём
                мастер.stock[res] = мастер.stock.get(res, 0.0) + берём
                плата[res] = берём
        if sum(плата.values()) < цена * 0.5:
            continue                       # заказчику нечем платить — ждёт
        spend(h, мастер, "материалы", нужно)
        if что == "генератор":
            spend(h, мастер, "движок", 1.0)
        flat = h.where(p)
        if что == "буржуйка" or что == "генератор":
            flat.shelter[у["поле"]] = True
        else:
            flat.shelter[у["поле"]] = flat.shelter.get(у["поле"], 0) + 1
        flat.вложено += нужно
        h.заказы.pop(p.id, None)
        h.мастер_занят.pop(мастер.id, None)
        social.adjust(p, мастер.id, trust=2.0, hate=-10)
        social.adjust(мастер, p.id, trust=1.0)
        social.сдержал(h, мастер, p, "сделать", что)
        h.bump("работ_на_заказ")
        h.bump("заказ_" + что)
        h.journal.line(f"{мастер.short} {vb(мастер.sex, 'сделал')} {p.form('dat')} "
                       f"{УСЛУГА_РАБОТА[что]}. Расплатились: "
                       + ", ".join(f"{k} {round(v, 1):g}"
                                   for k, v in плата.items()) + ".", 2)
        h.note(f"{мастер.short}: работа {p.form('dat')} ({что})")



