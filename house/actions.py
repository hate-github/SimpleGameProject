def холод_впереди(h, npc, b):
    """Насколько человеку скоро станет холодно (GDD 15, 21).

    Смотрят не только на сегодня: метель с каждым днём злее, и это все знают.
    Этим же числом человек решает, заказывать ли печь у соседа: пока в комнате
    шестнадцать градусов, её не заказывают — заказывают, когда видно, куда
    идёт термометр.
    """
    room = h.room_temp(npc, burning=True)
    room_soon = room - b["температура_падение_в_день"] * 3
    return clamp((b["комфортная_температура"] + 4 - room_soon) / 14.0, 0.0, 1.6)


def тревога(h, npc):
    """Насколько человеку страшно вообще: своя паника плюс то, что в доме."""
    return npc.panic / 100.0 + social.recent_incidents(h) * 0.25


def кошелёк_за_работу(npc):
    """Чем человек может расплатиться за работу: едой и дровами (GDD 18)."""
    return npc.stock.get("еда", 0.0) + npc.stock.get("топливо", 0.0)


def цена_услуги(h, заказчик, мастер, что, b, материал_заказчика=True):
    """Чего стоит работа. GDD 18: «после дня 0 услуги дороже вещей».

    Цена растёт не от дефицита ресурса, а от беды покупателя — это единственное
    место в модели, где так. У кого вчера ломали дверь, тот заплатит за стальные
    листы вдвое, и это правильно: он платит не за железо, а за то, чтобы дожить
    до утра. Своим при этом дешевле, и жадный берёт больше.

    Доски мастера идут в цену по счёту, а не плоской надбавкой. Пока за них
    доплачивали полторы банки независимо от количества, семь материалов
    на генератор — три с половиной уровня утепления или три дня топки
    мебелью — стоили столько же, сколько три доски на дверь. Отсюда и брался
    генератор за шесть.
    """
    цена = b["услуга_цена"][что]
    цена *= 1.0 + мастер.t01("жадность") * b["услуга_за_жадность"]
    # беда покупателя: паника, происшествия в доме и дыры в его собственных стенах
    беда = clamp(заказчик.panic / 100.0 + 0.15 * h.where(заказчик).дыр(), 0.0, 1.5)
    цена *= 1.0 + беда * b["услуга_за_нужду"]
    цена *= max(0.5, 1.0 - мастер.trust.get(заказчик.id, 3.0) * b["услуга_за_доверие"])
    if not материал_заказчика:
        цена += b[УСЛУГИ[что]["мат"]] * b["услуга_за_доску"]
    return цена


def есть_движок(*кто):
    """Есть ли у кого-нибудь из этих людей то, из чего собирают генератор.

    Из семи досок двигатель не собирается. Генератор в этой игре — вещь,
    а не рецепт: движок один на весь дом, лежит он в погребе у слесаря,
    и всё, что делает электрик, — приводит его в чувство и подключает.

    То же правило, что у оружия: почти всё, что есть в доме, было в доме
    с первого дня. Отсюда же и повод — единственный движок лежит за замком,
    ключ от которого есть у одного человека.
    """
    return any(p is not None and p.stock.get("движок", 0.0) >= 1.0 for p in кто)


def нужен_генератор(h, npc, flat, cold_pressure):
    """Зачем этому человеку генератор — и зачем он ему сегодня (GDD 15, уровень 3).

    Одно место на оценку своей стройки и на оценку заказа: пока их было два,
    они успели разойтись (`cold_pressure * 3.5` в заказе против `cold * 4.0`
    в стройке), и человек хотел от соседа не то же самое, что делал бы сам.

    Считается из того, что генератор на самом деле даст: обогреватель без
    электричества — мёртвый ящик, снег на нём топят, когда топить больше
    не на чем, а свет в окне — это настроение. Пока здесь стояла константа
    «2.0», человек хотел генератор при нулевой нужде — и хотел сильнее,
    чем печку, потому что печка считается от холода, а холода в первые дни
    ещё нет. Замер: 37 из 49 уговоров о генераторе заключались в первые два
    дня, 94% — при работающих розетках, которые гаснут на десятый.
    """
    b = h.B
    s = b["генератор_за_свет"] + cold_pressure * b["генератор_за_холод"]
    if flat.shelter.get("обогреватель"):
        s += b["генератор_за_обогреватель"]
    if not h.water_on and not flat.shelter.get("буржуйка"):
        s += b["генератор_за_снег"]
    if h.power_on:
        # пока розетки живы, генератор — не нужда, а запасливость
        s *= b["генератор_загодя"]
    return s


def чем_поделиться(h, npc, t, b):
    """Чем именно помочь соседу. Возвращает (ресурс, излишек) или (None, 0).

    Пока помощь была только едой, замерзающему соседу по своей воле не приносили
    дров ни разу: он должен был прийти и попросить, а просьба стоит и доверия,
    и гордости. При том что холод — треть всех смертей в доме.

    Смотрит на то, чего соседу, по его мнению, не хватает, и на то, чего у самого
    больше. Излишек меряется против соседа, а не против собственного горизонта:
    против горизонта он к третьей неделе требовал тридцати двух дней запаса
    и не выполнялся никогда — щедрость выключалась арифметикой, а не решением.
    Одно место на оценку и на исполнение, как у `что_разбирать`.
    """
    лучший, лучший_излишек, вес = None, 0.0, 0.0
    for res in ("еда", "топливо", "вода", "лекарства"):
        if npc.stock.get(res, 0.0) < 1.0:
            continue
        if res == "лекарства":
            # аптечку несут тому, кто болен и у кого своей нет. Это ближе
            # к лечению, чем к щедрости, и меряется не днями запаса.
            # Условие строже, чем «нужен врач»: с ушибом к соседу за аптечкой
            # не идут и аптечку с ушибом не носят
            болен = t.sick or len(t.injuries) >= 2
            ребёнок = t.слабейший_ребёнок()
            болен = болен or (ребёнок is not None and ребёнок["болен"])
            if t.stock.get("лекарства", 0.0) >= 1.0 or not болен:
                continue
            if npc.stock.get("лекарства", 0.0) < b["помощь_лекарства_запас"]:
                continue
            излишек, s = 2.0, b["помощь_вес"]["лекарства"]
        else:
            # дрова тому, кому их нечем жечь, — не помощь, а мёртвый груз
            if res == "топливо" and not (t.топит_сам()
                                         and h.where(t).shelter.get("буржуйка")):
                continue
            его = social.believed_days(npc, t, res)
            мои = npc.days_of(res)
            if (его >= b["помощь_порог_дней"] or мои <= его + 1.0
                    or мои <= b["помощь_минимум_дней"]):
                continue
            излишек = мои / max(1.0, его + 1.0)
            # порог тем выше, чем дешевле помощь: кружку воды натопить можно,
            # а банка одна. Без этого 61% всей помощи в доме уходило водой —
            # не потому, что она нужнее, а потому, что её проще иметь в избытке
            if излишек <= b["порог_излишка"] / b["помощь_вес"][res]:
                continue
            # чем хуже соседу с этим ресурсом, тем нужнее именно он. И не всё
            # одинаково дорого отдавать: воду натопить можно, а банка одна.
            # Без этих весов вода вытесняла всё остальное — 61% всей помощи
            # в доме уходило кружкой воды, потому что её проще всего иметь в
            # избытке, а не потому, что она кому-то нужнее еды
            s = (излишек * (1.0 - min(1.0, его / max(0.5, b["помощь_порог_дней"])))
                 * b["помощь_вес"][res])
        if s > вес:
            лучший, лучший_излишек, вес = res, излишек, s
    return лучший, лучший_излишек


def плата_за_лечение(h, медик, больной, b):
    """Возьмёт ли медик за работу и сколько (GDD 18: услуги — тоже товар).

    ГДД 12.6 говорит про медика: «все хотят её расположения». До сих пор это
    не было подпёрто ничем — она тратила своё лекарство и получала одно доверие,
    и оттого выходила чистым раздатчиком: 249 лечений за сорок прогонов и ноль
    рычагов. Даром она лечит своих, детей и тех, кому платить нечем: отказать
    она всё равно не может — уже пришла и уже открыла аптечку. Но помнит, кто
    не заплатил, и в следующий раз идёт не сразу.
    """
    # решает не жадность, а собственный шкаф и то, на сколько жизнь уже не та.
    # Медик в этом доме один и по замыслу самый лояльный человек в нём: если
    # считать по жадности, платить ему не будут никогда. ГДД 18 говорит ровно
    # обратное — после дня 0 услуги дорожают, и дорожают они у всех
    просит = (медик.t01("жадность") * 2.0
              + (1.0 - min(1.0, медик.secure("еда"))) * b["лечение_плата_нужда"]
              + (1.0 - медик.normalcy) * b["лечение_плата_нормальность"]
              - медик.t01("лояльность") * 1.5
              - медик.trust.get(больной.id, 3.0) * 0.2)
    if больной.id in медик.allies:
        просит -= 2.0
    if больной.dependents:
        просит -= 1.5              # к матери с ребёнком с прейскурантом не ходят
    if просит < b["лечение_плата_порог"]:
        return None
    # цена растёт с бедой: за перевязку в первый день и за жар на двадцатый
    # платят разное, и это то же правило, что у работы мастера
    цена = b["лечение_цена"] * (1.0 + больной.невмоготу() * b["услуга_за_нужду"])
    плата = {}
    for res in ("еда", "топливо"):
        берём = min(цена - sum(плата.values()), больной.stock.get(res, 0.0))
        if берём > 0:
            больной.stock[res] -= берём
            медик.stock[res] = медик.stock.get(res, 0.0) + берём
            плата[res] = берём
    if sum(плата.values()) < цена * 0.5:
        # нечем. Лечить она всё равно будет, но запомнит
        медик.ask_record(больной.id)["не_заплатил"] = (
            медик.ask_record(больной.id).get("не_заплатил", 0.0) + 1.0)
        h.bump("лечений_в_долг")
        return плата or {}
    h.bump("лечений_за_плату")
    return плата


def что_заказать(h, npc, мастер, b, cold_pressure, fear):
    """Что этот человек заказал бы вот у этого мастера и насколько сильно хочет.

    Одно место на оценку и на исполнение — тот же приём, что у `что_разбирать`:
    пока их было два, человек считал одно, а делал другое.

    Оценки нарочно те же, которыми он решал бы строить это сам (см. gather),
    и через ту же мерку нормальности: заказать арматуру по стенам — такой же
    крайний поступок, как протянуть её самому.
    """
    flat = h.where(npc)
    лучшее, оценка = None, 0.0
    for что, у in УСЛУГИ.items():
        # своими руками дешевле: заказывают то, чего сам не умеешь
        if any(u in npc.skills for u in у["умения"]):
            continue
        if not any(u in мастер.skills for u in у["умения"]):
            continue
        if (flat.shelter.get(у["поле"], 0) or 0) >= у["потолок"]:
            continue
        if что == "буржуйка" and not npc.топит_сам():
            continue          # гость греется хозяйской печкой, своя ему не нужна
        if что == "звукоизоляция" and not flat.shelter.get("генератор"):
            continue          # глушить нечего
        if что == "генератор" and not есть_движок(npc, мастер):
            continue          # из досок двигатель не собрать (см. `есть_движок`)
        s = {"буржуйка": cold_pressure * 7.0,
             "генератор": нужен_генератор(h, npc, flat, cold_pressure),
             "листы": fear * 4.0,
             "звукоизоляция": fear * 2.0,
             "стены": fear * 5.0 - 1.0 + flat.дыр() * b["заказ_за_пролом"],
             }[что]
        # ключ постройки для мерки нормальности: у генератора он свой
        ключ = "генератор_собрать" if что == "генератор" else что
        s *= norm_gate(npc, ключ, b)
        if s > оценка:
            лучшее, оценка = что, s
    return лучшее, оценка


def что_разбирать(h, pool, b):
    """Какую из пустых квартир разберут. Одно место на оценку и на само дело.

    Пока их было два, человек считал одну квартиру, а шёл в другую: оценка
    смотрела на ту, где больше лежит, а руки — на ту, где меньше выломано.
    """
    return max(pool, key=lambda f: (вещи(f.stock)
                                    + (b["разбор_максимум"]
                                       - min(b["разбор_максимум"], f.stripped))
                                    + (b["разбор_взлом_решимость"] if f.открыта else 0.0)))


def нужен_врач(p):
    """Кому за этой дверью нужна аптечка — ему самому или ребёнку (GDD 12.6)."""
    if p.injuries or p.sick:
        return True
    р = p.слабейший_ребёнок()
    return bool(р and (р["болен"] or р["здоровье"] < 70))


def мерка_поступка(npc, key, b):
    """(запрет, склонность) — как ценности человека держат его руку (GDD 12.1).

    Разведены нарочно, потому что действуют они по-разному. Запрет — вычет:
    «не терплю воровство» обязано уметь остановить, даже когда очень хочется.
    Склонность — доля: «ценю работу» делает человека охотнее в том, что он
    и так собрался делать, но не выдумывает ему дела на пустом месте.

    Пока обе входили слагаемыми, склонность работала как нужда: Виктор
    получал +1.5 к любой стройке при нулевом холоде и собирал генератор
    на третий день метели, при горячих розетках.
    """
    теги = ТЕГИ.get(key)
    if not теги:
        return 0.0, 0.0
    v = npc.values or {}
    не_терпит = v.get("не_терпит") or ()
    ценит = v.get("ценит") or ()
    запрет = sum(b["своя_мерка"] for tag in теги if tag in не_терпит)
    склонность = sum(b["своя_мерка_склонность"] for tag in теги if tag in ценит)
    return запрет, склонность


def своя_мерка(npc, key, b):
    """Насколько этот поступок противен самому человеку (GDD 12.1).

    Та же метка, которой он судит соседа. «Не терплю воровство» — тормоз
    для своей руки, «ценю щедрость» — прибавка к помощи. Своё осуждается
    сильнее, чем одобряется чужое: запрет весит больше, чем склонность.

    Меток бывает несколько, и они складываются: поступок, в котором человек
    видит и своё, и чужое сразу, тянет его в обе стороны — Игорь одобряет силу
    в отъёме, Костя видит в том же отъёме насилие, и это разные люди.
    """
    теги = ТЕГИ.get(key)
    if not теги:
        return 0.0
    v = npc.values or {}
    не_терпит = v.get("не_терпит") or ()
    ценит = v.get("ценит") or ()
    s = 0.0
    for tag in теги:
        if tag in не_терпит:
            s -= b["своя_мерка"]
        if tag in ценит:
            s += b["своя_мерка"] * 0.6
    return s


# Обычная жизнь на виду: то, чем человек с крепким полом нормальности держит
# дом. Носит воду, лечит, латает окна, выносит тела — и у тех, кто ему верит,
# привычное рассыпается медленнее (GDD 12.4, social.держится).
ОБЫЧНОЕ = {"быт", "лечить", "поделиться", "вернуть", "обмен", "топить_снег",
           "вынести", "утепление", "одежда", "разговор"}


def norm_gate(npc, key, b):
    """Множитель к оценке: чем нормальнее ещё кажется жизнь, тем немыслимее поступок."""
    w = НОРМА.get(key, 0.0)
    if not w:
        return 1.0
    return clamp(b["нормальность_порог"] - npc.normalcy * w, 0.02, 1.0)


