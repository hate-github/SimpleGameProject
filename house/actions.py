def чужое_место(м):
    """Стоит ли на этом месте чужой замок."""
    return м.мерка == "вылазка_чужое"

# Виды кладовых (model.Кладовая). Погреб — в подвале этого же дома: туда
# спускаются и в буран, и с ребёнком на руках. Гараж — за домом, то есть улица
# со всем, что к ней прилагается: мороз, дорога и чужие глаза.
КЛАДОВЫЕ_ВИДЫ = ("погреб", "гараж")


def часы_кладовой(h, к):
    """Сколько времени займёт спуск в погреб или ходка в гараж."""
    v = h.B["кладовая_часы"][к.вид]
    return v * (погода_часы(h) if к.вид == "гараж" else 1.0)


def кладовая_доступна(h, npc, к, часов=None):
    """Можно ли этому человеку сегодня туда дойти.

    Погреб — внутри дома: ни мороз, ни буран, ни ребёнок на руках его не
    закрывают, и в этом вся его ценность. Гараж закрывается тем же, чем
    и вылазка, — и к третьей неделе хозяин до собственного топора не дойдёт.
    """
    if часов is not None and часы_кладовой(h, к) > часов + 0.001:
        return False
    if к.вид == "гараж":
        if npc.dependents and h.B["кладовая_часы"]["гараж"] > h.B["ребёнок_предел_часов"]:
            return False
        if h.outside <= npc.мороз_предел(h.B) or npc.warmth <= 32 or npc.health <= 45:
            return False
    return True


def не_свой(h, npc, к):
    """Чужая ли это кладовка для него — и есть ли там ещё что брать."""
    return not h.есть_ключ(npc, к) and not к.пусто()


def часы_вскрытия(h, к):
    """Сорвать замок и вынести. Дольше, чем зайти своим ключом."""
    return часы_кладовой(h, к) + h.B["кладовая_вскрытие_часы"]


def чужая_кладовая(h, npc, часов=None):
    """К какому чужому замку он пойдёт, если пойдёт.

    Выбирает по хозяину, а не по содержимому: что лежит за чужой дверью,
    человек не знает — он знает только, что дверь есть и чья она. Это те же
    сведения (`loot_value`), которыми меряется чужая квартира.
    """
    лучшая, оценка = None, None
    for к in sorted(h.кладовые.values(), key=lambda x: x.id):
        if not не_свой(h, npc, к) or not кладовая_доступна(h, npc, к, часов):
            continue
        if часов is not None and часы_вскрытия(h, к) > часов + 0.001:
            continue
        хозяин = h.хозяин_кладовой(к)
        s = npc.loot_value(хозяин.id) if хозяин is not None else 1.0
        if оценка is None or s > оценка:
            лучшая, оценка = к, s
    return лучшая


def вскрыть_кладовую(h, вор, к, вслух=True):
    """Сорвать замок с чужой кладовки. Возвращает то, что вынес.

    Одно место на два случая: на умышленный поход в чужой погреб и на гараж
    соседа, попавшийся под руку в общем ряду за домом. Разница между ними
    в решении, а не в последствиях: замок сорван, и с этого дня туда ходят
    все, кто знает. Это важнее самой добычи — сорванный замок превращает
    частный запас в общий пирог, и начинается гонка.
    """
    b = h.B
    впервые = not к.вскрыта
    к.вскрыта = True
    хозяин = h.хозяин_кладовой(к)
    got = {}
    for res, было in sorted(к.stock.items()):
        take = min(было, b["кладовая_за_раз"])
        if take > 0:
            к.stock[res] = было - take
            вор.stock[res] = вор.stock.get(res, 0.0) + take
            got[res] = take
    if к.тулуп and вор.одежда < b["одежда_максимум"]:
        к.тулуп = False
        вор.одежда = b["одежда_максимум"]
        got["тулуп"] = 1
    взял = conflict.подобрать_оружие(h, вор, к, вслух=вслух)
    if взял:
        got[взял] = 1
    к.ходок += 1
    if впервые:
        h.bump("вскрытых_кладовых")
        h.bump("вскрыто_" + ("умыслом" if вслух else "попутно"))
        if "первое_вскрытие" not in h.stats:
            h.stats["первое_вскрытие"] = h.day
    # у кладовки может быть живой хозяин — и тогда это не находка, а повод.
    # Узнаёт он не сразу: замок в подвале срывают тихо, и обнаруживается это
    # тогда же, когда пропажа из квартиры, — наутро (engine._morning)
    if хозяин is not None and хозяин.id != вор.id and к.id in хозяин.ключи_кладовых:
        h.mods.setdefault("вскрытые_кладовые", []).append((вор.id, к.id))
    social.переступил(h, вор, "вскрыть_кладовую")
    return got


def нужно_наверх(h, npc, res, b):
    """Понесёт ли человек это к себе в квартиру прямо сейчас.

    Из погреба не выгребают всё разом, и не от лени: наверху запас можно
    украсть, а внизу за замком он лежит. Человек поднимает то, чего ему
    не хватает по его же горизонту, — и оттого выглядит бедным в квартире,
    оставаясь богатым в подвале. Из этого же само собой берётся, почему он
    не делится: в его собственную арифметику подвал не входит.

    Мерка та же, что у покупки в магазине (`_что_купить`), но срок короче
    личного горизонта: наверх носят на несколько дней вперёд, а не на месяц.
    Это и есть причина, по которой погреб не выгребают за три захода, —
    и по которой он остаётся тем, за чем однажды придут с ломом.
    """
    срок = min(max(4.0, npc.horizon), b["кладовая_поднимает_дней"])
    if res in ("еда", "вода"):
        return npc.days_of(res) < срок
    if res == "топливо":
        return npc.топит_сам() and npc.days_of(res) < срок
    if res == "лекарства":
        return npc.stock.get(res, 0.0) < b["магазин_аптечка"]
    if res == "материалы":
        return npc.stock.get(res, 0.0) < b["магазин_материалы"]
    if res == "патроны":
        from .model import FIREARMS
        return npc.weapon in FIREARMS and npc.stock.get(res, 0.0) < b["магазин_патроны"]
    return npc.stock.get(res, 0.0) < 1.0


def _из_кладовой(h, npc, к, dur):
    """Поднять из своего погреба или привезти из своего гаража.

    Не добыча, а перекладывание: эти банки лежали в доме с первого дня.
    Поэтому здесь нет ни счётчика «принесено», ни броска на богатство района —
    сколько там есть, столько и есть, и оно кончается. Учёт сходится сам собой,
    потому что снимок мира (checks.snapshot) считает кладовые наравне
    с квартирами.
    """
    b = h.B
    got = {}
    for res, было in sorted(к.stock.items()):
        if not нужно_наверх(h, npc, res, b):
            continue
        take = min(было, b["кладовая_за_раз"])
        if take > 0:
            к.stock[res] = было - take
            npc.stock[res] = npc.stock.get(res, 0.0) + take
            got[res] = take
    # старый тулуп на гвозде и топор в углу — там же, где и всё остальное
    if к.тулуп and npc.одежда < b["одежда_максимум"]:
        к.тулуп = False
        npc.одежда = b["одежда_максимум"]
        got["тулуп"] = 1
        h.bump("тулупов_из_кладовой")
    взял = conflict.подобрать_оружие(h, npc, к)
    if взял:
        got[взял] = 1
    к.ходок += 1
    npc.rest = clamp(npc.rest - 2)
    h.bump("ходок_в_кладовую")
    h.bump("ходок_" + к.вид)

    если = ", ".join(f"{k} {v:g}" for k, v in got.items()) if got else "пусто"
    # «свой» — только если кладовка приписана к его собственным стенам.
    # Ключ, отнятый на лестнице, доступ даёт, а «своим» погреб не делает;
    # в сорванный замок и вовсе ходят все, кто знает
    свой = к.apt == npc.apt
    if свой:
        чей = "в свой погреб"
    elif к.id in npc.ключи_кладовых:
        чей = f"в погреб кв.{к.apt} — по чужому ключу"
    else:
        чей = f"в погреб кв.{к.apt} — тот, что вскрыли"
    if к.вид == "погреб":
        txt = f"{npc.short} {vb(npc.sex, 'спустился')} {чей}: {если}"
    else:
        # гараж — это улица со всем, что к ней прилагается
        тепло_одежды = 1.0 - b["одежда_холод"] * npc.одежда
        npc.warmth = clamp(npc.warmth - b["вылазка_холод_за_час"] * dur * тепло_одежды
                           * (1.0 + max(0.0, (-h.outside - 12)) * 0.03))
        npc.stats["день_вылазки"] = h.day       # его видели с пакетами
        if свой:
            куда = "в свой гараж"
        elif к.id in npc.ключи_кладовых:
            куда = f"в гараж кв.{к.apt} — по чужому ключу"
        else:
            куда = f"в гараж кв.{к.apt} — тот, что вскрыли"
        txt = f"{npc.short} {vb(npc.sex, 'сходил')} {куда}: {если}"
        if h.rng.chance(b["вылазка_шанс_встречи"] * world.улица_злая(h)):
            npc.panic = clamp(npc.panic + 8)
            txt += "; у гаражей кто-то ходил между рядами"
        social.emit(h, npc, 2, "возвращение", night=False)
    h.journal.line(txt + ".", 1)
    # сосед ходит в подвал и возвращается не с пустыми руками — это и есть
    # та асимметрия, которую должно быть видно с лестницы
    if got:
        for other in h.others(npc):
            if h.rng.chance(b["кладовая_заметность"]):
                social.adjust(other, npc.id, aware=10)
                social.note_signal(other, npc.id, "еда",
                                   other.believed(npc.id, "еда") + got.get("еда", 0), 0.5)


def сколько_поднимет(h, npc, к, b):
    """Сколько единиц человек вообще возьмёт отсюда сегодня.

    Не «сколько там лежит»: из погреба поднимают нужное, а не всё (см.
    `нужно_наверх`). Одно место на оценку и на само дело — тот же приём,
    что у `что_разбирать` и `что_заказать`: пока их было два, человек считал
    одно, а делал другое.
    """
    v = sum(min(было, b["кладовая_за_раз"]) for res, было in к.stock.items()
            if было > 0 and нужно_наверх(h, npc, res, b))
    if к.тулуп and npc.одежда < b["одежда_максимум"]:
        v += 2.0
    if к.оружие:
        from .model import WEAPONS
        if max(WEAPONS.get(w, 0.0) for w in к.оружие) > WEAPONS.get(npc.weapon, 0.0):
            v += 2.0
    return v


def выбрать_кладовую(h, npc, часов=None):
    """В какую из своих кладовок он пойдёт: где нужнее и куда ближе.

    Свою человек знает наизусть — это единственное место в мире, о котором
    у него точные сведения, а не вера в то, что «там как всегда».
    """
    лучшая, оценка = None, 0.0
    for к in h.мои_кладовые(npc):
        if к.пусто() or not кладовая_доступна(h, npc, к, часов):
            continue
        сколько = сколько_поднимет(h, npc, к, h.B)
        if сколько <= 0:
            continue                   # спускаться не за чем
        s = сколько / (1.0 + часы_кладовой(h, к))
        if s > оценка:
            лучшая, оценка = к, s
    return лучшая


def кошелёк(h, npc):
    """Чем этот человек может заплатить в магазине сегодня.

    Пока живы банки, карту принимают наравне с наличными; после — только то,
    что лежит дома. В этом вся разница между бумажными и цифровыми деньгами:
    бумажные можно украсть, но их нельзя отключить.
    """
    карта = npc.счёт if h.банки else 0.0
    return карта + npc.stock.get("деньги", 0.0)


def _что_купить(h, npc):
    """Чего человеку не хватает больше всего — то он и берёт с полки.

    Считается против его собственного горизонта, того же, которым он меряет
    «мне хватит» (GDD 12.3). Поэтому запасливый выносит из магазина втрое
    больше беспечного при тех же деньгах — и это видно уже на первом дне.
    """
    b = h.B
    горизонт = max(4.0, npc.horizon)
    хочу = [(npc.days_of(res) / горизонт, res) for res in ("еда", "вода")
            if npc.days_of(res) < горизонт]
    if npc.топит_сам() and npc.days_of("топливо") < горизонт:
        # без печки дрова покупают неохотно: жечь их пока не в чем
        штраф = 0.0 if npc.shelter.get("буржуйка") else 0.4
        хочу.append((npc.days_of("топливо") / горизонт + штраф, "топливо"))
    if npc.stock.get("лекарства", 0) < b["магазин_аптечка"]:
        хочу.append((0.6, "лекарства"))
    if npc.stock.get("материалы", 0) < b["магазин_материалы"]:
        хочу.append((0.7, "материалы"))
    # патроны берёт только тот, кому есть чем стрелять: охотник за день до того,
    # как охотиться станет не на кого
    from .model import FIREARMS
    if npc.weapon in FIREARMS and npc.stock.get("патроны", 0) < b["магазин_патроны"]:
        хочу.append((0.65, "патроны"))
    return min(хочу)[1] if хочу else None


def _купить(h, npc, м):
    """Магазин, пока он работает (GDD 18): не находят, а покупают.

    Возвращает (что взято, сколько ушло с карты, сколько наличными). Отдельная
    ветка нужна потому, что здесь всё решает не богатство места и не храбрость,
    а кошелёк: без денег в работающем магазине делать нечего — витрина есть,
    а взять нельзя.

    Цена растёт с каждым днём (соседи закупаются по мере паники), а сколько
    вообще осталось на полках — это то же `богатство_места`, что и у вылазки:
    магазин обирает весь квартал, а не эти шестеро.
    """
    b = h.B
    осталось = h.богатство_места(м.имя)
    наценка = 1.0 + b["магазин_наценка_в_день"] * (h.day - 1)
    цены = b["магазин_цена"]
    карта = npc.счёт if h.банки else 0.0
    наличные = npc.stock.get("деньги", 0.0)
    потолок = b["магазин_унос_макс"] * осталось
    got, картой, налом = {}, 0.0, 0.0

    def платим(цена):
        """Сначала карта, потом бумага: наличные берегут — их примут и завтра."""
        nonlocal карта, наличные, картой, налом
        цена = round(цена, 2)      # цены в копейках, чтобы деньги не крошились
        if цена > карта + наличные + 1e-9:
            return False
        с_карты = min(карта, цена)
        карта -= с_карты
        картой += с_карты
        наличные -= цена - с_карты
        налом += цена - с_карты
        return True

    while sum(v for k, v in got.items() if k != "тулуп") < потолок:
        res = _что_купить(h, npc)
        if res is None or not платим(цены[res] * наценка):
            break
        got[res] = got.get(res, 0) + 1
        npc.stock[res] = npc.stock.get(res, 0.0) + 1
        h.stats["принесено_" + res] = h.stats.get("принесено_" + res, 0) + 1
    # тулуп с вешалки у входа: дорого, но это ещё неделя открытой улицы (GDD 20).
    # В выметенном магазине его уже нет — как и всего остального
    if (потолок >= 1.0 and npc.одежда < b["одежда_максимум"]
            and платим(b["магазин_цена_тулупа"] * наценка)):
        npc.одежда = b["одежда_максимум"]
        got["тулуп"] = 1
        h.bump("тулупов_куплено")

    npc.счёт = max(0.0, npc.счёт - картой)
    if npc.счёт < 0.005:
        npc.счёт = 0.0             # остаток меньше пятака — это уже не деньги
    if налом > 0:
        spend(h, npc, "деньги", налом)
    h.stats["потрачено_картой"] = h.stats.get("потрачено_картой", 0.0) + картой
    h.stats["потрачено_налом"] = h.stats.get("потрачено_налом", 0.0) + налом
    return got, картой, налом


def что_подбросить(h, npc):
    """Что у него есть такого, что бросит тень на хозяина двери.

    Две вещи, и обе говорят сами за себя. Кусок тела — если в доме уже дошло
    до этого: объяснить, откуда он у твоего порога, нельзя ничем. Чужая вещь
    с меткой — если он сам её украл и теперь кладёт туда, где её найдут.
    """
    if npc.stock.get("мясо", 0) >= 1:
        return "мясо"
    # в доме, где вещи начали пропадать, чужая аптечка под дверью говорит
    # сама за себя: нашедший не станет спрашивать, откуда она у хозяина двери
    if npc.stock.get("лекарства", 0) >= 1 and h.stats.get("краж", 0):
        return "лекарства"
    return None


def погода_часы(h):
    """Множитель ко времени вылазки: в затишье дорога легче, по снегу — дольше.

    Снег входит сюда, а не в отдельный запрет: к третьей неделе та же ходка
    стоит вдвое дороже по времени, и дальние места закрываются сами собой —
    не потому, что туда нельзя, а потому, что до вечера не успеть (GDD 3, 20).
    """
    k = h.B["затишье_часы"] if h.mods.get("режим") == "затишье" else 1.0
    return k * (1.0 + h.снег * h.B["снег_дорога"])


def минимум_часов(h, м):
    """Сколько времени займёт самая короткая ходка в это место."""
    return h.B["вылазка_часы_мин"] * м.часы * погода_часы(h)


def место_доступно(h, npc, м, часов=None):
    """Можно ли этому человеку сегодня дойти до этого места.

    Два предела, и оба жёсткие, а не в вычет к оценке: ребёнок на руках
    (GDD 12.6 — с ним далеко не уходят) и остаток дня. Дорога стоит времени,
    и к вечеру дальние места закрываются сами собой.
    """
    if npc.dependents and м.часы > h.B["ребёнок_предел_часов"]:
        return False
    if часов is not None and минимум_часов(h, м) > часов + 0.001:
        return False
    return True


def оценка_места(h, npc, м):
    """Чего это место стоит вот этому человеку — по его сведениям.

    Отдельно от выбора, потому что спрашивают дважды: сначала «стоит ли вообще
    выходить», потом «куда». Пока это считалось только внутри выбора, оценка
    выхода не знала о месте ничего — и человек решал выйти, а шёл туда, куда
    его загнал остаток дня.
    """
    b = h.B
    богатство = м.богатство
    if м.магазин and h.магазины:
        # пока в магазине продают, а не берут, богатство полки решает
        # меньше, чем кошелёк: с пустыми руками там делать нечего
        богатство *= clamp(кошелёк(h, npc) / b["магазин_кошелёк_норма"], 0.0, 1.0)
    s = (богатство * npc.знаю_место(м.имя)
         * (1.0 + npc.desperation() * b["вылазка_дальше_за_нужду"]))
    # человек боится обеих опасностей сразу: и дороги, и тех, кого на ней встретит
    s -= (м.дорога + м.угроза) * (b["вылазка_осторожность"] * (1.4 - npc.t01("храбрость")))
    # а мороз пугает только длинной дорогой: на лестнице соседнего подъезда
    # минус тридцать ничем не хуже минус десяти
    s -= м.дорога * max(0.0, (-h.outside - 18)) * 0.15
    s -= м.часы * 0.25 if npc.dependents else 0.0
    # рыться в мусорках, пока за углом магазин, — поступок из другой жизни
    s -= м.дичь * npc.normalcy * b["вылазка_дичь_вес"]
    return s


def выбрать_место(h, npc, часов=None):
    """Куда пойти: смелость и нужда толкают дальше, мороз и раны — ближе.

    И главное — туда, где, по мнению этого человека, ещё что-то есть. Пока он
    не сходил сам и никто не рассказал, он считает, что в магазине всё как до
    метели. Отсюда естественный порядок: первые дни дом ходит в магазин, а
    гаражи и мусорки открывает потом, узнав, что магазин вынесли.

    Возвращает `None`, если идти сегодня некуда, — и тогда варианта «вылазка»
    просто не будет. Раньше здесь стоял молчаливый запасной выход
    (`лучшее = МЕСТА[0]`): когда пределы отсекали всё, человек всё равно шёл
    во двор — вопреки собственным же ограничениям.
    """
    лучшее, оценка = None, None
    for м in МЕСТА:
        if not место_доступно(h, npc, м, часов):
            continue
        s = оценка_места(h, npc, м)
        if оценка is None or s > оценка:
            лучшее, оценка = м, s
    return лучшее


def _outing(h, npc, dur, м):
    """Вылазка (GDD 20): единственный источник новых ресурсов.

    Место и время дороги решены до выхода, вместе с самим решением выйти
    (см. gather и execute), и приходят сюда готовыми.
    """
    from .world import outing_danger, улица_злая, дорожные_условия
    b = h.B
    npc.away = True
    место, богатство_к = м.имя, м.богатство
    # люди — одно, лёд и темнота — другое, и считаются они врозь
    danger = outing_danger(h) * м.угроза
    осталось = h.богатство_места(место)

    # чужой замок — свой поступок, и человек засчитывает его себе сам.
    # Дом при этом ничего не видит: слышно только «вернулся с пакетами»,
    # а куда он ходил, не видел никто. Поэтому чужого примера здесь нет —
    # нормальность падает у него одного
    if чужое_место(м):
        social.переступил(h, npc, "вылазка_чужое")
        h.bump("вылазок_в_чужое")

    покупка = м.магазин and h.магазины
    картой = налом = 0.0
    if покупка:
        got, картой, налом = _купить(h, npc, м)
    else:
        # сколько ходил — столько и принёс. Раньше часы и добыча бросались
        # независимо, и выходило, что один ходил четырнадцать часов ради трёх
        # банок, а другой за девять приносил девять: время не значило ничего
        ожидаемо = ((b["вылазка_часы_мин"] + b["вылазка_часы_макс"]) / 2.0
                    * м.часы * погода_часы(h))
        за_время = clamp(dur / max(0.5, ожидаемо), 0.45, 1.6)
        take = (b["вылазка_добыча_база"] * богатство_к * осталось * h.scav_richness
                * за_время * h.rng.uni(0.65, 1.25))
        take *= 0.8 + npc.t01("храбрость") * 0.5
        # в затишье не только легче идти, но и больше видно под снегом
        if h.mods.get("режим") == "затишье":
            take *= b["затишье_добыча"]
        # охотник умеет ходить по зимнему лесу и знает, где смотреть (GDD 12.1, 12.6)
        if "охотник" in npc.skills:
            take *= 1.0 + b["охотник_добыча"]
        got = {}
        for _ in range(int(take) + (1 if h.rng.chance(take % 1) else 0)):
            res = h.rng.weighted([(r, w) for r, w in b["вылазка_состав"].items()])
            got[res] = got.get(res, 0) + 1
            npc.stock[res] = npc.stock.get(res, 0) + 1
            h.stats["принесено_" + res] = h.stats.get("принесено_" + res, 0) + 1
        # настоящая зимняя одежда — вещь, которую находят: тулуп с чужой вешалки,
        # армейский бушлат в гараже. Дальше ходишь — больше шансов
        if npc.одежда < b["одежда_максимум"] and h.rng.chance(b["шанс_найти_тулуп"] * богатство_к):
            npc.одежда = b["одежда_максимум"]
            got["тулуп"] = 1
            h.bump("тулупов_найдено")
        # оружие в доме почти всё было в доме с первого дня. Улица даёт мелочь
        # и редко — нож в гараже, обрез у того, кому он уже не пригодится, —
        # и только там, где опаснее: чем дальше зашёл, тем больше нашёл.
        # Ружья на улице не бывает: винтовка в этой игре одна
        if h.rng.chance(b["шанс_найти_оружие"] * м.угроза):
            чем = h.rng.weighted(list(b["улица_оружие"].items()))
            if conflict.вооружиться(h, npc, чем, вслух=False):
                got[чем] = 1
                h.bump("оружия_найдено")
        # гаражи за домом — один ряд, и часть боксов в нём принадлежит этому же
        # подъезду. Рано или поздно сорванный замок оказывается соседским,
        # и вылазка «в никуда» превращается в повод, у которого есть имя
        свои = [к for к in sorted(h.кладовые.values(), key=lambda x: x.id)
                if м.кладовки and к.вид == м.кладовки and не_свой(h, npc, к)]
        if свои and h.rng.chance(b["гараж_попал_на_соседский"]):
            к = h.rng.pick(свои)
            взято = вскрыть_кладовую(h, npc, к, вслух=False)
            for r, v in взято.items():
                got[r] = got.get(r, 0) + v
    # вычерпывается именно это место, а не «район вообще»
    h.места[место] = max(b["вылазка_минимум_богатства"],
                         осталось - b["вылазка_истощение_за_ход"] * м.карман)
    npc.места[место] = h.места[место]      # сходил — знает точно
    # и заодно узнал, кто говорил, что тут пусто (GDD 14)
    if h.места[место] > b["вылазка_пусто_порог"]:
        for кто in h.others(npc):
            social.проверить_ложь(h, кто, npc, "место", место)

    тепло_одежды = 1.0 - b["одежда_холод"] * npc.одежда
    npc.warmth = clamp(npc.warmth - b["вылазка_холод_за_час"] * dur * тепло_одежды
                       * (1.0 + max(0.0, (-h.outside - 12)) * 0.03))
    # у самого порога куртка уже не держит: пальцы белеют за час
    отморозил = False
    if (h.outside < npc.мороз_предел(b) + b["выход_на_грани"]
            and not npc.hurt("обморож") and h.rng.chance(b["обморожение_на_грани"])):
        npc.injuries.append(h.rng.pick(["обморожение рук", "обморожение ног"]))
        npc.health = clamp(npc.health - h.rng.uni(5, 12))
        отморозил = True
    npc.rest = clamp(npc.rest - 6)

    # пустое место — новость, которую в тот же вечер знает весь подъезд.
    # Без неё каждый узнавал бы про каждое место собственными ногами, и дом
    # до конца метели ходил бы туда, где давно всё выгребли
    новость = (h.места[место] <= b["вылазка_пусто_порог"]
               and any(o.знаю_место(место) > b["вылазка_пусто_порог"] for o in h.others(npc)))
    if новость:
        for o in h.others(npc):
            o.места[место] = h.места[место]

    if покупка:
        txt = f"{npc.short} {vb(npc.sex, 'отстоял')} очередь в магазине на Заречной ({dur:.0f} ч): "
        if got:
            txt += ", ".join(f"{k} {v:g}" for k, v in got.items())
            чем = []
            if картой:
                чем.append(f"картой {картой:g}")
            if налом:
                чем.append(f"налом {налом:g}")
            txt += " — " + ", ".join(чем)
        elif кошелёк(h, npc) < 1.0:
            txt += "ни с чем: платить нечем"
        else:
            txt += "пусто: на полках уже ничего"
    else:
        txt = f"{npc.short} {vb(npc.sex, 'ходил')} {м.куда} ({dur:.0f} ч): "
        txt += ", ".join(f"{k} {v:g}" for k, v in got.items()) if got else "пусто"
    if отморозил:
        txt += "; {} пальцы на таком морозе".format("отморозила" if npc.sex == "ж" else "отморозил")
    if новость:
        txt += f"; {vb(npc.sex, 'сказал')} потом, что туда больше незачем — всё вынесли"

    # ногу ломают не о людей, а о лёд под снегом в темноте: травма считается
    # от дороги и от того, что с этой дорогой сегодня сделали снег и мороз
    hurt_risk = b["вылазка_шанс_травмы"] * м.дорога * дорожные_условия(h)
    if "охотник" in npc.skills:
        hurt_risk *= b["охотник_травма"]
    if h.rng.chance(hurt_risk):
        inj = h.rng.pick(["ушиб ноги", "порез руки", "перелом ноги", "ушиб руки"])
        npc.injuries.append(inj)
        npc.health = clamp(npc.health - h.rng.uni(8, 20))
        h.bump("травм_на_вылазке")
        txt += f"; {vb(npc.sex, 'вернулся') if npc.sex != 'ж' else 'вернулась'} с травмой ({inj})"
    if h.rng.chance(b["вылазка_шанс_встречи"] * danger * улица_злая(h)):
        h.bump("встреч_на_вылазке")
        if h.rng.chance(0.5):
            lost = {k: v for k, v in list(npc.stock.items()) if v > 0}
            res = h.rng.pick(list(lost)) if lost else None
            if res:
                had = npc.stock[res]
                npc.stock[res] = max(0, had - h.rng.rint(1, 2))
                # это единственное место, где ресурс уходит из мира насовсем;
                # без счётчика баланс дома не сходится и утечку не отличить от бага
                h.stats["потеряно_" + res] = h.stats.get("потеряно_" + res, 0) + (had - npc.stock[res])
            npc.panic = clamp(npc.panic + 15)
            txt += "; во дворе отняли часть добычи"
        else:
            npc.panic = clamp(npc.panic + 8)
            txt += "; на обратном пути кто-то шёл следом"

    # квартира стоит пустой, пока хозяин не вернулся к своему следующему делу.
    # Раньше away снимался здесь же, поэтому «пока хозяина нет» не видел никто
    # и дневная кража была недостижима (GDD 12.5).
    npc.stats["день_вылазки"] = h.day      # его видели с пакетами
    h.journal.line(txt, 1)
    # возвращение с пакетами видно всем (GDD 13)
    social.emit(h, npc, 2, "возвращение", night=False)
    if got:
        for other in h.others(npc):
            if h.rng.chance(0.35 + 0.1 * (2 - min(2, h.floor_gap(npc, other)))):
                social.adjust(other, npc.id, aware=14)
                social.note_signal(other, npc.id, "еда", other.believed(npc.id, "еда") + got.get("еда", 0), 0.5)
