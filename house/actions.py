def порция(h, npc, b):
    """Сколько сытости даёт одна порция еды.

    GDD 12.1: умения полезны игроку и группе. Повар вытягивает из той же банки
    больше — и кормит не только себя, но и всех, кто с ним под одной крышей.
    """
    cooks = "повар" in npc.skills
    if not cooks:
        for other_id in ([npc.living_with] if npc.living_with else []) + sorted(npc.guests):
            o = h.get(other_id)
            if o and o.alive and not o.exiled and "повар" in o.skills:
                cooks = True
                break
    return b["еда_за_порцию"] * ((1.0 + b["повар_прибавка"]) if cooks else 1.0)


def вложить(h, npc, материалов):
    """Материалы, ушедшие в стены, остаются в стенах.

    Это и есть привязанность к своему углу: человек не бросает квартиру,
    в которую вбил месяц работы, даже если рядом стоит лучше. Числом, а не
    отдельной чертой характера, — и потому у каждого своя.
    """
    h.where(npc).вложено += материалов


def spend(h, npc, res, amount):
    """Израсходовать ресурс безвозвратно и записать это.

    Съеденное, сожжённое и потраченное на стройку уходит из мира. Пока это
    не считалось, баланс дома не сходился, и настоящую утечку было не отличить
    от нормальной траты.
    """
    have = npc.stock.get(res, 0.0)
    used = min(amount, have)
    npc.stock[res] = have - used
    h.stats["израсходовано_" + res] = h.stats.get("израсходовано_" + res, 0.0) + used
    return used


# работа, а не быт: только на неё влияет состояние тела
РАБОТА = {"утепление", "дверь", "буржуйка", "разбор", "вылазка", "топить_снег", "вынести", "тело"}


def hours(key, npc, b):
    """Сколько часов занимает действие (GDD 5), с поправкой на состояние (GDD 6.1).

    Голодный, промёрзший и не спавший человек делает ту же работу дольше.
    Разговор и еда от этого не растягиваются — растягивается труд.
    """
    v = b["часы_действий"][key]
    if key == "буржуйка" and ("слесарь" in npc.skills or "электрик" in npc.skills):
        v -= b["часы_ремонта_за_умение"]
    if key in РАБОТА:
        v *= npc.speed(b)
    return v


# ---------------------------------------------------------------- выбор

def gather(h, npc):
    """Собрать все доступные действия с оценками. Оценка примерно 0..10."""
    b = h.B
    opts = []
    hungry = 1.0 - norm(npc.satiety, 15, 75)
    thirsty = 1.0 - norm(npc.hydration, 15, 75)
    cold = 1.0 - norm(npc.warmth, 20, 70)
    tired = 1.0 - norm(npc.rest, 20, 80)
    des = npc.desperation()
    плохо = npc.невмоготу()          # «мне сейчас физически плохо»
    зову = нужда(npc)                # с чем человек идёт к соседям
    room = h.room_temp(npc, burning=True)
    cold_pressure = холод_впереди(h, npc, b)
    fear = тревога(h, npc)

    # с кем он вообще близок — считается один раз на весь сбор вариантов:
    # предпочтение это разница с этим средним, а не сама близость
    соседи = h.others(npc)
    средний_свой = (sum(npc.свой(o.id) for o in соседи) / len(соседи)) if соседи else 0.0

    lim_day = b.get("лимит_в_день", {})
    lim_pair = b.get("лимит_на_пару_в_день", {})

    def add(key, score, target=None, часы=None, мерка=None):
        """Предложить действие.

        `часы` — если оно стоит не столько, сколько обычно: у вылазки время
        зависит от места, и ворота должны стоять на настоящей дороге, а не
        на средней цифре по всем вылазкам.

        `мерка` — по какому поступку его судить, если это не то же самое, что
        само действие. Сходить в магазин и вскрыть чужой гараж — одна вылазка
        по устройству и два разных поступка по совести; ключ действия должен
        остаться одним (иначе у человека будет два дневных лимита вместо
        одного), а метки, пунктики и нормальность — разными.
        """
        м = мерка or key
        # характер: личные пунктики и собственная мерка этого поступка.
        # Один интерпретатор на всё — новый характер это строка в данных,
        # а не строка в коде.
        #
        # Запрет и склонность входят по-разному, и это не украшение.
        # «Не терплю воровство» обязано уметь остановить руку — значит,
        # вычитается. «Ценю работу» обязано делать человека охотнее — но не
        # обязано выдумывать ему дело: пока склонность прибавлялась, Виктор
        # с его «руки решают» получал +1.5 к любой стройке при нулевой нужде
        # и собирал генератор на третий день метели, при горячих розетках,
        # ровно из той же арифметики, из-за которой генератор заказывали
        # на второй
        запрет, склонность = мерка_поступка(npc, м, b)
        # и то, чего человек добивается дольше одного дня. Прибавка, а не
        # приказ: замысел делает дело охотнее, но не отменяет ни голода,
        # ни мороза, ни совести (house/замысел.py)
        score = (score + npc.пунктик(м) + замысел.вес(h, npc, key) - запрет) * (1.0 + склонность)
        if score <= 0:
            return
        if key in СТРОЙКА and npc.hurt("руки"):
            return                    # разбитой рукой не строят (GDD 6.2)
        надо = hours(key, npc, b) if часы is None else часы
        if надо > npc.time_left + 0.001:
            return
        if used_day(h, npc, key) >= lim_day.get(key, 99):
            return
        # цель бывает не человеком: место вылазки — не тот, к кому ходят,
        # и пары «я и он» с ним не бывает (ср. mark)
        if getattr(target, "id", None) is not None:
            if used_pair(h, npc, target, key) >= lim_pair.get(key, 99):
                return
        opts.append(((key, target), score * norm_gate(npc, м, b)))

    # --- быт ---
    food_days = npc.days_of("еда")
    if npc.stock.get("мясо", 0) > 0 and npc.satiety < 70 and npc.stock.get("еда", 0) <= 0:
        add("поесть_мясо", hungry * 8.0)
    # ребёнка кормят раньше себя — в том числе когда сам ещё не голоден
    детский_голод = min([р["сытость"] for р in npc.дети], default=100.0)
    if npc.stock.get("еда", 0) > 0 and (npc.satiety < 88 or детский_голод < 75):
        s = hungry * 9.0
        if food_days < 2.5 and npc.satiety > 45:
            s *= 0.45            # режим экономии: терпит, пока может
        if npc.dependents:
            s += 1.2 + (1.0 - norm(детский_голод, 20, 80)) * 7.0
        add("поесть", s)

    if npc.hydration < 88:
        if h.water_on:
            add("попить", thirsty * 9.5)
        elif npc.stock.get("вода", 0) > 0:
            add("попить", thirsty * 9.5)
    # снег топят только там, где есть на чём (GDD 15: буржуйка — улучшение 2 уровня).
    # без печки вода становится настоящей проблемой: только запас, обмен или просьба
    can_melt = npc.shelter.get("буржуйка") or (h.powered(npc) and npc.shelter.get("обогреватель"))
    # печка в квартире одна, и дрова к ней общие: за снег гостя платит то же
    # хозяйство, у которого он греется. Иначе гость топил снег даром — своего
    # топлива у него нет по устройству
    очаг = h.хозяин_жилья(npc)
    есть_чем = (очаг.stock.get("топливо", 0) >= b["снег_топливо"]
                or npc.stock.get("материалы", 0) >= b["мебель_за_топку"])
    if not h.water_on and can_melt and npc.stock.get("вода", 0) < 4 and есть_чем:
        # снег топят охотнее, когда печка и так нужна: одно действие закрывает
        # и жажду, и холод
        together = cold * 3.0 if not очаг.burning and npc.shelter.get("буржуйка") else 0.0
        add("топить_снег", 2.0 + thirsty * 6.5 + together)

    # когда топливо кончилось, в печку идёт мебель — и тогда материалы
    # перестают быть строительным ресурсом. Это настоящий выбор: утеплиться или дожить
    can_burn = npc.stock.get("топливо", 0) >= 1 or npc.stock.get("материалы", 0) >= b["мебель_за_топку"]
    if npc.living_with:
        can_burn = False           # печку топит хозяин
    if npc.shelter.get("буржуйка") and can_burn and not npc.burning:
        # печку топят не для себя, а для комнаты. Пока хозяин считал только
        # свой холод, сытый и согревшийся хозяин не топил вовсе — и гости,
        # сложившие ему все свои дрова, замерзали у горячей печки. Смотрим
        # на того, кому в этой комнате хуже всех, включая ребёнка
        свои = [npc] + [h.get(g) for g in sorted(npc.guests)]
        мёрзнет, худо = cold, плохо
        for o in свои:
            if not (o and o.alive and not o.exiled):
                continue
            мёрзнет = max(мёрзнет, 1.0 - norm(o.warmth, 20, 70))
            худо = max(худо, o.невмоготу())
            for р in o.дети:
                мёрзнет = max(мёрзнет, 1.0 - norm(р["тепло"], 20, 70))
        # топят не только от холода в комнате: больному и раненому тепло нужнее
        need = max(мёрзнет, худо) * 8.0 + max(0.0, (14 - room)) * 0.35
        if npc.days_of("топливо") < 3:
            need *= 0.7
        add("топить", need)

    if npc.shelter.get("генератор") and очаг.stock.get("топливо", 0) >= 2 and not h.power_on:
        # генератор — это не грелка, а электричество на сутки: от него работает
        # обогреватель и на нём топят снег (GDD 15, уровень 3)
        нужен = cold * 4.0 + (1.0 - norm(npc.mood, 20, 80)) * 2.0
        if npc.shelter.get("питание") == h.day:
            нужен = 0.0            # он уже работает, второй раз заводить нечего
        if npc.shelter.get("обогреватель"):
            нужен += cold * 4.0
        if not h.water_on and npc.stock.get("вода", 0) < 3:
            нужен += thirsty * 3.0
        add("генератор", нужен - fear * 3.0 * (0.4 if npc.shelter.get("звукоизоляция") else 1.0))

    # уйти к пункту обогрева. Это не место вылазки, а расстояние: до школы №7
    # четырнадцать часов ходу, и это в один конец, а зимой в метель
    # непрерывного хода не бывает.
    #
    # Мерки нормальности у ухода нет и быть не должно: это разумное решение,
    # а не падение. Толкают его три вещи — отчаяние, ребёнок и то, что терять
    # уже нечего; держит одна — вложенное в свои стены. Тем же числом
    # `flat.вложено`, которым уже считается привязанность к своему углу
    if (npc.знает_пункт and npc.time_left >= b["уйти_часов_нужно"]
            and npc.health > b["уйти_здоровье_порог"]):
        часов = b["пункт_часы"] * погода_часы(h)
        # пока человек верит, что улица ещё кормит, он никуда не пойдёт:
        # сначала магазин и свой погреб, а к школе №7 — когда взять больше
        # негде. То же сравнение, которым держится и кража, и по той же
        # причине: уход — не порыв отчаяния, а последний оставшийся вариант
        s = (npc.desperation() * b["уйти_за_отчаяние"]
             * (1.0 - есть_куда_сходить(h, npc, завтра=True)) - b["уйти_решимость"])
        s += npc.dependents * b["уйти_за_ребёнка"]
        # терять нечего: ни запаса, ни целой квартиры, ни погреба.
        # У обоих вычетов есть потолок: разница между «полный шкаф» и «шкаф
        # вдвое полнее» на это решение уже не влияет — не уходят одинаково
        s -= clamp(вещи(npc.stock) * b["уйти_за_запас"], 0.0, b["уйти_запас_потолок"])
        s -= clamp(h.where(npc).вложено * b["уйти_за_вложенное"],
                   0.0, b["уйти_вложенное_потолок"])
        s -= len(h.мои_кладовые(npc)) * b["уйти_за_кладовую"]
        s -= len(npc.allies) * b["уйти_за_союз"]
        # дорога стала длиннее, чем была, когда объявление вешали
        s -= max(0.0, часов - b["пункт_часы"]) * b["уйти_за_дорогу"]
        # и то, ради чего возврат с полпути вообще нужен: теперь он знает
        s -= b["уйти_после_возврата"] * npc.stats.get("возвращался", 0)
        if npc.stats.get("дорога_закрыта"):
            s -= b["уйти_дорога_закрыта"]
        add("уйти", s)

    # «не отвечает третий день». Без этого тихая смерть не читается вовсе:
    # человек просто исчезает из журнала, и понять это можно только по панели.
    #
    # Постучаться в эту дверь по-настоящему он не может: пока он не знает,
    # что сосед мёртв, соседа нет и в списке живых — и добавлять покойника
    # обратно в перебор людей значило бы просить у него еды. Поэтому считается
    # не «сколько раз не открыли», а сколько дней от человека нет ни звука:
    # для мёртвого это одно и то же. Мёртвый не шумит, не пахнет готовкой
    # и не попадается на лестнице
    for t in h.people.values():
        if t.alive or t.exiled or t.died_day is None or t.id in npc.знает_о_смерти:
            continue
        молчит = h.day - t.died_day
        if молчит < b["не_открыл_дней"]:
            continue
        s = (b["проведать_вес"] * (0.5 + npc.trust.get(t.id, 3.0) * b["проведать_доверие"])
             * min(2.0, молчит / float(b["не_открыл_дней"])))
        s -= npc.hate.get(t.id, 0) * b["проведать_злость"]
        s -= npc.боится(t.id) * b["проведать_страх"]
        # и запах по стояку: через несколько дней тихая смерть перестаёт быть
        # тихой сама собой. Это страховка от того, что тело не найдут вовсе
        if молчит >= b["запах_дней"] and abs(h.where(npc).floor - t.floor) <= 1:
            s += b["проведать_запах"]
        add("проведать", s, t)

    # вытяжка: шахта обмёрзла изнутри, и печка больше не выдыхает наружу.
    # Догадаться об этом можно тремя путями, и все три честные: по себе
    # (утром болела голова), по уму — `сообразительность` наконец решает
    # что-то кроме одного вопроса про снег — и с чужих слов, от того, кому
    # уже было плохо. Связь к этому дню обычно мертва, так что «чужие слова»
    # здесь значат разговор в дверях, а не строчку в чате
    flat_в = h.where(npc)
    if flat_в.вентиляция < b["вентиляция_видно"]:
        видел = h.day - npc.stats.get("угар_признак", -99) <= b["вытяжка_помнит_дней"]
        слышал = h.day - npc.stats.get("слышал_про_угар", -99) <= b["вытяжка_помнит_дней"]
        s = (b["вытяжка_вес"] * (1.0 - flat_в.вентиляция)
             * (0.2 + npc.t01("сообразительность") * b["вытяжка_сообразительность"]))
        if видел:
            s += b["вытяжка_после_признака"]
        if слышал:
            s += b["вытяжка_с_чужих_слов"]
        add("вытяжка", s)

    # костёр: у кого нет печки, а комната больше не держит тепло. Опасно,
    # дымно и всё равно лучше, чем замёрзнуть.
    #
    # Отвечает он на холод В КОМНАТЕ, а не на озноб в теле, и это разные вещи.
    # Пока считалось наоборот, огонь посреди комнаты разводил тот, кто вернулся
    # промёрзшим с семичасовой ходки, — в квартиру, где двадцать градусов, на
    # второй день метели, при ещё живом тепле от батарей. Замер: треть всех
    # костров приходилась на первые три дня, и на второй день их разводили
    # в комнатах, где было плюс двадцать. Промёрзшее тело отходит само, за ночь
    # у тёплой стены; костёр нужен тому, кому отходить негде
    if (not npc.shelter.get("буржуйка") and npc.топит_сам()
            and h.where(npc).костёр != h.day
            and room < b["костёр_порог_комнаты"]
            and (npc.stock.get("материалы", 0) >= b["костёр_материалы"]
                 or npc.stock.get("топливо", 0) >= 1)):
        s = (b["костёр_порог_комнаты"] - room) * b["костёр_за_градус"]
        # тело только торопит: замёрзшему, больному и раненому та же комната
        # холоднее, и до утра он ждать не станет
        s *= 1.0 + max(cold, плохо) * b["костёр_за_тело"]
        add("костёр", s - b["костёр_решимость"])

    # заказать работу у того, у кого руки (GDD 18: «услуги — тоже товар,
    # и после дня 0 они дороже вещей»). Раньше заказ был один — буржуйка, —
    # и всё остальное, что требует умения, мастер строил только себе: пятеро
    # из шести не получали ни генератора, ни листов, ни арматуры никогда,
    # ни за какую цену. Арматура при этом единственная защита от пролома
    # в стене, и доступна она была ровно одному жильцу из шести
    if not h.mods.get("заказ_" + npc.id):
        for m in h.others(npc):
            # у мастера одни руки: пока он делает одну работу, вторую не берёт.
            # Без очереди Виктор набирал три заказа за день и раздавал их
            # всем разом на третий — печка выходила дешевле банки тушёнки
            if h.mods.get("мастер_занят_" + m.id):
                continue
            # и не заказывают печь у того, кто на этой неделе стоял у твоей
            # двери с ломом: работа на заказ требует пустить его внутрь
            if npc.счёты_свежи(m.id, h.day, b["счёты_дней"]):
                continue
            что, оценка = что_заказать(h, npc, m, b, cold_pressure, fear)
            if что is None:
                continue
            # и материал нужен сейчас, а не когда-нибудь: браться за работу,
            # которую нечем делать, — это не обещание, а отговорка. Материал
            # даёт заказчик, если он у него есть; иначе мастер из своего
            мат = b[УСЛУГИ[что]["мат"]]
            свой = npc.stock.get("материалы", 0) >= мат
            if not свой and m.stock.get("материалы", 0) < мат:
                continue
            if кошелёк_за_работу(npc) < цена_услуги(h, npc, m, что, b, свой) * 0.5:
                continue
            # та же мерка нормальности (НОРМА), что и у своей стройки: заказ
            # печи это не хозяйственность, а признание, что отопления больше
            # не будет. Пока здесь стояла безусловная тройка, печь заказывали
            # в первый же день метели, при горячих батареях
            # доверие к мастеру — множитель, а не слагаемое. Пока оно
            # прибавлялось (`+ trust * 0.3`, то есть +0.9 к любому заказу
            # у незнакомого соседа), оно само по себе перетаскивало через
            # `порог_действия` работу, которая человеку сегодня не нужна:
            # генератор с оценкой 0.3 при живых розетках становился делом дня.
            # Доверие решает, у кого заказывать, а не заказывать ли вообще
            add("заказать", оценка * (1.0 + npc.trust.get(m.id, 3.0) * b["заказ_за_доверие"])
                - npc.боится(m.id) * b["страх_вес_контакта"] * 0.5, m)

    # --- убежище (GDD 15) ---
    mats = npc.stock.get("материалы", 0)
    if not npc.shelter.get("буржуйка") and mats >= b["буржуйка_материалы"]:
        add("буржуйка", 4.0 + cold_pressure * 6.0)
    # утепление же и латает проломы: клеить плёнку на окно, пока в стене дыра
    # от чужого лома, бессмысленно, и человек это понимает раньше кода
    дыр = h.where(npc).дыр()
    if ((npc.shelter.get("утепление", 0) < b["максимум_утепления"] or дыр)
            and mats >= b["утепление_материалы"]):
        add("утепление", 1.0 + cold_pressure * 5.0 + дыр * b["дыра_чинят"])
    # --- убежище уровней 3 и 4 (GDD 15): их не построить без человека с руками
    for ключ, (уровень, мат_ключ, умения, потолок) in ПОСТРОЙКИ.items():
        если_есть = npc.shelter.get({"генератор_собрать": "генератор"}.get(ключ, ключ), 0)
        if (если_есть or 0) >= потолок:
            continue
        if not any(u in npc.skills for u in умения):
            continue
        if mats < b[мат_ключ]:
            continue
        if ключ == "генератор_собрать" and not есть_движок(npc):
            continue          # из досок двигатель не собрать
        # пока в доме есть свет, генератор — не нужда, а запасливость,
        # и семь материалов сейчас нужнее в окнах. Считается тем же
        # `нужен_генератор`, что и заказ у соседа: своими руками или чужими —
        # нужда одна и та же
        s = {"генератор_собрать": нужен_генератор(h, npc, h.where(npc), cold_pressure),
             "листы": fear * 4.0,
             "звукоизоляция": fear * 2.0 + (3.0 if npc.shelter.get("генератор") else 0.0),
             "стены": fear * 5.0 - 1.0}[ключ]
        add(ключ, s)

    if npc.shelter.get("дверь", 0) < b["максимум_двери"] and mats >= b["дверь_материалы"]:
        s = fear * 4.5 + npc.вес_черт("дверь")
        if h.mods.get("укрепление_порыв") == h.day:
            s += 2.5
        add("дверь", s)
    # квартиру можно разобрать лишь несколько раз — потом там голые стены
    strippable = [f for f in h.пустые_для(npc)
                  if f.stripped < b["разбор_максимум"] or вещи(f.stock) > 0]
    if strippable:
        want_mats = 0.0
        if not npc.shelter.get("буржуйка"):
            want_mats += 3.0
        if npc.shelter.get("утепление", 0) < 2:
            want_mats += 2.0
        if npc.shelter.get("дверь", 0) < 1:
            want_mats += 1.5 * fear
        want_mats += npc.вес_черт("разбор")
        # в квартире умершего может остаться еда — и это все понимают
        best_flat = max(strippable, key=lambda f: вещи(f.stock))
        if вещи(best_flat.stock) > 2:
            want_mats += 2.0 + des * 3.0
        # то же, чем меряется кража: пока улица ещё кормит, к чужой двери
        # не идут. Материалы приносят и с вылазки, и разница между «сходить
        # в гаражи» и «вскрыть кв.11» не в добыче, а в том, что второе делают,
        # когда первое перестало работать. Пока этого не было, доски из чужих
        # квартир таскали на третий день метели, при работающем ещё магазине:
        # четверть всех разборов за жизнь приходилась на первые четыре дня.
        #
        # «завтра» — та же поправка, что у ночной кражи: продрогший за день
        # человек к утру отойдёт, и улица для него не закрылась навсегда.
        # Без неё ранние разборы делали именно замёрзшие: улица для них
        # в ту же минуту переставала кормить, и запрет снимался целиком
        want_mats *= 1.0 - есть_куда_сходить(h, npc, завтра=True) * b["разбор_вес_улицы"]
        # и отдельно — запертая дверь. Пустая квартира и запертая чужая
        # квартира были для кода одним и тем же: доски выносили из-за целого
        # замка так же буднично, как из распахнутой после похорон
        цель = что_разбирать(h, strippable, b)
        if not цель.открыта:
            want_mats -= b["разбор_взлом_решимость"]
        add("разбор", want_mats - mats * 0.25)

    # --- вместе или порознь (GDD «Съехаться») ---
    # то же число, которым считают переезд, каждый день пересчитывается заново.
    # Пока выхода из сожительства не было, пары доживали до конца с взаимной
    # ненавистью 86 из 100 и продолжали делить одну комнату
    if npc.living_with:
        host = h.get(npc.living_with)
        if host and host.alive and not host.exiled:
            невыгодно = -social.выгода_соседства(h, npc, host) - b["съехать_порог"]
            # и то, чего нет ни в тепле, ни в тесноте: с человеком, которого
            # боишься, в одной комнате не остаются, даже если вдвоём теплее
            невыгодно += npc.боится(host.id) * b["страх_вес_соседства"]
            add("съехать", невыгодно * b["разъезд_вес"], host)
    for g_id in sorted(npc.guests):
        g = h.get(g_id)
        if not (g and g.alive and not g.exiled):
            continue
        # выставить может только тот, кто сильнее: слабый хозяин терпит
        if npc.power() < g.power() * b["выгнать_превосходство"]:
            continue
        add("выгнать", (-social.выгода_соседства(h, npc, g) - b["выгнать_порог"])
            * b["разъезд_вес"], g)

    # --- занять пустую квартиру (GDD 12): жильё — вещь, и его занимают ---
    # человек уходит не туда, где просто пусто, а туда, где заметно лучше:
    # целая дверь, заклеенные окна, чужая буржуйка. И тем тяжелее ему уйти,
    # чем больше он вложил в собственные стены — привязанность считается
    # материалами, а не отдельной чертой характера
    if not npc.living_with:
        своя = h.flats[npc.apt]
        моя_цена = h.ценность_жилья(своя, npc)
        держит = своя.вложено * b["жильё_привязанность"]
        for f in h.пустые_для(npc):
            if f.apt == npc.apt:
                continue
            выгода = h.ценность_жилья(f, npc) - моя_цена - держит - b["занять_порог"]
            if f.body and f.body.get("порций", 0) > 0:
                выгода -= b["занять_тело_штраф"] * (0.5 + npc.t01("лояльность"))
            прежний = h.чей(f)
            if прежний is not None:
                # угол живого человека: он сейчас у соседа, но возвращаться
                # ему будет некуда
                выгода -= b["занять_чужую_штраф"] * (0.5 + npc.t01("лояльность"))
                # если, конечно, этого человека он ещё считает живым. Тот,
                # кого списали со счетов, на свой угол в чужих глазах уже
                # не в счёт — и это ровно то, ради чего за ним и следили
                if прежний.id in npc.не_жилец:
                    выгода += b["занять_чужую_штраф"] * (0.5 + npc.t01("лояльность")) * 0.8
            add("занять", выгода, f)

    # --- то, до чего доходят на третьей неделе ---
    bodies = [f for f in h.пустые_для(npc) if f.body and f.body["порций"] > 0
              and h.day - f.body["день"] <= b["тело_порча_дней"]]
    if bodies:
        # вынести тело: так поступают те, кто ещё держится за человеческое
        if npc.trait("лояльность") >= 6 and npc.health > 45:
            add("вынести", npc.вес_черт("вынести") + social.recent_incidents(h) * 0.4 - 1.0)
        # и то, до чего доходят от голода
        hungry_enough = (npc.satiety < b["людоедство_порог_сытости"]
                         or npc.days_of("еда") < 0.8)
        if hungry_enough and not npc.dependents_only_child(h):
            s = des * 10.0 + (1.0 - norm(npc.satiety, 0, 45)) * 4.0
            s += npc.вес_черт("тело")
            s -= b["людоедство_порог_решимости"]
            s += npc.panic / 100.0 * 2.5
            near = min(bodies, key=lambda f: abs(f.floor - npc.floor))
            if near.owner_died and near.owner_died in npc.allies:
                s -= 5.0
            add("тело", s)

    # --- улица (GDD 20): ближе и беднее или дальше и опаснее ---
    # утеплить куртку: в обычной городской одежде мороз к третьей неделе
    # запирает человека дома надёжнее любой двери
    # руками куртку можно только подбить: тулуп из подручного утеплителя
    # не сошьёшь, второй уровень — находка, а не поделка
    if (npc.одежда < b["одежда_шитьё_потолок"]
            and npc.stock.get("материалы", 0) >= b["одежда_материалы"]):
        # тем нужнее, чем ближе мороз к порогу выхода. Запас — сколько ещё
        # градусов до «уже не выйти»; ниже нуля улица закрыта.
        #
        # Знак здесь был перевёрнут, и оценка выходила наибольшей в самую
        # тёплую погоду: в первый день метели, при минус девяти и горячих
        # батареях, подбить куртку было лучшим, что человек мог придумать
        # за день, — и он делал это в каждом прогоне
        запас = h.outside - npc.мороз_предел(b)
        s = clamp(3.0 - запас * 0.35, 0.0, 9.0)
        # нужда в куртке — от мороза, а срочность — от того, часто ли человек
        # выходит. Множитель, а не слагаемое: иначе тот, кто ходит на улицу,
        # шьёт куртку на третий день, при минус одиннадцати, когда до порога
        # ещё восемь градусов. По GDD 20 это решение второй половины забега
        s *= 0.5 + drive_наружу(npc)
        add("одежда", s)

    # снять наличные, пока банк работает (GDD 18). Ровно один день на то,
    # чтобы превратить цифры на экране в бумагу, которую примут и завтра
    if h.банки and npc.счёт >= 1.0 and h.mods.get("банкомат", 0.0) >= 1.0:
        сколько = min(npc.счёт, b["банкомат_лимит"], h.mods["банкомат"])
        add("банкомат", 1.4 + сколько * 0.22 - npc.stock.get("деньги", 0.0) * 0.05)

    # своя кладовка — погреб в подвале или гараж за домом. Единственное место,
    # куда можно сходить, не выходя на улицу и не влезая в чужое; поэтому
    # туда идут первым делом, пока там ещё что-то лежит
    к = выбрать_кладовую(h, npc, часов=npc.time_left)
    if к is not None:
        s = (drive_наружу(npc) * b["кладовая_тяга"]
             + (1.0 - norm(food_days, 1, 7)) * 2.0
             + clamp(сколько_поднимет(h, npc, к, b), 0.0, 8.0) * b["кладовая_за_запас"])
        add("кладовая", s, к, часы=часы_кладовой(h, к))

    # чужой замок в подвале: ступенька между разобранной пустой квартирой
    # и налётом. За той дверью никого нет — и потому это правда легче, чем
    # прийти к соседу с ломом. Судит человек об этом не по тому, что там
    # лежит (он не знает), а по тому, что, по его сведениям, есть у хозяина
    чужая = чужая_кладовая(h, npc, часов=npc.time_left)
    if чужая is not None:
        хозяин = h.хозяин_кладовой(чужая)
        s = нужда(npc) * b["кладовая_вскрытие_за_нужду"] + npc.вес_черт("разбор")
        if хозяин is not None:
            s += npc.loot_value(хозяин.id) * (0.3 + npc.t01("жадность") * 0.6)
            s += npc.hate.get(хозяин.id, 0.0) / 25.0
            s -= npc.боится(хозяин.id) * b["страх_вес_кражи"]
        # то же, чем меряется кража и разбор: пока улица кормит, замки не рвут
        s *= 1.0 - есть_куда_сходить(h, npc, завтра=True) * b["разбор_вес_улицы"]
        s -= b["кладовая_вскрытие_решимость"]
        s -= (1.0 - conflict.stealth(npc)) * 1.5
        add("вскрыть_кладовую", s, чужая, часы=часы_вскрытия(h, чужая))

    предел = npc.мороз_предел(b)
    if (npc.health > 45 and npc.warmth > 32 and len(npc.injuries) < 2 and not npc.sick
            and h.outside > предел):
        # за запасами идут не когда умирают, а когда боятся, что не хватит:
        # тревожный человек выходит на улицу ещё сытым — и в этом всё дело,
        # потому что район выгрызается досуха уже ко второй неделе
        #
        # Куда идти, решается здесь же, а не после выхода. Пока место выбирали
        # в `execute`, из остатка дня, «выходить ли» и «куда» были разными
        # решениями, и второе доставалось первому в наследство: человек решал
        # сходить за продуктами, а шёл в чужие гаражи, потому что до магазина
        # уже не успевал. Замер: 72% диких вылазок первого дня — это тот самый
        # подмен, и он не решение, а сдача остатка дня
        м = выбрать_место(h, npc, часов=npc.time_left)
        if м is not None:
            drive = drive_наружу(npc)
            s = drive * 7.0 + (1.0 - norm(food_days, 1, 7)) * 3.0
            s += npc.вес_черт("вылазка") - 1.5
            s -= npc.dependents * 1.2
            s -= max(0.0, (-h.outside - 20) * 0.12)
            s *= (1.0 - 0.25 * (h.mods.get("опасность_множитель", 1.0) - 1.0))
            # и то, чего в этом решении не было вовсе: куда именно он идёт.
            # Плохое место должно проигрывать утеплению окон и обмену, а не
            # доставаться человеку по умолчанию
            s += clamp(оценка_места(h, npc, м), -4.0, 4.0) * b["вылазка_вес_места"]
            add("вылазка", s, м, часы=минимум_часов(h, м), мерка=м.мерка)

    # подброс — ход не к человеку, а к двери, и потому стоит отдельно от цикла
    # по соседям: класть надо к порогу врага, а увидят это все, кто мимо ходит
    з = npc.замысел
    if (з is not None and з["вид"] == "рассорить" and not з.get("сегодня_спит")
            and з["враг"] and з["напор"] < замысел.осторожность(h, npc)):
        враг = h.get(з["враг"])
        чем = что_подбросить(h, npc)
        if враг is not None and враг.alive and not враг.exiled and чем is not None:
            # умный предпочитает подброс шёпоту: шёпот можно проверить
            # разговором с оболганным, а вещь у двери говорит сама
            подброс = (npc.hate.get(враг.id, 0.0) / 10.0
                       + npc.t01("сообразительность") * b["подброс_за_ум"]
                       - з["напор"] * b["шепнуть_осторожность"]
                       - b["подброс_решимость"])
            add("подбросить", подброс, враг)

    # проверить площадку, прежде чем выйти. Дешёвое действие человека,
    # у которого есть причина опасаться: с кем-то счёты или кого-то он боится.
    # Раньше жертва вчерашней осады выходила за дровами ровно так же, как
    # выходила до неё, — и это было единственное, чего ей не хватало
    боязно = max((npc.боится(o.id) for o in h.others(npc)), default=0.0)
    есть_счёты = any(npc.счёты_свежи(o.id, h.day, b["счёты_дней"]) for o in h.others(npc))
    if ((боязно > b["лестница_порог_страха"] or есть_счёты)
            and h.mods.get("смотрел_лестницу", {}).get(npc.id) != h.day):
        осторожно = (боязно * b["лестница_за_страх"]
                     + (b["лестница_за_счёты"] if есть_счёты else 0.0)
                     + npc.вес_черт("дежурить") * 0.3)
        add("лестница", осторожно, None)

    # --- люди ---
    for t in h.others(npc):
        if t.away:
            # хозяина нет дома: поговорить не с кем, но квартира стоит пустая.
            # Раньше эта ветка была ниже по циклу, за `continue`, и не достигалась
            # никогда — дневная кража из GDD 12.5 была мёртвым кодом
            if (npc.confidence(t.id) > 0.2 and not t.living_with
                    and not social.под_одной_крышей(h, npc, t)):
                # то же, что и ночью: пока улица кормит, чужая дверь не нужна
                greed = (npc.loot_value(t.id) * (0.4 + npc.t01("жадность") * 0.8)
                         * (1.0 - есть_куда_сходить(h, npc)))
                score = (greed * (0.4 + des) + npc.вес_черт("кража_днём")
                         - (1.0 - conflict.stealth(npc)) * 3.0)
                if h.day - npc.stats.get("день_вылазки", -99) <= 1:
                    score -= b["кража_только_принёс"]
                score += social.напряжение_дома(h, npc) * b["кража_за_напряжение"]
                score += npc.hate.get(t.id, 0) / 25.0
                score -= t.shelter.get("дверь", 0) * 1.4
                # днём ломать чужую дверь страшнее, чем ночью: в подъезде люди,
                # шум слышно всем, и объяснить себя нечем
                score -= b["кража_днём_решимость"]
                score -= npc.боится(t.id) * b["страх_вес_кражи"]
                score -= len([o for o in h.others(npc) if not o.away]) * 0.5
                add("кража_днём", score * norm_gate(npc, "кража", b), t)
            continue
        trust = npc.trust.get(t.id, 3.0)
        # между нами счёты: он ломал мою дверь на этой неделе, или я ломал его.
        # Пока этого состояния не было, назавтра после осады эти двое разговаривали
        # и менялись банками как ни в чём не бывало — 13% и 16% всех контактов
        счёты = npc.счёты_свежи(t.id, h.day, b["счёты_дней"])
        # наблюдение
        curiosity = npc.вес_черт("наблюдение") + npc.panic / 40.0 + npc.hate.get(t.id, 0) / 30.0
        curiosity += des * 2.0 - npc.confidence(t.id) * 3.0
        # за тем, кого списал со счетов, приглядывают отдельно — не из заботы,
        # а чтобы не пропустить день, когда за дверью станет тихо
        if t.id in npc.не_жилец:
            curiosity += b["наследство_вес"]
        # за тем, с кем счёты, следят пристально: не выходит ли, с чем ходит,
        # один ли он дома
        if счёты:
            curiosity += b["счёты_наблюдение"]
        # к страшному соседу не приглядываются: попадёшься — объясняй потом
        curiosity -= npc.боится(t.id) * b["страх_вес_контакта"]
        add("наблюдение", curiosity, t)
        # разговор
        свой = npc.свой(t.id)
        ближе = npc.предпочтение(t.id, средний_свой)
        talk = npc.вес_черт("разговор") + trust * 0.3
        # к своему заходят не потому, что он полезен, а потому, что он свой.
        # Пока в этой строке стояло одно доверие, все шестеро выбирали одного
        # и того же: доверие на четыре пятых репутация, а она у всех общая
        talk += ближе * b["близость_вес_разговора"]
        talk += (1.0 - norm(npc.mood, 20, 80)) * 2.0
        talk -= npc.hate.get(t.id, 0) / 12.0     # к тому, кого не выносишь, не идут
        talk -= npc.panic / 100.0
        # и к тому, кого боишься, тоже: страх держит крепче неприязни
        talk -= npc.боится(t.id) * b["страх_вес_контакта"]
        if not счёты:
            add("разговор", talk, t)
        # --- ходы заговорщика (house/замысел.py) ---
        # Оба доступны только тому, у кого есть замысел «рассорить», и оба
        # стоят напора: чем чаще он ходит, тем ближе тот день, когда дом
        # сложит одно к одному. Умный это чувствует и выжидает, глупый — нет,
        # и вся разница между двумя способами интриги ровно в этом
        з = npc.замысел
        if (з is not None and з["вид"] == "рассорить" and not з.get("сегодня_спит")
                and з["враг"] and з["враг"] != t.id
                and з["напор"] < замысел.осторожность(h, npc)):
            враг = h.get(з["враг"])
            if враг is not None and враг.alive and not враг.exiled:
                # шепнуть: сказать про врага то, чего не было. Дёшево, быстро
                # и разоблачается тем же, чем наговор, — добрым поступком
                # оболганного
                шёпот = (npc.hate.get(враг.id, 0.0) / 12.0
                         + t.свой(враг.id) * b["шепнуть_за_их_близость"]
                         - t.trust.get(враг.id, 3.0) * b["шепнуть_против_доверия"]
                         - з["напор"] * b["шепнуть_осторожность"])
                add("шепнуть", шёпот, t)
        # человек помнит, кто ему давал, а кто отказывал
        need_res = most_needed(npc)
        rec = npc.ask_record(t.id)
        can_ask = True
        if h.day - rec["последняя"] < b["просьба_перерыв_дней"]:
            can_ask = False                      # только что уже просил
        if rec["подряд"] >= 2 and h.day - rec["последняя"] < b["просьба_обида_дней"]:
            can_ask = False                      # дважды отказал — больше не унижаюсь
        if h.day - rec["я_дал"] < b["просьба_после_помощи"]:
            can_ask = False                      # сам ему на днях отдал последнее
        # просят не только когда кончается: промёрзший идёт за дровами, больной
        # за лекарством. Это и есть то, чем лечится «невмоготу» — не взломом
        if can_ask and not счёты and зову > 0.35 and npc.believed(t.id, need_res) > 1.5:
            # просят у того, кто свой, — не потому, что у него больше,
            # а потому, что перед своим не так стыдно стоять с протянутой рукой
            ask = (зову * 6.0 * (0.3 + trust / 10.0 + ближе * b["близость_вес_просьбы"])
                   + npc.вес_черт("попросить"))
            # к тому, кого ненавидишь, идут только если совсем припёрло —
            # и понимая, что у двери может начаться драка
            ask -= npc.hate.get(t.id, 0.0) / 14.0 * (1.5 - зову)
            # и не идут к тому, кому уже задолжали: стыдно
            ask -= npc.ask_record(t.id).get("должен", 0.0) * b["долг_вес"]
            # к щедрому идут первым, к скупому не идут вовсе
            ask *= b["просьба_вес_памяти"] + (2.0 - b["просьба_вес_памяти"]) * npc.generosity(t.id)
            # в дверь, за которой стоит страшный человек, не стучатся даже
            # голодными: просьба без доверия и так опасна (GDD 14)
            ask -= npc.боится(t.id) * b["страх_вес_контакта"]
            add("попросить", ask, t)
        # поделиться
        gave_me_today = h.mods.get("контакты", {}).get((t.id, npc.id, "поделиться"), 0)
        # видно не чужой шкаф, а чужое лицо: делятся с тем, кто КАЖЕТСЯ в беде.
        # И помочь можно не только банкой: дровами, водой, аптечкой
        чем, излишек = чем_поделиться(h, npc, t, b)
        # прийти с банкой к тому, кто ни о чём не просил, — это поступок,
        # и на него нужен повод: свой человек, недавняя просьба, болезнь
        # или собственная мерка («не могу пройти мимо ребёнка»). Без этого
        # условия помощь была рядовым пунктом расписания: 88% передач шли
        # тому, кто ничего не просил, и половина — в первые три дня
        просил = h.day - t.ask_record(npc.id).get("последняя", -99.0)
        ценит = (npc.values or {}).get("ценит") or ()
        # беда — та, которую он ВИДЕЛ. Пока здесь стояли `t.injuries or t.sick`,
        # человек знал о переломе соседа за двумя стенами, ни разу его
        # не встретив, и шёл с аптечкой к тому, кто ему в глаза не попадался
        плох_ = npc.плох(t.id)
        повод = (t.id in npc.allies
                 or свой >= b["помощь_свой_порог"]
                 or просил <= b["помощь_помнит_просьбу"]
                 or плох_ >= b["не_жилец_отмена"]
                 or npc.видит_хворь(t.id)
                 or trust >= b["помощь_доверие_без_повода"]
                 or (t.dependents and "ребёнок" in ценит))
        # и повод, и беду надо ВИДЕТЬ: домысел к двери не ведёт
        if (повод and чем is not None and not gave_me_today and not счёты
                and npc.confidence(t.id) > b["помощь_уверенность"]):
            give = npc.вес_черт("поделиться") + trust * 0.5 - des * 4.0
            give += ближе * b["близость_вес_помощи"]
            # на чужую беду отзываются тем слабее, чем дольше идёт метель.
            # Это не жестокость, а самосохранение: в первый день отдать банку
            # осунувшемуся соседу почти ничего не стоит, на двадцать пятый
            # это твой последний день еды
            своё_дороже = 1.0 - clamp(h.day / 30.0, 0.0, 1.0) * b["помощь_самосохранение"]
            give += плох_ * b["помощь_за_вид"] * своё_дороже
            # а тому, кого он про себя уже похоронил, нести незачем: банка
            # уйдёт в мертвеца. Самый холодный расчёт в доме и самый обычный
            if t.id in npc.не_жилец:
                give -= b["наследство_вес"]
            # и сама оценка зависит от того, чем помогаешь: отнести аптечку
            # больному — поступок, вынести кружку воды — почти ничего
            give += (b["помощь_вес"][чем] - 1.0) * b["помощь_вес_в_оценке"]
            # то же, что и при просьбе: «я тебе уже трижды носил». Асимметрия
            # была настоящей дырой — отказать в ответ на просьбу человек умел,
            # а сам таскать банки одному и тому же соседу мог бесконечно
            give -= npc.дал.get(t.id, 0.0) * b["долг_вес"]
            # и тот же страх, которым он отказывает на просьбу: человек, который
            # не знает, когда кончится метель, считает свой запас против срока,
            # который сам себе назначил. Раньше отказ считался по горизонту,
            # а добровольный подарок — по четырём дням, и выходило, что чужое
            # лицо у двери убедить труднее, чем собственную совесть
            give -= ((1.0 - min(1.0, npc.secure(чем if чем != "лекарства" else "еда")))
                     * b["жадность_от_нехватки"] * b["щедрость_вес_горизонта"])
            if t.id in npc.allies:
                give += 2.0
            if t.dependents:
                give += 1.5
            add("поделиться", give, t)
        # вернуть долг: человек помнит, что ему давали, и при излишке отдаёт.
        # Без этого память была односторонней — должник не возвращал никогда
        мой_долг = npc.ask_record(t.id).get("должен", 0.0)
        # но не в тот же день: «занёс банку — отдала банку» в первые сутки
        # обнуляет и подарок, и память о нём
        свежий = h.day - npc.ask_record(t.id).get("я_дал", -99.0)
        if (мой_долг >= 1.0 and npc.days_of("еда") > b["помощь_минимум_дней"]
                and свежий >= b["долг_возврат_не_раньше"]):
            add("вернуть", 2.0 + мой_долг * 1.2 + npc.t01("лояльность") * 2.0, t)
        # с раскрытым людоедом дом дел не имеет
        if t.stats.get("раскрыт"):
            continue
        # съехаться: когда своя квартира больше не держит тепло
        # отказ в переезде помнят: второй раз в ту же дверь не стучатся
        if (not npc.living_with and not npc.guests and not t.living_with
                and h.day - npc.ask_record(t.id).get("отказ_переезд", -99) >= b["переезд_обида_дней"]
                and npc.warmth < b["переезд_порог_тепла"]
                and h.room_temp(t, burning=True) > h.room_temp(npc, burning=True) + 4
                and trust >= b["переезд_доверие"]):
            move = social.выгода_соседства(h, npc, t) * b["переезд_вес_выгоды"]
            move += плохо * 4.0
            move += npc.вес_черт("переехать")      # гордость
            # и отдельно — тот, кто идёт не греться: чем больше у соседа добра
            # и чем меньше у гостя совести, тем охотнее он к нему просится.
            # Появляется только когда обычная жизнь уже кончилась
            move += (npc.loot_value(t.id) * npc.t01("жадность")
                     * (1.0 - npc.t01("лояльность")) * (1.0 - npc.normalcy)
                     * b["переезд_расчёт"])
            move -= npc.боится(t.id) * b["страх_вес_соседства"]
            add("переехать", move, t)
        # отнять на лестнице: без двери, без замка, лицом к лицу.
        #
        # Человека, с которым делишь одну комнату, на лестнице не зажимают:
        # вечером возвращаться в неё же. Раньше здесь стоял `continue`, и он
        # отрезал не только отъём, но и обмен с лечением ниже по циклу — то есть
        # ровно тем двоим, кто ближе всех друг к другу, было нельзя ни меняться,
        # ни лечить. Замер: 857 пар-дней сожительства на 40 жизней, и в 599 из них
        # (70%) находилась сделка, выгодная обеим сторонам и невозможная
        if not social.под_одной_крышей(h, npc, t):
            A = conflict.aggr(h)
            # сила соседа берётся такой, какой она КАЖЕТСЯ. Слабость видна
            # по лицу, и она приглашает: к тому, кто качается и держится
            # за стену, на лестнице подходят охотнее, чем к целому. И наоборот —
            # раненый, который держится прямо, этим и защищается
            ratio = npc.power() / max(0.2, npc.видимая_сила(t))
            # ловят того, кого видели с пакетами; случайная встреча на лестнице — редкость
            met = (t.stats.get("день_вылазки") == h.day) or h.rng.chance(0.08)
            # ключи имеет смысл отнимать только у того, кто живёт один: в квартиру
            # с сожителем с ними всё равно не войти
            один = not t.guests and not t.living_with
            жильё = conflict.хочу_его_квартиру(h, npc, t) if один else 0.0
            trigger = (des > 0.40 or npc.hate.get(t.id, 0) > 35
                       or жильё > b["отъём_жильё_порог"])
            if met and trigger and ratio > b["отъём_порог_силы"] / A and npc.loot_value(t.id) > 1.5:
                take = (des * 3.5 + npc.hate.get(t.id, 0) / 18.0) * (0.4 + npc.t01("жадность"))
                take += жильё * b["отъём_вес_жилья"]
                take *= min(2.2, ratio)
                take -= b["отъём_решимость"]
                take -= npc.t01("лояльность") * 5.0 / A
                # на лестнице зажимают слабого, а не страшного
                take -= npc.боится(t.id) * b["страх_вес_отъёма"]
                take -= len([o for o in h.others(npc) if t.id in o.allies]) * 1.6
                take -= 2.0 if t.id in npc.allies else 0.0
                take -= 1.5 if t.dependents else 0.0
                # дом закрывается против того, кто уже отнимал: это страшнее совести
                take -= len([o for o in h.others(npc) if o.hate.get(npc.id, 0) > 50]) * 1.8
                add("отнять", take, t)
        # подкараулить: сесть на площадке и ждать его. Это ответ на осаду
        # с обеих сторон сразу — и тот, кто ломал дверь и не вошёл, и тот, чью
        # дверь ломали, приходят к одной и той же мысли. Разница между ними
        # только в том, что один хочет забрать, а другой — рассчитаться
        пара = tuple(sorted((npc.id, t.id)))
        остыли = h.day - h.mods.get("засада_было", {}).get(пара, -99)
        if (счёты and not t.away and t.id not in npc.allies
                and npc.hate.get(t.id, 0.0) >= b["засада_порог_злости"]
                and остыли >= b["засада_перерыв_дней"]
                and not h.mods.get("караулят", {}).get(t.id)
                and not social.под_одной_крышей(h, npc, t)):
            # сила считается по тому, каким он КАЖЕТСЯ, и только превосходство:
            # на площадку садятся не от храбрости, а от расчёта
            перевес = clamp(npc.power() / max(0.2, npc.видимая_сила(t)) - 1.0, 0.0, 1.6)
            ждать = (npc.hate.get(t.id, 0.0) / b["засада_за_злость"]
                     + перевес * b["засада_за_силу"]
                     + npc.loot_value(t.id) * b["засада_за_добычу"]
                     - npc.боится(t.id) * b["страх_вес_отъёма"]
                     - b["засада_решимость"])
            add("подкараулить", ждать, t)
        # обмен. С тем, с кем счёты, не меняются: сделка требует подойти
        # к двери и отдать вещь из рук в руки, а к этой двери не подходят
        if not счёты:
            add("обмен", _trade_score(h, npc, t), t)
        # лечение
        # GDD 6.2: «помощь NPC-медика (если есть доверие)»
        if ("медик" in npc.skills and npc.stock.get("лекарства", 0) >= 1
                and нужен_врач(t) and t.trust.get(npc.id, 3.0) >= b["лечение_доверие"]):
            детский = 3.0 if (t.слабейший_ребёнок() or {}).get("болен") else 0.0
            # и то, что за прошлый раз не заплатили: даром она лечит, но
            # не бесконечно и не всех подряд (GDD 18)
            должок = npc.ask_record(t.id).get("не_заплатил", 0.0)
            add("лечить", 3.0 + t.невмоготу() * 4.0 + детский
                + npc.t01("лояльность") * 3.0 + trust * 0.3
                - должок * b["услуга_обида"], t)

    # --- себя ---
    if npc.stock.get("лекарства", 0) >= 1 and нужен_врач(npc):
        свой = npc.слабейший_ребёнок()
        детский = 0.0 if свой is None else (1.0 - norm(свой["здоровье"], 20, 90)) * 7.0
        add("лечить", 3.0 + max(плохо * 6.0, детский), npc)
    # --- позвать дом на площадку (GDD 25: дом как субъект) ---
    add("собрание", meeting.оценка(h, npc))
    add("отдых", tired * 6.0 + (1.0 - norm(npc.mood, 20, 70)) * 2.0 + (2.0 if npc.injuries else 0.0))
    # обычная жизнь: пока всё ещё похоже на нормальное, человек живёт, а не выживает
    # обычная жизнь заполняет то, что осталось, но не спорит с настоящими делами
    add("быт", 1.25 + npc.normalcy * 1.4 + (0.4 if h.network > 0 else 0.0))

    return opts


def _trade_score(h, a, b_npc):
    """Обмен по GDD 18: сделка идёт, если обе стороны считают её выгодной."""
    deal = find_deal(h, a, b_npc)
    if not deal:
        return 0.0
    give, get_ = deal
    gain = social.value_of(a, get_[0], get_[1]) - social.value_of(a, give[0], give[1])
    return clamp(gain * 1.2 + a.trust.get(b_npc.id, 3.0) * 0.2
                 - a.боится(b_npc.id) * h.B["страх_вес_контакта"], 0.0, 9.0)


# деньги здесь наравне с банками тушёнки — в этом весь смысл: пока их берут,
# у соседа можно купить, а не выпросить (GDD 18)
TRADABLE = ("еда", "топливо", "лекарства", "материалы", "вода", "деньги", "патроны")
# патроны в этом списке — не мелочь: они лежат в вылазке, их выносят при краже,
# но выменять их было нельзя, и за 40 жизней 114 штук осело у людей, которым
# нечем стрелять. Цену им теперь ставит не дефицит, а наличие ружья (social.value_of)


def find_deal(h, a, b_npc):
    """Найти сделку, которую ОБЕ стороны сочтут выгодной (GDD 18).

    Главное: инициатор не знает правды о чужом складе. И что у соседа есть,
    и насколько соседу это нужно, он прикидывает по своей оценке — той самой,
    ради которой построены шум, запах и слухи. Раньше здесь трижды читался
    настоящий `b_npc.stock`, и осведомлённость в обмене не участвовала вовсе.

    Стоимость единицы считается по одному разу на человека: `value_of` линейна
    по количеству, а количество в сделке всегда единица. Это самое горячее
    место симуляции, через него шло 60% всего времени.
    """
    b = h.B
    va = {r: social.value_of(a, r, 1.0) for r in TRADABLE}
    # как, по мнению a, живёт b_npc — а не как он живёт на самом деле
    vb = {r: social.value_of(b_npc, r, 1.0, days=social.believed_days(a, b_npc, r))
          for r in TRADABLE}
    best = None
    for give in TRADABLE:
        if a.stock.get(give, 0) < 2:
            continue
        for get_ in TRADABLE:
            if get_ == give:
                continue
            # предлагают за то, что у соседа, по-твоему, есть
            if a.believed(b_npc.id, get_) < b["обмен_порог_веры"]:
                continue
            n = 1.0
            mine_gain = va[get_] - va[give]
            their_gain = vb[give] - vb[get_]
            if mine_gain > 0.2 and their_gain > 0.2:
                score = mine_gain + their_gain
                if best is None or score > best[0]:
                    best = (score, (give, n), (get_, n))
    if best:
        return best[1], best[2]
    return None


def choose_and_do(h, npc):
    """Один ход одного человека. Возвращает True, если действие совершено."""
    npc.away = False          # раз он снова берётся за дело — значит, он дома
    opts = gather(h, npc)
    # если ничего толкового не осталось — день на этом и заканчивается.
    # без этого порога человек от нечего делать идёт разбирать чужую квартиру
    opts = [(o, s) for o, s in opts if s > h.B["порог_действия"]]
    if not opts:
        return False
    temp = h.B["температура_выбора"] + (npc.panic / 100.0) * h.B["температура_выбора_паника"]
    temp += (1.0 - npc.rest / 100.0) * 0.4
    key_target = h.rng.softmax_pick(opts, temp)
    key, target = key_target
    execute(h, npc, key, target)
    return True


