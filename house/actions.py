def drive_наружу(npc):
    """Насколько человека тянет на улицу: по нужде и по страху не хватить."""
    return max(npc.desperation(), npc.insecurity() * 0.85)


def нужда(npc):
    """Насколько срочно человеку нужна помощь соседей: 0..1.

    Кража и налёт отвечают на «я умираю» (`desperation`), а просьба, переезд
    и лечение — на «мне сейчас плохо» (`невмоготу`). Физическая часть весит
    чуть меньше: с одним ушибом к чужой двери не идут, а промёрзнув — идут.
    """
    return max(npc.desperation(), npc.невмоготу() * 0.8)


def есть_куда_сходить(h, npc, завтра=False):
    """0..1 — насколько улица, по мнению этого человека, ещё кормит.

    Главная альтернатива краже. Пока он верит, что в магазине что-то осталось,
    и туда можно выйти, к соседней двери он не пойдёт: сначала магазин, а
    к соседу — когда брать больше негде. Это не запрет, а проигрыш в сравнении:
    замер показывал, что 79% ранних краж случались в тот же день или на
    следующий после вылазки, причём вор знал, что в лучшем месте ещё 0.72.

    Мороз, раны и болезнь улицу закрывают — и тогда остаётся дом. Те же условия,
    что и у самой вылазки (см. gather), иначе человек «шёл бы в магазин» вместо
    кражи, не имея никакой возможности туда выйти.

    `завтра` — для ночного решения. Ночью человек выбирает не между «пойти
    к соседу» и «выйти сейчас», а между «пойти к соседу» и «выйти утром»,
    и продрогшее за день тело к утру отходит. Пока разницы не было, вернувшийся
    с пятнадцатичасовой ходки промерзал ниже порога выхода, улица для него
    в ту же минуту переставала кормить — и он шёл к соседской двери в ночь
    после самой богатой добычи. Оттого на первую ночь метели приходилось краж
    больше, чем на вторую, третью или четвёртую: в первый день на улицу выходят
    все и все возвращаются промёрзшими.
    """
    # свой погреб — тот же ответ на тот же вопрос, и ответ лучший: до него
    # идти час, он свой, и он не закрывается ни морозом, ни бураном. Пока
    # человеку есть что поднять снизу, к чужой двери он не пойдёт
    свой = any(not к.пусто() and сколько_поднимет(h, npc, к, h.B) > 0
               for к in h.мои_кладовые(npc))

    тело = npc.health <= 45 or len(npc.injuries) >= 2 or npc.sick
    if not завтра:
        тело = тело or npc.warmth <= 32
    if h.outside <= npc.мороз_предел(h.B) or тело:
        return clamp(свой * h.B["кража_вес_улицы"], 0.0, 1.0)
    # то же, чем он выбирает место: сколько там, по его мнению, осталось.
    # Богатство места режется единицей — «в магазине ещё есть» и «в магазине
    # вдвое больше, чем нужно» для этого решения одно и то же.
    #
    # И только те места, куда он в самом деле может дойти. Пока это считалось
    # по всем четырём, женщину с ребёнком от кражи удерживал магазин, в который
    # она не может войти ни в один день метели: до него дальше, чем позволяет
    # ребёнок на руках.
    #
    # Вес меньше единицы нарочно: даже при полном магазине чужая дверь не
    # перестаёт быть выходом совсем. Иначе первая кража уезжает за двенадцатый
    # день — то есть за тот срок, когда мороз и так запирает всех дома
    лучшее = max((npc.знаю_место(м.имя) * min(1.0, м.богатство)
                  for м in МЕСТА if место_доступно(h, npc, м)), default=0.0)
    return clamp(max(лучшее, свой) * h.B["кража_вес_улицы"], 0.0, 1.0)


def most_needed(npc):
    """Чего у человека меньше всего в днях — то и пойдёт просить.

    Переехавший к соседу дрова не просит: печку топит хозяин, а всё, что гость
    приносит, к этой же печке и уходит. Пока топливо считалось и ему, треть
    всех просьб о дровах в доме шла от людей, которые сидят у чужой горячей печи.
    """
    ресурсы = ("еда", "вода", "топливо") if npc.топит_сам() else ("еда", "вода")
    return min(ресурсы, key=lambda r: npc.days_of(r))


