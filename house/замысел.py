# -*- coding: utf-8 -*-
"""Замысел: цель, которая живёт дольше одного дня (GDD 12.1).

До сих пор человек пересчитывал всё заново в каждом слоте: дольше дня жили
ровно две вещи — обещание соседу и заказ мастеру. Поэтому дом читался как
лента поступков, а не как история: никто ничего не добивался, каждый только
отвечал на сегодняшнее состояние своего тела.

Замысел — не приказ и не расписание. Это перевес: он подкрашивает оценки
в `actions.gather` и держится, пока не выполнен, не брошен или не перебит
нуждой. Кончилась вода — замысел спит, человек идёт топить снег; отпустило —
вернулся. Если нужда держится дольше `замысел_терпит_дней`, замысел брошен
совсем, и это тоже история: человек, который месяц собирался утеплить окна
и так и не собрался.

Пять видов, и один из них отличается от прочих: у `рассорить` цель — не вещь
и не стены, а другие люди, и потому он единственный, который делает дом
непредсказуемым.
"""
from .util import clamp, norm

# Какие действия подкрашивает каждый замысел и насколько. Множитель к
# `замысел_вес`: тройка значит «это и есть то, ради чего я живу», единица —
# «по пути пригодится».
ПОДКРАШИВАЕТ = {
    "тепло":     {"утепление": 3.0, "буржуйка": 2.6, "дверь": 1.4, "топить": 1.2,
                  "заказать": 1.6, "генератор_собрать": 1.2, "костёр": 0.8},
    "запас":     {"вылазка": 2.4, "кладовая": 2.2, "обмен": 1.6, "вскрыть_кладовую": 1.0,
                  "разбор": 1.0, "попросить": 0.8},
    "угол":      {"занять": 3.0, "разбор": 1.8, "переехать": 1.4, "утепление": 0.8},
    "рассорить": {"шепнуть": 3.0, "подбросить": 2.6, "наблюдение": 1.4, "разговор": 0.8},
    "уйти":      {"уйти": 3.0, "одежда": 2.0, "вылазка": 1.2, "кладовая": 1.2},
}

НАЗВАНИЕ = {
    "тепло":     "чтобы дома всегда было тепло",
    "запас":     "набить шкаф и перестать считать дни",
    "угол":      "перебраться туда, где стены целы",
    "рассорить": "стравить этих двоих",
    "уйти":      "собраться и уйти",
}


# ---------------------------------------------------------------- выбор

def оценки(h, npc):
    """Чего этому человеку хочется добиваться. Возвращает {вид: оценка}."""
    b = h.B
    # мерка тепла — ночная, а не дневная: печку во сне никто не топит,
    # и «я не хочу больше мёрзнуть» — это про то, каким человек просыпается,
    # а не про то, как тепло у него, пока горит буржуйка
    ночью = h.room_temp(npc, burning=False)
    еды = npc.days_of("еда")
    о = {}

    # тепло: не «мне сейчас холодно», а «я не хочу больше мёрзнуть никогда»
    о["тепло"] = ((b["комфортная_температура"] - ночью) * b["замысел_тепло_за_градус"]
                  + npc.пунктик("замысел_тепло")
                  + (1.5 if npc.dependents else 0.0)
                  + npc.вес_черт("утепление"))

    # запас: черта запасливого и горизонт, а не сегодняшний голод
    # горизонт бывает и в двадцать пять дней, и тогда одна эта строка
    # перевешивает всё остальное вместе взятое: замысел «набить шкаф»
    # брали пятеро из шести и всегда. Потолок — чтобы запасливость оставалась
    # чертой характера, а не единственным, чего в этом доме можно хотеть
    о["запас"] = (min(b["замысел_запас_потолок"], (npc.horizon - еды))
                  * b["замысел_запас_за_день"]
                  + npc.t01("жадность") * 2.0
                  + npc.пунктик("замысел_запас"))

    # угол: своя квартира против лучшей из пустых, глазами хозяина
    своя = h.flats[npc.apt]
    лучшая = max((h.ценность_жилья(f, npc) for f in h.пустые_для(npc)), default=None)
    if лучшая is not None and not npc.living_with:
        # привязанность к своим стенам держит замысел слабее, чем сам переезд:
        # собраться и решиться — разные вещи, и первое дешевле
        о["угол"] = ((лучшая - h.ценность_жилья(своя, npc)) * b["замысел_угол_вес"]
                     - своя.вложено * b["жильё_привязанность"] * b["замысел_угол_привязанность"])

    # уйти: только если знает куда, и только когда терять уже нечего
    if npc.знает_пункт:
        о["уйти"] = (npc.desperation() * b["замысел_уйти_за_отчаяние"]
                     - своя.вложено * b["жильё_привязанность"]
                     - npc.dependents * 1.0
                     - b["замысел_уйти_решимость"])

    # рассорить: единственный замысел про людей. Берут его не от злобы вообще,
    # а от злобы на того, с кем самому не справиться, — потому и приходится
    # чужими руками
    враг = кого_ненавидит(h, npc)
    if враг is not None:
        слабее = clamp(npc.видимая_сила(враг) / max(0.3, npc.power()) - 1.0, 0.0, 2.0)
        о["рассорить"] = ((b["обида_вес_мести"] if враг.id in npc.не_прощу else 0.0)
                          + npc.hate.get(враг.id, 0.0) * b["замысел_рассорить_за_злость"]
                          + слабее * b["замысел_рассорить_за_бессилие"]
                          + npc.пунктик("замысел_рассорить")
                          - b["замысел_рассорить_решимость"])
    return о


def кого_ненавидит(h, npc):
    """Тот, на кого у него больше всего зла, — и он ещё жив.

    Непрощённый идёт первым, и это не то же самое, что самый ненавистный:
    злость оседает каждый день сама собой, а вынесенную квартиру помнят
    до конца метели.
    """
    враги = [t for t in h.others(npc)
             if npc.hate.get(t.id, 0.0) > 0 or t.id in npc.не_прощу]
    return max(враги, key=lambda t: (t.id in npc.не_прощу,
                                     npc.hate.get(t.id, 0.0)), default=None)


def кому_шептать(h, npc, враг):
    """Кому выгоднее всего наговорить на врага.

    Не всякому, а тому, чей разрыв с врагом дороже всего стоит: чем ближе
    эти двое, тем больнее их развести. Умный это понимает, глупый идёт
    к тому, кто просто под рукой.
    """
    from . import social
    кандидаты = [t for t in h.others(npc)
                 if t.id != враг.id and not t.away
                 and not (t.id in npc.не_жилец)
                 # и не тому, кому он это уже говорил. Правило то же, что
                 # у наговора в разговоре: наговор — это разговор, а не
                 # ежедневная сводка. Пока его здесь не было, заговорщик
                 # шептал одному и тому же соседу про одного и того же врага
                 # изо дня в день, и дом ловил его на одном и том же вранье
                 # по нескольку раз за метель
                 and not social.уже_говорил(npc, t, "человек", враг.id)]
    if not кандидаты:
        return None
    if npc.t01("сообразительность") >= h.B["замысел_умный_порог"]:
        return max(кандидаты, key=lambda t: (t.свой(враг.id), t.trust.get(враг.id, 3.0)))
    return max(кандидаты, key=lambda t: npc.свой(t.id))


def выбрать(h, npc):
    """Раз в день: не пора ли за что-нибудь взяться. Ничего не возвращает."""
    b = h.B
    if npc.замысел is not None or (npc.dependents and npc.health < 40):
        return
    if h.day < b["замысел_не_раньше"]:
        return
    if not h.rng.chance(b["замысел_шанс_в_день"]):
        return
    о = оценки(h, npc)
    вид = max(о, key=lambda k: о[k], default=None)
    if вид is None or о[вид] < b["замысел_порог"]:
        return
    # нужда не мешает ЗАДУМАТЬ — она мешает делать (см. `утро`). Но задумать
    # в нужде можно не всё: клеить окна с пустой флягой не собираются, а вот
    # набить шкаф или уйти отсюда — это и есть ответ на нужду
    if мешает_нужда(h, npc) and вид not in ("запас", "уйти"):
        return
    npc.замысел = {"вид": вид, "с_дня": h.day, "напор": 0.0, "ходов": 0,
                   "спал": 0, "враг": None, "жертва": None}
    if вид == "рассорить":
        враг = кого_ненавидит(h, npc)
        if враг is None:
            npc.замысел = None
            return
        npc.замысел["враг"] = враг.id
    h.bump("замыслов_принято")
    h.bump("замысел_" + вид)
    npc.stats["замыслов"] = npc.stats.get("замыслов", 0) + 1


# ---------------------------------------------------------------- жизнь замысла

def мешает_нужда(h, npc):
    """Нужда, которая перебивает любой замысел: пить, есть, лечиться.

    Перебивает, а не отменяет: человек, у которого кончилась вода, идёт
    топить снег, а не клеить окна, — и это не значит, что он раздумал клеить.
    """
    b = h.B
    return (npc.desperation() >= b["замысел_нужда"]
            or npc.невмоготу() >= b["замысел_невмоготу"]
            or npc.health < b["замысел_здоровье"])


def спит(h, npc):
    """Спит ли замысел сегодня."""
    return npc.замысел is not None and npc.замысел.get("сегодня_спит", False)


def утро(h, npc):
    """Раз в день: замысел спит, продолжается, выполнен или брошен."""
    b = h.B
    з = npc.замысел
    if з is None:
        выбрать(h, npc)
        return
    # напор оседает сам собой: тихий день гасит подозрения
    з["напор"] = max(0.0, з["напор"] - b["напор_оседает"])
    з["сегодня_спит"] = мешает_нужда(h, npc)
    if з["сегодня_спит"]:
        з["спал"] += 1
        if з["спал"] >= b["замысел_терпит_дней"]:
            бросить(h, npc, "так и не собрался")
        return
    з["спал"] = 0
    if выполнен(h, npc, з):
        h.bump("замыслов_исполнено")
        h.journal.line(f"{npc.short}: {НАЗВАНИЕ[з['вид']]} — сделано.", 0)
        npc.замысел = None


def выполнен(h, npc, з):
    """Достигнута ли цель. У каждого вида своя мерка."""
    b = h.B
    вид = з["вид"]
    if вид == "тепло":
        return h.room_temp(npc, burning=True) >= b["замысел_тепло_цель"]
    if вид == "запас":
        return npc.days_of("еда") >= npc.horizon and npc.days_of("топливо") >= b["замысел_запас_дров"]
    if вид == "угол":
        # он либо переехал, либо занял: и то и другое видно по тому, что
        # своя квартира перестала быть худшей
        лучшая = max((h.ценность_жилья(f, npc) for f in h.пустые_для(npc)), default=None)
        return лучшая is None or лучшая <= h.ценность_жилья(h.flats[npc.apt], npc)
    if вид == "рассорить":
        враг = h.get(з["враг"])
        if враг is None or not (враг.alive and not враг.exiled):
            return True          # с врагом разобрались и без него
        # цель — не убить, а поссорить: кто-то из дома должен возненавидеть его
        return any(t.hate.get(враг.id, 0.0) >= b["замысел_ссора_цель"]
                   for t in h.others(npc) if t.id != враг.id)
    if вид == "уйти":
        return False             # он кончается только уходом
    return False


def бросить(h, npc, почему):
    з = npc.замысел
    if з is None:
        return
    h.bump("замыслов_брошено")
    h.journal.line(f"{npc.short}: {НАЗВАНИЕ[з['вид']]} — {почему}.", 0)
    npc.замысел = None


# ---------------------------------------------------------------- влияние на выбор

def вес(h, npc, key):
    """Насколько замысел подталкивает вот к этому действию."""
    з = npc.замысел
    if з is None or з.get("сегодня_спит"):
        return 0.0
    к = ПОДКРАШИВАЕТ.get(з["вид"], {}).get(key)
    if not к:
        return 0.0
    return к * h.B["замысел_вес"]


# ---------------------------------------------------------------- рассорить

def напор_виден(h, npc):
    """Не пора ли дому заподозрить, что кто-то тут ведёт свою игру.

    Цена за напор, и она одна на оба способа. Умный чувствует её и выжидает,
    глупый — нет: он делает ход каждый день, и его раскусывают почти всегда.
    Раскрытым при этом оказывается не оболганный, а сам заговорщик, со всей
    ненавистью, которую он копил на других.
    """
    from . import social
    з = npc.замысел
    if з is None or з["вид"] != "рассорить":
        return False
    if not h.rng.chance(з["напор"] * h.B["напор_шанс_раскрыть"]):
        return False
    враг = h.get(з["враг"])
    свидетели = [t for t in h.others(npc) if t.id != npc.id]
    for t in свидетели:
        social.adjust(t, npc.id, hate=h.B["напор_ненависть"], trust=-2.0, aware=20)
        social.отдалились(t, npc.id, h.B["близость_за_обиду"])
        if враг is not None and t.id == враг.id:
            social.adjust(t, npc.id, hate=h.B["напор_ненависть"])
    h.bump("заговорщиков_раскрыто")
    social.register_incident(h, "заговор", None)
    h.journal.line(f"В подъезде сложили одно к одному: всё, что в последние дни "
                   f"говорили друг про друга, шло через {npc.form('acc')}.", 2)
    h.note(f"{npc.short} раскрыт как заговорщик")
    бросить(h, npc, "раскрыт")
    return True


def осторожность(h, npc):
    """Сколько напора этот человек готов себе позволить.

    Умный держит себя в руках и ждёт; глупый лезет каждый день. Это и есть
    единственная разница между двумя способами вести интригу — не в том,
    что они делают, а в том, когда останавливаются.
    """
    return h.B["напор_потолок"] * (0.35 + 0.65 * (1.0 - npc.t01("сообразительность")))
