# -*- coding: utf-8 -*-
"""Метель, инфраструктура и события (GDD 3, 21).

Три типа событий, как в документе:
  1) скриптовые по дням — одинаковы в каждой жизни;
  2) порождённые симуляцией — их делают сами люди (это не здесь, это в actions/conflict);
  3) внешние случайные — меняют условия, но никогда не убивают сами по себе.
"""
from .util import clamp


def build_calendar(h, events_data, days):
    """Составить календарь внешних событий на всю жизнь заранее (GDD 21).

    Один раз, своим потоком случайности, до первого действия. Тогда вмешательство
    игрока меняет дом, но не погоду — и повтор жизни ощущается честным.

    На каждый день заготавливается не одно событие, а до трёх по весу: у события
    может быть условие («после первой смерти», «если в доме есть раненый»),
    и если первое не подходит, срабатывает следующее. Все кубики брошены здесь,
    поэтому условия читают состояние дома, а поток случайности от этого не
    съезжает — иначе одно чужое решение сдвинуло бы весь календарь.
    """
    rng = h.rng.branch("мир")
    календарь = {}
    использованные = set()
    for день in range(1, days + 1):
        подходят = [ev for ev in events_data.get("случайные", [])
                    if ev.get("окно", [1, 99])[0] <= день <= ev.get("окно", [1, 99])[1]]
        свежие = [ev for ev in подходят if ev["id"] not in использованные]
        if not свежие:
            # набор исчерпан — можно снова с начала (GDD 21: повторов быть
            # не должно, пока игрок не увидел всё)
            использованные.clear()
            свежие = подходят
        if not свежие or not rng.chance(h.B["шанс_случайного_события"]):
            continue
        кандидаты = []
        пул = [(ev, ev.get("вес", 5)) for ev in свежие]
        for _ in range(3):
            if not пул:
                break
            ev = rng.weighted(пул)
            кандидаты.append(ev["id"])
            пул = [(e, w) for e, w in пул if e["id"] != ev["id"]]
        использованные.add(кандидаты[0])
        календарь[день] = кандидаты
    h.mods["календарь"] = календарь
    build_weather(h, days)


def build_weather(h, days):
    """Календарь погодных режимов (GDD 3, 21).

    Метель — не одна прямая. Буран на третий день делает из −14 сразу −24,
    и выйти нельзя никому; через день-два он стихает и оставляет после себя
    затишье — день, когда решается неделя: кто вышел, тот доживёт.

    База при этом продолжает падать, поэтому затишье к концу метели уже
    не спасает: +5 к −33 — это всё равно −28.
    """
    b = h.B
    rng = h.rng.branch("погода")
    календарь = {}
    день = 1
    последний = -99
    while день <= days:
        if день < b["буран_не_раньше"] or день - последний < b["погода_перерыв_дней"]:
            день += 1
            continue
        if rng.chance(b["буран_шанс_в_день"]):
            сколько = rng.rint(b["буран_дней_мин"], b["буран_дней_макс"])
            сдвиг = rng.uni(b["буран_градусов_мин"], b["буран_градусов_макс"])
            for i in range(сколько):
                if день + i <= days:
                    календарь[день + i] = ("буран", сдвиг)
            # после бурана ветер меняется, и это то самое затишье
            затих = день + сколько
            if rng.chance(b["затишье_после_бурана"]) and затих <= days:
                тихих = rng.rint(b["затишье_дней_мин"], b["затишье_дней_макс"])
                тепло = rng.uni(b["затишье_градусов_мин"], b["затишье_градусов_макс"])
                for i in range(тихих):
                    if затих + i <= days:
                        календарь[затих + i] = ("затишье", тепло)
                сколько += тихих
            последний = день + сколько
            день = последний
            continue
        if rng.chance(b["затишье_шанс_в_день"]):
            тихих = rng.rint(b["затишье_дней_мин"], b["затишье_дней_макс"])
            тепло = rng.uni(b["затишье_градусов_мин"], b["затишье_градусов_макс"])
            for i in range(тихих):
                if день + i <= days:
                    календарь[день + i] = ("затишье", тепло)
            последний = день + тихих
            день = последний
            continue
        день += 1
    h.mods["погода_календарь"] = календарь


def start_of_day(h, events_data):
    """Новое утро: погода, отключения, события."""
    h.day += 1
    b = h.B

    _tick_mods(h)

    # район выгребают не только эти шестеро: магазин на Заречной обирает весь
    # квартал, а гаражи за домом — почти никто. Поэтому магазин пустеет сам
    # собой, и через неделю очевидное место перестаёт быть лучшим
    from .actions import МЕСТА
    for м in МЕСТА:
        h.места[м.имя] = max(b["вылазка_минимум_богатства"],
                             h.богатство_места(м.имя) - b["вылазка_район_чистит"] * м.район)

    # --- температура (GDD 3: падает с каждым днём) ---
    base = b["температура_день1"] - b["температура_падение_в_день"] * (h.day - 1)
    режим, погода_сдвиг = h.mods.get("погода_календарь", {}).get(h.day, ("метель", 0.0))
    h.mods["режим"] = режим
    h.outside = base + h.mods.get("температура_сдвиг", 0.0) + погода_сдвиг
    if режим != h.mods.get("режим_вчера", "метель"):
        h.mods["режим_вчера"] = режим
        if режим == "буран":
            h.journal.line("Поднялся буран. За окном белая стена, слышно только ветер "
                           "в шахте лифта.", 2)
            h.note("буран")
        elif режим == "затишье":
            h.journal.line("К утру метель осела. Стало слышно двор — и стало видно, "
                           "кто выходит.", 2)
            h.note("затишье")
        else:
            h.journal.line("Ветер вернулся к обычному.", 1)

    # --- расписание отключений (GDD 21, скриптовые события) ---
    # каждое отключение — событие, а не ежедневное слагаемое: холодные батареи
    # роняют привычное в тот день, когда они остыли, и дальше человек к этому
    # притерпевается (см. social.видел и engine._morning)
    было = (h.heating, h.water_on, h.power_on, h.network > 0)
    if h.day >= b["день_отключения_отопления"]:
        h.heating = False
    if h.day >= b["день_отключения_воды"]:
        h.water_on = False
    if h.day >= b["день_отключения_электричества"]:
        h.power_on = False
    # GDD 19: «После дня 0 связь деградирует… к дню 10 сеть исчезает совсем».
    # Раньше первые шесть дней связь была идеальной, и деградация начиналась
    # только с седьмого — то есть «после дня 0» не выполнялось
    if h.day >= b["день_потери_связи"]:
        h.network = 0.0
    else:
        h.network = clamp(1.0 - h.day / float(b["день_потери_связи"]), 0.0, 1.0)

    стало = (h.heating, h.water_on, h.power_on, h.network > 0)
    погасло = sum(1 for a, c in zip(было, стало) if a and not c)
    if погасло:
        from .social import видел, громкое
        громкое(h)
        for p in h.alive():
            видел(h, p, погасло * b["нормальность_за_отключение"])

    # --- скриптовое событие дня ---
    # GDD 21: «одинаковы в каждой жизни, ЕСЛИ ИГРОК НЕ ВМЕШАЛСЯ». Значит,
    # у события может быть условие отмены — иначе «эпидемия, если игрок
    # не помог медику» непроверяема, а именно она и названа в документе
    for ev in events_data.get("скриптовые", []):
        if ev["день"] != h.day:
            continue
        if _отменено(h, ev.get("отменяется_если")):
            h.journal.line(ev.get("текст_отмены", "…обошлось."), 1)
            h.bump("событий_отменено")
            continue
        h.journal.event(ev["текст"], scripted=True)
        apply_effects(h, ev.get("эффекты", {}))

    # --- случайное внешнее событие ---
    _roll_random_event(h, events_data)


def условие_верно(h, условие):
    """Выполнено ли условие события.

    Одна дверь на два случая: `отменяется_если` у скриптового события и
    `условие` у случайного. Второе — то, ради чего событиям вообще нужны
    условия: тогда они отвечают на то, что дом уже сделал, а не сыплются
    независимо от него (GDD 21).

    Виды перечислены в engine.УСЛОВИЯ и проверяются при загрузке: условие,
    которого никто не понимает, тихо считалось бы невыполненным.
    """
    if not условие:
        return False
    from .social import recent_incidents
    вид = условие.get("вид")
    if вид == "жив_с_умением":
        return any(условие["умение"] in p.skills and p.health > условие.get("здоровье", 40)
                   for p in h.alive())
    if вид == "нет_происшествий":
        return recent_incidents(h, условие.get("дней", 5)) == 0
    if вид == "было_происшествие":
        return recent_incidents(h, условие.get("дней", 5)) > 0
    if вид == "все_в_тепле":
        return all(p.warmth > условие.get("тепло", 45) for p in h.alive())
    if вид == "была_смерть":
        return bool(h.stats.get("смертей"))
    if вид == "есть_раненый":
        return any(p.injuries or p.sick for p in h.alive())
    if вид == "пусто_снаружи":
        from .actions import МЕСТА
        порог = условие.get("осталось", 0.45)
        return all(h.богатство_места(м.имя) <= порог for м in МЕСТА)
    if вид == "есть_пустая_квартира":
        return len(h.пустые()) >= условие.get("сколько", 1)
    if вид == "холоднее":
        return h.outside <= условие.get("градусов", -25)
    if вид == "мало_живых":
        return len(h.alive()) <= условие.get("сколько", 3)
    if вид == "есть_тело":
        return any(f.body and f.body.get("порций", 0) > 0 for f in h.пустые())
    if вид == "режим":
        return h.mods.get("режим") == условие.get("какой", "буран")
    if вид == "подъезд_открыт":
        # заколоченная общими силами дверь — единственное, что дом может
        # сделать против улицы (см. meeting: «не пускать чужих»)
        return h.day - h.mods.get("подъезд_заколочен", -99) > h.B["дверь_подъезда_дней"]
    return False


def _отменено(h, условие):
    """Сработало ли условие отмены скриптового события."""
    return условие_верно(h, условие)


def _tick_mods(h):
    """Уменьшить срок действия временных модификаторов."""
    for key in ("температура_дней", "опасность_дней"):
        if h.mods.get(key, 0) > 0:
            h.mods[key] -= 1
            if h.mods[key] <= 0:
                if key == "температура_дней":
                    h.mods["температура_сдвиг"] = 0.0
                else:
                    h.mods["опасность_множитель"] = 1.0


def _roll_random_event(h, events_data):
    """Событие дня берётся из календаря, составленного до начала жизни.

    На день заготовлено до трёх кандидатов: срабатывает первый, чьё условие
    выполнено. Если ни одно не подходит — день проходит без события, и это
    правильно: «чужие ломятся в квартиру умершего» не должно случаться в доме,
    где ещё никто не умер.
    """
    кандидаты = h.mods.get("календарь", {}).get(h.day) or []
    if isinstance(кандидаты, str):
        кандидаты = [кандидаты]
    по_id = {ev["id"]: ev for ev in events_data.get("случайные", [])}
    for eid in кандидаты:
        ev = по_id.get(eid)
        if not ev:
            continue
        if ev.get("условие") and not условие_верно(h, ev["условие"]):
            h.bump("событий_не_подошло")
            continue
        h.journal.event(ev["текст"])
        apply_effects(h, ev.get("эффекты", {}))
        h.bump("событий_случилось")
        return


def apply_effects(h, eff):
    """Применить эффекты события ко всему дому."""
    from .social import spread_panic

    if "паника" in eff:
        for p in h.alive():
            spread = eff["паника"] * (0.7 + 0.6 * p.t01("вспыльчивость"))
            from .social import add_panic
            add_panic(p, spread)
    if "настроение" in eff:
        for p in h.alive():
            p.mood = clamp(p.mood + eff["настроение"])
    if "богатство" in eff:
        h.scav_richness = clamp(h.scav_richness + eff["богатство"], 0.0, 1.6)
    if "связь" in eff:
        h.network = clamp(h.network + eff["связь"], 0.0, 1.0)
    if "температура" in eff:
        # GDD 21: внешнее событие «никогда не убивает само по себе». Поэтому
        # похолодание бьёт по улице, но не проламывает то, что человек успел
        # построить: у сдвига есть предел, и он тем меньше, чем лучше утеплена
        # квартира. Раньше одно похолодание стоило дому полчеловека выживших
        t = eff["температура"]
        сдвиг = t["градусов"]
        if сдвиг < 0:
            сдвиг = max(сдвиг, -h.B["событие_холод_потолок"])
        h.mods["температура_сдвиг"] = сдвиг
        h.mods["температура_дней"] = t["дней"]
        h.outside += сдвиг
    if "опасность_вылазки" in eff:
        d = eff["опасность_вылазки"]
        h.mods["опасность_множитель"] = d["множитель"]
        h.mods["опасность_дней"] = d["дней"]
    if eff.get("укрепление_порыв"):
        h.mods["укрепление_порыв"] = h.day
    if "нормальность" in eff:
        # чужие в подъезде, стук в дверь ночью, крик за стеной: это дёшево
        # и сильно бьёт по тому, что человек считает обычной жизнью (GDD 11)
        from .social import видел, громкое
        громкое(h)
        for p in h.alive():
            видел(h, p, eff["нормальность"])
    if "болезнь_шанс" in eff:
        for p in h.alive():
            risk = eff["болезнь_шанс"] * (1.4 if p.warmth < 40 else 1.0) * (1.3 if p.satiety < 35 else 1.0)
            if not p.sick and h.rng.chance(risk):
                p.sick = "простуда"
                h.journal.line(f"{p.label()} слёг: жар, кашель.", 1)
    if eff.get("кража_в_доме"):
        _scripted_theft(h)
    if eff.get("смерть_от_холода"):
        _scripted_cold_death(h)
    spread_panic(h)


def _scripted_theft(h):
    """GDD 21: «день 5 — первая кража в доме».

    Скриптовое событие должно уметь запускать происшествие, а не только двигать
    шкалы: смысл этого слоя по документу — «игрок учит расписание и вмешивается»,
    а вмешаться в прибавку паники нельзя. Если дом уже обворовали сам собой,
    сценарий молчит — расписание задаёт первый раз, а не лишний.
    """
    from . import conflict
    if h.stats.get("краж") or h.stats.get("попыток_кражи"):
        return
    люди = h.alive()
    if len(люди) < 2:
        return
    вор = max(люди, key=lambda p: p.trait("жадность") - p.trait("лояльность") + p.desperation() * 3)
    # в свою же квартиру не влезают: у соседа по комнате не крадут, к нему
    # просто протягивают руку — а это уже другой поступок, и его в игре нет
    from .social import под_одной_крышей
    цели = [p for p in люди if p.id != вор.id and not под_одной_крышей(h, вор, p)]
    if not цели:
        return
    жертва = max(цели, key=lambda p: вор.loot_value(p.id))
    conflict.steal(h, вор, жертва)


def _scripted_cold_death(h):
    """GDD 21: «день 14 — смерть первого соседа от холода».

    Тоже только если дом ещё никого не потерял: расписание — это то, что
    случается «если игрок не вмешался», а не добавка к уже случившемуся.
    """
    from . import conflict
    from .util import vb
    if h.stats.get("смертей"):
        return
    люди = [p for p in h.alive() if not p.dependents]
    if len(люди) < 3:
        return
    жертва = min(люди, key=lambda p: p.warmth + p.health * 0.5)
    жертва.health = 0.0
    жертва.cause = "холод"
    жертва.died_day = h.day
    h.journal.line(f"† {жертва.name} не {vb(жертва.sex, 'проснулся')}. "
                   f"В квартире было минус четыре.", 2)
    conflict.on_death(h, жертва)


def outing_danger(h):
    """Общий множитель опасности вылазки (собаки, чужие, мороз).

    Улица звереет не сразу. В первые дни там ещё работают магазины, ходят люди
    и никто не отнимает пакет у прохожего: за продуктами выходят просто
    за продуктами. Отбирать и ходить следом начинают тогда же, когда это
    начинается в доме, — и по той же причине (GDD 3, 20).
    """
    m = h.mods.get("опасность_множитель", 1.0) or 1.0
    if h.outside < -22:
        m *= 1.3
    return m


def улица_злая(h):
    """Насколько опасны на улице люди, а не мороз.

    Ноль в первый день и единица примерно к десятому. Мороз, лёд и собаки
    работают с самого начала — поскользнуться и сломать ногу можно и в первый
    день. А вот отбирать пакеты и ходить следом начинают тогда же, когда это
    начинается в доме, и по той же причине: пока магазины ещё работают,
    за продуктами выходят просто за продуктами.
    """
    return clamp((h.day - 1) / float(h.B["опасность_разгон_дней"]), 0.0, 1.0)
