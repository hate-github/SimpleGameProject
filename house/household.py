# ---------------------------------------------------------------- утро и ночь под одной крышей

def дрова_к_печке(h):
    """Утро: всё, что гость принёс за вчера, идёт к хозяйской печке."""
    # всё, что гость принёс за вчера, идёт к общей печке: квартира одна,
    # дрова у неё общие. Пока этого не было, гость копил топливо, которое
    # по правилу «печку топит хозяин» не мог сжечь никогда, и просил ещё
    for p in h.alive():
        if not p.living_with:
            continue
        host = h.get(p.living_with)
        дрова = p.stock.get("топливо", 0.0)
        if host and host.здесь() and дрова > 0:
            host.stock["топливо"] = host.stock.get("топливо", 0.0) + дрова
            p.stock["топливо"] = 0.0
            # и помнит, сколько снёс. Пока этого не было, съезд был
            # единственной сделкой в доме без цены для второй стороны:
            # выставленный на мороз уходил без всего, что принёс сам
            p.снёс_дров += дрова
            h.journal.line(f"{p.short} {vb(p.sex, 'снёс')} дрова к печке "
                           f"{host.form('gen')} ({round(дрова, 1):g}).", 0)


def теснота_ночи(h, p):
    """Ночь в одной комнате: нервы, чужой кашель, общий котёл — и близость."""
    b = h.B
    # теснота: нервы, чужой кашель и общий котёл
    room_mates = len(p.guests) + (1 if p.living_with else 0)
    if room_mates:
        p.mood = clamp(p.mood - b["теснота_настроение"] * room_mates)
        # sorted, а не list: порядок множества строк зависит от PYTHONHASHSEED,
        # а внутри цикла бросается кубик — иначе зерно перестаёт быть зерном
        for other_id in sorted(p.guests) + ([p.living_with] if p.living_with else []):
            o = h.get(other_id)
            if o and o.alive:
                # спать в одной комнате — это и есть история пары,
                # даже если за день не сказано ни слова. Тем и тяжелее
                # потом выставить его на мороз
                social.сблизились(h, p, o, b["близость_под_крышей"])
                # и видят друг друга каждый день, вплотную: от того,
                # как выглядит человек напротив, в одной комнате
                # не спрячешься
                social.встретились(h, p, o)
                # у соседства своя злость, и она копится: ГДД 15 обещает
                # «накопленную злость», из которой растут разъезд,
                # изгнание гостя и нож ночью
                зло = social.теснота(h, p, o, b)
                social.adjust(p, o.id, trust=-b["теснота_доверие"], hate=зло)
                h.stats["ненависть_от_тесноты"] = (
                    h.stats.get("ненависть_от_тесноты", 0.0) + зло)
                # в одной комнате болезнь переходит почти наверняка
                if o.sick and not p.sick and h.rng.chance(b["теснота_зараза"]):
                    p.sick = "простуда"
                    h.journal.line(f"{p.label()} {vb(p.sex, 'слёг')} вслед за соседом по комнате.", 1)
        # соседи видят, что в одной квартире собрались несколько запасов
        for w in h.others(p):
            social.adjust(w, p.id, aware=2.5 * room_mates)


# ---------------------------------------------------------------- переехать

def переезд_с_умыслом(h, npc, host):
    """0..1 — насколько человек просится под эту крышу не греться, а смотреть.

    Одно место на оценку и на память: в оценке переезда это слагаемое, а при
    самом переезде оно записывается на человека — по нему потом видно, кто
    пришёл за теплом, а кто за шкафом (night.оценка_обобрать).

    Появляется только тогда, когда обычная жизнь уже кончилась: чем больше
    у человека рассыпалось привычное, тем спокойнее он смотрит на чужие банки.
    """
    return clamp(npc.loot_value(host.id) / 6.0 * npc.t01("жадность")
                 * (1.0 - npc.t01("лояльность")) * (1.0 - npc.normalcy),
                 0.0, 1.0)


def пустит_к_себе(h, host, гость, b):
    """Решает хозяин: греть двоих дороже, но вдвоём не так страшно.

    Больше нуля — пускает. Как `возьмёт_ребёнка` и `пойдёт_вдвоём`: решение
    ответной стороны названо и лежит рядом с исполнением, а не внутри него.
    """
    yes = host.t01("лояльность") * 5.0 + host.trust.get(гость.id, 3.0) * 0.8
    yes -= host.t01("жадность") * 2.0
    # хозяин считает не «хватит ли мне до конца метели», а «стану ли я
    # от него беднее». Разница решает всё: гость приходит со своими
    # дровами, и в тот же вечер они уходят в общую печку (GDD 15), а печка
    # горит одна на комнату — сколько бы человек в ней ни сидело. С едой
    # иначе: это лишний рот, и он считается полностью.
    #
    # Ту же ловушку уже находили в щедрости: против горизонта, который
    # к третьей неделе просит двадцать шесть дней запаса, не выполняется
    # ничего, и решение подменяется арифметикой. Хозяин отказывал в 96
    # просьбах из ста — за сорок жизней восемь переездов на двести просьб,
    # при том что по GDD 15 без переезда дом до конца метели не доживает
    for res, вес in (("топливо", b["переезд_страх_дров"]),
                     ("еда", b["переезд_страх_еды"])):
        гость_ест = 1.0 if res == "еда" else b["переезд_гость_топит"]
        рты = host.eaters() + гость.eaters() * гость_ест
        на_рот = (0.85 if res == "еда" else 1.0) * рты
        вместе = (host.stock.get(res, 0.0) + гость.stock.get(res, 0.0)) / max(0.2, на_рот)
        станет_хуже = clamp(1.0 - вместе / max(0.5, host.days_of(res)), 0.0, 1.0)
        yes -= станет_хуже * вес
    yes += 2.0 if гость.id in host.allies else 0.0
    yes += 1.5 if гость.dependents else 0.0
    # и то, чего в этом решении не было вовсе: он пускает человека к своему
    # шкафу и засыпает при нём. Судить об этом хозяин может только по тому,
    # что знает: по репутации, по тому, ловили ли гостя на чужом, и по тому,
    # врал ли он ему. Чужой жадности в лицо не видно — оттого предательство
    # и возможно (conflict.обобрать_и_уйти)
    риск = (1.0 - min(1.0, host.trust.get(гость.id, 3.0) / 6.0)) * b["переезд_риск_доверия"]
    риск += min(2.0, гость.поймали) * b["переезд_риск_пойманного"]
    риск += min(2.0, host.не_верю.get(гость.id, 0.0)) * b["переезд_риск_вруна"]
    # и то, насколько всё уже не так, как было: в первую неделю к соседу
    # пускают не думая, на третьей — думая
    риск += (1.0 - host.normalcy) * b["переезд_риск_распада"]
    yes -= риск * (0.5 + host.t01("жадность") * 0.8)
    # и то же самое, чем он потом будет мерить, не выгнать ли его обратно
    yes += social.выгода_соседства(h, host, гость) * b["переезд_вес_выгоды"]
    # в однушке с буржуйкой больше двоих не помещается
    yes -= len(host.guests) * b["теснота_отказ"]
    return yes - b["переезд_согласие"]


def переехать(h, npc, host):
    b = h.B
    if (по_правилу(h, host, "пустить к себе", "пустить", "отказать", пустит_к_себе(h, host, npc, b))
            and len(host.guests) < b["переезд_максимум_гостей"]):
        npc.living_with = host.id
        npc.переехал_день = h.day
        # с чем он сюда шёл — это и решит, встанет ли он тут ночью
        npc.переезд_умысел = переезд_с_умыслом(h, npc, host)
        host.guests.add(npc.id)
        fuel = npc.stock.get("топливо", 0.0)
        host.stock["топливо"] = host.stock.get("топливо", 0.0) + fuel
        npc.stock["топливо"] = 0.0
        social.adjust(npc, host.id, trust=2.0, hate=-20)
        social.adjust(host, npc.id, trust=1.0)
        npc.mood = clamp(npc.mood + 12)
        host.mood = clamp(host.mood + 6)
        h.bump("переездов")
        h.journal.line(f"{npc.short} {vb(npc.sex, 'перебрался')} к {host.form('dat')} "
                       f"в кв.{host.apt} — топят одну печку на двоих.", 2)
        h.note(f"{npc.short} {vb(npc.sex, 'переехал')} к {host.form('dat')}")
        # своя квартира остаётся пустой сама — в ней просто никто не живёт.
        # И её начнут разбирать: вернуться потом может быть некуда
    else:
        social.adjust(npc, host.id, trust=-1.0, hate=10)
        npc.ask_record(host.id)["отказ_переезд"] = h.day
        npc.mood = clamp(npc.mood - 8)
        h.journal.line(f"{npc.short} {vb(npc.sex, 'просил')} пустить к себе. {host.short} не {vb(host.sex, 'пустил')}.", 1)


# ---------------------------------------------------------------- уйти или быть выставленным

def отпустят_со_своим(h, гость, хозяин, b, выгоняют):
    """Дадут ли уходящему унести дрова, которые он сносил к этой печке.

    Вопрос не права, а совести и силы. Поленница лежит в хозяйской прихожей
    и стала общей в то же утро, когда он её принёс; держится за неё не один
    хозяин, а все, кто у этой печки остаётся греться. Спорить с уходящим будут
    тем охотнее, чем меньше в доме дров, и тем неохотнее, чем он страшнее.

    Выселение и съезд считаются одной меркой и разными порогами: выставляя
    человека на мороз, о его дровах вспоминают куда реже, чем провожая.
    """
    остаются = [хозяин] + [h.get(g) for g in sorted(хозяин.guests) if g != гость.id]
    остаются = [o for o in остаются if o and o.здесь()]
    держат = (1.0 - min(1.0, хозяин.secure("топливо"))) * b["дрова_держат_за_нужду"]
    держат += хозяин.hate.get(гость.id, 0.0) / 100.0 * b["дрова_держат_за_злость"]
    держат -= хозяин.t01("лояльность") * b["дрова_отдают_за_совесть"]
    держат -= хозяин.свой(гость.id) * b["дрова_отдают_за_близость"]
    # и то, о чём в такую минуту думают раньше всего: кто из нас сильнее.
    # С тем, кто один стоит всех оставшихся, о поленнице не спорят
    наша = sum(o.power() for o in остаются)
    держат -= clamp(гость.power() / max(0.2, наша) - 0.6, 0.0, 1.4) * b["дрова_отдают_за_силу"]
    держат -= хозяин.боится(гость.id) * b["дрова_отдают_за_страх"]
    порог = b["дрова_порог_выселения"] if выгоняют else b["дрова_порог_съезда"]
    return держат < порог


def забрать_своё(h, гость, хозяин, доля):
    """Сколько дров гость уносит из хозяйской печки, уходя. Одно место на съезд
    и на выселение.

    Каждое утро гость сносил своё топливо к общей печке (дрова_к_печке),
    и до сих пор оно там и оставалось: выставленный на мороз уходил ни с чем,
    хотя половина поленницы была его. Больше того, что он принёс, не унесёт,
    и больше доли того, что осталось у хозяина, — тоже: чужую печку
    не разбирают.
    """
    своё = min(гость.снёс_дров,
               хозяин.stock.get("топливо", 0.0) * доля)
    if своё <= 0.05:
        return 0.0
    хозяин.stock["топливо"] = хозяин.stock.get("топливо", 0.0) - своё
    гость.stock["топливо"] = гость.stock.get("топливо", 0.0) + своё
    гость.снёс_дров = 0.0
    return своё


def съехать(h, npc, host):
    b = h.B
    # своё он забирает — но спросив: поленница уже общая и стоит
    # в хозяйской прихожей. Уходящего по-хорошему держат редко.
    # А сверх своего хозяин даёт на дорогу, если не в ссоре
    дров = (забрать_своё(h, npc, host, b["выгнать_доля_дров"])
            if отпустят_со_своим(h, npc, host, b, выгоняют=False) else 0.0)
    if host.hate.get(npc.id, 0.0) < 40:
        сверх = min(b["выгнать_дров_на_дорогу"], host.stock.get("топливо", 0.0))
        host.stock["топливо"] = host.stock.get("топливо", 0.0) - сверх
        npc.stock["топливо"] = npc.stock.get("топливо", 0.0) + сверх
        дров += сверх
    npc.living_with = None
    host.guests.discard(npc.id)
    occupy_flat(h, npc)
    npc.warmth = clamp(npc.warmth - 8)
    social.adjust(npc, host.id, trust=-0.5)
    social.adjust(host, npc.id, trust=-0.5)
    h.bump("съездов")
    h.journal.line(f"{npc.short} {vb(npc.sex, 'вернулся')} к себе в кв.{npc.apt}"
                   + (f" — {host.short} {vb(host.sex, 'дал')} дров на первое время." if дров
                      else ". Ушёл молча."), 2)
    h.note(f"{npc.short} {vb(npc.sex, 'съехал')} от {host.form('gen')}")


def выгнать(h, npc, гость):
    b = h.B
    # что успел снести к этой печке, то и уносит — если отпустят. Тут
    # спорят всерьёз: дрова уже лежат в хозяйской прихожей, и держится
    # за них не один хозяин, а все, кто у этой печки остаётся греться
    было_чего = гость.снёс_дров
    отдали = отпустят_со_своим(h, гость, npc, b, выгоняют=True)
    унёс = забрать_своё(h, гость, npc, b["выгнать_доля_дров"]) if отдали else 0.0
    if not отдали and было_чего > 0.5:
        # не отдали. Это уже не «разошлись», а счёт, и он из тех,
        # что не проходят от времени
        гость.снёс_дров = 0.0
        social.обидели(h, гость, npc, b["обида_за_дрова"], вслух=False)
        h.bump("дров_не_отдали")
    гость.living_with = None
    npc.guests.discard(гость.id)
    occupy_flat(h, гость)
    гость.warmth = clamp(гость.warmth - 14)
    гость.mood = clamp(гость.mood - 14)
    гость.panic = clamp(гость.panic + 12)
    social.adjust(гость, npc.id, trust=-4.0, hate=b["ненависть_за_выселение"])
    social.adjust(npc, гость.id, trust=-1.0)
    social.отдалились(гость, npc.id, b["близость_за_обиду"])
    h.bump("выселений")
    h.journal.line(f"{npc.short} {vb(npc.sex, 'выставил')} {гость.form('acc')} обратно "
                   f"в кв.{гость.apt}. Разговаривать не о чем."
                   + (f" {гость.short} {vb(гость.sex, 'забрал')} свои дрова "
                      f"({унёс:g})." if унёс
                      else (f" Дрова, которые {гость.short} "
                            f"{vb(гость.sex, 'сносил')} к этой печке, "
                            f"остались у неё." if not отдали and было_чего > 0.5
                            else "")), 2)
    h.note(f"{npc.short} {vb(npc.sex, 'выгнал')} {гость.form('acc')}")
    social.judge(h, npc, ТЕГИ["выгнать"], hate=6.0, trust=-0.8)


# ---------------------------------------------------------------- когда сожительство кончилось

def occupy_flat(h, person):
    """Человек вернулся в свою квартиру: забирает то, что в ней осталось."""
    flat = h.flats.get(person.apt)
    if flat and not (flat.body and flat.body.порций > 0):
        for res, v in list(flat.stock.items()):
            if v:
                person.stock[res] = person.stock.get(res, 0.0) + v
                flat.stock[res] = 0.0
        # оружие — дело conflict; conflict сам зовёт household.cut_ties и
        # occupy_flat, поэтому обратная ссылка здесь ленивая
        from .conflict import подобрать_оружие
        подобрать_оружие(h, person, flat)
        # и связку с гвоздя: погреб приписан к квартире, а не к человеку,
        # и достаётся тому, кто в этих стенах теперь живёт
        if flat.ключи:
            person.ключи_кладовых |= flat.ключи
            for kid in sorted(flat.ключи):
                к = h.кладовые.get(kid)
                if к is not None:
                    h.journal.line(f"   Вместе со стенами {person.form('dat')} "
                                   f"{vb(person.sex, 'достался')} и ключ от {к.имя_род}.", 1)
            flat.ключи = set()
            h.bump("ключей_от_кладовых_по_наследству")


def cut_ties(h, person):
    """Разорвать все связи выбывшего: союзы, сожительство в обе стороны.

    Одно место на смерть и на изгнание. Пока это было только в on_death,
    гость изгнанного навсегда оставался с living_with — а значит, по правилу
    «печку топит хозяин», не мог затопить собственную и замерзал.
    """
    for other in h.people.values():
        other.allies.discard(person.id)
    person.allies.clear()
    for gid in sorted(person.guests):
        g = h.get(gid)
        if g and g.здесь():
            g.living_with = None
            g.warmth = clamp(g.warmth - 15)
            occupy_flat(h, g)
            h.journal.line(f"{g.short} {vb(g.sex, 'вернулся')} в свою выстывшую квартиру.", 1)
        elif g:
            g.living_with = None
    person.guests.clear()
    if person.living_with:
        host = h.get(person.living_with)
        if host:
            host.guests.discard(person.id)
        person.living_with = None
