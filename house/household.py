"""Сожительство: кто у кого греется, что приносит и с чем уходит (GDD 15).

До сих пор это было размазано по трём файлам: переезд, съезд и выселение —
в actions, разрыв связей и возвращение в свою квартиру — в conflict, дрова
гостя и теснота — в engine. Здесь одно понятие целиком: решение хозяина
пустить, снос дров к общей печке, ночь в одной комнате, уход со своим
или без, и то, что остаётся человеку, когда сожительство кончилось.
Исполнители переехать/съехать/выгнать в actions — тонкие, они зовут сюда.
"""
from .util import clamp, vb
