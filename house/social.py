"""Шум, осведомлённость, слухи, отношения и группы.

Сердце социальной части. Ровно то, что в GDD:
  · 13 — шум и наблюдение, из которых растёт осведомлённость;
  · 12.3 — три шкалы: осведомлённость, паника, ненависть, плюс доверие 0-10;
  · 12.4 — группы не заданы заранее, они складываются после первого инцидента;
  · 14 — слово: враньё, которое работает и разоблачается, и обещания.
"""
from .util import clamp, vb

# Что именно выдаёт тот или иной сигнал (GDD 13).
# (ресурс, насколько подрастает оценка, как это выглядит со стороны, заметность)
#
# Заметность — вторая ось из GDD 13 («каждое действие имеет громкость
# и заметность»), и устроена она иначе, чем громкость: дым из окна и пакеты
# в руках видны со двора и с площадки всему дому, по этажам не глохнут,
# зато их скрывают занавески — то есть утепление окон.
NOISE_MEANING = {
    "готовка":     (None, 0.0, "в кв.{apt} гремят посудой", 0.0),
    "буржуйка":    ("топливо", 1.1, "из окна кв.{apt} идёт дым", 0.45),
    "генератор":   ("топливо", 2.2, "в кв.{apt} гудит генератор", 0.55),
    "ремонт":      ("материалы", 1.2, "в кв.{apt} стучат", 0.0),
    "дверь":       ("материалы", 1.4, "в кв.{apt} что-то тяжёлое волокут к двери", 0.15),
    "разбор":      ("материалы", 1.0, "с пустой квартиры тащат доски", 0.35),
    "возвращение": ("еда", 1.6, "{кто} {вернулся} с улицы с пакетами", 0.65),
    "взлом":       (None, 0.0, "в подъезде скрипела чужая дверь", 0.2),
    "ссора":       (None, 0.0, "на лестнице кричали", 0.3),
    "выстрел":     (None, 0.0, "в доме стреляли", 0.0),
    "шаги":        (None, 0.0, "на лестнице шаги", 0.0),
}


# ---------------------------------------------------------------- где человек

def место(h, npc):
    """В какой квартире человек физически находится.

    Переехавший к соседу спит, ест и шумит не у себя: его собственная квартира
    стоит пустая. Пока этого не спрашивали, запах шёл «из кв.20», где никого нет,
    а к его двери приходили с ломом.
    """
    if npc.living_with:
        host = h.people.get(npc.living_with)
        if host and host.alive and not host.exiled:
            return host
    return npc


def своя_топится(h, npc):
    """Может ли человек прямо сейчас протопить собственную квартиру.

    Не «есть ли там буржуйка», а «есть ли там буржуйка и чем её топить».
    Без этой разницы гость, у которого дрова ушли в хозяйскую печь, считает
    свой угол тёплым и уходит замерзать.
    """
    своя = h.flats[npc.apt]
    return bool(своя.shelter.get("буржуйка")) and npc.stock.get("топливо", 0.0) >= 1.0


def выгода_соседства(h, a, партнёр):
    """Насколько выгодно жить с этим человеком в одной квартире.

    Больше нуля — вместе лучше. Одно число на три решения: съезжаться,
    съезжать и выгонять. Так «рациональная часть» получается настоящей:
    поссорились, ненавидят друг друга — но порознь их возьмут поодиночке,
    и оба это считают.
    """
    B = h.B
    своя = h.flats[a.apt]
    общая = h.where(партнёр) if партнёр.apt != a.apt else h.flats[a.apt]
    польза = 0.0
    if общая.apt != своя.apt:
        # гость: разница между хозяйскими стенами и своими, которые он ещё
        # и протопить не сможет, если дрова остались у хозяина
        польза += (h.flat_temp(общая, burning=True, powered=h.power_on)
                   - h.flat_temp(своя, burning=своя_топится(h, a), powered=h.power_on)
                   ) * B["соседство_вес_тепла"]
    else:
        польза += B["соседство_экономия_топлива"]   # одна печь вместо двух
    страх = min(1.5, a.panic / 100.0 + 0.25 * recent_incidents(h))
    польза += партнёр.power() * B["соседство_вес_защиты"] * страх
    if партнёр.id in a.allies:
        польза += 1.0

    цена = B["соседство_теснота"]
    цена += a.hate.get(партнёр.id, 0.0) / B["соседство_ненависть_делитель"]
    цена += max(0.0, 5.0 - a.trust.get(партнёр.id, 3.0)) * 0.4
    if партнёр.sick and not a.sick:
        цена += B["соседство_болезнь"]
    if партнёр.dependents and not a.dependents:
        цена += B["соседство_лишний_рот"] * (1.0 - min(1.0, a.secure("еда")))
    return польза - цена


def под_одной_крышей(h, a, b_npc):
    """Стоят ли эти двое в одной комнате прямо сейчас."""
    return место(h, a).id == место(h, b_npc).id


# ---------------------------------------------------------------- шум

def слышимость(h):
    """Насколько дом слышит и видит сам себя сегодня (GDD 3, 13).

    В буран ветер глушит всё: никто ничего не слышит и не чует, дом на сутки
    становится шестью отдельными квартирами. В затишье слышно каждый шаг на
    лестнице — и именно поэтому в затишье решается неделя.
    """
    режим = h.mods.get("режим")
    if режим == "буран":
        return h.B["буран_шум"]
    if режим == "затишье":
        return h.B["затишье_шум"]
    return 1.0


def emit(h, src, level, kind, night=False, text_for=None):
    """Издать шум. Возвращает список тех, кто услышал.

    level 1..5 (GDD 13: тихо / средне / громко).
    """
    if level <= 0:
        return []
    b = h.B
    base = b["шум_слышимость"].get(str(int(level)), 0.5)
    # дальность зависит от громкости: выстрел слышит весь стояк, шаги — соседняя
    # площадка. Раньше затухание было одинаковым для шёпота и для выстрела,
    # и «громко» из GDD 13 на практике означало меньше половины дома
    дальность = b["шум_дальность"].get(str(int(level)), 1.0)
    видно = NOISE_MEANING.get(kind, (None, 0.0, "", 0.0))[3]
    # погода за окном глушит и звук, и вид: в буран не слышно и не видно ничего
    погода = слышимость(h)
    видно *= погода
    # шумит не человек, а квартира, в которой он сейчас сидит
    дом = место(h, src)
    heard = []
    for other in h.others(src):
        if other.away:
            continue
        # сосед по комнате слышит всё и без броска: он в двух метрах
        if место(h, other).id == дом.id:
            heard.append(other)
            _hear(h, other, src, kind, level, дом)
            continue
        p = base * погода
        p *= b["шум_затухание_на_этаж"] ** (h.floor_gap(дом, место(h, other)) / max(0.35, дальность))
        if night:
            # ночью фон тише: звук идёт дальше, но спящий может его пропустить,
            # а громкое (4-5) будит всех
            p *= b["шум_ночью_множитель"]
            if other.tonight == "спать" and level < 4:
                p *= b["шум_спящий"]
        if дом.shelter.get("звукоизоляция"):
            p *= b["шум_звукоизоляция"]
        # закрытые окна из GDD 13: утеплённые окна и тепло держат, и скрывают
        окна = max(0.35, 1.0 - b["шум_за_утепление"] * дом.shelter.get("утепление", 0))
        p *= окна
        # пустая квартира МЕЖДУ источником и слушателем глушит (GDD 13).
        # Раньше проверялось только соседство с источником, поэтому множитель
        # был одинаков для всех и к третьей неделе включён всегда
        сл = место(h, other)
        лестница = range(min(дом.floor, сл.floor), max(дом.floor, сл.floor) + 1)
        между = sum(1 for f in h.пустые() if f.floor in лестница)
        if между:
            p *= b["шум_пустая_квартира"] ** между
        # заметность идёт своим каналом: по этажам не глохнет, прячут занавески
        замечено = видно > 0 and h.rng.chance(clamp(видно * окна, 0.0, 0.9))
        if h.rng.chance(clamp(p, 0.0, 0.97)) or замечено:
            heard.append(other)
            _hear(h, other, src, kind, level, дом)
    if heard and level >= 4:
        for p in heard:
            p.panic = clamp(p.panic + b["паника_от_громкого_шума"])
    return heard


def smell(h, src, hot=False):
    """Запах готовки идёт по подъезду. Возвращает тех, кто учуял.

    Отличия от звука (GDD 13 — «каждое действие имеет громкость и заметность»):
      · вверх по стояку доходит лучше, чем вниз;
      · звукоизоляция не помогает;
      · спящий учует утром — запах не исчезает вместе со звуком.
    """
    b = h.B
    дом = место(h, src)
    caught = []
    for other in h.others(src):
        if other.away:
            continue
        своя_комната = место(h, other).id == дом.id
        gap = место(h, other).floor - дом.floor
        p = b["запах_база"] * (1.15 if hot else 1.0) * слышимость(h)
        p *= (b["запах_вверх"] ** gap) if gap >= 0 else (b["запах_вниз"] ** abs(gap))
        # тот, кто сидит у той же печки, чует наверняка
        if not своя_комната and not h.rng.chance(clamp(p, 0.0, 0.95)):
            continue
        caught.append(other)
        # «у меня нет еды» — и через час по подъезду тянет его ужином
        проверить_ложь(h, src, other, "своё", "еда")
        adjust(other, src.id, aware=b["запах_осведомлённость"])
        cur = other.believed(src.id, "еда")
        note_signal(other, src.id, "еда", min(cur + 1.8, 7.0), 0.5)
        other.memory.append(f"д{h.day}:учуял:{src.id}")
        # голодный человек, которому пахнет чужим ужином, злится по-настоящему
        hunger = clamp((55 - other.satiety) / 55.0, 0.0, 1.0)
        if hunger > 0.1:
            adjust(other, src.id, hate=b["запах_зависть"] * hunger)
            other.mood = clamp(other.mood - 2.0 * hunger)
            other.panic = clamp(other.panic + 1.5 * hunger)
    # в журнале это событие, а не бытовой шум: пары строк за день достаточно
    seen = h.mods.setdefault("запах_журнал", {})
    if seen.get("день") != h.day:
        seen.clear()
        seen["день"] = h.day
    hungry = [p for p in caught if p.satiety < 55]
    if caught and seen.get("строк", 0) < 2 and (hungry or h.rng.chance(0.35)):
        seen["строк"] = seen.get("строк", 0) + 1
        who = ", ".join(p.short for p in caught)
        tail = " — и это слышно по их лицам" if len(hungry) >= 2 else ""
        h.journal.line(f"По подъезду тянет едой из кв.{дом.apt}. Учуяли: {who}.{tail}", 1)
    return caught


def _hear(h, listener, src, kind, level, дом=None):
    """Услышал — значит узнал. Осведомлённость растёт (GDD 12.3).

    Заодно это и есть сводка дня из GDD 4.4: сосед запоминает не «Виктор
    топил буржуйку», а «из окна кв.14 идёт дым». Формулировки лежат в третьем
    поле NOISE_MEANING — они были написаны, но никогда не показывались.
    """
    b = h.B
    дом = дом or src
    res, hint, как_видно, _видно = NOISE_MEANING.get(kind, (None, 0.0, "", 0.0))
    if как_видно:
        from .util import vb
        строка = как_видно.format(apt=дом.apt, кто=src.short,
                                  вернулся=vb(src.sex, "вернулся"))
        сводка = h.mods.setdefault("сводка", {}).setdefault(listener.id, [])
        if строка not in сводка:
            сводка.append(строка)
    gain = b["осведомлённость_за_шум"] * (0.6 + 0.15 * level)
    adjust(listener, src.id, aware=gain)
    # дым из окна — против «у меня дров нет»
    if kind in ("буржуйка", "генератор"):
        проверить_ложь(h, src, listener, "своё", "топливо")
    # про воду прямых сигналов не бывает — её можно только вывести: у кого
    # горит печь, тот наверняка топит на ней и снег, потому что это выгодно.
    # Догадаться дано не каждому, и это единственное место, где решает
    # сообразительность
    if kind in ("буржуйка", "генератор") and not h.water_on:
        if h.rng.chance(listener.t01("сообразительность") * b["догадка_про_воду"]):
            note_signal(listener, src.id, "вода",
                        min(listener.believed(src.id, "вода") + 1.4, 5.0), 0.35)
            listener.memory.append(f"д{h.day}:догадался:вода:{src.id}")
    if res:
        cur = listener.believed(src.id, res)
        # звук говорит «у него это есть», но не «у него этого гора»:
        # без потолка оценка растёт от каждого чиха и весь дом идёт грабить
        note_signal(listener, src.id, res, min(cur + hint, 6.0), 0.35)
    listener.memory.append(f"д{h.day}:слышал:{kind}:{src.id}")


def note_signal(a, target_id, res, hint_value, weight):
    """Сдвинуть оценку чужих запасов в сторону нового сигнала."""
    e = a.est.setdefault(target_id, {})
    cur = e.get(res, 2.0)
    e[res] = max(0.0, cur * (1.0 - weight) + hint_value * weight)


def observe(h, watcher, target):
    """Наблюдение: подсмотреть, как живёт сосед. Точнее любого шума.

    Заодно это единственный способ увидеть то, что сосед прячет.
    """
    b = h.B
    if target.stock.get("мясо", 0) > 0 and h.rng.chance(0.5):
        from . import conflict
        conflict.reveal_taboo(h, target, witness=watcher)
    adjust(watcher, target.id, aware=b["осведомлённость_за_наблюдение"])
    # увиденный шкаф: самое надёжное разоблачение из всех
    for res in ("еда", "топливо"):
        if target.stock.get(res, 0.0) >= b["ложь_видно_запаса"]:
            проверить_ложь(h, target, watcher, "своё", res)
    for res in ("еда", "топливо", "лекарства", "вода"):
        true_v = target.stock.get(res, 0.0)
        noise = h.rng.uni(0.75, 1.25)
        note_signal(watcher, target.id, res, true_v * noise, 0.75)
    watcher.memory.append(f"д{h.day}:смотрел:{target.id}")


def gossip(h, a, b_npc):
    """Разговор: обмен сведениями. Так осведомлённость расползается по дому."""
    bal = h.B
    # вес слуха — это доверие СЛУШАТЕЛЯ к рассказчику, а не наоборот. Раньше он
    # считался один раз и подставлялся в обе ветки: чем больше я доверял
    # собеседнику, тем охотнее ОН верил моим рассказам
    # и на вес слуха работает то, ловили ли рассказчика на вранье: пойманный
    # однажды теряет вес своих рассказов — в этом и вся цена лжи (GDD 14)
    вес_для_b = (0.25 + 0.05 * b_npc.trust.get(a.id, 3.0)) * вес_слов(b_npc, a)
    вес_для_a = (0.25 + 0.05 * a.trust.get(b_npc.id, 3.0)) * вес_слов(a, b_npc)
    # поговорив с человеком, о котором тебе сказали «он вор», начинаешь
    # понимать, кто из двоих врал. Наговор потому и рискован: он держится
    # ровно до первого нормального разговора с оболганным
    проверить_наговор(h, a, b_npc)
    проверить_наговор(h, b_npc, a)
    потолок = bal["слух_потолок_оценки"]
    for third in h.others(a):
        if third.id == b_npc.id:
            continue
        # рассказываю то, в чём уверен сам
        if a.aware.get(third.id, 0) > b_npc.aware.get(third.id, 0) + 12:
            adjust(b_npc, third.id, aware=bal["осведомлённость_за_слух"])
            for res in ("еда", "топливо", "лекарства"):
                # у пересказа есть потолок: разговоры не могут перевесить личный
                # опыт, иначе дом считает соседей вдвое богаче, чем они есть
                note_signal(b_npc, third.id, res,
                            min(a.believed(third.id, res), потолок), вес_для_b * 0.6)
        # и наоборот
        if b_npc.aware.get(third.id, 0) > a.aware.get(third.id, 0) + 12:
            adjust(a, third.id, aware=bal["осведомлённость_за_слух"])
            for res in ("еда", "топливо", "лекарства"):
                note_signal(a, third.id, res,
                            min(b_npc.believed(third.id, res), потолок), вес_для_a * 0.6)
    # обсуждают и то, у кого можно попросить, а у кого бесполезно
    for third in h.others(a):
        if third.id == b_npc.id:
            continue
        for teller, listener in ((a, b_npc), (b_npc, a)):
            mine = teller.asking.get(third.id)
            if not mine or (mine["дали"] + mine["отказали"]) < 1:
                continue
            theirs = listener.ask_record(third.id)
            # у слухов есть потолок: разговоры не могут перевесить личный опыт
            cap = bal["просьба_память_потолок"]
            if mine["отказали"] > mine["дали"]:
                theirs["отказали"] = min(theirs["отказали"] + 0.5, cap)
            elif mine["дали"] > mine["отказали"]:
                theirs["дали"] = min(theirs["дали"] + 0.5, cap)

    # и то, где ещё что-то осталось: первое, о чём говорят двое, столкнувшись
    # зимой на лестнице. Место только пустеет, поэтому меньшее число знает тот,
    # кто был там позже, — его слово и перевешивает
    известные = list(a.места) + [k for k in b_npc.места if k not in a.места]
    for имя in известные:
        зн_a, зн_b = a.знаю_место(имя), b_npc.знаю_место(имя)
        if зн_a < зн_b:
            b_npc.места[имя] = зн_b + (зн_a - зн_b) * вес_для_b
        elif зн_b < зн_a:
            a.места[имя] = зн_a + (зн_b - зн_a) * вес_для_a

    # чужая ненависть тоже заразна, если доверяешь рассказчику
    for third in h.others(a):
        if third.id == b_npc.id:
            continue
        if a.hate.get(third.id, 0) > 45 and a.trust.get(b_npc.id, 0) >= 5:
            b_npc.hate[third.id] = clamp(b_npc.hate.get(third.id, 0.0) + 5)

    # --- а теперь то, чего у разговора не было: неправда (GDD 14) ---
    for рассказчик, слушатель in ((a, b_npc), (b_npc, a)):
        # ложь о местах: «в магазине пусто» — и сходить туда одному.
        # Идёт после честного обмена, иначе врущий убедит сам себя
        for имя in sorted(рассказчик.места):
            if рассказчик.знаю_место(имя) < bal["ложь_место_порог"]:
                continue
            if слушатель.знаю_место(имя) <= bal["вылазка_пусто_порог"]:
                continue                      # он и так думает, что там нечего брать
            if уже_говорил(рассказчик, слушатель, "место", имя):
                continue
            if not решает_врать(h, рассказчик, слушатель, "место"):
                continue
            слушатель.места[имя] = bal["вылазка_пусто_порог"] * 0.6
            соврал(h, рассказчик, слушатель, "место", имя)
            break
        # ложь о людях: наговор. В общем чате это уже работало, в личном
        # разговоре — нет, хотя именно здесь он и опасен
        мишень = max(h.others(рассказчик),
                     key=lambda t: рассказчик.hate.get(t.id, 0.0), default=None)
        if мишень is None or мишень.id == слушатель.id:
            continue
        if рассказчик.hate.get(мишень.id, 0.0) < bal["наговор_порог_злости"]:
            continue
        if уже_говорил(рассказчик, слушатель, "человек", мишень.id):
            continue
        if not решает_врать(h, рассказчик, слушатель, "человек"):
            continue
        вес = вес_слов(слушатель, рассказчик)
        if слушатель.trust.get(мишень.id, 3.0) >= bal["наговор_защита_доверием"]:
            # слушатель этому человеку верит — и теперь косо смотрит на рассказчика
            adjust(слушатель, рассказчик.id, trust=-0.8, hate=5)
        else:
            adjust(слушатель, мишень.id, hate=bal["наговор_злость"] * вес,
                   trust=-0.5 * вес, aware=4)
            h.mods.setdefault("названы_в_чате", {})[мишень.id] = h.day
        соврал(h, рассказчик, слушатель, "человек", мишень.id)
        h.bump("наговоров")


# ---------------------------------------------------------------- слово (GDD 14)

def решает_врать(h, кто, кому, тема="своё"):
    """Соврёт ли этот человек вот этому — прямо сейчас.

    Не все и не всегда. Врут жадные и смелые (соврать в лицо надо решиться),
    врут тем, кого боятся и кого не любят; и почти не врут, пока жизнь ещё
    похожа на обычную — соседу по площадке врать неловко.

    Вся система сведений построена так, что ложь — сильнейший ход: оценки
    чужих запасов, знание о местах, подозрения после кражи. Поэтому у неё
    должна быть и цена — см. `проверить_ложь`.
    """
    b = h.B
    s = b["ложь_база"]
    s += кто.t01("жадность") * b["ложь_за_жадность"]
    s += кто.t01("храбрость") * b["ложь_за_храбрость"]
    s -= кто.normalcy * b["ложь_за_нормальность"]
    # страх собеседника: сильному соседу проще сказать «у меня нет», чем «не дам»
    s += min(2.0, кому.power() / max(0.3, кто.power())) * b["ложь_за_страх"]
    s -= кто.trust.get(кому.id, 3.0) * b["ложь_за_доверие"]
    s += кто.hate.get(кому.id, 0.0) / 100.0 * b["ложь_за_злость"]
    s += кто.пунктик("ложь")
    if тема == "место":
        s += b["ложь_про_место"]
    elif тема == "человек":
        s += b["ложь_про_человека"]
    return h.rng.chance(clamp(s, 0.0, b["ложь_потолок"]))


def соврал(h, кто, кому, тема, что=None):
    """Записать ложь. Пока её не разоблачили, она работает."""
    кто.врал.append({"кому": кому.id, "тема": тема, "что": что, "день": h.day})
    кто.bump("вранья")
    h.bump("вранья")
    h.journal.secret(f"{кто.short} соврал {кому.form('dat')} ({тема}"
                     + (f": {что})" if что else ")"))


def уже_говорил(кто, кому, тема, что=None):
    """Он ему это уже сказал. Одну и ту же неправду дважды не повторяют:
    наговор — это разговор, а не ежедневная сводка."""
    return any(з["кому"] == кому.id and з["тема"] == тема
               and (что is None or з["что"] == что) for з in кто.врал)


def проверить_ложь(h, кто, кому, тема, что=None):
    """Собеседник узнал правду. Возвращает True, если ложь раскрылась.

    Разоблачается тем же, чем и добывается всё остальное: запахом готовки,
    дымом из окна, увиденным шкафом, собственными ногами на том месте, про
    которое сказали «там пусто».
    """
    b = h.B
    for запись in кто.врал:
        if запись["кому"] != кому.id or запись["тема"] != тема:
            continue
        if что is not None and запись["что"] not in (None, что):
            continue
        if запись.get("раскрыто") or h.day - запись["день"] > b["ложь_память_дней"]:
            continue
        if not h.rng.chance(b["ложь_шанс_раскрыть"]):
            return False
        # запись остаётся: разоблачённая ложь всё равно уже сказана, и второй
        # раз то же самое тому же человеку не говорят
        запись["раскрыто"] = True
        # ложь бьёт по доверию, поэтому весит как кража
        adjust(кому, кто.id, hate=b["ненависть_за_ложь"],
               trust=b["доверие_за_ложь"], aware=15)
        кому.не_верю[кто.id] = кому.не_верю.get(кто.id, 0.0) + 1.0
        кому.memory.append(f"д{h.day}:поймал_на_лжи:{кто.id}")
        h.bump("вранья_раскрыто")
        register_incident(h, "ложь", None)
        h.journal.line(f"{кому.short} {vb(кому.sex, 'понял')}, что {кто.short} "
                       f"{vb(кто.sex, 'соврал')}"
                       + (f" про {что}." if что else "."), 2)
        h.note(f"{кто.short} пойман на вранье ({кому.form('dat')})")
        return True
    return False


def проверить_наговор(h, о_ком, кому):
    """Оболганный сделал что-то доброе — и слушатель понял, кто ему врал.

    Единственный способ разоблачить наговор: не доказательство, а поступок.
    Тот, о ком сказали «он вор», приносит банку — и наговорившему это стоит
    ровно столько же, сколько стоила бы ложь о своих запасах.
    """
    for кто in h.alive():
        if кто.id in (о_ком.id, кому.id):
            continue
        if проверить_ложь(h, кто, кому, "человек", о_ком.id):
            return True
    return False


def вес_слов(слушатель, рассказчик):
    """Насколько вообще стоит верить его рассказам. 0..1.

    Оболгавший однажды теряет вес своих слухов — и это единственное, что
    делает ложь по-настоящему рискованной: не наказание, а то, что тебя
    перестают слушать.
    """
    поймано = слушатель.не_верю.get(рассказчик.id, 0.0)
    if not поймано:
        return 1.0
    B = слушатель._h.B if слушатель._h is not None else {"ложь_вес_слов": 0.4}
    return clamp(1.0 - B["ложь_вес_слов"] * min(2.0, поймано), 0.1, 1.0)


def обещать(h, кто, кому, вид, что=None, дней=None):
    """Отложенное обязательство: кто, кому, что и к какому дню (GDD 14).

    Три вида, и все три опираются на действия, которые уже есть:
      · отдать    — «верну банку к пятнице», из просьбы;
      · сделать   — «поставлю тебе печь», из заказа у мастера;
      · не_делать — «к твоей квартире не подойду», из осады и после ссоры.

    Нарушенное обещание — самый человеческий источник вражды и самая дешёвая
    механика доверия из всех: до сих пор во всей модели не было ни одного
    способа договориться о завтрашнем дне.
    """
    b = h.B
    if дней is None:
        дней = b["обещание_срок_не_делать"] if вид == "не_делать" else b["обещание_срок"]
    # одно обещание одного вида одному человеку за раз
    for о in кто.обещал:
        if о["кому"] == кому.id and о["вид"] == вид:
            return None
    о = {"кому": кому.id, "вид": вид, "что": что, "срок": h.day + дней, "день": h.day}
    кто.обещал.append(о)
    кто.bump("обещаний")
    h.bump("обещаний")
    return о


def сдержал(h, кто, кому, вид, что=None):
    """Обещание выполнено. Доверие сопоставимо с помощью — за это его и дают."""
    b = h.B
    for о in кто.обещал:
        if о["кому"] != кому.id or о["вид"] != вид:
            continue
        if что is not None and о["что"] not in (None, что):
            continue
        кто.обещал.remove(о)
        adjust(кому, кто.id, trust=b["доверие_за_обещание"], hate=-8)
        кому.favors[кто.id] = кому.favors.get(кто.id, 0) + 1
        кто.bump("обещаний_сдержано")
        h.bump("обещаний_сдержано")
        return True
    return False


def нарушил(h, кто, кому, вид, что=None, вслух=True):
    """Слово не сдержано. Помнится долго и мешает договариваться впредь."""
    b = h.B
    for о in list(кто.обещал):
        if о["кому"] != кому.id or о["вид"] != вид:
            continue
        if что is not None and о["что"] not in (None, что):
            continue
        кто.обещал.remove(о)
        adjust(кому, кто.id, hate=b["ненависть_за_нарушение"],
               trust=b["доверие_за_нарушение"])
        кому.не_верю[кто.id] = кому.не_верю.get(кто.id, 0.0) + 1.0
        кто.bump("обещаний_нарушено")
        h.bump("обещаний_нарушено")
        if вслух:
            h.journal.line(f"{кто.short} не {vb(кто.sex, 'сделал')} того, что "
                           f"{vb(кто.sex, 'обещал')} {кому.form('dat')}.", 1)
        return True
    return False


def проверить_обещания(h):
    """Каждый вечер: у кого вышел срок. И заодно — забывание.

    «Не делать» работает наоборот: если срок вышел и человек ничего не сделал,
    слово сдержано.
    """
    b = h.B
    for p in h.alive():
        for о in list(p.обещал):
            if h.day < о["срок"]:
                continue
            кому = h.get(о["кому"])
            if not (кому and кому.alive and not кому.exiled):
                p.обещал.remove(о)
                continue
            if о["вид"] == "не_делать":
                сдержал(h, p, кому, "не_делать", о.get("что"))
            else:
                нарушил(h, p, кому, о["вид"], о.get("что"))
        # старую ложь уже не разоблачить: сказанное неделю назад забылось
        p.врал = [з for з in p.врал if h.day - з["день"] <= b["ложь_память_дней"]]
        for k in list(p.не_верю):
            p.не_верю[k] = max(0.0, p.не_верю[k] - b["не_верю_забывается"])
            if p.не_верю[k] <= 0.0:
                del p.не_верю[k]


# ---------------------------------------------------------------- отношения

def adjust(a, b_npc_id, trust=0.0, hate=0.0, aware=0.0):
    """Все изменения шкал идут через эту дверь.

    Рост затухает: последние проценты доверия и осведомлённости даются тяжело.
    Иначе за пару дней все всё знают и всем доверяют — проверено.
    """
    if trust:
        cur = a.trust.get(b_npc_id, 3.0)
        if trust > 0:
            trust *= max(0.12, 1.0 - cur / 11.0)
        a.trust[b_npc_id] = clamp(cur + trust, 0.0, 10.0)
    if hate:
        # прощение — тоже пунктик: злопамятному добрый поступок стоит дешевле,
        # чем всем остальным (обиду он спишет только частично)
        if hate < 0:
            hate *= clamp(1.0 + a.пунктик("прощение"), 0.0, 2.0)
        a.hate[b_npc_id] = clamp(a.hate.get(b_npc_id, 0.0) + hate)
    if aware:
        cur = a.aware.get(b_npc_id, 0.0)
        if aware > 0:
            aware *= max(0.08, 1.0 - cur / 105.0)
        a.aware[b_npc_id] = clamp(cur + aware)


def add_panic(p, delta):
    """Паника растёт с затуханием: последние проценты набрать трудно.

    Иначе к десятому дню у всех ровно 100 и шкала перестаёт что-либо значить.
    """
    if delta > 0:
        delta *= max(0.15, 1.0 - p.panic / 130.0)
    p.panic = clamp(p.panic + delta)


def recent_incidents(h, window=4):
    """Сколько происшествий было за последние дни. Дом забывает старое."""
    return len([d for d in h.mods.get("происшествия_дни", []) if h.day - d < window])


def напряжение_дома(h, npc):
    """0..1 — «в доме уже неспокойно», глазами этого человека.

    Три вещи, которые он видит и слышит сам: что случилось за последние дни,
    сколько раз ему отказали и насколько в доме уже открыто злы друг на друга.

    Это не его личная нормальность. Дом может трещать вокруг человека, который
    сам ещё держится, — и наоборот; поэтому к соседской двери приглядываются
    не только по своему состоянию, но и по состоянию подъезда.
    """
    b = h.B
    v = recent_incidents(h, 6) * b["напряжение_за_происшествие"]
    v += min(b["напряжение_отказов_потолок"],
             sum(r.get("отказали", 0.0) for r in npc.asking.values())) * b["напряжение_за_отказ"]
    # самая громкая ссора в доме — как её видно с утра (см. engine._morning)
    v += h.mods.get("злость_дома", 0.0) / 100.0 * b["напряжение_за_злость"]
    return clamp(v, 0.0, 1.0)


def spread_panic(h):
    """Чужая паника заражает (GDD 12.3: «паника растёт от чужой паники»)."""
    people = h.alive()
    if len(people) < 2:
        return
    avg = sum(p.panic for p in people) / len(people)
    k = h.B["паника_заражение"]
    for p in people:
        # общительные заражаются сильнее, замкнутые меньше
        p.panic = clamp(p.panic + (avg - p.panic) * k * (0.5 + 0.1 * p.trait("общительность")))


def house_shock(h, panic=0.0, mood=0.0, note=None):
    """Общая встряска дома: смерть, налёт, выстрел."""
    for p in h.alive():
        if panic:
            add_panic(p, panic * (0.7 + 0.6 * p.t01("вспыльчивость")))
        if mood:
            p.mood = clamp(p.mood + mood)
    if note:
        h.journal.line(note, 2)


def judge(h, actor, tag, hate=0.0, trust=0.0, witnesses=None):
    """Дом оценивает поступок. У каждого своя мерка (GDD 12.1, «Ценности»).

    Одно и то же — раздать последнее или отнять на лестнице — для Лиды и для
    Игоря весит по-разному. Без этого «ценности» лежали в данных строкой
    и не значили ничего.
    """
    k = h.B["ценности_вес"]
    for w in (witnesses if witnesses is not None else h.others(actor)):
        if w.id == actor.id:
            continue
        сила = 1.0
        v = w.values or {}
        if tag in (v.get("не_терпит") or ()):
            сила += k
        if tag in (v.get("ценит") or ()):
            сила -= k * 0.5 if hate > 0 else -k
        adjust(w, actor.id, hate=hate * сила, trust=trust * сила)


# ---------------------------------------------------------------- нормальность

def видел(h, witness, вес, кто=None):
    """Человек увидел то, чего в обычной жизни не бывает (GDD 11).

    Одна дверь на все источники: отключение, происшествие, смерть, чужой
    крайний поступок, свой собственный. Вес — насколько это дико; для
    поступков он берётся из `actions.НОРМА`, поэтому заколоченная дверь
    весит меньше, чем разобранная чужая квартира, а та — меньше, чем
    отъём на лестнице.

    Заражение работает через того, кому доверяют. Если дверь заколотил
    уважаемый Пётр — это разрешение для всех: так, значит, уже можно.
    Если Игорь, которого никто не любит, — это не разрешение, а повод его
    бояться, и тогда падает не нормальность, а спокойствие: растёт
    осведомлённость, настороженность и злость.
    """
    b = h.B
    if кто is not None and кто.id != witness.id:
        доверие = witness.trust.get(кто.id, 3.0)
        доля = clamp((доверие - b["заражение_доверие_порог"])
                     / b["заражение_доверие_делитель"], -1.0, 1.0)
        if доля <= 0.0:
            adjust(witness, кто.id, aware=b["заражение_настороженность"] * вес,
                   hate=b["заражение_злость"] * вес * (0.2 - доля))
            add_panic(witness, b["заражение_паника"] * вес)
            h.bump("чужой_пример_испугал")
            return
        вес *= доля
        h.bump("чужой_пример_заразил")
    witness.normalcy = clamp(witness.normalcy - вес * witness.нормальность_скорость,
                             witness.нормальность_пол, 1.0)


def держится(h, witness, кто):
    """Обратный ход: кто-то на виду делает обычные вещи, и это держит дом.

    Носит воду, лечит, выносит тела, латает окна — и у тех, кто ему доверяет,
    привычное перестаёт рассыпаться так быстро. Это ровно то, что должно
    работать для игрока: дом можно держать своим поведением.
    """
    b = h.B
    доверие = witness.trust.get(кто.id, 3.0)
    if доверие < b["опора_доверие"]:
        return
    witness.normalcy = clamp(witness.normalcy + b["опора_прибавка"], 0.0, 1.0)
    h.bump("дом_держали")


def переступил(h, npc, key):
    """Человек сам сделал то, чего раньше не делал.

    Свой поступок меняет сильнее чужого примера и только в первый раз:
    вторая кража — это уже привычка, а не порог.
    """
    from .actions import НОРМА
    вес = НОРМА.get(key, 0.0)
    if вес < h.B["нормальность_дикость_порог"]:
        return
    метка = "переступил_" + key
    if npc.stats.get(метка):
        return
    npc.stats[метка] = 1
    h.bump("переступили")
    видел(h, npc, вес * h.B["нормальность_за_свой_поступок"])


def громкое(h):
    """Пометить, что сегодня в доме что-то случилось. Тишину считают отсюда."""
    h.mods["последнее_громкое"] = h.day


def тихо_ли(h):
    """Три дня ничего не случилось — человек начинает привыкать (GDD 11)."""
    return h.day - h.mods.get("последнее_громкое", -99) >= h.B["нормальность_тишина_дней"]


def register_incident(h, kind, text):
    """Происшествие в доме. После первого дом начинает делиться на группы (GDD 12.4)."""
    h.incidents += 1
    h.mods.setdefault("происшествия_дни", []).append(h.day)
    громкое(h)
    for p in h.alive():
        видел(h, p, h.B["нормальность_за_происшествие"])
    if h.first_incident_day is None:
        h.first_incident_day = h.day
        h.note(f"первое происшествие в доме ({kind}) — дом начал делиться")
    h.bump(f"происшествий_{kind}")
    if text:
        h.journal.line(text, 2)


