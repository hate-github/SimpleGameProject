# -*- coding: utf-8 -*-
"""Ночь: сон, дежурство, кражи, налёт и нож (GDD 4.3 «Ночью происходит основной риск»).

Ночной выбор — такой же слой, как gather днём: каждый решает, что делать
ночью, потом дом разыгрывает налёт, убийства, уходы с хозяйским и кражи —
в этом порядке, и порядок здесь и есть поведение. Оценки ночных поступков
(убить соседа, обобрать хозяина, пойти к чужой двери с группой) — здесь же,
рядом с решением, а не в оркестраторе и не среди драк.
"""
from .util import clamp, norm
from .model import вещи, FIREARMS, Ночь
from . import social, conflict, meeting, world, character, actions


def ночь(h):
    targets = {}
    for p in h.alive():
        mode, target = решение(h, p)
        p.tonight = mode
        targets[p.id] = target

    # налёт — максимум один за ночь и не каждую ночь: после осады дом
    # несколько дней отходит (GDD 16 — рейд это событие, а не быт)
    raid_done = h.day - h.календарь.последний_налёт < h.B["налёт_перерыв_дней"]
    # вожаком налёта становится самый злой и жадный, а не просто самый смелый
    for p in sorted(h.alive(), key=lambda x: -(x.trait("жадность") + x.trait("вспыльчивость")
                                               + x.trait("храбрость") * 0.5 - x.trait("лояльность"))):
        if raid_done or not p.здесь():
            continue
        t = consider_raid(h, p)
        if t:
            p.tonight = Ночь.НАЛЁТ
            conflict.run_siege(h, p, t)
            h.календарь.последний_налёт = h.day
            raid_done = True

    # ночь в общей квартире. До краж: тот, кто на это решился, уже не пойдёт
    # никуда лезть, а дом наутро будет считать совсем другое
    for p in h.rng.shuffled(h.alive()):
        if p.tonight != Ночь.УБИТЬ_СОСЕДА or not p.здесь():
            continue
        c = targets.get(p.id)
        if c and c.здесь() and h.под_одной_крышей(p, c):
            conflict.убить_соседа(h, p, c)

    # обобрать и уйти. После ножа и до краж: тот, кто на это решился,
    # этой ночью больше никуда не пойдёт, а дом наутро считает другое
    for p in h.rng.shuffled(h.alive()):
        if p.tonight != Ночь.ОБОБРАТЬ or not p.здесь():
            continue
        c = targets.get(p.id)
        if c and c.здесь() and p.living_with == c.id:
            conflict.обобрать_и_уйти(h, p, c)

    # кражи. Список составлен до осады, а осада могла кого-то из него убить
    # или выставить на мороз — поэтому проверяем обоих ещё раз
    for p in h.rng.shuffled(h.alive()):
        if p.tonight != Ночь.КРАЖА or not p.здесь():
            continue
        t = targets.get(p.id)
        if t and t.здесь():
            conflict.steal(h, p, t)

    # сон
    for p in h.alive():
        if p.rest < 35 and p.tonight == Ночь.ДЕЖУРИТЬ:
            p.tonight = Ночь.СПАТЬ      # человек просто не выдерживает ещё одну ночь
        if p.rest < 25 and p.tonight in (Ночь.КРАЖА, Ночь.ДЕЖУРИТЬ):
            p.tonight = Ночь.СПАТЬ     # на ногах уже не стоит
        if p.tonight == Ночь.ДЕЖУРИТЬ:
            slept = 4.5
            p.ночей_дежурства += 1
            p.дежурил_ночь = h.day
        elif p.tonight in (Ночь.КРАЖА, Ночь.НАЛЁТ, Ночь.УБИТЬ_СОСЕДА, Ночь.ОБОБРАТЬ):
            slept = 5.5
        else:
            slept = 11.0 if p.rest < 35 else (9.5 if p.rest < 60 else 8.0)
        p.slept = slept
        # обезвоженный спит хуже — это единственное, что GDD 6.1 обещает
        # жажде помимо самой смерти, и до сих пор этого не было
        качество = 1.0 - h.B["сон_за_жажду"] * (1.0 - norm(p.hydration, 15, 70))
        p.rest = clamp(p.rest + slept * h.B["сон_за_час"] * качество
                       - h.B["часов_бодрствования"] * h.B["бодрствование_за_час"])

    # и то, чего в доме до сих пор не могло случиться: смерть, которой
    # никто не заметил. Считается после сна, потому что угорают спящие
    world.угар(h)


def решение(h, p):
    b = h.B
    # как человек себя чувствует этой ночью — та же запись, что и днём
    # (actions.самочувствие): усталость и отчаяние считались здесь заново,
    # и совпадение с дневными числами держалось на том, что формулы одинаковы
    с = actions.самочувствие(h, p)
    opts = [((Ночь.СПАТЬ, None), 2.5 + с.усталость * 6.0)]

    gate = character.norm_gate
    wealth = p.stock.get("еда", 0) * 0.6 + p.stock.get("топливо", 0) * 0.3
    watch = p.panic / 100.0 * 3.0 + social.recent_incidents(h) * 0.8 + wealth * 0.10 - с.усталость * 6.0
    watch += p.обокрали * 2.0
    watch += p.вес_черт("дежурить")
    watch += p.пунктик("дежурить")
    # своя ночь по общему расписанию: это уже не желание, а обязательство
    # перед всеми (см. meeting.проверить_дежурство)
    дежурный = meeting.чья_ночь(h)
    if дежурный is not None and дежурный.id == p.id:
        watch += b["дежурство_обязанность"]
        h.ожидает.дежурил_вчера = p.id
    # с ребёнком всю ночь на лестнице не просидишь: он просыпается,
    # мёрзнет и его надо держать при себе (GDD 12.6)
    if not p.dependents:
        opts.append(((Ночь.ДЕЖУРИТЬ, None), watch * gate(p, "дежурить", b)))

    # тот, с кем он делит комнату: ночью до него два метра и никакой двери
    соседи = ([h.get(p.living_with)] if p.living_with
              else [h.get(g) for g in sorted(p.guests)])
    for c in соседи:
        if not (c and c.здесь()):
            continue
        ночью = (оценка_убийства(h, p, c)
                 + p.пунктик("убить_соседа")
                 + character.своя_мерка(p, "убить_соседа", b))
        opts.append(((Ночь.УБИТЬ_СОСЕДА, c), ночью * gate(p, "убить_соседа", b)))
        # и то, что лежит между «съехать по-хорошему» и ножом: собрать
        # хозяйское и уйти к себе в ту же ночь. Только гостю — хозяину
        # уходить некуда, у него эта квартира и есть
        if p.living_with == c.id:
            обобрать = (оценка_обобрать(h, p, c)
                        + p.пунктик("обобрать")
                        + character.своя_мерка(p, "обобрать", b))
            opts.append(((Ночь.ОБОБРАТЬ, c), обобрать * gate(p, "обобрать", b)))

    for t in h.others(p):
        if not t.alive:
            continue
        if t.living_with:
            continue           # его нет дома, он у соседа
        if h.под_одной_крышей(p, t):
            continue           # это тот, у чьей печки я сплю
        # сытый и незлой человек ночью не лезет к соседу
        A = conflict.aggr(h)
        if с.отчаяние < 0.30 / A and p.hate.get(t.id, 0) < 25 / A:
            continue
        # сначала магазин, к соседу — потом. Пока человек верит, что на
        # улице ещё есть что взять, чужая дверь почти ничего не стоит
        greed = (p.loot_value(t.id) * (0.35 + p.t01("жадность") * 0.9)
                 * (1.0 - actions.есть_куда_сходить(h, p, завтра=True)))
        score = greed * (0.35 + с.отчаяние * 1.3)
        # «я же только что принёс»
        if h.day - p.день_вылазки <= 1:
            score -= b["кража_только_принёс"]
        # и то, что в доме уже неспокойно: происшествия, отказы, чужая злость
        score += social.напряжение_дома(h, p) * b["кража_за_напряжение"]
        score += p.вес_черт("кража")
        score += p.пунктик("кража") + character.своя_мерка(p, "кража", b)
        score -= (1.0 - conflict.stealth(p)) * 3.5
        score -= t.shelter.get("дверь", 0) * 1.2
        score += p.hate.get(t.id, 0) / 22.0
        score -= 2.0 if t.id in p.allies else 0.0
        # сила хозяина — какой она КАЖЕТСЯ вору: рана, которую сосед прячет,
        # ночью его не защитит, а осунувшееся лицо приглашает. Незнакомого
        # считают целым (план агента, фаза 1а)
        score -= p.видимая_сила(t) * 0.6
        # сила — это расчёт, а страх — память: к тому, кто на его глазах
        # уже стрелял, ночью не идут, как бы ни было пусто в шкафу
        score -= p.боится(t.id) * b["страх_вес_кражи"]
        # человек прикидывает шансы: в укреплённую дверь при дежурстве не лезут
        chance = conflict.theft_chance(h, p, t, известно=False)
        if chance < b["кража_порог_шанса"] / A:
            continue
        score *= 0.45 + chance
        # страх последствий: обжёгся сам, видел или слышал, как за это убивали
        # и выгоняли. Не счёт дома, а то, что знает он сам: убийство за стеной,
        # о котором никто не сказал, вора не остановит (план поведения, шаг 4)
        score -= p.поймали * 1.8 / A
        score -= p.знает_убийств * b["страх_последствий_убийство"] / A
        score -= p.знает_изгнаний * b["страх_последствий_изгнание"] / A
        opts.append(((Ночь.КРАЖА, t), score * gate(p, "кража", b)))

    # тот же порог, что и днём (actions.choose_and_do): от нечего делать
    # человек не идёт ночью к чужой двери. Пока порога здесь не было,
    # мягкий выбор поднимал со дна то, что оценено почти в ноль, — а дешевле
    # всего «спать» стоит как раз в первую ночь метели, когда все выспались.
    # Сон остаётся всегда: это не одно из дел, а то, чем ночь кончается
    стоящие = [(o, s) for o, s in opts
               if o[0] == "спать" or s > b["порог_действия"]]
    # выбор — за решающим жильца (decision.py); мягкий выбор NPC — там же.
    # Самочувствие идёт следом: слагаемых у ночных оценок нет, а вот с чем
    # человек к ним подошёл — половина объяснения (decision.состояние)
    return p.решающий.ночь(h, p, стоящие, с)


# ---------------------------------------------------------------- оценки ночных поступков

def оценка_убийства(h, a, victim):
    """Стоит ли ночью убить того, с кем живёшь.

    Самый тёмный поступок в доме после людоедства, и устроен он иначе, чем
    налёт: не сила решает, а то, что жертва спит в двух метрах и доверяет.
    Отсюда и стратегия «втереться»: сначала переехать, потом дождаться ночи.
    """
    b = h.B
    добыча = a.loot_value(victim.id)
    if a.living_with == victim.id:
        # квартира достанется ему целиком — но он в ней уже греется, и убийство
        # даёт не тепло, а лишь то, что отсюда больше не выставят. Полный вес
        # этой разницы делал убийство привлекательным ровно для того, кому
        # переезд и был выгоден, то есть для всех подряд
        добыча += max(0.0, h.ценность_жилья(h.flats[victim.apt], a)
                      - h.ценность_жилья(h.flats[a.apt], a)) * b["убийство_вес_жилья"]
    хочу = добыча * (0.25 + a.t01("жадность") * 0.8)
    хочу += a.hate.get(victim.id, 0.0) / 30.0
    # того, кто вынес его квартиру, он не простит и случая ждать не станет:
    # мстят за такое любым способом, и нож ночью — один из них
    хочу += b["обида_вес_мести"] if victim.id in a.не_прощу else 0.0
    хочу += a.desperation() * b["убийство_за_отчаяние"]
    # доверие — главный тормоз, и его тут не было вовсе. Человек не режет того,
    # кому верит: в замере 43% убийц доверяли жертве выше 7 из 10, а 48% жертв
    # были им союзниками. Считать это надо до совести, а не после
    хочу -= a.trust.get(victim.id, 3.0) * b["убийство_за_доверие"]
    # и того, у кого на руках ребёнок, нож в спину не касается: ему есть
    # что терять и есть ради кого не рисковать. Раньше в формуле стояли только
    # ЧУЖИЕ иждивенцы, и половина убийц оказывалась матерями
    if a.dependents:
        хочу -= b["убийство_свой_ребёнок"]
    # главное: за нож берутся не от ссоры, а когда разойтись нельзя. Хозяин
    # может выставить гостя, гость может уйти — если ему есть куда вернуться.
    # А вот тот, чью квартиру разобрали на доски, пока он грелся у соседа,
    # заперт с ним в одной комнате, и это совсем другой расчёт
    if a.living_with == victim.id:
        своя = h.flats[a.apt]
        есть_куда = h.flat_temp(своя, burning=social.своя_топится(h, a),
                                powered=h.power_on) > b["комфортная_температура"] - 8
    else:
        есть_куда = a.power() >= victim.power() * b["выгнать_превосходство"]  # правда: под одной крышей: силу соседа по комнате знаешь
    if есть_куда:
        хочу -= b["убийство_есть_выход"]
    хочу -= a.t01("лояльность") * b["убийство_совесть"]
    # и просто страшно: за нож против того, кого боишься, берутся тяжелее
    # всего — он может проснуться, а дальше в комнате останется один
    хочу -= a.боится(victim.id) * b["страх_вес_насилия"]
    хочу -= b["убийство_союзник"] if victim.id in a.allies else 0.0
    хочу -= 2.5 if victim.dependents else 0.0
    # рядом был он один, и дом это поймёт: чем больше свидетелей вокруг,
    # тем страшнее. Скрытному страшно меньше
    хочу -= b["убийство_страх_раскрытия"] * (1.0 + 0.15 * len(h.alive())) * (1.4 - conflict.stealth(a))
    # даже спящий сильный человек может проснуться
    хочу -= max(0.0, victim.power() - a.power()) * 0.8  # правда: под одной крышей
    return хочу


def оценка_обобрать(h, гость, хозяин):
    """Стоит ли ночью собрать хозяйское и уйти к себе.

    Середина, которой в модели не было. Мотив «переехать не греться, а
    посмотреть» был давно — `переезд_расчёт` в оценке переезда прямо считает
    чужой шкаф против совести гостя, — а расплаты за него не существовало:
    втереться было можно, а вынести нельзя, и единственным выходом из чужой
    квартиры оставался нож. Отсюда и перекос: человек, которому нужны были
    чужие банки, шёл убивать за них хозяина, потому что другого способа
    уйти с ними не было.

    Отличий от кражи два, и оба в пользу вора. Замка нет — он внутри. И шкаф
    он видел своими глазами, а не по дыму из окна: здесь `est` не нужен, здесь
    правда мира. Отличие от убийства одно, и оно против него: хозяин остаётся
    жив и наутро точно знает, кто у него ночевал.
    """
    b = h.B
    своя = h.flats[гость.apt]
    добыча = вещи(хозяин.stock) * b["обобрать_вес_добычи"]  # правда: под одной крышей: шкаф видел своими глазами
    хочу = добыча * (0.25 + гость.t01("жадность") * 0.9)
    хочу += гость.desperation() * b["обобрать_за_отчаяние"]
    хочу += гость.hate.get(хозяин.id, 0.0) / 25.0
    хочу += b["обида_вес_мести"] if хозяин.id in гость.не_прощу else 0.0
    # уходить надо в ту же ночь, и уходить есть смысл только туда, где
    # не замёрзнешь. Унесённые дрова свою же квартиру и протопят — но только
    # если в ней есть чем топить и если её ещё не разобрали на доски
    тепло = h.flat_temp(своя, burning=bool(своя.shelter.get("буржуйка")),
                        powered=h.power_on)
    хочу -= max(0.0, b["комфортная_температура"] - тепло) * b["обобрать_за_холод"]
    # и всё, что держит руку: доверие к тому, кто пустил, история пары,
    # совесть, страх и простая мысль, что он может проснуться
    хочу -= гость.trust.get(хозяин.id, 3.0) * b["обобрать_за_доверие"]
    хочу -= гость.свой(хозяин.id) * b["обобрать_за_близость"]
    хочу -= гость.t01("лояльность") * b["обобрать_совесть"]
    хочу -= гость.боится(хозяин.id) * b["страх_вес_кражи"]
    хочу -= max(0.0, хозяин.power() - гость.power()) * b["обобрать_за_силу"]  # правда: под одной крышей
    # наутро об этом узнает весь подъезд, и объяснить себя будет нечем
    хочу -= b["обобрать_решимость"]
    # и то, сколько он тут живёт. К тому, кто вчера пустил тебя к своей печке,
    # ночью не встают: ты ещё не знаешь этой квартиры, тебя ещё разглядывают,
    # и главное — ты только что получил ровно то, за чем шёл. В журнале иначе
    # выходило, что дом складывается в общий котёл и в ту же ночь двое гостей
    # из трёх обирают хозяина
    прожил = h.day - гость.переехал_день
    умысел = гость.переезд_умысел
    хочу -= (max(0.0, b["обобрать_обжиться_дней"] - прожил)
             * b["обобрать_за_новизну"] * (1.0 - умысел))
    return хочу


def consider_raid(h, npc):
    """Условие запуска рейда ровно по GDD 16.

    «Рейд запускается, когда паника выше половины и высока либо ненависть,
    либо осведомлённость.»

    Пороги из документа больше не делятся на агрессивность дома: когда они
    делились, «паника выше половины» на практике означала «выше четверти»,
    и записанное в GDD условие переставало описывать игру. Агрессивность
    теперь двигает только поведение — совесть, вербовку, готовность откупиться
    и осторожность вора, — а не саму формулу запуска.
    """
    b = h.B
    A = conflict.aggr(h)
    # ворота нормальности стоят первыми: пока жизнь ещё похожа на обычную,
    # человек до чужой двери просто не додумывается — какой бы ни была паника.
    # Раньше эта проверка стояла после паники и не срабатывала ни разу
    if npc.normalcy > b["нормальность_потолок_налёта"]:
        return None
    if npc.panic < b["налёт_порог_паники"]:
        return None
    # «нечего терять»: умирающий идёт и разбитым, и один — просто почти
    # наверняка неудачно. Пока это был запрет, 26% случаев «рядом сытый сосед,
    # а я умираю от голода» упирались именно в него
    if (npc.health < 35 or len(npc.injuries) >= 2) and npc.desperation() < b["налёт_нечего_терять"]:
        return None
    # к чужой двери с ребёнком на руках не идут — ни вожаком, ни в толпе
    if npc.dependents:
        return None
    # налёт — это всегда либо нужда, либо личное
    if npc.desperation() < 0.30 / A and max(list(npc.hate.values()) or [0]) < 50 / A:
        return None
    best = None
    for t in h.others(npc):
        # к тому, с кем живёшь под одной крышей, не идут с ломом
        if h.под_одной_крышей(npc, t):
            continue
        # и к двери переехавшего тоже: за ней пусто, а сам он у хозяина —
        # если нужны его запасы, идти надо к хозяину, он в этом же списке
        if t.living_with:
            continue
        hate = npc.hate.get(t.id, 0.0)
        aware = npc.сведения_о(t.id).aware
        if hate < b["налёт_порог_ненависти"] and aware < b["налёт_порог_осведомлённости"]:
            continue
        want = npc.loot_value(t.id) * (0.5 + npc.t01("жадность"))
        want *= 0.6 + npc.desperation() * 1.4
        want += hate / 25.0
        # за дверью не только банки: за ней стены, печка и целая дверь.
        # Это второй мотив осады, и он не кончается, в отличие от еды
        want += conflict.хочу_его_квартиру(h, npc, t) * b["налёт_вес_жилья"]
        # если тихо взять не выйдет, дверь начинает притягивать людей с ломом:
        # укреплённая квартира защищает от вора и приманивает налёт (GDD 16)
        want += (1.0 - conflict.theft_chance(h, npc, t, известно=False)) * 2.6
        # страх перед хозяином: чем сильнее сосед, тем меньше желания.
        # человек считает не себя одного, а тех, кого реально может привести.
        # Считаем тем же кодом, что и собирает группу, — иначе вожак идёт туда,
        # куда его группа не пойдёт, и остаётся у двери один
        crew_size = len(conflict.recruit(h, npc, t)[0])   # прикидка, а не зов: он ещё не пошёл
        # за дверью не один человек, а квартира: сожители дерутся за неё
        # по определению (см. defenders_of). Пока страх считался по одному
        # хозяину, «вместе безопаснее» было правдой только в момент драки,
        # а в голове у налётчика этого не было — и съезжаться не защищало
        # и по силе, какой она кажется вожаку, а не какая есть: здоровье
        # за чужой дверью он не видит — видит лицо на площадке (план агента,
        # фаза 1а; слабость по `плох` ниже — та же мысль, другой ход)
        fear = sum(npc.видимая_сила(p) for p in h.household(t)) * (1.4 - npc.t01("храбрость")) * 1.5
        fear /= 1.0 + 0.45 * (crew_size - 1)
        fear += t.shelter.get("дверь", 0) * 0.8
        # и то, кого он за этой дверью боится. Не «сильный», а именно
        # страшный: тот, кто на его глазах стрелял, зарубил соседа или
        # вышел на площадку со стволом. Сила забывается, страх помнится
        fear += max(npc.боится(p.id) for p in h.household(t)) * b["страх_вес_налёта"]
        if t.weapon in FIREARMS and npc.сведения_о(t.id).aware > 30:
            fear += 2.2
        # и то, каким его КАЖУТ: слабость видна и она приглашает. Не правда
        # мира — по правде мира у осаждающего нет способа узнать, сколько
        # у соседа здоровья, — а лицо, которое он видел на площадке
        # (social.разглядел). Тот, кто держится прямо, этим и защищается
        слабость = max((npc.плох(p.id) for p in h.household(t)), default=0.0)
        fear -= слабость * b["добить_за_слабость"]
        # к тому, кого не простил, идут и через страх: это не расчёт, а счёт
        if t.id in npc.не_прощу:
            fear -= b["обида_вес_мести"]
        # и свет на площадке. Кто-то в доме не спит — значит, их услышат
        # на лестнице и поднимут весь подъезд. До сих пор дежурство не значило
        # для налётчика ровно ничего: 96 осад из 115 приходились на ночи,
        # когда кто-то дежурил
        дежурят = sum(1 for o in h.others(npc) if o.tonight == Ночь.ДЕЖУРИТЬ and o.id != t.id)  # правда: видно: свет на площадке — кто этой ночью не спит
        if дежурят:
            fear += b["налёт_страх_дежурства"] * min(2, дежурят)
        # совесть
        conscience = npc.вес_черт("налёт_совесть") * (1.0 - npc.desperation() * 0.5) / A
        conscience += 3.5 if t.id in npc.allies else 0.0   # на своего идти тяжело
        conscience += 1.2 if t.dependents else 0.0   # к матери с ребёнком идут последними
        # и тот, кто ещё пригодится: единственный человек в доме, который умеет
        # собрать генератор или сбить жар. Это, кажется, единственная защита
        # в этой игре, которая не из досок (GDD 18: «повод быть нужным»)
        if any(u in t.skills for u in ("слесарь", "электрик", "медик")):
            conscience += b["налёт_польза_мастера"]
            if h.мастер_занят.get(t.id) == npc.id:
                conscience += b["налёт_польза_мастера"]   # он сейчас делает мне печь
        # в одиночку к чужой двери идут только те, кто явно сильнее хозяина:
        # GDD 16 говорит о группе, а один человек у двери — это не осада,
        # а разговор через цепочку
        соло = (crew_size < b["налёт_минимум_группы"]
                and npc.power() < npc.видимая_сила(t) * b["налёт_соло_превосходство"])
        if соло:
            if npc.desperation() < b["налёт_нечего_терять"]:
                continue
            fear *= b["налёт_соло_страх"]     # он понимает, на что идёт
        score = want - fear - conscience + npc.пунктик("налёт_вожак")
        if best is None or score > best[1]:
            best = (t, score)
    if best and best[1] >= b["налёт_порог_желания"] / A:
        return best[0]
    return None
