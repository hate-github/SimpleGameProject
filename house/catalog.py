def _проверить():
    """Справочник не в порядке — падать при импорте, а не молчать сорок прогонов.

    Та же мысль, что у schema.validate_data: запись без поля или с опечаткой
    иначе тихо ничего не делает. Полноту против исполнителей проверяет
    `actions` при своём импорте (исполнитель без записи, запись без
    исполнителя): catalog про actions не знает и не должен — иначе цикл.
    Против balance.json (часы, лимиты) — schema.validate_data.
    """
    bad = []
    ключи = [з.key for з in ДЕЙСТВИЯ] + [п.key for п in ПОСТУПКИ]
    for k in sorted({k for k in ключи if ключи.count(k) > 1}):
        bad.append(f"ключ «{k}» описан дважды")
    for д in ДЕЙСТВИЯ:
        где = f"действие «{д.key}»"
        if not (isinstance(д.шум, tuple) and len(д.шум) == 2 and isinstance(д.шум[0], int)
                and (д.шум[1] is None or isinstance(д.шум[1], str))):
            bad.append(f"{где}: нет шума — нужна пара (громкость, вид)")
        elif д.шум[0] > 0 and д.шум[1] is None:
            bad.append(f"{где}: громкость {д.шум[0]} без вида шума")
        if not 0.0 <= д.норма <= 2.0:
            bad.append(f"{где}: норма {д.норма} вне 0..2")
        if not (isinstance(д.теги, tuple) and all(isinstance(t, str) for t in д.теги)):
            bad.append(f"{где}: теги — не кортеж строк")
        if д.заметность not in (0, 1, 2):
            bad.append(f"{где}: заметность {д.заметность}, а бывает 0, 1 или 2")
        if д.суд is not None and not (isinstance(д.суд, tuple) and len(д.суд) == 2):
            bad.append(f"{где}: суд — не пара (ненависть, доверие)")
        if д.суд is not None and not д.теги:
            bad.append(f"{где}: суд есть, а меток, по которым судить, нет")
        if д.постройка is not None and д.стройка is None:
            bad.append(f"{где}: постройка без стройки — провал не описан")
        if д.постройка is not None and not (isinstance(д.постройка, tuple) and len(д.постройка) == 4):
            bad.append(f"{где}: постройка — не (уровень, материалы, умения, потолок)")
    for п in ПОСТУПКИ:
        if not п.норма and not п.теги:
            bad.append(f"поступок «{п.key}»: ни нормы, ни меток")
    if bad:
        raise ValueError("Справочник действий не в порядке:\n  · " + "\n  · ".join(bad))


_проверить()
