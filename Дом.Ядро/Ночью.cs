// Перенос house/night.py: сон, дежурство, кражи, налёт и нож.
//
// GDD 4.3: «ночью происходит основной риск». Ночной выбор — такой же слой,
// как сбор вариантов днём: каждый решает, что делать ночью, потом дом
// разыгрывает налёт, убийства, уходы с хозяйским и кражи — в этом порядке,
// и порядок здесь и есть поведение.
//
// Класс назван `Ночью`, а не `Ночь`: `Ночь` — это перечисление того, чем
// человек занят до утра, и оно приехало раньше, вместе с моделью.

namespace Дом.Ядро;

public static partial class Ночью
{
    /// <summary>Ночь целиком: решения, налёт, нож, обобрать, кражи, сон.</summary>
    public static void ночь(House h)
    {
        var targets = Словари.Строкой<NPC?>();
        foreach (var p in h.alive())
        {
            var (mode, target) = решение(h, p);
            p.tonight = Слова.Ночь(mode);
            targets[p.id] = target;
        }

        // налёт — максимум один за ночь и не каждую ночь: после осады дом
        // несколько дней отходит (GDD 16 — рейд это событие, а не быт)
        bool raid_done = h.day - h.календарь.последний_налёт < h.B["налёт_перерыв_дней"];
        // вожаком налёта становится самый злой и жадный, а не просто самый смелый
        var порядок = h.alive().OrderByDescending(
            x => x.trait("жадность") + x.trait("вспыльчивость")
                 + x.trait("храбрость") * 0.5 - x.trait("лояльность")).ToList();
        foreach (var p in порядок)
        {
            if (raid_done || !p.здесь())
                continue;
            var t = consider_raid(h, p);
            if (t is not null)
            {
                p.tonight = Ночь.НАЛЁТ;
                var исход = Конфликт.run_siege(h, p, t);
                h.событие(ВидСобытия.ИСХОД, кто: p.id, кому: t.id,
                          что: Конфликт.Словами(исход), где: t.apt);
                h.календарь.последний_налёт = h.day;
                raid_done = true;
            }
        }

        // ночь в общей квартире. До краж: тот, кто на это решился, уже
        // не пойдёт никуда лезть, а дом наутро будет считать совсем другое
        foreach (var p in h.rng.Shuffled(h.alive()))
        {
            if (p.tonight != Ночь.УБИТЬ_СОСЕДА || !p.здесь())
                continue;
            var c = targets.Взять(p.id, null);
            if (c is not null && c.здесь() && h.под_одной_крышей(p, c))
                Конфликт.убить_соседа(h, p, c);
        }

        // обобрать и уйти. После ножа и до краж: тот, кто на это решился,
        // этой ночью больше никуда не пойдёт
        foreach (var p in h.rng.Shuffled(h.alive()))
        {
            if (p.tonight != Ночь.ОБОБРАТЬ || !p.здесь())
                continue;
            var c = targets.Взять(p.id, null);
            if (c is not null && c.здесь()
                && string.Equals(p.living_with, c.id, StringComparison.Ordinal))
                Конфликт.обобрать_и_уйти(h, p, c);
        }

        // кражи. Список составлен до осады, а осада могла кого-то из него
        // убить или выставить на мороз — поэтому проверяем обоих ещё раз
        foreach (var p in h.rng.Shuffled(h.alive()))
        {
            if (p.tonight != Ночь.КРАЖА || !p.здесь())
                continue;
            var t = targets.Взять(p.id, null);
            if (t is not null && t.здесь())
                Конфликт.steal(h, p, t);
        }

        // сон
        foreach (var p in h.alive())
        {
            if (p.rest < 35 && p.tonight == Ночь.ДЕЖУРИТЬ)
                // человек просто не выдерживает ещё одну ночь
                p.tonight = Ночь.СПАТЬ;
            if (p.rest < 25 && (p.tonight == Ночь.КРАЖА || p.tonight == Ночь.ДЕЖУРИТЬ))
                p.tonight = Ночь.СПАТЬ;     // на ногах уже не стоит
            double slept;
            if (p.tonight == Ночь.ДЕЖУРИТЬ)
            {
                slept = 4.5;
                p.ночей_дежурства += 1;
                p.дежурил_ночь = h.day;
            }
            else if (p.tonight == Ночь.КРАЖА || p.tonight == Ночь.НАЛЁТ
                     || p.tonight == Ночь.УБИТЬ_СОСЕДА || p.tonight == Ночь.ОБОБРАТЬ)
                slept = 5.5;
            else
                slept = p.rest < 35 ? 11.0 : (p.rest < 60 ? 9.5 : 8.0);
            p.slept = slept;
            // обезвоженный спит хуже — это единственное, что GDD 6.1 обещает
            // жажде помимо самой смерти, и до сих пор этого не было
            double качество = 1.0 - h.B["сон_за_жажду"]
                              * (1.0 - Util.Norm(p.hydration, 15, 70));
            p.rest = Util.Clamp(p.rest + slept * h.B["сон_за_час"] * качество
                                - h.B["часов_бодрствования"] * h.B["бодрствование_за_час"]);
        }

        // и то, чего в доме до сих пор не могло случиться: смерть, которой
        // никто не заметил. Считается после сна, потому что угорают спящие
        Мир.угар(h);
    }

    /// <summary>Чем человек занят до утра и с кем.</summary>
    public static (string mode, NPC? цель) решение(House h, NPC p)
    {
        var b = h.B;
        // как человек себя чувствует этой ночью — та же запись, что и днём:
        // усталость и отчаяние считались здесь заново, и совпадение
        // с дневными числами держалось на том, что формулы одинаковы
        var с = Действия.самочувствие(h, p);
        // сколько расправ он знает — один проход по памяти на всю ночь,
        // а не на каждую дверь
        var расправ = p.знает_расправ();
        var opts = new List<((string, NPC?), double)>
        {
            ((Ночь.СПАТЬ.Текст(), null), 2.5 + с.усталость * 6.0),
        };

        double wealth = p.stock.Взять("еда", 0.0) * 0.6 + p.stock.Взять("топливо", 0.0) * 0.3;
        double watch = p.panic / 100.0 * 3.0 + Социальное.recent_incidents(h) * 0.8
                       + wealth * 0.10 - с.усталость * 6.0;
        watch += p.обокрали * 2.0;
        watch += p.вес_черт("дежурить");
        watch += p.пунктик("дежурить");
        // своя ночь по общему расписанию: это уже не желание, а обязательство
        // перед всеми
        var дежурный = Площадка.чья_ночь(h);
        if (дежурный is not null && string.Equals(дежурный.id, p.id, StringComparison.Ordinal))
        {
            watch += b["дежурство_обязанность"];
            h.ожидает.дежурил_вчера = p.id;
        }
        // с ребёнком всю ночь на лестнице не просидишь: он просыпается,
        // мёрзнет и его надо держать при себе (GDD 12.6)
        if (p.dependents == 0)
            opts.Add(((Ночь.ДЕЖУРИТЬ.Текст(), null),
                      watch * Характер.norm_gate(p, "дежурить", b)));

        // тот, с кем он делит комнату: ночью до него два метра и никакой двери
        var соседи = !string.IsNullOrEmpty(p.living_with)
            ? new List<NPC?> { h.get(p.living_with!) }
            : p.guests.OrderBy(g => g, StringComparer.Ordinal)
                      .Select(g => h.get(g)).ToList();
        foreach (var c in соседи)
        {
            if (c is null || !c.здесь())
                continue;
            double ночью = оценка_убийства(h, p, c)
                           + p.пунктик("убить_соседа")
                           + Характер.своя_мерка(p, "убить_соседа", b);
            opts.Add(((Ночь.УБИТЬ_СОСЕДА.Текст(), c),
                      ночью * Характер.norm_gate(p, "убить_соседа", b)));
            // и то, что лежит между «съехать по-хорошему» и ножом: собрать
            // хозяйское и уйти к себе в ту же ночь. Только гостю — хозяину
            // уходить некуда, у него эта квартира и есть
            if (string.Equals(p.living_with, c.id, StringComparison.Ordinal))
            {
                double обобрать = оценка_обобрать(h, p, c)
                                  + p.пунктик("обобрать")
                                  + Характер.своя_мерка(p, "обобрать", b);
                opts.Add(((Ночь.ОБОБРАТЬ.Текст(), c),
                          обобрать * Характер.norm_gate(p, "обобрать", b)));
            }
        }

        foreach (var t in h.others(p))
        {
            if (!t.alive)
                continue;
            if (!string.IsNullOrEmpty(t.living_with))
                continue;           // его нет дома, он у соседа
            if (h.под_одной_крышей(p, t))
                continue;           // это тот, у чьей печки я сплю
            // сытый и незлой человек ночью не лезет к соседу
            double A = Конфликт.aggr(h);
            if (с.отчаяние < 0.30 / A && p.hate.Взять(t.id, 0.0) < 25 / A)
                continue;
            // сначала магазин, к соседу — потом. Пока человек верит, что
            // на улице ещё есть что взять, чужая дверь почти ничего не стоит
            double greed = p.loot_value(t.id) * (0.35 + p.t01("жадность") * 0.9)
                           * (1.0 - Действия.есть_куда_сходить(h, p, завтра: true));
            double score = greed * (0.35 + с.отчаяние * 1.3);
            // «я же только что принёс»
            if (h.day - p.день_вылазки <= 1)
                score -= b["кража_только_принёс"];
            // и то, что в доме уже неспокойно: происшествия, отказы, чужая злость
            score += Социальное.напряжение_дома(h, p) * b["кража_за_напряжение"];
            score += p.вес_черт("кража");
            score += p.пунктик("кража") + Характер.своя_мерка(p, "кража", b);
            score -= (1.0 - Конфликт.stealth(p)) * 3.5;
            score -= t.shelter.Взять("дверь", 0.0) * 1.2;
            score += p.hate.Взять(t.id, 0.0) / 22.0;
            score -= p.allies.Contains(t.id) ? 2.0 : 0.0;
            // сила хозяина — какой она КАЖЕТСЯ вору: рана, которую сосед
            // прячет, ночью его не защитит, а осунувшееся лицо приглашает.
            // Незнакомого считают целым
            score -= p.видимая_сила(t) * 0.6;
            // сила — это расчёт, а страх — память: к тому, кто на его глазах
            // уже стрелял, ночью не идут, как бы ни было пусто в шкафу
            score -= p.боится(t.id) * b["страх_вес_кражи"];
            // человек прикидывает шансы: в укреплённую дверь при дежурстве
            // не лезут
            double chance = Конфликт.theft_chance(h, p, t, известно: false);
            if (chance < b["кража_порог_шанса"] / A)
                continue;
            score *= 0.45 + chance;
            // страх последствий: обжёгся сам, видел или слышал, как за это
            // убивали и выгоняли. Не счёт дома, а то, что знает он сам:
            // убийство за стеной, о котором никто не сказал, вора не остановит
            score -= p.поймали * 1.8 / A;
            score -= расправ.убийств * b["страх_последствий_убийство"] / A;
            score -= расправ.изгнаний * b["страх_последствий_изгнание"] / A;
            opts.Add(((Ночь.КРАЖА.Текст(), t), score * Характер.norm_gate(p, "кража", b)));
        }

        // тот же порог, что и днём: от нечего делать человек не идёт ночью
        // к чужой двери. Пока порога здесь не было, мягкий выбор поднимал
        // со дна то, что оценено почти в ноль, — а дешевле всего «спать»
        // стоит как раз в первую ночь метели, когда все выспались.
        // Сон остаётся всегда: это не одно из дел, а то, чем ночь кончается
        var стоящие = opts.Where(
            в => string.Equals(в.Item1.Item1, "спать", StringComparison.Ordinal)
                 || в.Item2 > b["порог_действия"]).ToList();
        // выбор — за решающим жильца. Самочувствие идёт следом: слагаемых
        // у ночных оценок нет, а вот с чем человек к ним подошёл — половина
        // объяснения
        var список = стоящие
            .Select(в => ((в.Item1.Item1, (object?)в.Item1.Item2), в.Item2)).ToList();
        var выбран = (p.решающий as Решающий)!.ночь(h, p, список, с);
        if (выбран is null)
            return (Ночь.СПАТЬ.Текст(), null);
        return (выбран.Value.вид, выбран.Value.кому as NPC);
    }
}
