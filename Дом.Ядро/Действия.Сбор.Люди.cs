// Перенос house/actions.py, `_люди` и `_себя`: пятый и шестой разделы сбора,
// и сам `gather`.
//
// Всё, что человек может сделать с другим человеком: посмотреть, поговорить,
// шепнуть, попросить, отдать ребёнка на ночь, поделиться, вернуть долг,
// съехаться, зажать на лестнице, подкараулить, поменяться, вылечить.

namespace Дом.Ядро;

public static partial class Действия
{
    /// <summary>Раздел gather: люди.</summary>
    public static void _люди(Корзина корзина, House h, NPC npc, Баланс b, Самочувствие с,
                             NPC? шептать_кому)
    {
        foreach (var t in h.others(npc))
        {
            if (t.away)
            {
                // хозяина нет дома: поговорить не с кем, но квартира стоит
                // пустая. Раньше эта ветка была ниже по циклу, за `continue`,
                // и не достигалась никогда — дневная кража из GDD 12.5 была
                // мёртвым кодом
                if (npc.confidence(t.id) > 0.2 && string.IsNullOrEmpty(t.living_with)
                    && !h.под_одной_крышей(npc, t))
                {
                    // то же, что и ночью: пока улица кормит, чужая дверь не нужна
                    double greed = npc.loot_value(t.id) * (0.4 + npc.t01("жадность") * 0.8)
                                   * (1.0 - есть_куда_сходить(h, npc));
                    double score = greed * (0.4 + с.отчаяние) + npc.вес_черт("кража_днём")
                                   - (1.0 - Конфликт.stealth(npc)) * 3.0;
                    if (h.day - npc.день_вылазки <= 1)
                        score -= b["кража_только_принёс"];
                    score += Социальное.напряжение_дома(h, npc) * b["кража_за_напряжение"];
                    score += npc.hate.Взять(t.id, 0.0) / 25.0;
                    score += npc.не_прощу.Contains(t.id) ? b["обида_вес_мести"] : 0.0;
                    score -= t.shelter.Взять("дверь", 0.0) * 1.4;   // правда: видно: дверь соседа видно с площадки
                    // днём ломать чужую дверь страшнее, чем ночью: в подъезде
                    // люди, шум слышно всем, и объяснить себя нечем
                    score -= b["кража_днём_решимость"];
                    score -= npc.боится(t.id) * b["страх_вес_кражи"];
                    score -= h.others(npc).Count(o => !o.away) * 0.5;
                    корзина.add("кража_днём", score * Характер.norm_gate(npc, "кража", b), t);
                }
                continue;
            }
            double trust = npc.trust.Взять(t.id, 3.0);
            // между нами счёты: он ломал мою дверь на этой неделе, или я ломал
            // его. Пока этого состояния не было, назавтра после осады эти двое
            // разговаривали и менялись банками как ни в чём не бывало
            bool счёты = npc.враждует(t.id, b["обида_порог_вражды"]);
            // улеглось, но не забылось: обида не опускается ниже дна никогда
            double помнит = npc.обида(t.id) * b["обида_вес_помнящего"];
            double месть = npc.не_прощу.Contains(t.id) ? b["обида_вес_мести"] : 0.0;
            // а это обида ЕГО на меня: я стоял у его двери, и он этого
            // не забыл. Гасится она поступками — но не в тот же день
            double свежая = h.обиды_дни.Взять((npc.id, t.id), -99);
            double виноват = !t.не_прощу.Contains(npc.id)             // правда: событие было со мной: сказано вслух, при всех
                             && h.day - свежая >= b["загладить_не_раньше"]
                ? t.обида(npc.id) : 0.0;                              // правда: событие было со мной: я стоял у его двери

            // наблюдение
            double curiosity = npc.вес_черт("наблюдение") + npc.panic / 40.0
                               + npc.hate.Взять(t.id, 0.0) / 30.0;
            curiosity += с.отчаяние * 2.0 - npc.confidence(t.id) * 3.0;
            // за тем, кого списал со счетов, приглядывают отдельно — не из
            // заботы, а чтобы не пропустить день, когда за дверью станет тихо
            if (npc.не_жилец.Contains(t.id))
                curiosity += b["наследство_вес"];
            // за тем, с кем счёты, следят пристально
            if (счёты)
                curiosity += b["счёты_наблюдение"];
            curiosity += месть;
            // к страшному соседу не приглядываются: попадёшься — объясняй потом
            curiosity -= npc.боится(t.id) * b["страх_вес_контакта"];
            корзина.add("наблюдение", curiosity, t);

            // разговор
            double свой = npc.свой(t.id);
            double ближе = npc.предпочтение(t.id, с.средний_свой);
            double talk = npc.вес_черт("разговор") + trust * 0.3;
            // к своему заходят не потому, что он полезен, а потому, что он
            // свой. Пока в этой строке стояло одно доверие, все выбирали
            // одного и того же: доверие на четыре пятых репутация
            talk += ближе * b["близость_вес_разговора"];
            talk += (1.0 - Util.Norm(npc.mood, 20, 80)) * 2.0;
            talk -= npc.hate.Взять(t.id, 0.0) / 12.0;   // к тому, кого не выносишь, не идут
            talk -= npc.panic / 100.0;
            // и к тому, кого боишься, тоже: страх держит крепче неприязни
            talk -= npc.боится(t.id) * b["страх_вес_контакта"];
            talk -= помнит;
            // медик обходит тех, кого давно не видел: болезни за закрытой
            // дверью он больше не знает, значит, должен в неё постучать
            if (npc.skills.Contains("медик", StringComparer.Ordinal)
                && npc.stock.Взять("лекарства", 0.0) >= 1)
                talk += b["медик_обход"]
                        * Math.Min(1.0, npc.давно_видел(t.id, h.day) / b["медик_обход_дней"]);
            if (!счёты)
                корзина.add("разговор", talk, t);

            // --- ходы заговорщика ---
            var з = npc.замысел;
            if (ReferenceEquals(шептать_кому, t) && з is not null
                && !string.Equals(з.враг, t.id, StringComparison.Ordinal))
            {
                var враг = h.get(з.враг!);
                if (враг is not null)
                {
                    // шепнуть: сказать про врага то, чего не было. Дёшево,
                    // быстро и разоблачается тем же, чем наговор
                    double шёпот = npc.hate.Взять(враг.id, 0.0) / 12.0
                        + t.свой(враг.id) * b["шепнуть_за_их_близость"]      // правда: общее знание: кто к кому ходит, в подъезде видно
                        - t.trust.Взять(враг.id, 3.0) * b["шепнуть_против_доверия"]  // правда: общее знание: и кто с кем не разговаривает — тоже
                        - з.напор * b["шепнуть_осторожность"]
                        // умный прямого наговора избегает — его можно проверить
                        // разговором с оболганным
                        - npc.t01("сообразительность") * b["шепнуть_против_ума"];
                    корзина.add("шепнуть", шёпот, t);
                }
            }

            // человек помнит, кто ему давал, а кто отказывал
            string need_res = что_просить(h, npc, t);
            var rec = npc.ask_record(t.id);
            bool can_ask = true;
            if (h.day - rec.последняя < b["просьба_перерыв_дней"])
                can_ask = false;                     // только что уже просил
            if (rec.подряд >= 2 && h.day - rec.последняя < b["просьба_обида_дней"])
                can_ask = false;                     // дважды отказал — больше не унижаюсь
            if (h.day - rec.я_дал < b["просьба_после_помощи"])
                can_ask = false;                     // сам ему на днях отдал последнее
            // просят не только когда кончается: промёрзший идёт за дровами,
            // больной за лекарством. Это и есть то, чем лечится «невмоготу»
            if (can_ask && !счёты && с.зову > 0.35
                && npc.believed(t.id, need_res) > b["просьба_верит"])
            {
                // просят у того, кто свой, — не потому, что у него больше,
                // а потому, что перед своим не так стыдно стоять
                double ask = с.зову * 6.0
                             * (0.3 + trust / 10.0 + ближе * b["близость_вес_просьбы"])
                             + npc.вес_черт("попросить");
                // к тому, кого ненавидишь, идут только если совсем припёрло
                ask -= npc.hate.Взять(t.id, 0.0) / 14.0 * (1.5 - с.зову);
                // и не идут к тому, кому уже задолжали: стыдно
                ask -= npc.ask_record(t.id).должен * b["долг_вес"];
                // к щедрому идут первым, к скупому не идут вовсе
                ask *= b["просьба_вес_памяти"]
                       + (2.0 - b["просьба_вес_памяти"]) * npc.generosity(t.id);
                // в дверь, за которой стоит страшный человек, не стучатся
                // даже голодными
                ask -= npc.боится(t.id) * b["страх_вес_контакта"];
                // и то, что человек про себя знает: когда по нему всё видно,
                // просить легче
                ask += npc.каким_кажусь() * b["просьба_за_вид"];
                корзина.add("попросить", ask, t, детали_: need_res);
            }

            // отдать ребёнка на ночь в чужое тепло. Единственный ход, который
            // у матери на самом деле есть: просить банку бессмысленно —
            // банка не греет
            var свой_р = npc.слабейший_ребёнок();
            double отказ_ночёвка = npc.ask_record(t.id).отказ_ночёвка;
            // ворота, без которых это было просто хождением по подъезду:
            // ребёнка несут туда, где ТЕПЛЕЕ
            double теплее = h.room_temp(t, burning: true) - h.room_temp(npc, burning: true);
            if (свой_р is not null && string.IsNullOrEmpty(свой_р.у) && !счёты
                && h.day - отказ_ночёвка >= b["просьба_обида_дней"]
                && теплее >= b["ночёвка_нужен_градус"]
                && npc.ребёнку_плохо() >= b["ночёвка_порог_беды"])
            {
                double отдать = npc.ребёнку_плохо() * b["ночёвка_за_беду"]
                    + Math.Max(0.0, теплее) * b["ночёвка_за_тепло"]
                    + (trust - 3.0) * 0.4 + ближе * b["близость_вес_просьбы"]
                    // тому, кого она боится, ребёнка не отдают ни при каком
                    // холоде: это единственное, что она решает без счёта
                    - npc.боится(t.id) * b["ночёвка_страх"]
                    - b["ночёвка_решимость"];
                // и то же, чем она выбирает, у кого просить банку
                отдать *= b["просьба_вес_памяти"]
                          + (2.0 - b["просьба_вес_памяти"]) * npc.generosity(t.id);
                // к той двери, за которой свой такой же, идут охотнее
                отдать += t.дети.Count > 0 ? b["ночёвка_к_своим_детям"] : 0.0;
                корзина.add("отдать_на_ночь", отдать, t);
            }

            // поделиться
            int gave_me_today = h.сутки.контакты.Взять((t.id, npc.id, "поделиться"), 0);
            // видно не чужой шкаф, а чужое лицо: делятся с тем, кто КАЖЕТСЯ
            // в беде. И помочь можно не только банкой
            var (чем, излишек) = чем_поделиться(h, npc, t, b);
            // прийти с банкой к тому, кто ни о чём не просил, — это поступок,
            // и на него нужен повод. Без этого условия помощь была рядовым
            // пунктом расписания: 88 % передач шли тому, кто ничего не просил
            double просил = h.day - t.ask_record(npc.id).последняя;   // правда: событие было со мной: он просил у меня
            // беда — та, которую он ВИДЕЛ: пока здесь стояли настоящие раны,
            // человек знал о переломе соседа за двумя стенами
            double плох_ = npc.плох(t.id);
            bool повод = npc.allies.Contains(t.id)
                || виноват > 0.0
                || свой >= b["помощь_свой_порог"]
                || просил <= b["помощь_помнит_просьбу"]
                || плох_ >= b["не_жилец_отмена"]
                || npc.видит_хворь(t.id)
                || trust >= b["помощь_доверие_без_повода"]
                || (t.dependents != 0 && npc.ценит("ребёнок"))
                // и сам ребёнок, когда ему плохо: его слышно за стеной всему
                // подъезду. Пока этого не было, дом приносил еду в 15 днях
                // беды из 280
                || (t.dependents != 0
                    && t.ребёнку_плохо() > b["ребёнок_слышно_порог"]);   // правда: общее знание: ребёнка за стеной слышно всему подъезду
            // своя доля обиды не должна мешать её заглаживать: раздражение
            // на человека, чью дверь ты ломал, — не причина не нести ему банку
            if (повод && чем is not null && gave_me_today == 0
                && (!счёты || виноват > 0.0)
                && npc.confidence(t.id) > b["помощь_уверенность"])
            {
                double give = npc.вес_черт("поделиться") + trust * 0.5 - с.отчаяние * 4.0;
                give += ближе * b["близость_вес_помощи"] - помнит;
                // донести банку тому, у чьей двери стоял, — единственный
                // способ это уладить. Идут на него не от совести одной: враг
                // за стеной опаснее пустой полки
                give += виноват * b["загладить_вес"]
                        * (0.4 + npc.t01("лояльность") * 0.6
                           + Util.Clamp(npc.видимая_сила(t) / Math.Max(0.2, npc.power()) - 1.0,
                                        0.0, 1.0));
                // на чужую беду отзываются тем слабее, чем дольше идёт метель.
                // Это не жестокость, а самосохранение
                double своё_дороже = 1.0 - Util.Clamp(h.day / 30.0, 0.0, 1.0)
                                     * b["помощь_самосохранение"];
                give += плох_ * b["помощь_за_вид"] * своё_дороже;
                // а тому, кого он про себя уже похоронил, нести незачем:
                // банка уйдёт в мертвеца
                if (npc.не_жилец.Contains(t.id))
                    give -= b["наследство_вес"];
                // и сама оценка зависит от того, чем помогаешь: отнести
                // аптечку больному — поступок, вынести кружку воды — почти ничего
                give += (b.Таблица("помощь_вес")[чем] - 1.0) * b["помощь_вес_в_оценке"];
                // то же, что и при просьбе: «я тебе уже трижды носил»
                give -= npc.дал.Взять(t.id, 0.0) * b["долг_вес"];
                // и тот же страх, которым он отказывает на просьбу
                give -= (1.0 - Math.Min(1.0,
                            npc.secure(чем != "лекарства" ? чем : "еда")))
                        * b["жадность_от_нехватки"] * b["щедрость_вес_горизонта"];
                if (npc.allies.Contains(t.id))
                    give += 2.0;
                if (t.dependents != 0)
                {
                    give += b["помощь_за_ребёнка"];
                    // голодного ребёнка за стеной слышно всему подъезду.
                    // До сих пор здесь стояла плоская прибавка, одинаковая
                    // и когда ребёнок сыт, и когда он третий день не ест
                    double беда = t.ребёнку_плохо();   // правда: общее знание: ребёнка за стеной слышно всему подъезду
                    if (беда > b["ребёнок_слышно_порог"]
                        && (чем == "еда" || чем == "лекарства"))
                        // и здесь же остаётся чёрствость, иначе дом становится
                        // добрее, чем задуман: к чужому ребёнку идёт сытый
                        // сосед; тот, у кого у самого пусто, не идёт никуда
                        give += беда * b["помощь_за_ребёнка_в_беде"]
                                * Util.Clamp(1.0 - с.отчаяние, 0.0, 1.0)
                                * (1.0 - npc.t01("жадность") * b["ребёнок_за_жадность"]);
                }
                корзина.add("поделиться", give, t, детали_: чем);
            }

            // вернуть долг: человек помнит, что ему давали, и при излишке
            // отдаёт. Без этого память была односторонней
            double мой_долг = npc.ask_record(t.id).должен;
            // но не в тот же день: «занёс банку — отдала банку» в первые
            // сутки обнуляет и подарок, и память о нём
            double свежий = h.day - npc.ask_record(t.id).я_дал;
            if (мой_долг >= 1.0 && npc.days_of("еда") > b["помощь_минимум_дней"]
                && свежий >= b["долг_возврат_не_раньше"])
                корзина.add("вернуть",
                    2.0 + мой_долг * 1.2 + npc.t01("лояльность") * 2.0, t);

            // с раскрытым людоедом дом дел не имеет
            if (t.раскрыт)
                continue;

            // съехаться: когда своя квартира больше не держит тепло
            if (string.IsNullOrEmpty(npc.living_with) && npc.guests.Count == 0
                && string.IsNullOrEmpty(t.living_with)
                && h.day - npc.ask_record(t.id).отказ_переезд >= b["переезд_обида_дней"]
                && npc.warmth < b["переезд_порог_тепла"]
                && h.room_temp(t, burning: true) > h.room_temp(npc, burning: true) + 4
                && trust >= b["переезд_доверие"])
            {
                double move = Социальное.выгода_соседства(h, npc, t) * b["переезд_вес_выгоды"];
                move += с.невмоготу * 4.0;
                move += npc.вес_черт("переехать");     // гордость
                // и отдельно — тот, кто идёт не греться: чем больше у соседа
                // добра и чем меньше у гостя совести, тем охотнее он просится
                move += Сожительство.переезд_с_умыслом(h, npc, t) * b["переезд_расчёт"];
                move -= npc.боится(t.id) * b["страх_вес_соседства"];
                корзина.add("переехать", move, t);
            }

            // отнять на лестнице: без двери, без замка, лицом к лицу.
            // Человека, с которым делишь одну комнату, на лестнице
            // не зажимают: вечером возвращаться в неё же
            if (!h.под_одной_крышей(npc, t))
            {
                double A = Конфликт.aggr(h);
                // сила соседа берётся такой, какой она КАЖЕТСЯ. Слабость видна
                // по лицу, и она приглашает; раненый, который держится прямо,
                // этим и защищается
                double ratio = npc.power() / Math.Max(0.2, npc.видимая_сила(t));
                // ловят того, кого ВИДЕЛИ с пакетами: «вернулся с улицы» —
                // сигнал, и он доходит не до всех. Случайная встреча
                // на лестнице — редкость
                bool met = npc.слышал(t.id, "возвращение", h.day) || h.rng.Chance(0.08);
                // ключи имеет смысл отнимать только у того, кто живёт один
                bool один = t.guests.Count == 0 && string.IsNullOrEmpty(t.living_with);
                double жильё = один ? Конфликт.хочу_его_квартиру(h, npc, t) : 0.0;
                bool trigger = с.отчаяние > 0.40 || npc.hate.Взять(t.id, 0.0) > 35
                               || жильё > b["отъём_жильё_порог"];
                if (met && trigger && ratio > b["отъём_порог_силы"] / A
                    && npc.loot_value(t.id) > 1.5)
                {
                    double take = (с.отчаяние * 3.5 + npc.hate.Взять(t.id, 0.0) / 18.0)
                                  * (0.4 + npc.t01("жадность"));
                    take += жильё * b["отъём_вес_жилья"];
                    take *= Math.Min(2.2, ratio);
                    take -= b["отъём_решимость"];
                    take -= npc.t01("лояльность") * 5.0 / A;
                    // на лестнице зажимают слабого, а не страшного
                    take -= npc.боится(t.id) * b["страх_вес_отъёма"];
                    take -= h.others(npc).Count(o => o.allies.Contains(t.id)) * 1.6;
                    take -= npc.allies.Contains(t.id) ? 2.0 : 0.0;
                    take += npc.не_прощу.Contains(t.id) ? b["обида_вес_мести"] : 0.0;
                    take -= t.dependents != 0 ? 1.5 : 0.0;
                    // дом закрывается против того, кто уже отнимал: это
                    // страшнее совести. Порог здесь — та же доля от порога
                    // вражды, за которым дверь закрыта с той стороны
                    double закрыто = b["обида_порог_вражды"] * b["обида_обидчику"];
                    take -= h.others(npc).Count(o => npc.враждует(o.id, закрыто)) * 1.8;
                    корзина.add("отнять", take, t);
                }
            }

            // подкараулить: сесть на площадке и ждать его. Это ответ на осаду
            // с обеих сторон сразу
            var пара = Социальное.Пара(npc.id, t.id);
            double остыли = h.day - h.засады.Взять(пара, -99);
            if (счёты && !t.away && !npc.allies.Contains(t.id)
                && (npc.hate.Взять(t.id, 0.0) >= b["засада_порог_злости"]
                    || npc.не_прощу.Contains(t.id))
                && остыли >= b["засада_перерыв_дней"]
                && !h.сутки.караулят.Есть(t.id)
                && !h.под_одной_крышей(npc, t))
            {
                // сила считается по тому, каким он КАЖЕТСЯ, и только
                // превосходство: на площадку садятся не от храбрости,
                // а от расчёта
                double перевес = Util.Clamp(
                    npc.power() / Math.Max(0.2, npc.видимая_сила(t)) - 1.0, 0.0, 1.6);
                double ждать = npc.hate.Взять(t.id, 0.0) / b["засада_за_злость"]
                               + перевес * b["засада_за_силу"]
                               + npc.loot_value(t.id) * b["засада_за_добычу"]
                               - npc.боится(t.id) * b["страх_вес_отъёма"]
                               - b["засада_решимость"];
                корзина.add("подкараулить", ждать + месть, t);
            }

            // обмен. С тем, с кем счёты, не меняются: сделка требует подойти
            // к двери и отдать вещь из рук в руки
            if (!счёты)
                корзина.add("обмен", _trade_score(h, npc, t) - помнит, t);

            // лечение (GDD 6.2). Медик идёт к тому, у кого ВИДЕЛ рану или
            // слышал кашель, а не к тому, кто болен по правде мира. Ребёнок
            // за стеной — исключение: его слышно всему подъезду
            var слаб = t.слабейший_ребёнок();   // правда: общее знание: ребёнок за стеной слышен всему подъезду
            bool ребёнку_плохо = слаб is not null
                                 && (слаб.болен is not null || слаб.здоровье < 70);
            // впустит ли — решает больной у своей двери, а не медик по его
            // доверию. К тому, кто на днях не открыл, второй раз не идут
            if (npc.skills.Contains("медик", StringComparer.Ordinal)
                && npc.stock.Взять("лекарства", 0.0) >= 1
                && (npc.видит_хворь(t.id) || ребёнку_плохо)
                && h.day - npc.ask_record(t.id).не_впустил >= b["просьба_обида_дней"])
            {
                double детский = слаб is not null && слаб.болен is not null ? 3.0 : 0.0;
                // и то, что за прошлый раз не заплатили: даром она лечит,
                // но не бесконечно и не всех подряд (GDD 18)
                double должок = npc.ask_record(t.id).не_заплатил;
                // насколько ему плохо — тоже по виду, той же меркой, что плох()
                корзина.add("лечить", 3.0 + npc.плох(t.id) * 4.0 + детский
                    + npc.t01("лояльность") * 3.0 + trust * 0.3
                    - должок * b["услуга_обида"], t);
            }
        }
    }

    /// <summary>Раздел gather: себя — и позвать дом на площадку (GDD 25).</summary>
    public static void _себя(Корзина корзина, House h, NPC npc, Баланс b, Самочувствие с)
    {
        if (npc.stock.Взять("лекарства", 0.0) >= 1 && нужен_врач(npc))
        {
            var свой = npc.слабейший_ребёнок();
            double детский = свой is null ? 0.0
                : (1.0 - Util.Norm(свой.здоровье, 20, 90)) * 7.0;
            корзина.add("лечить", 3.0 + Math.Max(с.невмоготу * 6.0, детский), npc);
        }
        // --- позвать дом на площадку (GDD 25: дом как субъект) ---
        корзина.add("собрание", Площадка.оценка(h, npc));
        // отдых — самая крупная строка дома после того, как быт отступил.
        // Отступает он не так, как быт: быт отступает перед бедой любой,
        // отдых — только перед поправимой
        корзина.add("отдых", с.усталость * 6.0
            + (1.0 - Util.Norm(npc.mood, 20, 70)) * 2.0
            + (npc.injuries.Count > 0 ? 2.0 : 0.0)
            - поправимая_беда(h, npc, b) * b["отдых_отступает"]);
        // обычная жизнь: пока всё ещё похоже на нормальное, человек живёт,
        // а не выживает. Это было единственное действие в модели без единой
        // причины — и при этом самой крупной строкой у каждого: 21 % всех
        // ходов дома, а у матери в дни, когда ребёнку плохо, 30 %
        //
        // Привычка: то, чем человек занимает своё утро или свой вечер, пока
        // жизнь ещё похожа на жизнь. Прибавка гаснет и от беды, и
        // от рассыпавшегося привычного, поэтому к третьей неделе метели
        // книгу не открывает никто
        string? занятие = npc.привычки.Взять(npc.отрезок(), null!);
        double по_привычке = занятие is not null
            ? b["привычка_вес"] * npc.normalcy
              * Util.Clamp(1.0 - Math.Max(с.невмоготу, с.отчаяние), 0.0, 1.0)
            : 0.0;
        корзина.add("быт", 1.25 + npc.normalcy * 1.4 + (h.network > 0 ? 0.4 : 0.0)
            + по_привычке
            - Math.Max(с.невмоготу, с.отчаяние) * b["быт_отступает"], детали_: занятие);
    }

    /// <summary>
    /// Собрать все доступные действия с оценками. Оценка примерно 0..10.
    ///
    /// Возвращает саму корзину, а не список: кроме вариантов в ней лежит то,
    /// из чего сложилась каждая оценка, что не прошло ворота и с каким
    /// самочувствием человек подошёл к выбору.
    /// </summary>
    public static Корзина gather(House h, NPC npc)
    {
        h.hooks.Зов_gather(h, npc);
        var корзина = _gather(h, npc);
        h.hooks.Зов_после_gather(h, npc, корзина);
        return корзина;
    }

    private static Корзина _gather(House h, NPC npc)
    {
        var b = h.B;
        // как человек себя сейчас чувствует — один расчёт на весь сбор
        var с = самочувствие(h, npc);
        var соседи = h.others(npc);

        // кому заговорщик сегодня шепнёт — тоже один раз, и не всякому.
        // Умный работает чужими руками и выбирает того, чей разрыв с врагом
        // дороже всего стоит, а глупый идёт к тому, кто под рукой
        NPC? шептать_кому = null;
        var _з = npc.замысел;
        if (_з is not null && _з.вид == "рассорить" && !_з.сегодня_спит
            && !string.IsNullOrEmpty(_з.враг)
            && _з.напор < Замыслы.осторожность(h, npc))
        {
            var _враг = h.живой(_з.враг);
            if (_враг is not null)
                шептать_кому = Замыслы.кому_шептать(h, npc, _враг);
        }

        // сколько раз за день человек вообще выходит к соседям. Общий предел
        // на все двери сразу, а не на каждую по отдельности: пока их было три
        // штуки по своему ключу, шестеро успевали сходить друг к другу
        // шестнадцать раз за второй день метели
        int визитов = 0;
        foreach (var ((кто, k), n) in h.сутки.сделано)
            if (string.Equals(кто, npc.id, StringComparison.Ordinal)
                && Каталог.ВИЗИТЫ.Contains(k))
                визитов += n;
        double предел_визитов = b["визитов_в_день"]
                                + Math.Max(с.зову, с.отчаяние) * b["визитов_за_нужду"]
                                + (1.0 - npc.normalcy) * b["визитов_за_распад"];

        var корзина = new Корзина(h, npc, визитов, предел_визитов, с);

        _быт(корзина, h, npc, b, с);
        _убежище(корзина, h, npc, b, с);
        _жильё(корзина, h, npc, b, с);
        _улица(корзина, h, npc, b, с, соседи);
        _люди(корзина, h, npc, b, с, шептать_кому);
        _себя(корзина, h, npc, b, с);

        return корзина;
    }
