// Перенос house/night.py, строки 200–423: оценки ночных поступков.
//
// Лежат рядом с решением, а не среди драк и не в оркестраторе: «стоит ли»
// и «что из этого вышло» — разные вещи, и первое считается до всякого броска.

namespace Дом.Ядро;

public static partial class Ночью
{
    /// <summary>
    /// Стоит ли ночью убить того, с кем живёшь.
    ///
    /// Самый тёмный поступок в доме после людоедства, и устроен он иначе,
    /// чем налёт: не сила решает, а то, что жертва спит в двух метрах
    /// и доверяет. Отсюда и стратегия «втереться»: сначала переехать,
    /// потом дождаться ночи.
    /// </summary>
    public static double оценка_убийства(House h, NPC a, NPC victim)
    {
        var b = h.B;
        double добыча = a.loot_value(victim.id);
        if (string.Equals(a.living_with, victim.id, StringComparison.Ordinal))
            // квартира достанется ему целиком — но он в ней уже греется,
            // и убийство даёт не тепло, а лишь то, что отсюда больше
            // не выставят. Полный вес этой разницы делал убийство
            // привлекательным ровно для того, кому переезд и был выгоден
            добыча += Math.Max(0.0, h.ценность_жилья(h.flats[victim.apt], a)
                                    - h.ценность_жилья(h.flats[a.apt], a))
                      * b["убийство_вес_жилья"];
        double хочу = добыча * (0.25 + a.t01("жадность") * 0.8);
        хочу += a.hate.Взять(victim.id, 0.0) / 30.0;
        // того, кто вынес его квартиру, он не простит и случая ждать не станет
        хочу += a.не_прощу.Contains(victim.id) ? b["обида_вес_мести"] : 0.0;
        хочу += a.desperation() * b["убийство_за_отчаяние"];
        // доверие — главный тормоз, и его тут не было вовсе. Человек не режет
        // того, кому верит: в замере 43% убийц доверяли жертве выше 7 из 10,
        // а 48% жертв были им союзниками. Считать это надо до совести
        хочу -= a.trust.Взять(victim.id, 3.0) * b["убийство_за_доверие"];
        // и того, у кого на руках ребёнок, нож в спину не касается: ему есть
        // что терять и есть ради кого не рисковать. Раньше в формуле стояли
        // только ЧУЖИЕ иждивенцы, и половина убийц оказывалась матерями
        if (a.dependents > 0)
            хочу -= b["убийство_свой_ребёнок"];
        // главное: за нож берутся не от ссоры, а когда разойтись нельзя.
        // Хозяин может выставить гостя, гость может уйти — если ему есть куда
        // вернуться. А вот тот, чью квартиру разобрали на доски, пока он
        // грелся у соседа, заперт с ним в одной комнате
        bool есть_куда;
        if (string.Equals(a.living_with, victim.id, StringComparison.Ordinal))
        {
            var своя = h.flats[a.apt];
            есть_куда = h.flat_temp(своя, burning: Социальное.своя_топится(h, a),
                                    powered: h.power_on)
                        > b["комфортная_температура"] - 8;
        }
        else
            // правда: под одной крышей: силу соседа по комнате знаешь
            есть_куда = a.power() >= victim.power() * b["выгнать_превосходство"];
        if (есть_куда)
            хочу -= b["убийство_есть_выход"];
        хочу -= a.t01("лояльность") * b["убийство_совесть"];
        // и просто страшно: за нож против того, кого боишься, берутся тяжелее
        // всего — он может проснуться, а дальше в комнате останется один
        хочу -= a.боится(victim.id) * b["страх_вес_насилия"];
        хочу -= a.allies.Contains(victim.id) ? b["убийство_союзник"] : 0.0;
        хочу -= victim.dependents > 0 ? 2.5 : 0.0;
        // рядом был он один, и дом это поймёт: чем больше свидетелей вокруг,
        // тем страшнее. Скрытному страшно меньше
        хочу -= b["убийство_страх_раскрытия"] * (1.0 + 0.15 * h.alive().Count)
                * (1.4 - Конфликт.stealth(a));
        // даже спящий сильный человек может проснуться
        хочу -= Math.Max(0.0, victim.power() - a.power()) * 0.8;  // правда: под одной крышей
        return хочу;
    }

    /// <summary>
    /// Стоит ли ночью собрать хозяйское и уйти к себе.
    ///
    /// Середина, которой в модели не было. Мотив «переехать не греться,
    /// а посмотреть» был давно, а расплаты за него не существовало: втереться
    /// было можно, а вынести нельзя, и единственным выходом из чужой квартиры
    /// оставался нож. Отсюда и перекос: человек, которому нужны были чужие
    /// банки, шёл убивать за них хозяина.
    ///
    /// Отличий от кражи два, и оба в пользу вора. Замка нет — он внутри.
    /// И шкаф он видел своими глазами. Отличие от убийства одно, и оно против
    /// него: хозяин остаётся жив и наутро точно знает, кто у него ночевал.
    /// </summary>
    public static double оценка_обобрать(House h, NPC гость, NPC хозяин)
    {
        var b = h.B;
        var своя = h.flats[гость.apt];
        // правда: под одной крышей: шкаф видел своими глазами
        double добыча = Ресурсы.Вещи(хозяин.stock) * b["обобрать_вес_добычи"];
        double хочу = добыча * (0.25 + гость.t01("жадность") * 0.9);
        хочу += гость.desperation() * b["обобрать_за_отчаяние"];
        хочу += гость.hate.Взять(хозяин.id, 0.0) / 25.0;
        хочу += гость.не_прощу.Contains(хозяин.id) ? b["обида_вес_мести"] : 0.0;
        // уходить надо в ту же ночь, и уходить есть смысл только туда, где
        // не замёрзнешь. Унесённые дрова свою же квартиру и протопят — но
        // только если в ней есть чем топить и если её ещё не разобрали
        double тепло = h.flat_temp(своя,
            burning: своя.shelter.Взять("буржуйка", 0.0) != 0.0, powered: h.power_on);
        хочу -= Math.Max(0.0, b["комфортная_температура"] - тепло) * b["обобрать_за_холод"];
        // и всё, что держит руку: доверие к тому, кто пустил, история пары,
        // совесть, страх и простая мысль, что он может проснуться
        хочу -= гость.trust.Взять(хозяин.id, 3.0) * b["обобрать_за_доверие"];
        хочу -= гость.свой(хозяин.id) * b["обобрать_за_близость"];
        хочу -= гость.t01("лояльность") * b["обобрать_совесть"];
        хочу -= гость.боится(хозяин.id) * b["страх_вес_кражи"];
        // правда: под одной крышей
        хочу -= Math.Max(0.0, хозяин.power() - гость.power()) * b["обобрать_за_силу"];
        // наутро об этом узнает весь подъезд, и объяснить себя будет нечем
        хочу -= b["обобрать_решимость"];
        // и то, сколько он тут живёт. К тому, кто вчера пустил тебя к своей
        // печке, ночью не встают: ты ещё не знаешь этой квартиры, тебя ещё
        // разглядывают, и главное — ты только что получил ровно то, за чем
        // шёл. В журнале иначе выходило, что дом складывается в общий котёл
        // и в ту же ночь двое гостей из трёх обирают хозяина
        double прожил = h.day - гость.переехал_день;
        double умысел = гость.переезд_умысел;
        хочу -= Math.Max(0.0, b["обобрать_обжиться_дней"] - прожил)
                * b["обобрать_за_новизну"] * (1.0 - умысел);
        return хочу;
    }

    /// <summary>
    /// Условие запуска рейда ровно по GDD 16: «рейд запускается, когда паника
    /// выше половины и высока либо ненависть, либо осведомлённость».
    ///
    /// Пороги из документа больше не делятся на агрессивность дома: когда они
    /// делились, «паника выше половины» на практике означала «выше четверти»,
    /// и записанное в GDD условие переставало описывать игру.
    /// </summary>
    public static NPC? consider_raid(House h, NPC npc)
    {
        var b = h.B;
        double A = Конфликт.aggr(h);
        // ворота нормальности стоят первыми: пока жизнь ещё похожа
        // на обычную, человек до чужой двери просто не додумывается — какой
        // бы ни была паника. Раньше эта проверка стояла после паники
        // и не срабатывала ни разу
        if (npc.normalcy > b["нормальность_потолок_налёта"])
            return null;
        if (npc.panic < b["налёт_порог_паники"])
            return null;
        // «нечего терять»: умирающий идёт и разбитым, и один — просто почти
        // наверняка неудачно. Пока это был запрет, 26% случаев «рядом сытый
        // сосед, а я умираю от голода» упирались именно в него
        if ((npc.health < 35 || npc.injuries.Count >= 2)
            && npc.desperation() < b["налёт_нечего_терять"])
            return null;
        // к чужой двери с ребёнком на руках не идут — ни вожаком, ни в толпе
        if (npc.dependents > 0)
            return null;
        // налёт — это всегда либо нужда, либо личное
        // ноль на пустом словаре — то же, что `max(values or [0])` в Python:
        // злость снизу зажата нулём, отрицательной её не бывает
        double злейшая = 0.0;
        foreach (string id in npc.hate.Ключи)
            злейшая = Math.Max(злейшая, npc.hate.Взять(id, 0.0));
        if (npc.desperation() < 0.30 / A && злейшая < 50 / A)
            return null;
        NPC? кто = null;
        double лучшее = 0.0;
        foreach (var t in h.others(npc))
        {
            // к тому, с кем живёшь под одной крышей, не идут с ломом
            if (h.под_одной_крышей(npc, t))
                continue;
            // и к двери переехавшего тоже: за ней пусто, а сам он у хозяина —
            // если нужны его запасы, идти надо к хозяину, он в этом же списке
            if (!string.IsNullOrEmpty(t.living_with))
                continue;
            double hate = npc.hate.Взять(t.id, 0.0);
            double aware = npc.сведения_о(t.id).aware;
            if (hate < b["налёт_порог_ненависти"]
                && aware < b["налёт_порог_осведомлённости"])
                continue;
            double want = npc.loot_value(t.id) * (0.5 + npc.t01("жадность"));
            want *= 0.6 + npc.desperation() * 1.4;
            want += hate / 25.0;
            // за дверью не только банки: за ней стены, печка и целая дверь.
            // Это второй мотив осады, и он не кончается, в отличие от еды
            want += Конфликт.хочу_его_квартиру(h, npc, t) * b["налёт_вес_жилья"];
            // если тихо взять не выйдет, дверь начинает притягивать людей
            // с ломом: укреплённая квартира защищает от вора и приманивает
            // налёт (GDD 16)
            want += (1.0 - Конфликт.theft_chance(h, npc, t, известно: false)) * 2.6;
            // страх перед хозяином: человек считает не себя одного, а тех,
            // кого реально может привести. Считаем тем же кодом, что
            // и собирает группу, — иначе вожак идёт туда, куда его группа
            // не пойдёт, и остаётся у двери один
            // прикидка, а не зов: он ещё не пошёл
            int crew_size = Конфликт.recruit(h, npc, t, прикидка: true).crew.Count;
            // за дверью не один человек, а квартира: сожители дерутся за неё
            // по определению. Пока страх считался по одному хозяину, «вместе
            // безопаснее» было правдой только в момент драки.
            // И по силе, какой она кажется вожаку, а не какая есть: здоровье
            // за чужой дверью он не видит — видит лицо на площадке
            var дом_цели = h.household(t);
            double fear = Util.Sum(дом_цели.Select(p => npc.видимая_сила(p)))
                          * (1.4 - npc.t01("храбрость")) * 1.5;
            fear /= 1.0 + 0.45 * (crew_size - 1);
            fear += t.shelter.Взять("дверь", 0.0) * 0.8;
            // и то, кого он за этой дверью боится. Не «сильный», а именно
            // страшный: тот, кто на его глазах стрелял, зарубил соседа или
            // вышел на площадку со стволом. Сила забывается, страх помнится
            fear += дом_цели.Max(p => npc.боится(p.id)) * b["страх_вес_налёта"];
            if (Таблицы.ОГНЕСТРЕЛ.Contains(t.weapon) && npc.сведения_о(t.id).aware > 30)
                fear += 2.2;
            // и то, каким его КАЖУТ: слабость видна и она приглашает. Не правда
            // мира — по правде мира у осаждающего нет способа узнать, сколько
            // у соседа здоровья, — а лицо, которое он видел на площадке
            double слабость = дом_цели.Count > 0
                              ? дом_цели.Max(p => npc.плох(p.id)) : 0.0;
            fear -= слабость * b["добить_за_слабость"];
            // к тому, кого не простил, идут и через страх: это не расчёт, а счёт
            if (npc.не_прощу.Contains(t.id))
                fear -= b["обида_вес_мести"];
            // и свет на площадке. Кто-то в доме не спит — значит, их услышат
            // на лестнице и поднимут весь подъезд. До сих пор дежурство
            // не значило для налётчика ровно ничего: 96 осад из 115
            // приходились на ночи, когда кто-то дежурил.
            // правда: видно: свет на площадке — кто этой ночью не спит
            int дежурят = h.others(npc).Count(
                o => o.tonight == Ночь.ДЕЖУРИТЬ
                     && !string.Equals(o.id, t.id, StringComparison.Ordinal));
            if (дежурят > 0)
                fear += b["налёт_страх_дежурства"] * Math.Min(2, дежурят);
            // совесть
            double conscience = npc.вес_черт("налёт_совесть")
                                * (1.0 - npc.desperation() * 0.5) / A;
            // на своего идти тяжело
            conscience += npc.allies.Contains(t.id) ? 3.5 : 0.0;
            // к матери с ребёнком идут последними
            conscience += t.dependents > 0 ? 1.2 : 0.0;
            // и тот, кто ещё пригодится: единственный человек в доме, который
            // умеет собрать генератор или сбить жар. Это, кажется,
            // единственная защита в этой игре, которая не из досок
            if (new[] { "слесарь", "электрик", "медик" }
                    .Any(u => t.skills.Contains(u, StringComparer.Ordinal)))
            {
                conscience += b["налёт_польза_мастера"];
                if (string.Equals(h.мастер_занят.Взять(t.id, null), npc.id,
                                  StringComparison.Ordinal))
                    conscience += b["налёт_польза_мастера"];   // он сейчас делает мне печь
            }
            // в одиночку к чужой двери идут только те, кто явно сильнее
            // хозяина: GDD 16 говорит о группе, а один человек у двери —
            // это не осада, а разговор через цепочку
            bool соло = crew_size < b["налёт_минимум_группы"]
                        && npc.power() < npc.видимая_сила(t) * b["налёт_соло_превосходство"];
            if (соло)
            {
                if (npc.desperation() < b["налёт_нечего_терять"])
                    continue;
                fear *= b["налёт_соло_страх"];     // он понимает, на что идёт
            }
            double score = want - fear - conscience + npc.пунктик("налёт_вожак");
            if (кто is null || score > лучшее)
            {
                кто = t;
                лучшее = score;
            }
        }
        return кто is not null && лучшее >= b["налёт_порог_желания"] / A ? кто : null;
    }
}
