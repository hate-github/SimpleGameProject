// Перенос house/actions.py, строки 3169–3434: просьба, мена и то, что решает
// хозяин у своей двери.
//
// GDD 14: просьба без доверия сама по себе опасна. Отсюда два решения хозяина
// подряд — открыть ли вообще и дать ли, — и оба задаются ему как вопросы,
// а не считаются за него.

namespace Дом.Ядро;

public static partial class Действия
{
    /// <summary>
    /// Откроет ли он вообще. Вероятность до броска. Через дверь тоже
    /// разговаривают, но так почти не дают и почти ничего друг о друге
    /// не узнают.
    /// </summary>
    public static double откроет_дверь(House h, NPC хозяин, NPC просящий, Баланс b)
    {
        double trust = хозяин.trust.Взять(просящий.id, 3.0);
        double откроет = b["дверь_база_открыть"] + trust * 0.06
                         - хозяин.hate.Взять(просящий.id, 0.0) / b["дверь_ненависть_делитель"]
                         - хозяин.panic / 400.0
                         - хозяин.боится(просящий.id) * b["страх_вес_двери"]
                         + (хозяин.allies.Contains(просящий.id) ? 0.15 : 0.0)
                         - (хозяин.dependents > 0 ? 0.05 : 0.0);
        return Util.Clamp(откроет, 0.05, 0.97);
    }

    /// <summary>
    /// Решает хозяин: отдать ли из того, что считает лишним для себя.
    /// Больше нуля — даст, если есть из чего.
    /// </summary>
    public static double даст_ли(House h, NPC хозяин, NPC просящий, string res,
                                 bool через_дверь, Баланс b)
    {
        double trust = хозяин.trust.Взять(просящий.id, 3.0);
        double give = хозяин.t01("лояльность") * 5.0 + trust * 0.9;
        give -= хозяин.t01("жадность") * 2.5;
        give -= хозяин.hate.Взять(просящий.id, 0.0) / 12.0;
        // «я тебе уже трижды давал»: бесконечно отдавать нельзя, и отказ
        // по этой причине читается иначе, чем жадность
        double долг = хозяин.дал.Взять(просящий.id, 0.0);
        give -= долг * b["долг_вес"];
        if (хозяин.allies.Contains(просящий.id))
            give += 2.5;
        if (просящий.dependents > 0)
            give += 1.8;
        if (хозяин.favors.Взять(просящий.id, 0) != 0)
            give += 1.0;
        // с тем, кто уже врал или не сдержал слова, дела не ведут. И отказ
        // этот не про жадность — просто ему больше не верят (GDD 14)
        give -= хозяин.не_верю.Взять(просящий.id, 0.0) * b["обещание_вес_репутации"];
        if (через_дверь)
            give -= b["просьба_через_дверь"];
        // главное: человек отдаёт только то, что считает лишним для себя.
        // Он не знает, сколько ещё терпеть, и считает по своему горизонту
        double shortfall = 1.0 - Math.Min(1.0, хозяин.secure(res));
        if (string.Equals(res, "лекарства", StringComparison.Ordinal))
            // аптечка не тратится по стольку-то в день: у неё не запас
            // на срок, а «есть или нет», и по горизонту она в дефиците всегда.
            // Отдают её тогда, когда самому она сейчас не нужна
            shortfall = нужна_аптечка(хозяин) ? 1.0 : 0.0;
        give -= shortfall * h.B["жадность_от_нехватки"];
        give -= shortfall * хозяин.t01("жадность") * 4.0;
        // и то, чего в отказе не было вовсе: страх. Тому, кто на глазах
        // у всех зарубил соседа, банку отдают не из щедрости, а чтобы он ушёл
        give += хозяин.боится(просящий.id) * b["страх_уступает"];
        // своим последним топливом делятся тяжелее, чем последней банкой,
        // а последней аптечкой — тяжелее всего: это не запас, а чужая жизнь
        // против своей
        if (string.Equals(res, "топливо", StringComparison.Ordinal))
            give -= 1.0;
        else if (string.Equals(res, "лекарства", StringComparison.Ordinal))
            give -= b["просьба_за_аптечку"];
        return give - 3.0;                      // порог, при котором ещё дают
    }

    /// <summary>
    /// Просьба о припасах. <paramref name="res"/> — за чем пришёл; решено
    /// в сборе и пришло сюда целиком, чтобы человек просил то, что выбрал,
    /// а не то, что пересчиталось.
    /// </summary>
    public static string _ask(House h, NPC npc, NPC target, string? res = null)
    {
        var b = h.B;
        double trust = target.trust.Взять(npc.id, 3.0);
        double долг = target.дал.Взять(npc.id, 0.0);
        if (res is null)
        {
            h.bump("пересчётов_в_исполнении");
            res = что_просить(h, npc, target);
        }
        double has = target.stock.Взять(res, 0.0);
        // первое решение хозяина: открыть ли — монета по его склонности
        bool через_дверь = !Решение.монета(h, target, Вопрос.ОТКРЫТЬ_ДВЕРЬ,
            "открыть", "через дверь", откроет_дверь(h, target, npc, b));
        // сам факт просьбы: «просят — значит, скоро будут отбирать» (GDD 14)
        target.panic = Util.Clamp(target.panic + 4);
        // человек, пришедший просить, сам о себе всё и рассказал: теперь сосед
        // знает, что у него пусто. Раньше здесь стояло aware=-5 — просьба
        // почему-то делала просящего менее понятным
        Социальное.adjust(target, npc.id,
            aware: b["просьба_осведомлённость"] * (через_дверь ? 0.4 : 1.0));
        Социальное.note_signal(target, npc.id, res, 0.5, 0.35);
        Социальное.adjust(npc, target.id, aware: 12 * (через_дверь ? 0.3 : 1.0));
        // открытая дверь и двое на взводе — это не всегда разговор
        if (!через_дверь)
        {
            double жар = (npc.hate.Взять(target.id, 0.0)
                          + target.hate.Взять(npc.id, 0.0)) / 200.0;
            жар += (npc.t01("вспыльчивость") + target.t01("вспыльчивость")) * 0.25;
            жар *= 0.5 + нужда(npc);
            if (h.rng.Chance(Util.Clamp(b["дверь_риск_ссоры"] * жар, 0.0, 0.5)))
            {
                h.journal.line($"{npc.@short} и {target.@short} сцепились в дверях.", 2);
                Конфликт.scuffle(h, npc, target, place: $"кв.{target.apt}");
                Социальное.register_incident(h, "ссора", null);
                Социальное.adjust(target, npc.id, hate: 15, trust: -2.0);
                Социальное.adjust(npc, target.id, hate: 15, trust: -2.0);
                var отказ = npc.ask_record(target.id);
                отказ.последняя = h.day;
                отказ.отказали += 1;
                отказ.подряд += 1;
                return $"{npc.@short} {Util.Vb(npc.sex, "пришёл")} просить у "
                       + $"{target.form("gen")} — вышла драка";
            }
        }
        // второе решение хозяина — дать ли — только теперь: если в дверях
        // вышла драка, спрашивать было не о чем. `даст_ли` ничего не бросает,
        // поэтому порядок вопросов сдвинулся, а лента случайности — нет
        bool даст = Решение.по_правилу(h, target, Вопрос.ДАТЬ_ИЗ_СВОЕГО, "дать", "отказать",
                                       даст_ли(h, target, npc, res, через_дверь, b));
        double цена = b["просьба_цена_доверия"] * (1.0 - Math.Min(1.0, trust / 8.0));
        Социальное.adjust(target, npc.id, trust: -цена);

        var rec = npc.ask_record(target.id);
        rec.последняя = h.day;
        if (has >= 2 && даст)
        {
            target.stock[res] = has - 1;
            npc.stock[res] = npc.stock.Взять(res, 0.0) + 1;
            Социальное.adjust(npc, target.id, trust: b["доверие_за_помощь"], hate: -15);
            Социальное.adjust(target, npc.id, trust: 0.5);
            npc.mood = Util.Clamp(npc.mood + 8);
            target.mood = Util.Clamp(target.mood + 4);
            npc.favors[target.id] = npc.favors.Взять(target.id, 0) + 1;
            rec.должен += 1.0;
            target.дал[npc.id] = target.дал.Взять(npc.id, 0.0) + 1.0;
            rec.дали += 1;
            rec.подряд = 0;
            // я ему дал — теперь не прошу сам
            target.ask_record(npc.id).я_дал = h.day;
            h.bump("помощи");
            // дал тот, у кого просили: «кто» события — всегда тот, чей это поступок
            h.событие(ВидСобытия.ПОМОЩЬ, кто: target.id, кому: npc.id, что: res,
                      сколько: 1.0, где: target.apt);
            // «верну к пятнице»: у долга появляется срок, а у слова — цена
            var обещание = Социальное.обещать(h, npc, target, "отдать", res);
            // и заодно: если про пришедшего кто-то говорил «он вор», а он вот
            // стоит и просит банку, а не берёт молча, — наговор всплывает
            Социальное.проверить_наговор(h, npc, target);
            string хвост = обещание is not null
                           ? $", {Util.Vb(npc.sex, "обещал")} вернуть" : "";
            return $"{npc.@short} {Util.Vb(npc.sex, "попросил")} "
                   + $"{(RES_GEN.TryGetValue(res, out var р1) ? р1 : res)} "
                   + $"у {target.form("gen")} — дали{хвост}";
        }
        // соврать про свои запасы — самый дешёвый отказ из всех: сосед уходит
        // не злым, а сочувствующим, и оценка твоего шкафа у него падает.
        // Пока это не разоблачат (запах, дым, увиденный шкаф)
        bool врёт = has >= 2 && Социальное.решает_врать(h, target, npc, "своё");
        if (врёт)
        {
            Социальное.соврал(h, target, npc, "своё", res);
            Социальное.note_signal(npc, target.id, res, b["ложь_оценка"], 0.7);
        }
        // отказ тем обиднее, чем нужнее было: и когда кончается, и когда
        // невмоготу. И меряет его просящий своей меркой: тому, кто считает,
        // что ему все должны, в чужом «нет» слышится не бедность,
        // а высокомерие
        Социальное.judge(h, target, "высокомерие",
            hate: b["ненависть_за_отказ"] * (0.7 + нужда(npc))
                  * (врёт ? b["ложь_смягчает_отказ"] : 1.0),
            trust: b["доверие_за_отказ"], witnesses: new[] { npc },
            участники: new[] { npc });
        rec.отказали += 1;
        rec.подряд += 1;
        // и это ход в обратную сторону по близости, односторонний: отказавший
        // ничего не потерял, для него просто зашёл сосед, — а тот, кому
        // отказали, стоял под дверью и слышал «нет»
        Социальное.отдалились(npc, target.id, b["близость_за_отказ"]);
        // «жмётся — значит есть». Отказ выдаёт запасы не хуже наблюдения —
        // но не тогда, когда в отказе поверили
        if (!врёт)
            Социальное.adjust(npc, target.id, aware: b["отказ_осведомлённость"]);
        npc.mood = Util.Clamp(npc.mood - 6);
        h.bump("отказов");
        string род = RES_GEN.TryGetValue(res, out var р2) ? р2 : res;
        if (врёт)
        {
            string сам = string.Equals(target.sex, "ж", StringComparison.Ordinal)
                         ? "самой" : "самого";
            return $"{npc.@short} {Util.Vb(npc.sex, "просил")} {род} "
                   + $"у {target.form("gen")} — {Util.Vb(target.sex, "сказал")}, "
                   + $"что у {сам} нет";
        }
        if (долг >= b["долг_предел"])
            return $"{npc.@short} {Util.Vb(npc.sex, "попросил")} {род} "
                   + $"у {target.form("gen")} — {Util.Vb(target.sex, "напомнил")}, "
                   + $"сколько уже {Util.Vb(target.sex, "отдал")}, и не дал";
        if (через_дверь)
            return $"{npc.@short} {Util.Vb(npc.sex, "просил")} {род} "
                   + $"у {target.form("gen")} через дверь — не открыли";
        return $"{npc.@short} {Util.Vb(npc.sex, "попросил")} {род} "
               + $"у {target.form("gen")} — отказали";
    }

    /// <summary>Мена: сговорились или нет. null — предлагать было нечего.</summary>
    public static string? _trade(House h, NPC a, NPC b_npc)
    {
        var deal = find_deal(h, a, b_npc);
        if (deal is null)
            return null;
        var ((give, gn), (get_, tn)) = deal.Value;
        if (a.stock.Взять(give, 0.0) < gn)
            return null;
        string родGet = RES_GEN.TryGetValue(get_, out var рg) ? рg : get_;
        if (b_npc.stock.Взять(get_, 0.0) < tn)
        {
            // пришёл менять на то, чего у соседа нет: сходил зря и понял,
            // что ошибся
            Социальное.note_signal(a, b_npc.id, get_, 0.0, 0.6);
            Социальное.adjust(a, b_npc.id, aware: 6);
            // и запоминает, за чем именно ходил зря. Пока этого не было,
            // оценка чужого шкафа к утру подтягивалась обратно к «не знаю»,
            // и человек шёл к тому же соседу за тем же самым: 79 холостых
            // ходок за жизнь против 102 состоявшихся
            a.ask_record(b_npc.id).нет[get_] = h.day;
            h.bump("сделок_сорвалось");
            return $"{a.@short} {Util.Vb(a.sex, "предложил")} {b_npc.form("dat")} мену, "
                   + $"но {родGet} у {b_npc.form("gen")} не оказалось";
        }
        // сосед считает выгоду по СВОИМ настоящим запасам — и может отказаться
        double их = Социальное.value_of(b_npc, give, gn) - Социальное.value_of(b_npc, get_, tn);
        // и последнее слово за ним самим: правило прежнее — меняется, когда
        // выгодно, — но теперь это его ответ, а не вывод о нём
        if (!Решение.по_правилу(h, b_npc, Вопрос.МЕНЯТЬСЯ, "меняться", "отказать", их))
        {
            Социальное.adjust(a, b_npc.id, aware: 4);
            // «нет» помнят так же, как помнят «у меня этого нет»: ходить
            // к той же двери с тем же предложением человек перестаёт до тех
            // пор, пока у соседа не переменятся дела
            a.ask_record(b_npc.id).мена[ключ_отказа(give, get_)] = h.day;
            // и сам отказ — это сведения, ровно как отказ в просьбе: не берёт
            // мою воду за свою банку — значит, воды у него хватает
            Социальное.note_signal(a, b_npc.id, give,
                a.believed(b_npc.id, give) + h.B["мена_отказ_оценка"], 0.5);
            // и злит. Не как предательство — как то, чем оно и является:
            // человек шёл через холодную лестницу к тому, у кого, по его
            // сведениям, это есть, и вернулся ни с чем. Злость небольшая,
            // но она копится и через ненависть попадает в налёт
            Социальное.adjust(a, b_npc.id,
                hate: h.B["мена_отказ_злость"] * Math.Min(1.0, a.desperation() + 0.3));
            var зап = a.ask_record(b_npc.id);
            зап.мена_подряд += 1;
            if (зап.мена_подряд >= h.B["мена_хватит_отказов"])
            {
                зап.мена_подряд = 0.0;
                зап.мена_закрыт = h.day;
            }
            h.bump("сделок_отклонено");
            return $"{b_npc.@short} не {Util.Vb(b_npc.sex, "стал")} меняться "
                   + $"с {a.form("ins")}";
        }
        a.stock[give] = a.stock.Взять(give, 0.0) - gn;
        b_npc.stock[give] = b_npc.stock.Взять(give, 0.0) + gn;
        b_npc.stock[get_] = b_npc.stock.Взять(get_, 0.0) - tn;
        a.stock[get_] = a.stock.Взять(get_, 0.0) + tn;
        Социальное.adjust(a, b_npc.id, trust: h.B["доверие_за_сделку"], aware: 10);
        Социальное.adjust(b_npc, a.id, trust: h.B["доверие_за_сделку"], aware: 10);
        a.ask_record(b_npc.id).мена_подряд = 0.0;   // сговорились — счёт обнулился
        h.bump("обменов");
        h.событие(ВидСобытия.ОБМЕН, кто: a.id, кому: b_npc.id, что: $"{give} за {get_}",
                  сколько: gn, где: b_npc.apt);
        Социальное.сблизились(h, a, b_npc, h.B["близость_за_обмен"]);
        // сделка с деньгами — это уже не мена, а купля-продажа, и в журнале
        // она должна читаться так же: за что и почём
        if (string.Equals(get_, "деньги", StringComparison.Ordinal))
        {
            h.bump("продаж");
            return $"{a.@short} {Util.Vb(a.sex, "продал")} "
                   + $"{(RES_ACC.TryGetValue(give, out var в1) ? в1 : give)} "
                   + $"{b_npc.form("dat")} за {Текст.G(tn)}";
        }
        if (string.Equals(give, "деньги", StringComparison.Ordinal))
        {
            h.bump("продаж");
            return $"{a.@short} {Util.Vb(a.sex, "купил")} "
                   + $"{(RES_ACC.TryGetValue(get_, out var в2) ? в2 : get_)} "
                   + $"у {b_npc.form("gen")} за {Текст.G(gn)}";
        }
        return $"{a.@short} {Util.Vb(a.sex, "обменял")} "
               + $"{(RES_ACC.TryGetValue(give, out var в3) ? в3 : give)} на "
               + $"{(RES_ACC.TryGetValue(get_, out var в4) ? в4 : get_)} "
               + $"с {b_npc.form("ins")}";
    }
