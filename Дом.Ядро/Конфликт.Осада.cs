    /// <summary>
    /// Кто из дежурных услышал их на лестнице и поднял дом. Или null.
    ///
    /// Услышать проще, чем решиться: на площадке трое с ломом, и они
    /// не крадутся. Мешает погода — в буран ветер глушит всё (GDD 21), —
    /// и мешает собственная усталость. Не мешает ничего больше: это и есть
    /// смысл не спать.
    /// </summary>
    public static NPC? дежурный_услышал(House h, IReadOnlyList<NPC> crew, NPC target)
    {
        var b = h.B;
        var состав = new HashSet<string>(crew.Select(c => c.id), StringComparer.Ordinal);
        var дежурные = h.alive()
            .Where(p => p.tonight == Ночь.ДЕЖУРИТЬ && !состав.Contains(p.id)
                        && !string.Equals(p.id, target.id, StringComparison.Ordinal))
            .ToList();
        if (дежурные.Count == 0)
            return null;
        // слышит тот, кто ближе к чужой двери: этажи считаются как для шума
        дежурные = дежурные
            .OrderBy(p => h.floor_gap(p, target))
            .ThenBy(p => p.id, StringComparer.Ordinal).ToList();
        var кто = дежурные[0];
        double шанс = b["дежурный_слышит"] * Социальное.слышимость(h);
        шанс *= Math.Pow(b["дежурный_слышит_этаж"], h.floor_gap(кто, target));
        шанс *= 1.0 + 0.05 * crew.Count;        // чем больше пришло, тем громче
        if (!h.rng.Chance(Util.Clamp(шанс, 0.02, 0.95)))
            return null;
        h.bump("дежурный_поднял_дом");
        кто.bump("поднял_дом");
        h.journal.line($"{кто.@short} не {Util.Vb(кто.sex, "спал")} и "
                       + $"{Util.Vb(кто.sex, "услышал")} их на лестнице. "
                       + $"{Util.Vb(кто.sex, "Поднял")} весь подъезд.", 2);
        // и дом узнаёт состав не по слухам, а глазами
        foreach (var p in crew)
        {
            Социальное.adjust(кто, p.id, aware: 25);
            foreach (var w in h.alive())
                if (!состав.Contains(w.id))
                    Социальное.adjust(w, p.id, aware: 10);
        }
        return кто;
    }

    /// <summary>
    /// Позовёт ли жертва на помощь, когда за дверью стоят с ломом (GDD 16).
    ///
    /// Единственное решение, которого у того, к чьей двери пришли, до сих пор
    /// не было вовсе. Между тем это ровно та минута, ради которой дом
    /// и строился: стоят у двери, и весь вопрос в том, откроет ли кто-нибудь
    /// свою.
    ///
    /// Кричат не все. Мешает храбрость — тот, кто считает, что справится сам,
    /// зовёт последним, — и мешает то, что кричать некому: человек, который
    /// не верит в этот дом, не станет звать его вслух.
    /// </summary>
    public static bool кричать(House h, NPC target, IReadOnlyList<NPC> crew, Баланс b)
    {
        if (!target.здесь())
            return false;
        var состав = new HashSet<string>(crew.Select(c => c.id), StringComparer.Ordinal);
        var соседи = h.others(target).Where(p => !состав.Contains(p.id)).ToList();
        if (соседи.Count == 0)
            return false;
        double хочу = (crew.Count > 0 ? crew.Max(p => target.боится(p.id)) : 0.0)
                          * b["крик_за_страх"]
                      + target.panic / 100.0 * b["крик_за_панику"]
                      // трое у двери — это уже не разговор через дверь
                      + (crew.Count - 1) * b["крик_за_число"];
        // кого он зовёт: не дом вообще, а тех, кто, по его памяти, выходил
        // к другим и к кому он сам выходил
        хочу += соседи.Max(p => target.свой(p.id)) * b["крик_за_своих"];
        хочу += target.t01("общительность") * 1.5;
        хочу -= target.t01("храбрость") * b["крик_гордость"];
        хочу -= b["крик_решимость"];
        // правило сказало своё — последнее слово за жильцом
        return Решение.по_правилу(h, target, Вопрос.КРИЧАТЬ, "кричать", "молчать", хочу);
    }

    /// <summary>
    /// Кто придёт на помощь (союзники и просто порядочные).
    ///
    /// <paramref name="предупреждён"/> — жертву успели предупредить, и она
    /// обошла площадку сама. <paramref name="поднял"/> — дежурный, который
    /// услышал их на лестнице. <paramref name="крик"/> — жертва позвала
    /// на помощь, и её слышал весь подъезд.
    /// </summary>
    public static List<NPC> defenders_of(House h, NPC target, IReadOnlySet<string> crew_ids,
                                         bool предупреждён = false, NPC? поднял = null,
                                         bool крик = false)
    {
        var d = new List<NPC> { target };
        if (поднял is not null && !crew_ids.Contains(поднял.id)
            && !string.Equals(поднял.id, target.id, StringComparison.Ordinal))
            d.Add(поднял);
        // те, кто живёт в этой квартире, дерутся за неё по определению
        foreach (var p in h.others(target))
        {
            if (crew_ids.Contains(p.id) || d.Contains(p))
                continue;
            if (string.Equals(p.living_with, target.id, StringComparison.Ordinal)
                || string.Equals(target.living_with, p.id, StringComparison.Ordinal))
                d.Add(p);
        }
        foreach (var p in h.others(target))
        {
            if (d.Contains(p))
                continue;
            if (crew_ids.Contains(p.id) || p.health < 40)
                continue;
            double will = p.trust.Взять(target.id, 3.0) * 0.6 + p.t01("лояльность") * 4.0
                          + p.t01("храбрость") * 3.0;
            // и то, чего в этом решении не было вовсе: свой он ему или чужой.
            // Выйти ночью на лестницу за человека — самое сильное событие пары
            // в этой игре, но сама близость на выход не влияла ни на грамм:
            // считались доверие, лояльность и храбрость, то есть репутация
            // и характер. Оттого за незнакомого выходили с той же готовностью,
            // что и за того, с кем полжизни у одной печки
            will += p.свой(target.id) * h.B["защита_за_близость"];
            will -= p.panic / 100.0 * 3.0;
            will -= p.hate.Взять(target.id, 0.0) / 20.0;
            // на лестницу против того, кого боишься, не выходят даже за своего
            will -= (crew_ids.Count > 0 ? crew_ids.Max(c => p.боится(c)) : 0.0)
                    * h.B["страх_вес_защиты"];
            if (p.allies.Contains(target.id))
                will += 3.0;
            if (p.dependents > 0)
                will -= 2.0;
            // и то, что этот дом уже знает друг про друга: когда кричал он сам,
            // этот сосед не вышел. Помнится это ровно там, где имеет значение
            if (p.не_вышли.Contains(target.id))
                will -= h.B["невыход_помнят"];
            // и то, о чём эти двое условились ещё до всякой осады: перезимовать
            // вдвоём. Замысел не даёт ни еды, ни тепла — он даёт вот эту минуту
            if (p.замысел is not null
                && string.Equals(p.замысел.вид, "вместе", StringComparison.Ordinal)
                && string.Equals(p.замысел.друг, target.id, StringComparison.Ordinal))
                will += h.B["замысел_вместе_защита"];
            double порог = 6.5;
            if (предупреждён)
                порог -= h.B["предупреждён_порог_защиты"];
            if (крик)
                // на крик выходят не потому, что стали храбрее, а потому,
                // что теперь это выбор, а не неведение: слышали все, и все
                // знают, что слышали все
                порог -= h.B["крик_порог_защиты"] * (0.5 + p.свой(target.id));
            if (поднял is not null)
                порог -= h.B["дежурный_порог_защиты"];   // его будят, а не он решает
            // и последнее слово за самим соседом. Правило то же — NPC выходит,
            // когда перевесило, — но теперь это его решение, а не вывод функции
            // о нём: игрок в этой роли услышит, что за стеной ломают дверь,
            // и ответит сам
            if (Решение.по_правилу(h, p, Вопрос.ВЫЙТИ_К_ДВЕРИ, "выйти", "остаться",
                                   will - порог))
                d.Add(p);
        }
        return d;
    }

    /// <summary>Чем кончилась осада.</summary>
    public enum ИсходОсады
    {
        УШЛИ_НА_КРИК, ОТКУПИЛСЯ, ПЕРЕУБЕДИЛ, ОТБИЛСЯ, СБЕЖАЛ,
        УБИТ, ЗАНЯЛ, ИЗГНАН, ОГРАБЛЕН,
    }

    /// <summary>Как исход осады называется в событии дня — теми же словами,
    /// что в прототипе: их читает отчёт и по ним считаются исходы.</summary>
    public static string Словами(ИсходОсады и) => и switch
    {
        ИсходОсады.УШЛИ_НА_КРИК => "ушли на крик",
        ИсходОсады.ОТКУПИЛСЯ    => "откупился",
        ИсходОсады.ПЕРЕУБЕДИЛ   => "переубедил",
        ИсходОсады.ОТБИЛСЯ      => "отбился",
        ИсходОсады.СБЕЖАЛ       => "сбежал",
        ИсходОсады.УБИТ         => "убит",
        ИсходОсады.ЗАНЯЛ        => "занял",
        ИсходОсады.ИЗГНАН       => "изгнан",
        _                       => "ограблен",
    };

    /// <summary>Осада по стадиям (GDD 16).</summary>
    public static ИсходОсады run_siege(House h, NPC leader, NPC target)
    {
        var b = h.B;
        var (crew, отказали) = recruit(h, leader, target);
        // вожак обошёл соседей, и это не проходит бесследно, кто бы что
        // ни ответил
        var предупредил = зов(h, leader, target, отказали);
        var crew_ids = new HashSet<string>(crew.Select(p => p.id), StringComparer.Ordinal);
        // состав читает обвязка покрытия: пока она звала recruit сама,
        // зов выполнялся дважды
        h.сутки.состав_налёта.Clear();
        h.сутки.состав_налёта.AddRange(crew.Select(p => p.id));
        // предательство: на дверь идут те, с кем ещё вчера держались вместе
        foreach (var p in crew.Where(p => p.allies.Contains(target.id)).ToList())
        {
            p.allies.Remove(target.id);
            target.allies.Remove(p.id);
            var пара = string.CompareOrdinal(p.id, target.id) <= 0
                       ? (p.id, target.id) : (target.id, p.id);
            h.разрывы[пара] = h.day;
            h.bump("предательств");
            h.bump("союзов_распалось");
            h.journal.line($"{p.@short} {Util.Vb(p.sex, "пришёл")} к двери "
                + $"{target.form("gen")}, с кем ещё вчера "
                + $"{Util.Vb(p.sex, "держался")} вместе.", 2);
            h.note($"предательство: {p.@short} против {target.form("gen")}");
            Социальное.adjust(target, p.id, trust: -6.0, hate: 35);
            Социальное.judge(h, p, "предательство", hate: 10.0, trust: -1.0);
        }
        h.bump("налётов");
        leader.bump("налётов");
        h.событие(ВидСобытия.НАЛЁТ, кто: leader.id, кому: target.id,
                  сколько: crew.Count, где: target.apt);
        // с этой минуты между ними счёты, кем бы ни кончилась ночь у двери.
        // Тяжесть уточнится по исходу: разошлись миром — забудется за пару
        // дней, вынесли квартиру — не забудется
        foreach (var p in crew)
            Социальное.обидели(h, target, p, b["обида_за_осаду"]);
        foreach (var p in crew)
        {
            Социальное.переступил(h, p, "налёт");
            // тот, кто в прошлый раз пообещал не приходить, пришёл снова
            Социальное.нарушил(h, p, target, "не_делать", target.id);
        }
        string names = string.Join(", ", crew.Select(p => p.@short));
        Социальное.register_incident(h, "налёт",
            $"НАЛЁТ. {names} — к двери кв.{target.apt} ({target.@short}).");
        Социальное.emit(h, target, 3, "ссора", night: true);

        // тот, кто не спит и слушает лестницу, слышит троих с ломом. До сих пор
        // дежурство читали ровно два места — шанс кражи и шанс убийства
        // соседа, — и 96 осад из 115 случались в ночь, когда кто-то в доме
        // дежурил, ничего при этом не меняя. Дежурный будит дом: это
        // единственное, ради чего общее дежурство вообще имеет смысл
        var поднял = дежурный_услышал(h, crew, target);

        // ---- стадия 1: предупреждение ----
        bool крикнул = кричать(h, target, crew, b);
        if (крикнул)
        {
            h.bump("криков");
            h.journal.line($"{target.@short} {Util.Vb(target.sex, "закричал")} — так, "
                           + "что слышал весь подъезд.", 2);
            foreach (var w in h.alive())
            {
                if (string.Equals(w.id, target.id, StringComparison.Ordinal))
                    continue;
                Социальное.adjust(w, target.id, aware: b["крик_осведомлённость"]);
                if (!crew_ids.Contains(w.id))
                    Социальное.add_panic(w, b["крик_паника"]);
            }
            // и вожак это слышит. Пока не собрался подъезд, можно уйти:
            // осада не состоялась, но и цены за неё никто не заплатил
            double уйти = b["крик_вожак_уходит"] * (1.4 - leader.t01("храбрость"))
                          / Math.Max(0.5, crew.Count);
            if (Решение.монета(h, leader, Вопрос.УЙТИ_НА_КРИК, "уйти", "остаться",
                               Util.Clamp(уйти, 0.0, 0.9)))
            {
                h.journal.line("На крик в подъезде зажёгся свет. Постояли и ушли.", 2);
                foreach (var p in crew)
                    Социальное.adjust(target, p.id, hate: 20, trust: -2.0);
                h.bump("исход_ушли_на_крик");
                return ИсходОсады.УШЛИ_НА_КРИК;
            }
        }

        // предупреждённый успел обойти площадку сам: выходят к нему и те,
        // кто спросонья не вышел бы. Это и есть цена утечки для вожака
        var defenders = defenders_of(h, target, crew_ids,
                                     предупреждён: предупредил is not null,
                                     поднял: поднял, крик: крикнул);
        double attack_power = Util.Sum(crew.Select(p => p.power()));
        double def_power = Util.Sum(defenders.Select(p => p.power()))
                           * (1.0 + 0.2 * target.shelter.Взять("дверь", 0.0));
        // у двери с оружием в руках привыкают к нему быстрее, чем за месяц
        // ухода за ним: страшно, но руки запоминают
        foreach (var p in crew.Concat(defenders))
            if (p.weapon != Оружие.НЕТ)
            {
                double было = p.рука.Взять(p.weapon,
                    Таблицы.СВОЙСКОЕ.TryGetValue(p.weapon, out var своё) ? своё : 0.0);
                p.рука[p.weapon] = Util.Clamp(было + b["рука_за_бой"], 0.0, 1.0);
            }

        // и то, что дом узнаёт о себе. Кто не вышел на крик — знает, что
        // не вышел, и знает об этом тот, кто кричал. Это не общая ненависть:
        // односторонний шаг близости вниз у самой жертвы, и он не возвращается
        // сам собой. Дом после осады другой не потому, что кто-то плохой,
        // а потому, что теперь известно, кто выходит, а кто нет
        if (крикнул)
        {
            var вышли = new HashSet<string>(defenders.Select(p => p.id),
                                            StringComparer.Ordinal);
            foreach (var p in h.others(target))
            {
                if (вышли.Contains(p.id) || crew_ids.Contains(p.id))
                    continue;
                Социальное.отдалились(target, p.id, b["близость_за_невыход"]);
                target.не_вышли.Add(p.id);
            }
        }

        if (defenders.Count > 1)
        {
            h.bump("осад_с_защитой");
            h.bump("защитников", defenders.Count - 1);
            h.journal.line("На лестницу вышли: "
                + string.Join(", ", defenders.Skip(1).Select(p => p.@short))
                + $" — за {target.form("acc")}.", 2);
            foreach (var d in defenders.Skip(1))
            {
                Социальное.adjust(target, d.id, trust: b["доверие_за_защиту"]);
                // выйти ночью на лестницу за человека — самое сильное событие
                // пары в этой игре, и до сих пор оно в историю пары не попадало
                // вовсе. Симметрично, как разговор и общая печка
                Социальное.сблизились(h, target, d, b["близость_за_защиту"]);
                // и самое дорогое, чем в этом доме гасят обиду
                Социальное.загладил(h, d, target, b["обида_за_защиту"]);
            }
        }

        // у двери есть выходы: откупиться, переубедить, драться
        bool pay_ok = target.stock.Взять("еда", 0.0) + target.stock.Взять("топливо", 0.0) >= 2;
        double fear = Util.Clamp(
            0.25 + (attack_power / Math.Max(0.5, def_power)) * 0.35
            - target.t01("храбрость") * 0.5, 0.0, 0.95);
        double talk = target.t01("общительность") * 0.5
                      + Util.Sum(crew.Select(p => p.trust.Взять(target.id, 3.0)))
                        / (crew.Count * 20.0);
        talk += defenders.Any(p => p.skills.Contains("медик", StringComparer.Ordinal))
                ? 0.25 : 0.0;
        if (предупредил is not null)
        {
            // он ждал их весь вечер и знает, что сказать: это не растерянный
            // человек за дверью, а человек, который успел придумать слова
            talk += b["предупреждён_уговор"];
            fear -= b["предупреждён_смелее"];
        }

        // кого именно он слышит за дверью: перед знакомым топором откупаются
        // охотнее, чем перед незнакомой злостью (GDD 17)
        double страшно = crew.Count > 0 ? crew.Max(p => target.боится(p.id)) : 0.0;
        double готов_платить = Util.Clamp(
            0.45 / aggr(h) * (1.0 + страшно * b["страх_вес_откупа"]), 0.0, 0.95);
        // ворота откупа стали склонностью. Напуганный, трусливый или знающий
        // этот топор бросает монету, как и прежде. Смелый и богатый раньше
        // об откупе не думал вовсе — теперь вопрос задаётся и ему, а отвечает
        // он по ручке откуп_смелого: при нуле — правилом, без броска
        bool напуган = fear > 0.5 || target.t01("храбрость") < 0.45 || страшно > 0.35;
        bool откупается;
        if (pay_ok && напуган)
            откупается = Решение.монета(h, target, Вопрос.ОТКУПИТЬСЯ,
                                        "откупиться", "не платить", готов_платить);
        else if (pay_ok && b["откуп_смелого"] > 0)
            откупается = Решение.монета(h, target, Вопрос.ОТКУПИТЬСЯ,
                "откупиться", "не платить",
                Util.Clamp(готов_платить * b["откуп_смелого"], 0.0, 0.95));
        else if (pay_ok)
            откупается = Решение.по_правилу(h, target, Вопрос.ОТКУПИТЬСЯ,
                                            "откупиться", "не платить", 0.0);
        else
            откупается = false;
        if (откупается)
        {
            var добыча = вынести_на_всех(h, target, crew, b["откуп_доля"]);
            h.journal.line($"{target.@short} "
                + (string.Equals(target.sex, "ж", StringComparison.Ordinal)
                   ? "откупилась: отдала" : "откупился: отдал")
                + $" {_fmt(добыча)}. Ушли.", 2);
            foreach (var p in crew)
            {
                Социальное.adjust(p, target.id, hate: -12);
                Социальное.adjust(target, p.id, hate: 30, trust: -3.0);
                // уговор у двери: «больше не придём». Слово, которое можно
                // нарушить
                Социальное.обещать(h, p, target, "не_делать", target.id);
            }
            _house_learns(h, target, crew);
            // откупился — значит, всё-таки отдал: это уже не «постояли и ушли»
            foreach (var p in crew)
                Социальное.обидели(h, target, p, b["обида_за_откуп"]);
            h.bump("исход_откупился");
            return ИсходОсады.ОТКУПИЛСЯ;
        }

        if (Решение.монета(h, target, Вопрос.ГОВОРИТЬ_ЧЕРЕЗ_ДВЕРЬ, "говорить", "молчать",
                           Util.Clamp(talk * 0.55 / aggr(h), 0.0, 0.6)))
        {
            h.journal.line($"{target.@short} {Util.Vb(target.sex, "говорил")} с ними "
                           + "через дверь. Постояли и разошлись.", 2);
            foreach (var p in crew)
            {
                Социальное.adjust(p, target.id, hate: -6);
                Социальное.adjust(target, p.id, hate: 20, trust: -2.0);
                Социальное.обещать(h, p, target, "не_делать", target.id);
            }
            h.bump("исход_переубедил");
            return ИсходОсады.ПЕРЕУБЕДИЛ;
        }

        // ---- стадия 2: дверь ----
        // угроза оружием часто ценнее выстрела (GDD 17)
        var armed = defenders.Where(d => Таблицы.ОГНЕСТРЕЛ.Contains(d.weapon)
                                         && d.stock.Взять("патроны", 0.0) > 0).ToList();
        if (armed.Count > 0)
        {
            var shooter = armed[0];
            double scare = b["угроза_оружием_отпугивает"]
                * (1.0 - Util.Sum(crew.Select(p => p.t01("храбрость"))) / crew.Count * 0.6);
            scare /= aggr(h);
            // уйти от ствола или лезть дальше — решает вожак, он привёл людей
            if (Решение.монета(h, leader, Вопрос.УЙТИ_ОТ_СТВОЛА, "уйти", "лезть дальше",
                               Util.Clamp(scare, 0.05, 0.95)))
            {
                h.journal.line($"{shooter.@short} "
                    + (string.Equals(shooter.sex, "ж", StringComparison.Ordinal)
                       ? "вышла" : "вышел")
                    + " на площадку со стволом. Разошлись без слова.", 2);
                Социальное.увидел_оружие(h, null, shooter, свидетели: crew);
                foreach (var p in crew)
                {
                    Социальное.adjust(p, shooter.id, hate: 15, aware: 10);
                    p.panic = Util.Clamp(p.panic + 8);
                }
                h.bump("исход_отбился");
                return ИсходОсады.ОТБИЛСЯ;
            }
        }

        // чем больше пришло и чем тяжелее в руках, тем меньше значит дверь
        double tools = инструменты(crew);
        Социальное.emit(h, target, 5, "взлом", night: true);

        // GDD 16, стадия «Дверь»: «время на подготовку, побег через
        // окно/чердак, засада». Пока дверь держат, у хозяина есть эти минуты —
        // и это его выбор, а не бросок на следующей стадии
        double прочность = target.door_strength();
        bool по_ключам = leader.ключи.Contains(target.apt);
        if (по_ключам)
            h.journal.line($"{leader.@short} {Util.Vb(leader.sex, "открыл")} дверь "
                           + $"кв.{target.apt} ключом. Ломать не пришлось.", 2);
        bool держит = !по_ключам && tools <= прочность * h.rng.Uni(0.75, 1.35);
        if (держит || прочность >= 2.0)
        {
            double уйти = (1.0 - target.t01("храбрость")) * b["побег_за_трусость"];
            уйти += b["побег_за_превосходство"]
                    * Util.Clamp(attack_power / Math.Max(0.5, def_power) - 1.0, 0.0, 2.0);
            уйти -= target.dependents > 0 ? b["побег_за_иждивенцев"] : 0.0;
            // и то, кого именно он слышит за дверью: от знакомого топора бегут
            уйти += (crew.Count > 0 ? crew.Max(p => target.боится(p.id)) : 0.0)
                    * b["страх_вес_побега"];
            if (defenders.Count > 1)
                уйти *= 0.4;                    // при своих не бегут
            if (Решение.монета(h, target, Вопрос.БЕЖАТЬ_ЧЕРЕЗ_ОКНО, "бежать", "остаться",
                               Util.Clamp(уйти, 0.0, 0.9)))
            {
                var добыча = вынести_на_всех(h, target, crew,
                                             b["налёт_доля_пустой_квартиры"]);
                target.warmth = Util.Clamp(target.warmth - 25);
                h.journal.line($"{target.@short} {Util.Vb(target.sex, "ушёл")} через окно "
                    + $"на пожарную лестницу, пока били дверь. Квартиру вынесли: "
                    + $"{_fmt(добыча)}.", 2);
                _house_learns(h, target, crew);
                // он ушёл через окно, а квартиру вынесли. Это то самое, что
                // не прощается и о чём вспоминают до конца метели
                foreach (var p in crew)
                    Социальное.обидели(h, target, p, b["обида_за_разграбление"],
                                       непрощаемо: true);
                h.bump("исход_сбежал");
                return ИсходОсады.СБЕЖАЛ;
            }
            // засада: тот, кто ждёт за дверью с топором, встречает первого
            // вошедшего
            if (!держит && target.weapon != Оружие.НЕТ && target.t01("храбрость") > 0.55
                && Решение.монета(h, target, Вопрос.ЖДАТЬ_ЗА_ДВЕРЬЮ, "ждать", "не ждать",
                                  b["засада_шанс"]))
            {
                var первый = h.rng.Pick(crew)!;
                первый.injuries.Add(h.rng.Pick(new[] { "ушиб", "порез" })!);
                первый.health = Util.Clamp(первый.health - h.rng.Uni(10, 22));
                h.journal.line($"{target.@short} {Util.Vb(target.sex, "ждал")} за дверью. "
                    + $"{первый.@short} {Util.Vb(первый.sex, "получил")} первым.", 2);
                Социальное.увидел_оружие(h, null, target, свидетели: crew);
                Социальное.испугался(h, первый, target, b["страх_за_насилие"]);
                foreach (var p in crew)
                    p.panic = Util.Clamp(p.panic + 10);
            }
        }

        bool door_broken = !держит;
        string? вошли = null;
        if (!door_broken)
        {
            // ---- стадия «другой путь»: окно, стена, перекрытия (GDD 16) ----
            var (как, пробовали) = _войти_иначе(h, crew, target, defenders);
            вошли = как;
            door_broken = вошли is not null;
            if (!door_broken)
            {
                string хвост = "";
                if (пробовали.Count > 0)
                    хвост = (пробовали.Count == 1
                             && string.Equals(пробовали[0], "окно", StringComparison.Ordinal))
                            ? " Лезли в окно — не вышло."
                            : " Пробовали и обойти — не вышло.";
                h.journal.line($"Дверь кв.{target.apt} выдержала. Били долго, "
                               + $"ушли под утро.{хвост}", 2);
                target.panic = Util.Clamp(target.panic + 14);
                target.mood = Util.Clamp(target.mood - 10);
                // дверь повело
                target.shelter["дверь"] = Math.Max(0,
                    target.shelter.Взять("дверь", 0.0) - b["дверь_ломается_за"]);
                foreach (var p in crew)
                    Социальное.adjust(p, target.id, hate: 8, aware: 12);
                _house_learns(h, target, crew);
                h.bump("исход_отбился");
                return ИсходОсады.ОТБИЛСЯ;
            }
        }

        // ---- стадия 3: прорыв ----
        if (вошли is null)
            h.journal.line($"Дверь кв.{target.apt} вынесли.", 2);
        // GDD 16, «Прорыв»: сдаться, отбиваться или бежать. Бежать было
        // поздно — это решалось, пока дверь ещё держали.
        // Что на кону: ребёнок за спиной и последняя еда сдвигают пороги
        // правила — трусости и превосходства
        double трусость = b["сдаться_трусость"]
                          + (target.dependents > 0 ? b["сдаться_за_ребёнка"] : 0.0);
        bool голоден = target.days_of("еда") < b["сдаться_голод_дней"];
        double превосходство = b["сдаться_превосходство"]
                               * (1.0 + (голоден ? b["сдаться_за_голод"] : 0.0));
        bool по_силам = def_power < attack_power * превосходство
                        || target.t01("храбрость") < трусость;
        bool surrender = Решение.по_правилу(h, target, Вопрос.СДАТЬСЯ, "сдаться", "драться",
                                            по_силам ? 1.0 : 0.0);

        if (surrender)
        {
            var добыча = вынести_на_всех(h, target, crew, 0.75);
            // выносят и то, чем он мог бы ответить в другой раз: топор из угла,
            // ружьё над дверью. Отсюда и берётся то, чего в модели не было
            // вовсе, — осада, после которой человек беззащитен не на вечер,
            // а до конца метели
            string? унёс = унести_оружие(h, target, leader, b["оружие_при_осаде"]);
            if (унёс is not null)
                добыча[унёс] = 1;
            h.journal.line($"{target.@short} не {Util.Vb(target.sex, "стал")} драться. "
                           + $"Забрали: {_fmt(добыча)}.", 2);
            foreach (var p in crew)
                Социальное.adjust(target, p.id, hate: b["ненависть_за_налёт"], trust: -5.0);
            // GDD 12.5 называет убийство отдельным действием NPC против NPC,
            // а GDD 11 ставит «убийство безоружного» в самый тяжёлый вес.
            // До сих пор смерть могла случиться только как побочный результат
            // драки
            double решимость = leader.t01("вспыльчивость")
                               + leader.hate.Взять(target.id, 0.0) / 100.0
                               - leader.t01("лояльность") * 1.5;
            if (решимость > b["добить_решимость"] && target.dependents == 0
                && Решение.монета(h, leader, Вопрос.ДОБИТЬ, "добить", "оставить",
                                  b["добить_шанс"]))
            {
                leader.bump("убийств");
                h.bump("убийств");
                h.bump("убийств_безоружных");
                h.journal.line($"{target.@short} не {Util.Vb(target.sex, "сопротивлялся")}. "
                    + $"{leader.@short} {Util.Vb(leader.sex, "убил")} {target.form("acc")} "
                    + "всё равно.", 2);
                h.note($"{leader.@short} {Util.Vb(leader.sex, "убил")} безоружного "
                       + $"{target.form("acc")}");
                // судят те, кто остаётся: убитого среди свидетелей уже нет
                Социальное.judge(h, leader, "насилие", hate: b["ненависть_за_налёт"],
                    trust: -4.0,
                    witnesses: h.others(leader).Where(w => !ReferenceEquals(w, target))
                                               .ToList());
                умер(h, target, Util.Vb(target.sex, "убит") + " безоружным при налёте",
                     killer: leader, свидетели: весь_дом(h));
                _house_learns(h, target, crew);
                h.bump("исход_убит");
                return ИсходОсады.УБИТ;
            }
            // если шли за квартирой — её и забирают. Хозяина меняют местами
            // с вожаком: тот перебирается в чужие стены, а бывшему остаётся
            // дыра, из которой пришли
            if (хочу_его_квартиру(h, leader, target) > 0
                && Решение.монета(h, leader, Вопрос.ЗАНЯТЬ_КВАРТИРУ, "занять", "уйти",
                                  b["занять_после_налёта"]))
            {
                занять_силой(h, leader, target);
                _house_learns(h, target, crew);
                h.bump("исход_занял");
                return ИсходОсады.ЗАНЯЛ;
            }
            // изгнание — если вожак злой (GDD 16). Сначала — есть ли у жертвы
            // ребёнок: мать на мороз не выставляют, и спрашивать об этом вожака
            // незачем. Раньше монета бросалась до этой проверки, и ответ
            // пропадал: для NPC исход тот же, для человека — вопрос впустую,
            // для ленты случайности — сдвиг
            if ((leader.trait("вспыльчивость") >= 7
                 || leader.hate.Взять(target.id, 0.0) > 70)
                && target.dependents == 0
                && Решение.монета(h, leader, Вопрос.ВЫСТАВИТЬ_НА_МОРОЗ,
                                  "выставить", "оставить", b["изгнание_после_налёта"]))
            {
                // выставили из собственных стен на мороз. Тяжелее этого в доме
                // только смерть, и это не прощается никогда
                foreach (var p in crew)
                    Социальное.обидели(h, target, p, b["обида_за_изгнание"],
                                       непрощаемо: true);
                exile(h, target, by: leader, reason: "налёт");
                h.bump("исход_изгнан");
                return ИсходОсады.ИЗГНАН;
            }
            foreach (var p in crew)
                Социальное.обидели(h, target, p, b["обида_за_разграбление"],
                                   непрощаемо: true);
            _house_learns(h, target, crew);
            h.bump("исход_ограблен");
            return ИсходОсады.ОГРАБЛЕН;
        }

        // драка
        var res = fight(h, crew, defenders, place: $"кв.{target.apt}", reason: "налёт");
        if (!target.alive)
        {
            // GDD 16 называет «убит» отдельным исходом осады. Раньше гибель
            // цели засчитывалась как «ограблен». Запасы убитого уже лежат
            // в его квартире — она теперь пустая и открытая
            _house_learns(h, target, crew);
            h.bump("исход_убит");
            return ИсходОсады.УБИТ;
        }
        if (res == ИсходБоя.A && хочу_его_квартиру(h, leader, target) > 0 && leader.alive)
        {
            foreach (var p in crew)
                Социальное.обидели(h, target, p, b["обида_за_изгнание"], непрощаемо: true);
            занять_силой(h, leader, target);
            _house_learns(h, target, crew);
            h.bump("исход_занял");
            return ИсходОсады.ЗАНЯЛ;
        }
        if (res == ИсходБоя.A)
        {
            var добыча = вынести_на_всех(h, target, crew.Where(c => c.alive).ToList(), 0.85);
            if (добыча.Count > 0)
            {
                h.journal.line($"Квартиру кв.{target.apt} обобрали: {_fmt(добыча)}.", 2);
                foreach (var p in crew)
                    Социальное.обидели(h, target, p, b["обида_за_разграбление"],
                                       непрощаемо: true);
            }
            _house_learns(h, target, crew);
            h.bump("исход_ограблен");
            return ИсходОсады.ОГРАБЛЕН;
        }
        h.journal.line($"{target.@short} "
            + (string.Equals(target.sex, "ж", StringComparison.Ordinal)
               ? "отбилась" : "отбился") + ".", 2);
        _house_learns(h, target, crew);
        h.bump("исход_отбился");
        return ИсходОсады.ОТБИЛСЯ;
    }

    /// <summary>
    /// Вожак въезжает в чужую квартиру, хозяина отправляют в его прежнюю.
    ///
    /// Меняются местами, а не выбрасываются на мороз: дом маленький, углов
    /// хватает, и это делает захват расчётливым поступком, а не убийством.
    /// </summary>
    public static void занять_силой(House h, NPC кто, NPC у_кого)
    {
        var старая = h.flats[кто.apt];
        var новая = h.flats[у_кого.apt];
        if (у_кого.здесь())
        {
            у_кого.apt = старая.apt;
            у_кого.floor = старая.floor;
            у_кого.mood = Util.Clamp(у_кого.mood - 18);
            у_кого.panic = Util.Clamp(у_кого.panic + 15);
            у_кого.warmth = Util.Clamp(у_кого.warmth - 10);
            Социальное.adjust(у_кого, кто.id, trust: -6.0, hate: h.B["ненависть_за_захват"]);
        }
        кто.apt = новая.apt;
        кто.floor = новая.floor;
        кто.ключи.Remove(новая.apt);
        h.bump("захвачено_квартир");
        h.journal.line($"{кто.@short} {Util.Vb(кто.sex, "перебрался")} в кв.{новая.apt}. "
            + (у_кого.здесь()
               ? $"{у_кого.@short} {Util.Vb(у_кого.sex, "ушёл")} в его прежнюю, "
                 + $"кв.{старая.apt}."
               : "Хозяина больше нет."), 2);
        h.note($"{кто.@short} {Util.Vb(кто.sex, "отнял")} квартиру {у_кого.form("gen")}");
        Социальное.judge(h, кто, "воровство", hate: 12.0, trust: -1.5);
    }

    /// <summary>После налёта весь дом узнаёт и о жертве, и о нападавших.</summary>
    public static void _house_learns(House h, NPC target, IReadOnlyList<NPC> crew)
    {
        var b = h.B;
        Социальное.house_shock(h, panic: b["паника_от_налёта_в_доме"], mood: -6);
        var свои = new HashSet<string>(crew.Select(c => c.id), StringComparer.Ordinal);
        // судит дом, а не соучастники: тот, кто сам стоял у этой двери,
        // не злится на того, с кем он туда пришёл. Пока состав не был исключён
        // из перебора, налёт добавлял +17 ненависти между подельниками,
        // и агрессивное ядро из GDD 12.4 съедало само себя за две ночи
        var судьи = h.alive().Where(p => !свои.Contains(p.id)).ToList();
        foreach (var p in h.alive())
        {
            Социальное.adjust(p, target.id, aware: 18);
            if (свои.Contains(p.id))
                continue;
            foreach (var c in crew)
            {
                Социальное.adjust(p, c.id, trust: -1.2 * p.t01("лояльность") * 2,
                                  hate: 10 + 12 * p.t01("лояльность"), aware: 8);
                // и главное, чего у дома не было: он теперь их боится.
                // Ненависть оседает за неделю, страх — нет, и следующей ночью
                // к этой компании никто уже не пойдёт ни просить, ни красть
                Социальное.испугался(h, p, c, b["страх_за_налёт"]);
                Социальное.увидел_оружие(h, p, c);
            }
        }
        // тому, к чьей двери приходили, страшнее всех
        foreach (var c in crew)
            Социальное.испугался(h, target, c, b["страх_за_насилие"]);
        // и отдельно — по личной мерке каждого (GDD 12.1)
        foreach (var c in crew)
            Социальное.judge(h, c, "насилие", hate: 8.0, trust: -0.6, witnesses: судьи);
    }
