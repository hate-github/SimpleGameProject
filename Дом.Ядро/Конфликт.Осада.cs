// Перенос house/conflict.py, строки 1550–2109: осада по стадиям.
//
// GDD 16 обещает, что на каждой стадии есть выход, — и почти каждый из них
// теперь чей-то ход, а не бросок кубика: закричать, откупиться, говорить
// через дверь, бежать через окно, ждать за дверью с топором, сдаться.
// У того, к чьей двери пришли, до переноса не было ни одного хода: за него
// всё считал `defenders_of`.

