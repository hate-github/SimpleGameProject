    /// <summary>
    /// Дадут ли уходящему унести дрова, которые он сносил к этой печке.
    /// Вопрос не права, а совести и силы: поленница лежит в хозяйской прихожей
    /// и стала общей в то же утро, когда он её принёс.
    /// </summary>
    public static bool отпустят_со_своим(House h, NPC гость, NPC хозяин, Баланс b,
                                         bool выгоняют)
    {
        var остаются = new List<NPC> { хозяин };
        foreach (var g in хозяин.guests.OrderBy(x => x, StringComparer.Ordinal))
            if (!string.Equals(g, гость.id, StringComparison.Ordinal))
            {
                var o = h.get(g);
                if (o is not null)
                    остаются.Add(o);
            }
        остаются = остаются.Where(o => o.здесь()).ToList();
        double держат = (1.0 - Math.Min(1.0, хозяин.secure("топливо")))
                        * b["дрова_держат_за_нужду"];
        держат += хозяин.hate.Взять(гость.id, 0.0) / 100.0 * b["дрова_держат_за_злость"];
        держат -= хозяин.t01("лояльность") * b["дрова_отдают_за_совесть"];
        держат -= хозяин.свой(гость.id) * b["дрова_отдают_за_близость"];
        // и то, о чём в такую минуту думают раньше всего: кто из нас сильнее
        double наша = Util.Sum(остаются.Select(o => o.power()));   // правда: под одной крышей: остающиеся у той же печки
        держат -= Util.Clamp(гость.power() / Math.Max(0.2, наша) - 0.6, 0.0, 1.4)
                  * b["дрова_отдают_за_силу"];        // правда: под одной крышей: он здесь жил
        держат -= хозяин.боится(гость.id) * b["дрова_отдают_за_страх"];
        double порог = выгоняют ? b["дрова_порог_выселения"] : b["дрова_порог_съезда"];
        return держат < порог;
    }

    /// <summary>
    /// Сколько дров гость уносит из хозяйской печки, уходя. Больше того, что
    /// он принёс, не унесёт, и больше доли того, что осталось у хозяина, —
    /// тоже: чужую печку не разбирают.
    /// </summary>
    public static double забрать_своё(House h, NPC гость, NPC хозяин, double доля)
    {
        double своё = Math.Min(гость.снёс_дров, хозяин.stock.Взять("топливо", 0.0) * доля);
        if (своё <= 0.05)
            return 0.0;
        хозяин.stock["топливо"] = хозяин.stock.Взять("топливо", 0.0) - своё;
        гость.stock["топливо"] = гость.stock.Взять("топливо", 0.0) + своё;
        гость.снёс_дров = 0.0;
        return своё;
    }

    public static void съехать(House h, NPC npc, NPC host)
    {
        var b = h.B;
        // своё он забирает — но спросив: поленница уже общая и стоит
        // в хозяйской прихожей. А сверх своего хозяин даёт на дорогу,
        // если не в ссоре
        double дров = отпустят_со_своим(h, npc, host, b, выгоняют: false)
            ? забрать_своё(h, npc, host, b["выгнать_доля_дров"]) : 0.0;
        if (host.hate.Взять(npc.id, 0.0) < 40)
        {
            double сверх = Math.Min(b["выгнать_дров_на_дорогу"],
                                    host.stock.Взять("топливо", 0.0));
            host.stock["топливо"] = host.stock.Взять("топливо", 0.0) - сверх;
            npc.stock["топливо"] = npc.stock.Взять("топливо", 0.0) + сверх;
            дров += сверх;
        }
        npc.living_with = null;
        host.guests.Remove(npc.id);
        occupy_flat(h, npc);
        npc.warmth = Util.Clamp(npc.warmth - 8);
        Социальное.adjust(npc, host.id, trust: -0.5);
        Социальное.adjust(host, npc.id, trust: -0.5);
        h.bump("съездов");
        h.journal.line($"{npc.@short} {Util.Vb(npc.sex, "вернулся")} к себе в кв.{npc.apt}"
            + (дров != 0.0
                ? $" — {host.@short} {Util.Vb(host.sex, "дал")} дров на первое время."
                : ". Ушёл молча."), 2);
        h.note($"{npc.@short} {Util.Vb(npc.sex, "съехал")} от {host.form("gen")}");
    }

    public static void выгнать(House h, NPC npc, NPC гость)
    {
        var b = h.B;
        // что успел снести к этой печке, то и уносит — если отпустят
        double было_чего = гость.снёс_дров;
        bool отдали = отпустят_со_своим(h, гость, npc, b, выгоняют: true);
        double унёс = отдали ? забрать_своё(h, гость, npc, b["выгнать_доля_дров"]) : 0.0;
        if (!отдали && было_чего > 0.5)
        {
            // не отдали. Это уже не «разошлись», а счёт, и он из тех,
            // что не проходят от времени
            гость.снёс_дров = 0.0;
            Социальное.обидели(h, гость, npc, b["обида_за_дрова"], вслух: false);
            h.bump("дров_не_отдали");
        }
        гость.living_with = null;
        npc.guests.Remove(гость.id);
        occupy_flat(h, гость);
        гость.warmth = Util.Clamp(гость.warmth - 14);
        гость.mood = Util.Clamp(гость.mood - 14);
        гость.panic = Util.Clamp(гость.panic + 12);
        Социальное.adjust(гость, npc.id, trust: -4.0, hate: b["ненависть_за_выселение"]);
        Социальное.adjust(npc, гость.id, trust: -1.0);
        Социальное.отдалились(гость, npc.id, b["близость_за_обиду"]);
        h.bump("выселений");
        h.journal.line($"{npc.@short} {Util.Vb(npc.sex, "выставил")} {гость.form("acc")} обратно "
            + $"в кв.{гость.apt}. Разговаривать не о чем."
            + (унёс != 0.0
                ? $" {гость.@short} {Util.Vb(гость.sex, "забрал")} свои дрова ({Текст.G(унёс)})."
                : (!отдали && было_чего > 0.5
                    ? $" Дрова, которые {гость.@short} {Util.Vb(гость.sex, "сносил")} "
                      + "к этой печке, остались у неё."
                    : "")), 2);
        h.note($"{npc.@short} {Util.Vb(npc.sex, "выгнал")} {гость.form("acc")}");
        Социальное.judge(h, npc, Каталог.ТЕГИ["выгнать"], hate: 6.0, trust: -0.8);
    }

