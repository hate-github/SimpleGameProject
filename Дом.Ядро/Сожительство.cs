// Перенос house/household.py: кто у кого греется, что приносит и с чем
// уходит (GDD 15).
//
// Одно понятие целиком: решение хозяина пустить, снос дров к общей печке,
// ночь в одной комнате, уход со своим или без, и то, что остаётся человеку,
// когда сожительство кончилось.

namespace Дом.Ядро;

public static class Сожительство
{
    // ------------------------------------- утро и ночь под одной крышей

    /// <summary>Утро: всё, что гость принёс за вчера, идёт к хозяйской печке.</summary>
    public static void дрова_к_печке(House h)
    {
        // квартира одна, дрова у неё общие. Пока этого не было, гость копил
        // топливо, которое по правилу «печку топит хозяин» не мог сжечь
        // никогда, и просил ещё
        foreach (var p in h.alive())
        {
            if (string.IsNullOrEmpty(p.living_with))
                continue;
            var host = h.get(p.living_with);
            double дрова = p.stock.Взять("топливо", 0.0);
            if (host is not null && host.здесь() && дрова > 0)
            {
                host.stock["топливо"] = host.stock.Взять("топливо", 0.0) + дрова;
                p.stock["топливо"] = 0.0;
                // и помнит, сколько снёс. Пока этого не было, съезд был
                // единственной сделкой в доме без цены для второй стороны:
                // выставленный на мороз уходил без всего, что принёс сам
                p.снёс_дров += дрова;
                h.journal.line($"{p.@short} {Util.Vb(p.sex, "снёс")} дрова к печке "
                               + $"{host.form("gen")} ({Текст.G(Math.Round(дрова, 1))}).", 0);
            }
        }
    }

    /// <summary>Ночь в одной комнате: нервы, чужой кашель, общий котёл —
    /// и близость.</summary>
    public static void теснота_ночи(House h, NPC p)
    {
        var b = h.B;
        int room_mates = p.guests.Count + (string.IsNullOrEmpty(p.living_with) ? 0 : 1);
        if (room_mates == 0)
            return;
        p.mood = Util.Clamp(p.mood - b["теснота_настроение"] * room_mates);
        // sorted, а не list: порядок множества строк зависит от хэшей,
        // а внутри цикла бросается кубик — иначе зерно перестаёт быть зерном
        var кто = p.guests.OrderBy(x => x, StringComparer.Ordinal).ToList();
        if (!string.IsNullOrEmpty(p.living_with))
            кто.Add(p.living_with);
        foreach (var other_id in кто)
        {
            var o = h.get(other_id);
            if (o is null || !o.alive)
                continue;
            // спать в одной комнате — это и есть история пары, даже если
            // за день не сказано ни слова. Тем и тяжелее потом выставить его
            // на мороз
            Социальное.сблизились(h, p, o, b["близость_под_крышей"]);
            // и видят друг друга каждый день, вплотную
            Социальное.встретились(h, p, o);
            // у соседства своя злость, и она копится: ГДД 15 обещает
            // «накопленную злость», из которой растут разъезд, изгнание
            // гостя и нож ночью
            double зло = Социальное.теснота(h, p, o, b);
            Социальное.adjust(p, o.id, trust: -b["теснота_доверие"], hate: зло);
            h.stats["ненависть_от_тесноты"] =
                h.stats.Взять("ненависть_от_тесноты", 0.0) + зло;
            // в одной комнате болезнь переходит почти наверняка
            if (o.sick is not null && p.sick is null && h.rng.Chance(b["теснота_зараза"]))
            {
                p.sick = "простуда";
                h.journal.line(
                    $"{p.label()} {Util.Vb(p.sex, "слёг")} вслед за соседом по комнате.", 1);
            }
        }
        // соседи видят, что в одной квартире собрались несколько запасов
        foreach (var w in h.others(p))
            Социальное.adjust(w, p.id, aware: 2.5 * room_mates);
    }

