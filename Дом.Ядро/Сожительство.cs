    /// <summary>
    /// 0..1 — насколько человек просится под эту крышу не греться, а смотреть.
    /// Появляется только тогда, когда обычная жизнь уже кончилась: чем больше
    /// у человека рассыпалось привычное, тем спокойнее он смотрит на чужие
    /// банки.
    /// </summary>
    public static double переезд_с_умыслом(House h, NPC npc, NPC host)
        => Util.Clamp(npc.loot_value(host.id) / 6.0 * npc.t01("жадность")
                      * (1.0 - npc.t01("лояльность")) * (1.0 - npc.normalcy), 0.0, 1.0);

    /// <summary>
    /// Решает хозяин: греть двоих дороже, но вдвоём не так страшно. Больше
    /// нуля — пускает.
    /// </summary>
    public static double пустит_к_себе(House h, NPC host, NPC гость, Баланс b)
    {
        double yes = host.t01("лояльность") * 5.0 + host.trust.Взять(гость.id, 3.0) * 0.8;
        yes -= host.t01("жадность") * 2.0;
        // хозяин считает не «хватит ли мне до конца метели», а «стану ли я
        // от него беднее». Разница решает всё: гость приходит со своими
        // дровами, и они уходят в общую печку, а печка горит одна на комнату.
        // С едой иначе: это лишний рот, и он считается полностью.
        // Хозяин отказывал в 96 просьбах из ста — за сорок жизней восемь
        // переездов на двести просьб, при том что по GDD 15 без переезда дом
        // до конца метели не доживает
        foreach (var (res, вес) in new (string, double)[]
                 { ("топливо", b["переезд_страх_дров"]), ("еда", b["переезд_страх_еды"]) })
        {
            double гость_ест = res == "еда" ? 1.0 : b["переезд_гость_топит"];
            double рты = host.eaters() + гость.eaters() * гость_ест;
            double на_рот = (res == "еда" ? 0.85 : 1.0) * рты;
            double вместе = (host.stock.Взять(res, 0.0) + гость.stock.Взять(res, 0.0))
                            / Math.Max(0.2, на_рот);   // правда: видно: гость стоит в дверях со своим
            double станет_хуже = Util.Clamp(1.0 - вместе / Math.Max(0.5, host.days_of(res)),
                                            0.0, 1.0);
            yes -= станет_хуже * вес;
        }
        yes += host.allies.Contains(гость.id) ? 2.0 : 0.0;
        yes += гость.dependents != 0 ? 1.5 : 0.0;
        // и то, чего в этом решении не было вовсе: он пускает человека
        // к своему шкафу и засыпает при нём. Судить об этом хозяин может
        // только по тому, что знает: по репутации, по тому, ловили ли гостя
        // на чужом, и по тому, врал ли он ему
        double риск = (1.0 - Math.Min(1.0, host.trust.Взять(гость.id, 3.0) / 6.0))
                      * b["переезд_риск_доверия"];
        риск += Math.Min(2.0, гость.поймали) * b["переезд_риск_пойманного"];
        риск += Math.Min(2.0, host.не_верю.Взять(гость.id, 0.0)) * b["переезд_риск_вруна"];
        // и то, насколько всё уже не так, как было: в первую неделю к соседу
        // пускают не думая, на третьей — думая
        риск += (1.0 - host.normalcy) * b["переезд_риск_распада"];
        yes -= риск * (0.5 + host.t01("жадность") * 0.8);
        // и то же самое, чем он потом будет мерить, не выгнать ли его обратно
        yes += Социальное.выгода_соседства(h, host, гость) * b["переезд_вес_выгоды"];
        // в однушке с буржуйкой больше двоих не помещается
        yes -= host.guests.Count * b["теснота_отказ"];
        return yes - b["переезд_согласие"];
    }

    public static void переехать(House h, NPC npc, NPC host)
    {
        var b = h.B;
        if (Решение.по_правилу(h, host, Вопрос.ПУСТИТЬ_К_СЕБЕ, "пустить", "отказать",
                               пустит_к_себе(h, host, npc, b))
            && host.guests.Count < b["переезд_максимум_гостей"])
        {
            npc.living_with = host.id;
            npc.переехал_день = h.day;
            // с чем он сюда шёл — это и решит, встанет ли он тут ночью
            npc.переезд_умысел = переезд_с_умыслом(h, npc, host);
            host.guests.Add(npc.id);
            double fuel = npc.stock.Взять("топливо", 0.0);
            host.stock["топливо"] = host.stock.Взять("топливо", 0.0) + fuel;
            npc.stock["топливо"] = 0.0;
            Социальное.adjust(npc, host.id, trust: 2.0, hate: -20);
            Социальное.adjust(host, npc.id, trust: 1.0);
            npc.mood = Util.Clamp(npc.mood + 12);
            host.mood = Util.Clamp(host.mood + 6);
            h.bump("переездов");
            h.событие(ВидСобытия.ПЕРЕЕЗД, кто: npc.id, кому: host.id, где: host.apt);
            h.journal.line($"{npc.@short} {Util.Vb(npc.sex, "перебрался")} к {host.form("dat")} "
                           + $"в кв.{host.apt} — топят одну печку на двоих.", 2);
            h.note($"{npc.@short} {Util.Vb(npc.sex, "переехал")} к {host.form("dat")}");
            // своя квартира остаётся пустой сама — в ней просто никто не живёт.
            // И её начнут разбирать: вернуться потом может быть некуда
        }
        else
        {
            Социальное.adjust(npc, host.id, trust: -1.0, hate: 10);
            npc.ask_record(host.id).отказ_переезд = h.day;
            npc.mood = Util.Clamp(npc.mood - 8);
            h.journal.line($"{npc.@short} {Util.Vb(npc.sex, "просил")} пустить к себе. "
                           + $"{host.@short} не {Util.Vb(host.sex, "пустил")}.", 1);
        }
    }

