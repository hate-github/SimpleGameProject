    /// <summary>Человек вернулся в свою квартиру: забирает то, что в ней
    /// осталось.</summary>
    public static void occupy_flat(House h, NPC person)
    {
        if (!h.flats.TryGetValue(person.apt, out var flat))
            return;
        if (flat.body is not null && flat.body.порций > 0)
            return;
        foreach (var res in flat.stock.Ключи)
        {
            double v = flat.stock[res];
            if (v != 0.0)
            {
                person.stock[res] = person.stock.Взять(res, 0.0) + v;
                flat.stock[res] = 0.0;
            }
        }
        // оружие — дело конфликта
        Конфликт.подобрать_оружие(h, person, flat);
        // и связку с гвоздя: погреб приписан к квартире, а не к человеку,
        // и достаётся тому, кто в этих стенах теперь живёт
        if (flat.ключи.Count > 0)
        {
            person.ключи_кладовых.UnionWith(flat.ключи);
            foreach (var kid in flat.ключи.OrderBy(x => x, StringComparer.Ordinal))
                if (h.кладовые.TryGetValue(kid, out var к))
                    h.journal.line($"   Вместе со стенами {person.form("dat")} "
                        + $"{Util.Vb(person.sex, "достался")} и ключ от {к.имя_род}.", 1);
            flat.ключи.Clear();
            h.bump("ключей_от_кладовых_по_наследству");
        }
    }

    /// <summary>
    /// Разорвать все связи выбывшего: союзы, сожительство в обе стороны.
    /// Одно место на смерть и на изгнание. Пока это было только в `on_death`,
    /// гость изгнанного навсегда оставался с `living_with` — а значит,
    /// по правилу «печку топит хозяин», не мог затопить собственную
    /// и замерзал.
    /// </summary>
    public static void cut_ties(House h, NPC person)
    {
        foreach (var other in h.people.Значения)
            other.allies.Remove(person.id);
        person.allies.Clear();
        foreach (var gid in person.guests.OrderBy(x => x, StringComparer.Ordinal))
        {
            var g = h.get(gid);
            if (g is null)
                continue;
            if (g.здесь())
            {
                g.living_with = null;
                g.warmth = Util.Clamp(g.warmth - 15);
                occupy_flat(h, g);
                h.journal.line(
                    $"{g.@short} {Util.Vb(g.sex, "вернулся")} в свою выстывшую квартиру.", 1);
            }
            else
                g.living_with = null;
        }
        person.guests.Clear();
        if (!string.IsNullOrEmpty(person.living_with))
        {
            var host = h.get(person.living_with);
            host?.guests.Remove(person.id);
            person.living_with = null;
        }
    }
