// Перенос house/social.py: шум, осведомлённость, слухи, отношения и группы.
//
// Сердце социальной части. Ровно то, что в ГДД:
//   · 13 — шум и наблюдение, из которых растёт осведомлённость;
//   · 12.3 — три шкалы: осведомлённость, паника, ненависть, плюс доверие 0-10;
//   · 12.4 — группы не заданы заранее, они складываются после первого инцидента;
//   · 14 — слово: враньё, которое работает и разоблачается, и обещания.
//
// Модуль разложен по файлам ровно по тем разделам, которыми он разделён
// в прототипе: `Социальное.Шум.cs`, `Социальное.Слово.cs`,
// `Социальное.Отношения.cs`, `Социальное.Цена.cs`. Это один класс —
// в Python это один модуль.

namespace Дом.Ядро;

/// <summary>
/// Что именно выдаёт тот или иной сигнал (GDD 13).
///
/// Заметность — вторая ось из GDD 13 («каждое действие имеет громкость
/// и заметность»), и устроена она иначе, чем громкость: дым из окна и пакеты
/// в руках видны со двора и с площадки всему дому, по этажам не глохнут,
/// зато их скрывают занавески — то есть утепление окон.
/// </summary>
public sealed record ЗначениеШума(string? рес, double подсказка, string как_видно, double видно);

public static partial class Социальное
{
    public static readonly IReadOnlyDictionary<string, ЗначениеШума> NOISE_MEANING =
        new Dictionary<string, ЗначениеШума>(StringComparer.Ordinal)
        {
            ["готовка"] = new(null, 0.0, "в кв.{apt} гремят посудой", 0.0),
            ["буржуйка"] = new("топливо", 1.1, "из окна кв.{apt} идёт дым", 0.45),
            ["генератор"] = new("топливо", 2.2, "в кв.{apt} гудит генератор", 0.55),
            ["ремонт"] = new("материалы", 1.2, "в кв.{apt} стучат", 0.0),
            ["дверь"] = new("материалы", 1.4, "в кв.{apt} что-то тяжёлое волокут к двери", 0.15),
            ["разбор"] = new("материалы", 1.0, "с пустой квартиры тащат доски", 0.35),
            ["подвал"] = new("еда", 1.4, "{кто} {спускался} в подвал и {вернулся} не с пустыми руками", 0.5),
            ["возвращение"] = new("еда", 1.6, "{кто} {вернулся} с улицы с пакетами", 0.65),
            ["взлом"] = new(null, 0.0, "в подъезде скрипела чужая дверь", 0.2),
            ["пролом"] = new(null, 0.0, "за стеной долго и тяжело били во что-то", 0.1),
            ["ссора"] = new(null, 0.0, "на лестнице кричали", 0.3),
            ["выстрел"] = new(null, 0.0, "в доме стреляли", 0.0),
            ["шаги"] = new(null, 0.0, "на лестнице шаги", 0.0),
        };

    private static readonly ЗначениеШума ПУСТОЙ_ШУМ = new(null, 0.0, "", 0.0);

    public static ЗначениеШума ЧтоЗначит(string kind)
        => NOISE_MEANING.TryGetValue(kind, out var з) ? з : ПУСТОЙ_ШУМ;

    static Социальное()
    {
        // новый вид шума, который что-то говорит о запасах, должен попасть
        // и в обратную таблицу (`Таблицы.ШУМ_ПРО`) — иначе мена его не увидит
        // и человек не пойдёт к двери за тем, о чём сам же слышал
        foreach (var (рес, виды) in Таблицы.ШУМ_ПРО)
            foreach (var вид in виды)
            {
                string? что = ЧтоЗначит(вид).рес;
                if (что is not null && !string.Equals(что, рес, StringComparison.Ordinal))
                    throw new InvalidOperationException(
                        $"шум «{вид}» говорит про «{что}», а в ШУМ_ПРО стоит у «{рес}»");
            }
    }

    // ---------------------------------------------------------- где человек

    /// <summary>У кого человек физически находится — см. <c>House.хозяин_жилья</c>.</summary>
    public static NPC место(House h, NPC npc) => h.хозяин_жилья(npc);

    /// <summary>
    /// Может ли человек прямо сейчас протопить собственную квартиру.
    /// Не «есть ли там буржуйка», а «есть ли там буржуйка и чем её топить».
    /// Без этой разницы гость, у которого дрова ушли в хозяйскую печь, считает
    /// свой угол тёплым и уходит замерзать.
    /// </summary>
    public static bool своя_топится(House h, NPC npc)
    {
        var своя = h.flats[npc.apt];
        return своя.shelter.Взять("буржуйка", 0.0) != 0.0
               && npc.stock.Взять("топливо", 0.0) >= 1.0;
    }

    /// <summary>
    /// Насколько выгодно жить с этим человеком в одной квартире. Больше нуля —
    /// вместе лучше. Одно число на три решения: съезжаться, съезжать
    /// и выгонять. Так «рациональная часть» получается настоящей: поссорились,
    /// ненавидят друг друга — но порознь их возьмут поодиночке, и оба это
    /// считают.
    /// </summary>
    public static double выгода_соседства(House h, NPC a, NPC партнёр)
    {
        var B = h.B;
        var своя = h.flats[a.apt];
        var общая = партнёр.apt != a.apt ? h.where(партнёр) : h.flats[a.apt];
        double польза = 0.0;
        if (общая.apt != своя.apt)
            // гость: разница между хозяйскими стенами и своими, которые он ещё
            // и протопить не сможет, если дрова остались у хозяина
            польза += (h.flat_temp(общая, burning: true, powered: h.power_on)
                       - h.flat_temp(своя, burning: своя_топится(h, a), powered: h.power_on))
                      * B["соседство_вес_тепла"];
        else
            польза += B["соседство_экономия_топлива"];   // одна печь вместо двух

        // и то, чего у сплочения не было вовсе: страх перед конкретным
        // человеком. Тот, кто боится соседа с топором, ищет, к кому прибиться,
        // и ищет тем сильнее, чем страшнее. Паника отвечает за «всё плохо»,
        // страх — за «плохо вот от него», и к чужой печке гонит именно второе
        double самый_страшный = 0.0;
        foreach (var (_, v) in a.страх)
            if (v > самый_страшный)
                самый_страшный = v;
        double тревога = Math.Min(1.5, a.panic / 100.0 + 0.25 * recent_incidents(h)
                                       + самый_страшный / 100.0);
        // за этой дверью не один человек, а квартира: у кого уже сидит гость,
        // тот держит дверь вдвоём. К хозяину идут вместе с теми, кто у него
        // уже сидит; гость приходит один
        var свои = string.IsNullOrEmpty(партнёр.living_with)
            ? h.household(партнёр)
            : new List<NPC> { партнёр };
        свои = свои.Where(o => !string.Equals(o.id, a.id, StringComparison.Ordinal)).ToList();
        // сила защитников — какой она кажется тому, кто выбирает, к кому
        // проситься: чужое здоровье он не знает, знает лицо
        double сила = Util.Sum(свои.Select(o => a.видимая_сила(o)));
        польза += сила * B["соседство_вес_защиты"] * тревога;
        if (a.allies.Contains(партнёр.id))
            польза += 1.0;

        double цена = B["соседство_теснота"];
        цена += a.hate.Взять(партнёр.id, 0.0) / B["соседство_ненависть_делитель"];
        цена += Math.Max(0.0, 5.0 - a.trust.Взять(партнёр.id, 3.0)) * 0.4;
        // чужая болезнь — та, что видел: кашель, который слышал, рана, которую
        // заметил; своя — своя
        if (a.видит_хворь(партнёр.id) && a.sick is null)
            цена += B["соседство_болезнь"];
        if (партнёр.dependents != 0 && a.dependents == 0)
            цена += B["соседство_лишний_рот"] * (1.0 - Math.Min(1.0, a.secure("еда")));
        return польза - цена;
    }

    /// <summary>
    /// За что злятся те, кто делит одну комнату (GDD 15). Прибавка злости
    /// за сутки. Поводы здесь только бытовые, и это важно: ссорятся не из-за
    /// принципов, а из-за печки, шкафа, кашля и ребёнка, который просыпается
    /// ночью.
    /// </summary>
    public static double теснота(House h, NPC p, NPC сосед, Баланс b)
    {
        double зло = b["теснота_злость"];
        // печка одна на комнату, и топить или не топить решает хозяин. Мёрзнут
        // оба, но злится тот, кто не решает
        double room = h.room_temp(p);
        if (room < b["теснота_холодно"])
        {
            double доля = Math.Min(1.5, (b["теснота_холодно"] - room) / 10.0);
            double свой = string.Equals(p.living_with, сосед.id, StringComparison.Ordinal)
                ? 1.0 : b["теснота_хозяин_доля"];
            зло += доля * b["теснота_за_холод"] * свой;
        }
        // чужой шкаф на виду: под одной крышей не надо ни слухов, ни наблюдения,
        // и голодный рядом с сытым — это уже не оценка запасов, а злость
        double разница = сосед.days_of("еда") - p.days_of("еда");   // правда: под одной крышей: чужой шкаф на виду
        if (разница > b["теснота_еда_разница"])
            зло += Math.Min(разница, 6.0) * b["теснота_за_еду"];
        // чужой кашель всю ночь — тем хуже, чем хуже спится
        if (сосед.sick is not null)                                  // правда: под одной крышей: кашель слышно всю ночь
            зло += b["теснота_за_болезнь"] * (1.4 - Util.Norm(p.rest, 20, 80));
        // и ребёнок, который просыпается
        if (сосед.dependents != 0 && p.dependents == 0)
            зло += b["теснота_за_ребёнка"];
        return зло;
    }

    /// <summary>Стоят ли эти двое в одной комнате — см. <c>House.под_одной_крышей</c>.</summary>
    public static bool под_одной_крышей(House h, NPC a, NPC b_npc) => h.под_одной_крышей(a, b_npc);

    /// <summary>Три дня ничего не случилось — человек начинает привыкать
    /// (GDD 12.4).</summary>
    public static bool тихо_ли(House h)
        => h.day - h.календарь.последнее_громкое >= h.B["нормальность_тишина_дней"];

    /// <summary>
    /// Паника растёт с затуханием: последние проценты набрать трудно.
    /// Иначе к десятому дню у всех ровно 100 и шкала перестаёт что-либо
    /// значить.
    /// </summary>
    public static void add_panic(NPC p, double delta)
    {
        if (delta > 0)
            delta *= Math.Max(0.15, 1.0 - p.panic / 130.0);
        p.panic = Util.Clamp(p.panic + delta);
    }
}
