// Перенос house/model.py, строки 1100–1412: что человек знает о соседе,
// как он относится и который у него час.
//
// Всё, что здесь считается о соседе, считается по знанию: `видит`,
// `сведения_о`, память. Настоящие поля соседа читают ровно два метода —
// `видимая_сила` (берёт его силу и подменяет телесную поправку увиденной)
// и `believed_days` (расход семьи — общее знание, ADR-9).

namespace Дом.Ядро;

public sealed partial class NPC
{
    /// <summary>
    /// Насколько этот сосед ближе ПРОЧИХ: −1 (чужее всех) … +1 (свой).
    ///
    /// Решает не близость сама по себе, а разница. Тот, кто одинаково близок
    /// со всеми, не предпочитает никого — и это не сбой, а суть: внимания
    /// у человека столько же, сколько часов в дне, и «свой» значит «этот
    /// вместо тех». Пока в выборе стояла абсолютная близость, она оказалась
    /// положительной обратной связью без тормоза.
    /// </summary>
    public double предпочтение(string other_id, double средний)
        => Util.Clamp(близость.Взять(other_id, 0.0) / 10.0 - средний, -1.0, 1.0);

    /// <summary>
    /// Насколько сосед, на его взгляд, плох: 0 — здоров, 1 — не жилец.
    /// По самому провалившемуся из трёх, а не по среднему: человек, который
    /// сыт и в тепле, но качается и держится за стену, — плох, и никакая
    /// сытость этого не отменяет.
    /// </summary>
    public double плох(string other_id)
    {
        var v = видит(other_id);
        if (v is null)
            return 0.0;
        double худшее = v.худшее();
        double плохо = Util.Clamp(1.0 - худшее / 55.0, 0.0, 1.0);
        // и то, КОГДА он его таким видел. Впечатление недельной давности —
        // это уже не «он плох», а «он был плох тогда»: чем дольше
        // не встречались, тем ближе оценка к «не знаю»
        if (_h is not null)
        {
            int дней = давно_видел(other_id, _h.day);
            плохо *= Util.Clamp(1.0 - дней * _h.B["взгляд_стареет"], 0.3, 1.0);
        }
        return плохо;
    }

    /// <summary>
    /// 0..1 — насколько плохо я, по-моему, выгляжу со стороны. Та же мерка,
    /// которой человек судит соседа (<see cref="плох"/>), но о себе
    /// и по своим настоящим шкалам.
    ///
    /// Ошибки, как во взгляде на соседа, здесь нет: своё состояние человек
    /// знает. Ошибается он в другом — насколько это заметно, — и потому
    /// храбрый считает, что держится лучше, чем есть.
    /// </summary>
    public double каким_кажусь()
    {
        double худшее = Math.Min(satiety, Math.Min(health, warmth));
        double кажусь = Util.Clamp(1.0 - худшее / 55.0, 0.0, 1.0);
        return Util.Clamp(кажусь * (1.2 - t01("храбрость") * 0.4), 0.0, 1.0);
    }

    /// <summary>
    /// Сколько убийств и изгнаний он знает — по своей памяти, одним проходом.
    /// Его страх последствий, а не счёт дома: убийство за стеной, о котором
    /// ему не сказали, вора не остановит.
    /// </summary>
    public (int убийств, int изгнаний) знает_расправ()
    {
        int убийств = 0, изгнаний = 0;
        foreach (var m in memory)
        {
            if (m.вид == Вид.ВИДЕЛ_УБИЙСТВО) убийств++;
            else if (m.вид == Вид.ВИДЕЛ_ИЗГНАНИЕ) изгнаний++;
        }
        return (убийств, изгнаний);
    }

    /// <summary>
    /// Знает ли он, что в доме крадут: сам крал, ловил вора, у самого пропало
    /// или слышал, как в чате назвали вора. Не счётчик дома, а его память.
    /// </summary>
    public bool знает_о_кражах()
    {
        foreach (var m in memory)
            if (Виды.ЗНАЕТ_О_КРАЖАХ.Contains(m.вид))
                return true;
        return false;
    }

    /// <summary>
    /// Слышал ли он за последние дни, что этого соседа называли вором. Своя
    /// память, а не общий счёт дома: обвинение в чате слышат те, у кого
    /// работает связь, наговор — тот, кому его сказали.
    /// </summary>
    public bool слышал_обвинение(string other_id, int день, double дней)
    {
        foreach (var m in memory)
            if (m.вид == Вид.НАЗВАЛИ_ВОРОМ
                && string.Equals(m.кто, other_id, StringComparison.Ordinal)
                && день - m.день <= дней)
                return true;
        return false;
    }

    /// <summary>
    /// Слышал ли или видел он в этот день вот это о соседе: запись памяти вида
    /// «слышал» — шум за стеной, дым из окна, пакеты в руках. По ней, а не
    /// по правде, судят «его видели с пакетами».
    /// </summary>
    public bool слышал(string other_id, string что, int день)
    {
        foreach (var m in memory)
            if (m.вид == Вид.СЛЫШАЛ
                && string.Equals(m.кто, other_id, StringComparison.Ordinal)
                && string.Equals(m.что, что, StringComparison.Ordinal)
                && m.день == день)
                return true;
        return false;
    }

    /// <summary>
    /// Есть ли у меня основание думать, что у соседа есть вот это.
    ///
    /// Не оценка (<see cref="believed"/>) — та есть всегда, потому что
    /// незнание человек достраивает по себе, — а то, откуда она взялась:
    /// видел, учуял, подсмотрел, догадался или ему сказали. Без этого мена
    /// шла вслепую: на один состоявшийся обмен приходилось почти три
    /// холостых подхода.
    /// </summary>
    public bool знаю_про(string other_id, string res, int день, double дней)
    {
        Таблицы.ШУМ_ПРО.TryGetValue(res, out var шумы);
        foreach (var m in memory)
        {
            if (!string.Equals(m.кто, other_id, StringComparison.Ordinal) || день - m.день > дней)
                continue;
            if (m.вид is Вид.СМОТРЕЛ or Вид.УКРАЛ or Вид.ПОЙМАЛ_ВОРА)
                return true;                    // чужой шкаф своими глазами
            if (m.вид == Вид.УЧУЯЛ && string.Equals(res, "еда", StringComparison.Ordinal))
                return true;
            if ((m.вид is Вид.ДОГАДАЛСЯ or Вид.СКАЗАЛИ)
                && string.Equals(m.что, res, StringComparison.Ordinal))
                return true;
            if (m.вид == Вид.СЛЫШАЛ && шумы is not null && m.что is not null
                && Array.IndexOf(шумы, m.что) >= 0)
                return true;
        }
        return false;
    }

    /// <summary>
    /// Каким сильным сосед КАЖЕТСЯ — по лицу, а не по правде мира. Оружие
    /// и рост видно, а сколько у него на самом деле здоровья — нет. Поэтому
    /// берётся его настоящая сила, но телесная поправка в ней заменяется
    /// на ту, которую видит смотрящий: раненый, который держится прямо,
    /// кажется целым, и к нему не идут.
    /// </summary>
    public double видимая_сила(NPC other)
    {
        double сила = other.power();            // правда: видно: оружие и рост видно с площадки
        var v = видит(other.id);
        // не разглядел — считает обычным: целым и сытым, как и `плох` считает
        // того же соседа здоровым. Раньше здесь возвращалась настоящая сила,
        // и незнакомец был виден вернее знакомого
        double кажется = v is null
            ? 100.0
            : Util.Clamp(Math.Min(v.целость, v.сытость + 25.0), 0.0, 100.0);
        // ту же поправку, что power даёт за здоровье, но по увиденному
        double настоящая = 0.55 + 0.45 * (other.health / 100.0);   // правда: исполнение: снимается тем же множителем
        double видимая = 0.55 + 0.45 * (кажется / 100.0);
        return Math.Max(0.15, сила / Math.Max(0.2, настоящая) * видимая);
    }

    /// <summary>0..1 — насколько он уверен в сведениях. Это и есть
    /// осведомлённость.</summary>
    public double confidence(string other_id) => сведения_о(other_id).aware / 100.0;

    /// <summary>
    /// 0..1 — насколько он опасается этого человека (GDD 12.3, 17).
    ///
    /// Страх не толкает, а держит: к тому, кого боятся, не идут ни говорить,
    /// ни просить, ни красть, ни ломать его дверь, — но ему отдают, когда
    /// он приходит сам. Ровно то, что GDD 17 называет «угроза оружием часто
    /// ценнее выстрела».
    /// </summary>
    public double боится(string other_id)
        => Util.Clamp(страх.Взять(other_id, 0.0) / 100.0, 0.0, 1.0);

    /// <summary>
    /// (id, страх) того, кого он боится больше всех, или null.
    /// <paramref name="среди"/> — кого имеет смысл считать: панель дома
    /// показывает срез сегодняшнего подъезда, и «боится Игоря 67» через три
    /// дня после похорон Игоря — правда модели, но не то, что там нужно.
    /// </summary>
    public (string кто, double страх)? самый_страшный(
        IReadOnlySet<string>? среди = null, double порог = 0.0)
    {
        (string, double)? лучший = null;
        foreach (var (k, v) in страх)           // порядок вставки, как в Python
            if (v > порог && (среди is null || среди.Contains(k)))
                if (лучший is null || v > лучший.Value.Item2)
                    лучший = (k, v);
        return лучший;
    }

    /// <summary>Насколько лакомой выглядит чужая квартира: сведения
    /// на уверенность.</summary>
    public double loot_value(string other_id)
    {
        var e = сведения_о(other_id).est;
        double raw = e.Взять("еда", 2.0) * 1.0 + e.Взять("топливо", 2.0) * 0.7
                   + e.Взять("лекарства", 0.0) * 1.1;
        return raw * (0.35 + 0.65 * confidence(other_id));
    }

    /// <summary>Имя в нужном падеже. Формы лежат в data/npcs.json, а не в коде.</summary>
    public string form(string @case)
    {
        string v = @case switch
        {
            "gen" => gen,
            "dat" => dat,
            "acc" => acc,
            "ins" => ins,
            "short" => @short,
            "name" => name,
            _ => "",
        };
        return string.IsNullOrEmpty(v) ? @short : v;
    }

    /// <summary>
    /// 0..1 — насколько, по моему опыту, у этого человека можно выпросить.
    /// Пока опыта нет, оценка около половины: попробовать стоит.
    /// </summary>
    public double generosity(string other_id)
    {
        if (!asking.TryGetValue(other_id, out var r))
            return 0.5;
        return (r.дали + 1.0) / (r.дали + r.отказали + 2.0);
    }

    /// <summary>
    /// 0..10 — как, по-моему, этот сосед ко мне относится.
    ///
    /// Не его доверие — чужих мыслей не видно, — а то, что я о нём знаю сам:
    /// как отвечал на мои просьбы, что делал для меня, свой ли он мне,
    /// в союзе ли мы, выходил ли на мой крик и не нажил ли я ему счёта.
    /// Веса — в balance.json; умолчание 3.0, как у доверия к незнакомому.
    /// </summary>
    public double расположение_ко_мне(string other_id)
    {
        if (_h is null)
            return 3.0;
        var b = _h.B;
        double р = 3.0;
        р += (generosity(other_id) - 0.5) * b["расположение_за_щедрость"];
        р += Math.Min(3, favors.Взять(other_id, 0)) * b["расположение_за_услугу"];
        р += свой(other_id) * b["расположение_за_близость"];
        if (allies.Contains(other_id))
            р += b["расположение_за_союз"];
        if (не_вышли.Contains(other_id))
            р -= b["расположение_за_невыход"];
        р -= обида(other_id) / b["расположение_за_обиду"];
        return Util.Clamp(р, 0.0, 10.0);
    }

    public string label() => $"{@short} (кв.{apt})";

    /// <summary>
    /// Который сейчас час у этого человека. Внутри дня времени в модели
    /// не было вовсе — был счётчик оставшихся часов, — и оттого нечем было
    /// выразить ни расписание из ГДД 12.1, ни привычку. А оно всё это время
    /// лежало на поверхности: человек встал в свой час и потратил столько,
    /// сколько потратил.
    /// </summary>
    public double час()
    {
        double бодрствования = _h is not null ? _h.B["часов_бодрствования"] : 16.0;
        return подъём + (бодрствования - time_left);
    }

    /// <summary>
    /// Утро, день, вечер или ночь — по его собственным часам, а не по общим.
    /// Ночной сосед в девять вечера ещё в своём «дне», а тот, кто встал
    /// в шесть, в это же время уже в ночи.
    /// </summary>
    public string отрезок()
    {
        double ч = час();
        if (ч < 12.0) return "утро";
        if (ч < 18.0) return "день";
        if (ч < 23.0) return "вечер";
        return "ночь";
    }

    /// <summary>«08:30» — время его хода, как оно печатается в журнале.</summary>
    public string часы_вслух()
    {
        double ч = час();
        int часы = (int)ч % 24;
        int минуты = (int)((ч % 1.0) * 60);
        return $"{часы:D2}:{минуты:D2}";
    }
}
