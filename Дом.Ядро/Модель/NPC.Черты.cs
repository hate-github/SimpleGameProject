// Перенос house/model.py, строки 810–860: черты, веса и пунктики.
// Раздел «производные величины» класса NPC, первая его часть.

namespace Дом.Ядро;

public sealed partial class NPC
{
    public double trait(string name) => traits.Взять(name, 5.0);

    /// <summary>Черта, приведённая к 0..1.</summary>
    public double t01(string name) => trait(name) / 10.0;

    /// <summary>
    /// Сумма «черта × вес» для этого решения. Веса лежат в balance.json.
    ///
    /// Характер — это и есть эти веса: <c>лояльность × 4</c> в щедрости
    /// и <c>− лояльность × 4.5</c> в краже. Пока они были зашиты в код,
    /// крутить можно было темп и злость дома, но не человека.
    ///
    /// Выносятся только слагаемые вида «черта × число». Там, где черта входит
    /// множителем (жадность в отъёме, храбрость в бою), она осталась в коде:
    /// это не вес характера, а устройство самого действия.
    /// </summary>
    public double вес_черт(string key)
    {
        if (_h is null)
            return 0.0;
        var веса = _h.B.Таблица2("веса_черт");
        if (!веса.TryGetValue(key, out var таблица))
            return 0.0;
        var части = new List<double>();
        foreach (var (черта, вес) in таблица)      // порядок вставки, как в Python
            части.Add(t01(черта) * вес);
        return Util.Sum(части);
    }

    /// <summary>
    /// Сдвиг от личных пунктиков (GDD 12.1: «ценности» как правила).
    ///
    /// Пунктик — это правило, а не сила склонности: «первым не ударит» нельзя
    /// выразить через храбрость, потому что человек может быть смелым
    /// и при этом не начинать. Список пунктиков человека лежит в npcs.json,
    /// сами пунктики — в balance.json; в коде один интерпретатор.
    /// </summary>
    public double пунктик(string key)
    {
        if (пунктики.Count == 0 || _h is null)
            return 0.0;
        var таблица = _h.B.Таблица2("пунктики");
        var части = new List<double>();
        foreach (var п in пунктики)
            части.Add(таблица.TryGetValue(п, out var свой) ? свой.Взять(key, 0.0) : 0.0);
        return Util.Sum(части);
    }

    /// <summary>Сколько ртов кормит (GDD 12.1: дневное потребление).</summary>
    public double eaters() => 1.0 + 0.6 * dependents;

    /// <summary>Сколько этого уходит в день на его семью (GDD 12.1).</summary>
    public double расход_в_день(string res) => res switch
    {
        "еда" => 0.85,
        "вода" => 0.9,
        "топливо" => 1.0,
        _ => 1.0,
    } * eaters();

    /// <summary>На сколько дней хватит ресурса при текущем потреблении.</summary>
    public double days_of(string res)
        => stock.Взять(res, 0.0) / Math.Max(0.2, расход_в_день(res));
}
