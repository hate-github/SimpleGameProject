// Перенос house/model.py, строки 20–210: ресурсы, перечисления и таблицы,
// которые лежат рядом с ними, потому что это свойства вещей, а не ручки
// баланса.
//
// В Python это `StrEnum` — член равен своей строке. В C# такого нет, поэтому
// член остаётся членом, а строка лежит таблицей рядом (`Текст`/`Из`).
// Канонический снимок сворачивает перечисление в свою строку — как и в
// прототипе, так что отпечаток состояния от этой разницы не зависит.

namespace Дом.Ядро;

/// <summary>Ресурсы (GDD 12.1: «Запасы: еда, вода, топливо в днях»).</summary>
public static class Ресурсы
{
    // «мясо» намеренно не в списке: это не ресурс, который меняют и просят.
    // «деньги» — наличные, и лежат они в том же шкафу: их крадут, их выносят
    // при осаде, они остаются в квартире умершего (GDD 18)
    public static readonly IReadOnlyList<string> ВСЕ = new[]
        { "еда", "вода", "топливо", "лекарства", "материалы", "патроны", "деньги" };

    public const string ЕДА = "еда";
    public const string ВОДА = "вода";
    public const string ТОПЛИВО = "топливо";
    public const string ЛЕКАРСТВА = "лекарства";
    public const string МАТЕРИАЛЫ = "материалы";
    public const string ПАТРОНЫ = "патроны";
    public const string ДЕНЬГИ = "деньги";

    /// <summary>
    /// Сколько на этом складе полезного. Деньги не в счёт.
    ///
    /// Нужно там, где склад оценивают как приз: пустая квартира на разбор,
    /// чужие стены при переезде. Пачка купюр в тумбочке мертвеца квартиру
    /// дороже не делает — за неё не согреешься, а к концу метели её
    /// и не возьмут.
    /// </summary>
    public static double Вещи(Словарь<string, double> stock)
    {
        double сумма = 0.0;
        foreach (var (k, v) in stock)          // порядок вставки, как в Python
            if (!string.Equals(k, ДЕНЬГИ, StringComparison.Ordinal))
                сумма += v;
        return сумма;
    }

    /// <summary>
    /// Израсходовать ресурс безвозвратно и записать это.
    ///
    /// Съеденное, сожжённое и потраченное на стройку уходит из мира. Пока это
    /// не считалось, баланс дома не сходился, и настоящую утечку было
    /// не отличить от нормальной траты.
    /// </summary>
    public static double Spend(House h, NPC npc, string res, double amount)
    {
        double have = npc.stock.Взять(res, 0.0);
        double used = Math.Min(amount, have);
        npc.stock[res] = have - used;
        string ключ = "израсходовано_" + res;
        h.stats[ключ] = h.stats.Взять(ключ, 0.0) + used;
        return used;
    }
}

/// <summary>Что у человека в руках (GDD 17).</summary>
public enum Оружие { НЕТ, НОЖ, ДУБИНА, ТОПОР, ПИСТОЛЕТ, ДРОБОВИК, ВИНТОВКА }

/// <summary>Погреб — в подвале этого же дома, гараж — за домом, то есть улица.</summary>
public enum ВидКладовой { ПОГРЕБ, ГАРАЖ }

/// <summary>Погода дня (GDD 3): метель — обычно, буран — глухо и холодно,
/// затишье — слышно каждый шаг.</summary>
public enum Режим { МЕТЕЛЬ, БУРАН, ЗАТИШЬЕ }

/// <summary>
/// Что случилось в доме — крупными мазками, как это увидит движок.
///
/// Журнал пишет строку для человека: «Толик зажал Виктора на лестнице
/// и забрал еда 3, топливо 1». Событие — та же вещь для машины: кто, с кем,
/// где, что и сколько. По строке нельзя выбрать ни анимацию, ни звук,
/// ни иконку в телефоне; по записи — можно, и ради этого она и заводится.
///
/// Список закрыт нарочно, как виды памяти и оружия: событие, которого нет
/// в перечислении, — это событие, которое интерфейс не покажет.
/// </summary>
public enum ВидСобытия
{
    СМЕРТЬ,
    УБИЙСТВО,
    ИЗГНАНИЕ,
    НАЛЁТ,          // пришли к двери; `сколько` — сколько их
    ИСХОД,          // чем осада кончилась; `что` — исход
    КРАЖА,
    ОТЪЁМ,
    ПОМОЩЬ,         // `что` — ресурс
    ОБМЕН,
    ЛЕЧЕНИЕ,
    ПЕРЕЕЗД,
    СОБРАНИЕ,       // `что` — тема
    ВСКРЫТИЕ,       // сорвали замок с погреба или гаража
    ПОЖАР,
}

/// <summary>
/// Откуда человек это знает: вид записи в <see cref="Память"/>.
///
/// Разделены восприятие («слышал», «учуял», «смотрел») и своя рука («украл»,
/// «поймал_вора»): и то и другое — знание, но добыто оно по-разному.
/// </summary>
public enum Вид
{
    СЛЫШАЛ,             // шум за стеной (social._hear); `что` — вид шума
    СКАЗАЛИ,            // мне про него сказали (social.gossip); `что` — ресурс
    УЧУЯЛ,              // запах готовки по стояку
    СМОТРЕЛ,            // наблюдение за соседом
    ДОГАДАЛСЯ,          // вывод, а не наблюдение; `что` — ресурс
    УКРАЛ,
    ПОЙМАЛ_ВОРА,
    ПОЙМАЛ_НА_ЛЖИ,
    ПРОПАЖА,            // у него самого пропало
    СЛЫШАЛ_О_ВОРЕ,      // из этого он знает, что в доме крадут
    // …а из этого — что вором назвали вот этого соседа. Вид отдельный нарочно:
    // «в доме крадут» человек выносит только из слов того, кто сам знает,
    // а «на него думают» запоминает всякий, кто это слышал
    НАЗВАЛИ_ВОРОМ,
    ВИДЕЛ_УБИЙСТВО,     // расправа, о которой он знает: страх последствий
    ВИДЕЛ_ИЗГНАНИЕ,
}

/// <summary>Что человек решил делать ночью (night.решение).</summary>
public enum Ночь { СПАТЬ, ДЕЖУРИТЬ, КРАЖА, НАЛЁТ, УБИТЬ_СОСЕДА, ОБОБРАТЬ }

/// <summary>
/// Строки перечислений — те же, что в прототипе. Ими пишется журнал,
/// читаются данные и сворачивается канонический снимок.
/// </summary>
public static class Слова
{
    private static readonly string[] _оружие =
        { "нет", "нож", "дубина", "топор", "пистолет", "дробовик", "винтовка" };
    private static readonly string[] _кладовая = { "погреб", "гараж" };
    private static readonly string[] _режим = { "метель", "буран", "затишье" };
    private static readonly string[] _событие =
    {
        "смерть", "убийство", "изгнание", "налёт", "исход", "кража", "отъём",
        "помощь", "обмен", "лечение", "переезд", "собрание", "вскрытие", "пожар",
    };
    private static readonly string[] _вид =
    {
        "слышал", "сказали", "учуял", "смотрел", "догадался", "украл",
        "поймал_вора", "поймал_на_лжи", "пропажа", "слышал_о_воре",
        "назвали_вором", "видел_убийство", "видел_изгнание",
    };
    private static readonly string[] _ночь =
        { "спать", "дежурить", "кража", "налёт", "убить_соседа", "обобрать" };

    public static string Текст(this Оружие о) => _оружие[(int)о];
    public static string Текст(this ВидКладовой к) => _кладовая[(int)к];
    public static string Текст(this Режим р) => _режим[(int)р];
    public static string Текст(this ВидСобытия с) => _событие[(int)с];
    public static string Текст(this Вид в) => _вид[(int)в];
    public static string Текст(this Ночь н) => _ночь[(int)н];

    public static Оружие Оружие(string s) => (Оружие)Найти(_оружие, s, nameof(Оружие));
    public static ВидКладовой Кладовая(string s) => (ВидКладовой)Найти(_кладовая, s, "ВидКладовой");
    public static Режим Режим(string s) => (Режим)Найти(_режим, s, nameof(Режим));
    public static ВидСобытия Событие(string s) => (ВидСобытия)Найти(_событие, s, "ВидСобытия");
    public static Вид Вид(string s) => (Вид)Найти(_вид, s, nameof(Вид));
    public static Ночь Ночь(string s) => (Ночь)Найти(_ночь, s, nameof(Ночь));

    private static int Найти(string[] где, string что, string чего)
    {
        int i = Array.IndexOf(где, что);
        if (i < 0)
            throw new ArgumentException($"{чего}: нет такого значения «{что}»");
        return i;
    }
}

