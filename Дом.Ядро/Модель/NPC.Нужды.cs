// Перенос house/model.py, строки 859–1100: запас, тело, сила — и первые
// три метода знания, без которых не считается `believed`.
//
// Граница знания (навык sim-core): решение читает о соседе только то, что
// здесь названо знанием — `сведения_о`, `видит`, `believed`, — и никогда
// `t.stock` / `t.sick` / `t.trust`. В Python это стережёт линтер
// `check.проверить_чтение_правды`; в C# ту же границу будут держать типы,
// и это единственное улучшение, разрешённое до схождения эталона.

namespace Дом.Ядро;

public sealed partial class NPC
{
    /// <summary>На сколько дней, по-моему, хватит соседу: моя оценка его
    /// запасов на его расход. Семью его я знаю (ADR-9), а шкаф — только
    /// по слухам.</summary>
    public double believed_days(NPC other, string res)
        => believed(other.id, res) / Math.Max(0.2, other.расход_в_день(res));

    /// <summary>
    /// 1.0 = запасов ровно на тот срок, который человек считает нужным.
    /// Ниже единицы — «мне не хватит», и это главный источник жадности:
    /// отказывают не злые, а те, кто посчитал.
    /// </summary>
    public double secure(string res)
        => Util.Clamp(days_of(res) / Math.Max(3.0, horizon), 0.0, 2.5);

    /// <summary>
    /// Отвечает ли этот человек за своё отопление. Переехавший к соседу —
    /// нет: его дрова ушли в общую печку, и топит её хозяин. Пока это
    /// не спрашивалось, у гостя топлива всегда было ноль, и он вечно
    /// числился в отчаянии, сидя в тепле и сытости.
    /// </summary>
    public bool топит_сам() => string.IsNullOrEmpty(living_with);

    /// <summary>
    /// Ниже какой температуры этот человек на улицу не выйдет. В обычной
    /// городской куртке при минус двадцати пяти на улице делать нечего —
    /// не «опасно», а нельзя: обморожение раньше, чем добыча (GDD 20).
    /// </summary>
    public double мороз_предел(Баланс b) => b["выход_предел"] - одежда * b["выход_за_одежду"];

    /// <summary>
    /// Насколько топливо для него вообще ресурс. Без буржуйки дрова не сжечь:
    /// обогреватель ест электричество, генератор надо сперва собрать. Считать
    /// их такой же нуждой, как еду, — значит заставить человека без печки
    /// паниковать из-за мёртвого груза и ходить просить дрова у соседей.
    /// </summary>
    public double могу_топить()
    {
        if (!топит_сам())
            return 0.0;
        if (shelter.Взять("буржуйка", 0.0) != 0.0)
            return 1.0;
        if (stock.Взять("материалы", 0.0) >= 4.0)
            return 0.5;         // есть из чего собрать — запасается не зря
        return 0.15;
    }

    /// <summary>
    /// 0..1 — «мне не хватит». Это не голод, а страх: человек считает запас
    /// против срока, который сам себе назначил, и не знает, когда кончится
    /// метель. Отсюда жадность и паника — но не преступление.
    /// </summary>
    public double insecurity()
    {
        double еда = 1.0 - Math.Min(1.0, secure("еда"));
        double вода = 1.0 - Math.Min(1.0, secure("вода"));
        double дрова = (1.0 - Math.Min(1.0, secure("топливо"))) * 0.9 * могу_топить();
        return Util.Clamp(Math.Max(еда, Math.Max(вода, дрова)), 0.0, 1.0);
    }

    /// <summary>
    /// 0..1 — «мне сейчас физически плохо». Третье чувство, которого
    /// не хватало между «мне не хватит» и «я умираю». Это не про запасы
    /// вообще: холод в комнате, боль от травмы, жар. И лечится оно печкой,
    /// костром, просьбой, переездом и аптечкой — а не взломом.
    ///
    /// Пока этого не было, холод и ушиб входили слагаемыми в отчаяние,
    /// и человек с полным шкафом в нетопленой квартире читался как умирающий.
    /// </summary>
    public double невмоготу()
    {
        double холод = 1.0 - Util.Norm(warmth, 12, 55);
        double боль = 0.0;
        if (injuries.Count > 0)
            боль = Math.Min(1.0, 0.35 + 0.2 * (injuries.Count - 1));
        if (sick is not null)
            боль = Math.Max(боль, 0.45);
        double слабость = 1.0 - Util.Norm(health, 20, 70);
        // и то, чего в «мне плохо» не было вовсе: тот, кто на руках. Состояние
        // ребёнка читали четыре места из сорока, и потому мать промёрзшего
        // и больного ребёнка не шла ни просить, ни переезжать, ни за лекарством:
        // сама-то она цела. Через это же число ребёнок попадает и в панику,
        // и в то, спит ли замысел, — для матери это одна беда
        return Util.Clamp(
            Math.Max(холод, Math.Max(боль, Math.Max(слабость, ребёнку_плохо()))), 0.0, 1.0);
    }

    /// <summary>
    /// 0..1 — насколько плохо тому, кто на руках (GDD 12.6). По самому слабому
    /// из детей и по самой провалившейся из трёх его шкал: голодный,
    /// промёрзший или больной — для матери это одна беда, и на три
    /// она не делится.
    /// </summary>
    public double ребёнку_плохо()
    {
        var р = слабейший_ребёнок();
        if (р is null)
            return 0.0;
        double голод = 1.0 - Util.Norm(р.сытость, 15, 60);
        double холод = 1.0 - Util.Norm(р.тепло, 15, 55);
        double хворь = 1.0 - Util.Norm(р.здоровье, 20, 75);
        if (р.болен is not null)
            хворь = Math.Max(хворь, 0.5);
        double вес = _h is not null ? _h.B["ребёнок_вес_беды"] : 1.0;
        return Util.Clamp(Math.Max(голод, Math.Max(холод, хворь)) * вес, 0.0, 1.0);
    }

    /// <summary>
    /// 0..1 — «я умираю». Считается по запасам: вот это толкает на кражу
    /// и налёт. Холод, боль и болезнь сюда не входят — они в `невмоготу`.
    /// </summary>
    public double desperation()
    {
        double food = 1.0 - Util.Norm(Math.Min(days_of("еда"), 10), 0, 6);
        double water = 1.0 - Util.Norm(Math.Min(days_of("вода"), 10), 0, 4);
        double fuel = (1.0 - Util.Norm(Math.Min(days_of("топливо"), 10), 0, 6)) * могу_топить();
        // телесная часть — только настоящее истощение, ниже критического порога:
        // иначе человек «в отчаянии» каждый день перед ужином
        double body = 1.0 - Util.Norm(Math.Min(satiety, hydration), 5, 30);
        return Util.Clamp(
            Math.Max(food * 0.95, Math.Max(water * 0.9, Math.Max(fuel * 0.75, body))), 0.0, 1.0);
    }

    /// <summary>
    /// Повреждена ли конечность (GDD 6.2: «нога снижает скорость, рука —
    /// ремонт»). Травмы хранятся строками вида «перелом ноги», «порез руки» —
    /// тип и место в одном тексте, чтобы журнал читался как журнал.
    /// </summary>
    public bool hurt(string limb)
    {
        foreach (var i in injuries)
            if (i.Contains(limb, StringComparison.Ordinal))
                return true;
        return false;
    }

    /// <summary>
    /// Множитель ко времени действия (GDD 6.1). Голод, холод и недосып
    /// замедляют всё; повреждённая нога — переноску и вылазки. Меньше единицы
    /// человек не работает быстрее, только медленнее.
    /// </summary>
    public double speed(Баланс b)
    {
        double v = 1.0;
        v += b["медленнее_за_голод"] * (1.0 - Util.Norm(satiety, 15, 70));
        v += b["медленнее_за_недосып"] * (1.0 - Util.Norm(rest, 15, 70));
        v += b["медленнее_за_холод"] * (1.0 - Util.Norm(warmth, 20, 65));
        if (sick is not null)
            v += b["медленнее_за_болезнь"];
        if (hurt("ноги"))
            v += b["медленнее_за_ногу"];
        return v;
    }

    /// <summary>Шанс, что работа выйдет с первого раза (GDD 7: у действий
    /// есть провал).</summary>
    public double success(Баланс b)
    {
        double p = b["успех_база"];
        p -= b["успех_за_недосып"] * (1.0 - Util.Norm(rest, 15, 70));
        p -= b["успех_за_голод"] * (1.0 - Util.Norm(satiety, 15, 70));
        p -= b["успех_за_холод"] * (1.0 - Util.Norm(warmth, 20, 65));
        if (hurt("руки"))
            p -= b["успех_за_руку"];
        return Util.Clamp(p, 0.15, 0.98);
    }

    /// <summary>Насколько это оружие у него в руке своё: 0 — впервые держит,
    /// 1 — своё.</summary>
    public double привычка(Оружие? оружие = null)
    {
        Оружие w = оружие ?? weapon;
        if (w == Оружие.НЕТ)
            return 1.0;
        double своё = Таблицы.СВОЙСКОЕ.TryGetValue(w, out var с) ? с : 0.0;
        return Util.Clamp(рука.Взять(w, своё), 0.0, 1.0);
    }

    /// <summary>Боевая сила (GDD 17: оружие и численное превосходство решают
    /// почти всё).</summary>
    public double power()
    {
        double p = 0.6 + t01("храбрость") * 0.9;
        double вес = Таблицы.ОРУЖИЕ_ВЕС[weapon];
        // оружие весит столько, насколько человек с ним свыкся. Пока этого
        // не было, винтовка была одинаково смертельна в любых руках, и вся
        // разница между охотником и кассиром кончалась на том, у кого она
        // сегодня в руках
        p += вес * 0.8 * (Таблицы.ЧУЖОЕ_ОРУЖИЕ
                          + (1.0 - Таблицы.ЧУЖОЕ_ОРУЖИЕ) * привычка());
        if (Таблицы.ОГНЕСТРЕЛ.Contains(weapon) && stock.Взять("патроны", 0.0) <= 0)
            p -= вес * 0.55;
        p *= 0.55 + 0.45 * (health / 100.0);
        // Физика (ГДД 8.1): у соседей умений нет, и множитель — единица.
        // Поэтому прогон без игрока считается ровно как раньше
        p *= Поправки.Сила(this);
        p *= Math.Max(0.35, 1.0 - 0.18 * injuries.Count);
        if (hurt("руки"))
            p *= 0.8;           // оружие в разбитой руке держится плохо (GDD 6.2)
        if (age > 58)
            p *= 0.88;
        if (sick is not null)
            p *= 0.8;
        return Math.Max(0.15, p);
    }

    /// <summary>Прочность двери для стадии осады «Дверь» (GDD 16). Стальные
    /// листы — уровень 3 убежища, они добавляются к засову.</summary>
    public double door_strength()
        => 1.0 + 1.6 * shelter.Взять("дверь", 0.0) + 1.2 * shelter.Взять("листы", 0.0);

    /// <summary>
    /// Что я думаю о месте, пока сам не сходил и никто не рассказал.
    /// По умолчанию — «наверное, там как всегда»: до метели в магазине была
    /// еда, и человек идёт туда, пока не узнает обратного. Это и есть
    /// нормальный порядок вылазок: сначала очевидное, мусорки — потом.
    /// </summary>
    public double знаю_место(string имя) => места.Взять(имя, 1.0);

    /// <summary>Что он знает о соседе; о незнакомом — ничего, пустая запись.</summary>
    public Сведения сведения_о(string other_id)
        => сведения.TryGetValue(other_id, out var св) ? св : new Сведения();

    /// <summary>
    /// Каким он видит соседа — или null, если ещё не разглядел. Решению даётся
    /// это, а не сам сосед: что у того в шкафу и в лёгких — правда мира,
    /// и отсюда её не прочесть (GDD 13).
    /// </summary>
    public Взгляд? видит(string other_id) => вид.TryGetValue(other_id, out var v) ? v : null;

    /// <summary>Видел ли он на соседе рану или слышал ли кашель.</summary>
    public bool видит_хворь(string other_id) => видит(other_id)?.хворь == true;

    /// <summary>Сколько дней назад он в последний раз видел этого соседа вблизи.</summary>
    public int давно_видел(string other_id, int день)
    {
        var v = видит(other_id);
        return v is null ? 99 : день - v.день;
    }

    /// <summary>
    /// Сколько, по мнению этого NPC, у другого есть ресурса.
    ///
    /// У патронов своя догадка по умолчанию, и она почти нулевая: банки, воду
    /// и дрова держит дома всякий, а патроны — нет. А у медика аптечка есть —
    /// это общее знание подъезда (ADR-9: профессию знают все), и забывание
    /// его не стирает. Ошибиться здесь можно — сумка бывает и пустой, —
    /// но это ошибка в одну ходку, а не в оценку.
    /// </summary>
    public double believed(string other_id, string res)
    {
        double догадка = Таблицы.ДОГАДКА.TryGetValue(res, out var д) ? д : 2.0;
        double est = сведения_о(other_id).est.Взять(res, догадка);
        if (string.Equals(res, "лекарства", StringComparison.Ordinal) && _h is not null)
        {
            var сосед = _h.get(other_id);
            if (сосед is not null && сосед.skills.Contains("медик", StringComparer.Ordinal))
                est = Math.Max(est, Таблицы.ДОГАДКА_МЕДИКА);
        }
        return est;
    }

    /// <summary>Насколько между нами не улажено: 0 — ничего не было, 100 — всё.</summary>
    public double обида(string other_id) => счёты.Взять(other_id, 0.0);

    /// <summary>Настолько не улажено, что к этой двери он не подойдёт мирно.</summary>
    public bool враждует(string other_id, double порог)
        => обида(other_id) >= порог || не_прощу.Contains(other_id);

    /// <summary>
    /// Насколько этот сосед ему свой: 0 — просто жилец из подъезда, 1 — свой.
    /// Отдельно от доверия нарочно: доверять можно и тому, с кем за месяц
    /// не сказал двух слов, — за репутацию; своим он от этого не станет.
    /// </summary>
    public double свой(string other_id)
        => Util.Clamp(близость.Взять(other_id, 0.0) / 10.0, 0.0, 1.0);

    /// <summary>Тот из детей, кому хуже всех. Ему и достаётся лекарство.</summary>
    public Ребёнок? слабейший_ребёнок()
    {
        if (дети.Count == 0)
            return null;
        // min() в Python берёт первого из равных — MinBy делает то же
        return дети.MinBy(р => Math.Min(р.здоровье, Math.Min(р.тепло, р.сытость)));
    }

    /// <summary>
    /// Заглушка-запрет: ребёнок никогда не может стать едой. Тел детей в мире
    /// не появляется вовсе (см. conflict._orphan), этот метод оставлен как
    /// явная точка, чтобы правило было видно в коде.
    /// </summary>
    public bool dependents_only_child(House? h = null) => false;

    /// <summary>Что я помню про просьбы к этому человеку.</summary>
    public ОпытПросьб ask_record(string other_id)
    {
        if (!asking.TryGetValue(other_id, out var о))
        {
            о = new ОпытПросьб();
            asking[other_id] = о;
        }
        return о;
    }
}
