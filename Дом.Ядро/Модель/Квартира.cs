namespace Дом.Ядро;

/// <summary>
/// Квартира — вещь, а не приложение к жильцу (GDD 12, 15).
///
/// Утепление, дверь, буржуйка и арматура принадлежат стенам. Пока они висели
/// на человеке, «занять квартиру получше» было нечем выразить: переехавший
/// уносил буржуйку на спине, а после смерти хозяина всё, что он построил
/// за месяц, исчезало вместе с ним.
///
/// Отсюда же берётся жильё как имущество: его можно занять, за него можно
/// прийти с ломом, и его можно испортить, ломая дверь.
/// </summary>
public sealed class Flat
{
    public required int apt { get; set; }
    public required int floor { get; set; }
    public Словарь<string, double> shelter { get; } = Словари.Числа();
    public Словарь<string, double> stock { get; } = Словари.Числа();
    public int stripped { get; set; }
    public string? owner_died { get; set; }
    public Тело? body { get; set; }             // тело хозяина, если он умер дома
    public double вложено { get; set; }         // сколько материалов в неё вбито
    public int костёр { get; set; } = -99;      // день, когда в ней жгли костёр
    public bool тулуп { get; set; }             // зимняя одежда хозяина осталась здесь

    // оружие, оставшееся в этих стенах: топор в углу, ружьё над дверью.
    // До сих пор оружие было единственной вещью в модели, которая исчезала
    // вместе с человеком, — тулуп с мёртвого снимали, а винтовку нет, — и
    // оттого расклад сил в доме был заморожен на первом дне метели.
    public List<Оружие> оружие { get; } = new();

    // ключи от кладовых, оставшиеся в этих стенах. Умерший не уносит ключ
    // от своего погреба с собой: он висит на гвозде в прихожей, и тот, кто
    // разбирает квартиру, его находит.
    public HashSet<string> ключи { get; } = new(StringComparer.Ordinal);

    // чем её ломали: «окно», «стена», «пол», «потолок» -> сколько раз (GDD 16).
    // Пролом остаётся в стенах ровно так же, как утепление: в него выдувает,
    // через него лезут в следующий раз, и заделать его стоит материалов
    public Словарь<string, int> дыры { get; } = Словари.Строкой<int>();

    // замок уже сломан. Пока этого не было, «пустая квартира» и «запертая
    // чужая квартира» были для кода одним и тем же
    public bool открыта { get; set; }

    // 1.0 — вытяжка тянет, 0.0 — шахта забита льдом наглухо (GDD 15).
    // Люди не идиоты: печку в закрытой комнате не жгут, потому что есть
    // вентиляция. Но вентиляция в панельном доме обрастает льдом изнутри,
    // от собственного пара, и в какой-то день перестаёт тянуть.
    public double вентиляция { get; set; } = 1.0;

    /// <summary>Чтобы квартира годилась в цели действия наравне с человеком.</summary>
    public string id => $"кв{apt}";

    /// <summary>
    /// Прочность двери для стадии осады «Дверь» (GDD 16). Стальные листы —
    /// уровень 3 убежища, они добавляются к засову.
    /// </summary>
    public double door_strength()
        => 1.0 + 1.6 * shelter.Взять("дверь", 0.0) + 1.2 * shelter.Взять("листы", 0.0);

    /// <summary>Сколько в квартире проломов — окно, стена, пол, потолок (GDD 16).</summary>
    public int дыр()
    {
        int сумма = 0;
        foreach (var (_, n) in дыры)
            сумма += n;
        return сумма;
    }

    /// <summary>
    /// Сколько градусов уносит в проломы. Это и есть цена осады
    /// для победителя (GDD 16: «выламывая дверь, нападающий портит ровно то,
    /// ради чего пришёл»). Выбитое в метель окно забирает больше, чем даёт
    /// вынесенный шкаф, — и квартира, взятая с боем, греет хуже брошенной.
    /// </summary>
    public double потери_тепла(Баланс b)
    {
        var цены = b.Таблица("дыра_градусов");
        double сумма = 0.0;
        foreach (var (вид, n) in дыры)          // порядок вставки, как в Python
            сумма += цены.Взять(вид, цены["стена"]) * n;
        return сумма;
    }

    /// <summary>
    /// Насколько за этой дверью можно отсидеться (GDD 15, 16). Дыра в стене
    /// отменяет засов: за ней уже не отсидеться, сколько бы листов ни было
    /// прибито к двери.
    /// </summary>
    public double защита(Баланс? b = null)
    {
        double v = door_strength() + 1.2 * shelter.Взять("стены", 0.0);
        if (b is not null)
            v -= b["дыра_защита"] * дыр();
        return Math.Max(0.0, v);
    }
}

/// <summary>
/// Погреб в подвале или гараж за домом — имущество за порогом квартиры.
///
/// До сих пор всё, что не в шкафу, было ничьим в равной мере: и мусорка
/// во дворе, и чужой гараж, и чужая площадка. Поэтому «сходить за своим»
/// и «залезть в чужое» были для кода одним действием с разной добычей,
/// и порядок между ними задавала не совесть, а арифметика часов: в первый
/// день метели 44 % всех вылазок уходило в чужие подъезды и гаражи.
///
/// Кладовая — не новый источник еды, а перераспределение того же самого:
/// столько же банок в мире, но не у всех, не в шкафу и за отдельным замком.
/// Принадлежит она квартире, а не человеку, — по той же причине, по какой
/// квартира стала вещью: занял чужой угол — получил и то, что к нему
/// приписано.
/// </summary>
public sealed class Кладовая
{
    public required string id { get; set; }
    public required ВидКладовой вид { get; set; }
    public required int apt { get; set; }       // за какой квартирой закреплена
    public Словарь<string, double> stock { get; } = Словари.Числа();
    public List<Оружие> оружие { get; } = new();
    public bool тулуп { get; set; }
    public bool вскрыта { get; set; }           // замок сорван — теперь туда ходят все
    public int ходок { get; set; }              // сколько раз оттуда уже носили

    // родительный падеж вида: «ключ от погреба», «замок с гаража»
    private static readonly Dictionary<ВидКладовой, string> ВИД_РОД = new()
    {
        [ВидКладовой.ПОГРЕБ] = "погреба",
        [ВидКладовой.ГАРАЖ] = "гаража",
    };

    /// <summary>Как её называют в журнале: «погреб кв.6».</summary>
    public string имя => $"{вид.Текст()} кв.{apt}";

    /// <summary>Родительный падеж: «ключ от погреба кв.6». Формы лежат рядом
    /// с самим списком видов — как у имён и у оружия.</summary>
    public string имя_род
        => $"{(ВИД_РОД.TryGetValue(вид, out var р) ? р : вид.Текст())} кв.{apt}";

    public bool пусто() => Ресурсы.Вещи(stock) <= 0.01 && оружие.Count == 0 && !тулуп;
}
