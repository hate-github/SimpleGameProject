// Перенос house/character.py: характер как мерка поступка (GDD 12.1, 12.4).
//
// Три функции, которыми человек судит собственную руку. Их спрашивают
// не только из выбора действия: вербовка в налёт и ночные решения задают
// тот же вопрос, и потому они живут отдельно от `actions` (аудит §7).

namespace Дом.Ядро;

public static class Характер
{
    /// <summary>
    /// (запрет, склонность) — как ценности человека держат его руку (GDD 12.1).
    ///
    /// Разведены нарочно, потому что действуют по-разному. Запрет — вычет:
    /// «не терплю воровство» обязано уметь остановить, даже когда очень
    /// хочется. Склонность — доля: «ценю работу» делает человека охотнее
    /// в том, что он и так собрался делать, но не выдумывает ему дела
    /// на пустом месте.
    ///
    /// Пока обе входили слагаемыми, склонность работала как нужда: Виктор
    /// получал +1.5 к любой стройке при нулевом холоде и собирал генератор
    /// на третий день метели, при горячих розетках.
    /// </summary>
    public static (double запрет, double склонность) мерка_поступка(NPC npc, string key, Баланс b)
    {
        if (!Каталог.ТЕГИ.TryGetValue(key, out var теги) || теги.Length == 0)
            return (0.0, 0.0);
        double запрет = 0.0, склонность = 0.0;
        foreach (var tag in теги)
            if (npc.не_терпит(tag))
                запрет += b["своя_мерка"];
        foreach (var tag in теги)
            if (npc.ценит(tag))
                склонность += b["своя_мерка_склонность"];
        return (запрет, склонность);
    }

    /// <summary>
    /// Насколько этот поступок противен самому человеку (GDD 12.1).
    ///
    /// Та же метка, которой он судит соседа. «Не терплю воровство» — тормоз
    /// для своей руки, «ценю щедрость» — прибавка к помощи. Своё осуждается
    /// сильнее, чем одобряется чужое: запрет весит больше, чем склонность.
    ///
    /// Меток бывает несколько, и они складываются: поступок, в котором
    /// человек видит и своё, и чужое сразу, тянет его в обе стороны — Игорь
    /// одобряет силу в отъёме, Костя видит в том же отъёме насилие,
    /// и это разные люди.
    /// </summary>
    public static double своя_мерка(NPC npc, string key, Баланс b)
    {
        if (!Каталог.ТЕГИ.TryGetValue(key, out var теги) || теги.Length == 0)
            return 0.0;
        double s = 0.0;
        foreach (var tag in теги)
        {
            if (npc.не_терпит(tag))
                s -= b["своя_мерка"];
            if (npc.ценит(tag))
                s += b["своя_мерка"] * 0.6;
        }
        return s;
    }

    /// <summary>Множитель к оценке: чем нормальнее ещё кажется жизнь,
    /// тем немыслимее поступок.</summary>
    public static double norm_gate(NPC npc, string key, Баланс b)
    {
        double w = Каталог.НОРМА.Взять(key, 0.0);
        if (w == 0.0)
            return 1.0;
        return Util.Clamp(b["нормальность_порог"] - npc.normalcy * w, 0.02, 1.0);
    }
}
