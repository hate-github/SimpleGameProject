// Перенос house/actions.py, строки 519–642: корзина вариантов хода.
//
// Явный объект вместо замыкания внутри `gather`: разделы сбора становятся
// функциями и получают корзину в руки, а ворота — часы, лимиты, визиты,
// характер — остаются одними на всех.

using System.Runtime.CompilerServices;

namespace Дом.Ядро;

/// <summary>
/// Из чего сложилась оценка варианта — то самое объяснение решения.
///
/// Число в списке вариантов говорит «попросить у Лиды стоит 4.2», но
/// не говорит почему; а почему — это и есть характер: пунктик, долгая цель,
/// личный запрет, склонность и ворота нормальности.
/// </summary>
public sealed record Слагаемые(
    double сырое,        // что насчитал раздел gather, до характера
    double пунктик,      // именованное правило характера (NPC.пунктик)
    double замысел,      // подкраска долгой цели
    double запрет,       // «не терплю воровство» — вычет
    double склонность,   // «ценю работу» — доля, а не слагаемое
    double ворота,       // множитель нормальности
    double часы);        // сколько это стоит времени

/// <summary>Ключ «действие плюс его цель». Цель сравнивается по ссылке —
/// это `id(target)` из прототипа.</summary>
public readonly struct КлючЦели : IEquatable<КлючЦели>
{
    public readonly string key;
    public readonly object? target;

    public КлючЦели(string key, object? target)
    {
        this.key = key;
        this.target = target;
    }

    public bool Equals(КлючЦели о)
        => string.Equals(key, о.key, StringComparison.Ordinal)
           && ReferenceEquals(target, о.target);

    public override bool Equals(object? о) => о is КлючЦели к && Equals(к);

    public override int GetHashCode()
        => HashCode.Combine(key,
            target is null ? 0 : RuntimeHelpers.GetHashCode(target));
}

/// <summary>
/// Варианты хода одного человека с оценками: то, что <c>gather</c> собирает,
/// а <c>choose_and_do</c> разыгрывает.
///
/// Заодно корзина помнит, из чего сложилась каждая оценка, и что не прошло
/// общие ворота — но только если есть кому это читать: у жильца с мягким
/// выбором объяснение никто не спрашивает, а за прогон это сотни тысяч
/// записей на выброс.
/// </summary>
public sealed class Корзина
{
    private readonly House h;
    private readonly NPC npc;
    private readonly Баланс b;
    private readonly Словарь<string, double> lim_day;
    private readonly Словарь<string, double> lim_pair;

    /// <summary>Сколько раз сегодня уже выходил к соседям и сколько ещё можно.</summary>
    public int визитов { get; }
    public int предел_визитов { get; }

    public List<((string key, object? target) что, double оценка)> варианты { get; } = new();

    /// <summary>С чем человек подошёл к выбору.</summary>
    public Самочувствие? с { get; }

    public bool разбирать { get; }
    public Dictionary<КлючЦели, Слагаемые> слагаемые { get; } = new();
    public List<(string key, object? target, string почему)> отказы { get; } = new();
    public Dictionary<КлючЦели, object?> детали { get; } = new();

    public Корзина(House h, NPC npc, int визитов, int предел_визитов, Самочувствие? с = null)
    {
        this.h = h;
        this.npc = npc;
        b = h.B;
        this.визитов = визитов;
        this.предел_визитов = предел_визитов;
        lim_day = b.Таблица("лимит_в_день");
        lim_pair = b.Таблица("лимит_на_пару_в_день");
        this.с = с;
        разбирать = (npc.решающий as Решающий)?.разбирает ?? false;
    }

    /// <summary>Дверь, которая была закрыта. Пишется только для того, кто спросит.</summary>
    private void _отказ(string key, object? target, string почему)
    {
        if (разбирать)
            отказы.Add((key, target, почему));
    }

    /// <summary>
    /// Предложить действие.
    ///
    /// <paramref name="детали_"/> — что именно решено, если у действия есть
    /// выбор внутри: какую услугу заказать, чем поделиться, что просить.
    /// Исполнителю они достаются готовыми, а не считаются заново — иначе
    /// человек выбирает одно, а делает другое, и игроку это видно первым.
    ///
    /// <paramref name="часы"/> — если оно стоит не столько, сколько обычно.
    /// <paramref name="мерка"/> — по какому поступку его судить, если это
    /// не то же самое, что само действие: сходить в магазин и вскрыть чужой
    /// гараж — одна вылазка по устройству и два разных поступка по совести.
    /// </summary>
    public void add(string key, double score, object? target = null, double? часы = null,
                    string? мерка = null, object? детали_ = null)
    {
        string м = мерка ?? key;
        // характер: личные пунктики и собственная мерка этого поступка.
        // Запрет и склонность входят по-разному, и это не украшение.
        // «Не терплю воровство» обязано уметь остановить руку — значит,
        // вычитается. «Ценю работу» обязано делать человека охотнее — но
        // не обязано выдумывать ему дело: пока склонность прибавлялась,
        // Виктор собирал генератор на третий день метели, при горячих розетках
        var (запрет, склонность) = Характер.мерка_поступка(npc, м, b);
        // и то, чего человек добивается дольше одного дня. Прибавка, а не
        // приказ: замысел делает дело охотнее, но не отменяет ни голода,
        // ни мороза, ни совести
        double сырое = score;
        double пунктик = npc.пунктик(м);
        double вес_замысла = Замыслы.вес(h, npc, key, target);
        score = (сырое + пунктик + вес_замысла - запрет) * (1.0 + склонность);
        if (score <= 0)
        {
            _отказ(key, target, "характер: оценка не выше нуля");
            return;
        }
        if (Каталог.СТРОЙКА.Есть(key) && npc.hurt("руки"))
        {
            _отказ(key, target, "разбитая рука");
            return;                   // разбитой рукой не строят (GDD 6.2)
        }
        double надо = часы ?? Действия.hours(key, npc, b);
        if (надо > npc.time_left + 0.001)
        {
            _отказ(key, target,
                $"не хватит часов: надо {надо:F1}, осталось {npc.time_left:F1}");
            return;
        }
        if (Действия.used_day(h, npc, key) >= lim_day.Взять(key, 99))
        {
            _отказ(key, target, "дневной предел");
            return;
        }
        if (Каталог.ВИЗИТЫ.Contains(key) && визитов >= предел_визитов)
        {
            _отказ(key, target, "на сегодня к соседям уже находился");
            return;
        }
        // цель бывает не человеком: место вылазки — не тот, к кому ходят,
        // и пары «я и он» с ним не бывает
        if (target is NPC кто)
        {
            if (Действия.used_pair(h, npc, кто, key) >= lim_pair.Взять(key, 99))
            {
                _отказ(key, target, "предел на эту пару за день");
                return;
            }
        }
        double ворота = Характер.norm_gate(npc, м, b);
        if (детали_ is not null)
            детали[new КлючЦели(key, target)] = детали_;
        if (разбирать)
            слагаемые[new КлючЦели(key, target)] = new Слагаемые(
                сырое: сырое, пунктик: пунктик, замысел: вес_замысла, запрет: запрет,
                склонность: склонность, ворота: ворота, часы: надо);
        варианты.Add(((key, target), score * ворота));
    }
}
