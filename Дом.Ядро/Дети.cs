// Перенос house/child.py: сутки ребёнка (GDD 12.6).
//
// Ребёнок — состояние, а не множитель к чужим решениям: у него своя сытость,
// своё тепло и своё здоровье. Он остывает быстрее взрослого и болеет чаще,
// а лечится хуже.

namespace Дом.Ядро;

public static class Дети
{
    /// <summary>
    /// Сутки ребёнка: ест после матери, остывает быстрее, болеет чаще.
    /// <paramref name="room"/> — комната матери; ночь у соседа считается
    /// соседской печкой.
    /// </summary>
    public static void сутки(House h, NPC p, double room)
    {
        var b = h.B;
        foreach (var р in p.дети.ToList())
        {
            р.сытость = Util.Clamp(р.сытость - b["ребёнок_расход_сытости"]);
            // ту ночь, которую он провёл у соседа, он греется соседской
            // печкой: ради этого его туда и отнесли
            double комната = room;
            var у_кого = string.IsNullOrEmpty(р.у) ? null : h.живой(р.у);
            if (у_кого is not null)
                комната = h.room_temp(у_кого, burning: у_кого.burning);
            // та же комната, но ребёнок остывает быстрее взрослого
            р.тепло = Util.Clamp(р.тепло + (комната - b["комфортная_температура"])
                                 * b["тепло_за_градус"] * b["ребёнок_мёрзнет"]);
            double урон = 0.0;
            foreach (var v in new[] { р.сытость, р.тепло })
                if (v < b["критичный_порог"])
                    урон += (b["критичный_порог"] - v) * b["здоровье_за_критичное"]
                            * b["ребёнок_хрупкость"];
            if (р.болен is not null)
                урон += b["болезнь_урон_в_день"] * b["ребёнок_хрупкость"];
            if (урон > 0)
                р.здоровье = Util.Clamp(р.здоровье - урон);
            else if (Math.Min(р.сытость, р.тепло) > b["порог_восстановления"])
                р.здоровье = Util.Clamp(р.здоровье + b["здоровье_восстановление"]);

            if (р.болен is null && р.тепло < 40
                && h.rng.Chance(b["болезнь_шанс_на_холоде"] * b["ребёнок_болеет"]))
            {
                р.болен = "простуда";
                h.journal.line($"{р.имя} закашлял у {p.form("gen")} на руках.", 1);
            }
            else if (р.болен is not null
                     && h.rng.Chance(b["болезнь_проходит"] * b["ребёнок_болезнь_проходит"]
                                     * (р.тепло > 55 ? b["болезнь_проходит_в_тепле"] : 1.0)))
            {
                р.болен = null;
            }
            if (р.здоровье <= 0)
                Конфликт.смерть_ребёнка(h, p, р);
        }
    }
}
