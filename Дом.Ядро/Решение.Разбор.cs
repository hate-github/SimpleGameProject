// Перенос house/decision.py, строки 139–218 и 246–347: разбор решения.
//
// Объяснение решения — это три разные вещи, и в одну строку они не
// складываются: с чем человек подошёл (`состояние`), из чего сложились
// оценки (`объяснить`) и какие двери были закрыты вовсе (`закрытое`).
// Половина вопросов «почему он этого не сделал» упирается в третье,
// которого в списке вариантов не видно.
//
// Сюда же — двое решающих, которым это объяснение и нужно: `Скрипт`
// (проверки и сценарии, без случайности) и `Человек` (игрок).

namespace Дом.Ядро;

public static class Разбор
{
    /// <summary>Как назвать вариант в строке объяснения.</summary>
    public static string имя(object? о)
    {
        if (о is ValueTuple<string, object?> пара)
        {
            var (ключ, цель) = пара;
            // в прототипе это `getattr(цель, "short") or getattr(цель, "имя")`:
            // цель бывает жильцом, кладовкой, местом вылазки и пустой квартирой
            string? кто = цель switch
            {
                NPC n      => n.@short,
                Кладовая к => к.имя,
                Место м    => м.имя,
                Ребёнок р  => р.имя,
                // квартира — это «кв.11», а не весь её repr со шкафом и убежищем
                Flat f     => $"кв.{f.apt}",
                _          => null,
            };
            if (!string.IsNullOrEmpty(кто))
                return $"{ключ} → {кто}";
            return цель is not null ? $"{ключ} → {цель}" : ключ;
        }
        return о?.ToString() ?? "";
    }

    /// <summary>Из чего сложилась оценка: `Слагаемые` одной строкой.</summary>
    public static string разложение(Слагаемые сл)
    {
        var части = new List<string> { $"{Текст.Ф(сл.сырое, 2)} сырое" };
        foreach (var (название, v) in new (string, double)[]
                 { ("пунктик", сл.пунктик), ("замысел", сл.замысел), ("запрет", -сл.запрет) })
            if (Math.Abs(v) > 0.005)
                части.Add($"{Текст.Знак(v, 2)} {название}");
        if (Math.Abs(сл.склонность) > 0.005)
            части.Add($"×{Текст.Ф(1.0 + сл.склонность, 2)} склонность");
        if (Math.Abs(сл.ворота - 1.0) > 0.005)
            части.Add($"×{Текст.Ф(сл.ворота, 2)} нормальность");
        return string.Join(" ", части) + $", {Текст.Ф(сл.часы, 1)} ч";
    }

    /// <summary>
    /// Оценённые варианты строками, от лучшего к худшему: то, что показывают
    /// человеку и пишут в разбор. Это и есть объяснение решения.
    ///
    /// Строк ровно столько, сколько вариантов: по ним человек и выбирает
    /// номером, поэтому ни самочувствие, ни закрытые двери сюда
    /// не подмешиваются — они отдельно.
    /// </summary>
    public static List<string> объяснить(IReadOnlyList<(object? что, double вес)> варианты,
                                         int лучших = 6, Корзина? корзина = null)
    {
        var top = ПоУбыванию(варианты).Take(лучших).ToList();
        var слагаемые = корзина?.слагаемые;
        var строки = new List<string>();
        foreach (var (о, s) in top)
        {
            string строка = $"{Текст.Слева(имя(о), 30)} {Текст.Справа(s, 7, 2)}";
            if (слагаемые is not null && о is ValueTuple<string, object?> пара
                && слагаемые.TryGetValue(new КлючЦели(пара.Item1, пара.Item2), out var сл))
                строка += "   = " + разложение(сл);
            строки.Add(строка);
        }
        return строки;
    }

    /// <summary>
    /// С чем человек подошёл к выбору: `Самочувствие` одной строкой.
    /// Печатается только то, что не ноль: у сытого и целого строка короткая.
    /// </summary>
    public static string состояние(Самочувствие? с)
    {
        if (с is null)
            return "";
        var названо = new (string, double)[]
        {
            ("отчаяние", с.отчаяние), ("невмоготу", с.невмоготу), ("зову", с.зову),
            ("голод", с.голод), ("жажда", с.жажда), ("холод", с.холод),
            ("усталость", с.усталость), ("тревога", с.тревога),
        };
        var есть = названо.Where(п => п.Item2 > 0.005)
                          .Select(п => $"{п.Item1} {Текст.Ф(п.Item2, 2)}").ToList();
        string чувства = есть.Count > 0 ? string.Join(", ", есть) : "ничего не жмёт";
        return $"самочувствие: {чувства}; в комнате {Текст.Ф(с.комната, 0)}°, "
             + $"еды {Текст.Ф(с.еды_дней, 1)} дн";
    }

    /// <summary>Двери, которые сегодня были закрыты, и почему.</summary>
    public static string закрытое(Корзина? корзина, int сколько = 6)
    {
        var отказы = корзина?.отказы;
        if (отказы is null || отказы.Count == 0)
            return "";
        // сначала двери, закрытые обстоятельствами — часами, лимитом, разбитой
        // рукой, — и только потом самые частые и самые скучные: «ему этого
        // сейчас не хочется». Иначе первые шесть строк всегда одни и те же
        var порядок = отказы
            .OrderBy(о => о.почему.StartsWith("характер", StringComparison.Ordinal) ? 1 : 0)
            .ToList();
        var видно = порядок.Take(сколько)
            .Select(о => $"{имя(((string, object?))(о.key, о.target))} ({о.почему})").ToList();
        int ещё = отказы.Count - видно.Count;
        return "закрыто: " + string.Join("; ", видно) + (ещё > 0 ? $" и ещё {ещё}" : "");
    }

    /// <summary>По убыванию веса, устойчиво: равные держат исходный порядок,
    /// как `sorted(key=lambda v: -v[1])` в Python.</summary>
    internal static List<(object? что, double вес)> ПоУбыванию(
        IReadOnlyList<(object? что, double вес)> варианты)
        => варианты.OrderByDescending(v => v.вес).ToList();

    /// <summary>Первый из наибольших — ровно то, что делает `max` в Python.</summary>
    internal static object? Лучший(IReadOnlyList<(object? что, double вес)> варианты)
    {
        if (варианты.Count == 0)
            return null;
        int луч = 0;
        for (int i = 1; i < варианты.Count; i++)
            if (варианты[i].вес > варианты[луч].вес)
                луч = i;
        return варианты[луч].что;
    }
}

/// <summary>
/// Для проверок и сценариев: без случайности. Всегда лучший вариант, монета —
/// по склонности от половины, правило — как есть; отдельные ответы можно
/// задать заранее по вопросу. Каждое решение остаётся в <c>разбор</c>.
/// </summary>
public sealed class Скрипт : Решающий
{
    public override bool разбирает => true;

    /// <summary>вопрос → ответ, задано заранее.</summary>
    public Dictionary<Вопрос, string> ответы { get; }

    /// <summary>(день, кто, вопрос, строки объяснения, выбор).</summary>
    public List<(int день, string кто, Вопрос вопрос, List<string> строки, string? выбор)>
        разбор { get; } = new();

    public Скрипт(IEnumerable<KeyValuePair<Вопрос, string>>? ответы = null)
        => this.ответы = ответы is null ? new() : new Dictionary<Вопрос, string>(ответы);

    /// <summary>Строки разбора: самочувствие, оценённые варианты со слагаемыми,
    /// закрытые двери. Пустые части не пишутся.</summary>
    private void _записать(House h, NPC npc, Вопрос вопрос,
                           IReadOnlyList<(object? что, double вес)> варианты, string? выбор,
                           Корзина? корзина = null, Самочувствие? чувства = null)
    {
        чувства ??= корзина?.с;
        var строки = new List<string>();
        if (чувства is not null)
            строки.Add(Разбор.состояние(чувства));
        строки.AddRange(Разбор.объяснить(варианты, корзина: корзина));
        string хвост = Разбор.закрытое(корзина);
        if (хвост.Length > 0)
            строки.Add(хвост);
        разбор.Add((h.day, npc.id, вопрос, строки, выбор));
    }

    public override (string key, object? target)? день(
        House h, NPC npc, IReadOnlyList<((string key, object? target) что, double вес)> варианты,
        Корзина? корзина = null)
    {
        var общие = Решающий.Вширь(варианты);
        var выбор = (ValueTuple<string, object?>?)Разбор.Лучший(общие);
        _записать(h, npc, Вопрос.ДЕНЬ, общие, Разбор.имя(выбор), корзина: корзина);
        return выбор is null ? null : (выбор.Value.Item1, выбор.Value.Item2);
    }

    public override (string вид, object? кому)? ночь(
        House h, NPC npc,
        IReadOnlyList<((string вид, object? кому) что, double вес)> варианты,
        Самочувствие? с = null)
    {
        var общие = Решающий.Вширь(варианты);
        var что = (ValueTuple<string, object?>?)Разбор.Лучший(общие);
        _записать(h, npc, Вопрос.НОЧЬ, общие, Разбор.имя(что), чувства: с);
        return что is null ? null : (что.Value.Item1, что.Value.Item2);
    }

    public override string? ответ(House h, NPC npc, Ситуация с)
    {
        string? итог;
        if (ответы.TryGetValue(с.вопрос, out var задано))
            итог = задано;
        else if (с.склонность is not null)
            итог = с.склонность.Value >= 0.5 ? с.варианты[0].ответ : с.варианты[1].ответ;
        else
            итог = с.по_правилу;
        _записать(h, npc, с.вопрос, Решающий.Вширь(с.варианты), итог);
        return итог;
    }

    public override string? выбор(House h, NPC npc, Вопрос вопрос,
                                  IReadOnlyList<(string что, double вес)> варианты)
    {
        var общие = Решающий.Вширь(варианты);
        string? итог = ответы.TryGetValue(вопрос, out var если)
                       ? если : (string?)Разбор.Лучший(общие);
        _записать(h, npc, вопрос, общие, Разбор.имя(итог));
        return итог;
    }
}

/// <summary>
/// Игрок (GDD 13): ему показывают оценённые варианты и спрашивают.
///
/// Спрашивают двумя способами, и это один и тот же вопрос. Экран получает
/// запись <see cref="ВопросИгроку"/> — с членом перечисления, самими
/// вариантами и весами. Консоль получает её же, но сведённую к строкам:
/// <c>спросить(заголовок, строки) → номер</c>. Второй сделан через первый,
/// поэтому разъехаться им негде.
///
/// Оценки игроку видны те же, что и NPC: это и есть «правило одно для всех».
/// </summary>
public sealed class Человек : Решающий
{
    public override bool разбирает => true;

    private readonly Func<ВопросИгроку, int> спросить;

    /// <summary>Спрашивать строками: заголовок и нумерованный список.
    /// Так устроена консоль и так же было в прототипе.</summary>
    public Человек(Func<string, List<string>, int>? спросить = null)
    {
        var с = спросить ?? _консоль;
        this.спросить = в => с(в.заголовок, в.строки);
    }

    /// <summary>Спрашивать записью: всё, что есть у вопроса, без сведения
    /// к тексту. Так устроен экран (навык godot-boundary).</summary>
    public Человек(Func<ВопросИгроку, int> спросить)
        => this.спросить = спросить;

    private static int _консоль(string вопрос, List<string> строки)
    {
        Console.WriteLine(вопрос);
        for (int i = 0; i < строки.Count; i++)
            Console.WriteLine($"  {i}. {строки[i]}");
        while (true)
        {
            Console.Write("> ");
            if (int.TryParse(Console.ReadLine(), out int n))
                return n;
        }
    }

    /// <summary>
    /// Собрать вопрос и спросить.
    ///
    /// Строки — ровно варианты, по ним человек и выбирает номером.
    /// Самочувствие и закрытые двери идут в заголовок: подмешать их
    /// в список значило бы сдвинуть нумерацию под рукой у игрока.
    /// </summary>
    private object? _выбрать(House h, NPC npc, Вопрос вопрос,
                             IReadOnlyList<(object? что, double вес)> варианты,
                             Корзина? корзина = null, Самочувствие? чувства = null)
    {
        var порядок = Разбор.ПоУбыванию(варианты);
        чувства ??= корзина?.с;
        string шапка = $"день {h.day}, {npc.@short}: {Вопросы.Текст(вопрос)}";
        foreach (string хвост in new[] { Разбор.состояние(чувства), Разбор.закрытое(корзина) })
            if (хвост.Length > 0)
                шапка += "\n  " + хвост;

        // строки строятся по несортированному списку, а выбор — по сортированному:
        // так было в прототипе, и `объяснить` сортирует внутри себя сам
        var подписи = Разбор.объяснить(варианты, варианты.Count, корзина);
        var в = new List<ВариантИгроку>(порядок.Count);
        for (int k = 0; k < порядок.Count; k++)
            в.Add(new ВариантИгроку(порядок[k].что, порядок[k].вес,
                                    k < подписи.Count ? подписи[k] : ""));

        int i = спросить(new ВопросИгроку(h.day, npc.id, вопрос, шапка, в, чувства, корзина));
        return порядок[Math.Max(0, Math.Min(i, порядок.Count - 1))].что;
    }

    public override (string key, object? target)? день(
        House h, NPC npc, IReadOnlyList<((string key, object? target) что, double вес)> варианты,
        Корзина? корзина = null)
    {
        if (варианты.Count == 0)
            return null;
        var о = (ValueTuple<string, object?>?)_выбрать(
            h, npc, Вопрос.ЧТО_ДЕЛАТЬ, Решающий.Вширь(варианты), корзина);
        return о is null ? null : (о.Value.Item1, о.Value.Item2);
    }

    public override (string вид, object? кому)? ночь(
        House h, NPC npc,
        IReadOnlyList<((string вид, object? кому) что, double вес)> варианты,
        Самочувствие? с = null)
    {
        if (варианты.Count == 0)
            return null;
        var о = (ValueTuple<string, object?>?)_выбрать(
            h, npc, Вопрос.НОЧЬ, Решающий.Вширь(варианты), чувства: с);
        return о is null ? null : (о.Value.Item1, о.Value.Item2);
    }

    public override string? ответ(House h, NPC npc, Ситуация с)
    {
        // здесь порядок вариантов — тот, в котором их собрало правило,
        // а не по убыванию веса: первый вариант — «да» этой ситуации,
        // и переставлять его нельзя
        var в = с.варианты
            .Select(x => new ВариантИгроку(
                x.ответ, x.вес,
                $"{Текст.Слева(x.ответ, 30)} {Текст.Справа(x.вес, 7, 2)}"))
            .ToList();
        int i = спросить(new ВопросИгроку(
            h.day, npc.id, с.вопрос,
            $"день {h.day}, {npc.@short}: {Вопросы.Текст(с.вопрос)}", в, null, null));
        return с.варианты[Math.Max(0, Math.Min(i, с.варианты.Count - 1))].ответ;
    }

    public override string? выбор(House h, NPC npc, Вопрос вопрос,
                                  IReadOnlyList<(string что, double вес)> варианты)
        => варианты.Count == 0
           ? null
           : (string?)_выбрать(h, npc, вопрос, Решающий.Вширь(варианты));
}
