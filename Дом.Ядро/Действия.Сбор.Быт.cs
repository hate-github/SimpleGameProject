// Перенос house/actions.py, `_быт`: первый раздел сбора вариантов.
//
// Еда, вода, печка, генератор, уход к пункту обогрева, «не отвечает третий
// день», вытяжка, костёр и заказ работы у того, у кого руки.

namespace Дом.Ядро;

public static partial class Действия
{
    /// <summary>Раздел gather: быт.</summary>
    public static void _быт(Корзина корзина, House h, NPC npc, Баланс b, Самочувствие с)
    {
        if (npc.stock.Взять("мясо", 0.0) > 0 && npc.satiety < 70
            && npc.stock.Взять("еда", 0.0) <= 0)
            корзина.add("поесть_мясо", с.голод * 8.0);
        // ребёнка кормят раньше себя — в том числе когда сам ещё не голоден
        double детский_голод = npc.дети.Count > 0 ? npc.дети.Min(р => р.сытость) : 100.0;
        if (npc.stock.Взять("еда", 0.0) > 0 && (npc.satiety < 88 || детский_голод < 75))
        {
            double s = с.голод * 9.0 * с.край(npc.satiety);
            if (с.еды_дней < 2.5 && npc.satiety > 45)
                s *= 0.45;           // режим экономии: терпит, пока может
            if (npc.dependents != 0)
                s += 1.2 + (1.0 - Util.Norm(детский_голод, 20, 80)) * 7.0;
            корзина.add("поесть", s);
        }

        if (npc.hydration < 88 && (h.water_on || npc.stock.Взять("вода", 0.0) > 0))
            корзина.add("попить", с.жажда * 9.5 * с.край(npc.hydration));
        // снег топят только там, где есть на чём (GDD 15: буржуйка — улучшение
        // 2 уровня). Без печки вода становится настоящей проблемой
        bool can_melt = npc.shelter.Взять("буржуйка", 0.0) != 0.0
                        || (h.powered(npc) && npc.shelter.Взять("обогреватель", 0.0) != 0.0);
        // печка в квартире одна, и дрова к ней общие: за снег гостя платит
        // то же хозяйство, у которого он греется
        var очаг = h.хозяин_жилья(npc);
        bool есть_чем = очаг.stock.Взять("топливо", 0.0) >= b["снег_топливо"]  // правда: под одной крышей: дрова у печки общие
                        || npc.stock.Взять("материалы", 0.0) >= b["мебель_за_топку"];
        if (!h.water_on && can_melt && npc.stock.Взять("вода", 0.0) < 4 && есть_чем)
        {
            // снег топят охотнее, когда печка и так нужна: одно действие
            // закрывает и жажду, и холод
            double together = !очаг.burning && npc.shelter.Взять("буржуйка", 0.0) != 0.0
                ? с.холод * 3.0 : 0.0;
            корзина.add("топить_снег", 2.0 + с.жажда * 6.5 + together);
        }

        // когда топливо кончилось, в печку идёт мебель — и тогда материалы
        // перестают быть строительным ресурсом. Это настоящий выбор:
        // утеплиться или дожить
        bool can_burn = npc.stock.Взять("топливо", 0.0) >= 1
                        || npc.stock.Взять("материалы", 0.0) >= b["мебель_за_топку"];
        if (!string.IsNullOrEmpty(npc.living_with))
            can_burn = false;        // печку топит хозяин
        if (npc.shelter.Взять("буржуйка", 0.0) != 0.0 && can_burn && !npc.burning)
        {
            // печку топят не для себя, а для комнаты. Пока хозяин считал
            // только свой холод, сытый и согревшийся хозяин не топил вовсе —
            // и гости, сложившие ему все свои дрова, замерзали у горячей печки
            var свои = new List<NPC?> { npc };
            foreach (var g in npc.guests.OrderBy(x => x, StringComparer.Ordinal))
                свои.Add(h.get(g));
            double мёрзнет = с.холод, худо = с.невмоготу;
            foreach (var o in свои)
            {
                if (o is null || !o.здесь())
                    continue;
                мёрзнет = Math.Max(мёрзнет, 1.0 - Util.Norm(o.warmth, 20, 70));  // правда: под одной крышей: кому в этой комнате хуже всех
                худо = Math.Max(худо, o.невмоготу());                            // правда: под одной крышей
                foreach (var р in o.дети)
                    мёрзнет = Math.Max(мёрзнет, 1.0 - Util.Norm(р.тепло, 20, 70));
            }
            // топят не только от холода в комнате: больному и раненому тепло нужнее
            double need = Math.Max(мёрзнет, худо) * 8.0
                          + Math.Max(0.0, 14 - с.комната) * 0.35;
            if (npc.days_of("топливо") < 3)
                need *= 0.7;
            корзина.add("топить", need);
        }

        if (npc.shelter.Взять("генератор", 0.0) != 0.0
            && очаг.stock.Взять("топливо", 0.0) >= 2 && !h.power_on)  // правда: под одной крышей: топливо к генератору общее
        {
            // генератор — это не грелка, а электричество на сутки: от него
            // работает обогреватель и на нём топят снег (GDD 15, уровень 3)
            double нужен = с.холод * 4.0 + (1.0 - Util.Norm(npc.mood, 20, 80)) * 2.0;
            if (npc.shelter.Взять("питание", double.NaN) == h.day)
                нужен = 0.0;         // он уже работает, второй раз заводить нечего
            if (npc.shelter.Взять("обогреватель", 0.0) != 0.0)
                нужен += с.холод * 4.0;
            if (!h.water_on && npc.stock.Взять("вода", 0.0) < 3)
                нужен += с.жажда * 3.0;
            корзина.add("генератор", нужен - с.тревога * 3.0
                * (npc.shelter.Взять("звукоизоляция", 0.0) != 0.0 ? 0.4 : 1.0));
        }

        // уйти к пункту обогрева. Это не место вылазки, а расстояние: до школы
        // № 7 четырнадцать часов ходу, и это в один конец. Мерки нормальности
        // у ухода нет и быть не должно: это разумное решение, а не падение
        if (npc.знает_пункт && npc.time_left >= b["уйти_часов_нужно"]
            && npc.health > b["уйти_здоровье_порог"])
        {
            double часов = b["пункт_часы"] * Улица.погода_часы(h);
            // пока человек верит, что улица ещё кормит, он никуда не пойдёт:
            // сначала магазин и свой погреб, а к школе № 7 — когда взять
            // больше негде
            double s = npc.desperation() * b["уйти_за_отчаяние"]
                       * (1.0 - есть_куда_сходить(h, npc, завтра: true)) - b["уйти_решимость"];
            s += npc.dependents * b["уйти_за_ребёнка"];
            // терять нечего: ни запаса, ни целой квартиры, ни погреба.
            // У обоих вычетов есть потолок: разница между «полный шкаф»
            // и «шкаф вдвое полнее» на это решение уже не влияет
            s -= Util.Clamp(Ресурсы.Вещи(npc.stock) * b["уйти_за_запас"],
                            0.0, b["уйти_запас_потолок"]);
            s -= Util.Clamp(h.where(npc).вложено * b["уйти_за_вложенное"],
                            0.0, b["уйти_вложенное_потолок"]);
            s -= h.мои_кладовые(npc).Count * b["уйти_за_кладовую"];
            s -= npc.allies.Count * b["уйти_за_союз"];
            // дорога стала длиннее, чем была, когда объявление вешали
            s -= Math.Max(0.0, часов - b["пункт_часы"]) * b["уйти_за_дорогу"];
            // и то, ради чего возврат с полпути вообще нужен: теперь он знает
            s -= b["уйти_после_возврата"] * npc.возвращался;
            if (npc.дорога_закрыта is not null)
                s -= b["уйти_дорога_закрыта"];
            корзина.add("уйти", s);
        }

        // «не отвечает третий день». Без этого тихая смерть не читается вовсе.
        // Считается не «сколько раз не открыли», а сколько дней от человека
        // нет ни звука: для мёртвого это одно и то же
        foreach (var t in h.people.Значения)
        {
            if (t.alive || t.exiled || t.died_day is null
                || npc.знает_о_смерти.Contains(t.id))   // правда: видно: мёртвый не шумит и не попадается — молчание за дверью
                continue;
            int молчит = h.day - t.died_day.Value;      // правда: видно: сколько дней от него ни звука
            if (молчит < b["не_открыл_дней"])
                continue;
            double s = b["проведать_вес"]
                       * (0.5 + npc.trust.Взять(t.id, 3.0) * b["проведать_доверие"])
                       * Math.Min(2.0, молчит / b["не_открыл_дней"]);
            s -= npc.hate.Взять(t.id, 0.0) * b["проведать_злость"];
            s -= npc.боится(t.id) * b["проведать_страх"];
            // и запах по стояку: через несколько дней тихая смерть перестаёт
            // быть тихой сама собой
            if (молчит >= b["запах_дней"] && Math.Abs(h.where(npc).floor - t.floor) <= 1)
                s += b["проведать_запах"];
            корзина.add("проведать", s, t);
        }

        // вытяжка: шахта обмёрзла изнутри, и печка больше не выдыхает наружу.
        // Догадаться можно тремя путями, и все три честные: по себе, по уму
        // и с чужих слов
        var flat_в = h.where(npc);
        if (flat_в.вентиляция < b["вентиляция_видно"])
        {
            bool видел = h.day - npc.угар_признак <= b["вытяжка_помнит_дней"];
            bool слышал = h.day - npc.слышал_про_угар <= b["вытяжка_помнит_дней"];
            double s = b["вытяжка_вес"] * (1.0 - flat_в.вентиляция)
                       * (0.2 + npc.t01("сообразительность") * b["вытяжка_сообразительность"]);
            if (видел)
                s += b["вытяжка_после_признака"];
            if (слышал)
                s += b["вытяжка_с_чужих_слов"];
            корзина.add("вытяжка", s);
        }

        // костёр: у кого нет печки, а комната больше не держит тепло. Опасно,
        // дымно и всё равно лучше, чем замёрзнуть. Отвечает он на холод
        // В КОМНАТЕ, а не на озноб в теле: промёрзшее тело отходит само,
        // за ночь у тёплой стены; костёр нужен тому, кому отходить негде
        if (npc.shelter.Взять("буржуйка", 0.0) == 0.0 && npc.топит_сам()
            && h.where(npc).костёр != h.day
            && с.комната < b["костёр_порог_комнаты"]
            && (npc.stock.Взять("материалы", 0.0) >= b["костёр_материалы"]
                || npc.stock.Взять("топливо", 0.0) >= 1))
        {
            double s = (b["костёр_порог_комнаты"] - с.комната) * b["костёр_за_градус"];
            // тело только торопит: замёрзшему, больному и раненому та же
            // комната холоднее, и до утра он ждать не станет
            s *= 1.0 + Math.Max(с.холод, с.невмоготу) * b["костёр_за_тело"];
            корзина.add("костёр", s - b["костёр_решимость"]);
        }

        // заказать работу у того, у кого руки (GDD 18). Раньше заказ был
        // один — буржуйка, — и всё остальное мастер строил только себе
        if (!h.заказы.Есть(npc.id))
            foreach (var m in h.others(npc))
            {
                // у мастера одни руки: пока он делает одну работу, вторую
                // не берёт. Без очереди Виктор набирал три заказа за день
                if (h.мастер_занят.Есть(m.id))
                    continue;
                // и не заказывают печь у того, кто на этой неделе стоял
                // у твоей двери с ломом: работа требует пустить его внутрь
                if (npc.враждует(m.id, b["обида_порог_вражды"]))
                    continue;
                var (что, оценка) = Услуги.что_заказать(h, npc, m, b, с.холод_впереди,
                                                        с.тревога);
                if (что is null)
                    continue;
                // и материал нужен сейчас, а не когда-нибудь: браться
                // за работу, которую нечем делать, — это не обещание,
                // а отговорка
                double мат = b[Услуги.УСЛУГИ[что].мат];
                bool свой = npc.stock.Взять("материалы", 0.0) >= мат;
                // доски мастера — по оценке его шкафа, а не по правде: что
                // у соседа лежит, слышно по стуку и видно при наблюдении
                if (!свой && npc.believed(m.id, "материалы") < мат)
                    continue;
                if (Услуги.кошелёк_за_работу(npc)
                    < Услуги.цена_услуги(h, npc, m, что, b, свой) * 0.5)
                    continue;
                // доверие к мастеру — множитель, а не слагаемое. Пока оно
                // прибавлялось, оно само по себе перетаскивало через порог
                // работу, которая человеку сегодня не нужна: генератор
                // с оценкой 0.3 при живых розетках становился делом дня
                корзина.add("заказать",
                    оценка * (1.0 + npc.trust.Взять(m.id, 3.0) * b["заказ_за_доверие"])
                        - npc.боится(m.id) * b["страх_вес_контакта"] * 0.5,
                    m, детали_: что);
            }
    }
}
