// Куда дом пишет строки. Пока — заглушка.
//
// `docs/ПОРТ.md`, пункт 4: текст переносится последним, когда состояние
// сойдётся по всем зёрнам. До тех пор строки печатать нечем и не нужно:
// сверка идёт по состоянию, а форматирование чисел на другом языке всё равно
// другое. Заглушка ничего не пишет и ничего не меняет — состояние от неё
// не зависит, и это ровно то, что значит «печатать заглушки».
//
// Настоящий журнал (`house/report.py`) приезжает на этапе 2, вместе
// с консольной игрой.

namespace Дом.Ядро;

public interface IЖурнал
{
    /// <summary>Строка дня. `заметность` — то же, что в прототипе:
    /// 0 показывать только подробно, 1 обычно, 2 наравне со смертью.</summary>
    void line(string текст, int заметность = 0);

    /// <summary>То, чего дом не видит: кто на самом деле украл и подбросил.
    /// Печатается только с `--секреты`.</summary>
    void secret(string текст);
}

/// <summary>Журнал, который ничего не пишет.</summary>
public sealed class ЗаглушкаЖурнала : IЖурнал
{
    public void line(string текст, int заметность = 0) { }
    public void secret(string текст) { }
}
