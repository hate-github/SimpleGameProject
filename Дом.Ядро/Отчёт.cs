// Перенос house/report.py — только то, что не вывод.
//
// Сам журнал (форматирование, панель, сводка дня) приезжает на этапе 2,
// вместе с консольной игрой: `docs/ПОРТ.md`, пункт 4 — текст последним.
// Здесь две вещи, которые движок зовёт каждый день и без которых состояние
// не сойдётся: одна пишет в счётчики дома, вторая — единственная строка,
// которую нельзя собрать в самом действии.

namespace Дом.Ядро;

public static class Отчёт
{
    /// <summary>
    /// Чем кончился день у тех, кто его пролежал: одна строка вместо восьми.
    ///
    /// Отдых стоит два часа, и восемь раз подряд — это ровно сутки. Поведение
    /// честное (сил нет, дел нет), а вот восемь одинаковых строк в журнале
    /// превращают человека в сломанный автомат. Поэтому исполнитель отдыха
    /// только считает разы, а говорит за них эта строка — одна на день.
    /// </summary>
    public static void отдых_за_день(House h)
    {
        foreach (var p in h.alive())
        {
            if (p.отдых_день != h.day)
                continue;
            int раз = p.отдых_раз;
            // и то, отчего этот день прошёл впустую. У матери, которой нечем
            // помочь ребёнку, «лежала и ничего не делала» — неправда журнала,
            // а не поведения: делать ей и правда нечего, но она не лежит
            bool с_ребёнком = p.дети.Count > 0
                              && p.ребёнку_плохо() >= h.B["быт_ребёнку_плохо"];
            string если_ребёнок = " рядом с "
                + (p.dependent_ins.Length > 0 ? p.dependent_ins
                   : (p.dependent_name.Length > 0 ? p.dependent_name : "ребёнком"));
            if (раз >= h.B["отдых_весь_день"])
                h.journal.line($"{p.@short} почти весь день "
                    + (с_ребёнком
                       ? $"{Util.Vb(p.sex, "просидел")}{если_ребёнок}."
                       : $"{Util.Vb(p.sex, "пролежал")} и ничего не "
                         + $"{Util.Vb(p.sex, "делал")}."), 1);
            else if (раз >= 2)
                h.journal.line($"{p.@short} подолгу "
                    + (с_ребёнком
                       ? $"{Util.Vb(p.sex, "сидел")}{если_ребёнок}."
                       : $"{Util.Vb(p.sex, "лежал")} и ничего не "
                         + $"{Util.Vb(p.sex, "делал")}."), 0);
            else
                h.journal.line($"{p.@short} "
                    + (с_ребёнком
                       ? $"{Util.Vb(p.sex, "сидел")}{если_ребёнок}."
                       : $"{Util.Vb(p.sex, "лежал")} и ничего не "
                         + $"{Util.Vb(p.sex, "делал")}."), 0);
        }
    }

    /// <summary>Диагностика: в какой день дом впервые дошёл до налёта,
    /// смерти, союза, кражи, ухода.</summary>
    public static void первые_дни(House h)
    {
        var s = h.stats;
        if (s.Взять("налётов", 0.0) != 0 && !s.Есть("первый_налёт_день"))
            s["первый_налёт_день"] = h.day;
        if (s.Взять("смертей", 0.0) != 0 && !s.Есть("первая_смерть_день"))
            s["первая_смерть_день"] = h.day;
        if (s.Взять("союзов_заключено", 0.0) != 0 && !s.Есть("первый_союз_день"))
            s["первый_союз_день"] = h.day;
        if (s.Взять("краж", 0.0) != 0 && !s.Есть("первая_кража_день"))
            s["первая_кража_день"] = h.day;
        if ((s.Взять("ушедших", 0.0) != 0 || s.Взять("возвратов_с_полпути", 0.0) != 0)
            && !s.Есть("первая_попытка_уйти"))
            s["первая_попытка_уйти"] = h.day;
    }
}
