// Перенос house/social.py, разделы «разговор» и «слово» (GDD 14).
//
// Ложь, которая работает, пока её не разоблачили, и обещания со сроком.
// Разоблачается ложь тем же, чем добывается всё остальное: запахом готовки,
// дымом из окна, увиденным шкафом, собственными ногами на том месте,
// про которое сказали «там пусто».

namespace Дом.Ядро;

public static partial class Социальное
{
    /// <summary>Разговор: обмен сведениями. Так осведомлённость расползается
    /// по дому.</summary>
    public static void gossip(House h, NPC a, NPC b_npc)
    {
        var bal = h.B;
        // вес слуха — это доверие СЛУШАТЕЛЯ к рассказчику, а не наоборот.
        // И на него работает то, ловили ли рассказчика на вранье: пойманный
        // однажды теряет вес своих рассказов — в этом и вся цена лжи (GDD 14)
        double вес_для_b = (0.25 + 0.05 * b_npc.trust.Взять(a.id, 3.0)) * вес_слов(b_npc, a);
        double вес_для_a = (0.25 + 0.05 * a.trust.Взять(b_npc.id, 3.0)) * вес_слов(a, b_npc);
        // поговорив с человеком, о котором тебе сказали «он вор», начинаешь
        // понимать, кто из двоих врал. Наговор потому и рискован: он держится
        // ровно до первого нормального разговора с оболганным
        проверить_наговор(h, a, b_npc);
        проверить_наговор(h, b_npc, a);
        double потолок = bal["слух_потолок_оценки"];
        foreach (var third in h.others(a))
        {
            if (string.Equals(third.id, b_npc.id, StringComparison.Ordinal))
                continue;
            // рассказываю то, в чём уверен сам
            if (a.сведения_о(third.id).aware > b_npc.сведения_о(third.id).aware + 12)
            {
                adjust(b_npc, third.id, aware: bal["осведомлённость_за_слух"]);
                foreach (var res in new[] { "еда", "топливо", "лекарства" })
                {
                    // у пересказа есть потолок: разговоры не могут перевесить
                    // личный опыт, иначе дом считает соседей вдвое богаче
                    note_signal(b_npc, third.id, res,
                                Math.Min(a.believed(third.id, res), потолок), вес_для_b * 0.6);
                    // и слух оставляет след: «мне про него сказали» — такое же
                    // основание пойти к его двери, как «я видел его с мешками»
                    b_npc.memory.Add(new Память
                        { день = h.day, вид = Вид.СКАЗАЛИ, кто = third.id, что = res });
                }
            }
            // и наоборот
            if (b_npc.сведения_о(third.id).aware > a.сведения_о(third.id).aware + 12)
            {
                adjust(a, third.id, aware: bal["осведомлённость_за_слух"]);
                foreach (var res in new[] { "еда", "топливо", "лекарства" })
                {
                    note_signal(a, third.id, res,
                                Math.Min(b_npc.believed(third.id, res), потолок), вес_для_a * 0.6);
                    a.memory.Add(new Память
                        { день = h.day, вид = Вид.СКАЗАЛИ, кто = third.id, что = res });
                }
            }
        }
        // обсуждают и то, у кого можно попросить, а у кого бесполезно
        foreach (var third in h.others(a))
        {
            if (string.Equals(third.id, b_npc.id, StringComparison.Ordinal))
                continue;
            foreach (var (teller, listener) in new[] { (a, b_npc), (b_npc, a) })
            {
                if (!teller.asking.TryGetValue(third.id, out var mine))
                    continue;
                if (mine.дали + mine.отказали < 1)
                    continue;
                var theirs = listener.ask_record(third.id);
                // у слухов есть потолок: разговоры не могут перевесить личный опыт
                double cap = bal["просьба_память_потолок"];
                if (mine.отказали > mine.дали)
                    theirs.отказали = Math.Min(theirs.отказали + 0.5, cap);
                else if (mine.дали > mine.отказали)
                    theirs.дали = Math.Min(theirs.дали + 0.5, cap);
            }
        }

        // и то, где ещё что-то осталось: первое, о чём говорят двое,
        // столкнувшись зимой на лестнице. Место только пустеет, поэтому
        // меньшее число знает тот, кто был там позже, — его слово и перевешивает
        var известные = new List<string>(a.места.Ключи);
        foreach (var k in b_npc.места.Ключи)
            if (!a.места.Есть(k))
                известные.Add(k);
        foreach (var имя in известные)
        {
            double зн_a = a.знаю_место(имя), зн_b = b_npc.знаю_место(имя);
            if (зн_a < зн_b)
                b_npc.места[имя] = зн_b + (зн_a - зн_b) * вес_для_b;
            else if (зн_b < зн_a)
                a.места[имя] = зн_a + (зн_b - зн_a) * вес_для_a;
        }

        // «мне ночью было худо, голова раскалывалась, и свеча гасла». Это
        // единственный путь, которым дом может узнать про угар ДО того, как
        // кто-то умрёт, — чат к этому дню уже не работает (GDD 19)
        foreach (var (рассказчик, слушатель) in new[] { (a, b_npc), (b_npc, a) })
        {
            int день = рассказчик.угар_признак;
            if (h.day - день <= bal["вытяжка_помнит_дней"])
                слушатель.слышал_про_угар = Math.Max(слушатель.слышал_про_угар, день);
        }

        // куда идти, если идти. Объявление на двери подъезда видели не все,
        // а знать надо всем — иначе уходить некуда. И обратное знание тоже
        // ходит: «я дошёл до перекрёстка и повернул»
        foreach (var (рассказчик, слушатель) in new[] { (a, b_npc), (b_npc, a) })
        {
            if (рассказчик.знает_пункт && !слушатель.знает_пункт)
                слушатель.знает_пункт = true;
            if (рассказчик.дорога_закрыта is not null && слушатель.дорога_закрыта is null)
                слушатель.дорога_закрыта = рассказчик.дорога_закрыта;
        }

        // известие о смерти. Оно ходит слухом, как и всё остальное, и упирается
        // в то же самое: кто рассказчику не верит, тот принимает не известие,
        // а вопрос — откуда ты знаешь? Разоблачается это ровно как наговор,
        // только «покойник» на площадку живым уже не выйдет (GDD 14)
        foreach (var (рассказчик, слушатель) in new[] { (a, b_npc), (b_npc, a) })
        {
            var новые = рассказчик.знает_о_смерти.Except(слушатель.знает_о_смерти,
                                                          StringComparer.Ordinal)
                                                 .OrderBy(x => x, StringComparer.Ordinal)
                                                 .ToList();
            foreach (var кто_id in новые)
                сообщить_о_смерти(h, рассказчик, слушатель, h.get(кто_id));
        }

        // чужая ненависть тоже заразна, если доверяешь рассказчику
        foreach (var third in h.others(a))
        {
            if (string.Equals(third.id, b_npc.id, StringComparison.Ordinal))
                continue;
            if (a.hate.Взять(third.id, 0.0) > 45 && a.trust.Взять(b_npc.id, 0.0) >= 5)
                b_npc.hate[third.id] = Util.Clamp(b_npc.hate.Взять(third.id, 0.0) + 5);
        }

        // --- а теперь то, чего у разговора не было: неправда (GDD 14) ---
        foreach (var (рассказчик, слушатель) in new[] { (a, b_npc), (b_npc, a) })
        {
            // ложь о местах: «в магазине пусто» — и сходить туда одному.
            // Идёт после честного обмена, иначе врущий убедит сам себя
            foreach (var имя in рассказчик.места.Ключи.OrderBy(x => x, StringComparer.Ordinal))
            {
                if (рассказчик.знаю_место(имя) < bal["ложь_место_порог"])
                    continue;
                if (слушатель.знаю_место(имя) <= bal["вылазка_пусто_порог"])
                    continue;                   // он и так думает, что там нечего брать
                if (уже_говорил(рассказчик, слушатель, "место", имя))
                    continue;
                if (!решает_врать(h, рассказчик, слушатель, "место"))
                    continue;
                слушатель.места[имя] = bal["вылазка_пусто_порог"] * 0.6;
                соврал(h, рассказчик, слушатель, "место", имя);
                break;
            }
            // ложь о людях: наговор. В общем чате это уже работало, в личном
            // разговоре — нет, хотя именно здесь он и опасен
            NPC? мишень = null;
            foreach (var t in h.others(рассказчик))
                if (мишень is null
                    || рассказчик.hate.Взять(t.id, 0.0) > рассказчик.hate.Взять(мишень.id, 0.0))
                    мишень = t;
            if (мишень is null || string.Equals(мишень.id, слушатель.id, StringComparison.Ordinal))
                continue;
            if (рассказчик.hate.Взять(мишень.id, 0.0) < bal["наговор_порог_злости"])
                continue;
            if (уже_говорил(рассказчик, слушатель, "человек", мишень.id))
                continue;
            if (!решает_врать(h, рассказчик, слушатель, "человек"))
                continue;
            double вес = вес_слов(слушатель, рассказчик);
            if (слушатель.trust.Взять(мишень.id, 3.0) >= bal["наговор_защита_доверием"])
                // слушатель этому человеку верит — и теперь косо смотрит
                // на рассказчика
                adjust(слушатель, рассказчик.id, trust: -0.8, hate: 5);
            else
            {
                adjust(слушатель, мишень.id, hate: bal["наговор_злость"] * вес,
                       trust: -0.5 * вес, aware: 4);
                // поверил — значит запомнил, на кого теперь думать. Знает
                // об этом он один: наговор говорят с глазу на глаз
                слушатель.memory.Add(new Память
                    { день = h.day, вид = Вид.НАЗВАЛИ_ВОРОМ, кто = мишень.id });
            }
            соврал(h, рассказчик, слушатель, "человек", мишень.id);
            h.bump("наговоров");
        }
    }

