    /// <summary>
    /// Соврёт ли этот человек вот этому — прямо сейчас.
    ///
    /// Не все и не всегда. Врут жадные и смелые (соврать в лицо надо
    /// решиться), врут тем, кого боятся и кого не любят; и почти не врут,
    /// пока жизнь ещё похожа на обычную — соседу по площадке врать неловко.
    /// </summary>
    public static bool решает_врать(House h, NPC кто, NPC кому, string тема = "своё")
    {
        var b = h.B;
        double s = b["ложь_база"];
        s += кто.t01("жадность") * b["ложь_за_жадность"];
        s += кто.t01("храбрость") * b["ложь_за_храбрость"];
        s -= кто.normalcy * b["ложь_за_нормальность"];
        // страх собеседника: сильному соседу проще сказать «у меня нет», чем
        // «не дам» — и таким, каким сосед КАЖЕТСЯ: прячущий рану пугает
        // как целый
        s += Math.Min(2.0, кто.видимая_сила(кому) / Math.Max(0.3, кто.power()))
             * b["ложь_за_страх"];
        s -= кто.trust.Взять(кому.id, 3.0) * b["ложь_за_доверие"];
        s += кто.hate.Взять(кому.id, 0.0) / 100.0 * b["ложь_за_злость"];
        s += кто.пунктик("ложь");
        if (тема == "место")
            s += b["ложь_про_место"];
        else if (тема == "человек")
            s += b["ложь_про_человека"];
        // соврать или сказать как есть — решает сам говорящий: монета та же,
        // что бросалась здесь раньше, а игроку в его роли этот вопрос
        // и есть половина разговора
        return Решение.монета(h, кто, Вопрос.СОВРАТЬ, "соврать", "сказать правду",
                              Util.Clamp(s, 0.0, b["ложь_потолок"]));
    }

    /// <summary>Записать ложь. Пока её не разоблачили, она работает.</summary>
    public static void соврал(House h, NPC кто, NPC кому, string тема, string? что = null)
    {
        кто.врал.Add(new Ложь { кому = кому.id, тема = тема, что = что, день = h.day });
        кто.bump("вранья");
        h.bump("вранья");
        string предмет = предмет_вранья(h, тема, что) ?? "";
        h.journal.secret($"{кто.@short} {Util.Vb(кто.sex, "соврал")} {кому.form("dat")} ({тема}"
                         + (что is not null ? $": {предмет})" : ")"));
    }

    /// <summary>Он ему это уже сказал. Одну и ту же неправду дважды
    /// не повторяют: наговор — это разговор, а не ежедневная сводка.</summary>
    public static bool уже_говорил(NPC кто, NPC кому, string тема, string? что = null)
    {
        foreach (var з in кто.врал)
            if (string.Equals(з.кому, кому.id, StringComparison.Ordinal)
                && string.Equals(з.тема, тема, StringComparison.Ordinal)
                && (что is null || string.Equals(з.что, что, StringComparison.Ordinal)))
                return true;
        return false;
    }

    // «соврал про еду», «соврал про дрова»: винительный ресурса. Своя табличка,
    // а не заимствованная у действий, — там формы для «занёс воды», это другой
    // падеж
    private static readonly IReadOnlyDictionary<string, string> РЕСУРС_ВИН =
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["еда"] = "еду", ["вода"] = "воду", ["топливо"] = "топливо",
            ["лекарства"] = "лекарства", ["материалы"] = "материалы",
            ["патроны"] = "патроны", ["деньги"] = "деньги",
        };

    /// <summary>Как назвать то, про что соврали, чтобы строка читалась
    /// по-русски.</summary>
    public static string? предмет_вранья(House h, string тема, string? что)
    {
        if (что is null)
            return null;
        if (тема == "человек")
        {
            var кого = h.get(что);
            return кого is not null ? кого.form("acc") : что;
        }
        if (тема == "своё")
            return РЕСУРС_ВИН.TryGetValue(что, out var в) ? в : что;
        return что;
    }

    /// <summary>Собеседник узнал правду. Возвращает true, если ложь
    /// раскрылась.</summary>
    public static bool проверить_ложь(House h, NPC кто, NPC кому, string тема,
                                      string? что = null)
    {
        var b = h.B;
        foreach (var запись in кто.врал)
        {
            if (!string.Equals(запись.кому, кому.id, StringComparison.Ordinal)
                || !string.Equals(запись.тема, тема, StringComparison.Ordinal))
                continue;
            if (что is not null && запись.что is not null
                && !string.Equals(запись.что, что, StringComparison.Ordinal))
                continue;
            if (запись.раскрыто || h.day - запись.день > b["ложь_память_дней"])
                continue;
            if (!h.rng.Chance(b["ложь_шанс_раскрыть"]))
                return false;
            // запись остаётся: разоблачённая ложь всё равно уже сказана,
            // и второй раз то же самое тому же человеку не говорят
            запись.раскрыто = true;
            // ложь бьёт по доверию, поэтому весит как кража
            adjust(кому, кто.id, hate: b["ненависть_за_ложь"],
                   trust: b["доверие_за_ложь"], aware: 15);
            кому.не_верю[кто.id] = кому.не_верю.Взять(кто.id, 0.0) + 1.0;
            кому.memory.Add(new Память
                { день = h.day, вид = Вид.ПОЙМАЛ_НА_ЛЖИ, кто = кто.id });
            h.bump("вранья_раскрыто");
            register_incident(h, "ложь", null);
            string? предмет = предмет_вранья(h, тема, что);
            h.journal.line($"{кому.@short} {Util.Vb(кому.sex, "понял")}, что {кто.@short} "
                           + $"{Util.Vb(кто.sex, "соврал")}"
                           + (предмет is not null ? $" про {предмет}." : "."), 2);
            h.note($"{кто.@short} пойман на вранье ({кому.form("dat")})");
            return true;
        }
        return false;
    }

    /// <summary>
    /// Оболганный сделал что-то доброе — и слушатель понял, кто ему врал.
    /// Единственный способ разоблачить наговор: не доказательство, а поступок.
    /// </summary>
    public static bool проверить_наговор(House h, NPC о_ком, NPC кому)
    {
        foreach (var кто in h.alive())
        {
            if (string.Equals(кто.id, о_ком.id, StringComparison.Ordinal)
                || string.Equals(кто.id, кому.id, StringComparison.Ordinal))
                continue;
            if (проверить_ложь(h, кто, кому, "человек", о_ком.id))
                return true;
        }
        return false;
    }

    /// <summary>
    /// Насколько вообще стоит верить его рассказам. 0..1. Оболгавший однажды
    /// теряет вес своих слухов — и это единственное, что делает ложь
    /// по-настоящему рискованной: не наказание, а то, что тебя перестают
    /// слушать.
    /// </summary>
    public static double вес_слов(NPC слушатель, NPC рассказчик)
    {
        double поймано = слушатель.не_верю.Взять(рассказчик.id, 0.0);
        if (поймано == 0.0)
            return 1.0;
        double вес = слушатель._h is not null ? слушатель._h.B["ложь_вес_слов"] : 0.4;
        return Util.Clamp(1.0 - вес * Math.Min(2.0, поймано), 0.1, 1.0);
    }

    /// <summary>
    /// Отложенное обязательство: кто, кому, что и к какому дню (GDD 14).
    /// Три вида: отдать («верну банку к пятнице»), сделать («поставлю печь»),
    /// не_делать («к твоей квартире не подойду»).
    /// </summary>
    public static Обещание? обещать(House h, NPC кто, NPC кому, string вид,
                                    string? что = null, double? дней = null)
    {
        var b = h.B;
        double срок_дней = дней ?? (вид == "не_делать"
            ? b["обещание_срок_не_делать"] : b["обещание_срок"]);
        // одно обещание одного вида одному человеку за раз
        foreach (var о0 in кто.обещал)
            if (string.Equals(о0.кому, кому.id, StringComparison.Ordinal)
                && string.Equals(о0.вид, вид, StringComparison.Ordinal))
                return null;
        var о = new Обещание
        {
            кому = кому.id, вид = вид, что = что,
            срок = h.day + (int)срок_дней, день = h.day,
        };
        кто.обещал.Add(о);
        кто.bump("обещаний");
        h.bump("обещаний");
        return о;
    }

    /// <summary>Обещание выполнено. Доверие сопоставимо с помощью — за это
    /// его и дают.</summary>
    public static bool сдержал(House h, NPC кто, NPC кому, string вид, string? что = null)
    {
        var b = h.B;
        foreach (var о in кто.обещал)
        {
            if (!string.Equals(о.кому, кому.id, StringComparison.Ordinal)
                || !string.Equals(о.вид, вид, StringComparison.Ordinal))
                continue;
            if (что is not null && о.что is not null
                && !string.Equals(о.что, что, StringComparison.Ordinal))
                continue;
            кто.обещал.Remove(о);
            adjust(кому, кто.id, trust: b["доверие_за_обещание"], hate: -8);
            сблизились(h, кто, кому, b["близость_за_слово"]);
            кому.favors[кто.id] = кому.favors.Взять(кто.id, 0) + 1;
            кто.bump("обещаний_сдержано");
            h.bump("обещаний_сдержано");
            return true;
        }
        return false;
    }

    /// <summary>Слово не сдержано. Помнится долго и мешает договариваться
    /// впредь.</summary>
    public static bool нарушил(House h, NPC кто, NPC кому, string вид,
                               string? что = null, bool вслух = true)
    {
        var b = h.B;
        foreach (var о in кто.обещал.ToList())
        {
            if (!string.Equals(о.кому, кому.id, StringComparison.Ordinal)
                || !string.Equals(о.вид, вид, StringComparison.Ordinal))
                continue;
            if (что is not null && о.что is not null
                && !string.Equals(о.что, что, StringComparison.Ordinal))
                continue;
            кто.обещал.Remove(о);
            // нарушенное слово мерят своей меркой — и тот, кому не сделали,
            // и дом, если это было слышно. Метка «предательство» до сих пор
            // судилась ровно в одном месте и за двадцать жизней не выпала ни разу
            judge(h, кто, "предательство", hate: b["ненависть_за_нарушение"],
                  trust: b["доверие_за_нарушение"], witnesses: new List<NPC> { кому });
            if (вслух)
            {
                double доля = b["слово_дом_слышит"];
                var прочие = h.others(кто)
                    .Where(o => !string.Equals(o.id, кому.id, StringComparison.Ordinal))
                    .ToList();
                judge(h, кто, "предательство", hate: b["ненависть_за_нарушение"] * доля,
                      trust: b["доверие_за_нарушение"] * доля, witnesses: прочие);
            }
            кому.не_верю[кто.id] = кому.не_верю.Взять(кто.id, 0.0) + 1.0;
            кто.bump("обещаний_нарушено");
            h.bump("обещаний_нарушено");
            if (вслух)
                h.journal.line($"{кто.@short} не {Util.Vb(кто.sex, "сделал")} того, что "
                               + $"{Util.Vb(кто.sex, "обещал")} {кому.form("dat")}.", 1);
            return true;
        }
        return false;
    }

    /// <summary>
    /// Каждый вечер: у кого вышел срок. И заодно — забывание. «Не делать»
    /// работает наоборот: если срок вышел и человек ничего не сделал, слово
    /// сдержано.
    /// </summary>
    public static void проверить_обещания(House h)
    {
        var b = h.B;
        foreach (var p in h.alive())
        {
            foreach (var о in p.обещал.ToList())
            {
                if (h.day < о.срок)
                    continue;
                var кому = h.живой(о.кому);
                if (кому is null)
                {
                    p.обещал.Remove(о);
                    continue;
                }
                if (о.вид == "не_делать")
                    сдержал(h, p, кому, "не_делать", о.что);
                else
                    нарушил(h, p, кому, о.вид, о.что);
            }
            // старую ложь уже не разоблачить: сказанное неделю назад забылось
            p.врал.RemoveAll(з => h.day - з.день > b["ложь_память_дней"]);
            // и сама память стареет — если ей велено стареть. При умолчании
            // (`память_дней` больше метели) не забывается ничего, и это правда
            // про тридцать дней: человек помнит всё, что видел за месяц
            if (b["память_дней"] < 999)
                p.memory.RemoveAll(m => h.day - m.день > b["память_дней"]);
            foreach (var k in p.не_верю.Ключи)
            {
                p.не_верю[k] = Math.Max(0.0, p.не_верю[k] - b["не_верю_забывается"]);
                if (p.не_верю[k] <= 0.0)
                    p.не_верю.Убрать(k);
            }
        }
    }
