// Перенос house/conflict.py, строки 1191–2109: осада из стадий.
//
// GDD 16: рейд — не бой, а осада, и на каждой стадии есть выход. Собрать
// людей, дойти до двери, дать хозяину закричать, откупиться, договориться,
// сломать дверь, найти другой путь, сдаться или драться. Каждая стадия —
// чей-то ход, а не бросок кубика, и почти на каждой это ход человека,
// у которого спрашивают.

namespace Дом.Ядро;

public static partial class Конфликт
{
    /// <summary>
    /// Состав группы ровно по GDD 16.
    ///
    /// <paramref name="прикидка"/> = true — вожак только считает, с кем
    /// он мог бы пойти, и никого ещё не зовёт: вопрос соседям не задаётся.
    ///
    /// К вожаку идут по трём разным причинам, и путать их нельзя: свои —
    /// те, кто уже в агрессивном ядре дома; злые лично — те, у кого своя
    /// ненависть к этой двери; нейтралы — те, у кого высоки ОБЕ шкалы,
    /// и паника, и осведомлённость о запасах цели.
    ///
    /// Возвращает (кто пошёл, кого позвали и получили «нет»). Второй список
    /// важен не меньше первого: за сорок жизней вожаки получали по тридцать
    /// отказов за жизнь, и до сих пор после отказа не происходило ничего.
    /// </summary>
    public static (List<NPC> crew, List<NPC> отказали) recruit(
        House h, NPC leader, NPC target, bool прикидка = false)
    {
        var b = h.B;
        double A = aggr(h);
        var crew = new List<NPC> { leader };
        var отказали = new List<NPC>();
        foreach (var p in h.others(leader))
        {
            if (string.Equals(p.id, target.id, StringComparison.Ordinal)
                || p.health < 40 || p.injuries.Count >= 2)
                continue;
            if (p.dependents > 0)
                continue;                 // его руки связаны (GDD 12.6)
            // свою же дверь не ломают: под одной крышей — значит на одной стороне
            if (string.Equals(p.living_with, target.id, StringComparison.Ordinal)
                || string.Equals(target.living_with, p.id, StringComparison.Ordinal))
                continue;
            // с кем живёшь, за тем и идёшь
            bool свой_кров = string.Equals(p.living_with, leader.id, StringComparison.Ordinal)
                             || string.Equals(leader.living_with, p.id, StringComparison.Ordinal);
            double trust = p.trust.Взять(leader.id, 3.0);

            bool ядро = string.Equals(p.group, "агрессивные", StringComparison.Ordinal);
            bool злой = p.hate.Взять(target.id, 0.0) >= b["налёт_порог_ненависти"];
            bool нейтрал = p.panic >= b["налёт_нейтралы_порог"]
                           && p.сведения_о(target.id).aware >= b["налёт_нейтралы_порог"]
                           && trust >= b["налёт_вербовка_доверие"];
            bool причина = ядро || злой || нейтрал
                           || (свой_кров && trust >= b["налёт_вербовка_доверие"]);
            // и те, про кого он просто надеется. Втроём ломают стену,
            // а в одиночку лезут в окно от отчаяния (GDD 16), и разница так
            // велика, что вожак обходит и сомнительных. Именно здесь и берутся
            // отказы: пока «кого звать» и «кто пойдёт» были одним условием,
            // отказов не было вовсе. К союзнику жертвы он при этом не пойдёт:
            // дом маленький, и кто с кем держится, слышали все
            bool надежда = trust >= b["зов_надежда_доверие"]
                           && p.hate.Взять(leader.id, 0.0) < b["зов_надежда_ненависть"]
                           && !p.allies.Contains(target.id);
            if (!(причина || надежда))
                continue;
            // к тому, кто уже отказал, второй раз в ту же дверь не стучатся
            if (h.day - leader.ask_record(p.id).отказ_налёт < b["зов_обида_дней"])
                continue;

            double pull = p.desperation() * 2.0 + p.вес_черт("налёт_вербовка") + trust * 0.25;
            pull += p.hate.Взять(target.id, 0.0) / 30.0;
            pull += ядро ? 1.0 : 0.0;
            pull -= p.allies.Contains(target.id) ? 1.2 : 0.0;
            pull -= 1.5;
            // к страшной двери не идут даже за компанию…
            pull -= p.боится(target.id) * b["страх_вес_вербовки"];
            // …а страшному вожаку труднее отказать
            pull += p.боится(leader.id) * b["страх_вес_вербовки"] * 0.4;
            pull += p.пунктик("налёт_вербовка");
            // и своя мерка того, что ему предлагают (GDD 12.1)
            pull += Характер.своя_мерка(p, "налёт", b);
            // ворота нормальности — те же, что у вожака, и до сих пор их
            // у идущих следом не было вовсе: НОРМА["налёт"] применялась только
            // к тому, кто позвал. Оттого отказов не случалось ни одного
            // за сорок жизней
            double порог = b["налёт_порог_вербовки"] / A
                           + p.normalcy * b["налёт_вербовка_нормальность"];
            // идти или отказать — решает тот, кого зовут. В прикидке вопрос
            // не задаётся: вожак ещё никого не звал, и спрашивать игрока
            // о том, чего не случилось, нельзя
            bool идёт = прикидка
                ? pull > порог
                : Решение.по_правилу(h, p, Вопрос.ПОЙТИ_В_НАЛЁТ, "пойти", "отказать",
                                     pull - порог);
            if (идёт)
                crew.Add(p);
            else
                отказали.Add(p);
        }
        return (crew, отказали);
    }

    /// <summary>
    /// Что остаётся в доме после того, как вожак обошёл соседей.
    ///
    /// До сих пор вербовка была молчаливым фильтром: человеку предлагали
    /// пойти ломать соседскую дверь, он отказывался, и не происходило
    /// ничего — вожак не помнил, отказавшийся не шёл предупредить, жертва
    /// не узнавала, что за ней собирались. Это был самый дешёвый
    /// неиспользованный источник в модели, и даёт он сразу и вражду,
    /// и доверие.
    /// </summary>
    public static NPC? зов(House h, NPC leader, NPC target, IReadOnlyList<NPC> отказали)
    {
        var b = h.B;
        if (отказали.Count > 0)
            h.bump("зовов_отказано", отказали.Count);
        NPC? предупредил = null;
        foreach (var p in отказали)
        {
            // позвали — значит, рассказали: и про то, что за той дверью
            // что-то есть, и про то, что в доме уже собирают людей
            Социальное.adjust(p, target.id, aware: b["зов_осведомлённость"]);
            Социальное.add_panic(p, b["зов_паника"]);
            // и показали, что так теперь можно. Это не увиденный поступок,
            // а предложенный, и весит он меньше — но по той же шкале (GDD 12.4)
            Социальное.видел(h, p, b["нормальность_за_зов"], кто: leader);
            // вожак помнит отказ. Не ненависть — обида: доверие вниз, и звать
            // этого человека он какое-то время больше не станет
            Социальное.adjust(leader, p.id, trust: b["зов_отказ_доверие"]);
            leader.ask_record(p.id).отказ_налёт = h.day;
            p.bump("отказов_идти");
            // и может пойти предупредить. Это единственный источник доверия
            // помимо помощи и лечения, который стоит дороже них обоих
            if (предупредил is not null)
                continue;
            // предупреждают не потому, что любят соседа, а потому, что в доме
            // собирают людей идти ночью к чужой двери, и это ещё не стало
            // обычным делом. Ненависть мешает, но не решает: к третьей неделе
            // в этом доме ненавидят все и всех
            double хочу = p.t01("лояльность") * 4.5
                          + p.normalcy * b["предупредить_нормальность"]
                          + p.trust.Взять(target.id, 3.0) * 0.5
                          - p.hate.Взять(target.id, 0.0) / 40.0
                          // страх держит: сказать вожаку «нет» можно, а пойти
                          // к жертве за его спиной — это уже против него
                          - p.боится(leader.id) * b["страх_вес_предупреждения"]
                          - b["предупредить_решимость"];
            if (p.allies.Contains(target.id))
                хочу += 3.0;
            if (p.dependents > 0)
                хочу -= 1.0;        // ему есть что терять, если узнают
            // пойти ли за спиной вожака к жертве — решает сам отказавшийся
            if (хочу > 0 && Решение.монета(h, p, Вопрос.ПРЕДУПРЕДИТЬ_ЖЕРТВУ,
                    "предупредить", "смолчать", Util.Clamp(хочу / 3.5, 0.05, 0.85)))
                предупредил = p;
        }
        if (предупредил is null)
            return null;

        h.bump("предупреждений");
        h.journal.line($"{предупредил.@short} {Util.Vb(предупредил.sex, "успел")} шепнуть "
            + $"{target.form("dat")}, что за {target.form("ins")} сегодня придут.", 2);
        h.note($"{предупредил.@short} предупредил {target.form("acc")}");
        Социальное.adjust(target, предупредил.id, trust: b["доверие_за_предупреждение"],
                          hate: -15);
        Социальное.adjust(предупредил, target.id, trust: 0.5);
        // правда: исполнение: предупреждение состоялось
        target.panic = Util.Clamp(target.panic + b["паника_от_предупреждения"]);
        // и дом наутро берётся за двери: не потому, что случилось, а потому,
        // что стало известно, чем тут теперь занимаются
        h.календарь.укрепление_порыв = h.day + 1;
        // слух идёт дальше жертвы: вожак теперь тот, кто собирает людей
        foreach (var w in h.others(leader))
        {
            if (string.Equals(w.id, предупредил.id, StringComparison.Ordinal))
                continue;
            if (h.rng.Chance(b["зов_слух"]))
            {
                Социальное.adjust(w, leader.id, aware: 6);
                Социальное.испугался(h, w, leader, b["страх_за_сговор"]);
            }
        }
        return предупредил;
    }

    /// <summary>
    /// «Прочность двери против инструментов группы» (GDD 16). Инструменты —
    /// это не только руки: топор и слесарь в компании решают больше,
    /// чем лишний человек.
    /// </summary>
    public static double инструменты(IReadOnlyList<NPC> crew)
    {
        double Вес(NPC p)
        {
            double w = 0.75 + p.t01("храбрость") * 0.6;
            if (p.weapon == Оружие.ТОПОР || p.skills.Contains("слесарь", StringComparer.Ordinal))
                w += 1.2;
            else if (p.weapon == Оружие.ДУБИНА || p.weapon == Оружие.НОЖ)
                w += 0.55;
            return w;
        }
        return Util.Sum(crew.Select(Вес)) * (1.0 + 0.22 * (crew.Count - 1));
    }

    /// <summary>
    /// Уйдут ли они от целой двери или полезут другим путём (GDD 16).
    ///
    /// Решает не злость, а нужда: человеку, которому нечего есть, некуда идти
    /// от этой двери — дома его ждёт то же самое, только без еды. Он полезет
    /// в окно на четвёртом этаже; сытый в такое окно не полезет.
    /// </summary>
    public static double упорство(House h, IReadOnlyList<NPC> crew, NPC target)
    {
        var b = h.B;
        double нужда = crew.Max(p => p.desperation());
        double злость = crew.Max(p => p.hate.Взять(target.id, 0.0)) / 100.0;
        double v = нужда * b["налёт_упорство_за_нужду"]
                   + злость * b["налёт_упорство_за_злость"];
        v += (crew.Count - 1) * b["налёт_упорство_за_людей"];
        // и то, кого они слышат за дверью: от знакомого ружья уходят
        v -= crew.Max(p => p.боится(target.id)) * b["налёт_упорство_за_страх"];
        return v;
    }
}
