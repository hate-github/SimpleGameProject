// Перенос house/замысел.py, строки 77–403: как замысел берётся, живёт
// и кончается.
//
// Замысел — не приказ и не расписание. Это перевес: он подкрашивает оценки
// в сборе и держится, пока не выполнен, не брошен или не перебит нуждой.
// Кончилась вода — замысел спит, человек идёт топить снег; отпустило —
// вернулся. Если нужда держится дольше срока, замысел брошен совсем,
// и это тоже история: человек, который месяц собирался утеплить окна
// и так и не собрался.

namespace Дом.Ядро;

public static partial class Замыслы
{
    /// <summary>Чего этому человеку хочется добиваться. Порядок вставки —
    /// порядок вариантов у решающего, и при равных он решает.</summary>
    public static Словарь<string, double> оценки(House h, NPC npc)
    {
        var b = h.B;
        // мерка тепла — ночная, а не дневная: печку во сне никто не топит,
        // и «я не хочу больше мёрзнуть» — это про то, каким человек
        // просыпается, а не про то, как тепло у него, пока горит буржуйка
        double ночью = h.room_temp(npc, burning: false);
        double еды = npc.days_of("еда");
        var о = Словари.Числа();

        // тепло: не «мне сейчас холодно», а «я не хочу больше мёрзнуть никогда»
        о["тепло"] = (b["комфортная_температура"] - ночью) * b["замысел_тепло_за_градус"]
                     + npc.пунктик("замысел_тепло")
                     + (npc.dependents > 0 ? 1.5 : 0.0)
                     + npc.вес_черт("утепление");

        // запас: черта запасливого и горизонт, а не сегодняшний голод.
        // Горизонт бывает и в двадцать пять дней, и тогда одна эта строка
        // перевешивает всё остальное вместе взятое: замысел «набить шкаф»
        // брали пятеро из шести и всегда. Потолок — чтобы запасливость
        // оставалась чертой характера, а не единственным, чего можно хотеть
        о["запас"] = Math.Min(b["замысел_запас_потолок"], npc.horizon - еды)
                     * b["замысел_запас_за_день"]
                     + npc.t01("жадность") * 2.0
                     + npc.пунктик("замысел_запас");

        // угол: своя квартира против лучшей из пустых, глазами хозяина
        var своя = h.flats[npc.apt];
        double? лучшая = null;
        foreach (var f in h.пустые_для(npc))
        {
            double v = h.ценность_жилья(f, npc);
            if (лучшая is null || v > лучшая)
                лучшая = v;
        }
        if (лучшая is not null && string.IsNullOrEmpty(npc.living_with))
            // привязанность к своим стенам держит замысел слабее, чем сам
            // переезд: собраться и решиться — разные вещи, и первое дешевле
            о["угол"] = (лучшая.Value - h.ценность_жилья(своя, npc)) * b["замысел_угол_вес"]
                        - своя.вложено * b["жильё_привязанность"]
                          * b["замысел_угол_привязанность"];

        // уйти: только если знает куда, и только когда терять уже нечего
        if (npc.знает_пункт)
            о["уйти"] = npc.desperation() * b["замысел_уйти_за_отчаяние"]
                        - своя.вложено * b["жильё_привязанность"]
                        - npc.dependents * 1.0
                        - b["замысел_уйти_решимость"];

        // рассорить: единственный замысел про людей. Берут его не от злобы
        // вообще, а от злобы на того, с кем самому не справиться, — потому
        // и приходится чужими руками
        var враг = кого_ненавидит(h, npc);
        if (враг is not null)
        {
            double слабее = Util.Clamp(
                npc.видимая_сила(враг) / Math.Max(0.3, npc.power()) - 1.0, 0.0, 2.0);
            о["рассорить"] = (npc.не_прощу.Contains(враг.id) ? b["обида_вес_мести"] : 0.0)
                             + npc.hate.Взять(враг.id, 0.0) * b["замысел_рассорить_за_злость"]
                             + слабее * b["замысел_рассорить_за_бессилие"]
                             + npc.пунктик("замысел_рассорить")
                             - b["замысел_рассорить_решимость"];
        }

        // вместе: единственный замысел, который не про себя. Не «мне нужен
        // он», а «перезимуем». Оттого и берётся он не по нужде, а по тому,
        // сколько между этими двоими уже было
        var друг = с_кем_вместе(h, npc);
        if (друг is not null)
            о["вместе"] = npc.свой(друг.id) * b["замысел_вместе_за_близость"]
                          + npc.t01("лояльность") * 2.0
                          + (npc.trust.Взять(друг.id, 3.0) - 3.0) * 0.4
                          + npc.пунктик("замысел_вместе")
                          - b["замысел_вместе_решимость"];
        return о;
    }

    /// <summary>С кем этот человек стал бы зимовать вдвоём: самый свой,
    /// если он есть.</summary>
    public static NPC? с_кем_вместе(House h, NPC npc)
    {
        var свои = h.others(npc).Where(t => !npc.не_прощу.Contains(t.id)).ToList();
        if (свои.Count == 0)
            return null;
        var лучший = свои[0];
        foreach (var t in свои)
            if (npc.свой(t.id) > npc.свой(лучший.id))
                лучший = t;
        return npc.свой(лучший.id) >= h.B["замысел_вместе_близость"] ? лучший : null;
    }

    /// <summary>
    /// Тот, на кого у него больше всего зла, — и он ещё жив.
    ///
    /// Непрощённый идёт первым, и это не то же самое, что самый ненавистный:
    /// злость оседает каждый день сама собой, а вынесенную квартиру помнят
    /// до конца метели.
    /// </summary>
    public static NPC? кого_ненавидит(House h, NPC npc)
    {
        NPC? худший = null;
        (bool непрощён, double злость) лучшее = (false, 0.0);
        foreach (var t in h.others(npc))
        {
            if (!(npc.hate.Взять(t.id, 0.0) > 0 || npc.не_прощу.Contains(t.id)))
                continue;
            var ключ = (npc.не_прощу.Contains(t.id), npc.hate.Взять(t.id, 0.0));
            if (худший is null
                || ключ.Item1.CompareTo(лучшее.непрощён) > 0
                || (ключ.Item1 == лучшее.непрощён && ключ.Item2 > лучшее.злость))
            {
                худший = t;
                лучшее = ключ;
            }
        }
        return худший;
    }

    /// <summary>Раз в день: не пора ли за что-нибудь взяться.</summary>
    public static void выбрать(House h, NPC npc)
    {
        var b = h.B;
        if (npc.замысел is not null || (npc.dependents > 0 && npc.health < 40))
            return;
        if (h.day < b["замысел_не_раньше"])
            return;
        if (!h.rng.Chance(b["замысел_шанс_в_день"]))
            return;
        var о = оценки(h, npc);
        // за что взяться — вопрос самому человеку: NPC берёт лучшее, как
        // и брал, а игрок выбирает, ради чего живёт эту неделю (GDD 13).
        // Порядок вариантов — порядок `оценки`, и при равных он решает
        var список = о.Ключи.Select(k => (k, о.Взять(k, 0.0))).ToList();
        string? вид = (npc.решающий as Решающий)!.выбор(
            h, npc, Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ, список);
        if (вид is null || о.Взять(вид, 0.0) < b["замысел_порог"])
            return;
        // нужда не мешает ЗАДУМАТЬ — она мешает делать. Но задумать в нужде
        // можно не всё: клеить окна с пустой флягой не собираются, а вот
        // набить шкаф или уйти отсюда — это и есть ответ на нужду
        if (мешает_нужда(h, npc)
            && !string.Equals(вид, "запас", StringComparison.Ordinal)
            && !string.Equals(вид, "уйти", StringComparison.Ordinal))
            return;
        NPC? друг = null;
        if (string.Equals(вид, "вместе", StringComparison.Ordinal))
        {
            // берётся обоими или никем. Это единственное место в модели, где
            // замысел одного человека зависит от того, что думает другой:
            // «перезимуем вдвоём» в одиночку не бывает
            друг = с_кем_вместе(h, npc);
            if (друг is null)
                return;
            var его = оценки(h, друг);
            if (!его.Есть("вместе"))
                return;
            double сколько_ему = его.Взять("вместе", 0.0);
            // и второго об этом спрашивают: уговор берётся обоими, и записывать
            // человека в него молча нельзя — тем более игрока. Правило прежнее:
            // его «вместе» не ниже порога, а если у него уже есть своё дело,
            // «перезимуем» должно перевесить. Порог включительно, отсюда
            // крошечная прибавка к мерке
            double мерка = сколько_ему - b["замысел_порог"] + 1e-9;
            double? прежнее = null;
            // правда: общее знание: перезимуем вдвоём — уговор, о своём деле
            // второй говорит сам
            if (друг.замысел is not null)
            {
                прежнее = его.Взять(друг.замысел.вид, 0.0);   // правда: общее знание: уговор
                мерка = Math.Min(мерка, сколько_ему - прежнее.Value);
            }
            if (!Решение.по_правилу(h, друг, Вопрос.ПЕРЕЗИМОВАТЬ_ВДВОЁМ,
                                    "согласиться", "отказать", мерка))
                return;
            if (прежнее is not null)
                бросить(h, друг, $"теперь важнее {НАЗВАНИЕ["вместе"]}");
        }
        npc.замысел = new Замысел { вид = вид, с_дня = h.day };
        if (string.Equals(вид, "рассорить", StringComparison.Ordinal))
        {
            var враг = кого_ненавидит(h, npc);
            if (враг is null)
            {
                npc.замысел = null;
                return;
            }
            npc.замысел.враг = враг.id;
        }
        if (string.Equals(вид, "вместе", StringComparison.Ordinal))
        {
            npc.замысел.друг = друг!.id;
            друг.замысел = new Замысел { вид = "вместе", с_дня = h.day, друг = npc.id };
            друг.замыслов += 1;
            h.bump("замыслов_принято");
            h.bump("замысел_вместе");
            // не «договорились держаться вместе» — так в журнале называется
            // союз, и две почти одинаковые строки читались бы как одно
            // событие, случившееся дважды
            h.journal.line($"{npc.@short} и {друг.@short} условились: перезимуем "
                           + "вдвоём, как бы ни повернулось.", 2);
        }
        h.bump("замыслов_принято");
        h.bump("замысел_" + вид);
        npc.замыслов += 1;
        // замысел взят и заполнен целиком — теперь его можно показать наблюдателю
        h.hooks.Зов_замысел(h, npc, npc.замысел);
    }

    /// <summary>
    /// Нужда, которая перебивает любой замысел: пить, есть, лечиться.
    /// Перебивает, а не отменяет: человек, у которого кончилась вода, идёт
    /// топить снег, а не клеить окна, — и это не значит, что он раздумал.
    /// </summary>
    public static bool мешает_нужда(House h, NPC npc)
    {
        var b = h.B;
        return npc.desperation() >= b["замысел_нужда"]
               || npc.невмоготу() >= b["замысел_невмоготу"]
               || npc.health < b["замысел_здоровье"];
    }

    /// <summary>Спит ли замысел сегодня.</summary>
    public static bool спит(House h, NPC npc)
        => npc.замысел is not null && npc.замысел.сегодня_спит;

    /// <summary>Раз в день: замысел спит, продолжается, выполнен или брошен.</summary>
    public static void утро(House h, NPC npc)
    {
        var b = h.B;
        var з = npc.замысел;
        if (з is null)
        {
            выбрать(h, npc);
            return;
        }
        // напор оседает сам собой: тихий день гасит подозрения
        з.напор = Math.Max(0.0, з.напор - b["напор_оседает"]);
        з.сегодня_спит = мешает_нужда(h, npc);
        if (з.сегодня_спит)
        {
            з.спал += 1;
            if (з.спал >= b["замысел_терпит_дней"])
                бросить(h, npc, "так и не собрался");
            return;
        }
        з.спал = 0;
        // «перезимуем вдвоём» кончается не выполнением, а тем, что второго
        // больше нет: умер, ушёл, перестал быть своим или сам бросил
        if (string.Equals(з.вид, "вместе", StringComparison.Ordinal))
        {
            var друг = h.живой(з.друг);
            if (друг is null)
            {
                бросить(h, npc, "остался один");
                return;
            }
            if (npc.свой(друг.id) < b["замысел_вместе_держится"])
            {
                бросить(h, npc, "разошлись");
                return;
            }
            if (друг.замысел is null
                || !string.Equals(друг.замысел.друг, npc.id, StringComparison.Ordinal))
            {
                бросить(h, npc, "остался в этом один");
                return;
            }
        }
        if (выполнен(h, npc, з))
        {
            h.bump("замыслов_исполнено");
            h.journal.line($"{npc.@short}: {НАЗВАНИЕ[з.вид]} — сделано.", 0);
            npc.замысел = null;
        }
    }

    /// <summary>Достигнута ли цель. У каждого вида своя мерка.</summary>
    public static bool выполнен(House h, NPC npc, Замысел з)
    {
        var b = h.B;
        string вид = з.вид;
        if (string.Equals(вид, "тепло", StringComparison.Ordinal))
            return h.room_temp(npc, burning: true) >= b["замысел_тепло_цель"];
        if (string.Equals(вид, "запас", StringComparison.Ordinal))
            return npc.days_of("еда") >= npc.horizon
                   && npc.days_of("топливо") >= b["замысел_запас_дров"];
        if (string.Equals(вид, "угол", StringComparison.Ordinal))
        {
            // он либо переехал, либо занял: и то и другое видно по тому, что
            // своя квартира перестала быть худшей
            double? лучшая = null;
            foreach (var f in h.пустые_для(npc))
            {
                double v = h.ценность_жилья(f, npc);
                if (лучшая is null || v > лучшая)
                    лучшая = v;
            }
            return лучшая is null || лучшая <= h.ценность_жилья(h.flats[npc.apt], npc);
        }
        if (string.Equals(вид, "рассорить", StringComparison.Ordinal))
        {
            var враг = h.живой(з.враг);
            if (враг is null)
                return true;          // с врагом разобрались и без него
            // цель — не убить, а поссорить: кто-то из дома должен возненавидеть его.
            // правда: видно: открытая злость слышна на лестнице
            return h.others(npc).Any(
                t => !string.Equals(t.id, враг.id, StringComparison.Ordinal)
                     && t.hate.Взять(враг.id, 0.0) >= b["замысел_ссора_цель"]);
        }
        return false;                 // «уйти» кончается только уходом
    }

    /// <summary>Замысел брошен: почему — в журнал, счётчик — дому.</summary>
    public static void бросить(House h, NPC npc, string почему)
    {
        var з = npc.замысел;
        if (з is null)
            return;
        h.bump("замыслов_брошено");
        h.journal.line($"{npc.@short}: {НАЗВАНИЕ[з.вид]} — {почему}.", 0);
        npc.замысел = null;
    }

    /// <summary>
    /// Не пора ли дому заподозрить, что кто-то тут ведёт свою игру.
    ///
    /// Цена за напор, и она одна на оба способа. Умный чувствует её
    /// и выжидает, глупый — нет: он делает ход каждый день, и его раскусывают
    /// почти всегда. Раскрытым при этом оказывается не оболганный, а сам
    /// заговорщик, со всей ненавистью, которую он копил на других.
    /// </summary>
    public static bool напор_виден(House h, NPC npc)
    {
        var з = npc.замысел;
        if (з is null || !string.Equals(з.вид, "рассорить", StringComparison.Ordinal))
            return false;
        if (!h.rng.Chance(з.напор * h.B["напор_шанс_раскрыть"]))
            return false;
        var враг = h.get(з.враг);
        var свидетели = h.others(npc)
            .Where(t => !string.Equals(t.id, npc.id, StringComparison.Ordinal)).ToList();
        foreach (var t in свидетели)
        {
            Социальное.adjust(t, npc.id, hate: h.B["напор_ненависть"], trust: -2.0,
                              aware: 20);
            Социальное.отдалились(t, npc.id, h.B["близость_за_обиду"]);
            if (враг is not null && string.Equals(t.id, враг.id, StringComparison.Ordinal))
                Социальное.adjust(t, npc.id, hate: h.B["напор_ненависть"]);
        }
        h.bump("заговорщиков_раскрыто");
        Социальное.register_incident(h, "заговор", null);
        h.journal.line("В подъезде сложили одно к одному: всё, что в последние дни "
                       + $"говорили друг про друга, шло через {npc.form("acc")}.", 2);
        h.note($"{npc.@short} раскрыт как заговорщик");
        бросить(h, npc, "раскрыт");
        return true;
    }
}
