// Перенос house/engine.py: сборка и главный цикл — день, ночь, расчёт.
//
// День: у каждого 16 часов, он тратит их на действия (GDD 5).
// Ночь: сон, дежурство, кражи и налёты (GDD 4.3 — «ночью происходит
// основной риск»). Утро: сводка (GDD 4.4) — что заметили соседи, что
// пропало, кто что слышал.
//
// Здесь ровно два десятка вызовов и ни одной формулы: всё, что решает,
// лежит в своих модулях. Порядок вызовов и есть то единственное, чем
// оркестратор владеет, — и он же поведение: `огласить_непрощённых` стоит
// дважды не по недосмотру, а потому, что за день и за ночь копятся разные
// обиды, и человек говорит про них по разу.

using System.Text.Json;

namespace Дом.Ядро;

/// <summary>Одна жизнь дома: от сборки до последнего дня.</summary>
public sealed class Прогон
{
    public long seed { get; }
    public int days { get; }
    public House h { get; }

    private readonly Данные данные;

    /// <summary>
    /// <paramref name="ручки"/> — {ключ: значение} поверх balance.json.
    /// Нужно, чтобы сравнивать две настройки одной ручки, не правя файл:
    /// без этого A/B по параметру технически невозможен.
    ///
    /// <paramref name="hooks"/> — наблюдатели, общие на сколько угодно жизней:
    /// линейка подписывается один раз и гоняет зёрна, дом зовёт её сам.
    /// </summary>
    /// <remarks>
    /// <paramref name="каталог"/> идёт первым и без умолчания нарочно: ядро
    /// не знает, где лежат данные, и знать не должно (`Дом.Годот/ЧИТАЙ.md`).
    /// Путь ему даёт тот, кто его завёл, — консоль или движок.
    /// </remarks>
    public Прогон(string каталог, long seed = 1, int days = 30,
                  IReadOnlyDictionary<string, double>? ручки = null,
                  Хуки? hooks = null, IЖурнал? журнал = null)
    {
        this.seed = seed;
        this.days = days;
        данные = Схема.Прочитать(каталог);
        // ручки ложатся поверх уже проверенных данных, а в прототипе —
        // до проверки. Разница видна только на заведомо негодной ручке:
        // там прототип упадёт на проверке данных, а порт — на первом же
        // чтении. Ни поведения, ни состояния это не трогает; записано,
        // чтобы не искать потом
        if (ручки is not null)
        {
            var нет = ручки.Keys.Where(k => !данные.Баланс.Есть(k))
                                .OrderBy(k => k, StringComparer.Ordinal).ToList();
            if (нет.Count > 0)
                throw new ArgumentException(
                    "нет такой ручки в balance.json: " + string.Join(", ", нет));
            foreach (var (k, v) in ручки)
                данные.Баланс.Число(k, v);
        }
        h = new House
        {
            rng = new Rng(seed),
            B = данные.Баланс,
            hooks = hooks ?? new Хуки(),
        };
        h.реплики_быт = данные.lines.Массив("быт");
        h.journal = журнал ?? new ЗаглушкаЖурнала();
        Сборка.build_house(h, данные.npcs);
    }

    /// <summary>
    /// Прожить все дни. В конце каждого зовёт наблюдателей `on_day`.
    ///
    /// Так проверка снимает отпечаток дома по дням, а линейки — свои мерки,
    /// и никто не подменяет сам день. Наблюдатель ничего не меняет и ничего
    /// не тянет из генератора: с пустым списком прогон тот же
    /// до последнего слова.
    /// </summary>
    public House run()
    {
        Мир.build_calendar(h, данные.events, days);
        for (int д = 0; д < days; д++)
        {
            one_day();
            h.hooks.Зов_day(h);
            if (h.alive().Count == 0)
            {
                h.journal.line("В подъезде не осталось никого.", 2);
                h.journal.flush_day(h);
                break;
            }
        }
        return h;
    }

    /// <summary>Один день целиком: утро, день, чат, ночь, расчёт суток.</summary>
    public void one_day()
    {
        Мир.start_of_day(h, данные.events);
        _morning();
        _day();
        // то, чего человек не простил за сегодняшний день, — одной строкой
        // на всех, а не по строке на каждого
        Обнаружения.огласить_непрощённых(h);
        Чат.daily_chat(h, данные.lines);
        Ночью.ночь(h);
        Обнаружения.огласить_непрощённых(h);
        _upkeep();
        Социальное.проверить_обещания(h);
        Социальное.alliance_check(h);
        Социальное.update_groups(h);
        Социальное.daily_decay(h);
        Социальное.spread_panic(h);
        Отчёт.отдых_за_день(h);
        Отчёт.первые_дни(h);
        h.journal.сводка_дня(h);
        h.journal.flush_day(h);
        h.journal.panel(h);
    }

    // ------------------------------------------------------------ утро
    private void _morning()
    {
        h.новый_день();
        // утро после ночи у чужих: ребёнка забирают. Или не отдают
        Конфликт.вернуть_детей(h);
        foreach (var p in h.alive())
        {
            Психика.горизонт(h, p);
            Психика.дрейф_нормальности(h, p);
            // замысел решает своё до всего остального: спит он сегодня или
            // нет, не пора ли его бросить и не пора ли взяться за новый
            Замыслы.утро(h, p);
            p.новый_день(h.B);
        }
        Сожительство.дрова_к_печке(h);
        Услуги.готовые_заказы(h);
        // вышел ли вчерашний дежурный: перед домом, а не перед соседом
        Площадка.проверить_дежурство(h);
        Обнаружения.вскрытые_кладовые(h);
        Обнаружения.подброшенное(h);
        // не пора ли дому сложить одно к одному про того, кто ведёт свою игру
        foreach (var p in h.alive())
            Замыслы.напор_виден(h, p);
        Обнаружения.пропажи(h);
    }

    // ------------------------------------------------------------ день
    /// <summary>
    /// День идёт по часам: ход делает тот, у кого сейчас раньше.
    ///
    /// Раньше день был раундами — все по разу, потом все ещё по разу, —
    /// и порядок внутри дня не значил ничего: человек, вставший в шесть,
    /// приходил в магазин тогда же, когда встававший в десять. С личными
    /// часами день стал лентой: ранняя пташка успевает первой, поздний
    /// застаёт полки пустыми, и «кто в это время на лестнице» впервые имеет
    /// ответ. Жребий остался — но только для тех, у кого на часах одно
    /// и то же: очередь внутри одного часа не заслуга.
    /// </summary>
    private void _day()
    {
        int guard = 0;
        while (guard < 600)
        {
            guard += 1;
            var готовые = h.alive()
                .Where(p => p.time_left >= 0.3 && p.health > 0 && p.здесь()).ToList();
            if (готовые.Count == 0)
                break;
            var жребий = new Dictionary<string, int>(StringComparer.Ordinal);
            int i = 0;
            foreach (var p in h.rng.Shuffled(готовые))
                жребий[p.id] = i++;
            var кто = готовые[0];
            foreach (var x in готовые)
                if (x.час() < кто.час()
                    || (x.час() == кто.час() && жребий[x.id] < жребий[кто.id]))
                    кто = x;
            if (!Действия.choose_and_do(h, кто))
                // ему сегодня больше нечего делать — день для него кончился
                кто.time_left = 0.0;
        }
        // ночью все дома: «хозяин ушёл» не должно перетекать в ночную кражу
        foreach (var p in h.alive())
            p.away = false;
    }

    // ------------------------------------------------------------ расчёт суток
    private void _upkeep()
    {
        // сколько всего в доме отключено: одно число на настроение и на панику
        int infra = (h.heating ? 0 : 1) + (h.water_on ? 0 : 1)
                    + (h.power_on ? 0 : 1) + (h.network <= 0 ? 1 : 0);
        foreach (var p in h.alive().ToList())
        {
            double room = Физиология.расход_и_тепло(h, p, infra);
            Сожительство.теснота_ночи(h, p);
            Дети.сутки(h, p, room);
            Физиология.износ(h, p, infra);
        }

        // вытяжка обмерзает от сегодняшнего пара: то, что натопили за день,
        // аукнется не этой ночью, а следующими
        Мир.вытяжка_мёрзнет(h);
        Мир.запах_по_стояку(h);
    }
}
