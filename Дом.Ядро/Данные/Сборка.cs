// Перенос house/assembly.py: сборка дома из данных.
//
// Единственное место, где данные становятся состоянием. Отдельно от движка
// дня — тот остаётся оркестрацией.
using System.Text.Json;

namespace Дом.Ядро;

public static class Сборка
{
    /// <summary>Собрать дом из npcs.json: квартиры, кладовые, жильцы
    /// и стартовые отношения.</summary>
    public static void build_house(House h, JsonElement npcs_data)
    {
        foreach (var f in npcs_data.Массив("пустые_квартиры").EnumerateArray())
        {
            var flat = new Flat { apt = f.Целое("кв"), floor = f.Целое("этаж") };
            Влить(flat.shelter, f.Объект("убежище"));
            Влить(flat.stock, f.Объект("запасы"));
            h.flats[flat.apt] = flat;
        }
        var жильцы = npcs_data.Массив("жильцы").EnumerateArray().ToList();
        foreach (var d in жильцы)
        {
            // квартира заводится вместе с жильцом, но принадлежит дому, а не
            // ему: он может её бросить, её могут занять, и всё, что он в неё
            // вложил, останется в стенах
            var flat = new Flat
            {
                apt = d.Целое("кв"),
                floor = d.Целое("этаж"),
                вложено = d.Число("вложено", 3.0),
            };
            Влить(flat.shelter, d.Объект("убежище"));
            h.flats[flat.apt] = flat;
        }
        // погреба и гаражи — то же самое, только за порогом квартиры
        foreach (var k in npcs_data.Массив("кладовые").EnumerateArray())
        {
            var кл = new Кладовая
            {
                id = k.Строка("id"),
                вид = Слова.Кладовая(k.Строка("вид")),
                apt = k.Целое("кв"),
                тулуп = k.Флаг("тулуп"),
            };
            Влить(кл.stock, k.Объект("запасы"));
            foreach (var w in k.Строки("оружие"))
                кл.оружие.Add(Слова.Оружие(w));
            h.кладовые[кл.id] = кл;
        }
        foreach (var d in жильцы)
        {
            var p = new NPC
            {
                id = d.Строка("id"),
                name = d.Строка("имя"),
                @short = d.Строка("коротко"),
                apt = d.Целое("кв"),
                floor = d.Целое("этаж"),
                age = d.Целое("возраст"),
                role = d.Строка("роль"),
                sex = d.Строка("пол", "м"),
                gen = d.Строка("коротко_род"),
                dat = d.Строка("коротко_дат"),
                acc = d.Строка("коротко_вин"),
                ins = d.Строка("коротко_твор"),
                weapon = Слова.Оружие(d.Строка("оружие", "нет")),
                одежда = d.Целое("одежда"),
                счёт = d.Число("счёт", 0.0),
                dependents = d.Целое("иждивенцы"),
                dependent_name = d.Строка("иждивенец_имя"),
                dependent_acc = d.Строка("иждивенец_вин"),
                dependent_gen = d.Строка("иждивенец_род"),
                dependent_ins = d.Строка("иждивенец_твор"),
                подъём = d.Число("подъём", 8.0),
                нормальность_пол = d.Число("нормальность_пол", 0.1),
                нормальность_скорость = d.Число("нормальность_скорость", 1.0),
            };
            p.skills.AddRange(d.Строки("умения"));
            p.пунктики.AddRange(d.Строки("пунктики"));
            var ценности = d.Объект("ценности");
            p.values.описание = ценности.Строка("описание");
            p.values.ценит.AddRange(ценности.Строки("ценит"));
            p.values.не_терпит.AddRange(ценности.Строки("не_терпит"));
            Влить(p.traits, d.Объект("черты"));
            Влить(p.stock, d.Объект("запасы"));
            foreach (var (отрезок, занятие) in d.Строкой("привычки"))
                p.привычки[отрезок] = занятие;

            p._h = h;
            // кто за него решает (GDD 13): по умолчанию мягкий выбор NPC;
            // «скрипт» и «человек» — для сценариев и игрока, правила у всех
            // одни
            p.решающий = Решающие.Создать(d.Строка("решает", Решающие.СОФТМАКС));
            // ключ от своего погреба или гаража. Дальше он ходит только
            // вместе с имуществом: через смерть, отъём, осаду и занятую
            // квартиру
            foreach (var k in h.кладовые.Значения)
                if (k.apt == p.apt)
                    p.ключи_кладовых.Add(k.id);
            for (int i = 0; i < p.dependents; i++)
                // падежи ребёнок носит с собой все четыре: он переходит
                // из рук в руки, и на новом месте «ушла с Ваней» должно
                // читаться так же, как читалось у матери
                p.дети.Add(new Ребёнок
                {
                    имя = Или(p.dependent_name, "ребёнок"),
                    вин = Или(p.dependent_acc, p.dependent_name, "ребёнка"),
                    род = Или(p.dependent_gen, p.dependent_name, "ребёнка"),
                    твор = Или(p.dependent_ins, p.dependent_name, "ребёнком"),
                });
            h.people[p.id] = p;
        }

        // стартовые отношения
        // чужой шкаф каждый оценивает по себе, но у подъезда есть и то, что
        // он видел своими глазами задолго до метели: кто всю осень таскал
        // в подвал мешки, а кто въехал в пустую квартиру с рюкзаком. Это
        // не догадка и не слух, а знание, с которым дом входит в первый день
        var известен = Словари.Строкой<JsonElement>();
        foreach (var d in жильцы)
            известен[d.Строка("id")] = d.Объект("известен_дому");

        foreach (var d in жильцы)
        {
            var p = h.people[d.Строка("id")];
            // оружие, с которым человек вошёл в метель, ему привычно: оно
            // у него годами. Охотнику привычно любое огнестрельное — это его
            // ремесло, а не эта конкретная винтовка
            if (p.weapon != Оружие.НЕТ)
                p.рука[p.weapon.Текст()] = 1.0;
            if (p.skills.Contains("охотник", StringComparer.Ordinal))
                foreach (var w in Таблицы.ОГНЕСТРЕЛ.Select(о => о.Текст())
                                                   .OrderBy(x => x, StringComparer.Ordinal))
                    p.рука[w] = Math.Max(p.рука.Взять(w, 0.0), h.B["рука_охотника"]);

            foreach (var other in h.people.Значения)
            {
                if (string.Equals(other.id, p.id, StringComparison.Ordinal))
                    continue;
                p.trust[other.id] = 3.0;
                p.hate[other.id] = 0.0;
                p.страх[other.id] = 0.0;
                var слава = известен.Взять(other.id, default);
                var св = new Сведения();
                // порядок ключей — как у `{…} | {…}` в Python: сперва общая
                // догадка, потом то, что подъезд знал заранее
                св.est["еда"] = 3.0;
                св.est["топливо"] = 3.0;
                св.est["лекарства"] = 0.5;
                св.est["материалы"] = 1.0;
                foreach (var (res, v) in слава.Числа("запас"))
                    св.est[res] = v;
                св.aware = слава.Число("осведомлённость",
                                       15.0 + (other.floor == p.floor ? 10.0 : 0.0));
                p.сведения[other.id] = св;
            }

            foreach (var (k, v) in d.Числа("доверие_старт"))
            {
                p.trust[k] = v;
                // до метели эти двое уже были знакомы, и близость начинается
                // не с нуля. Оксана с Лидой (8 и 7) входят в метель парой,
                // Игорь с Петром (1 и 2) — никем друг другу; дальше это или
                // выдержит, или нет, но начальная несимметрия у дома есть
                p.близость[k] = v * h.B["близость_старт_от_доверия"];
            }
            foreach (var (k, v) in d.Числа("ненависть_старт"))
                p.hate[k] = v;
            foreach (var (k, v) in d.Числа("осведомлённость_старт"))
                p.сведения[k].aware = v;
        }
    }

    private static void Влить(Словарь<string, double> куда, JsonElement откуда)
    {
        foreach (var п in откуда.EnumerateObject())
            куда[п.Name] = п.Value.ValueKind switch
            {
                JsonValueKind.Number => п.Value.GetDouble(),
                JsonValueKind.True => 1.0,
                JsonValueKind.False => 0.0,
                _ => 0.0,
            };
    }

    private static string Или(params string[] варианты)
    {
        foreach (var в in варианты)
            if (!string.IsNullOrEmpty(в))
                return в;
        return "";
    }
}
