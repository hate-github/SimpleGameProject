    static Каталог()
    {
        // Справочник не в порядке — падать при первом обращении, а не молчать
        // сорок прогонов: запись без поля или с опечаткой иначе тихо ничего
        // не делает.
        var плохо = Проверить();
        if (плохо.Count > 0)
            throw new InvalidOperationException(
                "Справочник действий не в порядке:\n  · " + string.Join("\n  · ", плохо));
    }

    /// <summary>
    /// То же, что <c>catalog._проверить</c>. Часть проверок прототипа здесь
    /// не нужна: «шум — пара (int, str|None)», «теги — кортеж строк», «суд —
    /// пара» и «постройка — четвёрка» держат типы, а не проверка.
    /// </summary>
    public static List<string> Проверить()
    {
        var плохо = new List<string>();
        var ключи = ДЕЙСТВИЯ.Select(з => з.key).Concat(ПОСТУПКИ.Select(п => п.key)).ToList();
        foreach (var k in ключи.Where(k => ключи.Count(x => string.Equals(x, k, StringComparison.Ordinal)) > 1)
                               .Distinct(StringComparer.Ordinal)
                               .OrderBy(x => x, StringComparer.Ordinal))
            плохо.Add($"ключ «{k}» описан дважды");
        foreach (var д in ДЕЙСТВИЯ)
        {
            string где = $"действие «{д.key}»";
            if (д.шум is null)
                плохо.Add($"{где}: нет шума — нужна пара (громкость, вид)");
            else if (д.шум.громкость > 0 && д.шум.вид is null)
                плохо.Add($"{где}: громкость {д.шум.громкость} без вида шума");
            if (!(0.0 <= д.норма && д.норма <= 2.0))
                плохо.Add($"{где}: норма {д.норма} вне 0..2");
            if (д.заметность is not (0 or 1 or 2))
                плохо.Add($"{где}: заметность {д.заметность}, а бывает 0, 1 или 2");
            if (д.суд is not null && д.теги.Length == 0)
                плохо.Add($"{где}: суд есть, а меток, по которым судить, нет");
            if (д.постройка is not null && д.стройка is null)
                плохо.Add($"{где}: постройка без стройки — провал не описан");
        }
        foreach (var п in ПОСТУПКИ)
            if (п.норма == 0.0 && п.теги.Length == 0)
                плохо.Add($"поступок «{п.key}»: ни нормы, ни меток");
        return плохо;
    }

    // --- сборка таблиц: порядок записей сохраняется, как у dict в Python ---

    private static Словарь<string, T> Собрать<T>(Func<Действие, T> что,
                                                 Func<Действие, bool>? когда = null)
    {
        var т = Словари.Строкой<T>();
        foreach (var д in ДЕЙСТВИЯ)
            if (когда is null || когда(д))
                т[д.key] = что(д);
        return т;
    }

    private static Словарь<string, T> СобратьВсе<T>(Func<(string key, double норма, string[] теги), T> что,
                                                    Func<T, bool> когда)
    {
        var т = Словари.Строкой<T>();
        foreach (var з in ДЕЙСТВИЯ.Select(д => (д.key, д.норма, д.теги))
                                  .Concat(ПОСТУПКИ.Select(п => (п.key, п.норма, п.теги))))
        {
            var v = что(з);
            if (когда(v))
                т[з.key] = v;
        }
        return т;
    }

    private static HashSet<string> Ключи(Func<Действие, bool> когда)
    {
        var s = new HashSet<string>(StringComparer.Ordinal);
        foreach (var д in ДЕЙСТВИЯ)
            if (когда(д))
                s.Add(д.key);
        return s;
    }

    private static HashSet<string> СобратьЦенности()
    {
        var s = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (_, теги) in ТЕГИ)
            foreach (var t in теги)
                s.Add(t);
        s.UnionWith(new[] { "высокомерие", "предательство", "ребёнок" });
        return s;
    }

