// Перенос house/catalog.py: справочник действий.
//
// Одна запись на действие вместо двенадцати таблиц по ключу. Таблицы лежат
// отдельно от `actions`, потому что их читают знание, характер, проверка
// данных и линейки, — а пока они жили в `actions`, каждый такой читатель
// тянул за собой весь модуль выбора и исполнения по кругу (аудит §7).
// Здесь — только данные, без единой ссылки на другие части ядра.
//
// Часы и дневные лимиты остаются в balance.json (`часы_действий`,
// `лимит_в_день`, `лимит_на_пару_в_день`): их крутит дизайнер, а проверка
// данных сверяет их ключи с этим списком.

namespace Дом.Ядро;

/// <summary>Что слышно за стеной (GDD 13): громкость и вид шума.</summary>
public sealed record Шум(int громкость, string? вид);

/// <summary>
/// GDD 15: у третьего и четвёртого уровня есть требования к умениям.
/// «Смекалки» в прототипе нет — её заменяют умения жильцов.
/// </summary>
public sealed record Постройка(int уровень, string материалы, string[] умения, int потолок);

/// <summary>
/// Что дом думает о поступке, который просто увидел или услышал: имена ручек
/// баланса на каждого свидетеля. <c>null</c> — ноль, как <c>0.0</c>
/// в прототипе.
/// </summary>
public sealed record Суд(string? ненависть, string? доверие);

/// <summary>Всё, что дом знает о действии дня, кроме того, как его делать.</summary>
public sealed record Действие(string key)
{
    /// <summary>Что слышно за стеной. Часы лежат в balance.json: держать их
    /// в двух местах — верный способ поменять одно и забыть другое.</summary>
    public Шум? шум { get; init; }

    /// <summary>Насколько поступок «не принят», пока жизнь ещё похожа
    /// на обычную. 0 — делают и в мирное время, 1 — только когда всё рухнуло.</summary>
    public double норма { get; init; }

    /// <summary>
    /// Метки поступка (GDD 12.1, «Ценности»). По ним дом судит других — и по
    /// ним же человек судит себя. Меток может быть несколько, и это не
    /// украшение: отъём на лестнице для Кости — насилие, а для Игоря, который
    /// ценит силу, — то, как и надо жить.
    /// </summary>
    public string[] теги { get; init; } = Array.Empty<string>();

    /// <summary>Что показывать в обычном режиме (1), а что только подробно (0);
    /// 2 — событие того же веса, что и смерть.</summary>
    public int заметность { get; init; }

    /// <summary>Суд свидетелей за быт, которого раньше не судил никто.
    /// Крупные поступки судятся отдельно и своими числами.</summary>
    public Суд? суд { get; init; }

    /// <summary>У стройки есть чем провалиться: тратится материал, страдает
    /// рука (GDD 7). Значение — за что «взялся» в строке о провале.</summary>
    public string? стройка { get; init; }

    public Постройка? постройка { get; init; }

    /// <summary>Двери, за которыми стоит сосед: всё, ради чего человек выходит
    /// на площадку к другому человеку. Предел у них общий — это не «сколько
    /// раз можно поговорить», а «сколько раз в день ты выходишь к людям».</summary>
    public bool визит { get; init; }

    /// <summary>Работа, а не быт: только на неё влияет состояние тела.</summary>
    public bool работа { get; init; }

    /// <summary>Обычная жизнь на виду: то, чем человек с крепким полом
    /// нормальности держит дом (GDD 12.4).</summary>
    public bool обычное { get; init; }

    /// <summary>Действия, ради которых человек выходит из своей квартиры
    /// и проходит площадку.</summary>
    public bool выход { get; init; }
}

/// <summary>
/// Поступок без действия дня: то, чем меряют ночь, осаду и место вылазки.
/// У него есть норма и метки, но нет исполнителя.
/// </summary>
public sealed record Поступок(string key)
{
    public double норма { get; init; }
    public string[] теги { get; init; } = Array.Empty<string>();
}

