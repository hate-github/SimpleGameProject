    /// <summary>Насколько человека тянет на улицу: по нужде и по страху
    /// не хватить.</summary>
    public static double drive_наружу(NPC npc)
        => Math.Max(npc.desperation(), npc.insecurity() * 0.85);

    /// <summary>
    /// Насколько срочно человеку нужна помощь соседей: 0..1. Кража и налёт
    /// отвечают на «я умираю», а просьба, переезд и лечение — на «мне сейчас
    /// плохо». Физическая часть весит чуть меньше: с одним ушибом к чужой
    /// двери не идут, а промёрзнув — идут.
    /// </summary>
    public static double нужда(NPC npc)
        => Math.Max(npc.desperation(), npc.невмоготу() * 0.8);

    /// <summary>
    /// 0..1 — насколько улица, по мнению этого человека, ещё кормит. Главная
    /// альтернатива краже: пока он верит, что в магазине что-то осталось,
    /// к соседней двери он не пойдёт.
    ///
    /// <paramref name="завтра"/> — для ночного решения. Ночью человек выбирает
    /// между «пойти к соседу» и «выйти утром», и продрогшее за день тело
    /// к утру отходит. Пока разницы не было, вернувшийся с пятнадцатичасовой
    /// ходки шёл к соседской двери в ночь после самой богатой добычи.
    /// </summary>
    public static double есть_куда_сходить(House h, NPC npc, bool завтра = false)
    {
        // свой погреб — тот же ответ на тот же вопрос, и ответ лучший: до него
        // идти час, он свой, и он не закрывается ни морозом, ни бураном
        bool свой = h.мои_кладовые(npc).Any(
            к => !к.пусто() && Улица.сколько_поднимет(h, npc, к, h.B) > 0);

        bool тело = npc.health <= 45 || npc.injuries.Count >= 2 || npc.sick is not null;
        if (!завтра)
            тело = тело || npc.warmth <= 32;
        if (h.outside <= npc.мороз_предел(h.B) || тело)
            return Util.Clamp((свой ? 1.0 : 0.0) * h.B["кража_вес_улицы"], 0.0, 1.0);
        // то же, чем он выбирает место: сколько там, по его мнению, осталось.
        // И только те места, куда он в самом деле может дойти: пока это
        // считалось по всем четырём, женщину с ребёнком от кражи удерживал
        // магазин, в который она не может войти ни в один день метели
        double лучшее = 0.0;
        foreach (var м in Улица.МЕСТА)
            if (Улица.место_доступно(h, npc, м))
                лучшее = Math.Max(лучшее, npc.знаю_место(м.имя) * Math.Min(1.0, м.богатство));
        return Util.Clamp(Math.Max(лучшее, свой ? 1.0 : 0.0) * h.B["кража_вес_улицы"], 0.0, 1.0);
    }

    /// <summary>
    /// Кому аптечка нужна по-настоящему: жар, две раны или больной ребёнок.
    /// Строже, чем <see cref="нужен_врач"/>: с ушибом к соседу за аптечкой
    /// не идут и аптечку с ушибом не носят.
    /// </summary>
    public static bool нужна_аптечка(NPC npc)
    {
        var ребёнок = npc.слабейший_ребёнок();
        return npc.sick is not null || npc.injuries.Count >= 2
               || (ребёнок is not null && ребёнок.болен is not null);
    }

    /// <summary>
    /// Чего у человека меньше всего в днях — то и пойдёт просить. Переехавший
    /// к соседу дрова не просит: печку топит хозяин. Аптечка идёт первой,
    /// но только у того, кому она сейчас нужна и у кого её нет.
    /// </summary>
    public static string most_needed(NPC npc, bool без_аптечки = false)
    {
        if (!без_аптечки && нужна_аптечка(npc) && npc.stock.Взять("лекарства", 0.0) < 1.0)
            return "лекарства";
        var ресурсы = npc.топит_сам()
            ? new[] { "еда", "вода", "топливо" }
            : new[] { "еда", "вода" };
        string лучший = ресурсы[0];
        foreach (var r in ресурсы)
            if (npc.days_of(r) < npc.days_of(лучший))
                лучший = r;
        return лучший;
    }

    /// <summary>
    /// Что просить вот у этого соседа. Аптечка идёт первой, но только у того,
    /// у кого она, по-моему, есть. У соседа, чья сумка по моим сведениям
    /// пуста, просят не аптечку, а то, чего не хватает следом.
    /// </summary>
    public static string что_просить(House h, NPC npc, NPC t)
    {
        string res = most_needed(npc);
        if (res == "лекарства" && npc.believed(t.id, res) <= h.B["просьба_верит"])
            res = most_needed(npc, без_аптечки: true);
        return res;
    }

    /// <summary>
    /// Насколько человеку скоро станет холодно (GDD 15, 21). Смотрят
    /// не только на сегодня: метель с каждым днём злее, и это все знают.
    /// </summary>
    public static double холод_впереди(House h, NPC npc, Баланс b)
    {
        double room = h.room_temp(npc, burning: true);
        double room_soon = room - b["температура_падение_в_день"] * 3;
        return Util.Clamp((b["комфортная_температура"] + 4 - room_soon) / 14.0, 0.0, 1.6);
    }

    /// <summary>Насколько человеку страшно вообще: своя паника плюс то,
    /// что в доме.</summary>
    public static double тревога(House h, NPC npc)
        => npc.panic / 100.0 + Социальное.recent_incidents(h) * 0.25;

    /// <summary>
    /// Как человек себя чувствует сейчас: один расчёт на ход. Считается
    /// в начале сбора вариантов и отдаётся всем шести разделам одной записью.
    /// Ничего не меняет и ничего не бросает из `rng`.
    /// </summary>
    public static Самочувствие самочувствие(House h, NPC npc)
    {
        var b = h.B;
        var соседи = h.others(npc);
        double свой_сумма = Util.Sum(соседи.Select(o => npc.свой(o.id)));
        return new Самочувствие
        {
            голод = 1.0 - Util.Norm(npc.satiety, 15, 75),
            жажда = 1.0 - Util.Norm(npc.hydration, 15, 75),
            холод = 1.0 - Util.Norm(npc.warmth, 20, 70),
            усталость = 1.0 - Util.Norm(npc.rest, 20, 80),
            отчаяние = npc.desperation(),
            невмоготу = npc.невмоготу(),
            зову = нужда(npc),
            комната = h.room_temp(npc, burning: true),
            холод_впереди = холод_впереди(h, npc, b),
            тревога = тревога(h, npc),
            еды_дней = npc.days_of("еда"),
            // с кем он вообще близок: предпочтение — это разница с этим
            // средним, а не сама близость
            средний_свой = соседи.Count > 0 ? свой_сумма / соседи.Count : 0.0,
            критичный_порог = b["критичный_порог"],
            нужда_за_критичное = b["нужда_за_критичное"],
        };
    }

    /// <summary>
    /// 0..1 — та часть беды, у которой есть ответ руками, здесь и сейчас.
    ///
    /// Быт отступает перед бедой любой, и это верно: банки в шкафу
    /// переставляют, пока всё более или менее. Отдых устроен иначе — он
    /// отступает только перед той бедой, которую можно поправить. Перед
    /// непоправимой он не отступает: мать, у которой горит ребёнок,
    /// а лекарств нет ни у неё, ни у соседей, никуда не побежит, потому что
    /// бежать некуда.
    /// </summary>
    public static double поправимая_беда(House h, NPC npc, Баланс b)
    {
        var ребёнок = npc.слабейший_ребёнок();
        var очаг = h.хозяин_жилья(npc);
        // к тому, кого всерьёз боятся, не идут ни просить, ни занимать
        var соседи = h.others(npc).Where(o => npc.боится(o.id) < 0.5).ToList();

        // Есть ли у кого просить: сосед, у которого этого, по-моему, заметно
        // больше. По оценке его запасов, а не по правде его шкафа
        double Просить(string res, double дней = 2.0)
        {
            double мои = npc.days_of(res);
            foreach (var o in соседи)
                if (npc.believed_days(o, res) > Math.Max(дней, мои + 1.0))
                    return 0.55;
            return 0.0;
        }

        // --- холод: печка, костёр, мебель в топку, чужие дрова
        double холод = 1.0 - Util.Norm(npc.warmth, 12, 55);
        if (ребёнок is not null)
            холод = Math.Max(холод, 1.0 - Util.Norm(ребёнок.тепло, 15, 55));
        bool печка = очаг.shelter.Взять("буржуйка", 0.0) != 0.0
                     || (h.powered(npc) && npc.shelter.Взять("обогреватель", 0.0) != 0.0);
        double греет;
        if (очаг.burning)
            // печка уже топится — руки своё сделали, и лечь у горячей стены
            // это и есть правильный следующий ход, а не отлынивание
            греет = 0.0;
        else if (печка)
        {
            if (очаг.stock.Взять("топливо", 0.0) >= 1            // правда: под одной крышей: дрова у печки общие
                || очаг.stock.Взять("материалы", 0.0) >= b["мебель_за_топку"])  // правда: под одной крышей
                греет = 1.0;                  // есть чем топить прямо сейчас
            else
                греет = Math.Max(h.мои_кладовые(npc).Count > 0 ? 0.6 : 0.0,
                                 Просить("топливо"));
        }
        else
            // без печки остаётся костёр посреди комнаты и чужое тепло
            греет = Math.Max(
                npc.stock.Взять("материалы", 0.0) >= b["мебель_за_топку"] ? 0.5 : 0.0,
                соседи.Count > 0 ? 0.4 : 0.0);

        // --- голод и жажда: свой шкаф, погреб, улица, соседи
        double детский_голод = npc.дети.Count > 0 ? npc.дети.Min(р => р.сытость) : 100.0;
        double голод, кормит;
        if (npc.satiety >= 88 && детский_голод >= 75)
        {
            голод = 0.0;
            кормит = 0.0;                     // только что ели, и есть не станут
        }
        else
        {
            голод = 1.0 - Util.Norm(npc.satiety, 15, 60);
            голод = Math.Max(голод, Math.Max(1.0 - Util.Norm(детский_голод, 15, 60),
                1.0 - Util.Norm(Math.Min(npc.days_of("еда"), 10), 0, 6)));
            кормит = npc.stock.Взять("еда", 0.0) > 0 || npc.stock.Взять("мясо", 0.0) > 0
                ? 1.0 : 0.0;
            кормит = Math.Max(кормит, Math.Max(есть_куда_сходить(h, npc, завтра: true),
                                               Просить("еда")));
        }

        double жажда, поит;
        if (npc.hydration >= 88)
        {
            жажда = 0.0;
            поит = 0.0;
        }
        else
        {
            жажда = Math.Max(1.0 - Util.Norm(npc.hydration, 15, 60),
                             1.0 - Util.Norm(Math.Min(npc.days_of("вода"), 10), 0, 4));
            поит = h.water_on || npc.stock.Взять("вода", 0.0) > 0 ? 1.0 : 0.0;
            if (поит == 0.0)
                поит = Math.Max(
                    печка && очаг.stock.Взять("топливо", 0.0) >= b["снег_топливо"]  // правда: под одной крышей
                        ? 0.9 : 0.0,
                    Просить("вода", 1.5));
        }

        // --- хворь и раны: своя аптечка или сосед-медик. С ушибом не лечатся
        double хворь = 0.0, лечит = 0.0;
        bool болен_ребёнок = ребёнок is not null
                             && (ребёнок.болен is not null || ребёнок.здоровье < 60);
        if (нужен_врач(npc) || болен_ребёнок)
        {
            if (npc.injuries.Count > 0)
                хворь = Math.Min(1.0, 0.35 + 0.2 * (npc.injuries.Count - 1));
            if (npc.sick is not null)
                хворь = Math.Max(хворь, 0.45);
            if (болен_ребёнок)
                хворь = Math.Max(хворь, Math.Max(1.0 - Util.Norm(ребёнок!.здоровье, 20, 75),
                                                 ребёнок.болен is not null ? 0.5 : 0.0));
            лечит = npc.stock.Взять("лекарства", 0.0) >= 1 ? 1.0 : 0.0;
            if (лечит == 0.0)
            {
                // аптечка соседа — по оценке, а не по правде его шкафа;
                // и придёт ли медик — по тому, как он, по-моему, ко мне
                // относится, а не по его доверию: чужих мыслей не видно
                bool медик = соседи.Any(o => o.skills.Contains("медик", StringComparer.Ordinal)
                    && npc.believed(o.id, "лекарства") >= 1
                    && npc.расположение_ко_мне(o.id) >= b["лечение_доверие"]);
                bool у_кого_то = нужна_аптечка(npc)
                    && соседи.Any(o => npc.believed(o.id, "лекарства") >= 1);
                лечит = Math.Max(медик ? 0.7 : 0.0, у_кого_то ? 0.5 : 0.0);
            }
        }

        return Util.Clamp(Math.Max(холод * греет,
                          Math.Max(голод * кормит,
                          Math.Max(жажда * поит, хворь * лечит))), 0.0, 1.0);
    }

    /// <summary>
    /// Чем именно помочь соседу. Возвращает (ресурс, излишек) или (null, 0).
    ///
    /// Смотрит на то, чего соседу, по его мнению, не хватает, и на то, чего
    /// у самого больше. Излишек меряется против соседа, а не против
    /// собственного горизонта: против горизонта он к третьей неделе требовал
    /// тридцати двух дней запаса и не выполнялся никогда.
    /// </summary>
    public static (string? res, double излишек) чем_поделиться(House h, NPC npc, NPC t,
                                                                Баланс b)
    {
        // перед кем он виноват — то есть у кого к нему неулаженный счёт.
        // Непрощаемое сюда не входит: разграбленную квартиру банкой не закрыть
        double вина = !t.не_прощу.Contains(npc.id) ? t.обида(npc.id) : 0.0;  // правда: событие было со мной: я стоял у его двери
        string? лучший = null;
        double лучший_излишек = 0.0, вес = 0.0;
        foreach (var res in new[] { "еда", "топливо", "вода", "лекарства" })
        {
            if (npc.stock.Взять(res, 0.0) < 1.0)
                continue;
            double излишек;
            double s;
            if (вина > 0.0 && res != "лекарства")
            {
                // виноватому не нужен ни излишек, ни чужая нужда: он идёт
                // не помогать, а мириться, и несёт то, что есть. Единственный
                // тормоз — не отдать последнее
                if (res == "топливо" && !(t.топит_сам()
                        && h.where(t).shelter.Взять("буржуйка", 0.0) != 0.0))
                    continue;
                if (npc.days_of(res) < b["вина_оставляет_дней"])
                    continue;
                излишек = 1.0;
                s = b.Таблица("помощь_вес")[res] * b["вина_вес_поступка"];
            }
            else if (res == "лекарства")
            {
                // аптечку несут тому, кто болен и у кого своей нет. Есть ли
                // у него своя и болен ли он — по тому, что видел и знает,
                // а не по его шкафу и лёгким
                bool болен = npc.видит_хворь(t.id)
                             || t.дети.Any(р => р.болен is not null);   // правда: общее знание: больного ребёнка слышно всему подъезду
                if (npc.believed(t.id, "лекарства") >= 1.0 || !болен)
                    continue;
                if (npc.stock.Взять("лекарства", 0.0) < b["помощь_лекарства_запас"])
                    continue;
                излишек = 2.0;
                s = b.Таблица("помощь_вес")["лекарства"];
            }
            else
            {
                // дрова тому, кому их нечем жечь, — не помощь, а мёртвый груз
                if (res == "топливо" && !(t.топит_сам()
                        && h.where(t).shelter.Взять("буржуйка", 0.0) != 0.0))
                    continue;
                double его = Социальное.believed_days(npc, t, res);
                double мои = npc.days_of(res);
                if (его >= b["помощь_порог_дней"] || мои <= его + 1.0
                    || мои <= b["помощь_минимум_дней"])
                    continue;
                излишек = мои / Math.Max(1.0, его + 1.0);
                // порог тем выше, чем дешевле помощь: кружку воды натопить
                // можно, а банка одна. Без этого 61 % всей помощи в доме
                // уходило водой — не потому, что она нужнее, а потому,
                // что её проще иметь в избытке
                if (излишек <= b["порог_излишка"] / b.Таблица("помощь_вес")[res])
                    continue;
                s = излишек * (1.0 - Math.Min(1.0, его / Math.Max(0.5, b["помощь_порог_дней"])))
                    * b.Таблица("помощь_вес")[res];
            }
            if (s > вес)
            {
                лучший = res;
                лучший_излишек = излишек;
                вес = s;
            }
        }
        return (лучший, лучший_излишек);
    }

    /// <summary>
    /// Возьмёт ли сосед чужого ребёнка к себе на ночь. Решает он. Попросить
    /// взять ребёнка до утра — единственный ход, который у матери на самом
    /// деле есть, когда в комнате плюс десять, лекарств нет и еды нет тоже.
    /// </summary>
    public static double возьмёт_ребёнка(House h, NPC мать, NPC хозяин, Ребёнок р, Баланс b)
    {
        if (!хозяин.здесь() || string.Equals(хозяин.id, мать.id, StringComparison.Ordinal))
            return 0.0;
        if (хозяин.дети.Count > 0 && хозяин.дети.Count >= b["ночёвка_детей_предел"])
            return 0.0;
        double да = хозяин.t01("лояльность") * b["ночёвка_за_лояльность"]
                    + хозяин.свой(мать.id) * b["ночёвка_за_близость"]
                    + (хозяин.trust.Взять(мать.id, 3.0) - 3.0) * 0.3;
        // то, ради чего его и просят: у него теплее и есть чем кормить
        да += Util.Clamp(Math.Min(1.0, хозяин.secure("еда")) - 0.5, -0.5, 0.5) * 2.0;
        да += (1.0 - хозяин.desperation()) * b["ночёвка_за_достаток"];
        да -= хозяин.t01("жадность") * b["ночёвка_за_жадность"];
        да -= хозяин.hate.Взять(мать.id, 0.0) / 25.0;
        да += хозяин.skills.Contains("медик", StringComparer.Ordinal) ? 2.0 : 0.0;
        // ребёнок болен — и это в обе стороны: одного это зовёт, другого гонит
        if (р.болен is not null)
            да += b["ночёвка_за_болезнь"] * (хозяин.t01("лояльность") - 0.4);
        var (запрет, склонность) = Характер.мерка_поступка(хозяин, "отдать_на_ночь", b);
        return (да - запрет) * (1.0 + склонность) - b["ночёвка_согласие"];
    }

    /// <summary>
    /// Какую из пустых квартир разберут. Одно место на оценку и на само дело:
    /// пока их было два, человек считал одну квартиру, а шёл в другую.
    /// </summary>
    public static Flat что_разбирать(House h, IReadOnlyList<Flat> pool, Баланс b)
    {
        Flat лучшая = pool[0];
        double лучше = double.NegativeInfinity;
        foreach (var f in pool)
        {
            double s = Ресурсы.Вещи(f.stock)                    // правда: квартира: видно снаружи
                       + (b["разбор_максимум"] - Math.Min(b["разбор_максимум"], f.stripped))
                       + (f.открыта ? b["разбор_взлом_решимость"] : 0.0);
            if (s > лучше)
            {
                лучше = s;
                лучшая = f;
            }
        }
        return лучшая;
    }

    /// <summary>Кому за этой дверью нужна аптечка — ему самому или ребёнку
    /// (GDD 12.6).</summary>
    public static bool нужен_врач(NPC p)
    {
        if (p.injuries.Count > 0 || p.sick is not null)
            return true;
        var р = p.слабейший_ребёнок();
        return р is not null && (р.болен is not null || р.здоровье < 70);
    }

    /// <summary>
    /// Сколько сытости даёт одна порция еды. GDD 12.1: умения полезны игроку
    /// и группе. Повар вытягивает из той же банки больше — и кормит не только
    /// себя, но и всех, кто с ним под одной крышей.
    /// </summary>
    public static double порция(House h, NPC npc, Баланс b)
    {
        bool cooks = npc.skills.Contains("повар", StringComparer.Ordinal);
        if (!cooks)
        {
            var кто = new List<string>();
            if (!string.IsNullOrEmpty(npc.living_with))
                кто.Add(npc.living_with);
            кто.AddRange(npc.guests.OrderBy(x => x, StringComparer.Ordinal));
            foreach (var other_id in кто)
            {
                var o = h.живой(other_id);
                if (o is not null && o.skills.Contains("повар", StringComparer.Ordinal))
                {
                    cooks = true;
                    break;
                }
            }
        }
        return b["еда_за_порцию"] * (cooks ? 1.0 + b["повар_прибавка"] : 1.0);
    }

    /// <summary>
    /// Материалы, ушедшие в стены, остаются в стенах. Это и есть
    /// привязанность к своему углу: человек не бросает квартиру, в которую
    /// вбил месяц работы, даже если рядом стоит лучше.
    /// </summary>
    public static void вложить(House h, NPC npc, double материалов)
        => h.where(npc).вложено += материалов;

    /// <summary>
    /// Сколько часов занимает действие (GDD 5), с поправкой на состояние
    /// (GDD 6.1). Голодный, промёрзший и не спавший человек делает ту же
    /// работу дольше. Разговор и еда от этого не растягиваются —
    /// растягивается труд.
    /// </summary>
    public static double hours(string key, NPC npc, Баланс b)
    {
        double v = b.Таблица("часы_действий")[key];
        if (key == "буржуйка" && (npc.skills.Contains("слесарь", StringComparer.Ordinal)
                                  || npc.skills.Contains("электрик", StringComparer.Ordinal)))
            v -= b["часы_ремонта_за_умение"];
        if (Каталог.РАБОТА.Contains(key))
            v *= npc.speed(b);
        return v;
    }
