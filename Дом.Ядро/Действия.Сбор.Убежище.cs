// Перенос house/actions.py, `_убежище` и `_жильё`: второй и третий разделы
// сбора.
//
// Печка, утепление, постройки третьего и четвёртого уровня, разбор пустой
// квартиры — и жильё как имущество: съехать, выгнать, занять, вынести тело.

namespace Дом.Ядро;

public static partial class Действия
{
    /// <summary>Раздел gather: убежище (GDD 15) и постройки уровней 3–4.</summary>
    public static void _убежище(Корзина корзина, House h, NPC npc, Баланс b, Самочувствие с)
    {
        double mats = npc.stock.Взять("материалы", 0.0);
        if (npc.shelter.Взять("буржуйка", 0.0) == 0.0 && mats >= b["буржуйка_материалы"])
            // база у печки была безусловной — и в лог первого дня метели, при
            // горячих ещё батареях, попадало «собрал буржуйку» от двоих сразу.
            // Печку собирают не от хозяйственности, а увидев, куда идёт
            // термометр, — и мерка та же, что у заказа
            корзина.add("буржуйка", b["буржуйка_база"] + с.холод_впереди * 6.0);
        // утепление же и латает проломы: клеить плёнку на окно, пока в стене
        // дыра от чужого лома, бессмысленно
        int дыр = h.where(npc).дыр();
        if ((npc.shelter.Взять("утепление", 0.0) < b["максимум_утепления"] || дыр != 0)
            && mats >= b["утепление_материалы"])
            корзина.add("утепление", 1.0 + с.холод_впереди * 5.0 + дыр * b["дыра_чинят"]);

        // --- убежище уровней 3 и 4 (GDD 15): их не построить без человека
        // с руками
        foreach (var (ключ, п) in Каталог.ПОСТРОЙКИ)
        {
            string поле = ключ == "генератор_собрать" ? "генератор" : ключ;
            if (npc.shelter.Взять(поле, 0.0) >= п.потолок)
                continue;
            if (!п.умения.Any(u => npc.skills.Contains(u, StringComparer.Ordinal)))
                continue;
            if (mats < b[п.материалы])
                continue;
            if (ключ == "генератор_собрать" && !Услуги.есть_движок(npc))
                continue;         // из досок двигатель не собрать
            // пока в доме есть свет, генератор — не нужда, а запасливость,
            // и семь материалов сейчас нужнее в окнах. Считается тем же
            // `нужен_генератор`, что и заказ у соседа
            double s = ключ switch
            {
                "генератор_собрать" =>
                    Услуги.нужен_генератор(h, npc, h.where(npc), с.холод_впереди),
                "листы" => с.тревога * 4.0,
                "звукоизоляция" => с.тревога * 2.0
                    + (npc.shelter.Взять("генератор", 0.0) != 0.0 ? 3.0 : 0.0),
                "стены" => с.тревога * 5.0 - 1.0,
                _ => throw new KeyNotFoundException(ключ),
            };
            корзина.add(ключ, s);
        }

        if (npc.shelter.Взять("дверь", 0.0) < b["максимум_двери"]
            && mats >= b["дверь_материалы"])
        {
            double s = с.тревога * 4.5 + npc.вес_черт("дверь");
            if (h.календарь.укрепление_порыв == h.day)
                s += 2.5;
            корзина.add("дверь", s);
        }

        // квартиру можно разобрать лишь несколько раз — потом там голые стены
        var strippable = h.пустые_для(npc)
            .Where(f => f.stripped < b["разбор_максимум"] || Ресурсы.Вещи(f.stock) > 0)  // правда: квартира: что лежит в пустой, видно снаружи
            .ToList();
        if (strippable.Count > 0)
        {
            double want_mats = 0.0;
            if (npc.shelter.Взять("буржуйка", 0.0) == 0.0)
                want_mats += 3.0;
            if (npc.shelter.Взять("утепление", 0.0) < 2)
                want_mats += 2.0;
            if (npc.shelter.Взять("дверь", 0.0) < 1)
                want_mats += 1.5 * с.тревога;
            want_mats += npc.вес_черт("разбор");
            // в квартире умершего может остаться еда — и это все понимают
            Flat best_flat = strippable[0];
            foreach (var f in strippable)
                if (Ресурсы.Вещи(f.stock) > Ресурсы.Вещи(best_flat.stock))   // правда: квартира
                    best_flat = f;
            if (Ресурсы.Вещи(best_flat.stock) > 2)                            // правда: квартира
                want_mats += 2.0 + с.отчаяние * 3.0;
            // то же, чем меряется кража: пока улица ещё кормит, к чужой двери
            // не идут. Разница между «сходить в гаражи» и «вскрыть кв.11»
            // не в добыче, а в том, что второе делают, когда первое перестало
            // работать
            want_mats *= 1.0 - есть_куда_сходить(h, npc, завтра: true) * b["разбор_вес_улицы"];
            // и отдельно — запертая дверь. Пустая квартира и запертая чужая
            // квартира были для кода одним и тем же
            var цель = что_разбирать(h, strippable, b);
            if (!цель.открыта)
                want_mats -= b["разбор_взлом_решимость"];
            корзина.add("разбор", want_mats - mats * 0.25);
        }
    }

    /// <summary>
    /// Раздел gather: жильё — вместе или порознь, занять пустую квартиру
    /// и то, до чего доходят в пустых квартирах на третьей неделе.
    /// </summary>
    public static void _жильё(Корзина корзина, House h, NPC npc, Баланс b, Самочувствие с)
    {
        // то же число, которым считают переезд, каждый день пересчитывается
        // заново. Пока выхода из сожительства не было, пары доживали до конца
        // с взаимной ненавистью 86 из 100 и продолжали делить одну комнату
        if (!string.IsNullOrEmpty(npc.living_with))
        {
            var host = h.живой(npc.living_with);
            if (host is not null)
            {
                double невыгодно = -Социальное.выгода_соседства(h, npc, host)
                                   - b["съехать_порог"];
                // и то, чего нет ни в тепле, ни в тесноте: с человеком,
                // которого боишься, в одной комнате не остаются
                невыгодно += npc.боится(host.id) * b["страх_вес_соседства"];
                корзина.add("съехать", невыгодно * b["разъезд_вес"], host);
            }
        }
        foreach (var g_id in npc.guests.OrderBy(x => x, StringComparer.Ordinal))
        {
            var g = h.живой(g_id);
            if (g is null)
                continue;
            // выставить может только тот, кто сильнее: слабый хозяин терпит
            if (npc.power() < g.power() * b["выгнать_превосходство"])   // правда: под одной крышей: гость
                continue;
            корзина.add("выгнать",
                (-Социальное.выгода_соседства(h, npc, g) - b["выгнать_порог"])
                    * b["разъезд_вес"], g);
        }

        // --- занять пустую квартиру (GDD 12): жильё — вещь, и его занимают
        // человек уходит не туда, где просто пусто, а туда, где заметно лучше:
        // целая дверь, заклеенные окна, чужая буржуйка. И тем тяжелее ему
        // уйти, чем больше он вложил в собственные стены
        if (string.IsNullOrEmpty(npc.living_with))
        {
            var своя = h.flats[npc.apt];
            double моя_цена = h.ценность_жилья(своя, npc);
            double держит = своя.вложено * b["жильё_привязанность"];
            foreach (var f in h.пустые_для(npc))
            {
                if (f.apt == npc.apt)
                    continue;
                double выгода = h.ценность_жилья(f, npc) - моя_цена - держит
                                - b["занять_порог"];
                if (f.body is not null && f.body.порций > 0)
                    выгода -= b["занять_тело_штраф"] * (0.5 + npc.t01("лояльность"));
                var прежний = h.чей(f);
                if (прежний is not null)
                {
                    // угол живого человека: он сейчас у соседа, но возвращаться
                    // ему будет некуда
                    выгода -= b["занять_чужую_штраф"] * (0.5 + npc.t01("лояльность"));
                    // если, конечно, этого человека он ещё считает живым.
                    // Тот, кого списали со счетов, на свой угол в чужих глазах
                    // уже не в счёт — и это ровно то, ради чего за ним следили
                    if (npc.не_жилец.Contains(прежний.id))
                        выгода += b["занять_чужую_штраф"] * (0.5 + npc.t01("лояльность")) * 0.8;
                }
                корзина.add("занять", выгода, f);
            }
        }

        // --- то, до чего доходят на третьей неделе ---
        var bodies = h.пустые_для(npc)
            .Where(f => f.body is not null && f.body.порций > 0
                        && h.day - f.body.день <= b["тело_порча_дней"]).ToList();
        if (bodies.Count > 0)
        {
            // вынести тело: так поступают те, кто ещё держится за человеческое
            if (npc.trait("лояльность") >= 6 && npc.health > 45)
                корзина.add("вынести", npc.вес_черт("вынести")
                    + Социальное.recent_incidents(h) * 0.4 - 1.0);
            // и то, до чего доходят от голода
            bool hungry_enough = npc.satiety < b["людоедство_порог_сытости"]
                                 || npc.days_of("еда") < 0.8;
            if (hungry_enough && !npc.dependents_only_child(h))
            {
                double s = с.отчаяние * 10.0 + (1.0 - Util.Norm(npc.satiety, 0, 45)) * 4.0;
                s += npc.вес_черт("тело");
                s -= b["людоедство_порог_решимости"];
                s += npc.panic / 100.0 * 2.5;
                Flat near = bodies[0];
                foreach (var f in bodies)
                    if (Math.Abs(f.floor - npc.floor) < Math.Abs(near.floor - npc.floor))
                        near = f;
                if (near.owner_died is not null && npc.allies.Contains(near.owner_died))
                    s -= 5.0;
                корзина.add("тело", s);
            }
        }
    }
}
