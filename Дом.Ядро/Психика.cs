// Перенос house/psyche.py: медленные движения горизонта и нормальности —
// раз в сутки, утром.
//
// Не оркестрация и не решение, а то, с чем человек просыпается. Нормальность
// падает в момент события (`social.видел`: отключение, происшествие, смерть,
// чужой пример, свой первый крайний поступок) — здесь только слабый календарь
// и отрастание в тихие дни. Горизонт — «вера, что скоро всё кончится» (GDD 12.3).

namespace Дом.Ядро;

public static class Психика
{
    /// <summary>На сколько дней вперёд человек сегодня считает запас.</summary>
    public static void горизонт(House h, NPC p)
    {
        var b = h.B;
        // чем дольше метель, тем меньше веры, что она кончится (GDD 12.3:
        // паника — это «вера, что скоро всё кончится»)
        p.horizon = Math.Min(b["горизонт_потолок"],
                             b["горизонт_старт"] + h.day * b["горизонт_за_день"]
                             + p.panic * b["горизонт_за_панику"]
                             + p.trait("жадность") * b["горизонт_за_жадность"]);
        // запасливый считает вперёд с самого начала, не дожидаясь страха
        p.horizon = Math.Max(p.horizon,
                             Math.Min(b["горизонт_потолок"], p.пунктик("горизонт_пол")));
    }

    /// <summary>
    /// Календарь и тихие дни: два медленных движения нормальности за сутки.
    ///
    /// Нормальность — состояние, а не формула. Пока она считалась каждое утро
    /// заново по формуле, где главным слагаемым был номер дня, к седьмому дню
    /// она была нулём у всех сразу, и двадцать три дня из тридцати дом вёл
    /// себя как один человек: личность весила ±0.1 и тонула.
    /// </summary>
    public static void дрейф_нормальности(House h, NPC p)
    {
        var b_n = h.B;
        double n = p.normalcy - b_n["нормальность_за_день"];
        n -= (p.panic / 100.0) * b_n["нормальность_за_панику"];
        if (Социальное.тихо_ли(h))
            // ложная надежда, из которой распад потом бьёт сильнее
            n += b_n["нормальность_отрастает"];
        p.normalcy = Util.Clamp(n, p.нормальность_пол, 1.0);
    }
}
