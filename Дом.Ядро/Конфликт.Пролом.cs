// Перенос house/conflict.py, строки 1364–1494: чем ещё войти, если дверь
// выдержала.
//
// GDD 16 называет это стадией — и до переноса она была единственной, которую
// код пропускал: «дверь выдержала» означало «все разошлись». Между тем
// человек, у которого дома пусто, от чужой двери с пустыми руками не уходит:
// он идёт вокруг — в окно, если пускает погода, или сквозь стену, если пришли
// втроём и рядом стоит пустая квартира.
//
// Дыра остаётся в стенах, и в этом вся цена такой победы: в неё дует,
// за ней больше не спрятаться, и в следующий раз через неё войдут уже
// без всякой осады.

namespace Дом.Ядро;

public static partial class Конфликт
{
    /// <summary>Что говорит журнал про окно — смотря откуда лезли.</summary>
    private static readonly Словарь<string, string> ОКНО_ТЕКСТ = Окно();

    private static Словарь<string, string> Окно()
    {
        var т = Словари.Строкой<string>();
        т["низ"] = "Тогда выставили окно со двора и влезли внутрь.";
        т["крыша"] = "Тогда спустились с крыши на верёвке и выдавили раму.";
        т["балкон"] = "Тогда прошли по балконам от соседнего окна и выставили створку.";
        return т;
    }

    /// <summary>Стена ломается в обе стороны, а пол одной квартиры —
    /// это потолок другой.</summary>
    private static string Обратный(string вид) => вид switch
    {
        "стена" => "стена",
        "потолок" => "пол",
        _ => "потолок",
    };

    /// <summary>
    /// Откуда ломать: своя квартира или пустая (GDD 16, стадия стен).
    ///
    /// Стену и перекрытие ломают, стоя в другой квартире, и это настоящее
    /// ограничение, а не бросок кубика: к Лиде на третьем спускаются сверху,
    /// потому что над ней кв.14 и кв.16, — а к Игорю на первом снизу
    /// не придёт никто, там подвал.
    /// </summary>
    private static Flat? _площадка(House h, IReadOnlyList<NPC> crew, Flat flat, string где)
    {
        var свои = new HashSet<int>(crew.Select(p => p.apt));
        foreach (var p in crew)
            свои.Add(h.where(p).apt);
        var занято = h.занятые();
        foreach (var f in h.соседние(flat, где))
            if (свои.Contains(f.apt) || !занято.Contains(f.apt))
                return f;
        return null;
    }

    /// <summary>
    /// Чем ещё можно войти, если дверь выдержала (GDD 16).
    ///
    /// Список (вид, шанс, охота, площадка, откуда), отсортированный по охоте.
    /// Окно зависит от погоды и этажа, перекрытия — от того, есть ли рядом
    /// пустая квартира и хватает ли людей на объединённый рейд.
    /// </summary>
    public static List<(string вид, double шанс, double охота, Flat? площадка, string? откуда)>
        пути_внутрь(House h, IReadOnlyList<NPC> crew, NPC target,
                    IReadOnlyList<NPC> defenders, double упор = 0.0)
    {
        var b = h.B;
        var flat = h.flats[target.apt];
        var шансы = b.Таблица("пролом_шанс");
        double сила = Util.Clamp(0.5 + инструменты(crew) * b["пролом_за_инструменты"],
                                 0.3, 1.6);
        double арматура = 1.0 + b["стены_за_уровень"] * flat.shelter.Взять("стены", 0.0);
        bool за_жильём = хочу_его_квартиру(h, crew[0], target) > 0;
        var сырые = new List<(string вид, double шанс, Flat? площадка, string? откуда)>();

        // окно: со двора, с крыши или по балконам — и только если погода
        // пускает. В буран на карниз не выйдет никто, и на тридцатиградусном
        // морозе тоже: пальцы белеют раньше, чем поддастся рама
        if (h.режим != Режим.БУРАН && h.outside > b["окно_мороз"])
        {
            int верх = h.flats.Значения.Max(f => f.floor);
            string откуда = flat.floor <= 1 ? "низ" : (flat.floor >= верх ? "крыша" : "балкон");
            double шанс = шансы.Взять("окно", 0.0) * сила
                          * b.Таблица("окно_доступ").Взять(откуда, 0.0);
            // заколоченные окна — та самая двойная выгода утепления (GDD 13:
            // тепло и тишина; теперь ещё и створка, которую снаружи
            // не выставить). Делитель, а не вычет: четвёртый слой утепления
            // должен окно защищать, а не закрывать эту стадию вовсе —
            // с вычетом шанс уходил в ноль у всех, к кому вообще ходят с ломом
            шанс /= 1.0 + b["окно_за_утепление"] * flat.shelter.Взять("утепление", 0.0);
            шанс -= Math.Max(0, defenders.Count - 1) * b["окно_за_защитника"];
            сырые.Add(("окно", шанс, null, откуда));
        }

        // стена и перекрытия — объединённым рейдом, трое и больше (GDD 16).
        // Арматура по стене и потолку (убежище 4 уровня) — единственная защита
        // от этой стадии, и ради неё её и строят.
        //
        // Или в одиночку, если терять уже нечего: трое ломают стену
        // расчётливо, а один — от отчаяния, и это ровно то же самое отчаяние,
        // из-за которого он вообще не ушёл от целой двери
        if (crew.Count >= b["стены_нужно_людей"] || упор >= b["налёт_упорство_отчаяние"])
            foreach (string где in new[] { "стена", "потолок", "пол" })
            {
                var площадка = _площадка(h, crew, flat, где);
                if (площадка is not null)
                    сырые.Add((где, шансы.Взять(где, 0.0) * сила / арматура, площадка, null));
            }

        var готовые = new List<(string, double, double, Flat?, string?)>();
        foreach (var (вид, сырой, площадка, откуда) in сырые)
        {
            double шанс = Util.Clamp(сырой, 0.0, 0.95);
            double охота = шанс;
            if (за_жильём)
                // ломая, портишь ровно то, ради чего пришёл (GDD 16):
                // за квартирой лезут через стену, а не в окно — выбитая рама
                // в метель дороже
                охота -= b.Таблица("дыра_градусов").Взять(вид, 0.0)
                         * b["пролом_бережёт_приз"];
            готовые.Add((вид, шанс, охота, площадка, откуда));
        }
        return готовые.OrderByDescending(x => x.Item3).ToList();
    }

    /// <summary>
    /// Дыра остаётся в стенах — и сразу в двух квартирах, если это
    /// перекрытие. В этом вся цена такой победы: в пролом дует, за ним больше
    /// не спрятаться, и в следующий раз через него войдут уже без осады.
    /// </summary>
    public static void пролом(House h, Flat flat, string вид, Flat? площадка = null)
    {
        flat.дыры[вид] = flat.дыры.Взять(вид, 0) + 1;
        flat.открыта = true;
        flat.вложено = Math.Max(0.0, flat.вложено - 2.0);
        if (string.Equals(вид, "окно", StringComparison.Ordinal)
            && flat.shelter.Взять("утепление", 0.0) > 0)
            flat.shelter["утепление"] = flat.shelter.Взять("утепление", 0.0) - 1;
        if (площадка is not null)
        {
            string обратный = Обратный(вид);
            площадка.дыры[обратный] = площадка.дыры.Взять(обратный, 0) + 1;
            площадка.открыта = true;
        }
        h.bump("проломов");
        h.bump("пролом_" + вид);
    }

    /// <summary>
    /// Дверь выдержала: разойтись или искать другой путь (GDD 16).
    /// Возвращает (вид пролома или null, что успели попробовать).
    /// </summary>
    public static (string? вошли, List<string> пробовали) _войти_иначе(
        House h, IReadOnlyList<NPC> crew, NPC target, IReadOnlyList<NPC> defenders)
    {
        var b = h.B;
        double упор = упорство(h, crew, target);
        if (упор < b["налёт_упорство_порог"])
            return (null, new List<string>());
        // чем отчаяннее группа, тем больше способов она успевает попробовать
        int попыток = 1 + (упор >= b["налёт_упорство_порог"] * 2 ? 1 : 0);
        var flat = h.flats[target.apt];
        var пробовали = new List<string>();
        foreach (var (вид, шанс, _, площадка, откуда) in
                 пути_внутрь(h, crew, target, defenders, упор).Take(попыток))
        {
            пробовали.Add(вид);
            bool окно = string.Equals(вид, "окно", StringComparison.Ordinal);
            Социальное.emit(h, target, окно ? 3 : 5, окно ? "взлом" : "пролом",
                            night: true);
            if (!h.rng.Chance(шанс))
                continue;
            пролом(h, flat, вид, площадка);
            if (окно)
                h.journal.line($"Дверь кв.{target.apt} выдержала. "
                               + ОКНО_ТЕКСТ.Взять(откуда!, ""), 2);
            else if (string.Equals(вид, "стена", StringComparison.Ordinal))
                h.journal.line($"Дверь кв.{target.apt} выдержала — тогда пробили стену "
                               + $"из кв.{площадка!.apt}.", 2);
            else if (string.Equals(вид, "потолок", StringComparison.Ordinal))
                h.journal.line($"Дверь кв.{target.apt} выдержала. Разобрали пол "
                               + $"в кв.{площадка!.apt} и спустились сверху.", 2);
            else
                h.journal.line($"Дверь кв.{target.apt} выдержала. Вскрыли перекрытие "
                               + $"снизу, из кв.{площадка!.apt}.", 2);
            // ломать пришлось из собственных стен — и дыра осталась в них тоже
            var свой = площадка is not null ? h.чей(площадка) : null;
            if (свой is not null && crew.Contains(свой))
                h.journal.line($"   Ломали из своей же кв.{площадка!.apt}. "
                               + "Теперь дует и там.", 1);
            return (вид, пробовали);
        }
        return (null, пробовали);
    }
}
