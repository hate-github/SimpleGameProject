// Перенос house/actions.py, строки 2242–2600: разбор чужой квартиры
// и всё, что делают с соседом лицом к лицу.
//
// Разбор стоит здесь, а не среди быта, потому что он и есть первый шаг
// от быта к чужому: доски из пустой квартиры — тот же ресурс, что топливо
// для буржуйки, и дом проедает сам себя ими.

namespace Дом.Ядро;

public static partial class Действия
{
    internal static void ЗарегистрироватьСоседей()
    {
        исполняет("разбор", (h, npc, target, spent) =>
        {
            var b = h.B;
            var пустые = h.пустые_для(npc);
            var pool = пустые.Where(f => f.stripped < b["разбор_максимум"]
                                         || Ресурсы.Вещи(f.stock) > 0).ToList();
            if (pool.Count == 0)
                pool = пустые;
            if (pool.Count == 0)
                return НЕ_СОСТОЯЛОСЬ;
            var flat = что_разбирать(h, pool, b);
            Социальное.вошёл_в_квартиру(h, npc, flat);
            // запертую дверь сначала ломают, и это слышит весь подъезд
            bool вскрыл = !flat.открыта;
            if (вскрыл)
            {
                flat.открыта = true;
                h.bump("вскрытых_квартир");
                Социальное.emit(h, npc, 4, "взлом", night: false);
            }
            var got = Словари.Строкой<double>();
            foreach (string res in flat.stock.Ключи.ToList())
            {
                double amount = flat.stock.Взять(res, 0.0);
                double take = Math.Min(amount, 3.0);      // за один заход больше не утащить
                if (take > 0)
                {
                    flat.stock[res] = amount - take;
                    npc.stock[res] = npc.stock.Взять(res, 0.0) + take;
                    got[res] = take;
                }
            }
            if (flat.stripped < b["разбор_максимум"])
            {
                npc.stock["материалы"] = npc.stock.Взять("материалы", 0.0)
                                         + b["разбор_материалов"];
                got["материалы"] = got.Взять("материалы", 0.0) + b["разбор_материалов"];
                // доски из стен — это приход в мир, а не перекладывание;
                // считаем, иначе баланс материалов в доме не сходится
                h.stats["наразобрано_материалы"] =
                    h.stats.Взять("наразобрано_материалы", 0.0) + b["разбор_материалов"];
            }
            if (flat.тулуп && npc.одежда < b["одежда_максимум"])
            {
                flat.тулуп = false;
                npc.одежда = (int)b["одежда_максимум"];
                got["тулуп"] = 1;
                h.bump("тулупов_снято_с_мёртвых");
            }
            // и то, что стоит в углу за дверью: кто разбирает чужую квартиру,
            // тот первым и находит топор бывшего хозяина
            string? взял = Конфликт.подобрать_оружие(h, npc, flat);
            if (взял is not null)
                got[взял] = 1;
            // и ключ с гвоздя в прихожей. Без этого запас в подвале умирал бы
            // вместе с хозяином и выпадал из игры навсегда
            foreach (string kid in flat.ключи.OrderBy(x => x, StringComparer.Ordinal).ToList())
                if (h.rng.Chance(b["ключи_шанс"]))
                {
                    flat.ключи.Remove(kid);
                    npc.ключи_кладовых.Add(kid);
                    var к = h.кладовые.Взять(kid, null);
                    h.bump("ключей_от_кладовых_найдено");
                    if (к is not null)
                        h.journal.line($"   На гвозде в прихожей {Util.Vb(npc.sex, "нашёл")} "
                                       + $"ключ от {к.имя_род}.", 1);
                }
            flat.stripped += 1;
            // доски берут не из воздуха: сначала выламывают то, чем квартира
            // утеплена, потом дверь. Запасная комната и топливо для буржуйки —
            // один и тот же ресурс
            string? если_было = null;
            if (flat.shelter.Взять("утепление", 0.0) > 0)
            {
                flat.shelter["утепление"] = flat.shelter.Взять("утепление", 0.0) - 1;
                если_было = "рамы";
            }
            else if (flat.shelter.Взять("дверь", 0.0) > 0)
            {
                flat.shelter["дверь"] = flat.shelter.Взять("дверь", 0.0) - 1;
                если_было = "дверь";
            }
            flat.вложено = Math.Max(0.0, flat.вложено - b["разбор_материалов"]);
            if (flat.owner_died is not null
                && Util.Sum(got.Ключи
                    .Where(k => !string.Equals(k, "материалы", StringComparison.Ordinal))
                    .Select(k => got.Взять(k, 0.0))) > 0)
                npc.mood = Util.Clamp(npc.mood - 5 * npc.t01("лояльность"));
            string took = string.Join(", ", got.Ключи
                .Where(k => got.Взять(k, 0.0) != 0.0)
                .Select(k => $"{k} {(long)got.Взять(k, 0.0)}"));
            string said = $"{npc.@short} {Util.Vb(npc.sex, "разобрал")} часть кв.{flat.apt}"
                          + (took.Length > 0 ? $": {Util.Vb(npc.sex, "взял")} {took}" : "");
            if (string.Equals(если_было, "рамы", StringComparison.Ordinal))
                said += "; окна там теперь голые";
            else if (string.Equals(если_было, "дверь", StringComparison.Ordinal))
                said += "; дверь снял с петель";
            if (вскрыл)
                said += "; замок пришлось сорвать";
            // у пустой квартиры может быть живой хозяин: он греется у соседа,
            // а его угол растаскивают на доски (GDD 15, ловушка для
            // переехавшего). До сих пор он этого попросту не замечал
            var хозяин = h.чей(flat);
            if (хозяин is not null
                && !string.Equals(хозяин.id, npc.id, StringComparison.Ordinal)
                && хозяин.здесь())
            {
                Социальное.adjust(хозяин, npc.id, trust: -2.0, hate: b["ненависть_за_разбор"]);
                хозяин.mood = Util.Clamp(хозяин.mood - 8);
                h.journal.line($"   {хозяин.@short} {Util.Vb(хозяин.sex, "видел")}, как из "
                    + $"{(string.Equals(хозяин.sex, "ж", StringComparison.Ordinal) ? "её" : "его")} "
                    + $"квартиры {Util.Vb(npc.sex, "таскал")} доски.", 1);
            }
            return said;
        });

        // --- соседи ---

        исполняет("разговор", (h, npc, target, spent) =>
        {
            var b = h.B;
            var t = (NPC)target!;
            Социальное.встретились(h, npc, t);
            Социальное.gossip(h, npc, t);
            // разговоры поднимают доверие только до уровня знакомства. Выше —
            // поступками: помощью, лечением, защитой у двери. Иначе семь бесед
            // в день превращают чужих людей в друзей за неделю метели
            double Словами(NPC кто, string о_ком)
            {
                double есть = кто.trust.Взять(о_ком, 3.0);
                double запас = Util.Clamp((b["доверие_от_слов_потолок"] - есть)
                                          / b["доверие_от_слов_потолок"], 0.0, 1.0);
                // и те же слова от своего стоят дороже, чем от соседа
                // по площадке. Без этого разговор давал всем одинаково,
                // и доверие выходило общим мнением о человеке, а не тем,
                // что было между этими двумя
                return b["доверие_за_разговор"] * запас
                       * (b["доверие_слов_от_чужого"]
                          + (1.0 - b["доверие_слов_от_чужого"]) * кто.свой(о_ком) * 2.0);
            }
            Социальное.adjust(npc, t.id, trust: Словами(npc, t.id));
            Социальное.adjust(t, npc.id, trust: Словами(t, npc.id) * 0.8);
            npc.mood = Util.Clamp(npc.mood + b["настроение_от_общения"]);
            t.mood = Util.Clamp(t.mood + b["настроение_от_общения"] * 0.7);
            npc.panic = Util.Clamp(npc.panic - 2);
            npc.день_разговора = h.day;
            t.день_разговора = h.day;
            // отдельно от чата: разговор в дверях и строчка в общем чате —
            // разные вещи, и одиночество меряется первым. Пока это было одним
            // полем, самый общительный житель дома, который в этот чат и пишет,
            // числился неодиноким ровно потому, что писал
            npc.день_беседы = h.day;
            t.день_беседы = h.day;
            // и главное, чего у разговора не было: он сближает. Доверие
            // от слов упирается в потолок знакомства, и правильно — своим
            // человека делают не слова. Но то, что эти двое второй день
            // подряд находят друг друга на лестнице, — это уже история пары
            Социальное.сблизились(h, npc, t, b["близость_за_разговор"]);
            return $"{npc.@short} {Util.Vb(npc.sex, "зашёл")} к {t.form("dat")}";
        });

        исполняет("попросить", (h, npc, target, spent, res) =>
        {
            var t = (NPC)target!;
            Социальное.встретились(h, npc, t);
            return _ask(h, npc, t, res as string);
        }, детали: true);

        исполняет("поделиться", (h, npc, target, spent, детали) =>
        {
            var b = h.B;
            var t = (NPC)target!;
            string? чем = детали as string;
            const double n = 1.0;
            // чем помочь, решено в сборе тем же кодом, что оценивал помощь,
            // и пришло сюда. Пока помощь была только едой, замерзающему
            // по своей воле не носили дров ни разу
            if (чем is null)
            {
                // сюда попадают только вызовы мимо сбора (сценарий, проверка):
                // дом ходом дня всегда передаёт решённое. Счётчик это и стережёт
                h.bump("пересчётов_в_исполнении");
                чем = чем_поделиться(h, npc, t, b).res;
            }
            Социальное.встретились(h, npc, t);
            if (чем is not null && npc.stock.Взять(чем, 0.0) >= n)
            {
                npc.stock[чем] = npc.stock.Взять(чем, 0.0) - n;
                t.stock[чем] = t.stock.Взять(чем, 0.0) + n;
                // банка от своего и банка от чужого — не одно и то же: первая
                // подтверждает то, что уже есть, вторая только начинает
                Социальное.adjust(t, npc.id,
                    trust: b["доверие_за_помощь"] * 1.3
                           * (b["доверие_слов_от_чужого"]
                              + (1.0 - b["доверие_слов_от_чужого"]) * t.свой(npc.id) * 2.0),
                    hate: -10);
                Социальное.adjust(npc, t.id, trust: 0.6);
                npc.mood = Util.Clamp(npc.mood + b["настроение_от_помощи"]);
                t.mood = Util.Clamp(t.mood + 8);
                t.favors[npc.id] = t.favors.Взять(npc.id, 0) + 1;
                var опыт = t.ask_record(npc.id);
                опыт.я_дал = h.day;
                опыт.должен += 1.0;
                // долг помнит, чем брали: взял дрова — верни дрова, а не банку
                опыт.должен_чем = чем;
                npc.дал[t.id] = npc.дал.Взять(t.id, 0.0) + 1.0;
                // он мне не отказывал, я сам принёс
                npc.ask_record(t.id).дали += 0.5;
                // то же событие, что и «дали, когда попросил»: для движка это
                // одна и та же вещь — банка перешла из рук в руки, — а чем она
                // отличается, видно по тому, была ли перед ней просьба
                h.событие(ВидСобытия.ПОМОЩЬ, кто: npc.id, кому: t.id, что: чем,
                          сколько: n, где: t.apt);
                сказать_сразу(h, "поделиться",
                    $"{npc.@short} "
                    + (string.Equals(npc.sex, "ж", StringComparison.Ordinal)
                       ? "сама занесла" : "сам занёс")
                    + $" {(RES_ВИН.TryGetValue(чем, out var в_) ? в_ : чем)} {t.form("dat")}");
                // принёсший знает, что теперь у соседа банкой больше; и лестница
                // не пустая — соседи видят, к чьей двери сегодня ходили. Пока
                // этого не было, четверо в один день несли еду одному человеку,
                // и каждый следующий по-прежнему считал, что тот голодает
                Социальное.note_signal(npc, t.id, чем, npc.believed(t.id, чем) + n, 0.8);
                var заметили = new List<NPC>();
                foreach (var сосед in h.others(npc))
                {
                    if (string.Equals(сосед.id, t.id, StringComparison.Ordinal) || сосед.away)
                        continue;
                    if (h.rng.Chance(b["заметность_помощи"]))
                    {
                        заметили.Add(сосед);
                        Социальное.adjust(сосед, t.id, aware: 3);
                        Социальное.note_signal(сосед, t.id, чем,
                                               сосед.believed(t.id, чем) + n, 0.5);
                    }
                }
                // судят те, кто это видел, а не весь дом. Пока «щедрость»
                // весом 0.35 доставалась всем пятерым безусловно, помощь
                // работала не на того, кому помогли, а на общую репутацию
                // помогающего
                Социальное.judge(h, npc, "щедрость", trust: 0.35,
                                 witnesses: заметили.Append(t).ToList(),
                                 участники: new[] { t });
                Социальное.сблизились(h, npc, t, b["близость_за_помощь"]);
                // безвозмездная банка — единственное, чем гасится обида.
                // Ни разговор, ни сделка её не трогают
                Социальное.загладил(h, npc, t, b["обида_за_помощь"]);
                Социальное.проверить_наговор(h, npc, t);
                h.bump("поделились_" + чем);
            }
            return null;
        }, детали: true);

        исполняет("вернуть", (h, npc, target, spent) =>
        {
            var b = h.B;
            var t = (NPC)target!;
            Социальное.встретились(h, npc, t);
            var rec = npc.ask_record(t.id);
            // чем брал, тем и отдаёт. Пока долг всегда номинировался в еде,
            // человек, взявший дрова, возвращал банку тушёнки — и у соседа
            // по-прежнему не было чем топить
            string чем = string.IsNullOrEmpty(rec.должен_чем) ? "еда" : rec.должен_чем!;
            if (npc.stock.Взять(чем, 0.0) < 1.0)
            {
                чем = "еда";
                foreach (string r in new[] { "еда", "топливо", "вода" })
                    if (npc.days_of(r) > npc.days_of(чем))
                        чем = r;
            }
            double сколько = Math.Min(1.0, npc.stock.Взять(чем, 0.0));
            if (сколько <= 0)
                return НЕ_СОСТОЯЛОСЬ;
            npc.stock[чем] = npc.stock.Взять(чем, 0.0) - сколько;
            t.stock[чем] = t.stock.Взять(чем, 0.0) + сколько;
            rec.должен = Math.Max(0.0, rec.должен - 1.0);
            t.дал[npc.id] = Math.Max(0.0, t.дал.Взять(npc.id, 0.0) - 1.0);
            сказать_сразу(h, "вернуть",
                $"{npc.@short} {Util.Vb(npc.sex, "занёс")} {(RES_ВИН.TryGetValue(чем, out var в_) ? в_ : чем)} "
                + $"{t.form("dat")} — "
                + (string.Equals(npc.sex, "ж", StringComparison.Ordinal)
                   ? "отдала" : "отдал") + " долг");
            // возврат восстанавливает равновесие, а не создаёт новое доверие:
            // иначе пара «дал — вернул» кончается тем, что оба доверяют друг
            // другу больше прежнего, хотя ничего не произошло
            Социальное.adjust(t, npc.id, trust: b["доверие_за_возврат"], hate: -3);
            npc.mood = Util.Clamp(npc.mood + 3);
            t.mood = Util.Clamp(t.mood + 4);
            h.bump("долгов_возвращено");
            // сдержанное слово стоит больше самого возврата (GDD 14)
            Социальное.сдержал(h, npc, t, "отдать");
            Социальное.сблизились(h, npc, t, b["близость_за_возврат"]);
            Социальное.проверить_наговор(h, npc, t);
            return null;
        });

        исполняет("обмен", (h, npc, target, spent) =>
        {
            var t = (NPC)target!;
            Социальное.встретились(h, npc, t);
            return _trade(h, npc, t);
        });
    }
}
