// Перенос house/social.py, раздел «обмен»: чего вещь стоит вот этому человеку.
//
// Три функции, на которых стоит вся мена. Главное в них — `глазами`: чужую
// цену считают по знанию о соседе, а не по его шкафу.

namespace Дом.Ядро;

public static partial class Социальное
{
    /// <summary>
    /// Чего стоит для этого человека тысяча рублей (GDD 18).
    ///
    /// Две части, и обе важны. Мировая — курс дома: пока магазин работает,
    /// деньги настоящие, дальше они дешевеют. И личная — во что человек ещё
    /// верит: пока жизнь похожа на обычную, купюра остаётся купюрой;
    /// у того, у кого привычное рассыпалось, она уже бумага.
    /// </summary>
    public static double цена_денег(NPC npc)
    {
        var h = npc._h;
        if (h is null)
            return 0.0;
        var b = h.B;
        double вера = 1.0 - b["деньги_вера_нормальность"] * (1.0 - npc.normalcy);
        return b["деньги_цена"] * h.курс() * вера;
    }

    /// <summary>
    /// Сколько ресурс стоит лично для этого человека (GDD 18: с учётом
    /// дефицита).
    ///
    /// <paramref name="days"/> можно передать снаружи — тогда считается
    /// не по настоящим запасам, а по тому, на сколько дней их, по чужому
    /// мнению, хватает. <paramref name="глазами"/> — тот, кто прикидывает
    /// чужую цену со стороны: тогда и остальное берётся по его знанию —
    /// патроны по оценке, хворь по взгляду, вера в деньги по себе.
    /// </summary>
    public static double value_of(NPC npc, string res, double amount,
                                  double? days = null, NPC? глазами = null)
    {
        if (res == "деньги")
            // деньги не кончаются «через столько-то дней» — у них не дефицит,
            // а курс, и считается он отдельно. Во что верит сосед, со стороны
            // не видно — судят по себе
            return amount * цена_денег(глазами ?? npc);
        if (res == "патроны")
        {
            // патрон стоит ровно столько, сколько стоит ружьё, из которого
            // стрелять. Пока цена считалась общей формулой, патрон у Лиды
            // стоил как у Петра, и безоружные держали их мёртвым грузом
            if (!Таблицы.ОГНЕСТРЕЛ.Contains(npc.weapon))    // правда: общее знание: с чем сосед стоит в дверях, дом знает
                return amount * 0.2;
            double свои = глазами is not null
                ? глазами.believed(npc.id, "патроны")
                : npc.stock.Взять("патроны", 0.0);
            double нужда = свои < 2 ? 3.4 : (свои < 5 ? 2.4 : 1.6);
            return amount * нужда;
        }
        double d;
        if (days is null)
        {
            d = res is "еда" or "вода" or "топливо" ? npc.days_of(res) : 5.0;
            // у гостя своего топлива нет по устройству: оно ушло в печку
            // хозяина. Считать его отчаянно нуждающимся в дровах — значит
            // заставить его выменивать на них последнюю еду
            if (res == "топливо" && !npc.топит_сам())
                d = 5.0;
        }
        else
            d = days.Value;
        double scarcity = d < 1.5 ? 3.2 : (d < 3 ? 2.0 : (d < 6 ? 1.3 : 0.8));
        double @base = res switch
        {
            "еда" => 1.0, "вода" => 0.85, "топливо" => 0.9,
            "лекарства" => 1.1, "материалы" => 0.55, "патроны" => 1.2,
            _ => 0.7,
        };
        double extra = 0.0;
        // хворь соседа — та, что видел; ребёнок — общее знание
        bool хворь = глазами is not null
            ? глазами.видит_хворь(npc.id)
            : npc.injuries.Count > 0 || npc.sick is not null;
        if (res == "лекарства" && (хворь || npc.dependents != 0))   // правда: общее знание: ребёнок на руках виден всем
            extra = 1.2;
        // аптечка в руках медика — инструмент, а не запас: ею лечат, и за это
        // платят. Пока это не считалось, медсестра на четвёртый день метели
        // меняла аптечки на доски. Та же мысль, что у патронов выше: вещь
        // стоит столько, сколько стоит то, что ею делают
        if (res == "лекарства" && npc.skills.Contains("медик", StringComparer.Ordinal))
        {
            var h = npc._h;
            extra = Math.Max(extra, h is not null ? h.B["аптечка_медику"] : 0.0);
        }
        if (res == "материалы" && npc.shelter.Взять("буржуйка", 0.0) == 0.0)
            extra = 0.9;
        return amount * (@base * scarcity + extra);
    }

    /// <summary>
    /// На сколько дней, по мнению a, хватит ресурса у target. Это и есть
    /// осведомлённость в деле: чем меньше a знает, тем ближе оценка
    /// к «наверное, как у всех».
    /// </summary>
    public static double believed_days(NPC a, NPC target, string res)
    {
        double сколько = a.believed(target.id, res);
        double за_день = (res switch { "еда" => 0.85, "вода" => 0.9, "топливо" => 1.0, _ => 1.0 })
                         * target.eaters();      // правда: общее знание: сколько ртов, знают все (ADR-9)
        double оценка = сколько / Math.Max(0.2, за_день);
        double c = a.confidence(target.id);
        // Чего не знаешь — то домысливаешь ПО СЕБЕ. Раньше здесь стояла
        // константа 4.0, и это была самая дорогая цифра в модели: порог
        // «сосед голодает» — 3.6 дня, то есть незнание само по себе читалось
        // как «у него на исходе». Мать двоих при том же незнании выглядела
        // вдвое голоднее всех и получала 91 % всей помощи в доме
        double наверное = a.days_of(res);
        return оценка * c + наверное * (1.0 - c);
    }
}
