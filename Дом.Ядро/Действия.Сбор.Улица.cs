// Перенос house/actions.py, `_улица`: четвёртый раздел сбора (GDD 20).
//
// Куртка, банкомат, своя кладовка и чужой замок, выход на улицу — один
// или вдвоём, — подброс к чужой двери и взгляд на площадку перед выходом.

namespace Дом.Ядро;

public static partial class Действия
{
    /// <summary>Раздел gather: улица — ближе и беднее или дальше и опаснее.</summary>
    public static void _улица(Корзина корзина, House h, NPC npc, Баланс b, Самочувствие с,
                              IReadOnlyList<NPC> соседи)
    {
        // утеплить куртку: в обычной городской одежде мороз к третьей неделе
        // запирает человека дома надёжнее любой двери. Руками куртку можно
        // только подбить: тулуп из подручного утеплителя не сошьёшь
        if (npc.одежда < b["одежда_шитьё_потолок"]
            && npc.stock.Взять("материалы", 0.0) >= b["одежда_материалы"])
        {
            // тем нужнее, чем ближе мороз к порогу выхода. Знак здесь был
            // перевёрнут, и оценка выходила наибольшей в самую тёплую погоду:
            // в первый день метели подбить куртку было лучшим, что человек
            // мог придумать за день
            double запас = h.outside - npc.мороз_предел(b);
            double s = Util.Clamp(3.0 - запас * 0.35, 0.0, 9.0);
            // нужда в куртке — от мороза, а срочность — от того, часто ли
            // человек выходит. Множитель, а не слагаемое
            s *= 0.5 + drive_наружу(npc);
            корзина.add("одежда", s);
        }

        // снять наличные, пока банк работает (GDD 18). Ровно один день на то,
        // чтобы превратить цифры на экране в бумагу, которую примут и завтра
        if (h.банки && npc.счёт >= 1.0 && h.банкомат >= 1.0)
        {
            double сколько = Math.Min(npc.счёт, Math.Min(b["банкомат_лимит"], h.банкомат));
            корзина.add("банкомат",
                1.4 + сколько * 0.22 - npc.stock.Взять("деньги", 0.0) * 0.05);
        }

        // своя кладовка — единственное место, куда можно сходить, не выходя
        // на улицу и не влезая в чужое; поэтому туда идут первым делом
        var к = Улица.выбрать_кладовую(h, npc, часов: npc.time_left);
        if (к is not null)
        {
            double s = drive_наружу(npc) * b["кладовая_тяга"]
                       + (1.0 - Util.Norm(с.еды_дней, 1, 7)) * 2.0
                       + Util.Clamp(Улица.сколько_поднимет(h, npc, к, b), 0.0, 8.0)
                         * b["кладовая_за_запас"];
            корзина.add("кладовая", s, к, часы: Улица.часы_кладовой(h, к));
        }

        // чужой замок в подвале: ступенька между разобранной пустой квартирой
        // и налётом. Судит человек об этом не по тому, что там лежит,
        // а по тому, что, по его сведениям, есть у хозяина
        var чужая = Улица.чужая_кладовая(h, npc, часов: npc.time_left);
        if (чужая is not null)
        {
            var хозяин = h.хозяин_кладовой(чужая);
            double s = нужда(npc) * b["кладовая_вскрытие_за_нужду"] + npc.вес_черт("разбор");
            if (хозяин is not null)
            {
                s += npc.loot_value(хозяин.id) * (0.3 + npc.t01("жадность") * 0.6);
                s += npc.hate.Взять(хозяин.id, 0.0) / 25.0;
                s -= npc.боится(хозяин.id) * b["страх_вес_кражи"];
            }
            // то же, чем меряется кража и разбор: пока улица кормит, замки не рвут
            s *= 1.0 - есть_куда_сходить(h, npc, завтра: true) * b["разбор_вес_улицы"];
            s -= b["кладовая_вскрытие_решимость"];
            s -= (1.0 - Конфликт.stealth(npc)) * 1.5;
            корзина.add("вскрыть_кладовую", s, чужая, часы: Улица.часы_вскрытия(h, чужая));
        }

        if (может_на_улицу(h, npc, b))
        {
            // за запасами идут не когда умирают, а когда боятся, что не хватит.
            // Куда идти, решается здесь же: пока место выбирали в execute,
            // «выходить ли» и «куда» были разными решениями, и второе
            // доставалось первому в наследство
            double Оценка_выхода(Место м)
            {
                double s = drive_наружу(npc) * 7.0 + (1.0 - Util.Norm(с.еды_дней, 1, 7)) * 3.0;
                s += npc.вес_черт("вылазка") - 1.5;
                s -= npc.dependents * 1.2;
                s -= Math.Max(0.0, (-h.outside - 20) * 0.12);
                s *= 1.0 - 0.25 * (h.опасность_множитель - 1.0);
                // и то, чего в этом решении не было вовсе: куда именно
                // он идёт. Плохое место должно проигрывать утеплению окон
                // и обмену, а не доставаться человеку по умолчанию
                return s + Util.Clamp(Улица.оценка_места(h, npc, м), -4.0, 4.0)
                           * b["вылазка_вес_места"];
            }

            var м = Улица.выбрать_место(h, npc, часов: npc.time_left);
            if (м is not null)
                корзина.add("вылазка", Оценка_выхода(м), м,
                            часы: Улица.минимум_часов(h, м), мерка: м.мерка);

            // и то же самое, но не одному. Из сорока шести дневных действий
            // это единственное, где двое делают одно дело. В магазин вдвоём
            // не зовут: там очередь, а не лёд и темнота
            var зовут = м is not null && !м.магазин
                ? м
                : Улица.выбрать_место(h, npc, часов: npc.time_left, без_магазина: true);
            if (зовут is not null && !не_ходит_сегодня(h, npc))
            {
                npc.зов_куда = зовут.имя;
                double опасность = Мир.outing_danger(h) * зовут.угроза;

                // кого звать — один вопрос, а не пять. Пока зов предлагался
                // каждому соседу отдельной строкой, пять почти одинаковых
                // вариантов перевешивали одиночную вылазку просто числом
                bool Позвать_можно(NPC t)
                    => !t.away && может_на_улицу(h, t, b)          // правда: видно: цел ли сосед и не хромает ли
                       && t.день_вылазки != h.day                  // правда: видно: сегодня уже вернулся с пакетами
                       && t.time_left >= Улица.минимум_часов(h, зовут)  // правда: видно: темнеет у обоих
                       && !npc.не_прощу.Contains(t.id)
                       && npc.ask_record(t.id).отказ_зов < h.day - 1;

                double Годится(NPC t) => npc.свой(t.id) - npc.боится(t.id) * 3.0;

                NPC? кого = null;
                foreach (var t in соседи)
                    if (Позвать_можно(t) && (кого is null || Годится(t) > Годится(кого)))
                        кого = t;
                if (кого is not null)
                {
                    double зов = Оценка_выхода(зовут);
                    зов += npc.предпочтение(кого.id, с.средний_свой) * b["зов_за_близость"];
                    зов += (тревога(h, npc) + опасность) * b["зов_вместе_смелее"];
                    зов -= npc.t01("жадность") * b["зов_за_жадность"];
                    зов -= npc.боится(кого.id) * b["страх_вес_контакта"];
                    зов -= b["зов_решимость"];
                    корзина.add("позвать", зов, кого, мерка: зовут.мерка,
                        часы: b.Таблица("часы_действий")["позвать"]
                              + Улица.минимум_часов(h, зовут));
                }
            }
        }

        // подброс — ход не к человеку, а к двери, и потому стоит отдельно
        // от цикла по соседям: класть надо к порогу врага, а увидят это все,
        // кто мимо ходит
        var з = npc.замысел;
        if (з is not null && з.вид == "рассорить" && !з.сегодня_спит
            && !string.IsNullOrEmpty(з.враг) && з.напор < Замыслы.осторожность(h, npc))
        {
            var враг = h.get(з.враг);
            string? чем = что_подбросить(h, npc);
            if (враг is not null && враг.здесь() && чем is not null)
            {
                // умный предпочитает подброс шёпоту: шёпот можно проверить
                // разговором с оболганным, а вещь у двери говорит сама
                double подброс = npc.hate.Взять(враг.id, 0.0) / 10.0
                                 + npc.t01("сообразительность") * b["подброс_за_ум"]
                                 - з.напор * b["шепнуть_осторожность"]
                                 - b["подброс_решимость"];
                корзина.add("подбросить", подброс, враг);
            }
        }

        // проверить площадку, прежде чем выйти. Дешёвое действие человека,
        // у которого есть причина опасаться. Раньше жертва вчерашней осады
        // выходила за дровами ровно так же, как выходила до неё
        double боязно = 0.0;
        foreach (var o in h.others(npc))
            боязно = Math.Max(боязно, npc.боится(o.id));
        bool есть_счёты = h.others(npc).Any(o => npc.враждует(o.id, b["обида_порог_вражды"]));
        // и третья причина посмотреть, прежде чем выйти: то, как человек сам
        // выглядит. Тот, кто осунулся и хромает, знает, что на лестнице его
        // видят таким же
        double кажусь = npc.каким_кажусь();
        if ((боязно > b["лестница_порог_страха"] || есть_счёты
             || кажусь > b["лестница_порог_вида"])
            && h.сутки.смотрел_лестницу.Взять(npc.id, int.MinValue) != h.day)
        {
            double осторожно = боязно * b["лестница_за_страх"]
                               + (есть_счёты ? b["лестница_за_счёты"] : 0.0)
                               + кажусь * b["лестница_за_вид"]
                               + npc.вес_черт("дежурить") * 0.3;
            корзина.add("лестница", осторожно, null);
        }
    }

    /// <summary>
    /// Что у него есть такого, что бросит тень на хозяина двери. Две вещи,
    /// и обе говорят сами за себя: кусок тела и чужая вещь.
    /// </summary>
    public static string? что_подбросить(House h, NPC npc)
    {
        if (npc.stock.Взять("мясо", 0.0) >= 1)
            return "мясо";
        // в доме, где — как он сам знает — вещи начали пропадать, чужая
        // аптечка под дверью говорит сама за себя. Знает по своей памяти,
        // а не по счётчику дома
        if (npc.stock.Взять("лекарства", 0.0) >= 1 && npc.знает_о_кражах())
            return "лекарства";
        return null;
    }

    /// <summary>
    /// Пустит ли этого человека на улицу его собственное тело и мороз.
    /// Отдельной функцией: зов на вылазку задаёт этот вопрос дважды —
    /// про того, кто зовёт, и про того, кого зовут.
    /// </summary>
    public static bool может_на_улицу(House h, NPC npc, Баланс b)
        => npc.health > 45 && npc.warmth > 32 && npc.injuries.Count < 2
           && npc.sick is null && h.outside > npc.мороз_предел(b);

    /// <summary>Тот, кто увидел на площадке чужого, сегодня из квартиры
    /// не выходит.</summary>
    public static bool не_ходит_сегодня(House h, NPC npc)
        => h.сутки.не_выходить.Взять(npc.id, int.MinValue) == h.day;

    /// <summary>
    /// Согласится ли второй пойти на вылазку вместе. Решает он. Зов устроен
    /// как переезд: один предлагает, другой отвечает, и отказ — такой же
    /// настоящий исход, как согласие.
    /// </summary>
    public static double пойдёт_вдвоём(House h, NPC зовущий, NPC второй, Место м, Баланс b)
    {
        if (!второй.здесь() || второй.away)
            return 0.0;
        if (не_ходит_сегодня(h, второй))
            return 0.0;
        if (!может_на_улицу(h, второй, b))
            return 0.0;
        if (!Улица.место_доступно(h, второй, м, часов: второй.time_left))
            return 0.0;
        if (used_day(h, второй, "вылазка") >= b.Таблица("лимит_в_день").Взять("вылазка", 99))
            return 0.0;
        // с тем, кого списал со счетов, за угол дома не ходят
        if (второй.не_прощу.Contains(зовущий.id)
            || второй.hate.Взять(зовущий.id, 0.0) >= 55)
            return 0.0;

        double да = drive_наружу(второй) * b["зов_согласие_за_нужду"];
        да += Util.Clamp(Улица.оценка_места(h, второй, м), -4.0, 4.0) * b["вылазка_вес_места"];
        да += второй.вес_черт("вылазка");
        // и то, ради чего это вообще предлагают: вдвоём на улице не так
        // страшно, и страшнее всего это в те дни, когда во дворе уже отнимали
        да += (тревога(h, второй) + Мир.outing_danger(h) * м.угроза) * b["зов_вместе_смелее"];
        // с кем идти. Близость решает больше доверия: полдня на льду проводят
        // не с тем, кто честен, а с тем, кто свой
        да += второй.свой(зовущий.id) * b["зов_за_близость_второго"];
        да += (второй.trust.Взять(зовущий.id, 3.0) - 3.0) * 0.35;
        да -= второй.боится(зовущий.id) * b["страх_вес_контакта"];
        да -= Math.Max(0.0, (-h.outside - 20) * 0.12);
        // чужой замок — его собственный поступок, и мерка у него своя
        var (запрет, склонность) = Характер.мерка_поступка(второй, м.мерка, b);
        да = (да - запрет) * (1.0 + склонность) * Характер.norm_gate(второй, м.мерка, b);
        return да - b["зов_согласие"];
    }
}
