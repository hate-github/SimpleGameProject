// Что переносится между жизнями — и больше ничего.
//
// ГДД 8 называет ровно три вещи и объявляет это стержнем баланса: очки
// навыков, память, инвентарь как пустое пространство. Не переносятся
// предметы, деньги, отношения с соседями, состояние убежища; NPC не помнят
// ничего. Правило простое и держать его надо буквально — потому что любая
// четвёртая вещь, «которую же логично сохранить», убивает смысл второй
// жизни: она перестаёт быть новой.
//
// Отсюда устройство: `Наследие` — единственное, что живёт дольше дома,
// и всё, чего в нём нет, начинается с нуля каждый раз. Дом об этом классе
// не знает вовсе: он читает наследие, а не наоборот.

namespace Дом.Ядро;

/// <summary>Три навыка (ГДД 8.1). Уровней у каждого пять; на третьем
/// и выше соответствующие мини-игры исчезают — но это этап 5,
/// а пока навык только копится.</summary>
public enum Навык
{
    ФИЗИКА,             // вес в руках, скорость работы, шанс в бою
    УСТОЙЧИВОСТЬ,       // холод, голод и жажда на морозе
    СМЕКАЛКА,           // щиток, генератор, камера; скрытые реплики
}

/// <summary>
/// Откуда взялась запись в телефоне. Вид, а не свободный текст: по нему
/// экран решает, куда её положить и чем подсветить, а проверка — что
/// запись вообще могла появиться.
/// </summary>
public enum ВидЗаписи
{
    МОЯ_СМЕРТЬ,         // чем кончилась прошлая жизнь
    УБИЙЦА,             // кто меня убил
    СМЕРТЬ_СОСЕДА,      // кто умер и от чего — из того, что я знаю
    ЗАПАС,              // у кого что есть — по моей оценке, не по правде
    ПОМОГ,              // кто мне давал
    ОТКАЗАЛ,            // кто не открыл
    ВОР,                // кого назвали вором
    НАДПИСЬ,            // граффити пророка, увиденное на вылазке (ГДД 11)
}

/// <summary>
/// Заметка в телефоне (ГДД 10).
///
/// Пишется <b>из знания игрока</b>, а не из правды мира. Это не вежливость
/// к архитектуре: телефон, в который дом складывает всё, что случилось,
/// отдаёт игроку то, чего не знает ни один NPC, — и вся игра про догадки
/// перестаёт быть игрой. Поэтому источник записи всегда один из двух:
/// собственная память героя (`NPC.memory`) или событие, в котором он сам
/// участвовал.
/// </summary>
public sealed record ЗаписьПамяти(
    int жизнь,
    int день,
    ВидЗаписи вид,
    string? кто,            // id соседа, если запись о нём
    int? где,               // номер квартиры, если запись о месте
    string текст);

/// <summary>
/// Отголосок (ГДД 10): вспышка образа из прошлой жизни в том месте,
/// где что-то случилось.
///
/// Игра не объясняет, что это. Игрок сам вспоминает — или не вспоминает.
/// </summary>
public sealed record Отголосок(
    int квартира,
    int жизнь,
    string текст);

/// <summary>
/// Всё, что переживает смерть. «Частичка души», как это описано изнутри
/// мира (ГДД 3): память, навыки и карман вне времени.
/// </summary>
public sealed class Наследие
{
    /// <summary>Нерастраченные очки навыков.</summary>
    public int очки { get; set; }

    /// <summary>Уровни по навыкам, 0…5.</summary>
    public Словарь<Навык, int> уровни { get; } = new();

    /// <summary>Сколько места в кармане вне времени. Содержимое
    /// не переносится <b>никогда</b> — только сам объём (ГДД 8, 9).</summary>
    public int карман { get; set; } = 4;

    /// <summary>Заметки телефона, старые первыми.</summary>
    public List<ЗаписьПамяти> записи { get; } = new();

    /// <summary>Отголоски по местам.</summary>
    public List<Отголосок> отголоски { get; } = new();

    /// <summary>Скрытая шкала (ГДД 11). Числом игроку не показывается
    /// никогда — только через монолог, реплики и доступные действия.</summary>
    public double рассудок { get; set; }

    /// <summary>Сколько жизней уже прожито.</summary>
    public int жизней { get; set; }

    /// <summary>Лучшая прожитая жизнь в днях: от неё считаются очки
    /// начиная с третьей (ГДД 8.2).</summary>
    public int рекорд { get; set; }

    /// <summary>Слово пророка введено — петля идёт в «нирване»
    /// (ГДД 11). Рассудок при этом зафиксирован.</summary>
    public bool нирвана { get; set; }

    /// <summary>
    /// Видел ли он хоть одну надпись пророка.
    ///
    /// Отдельным полем, а не выводом из записей: записи обрезаются
    /// (`записей_помнить`), и надпись, увиденная на первой жизни, к десятой
    /// вымылась бы из журнала вместе со знанием слова. Увидел однажды —
    /// помнишь всегда.
    /// </summary>
    public bool знает_слово { get; set; }

    /// <summary>Уровень навыка: ноль, если ни разу не поднимали.</summary>
    public int Уровень(Навык н) => уровни.Взять(н, 0);

    /// <summary>
    /// Поднять навык, если хватает очков.
    ///
    /// Тратит игрок, а не игра: очки копятся сами, а во что их вложить —
    /// решение, и отбирать его нельзя.
    /// </summary>
    public bool Поднять(Навык н, РучкиПетли ручки)
    {
        int было = Уровень(н);
        if (было >= (int)ручки["уровней_навыка"])
            return false;
        int цена = (int)ручки["очков_на_уровень"];
        if (очки < цена)
            return false;
        очки -= цена;
        уровни[н] = было + 1;
        return true;
    }
}
