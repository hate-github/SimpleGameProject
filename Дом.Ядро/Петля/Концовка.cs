// Девять концовок (ГДД 22).
//
// Финальная заставка собирается из того, кто дожил и в каком состоянии дом.
// Ни одна из девяти не выбирается вручную и ни одна не подпёрта флагом:
// все они — прочтение того, что от метели осталось.
//
// Порядок важен, потому что условия перекрываются. «Тёмная» — это тоже
// «игрок дожил», и «Одиночка» — тоже; разбирать их надо от частного
// к общему, иначе дом, который герой вырезал сам, отчитается «домом,
// который выстоял». Порядок здесь и есть содержание.
//
// Норма, к которой это калибруется (ГДД 22): из пятнадцати жильцов метель
// переживает около двух с половиной. Значит «Дом выстоял» и «Все живы» —
// концовки почти недостижимые, а «Последние» — обычная. Так и задумано:
// заставка, которая выпадает каждый раз, ничего не значит.

namespace Дом.Ядро;

/// <summary>Девять концовок ГДД 22.</summary>
public enum Концовка
{
    СМЕРТЬ,             // герой погиб — переход в новую жизнь
    ДОМ_ЗАМЁРЗ,         // не дожил никто
    ДОМ_ВЫСТОЯЛ,        // дожил игрок и большинство соседей
    ПОСЛЕДНИЕ,          // дожили игрок и ещё несколько
    ОДИНОЧКА,           // герой пережил метель один, дом опустел
    ВСЕ_ЖИВЫ,           // почти невозможная
    ТЁМНАЯ,             // герой дожил, перебив дом
    ПЕРЕСТАЛ_ВОЗВРАЩАТЬСЯ,  // точка невозврата рассудка
    НИРВАНА,            // слово введено, петля продолжается иначе
}

/// <summary>Чем кончилась метель и почему именно так.</summary>
public sealed record Развязка(
    Концовка какая,
    string имя,
    string почему,
    int дожило,
    int всего,
    int убил_сам);

public static class Концовки
{
    /// <summary>
    /// Прочесть концовку по дому.
    ///
    /// Читается уже прожитый дом — ничего не решается и не ставится.
    /// </summary>
    public static Развязка Какая(House h, string кто, Наследие наследие,
                                 РучкиПетли ручки)
    {
        var я = h.people[кто];
        int всего = h.people.Ключи.Count();
        int дожило = h.people.Значения.Count(p => p.здесь());
        int соседей_дожило = дожило - (я.здесь() ? 1 : 0);
        int убил = h.события.Count(
            с => с.вид == ВидСобытия.УБИЙСТВО
                 && string.Equals(с.кто, я.id, StringComparison.Ordinal));

        Развязка Р(Концовка к, string имя, string почему)
            => new(к, имя, почему, дожило, всего, убил);

        // ---- рассудок раньше всего: он обрывает петлю, а не жизнь ----
        if (наследие.нирвана)
            return Р(Концовка.НИРВАНА, "Нирвана",
                     "слово названо; рассудок больше не меняется");
        if (Рассудок.Где(наследие.рассудок, ручки) == Порог.НЕВОЗВРАТ)
            return Р(Концовка.ПЕРЕСТАЛ_ВОЗВРАЩАТЬСЯ, "Он перестал возвращаться",
                     "рассудок дошёл до точки невозврата");

        // ---- герой не дожил ----
        if (!я.здесь())
            return дожило == 0
                ? Р(Концовка.ДОМ_ЗАМЁРЗ, "Дом замёрз",
                    "не дожил никто: дом, который не сумел договориться")
                : Р(Концовка.СМЕРТЬ, "Смерть",
                    $"{я.cause}; в доме осталось {дожило} из {всего}");

        // ---- герой дожил; дальше от частного к общему ----
        if (убил >= (int)ручки["тёмная_убийств"])
            return Р(Концовка.ТЁМНАЯ, "Тёмная",
                     $"дожил, убив {убил} — дом пережил не метель, а его");
        if (дожило == всего)
            return Р(Концовка.ВСЕ_ЖИВЫ, "Все живы",
                     "метель не забрала никого");
        if (соседей_дожило == 0)
            return Р(Концовка.ОДИНОЧКА, "Одиночка",
                     "дом опустел, а он остался");
        if (дожило >= всего * ручки["выстоял_доля"])
            return Р(Концовка.ДОМ_ВЫСТОЯЛ, "Дом выстоял",
                     $"дожили {дожило} из {всего}: дом договорился");
        return Р(Концовка.ПОСЛЕДНИЕ, "Последние",
                 $"их осталось {дожило}");
    }

    /// <summary>Кого показывать на заставке: тех, кто дожил, — и только их
    /// («заставка только с ними», ГДД 22).</summary>
    public static IReadOnlyList<string> Кто_остался(House h)
        => h.people.Значения
            .Where(p => p.здесь())
            .OrderBy(p => p.apt)
            .Select(p => p.@short)
            .ToList();
}
