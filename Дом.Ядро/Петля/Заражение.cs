// Заражение с «Вектора-3» (задание автора, пп. 6–7).
//
// Законсервированное предприятие, где делали биологическое оружие
// на сибирской язве; метель нарушила консервацию, и часть корпусов
// промзоны опасна. Болезнь идёт три-пять дней и убивает всегда — так
// в задании. Не мгновенный конец игры, а стадии, и по ним видно, что
// происходит: здоров → задет → заражён → болен → тяжело → мёртв
// (Safe, Exposed, Infected, Sick, Critical, Dead).
//
//   · **задеть** можно в промзоне (`Промзона`): кто знает, какие корпуса
//     обходить (рассказ Аркадия), задевается реже, но и находит меньше;
//   · задетый наутро заболевает с шансом, иначе обошлось;
//   · стадии держатся по нескольку дней (`дней`, от и до), больной и тяжёлый
//     теряют здоровье каждый день, в конце — смерть, общей смертью дома
//     (`Конфликт.умер`): свидетели, память, дом пустеет, как от всякой смерти;
//   · **больной заразен**: кто за день встречался с ним лицом к лицу —
//     пришёл к его двери, он пришёл к нему, живут под одной крышей, —
//     задет с шансом. Так болезнь и ходит между героем и соседями.
//     Встреча — дело, в котором ядро само сводит двоих лицом к лицу
//     (`Социальное.встретились`: разговор, мена, просьба, помощь, отъём),
//     а не любое дело «про соседа»: присматриваться к квартире или
//     обокрасть пустую — не встреча;
//   · **больной слёг** (`на_ногах`): после каждого своего дела он на ногах
//     не дольше своей доли дня — больной полдня, тяжёлый встал, поел
//     и лёг. Без этого кашляющий кровью весь день ходил по квартирам,
//     и одна вылазка героя в промзону выкашивала дом за две недели.
//
// Броски — своим генератором от зерна мира, человека и дня, мимо `h.rng`.
// Встречи записывает наблюдатель исполнения (ничего не меняет); сама
// болезнь идёт в конце дня, на `on_day`, — это не наблюдатель, а часть
// мира героя, и в прогоне без игрока её нет вовсе: округа заводится
// только в игре.

using System.Text;
using System.Text.Json;

namespace Дом.Ядро;

/// <summary>Стадия болезни — как в задании: Safe, Exposed, Infected, Sick, Critical, Dead.</summary>
public enum Стадия { ЗДОРОВ, ЗАДЕТ, ЗАРАЖЁН, БОЛЕН, ТЯЖЕЛО, МЁРТВ }

/// <summary>Болезнь человека: стадия, с какого дня и до какого она держится.</summary>
public sealed record Болезнь(Стадия стадия, int с_дня, int до_дня);

/// <summary>Числа болезни из `data/мир.json`, «заражение».</summary>
public sealed record ДанныеЗаражения(
    double задетый_заболеет,
    IReadOnlyDictionary<Стадия, (int от, int до)> дней,
    IReadOnlyDictionary<Стадия, double> урон,
    double передача,
    double промзона_часов, double задеть, double задеть_зная,
    IReadOnlyDictionary<string, (int от, int до)> находка,
    IReadOnlyDictionary<Стадия, double> на_ногах)
{
    public static readonly ДанныеЗаражения НИКАКОГО = new(0.0,
        new Dictionary<Стадия, (int, int)>(), new Dictionary<Стадия, double>(), 0.0, 0.0, 0.0, 0.0,
        new Dictionary<string, (int, int)>(StringComparer.Ordinal), new Dictionary<Стадия, double>());

    public static ДанныеЗаражения Прочитать(JsonElement з)
    {
        var дней = new Dictionary<Стадия, (int, int)>();
        foreach (var п in з.GetProperty("дней").EnumerateObject())
        {
            var пара = п.Value.EnumerateArray().Select(x => x.GetInt32()).ToList();
            дней[Стадия_(п.Name)] = (пара[0], пара[1]);
        }
        var урон = new Dictionary<Стадия, double>();
        foreach (var п in з.GetProperty("урон").EnumerateObject())
            урон[Стадия_(п.Name)] = п.Value.GetDouble();
        var пз = з.GetProperty("промзона");
        var находка = new Dictionary<string, (int, int)>(StringComparer.Ordinal);
        foreach (var п in пз.GetProperty("находка").EnumerateObject())
        {
            var пара = п.Value.EnumerateArray().Select(x => x.GetInt32()).ToList();
            находка[п.Name] = (пара[0], пара[1]);
        }
        var на_ногах = new Dictionary<Стадия, double>();
        if (з.TryGetProperty("на_ногах", out var нн))
            foreach (var п in нн.EnumerateObject())
            {
                double доля = п.Value.GetDouble();
                if (доля < 0.0 || доля > 1.0)
                    throw new InvalidDataException($"мир.json: «на_ногах» у «{п.Name}» — доля дня, от 0 до 1, а не {доля}");
                на_ногах[Стадия_(п.Name)] = доля;
            }
        foreach (var с in new[] { Стадия.ЗАРАЖЁН, Стадия.БОЛЕН, Стадия.ТЯЖЕЛО })
            if (!дней.TryGetValue(с, out var д) || д.Item1 < 1 || д.Item2 < д.Item1)
                throw new InvalidDataException($"мир.json: у стадии «{с}» нужно дней от и до, не меньше одного");
        return new ДанныеЗаражения(з.GetProperty("задетый_заболеет").GetDouble(), дней, урон,
            з.GetProperty("передача").GetDouble(),
            пз.GetProperty("часов").GetDouble(), пз.GetProperty("задеть").GetDouble(),
            пз.GetProperty("задеть_зная").GetDouble(), находка, на_ногах);
    }

    private static Стадия Стадия_(string имя) => имя switch
    {
        "задет" => Стадия.ЗАДЕТ,
        "заражён" => Стадия.ЗАРАЖЁН,
        "болен" => Стадия.БОЛЕН,
        "тяжело" => Стадия.ТЯЖЕЛО,
        _ => throw new InvalidDataException($"мир.json: стадии «{имя}» нет"),
    };
}

/// <summary>Чем кончился поход в промзону: сколько ходил, что нашёл, задело ли.</summary>
public sealed record Промзона(double часы, Словарь<string, double> нашёл, Словарь<string, double> унёс,
                              bool задело, bool знал);

/// <summary>Болезнь в доме — часть округи героя.</summary>
public sealed class Заражение
{
    /// <summary>
    /// Дела лицом к лицу — ровно те, чьи исполнители зовут
    /// `Социальное.встретились`. Список сверяет проверка «заражение
    /// и знатоки» с исходниками исполнителей в обе стороны.
    /// </summary>
    public static readonly IReadOnlySet<string> ЛИЦОМ_К_ЛИЦУ = new HashSet<string>(StringComparer.Ordinal)
    {
        "разговор", "обмен", "поделиться", "попросить", "вернуть", "лечить", "шепнуть", "отнять",
    };

    private readonly ДанныеЗаражения _д;
    private readonly long _зерно;
    private readonly Dictionary<string, Болезнь> _болезни = new(StringComparer.Ordinal);
    private readonly HashSet<(string, string)> _встречи = new();
    private int _посчитан_день = -1;

    public Заражение(ДанныеЗаражения д, long зерно)
    {
        _д = д;
        _зерно = зерно;
    }

    public ДанныеЗаражения данные => _д;

    /// <summary>Стадия человека сейчас.</summary>
    public Стадия Стадия(string кто) => _болезни.TryGetValue(кто, out var б) ? б.стадия : Ядро.Стадия.ЗДОРОВ;

    /// <summary>Болезни всех, кто не здоров, — для проверок и подсказок.</summary>
    public IReadOnlyDictionary<string, Болезнь> болезни => _болезни;

    /// <summary>Заразен ли: болен или тяжело.</summary>
    public bool Заразен(string кто) => Стадия(кто) is Ядро.Стадия.БОЛЕН or Ядро.Стадия.ТЯЖЕЛО;

    /// <summary>Задеть: здорового — да, прочих — уже поздно.</summary>
    public bool Задеть(string кто, int день)
    {
        if (Стадия(кто) != Ядро.Стадия.ЗДОРОВ)
            return false;
        _болезни[кто] = new Болезнь(Ядро.Стадия.ЗАДЕТ, день, день + 1);
        return true;
    }

    /// <summary>Двое встретились лицом к лицу — запомнить до конца дня.</summary>
    public void Встретились(string а, string б)
    {
        if (string.Equals(а, б, StringComparison.Ordinal))
            return;
        _встречи.Add(string.CompareOrdinal(а, б) < 0 ? (а, б) : (б, а));
    }

    /// <summary>
    /// Больной слёг: после своего дела он на ногах не дольше своей доли
    /// дня (`на_ногах`), остальное — лёжа. День кончается раньше: дом
    /// больше не даёт ему хода до утра.
    /// </summary>
    public void Слечь(House h, NPC p)
    {
        if (!_д.на_ногах.TryGetValue(Стадия(p.id), out var доля))
            return;
        double день = h.B["часов_бодрствования"];
        double прожито = день - p.time_left;
        p.time_left = Math.Max(0.0, Math.Min(p.time_left, день * доля - прожито));
    }

    /// <summary>Подписаться на дом: встречи — наблюдателем исполнения;
    /// болезнь — в конце каждого дня.</summary>
    public void Слушать(House h)
    {
        h.hooks.after_execute.Add((дом, npc, ключ, цель, _, _) =>
        {
            if (цель is NPC t && ЛИЦОМ_К_ЛИЦУ.Contains(ключ))
                Встретились(npc.id, t.id);
            Слечь(дом, npc);
        });
        h.hooks.on_day.Add(дом => Конец_дня(дом));
    }

    /// <summary>
    /// Конец дня: сперва передача по встречам (и тем, кто под одной крышей
    /// с больным), потом стадии — на завтра, урон и смерти. Дважды за день
    /// не идёт.
    /// </summary>
    public void Конец_дня(House h)
    {
        if (h.day == _посчитан_день)
            return;
        _посчитан_день = h.day;
        int день = h.day;
        // передача: встречи дня и общая крыша
        var пары = _встречи.ToList();
        foreach (var а in h.alive())
            foreach (var б in h.alive())
                if (string.CompareOrdinal(а.id, б.id) < 0 && h.под_одной_крышей(а, б))
                    пары.Add((а.id, б.id));
        foreach (var (а, б) in пары.Distinct().OrderBy(п => п.Item1, StringComparer.Ordinal)
                                   .ThenBy(п => п.Item2, StringComparer.Ordinal))
        {
            if (Заразен(а) && Бросок("передача", б, день) < _д.передача)
                Задеть(б, день);
            else if (Заразен(б) && Бросок("передача", а, день) < _д.передача)
                Задеть(а, день);
        }
        _встречи.Clear();
        // стадии: кто дожил до конца своей — дальше
        foreach (var (кто, б) in _болезни.OrderBy(п => п.Key, StringComparer.Ordinal).ToList())
        {
            var p = h.get(кто);
            if (p is null || !p.alive || б.стадия == Ядро.Стадия.МЁРТВ)
                continue;
            if (б.стадия is Ядро.Стадия.БОЛЕН or Ядро.Стадия.ТЯЖЕЛО
                && _д.урон.TryGetValue(б.стадия, out var урон))
                p.health = Math.Max(1.0, p.health - урон);
            if (день + 1 < б.до_дня)
                continue;
            var дальше = б.стадия switch
            {
                Ядро.Стадия.ЗАДЕТ => Бросок("заболеет", кто, день) < _д.задетый_заболеет
                    ? Ядро.Стадия.ЗАРАЖЁН : Ядро.Стадия.ЗДОРОВ,
                Ядро.Стадия.ЗАРАЖЁН => Ядро.Стадия.БОЛЕН,
                Ядро.Стадия.БОЛЕН => Ядро.Стадия.ТЯЖЕЛО,
                _ => Ядро.Стадия.МЁРТВ,
            };
            if (дальше == Ядро.Стадия.ЗДОРОВ)
            {
                _болезни.Remove(кто);
                continue;
            }
            if (дальше == Ядро.Стадия.МЁРТВ)
            {
                _болезни[кто] = new Болезнь(Ядро.Стадия.МЁРТВ, день + 1, int.MaxValue);
                Конфликт.умер(h, p, "болезнь с «Вектора»",
                              строка: $"{p.@short} {Util.Vb(p.sex, "умер")} — жар, кровь в кашле, три дня, и всё.");
                continue;
            }
            var (от, до) = _д.дней.TryGetValue(дальше, out var д) ? д : (1, 1);
            int держится = от + (int)Math.Floor(Бросок("дней", кто, день) * (до - от + 1));
            _болезни[кто] = new Болезнь(дальше, день + 1, день + 1 + держится);
        }
    }

    /// <summary>
    /// Поход в промзону: часы уходят, находка ложится в тару (что не влезло —
    /// там и осталось), и может задеть — реже, если знаешь, какие корпуса
    /// обходить. Только пока дом спит на вопросе.
    /// </summary>
    public Промзона В_промзону(House h, NPC я, bool знаю_корпуса, РучкиПетли ручки,
                               bool тратить = true)
    {
        // часы — здесь или уже ушли делом, кусками (`тратить: false`)
        double часы = Math.Min(_д.промзона_часов, тратить ? я.time_left : _д.промзона_часов);
        if (тратить)
            я.time_left -= часы;
        var нашёл = Словари.Числа();
        int i = 0;
        foreach (var (что, (от, до)) in _д.находка.OrderBy(п => п.Key, StringComparer.Ordinal))
        {
            // кто обходит опасные корпуса, берёт вдвое меньше
            double сколько = от + Math.Floor(Бросок("находка" + i++, я.id, h.day) * (до - от + 1));
            if (знаю_корпуса)
                сколько = Math.Floor(сколько / 2.0);
            if (сколько > 0)
                нашёл[что] = сколько;
        }
        var унёс = Словари.Числа();
        if (нашёл.Ключи.Count > 0)
        {
            я.ноша ??= new Ноша();
            var тара = я.ноша.тара ?? Тара.РЮКЗАК;
            унёс = я.ноша.Положить(тара, нашёл, ручки);
            foreach (var р in унёс.Ключи)
                h.stats["принесено_" + р] = h.stats.Взять("принесено_" + р, 0.0) + унёс[р];
        }
        bool задело = Бросок("промзона", я.id, h.day) < (знаю_корпуса ? _д.задеть_зная : _д.задеть)
                      && Задеть(я.id, h.day);
        return new Промзона(часы, нашёл, унёс, задело, знаю_корпуса);
    }

    /// <summary>Бросок от зерна мира, повода, человека и дня: мимо `h.rng`,
    /// и в одном мире — один ответ.</summary>
    private double Бросок(string повод, string кто, int день)
    {
        ulong h = 14695981039346656037UL;
        foreach (byte b in BitConverter.GetBytes(_зерно).Concat(BitConverter.GetBytes(день))
                                  .Concat(Encoding.UTF8.GetBytes(повод + "|" + кто)))
        {
            h ^= b;
            h *= 1099511628211UL;
        }
        return new Rng((long)(h & 0x7fffffffffffffffUL)).Random();
    }
}
