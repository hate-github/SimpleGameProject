// Телефон героя (ГДД 19): «заряд телефона — ресурс»; «развлечения — одна
// кнопка „провести время“ (восстанавливает настроение, тратит время и заряд)»;
// «после дня 0 связь деградирует … к дню 10 сеть исчезает совсем».
//
// Сеть — у дома: `House.network` (0…1) тает сама к «день_потери_связи», и по ней
// же соседи слышат чат (`Чат.cs`). Здесь от неё только палки на экране.
//
// Заряд — у героя, в процентах. Сам по себе телефон садится медленно, в руке —
// быстро; там, где есть свет, заряжается (у розетки — дома, пока в доме свет
// или работает свой генератор: `House.powered`; решает это движок, он знает,
// где герой стоит). Считается по часам героя от прошлой сверки: ночь, перемотка,
// любой пропуск — одним куском, по тому, у розетки ли он сейчас. Часы пошли
// назад (новая жизнь, загрузка) — только запомнить, где они.
//
// Сел — в телефоне остаются только мысли: это голова героя, а не приложение
// (вопрос дня переехал в телефон как способ показать мысли, а не как ещё одна
// программа). Чата, заметок, сервисов и «провести время» без заряда нет.
//
// Всё это — только у игрока, в его округе (`Округа.телефон`), мимо дома
// и снимка; пишется в сохранение игры вместе с округой.

using System.Text.Json.Nodes;

namespace Дом.Ядро;

public sealed class Телефон
{
    /// <summary>Заряд, проценты: 0 — сел, 100 — полный.</summary>
    public double заряд { get; private set; } = 100.0;

    /// <summary>Часы героя (день × 24 + час) прошлой сверки; null — сверки
    /// ещё не было.</summary>
    private double? _сверено;

    public bool сел => заряд <= 0.0;

    /// <summary>Сколько часов этой жизни герой провёл в телефоне: ГДД 11 —
    /// «что удерживает: … музыка/развлечения с телефона» (`Рассудок.Вклады`).</summary>
    public double часов_провёл { get; private set; }

    /// <summary>
    /// Часы героя от начала: день пролога (−2, −1) или метели (1, 2, …) и час.
    /// Метель начинается назавтра после последнего дня пролога, а дни метели
    /// считаются с единицы — поэтому её день сдвинут на один. Без сдвига между
    /// последней ночью пролога и первым утром метели пропадали сутки, и телефон
    /// встречал метель севшим (нашла проба через MCP).
    /// </summary>
    public static double Часы(int? день_пролога, int день_метели, double час)
        => (день_пролога ?? день_метели - 1) * 24.0 + час;

    /// <summary>Сколько палок сети показать: 0–4 по `House.network`.</summary>
    public static int Палок(double сеть)
        => сеть <= 0.0 ? 0 : Math.Clamp((int)Math.Ceiling(сеть * 4.0 - 1e-9), 1, 4);

    /// <summary>
    /// Сверить заряд к часам героя <paramref name="сейчас"/> (день × 24 + час):
    /// у розетки — заряжается, иначе садится, в руке — быстрее.
    /// </summary>
    public void Сверить(double сейчас, bool у_розетки, bool в_руке, РучкиПетли ручки)
    {
        if (_сверено is not double было || сейчас <= было)
        {
            _сверено = сейчас;
            return;
        }
        double часов = сейчас - было;
        _сверено = сейчас;
        заряд = у_розетки
            ? Math.Min(100.0, заряд + часов * ручки["телефон_заряд_в_час"])
            : Math.Max(0.0, заряд - часов * (в_руке ? ручки["телефон_разряд_в_руке_в_час"]
                                                     : ручки["телефон_разряд_в_час"]));
    }

    /// <summary>
    /// «Провести время» (ГДД 19): час героя, заряд — за настроение. Сел или
    /// заряда на это не хватит — нельзя, и ничего не меняется. Часы тратит
    /// зовущий (`Сделано.часов`), как у прочих дел на месте.
    /// </summary>
    public Сделано Провести_время(NPC я, РучкиПетли ручки)
    {
        double нужно = ручки["телефон_провести_время_заряд"];
        if (сел)
            return new Сделано(false, 0.0, "телефон сел — зарядить можно дома, пока есть свет");
        if (заряд < нужно)
            return new Сделано(false, 0.0, $"заряда {Текст.G(Math.Floor(заряд))}% — на это не хватит");
        заряд -= нужно;
        я.mood = Util.Clamp(я.mood + ручки["телефон_провести_время_настроение"]);
        часов_провёл += ручки["телефон_провести_время_часов"];
        return new Сделано(true, ручки["телефон_провести_время_часов"],
                           "посидел в телефоне — немного отпустило");
    }

    public JsonObject Сложить() => new() { ["заряд"] = заряд, ["провёл"] = часов_провёл };

    /// <summary>Поднять из сохранения; в старом сейве телефона нет — полный.</summary>
    public void Разложить(JsonObject? о)
    {
        заряд = о?["заряд"] is { } з ? Math.Clamp(з.GetValue<double>(), 0.0, 100.0) : 100.0;
        часов_провёл = о?["провёл"] is { } п ? Math.Max(0.0, п.GetValue<double>()) : 0.0;
        _сверено = null;
    }
}
