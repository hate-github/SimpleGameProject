// Мини-игры (ГДД 7): «все значимые действия… имеют шанс успеха, зависящий
// от навыков и состояния. Действия сгруппированы в четыре категории, у каждой
// одна короткая (3–7 секунд) мини-игра»; «при достаточном уровне навыка
// мини-игра не запускается — действие выполняется автоматически. Это главная
// осязаемая награда за прокачку» (ГДД 8.1: на уровне 3+ соответствующие
// мини-игры исчезают).
//
// Здесь — правила, общие для всех четырёх; сама игра (что на экране и как
// мерить) — в движке, и отдаёт она одно число: **качество** от нуля
// до единицы. Половина — «сыграно как обычно»: шанс остаётся прежним,
// и всё, что раньше бросалось без мини-игры, бросается бросок в бросок
// как раньше. Хуже — шанс ниже и шумнее (провал «Взлома» по ГДД — шум),
// лучше — выше.
//
// Какой навык снимает какую игру (ГДД 8.1): «Взлом» и «Разговор» —
// Смекалка, «Физическая работа» — Физика, «Ремонт» (на улице) —
// Устойчивость. До третьего уровня навык расширяет зону — играть легче;
// с третьего игры нет, и качество «само» растёт с уровнем.
//
// Первой сделан «Взлом» — у него уже есть провал в мире: замки кладовых,
// гермодверь бункера, решётка камеры, всё на стороне игрока. «Ремонт»,
// «Работа» и «Разговор» — дела дома, и их мини-игра встанет перед ответом
// дому тем же числом, когда у дома появится куда его приложить.
//
// Раньше здесь стояло «Смекалки нет: за ручкой нечего мерить». Теперь есть:
// раздел «мини-игры» меряет шанс взлома при плохой, обычной и хорошей игре
// и то, что с третьего уровня игры нет.

namespace Дом.Ядро;

/// <summary>Категория мини-игры (ГДД 7).</summary>
public enum МиниИгра
{
    РЕМОНТ,     // утепление, укрепление двери, обогреватель — тайминг
    ВЗЛОМ,      // замок, чужая квартира, камера — удержание в зоне
    РАБОТА,     // разбор квартиры, переноска, откапывание — ритм
    РАЗГОВОР,   // убеждение, торг, отвод подозрений — реплика на время
}

public static class МиниИгры
{
    /// <summary>Какой навык снимает эту мини-игру (ГДД 8.1).</summary>
    public static Навык Навык(МиниИгра м) => м switch
    {
        МиниИгра.ВЗЛОМ or МиниИгра.РАЗГОВОР => Ядро.Навык.СМЕКАЛКА,
        МиниИгра.РАБОТА => Ядро.Навык.ФИЗИКА,
        _ => Ядро.Навык.УСТОЙЧИВОСТЬ,
    };

    private static int Уровень(NPC кто, МиниИгра м) => кто.умения?.наследие.Уровень(Навык(м)) ?? 0;

    /// <summary>Нужна ли мини-игра: у героя — пока навык ниже порога
    /// (`мини_игра_исчезает`); у соседей — никогда, они не играют.</summary>
    public static bool Нужна(NPC кто, МиниИгра м, РучкиПетли ручки)
        => кто.умения is not null && Уровень(кто, м) < (int)ручки["мини_игра_исчезает"];

    /// <summary>
    /// Как сыграно само, когда мини-игры нет: с порога — `мини_само`,
    /// и выше за каждый уровень сверх порога. У соседей — половина: как
    /// обычно, прежний бросок.
    /// </summary>
    public static double Само(NPC кто, МиниИгра м, РучкиПетли ручки)
        => кто.умения is null ? 0.5 : Само_по(Уровень(кто, м), ручки);

    /// <summary>Как сыграно само на этом уровне навыка: ниже порога —
    /// половина (игра есть, и само не играется), с порога — `мини_само`
    /// и выше за каждый уровень.</summary>
    public static double Само_по(int уровень, РучкиПетли ручки)
    {
        int сверх = уровень - (int)ручки["мини_игра_исчезает"];
        return сверх < 0 ? 0.5 : Util.Clamp(ручки["мини_само"] + сверх * ручки["мини_само_за_уровень"], 0.0, 1.0);
    }

    /// <summary>
    /// Шанс с тем, как сыграно: половина — прежний шанс; ноль — в
    /// `мини_хуже` раз; единица — в `мини_лучше` раз. В пределах 0.05–0.95,
    /// как всякий шанс дела.
    /// </summary>
    public static double Шанс(double шанс, double качество, РучкиПетли ручки)
    {
        double к = Util.Clamp(качество, 0.0, 1.0);
        double множитель = к <= 0.5
            ? ручки["мини_хуже"] + (1.0 - ручки["мини_хуже"]) * (к / 0.5)
            : 1.0 + (ручки["мини_лучше"] - 1.0) * ((к - 0.5) / 0.5);
        return Math.Abs(множитель - 1.0) < 1e-12 ? шанс : Util.Clamp(шанс * множитель, 0.05, 0.95);
    }

    /// <summary>Шум дела: сыграно плохо (ниже `мини_шумно_ниже`) — на ступень
    /// громче. Провал «Взлома» по ГДД 7 — шум, свидетель, подозрение.</summary>
    public static int Шум(int шум, double качество, РучкиПетли ручки)
        => качество < ручки["мини_шумно_ниже"] ? шум + 1 : шум;

    /// <summary>Ширина зоны в «Удержании» — доля дорожки: шире с каждым
    /// уровнем навыка до порога (играть легче, пока игра ещё есть).</summary>
    public static double Зона(NPC кто, МиниИгра м, РучкиПетли ручки) => Зона_по(Уровень(кто, м), ручки);

    public static double Зона_по(int уровень, РучкиПетли ручки)
        => Util.Clamp(ручки["мини_зона"] + уровень * ручки["мини_зона_за_уровень"], 0.05, 0.9);

    /// <summary>Как сыгранное назвать словами — для вести после дела.</summary>
    public static string Словами(double качество) => качество switch
    {
        < 0.3 => "руки не слушались",
        < 0.45 => "шло туго",
        < 0.65 => "как обычно",
        < 0.85 => "шло ловко",
        _ => "чисто, как по нотам",
    };
}
