// Мини-игры (ГДД 7): «все значимые действия… имеют шанс успеха, зависящий
// от навыков и состояния. Действия сгруппированы в четыре категории, у каждой
// одна короткая (3–7 секунд) мини-игра»; «при достаточном уровне навыка
// мини-игра не запускается — действие выполняется автоматически. Это главная
// осязаемая награда за прокачку» (ГДД 8.1: на уровне 3+ соответствующие
// мини-игры исчезают).
//
// Здесь — правила, общие для всех четырёх; сама игра (что на экране и как
// мерить) — в движке, и отдаёт она одно число: **качество** от нуля
// до единицы. Половина — «сыграно как обычно»: шанс остаётся прежним,
// и всё, что раньше бросалось без мини-игры, бросается бросок в бросок
// как раньше. Хуже — шанс ниже и шумнее (провал «Взлома» по ГДД — шум),
// лучше — выше.
//
// Какой навык снимает какую игру (ГДД 8.1): «Взлом» и «Разговор» —
// Смекалка, «Физическая работа» — Физика, «Ремонт» (на улице) —
// Устойчивость. До третьего уровня навык расширяет зону — играть легче;
// с третьего игры нет, и качество «само» растёт с уровнем.
//
// Первой сделан «Взлом» — у него уже есть провал в мире: замки кладовых,
// гермодверь бункера, решётка камеры, всё на стороне игрока.
//
// «Ремонт» и «Работа» — дела дома: герой отвечает дому мыслью (утеплить
// окна, разобрать квартиру), и мини-игра играется перед ответом. Итог
// едет в дом полем героя `NPC.сыграно` — множители, а не ручки: у хода
// дома ручек петли нет. Ядро читает его в одном месте на каждое
// (`Поправки.Шанс_игры` — провал стройки, `Поправки.Часы_игры` — часы
// работы руками) и сбрасывает после дела (`Действия.execute`). У соседей
// поле пусто, а при игре «как обычно» множители ровно единица — эталон
// не сдвигается ни на бросок.
//
// «Разговор» — реплика на время (ГДД 7: «убеждение, торг, отвод подозрений;
// выбор реплики за ограниченное время; провал — падение доверия»). Играется
// перед разговором дома с соседом (`Реплики`): три тона, верный — по тому,
// что сосед ценит первым. Итог едет тем же `NPC.сыграно` и множит доверие,
// которое сосед получает от разговора (`Поправки.Доверие_игры`): половина —
// ровно единица, провал — доверие падает вместо роста.
//
// Торг — тот же «Разговор» перед меной: итог множит то, во сколько сосед
// ставит предложенное ему (`Поправки.Торг_игры` в `Действия._trade`) —
// уговорил, и он берёт то, от чего отказался бы; давил не тем тоном — наоборот,
// и доверие падает (`Реплики.Торг_сорвался`, зовёт движок).
//
// Убеждение — тот же «Разговор» перед просьбой: итог сдвигает решение соседа
// «дать ли» (`Поправки.Уговор_игры` в `Действия._ask`) — уговорил, и он даёт
// там, где отказал бы; просил не так — наоборот, и доверие падает.
//
// Раньше здесь стояло «Смекалки нет: за ручкой нечего мерить». Теперь есть:
// раздел «мини-игры» меряет шанс взлома при плохой, обычной и хорошей игре
// и то, что с третьего уровня игры нет.

namespace Дом.Ядро;

/// <summary>Категория мини-игры (ГДД 7).</summary>
public enum МиниИгра
{
    РЕМОНТ,     // утепление, укрепление двери, обогреватель — тайминг
    ВЗЛОМ,      // замок, чужая квартира, камера — удержание в зоне
    РАБОТА,     // разбор квартиры, переноска, откапывание — ритм
    РАЗГОВОР,   // убеждение, торг, отвод подозрений — реплика на время
}

/// <summary>Как сыграна мини-игра перед делом дома: какая, во сколько раз
/// шанс, во сколько раз часы и — у «Разговора» перед меной — во сколько раз
/// сосед ставит предложенное. Только у героя, на одно дело — мимо снимка
/// и сейва.</summary>
public sealed record Сыграно(МиниИгра вид, double шанс, double часы, double торг = 1.0,
                            double уговор = 0.0);

public static class МиниИгры
{
    /// <summary>Работа руками — «Физическая работа» ГДД 7: разбор квартиры,
    /// тело, вынести. Прочий труд (топить снег, вылазка) — будни, не игра.</summary>
    public static readonly IReadOnlySet<string> РАБОТА_РУКАМИ =
        new HashSet<string>(StringComparer.Ordinal) { "разбор", "тело", "вынести" };

    /// <summary>Какая мини-игра у дела дома — или null: у этого дела её нет.
    /// Стройка — «Ремонт», работа руками — «Работа», разговор, мена (торг)
    /// и просьба (убеждение) — «Разговор».</summary>
    public static МиниИгра? Какая(string ключ)
        => Каталог.СТРОЙКА.Есть(ключ) ? МиниИгра.РЕМОНТ
           : РАБОТА_РУКАМИ.Contains(ключ) ? МиниИгра.РАБОТА
           : ключ is "разговор" or "обмен" or "попросить" ? МиниИгра.РАЗГОВОР
           : null;

    /// <summary>Что сыграно — в дом: множитель шанса и часов по качеству;
    /// у «Разговора» вместо шанса — множитель доверия (`Доверие`) и торга
    /// (`Торг`).</summary>
    public static Сыграно Сыграно_для(МиниИгра м, double качество, РучкиПетли ручки)
        => new(м, м == МиниИгра.РАЗГОВОР ? Доверие(качество, ручки) : Множитель(качество, ручки),
               м == МиниИгра.РАБОТА ? Часы(качество, ручки) : 1.0,
               м == МиниИгра.РАЗГОВОР ? Торг(качество, ручки) : 1.0,
               м == МиниИгра.РАЗГОВОР ? Уговор(качество, ручки) : 0.0);

    /// <summary>На сколько сдвигается решение соседа «дать ли» после того,
    /// как его уговаривали: половина — ровно ноль, ноль и единица —
    /// на `мини_уговор_сила` ниже и выше (в мерке `Действия.даст_ли`).</summary>
    public static double Уговор(double качество, РучкиПетли ручки)
    {
        double к = Util.Clamp(качество, 0.0, 1.0);
        return (к - 0.5) * 2.0 * ручки["мини_уговор_сила"];
    }

    /// <summary>Во сколько раз сосед ставит предложенное в мене при этом
    /// качестве торга: половина — ровно единица, ноль и единица —
    /// на `мини_торг_сила` ниже и выше.</summary>
    public static double Торг(double качество, РучкиПетли ручки)
    {
        double к = Util.Clamp(качество, 0.0, 1.0);
        return 1.0 + (к - 0.5) * 2.0 * ручки["мини_торг_сила"];
    }

    /// <summary>Во сколько раз доверие от разговора при этом качестве:
    /// половина — ровно единица; ноль — `мини_разговор_хуже` (меньше нуля:
    /// провал — доверие падает, ГДД 7); единица — `мини_лучше`.</summary>
    public static double Доверие(double качество, РучкиПетли ручки)
    {
        double к = Util.Clamp(качество, 0.0, 1.0);
        return к <= 0.5
            ? ручки["мини_разговор_хуже"] + (1.0 - ручки["мини_разговор_хуже"]) * (к / 0.5)
            : 1.0 + (ручки["мини_лучше"] - 1.0) * ((к - 0.5) / 0.5);
    }

    /// <summary>Во сколько раз шанс при этом качестве: половина — ровно
    /// единица; ноль — `мини_хуже`; единица — `мини_лучше`.</summary>
    public static double Множитель(double качество, РучкиПетли ручки)
    {
        double к = Util.Clamp(качество, 0.0, 1.0);
        return к <= 0.5
            ? ручки["мини_хуже"] + (1.0 - ручки["мини_хуже"]) * (к / 0.5)
            : 1.0 + (ручки["мини_лучше"] - 1.0) * ((к - 0.5) / 0.5);
    }

    /// <summary>Во сколько раз часы работы руками: половина — единица;
    /// ноль — `мини_работа_дольше`; единица — `мини_работа_быстрее`.
    /// Провал «Работы» по ГДД 7 — усталость: дольше.</summary>
    public static double Часы(double качество, РучкиПетли ручки)
    {
        double к = Util.Clamp(качество, 0.0, 1.0);
        return к <= 0.5
            ? ручки["мини_работа_дольше"] + (1.0 - ручки["мини_работа_дольше"]) * (к / 0.5)
            : 1.0 + (ручки["мини_работа_быстрее"] - 1.0) * ((к - 0.5) / 0.5);
    }

    /// <summary>Какой навык снимает эту мини-игру (ГДД 8.1).</summary>
    public static Навык Навык(МиниИгра м) => м switch
    {
        МиниИгра.ВЗЛОМ or МиниИгра.РАЗГОВОР => Ядро.Навык.СМЕКАЛКА,
        МиниИгра.РАБОТА => Ядро.Навык.ФИЗИКА,
        _ => Ядро.Навык.УСТОЙЧИВОСТЬ,
    };

    private static int Уровень(NPC кто, МиниИгра м) => кто.умения?.наследие.Уровень(Навык(м)) ?? 0;

    /// <summary>Нужна ли мини-игра: у героя — пока навык ниже порога
    /// (`мини_игра_исчезает`); у соседей — никогда, они не играют.</summary>
    public static bool Нужна(NPC кто, МиниИгра м, РучкиПетли ручки)
        => кто.умения is not null && Уровень(кто, м) < (int)ручки["мини_игра_исчезает"];

    /// <summary>
    /// Как сыграно само, когда мини-игры нет: с порога — `мини_само`,
    /// и выше за каждый уровень сверх порога. У соседей — половина: как
    /// обычно, прежний бросок.
    /// </summary>
    public static double Само(NPC кто, МиниИгра м, РучкиПетли ручки)
        => кто.умения is null ? 0.5 : Само_по(Уровень(кто, м), ручки);

    /// <summary>Как сыграно само на этом уровне навыка: ниже порога —
    /// половина (игра есть, и само не играется), с порога — `мини_само`
    /// и выше за каждый уровень.</summary>
    public static double Само_по(int уровень, РучкиПетли ручки)
    {
        int сверх = уровень - (int)ручки["мини_игра_исчезает"];
        return сверх < 0 ? 0.5 : Util.Clamp(ручки["мини_само"] + сверх * ручки["мини_само_за_уровень"], 0.0, 1.0);
    }

    /// <summary>
    /// Шанс с тем, как сыграно: половина — прежний шанс; ноль — в
    /// `мини_хуже` раз; единица — в `мини_лучше` раз. В пределах 0.05–0.95,
    /// как всякий шанс дела.
    /// </summary>
    public static double Шанс(double шанс, double качество, РучкиПетли ручки)
        => Применить(шанс, Множитель(качество, ручки));

    /// <summary>
    /// Шанс, умноженный на множитель игры: ровно единица — шанс как есть,
    /// бросок в бросок; иначе — в пределах 0.05–0.95, но не внутрь того,
    /// что уже было снаружи. У здорового героя шанс стройки — под 0.98,
    /// и первая версия обрезала хорошую игру потолком 0.95: сыграл лучше —
    /// вышло хуже. Раздел «мини-игры» это поймал живым утеплением.
    /// </summary>
    public static double Применить(double шанс, double множитель)
        => Math.Abs(множитель - 1.0) < 1e-12
            ? шанс
            : Util.Clamp(шанс * множитель, Math.Min(шанс, 0.05), Math.Max(шанс, 0.95));

    /// <summary>Шум дела: сыграно плохо (ниже `мини_шумно_ниже`) — на ступень
    /// громче. Провал «Взлома» по ГДД 7 — шум, свидетель, подозрение.</summary>
    public static int Шум(int шум, double качество, РучкиПетли ручки)
        => качество < ручки["мини_шумно_ниже"] ? шум + 1 : шум;

    /// <summary>Ширина зоны в «Удержании» — доля дорожки: шире с каждым
    /// уровнем навыка до порога (играть легче, пока игра ещё есть).</summary>
    public static double Зона(NPC кто, МиниИгра м, РучкиПетли ручки) => Зона_по(Уровень(кто, м), ручки);

    public static double Зона_по(int уровень, РучкиПетли ручки)
        => Util.Clamp(ручки["мини_зона"] + уровень * ручки["мини_зона_за_уровень"], 0.05, 0.9);

    /// <summary>Как сыгранное назвать словами — для вести после дела.</summary>
    public static string Словами(double качество) => качество switch
    {
        < 0.3 => "руки не слушались",
        < 0.45 => "шло туго",
        < 0.65 => "как обычно",
        < 0.85 => "шло ловко",
        _ => "чисто, как по нотам",
    };
}
