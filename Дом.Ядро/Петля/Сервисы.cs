// Сервисы города до метели (просьба автора: «систему кредитов для игрока:
// до метели он оформил микрозайм или кредит, чтобы деньги получить
// максимально быстро; также доставку еды: пицца, бургер, картошка фри,
// газировка — с начала метели перестают работать»).
//
// До метели город живёт обычной жизнью (ГДД 4), и у героя есть то же,
// что у всех: телефон, карта и приложения (`data/сервисы.json`).
//
//   · **займы.** Микрозайм — деньги на карту сразу, по паспорту, под
//     процент в день; кредит в банке — больше и дешевле, но решение
//     к утру, и одобряют не всем. Одобрят ли — бросок от зерна жизни,
//     конторы и дня, мимо `h.rng`: не выбор жильца и не исход дела дома.
//     Отказали — второй раз туда не подать; взял — одна контора, один
//     займ. Долг растёт с каждым днём, и в день платежа телефон
//     напоминает, — но в метель банки встали на второй день, и платить
//     нечем и некуда. Долг, как всё в прологе, откатывается с жизнью.
//   · **доставка.** Картой, курьер через час дня героя; пока героя нет
//     дома, пакет ждёт у двери и заносится, когда он придёт. Привезённое
//     ложится на полку вещами (`Продукты`) и числом «еда» в шкаф — закон
//     полки держит зовущий, как у ящика и покупки.
//
// Работает всё это только в прологе: с первого дня метели банк
// не отвечает, курьеры не ездят, а заказ, не доехавший до метели,
// отменён — деньги вернулись на карту (в первые дни банки ещё живы).
//
// Живёт в округе героя: без игрока сервисов нет, и дом считает, как считал.

using System.Text.Json;
using System.Text.Json.Nodes;

namespace Дом.Ядро;

/// <summary>Контора: сколько даёт, за сколько часов, сразу ли, шанс, процент в день, срок.</summary>
public sealed record Займ(string id, string имя, double сумма, double часов, bool сразу,
                         double одобрят, double в_день, int дней, string условия);

/// <summary>Строка меню доставки: какой продукт (`еда.json`) и почём.</summary>
public sealed record Блюдо(string еда, double цена);

/// <summary>Числа сервисов из `data/сервисы.json`.</summary>
public sealed record ДанныеСервисов(IReadOnlyList<Займ> займы, double доставка_часов, IReadOnlyList<Блюдо> меню)
{
    /// <summary>Прочитать; файла нет — сервисов нет (null). Меню сверяется
    /// с каталогом еды: блюдо без продукта — ошибка данных.</summary>
    public static ДанныеСервисов? Прочитать(string каталог, КаталогЕды? еда)
    {
        string путь = Path.Combine(каталог, "сервисы.json");
        if (!File.Exists(путь))
            return null;
        using var поток = File.OpenRead(путь);
        using var док = JsonDocument.Parse(поток);
        var к = док.RootElement;
        var займы = new List<Займ>();
        foreach (var з in к.GetProperty("займы").EnumerateArray())
        {
            var займ = new Займ(
                з.GetProperty("id").GetString()!, з.GetProperty("имя").GetString()!,
                з.GetProperty("сумма").GetDouble(), з.GetProperty("часов").GetDouble(),
                з.GetProperty("сразу").GetBoolean(), з.GetProperty("одобрят").GetDouble(),
                з.GetProperty("в_день").GetDouble(), з.GetProperty("дней").GetInt32(),
                з.GetProperty("условия").GetString()!);
            if (займ.сумма <= 0 || займ.одобрят is < 0 or > 1 || займ.дней < 1 || займ.в_день < 0
                || займы.Any(x => x.id == займ.id))
                throw new InvalidDataException($"сервисы.json: займ «{займ.id}» — сумма больше нуля, шанс от нуля до единицы, срок от дня, id один раз");
            займы.Add(займ);
        }
        var д = к.GetProperty("доставка");
        var меню = new List<Блюдо>();
        foreach (var б in д.GetProperty("меню").EnumerateArray())
        {
            var блюдо = new Блюдо(б.GetProperty("еда").GetString()!, б.GetProperty("цена").GetDouble());
            if (еда is not null && !еда.Есть(блюдо.еда))
                throw new InvalidDataException($"сервисы.json: в меню «{блюдо.еда}» — такого продукта в еда.json нет");
            if (блюдо.цена <= 0)
                throw new InvalidDataException($"сервисы.json: у «{блюдо.еда}» цена больше нуля");
            меню.Add(блюдо);
        }
        return new ДанныеСервисов(займы, д.GetProperty("часов").GetDouble(), меню);
    }
}

/// <summary>Долг: какая контора, сколько взял, в какой день (день пролога —
/// отрицательный), процент в день и срок.</summary>
public sealed record Долг(string займ, double взял, int день, double в_день, int дней)
{
    public int срок => день + дней;

    /// <summary>Сколько вернуть на этот день: долг растёт с каждым днём.</summary>
    public double Вернуть(int сегодня) => взял * (1.0 + в_день * Math.Max(0, сегодня - день));
}

/// <summary>Заказ в пути: что везут и к какому часу дня героя.</summary>
public sealed record ЗаказДоставки(IReadOnlyList<string> еда, double к_часу, int день, double заплачено);

public sealed class Сервисы
{
    public ДанныеСервисов данные { get; }
    private readonly long _зерно;
    private readonly List<Долг> _долги = new();
    private readonly List<(string займ, int день)> _заявки = new();
    private readonly HashSet<string> _отказали = new(StringComparer.Ordinal);
    private readonly HashSet<string> _напомнил = new(StringComparer.Ordinal);
    private ЗаказДоставки? _заказ;

    public Сервисы(ДанныеСервисов д, long зерно)
    {
        данные = д;
        _зерно = зерно;
    }

    public IReadOnlyList<Долг> долги => _долги;
    public ЗаказДоставки? заказ => _заказ;
    public bool Подана(string займ) => _заявки.Any(з => з.займ == займ);
    public bool Отказали(string займ) => _отказали.Contains(займ);

    // ------------------------------------------------------------ займы

    /// <summary>Почему этот займ сейчас не взять — или null. <paramref name="работают"/> —
    /// идёт ли ещё пролог (в метель банк не отвечает).</summary>
    public string? Нельзя(Займ з, NPC я, bool работают)
    {
        if (!работают)
            return "не отвечает: метель, связь с банком пропала";
        if (_долги.Any(д => д.займ == з.id))
            return "уже взят";
        if (Подана(з.id))
            return "заявка подана — решение к утру";
        if (Отказали(з.id))
            return "отказали — второй раз не подать";
        if (я.time_left < з.часов - 1e-9)
            return "сегодня уже не успеть — ночь";
        return null;
    }

    /// <summary>
    /// Подать заявку. Микрозайм решается сразу: одобрили — деньги на карту
    /// и долг; нет — отказ. Банк — к утру (<see cref="Утро"/>). Часы заявки
    /// проживает зовущий (<see cref="Сделано.часов"/>).
    /// </summary>
    public Сделано Взять(NPC я, Займ з, int день, bool работают)
    {
        if (Нельзя(з, я, работают) is string нельзя)
            return new Сделано(false, 0, нельзя);
        if (!з.сразу)
        {
            _заявки.Add((з.id, день));
            return new Сделано(true, з.часов, $"{з.имя}: заявка подана — решение придёт к утру");
        }
        if (Округа.Бросок(_зерно, "займ:" + з.id, я.id, день) >= з.одобрят)
        {
            _отказали.Add(з.id);
            return new Сделано(true, з.часов, $"{з.имя}: отказ — «к сожалению, мы не можем предложить вам займ»");
        }
        я.счёт += з.сумма;
        var долг = new Долг(з.id, з.сумма, день, з.в_день, з.дней);
        _долги.Add(долг);
        return new Сделано(true, з.часов,
            $"{з.имя}: одобрено — +{Текст.G(з.сумма)} на карту; вернуть {Текст.G(Текст.Округлить(долг.Вернуть(долг.срок), 1))} "
            + $"через {з.дней} дней");
    }

    /// <summary>
    /// Утро дня <paramref name="день"/> (пролога или метели): банк решил
    /// по вчерашним заявкам — одобрил, и деньги пришли, если банки ещё
    /// работают; и день платежа — напоминание. Возвращает, что сказать.
    /// </summary>
    public List<string> Утро(NPC я, int день, bool банки)
    {
        var вести = new List<string>();
        foreach (var (id, подана) in _заявки.Where(з => з.день < день).ToList())
        {
            _заявки.Remove((id, подана));
            var з = данные.займы.First(x => x.id == id);
            if (Округа.Бросок(_зерно, "займ:" + з.id, я.id, подана) >= з.одобрят)
            {
                _отказали.Add(з.id);
                вести.Add($"{з.имя}: банк отказал");
                continue;
            }
            if (!банки)
            {
                вести.Add($"{з.имя}: одобрено — но банки уже не работают, деньги не пришли");
                continue;
            }
            я.счёт += з.сумма;
            _долги.Add(new Долг(з.id, з.сумма, подана, з.в_день, з.дней));
            вести.Add($"{з.имя}: одобрено — +{Текст.G(з.сумма)} на карту");
        }
        foreach (var д in _долги)
        {
            if (день >= д.срок && _напомнил.Add(д.займ))
                вести.Add($"СМС: «{данные.займы.First(x => x.id == д.займ).имя} — сегодня день платежа: "
                          + $"{Текст.G(Текст.Округлить(д.Вернуть(день), 1))} тыс. Просрочка — пени и передача долга коллекторам»");
        }
        return вести;
    }

    // ------------------------------------------------------------ доставка

    /// <summary>Почему это блюдо сейчас не заказать — или null.</summary>
    public string? Нельзя(Блюдо б, House h, NPC я, bool работают)
    {
        if (!работают)
            return "курьеры не ездят: метель";
        if (!h.банки || я.счёт < б.цена - 1e-9)
            return "на карте не хватает";
        return null;
    }

    /// <summary>
    /// Заказать: картой, курьер через «часов» часов дня героя. Если курьер
    /// уже едет — блюдо в тот же пакет, к тому же часу.
    /// </summary>
    public Сделано Заказать(House h, NPC я, Блюдо б, bool работают, int день)
    {
        if (Нельзя(б, h, я, работают) is string нельзя)
            return new Сделано(false, 0, нельзя);
        я.счёт = Math.Max(0.0, я.счёт - б.цена);
        _заказ = _заказ is { } з
            ? з with { еда = з.еда.Append(б.еда).ToList(), заплачено = з.заплачено + б.цена }
            : new ЗаказДоставки(new[] { б.еда }, я.час() + данные.доставка_часов, день, б.цена);
        return new Сделано(true, 0, $"заказал — курьер к {ХодВремени.Часы(_заказ.к_часу)}");
    }

    /// <summary>
    /// Привезли ли: час настал и герой дома — пакет на полку вещами,
    /// порции — в шкаф. Не дома — ждёт у двери. Возвращает привезённое
    /// или null.
    /// </summary>
    public IReadOnlyList<string>? Привезти(NPC я, double час, bool дома, Продукты? продукты)
    {
        if (_заказ is not { } з || час < з.к_часу - 1e-9 || !дома)
            return null;
        foreach (var еда in з.еда)
        {
            var вид = продукты?.каталог.Есть(еда) == true ? продукты.каталог[еда] : null;
            double порций = вид?.единиц ?? 1.0;
            я.stock[Продукты.ЕДА] = я.stock.Взять(Продукты.ЕДА, 0.0) + порций;
            if (продукты is not null && вид is not null)
                продукты.Положить(МестоЕды.ПОЛКА, продукты.Новая(еда));
        }
        _заказ = null;
        return з.еда;
    }

    /// <summary>Пришла метель: не доехавший заказ отменён, деньги — на карту.</summary>
    public string? Метель(NPC я)
    {
        if (_заказ is not { } з)
            return null;
        _заказ = null;
        я.счёт += з.заплачено;
        return $"доставка: заказ отменён — курьеры не ездят, {Текст.G(Текст.Округлить(з.заплачено, 2))} вернулись на карту";
    }

    // ------------------------------------------------------------ сохранение игры

    public JsonObject Сложить() => new()
    {
        ["долги"] = new JsonArray(_долги.Select(д => (JsonNode?)new JsonObject
        {
            ["займ"] = д.займ, ["взял"] = д.взял, ["день"] = д.день, ["в_день"] = д.в_день, ["дней"] = д.дней,
        }).ToArray()),
        ["заявки"] = new JsonArray(_заявки.Select(з => (JsonNode?)new JsonObject { ["займ"] = з.займ, ["день"] = з.день }).ToArray()),
        ["отказали"] = new JsonArray(_отказали.OrderBy(x => x, StringComparer.Ordinal).Select(x => (JsonNode?)x).ToArray()),
        ["напомнил"] = new JsonArray(_напомнил.OrderBy(x => x, StringComparer.Ordinal).Select(x => (JsonNode?)x).ToArray()),
        ["заказ"] = _заказ is { } з
            ? new JsonObject
            {
                ["еда"] = new JsonArray(з.еда.Select(x => (JsonNode?)x).ToArray()),
                ["к_часу"] = з.к_часу, ["день"] = з.день, ["заплачено"] = з.заплачено,
            }
            : null,
    };

    public void Разложить(JsonObject? о)
    {
        _долги.Clear();
        _заявки.Clear();
        _отказали.Clear();
        _напомнил.Clear();
        _заказ = null;
        if (о is null)
            return;
        foreach (var x in о["долги"]?.AsArray() ?? new JsonArray())
            _долги.Add(new Долг(x!["займ"]!.GetValue<string>(), x["взял"]!.GetValue<double>(), x["день"]!.GetValue<int>(),
                                x["в_день"]!.GetValue<double>(), x["дней"]!.GetValue<int>()));
        foreach (var x in о["заявки"]?.AsArray() ?? new JsonArray())
            _заявки.Add((x!["займ"]!.GetValue<string>(), x["день"]!.GetValue<int>()));
        foreach (var x in о["отказали"]?.AsArray() ?? new JsonArray())
            _отказали.Add(x!.GetValue<string>());
        foreach (var x in о["напомнил"]?.AsArray() ?? new JsonArray())
            _напомнил.Add(x!.GetValue<string>());
        if (о["заказ"] is JsonObject з)
            _заказ = new ЗаказДоставки(з["еда"]!.AsArray().Select(x => x!.GetValue<string>()).ToList(),
                               з["к_часу"]!.GetValue<double>(), з["день"]!.GetValue<int>(), з["заплачено"]!.GetValue<double>());
    }
}
