    /// <summary>
    /// Ходка с полной тарой — к участку или от него. Кто дома, тот с шансом
    /// «заметят» видит из окна: решает, что у героя есть что носить,
    /// и считает ходки; заметивший «выследят» раз идёт по следу и знает,
    /// откуда герой носит. Как у бункера (`Бункер.Ходка`). Возвращает
    /// заметивших — герой видит только, что в окне кто-то стоял.
    /// </summary>
    public List<NPC> Ходка(House h, NPC я)
    {
        var заметили = new List<NPC>();
        if (данные.гости is not { } г || я.ноша is not { пусто: false } ноша)
            return заметили;
        int ходка = _ходок++;
        foreach (var p in h.others(я).OrderBy(p => p.id, StringComparer.Ordinal))
        {
            if (!p.здесь() || p.away
                || Округа.Бросок(_зерно, $"к_участку{ходка}", p.id, h.day) >= г.заметят)
                continue;
            foreach (var р in ноша.ресурсы.OrderBy(к => к, StringComparer.Ordinal))
                Социальное.note_signal(p, я.id, р, я.stock.Взять(р, 0.0) + ноша.Сколько(р), г.вес);   // правда: видно: нёс на глазах
            _заметил[p.id] = _заметил.GetValueOrDefault(p.id) + 1;
            if (_заметил[p.id] >= г.выследят)
                _знают.Add(p.id);
            заметили.Add(p);
        }
        return заметили;
    }

    /// <summary>Подписаться на конец дня: кто выследил участок — приходит.</summary>
    public void Слушать(House h, Округа о)
        => h.hooks.on_day.Add(дом =>
        {
