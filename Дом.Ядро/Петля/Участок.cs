    private System.Text.Json.Nodes.JsonObject Сложить_гостей()
    {
        var заметил = new System.Text.Json.Nodes.JsonObject();
        foreach (var (кто, н) in _заметил.OrderBy(п => п.Key, StringComparer.Ordinal))
            заметил[кто] = н;
        lock (_замок)
            return new()
            {
                ["ходок"] = _ходок,
                ["заметил"] = заметил,
                ["знают"] = new System.Text.Json.Nodes.JsonArray(_знают.OrderBy(x => x, StringComparer.Ordinal)
                    .Select(x => (System.Text.Json.Nodes.JsonNode?)x).ToArray()),
                ["пропало"] = Карман.Числа_в(_пропало.Ключи.Select(к => new KeyValuePair<string, double>(к, _пропало[к]))),
                ["вести"] = new System.Text.Json.Nodes.JsonArray(_вести.Select(x => (System.Text.Json.Nodes.JsonNode?)x).ToArray()),
                ["визит"] = _визит is { } в
                    ? new System.Text.Json.Nodes.JsonObject
                    {
                        ["кто"] = new System.Text.Json.Nodes.JsonArray(в.кто.Select(x => (System.Text.Json.Nodes.JsonNode?)x).ToArray()),
                        ["день"] = в.день,
                    }
                    : null,
            };
    }

    private void Разложить_гостей(System.Text.Json.Nodes.JsonObject? о)
    {
        _ходок = о?["ходок"]?.GetValue<int>() ?? 0;
        _заметил.Clear();
        _знают.Clear();
        if (о?["заметил"] is System.Text.Json.Nodes.JsonObject заметил)
            foreach (var (к, v) in заметил)
                _заметил[к] = v!.GetValue<int>();
        if (о?["знают"] is System.Text.Json.Nodes.JsonArray знают)
            foreach (var x in знают)
                _знают.Add(x!.GetValue<string>());
        lock (_замок)
        {
            _пропало.Очистить();
            _вести.Clear();
            _визит = null;
            if (о?["пропало"] is System.Text.Json.Nodes.JsonObject пропало)
                foreach (var (к, v) in пропало)
                    _пропало[к] = v!.GetValue<double>();
            if (о?["вести"] is System.Text.Json.Nodes.JsonArray вести)
                foreach (var x in вести)
                    _вести.Enqueue(x!.GetValue<string>());
            if (о?["визит"] is System.Text.Json.Nodes.JsonObject в)
                _визит = new Визит(в["кто"]!.AsArray().Select(x => x!.GetValue<string>()).ToList(),
                                   в["день"]!.GetValue<int>());
        }
    }

    public System.Text.Json.Nodes.JsonObject Сложить() => new()
    {
        ["где"] = где.ToString(),
        ["кладовая"] = Карман.Числа_в(_кладовая.Ключи.Select(к => new KeyValuePair<string, double>(к, _кладовая[к]))),
        ["оружейная"] = new System.Text.Json.Nodes.JsonArray(_оружейная.Select(x => (System.Text.Json.Nodes.JsonNode?)x).ToArray()),
        ["патронов"] = _патронов,
        ["вещдоки"] = Карман.Числа_в(_вещдоки.Ключи.Select(к => new KeyValuePair<string, double>(к, _вещдоки[к]))),
        ["тара_вещдоков"] = _тара_вещдоков?.ToString(),
        ["отобрано"] = new System.Text.Json.Nodes.JsonArray(_отобрано.Select(x => (System.Text.Json.Nodes.JsonNode?)x).ToArray()),
        ["печь_день"] = _печь_день,
        ["мебели_разобрано"] = _мебели_разобрано,
        ["гости"] = Сложить_гостей(),
    };

    /// <summary>Разложить и снова греть героя здесь, если он в участке.</summary>
    public void Разложить(System.Text.Json.Nodes.JsonObject о, NPC я)
    {
        где = Enum.Parse<ВУчастке>(о["где"]!.GetValue<string>());
        _кладовая.Очистить();
        foreach (var (к, v) in о["кладовая"]!.AsObject())
            _кладовая[к] = v!.GetValue<double>();
        _оружейная.Clear();
        foreach (var x in о["оружейная"]!.AsArray())
            _оружейная.Add(x!.GetValue<string>());
        _патронов = о["патронов"]!.GetValue<double>();
        _вещдоки.Очистить();
        foreach (var (к, v) in о["вещдоки"]!.AsObject())
            _вещдоки[к] = v!.GetValue<double>();
        _тара_вещдоков = о["тара_вещдоков"]?.GetValue<string>() is string т ? Enum.Parse<Тара>(т) : null;
        _отобрано.Clear();
        foreach (var x in о["отобрано"]!.AsArray())
            _отобрано.Add(x!.GetValue<string>());
        _печь_день = о["печь_день"]!.GetValue<int>();
        _мебели_разобрано = о["мебели_разобрано"]?.GetValue<int>() ?? 0;
        Разложить_гостей(о["гости"] as System.Text.Json.Nodes.JsonObject);
        я.приют = где == ВУчастке.НЕТ ? null : this;
    }
