// Полицейский участок в метель (задание автора, пп. 16–18).
//
// Попасться на краже до метели — значит оказаться здесь: задержали, забрали
// сумку и снаряжение (карман вне времени не отнять — его нет в мире), ночь
// в камере — а утром метель, и дежурные разошлись по домам. Камера заперта,
// участок пуст. Время тут идёт так же, как везде: дом живёт своё, и герой
// в нём по-прежнему жилец — только греется и ест он не дома, а здесь.
//
//   · **выбраться** — ломать дверь камеры: тяжёлым инструментом (монтировка,
//     топор — что есть при себе, а при себе после задержания только то,
//     что было в кармане) — часы и шанс по замку «железная_дверь»;
//     голыми руками — долго, редко и с кровью. Не вышел — холод и голод
//     по тому, что при себе (п. 17: «не случайный Game Over»);
//   · **остаться** (п. 18) — участок как убежище: кладовая (еды на месяц
//     одному), оружейная (игровой набор), вещдоки (своё, отобранное),
//     печка в дежурке — тепло, пока есть чем топить;
//   · **вернуться домой** — дорога по сегодняшнему снегу, как поход.
//
// Тепло — единственное, что участок подсказывает дому: пока герой здесь,
// его комната — здесь (`IПриют`). У соседей приюта нет, и дом считает их,
// как считал; сам участок живёт в округе героя — мимо снимка и сейва.

namespace Дом.Ядро;

/// <summary>Где герой греется, если не дома, — только у игрока; у соседей
/// null, и комнату им считает дом.</summary>
public interface IПриют
{
    /// <summary>Температура там, где он сейчас, — или null: дома.</summary>
    double? Температура(House h, NPC кто);
}

/// <summary>Где герой в участке: не там, заперт в камере, свободен.</summary>
public enum ВУчастке { НЕТ, КАМЕРА, УЧАСТОК }

/// <summary>Числа участка из `data/мир.json`, «участок».</summary>
public sealed record ДанныеУчастка(
    string имя,
    double дорога_часов,
    string замок_камеры,
    double камера_градусов,
    double участок_градусов,
    double печь_градусов,
    double печь_топлива,
    double руками_часов,
    double руками_шанс,
    double руками_урон,
    IReadOnlyDictionary<string, double> кладовая,
    IReadOnlyList<string> оружейная,
    double патронов)
{
    public static ДанныеУчастка Прочитать(System.Text.Json.JsonElement у)
    {
        var к = у.GetProperty("камера");
        var р = у.GetProperty("руками");
        var п = у.GetProperty("печь");
        var о = у.GetProperty("оружейная");
        var кладовая = new Dictionary<string, double>(StringComparer.Ordinal);
        foreach (var x in у.GetProperty("кладовая").EnumerateObject())
            кладовая[x.Name] = x.Value.GetDouble();
        return new ДанныеУчастка(
            у.GetProperty("имя").GetString()!,
            у.GetProperty("дорога_часов").GetDouble(),
            к.GetProperty("замок").GetString()!,
            к.GetProperty("градусов").GetDouble(),
            у.GetProperty("участок_градусов").GetDouble(),
            п.GetProperty("градусов").GetDouble(),
            п.GetProperty("топлива").GetDouble(),
            р.GetProperty("часов").GetDouble(),
            р.GetProperty("шанс").GetDouble(),
            р.GetProperty("урон").GetDouble(),
            кладовая,
            о.GetProperty("оружие").EnumerateArray().Select(x => x.GetString()!).ToList(),
            о.GetProperty("патроны").GetDouble());
    }
}

/// <summary>Чем кончилась попытка выбраться из камеры.</summary>
public sealed record Побег(bool вышел, double часов, string чем, string весть);

public sealed class Участок : IПриют
{
    public ДанныеУчастка данные { get; }
    private readonly Словарь<string, double> _кладовая = Словари.Числа();
    private readonly List<string> _оружейная = new();
    private double _патронов;
    private readonly Словарь<string, double> _вещдоки = Словари.Числа();
    private Тара? _тара_вещдоков;
    private readonly List<string> _отобрано = new();
    private int _печь_день = -99;

    public Участок(ДанныеУчастка д)
    {
        данные = д;
        foreach (var (р, сколько) in д.кладовая.OrderBy(п => п.Key, StringComparer.Ordinal))
            _кладовая[р] = сколько;
        _оружейная.AddRange(д.оружейная);
        _патронов = д.патронов;
    }

    /// <summary>Где герой: не здесь, в камере, свободен в участке.</summary>
    public ВУчастке где { get; private set; }

    public IReadOnlyList<string> кладовая_что => _кладовая.Ключи;
    public double В_кладовой(string р) => _кладовая.Взять(р, 0.0);
    public IReadOnlyList<string> оружейная => _оружейная;
    public double патронов => _патронов;
    public IReadOnlyList<string> отобрано => _отобрано;
    public IReadOnlyList<string> вещдоки_что => _вещдоки.Ключи;
    public double В_вещдоках(string р) => _вещдоки.Взять(р, 0.0);
    public bool печь_топится(int день) => _печь_день == день;

    // ------------------------------------------------------------ приют

    public double? Температура(House h, NPC кто) => где switch
    {
        ВУчастке.КАМЕРА => данные.камера_градусов,
        ВУчастке.УЧАСТОК => данные.участок_градусов + (печь_топится(h.day) ? данные.печь_градусов : 0.0),
        _ => null,
    };

    // ------------------------------------------------------------ задержание

    /// <summary>
    /// Задержали: сумку — в вещдоки, снаряжение (инструменты, снегоступы,
    /// оружие в руках) — туда же; карман вне времени не отнять. Герой —
    /// в камере, и греется теперь здесь.
    /// </summary>
    public void Задержать(NPC я)
    {
        if (я.ноша is { пусто: false } ноша)
        {
            _тара_вещдоков = ноша.тара;
            foreach (var р in ноша.ресурсы.ToList())
                _вещдоки[р] = _вещдоки.Взять(р, 0.0) + ноша.Сколько(р);
            ноша.Обнулить();
        }
        if (я.снаряжение is { } с)
            foreach (var id in с.с_собой.OrderBy(x => x, StringComparer.Ordinal).ToList())
                if (с.Положить_насовсем(id))
                    _отобрано.Add(id);
        где = ВУчастке.КАМЕРА;
        я.приют = this;
    }

    // ------------------------------------------------------------ побег

    /// <summary>Чем ломать дверь камеры: инструмент при себе, который берёт
    /// её замок, — лучший по шансу; нет — голые руки (null).</summary>
    public string? Чем_ломать(NPC я, Инструменты каталог)
        => я.снаряжение?.с_собой
            .Where(id => Приём_(id, каталог) is not null)
            .OrderByDescending(id => Приём_(id, каталог)!.шанс)
            .ThenBy(id => id, StringComparer.Ordinal)
            .FirstOrDefault();

    private Приём? Приём_(string id, Инструменты каталог)
        => каталог.все.TryGetValue(id, out var и) ? и.Берёт(данные.замок_камеры) : null;

    /// <summary>Сколько часов уйдёт на попытку: инструментом — по замку,
    /// руками — долго.</summary>
    public double Часов_ломать(House h, string? инструмент, Инструменты каталог)
        => инструмент is string и && Приём_(и, каталог) is { } з
            ? Взлом.часы(h, з) : данные.руками_часов;

    /// <summary>
    /// Попытка выбраться: часы уже ушли делом. Инструментом — шанс по замку
    /// (мерка работы, как взлом), руками — `руками_шанс` и кровь. Бросок —
    /// исход, из `h.rng`. Вышел — свободен в участке.
    /// </summary>
    public Побег Ломать(House h, NPC я, string? инструмент, Инструменты каталог, РучкиПетли ручки)
    {
        if (где != ВУчастке.КАМЕРА)
            return new Побег(где == ВУчастке.УЧАСТОК, 0, "", "дверь камеры и так открыта");
        double часов = Часов_ломать(h, инструмент, каталог);
        if (инструмент is string и && Приём_(и, каталог) is { } з)
        {
            double шанс = Взлом.шанс(h, я, ручки, з);
            string чем = каталог.все[и].чем;
            if (!h.rng.Chance(шанс))
                return new Побег(false, часов, чем, $"{чем} — дверь держит; ещё раз");
            где = ВУчастке.УЧАСТОК;
            return new Побег(true, часов, чем, $"{чем} — замок камеры сорван, ты в коридоре участка");
        }
        я.health = Math.Max(1.0, я.health - данные.руками_урон);
        if (!h.rng.Chance(данные.руками_шанс))
            return new Побег(false, часов, "руками", "решётку не расшатать — только ободрал руки в кровь");
        где = ВУчастке.УЧАСТОК;
        return new Побег(true, часов, "руками", "прут решётки поддался — протиснулся в коридор");
    }

    // ------------------------------------------------------------ участок

    /// <summary>Поесть или попить из кладовой — порцию, как дома:
    /// еда — сытость, вода — жажда. false — нечего или ещё в камере.</summary>
    public bool Поесть(House h, NPC я, string ресурс)
    {
        if (где != ВУчастке.УЧАСТОК || _кладовая.Взять(ресурс, 0.0) < 1.0)
            return false;
        _кладовая[ресурс] = _кладовая.Взять(ресурс, 0.0) - 1.0;
        Съесть(h, я, ресурс);
        return true;
    }

    /// <summary>Съесть или выпить из кармана вне времени — где угодно, и в камере
    /// тоже: единственное, что при себе после задержания. false — нечего.</summary>
    public static bool Из_кармана(House h, NPC я, string ресурс)
    {
        if (я.карман is not { } к || к.Потратить(ресурс, 1.0) < 1.0 - 1e-9)
            return false;
        Съесть(h, я, ресурс);
        return true;
    }

    /// <summary>Порция тела — та же, что дома за «поесть» и «попить».</summary>
    public static void Съесть(House h, NPC я, string ресурс)
    {
        var b = h.B;
        if (ресурс == "еда")
            я.satiety = Util.Clamp(я.satiety + Действия.порция(h, я, b));
        else if (ресурс == "вода")
            я.hydration = Util.Clamp(я.hydration + b["вода_за_порцию"]);
    }

    /// <summary>Взять из кладовой в тару — унести. Сколько влезло.</summary>
    public double Взять(NPC я, string ресурс, double сколько, РучкиПетли ручки)
    {
        if (где != ВУчастке.УЧАСТОК)
            return 0.0;
        я.ноша ??= new Ноша();
        var тара = я.ноша.тара ?? Тара.ПАКЕТ;
        сколько = Math.Min(сколько, Math.Min(_кладовая.Взять(ресурс, 0.0), я.ноша.свободно(тара, ручки)));
        if (сколько <= 0.0)
            return 0.0;
        var взять = Словари.Числа();
        взять[ресурс] = сколько;
        я.ноша.Положить(тара, взять, ручки);
        _кладовая[ресурс] = _кладовая.Взять(ресурс, 0.0) - сколько;
        return сколько;
    }

    /// <summary>Затопить печку в дежурке на сегодня — топливо из кладовой.</summary>
    public string? Затопить(House h)
    {
        if (где != ВУчастке.УЧАСТОК)
            return "из камеры до печки не дотянуться";
        if (печь_топится(h.day))
            return "печка уже топится";
        if (_кладовая.Взять("топливо", 0.0) < данные.печь_топлива)
            return "топить нечем: в кладовой пусто";
        _кладовая["топливо"] = _кладовая.Взять("топливо", 0.0) - данные.печь_топлива;
        _печь_день = h.day;
        return null;
    }

    /// <summary>Взять оружие из оружейной: при себе и в руку жильцу
    /// (оружие дома — `NPC.weapon`), патроны — в тару.</summary>
    public string? Вооружиться(NPC я, string id, Инструменты каталог, РучкиПетли ручки)
    {
        if (где != ВУчастке.УЧАСТОК)
            return "оружейная за дверью камеры";
        if (!_оружейная.Contains(id))
            return "такого здесь нет";
        var оружие = каталог.Оружие_из(id);
        if (оружие is null)
            return "это не оружие";
        _оружейная.Remove(id);
        я.weapon = оружие.Value;
        я.снаряжение?.Подобрать(id, каталог);
        if (_патронов > 0)
        {
            я.ноша ??= new Ноша();
            var тара = я.ноша.тара ?? Тара.ПАКЕТ;
            double взял = Math.Min(_патронов, я.ноша.свободно(тара, ручки));
            if (взял > 0)
            {
                var п = Словари.Числа();
                п["патроны"] = взял;
                я.ноша.Положить(тара, п, ручки);
                _патронов -= взял;
            }
        }
        return null;
    }

    /// <summary>Забрать своё из вещдоков: снаряжение — при себе,
    /// сумку — в руки. Сколько вещей вернулось.</summary>
    public int Забрать_своё(NPC я, Инструменты каталог, РучкиПетли ручки)
    {
        if (где != ВУчастке.УЧАСТОК)
            return 0;
        int вернулось = 0;
        foreach (var id in _отобрано.ToList())
            if (я.снаряжение?.Подобрать(id, каталог) == true)
            {
                _отобрано.Remove(id);
                вернулось++;
            }
        if (_вещдоки.Ключи.Count > 0)
        {
            я.ноша ??= new Ноша();
            var тара = я.ноша.тара ?? _тара_вещдоков ?? Тара.ПАКЕТ;
            var взять = Словари.Числа();
            foreach (var р in _вещдоки.Ключи.ToList())
                взять[р] = _вещдоки[р];
            var не_влезло = я.ноша.Положить(тара, взять, ручки);
            _вещдоки.Очистить();
            foreach (var р in не_влезло.Ключи)
                _вещдоки[р] = не_влезло[р];
            вернулось += взять.Ключи.Count;
        }
        return вернулось;
    }

    /// <summary>Ушёл из участка — домой или куда ещё: греется снова дома.</summary>
    public void Ушёл(NPC я)
    {
        где = ВУчастке.НЕТ;
        if (ReferenceEquals(я.приют, this))
            я.приют = null;
    }

    /// <summary>Пришёл в участок походом (в метель): дверь открыта, дежурных
    /// нет — свободен в коридоре.</summary>
    public void Пришёл(NPC я)
    {
        где = ВУчастке.УЧАСТОК;
        я.приют = this;
    }
}
