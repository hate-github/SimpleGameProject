    /// <summary>
    /// Конец дня, ночь позади. Кто выследил участок, тот с шансом «придут»
    /// идёт за запасом: сам голодный — охотнее (`desperation`), боится
    /// героя — реже; по завалу — только в снегоступах, как герой. С собой
    /// зовёт тех, кого позвал бы на налёт на героя: та же вербовка дома,
    /// прикидкой — никого не спрашивают. Героя здесь нет — уносят долю
    /// каждого запаса к себе; герой в камере — слышит; герой здесь —
    /// на рассвете стучат в дверь дежурки и ждут ответа (<see cref="визит"/>).
    /// Броски — от зерна, мимо `h.rng`.
    /// </summary>
    public void Конец_дня(House h, NPC я, Округа о)
    {
        if (данные.гости is not { } г || !я.alive || h.day < 1 || визит is not null || запас_всего < 1.0)
            return;
        NPC? вожак = null;
        foreach (var id in _знают.OrderBy(x => x, StringComparer.Ordinal))
        {
            if (h.живой(id) is not NPC p || !Может_идти(p) || о.Закрыто(h, p, "участок"))
                continue;
            double шанс = г.придут * (0.4 + 0.6 * p.desperation()) * (1.0 - p.боится(я.id));
            if (Округа.Бросок(_зерно, "к_участку", id, h.day) < шанс)
            {
                вожак = p;
                break;
            }
        }
        if (вожак is null)
            return;
        var идут = new List<NPC> { вожак };
        foreach (var p in Конфликт.recruit(h, вожак, я, прикидка: true).crew)
            if (идут.Count < 1 + г.с_собой && !ReferenceEquals(p, вожак) && Может_идти(p))
                идут.Add(p);
        Пришли(h, идут);
    }

    /// <summary>
    /// Пришли за запасом (первый — кто привёл). Героя нет — уносят долю
    /// каждого запаса, он увидит пропажу, когда придёт; герой в камере —
    /// слышит; герой здесь — стучат и ждут ответа (<see cref="визит"/>).
    /// </summary>
    public void Пришли(House h, IReadOnlyList<NPC> идут)
    {
        if (данные.гости is not { } г || идут.Count == 0)
            return;
        if (где == ВУчастке.УЧАСТОК)
        {
            lock (_замок)
                _визит = new Визит(идут.Select(p => p.id).ToList(), h.day + 1);
            return;
        }
        var унесли = Унести(идут, г.унесут_доля, без_героя: true);
        if (где == ВУчастке.КАМЕРА && унесли.Count > 0)
            Сказать("ночью по коридору ходили: из-за решётки было слышно, как выгребают кладовую");
    }

    private static bool Может_идти(NPC p) => p.здесь() && p.health >= 40 && p.injuries.Count < 2;

    /// <summary>
    /// Ответ тем, кто стучит (<see cref="визит"/>). Открыл и поделился —
    /// уносят «отдать» и уходят, и зла не держат. Не открыл — железная
    /// дверь держит с шансом «дверь.держит», хуже за каждого лишнего;
    /// выломали — драка без перевеса дверей. Встретил в дверях с оружием —
    /// они его видят и с шансом «угроза» × (своя сила / их сила) пятятся;
    /// нет — драка с перевесом «стены». Драка — сила на силу (`NPC.power`):
    /// отбился — самый сильный из них уходит битым, все — со страхом
    /// и обидой; нет — избили и унесли «силой». Насмерть здесь не бьют:
    /// тело в участке дому некуда положить — смерть дома лежит в квартире.
    /// Героя уже нет — уносят без него. Броски — от зерна, мимо `h.rng`.
    /// </summary>
    public ИтогВстречи Встретить(House h, NPC я, Встреча как)
    {
        Визит? в;
        lock (_замок)
        {
            в = _визит;
            _визит = null;
        }
        var г = данные.гости!;
        var пусто = Словари.Числа();
        var идут = в is null ? new List<NPC>()
            : в.кто.Select(id => h.живой(id)).OfType<NPC>().Where(p => p.здесь()).ToList();
        if (идут.Count == 0)
            return new ИтогВстречи("за дверью стихло — ушли", пусто, false, false);
        if (где != ВУчастке.УЧАСТОК)
            return new ИтогВстречи("", Унести(идут, г.унесут_доля, без_героя: true), false, false);
        h.событие(ВидСобытия.НАЛЁТ, кто: идут[0].id, кому: я.id, сколько: идут.Count);
        switch (как)
        {
            case Встреча.ОТДАТЬ:
            {
                var унесли = Унести(идут, г.отдать_доля, без_героя: false);
                // открыл сам — не враг: взявший это помнит
                foreach (var p in идут)
                    Социальное.adjust(p, я.id, trust: 0.3);
                return new ИтогВстречи($"открыл и поделился — взяли {Что(унесли)} и ушли", унесли, false, false);
            }
            case Встреча.НЕ_ОТКРЫВАТЬ:
            {
                double держит = Util.Clamp(г.дверь_держит - г.дверь_за_каждого * (идут.Count - 1), 0.05, 0.95);
                if (Округа.Бросок(_зерно, "дверь_участка", я.id, h.day) < держит)
                {
                    foreach (var p in идут)
                        Социальное.обидели(h, p, я, г.обида * 0.5, вслух: false);
                    return new ИтогВстречи("не открыл: колотили, ругались, пробовали дверь ломом — железная, "
                                           + "выдержала; ушли ни с чем", пусто, false, false);
                }
                return Драка(h, я, идут, г, ворвались: true);
            }
            default:
            {
                if (я.weapon != Оружие.НЕТ)
                {
                    double моя = Сила(я), их = Util.Sum(идут.Select(p => p.power()));
                    double попятятся = Util.Clamp(г.угроза * моя / Math.Max(0.1, их), 0.05, 0.95);
                    Социальное.увидел_оружие(h, null, я, свидетели: идут);
                    if (Округа.Бросок(_зерно, "угроза_участка", я.id, h.day) < попятятся)
                        return new ИтогВстречи($"вышел навстречу, в руках — {я.weapon.Текст()}: посмотрели — "
                                               + "попятились и ушли", пусто, true, false);
                }
                return Драка(h, я, идут, г, ворвались: false);
            }
        }
    }

    private ИтогВстречи Драка(House h, NPC я, List<NPC> идут, ГостиУчастка г, bool ворвались)
    {
        double моя = Сила(я) * (ворвались ? 1.0 : г.стены);
        double их = Util.Sum(идут.Select(p => p.power()));
        bool выстрел = Таблицы.ОГНЕСТРЕЛ.Contains(я.weapon)
                       && (я.ноша?.Сколько("патроны") ?? 0.0) + я.stock.Взять("патроны", 0.0) >= 1.0;
        if (выстрел)
            Патрон(я);
        double урон = г.урон_мин + (г.урон_макс - г.урон_мин) * Округа.Бросок(_зерно, "урон_участка", я.id, h.day);
        string начало = ворвались ? "дверь выломали — " : "";
        if (Округа.Бросок(_зерно, "драка_участка", я.id, h.day) < моя / (моя + их))
        {
            var битый = идут.OrderByDescending(p => p.power()).ThenBy(p => p.id, StringComparer.Ordinal).First();
            битый.health = Math.Max(1.0, битый.health - урон * (выстрел ? 1.6 : 1.0));
            битый.injuries.Add(выстрел ? "огнестрел" : "ушиб");
            я.health = Math.Max(1.0, я.health - урон * 0.3);
            foreach (var p in идут)
            {
                Социальное.испугался(h, p, я, г.страх);
                Социальное.обидели(h, p, я, г.обида, вслух: false);
            }
            return new ИтогВстречи(начало + (выстрел
                    ? "выстрелил: один осел с простреленной ногой, его уволокли — ушли"
                    : "сцепились в дверях — отбился: один ушёл битым, остальные следом"),
                Словари.Числа(), true, ворвались);
        }
        я.health = Math.Max(1.0, я.health - урон);
        я.injuries.Add("ушиб");
        foreach (var p in идут)
            Социальное.обидели(h, я, p, г.обида, вслух: false);
        var унесли = Унести(идут, г.силой_доля, без_героя: false);
        return new ИтогВстречи(начало + $"не отбился: избили и забрали {Что(унесли)}", унесли, false, ворвались);
    }

    /// <summary>Сила героя в дверях. Патроны у него в таре, а `NPC.power`
    /// смотрит в шкаф, — на время счёта они там.</summary>
    private static double Сила(NPC я)
    {
        double в_таре = я.ноша?.Сколько("патроны") ?? 0.0;
        if (в_таре <= 0.0)
            return я.power();
        bool было = я.stock.Есть("патроны");
        double сколько = я.stock.Взять("патроны", 0.0);
        я.stock["патроны"] = сколько + в_таре;
        try
        {
            return я.power();
        }
        finally
        {
            if (было)
                я.stock["патроны"] = сколько;
            else
                я.stock.Убрать("патроны");
        }
    }

    private static void Патрон(NPC я)
    {
        if ((я.ноша?.Сколько("патроны") ?? 0.0) >= 1.0)
            я.ноша!.Вынуть("патроны", 1.0);
        else
            я.stock["патроны"] = Math.Max(0.0, я.stock.Взять("патроны", 0.0) - 1.0);
    }

    /// <summary>Унести долю каждого запаса — поровну тем, кто пришёл.
    /// Без героя — это пропажа, он увидит её, когда придёт.</summary>
    private Словарь<string, double> Унести(IReadOnlyList<NPC> кто, double доля, bool без_героя)
    {
        var унесли = Словари.Числа();
        foreach (var р in _кладовая.Ключи)
        {
            double взял = Math.Floor(_кладовая[р] * доля);
            if (взял < 1.0)
                continue;
            _кладовая[р] -= взял;
            унесли[р] = взял;
            foreach (var p in кто)
                p.stock[р] = p.stock.Взять(р, 0.0) + взял / кто.Count;
        }
        if (без_героя)
            lock (_замок)
                foreach (var р in унесли.Ключи)
                    _пропало[р] = _пропало.Взять(р, 0.0) + унесли[р];
        return унесли;
    }

    private static string Что(Словарь<string, double> унесли)
        => унесли.Count == 0 ? "немного"
            : string.Join(", ", унесли.Ключи.Select(р => $"{р} {Текст.G(унесли[р])}"));

    private void Сказать(string что)
    {
        lock (_замок)
            _вести.Enqueue(что);
    }

    /// <summary>Что сказать герою — по одному; нет — null.</summary>
    public string? Весть()
    {
        lock (_замок)
            return _вести.Count > 0 ? _вести.Dequeue() : null;
    }

    /// <summary>Что пропало из кладовой без героя — он видит, когда придёт;
    /// после этого список пуст.</summary>
    public Словарь<string, double> Пропажи()
    {
        lock (_замок)
        {
            var было = Словари.Числа();
            foreach (var р in _пропало.Ключи)
                было[р] = _пропало[р];
            _пропало.Очистить();
            return было;
        }
    }

