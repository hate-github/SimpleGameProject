        return null;
    }

    /// <summary>Взять оружие из оружейной: при себе и в руку жильцу
    /// (оружие дома — `NPC.weapon`), патроны — в тару.</summary>
    public string? Вооружиться(NPC я, string id, Инструменты каталог, РучкиПетли ручки)
    {
        if (где != ВУчастке.УЧАСТОК)
            return "оружейная за дверью камеры";
        if (!_оружейная.Contains(id))
            return "такого здесь нет";
        var оружие = каталог.Оружие_из(id);
        if (оружие is null)
            return "это не оружие";
        _оружейная.Remove(id);
        я.weapon = оружие.Value;
        я.снаряжение?.Подобрать(id, каталог);
        if (_патронов > 0)
        {
            я.ноша ??= new Ноша();
            var тара = я.ноша.тара ?? Тара.ПАКЕТ;
            double взял = Math.Min(_патронов, я.ноша.свободно(тара, ручки));
            if (взял > 0)
            {
                var п = Словари.Числа();
                п["патроны"] = взял;
                я.ноша.Положить(тара, п, ручки);
                _патронов -= взял;
            }
        }
        return null;
    }

    /// <summary>Забрать своё из вещдоков: снаряжение — при себе,
    /// сумку — в руки. Сколько вещей вернулось.</summary>
    public int Забрать_своё(NPC я, Инструменты каталог, РучкиПетли ручки)
    {
        if (где != ВУчастке.УЧАСТОК)
            return 0;
        int вернулось = 0;
        foreach (var id in _отобрано.ToList())
            if (я.снаряжение?.Подобрать(id, каталог) == true)
            {
                _отобрано.Remove(id);
                вернулось++;
            }
        if (_вещдоки.Ключи.Count > 0)
        {
            я.ноша ??= new Ноша();
            var тара = я.ноша.тара ?? _тара_вещдоков ?? Тара.ПАКЕТ;
            var взять = Словари.Числа();
            foreach (var р in _вещдоки.Ключи.ToList())
                взять[р] = _вещдоки[р];
            var не_влезло = я.ноша.Положить(тара, взять, ручки);
            _вещдоки.Очистить();
            foreach (var р in не_влезло.Ключи)
                _вещдоки[р] = не_влезло[р];
            вернулось += взять.Ключи.Count;
        }
        return вернулось;
    }

