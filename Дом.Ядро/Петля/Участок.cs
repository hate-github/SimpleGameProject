// Полицейский участок в метель (задание автора, пп. 16–18).
//
// Попасться на краже до метели — значит оказаться здесь: задержали, забрали
// сумку и снаряжение (карман вне времени не отнять — его нет в мире), ночь
// в камере — а утром метель, и дежурные разошлись по домам. Камера заперта,
// участок пуст. Время тут идёт так же, как везде: дом живёт своё, и герой
// в нём по-прежнему жилец — только греется и ест он не дома, а здесь.
//
//   · **выбраться** — ломать дверь камеры: тяжёлым инструментом (монтировка,
//     топор — что есть при себе, а при себе после задержания только то,
//     что было в кармане) — часы и шанс по замку «железная_дверь»;
//     голыми руками — долго, редко и с кровью. Не вышел — холод и голод
//     по тому, что при себе (п. 17: «не случайный Game Over»);
//   · **остаться** (п. 18) — участок как убежище (`IУбежище`, правила быта —
//     `Убежище`): кладовая (еды на месяц одному), оружейная (игровой набор),
//     вещдоки (своё, отобранное), печка в дежурке — тепло, пока есть чем
//     топить; на ней же топят снег на воду, а топливо, когда кончится, —
//     столы и шкафы дежурки (`мебель`); принесённое из дома выкладывают
//     в кладовую;
//   · **вернуться домой** — дорога по сегодняшнему снегу, как поход;
//   · **гости** — ходки с полной тарой к участку и от него видно из окон,
//     как у бункера: заметивший не в первый раз идёт по следу и знает,
//     откуда герой носит. Такой приходит за запасом (сам голодный —
//     охотнее, боится героя — реже) и зовёт с собой, кого позвал бы
//     на налёт. Героя нет — уносят долю; герой здесь — стучат в дверь
//     дежурки, и отвечает он: поделиться, не открыть, встретить в дверях
//     (просьба автора: «к нему в участок пришли люди, чтобы ограбить» —
//     и распорядок от этого встаёт).
//
// Тепло — единственное, что участок подсказывает дому: пока герой здесь,
// его комната — здесь (`IПриют`). У соседей приюта нет, и дом считает их,
// как считал; сам участок живёт в округе героя — мимо снимка и сейва.

namespace Дом.Ядро;

/// <summary>Где герой греется, если не дома, — только у игрока; у соседей
/// null, и комнату им считает дом.</summary>
public interface IПриют
{
    /// <summary>Температура там, где он сейчас, — или null: дома.</summary>
    double? Температура(House h, NPC кто);
}

/// <summary>Где герой в участке: не там, заперт в камере, свободен.</summary>
public enum ВУчастке { НЕТ, КАМЕРА, УЧАСТОК }

/// <summary>Числа участка из `data/мир.json`, «участок».</summary>
public sealed record ДанныеУчастка(
    string имя,
    double дорога_часов,
    string замок_камеры,
    double камера_градусов,
    double участок_градусов,
    double печь_градусов,
    double печь_топлива,
    double руками_часов,
    double руками_шанс,
    double руками_урон,
    IReadOnlyDictionary<string, double> кладовая,
    IReadOnlyList<string> оружейная,
    double патронов)
{
    /// <summary>Кто приходит за запасом и чем кончается у двери; null — никто.</summary>
    public ГостиУчастка? гости { get; init; }

    /// <summary>Мебель дежурки на дрова: сколько раз, топлива за раз, часов.</summary>
    public int мебели { get; init; }
    public double мебель_топлива { get; init; }
    public double мебель_часов { get; init; } = 1.0;

    public static ДанныеУчастка Прочитать(System.Text.Json.JsonElement у)
    {
        var к = у.GetProperty("камера");
        var р = у.GetProperty("руками");
        var п = у.GetProperty("печь");
        var о = у.GetProperty("оружейная");
        var кладовая = new Dictionary<string, double>(StringComparer.Ordinal);
        foreach (var x in у.GetProperty("кладовая").EnumerateObject())
            кладовая[x.Name] = x.Value.GetDouble();
        var мебель = у.TryGetProperty("мебель", out var м) ? м : (System.Text.Json.JsonElement?)null;
        return new ДанныеУчастка(
            у.GetProperty("имя").GetString()!,
            у.GetProperty("дорога_часов").GetDouble(),
            к.GetProperty("замок").GetString()!,
            к.GetProperty("градусов").GetDouble(),
            у.GetProperty("участок_градусов").GetDouble(),
            п.GetProperty("градусов").GetDouble(),
            п.GetProperty("топлива").GetDouble(),
            р.GetProperty("часов").GetDouble(),
            р.GetProperty("шанс").GetDouble(),
            р.GetProperty("урон").GetDouble(),
            кладовая,
            о.GetProperty("оружие").EnumerateArray().Select(x => x.GetString()!).ToList(),
            о.GetProperty("патроны").GetDouble())
        {
            мебели = мебель?.GetProperty("раз").GetInt32() ?? 0,
            мебель_топлива = мебель?.GetProperty("топлива").GetDouble() ?? 0.0,
            мебель_часов = мебель?.GetProperty("часов").GetDouble() ?? 1.0,
            гости = у.TryGetProperty("гости", out var г) ? ГостиУчастка.Прочитать(г) : null,
        };
    }
}

/// <summary>
/// Кто приходит в участок за чужим и чем это кончается (`гости` в мир.json).
/// «ходки» — как у бункера: видят с шансом «заметят», решают о запасах героя
/// с весом «вес», выслеживают за «выследят» ходок. «придут» — шанс за ночь
/// у выследившего (с его нуждой и страхом), «с_собой» — сколько он позовёт.
/// «доля» — сколько каждого запаса уносят без героя, отданным и силой.
/// «дверь» — держит ли железная дверь дежурки и насколько хуже
/// за каждого лишнего. «угроза» — с оружием в руках: своя сила к их силе,
/// умноженная на это, — шанс, что попятятся. «стены» — перевес того,
/// кто встретил в дверях. «урон» — сколько здоровья стоит драка
/// проигравшему, от и до. «страх» и «обида» — что остаётся у битых.
/// </summary>
public sealed record ГостиУчастка(
    double заметят, double вес, int выследят,
    double придут, int с_собой,
    double унесут_доля, double отдать_доля, double силой_доля,
    double дверь_держит, double дверь_за_каждого,
    double угроза, double стены,
    double урон_мин, double урон_макс,
    double страх, double обида)
{
    public static ГостиУчастка Прочитать(System.Text.Json.JsonElement г)
    {
        var х = г.GetProperty("ходки");
        var д = г.GetProperty("доля");
        var дв = г.GetProperty("дверь");
        var у = г.GetProperty("урон");
        var гости = new ГостиУчастка(
            х.GetProperty("заметят").GetDouble(),
            х.GetProperty("вес").GetDouble(),
            х.GetProperty("выследят").GetInt32(),
            г.GetProperty("придут").GetDouble(),
            г.GetProperty("с_собой").GetInt32(),
            д.GetProperty("унесут").GetDouble(),
            д.GetProperty("отдать").GetDouble(),
            д.GetProperty("силой").GetDouble(),
            дв.GetProperty("держит").GetDouble(),
            дв.GetProperty("за_каждого").GetDouble(),
            г.GetProperty("угроза").GetDouble(),
            г.GetProperty("стены").GetDouble(),
            у[0].GetDouble(),
            у[1].GetDouble(),
            г.GetProperty("страх").GetDouble(),
            г.GetProperty("обида").GetDouble());
        if (гости.выследят < 1 || гости.с_собой < 0 || гости.урон_мин > гости.урон_макс
            || new[] { гости.заметят, гости.придут, гости.унесут_доля, гости.отдать_доля,
                       гости.силой_доля, гости.дверь_держит, гости.дверь_за_каждого }
                   .Any(x => x is < 0 or > 1))
            throw new InvalidDataException("мир.json: участок, «гости» — шансы и доли от нуля до единицы, "
                                           + "«выследят» от одной ходки, урон «от» не больше «до»");
        return гости;
    }
}

/// <summary>Как встретить тех, кто пришёл к участку.</summary>
public enum Встреча
{
    /// <summary>Открыть и поделиться: уносят долю и уходят.</summary>
    ОТДАТЬ,
    /// <summary>Не открывать: железная дверь держит — или нет.</summary>
    НЕ_ОТКРЫВАТЬ,
    /// <summary>Встретить в дверях: с оружием — пригрозить, без — драться.</summary>
    ВСТРЕТИТЬ,
}

/// <summary>Пришли к участку, пока герой там: кто (первый — кто привёл)
/// и с какого дня ждут ответа.</summary>
public sealed record Визит(IReadOnlyList<string> кто, int день);

/// <summary>Чем кончилось у двери: что сказать, что унесли, отбился ли,
/// выломали ли дверь.</summary>
public sealed record ИтогВстречи(string весть, Словарь<string, double> унесли, bool отбился, bool ворвались);

/// <summary>Чем кончилась попытка выбраться из камеры.</summary>
public sealed record Побег(bool вышел, double часов, string чем, string весть);

public sealed class Участок : IУбежище
{
    public ДанныеУчастка данные { get; }
    private readonly Словарь<string, double> _кладовая = Словари.Числа();
    private readonly List<string> _оружейная = new();
    private double _патронов;
    private readonly Словарь<string, double> _вещдоки = Словари.Числа();
    private Тара? _тара_вещдоков;
    private readonly List<string> _отобрано = new();
    private int _печь_день = -99;
    private int _мебели_разобрано;
    private readonly long _зерно;
    private int _ходок;
    private readonly Dictionary<string, int> _заметил = new(StringComparer.Ordinal);
    private readonly HashSet<string> _знают = new(StringComparer.Ordinal);
    private readonly Словарь<string, double> _пропало = Словари.Числа();
    private readonly Queue<string> _вести = new();
    private Визит? _визит;
    private readonly object _замок = new();

    public Участок(ДанныеУчастка д, long зерно = 0)
    {
        данные = д;
        _зерно = зерно;
        foreach (var (р, сколько) in д.кладовая.OrderBy(п => п.Key, StringComparer.Ordinal))
            _кладовая[р] = сколько;
        _оружейная.AddRange(д.оружейная);
        _патронов = д.патронов;
    }

    /// <summary>Где герой: не здесь, в камере, свободен в участке.</summary>
    public ВУчастке где { get; private set; }

    public IReadOnlyList<string> кладовая_что => _кладовая.Ключи;
    public double В_кладовой(string р) => _кладовая.Взять(р, 0.0);
    public IReadOnlyList<string> оружейная => _оружейная;
    public double патронов => _патронов;
    public IReadOnlyList<string> отобрано => _отобрано;
    public IReadOnlyList<string> вещдоки_что => _вещдоки.Ключи;
    public double В_вещдоках(string р) => _вещдоки.Взять(р, 0.0);
    public bool печь_топится(int день) => _печь_день == день;

    /// <summary>Сколько мебели дежурки ещё не сожжено.</summary>
    public int мебели_осталось => Math.Max(0, данные.мебели - _мебели_разобрано);

    /// <summary>Всего в кладовой — есть ли вообще за чем приходить.</summary>
    public double запас_всего => Util.Sum(_кладовая.Ключи.Select(к => _кладовая[к]));

    /// <summary>Кто из соседей выследил, откуда герой носит. Герою не видно.</summary>
    public IReadOnlyCollection<string> знают => _знают;

    /// <summary>Пришли и стучат, пока герой здесь, — ждут ответа; нет — null.</summary>
    public Визит? визит
    {
        get { lock (_замок) return _визит; }
    }

    // ------------------------------------------------------------ убежище

    public string Где => "участок";
    public bool Доступно => где == ВУчастке.УЧАСТОК;
    public double В_запасе(string ресурс) => _кладовая.Взять(ресурс, 0.0);
    public void Изъять(string ресурс, double сколько)
        => _кладовая[ресурс] = Math.Max(0.0, _кладовая.Взять(ресурс, 0.0) - сколько);
    public void Добавить(string ресурс, double сколько)
        => _кладовая[ресурс] = _кладовая.Взять(ресурс, 0.0) + сколько;
    public bool Печь_топится(int день) => печь_топится(день);
    public double топлива_на_день => данные.печь_топлива;

    // ------------------------------------------------------------ приют

    public double? Температура(House h, NPC кто) => где switch
    {
        ВУчастке.КАМЕРА => данные.камера_градусов,
        ВУчастке.УЧАСТОК => данные.участок_градусов + (печь_топится(h.day) ? данные.печь_градусов : 0.0),
        _ => null,
    };

    // ------------------------------------------------------------ задержание

    /// <summary>
    /// Задержали: сумку — в вещдоки, снаряжение (инструменты, снегоступы,
    /// оружие в руках) — туда же; карман вне времени не отнять. Герой —
    /// в камере, и греется теперь здесь.
    /// </summary>
    public void Задержать(NPC я)
    {
        if (я.ноша is { пусто: false } ноша)
        {
            _тара_вещдоков = ноша.тара;
            foreach (var р in ноша.ресурсы.ToList())
                _вещдоки[р] = _вещдоки.Взять(р, 0.0) + ноша.Сколько(р);
            ноша.Обнулить();
        }
        if (я.снаряжение is { } с)
            foreach (var id in с.с_собой.OrderBy(x => x, StringComparer.Ordinal).ToList())
                if (с.Положить_насовсем(id))
                    _отобрано.Add(id);
        где = ВУчастке.КАМЕРА;
        я.приют = this;
    }

    // ------------------------------------------------------------ побег

    /// <summary>Чем ломать дверь камеры: инструмент при себе, который берёт
    /// её замок, — лучший по шансу; нет — голые руки (null).</summary>
    public string? Чем_ломать(NPC я, Инструменты каталог)
        => я.снаряжение?.с_собой
            .Where(id => Приём_(id, каталог) is not null)
            .OrderByDescending(id => Приём_(id, каталог)!.шанс)
            .ThenBy(id => id, StringComparer.Ordinal)
            .FirstOrDefault();

    private Приём? Приём_(string id, Инструменты каталог)
        => каталог.все.TryGetValue(id, out var и) ? и.Берёт(данные.замок_камеры) : null;

    /// <summary>Сколько часов уйдёт на попытку: инструментом — по замку,
    /// руками — долго.</summary>
    public double Часов_ломать(House h, string? инструмент, Инструменты каталог)
        => инструмент is string и && Приём_(и, каталог) is { } з
            ? Взлом.часы(h, з) : данные.руками_часов;

    /// <summary>
    /// Попытка выбраться: часы уже ушли делом. Инструментом — шанс по замку
    /// (мерка работы, как взлом), руками — `руками_шанс` и кровь. Бросок —
    /// исход, из `h.rng`. Вышел — свободен в участке.
    /// </summary>
    public Побег Ломать(House h, NPC я, string? инструмент, Инструменты каталог, РучкиПетли ручки,
                        double качество = 0.5)
    {
        if (где != ВУчастке.КАМЕРА)
            return new Побег(где == ВУчастке.УЧАСТОК, 0, "", "дверь камеры и так открыта");
        double часов = Часов_ломать(h, инструмент, каталог);
        if (инструмент is string и && Приём_(и, каталог) is { } з)
        {
            double шанс = МиниИгры.Шанс(Взлом.шанс(h, я, ручки, з), качество, ручки);
            string чем = каталог.все[и].чем;
            if (!h.rng.Chance(шанс))
                return new Побег(false, часов, чем, $"{чем} — дверь держит; ещё раз");
            где = ВУчастке.УЧАСТОК;
            return new Побег(true, часов, чем, $"{чем} — замок камеры сорван, ты в коридоре участка");
        }
        я.health = Math.Max(1.0, я.health - данные.руками_урон);
        if (!h.rng.Chance(МиниИгры.Шанс(данные.руками_шанс, качество, ручки)))
            return new Побег(false, часов, "руками", "решётку не расшатать — только ободрал руки в кровь");
        где = ВУчастке.УЧАСТОК;
        return new Побег(true, часов, "руками", "прут решётки поддался — протиснулся в коридор");
    }

    // ------------------------------------------------------------ участок

    /// <summary>Поесть или попить из кладовой — как дома: порция или сколько
    /// влезло (`Убежище.Порция`). false — не лезет, нечего или ещё в камере.
    /// Часы дела — в <see cref="Сделано"/> у `Убежище.Поесть`; здесь — только итог.</summary>
    public bool Поесть(House h, NPC я, string ресурс)
        => (ресурс == Убежище.ВОДА ? Убежище.Попить(h, я, this) : Убежище.Поесть(h, я, this)).да;

    /// <summary>Съесть или выпить из кармана вне времени — где угодно, и в камере
    /// тоже: единственное, что при себе после задержания. Как из запаса:
    /// не больше порции и не больше, чем лезет.</summary>
    public static Сделано Из_кармана_(House h, NPC я, string ресурс)
        => я.карман is not { } к
            ? new Сделано(false, 0, "кармана нет")
            : Убежище.Порция(h, я, ресурс, к.Сколько(ресурс), с => к.Потратить(ресурс, с));

    /// <summary><see cref="Из_кармана_"/> — только да или нет.</summary>
    public static bool Из_кармана(House h, NPC я, string ресурс) => Из_кармана_(h, я, ресурс).да;

    /// <summary>Разобрать мебель дежурки на дрова — в кладовую. Сколько её,
    /// столько раз (`мебель` в мир.json).</summary>
    public Сделано Разобрать_мебель(House h)
    {
        if (где != ВУчастке.УЧАСТОК)
            return new Сделано(false, 0, "из камеры до мебели не дотянуться");
        if (мебели_осталось <= 0)
            return new Сделано(false, 0, "жечь больше нечего: столы и шкафы уже в печке");
        _мебели_разобрано++;
        Добавить(Убежище.ТОПЛИВО, данные.мебель_топлива);
        return new Сделано(true, данные.мебель_часов,
                           $"разломал мебель на дрова — топлива +{Текст.G(данные.мебель_топлива)}"
                           + (мебели_осталось > 0 ? $", ломать ещё на {мебели_осталось} раз" : ", больше ломать нечего"));
    }

    /// <summary>Выложить из ноши всё — в кладовую участка, мимо дома.</summary>
    public Словарь<string, double> Выложить(NPC я)
    {
        var было = Словари.Числа();
        if (где != ВУчастке.УЧАСТОК || я.ноша is not { пусто: false } ноша)
            return было;
        foreach (var р in ноша.ресурсы.ToList())
        {
            было[р] = ноша.Сколько(р);
            Добавить(р, ноша.Сколько(р));
        }
        ноша.Обнулить();
        return было;
    }

    /// <summary>Взять из кладовой в тару — унести. Сколько влезло.</summary>
    public double Взять(NPC я, string ресурс, double сколько, РучкиПетли ручки)
    {
        if (где != ВУчастке.УЧАСТОК)
            return 0.0;
        я.ноша ??= new Ноша();
        var тара = я.ноша.тара ?? Тара.ПАКЕТ;
        сколько = Math.Min(сколько, Math.Min(_кладовая.Взять(ресурс, 0.0), я.ноша.свободно(тара, ручки)));
        if (сколько <= 0.0)
            return 0.0;
        var взять = Словари.Числа();
        взять[ресурс] = сколько;
        я.ноша.Положить(тара, взять, ручки);
        _кладовая[ресурс] = _кладовая.Взять(ресурс, 0.0) - сколько;
        return сколько;
    }

    /// <summary>Затопить печку в дежурке на сегодня — топливо из кладовой.</summary>
