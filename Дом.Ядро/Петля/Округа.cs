// Округа героя: мир вокруг дома в этой жизни — то, что есть только
// у игрока (задание автора, этап 3).
//
// Дом сверен с прототипом, и прогон без игрока обязан считаться прежним.
// Поэтому всё, что этап 3 добавляет в мир — заметённые улицы, снегоступы,
// заражение, рассказы знатоков, — живёт не в доме, а здесь, и привязано
// к дому только в игре (`Петля.Слушать`). В прогоне без игрока округи нет
// вовсе: каждый вопрос к ней — `Округа.У(h)` — отвечает «нет», и ядро
// считает, как считало. Поля дома для этого не заводятся: округа висит
// на доме таблицей, мимо снимка и сейва.
//
// Здесь — улицы и снегоступы (пп. 11–12):
//   · **улицы глазами героя** (`IУлицы`): куда сегодня замело так, что
//     без снегоступов не пройти, — по летописи (`Летопись.Улица`). Ядро
//     спрашивает об этом, решая, доступно ли место (`Улица.место_доступно`),
//     и только у того, у кого есть улицы, — у героя;
//   · **у кого снегоступы**: у героя — в снаряжении (купил, отнял);
//     у мастеров — с их дня (Пётр-охотник, Руслан-сварщик), пока не отняли;
//     у того, кто отнял;
//   · **кто знает**: сосед — если слышал, как герой вернулся с улицы в тот
//     день, когда туда без снегоступов не пройти (`Ходил_на_снегоступах`);
//     герой — если мастер сам рассказал;
//   · **тяга отнять** (`Тянет`) — прибавка к мере отъёма на лестнице
//     (`Действия._люди`, «отнять»): видят у другого средство выжить —
//     и тянутся к нему, тем сильнее, чем глубже завал. Отняли — снегоступы
//     у того, кто отнял (`Отнять`).
// Соседи между собой за снегоступы не дерутся: это сдвиг эталона и решение
// автора, а не попутная правка.

using System.Runtime.CompilerServices;

namespace Дом.Ядро;

/// <summary>Улицы глазами того, кто их видит, — героя: закрыто ли место
/// снегом. У соседей этого нет, и дорогу им считает дом.</summary>
public interface IУлицы
{
    bool Закрыто(House h, NPC кто, string место);
}

/// <summary>Кто из соседей сам делает снегоступы и с какого дня.</summary>
public sealed record МастерСнегоступов(string кто, int с_дня);

/// <summary>Снегоступы в мире: мастера и сила тяги отнять.</summary>
public sealed record ДанныеСнегоступов(IReadOnlyList<МастерСнегоступов> мастера, double тяга,
                                        double тяга_по_завалу)
{
    public static readonly ДанныеСнегоступов НИКАКИХ = new(Array.Empty<МастерСнегоступов>(), 0.0, 0.0);
}

public sealed class Округа : IУлицы
{
    /// <summary>Id снегоступов в каталоге предметов.</summary>
    public const string СНЕГОСТУПЫ = "снегоступы";

    /// <summary>По какой дороге мерить завал «сегодня вообще».</summary>
    public const string ДОРОГА = "магазин на Заречной";

    private static readonly ConditionalWeakTable<House, Округа> _у = new();

    /// <summary>Округа этого дома — или null: в прогоне без игрока её нет.</summary>
    public static Округа? У(House h) => _у.TryGetValue(h, out var о) ? о : null;

    public string герой { get; }
    public Летопись летопись { get; }
    public long зерно { get; }

    private readonly ДанныеСнегоступов _снегоступы;
    private readonly HashSet<string> _у_соседей = new(StringComparer.Ordinal);
    private readonly HashSet<string> _лишились = new(StringComparer.Ordinal);
    private readonly HashSet<int> _дни_на_снегоступах = new();
    private readonly HashSet<string> _герой_знает = new(StringComparer.Ordinal);
    private readonly HashSet<string> _знания = new(StringComparer.Ordinal);

    private Округа(string герой, Летопись летопись, long зерно)
    {
        this.герой = герой;
        this.летопись = летопись;
        this.зерно = зерно;
        _снегоступы = летопись.снегоступы;
    }

    /// <summary>
    /// Завести округу на этот дом и дать герою улицы. Зовётся петлёй
    /// до `run()`. Наблюдатель вылазок записывает, когда герой ходил
    /// по завалу: ничего в доме не меняет и `rng` не трогает.
    /// </summary>
    public static Округа Завести(House h, string герой, Летопись летопись, long зерно)
    {
        var о = new Округа(герой, летопись, зерно);
        _у.AddOrUpdate(h, о);
        h.people[герой].улицы = о;
        h.hooks.on_outing.Add((дом, npc, _, м, _) =>
        {
            if (string.Equals(npc.id, герой, StringComparison.Ordinal)
                && !летопись.Пройти(м.имя, дом.day, зерно, снегоступы: false))
                о.Ходил_на_снегоступах(дом.day);
        });
        return о;
    }

    // ------------------------------------------------------------ улицы

    public bool Закрыто(House h, NPC кто, string место)
        => !летопись.Пройти(место, h.day, зерно, Есть_у(h, кто));

    /// <summary>Сколько снега сегодня на дороге к месту.</summary>
    public СостояниеУлицы Улица(House h, string место) => летопись.Улица(место, h.day, зерно);

    // ------------------------------------------------------------ походы

    /// <summary>Что герой знает о мире: где промзона, где искать бункер.
    /// Узнаёт от знатоков; держится до конца жизни.</summary>
    public IReadOnlyCollection<string> знания => _знания;

    public bool Знает(string что) => _знания.Contains(что);

    public void Узнал(string что) => _знания.Add(что);

    /// <summary>Часов дороги в один конец по сегодняшнему снегу — в снегоступах
    /// или без.</summary>
    public double Часы_дороги(House h, NPC я, Поход п)
        => п.часы * летопись.Часы_дороги(Улица(h, п.улица), Есть_у(h, я));

    /// <summary>
    /// Почему в этот поход сегодня не пойти — или null, если можно: не знаешь,
    /// куда идти; замело, а снегоступов нет; до ночи не обернуться
    /// (туда и обратно, и <paramref name="там_часов"/> на месте).
    /// </summary>
    public string? Нельзя(House h, NPC я, Поход п, double там_часов = 0.0)
    {
        if (п.знать is string что && !Знает(что))
            return "не знаешь, где это";
        if (!летопись.Пройти(п.улица, h.day, зерно, Есть_у(h, я)))
            return "замело — без снегоступов не пройти";
        double часов = 2.0 * Часы_дороги(h, я, п) + там_часов;
        if (я.time_left < часов - 1e-9)
            return $"до ночи не обернуться: нужно {Текст.G(Текст.Округлить(часов, 1))} ч";
        return null;
    }

    /// <summary>
    /// Герой вернулся из похода к дому: дом это слышит, как возвращение
    /// с вылазки, и если сегодня туда без снегоступов не пройти — кто
    /// слышал, знает, что снегоступы у него есть. Только пока дом спит.
    /// </summary>
    public void Вернулся(House h, NPC я, Поход п)
    {
        if (!летопись.Пройти(п.улица, h.day, зерно, снегоступы: false))
            Ходил_на_снегоступах(h.day);
        Социальное.emit(h, я, 2, "возвращение", night: false);
    }

    // ------------------------------------------------------------ снегоступы

    /// <summary>Есть ли снегоступы у этого человека сегодня.</summary>
    public bool Есть_у(House h, NPC кто)
    {
        if (!кто.alive)
            return false;
        if (string.Equals(кто.id, герой, StringComparison.Ordinal))
            return кто.снаряжение?.Есть(СНЕГОСТУПЫ) == true;
        if (_у_соседей.Contains(кто.id))
            return true;
        return !_лишились.Contains(кто.id)
               && _снегоступы.мастера.Any(м => string.Equals(м.кто, кто.id, StringComparison.Ordinal)
                                                && м.с_дня <= h.day);
    }

    /// <summary>Герой сегодня ходил по завалу — значит, в снегоступах: кто слышал,
    /// как он вернулся, знает, что они у него есть.</summary>
    public void Ходил_на_снегоступах(int день) => _дни_на_снегоступах.Add(день);

    /// <summary>Мастер сам сказал герою, что сделал себе снегоступы.</summary>
    public void Герой_узнал(string у_кого) => _герой_знает.Add(у_кого);

    /// <summary>Знает ли <paramref name="кто"/>, что у <paramref name="у_кого"/>
    /// есть снегоступы. Сосед о герое — по возвращению в день завала;
    /// герой о соседе — по рассказу. Соседи друг о друге — нет.</summary>
    public bool Знает(NPC кто, NPC у_кого)
    {
        if (string.Equals(у_кого.id, герой, StringComparison.Ordinal))
            return кто.memory.Any(м => string.Equals(м.кто, герой, StringComparison.Ordinal)
                                       && string.Equals(м.что, "возвращение", StringComparison.Ordinal)
                                       && _дни_на_снегоступах.Contains(м.день));
        if (string.Equals(кто.id, герой, StringComparison.Ordinal))
            return _герой_знает.Contains(у_кого.id);
        return false;
    }

    /// <summary>
    /// Насколько <paramref name="кто"/> тянется отнять у <paramref name="у_кого"/>
    /// снегоступы: ноль, если их нет или он о них не знает; иначе тяга
    /// и ещё по стольку же за каждый уровень завала сегодня.
    /// </summary>
    public double Тянет(House h, NPC кто, NPC у_кого)
    {
        if (!Есть_у(h, у_кого) || Есть_у(h, кто) || !Знает(кто, у_кого))
            return 0.0;
        int завал = (int)Улица(h, ДОРОГА);
        return _снегоступы.тяга + _снегоступы.тяга_по_завалу * завал / (double)СостояниеУлицы.ЗАВАЛЕНО;
    }

    /// <summary>
    /// Отнять снегоступы: были у жертвы и отнимавший за ними тянулся —
    /// теперь у него. Возвращает строку для журнала или null.
    /// </summary>
    public string? Отнять(House h, NPC кто, NPC у_кого)
    {
        if (Тянет(h, кто, у_кого) <= 0.0)
            return null;
        if (string.Equals(у_кого.id, герой, StringComparison.Ordinal))
            у_кого.снаряжение?.Положить_насовсем(СНЕГОСТУПЫ);
        else
        {
            _у_соседей.Remove(у_кого.id);
            _лишились.Add(у_кого.id);
        }
        if (string.Equals(кто.id, герой, StringComparison.Ordinal))
            кто.снаряжение?.Подобрать(СНЕГОСТУПЫ);
        else
            _у_соседей.Add(кто.id);
        return $"   И снегоступы — {Util.Vb(кто.sex, "забрал")} тоже.";
    }
}
