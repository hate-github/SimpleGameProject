// Ход времени (задание автора, пп. 24–25): время идёт само.
//
// До этого время в доме шло только от решений героя: дом спал на вопросе,
// и пока игрок стоял, читал телефон или шёл по лестнице, не проходило
// ни минуты — соседи стояли столбами, пока он не ответит. Задание просит
// иначе: время идёт всегда, в разговоре — медленно, почти как в жизни,
// в долгом деле — быстро, и соседи живут, пока герой возится с замком.
//
// **Дом при этом остаётся ходовым.** Это не упрощение, а то, на чём
// держится сверка с прототипом: дом, который тикает от кадров, на двух
// машинах прожил бы разные жизни. Поэтому часы идут не в доме, а здесь,
// у героя, и отдаются дому шагами: накопился шаг — герой прожил его,
// ничего не делая (`Прожить`), и дом пропускает его ход тем же ответом
// «сам», каким пропускал после взлома (`Партия.Пропустить`). Соседи
// проживают ровно эти часы, и жизнь по-прежнему воспроизводима: она
// зависит от того, сколько часов герой отдал, а не от частоты кадров.
//
// Темпы — четыре, как в задании (Normal, Dialogue, Fast action, Paused):
//   · ОБЫЧНО — стоит или ходит: минута дня за секунду (ГДД 3);
//   · РАЗГОВОР — окно вопроса, телефон, журнал: час за час, как в жизни;
//   · ДЕЛО — долгое дело само говорит, сколько в нём часов, а шкала
//     длится по `Секунд_дела`: полтора часа — десять секунд. Часы дела
//     отдаются кусками (`Кусков`), и между кусками дом живёт;
//   · СТОИТ — карман, карта, настройки: ГДД 9, «в инвентаре и меню время
//     стоит».
//
// Всё это только у игрока: соседи живут ходами дома, как жили.

namespace Дом.Ядро;

/// <summary>С какой скоростью идёт время у героя.</summary>
public enum Темп
{
    /// <summary>Стоит, ходит: минута дня за секунду.</summary>
    ОБЫЧНО,

    /// <summary>Окно вопроса, телефон, журнал: почти как в жизни.</summary>
    РАЗГОВОР,

    /// <summary>Долгое дело: время у дела своё, быстрое, и отдаётся кусками.</summary>
    ДЕЛО,

    /// <summary>Карман, карта, настройки: время стоит.</summary>
    СТОИТ,
}

/// <summary>
/// Часы героя между ходами дома: сколько времени накопилось и когда пора
/// отдать его дому шагом. Держит корневой узел движка; сам не трогает ни
/// дома, ни `h.rng`.
/// </summary>
public sealed class ХодВремени
{
    private readonly double _обычно, _разговор, _шаг;

    public ХодВремени(РучкиПетли ручки)
    {
        _обычно = ручки["время_секунд_на_час"];
        _разговор = ручки["время_разговор_секунд_на_час"];
        _шаг = ручки["время_шаг_часов"];
    }

    /// <summary>Какими шагами время отдаётся дому, в часах дня.</summary>
    public double шаг => _шаг;

    /// <summary>Сколько часов дня накопилось и ещё не отдано дому.</summary>
    public double долг { get; private set; }

    /// <summary>Темп прошлого кадра.</summary>
    public Темп темп { get; private set; } = Темп.ОБЫЧНО;

    /// <summary>Часов дня за секунду при этом темпе. Дело своё время
    /// считает само (<see cref="Секунд_дела"/>), и в долг оно не идёт.</summary>
    public double Скорость(Темп т) => т switch
    {
        Темп.ОБЫЧНО => 1.0 / _обычно,
        Темп.РАЗГОВОР => 1.0 / _разговор,
        _ => 0.0,
    };

    /// <summary>Прошло столько секунд при таком темпе.</summary>
    public void Кадр(double секунд, Темп т)
    {
        темп = т;
        if (секунд > 0.0)
            долг += секунд * Скорость(т);
    }

    /// <summary>Отдать дому шаг, если накопился: столько часов герой
    /// прожил, ничего не делая. Нет — null.</summary>
    public double? Шаг()
    {
        if (долг + 1e-12 < _шаг)
            return null;
        долг = Math.Max(0.0, долг - _шаг);
        return _шаг;
    }

    /// <summary>Забыть накопленное: новая жизнь, новый день у героя.</summary>
    public void Сбросить() => долг = 0.0;

    /// <summary>
    /// Прожить часы, ничего не делая: только у героя и только пока дом
    /// спит на вопросе дня. Больше, чем осталось до ночи, не проживается.
    /// Возвращает, сколько прожито.
    /// </summary>
    public static double Прожить(NPC я, double часы)
    {
        double прожито = Math.Min(Math.Max(0.0, часы), я.time_left);
        я.time_left -= прожито;
        return прожито;
    }

    /// <summary>Сколько секунд шкалы длится дело в столько часов дня:
    /// задание говорит «action_duration_game_time → animation_duration_real_time»,
    /// и скорость времени в деле — их отношение.</summary>
    public static double Секунд_дела(РучкиПетли ручки, double часы)
        => Math.Max(ручки["дело_секунд_не_меньше"], часы * ручки["дело_секунд_на_час"]);

    /// <summary>На сколько кусков дробится дело: между кусками дом живёт.
    /// Полтора часа — пять, сорок минут — два, двадцать — один.</summary>
    public static int Кусков(РучкиПетли ручки, double часы)
        => Math.Clamp((int)Math.Round(часы / ручки["дело_кусок_часов"], MidpointRounding.AwayFromZero),
                      1, (int)ручки["дело_кусков_не_больше"]);

    /// <summary>Часы в виде «14:05» — для строки над телом.</summary>
    public static string Часы(double час)
    {
        double ч = ((час % 24.0) + 24.0) % 24.0;
        int минут = (int)Math.Floor(ч * 60.0 + 1e-9);
        return $"{минут / 60:00}:{минут % 60:00}";
    }
}
