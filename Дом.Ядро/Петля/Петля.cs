// Петля (ГДД 3, 4, 21): герой умирает и просыпается утром первого дня.
//
// Для всех остальных это первый раз. Игра природу петли не объясняет
// никогда; изнутри мира это «частичка души», которая не умирает вместе
// с телом, — она и хранит память, навыки и карман вне времени. Поэтому
// герой принципиально отличается от соседей: они не помнят ничего.
//
// Устройство здесь одно и оно важное: **петля дом не трогает**. Она его
// читает — после того, как жизнь кончилась, — и складывает из прочитанного
// наследие. Ни одного поля дома она не пишет, ни одного броска `rng`
// не делает. Отсюда следует главное свойство: жизнь внутри петли считается
// ровно так же, как обычный прогон с тем же зерном, — и это не рассуждение,
// а проверка (раздел «петля» сверяет снимки).
//
// Зерно у всех жизней одно: мир и соседи проживают те же дни заново,
// календарь погоды и событий строится один раз от зерна и не съезжает
// от действий игрока. Расходится жизнь не календарём, а тем, что герой
// делает иначе.

namespace Дом.Ядро;

/// <summary>Чем кончилась одна жизнь и что она дала.</summary>
public sealed record Жизнь(
    int номер,
    long зерно,
    string кто,
    // род играющего: «дожил» или «дожила». Экран смерти рисуется, когда
    // дома уже может не быть под рукой, и лазить за родом обратно в дом
    // значило бы держать дом живым ради одной буквы
    string пол,
    int прожито,
    bool дожил,
    string? причина,
    int? день_смерти,
    int начислено,
    double рассудок_был,
    double рассудок_стал,
    IReadOnlyList<ВкладВРассудок> вклады,
    IReadOnlyList<ЗаписьПамяти> новые_записи,
    IReadOnlyList<Отголосок> новые_отголоски);

/// <summary>Чем начинается новая жизнь: монолог и то, что герой помнит.</summary>
public sealed record Начало(
    int номер,
    string монолог,
    bool можно_уйти,
    IReadOnlyList<ЗаписьПамяти> записи,
    IReadOnlyList<Отголосок> отголоски,
    int очки,
    int карман);

public sealed class Петля
{
    private readonly List<Жизнь> _жизни = new();

    public Петля(Наследие наследие, РучкиПетли ручки)
    {
        this.наследие = наследие;
        this.ручки = ручки;
    }

    public Наследие наследие { get; }

    public РучкиПетли ручки { get; }

    public IReadOnlyList<Жизнь> жизни => _жизни;

    /// <summary>Петля оборвалась: рассудок дошёл до точки невозврата
    /// (ГДД 11). Дальше — либо слово пророка и «нирвана», либо новый
    /// человек без памяти и очков.</summary>
    public bool оборвалась
        => !наследие.нирвана
           && Рассудок.Где(наследие.рассудок, ручки) == Порог.НЕВОЗВРАТ;

    /// <summary>
    /// Завести дневник на эту жизнь и подписать его на дом.
    ///
    /// Зовётся до `run()`. Без дневника петля тоже работает — но рассудок
    /// не досчитает голода, одиночества и темноты: у дома этой памяти нет
    /// (см. `Дневник`).
    /// </summary>
    public Дневник Слушать(Прогон прогон, string кто)
    {
        var д = new Дневник(кто, ручки);
        д.Слушать(прогон.h);
        _дневник = д;
        return д;
    }

    private Дневник? _дневник;

    /// <summary>С чем герой просыпается.</summary>
    public Начало Начать() => new(
        наследие.жизней + 1,
        Рассудок.Монолог(наследие, ручки),
        Рассудок.МожноУйти(наследие.рассудок, ручки),
        наследие.записи.ToList(),
        наследие.отголоски.ToList(),
        наследие.очки,
        наследие.карман);

    /// <summary>
    /// Жизнь кончилась — подвести итог и сложить наследие.
    ///
    /// Прогон сюда приходит уже прожитым и уходит нетронутым: петля читает
    /// дом и не пишет в него ничего. Берётся именно прогон, а не дом:
    /// зерно жизни знает он, а дом — нет, и хранить его отдельно значило бы
    /// завести второе место, где оно может разойтись.
    /// </summary>
    public Жизнь Закрыть(Прогон прогон, string кто)
    {
        var h = прогон.h;
        var я = h.people[кто];
        int прожито = я.здесь() ? h.day : (я.died_day ?? h.day);
        int номер = наследие.жизней + 1;

        int начислено = Очки(прожито, наследие.жизней, наследие.рекорд);
        var вклады = Рассудок.Вклады(h, я, ручки, _дневник);
        _дневник = null;            // дневник живёт ровно одну жизнь
        double было = наследие.рассудок;
        double стало = наследие.нирвана ? было : Рассудок.Сложить(было, вклады);

        var записи = Телефон(h, я, номер);
        var отголоски = Отголоски(h, я, номер);

        var жизнь = new Жизнь(
            номер, прогон.seed, кто, я.sex, прожито, я.здесь(), я.cause, я.died_day,
            начислено, было, стало, вклады, записи, отголоски);
        _жизни.Add(жизнь);

        // ---- и только теперь наследие меняется ----
        наследие.жизней = номер;
        наследие.очки += начислено;
        наследие.рекорд = Math.Max(наследие.рекорд, прожито);
        наследие.рассудок = стало;
        Подшить(наследие.записи, записи, (int)ручки["записей_помнить"]);
        Подшить(наследие.отголоски, отголоски, (int)ручки["отголосков_помнить"]);
        return жизнь;
    }

    /// <summary>
    /// Очки навыков (ГДД 8.2).
    ///
    /// Первые две жизни — за каждый прожитый день: это обучающий бонус,
    /// чтобы вторая жизнь была ощутимо сильнее первой. Дальше — только
    /// за дни сверх лучшей прошлой: иначе выгодно умирать поздно и часто,
    /// а игра не про фарм.
    ///
    /// Никаких очков за достижения и «пройденные пути»: игрок сам решает,
    /// как играть, и платить ему за один способ значит выбрать за него.
    /// </summary>
    public int Очки(int прожито, int жизней_до, int рекорд)
        => жизней_до < (int)ручки["обучающих_жизней"]
           ? прожито
           : Math.Max(0, прожито - рекорд);

    /// <summary>
    /// Что герой записал в телефон (ГДД 10).
    ///
    /// Только то, что он знает сам: своя память (`NPC.memory`) и события,
    /// в которых он был стороной. Взять здесь весь `h.события` было бы
    /// проще всего — и это отдало бы игроку знание, которого нет ни у кого
    /// в доме.
    /// </summary>
    private List<ЗаписьПамяти> Телефон(House h, NPC я, int номер)
    {
        var @out = new List<ЗаписьПамяти>();

        // чем кончилась жизнь и кто в этом виноват
        if (!я.здесь())
        {
            @out.Add(new ЗаписьПамяти(номер, я.died_day ?? h.day, ВидЗаписи.МОЯ_СМЕРТЬ,
                null, я.apt,
                $"Здесь я {Util.Vb(я.sex, "умер")}: {я.cause}. День {я.died_day}."));
            var убийство = h.события.LastOrDefault(
                с => с.вид is ВидСобытия.СМЕРТЬ or ВидСобытия.УБИЙСТВО
                     && string.Equals(с.кто, я.id, StringComparison.Ordinal)
                     && с.кому is not null);
            if (убийство?.кому is string убийца)
                @out.Add(new ЗаписьПамяти(номер, убийство.день, ВидЗаписи.УБИЙЦА,
                    убийца, h.get(убийца)?.apt,
                    $"{Имя(h, убийца)} "
                    + $"{Util.Vb(h.get(убийца)?.sex ?? "м", "убил")} меня. "
                    + $"День {убийство.день}."));
        }

        // о ком он что знает — по своей памяти, не по правде
        foreach (var з in я.memory)
        {
            switch (з.вид)
            {
                case Вид.ПОЙМАЛ_ВОРА:
                case Вид.НАЗВАЛИ_ВОРОМ:
                    @out.Add(new ЗаписьПамяти(номер, з.день, ВидЗаписи.ВОР, з.кто,
                        h.get(з.кто)?.apt, $"{Имя(h, з.кто)} — вор."));
                    break;
                case Вид.ВИДЕЛ_УБИЙСТВО:
                    @out.Add(new ЗаписьПамяти(номер, з.день, ВидЗаписи.СМЕРТЬ_СОСЕДА,
                        з.кто, h.get(з.кто)?.apt,
                        $"На моих глазах убили: {Имя(h, з.кто)}. День {з.день}."));
                    break;
            }
        }

        // у кого что есть — по его оценке; и кто давал, а кто нет
        foreach (var о in h.others(я).OrderBy(x => x.apt))
        {
            var опыт = я.asking.Взять(о.id, null!);
            if (опыт is null)
                continue;
            if (опыт.дали > 0)
                @out.Add(new ЗаписьПамяти(номер, я.died_day ?? h.day, ВидЗаписи.ПОМОГ,
                    о.id, о.apt,
                    $"{о.@short} {Util.Vb(о.sex, "давал")}, когда просил."));
            else if (опыт.отказали >= 2)
                @out.Add(new ЗаписьПамяти(номер, я.died_day ?? h.day, ВидЗаписи.ОТКАЗАЛ,
                    о.id, о.apt,
                    $"{о.@short} не {Util.Vb(о.sex, "открывал")}."));
            if (я.сведения_о(о.id).aware >= 50)
                @out.Add(new ЗаписьПамяти(номер, я.died_day ?? h.day, ВидЗаписи.ЗАПАС,
                    о.id, о.apt,
                    // родительный, а не короткое имя: «У Руслан» — это
                    // не по-русски, а падежи у жильца уже есть все четыре
                    $"У {о.form("gen")}: еды около {Текст.Ф(я.believed(о.id, "еда"), 0)}, "
                    + $"дров около {Текст.Ф(я.believed(о.id, "топливо"), 0)}."));
        }

        return @out;
    }

    /// <summary>
    /// Отголоски (ГДД 10): вспышки в местах, где что-то произошло.
    ///
    /// Место, а не событие: игрок входит в квартиру и что-то чувствует.
    /// Что именно было — он должен вспомнить сам, поэтому текст короткий
    /// и без объяснений.
    /// </summary>
    private List<Отголосок> Отголоски(House h, NPC я, int номер)
    {
        var @out = new List<Отголосок>();
        if (!я.здесь())
            @out.Add(new Отголосок(я.apt, номер, "Здесь было холодно и очень тихо."));
        foreach (var с in h.события)
        {
            if (с.где is not int кв)
                continue;
            // только то, чему он был свидетелем или стороной
            bool моё = string.Equals(с.кто, я.id, StringComparison.Ordinal)
                       || string.Equals(с.кому, я.id, StringComparison.Ordinal)
                       || я.memory.Any(з => з.день == с.день
                                            && string.Equals(з.кто, с.кто,
                                                             StringComparison.Ordinal));
            if (!моё)
                continue;
            string? текст = с.вид switch
            {
                ВидСобытия.УБИЙСТВО => "Кровь на полу. Не моя.",
                ВидСобытия.СМЕРТЬ => "Кто-то лежал здесь очень долго.",
                ВидСобытия.НАЛЁТ => "Дверь. Стук. Много рук.",
                ВидСобытия.ВСКРЫТИЕ => "Замок висел вот так же — сорванный.",
                ВидСобытия.ПОЖАР => "Пахнет гарью, хотя не горело.",
                ВидСобытия.ПОМОЩЬ => "Здесь мне однажды открыли.",
                _ => null,
            };
            if (текст is not null)
                @out.Add(new Отголосок(кв, номер, текст));
        }
        return @out;
    }

    private static string Имя(House h, string id) => h.get(id)?.@short ?? id;

    /// <summary>Подшить новое и обрезать старое: журнал, который нельзя
    /// дочитать, — это не память, а свалка.</summary>
    private static void Подшить<T>(List<T> куда, IReadOnlyList<T> что, int предел)
    {
        куда.AddRange(что);
        if (куда.Count > предел)
            куда.RemoveRange(0, куда.Count - предел);
    }
}
