// Ноша: что герой несёт домой (ГДД 7, 9).
//
// Найденное не ложится в шкаф само. Его несут — в пакете, в сумке,
// в рюкзаке — или кладут в карман вне времени (`Карман`), и запасом оно
// становится только дома. Пока его несут, дом о нём не знает: в шкафу
// его нет, ни съесть, ни отдать его нельзя, и тот, кто ограбит квартиру,
// его не найдёт.
//
// Тара — это место и шум (ручки в `петля.json`), и одно покупается другим:
//   · пакеты — места больше всего, но шуршат на весь подъезд;
//   · сумка — посередине и шумит как обычное возвращение с улицы;
//   · рюкзак — тише всего, но и влезает меньше всего.
// Первая раскладка дала рюкзаку и больше места, и меньше шума — тара,
// лучшая во всём, делала выбор пустым. Раздел «ноша» это стережёт.
// Шум — тот же, каким дом слышит возвращение с вылазки (`Социальное.emit`,
// вид «возвращение»): кто услышал или увидел, запоминает, что герой
// «вернулся с улицы с пакетами», и начинает думать, что у него есть еда.
// Правило одно для всех; игрок лишь выбирает, насколько громко нести.
//
// Тара одна за раз: сумку, начатую в гараже, до дома на рюкзак не меняют.
// Дома тара разгружается вся и сразу — у порога (`Разгрузить`); карман
// разгружается, когда захочется, своим экраном.
//
// Ноша — только у игрока, как и карман: соседи этих функций не зовут,
// в снимок и сейв дома она не входит и умирает вместе с героем.

namespace Дом.Ядро;

public enum Тара { ПАКЕТ, СУМКА, РЮКЗАК }

public static class Тары
{
    public static readonly IReadOnlyList<Тара> ВСЕ = new[] { Тара.ПАКЕТ, Тара.СУМКА, Тара.РЮКЗАК };

    public static string Текст(this Тара т) => т switch
    {
        Тара.ПАКЕТ => "пакет",
        Тара.СУМКА => "сумка",
        _ => "рюкзак",
    };

    /// <summary>«в пакет», «в сумку», «в рюкзак».</summary>
    public static string Куда(this Тара т) => т switch
    {
        Тара.ПАКЕТ => "в пакет",
        Тара.СУМКА => "в сумку",
        _ => "в рюкзак",
    };

    /// <summary>«в пакете», «в сумке», «в рюкзаке».</summary>
    public static string Где(this Тара т) => т switch
    {
        Тара.ПАКЕТ => "в пакете",
        Тара.СУМКА => "в сумке",
        _ => "в рюкзаке",
    };

    /// <summary>Сколько влезает.</summary>
    public static double мест(this Тара т, РучкиПетли ручки) => т switch
    {
        Тара.ПАКЕТ => ручки["пакет_мест"],
        Тара.СУМКА => ручки["сумка_мест"],
        _ => ручки["рюкзак_мест"],
    };

    /// <summary>Насколько громко: уровень шума дома (1 — шаги, 3 — на весь
    /// подъезд).</summary>
    public static int шум(this Тара т, РучкиПетли ручки) => (int)(т switch
    {
        Тара.ПАКЕТ => ручки["пакет_шум"],
        Тара.СУМКА => ручки["сумка_шум"],
        _ => ручки["рюкзак_шум"],
    });
}

public sealed class Ноша
{
    private readonly Словарь<string, double> _вещи = Словари.Числа();

    /// <summary>В чём несут — или ничего, пока ноша пуста.</summary>
    public Тара? тара { get; private set; }

    public bool пусто => _вещи.Ключи.Count == 0;

    public IReadOnlyList<string> ресурсы => _вещи.Ключи;

    public double Сколько(string ресурс) => _вещи.Взять(ресурс, 0.0);

    public double занято => Util.Sum(_вещи.Ключи.Select(к => _вещи[к]));

    public double предел(РучкиПетли ручки) => тара?.мест(ручки) ?? 0.0;

    /// <summary>Сколько ещё влезет в эту тару.</summary>
    public double свободно(Тара т, РучкиПетли ручки)
        => Можно(т) ? Math.Max(0.0, т.мест(ручки) - занято) : 0.0;

    /// <summary>Можно ли класть в эту тару: пустая ноша берёт любую,
    /// начатая — только свою.</summary>
    public bool Можно(Тара т) => тара is null || тара == т;

    /// <summary>
    /// Положить, сколько влезет. Возвращает положенное: что не влезло,
    /// остаётся у зовущего — в кладовой, откуда брали.
    /// </summary>
    public Словарь<string, double> Положить(Тара т, Словарь<string, double> вещи,
                                             РучкиПетли ручки)
    {
        var положено = Словари.Числа();
        if (!Можно(т))
            return положено;
        foreach (var р in вещи.Ключи.OrderBy(x => x, StringComparer.Ordinal))
        {
            double сколько = Math.Min(вещи[р], свободно(т, ручки));
            if (сколько <= 0.0)
                continue;
            тара = т;
            _вещи[р] = Сколько(р) + сколько;
            положено[р] = сколько;
        }
        return положено;
    }

    /// <summary>Разгрузить дома: всё — в шкаф героя, тара освобождается.</summary>
    public Словарь<string, double> Разгрузить(NPC я)
    {
        var было = Словари.Числа();
        foreach (var р in _вещи.Ключи.OrderBy(x => x, StringComparer.Ordinal))
        {
            я.stock[р] = я.stock.Взять(р, 0.0) + _вещи[р];
            было[р] = _вещи[р];
        }
        Обнулить();
        return было;
    }

    /// <summary>
    /// Пронести через подъезд. Шумит тара, а не человек: пустой пакет
    /// не слышен, полный — слышен так, как его тара. Возвращает тех,
    /// кто услышал или увидел; что они запомнили, решает дом.
    /// </summary>
    public List<NPC> Пронести(House h, NPC я, РучкиПетли ручки)
    {
        if (пусто || тара is not Тара т)
            return new List<NPC>();
        return Социальное.emit(h, я, т.шум(ручки), "возвращение");
    }

    /// <summary>Смерть или конец жизни: ноша не переносится.</summary>
    public void Обнулить()
    {
        _вещи.Очистить();
        тара = null;
    }

    public override string ToString()
        => пусто
           ? "пусто"
           : string.Join(", ", _вещи.Ключи
               .OrderBy(к => к, StringComparer.Ordinal)
               .Select(к => $"{к} {Текст.G(Текст.Округлить(_вещи[к], 2))}"));

    // ------------------------------------------------------------ сохранение игры

    public System.Text.Json.Nodes.JsonObject Сложить() => new()
    {
        ["тара"] = тара?.ToString(),
        ["вещи"] = Карман.Числа_в(_вещи.Ключи.Select(к => new KeyValuePair<string, double>(к, _вещи[к]))),
    };

    public void Разложить(System.Text.Json.Nodes.JsonObject о)
    {
        _вещи.Очистить();
        тара = о["тара"]?.GetValue<string>() is string т ? Enum.Parse<Тара>(т) : null;
        foreach (var (к, v) in о["вещи"]!.AsObject())
            _вещи[к] = v!.GetValue<double>();
    }
}
