// Мини-игра «Разговор» (ГДД 7: «убеждение, торг, отвод подозрений — выбор
// реплики за ограниченное время; провал — падение доверия»; ГДД 11: в нирване
// «Разговор» получает особые варианты).
//
// Перед разговором дома с соседом герой выбирает, как с ним говорить: три
// тона, несколько секунд. Свой тон у соседа — по тому, что он ценит первым
// (`NPC.values`): щедрость и ребёнок — по-доброму, работа и порядок — по делу,
// сила — твёрдо, на равных. Выбрал свой и быстро — разговор удался; чужой —
// как обычно; тон, который его задевает (твёрдость — тому, кто не терпит
// насилия), — провал; промолчал — тоже хуже обычного. В нирване есть четвёртая
// реплика — сказать то, чего знать было нельзя; она удаётся всегда.
//
// Ценности соседа герой не видит: узнаёт их, как всё в этой игре, — разговорами,
// заметками и прошлыми жизнями. Здесь они читаются как правда, потому что это
// исход, а не выбор: так дом сам решает, удалась ли стройка.
//
// Итог — качество от нуля до единицы, как у прочих мини-игр; в дом он едет
// множителем доверия (`МиниИгры.Доверие`, `Поправки.Доверие_игры`).

namespace Дом.Ядро;

/// <summary>Как говорить с соседом.</summary>
public enum Тон
{
    ДОБРО,      // о своих, о детях, чем помочь
    ДЕЛО,       // что починить, что где лежит
    ТВЁРДО,     // на равных: держаться вместе — сила
    ЗНАЮ,       // только в нирване: то, чего знать было нельзя
    ЦИНИЗМ,     // с тревоги (ГДД 11): каждый сам за себя
    ШУТКА,      // ГДД 14: «пошутить»; напуганный шуток не воспринимает
}

public static class Реплики
{
    /// <summary>Слова реплики на экране.</summary>
    public static string Слова(Тон т) => т switch
    {
        Тон.ДОБРО => "по-доброму: о своих, о детях, чем помочь друг другу",
        Тон.ДЕЛО => "по делу: что починить, где что лежит, как продержаться",
        Тон.ТВЁРДО => "твёрдо, на равных: в одиночку не выстоять, держаться вместе",
        Тон.ЦИНИЗМ => "цинично: каждый сам за себя — так хоть честно",
        Тон.ШУТКА => "с шуткой: посмеяться, пока ещё смешно",
        _ => "сказать то, чего знать было нельзя — и посмотреть, как он вздрогнет",
    };

    /// <summary>С какой паники сосед шуток не воспринимает: тот же порог,
    /// с которого он пишет в общий чат о страхе (`Чат.daily_chat`).</summary>
    public const double ПАНИКА_НЕ_ДО_ШУТОК = 45.0;

    /// <summary>Ниже этой паники сосед спокоен — шутка ему легче обычного.</summary>
    public const double СПОКОЕН = 25.0;

    /// <summary>Сколько секунд на реплику (ГДД 7: мини-игра — 3–7 секунд).</summary>
    public static double Секунд(РучкиПетли ручки) => ручки["мини_разговор_секунд"];

    /// <summary>Три тона на выбор — и «знаю» в нирване, циничный — с тревоги
    /// (ГДД 11: «появляются циничные варианты»).</summary>
    public static IReadOnlyList<Тон> На_выбор(bool нирвана, bool цинизм = false)
    {
        var тоны = new List<Тон> { Тон.ДОБРО, Тон.ДЕЛО, Тон.ТВЁРДО, Тон.ШУТКА };
        if (цинизм)
            тоны.Add(Тон.ЦИНИЗМ);
        if (нирвана)
            тоны.Add(Тон.ЗНАЮ);
        return тоны;
    }

    /// <summary>
    /// Почему реплика не идёт с языка — или null (ГДД 14: «настроение героя
    /// ограничивает варианты: в плохом настроении недоступны поддерживающие
    /// реплики»). Добрая — только пока самому не тошно: порог
    /// «разговор_добро_настроение» — тот же, что «тошно» в итоге дня.
    /// </summary>
    public static string? Не_идёт(Тон т, double настроение, РучкиПетли ручки)
        => т == Тон.ДОБРО && настроение < ручки["разговор_добро_настроение"]
           ? "не идёт с языка: самому тошно" : null;

    /// <summary>
    /// Что видно по человеку смекалистому (ГДД 14: «скрытые варианты
    /// открываются Смекалкой и памятью»): с уровня «разговор_подсказка_смекалка» —
    /// каким тоном с ним выходит. Память подсказывает своё (`Помнит`); с порога
    /// мини-игры (`мини_игра_исчезает`) реплики нет вовсе.
    /// </summary>
    public static string? Видно_по_нему(NPC с, NPC я, РучкиПетли ручки)
        => (я.умения?.наследие.Уровень(Навык.СМЕКАЛКА) ?? 0) >= (int)ручки["разговор_подсказка_смекалка"]
           ? $"по {(с.sex == "ж" ? "ней" : "нему")} видно: лучше {Кратко(Свой(с))}" : null;

    /// <summary>Какой тон этому человеку по душе — по тому, что он ценит
    /// первым; не ценит ничего из этого — по делу.</summary>
    public static Тон Свой(NPC с) => с.values.ценит.FirstOrDefault() switch
    {
        "щедрость" or "ребёнок" => Тон.ДОБРО,
        "сила" => Тон.ТВЁРДО,
        _ => Тон.ДЕЛО,
    };

    /// <summary>Задевает ли тон этого человека: твёрдость — того, кто
    /// не терпит насилия.</summary>
    public static bool Задевает(NPC с, Тон т) => т == Тон.ТВЁРДО && с.не_терпит("насилие");

    /// <summary>
    /// Как сыграно: <paramref name="т"/> — выбранный тон (null — промолчал,
    /// время вышло), <paramref name="осталось"/> — доля времени, что ещё
    /// оставалась. Свой тон — от трёх четвертей до единицы, чем быстрее, тем
    /// лучше; задел — провал; прочий — как обычно; промолчал — хуже обычного;
    /// «знаю» — всегда удаётся.
    /// </summary>
    public static double Качество(NPC с, Тон? т, double осталось)
    {
        if (т is not Тон тон)
            return 0.3;
        if (тон == Тон.ЗНАЮ)
            return 1.0;
        // шутка (ГДД 14: «NPC в панике не воспринимает шутки»): напуганному —
        // обида, спокойному — легче обычного, но не так, как его тон
        if (тон == Тон.ШУТКА)
            return с.panic >= ПАНИКА_НЕ_ДО_ШУТОК ? 0.1 : с.panic < СПОКОЕН ? 0.65 : 0.5;
        // цинизм: сильному — почти свой, доброму — обида, прочим — хуже обычного
        if (тон == Тон.ЦИНИЗМ)
            return с.ценит("сила") ? 0.6
                 : с.ценит("щедрость") || с.ценит("ребёнок") ? 0.1
                 : 0.4;
        if (Задевает(с, тон))
            return 0.1;
        return тон == Свой(с) ? 0.75 + 0.25 * Util.Clamp(осталось, 0.0, 1.0) : 0.5;
    }

    /// <summary>Приставка знания «как с ним говорить» в `Округа.знания`:
    /// «тон:лида:ДЕЛО». Переходит в наследие, как всё, что герой узнал
    /// (ГДД 10: заметки «кто что любит»), — в следующей жизни окно реплики
    /// подсказывает, а сосед этого не помнит.</summary>
    public const string ЗНАНИЕ = "тон:";

    /// <summary>Знание: с этим человеком — этим тоном.</summary>
    public static string Знание(NPC с, Тон т) => $"{ЗНАНИЕ}{с.id}:{т}";

    /// <summary>Каким тоном, по памяти героя, говорить с этим человеком —
    /// или null, если не знает.</summary>
    public static Тон? Помнит(Func<string, bool> знает, NPC с)
    {
        foreach (var т in Enum.GetValues<Тон>())
            if (знает(Знание(с, т)))
                return т;
        return null;
    }

    /// <summary>Запомнить ли тон: попал в свой — да; «знаю» в нирване —
    /// не его тон, а свой фокус.</summary>
    public static bool Запомнить(Тон т, double качество) => т != Тон.ЗНАЮ && качество >= 0.75;

    /// <summary>Тон коротко: «по-доброму», «по делу», «твёрдо».</summary>
    public static string Кратко(Тон т) => т switch
    {
        Тон.ДОБРО => "по-доброму",
        Тон.ДЕЛО => "по делу",
        Тон.ТВЁРДО => "твёрдо, на равных",
        Тон.ЦИНИЗМ => "цинично",
        Тон.ШУТКА => "с шуткой",
        _ => "тем, чего знать нельзя",
    };

    /// <summary>Соврал неубедительно (ГДД 7, «Разговор»: «отвод подозрений…
    /// провал — падение доверия»): задел или замялся.</summary>
    public static bool Ложь_провалена(double качество) => качество < 0.45;

    /// <summary>Не поверил: доверие к герою падает, а приглядываться к нему
    /// он начинает внимательнее. Сама ложь всё равно сказана — дом её
    /// запишет и разоблачит, как всякую.</summary>
    public static void Не_поверил(NPC кому, NPC я, РучкиПетли ручки)
        => Социальное.adjust(кому, я.id, trust: ручки["мини_ложь_провал_доверие"],
                             aware: ручки["мини_ложь_провал_осведомлённость"]);

    /// <summary>Торг сорвался — давил не тем тоном (ГДД 7: провал «Разговора» —
    /// падение доверия). Порог тот же, что у лжи.</summary>
    public static bool Торг_сорван(double качество) => Ложь_провалена(качество);

    /// <summary>Сорвавшийся торг: сосед доверяет меньше, чем до него.</summary>
    public static void Торг_сорвался(NPC кому, NPC я, РучкиПетли ручки)
        => Социальное.adjust(кому, я.id, trust: ручки["мини_торг_провал_доверие"]);

    /// <summary>Просил не так — сосед недоволен ещё до ответа (ГДД 7: провал
    /// «Разговора» — падение доверия). Порог тот же, что у лжи и торга.</summary>
    public static void Просьба_сорвалась(NPC кому, NPC я, РучкиПетли ручки)
        => Социальное.adjust(кому, я.id, trust: ручки["мини_просьба_провал_доверие"]);

    /// <summary>Чем кончился разговор — словами для вести.</summary>
    public static string Итог(double качество) => качество switch
    {
        < 0.2 => "задел за живое — разговор не задался",
        < 0.45 => "замялся — вышло натянуто",
        < 0.65 => "поговорили как обычно",
        < 0.9 => "нашёл нужные слова",
        _ => "попал в самую точку",
    };
}
