    public JsonObject Сложить()
    {
        var места = new JsonObject();
        foreach (var м in МЕСТА)
            места[м.ToString()] = new JsonArray(_где[м].Select(п => (JsonNode?)new JsonObject
            {
                ["номер"] = п.номер, ["вид"] = п.вид, ["единиц"] = п.единиц,
                ["возраст"] = п.возраст, ["открыта"] = п.открыта,
            }).ToArray());
        return new JsonObject
        {
            ["места"] = места,
            ["номер"] = _номер,
            ["день"] = _день,
            ["было"] = _было,
            ["случай"] = _rng.Состояние.ToString(System.Globalization.CultureInfo.InvariantCulture),
        };
    }

    public void Разложить(JsonObject о)
    {
        foreach (var м in МЕСТА)
        {
            _где[м].Clear();
            if (о["места"]![м.ToString()] is JsonArray список)
                foreach (var x in список)
                {
                    var п = x!.AsObject();
                    string вид = п["вид"]!.GetValue<string>();
                    if (!каталог.Есть(вид))
                        continue;               // продукт убран из каталога — вещь пропала
                    _где[м].Add(new Продукт(п["номер"]!.GetValue<int>(), вид, п["единиц"]!.GetValue<double>(),
                                            п["возраст"]!.GetValue<double>(), п["открыта"]!.GetValue<double>()));
                }
        }
        _номер = о["номер"]!.GetValue<int>();
        _день = о["день"]?.GetValue<int>();
        _было = о["было"]!.GetValue<bool>();
        _rng.Состояние = ulong.Parse(о["случай"]!.GetValue<string>(), System.Globalization.CultureInfo.InvariantCulture);
    }
