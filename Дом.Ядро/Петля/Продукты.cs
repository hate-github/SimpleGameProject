    /// <summary>Откуда пришла еда, которую дом положил сам.</summary>
    private string Откуда_само(МестоЕды м)
        => !_было ? "дом" : м == МестоЕды.ПОЛКА ? "сосед" : "магазин";

    /// <summary>
    /// Свести вещи с числами дома. Зовётся, пока дом спит: на каждом
    /// вопросе и перед тем, как экран покажет вещи. Возвращает, сколько
    /// порций вещей появилось без явного пути (принёс дом) — для проверки.
    /// </summary>
    public double Сверить(House h, NPC я)
    {
        Состарить(h.day);
        var снято = new List<Продукт>();
        foreach (var м in МЕСТА)
        {
            double лишнее = Сумма(м) - Число(я, м);
            if (лишнее > ТОЧНО)
                снято.AddRange(Снять(м, лишнее));
        }
        double принесено = 0.0;
        foreach (var м in МЕСТА)
        {
            double нехватка = Число(я, м) - Сумма(м);
            if (нехватка <= ТОЧНО)
                continue;
            // сперва снятое в другом месте — целиком, пока влезает
            foreach (var п in снято.OrderByDescending(п => п.единиц).ThenBy(п => п.номер).ToList())
            {
                if (п.единиц > нехватка + ТОЧНО)
                    continue;
                снято.Remove(п);
                _где[м].Add(п);
                нехватка -= п.единиц;
            }
            // потом часть снятого
            if (нехватка > ТОЧНО && снято.Count > 0)
            {
                var п = снято.OrderByDescending(x => x.единиц).ThenBy(x => x.номер).First();
                _где[м].Add(Новый(п.вид, нехватка, п.возраст,
                                  Вид(п).род == РодЕды.БАНКА ? Math.Max(0, п.открыта) : -1));
                п.единиц -= нехватка;
                нехватка = 0;
            }
            // чего не хватило — принесли
            if (нехватка > ТОЧНО)
            {
                foreach (var п in Сделать(Откуда_само(м), нехватка, целые_только: false))
                    _где[м].Add(п);
                принесено += нехватка;
            }
        }
        // остаток снятого съели, отдали, унесли — его в мире больше нет
        _было = true;
        return принесено;
    }

