    /// <summary>Вынуть порции из числа места (шкаф, ноша, карман).</summary>
    private static void Вынуть_число(NPC я, МестоЕды м, double сколько)
    {
        switch (м)
        {
            case МестоЕды.ПОЛКА:
                я.stock[ЕДА] = Math.Max(0.0, я.stock.Взять(ЕДА, 0.0) - сколько);
                break;
            case МестоЕды.НОША:
                я.ноша?.Вынуть(ЕДА, сколько);
                break;
            default:
                я.карман?.Потратить(ЕДА, сколько);
                break;
        }
    }

    /// <summary>
    /// Съесть вещь (поступок игрока, пока дом спит). Сытость — порции
    /// вещи на порцию дома (`Действия.порция`: повар под одной крышей
    /// тоже в счёт), больше, чем лезет, не съесть — банка остаётся
    /// початой, батон половиной. Настроение — своё у каждой еды.
    /// Испорченное — риск отравиться: сытости вдвое меньше, жажда,
    /// настроение вниз. Порция пахнет, как у соседа, который поел.
    /// </summary>
    public Съедено Съесть(House h, NPC я, Продукт п)
    {
        if (Где(п) is not МестоЕды м)
            return new Съедено(0, 0, 0, false, "этого уже нет");
        var в = Вид(п);
        // сырой овощ насыщает хуже, и лезет его во столько же раз больше
        double порция = Действия.порция(h, я, h.B) * в.сырым;
        double лезет = (100.0 - я.satiety) / порция;
        if (лезет < 0.1)
            return new Съедено(0, 0, 0, false, "не лезет — сыт");
        double сколько = Math.Min(п.единиц, лезет);
        if (п.единиц - сколько < 0.05)
            сколько = п.единиц;             // доесть крошки
        var свежесть = Свежесть(п);
        double шанс = свежесть switch
        {
            Дом.Ядро.Свежесть.ПРОСРОЧЕНА => каталог.отравление_просрочено,
            Дом.Ядро.Свежесть.ИСПОРЧЕНА => каталог.отравление_испорчено,
            _ => 0.0,
        };
        bool отравился = шанс > 0 && _rng.Chance(шанс);

        Вынуть_число(я, м, сколько);
        double сытости = порция * сколько * (отравился ? 0.5 : 1.0);
        double настроения = в.настроение * сколько * (свежесть == Дом.Ядро.Свежесть.СВЕЖАЯ ? 1.0 : 0.0)
                            - (отравился ? 8.0 : 0.0);
        я.satiety = Util.Clamp(я.satiety + сытости);
        я.mood = Util.Clamp(я.mood + настроения);
        if (отравился)
            я.hydration = Util.Clamp(я.hydration - 25.0);
        h.stats["съедено"] = h.stats.Взять("съедено", 0.0) + сколько;

        п.единиц -= сколько;
        if (в.род == РодЕды.БАНКА && !п.открыт)
            п.открыта = 0;
        if (п.единиц <= ТОЧНО)
            _где[м].Remove(п);              // пустую банку не хранят
        // поел — пахнет, как у соседа (`поесть`): горячее — если топится
        Социальное.smell(h, я, hot: я.burning);
        return new Съедено(сколько, сытости, настроения, отравился);
    }

    /// <summary>
    /// Переложить вещь между полкой и карманом (у полки). Карман —
    /// аномалия: кто рядом, видит, как вещь исчезла (`Карман.Положить`).
    /// null — переложил; иначе почему нет.
    /// </summary>
    public string? Переложить(House h, NPC я, Продукт п, МестоЕды куда,
                              out IReadOnlyList<Свидетель> видели)
    {
        видели = Array.Empty<Свидетель>();
        if (Где(п) is not МестоЕды откуда)
            return "этого уже нет";
        if (откуда == куда)
            return null;
        if (я.карман is not { } карман)
            return "кармана нет";
        if (откуда == МестоЕды.ПОЛКА && куда == МестоЕды.КАРМАН)
        {
            if (карман.свободно + ТОЧНО < п.единиц)
                return "в кармане нет места";
            видели = карман.Положить(h, я, ЕДА, п.единиц);
        }
        else if (откуда == МестоЕды.КАРМАН && куда == МестоЕды.ПОЛКА)
            карман.Достать(я, ЕДА, п.единиц);
        else
            return "так не переложить";
        _где[откуда].Remove(п);
        _где[куда].Add(п);
        return null;
    }

