// Продукты как вещи героя (docs/ЕДА_ПЛАН.md, этап 1).
//
// В доме еда — число: `stock["еда"]` в порциях, и соседи едят, меняют,
// крадут и отдают это число. На нём держится эталон, и потому дом
// не трогается. Вещи — слой только у героя: две банки свинины и шпроты
// там, где у дома «2.6 еды». Закон слоя один:
//
//     **в каждом из трёх мест — полка (шкаф), ноша, карман — сумма
//     вещей равна числу «еда» этого места.**
//
// Держится он двумя путями:
//   · **явным** — там, где вещь берёт сам игрок: ящик (`Обыск`) отдаёт
//     целые вещи, съесть, переложить. Вещь двигается вместе с числом;
//   · **сверкой** (`Сверить`) — для всего, что делает дом: мысль «поесть»,
//     мена, подарок, вор, разгрузка ноши у порога. Где число убыло,
//     вещи снимаются — сперва то, что съели бы первым (открытое, потом
//     то, что скоро испортится); где прибыло — сперва ложится снятое
//     (ноша ушла на полку — те же банки на полке), а чего не хватило,
//     то «принесли»: вещи делаются по тому, откуда еда могла прийти.
//
// Порча — в днях дома: на полке и в ноше день за день, в кармане вне
// времени — четверть (ГДД 9, `карман_время`). Открытая банка портится
// своими днями.
//
// Броски — свой генератор от зерна, мимо `h.rng`: какой продукт лежал
// в ящике — не выбор жильца и не исход дела дома. Слой висит на герое
// таблицей (как округа на доме), мимо снимка и сейва дома; у соседей
// его нет, и прогон без игрока считается как раньше.

using System.Runtime.CompilerServices;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace Дом.Ядро;

/// <summary>Банка (закрыта, открыта, початая; просрочка и порча открытой),
/// хлеб и овощ (целый, половина, кусок; свежий и в плесени). Овощ сырым
/// насыщает хуже — его готовят (docs/ЕДА_ПЛАН.md, этап 4).</summary>
public enum РодЕды { БАНКА, ХЛЕБ, ОВОЩ }

/// <summary>Часть вещи, какой она видна: вариант модели («1 kg», «half»),
/// с какой доли целой (от), и как назвать словом.</summary>
public sealed record ЧастьЕды(string меш, double от, string слово);

/// <summary>Где лежит еда героя: шкаф квартиры (полка), ноша, карман.</summary>
public enum МестоЕды { ПОЛКА, НОША, КАРМАН }

/// <summary>Свежая, просроченная (закрытая банка старше срока), испорченная
/// (открытая банка дольше своего, хлеб в плесени).</summary>
public enum Свежесть { СВЕЖАЯ, ПРОСРОЧЕНА, ИСПОРЧЕНА }

public sealed record ВидЕды(string id, string имя, РодЕды род, double единиц, double настроение,
                           double годна_дней, double открытая_дней, string модель, string меш,
                           string описание)
{
    /// <summary>Сколько сытости даёт сырым (овощ — меньше; банка и хлеб — вся).</summary>
    public double сырым { get; init; } = 1.0;

    /// <summary>Части по убыванию «от»: у хлеба — целый, половина, ломоть;
    /// у овоща — свои из каталога; у банки их нет (там открыта и початая).</summary>
    public IReadOnlyList<ЧастьЕды> части { get; init; } = Array.Empty<ЧастьЕды>();

    /// <summary>Как сказать «свежий» и «испорчен» про эту вещь.</summary>
    public string свежий { get; init; } = "свежая";
    public string испорчен { get; init; } = "испортилась";

    /// <summary>Какая часть при этой доле целой.</summary>
    public ЧастьЕды? Часть(double доля)
        => части.FirstOrDefault(ч => доля >= ч.от - 1e-9) ?? части.LastOrDefault();

    public static readonly IReadOnlyList<ЧастьЕды> ЧАСТИ_ХЛЕБА = new[]
    {
        new ЧастьЕды("full", 0.95, "целый"), new ЧастьЕды("half", 0.4, "половина"), new ЧастьЕды("slice", 0, "ломоть"),
    };
}

public sealed class КаталогЕды
{
    private readonly List<ВидЕды> _виды = new();
    private readonly Dictionary<string, ВидЕды> _по_id = new(StringComparer.Ordinal);
    private readonly Dictionary<string, List<(string вид, double вес)>> _откуда = new(StringComparer.Ordinal);
    private readonly Dictionary<string, Dictionary<РодЕды, double>> _возраст = new(StringComparer.Ordinal);

    public IReadOnlyList<ВидЕды> виды => _виды;
    public ВидЕды this[string id] => _по_id[id];
    public bool Есть(string id) => _по_id.ContainsKey(id);

    /// <summary>Сколько дня проходит в кармане за день дома.</summary>
    public double карман_время { get; private set; } = 0.25;

    /// <summary>Шанс отравиться просроченным и испорченным.</summary>
    public double отравление_просрочено { get; private set; } = 0.15;
    public double отравление_испорчено { get; private set; } = 0.5;

    public IReadOnlyCollection<string> откуда => _откуда.Keys;

    /// <summary>Какие продукты бывают здесь и с каким весом (порядок — как в файле).</summary>
    public IReadOnlyList<(string вид, double вес)> Откуда(string где)
        => _откуда.TryGetValue(где, out var с) ? с : Array.Empty<(string, double)>();

    /// <summary>Сколько вещь уже пролежала, в долях её срока (верх равномерного).</summary>
    public double Возраст(string где, РодЕды род)
        => _возраст.TryGetValue(где, out var в) && в.TryGetValue(род, out var д) ? д : 0.5;

    private static РодЕды Род(string s, string id) => s switch
    {
        "банка" => РодЕды.БАНКА,
        "хлеб" => РодЕды.ХЛЕБ,
        "овощ" => РодЕды.ОВОЩ,
        _ => throw new InvalidDataException($"еда.json: у «{id}» род «{s}» — есть только «банка», «хлеб» и «овощ»"),
    };

    /// <summary>Прочитать `еда.json`; нет файла — null, и вещей у героя нет:
    /// еда остаётся числом, как у соседей.</summary>
    public static КаталогЕды? Прочитать(string каталог)
    {
        string путь = Path.Combine(каталог, "еда.json");
        if (!File.Exists(путь))
            return null;
        var к = new КаталогЕды();
        using var поток = File.OpenRead(путь);
        using var док = JsonDocument.Parse(поток);
        var корень = док.RootElement;
        foreach (var п in корень.GetProperty("продукты").EnumerateArray())
        {
            string id = п.GetProperty("id").GetString()!;
            if (к._по_id.ContainsKey(id))
                throw new InvalidDataException($"еда.json: продукт «{id}» дважды");
            var вид = new ВидЕды(
                id, п.GetProperty("имя").GetString()!, Род(п.GetProperty("род").GetString()!, id),
                п.GetProperty("единиц").GetDouble(), п.GetProperty("настроение").GetDouble(),
                п.GetProperty("годна_дней").GetDouble(), п.GetProperty("открытая_дней").GetDouble(),
                п.GetProperty("модель").GetString()!, п.GetProperty("меш").GetString()!,
                п.GetProperty("описание").GetString()!);
            if (вид.единиц <= 0 || вид.годна_дней <= 0)
                throw new InvalidDataException($"еда.json: у «{id}» нужны единицы и срок больше нуля");
            var части = new List<ЧастьЕды>();
            if (п.TryGetProperty("части", out var ч))
                foreach (var x in ч.EnumerateArray())
                    части.Add(new ЧастьЕды(x.GetProperty("меш").GetString()!, x.GetProperty("от").GetDouble(),
                                           x.GetProperty("слово").GetString()!));
            if (вид.род == РодЕды.ОВОЩ && части.Count == 0)
                throw new InvalidDataException($"еда.json: у овоща «{id}» нужны «части» — какой он целым и кусками");
            if (части.Zip(части.Skip(1)).Any(пара => пара.First.от <= пара.Second.от) || части.Count > 0 && части[^1].от > 0)
                throw new InvalidDataException($"еда.json: у «{id}» части — по убыванию «от», последняя с нуля");
            string[] слова = п.TryGetProperty("свежесть", out var с)
                ? с.EnumerateArray().Select(x => x.GetString()!).ToArray()
                : вид.род switch
                {
                    РодЕды.ХЛЕБ => new[] { "свежий", "в плесени" },
                    РодЕды.ОВОЩ => new[] { "свежая", "с гнильцой" },
                    _ => new[] { "свежая", "испортилась" },
                };
            вид = вид with
            {
                сырым = п.TryGetProperty("сырым", out var сы) ? сы.GetDouble() : 1.0,
                части = части.Count > 0 ? части : вид.род == РодЕды.ХЛЕБ ? ВидЕды.ЧАСТИ_ХЛЕБА : части,
                свежий = слова[0],
                испорчен = слова[1],
            };
            к._виды.Add(вид);
            к._по_id[id] = вид;
        }
        foreach (var где in корень.GetProperty("откуда").EnumerateObject())
        {
            var список = new List<(string, double)>();
            foreach (var в in где.Value.EnumerateObject())
            {
                if (!к._по_id.ContainsKey(в.Name))
                    throw new InvalidDataException($"еда.json: в «откуда.{где.Name}» продукта «{в.Name}» нет");
                список.Add((в.Name, в.Value.GetDouble()));
            }
            к._откуда[где.Name] = список;
        }
        foreach (var где in корень.GetProperty("возраст").EnumerateObject())
        {
            var по_роду = new Dictionary<РодЕды, double>();
            foreach (var р in где.Value.EnumerateObject())
                по_роду[Род(р.Name, "возраст." + где.Name)] = р.Value.GetDouble();
            к._возраст[где.Name] = по_роду;
        }
        foreach (string нужно in Продукты.ОТКУДА)
            if (!к._откуда.ContainsKey(нужно))
                throw new InvalidDataException($"еда.json: нет «откуда.{нужно}»");
        к.карман_время = корень.GetProperty("карман_время").GetDouble();
        if (корень.TryGetProperty("отравление", out var о))
        {
            к.отравление_просрочено = о.GetProperty("просрочено").GetDouble();
            к.отравление_испорчено = о.GetProperty("испорчено").GetDouble();
        }
        return к;
    }
}

/// <summary>Одна вещь: банка, батон, половина батона.</summary>
public sealed class Продукт
{
    public Продукт(int номер, string вид, double единиц, double возраст, double открыта = -1)
    {
        this.номер = номер;
        this.вид = вид;
        this.единиц = единиц;
        this.возраст = возраст;
        this.открыта = открыта;
    }

    /// <summary>Постоянный номер вещи в этой жизни — по нему экран её узнаёт.</summary>
    public int номер { get; }
    public string вид { get; }

    /// <summary>Сколько порций в ней осталось.</summary>
    public double единиц { get; internal set; }

    /// <summary>Сколько дней пролежала (в кармане время идёт медленнее).</summary>
    public double возраст { get; internal set; }

    /// <summary>Сколько дней как открыта; −1 — закрыта (у хлеба всегда −1).</summary>
    public double открыта { get; internal set; }

    public bool открыт => открыта >= 0;
}

/// <summary>Что вышло из еды: сколько съедено, сытости и настроения,
/// отравился ли; <c>почему</c> — если не съел.</summary>
public sealed record Съедено(double единиц, double сытости, double настроения, bool отравился,
                            string? почему = null);

public sealed class Продукты
{
    /// <summary>Откуда еда приходит к герою — ключи `откуда` в `еда.json`.</summary>
    public static readonly IReadOnlyList<string> ОТКУДА = new[] { "дом", "магазин", "сосед", "гараж", "погреб" };

    public static readonly IReadOnlyList<МестоЕды> МЕСТА = new[] { МестоЕды.ПОЛКА, МестоЕды.НОША, МестоЕды.КАРМАН };

    public const string ЕДА = "еда";

    // сумма вещей и число сходятся до этого: числа дома — порции с дробью
    private const double ТОЧНО = 1e-6;

    private static readonly ConditionalWeakTable<NPC, Продукты> _у = new();

    /// <summary>Вещи героя — или null: у соседей их нет, еда у них число.</summary>
    public static Продукты? У(NPC? я) => я is not null && _у.TryGetValue(я, out var п) ? п : null;

    /// <summary>Завести вещи на героя этой жизни. Зовётся петлёй вместе
    /// с карманом и ношей.</summary>
    public static Продукты Завести(NPC я, КаталогЕды каталог, long зерно)
    {
        var п = new Продукты(каталог, зерно);
        _у.AddOrUpdate(я, п);
        return п;
    }

    public КаталогЕды каталог { get; }

    private readonly Dictionary<МестоЕды, List<Продукт>> _где = new()
    {
        [МестоЕды.ПОЛКА] = new(), [МестоЕды.НОША] = new(), [МестоЕды.КАРМАН] = new(),
    };
    private readonly Rng _rng;
    private int _номер;
    private int? _день;
    private bool _было;         // первая сверка жизни — запас «из дома»

    private Продукты(КаталогЕды каталог, long зерно)
    {
        this.каталог = каталог;
        _rng = new Rng(зерно).Branch("продукты");
    }

    public IReadOnlyList<Продукт> В(МестоЕды м) => _где[м];

    public double Сумма(МестоЕды м) => Util.Sum(_где[м].Select(п => п.единиц));

    /// <summary>Число «еда» в этом месте — то, что знает дом.</summary>
    public static double Число(NPC я, МестоЕды м) => м switch
    {
        МестоЕды.ПОЛКА => я.stock.Взять(ЕДА, 0.0),
        МестоЕды.НОША => я.ноша?.Сколько(ЕДА) ?? 0.0,
        _ => я.карман?.Сколько(ЕДА) ?? 0.0,
    };

    public МестоЕды? Где(Продукт п)
    {
        foreach (var м in МЕСТА)
            if (_где[м].Contains(п))
                return м;
        return null;
    }

    public Продукт? Найти(int номер)
        => МЕСТА.SelectMany(м => _где[м]).FirstOrDefault(п => п.номер == номер);

    public ВидЕды Вид(Продукт п) => каталог[п.вид];

    /// <summary>Какая доля целой вещи осталась.</summary>
    public double Доля(Продукт п) => п.единиц / Вид(п).единиц;

    public Свежесть Свежесть(Продукт п)
    {
        var в = Вид(п);
        if (в.род != РодЕды.БАНКА)
            return п.возраст > в.годна_дней ? Дом.Ядро.Свежесть.ИСПОРЧЕНА : Дом.Ядро.Свежесть.СВЕЖАЯ;
        if (п.открыт && п.открыта > в.открытая_дней)
            return Дом.Ядро.Свежесть.ИСПОРЧЕНА;
        return п.возраст > в.годна_дней ? Дом.Ядро.Свежесть.ПРОСРОЧЕНА : Дом.Ядро.Свежесть.СВЕЖАЯ;
    }

    /// <summary>Сколько дней до порчи — или 0, если уже.</summary>
    public double Дней_до_порчи(Продукт п)
    {
        var в = Вид(п);
        double до = в.годна_дней - п.возраст;
        if (в.род == РодЕды.БАНКА && п.открыт)
            до = Math.Min(до > 0 ? до : double.MaxValue, в.открытая_дней - п.открыта);
        return Math.Max(0.0, до);
    }

    // ------------------------------------------------------------ вещи

    private Продукт Новый(string вид, double единиц, double возраст, double открыта = -1)
        => new(++_номер, вид, единиц, возраст, открыта);

    /// <summary>
    /// Сделать вещи на <paramref name="сколько"/> порций — такие, какие
    /// бывают <paramref name="откуда"/>. Только целые — столько, сколько
    /// влезает (остаток зовущий возвращает, откуда взял); иначе недостающее
    /// добирается куском хлеба (половина батона — тоже вещь).
    /// </summary>
    public List<Продукт> Сделать(string откуда, double сколько, bool целые_только)
    {
        var вышло = new List<Продукт>();
        var веса = каталог.Откуда(откуда);
        double осталось = сколько;
        while (осталось > ТОЧНО)
        {
            var можно = веса.Where(в => в.вес > 0 && каталог[в.вид].единиц <= осталось + ТОЧНО).ToList();
            if (можно.Count == 0)
                break;
            string вид = _rng.Weighted(можно)!;
            var в = каталог[вид];
            вышло.Add(Новый(вид, в.единиц, Возраст(откуда, в)));
            осталось -= в.единиц;
        }
        if (!целые_только && осталось > ТОЧНО)
        {
            // кусок — хлеб, какой бывает здесь; хлеба нет — открытая банка
            var хлеб = веса.Where(в => в.вес > 0 && каталог[в.вид].род == РодЕды.ХЛЕБ).ToList();
            string вид = хлеб.Count > 0 ? _rng.Weighted(хлеб)! : (веса.Count > 0 ? веса[0].вид : каталог.виды[0].id);
            var в = каталог[вид];
            вышло.Add(Новый(вид, осталось, Возраст(откуда, в), в.род == РодЕды.БАНКА ? 0 : -1));
        }
        return вышло;
    }

    private double Возраст(string откуда, ВидЕды в)
        => _rng.Uni(0.0, каталог.Возраст(откуда, в.род) * в.годна_дней);

    /// <summary>Положить вещь в место — только в список: число места
    /// двигает зовущий (ноша, карман, шкаф), и закон сходится у него.</summary>
    public void Положить(МестоЕды м, Продукт п)
    {
        Убрать(п);
        _где[м].Add(п);
    }

    public bool Убрать(Продукт п)
    {
        foreach (var м in МЕСТА)
            if (_где[м].Remove(п))
                return true;
        return false;
    }

    /// <summary>Что съели бы первым: открытое, потом то, что раньше
    /// испортится, потом меньшее. Номер — чтобы порядок был полным.
    /// Сырой овощ — последним: мысль «поесть» дома — это еда, а не сырая
    /// картошка, и дом, который числа не различает, берёт её, только когда
    /// ничего другого нет.</summary>
    private IOrderedEnumerable<Продукт> Первым(IEnumerable<Продукт> что)
        => что.OrderBy(п => Вид(п).род == РодЕды.ОВОЩ)
              .ThenByDescending(п => п.открыт)
              .ThenBy(п => Дней_до_порчи(п))
              .ThenBy(п => п.единиц)
              .ThenBy(п => п.номер);

    /// <summary>Снять с места столько порций: целыми, а последнюю —
    /// частью (банка при этом открывается). Снятое — отдельными вещами.</summary>
    private List<Продукт> Снять(МестоЕды м, double сколько)
    {
        var снято = new List<Продукт>();
        foreach (var п in Первым(_где[м]).ToList())
        {
            if (сколько <= ТОЧНО)
                break;
            if (п.единиц <= сколько + ТОЧНО)
            {
                _где[м].Remove(п);
                снято.Add(п);
                сколько -= п.единиц;
                continue;
            }
            // часть: от вещи отходит кусок, сама она становится початой
            снято.Add(Новый(п.вид, сколько, п.возраст, Вид(п).род == РодЕды.БАНКА ? Math.Max(0, п.открыта) : -1));
            п.единиц -= сколько;
            if (Вид(п).род == РодЕды.БАНКА && !п.открыт)
                п.открыта = 0;
            сколько = 0;
        }
        return снято;
    }

    // ------------------------------------------------------------ порча

    /// <summary>Состарить вещи до этого дня дома: на полке и в ноше день
    /// за день, в кармане — медленнее. Первый зов только запоминает день.</summary>
    public void Состарить(int день)
    {
        if (_день is not int был)
        {
            _день = день;
            return;
        }
        int дней = день - был;
        if (дней <= 0)
            return;
        _день = день;
        foreach (var м in МЕСТА)
        {
            double темп = м == МестоЕды.КАРМАН ? каталог.карман_время : 1.0;
            foreach (var п in _где[м])
            {
                п.возраст += дней * темп;
                if (п.открыт)
                    п.открыта += дней * темп;
            }
        }
    }

