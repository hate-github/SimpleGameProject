// Сохранение игры посреди жизни (ГДД 24; задание автора, этап 5: «Продолжить»).
//
// «Одна жизнь — одно сохранение, автоматическое, перезаписывается при каждом
// сне; загрузить раньше нельзя». Наследие живёт своим файлом (`Хранение`)
// и переживает все жизни; здесь — ровно текущая жизнь, чтобы выйти
// посреди метели и вернуться туда же:
//
//   · кем играют (профиль героя или жилец) и зерно мира;
//   · дом — сейвом ядра (`Сохранение`, сверен с прототипом, продолженный
//     прогон догоняет непрерывный день в день);
//   · то, что живёт мимо сейва дома, — только у игрока: ноша, карман,
//     снаряжение, округа (знания, снегоступы, болезнь, участок), магазин,
//     пролог, дневник петли и прочитанные надписи.
//
// Поднимается так же, как собирался: прогон с тем же героем (он должен быть
// в доме до загрузки), загрузка дома, петля слушает, и только потом —
// состояние игрока поверх свежих объектов. Умерла жизнь — файла нет.

using System.Text.Json;
using System.Text.Json.Nodes;

namespace Дом.Ядро;

/// <summary>Что лежит в сохранении сверху: кем, в каком мире, какой день.</summary>
public sealed record ЗаголовокСохранения(ПрофильГероя? герой, string кто, long зерно, int дней, int день,
                                         bool пролог, int пролог_день);

public static class СохранениеИгры
{
    public const int ВЕРСИЯ = 1;

    /// <summary>Сложить текущую жизнь. Зовётся, пока дом спит или стоит
    /// на границе дня (наблюдатель `on_day`), — не на ходу.</summary>
    public static JsonObject Сложить(ПрофильГероя? герой, string кто, Прогон прогон, Петля петля,
                                     Магазин? магазин, Пролог? пролог)
    {
        var h = прогон.h;
        var я = h.people[кто];
        return new JsonObject
        {
            ["версия"] = ВЕРСИЯ,
            ["герой"] = герой is null ? null : new JsonObject { ["имя"] = герой.имя, ["пол"] = герой.пол },
            ["кто"] = кто,
            ["зерно"] = прогон.seed,
            ["дней"] = прогон.days,
            ["день"] = h.day,
            ["дом"] = Сохранение.сохранить(h),
            ["игрок"] = new JsonObject
            {
                ["ноша"] = я.ноша?.Сложить(),
                ["карман"] = я.карман?.Сложить(),
                ["снаряжение"] = я.снаряжение?.Сложить(),
            },
            ["округа"] = Округа.У(h)?.Сложить(),
            ["магазин"] = магазин?.Сложить(),
            ["пролог"] = пролог is { идёт: true } ? пролог.Сложить() : null,
            ["петля"] = петля.Сложить_жизнь(),
        };
    }

    public static ЗаголовокСохранения Заголовок(JsonObject о)
    {
        int версия = о["версия"]?.GetValue<int>() ?? 0;
        if (версия != ВЕРСИЯ)
            throw new InvalidDataException($"сохранение игры версии {версия}, а читаем {ВЕРСИЯ}");
        var г = о["герой"] as JsonObject;
        var п = о["пролог"] as JsonObject;
        return new ЗаголовокСохранения(
            г is null ? null : new ПрофильГероя(г["имя"]!.GetValue<string>(), г["пол"]!.GetValue<string>()),
            о["кто"]!.GetValue<string>(), о["зерно"]!.GetValue<long>(), о["дней"]!.GetValue<int>(),
            о["день"]!.GetValue<int>(), п is not null, п?["день"]?.GetValue<int>() ?? 0);
    }

    /// <summary>Прогон того же мира с тем же героем — и дом из сохранения.</summary>
    public static Прогон Прогон_из(JsonObject о, string каталог, IЖурнал? журнал = null)
    {
        var з = Заголовок(о);
        var прогон = new Прогон(каталог, seed: з.зерно, days: з.дней, журнал: журнал,
                                жильцы: з.герой is { } г ? (npcs => Герой.Заселить(npcs, г, каталог)) : null);
        Сохранение.загрузить(о["дом"]!.AsObject(), прогон.h);
        return прогон;
    }

    /// <summary>
    /// Вернуть игроку своё — после того как петля слушает дом (`Петля.Слушать`
    /// завела свежие ношу, карман, снаряжение и округу). Возвращает пролог,
    /// если сохранились в нём, — иначе null: метель уже идёт.
    /// </summary>
    public static Пролог? Разложить(JsonObject о, Прогон прогон, Петля петля, Магазин? магазин)
    {
        var h = прогон.h;
        var я = h.people[о["кто"]!.GetValue<string>()];
        var и = о["игрок"]!.AsObject();
        if (и["ноша"] is JsonObject н)
            (я.ноша ??= new Ноша()).Разложить(н);
        if (и["карман"] is JsonObject к && я.карман is not null)
            я.карман.Разложить(к);
        if (и["снаряжение"] is JsonObject с && я.снаряжение is not null)
            я.снаряжение.Разложить(с);
        if (о["округа"] is JsonObject ок && Округа.У(h) is { } округа)
            округа.Разложить(ок, я);
        if (о["магазин"] is JsonObject м && магазин is not null)
            магазин.Разложить(м);
        петля.Разложить_жизнь(о["петля"]!.AsObject());
        return о["пролог"] is JsonObject п ? Пролог.Разложить(п) : null;
    }

    public static void Записать(JsonObject о, string путь)
    {
        string временный = путь + ".новый";
        File.WriteAllText(временный, о.ToJsonString(new JsonSerializerOptions
        {
            Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping,
        }));
        // сперва целиком в соседний файл, потом подменить: выключенный посреди
        // записи компьютер не должен оставить сохранение битым
        File.Move(временный, путь, overwrite: true);
    }

    public static JsonObject Прочитать(string путь)
        => JsonNode.Parse(File.ReadAllText(путь))!.AsObject();
}
