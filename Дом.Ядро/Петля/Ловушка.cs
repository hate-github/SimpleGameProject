// Ловушка у своей двери (ГДД 15, уровень 4: «звукоизоляция генератора,
// укрепление стен и потолка арматурой, ловушки»; требования — «знания
// „Механик“ и „Строитель“, „Смекалка“ 4»).
//
// Ставят её из материалов (доски, проволока — из шкафа) у порога изнутри:
// снаружи не видно, а кто вошёл без спросу — попался. Поставить может тот,
// кто разбирается: Смекалка от «ловушка_смекалка» или знание «механик» —
// его рассказывает Руслан, сварщик с вахты, как знатоки рассказывают о мире
// (`мир.json`, «знатоки»), и оно переходит в следующую жизнь. Сыграть
// за слесаря (`NPC.skills`) — тоже можно. Знание и Смекалка здесь — «или»,
// как у камеры: строителя в доме нет, и ступень, закрытая двумя знаниями
// сразу, не открылась бы никогда.
//
// Срабатывает один раз — на того, кто входит в квартиру героя без него:
// ночной вор и дневной (`Конфликт.steal`), первый в пролом налёта
// (`Конфликт.run_siege`), сосед, вскрывший пустую квартиру
// (`Округа.Пустая_квартира`). Гостю, который стучит, она не страшна: он
// не входит. Попавшийся ранен в ногу, кричит — слышит площадка — и уходит
// ни с чем; к этой двери он больше не полезет (`Социальное.испугался`).
// Убить ловушка не может: рана тянет здоровье вниз, но не до нуля. Дальше
// это рана как любая другая (`Физиология`), и чем она кончится, решает
// метель. Сработала — взвести заново, тем же трудом.
//
// Герой дома — знает, кто попался: вышел на крик. Нет его — видит наутро
// кровь на пороге и не знает чью; камера, если висит, покажет.
//
// Ловушка принадлежит квартире, как все постройки убежища, и с новой жизнью
// её нет. Только у героя: живёт в округе (`Округа.ловушка`, в сохранении
// игры), дом о ней не знает, и прогон без игрока тот же бит в бит — все три
// места спрашивают `Округа.У(h)`, а её в нём нет.

using System.Text.Json.Nodes;

namespace Дом.Ядро;

/// <summary>Кто попался: день, кто, за каким делом шёл и знает ли герой, кто это.</summary>
public sealed record Попался(int день, string кто, string дело, bool узнал);

public sealed class Ловушка
{
    /// <summary>Знание, с которым ловушку ставят и без Смекалки.</summary>
    public const string МЕХАНИК = "механик";

    /// <summary>Умение соседа, с которым её ставит сам (`NPC.skills`).</summary>
    public const string СЛЕСАРЬ = "слесарь";

    /// <summary>Какую рану оставляет.</summary>
    public const string РАНА = "рана ноги";

    /// <summary>Ниже этого здоровья ловушка не сбивает: убить она не может.</summary>
    public const double ПОЛ_ЗДОРОВЬЯ = 8.0;

    private readonly List<Попался> _попались = new();
    private readonly object _замок = new();
    private int _показано;

    public Ловушка(int квартира, double урон)
    {
        this.квартира = квартира;
        this.урон = урон;
    }

    /// <summary>У чьей двери стоит.</summary>
    public int квартира { get; }

    /// <summary>Сколько здоровья отнимает, — каким её поставили.</summary>
    public double урон { get; private set; }

    /// <summary>Взведена — сработает на первого, кто войдёт.</summary>
    public bool взведена { get; private set; } = true;

    /// <summary>Кто попадался — по порядку.</summary>
    public IReadOnlyList<Попался> попались
    {
        get
        {
            lock (_замок)
                return _попались.ToList();
        }
    }

    /// <summary>
    /// Почему не поставить — или null, если можно: уже стоит взведённая,
    /// не разобраться (ни Смекалки, ни знания механика), не хватает материалов.
    /// </summary>
    public static string? Нельзя(House h, NPC я, РучкиПетли ручки)
    {
        var о = Округа.У(h);
        if (о?.ловушка is { взведена: true })
            return "ловушка уже стоит";
        if (!Умеет(я, о, ручки))
            return $"не разобраться — нужна Смекалка {(int)ручки["ловушка_смекалка"]} или знать дело механика";
        double нужно = ручки["ловушка_материалы"];
        if (я.stock.Взять("материалы", 0.0) < нужно - 1e-9)
            return $"на доски и проволоку нужно материалов {Текст.G(нужно)}";
        return null;
    }

    /// <summary>Сколько часов ставить — поступком героя.</summary>
    public static double Часы(РучкиПетли ручки) => ручки["ловушка_часы"];

    /// <summary>Разбирается ли он в этом: Смекалка от порога, знание механика
    /// (узнал у Руслана) или сам слесарь.</summary>
    public static bool Умеет(NPC я, Округа? о, РучкиПетли ручки)
        => (я.умения?.наследие.Уровень(Навык.СМЕКАЛКА) ?? 0) >= (int)ручки["ловушка_смекалка"]
           || о?.Знает(МЕХАНИК) == true
           || я.skills.Contains(СЛЕСАРЬ, StringComparer.Ordinal);

    /// <summary>
    /// Поставить у своей двери — или взвести сработавшую: материалы из шкафа.
    /// null — нельзя (`Нельзя`). Часы тратит зовущий — поступком героя
    /// («ловушка_часы»). Только пока дом спит.
    /// </summary>
    public static Ловушка? Поставить(House h, NPC я, РучкиПетли ручки)
    {
        if (Нельзя(h, я, ручки) is not null || Округа.У(h) is not { } о)
            return null;
        я.stock["материалы"] = я.stock.Взять("материалы", 0.0) - ручки["ловушка_материалы"];
        if (о.ловушка is { } была && была.квартира == я.apt)
        {
            была.урон = ручки["ловушка_урон"];
            была.взведена = true;
            return была;
        }
        var л = new Ловушка(я.apt, ручки["ловушка_урон"]);
        о.ловушка = л;
        return л;
    }

    /// <summary>
    /// <paramref name="кто"/> входит к <paramref name="хозяин"/> без спросу
    /// за делом <paramref name="дело"/>. Взведена и это та квартира — попался:
    /// рана, крик на площадке, страх перед этой дверью; ловушка спущена.
    /// Возвращает строку для журнала — или null, если ничего не было.
    /// Зовётся ядром, пока идёт день; `rng` не трогает, кроме шума.
    /// </summary>
    public string? Сработала(House h, NPC кто, NPC хозяин, string дело)
    {
        if (!взведена || хозяин.apt != квартира
            || string.Equals(кто.id, хозяин.id, StringComparison.Ordinal))
            return null;
        взведена = false;
        var b = h.B;
        кто.injuries.Add(РАНА);
        кто.health = Math.Max(кто.health - урон, Math.Min(кто.health, ПОЛ_ЗДОРОВЬЯ));
        кто.panic = Util.Clamp(кто.panic + 14);
        // к этой двери он больше не полезет: не совесть, а нога
        Социальное.испугался(h, кто, хозяин, b["страх_за_насилие"]);
        Социальное.adjust(кто, хозяин.id, hate: 10, aware: 10);
        // кричит — слышит площадка, а дома и сам хозяин
        Социальное.emit(h, хозяин, 4, "ссора", night: true);
        bool дома = !хозяин.нет_в_доме() && !хозяин.away;
        if (дома)
            Социальное.adjust(хозяин, кто.id, trust: -3.0, hate: 8, aware: 15);
        lock (_замок)
            _попались.Add(new Попался(h.day, кто.id, дело, дома));
        h.bump("ловушка_сработала");
        if (!дома)
        {
            h.journal.secret($"{кто.@short} {Util.Vb(кто.sex, "попал")} в ловушку у двери кв.{квартира}.");
            return $"У двери кв.{квартира} сработала ловушка: кто-то ушёл, хромая, на пороге кровь.";
        }
        return $"У двери кв.{квартира} сработала ловушка: {кто.@short} {Util.Vb(кто.sex, "попал")} "
               + $"в неё ногой и, хромая, {Util.Vb(кто.sex, "ушёл")} ни с чем.";
    }

    /// <summary>Что герой ещё не видел: попались с прошлого раза — по разу.</summary>
    public IReadOnlyList<Попался> Новые()
    {
        lock (_замок)
        {
            var новые = _попались.Skip(_показано).ToList();
            _показано = _попались.Count;
            return новые;
        }
    }

    // ------------------------------------------------------------ сохранение игры

    public JsonObject Сложить()
    {
        var попались = new JsonArray();
        lock (_замок)
            foreach (var п in _попались)
                попались.Add(new JsonObject
                {
                    ["день"] = п.день, ["кто"] = п.кто, ["дело"] = п.дело, ["узнал"] = п.узнал,
                });
        return new JsonObject
        {
            ["квартира"] = квартира, ["урон"] = урон, ["взведена"] = взведена,
            ["показано"] = _показано, ["попались"] = попались,
        };
    }

    public static Ловушка Разложить(JsonObject о)
    {
        var л = new Ловушка(о["квартира"]!.GetValue<int>(), о["урон"]!.GetValue<double>())
        {
            взведена = о["взведена"]!.GetValue<bool>(),
        };
        foreach (var x in о["попались"]!.AsArray())
            л._попались.Add(new Попался(x!["день"]!.GetValue<int>(), x["кто"]!.GetValue<string>(),
                                        x["дело"]!.GetValue<string>(), x["узнал"]!.GetValue<bool>()));
        л._показано = Math.Min(о["показано"]?.GetValue<int>() ?? л._попались.Count, л._попались.Count);
        return л;
    }
}
