// Жизнь вне дома — в участке и в бункере (задание автора, п. 18; ГДД 20).
//
// Там свой запас, своя печь и свои нары, и правила у них общие — те же,
// что дома, откуда и мерки: порция еды и воды (`Действия.порция`,
// `вода_за_порцию`), часы дел (`часы_действий`), снег на воду
// (`снег_топливо`, `снег_на_горящей_печке`, `снег_вода`).
//
// Первая версия кормила из запаса мгновенно и сколько угодно: «поесть» —
// кнопка без времени и без сытости, жми, пока не надоест (автор: «из
// ящика с провизией можно вечно есть и пить»). Теперь как дома:
//   · **не больше, чем лезет**: сытому еда не лезет, напившемуся вода,
//     и за раз — порция или меньше, сколько влезло;
//   · **за время**: дело стоит часов, и дом в эти часы живёт;
//   · **вода кончается** — снег топят на печке: вода прибавляется,
//     топливо уходит (горит печка — доплата меньше).
//
// Всё это только у игрока, как и сами места: соседи в участке и бункере
// не живут, и дом считает их, как считал.

namespace Дом.Ядро;

/// <summary>Место, где герой живёт не дома: запас, печь, тепло (`IПриют`).</summary>
public interface IУбежище : IПриют
{
    /// <summary>Как назвать место в вестях: «участок», «убежище».</summary>
    string Где { get; }

    /// <summary>Герой здесь и может брать из запаса (не в камере, дверь открыта).</summary>
    bool Доступно { get; }

    double В_запасе(string ресурс);
    void Изъять(string ресурс, double сколько);
    void Добавить(string ресурс, double сколько);

    bool Печь_топится(int день);

    /// <summary>Затопить печь на сегодня — null, или почему нет.</summary>
    string? Затопить(House h);
}

/// <summary>Чем кончилось дело на месте: сделано ли, сколько часов оно
/// стоит (их проживает зовущий — дом в это время живёт) и что сказать.</summary>
public sealed record Сделано(bool да, double часов, string весть);

public static class Убежище
{
    public const string ЕДА = "еда", ВОДА = "вода", ТОПЛИВО = "топливо";

    /// <summary>Сколько порций этого лезет сейчас: еда — по сытости, вода — по жажде.</summary>
    public static double Лезет(House h, NPC я, string ресурс)
        => ресурс == ВОДА
            ? (100.0 - я.hydration) / h.B["вода_за_порцию"]
            : (100.0 - я.satiety) / Действия.порция(h, я, h.B);

    /// <summary>
    /// Съесть или выпить откуда угодно — из запаса, из кармана: не больше
    /// порции и не больше, чем лезет; <paramref name="есть"/> — сколько там,
    /// <paramref name="взять"/> — вынуть столько. Часы — как у дома
    /// за «поесть» и «попить».
    /// </summary>
    public static Сделано Порция(House h, NPC я, string ресурс, double есть, Action<double> взять)
    {
        bool вода = ресурс == ВОДА;
        if (есть < 0.05)
            return new Сделано(false, 0, вода ? "воды нет" : "есть нечего");
        double лезет = Лезет(h, я, ресурс);
        if (лезет < 0.1)
            return new Сделано(false, 0, вода ? "пить не хочется" : "не лезет — сыт");
        double сколько = Math.Min(1.0, Math.Min(лезет, есть));
        взять(сколько);
        if (вода)
            я.hydration = Util.Clamp(я.hydration + h.B["вода_за_порцию"] * сколько);
        else
        {
            я.satiety = Util.Clamp(я.satiety + Действия.порция(h, я, h.B) * сколько);
            h.stats["съедено"] = h.stats.Взять("съедено", 0.0) + сколько;
        }
        return new Сделано(true, Действия.hours(вода ? "попить" : "поесть", я, h.B),
                           (вода ? "попил" : "поел") + (сколько < 0.99 ? " — сколько влезло" : ""));
    }

    public static Сделано Поесть(House h, NPC я, IУбежище у)
        => !у.Доступно
            ? new Сделано(false, 0, $"до запаса не добраться")
            : Порция(h, я, ЕДА, у.В_запасе(ЕДА), с => у.Изъять(ЕДА, с));

    public static Сделано Попить(House h, NPC я, IУбежище у)
        => !у.Доступно
            ? new Сделано(false, 0, $"до запаса не добраться")
            : Порция(h, я, ВОДА, у.В_запасе(ВОДА), с => у.Изъять(ВОДА, с));

    /// <summary>
    /// Натопить снега на печке — вода в запас. Печка холодная — затопить
    /// её (день тепла, топливо как за топку); горит — доплатить меньше,
    /// как дома (`снег_на_горящей_печке`).
    /// </summary>
    public static Сделано Снег(House h, NPC я, IУбежище у)
    {
        if (!у.Доступно)
            return new Сделано(false, 0, "до печки не добраться");
        bool затопил = false;
        if (!у.Печь_топится(h.day))
        {
            if (у.Затопить(h) is string нельзя)
                return new Сделано(false, 0, $"снег топят на печке — а {нельзя}");
            затопил = true;
        }
        else
        {
            double доплата = h.B["снег_топливо"] * h.B["снег_на_горящей_печке"];
            if (у.В_запасе(ТОПЛИВО) < доплата - 1e-9)
                return new Сделано(false, 0, "на снег топлива не хватит");
            у.Изъять(ТОПЛИВО, доплата);
        }
        у.Добавить(ВОДА, h.B["снег_вода"]);
        return new Сделано(true, Действия.hours("топить_снег", я, h.B),
                           (затопил ? "затопил печку и натопил снега" : "натопил снега на горячей печке")
                           + $" — воды +{Текст.G(h.B["снег_вода"])}");
    }

    /// <summary>Затопить делом: часы — как у дома за «топить».</summary>
    public static Сделано Затопить(House h, NPC я, IУбежище у)
    {
        if (у.Печь_топится(h.day))
            return new Сделано(false, 0, "печка уже топится");
        if (у.Затопить(h) is string нельзя)
            return new Сделано(false, 0, нельзя);
        return new Сделано(true, Действия.hours("топить", я, h.B), "затопил печку — до вечера будет тепло");
    }
}
