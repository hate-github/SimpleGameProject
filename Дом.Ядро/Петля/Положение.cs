// Положение героя (задание автора, п. 2): в каком он сейчас виде.
//
// Шесть положений — норма, подозревают, застали, скрутили, ранен, без
// сознания — и ни одно не заведено отдельным счётчиком: всё читается
// из того, что дом и так знает о теле героя и о его поимках. Отдельная
// «машина состояний» рядом с телом разошлась бы с ним на первой же драке:
// тело ранено, а машина говорит «норма».
//
//   · БЕЗ_СОЗНАНИЯ — избили до беспамятства (`Взлом.разобрать` отмечает
//     день) или здоровье ниже порога: день для героя кончился, ходить
//     и делать нельзя до следующего вопроса дома;
//   · СКРУТИЛИ — застали снова и держат, пока дом разбирает поимку;
//   · ЗАСТАЛИ — застали в первый раз, разбор идёт;
//   · РАНЕН — перелом или огнестрел, две раны разом или здоровье ниже
//     порога: ходит медленно, ломать замки не может;
//   · ПОДОЗРЕВАЮТ — сегодня стук уже слышали: дом настороже, и на
//     следующий стук спустятся охотнее (`Взлом.спустится`);
//   · НОРМА — всё прочее.
//
// Пороги — ручки петли (`без_сознания_ниже`, `ранен_ниже`). Положение
// только у игрока: соседи живут своим телом, и их решения это не трогает.

namespace Дом.Ядро;

public enum Положение { НОРМА, ПОДОЗРЕВАЮТ, ЗАСТАЛИ, СКРУТИЛИ, РАНЕН, БЕЗ_СОЗНАНИЯ }

/// <summary>Стук взлома, который сегодня слышали: день, сколько дел
/// и слышали ли уже идущее (его куски — один стук, `Взлом.кусок`).
/// Только у игрока — как ноша, мимо снимка и сейва.</summary>
public sealed record ШумВзлома(int день, int раз, bool в_этом_деле = false);

public static class Положения
{
    /// <summary>В каком виде герой сейчас. Читать — пока дом спит на вопросе.</summary>
    public static Положение Героя(House h, NPC я, РучкиПетли ручки)
    {
        if (я.без_сознания == h.day || я.health < ручки["без_сознания_ниже"])
            return Положение.БЕЗ_СОЗНАНИЯ;
        if (я.застали is { } з && з.день == h.day)
            return з.уровень > 0 ? Положение.СКРУТИЛИ : Положение.ЗАСТАЛИ;
        if (Ранен(я, ручки))
            return Положение.РАНЕН;
        if (я.шум_взлома is { } ш && ш.день == h.day)
            return Положение.ПОДОЗРЕВАЮТ;
        return Положение.НОРМА;
    }

    /// <summary>Ранен так, что тяжёлого не сделать: перелом или огнестрел,
    /// две раны разом, или здоровье ниже порога. Одна ссадина на руке —
    /// ещё не ранен: она и так бьёт по мерке работы.</summary>
    public static bool Ранен(NPC я, РучкиПетли ручки)
        => я.health < ручки["ранен_ниже"]
           || я.injuries.Count >= 2
           || я.injuries.Any(р => р.Contains("перелом", StringComparison.Ordinal)
                                  || р.Contains("огнестрел", StringComparison.Ordinal));

    /// <summary>Можно ли ломать замок: тяжёлое дело, нужны руки и ноги.</summary>
    public static bool Можно_ломать(Положение п) => п is Положение.НОРМА or Положение.ПОДОЗРЕВАЮТ;

    /// <summary>Можно ли обыскивать и вообще что-то делать руками.</summary>
    public static bool Можно_делать(Положение п)
        => п is not (Положение.БЕЗ_СОЗНАНИЯ or Положение.СКРУТИЛИ or Положение.ЗАСТАЛИ);

    /// <summary>Может ли ходить: держат или без сознания — нет.</summary>
    public static bool Может_ходить(Положение п)
        => п is not (Положение.БЕЗ_СОЗНАНИЯ or Положение.СКРУТИЛИ);

    /// <summary>Как положение звучит — строкой над телом; норма молчит.</summary>
    public static string Текст(this Положение п) => п switch
    {
        Положение.БЕЗ_СОЗНАНИЯ => "без сознания — день для тебя кончился",
        Положение.СКРУТИЛИ => "тебя держат",
        Положение.ЗАСТАЛИ => "тебя застали",
        Положение.РАНЕН => "ранен — тяжёлое не под силу",
        Положение.ПОДОЗРЕВАЮТ => "стук слышали — дом настороже",
        _ => "",
    };
}
