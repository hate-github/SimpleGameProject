// Чем герой жил — по дням, а не по остатку на конец.
//
// Рассудок ломают «долгое одиночество, голод, темнота» (ГДД 11), и все три
// про **дни**, а не про число на момент смерти. Дом их не помнит: сытость
// у него одна, текущая, а с какого дня нет света — не записано нигде.
//
// Считать это по остатку нельзя, и первая попытка это показала. Голод там
// мерился суммой отказов по всем соседям — то есть «сколько раз кому-то
// сказали нет», а не «сколько дней он ложился голодным»: на пяти
// одинаковых жизнях шкала уходила за точку невозврата втрое, и почти всё
// давала эта одна строка. Число выглядело настроенным и не значило ничего.
//
// Правильный способ у дома уже есть — наблюдатель (`Хуки.on_day`). Он
// зовётся в конце каждого дня, ничего не меняет и `rng` не трогает: это
// договор наблюдателя, и он же защищает петлю от влияния на симуляцию.
// Дневник — такой наблюдатель и ничего больше.

namespace Дом.Ядро;

/// <summary>Счётчики за жизнь: сколько дней было плохо и чем.</summary>
public sealed class Дневник
{
    private readonly string _кто;
    private readonly РучкиПетли _ручки;

    public Дневник(string кто, РучкиПетли ручки)
    {
        _кто = кто;
        _ручки = ручки;
    }

    /// <summary>Дней, которые он закончил голодным.</summary>
    public int голодных { get; private set; }

    /// <summary>Дней без света в доме.</summary>
    public int тёмных { get; private set; }

    /// <summary>Дней, за которые он ни с кем не соприкоснулся: одиночество
    /// в ГДД 11 — это «не с кем было», а не «жил один».</summary>
    public int одиноких { get; private set; }

    /// <summary>Дней прожито под наблюдением — на случай, если жизнь
    /// оборвали раньше, чем кончилась метель.</summary>
    public int дней { get; private set; }

    /// <summary>
    /// Подписаться на дом.
    ///
    /// Зовётся до `run()`. Наблюдатель в дом ничего не пишет — и это
    /// не обещание, а то, что проверяет раздел «петля»: дом с дневником
    /// обязан дать тот же снимок, что дом без него.
    /// </summary>
    public void Слушать(House h)
        => h.hooks.on_day.Add(День);

    private void День(House h)
    {
        var я = h.get(_кто);
        if (я is null || !я.здесь())
            return;                             // мёртвому дни не идут
        дней++;
        if (я.satiety < _ручки["голоден_ниже"])
            голодных++;
        if (!h.power_on)
            тёмных++;
        if (!Соприкасался(h, я))
            одиноких++;
    }

    /// <summary>
    /// Был ли у него сегодня хоть один контакт.
    ///
    /// Считается по суточным контактам дома (`h.сутки.контакты`) — там
    /// записано, кто с кем и о чём за сегодня сходился. Это то же место,
    /// откуда дом берёт пределы на пару за день, и другого столь же
    /// честного признака «сегодня с ним говорили» у нас нет.
    /// </summary>
    private bool Соприкасался(House h, NPC я)
    {
        foreach (var (ключ, сколько) in h.сутки.контакты)
            if (сколько > 0
                && (string.Equals(ключ.Item1, я.id, StringComparison.Ordinal)
                    || string.Equals(ключ.Item2, я.id, StringComparison.Ordinal)))
                return true;
        return false;
    }
}
