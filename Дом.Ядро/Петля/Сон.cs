// Сон героя (просьба автора, 28.09.2026): спать ложатся в постель, а не там,
// где застала ночь. Раньше ночь приходила окном посередине экрана, и «спать»
// нажималось в любом месте — в подвале, во дворе, у чужой двери.
//
// Теперь день кончился — у героя час, чтобы дойти до постели и лечь
// (`сон_запас_часов`): дома — матрас, в участке и в убежище — нары. Лёг
// позже — недоспал ровно на столько: бодрость наутро — как за столько часов
// сна меньше (`сон_за_час` дома). И чем больше недосып, тем вернее проспал
// будильник (`сон_проспать_шанс` за час, не больше `сон_проспать_не_больше`
// часов): утро начинается позже, день короче. Совсем не лёг — через
// `сон_уснуть_часов` после конца дня уснул, где стоял, со всем недосыпом.
//
// Только у игрока: ночь дома (сколько спят, что делают) не тронута — недосып
// ложится на героя утром, до первого его дела, и эталон его не видит.
// Бросок «проспал» — от зерна мира (`Округа.Бросок`), мимо `h.rng`.

namespace Дом.Ядро;

/// <summary>Чем кончилось позднее «спать»: сколько часов недоспал
/// и на сколько проспал будильник.</summary>
public sealed record Недосып(double часов, double проспал)
{
    public static readonly Недосып НЕТ = new(0, 0);
    public bool есть => часов > 1e-9;
}

public static class Сон
{
    /// <summary>
    /// Лёг через <paramref name="поздно"/> часов после конца дня:
    /// запас — без последствий, сверх него — недосып; проспал —
    /// с шансом по недосыпу (<paramref name="бросок"/> — от зерна мира).
    /// </summary>
    public static Недосып Лёг(double поздно, РучкиПетли ручки, double бросок)
    {
        double лишнего = Math.Max(0.0, поздно - ручки["сон_запас_часов"]);
        if (лишнего <= 1e-9)
            return Недосып.НЕТ;
        double шанс = Math.Min(1.0, лишнего * ручки["сон_проспать_шанс"]);
        double проспал = бросок < шанс ? Math.Min(лишнего, ручки["сон_проспать_не_больше"]) : 0.0;
        return new Недосып(лишнего, проспал);
    }

    /// <summary>Не лёг так долго, что уснул, где стоял.</summary>
    public static bool Уснул_где_стоял(double поздно, РучкиПетли ручки)
        => поздно >= ручки["сон_уснуть_часов"];

    /// <summary>Сколько после конца дня ещё можно лечь без недосыпа.</summary>
    public static double Запас(РучкиПетли ручки) => ручки["сон_запас_часов"];

    /// <summary>
    /// Утро после недосыпа: бодрость — как за столько часов сна меньше,
    /// проспал — день на столько короче. Зовут, пока дом спит на первом
    /// вопросе утра.
    /// </summary>
    public static void Утро(NPC я, Недосып н, Баланс b)
    {
        if (!н.есть)
            return;
        я.rest = Util.Clamp(я.rest - н.часов * b["сон_за_час"]);
        я.time_left = Math.Max(0.0, я.time_left - н.проспал);
    }
}
