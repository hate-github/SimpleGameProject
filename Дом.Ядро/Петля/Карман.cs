// Карман вне времени (ГДД 9).
//
// Не удобство, а аномалия — и это не украшение текста, а устройство.
// Вещь **исчезает из мира** в момент, когда её туда кладут: не «убирается
// в сумку», а перестаёт существовать для всех, кроме героя. Кто это увидел,
// получает максимальное подозрение, и никакой другой поступок в игре
// столько не даёт.
//
// Отсюда три правила, каждое из которых кому-то неудобно:
//   · вес ограничен и растёт только с Физикой;
//   · внутри время идёт медленнее — но пока не идёт вовсе: ГДД 9 говорит
//     «портится вчетверо медленнее», а снаружи еда не портится ни разу,
//     и сравнивать не с чем. Правило ждёт порчи в самом доме;
//   · содержимое **обнуляется при смерти**. Переносится пустое
//     пространство, и только оно (ГДД 8).
//
// Карман есть только у того, у кого есть наследие. У соседей его нет,
// и потому обычный прогон о нём не знает вовсе.

namespace Дом.Ядро;

/// <summary>Кто видел, как вещь исчезла.</summary>
public sealed record Свидетель(string кто, string ресурс, double сколько, int день);

public sealed class Карман
{
    private readonly Умения _умения;
    private readonly Словарь<string, double> _вещи = Словари.Числа();

    public Карман(Умения умения) => _умения = умения;

    /// <summary>Сколько влезает.</summary>
    public double предел => _умения.карман;

    /// <summary>Сколько занято.</summary>
    public double занято => Util.Sum(_вещи.Ключи.Select(к => _вещи[к]));

    public double свободно => System.Math.Max(0.0, предел - занято);

    public IReadOnlyList<string> ресурсы => _вещи.Ключи;

    public double Сколько(string ресурс) => _вещи.Взять(ресурс, 0.0);

    /// <summary>
    /// Положить — то есть убрать из мира.
    ///
    /// Возвращает свидетелей: тех, кто был в это время в той же квартире.
    /// Что с ними делать, решает вызывающий — карман сам в отношения
    /// не лезет, потому что он про вещи, а подозрение про людей.
    /// </summary>
    public IReadOnlyList<Свидетель> Положить(House h, NPC я, string ресурс,
                                             double сколько)
    {
        сколько = System.Math.Min(сколько, System.Math.Min(
            я.stock.Взять(ресурс, 0.0), свободно));
        if (сколько <= 0.0)
            return System.Array.Empty<Свидетель>();

        я.stock[ресурс] = я.stock.Взять(ресурс, 0.0) - сколько;
        _вещи[ресурс] = Сколько(ресурс) + сколько;

        // кто был рядом. Не «весь дом» и не «никто»: те, кто стоит
        // с ним в одной квартире, — гости и хозяин, если он переехал
        var видели = new List<Свидетель>();
        foreach (var о in h.household(h.хозяин_жилья(я)))
            if (!string.Equals(о.id, я.id, StringComparison.Ordinal) && о.здесь())
                видели.Add(new Свидетель(о.id, ресурс, сколько, h.day));
        return видели;
    }

    /// <summary>Достать обратно в мир.</summary>
    public double Достать(NPC я, string ресурс, double сколько)
    {
        сколько = System.Math.Min(сколько, Сколько(ресурс));
        if (сколько <= 0.0)
            return 0.0;
        _вещи[ресурс] = Сколько(ресурс) - сколько;
        if (_вещи[ресурс] <= 0.0)
            _вещи.Убрать(ресурс);
        я.stock[ресурс] = я.stock.Взять(ресурс, 0.0) + сколько;
        return сколько;
    }

    /// <summary>Смерть: содержимое не переносится никогда (ГДД 8).</summary>
    public void Обнулить() => _вещи.Очистить();

    public override string ToString()
        => _вещи.Ключи.Count == 0
           ? "пусто"
           : string.Join(", ", _вещи.Ключи
               .OrderBy(к => к, StringComparer.Ordinal)
               .Select(к => $"{к} {Текст.G(Текст.Округлить(_вещи[к], 2))}"));
}
