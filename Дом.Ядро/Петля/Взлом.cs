// Взлом замка — поступок игрока, а не решение дома (ГДД 7, 8.1).
//
// Соседи срывают замок и выносят ходку за раз (`Улица.вскрыть_кладовую`),
// и провала у них нет. У игрока взлом — дело: оно занимает время и может
// не выйти. Это упрощённая мини-игра «Взлом» из ГДД 7:
//
//   · **голыми руками не ломают** (задание автора, п. 4): нужен инструмент,
//     который берёт этот замок (`Инструменты`, `data/инструменты.json`);
//     нет такого — дело не начинается;
//   · времени уходит столько, сколько сосед возится с замком
//     (`кладовая_вскрытие_часы`), помноженное на то, как инструмент
//     берёт замок, — удачно или нет;
//   · удастся ли, решает та же мерка, что у работы (`NPC.success`:
//     недосып, голод, холод, рука), на трудность замка (`взлом_успех`)
//     и на то, как с ним справляется инструмент;
//   · провал — как у стройки: время ушло, и с шансом разбита рука.
//
// **Взлом — шаг отчаянный, и его слышно.** По замку бьют, и дом это слышит —
// по тем же правилам, что любой шум (ГДД 13), а громкость — от инструмента:
// молоток слышен на весь подвал, болторез почти беззвучен. Кто услышал,
// тот решает, спуститься ли: пока жизнь похожа на прежнюю (первые дни,
// высокая нормальность), на стук выходят; потом боятся и сидят за дверью.
//
// **И второй раз — не как первый** (задание автора, п. 2). Раньше каждый
// взлом бросался заново, а после первого происшествия нормальность дома
// падала — и на повторный стук выходили всё реже: сосед «переставал
// реагировать» ровно тогда, когда должен был разозлиться. Теперь:
//   · кто помнит героя вором (поймал сам или слышал), спускается охотнее —
//     и нормальность на это уже не влияет (`взлом_спуститься_помнит`);
//   · если стук сегодня уже слышали, дом настороже (`взлом_спуститься_снова`
//     за каждый прошлый раз) — это и есть «подозревают» в положении героя;
//   · поимка растёт уровнем: в первый раз — разговор, бежать или остаться;
//     со второго — пришедший зовёт тех, кто слышал, и героя держат:
//     сдаться или вырываться; держат часы (`взлом_скрутили_часы`) и бьют
//     (`взлом_побои`, с каждым уровнем больнее), до беспамятства —
//     и тогда день для героя кончился. Вырвался драться — настоящая драка,
//     одна против нескольких, и она может убить.
// Суд дома на вторую поимку — прежний (`Конфликт.house_verdict`).
//
// **Взлом идёт кусками** (задание автора, п. 24): полтора часа молотком —
// не один бросок в конце, а пять кусков (`кусок`, число — `ХодВремени.Кусков`),
// и между кусками дом живёт своё. Каждый кусок тратит свою долю часов
// и бросает свой стук — с таким шансом, чтобы за всё дело стук слышали
// столько же, сколько при одном броске (`услышали`, `доля`). Но кто
// услышал на втором куске, спускается сразу, посреди дела, — и дом,
// слышавший стук сегодня, на следующем куске настороже. Замок решается
// на последнем куске. `попытка` — всё дело разом, для проверок: с одним
// куском это прежний взлом бросок в бросок.
//
// Разбирается поимка не при взломе, а ходом дома (`разобрать`, из
// `Действия.САМ`): при взломе дом спит на вопросе героя, и спросить его
// «бежать или остаться» было бы нечем — главный поток ждал бы сам себя.
// Всё, что для разбора нужно из ручек, записывается в поимку при взломе:
// у хода дома ручек петли нет.
//
// Броски идут из `h.rng`: исход и восприятие — не выбор, а случай, и после
// них дом считается дальше уже с этим исходом. Поэтому звать это можно
// только пока дом спит на вопросе, как и карман. Решения соседей —
// правилом через их решающего (`Вопрос.ВЫЙТИ_К_ДВЕРИ`), без монеты.
//
// **Мини-игра «Взлом»** (ГДД 7; `МиниИгры`): качество игры — число от нуля
// до единицы, половина — «как обычно» и прежний бросок. Хуже — шанс ниже
// и стук на ступень громче, лучше — шанс выше. Со Смекалкой 3+ игры нет,
// и качество «само» растёт с уровнем.

using System.Globalization;

namespace Дом.Ядро;

/// <summary>Чем кончилась попытка (или кусок её): удалась ли, чем поранился,
/// сколько часов ушло, кто слышал стук и кто на него спустился (тогда попытка
/// сорвана), и идёт ли дело дальше — кусок не последний и никого не принесло.</summary>
public sealed record Попытка(bool удалась, string? травма, double часы,
                             IReadOnlyList<string>? слышали = null, string? застал = null,
                             bool идёт = false);

/// <summary>
/// Героя застали у чужой кладовой: кто, у какой, кто ещё слышал, в какой
/// день и какой по счёту раз (уровень: 0 — впервые). С ней — то, что для
/// разбора нужно из ручек петли: кого позовут держать, сколько часов
/// продержат и как побьют. Ждёт хода дома (`Взлом.разобрать`). Только
/// у игрока — как ноша, мимо снимка и сейва.
/// </summary>
public sealed record Застали(string кто, string кладовая, IReadOnlyList<string> слышали, int день,
                             int уровень = 0, IReadOnlyList<string>? держат = null,
                             double держат_часов = 0.0, double побои = 0.0,
                             double без_сознания_ниже = 0.0);

public static class Взлом
{
    /// <summary>Сколько часов уходит на попытку этим приёмом — удачную или нет.</summary>
    public static double часы(House h, Приём п) => h.B["кладовая_вскрытие_часы"] * п.часы;

    /// <summary>Хватит ли на попытку остатка дня.</summary>
    public static bool успеет(House h, NPC кто, Приём п) => кто.time_left >= часы(h, п);

    /// <summary>Какой шанс, что замок поддастся: мерка работы на трудность
    /// замка и на то, как его берёт инструмент.</summary>
    public static double шанс(House h, NPC кто, РучкиПетли ручки, Приём п)
        => Util.Clamp(кто.success(h.B) * ручки["взлом_успех"] * п.шанс, 0.05, 0.95);

    /// <summary>
    /// Чем ломать этот замок из того, что при герое. Что в руках — тем,
    /// если оно берёт этот замок: герой сам выбрал, чем ломать (задание
    /// автора, п. 22). Иначе — самым тихим, а при равном шуме самым быстрым.
    /// Нет подходящего — null: голыми руками замок не сорвать.
    /// </summary>
    public static (Инструмент инструмент, Приём приём)? чем(NPC вор, Кладовая к,
                                                           Инструменты каталог)
    {
        if (каталог.Замок(к) is not string замок || вор.снаряжение is not { } с)
            return null;
        if (с.в_руках is string держит && каталог.все.TryGetValue(держит, out var в_руке)
            && в_руке.Берёт(замок) is { } приём_руки
            && с.При_себе(вор, каталог).Contains(держит, StringComparer.Ordinal))
            return (в_руке, приём_руки);
        (Инструмент, Приём)? лучший = null;
        foreach (string id in с.При_себе(вор, каталог))
        {
            if (!каталог.все.TryGetValue(id, out var и) || и.Берёт(замок) is not { } п)
                continue;
            if (лучший is not { } л
                || п.шум < л.Item2.шум
                || (п.шум == л.Item2.шум && п.часы < л.Item2.часы))
                лучший = (и, п);
        }
        return лучший;
    }

    /// <summary>Чем этот замок вообще берут — для подсказки «нужен …».</summary>
    public static IReadOnlyList<Инструмент> чем_берут(Кладовая к, Инструменты каталог)
        => каталог.Замок(к) is string замок ? каталог.Берут(замок).ToList() : Array.Empty<Инструмент>();

    /// <summary>
    /// Попытка сорвать замок этим инструментом — всё дело разом, кусок
    /// за куском, без хода дома между ними. Игра зовёт `кусок` сама и между
    /// кусками пускает дом; это — для проверок, и с одним куском это прежний
    /// взлом бросок в бросок.
    /// </summary>
    public static Попытка попытка(House h, NPC вор, Кладовая к, РучкиПетли ручки,
                                  Инструмент инструмент, Приём п, int кусков = 1,
                                  double качество = 0.5)
    {
        double всего = 0.0;
        var слышали = new List<string>();
        for (int номер = 1; ; номер++)
        {
            var к_ = кусок(h, вор, к, ручки, инструмент, п, номер, кусков, качество);
            всего += к_.часы;
            foreach (var id in к_.слышали ?? Array.Empty<string>())
                if (!слышали.Contains(id, StringComparer.Ordinal))
                    слышали.Add(id);
            if (!к_.идёт)
                return к_ with { часы = всего, слышали = слышали };
        }
    }

    /// <summary>
    /// Кусок взлома: <paramref name="номер"/>-й из <paramref name="кусков"/>.
    /// Время куска тратится в любом случае. Сперва — кто слышал и кто
    /// спустится: застали — дело сорвано, замок цел, поимка ждёт хода дома.
    /// Кусок не последний — дело идёт дальше (`идёт`). Последний решает
    /// замок: удалась — замок сорван (`Улица.сорвать_замок`: событие, хозяин
    /// узнает, вина); нет — замок цел, а рука, может быть, нет.
    /// </summary>
    public static Попытка кусок(House h, NPC вор, Кладовая к, РучкиПетли ручки,
                                Инструмент инструмент, Приём п, int номер, int кусков,
                                double качество = 0.5)
    {
        var b = h.B;
        кусков = Math.Max(1, кусков);
        double потрачено = Math.Min(часы(h, п) / кусков, вор.time_left);
        вор.time_left -= потрачено;
        string что = $"{к.вид.Текст()}а кв.{к.apt}";

        // Новое дело — новый стук: прошлые дела сегодня дом уже слышал,
        // а это ещё нет. Куски одного дела — один и тот же стук, и дом
        // настораживается от дела к делу, а не от куска к куску: иначе
        // пять кусков молотка ловили бы вдвое чаще одного броска
        if (номер == 1 && вор.шум_взлома is { в_этом_деле: true } ш0)
            вор.шум_взлома = ш0 with { в_этом_деле = false };
        var слышали = услышали(h, вор, к, МиниИгры.Шум(п.шум, качество, ручки), ручки, доля: 1.0 / кусков);
        var ids = слышали.Select(p => p.id).ToList();
        var пришёл = спустится(h, вор, к, слышали, ручки);
        bool уже = вор.шум_взлома is { в_этом_деле: true } ш1 && ш1.день == h.day;
        if (слышали.Count > 0 && !уже)
            вор.шум_взлома = new ШумВзлома(h.day,
                (вор.шум_взлома is { } ш && ш.день == h.day ? ш.раз : 0) + 1, в_этом_деле: true);
        if (пришёл is not null)
        {
            // уровень поимки: сколько раз героя уже ловили — дом это помнит —
            // и не он ли сам уже ловил героя
            int уровень = вор.поймали
                          + (Помнит_вором(пришёл, вор) && вор.поймали == 0 ? 1 : 0);
            var держат = уровень > 0
                ? Помощники(h, вор, пришёл, слышали, (int)ручки["взлом_держать_помощники"])
                : new List<string>();
            вор.застали = new Застали(пришёл.id, к.id, ids, h.day, уровень, держат,
                                      ручки["взлом_скрутили_часы"],
                                      ручки["взлом_побои"] * уровень,
                                      ручки["без_сознания_ниже"]);
            h.journal.line($"{вор.@short} {Util.Vb(вор.sex, "бил")} по замку {что} "
                           + $"{инструмент.чем} — на стук {Util.Vb(пришёл.sex, "спустился")} "
                           + $"{пришёл.@short}.", 1);
            return new Попытка(false, null, потрачено, ids, пришёл.id);
        }
        if (номер < кусков)
            return new Попытка(false, null, потрачено, ids, идёт: true);

        if (h.rng.Chance(МиниИгры.Шанс(шанс(h, вор, ручки, п), качество, ручки)))
        {
            Улица.сорвать_замок(h, вор, к);
            h.journal.line($"{вор.@short} {Util.Vb(вор.sex, "сорвал")} замок с {что} "
                           + $"{инструмент.чем}.", 1);
            return new Попытка(true, null, потрачено, ids);
        }

        string текст = $"{вор.@short} {Util.Vb(вор.sex, "провозился")} с замком {что}, "
                       + "но замок не поддался";
        string? травма = null;
        if (h.rng.Chance(b["провал_шанс_травмы"]))
        {
            травма = h.rng.Pick(new[] { "ушиб руки", "порез руки" })!;
            вор.injuries.Add(травма);
            вор.health = Util.Clamp(вор.health - h.rng.Uni(4, 10));
            текст += $", а {Util.Vb(вор.sex, "рассадил")} руку";
        }
        h.journal.line(текст + ".", 1);
        return new Попытка(false, травма, потрачено, ids);
    }

    /// <summary>
    /// Кто слышал удары по замку. Та же слышимость, что у любого шума дома
    /// (`шум_слышимость` и `шум_дальность` на уровень <paramref name="уровень"/> —
    /// его задаёт инструмент; затухание на этаж, погода, пустые квартиры
    /// между), но источник — подвал, этаж ноль; гараж — улица за домом,
    /// его слышно хуже (`взлом_гараж_слышно`). Кто стучит, из подвала
    /// не видно: услышавший запоминает стук, а не человека. Беззвучный
    /// инструмент (уровень ноль) не слышит никто.
    ///
    /// <paramref name="доля"/> — какая часть дела стучит сейчас (кусок из
    /// пяти — одна пятая). Шанс куска такой, чтобы за всё дело не слышать
    /// стука было так же вероятно, как при одном броске: 1 − (1 − p)^доля.
    /// Целое дело (доля 1) бросает прежний шанс как есть.
    /// </summary>
    public static List<NPC> услышали(House h, NPC вор, Кладовая к, int уровень, РучкиПетли ручки,
                                     double доля = 1.0)
    {
        var слышали = new List<NPC>();
        if (уровень <= 0)
            return слышали;
        var b = h.B;
        string ключ = уровень.ToString(CultureInfo.InvariantCulture);
        double база = b.Таблица("шум_слышимость").Взять(ключ, 0.5);
        double дальность = b.Таблица("шум_дальность").Взять(ключ, 1.0);
        double улица = к.вид == ВидКладовой.ГАРАЖ ? ручки["взлом_гараж_слышно"] : 1.0;
        var пустые = h.пустые();
        foreach (var p in h.others(вор))
        {
            if (p.away)
                continue;
            int этаж = Социальное.место(h, p).floor;
            double шанс = база * Социальное.слышимость(h) * улица
                          * Math.Pow(b["шум_затухание_на_этаж"], этаж / Math.Max(0.35, дальность));
            int между = пустые.Count(f => f.floor <= этаж);
            if (между != 0)
                шанс *= Math.Pow(b["шум_пустая_квартира"], между);
            шанс = Util.Clamp(шанс, 0.0, 0.97);
            if (доля < 1.0)
                шанс = 1.0 - Math.Pow(1.0 - шанс, доля);
            if (!h.rng.Chance(шанс))
                continue;
            слышали.Add(p);
            string строка = к.вид == ВидКладовой.ГАРАЖ
                ? "во дворе долго били по железу"
                : "в подвале долго били по замку";
            if (!h.ожидает.сводка.TryGetValue(p.id, out var сводка))
            {
                сводка = new List<string>();
                h.ожидает.сводка[p.id] = сводка;
            }
            if (!сводка.Contains(строка, StringComparer.Ordinal))
                сводка.Add(строка);
            if (уровень >= 4)
                p.panic = Util.Clamp(p.panic + b["паника_от_громкого_шума"]);
        }
        return слышали;
    }

    /// <summary>
    /// Кто из услышавших спустится посмотреть — первым тот, кого тянет
    /// сильнее. Мерка — родня выхода на чужую дверь (`Конфликт.defenders_of`):
    /// храбрость, паника, дети; и то, чего там нет:
    ///   · нормальность самого соседа (`взлом_спуститься_норма`): пока жизнь
    ///     похожа на прежнюю, к вору выходят;
    ///   · своя кладовая того же вида (`взлом_спуститься_своё`);
    ///   · героя он помнит вором — сам ловил или слышал (`взлом_спуститься_помнит`):
    ///     «опять она», и одичание дома этого не гасит;
    ///   · стук сегодня уже слышали (`взлом_спуститься_снова` за каждый раз):
    ///     дом настороже.
    /// Кто стучит, сосед не видит; страх перед героем в мерку не входит.
    /// Решает сам сосед.
    /// </summary>
    public static NPC? спустится(House h, NPC вор, Кладовая к, IReadOnlyList<NPC> слышали,
                                 РучкиПетли ручки)
    {
        // раньше — сколько других дел сегодня уже слышали; это дело не в счёт
        int раньше = вор.шум_взлома is { } ш && ш.день == h.day
            ? ш.раз - (ш.в_этом_деле ? 1 : 0) : 0;
        NPC? первый = null;
        double сильнее = double.NegativeInfinity;
        foreach (var p in слышали)
        {
            if (p.health < 40 || p.injuries.Count >= 2)
                continue;
            bool своё_там = p.ключи_кладовых.Any(id =>
                h.кладовые.Есть(id) && h.кладовые[id].вид == к.вид);
            double тянет = p.normalcy * ручки["взлом_спуститься_норма"]
                           + p.t01("храбрость") * 3.0
                           + (своё_там ? ручки["взлом_спуститься_своё"] : 0.0)
                           + (Помнит_вором(p, вор) ? ручки["взлом_спуститься_помнит"] : 0.0)
                           + раньше * ручки["взлом_спуститься_снова"]
                           - p.panic / 100.0 * 3.0
                           - (p.dependents > 0 ? 2.0 : 0.0);
            double мерка = тянет - ручки["взлом_спуститься_порог"];
            // с кем — неизвестно: кто стучит, из квартиры не видно
            if (!Решение.по_правилу(h, p, Вопрос.ВЫЙТИ_К_ДВЕРИ, "выйти", "остаться", мерка,
                                    с_кем: null, суть: new Суть("погреб", к)))
                continue;
            if (тянет > сильнее)
            {
                сильнее = тянет;
                первый = p;
            }
        }
        return первый;
    }

    /// <summary>Помнит ли сосед героя вором: сам ловил или слышал, что ловили.
    /// Своя память, не счёт дома.</summary>
    public static bool Помнит_вором(NPC сосед, NPC вор)
        => сосед.memory.Any(м => string.Equals(м.кто, вор.id, StringComparison.Ordinal)
                                 && м.вид is Вид.ПОЙМАЛ_ВОРА or Вид.СЛЫШАЛ_О_ВОРЕ);

    /// <summary>
    /// Кого пришедший позовёт держать: из тех, кто тоже слышал стук, — целых,
    /// дома и не друзей герою (доверие не выше обычного), самых сильных
    /// первыми, не больше <paramref name="сколько"/>.
    /// </summary>
    private static List<string> Помощники(House h, NPC вор, NPC ловец,
                                          IReadOnlyList<NPC> слышали, int сколько)
        => слышали
            .Where(p => !string.Equals(p.id, ловец.id, StringComparison.Ordinal)
                        && p.health >= 40 && !p.away
                        && p.trust.Взять(вор.id, 3.0) <= 4.0)
            .OrderByDescending(p => p.power())
            .ThenBy(p => p.id, StringComparer.Ordinal)
            .Take(Math.Max(0, сколько))
            .Select(p => p.id)
            .ToList();

    /// <summary>
    /// Разобрать поимку ходом дома. Общее для любой поимки — как у соседа,
    /// пойманного в чужой квартире (`Конфликт.steal`): доверие и злость
    /// пришедшего, «поймал вора» в его памяти, хозяину кладовой скажут сразу,
    /// происшествие на весь дом, счёт поимок и суд дома. Дальше — по уровню:
    ///   · впервые — ствол у пришедшего (уходят без разговоров) или
    ///     «бежать или остаться» у героя и «хватать или отпустить» у пришедшего;
    ///   · снова — пришедший зовёт других, героя держат (`скрутить`).
    /// Кто слышал стук, к вечеру знает, кого поймали. Застали в прошлый
    /// день — поимки уже нет. Запись о поимке живёт до конца разбора:
    /// пока идут вопросы, герой «застигнут» или «скручен».
    /// </summary>
    public static void разобрать(House h, NPC вор)
    {
        var з = вор.застали;
        if (з is null)
            return;
        try
        {
            Разобрать(h, вор, з);
        }
        finally
        {
            вор.застали = null;
        }
    }

    private static void Разобрать(House h, NPC вор, Застали з)
    {
        var ловец = h.живой(з.кто);
        var к = h.кладовые.Взять(з.кладовая, null);
        if (ловец is null || к is null || !вор.здесь() || з.день != h.day)
            return;
        var b = h.B;
        var хозяин = h.хозяин_кладовой(к);
        string чья = $"{к.вид.Текст()}а кв.{к.apt}";
        bool она = string.Equals(вор.sex, "ж", StringComparison.Ordinal);
        var суть = new Суть(з.уровень > 0 ? "поймали" : "погреб", к);

        Социальное.adjust(ловец, вор.id, trust: -4.0, hate: b["ненависть_за_кражу"], aware: 20);
        ловец.memory.Add(new Память { день = h.day, вид = Вид.ПОЙМАЛ_ВОРА, кто = вор.id });
        if (хозяин is not null && хозяин.здесь()
            && !string.Equals(хозяин.id, ловец.id, StringComparison.Ordinal)
            && !string.Equals(хозяин.id, вор.id, StringComparison.Ordinal))
            Социальное.adjust(хозяин, вор.id, trust: -3.0,
                              hate: b["кладовая_вскрытие_ненависть"], aware: 20);
        Социальное.register_incident(h, "вскрытие",
            $"{ловец.@short} {Util.Vb(ловец.sex, "застал")} {вор.form("acc")} у {чья}: "
            + $"{(она ? "она" : "он")} ломал{(она ? "а" : "")} замок"
            + (з.уровень > 0 ? " — и уже не в первый раз." : "."));
        Социальное.переступил(h, вор, "вскрыть_кладовую");
        вор.поймали += 1;
        h.bump("взломов_застали");
        var знают = з.слышали.Select(h.живой).OfType<NPC>()
            .Where(p => !string.Equals(p.id, ловец.id, StringComparison.Ordinal))
            .Append(ловец).ToList();
        if (Конфликт.house_verdict(h, вор, хозяин ?? ловец))
        {
            Социальное.judge(h, вор, "воровство", hate: 12.0, trust: -1.2, witnesses: знают);
            return;
        }

        if (з.уровень > 0)
            Скрутить(h, вор, ловец, з, к, чья, суть);
        else
            Впервые(h, вор, ловец, чья, суть);
        Социальное.judge(h, вор, "воровство", hate: 12.0, trust: -1.2, witnesses: знают);
    }

    /// <summary>Впервые: ствол — уходят; иначе бежать или остаться,
    /// хватать или отпустить.</summary>
    private static void Впервые(House h, NPC вор, NPC ловец, string чья, Суть суть)
    {
        bool armed = Таблицы.ОГНЕСТРЕЛ.Contains(ловец.weapon)
                     && ловец.stock.Взять("патроны", 0.0) > 0;
        double scare = (0.62 + 0.03 * (10 - вор.trait("храбрость"))) / Конфликт.aggr(h);
        if (armed && Решение.монета(h, ловец, Вопрос.ВЫЙТИ_СО_СТВОЛОМ, "выйти", "не выходить",
                                    scare, с_кем: вор, суть: суть))
        {
            h.journal.line($"{ловец.@short} {Util.Vb(ловец.sex, "поднял")} ствол. "
                           + $"{вор.@short} {Util.Vb(вор.sex, "ушёл")} из подвала без разговоров.", 1);
            вор.panic = Util.Clamp(вор.panic + 18);
            Социальное.adjust(вор, ловец.id, hate: 12, aware: 15);
            Социальное.увидел_оружие(h, вор, ловец);
            return;
        }
        bool бежал = Решение.монета(h, вор, Вопрос.БЕЖАТЬ_ОТ_ХОЗЯИНА, "бежать", "остаться",
            Util.Clamp(0.35 + Конфликт.stealth(вор) * 0.5 - ловец.t01("храбрость") * 0.3,
                       0.1, 0.9),
            с_кем: ловец, суть: суть);
        if (бежал)
            h.journal.line($"{вор.@short} {Util.Vb(вор.sex, "вырвался")} и "
                           + $"{Util.Vb(вор.sex, "убежал")} из подвала.", 1);
        else if (Решение.по_правилу(h, ловец, Вопрос.ДРАТЬСЯ_С_ВОРОМ, "драться", "отпустить",
                     (ловец.trait("вспыльчивость") >= 6
                      || ловец.power() > вор.power() * 1.3) ? 1.0 : 0.0,
                     с_кем: вор, суть: суть))
            Конфликт.fight(h, new[] { ловец }, new[] { вор },
                           place: $"у {чья}", reason: "вор у кладовой");
        else
            h.journal.line($"{ловец.@short} {Util.Vb(ловец.sex, "отпустил")} "
                           + $"{вор.form("acc")} — но запомнил.", 1);
    }

    /// <summary>
    /// Снова: пришедший зовёт тех, кого записала поимка, и героя держат.
    /// Сдаться или вырываться — решает герой (сдаётся по правилу, когда
    /// их сила больше его). Вырвался драться — драка, одна против нескольких.
    /// Держат — часы уходят, бьют (с каждым уровнем больнее, без смертельного
    /// броска: это не драка, а побои), и если здоровья осталось меньше порога —
    /// беспамятство, день для героя кончился.
    /// </summary>
    private static void Скрутить(House h, NPC вор, NPC ловец, Застали з, Кладовая к,
                                 string чья, Суть суть)
    {
        var держат = new List<NPC> { ловец };
        foreach (var p in (з.держат ?? Array.Empty<string>()).Select(h.живой).OfType<NPC>())
            if (!p.away)
                держат.Add(p);
        if (держат.Count > 1)
            h.journal.line($"{ловец.@short} {Util.Vb(ловец.sex, "позвал")} "
                           + string.Join(" и ", держат.Skip(1).Select(p => p.form("acc")))
                           + $": {вор.form("acc")} держат.", 1);
        double их = Util.Sum(держат.Select(p => p.power()));
        bool сдался = Решение.по_правилу(h, вор, Вопрос.СДАТЬСЯ, "сдаться", "драться",
                                         их > вор.power() ? 1.0 : 0.0,
                                         с_кем: ловец, суть: суть);
        if (!сдался)
        {
            var исход = Конфликт.fight(h, держат, new[] { вор }, place: $"у {чья}",
                                       reason: "вора держат у кладовой");
            if (!вор.alive)
                return;
            if (исход == Конфликт.ИсходБоя.B)
            {
                // отбилась — держать больше некому
                h.journal.line($"{вор.@short} {Util.Vb(вор.sex, "отбился")} и "
                               + $"{Util.Vb(вор.sex, "убежал")} из подвала.", 1);
                return;
            }
        }
        double часов = Math.Min(з.держат_часов, вор.time_left);
        вор.time_left -= часов;
        вор.health = Math.Max(1.0, вор.health - з.побои);
        if (!вор.injuries.Contains("ушибы", StringComparer.Ordinal))
            вор.injuries.Add("ушибы");
        вор.panic = Util.Clamp(вор.panic + 20);
        foreach (var p in держат)
            Социальное.adjust(вор, p.id, hate: 15, aware: 15);
        string строка = $"{вор.@short} {(сдался ? "держали" : "скрутили")} "
                        + $"{Текст.G(Текст.Округлить(часов, 1))} ч и побили";
        if (вор.health < з.без_сознания_ниже)
        {
            вор.без_сознания = h.day;
            вор.time_left = 0.0;
            строка += $" — {Util.Vb(вор.sex, "очнулся")} только к ночи";
        }
        h.journal.line(строка + ".", 1);
    }
