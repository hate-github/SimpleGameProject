// Обыск коробки — поступок игрока, как и взлом (ГДД 7): не мгновенно
// и не даром.
//
// Первая версия гаража отдавала долю коробки сразу в шкаф и часов
// не брала: коробки пустели за секунды, найденное оказывалось дома раньше
// героя, и день стоял. Теперь обыск идёт в два шага:
//
//   1. `коробка` — часы дня уходят (`обыск_часы`, в гараже помноженные
//      на погоду: гараж — улица, как и в `Улица.часы_кладовой`), а доля
//      того, что осталось, вынимается из кладовой. Тулуп и оружие,
//      если они нужнее того, что есть, надеваются сразу — в сумку их
//      не кладут.
//   2. `унести` — игрок решает, куда: в карман вне времени или в тару
//      (`Ноша`). Что не влезло, возвращается в кладовую: коробка
//      опустеет, только когда опустеет кладовая. Журнал пишет то,
//      что действительно ушло.
//
// Между шагами дом спит на вопросе: и вынуть, и вернуть можно только
// пока он спит, как и всё, что игрок делает руками.

namespace Дом.Ядро;

/// <summary>Что нашлось в коробке: вещи для шкафа, что сразу надето
/// (тулуп, оружие) и сколько часов ушло.</summary>
public sealed record Добыча(Словарь<string, double> вещи, IReadOnlyList<string> надето,
                            double часы);

public static class Обыск
{
    /// <summary>Сколько часов уходит на одну коробку.</summary>
    public static double часы(House h, Кладовая к, РучкиПетли ручки)
        => ручки["обыск_часы"] * (к.вид == ВидКладовой.ГАРАЖ ? Улица.погода_часы(h) : 1.0);

    /// <summary>Хватит ли на коробку остатка дня.</summary>
    public static bool успеет(House h, NPC кто, Кладовая к, РучкиПетли ручки)
        => кто.time_left >= часы(h, к, ручки);

    /// <summary>
    /// Обыскать коробку, когда полных осталось <paramref name="коробок"/>:
    /// часы уходят, доля вынимается из кладовой и ждёт, куда её положат.
    /// </summary>
    public static Добыча коробка(House h, NPC кто, Кладовая к, int коробок,
                                 РучкиПетли ручки)
    {
        double потрачено = Math.Min(часы(h, к, ручки), кто.time_left);
        кто.time_left -= потрачено;
        var (вещи, надето) = Улица.доля_коробки(h, кто, к, коробок);
        return new Добыча(вещи, надето, потрачено);
    }

    /// <summary>
    /// Унести найденное: в тару (<paramref name="тара"/>) или, если её нет,
    /// в карман вне времени. Возвращает унесённое; остальное — обратно
    /// в кладовую. Без кармана и без тары не уносится ничего.
    /// </summary>
    public static Словарь<string, double> унести(House h, NPC кто, Кладовая к, Добыча д,
                                                 Тара? тара, РучкиПетли ручки)
    {
        Словарь<string, double> взято;
        if (тара is Тара т)
            взято = кто.ноша?.Положить(т, д.вещи, ручки) ?? Словари.Числа();
        else if (кто.карман is not null)
        {
            взято = Словари.Числа();
            foreach (var р in д.вещи.Ключи.OrderBy(x => x, StringComparer.Ordinal))
            {
                double влезло = кто.карман.Положить_найденное(р, д.вещи[р]);
                if (влезло > 0.0)
                    взято[р] = влезло;
            }
        }
        else
            взято = Словари.Числа();

        foreach (var р in д.вещи.Ключи)
        {
            double остаток = д.вещи[р] - взято.Взять(р, 0.0);
            if (остаток > 0.0)
                к.stock[р] = к.stock.Взять(р, 0.0) + остаток;
        }

        var всё = взято.Ключи.OrderBy(р => р, StringComparer.Ordinal)
            .Select(р => $"{р} {Текст.G(Текст.Округлить(взято[р], 2))}")
            .Concat(д.надето)
            .ToList();
        if (всё.Count > 0)
            h.journal.line($"{кто.@short} {Util.Vb(кто.sex, "взял")} из {к.вид.Текст()}а "
                           + $"кв.{к.apt}: " + string.Join(", ", всё) + ".", 1);
        return взято;
    }

    /// <summary>Ничего не брать: вся доля — обратно в кладовую. Надетое
    /// уже на герое, и журнал об этом скажет.</summary>
    public static void оставить(House h, NPC кто, Кладовая к, Добыча д)
    {
        foreach (var р in д.вещи.Ключи)
            к.stock[р] = к.stock.Взять(р, 0.0) + д.вещи[р];
        if (д.надето.Count > 0)
            h.journal.line($"{кто.@short} {Util.Vb(кто.sex, "взял")} из {к.вид.Текст()}а "
                           + $"кв.{к.apt}: " + string.Join(", ", д.надето) + ".", 1);
    }
}
