// Герой новой игры (задание автора, п. 20): мужчина, замкнутый, почти
// ни с кем не знаком.
//
// Шестнадцатый жилец — только в игре. `npcs.json` сверен с прототипом
// и не трогается; герой дописывается к жильцам в тот момент, когда игра
// собирает дом (`Прогон` берёт преобразование жильцов), и занимает пустую
// квартиру. В прогоне без игрока его нет — дом считается, как считался.
//
// Имя даёт игрок; падежи считаются здесь, потому что весь текст дома
// склоняет жильцов по полям «коротко_род» … «коротко_твор».

using System.Text.Json;
using System.Text.Json.Nodes;

namespace Дом.Ядро;

/// <summary>Кем играют: имя и пол (задание — мужчина).</summary>
public sealed record ПрофильГероя(string имя, string пол = "м");

/// <summary>
/// Кем и в каком мире идёт петля: пишется новой игрой и живёт, пока петля
/// не оборвётся, — все жизни одного человека проходят в одной метели
/// (ГДД 3: зерно у жизней петли одно). Профиль — у героя новой игры;
/// у жильца, за которого играют для проверки, его нет, есть только id.
/// </summary>
public sealed record ИграГероя(ПрофильГероя? герой, string кто, long зерно)
{
    public const int ВЕРСИЯ = 1;

    public static ИграГероя Новая(ПрофильГероя герой, long зерно) => new(герой, Герой.ID, зерно);

    public JsonObject Сложить() => new()
    {
        ["версия"] = ВЕРСИЯ,
        ["герой"] = герой is null ? null : new JsonObject { ["имя"] = герой.имя, ["пол"] = герой.пол },
        ["кто"] = кто,
        ["зерно"] = зерно,
    };

    public static ИграГероя Разложить(JsonObject о)
    {
        int версия = о["версия"]?.GetValue<int>() ?? 0;
        if (версия != ВЕРСИЯ)
            throw new InvalidDataException($"игра версии {версия}, а читаем {ВЕРСИЯ}");
        var г = о["герой"] as JsonObject;
        return new ИграГероя(
            г is null ? null : new ПрофильГероя(г["имя"]!.GetValue<string>(), г["пол"]!.GetValue<string>()),
            о["кто"]!.GetValue<string>(), о["зерно"]!.GetValue<long>());
    }

    public void Записать(string путь) => СохранениеИгры.Записать(Сложить(), путь);

    public static ИграГероя Прочитать(string путь) => Разложить(СохранениеИгры.Прочитать(путь));
}

public static class Герой
{
    /// <summary>Id героя новой игры в доме.</summary>
    public const string ID = "герой";

    public const int ИМЯ_ДЛИННЕЕ = 16;

    /// <summary>
    /// Имя, как его набрал игрок, — в порядок: пробелы по краям прочь,
    /// каждая часть с заглавной («иван» — Иван, «ИВАН» — Иван). Null
    /// и причина — если так человека не назвать: имя склоняется по правилам
    /// русских имён и стоит во всём тексте дома, поэтому только русскими
    /// буквами, одно слово (через дефис можно), от двух букв.
    /// </summary>
    public static string? Имя(string ввод, out string? почему)
    {
        string и = ввод.Trim();
        почему = null;
        if (и.Length < 2)
            почему = "имя — хотя бы две буквы";
        else if (и.Length > ИМЯ_ДЛИННЕЕ)
            почему = $"имя — не длиннее {ИМЯ_ДЛИННЕЕ} букв";
        else if (и.Any(c => !(c is >= 'а' and <= 'я' or >= 'А' and <= 'Я' or 'ё' or 'Ё' or '-')))
            почему = "имя — русскими буквами, одним словом";
        else if (и.StartsWith('-') || и.EndsWith('-') || и.Contains("--"))
            почему = "дефис — только между частями имени";
        if (почему is not null)
            return null;
        return string.Join("-", и.Split('-').Select(ч => char.ToUpperInvariant(ч[0]) + ч[1..].ToLowerInvariant()));
    }

    /// <summary>Что о герое известно до имени — для экрана нового человека:
    /// квартира, этаж, возраст, кто он.</summary>
    public static (int квартира, int этаж, int возраст, string роль) Шаблон(string каталог)
    {
        using var поток = File.OpenRead(Path.Combine(каталог, "герой.json"));
        var ш = JsonNode.Parse(поток)!.AsObject();
        int кв = ш["квартира"]!.GetValue<int>();
        using var дом = File.OpenRead(Path.Combine(каталог, "npcs.json"));
        int этаж = 0;
        foreach (var к in JsonNode.Parse(дом)!["пустые_квартиры"]!.AsArray())
            if (к!["кв"]!.GetValue<int>() == кв)
                этаж = к["этаж"]!.GetValue<int>();
        var ж = ш["жилец"]!;
        return (кв, этаж, ж["возраст"]!.GetValue<int>(), ж["роль"]!.GetValue<string>());
    }

    /// <summary>
    /// Падежи мужского имени: родительный, дательный, винительный,
    /// творительный. «Андрей» — Андрея, Андрею, Андрея, Андреем; «Игорь» —
    /// Игоря…; «Никита» — Никиты, Никите, Никиту, Никитой; «Лука» — Луки…;
    /// «Илья» — Ильи, Илье, Илью, Ильёй; «Иван» — Ивана, Ивану, Ивана, Иваном.
    /// </summary>
    public static (string род, string дат, string вин, string твор) Падежи(string имя)
    {
        if (имя.Length < 2)
            return (имя, имя, имя, имя);
        string осн = имя[..^1];
        char п = имя[^1];
        char пп = имя[^2];
        bool шипит(char c) => "жшчщц".Contains(char.ToLowerInvariant(c));
        bool задн(char c) => "кгхжшчщ".Contains(char.ToLowerInvariant(c));
        switch (char.ToLowerInvariant(п))
        {
            case 'й':
                return (осн + "я", осн + "ю", осн + "я", осн + "ем");
            case 'ь':
                return (осн + "я", осн + "ю", осн + "я", осн + "ем");
            case 'а':
                return (осн + (задн(пп) ? "и" : "ы"), осн + "е", осн + "у", осн + (шипит(пп) ? "ей" : "ой"));
            case 'я':
                return (осн + "и", осн + "е", осн + "ю", осн + (пп == 'ь' ? "ёй" : "ей"));
            case 'о':
            case 'е':
            case 'и':
            case 'у':
            case 'ю':
            case 'ы':
            case 'э':
                return (имя, имя, имя, имя);          // не склоняется
            default:
                return (имя + "а", имя + "у", имя + "а", имя + (шипит(п) ? "ем" : "ом"));
        }
    }

    /// <summary>
    /// Жильцы с героем: запись из `data/герой.json` с именем и падежами —
    /// к жильцам, его квартира — из пустых. Возвращает новые данные дома;
    /// исходные не меняются.
    /// </summary>
    public static JsonElement Заселить(JsonElement npcs, ПрофильГероя п, string каталог)
    {
        using var поток = File.OpenRead(Path.Combine(каталог, "герой.json"));
        var шаблон = JsonNode.Parse(поток)!.AsObject();
        int кв = шаблон["квартира"]!.GetValue<int>();
        var дом = JsonNode.Parse(npcs.GetRawText())!.AsObject();
        var пустые = дом["пустые_квартиры"]!.AsArray();
        JsonNode? квартира = null;
        foreach (var к in пустые)
            if (к!["кв"]!.GetValue<int>() == кв)
                квартира = к;
        if (квартира is null)
            throw new InvalidDataException($"герой.json: квартира {кв} не пустая — поселить некуда");
        int этаж = квартира["этаж"]!.GetValue<int>();
        пустые.Remove(квартира);

        var ж = шаблон["жилец"]!.DeepClone().AsObject();
        string имя = п.имя.Trim();
        var (род, дат, вин, твор) = Падежи(имя);
        ж["имя"] = имя;
        ж["коротко"] = имя;
        ж["коротко_род"] = род;
        ж["коротко_дат"] = дат;
        ж["коротко_вин"] = вин;
        ж["коротко_твор"] = твор;
        ж["пол"] = п.пол;
        ж["кв"] = кв;
        ж["этаж"] = этаж;
        дом["жильцы"]!.AsArray().Add(ж);
        return JsonDocument.Parse(дом.ToJsonString()).RootElement.Clone();
    }
}
