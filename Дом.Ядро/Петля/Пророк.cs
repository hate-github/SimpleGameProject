// Слово пророка (ГДД 11, 12.6).
//
// На точке невозврата петля обрывается, и на финальном экране есть поле
// для ввода слова. Если игрок его вводит — петля продолжается в «нирване».
//
// До этого этапа принималось любое непустое: место в механике было занято,
// а самого слова в мире не существовало. Теперь оно существует, и в этом
// вся суть — **узнать его можно только сходив**. Надписи оставлены
// в местах вылазок, в разных формулировках; слово во всех одно. Пока герой
// ни одной не видел, ему негде его взять, и поле на финальном экране
// остаётся пустым не потому, что игра жадничает, а потому что он правда
// не знает.
//
// Пророк — Аркадий из первой квартиры, тот, кто «знал заранее». Никакого
// кода под него нет и не нужно: он уже живёт в доме пунктиком, а надписи
// лежат в данных.
//
// Найденное переносится между жизнями, как и всё остальное знание (ГДД 8):
// увидел однажды — помнишь всегда. Это и делает слово наградой за то, что
// ходил, а не за то, что дожил.

using System.Text.Json;

namespace Дом.Ядро;

public sealed class Пророк
{
    private readonly Словарь<string, string> _надписи = Словари.Строкой<string>();

    private Пророк(string слово) => this.слово = слово;

    /// <summary>Само слово. Сравнивается без оглядки на регистр и пробелы:
    /// человек списывает его со стены, а не копирует из буфера.</summary>
    public string слово { get; }

    /// <summary>В каких местах есть надписи.</summary>
    public IReadOnlyList<string> места => _надписи.Ключи;

    /// <summary>Что написано в этом месте — или ничего.</summary>
    public string? Надпись(string место) => _надписи.Взять(место, null!);

    /// <summary>Совпало ли то, что набрал игрок.</summary>
    public bool Сошлось(string набрано)
        => string.Equals(набрано.Trim(), слово.Trim(),
                         StringComparison.OrdinalIgnoreCase);

    public static Пророк Прочитать(string каталог)
    {
        using var поток = File.OpenRead(Path.Combine(каталог, "пророк.json"));
        using var док = JsonDocument.Parse(поток);
        var корень = док.RootElement;
        var п = new Пророк(корень.GetProperty("слово").GetString()!);
        foreach (var н in корень.GetProperty("надписи").EnumerateObject())
            п._надписи[н.Name] = н.Value.GetString()!;
        if (п.слово.Trim().Length == 0)
            throw new InvalidDataException("пророк.json: слово пустое");
        if (п._надписи.Count == 0)
            throw new InvalidDataException("пророк.json: ни одной надписи");
        return п;
    }
}
