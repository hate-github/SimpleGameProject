// Кого герой знает по имени (вопрос автора: «если игровой персонаж не знает,
// как зовут NPC, то как он с ними может пытаться общаться?»).
//
// Герой новой игры въехал прошлой весной и ни с кем в доме не здоровается
// (задание, п. 20; `data/герой.json`): соседей он знает в лицо и по дверям,
// а не по именам. Общаться это не мешает — стучат не по имени, а в дверь:
// «сосед из кв.14». Имя он узнаёт лицом к лицу — когда говорит с соседом,
// просит, меняется, делится, лечит, проведывает, или когда сосед сам пришёл
// к нему с тем же (`ЛИЦОМ`, только состоявшееся). До того в мыслях,
// в окнах, на плане подъезда, в подсказках и в заметках сосед — «сосед
// из кв.14».
//
// Знание лежит в округе (`Округа.знания`, приставка «имя:») и потому
// переживает жизнь, как всё узнанное: в петле он помнит, кого как зовут, —
// а они его нет.
//
// Играют за жильца (проверки, консоль, прежний режим) — он в доме свой
// и знает всех. Чат подъезда подписан именами, как любой домовой чат: имя
// там есть, а какая это дверь — нет. Лента дня (журнал) — летопись дома,
// а не знание героя, и пишет, как писала.

namespace Дом.Ядро;

public static class Знакомство
{
    /// <summary>Приставка знания «как зовут этого соседа» в `Округа.знания`.</summary>
    public const string ИМЯ = "имя:";

    /// <summary>Дела, где знакомятся: лицом к лицу и не враждой.</summary>
    public static readonly IReadOnlySet<string> ЛИЦОМ = new HashSet<string>(StringComparer.Ordinal)
    {
        "разговор", "попросить", "поделиться", "обмен", "лечить", "вернуть", "проведать", "шепнуть",
        "позвать", "отдать_на_ночь", "переехать",
    };

    /// <summary>Знает ли <paramref name="я"/>, как зовут <paramref name="кто"/>.</summary>
    public static bool Знает(House h, NPC я, NPC кто)
        => string.Equals(я.id, кто.id, StringComparison.Ordinal)
           || !string.Equals(я.id, Герой.ID, StringComparison.Ordinal)
           || Округа.У(h) is not { } о
           || о.Знает(ИМЯ + кто.id);

    /// <summary>
    /// Как герой называет соседа: имя в нужном падеже (`NPC.form`: short,
    /// gen, dat, acc, ins, name) — или «сосед из кв.14» в том же падеже.
    /// </summary>
    public static string Как_зовут(House h, NPC я, NPC кто, string падеж = "short")
        => Знает(h, я, кто) ? кто.form(падеж) : Незнакомый(кто, падеж);

    /// <summary>«Сосед из кв.14» в падеже; «соседка» — у женщин.</summary>
    public static string Незнакомый(NPC кто, string падеж = "short")
        => $"{Сосед(кто, падеж)} из кв.{кто.apt}";

    /// <summary>Просто «сосед» / «соседка» в падеже — для заголовка у двери.</summary>
    public static string Сосед(NPC кто, string падеж = "short")
    {
        bool она = string.Equals(кто.sex, "ж", StringComparison.Ordinal);
        return падеж switch
        {
            "gen" => она ? "соседки" : "соседа",
            "dat" => она ? "соседке" : "соседу",
            "acc" => она ? "соседку" : "соседа",
            "ins" => она ? "соседкой" : "соседом",
            _ => она ? "соседка" : "сосед",
        };
    }
}
