// Готовка у своей печи (docs/ЕДА_ПЛАН.md, этап 4).
//
// Картошку и лук сырыми не наешься: картошка сырой насыщает на треть
// (`сырым` в `еда.json`). У своей печи, пока она топится, из них готовят:
// жарят картошку, варят суп. Рецепт — строка «блюда» в `еда.json`: из каких
// продуктов и сколько порций на одну готовку, сколько воды и сколько часов.
//
// Закон слоя держится сам: сырое снимается с полки ровно на те порции,
// на какие на полку ложится блюдо, — число «еда» шкафа не меняется ни на
// крошку, и дому сверять нечего. Меняется только качество: блюдо насыщает
// полной порцией, суп ещё и поит (`воды`), горячее в день готовки греет
// (`греет`), а портится блюдо за день-два. Вода на суп уходит из шкафа —
// это поступок героя, как съесть.
//
// Не хватает на полную готовку — готовят меньше (доля по самому скудному
// продукту), но не меньше четверти. Испорченное в котёл не идёт.
// Пахнет на весь подъезд, как горячий ужин соседа (`Социальное.smell`):
// дом это уже умеет — запах выдаёт, что у хозяина есть еда.
// Всё это только у героя: соседи едят число, как ели, и эталон цел.
//
// Мини-игры готовки (ГДД 7 — «одна короткая мини-игра» на дело; план еды,
// этап 4): у рецепта своя цепочка — нарезка (ритм ножа), жарка (перевернуть
// вовремя), варка (держать огонь ровно); сами игры — те же три механики,
// что у «Работы», «Ремонта» и «Взлома», играет их движок. Итог — одно
// качество от нуля до единицы (среднее по цепочке): плохо — подгорело,
// часть порций уходит в угли (единственный путь готовки, где число шкафа
// убывает — явно, вместе с вещью); как обычно — как без игры; на славу —
// настроение. Со Смекалки третьего уровня игры нет — готовится само,
// качество растёт с уровнем (`МиниИгры.Само_по`), как у всех мини-игр.

using System.Text.Json;

namespace Дом.Ядро;

/// <summary>Мини-игра готовки: нарезка — ритм ножа, жарка — перевернуть
/// вовремя, варка — держать огонь ровно.</summary>
public enum ИграГотовки { НАРЕЗКА, ЖАРКА, ВАРКА }

/// <summary>Рецепт: что получается (<paramref name="блюдо"/> — вид продукта),
/// из чего и сколько порций на полную готовку, сколько воды и часов,
/// как сказать, что сделано («пожарил картошку»).</summary>
public sealed record Рецепт(string блюдо, IReadOnlyList<(string вид, double порций)> из, double воды,
                            double часов, string что_делать, string сделано)
{
    /// <summary>Какие мини-игры играются, по порядку.</summary>
    public IReadOnlyList<ИграГотовки> игры { get; init; } = Array.Empty<ИграГотовки>();

    /// <summary>Порций блюда с полной готовки — сумма того, что пошло в котёл.</summary>
    public double порций => Util.Sum(из.Select(x => x.порций));

    internal static Рецепт Прочитать(JsonElement э, КаталогЕды к)
    {
        string блюдо = э.GetProperty("блюдо").GetString()!;
        if (!к.Есть(блюдо))
            throw new InvalidDataException($"еда.json: рецепт блюда «{блюдо}», а такого продукта нет");
        var из = new List<(string, double)>();
        foreach (var п in э.GetProperty("из").EnumerateObject())
        {
            if (!к.Есть(п.Name))
                throw new InvalidDataException($"еда.json: в рецепте «{блюдо}» продукта «{п.Name}» нет");
            if (п.Value.GetDouble() <= 0)
                throw new InvalidDataException($"еда.json: в рецепте «{блюдо}» «{п.Name}» — порций больше нуля");
            из.Add((п.Name, п.Value.GetDouble()));
        }
        if (из.Count == 0)
            throw new InvalidDataException($"еда.json: в рецепте «{блюдо}» не из чего готовить");
        var р = new Рецепт(блюдо, из, э.GetProperty("воды").GetDouble(), э.GetProperty("часов").GetDouble(),
                           э.GetProperty("что_делать").GetString()!, э.GetProperty("сделано").GetString()!);
        if (Math.Abs(р.порций - к[блюдо].единиц) > 1e-6)
            throw new InvalidDataException($"еда.json: блюдо «{блюдо}» — {к[блюдо].единиц} порций, а рецепт даёт {р.порций}");
        var игры = new List<ИграГотовки>();
        if (э.TryGetProperty("игры", out var и))
            foreach (var x in и.EnumerateArray())
                игры.Add(x.GetString() switch
                {
                    "нарезка" => ИграГотовки.НАРЕЗКА,
                    "жарка" => ИграГотовки.ЖАРКА,
                    "варка" => ИграГотовки.ВАРКА,
                    var чужая => throw new InvalidDataException($"еда.json: в рецепте «{блюдо}» игры «{чужая}» нет"),
                });
        return р with { игры = игры };
    }
}

/// <summary>Что вышло из готовки: сколько порций блюда (0 — не вышло),
/// почему, если не вышло, сколько ушло в угли и как это сказать.</summary>
public sealed record Сготовлено(double порций, double доля, string? почему_нет,
                                double сгорело = 0.0, string итог = "как обычно");

/// <summary>Числа готовки из `еда.json` («готовка»).</summary>
public sealed record ЧислаГотовки(double подгорело_ниже, double подгорело_теряется, double на_славу_выше,
                                  double настроение_на_славу, double настроение_подгорело)
{
    public static readonly ЧислаГотовки ОБЫЧНЫЕ = new(0.3, 0.25, 0.85, 4.0, -3.0);
}

/// <summary>Мини-игры готовки: нужны ли и как сыграно само.</summary>
public static class Готовка
{
    /// <summary>Играть ли: у героя — пока Смекалка ниже порога
    /// (`мини_игра_исчезает`); у кого нет наследия — нет (как обычно).</summary>
    public static bool Играть(NPC я, РучкиПетли ручки)
        => я.умения is not null && Уровень(я) < (int)ручки["мини_игра_исчезает"];

    /// <summary>Как сготовлено само, когда игры нет.</summary>
    public static double Само(NPC я, РучкиПетли ручки)
        => я.умения is null ? 0.5 : МиниИгры.Само_по(Уровень(я), ручки);

    /// <summary>Ширина зоны в игре: шире с каждым уровнем Смекалки до порога.</summary>
    public static double Зона(NPC я, РучкиПетли ручки) => МиниИгры.Зона_по(Уровень(я), ручки);

    private static int Уровень(NPC я) => я.умения?.наследие.Уровень(Навык.СМЕКАЛКА) ?? 0;
}

public sealed partial class Продукты
{
    /// <summary>Меньше какой доли рецепта не готовят — нечего и огонь переводить.</summary>
    public const double ГОТОВКА_НЕ_МЕНЬШЕ = 0.25;

    /// <summary>Свежего продукта этого вида на полке, порций.</summary>
    public double Свежего(string вид)
        => Util.Sum(_где[МестоЕды.ПОЛКА].Where(п => п.вид == вид && Свежесть(п) == Дом.Ядро.Свежесть.СВЕЖАЯ)
                                     .Select(п => п.единиц));

    /// <summary>
    /// Какую долю рецепта можно сготовить с полки героя <paramref name="я"/>
    /// (по самому скудному продукту и воде, не больше единицы) — и почему
    /// нельзя, если меньше четверти или печь не топится.
    /// </summary>
    public (double доля, string? почему_нет) Хватит(NPC я, Рецепт р, bool топится)
    {
        if (!топится)
            return (0, "печь не топится — сперва растопить");
        double доля = 1.0;
        string? скудно = null;
        foreach (var (вид, порций) in р.из)
        {
            double есть = Свежего(вид) / порций;
            if (есть < доля)
                (доля, скудно) = (есть, каталог[вид].имя.ToLowerInvariant());
        }
        if (р.воды > 0)
        {
            double есть = я.stock.Взять("вода", 0.0) / р.воды;
            if (есть < доля)
                (доля, скудно) = (есть, "воды");
        }
        if (доля < ГОТОВКА_НЕ_МЕНЬШЕ)
            return (доля, $"на полке мало: {скудно}");
        return (доля, null);                // доля начинается с единицы и только убывает
    }

    /// <summary>
    /// Сготовить у своей печи (поступок игрока, пока дом спит): снять
    /// с полки свежее сырое на долю рецепта, положить туда блюдо на те же
    /// порции (число шкафа не меняется), воду — из шкафа. Пахнет на весь
    /// подъезд, как горячий ужин. Часы тратит зовущий (узел — поступком).
    /// </summary>
    public Сготовлено Приготовить(House h, NPC я, Рецепт р, bool топится, double качество = 0.5)
    {
        var (доля, почему_нет) = Хватит(я, р, топится);
        if (почему_нет is not null)
            return new Сготовлено(0, доля, почему_нет);
        double порций = 0;
        foreach (var (вид, нужно) in р.из)
            порций += Снять_свежее(вид, нужно * доля);
        if (р.воды > 0)
            я.stock["вода"] = Math.Max(0.0, я.stock.Взять("вода", 0.0) - р.воды * доля);
        // как сыграно: подгорело — часть в угли (число шкафа убывает вместе
        // с вещью), на славу — радует; как обычно — ни того ни другого
        var ч = каталог.готовка;
        double сгорело = 0;
        string итог = "как обычно";
        if (качество < ч.подгорело_ниже)
        {
            сгорело = порций * ч.подгорело_теряется;
            Вынуть_число(я, МестоЕды.ПОЛКА, сгорело);
            я.mood = Util.Clamp(я.mood + ч.настроение_подгорело);
            итог = "подгорело";
        }
        else if (качество > ч.на_славу_выше)
        {
            я.mood = Util.Clamp(я.mood + ч.настроение_на_славу);
            итог = "на славу";
        }
        _где[МестоЕды.ПОЛКА].Add(Новый(р.блюдо, порций - сгорело, 0.0));
        if (!я.нет_в_доме())
            Социальное.smell(h, я, hot: true);
        return new Сготовлено(порций - сгорело, доля, null, сгорело, итог);
    }

    /// <summary>Снять с полки свежего продукта этого вида столько порций —
    /// сперва то, что раньше испортится; последнюю вещь — частью.</summary>
    private double Снять_свежее(string вид, double сколько)
    {
        double снято = 0;
        foreach (var п in _где[МестоЕды.ПОЛКА]
                     .Where(п => п.вид == вид && Свежесть(п) == Дом.Ядро.Свежесть.СВЕЖАЯ)
                     .OrderBy(п => Дней_до_порчи(п)).ThenBy(п => п.номер).ToList())
        {
            if (сколько - снято <= ТОЧНО)
                break;
            double взять = Math.Min(п.единиц, сколько - снято);
            п.единиц -= взять;
            снято += взять;
            if (п.единиц <= ТОЧНО)
                _где[МестоЕды.ПОЛКА].Remove(п);
        }
        return снято;
    }
}
