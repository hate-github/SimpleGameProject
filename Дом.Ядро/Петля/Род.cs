// Глагол о герое — в его роде. Героем бывает и героиня (экран нового
// человека, Оксана в петле), а вести о том, что герой сделал сам, долго
// писались в мужском роде: «взял», «уснул, где стоял», «сорвал замок».
//
// Склоняет `Util.Vb` — тот же, что у соседей в журнале. Но он перенесён
// из прототипа и сверяется с ним знак в знак, поэтому его таблицу
// неправильных глаголов трогать нельзя: глагол, которого в ней нет и который
// нужен только герою («лёг» — не «лёга»), лежит здесь.

namespace Дом.Ядро;

public static class Род
{
    /// <summary>Неправильные глаголы, которых нет в таблице ядра.</summary>
    private static readonly Dictionary<string, string> ЕЩЁ = new(StringComparer.Ordinal)
    {
        ["лёг"] = "легла", ["отпер"] = "отперла", ["запер"] = "заперла",
    };

    /// <summary>«взял» у героини — «взяла»; «лёг» — «легла».</summary>
    public static string Глагол(string пол, string слово)
        => пол == "ж" && ЕЩЁ.TryGetValue(слово, out var ж) ? ж : Util.Vb(пол, слово);
}
