// Распорядок: жить днями, не разыгрывая каждый час (просьба автора).
//
// Герой обжился — в участке, в бункере, дома — и у него есть чем жить:
// ему незачем стоять у кладовой и жать «поесть» раз в полдня. Распорядок
// делает это сам: пьёт, когда хочется пить, ест, когда голоден, топит,
// когда холодно, крутит вентиляцию в убежище к вечеру, — а время между
// делами пропускает шагами, как пропускает его стоящий герой. Дом всё это
// время живёт, как жил: распорядок не решает за соседей и не трогает
// `h.rng`, он только отвечает за героя тем же, чем ответил бы игрок.
//
// Главное в нём — **что прерывает**. Жить днями можно, пока ничего
// не случилось; случилось — распорядок встаёт и отдаёт героя игроку:
//   · дом спросил не «что делать» — стучат, зовут, пришли с налётом,
//     просят; ночью — только если распорядок не «до утра». Кроме своего:
//     «за что взяться» (замысел недели) — вопрос себе, а не от людей,
//     и «соврать или сказать как есть» — когда герой сам к слову
//     рассказывает (в чате подъезда, из участка), — на них распорядок
//     отвечает, как ответил бы сосед, — лучшим (живая проба: без этого
//     распорядок вставал в полночь и по утрам «к тебе обращаются», хотя
//     никто не стучал);
//   · с героем что-то случилось — событие дома, где он кто или кому
//     (обокрали, отняли, пришли к двери);
//   · здоровье упало, а есть или пить нечего.
//
// Здесь — только правило: что делать сейчас и не пора ли встать.
// Как это делается и как время идёт — дело движка (`ДомУзел.Распорядок`),
// у которого есть и дом, и место, и дело.

namespace Дом.Ядро;

/// <summary>Что распорядок сделает сейчас.</summary>
public enum Привычка { ПОПИТЬ, ПОЕСТЬ, ЗАТОПИТЬ, СНЕГ, ДРОВА, ВЕНТИЛЯЦИЯ, ЖДАТЬ }

/// <summary>Докуда жить по распорядку.</summary>
public enum ДоКогда
{
    /// <summary>Столько-то часов.</summary>
    ЧАСЫ,
    /// <summary>До вечера: ночной вопрос — уже игроку.</summary>
    ВЕЧЕР,
    /// <summary>До утра: ночью — спать.</summary>
    УТРО,
    /// <summary>День за днём, пока что-нибудь не случится.</summary>
    ДНИ,
}

/// <summary>Как сейчас телу и месту: сытость, вода (100 — не хочется пить),
/// градусы вокруг, топится ли печь, надо ли сегодня крутить вентиляцию, час дня.</summary>
public sealed record Быт(double сытость, double вода, double градусов, bool топится,
                         bool вентилировать, double час);

public static class Распорядок
{
    /// <summary>Ниже этого — есть, пить, топить; вентиляция — с этого часа.</summary>
    public const double ГОЛОД = 55, ЖАЖДА = 50, ХОЛОД = 12, ВЕНТИЛЯЦИЯ_С_ЧАСА = 17;

    /// <summary>Здоровья упало на столько с начала распорядка — встать.</summary>
    public const double ПЛОХО = 10;

    /// <summary>
    /// Что делать сейчас. <paramref name="можно"/> — есть ли чем: запас,
    /// мысль дома, топливо. Порядок — по срочности: жажда убивает раньше
    /// голода, голод — раньше холода; воды нет — топить снег; топить нечем —
    /// ломать мебель на дрова (живая игра нашла: к концу второй недели в участке
    /// топливо кончалось, а столы дежурки стояли целые).
    /// </summary>
    public static Привычка Что(Быт б, Func<Привычка, bool> можно)
    {
        if (б.вода < ЖАЖДА)
        {
            if (можно(Привычка.ПОПИТЬ))
                return Привычка.ПОПИТЬ;
            if (можно(Привычка.СНЕГ))
                return Привычка.СНЕГ;
            if (можно(Привычка.ДРОВА))
                return Привычка.ДРОВА;
        }
        if (б.сытость < ГОЛОД && можно(Привычка.ПОЕСТЬ))
            return Привычка.ПОЕСТЬ;
        if (б.градусов < ХОЛОД && !б.топится)
        {
            if (можно(Привычка.ЗАТОПИТЬ))
                return Привычка.ЗАТОПИТЬ;
            if (можно(Привычка.ДРОВА))
                return Привычка.ДРОВА;
        }
        if (б.вентилировать && б.час >= ВЕНТИЛЯЦИЯ_С_ЧАСА && можно(Привычка.ВЕНТИЛЯЦИЯ))
            return Привычка.ВЕНТИЛЯЦИЯ;
        return Привычка.ЖДАТЬ;
    }

    /// <summary>
    /// Не пора ли встать — и почему. <paramref name="новые"/> — события дома
    /// с начала распорядка; встают на те, где герой кто или кому.
    /// </summary>
    public static string? Встать(NPC я, IEnumerable<Событие> новые, double здоровье_было,
                                 Func<Привычка, bool> можно)
    {
        foreach (var с in новые)
            if (string.Equals(с.кто, я.id, StringComparison.Ordinal)
                || string.Equals(с.кому, я.id, StringComparison.Ordinal))
                return $"случилось: {с.вид.Текст()}";
        if (я.health < здоровье_было - ПЛОХО)
            return "стало плохо — не до распорядка";
        if (я.hydration < 15 && !можно(Привычка.ПОПИТЬ) && !можно(Привычка.СНЕГ))
            return "пить нечего — распорядок встал";
        if (я.satiety < 15 && !можно(Привычка.ПОЕСТЬ))
            return "есть нечего — распорядок встал";
        return null;
    }

    /// <summary>Вопрос себе, а не от людей: распорядок отвечает на него сам.</summary>
    public static bool Своё(Вопрос в) => в is Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ or Вопрос.СОВРАТЬ;

    /// <summary>Ответ на свой вопрос — лучший вариант, как у соседа; при равных — первый.</summary>
    public static int Лучший(IReadOnlyList<ВариантИгроку> варианты)
    {
        int лучший = 0;
        for (int i = 1; i < варианты.Count; i++)
            if (варианты[i].вес > варианты[лучший].вес)
                лучший = i;
        return лучший;
    }

    public static string Текст(this Привычка п) => п switch
    {
        Привычка.ПОПИТЬ => "попил",
        Привычка.ПОЕСТЬ => "поел",
        Привычка.ЗАТОПИТЬ => "затопил",
        Привычка.СНЕГ => "натопил снега",
        Привычка.ДРОВА => "разломал мебель на дрова",
        Привычка.ВЕНТИЛЯЦИЯ => "покрутил вентиляцию",
        _ => "ждал",
    };
}
