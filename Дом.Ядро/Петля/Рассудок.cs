// Рассудок (ГДД 11): скрытая шкала, которую игроку не показывают числом.
//
// Никогда. Ни цифрой, ни полоской, ни процентом — только через стартовый
// монолог, реплики героя, яркость отголосков и то, какие действия ему
// вообще доступны. Игрок должен заметить, что герой изменился, а не
// прочитать об этом.
//
// Шкала растёт от пережитого и опускается от прожитого хорошо, но ниже
// нуля не идёт: доброе дело не отменяет случившегося. Четыре порога:
// обычное поведение, тревога, отстранение, точка невозврата.
//
// Считается шкала <b>из того, что герой знает и делал сам</b>, а не из
// сводки мира: чужая смерть за закрытой дверью его не ломает, потому что
// он о ней не знает. Отсюда источники — его собственная память
// (`NPC.memory`) и события, в которых он был стороной.

namespace Дом.Ядро;

/// <summary>Четыре порога ГДД 11.</summary>
public enum Порог
{
    ОБЫЧНО,             // 0–3: герой борется до конца
    ТРЕВОГА,            // 4–7: циничные варианты, отголоски ярче
    ОТСТРАНЕНИЕ,        // 8–11: отказ от части разговоров, появляется «уйти»
    НЕВОЗВРАТ,          // 12+: петля обрывается
}

/// <summary>Из чего сложилась шкала за жизнь — чтобы экран смерти мог
/// показать не число, а причины.</summary>
public sealed record ВкладВРассудок(string за_что, double сколько);

public static class Рассудок
{
    /// <summary>Какой порог у этого значения.</summary>
    public static Порог Где(double шкала, РучкиПетли ручки)
        => шкала >= ручки["порог_невозврата"] ? Порог.НЕВОЗВРАТ
         : шкала >= ручки["порог_отстранения"] ? Порог.ОТСТРАНЕНИЕ
         : шкала >= ручки["порог_тревоги"] ? Порог.ТРЕВОГА
         : Порог.ОБЫЧНО;

    /// <summary>Появилась ли механика «уйти» (ГДД 11): тихий способ
    /// закончить жизнь по своему желанию. Не наказывается ничем —
    /// в этом и ужас.</summary>
    public static bool МожноУйти(double шкала, РучкиПетли ручки)
        => Где(шкала, ручки) >= Порог.ОТСТРАНЕНИЕ;

    /// <summary>
    /// Что жизнь сделала с рассудком.
    ///
    /// Складывается по вкладам, а не одним числом: экран смерти обязан
    /// показать <b>почему</b>, иначе шкала превращается в необъяснимый
    /// штраф. Возвращается список, а не сумма, — и суммирует его уже
    /// вызывающий.
    /// </summary>
    public static List<ВкладВРассудок> Вклады(House h, NPC я, РучкиПетли ручки,
                                             Дневник? дневник = null)
    {
        var @out = new List<ВкладВРассудок>();

        void Плюс(string за_что, double сколько)
        {
            if (сколько != 0.0)
                @out.Add(new ВкладВРассудок(за_что, сколько));
        }

        // ---- своя смерть ----
        if (!я.здесь())
            Плюс("своя смерть", ручки["смерть_своя"]);

        // ---- что он видел ----
        // Только своя память: чужая смерть за закрытой дверью его
        // не ломает, потому что он о ней не знает
        int видел_убийств = я.memory.Count(з => з.вид == Вид.ВИДЕЛ_УБИЙСТВО);
        Плюс("видел расправу", видел_убийств * ручки["смерть_соседа_на_глазах"]);

        // ---- что он сделал сам ----
        // События, где он — «кто»: это его рука, а не слух о ней
        int убил_в_бою = 0, убил_безоружного = 0, убил_свидетеля = 0;
        foreach (var с in h.события)
        {
            if (с.вид != ВидСобытия.УБИЙСТВО
                || !string.Equals(с.кто, я.id, StringComparison.Ordinal))
                continue;
            string что = с.что ?? "";
            if (что.Contains("безоруж", StringComparison.Ordinal))
                убил_безоружного++;
            else if (что.Contains("ночью", StringComparison.Ordinal))
                убил_свидетеля++;      // тихо, в его собственной квартире
            else
                убил_в_бою++;
        }
        Плюс("убил в бою", убил_в_бою * ручки["убийство_в_бою"]);
        Плюс("убил безоружного", убил_безоружного * ручки["убийство_безоружного"]);
        Плюс("убил свидетеля", убил_свидетеля * ручки["убийство_свидетеля"]);

        // ---- предательство доверенного ----
        // Доверенный — тот, кому он верил выше среднего; предательство —
        // кража у него или отказ в осаду. Считается по его же памяти
        int предали = я.memory.Count(
            з => з.вид == Вид.ПОЙМАЛ_ВОРА
                 && я.trust.Взять(з.кто, 3.0) >= 6.0);
        Плюс("предал тот, кому верил", предали * ручки["предательство_доверенного"]);

        // ---- что его держало ----
        // Считается по его руке, а не по чужой благодарности: помог —
        // это событие, где «кто» он сам
        int помог = 0, спас = 0;
        foreach (var с in h.события)
        {
            if (!string.Equals(с.кто, я.id, StringComparison.Ordinal))
                continue;
            if (с.вид == ВидСобытия.ПОМОЩЬ)
                помог++;
            else if (с.вид == ВидСобытия.ЛЕЧЕНИЕ)
                спас++;
        }
        Плюс("помогал", -помог * ручки["держит_помощь"]);
        Плюс("лечил", -спас * ручки["держит_спасение"]);

        // ---- чем жил ----
        // Дни считает наблюдатель: у дома этой памяти нет. Без дневника
        // эти три вклада просто не появляются — считать их по остатку
        // на конец жизни нельзя, и однажды уже пробовали
        int прожил = я.died_day ?? h.day;
        if (дневник is not null)
        {
            Плюс("голодал", дневник.голодных * ручки["день_голода"]);
            Плюс("был один", дневник.одиноких * ручки["день_одиночества"]);
            Плюс("сидел без света", дневник.тёмных * ручки["день_темноты"]);
        }
        Плюс("прожитые дни", -прожил * ручки["держит_день"]);

        return @out;
    }

    /// <summary>Сложить вклады и не дать шкале уйти ниже нуля.</summary>
    public static double Сложить(double было, IEnumerable<ВкладВРассудок> вклады)
        => Math.Max(0.0, было + вклады.Sum(в => в.сколько));

    /// <summary>
    /// Стартовый монолог (ГДД 4, 11): первое, что герой говорит себе,
    /// проснувшись снова. По нему игрок и понимает, что с героем стало, —
    /// числа он не увидит никогда.
    /// </summary>
    public static string Монолог(Наследие н, РучкиПетли ручки)
    {
        if (н.нирвана)
            return "Опять здесь. Ну и пусть. Сегодня будет то же самое, "
                 + "и это почти успокаивает.";
        if (н.жизней == 0)
            return "Будильник. Полседьмого. За окном ещё темно, и, кажется, "
                 + "метёт.";
        return Где(н.рассудок, ручки) switch
        {
            Порог.ОБЫЧНО =>
                "Опять это утро. Значит, вчера всё-таки было — и значит, "
                + "сегодня можно иначе.",
            Порог.ТРЕВОГА =>
                "Снова будильник. Руки почему-то трясутся ещё до того, "
                + "как я вспомнил почему.",
            Порог.ОТСТРАНЕНИЕ =>
                "Опять. Я уже знаю, кто из них умрёт первым, и почему-то "
                + "не хочется никого предупреждать.",
            _ =>
                "Опять здесь. Я больше не считаю, какой это раз.",
        };
    }

}
