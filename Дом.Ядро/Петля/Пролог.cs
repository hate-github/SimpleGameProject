// Пролог: дни подготовки до метели (задание автора, пп. 14–15; ГДД 4,
// «Фаза подготовки (дни −K … −1)»).
//
// Город живёт обычной жизнью, в новостях нарастает тревога. Герой просыпается
// здесь в каждой жизни — и в первой, и после смерти (п. 14: «вернуть примерно
// за два дня до катастрофы»): пролог — это откат, а не загрузка сохранения.
// Дом при этом **не считается**: соседи живут своей жизнью и почти
// не пересекаются с героем (п. 15), а сверенная с прототипом симуляция
// начинается, как и начиналась, с метели. Всё, что герой успел за пролог, —
// его шкаф и снаряжение, купленное и принесённое, — дом получает таким,
// каким застаёт его в первый день.
//
// Подозрительность (п. 15): кто слышал, как герой носит в дом полные сумки,
// запоминает это. Не наказание на месте, а знание: с первым днём метели
// оно ложится в сведения соседей о его запасах (`Социальное.note_signal`),
// и дальше дом решает сам, как решает всегда, — просить, выменивать,
// красть, отнимать. Карман вне времени не шумит: что пронесено в нём,
// того никто не видел.
//
// Пролог живёт только в игре, как округа: в прогоне без игрока его нет.

namespace Дом.Ядро;

public sealed class Пролог
{
    private readonly Dictionary<string, double> _подозрение = new(StringComparer.Ordinal);
    private readonly Dictionary<string, double> _принёс = new(StringComparer.Ordinal);

    /// <summary>Сколько дней подготовки — ручка `подготовка_дней`.</summary>
    public int дней { get; }

    /// <summary>Какой сейчас день: −дней … −1; ноль — метель пришла.</summary>
    public int день { get; private set; }

    /// <summary>Пролог ещё идёт.</summary>
    public bool идёт => день < 0;

    /// <summary>Пролог по ручкам петли (`подготовка_дней`).</summary>
    public static Пролог Из(РучкиПетли ручки) => new((int)ручки["подготовка_дней"]);

    public Пролог(int дней)
    {
        this.дней = Math.Max(0, дней);
        день = -this.дней;
    }

    /// <summary>Утро дня подготовки: день героя начинается заново.</summary>
    public void Утро(House h, NPC я)
    {
        я.time_left = h.B["часов_бодрствования"];
        я.away = false;
    }

    /// <summary>Ночь: следующий день. true — ещё день подготовки,
    /// false — утром метель.</summary>
    public bool Ночь()
    {
        if (день < 0)
            день++;
        return идёт;
    }

    /// <summary>
    /// Герой пронёс ношу в дом, и кто-то это слышал или видел. Каждый из них
    /// запоминает, сколько тот натаскал: полная тара — единица подозрения.
    /// </summary>
    public void Пронёс(IEnumerable<NPC> слышали, IReadOnlyDictionary<string, double> что, double доля_тары)
    {
        foreach (var (р, сколько) in что)
            _принёс[р] = _принёс.GetValueOrDefault(р) + сколько;
        foreach (var p in слышали)
            _подозрение[p.id] = _подозрение.GetValueOrDefault(p.id) + Math.Max(0.0, доля_тары);
    }

    private readonly HashSet<string> _предупредил = new(StringComparer.Ordinal);

    /// <summary>Предупредил ли уже этого соседа о метели.</summary>
    public bool Предупреждён(string кто) => _предупредил.Contains(кто);

    /// <summary>
    /// Герой предупредил соседа о метели — а откуда он знает? Сосед
    /// запоминает (подозрение), поверил или нет; поверивший ещё и запасся.
    /// </summary>
    public void Предупредил(string кто, double насторожился)
    {
        _предупредил.Add(кто);
        _подозрение[кто] = _подозрение.GetValueOrDefault(кто) + Math.Max(0.0, насторожился);
    }

    /// <summary>Сколько сосед насмотрелся, как герой таскает сумки.</summary>
    public double Подозрение(string кто) => _подозрение.GetValueOrDefault(кто);

    /// <summary>Кто что видел — для вести первого утра.</summary>
    public IReadOnlyDictionary<string, double> подозрения => _подозрение;

    /// <summary>Что он натаскал в дом на глазах (в карман — не в счёт).</summary>
    public IReadOnlyDictionary<string, double> принёс => _принёс;

    /// <summary>
    /// Метель пришла. Кто видел, как герой запасался, теперь считает, что
    /// у него есть, — по тому, что там на самом деле, с весом по тому,
    /// сколько видел (`пролог_подозрение_вес` за единицу, не больше 0.9).
    /// Дом дальше решает сам; сам пролог ничего не наказывает.
    /// Возвращает тех, кто насторожился, — для вести.
    /// </summary>
    public List<NPC> Метель(House h, NPC я, РучкиПетли ручки)
    {
        var насторожились = new List<NPC>();
        foreach (var (кто, сколько) in _подозрение.OrderBy(п => п.Key, StringComparer.Ordinal))
        {
            if (h.живой(кто) is not NPC p || сколько <= 0.0)
                continue;
            double вес = Math.Min(0.9, сколько * ручки["пролог_подозрение_вес"]);
            foreach (var р in _принёс.Keys.OrderBy(к => к, StringComparer.Ordinal))
                Социальное.note_signal(p, я.id, р, я.stock.Взять(р, 0.0), вес);   // правда: видно: носил на глазах
            насторожились.Add(p);
        }
        день = 0;
        return насторожились;
    }

    // ------------------------------------------------------------ сохранение игры

    public System.Text.Json.Nodes.JsonObject Сложить() => new()
    {
        ["дней"] = дней,
        ["день"] = день,
        ["подозрение"] = Карман.Числа_в(_подозрение),
        ["принёс"] = Карман.Числа_в(_принёс),
        ["предупредил"] = new System.Text.Json.Nodes.JsonArray(_предупредил.OrderBy(x => x, StringComparer.Ordinal).Select(x => (System.Text.Json.Nodes.JsonNode?)x).ToArray()),
    };

    public static Пролог Разложить(System.Text.Json.Nodes.JsonObject о)
    {
        var п = new Пролог(о["дней"]!.GetValue<int>()) { день = о["день"]!.GetValue<int>() };
        foreach (var (к, v) in о["подозрение"]!.AsObject())
            п._подозрение[к] = v!.GetValue<double>();
        foreach (var (к, v) in о["принёс"]!.AsObject())
            п._принёс[к] = v!.GetValue<double>();
        foreach (var x in о["предупредил"]!.AsArray())
            п._предупредил.Add(x!.GetValue<string>());
        return п;
    }
}
