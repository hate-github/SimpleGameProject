// Что навыки делают с днём (ГДД 8.1).
//
// Здесь одно правило, и оно держит весь этап: **навыки есть только
// у того, у кого есть наследие.** У соседей наследия нет и не будет —
// они ничего не помнят и ничему не учатся, это и отличает героя от них
// (ГДД 3). Поэтому у обычного жильца `npc.умения` — `null`, и каждая
// поправка обращается в единицу.
//
// Отсюда следует то, ради чего это так и устроено: прогон без игрока
// считается ровно как раньше, бит в бит. Эталон на двадцати четырёх
// зёрнах обязан остаться зелёным, и это не рассуждение, а проверка —
// раздел «навыки» гоняет тот же дом с наследием нулевого уровня
// и сверяет снимки.
//
// Числа живут в `data/петля.json`, а не здесь: подобрать их можно только
// игрой, и лезть за ними в код будет некому.
//
// Смекалки здесь нет, и это не забывчивость. В ГДД 8.1 она про сложные
// объекты, скрытые реплики и мини-игры «Взлом» и «Разговор» — а в доме
// ни у сборки генератора, ни у разговора провала нет вовсе: провал живёт
// в мини-игре (ГДД 7), которой ещё нет. Приделать ей эффект наугад значило
// бы завести ручку, за которой ничего не меряется, — как это уже вышло
// с темнотой в рассудке.

namespace Дом.Ядро;

/// <summary>
/// Навыки одного человека, приложенные к делу.
///
/// Обёртка над наследием и ручками, а не над одним наследием: множители
/// считаются из уровней, а уровни без ручек — просто числа. Считается один
/// раз на жизнь: уровни внутри метели не меняются (очки тратятся между
/// жизнями), и пересчитывать их на каждый бросок незачем.
/// </summary>
public sealed class Умения
{
    public Умения(Наследие наследие, РучкиПетли ручки)
    {
        this.наследие = наследие;

        int физика = наследие.Уровень(Навык.ФИЗИКА);
        int стойкость_ = наследие.Уровень(Навык.УСТОЙЧИВОСТЬ);

        сила = 1.0 + физика * ручки["физика_сила_за_уровень"];
        быстрее = 1.0 - физика * ручки["физика_быстрее_за_уровень"];
        холод = System.Math.Max(
            0.0, 1.0 - стойкость_ * ручки["стойкость_холод_за_уровень"]);
        карман = ручки["карман_вес"] + физика * ручки["физика_вес_за_уровень"];
    }

    public Наследие наследие { get; }

    /// <summary>Множитель к силе в бою. Единица — как у всех.</summary>
    public double сила { get; }

    /// <summary>Множитель к часам физической работы. Меньше единицы —
    /// быстрее.</summary>
    public double быстрее { get; }

    /// <summary>Множитель к расходу на холоде. Ноль на пятом уровне —
    /// мороз перестаёт съедать сытость сверх обычного.</summary>
    public double холод { get; }

    /// <summary>Сколько весу влезает в карман вне времени.</summary>
    public double карман { get; }
}

/// <summary>
/// Поправки к симуляции. Каждая — одна строка на месте вызова
/// и единица, когда умений нет.
/// </summary>
public static class Поправки
{
    /// <summary>Сила в бою: `power()` умножается на это.</summary>
    public static double Сила(NPC npc) => npc.умения?.сила ?? 1.0;

    /// <summary>Часы физической работы.</summary>
    public static double Быстрее(NPC npc) => npc.умения?.быстрее ?? 1.0;

    /// <summary>Расход сытости на холоде.</summary>
    public static double Холод(NPC npc) => npc.умения?.холод ?? 1.0;
}
