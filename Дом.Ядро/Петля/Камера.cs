// Камера на пролёт (ГДД 15, уровень 3: «генератор (шумный), камера на пролёт,
// стальные листы на дверь»; требования — «знание „Электрик“ или „Смекалка“ 3,
// материалы»; ГДД 8.1: Смекалка — «взаимодействие со сложными объектами
// (камера, генератор, щиток)»).
//
// Камеру покупают в строительном до метели (`строймаг.json`) и вешают над
// своей дверью: часы — поступком героя, материалы (провод, крепёж) — из шкафа.
// Повесить может тот, кто разбирается: Смекалка от «камера_смекалка» или знание
// «электрик» — его рассказывает Виктор, электрик из ЖЭКа, как знатоки
// рассказывают о мире (`мир.json`, «знатоки»), и оно, как всё узнанное,
// переходит в следующую жизнь. Сыграть за самого электрика (`NPC.skills`) —
// тоже можно.
//
// Пишет она, пока в квартире есть ток (`House.powered` для той квартиры: свет
// в доме или свой генератор сегодня), и видит одну площадку — свой этаж: кто
// стоял у какой двери, с какого часа по какой и за каким делом. Кадры — ходы
// хроники (`Дом.Экран.Хроника`), которые узел приносит на каждом вопросе;
// камера оставляет из них только то, что видно с её места, и только по разу.
// Смотрят запись в телефоне (вкладка «камера», `Дом.Экран.КамераГероя`).
// Главное в ней — то, что было без героя: кто стучал, кто возился с замком,
// кто выносил доски из пустой квартиры напротив.
//
// Камера принадлежит квартире, а не жильцу (ГДД 15): висит над той дверью,
// куда её повесили, и с новой жизнью её нет — состояние убежища
// не переносится (ГДД 8). Только у героя: живёт в округе (`Округа.камера`,
// в сохранении игры), дом о ней не знает, и прогон без игрока тот же.

using System.Text.Json.Nodes;

namespace Дом.Ядро;

/// <summary>Один кадр записи: кто с какого часа по какой стоял у двери
/// какой квартиры и за каким делом (ключ справочника).</summary>
public sealed record КадрКамеры(int день, double от, double до, string кто, int кв, string ключ);

public sealed class Камера
{
    /// <summary>Id камеры в каталоге предметов (`инструменты.json`).</summary>
    public const string ПРЕДМЕТ = "камера";

    /// <summary>Знание, с которым камеру вешают и без Смекалки.</summary>
    public const string ЭЛЕКТРИК = "электрик";

    private readonly List<КадрКамеры> _кадры = new();
    private readonly object _замок = new();

    public Камера(int квартира, int этаж, int с_дня, double с_часа)
    {
        this.квартира = квартира;
        this.этаж = этаж;
        this.с_дня = с_дня;
        this.с_часа = с_часа;
    }

    /// <summary>Над чьей дверью висит.</summary>
    public int квартира { get; }

    /// <summary>Какую площадку видит.</summary>
    public int этаж { get; }

    /// <summary>С какого дня и часа пишет: раньше её не было.</summary>
    public int с_дня { get; }
    public double с_часа { get; }

    /// <summary>Записанное — по порядку записи.</summary>
    public IReadOnlyList<КадрКамеры> кадры
    {
        get
        {
            lock (_замок)
                return _кадры.ToList();
        }
    }

    /// <summary>Есть ли сегодня ток в той квартире — свет в доме или свой генератор.</summary>
    public bool Работает(House h)
        => h.power_on
           || (h.flats.Есть(квартира) && h.flats[квартира].shelter.Взять("питание", double.NaN) == h.day);

    /// <summary>
    /// Записать то, что видно с её места: ходы у дверей своего этажа, после того
    /// как её повесили, без самого героя, каждый по разу. Без тока — ничего.
    /// Возвращает, сколько кадров легло. Зовётся, пока дом спит.
    /// </summary>
    public int Записать(House h, IEnumerable<КадрКамеры> ходы, string герой)
    {
        if (!Работает(h))
            return 0;
        int легло = 0;
        lock (_замок)
            foreach (var к in ходы)
            {
                if (string.Equals(к.кто, герой, StringComparison.Ordinal)
                    || к.день < с_дня || (к.день == с_дня && к.от < с_часа)
                    || !h.flats.Есть(к.кв) || h.flats[к.кв].floor != этаж
                    || _кадры.Any(б => б.день == к.день && б.от == к.от
                                       && string.Equals(б.кто, к.кто, StringComparison.Ordinal)))
                    continue;
                _кадры.Add(к);
                легло++;
            }
        return легло;
    }

    /// <summary>
    /// Почему не повесить — или null, если можно: камеры нет при себе и дома,
    /// уже висит, не разобраться (ни Смекалки, ни знания электрика), не хватает
    /// материалов на провод и крепёж.
    /// </summary>
    public static string? Нельзя(House h, NPC я, РучкиПетли ручки)
    {
        var о = Округа.У(h);
        if (о?.камера is not null)
            return "камера уже висит";
        if (я.снаряжение is not { } с || !(с.Есть(ПРЕДМЕТ) || с.дома.Contains(ПРЕДМЕТ)))
            return "камеры нет — её продают в строительном";
        if (!Умеет(я, о, ручки))
            return $"не разобраться: питание, провода — нужна Смекалка {(int)ручки["камера_смекалка"]} или знать дело электрика";
        double нужно = ручки["камера_материалы"];
        if (я.stock.Взять("материалы", 0.0) < нужно - 1e-9)
            return $"на провод и крепёж нужно материалов {Текст.G(нужно)}";
        return null;
    }

    /// <summary>Сколько часов вешать — поступком героя.</summary>
    public static double Часы(РучкиПетли ручки) => ручки["камера_часы"];

    /// <summary>Разбирается ли он в этом: Смекалка от порога, знание электрика
    /// (узнал у Виктора) или сам электрик.</summary>
    public static bool Умеет(NPC я, Округа? о, РучкиПетли ручки)
        => (я.умения?.наследие.Уровень(Навык.СМЕКАЛКА) ?? 0) >= (int)ручки["камера_смекалка"]
           || о?.Знает(ЭЛЕКТРИК) == true
           || я.skills.Contains(ЭЛЕКТРИК, StringComparer.Ordinal);

    /// <summary>
    /// Повесить над своей дверью: камера уходит из снаряжения, материалы —
    /// из шкафа; пишет с этого часа. null — нельзя (`Нельзя`). Часы тратит
    /// зовущий — поступком героя («камера_часы»). Только пока дом спит.
    /// </summary>
    public static Камера? Повесить(House h, NPC я, РучкиПетли ручки)
    {
        if (Нельзя(h, я, ручки) is not null || Округа.У(h) is not { } о)
            return null;
        я.снаряжение!.Израсходовать(ПРЕДМЕТ);
        я.stock["материалы"] = я.stock.Взять("материалы", 0.0) - ручки["камера_материалы"];
        var к = new Камера(я.apt, h.flats[я.apt].floor, h.day, я.час());
        о.камера = к;
        return к;
    }

    // ------------------------------------------------------------ сохранение игры

    public JsonObject Сложить()
    {
        var кадры = new JsonArray();
        lock (_замок)
            foreach (var к in _кадры)
                кадры.Add(new JsonObject
                {
                    ["день"] = к.день, ["от"] = к.от, ["до"] = к.до,
                    ["кто"] = к.кто, ["кв"] = к.кв, ["ключ"] = к.ключ,
                });
        return new JsonObject
        {
            ["квартира"] = квартира, ["этаж"] = этаж, ["с_дня"] = с_дня, ["с_часа"] = с_часа,
            ["кадры"] = кадры,
        };
    }

    public static Камера Разложить(JsonObject о)
    {
        var к = new Камера(о["квартира"]!.GetValue<int>(), о["этаж"]!.GetValue<int>(),
                           о["с_дня"]!.GetValue<int>(), о["с_часа"]!.GetValue<double>());
        foreach (var x in о["кадры"]!.AsArray())
            к._кадры.Add(new КадрКамеры(x!["день"]!.GetValue<int>(), x["от"]!.GetValue<double>(),
                                        x["до"]!.GetValue<double>(), x["кто"]!.GetValue<string>(),
                                        x["кв"]!.GetValue<int>(), x["ключ"]!.GetValue<string>()));
        return к;
    }
}
