// Магазин на Заречной — место, куда герой ходит сам (задание автора, п. 13).
//
// Это тот же магазин, что у соседей: у них он — вылазка, после которой
// товар сам оказывается в шкафу (`Улица._купить`: берут по нужде, по карману,
// в порядке «что нужнее»), у героя — прилавок, у которого он выбирает сам.
// Всё остальное общее, и так нарочно — две разные лавки разошлись бы:
//   · работает, пока работает у соседей (`h.магазины`, три первых дня);
//   · цены — `магазин_цена` дома, и наценка за каждый день метели;
//   · платят так же: сперва карта (пока живы банки), потом наличные —
//     наличные берегут, их примут и завтра;
//   · полка общая: купленное героем вычерпывает место (`богатство_места`),
//     и соседу потом остаётся меньше;
//   · купленное из шкафа ложится в тару (`Ноша`) и несётся домой, как найденное;
//     вещи (снегоступы, инструменты) — в снаряжение, и их на складе считано.
//
// Звать можно только пока дом спит на вопросе: покупка меняет дом.

using System.Text.Json;

namespace Дом.Ядро;

/// <summary>Товар: ресурс шкафа (цена — из баланса дома) или вещь героя
/// (своя цена и сколько её на складе).</summary>
public sealed record Товар(string id, string? ресурс, string? предмет, double цена, int всего);

/// <summary>Чем кончилась покупка: взято ли, сколько с карты, сколько
/// наличными, и если нет — почему.</summary>
public sealed record Покупка(bool взято, double картой, double налом, string? почему = null);

/// <summary>Чем кончилась кража: взято ли, заметили ли, в карман ли,
/// и если не взято и не заметили — почему.</summary>
public sealed record Кража(bool взято, bool заметили, bool в_карман, string? почему = null);

public sealed class Магазин
{
    private readonly List<Товар> _товары = new();
    private readonly Dictionary<string, int> _продано = new(StringComparer.Ordinal);

    /// <summary>Какое место дома — этот магазин.</summary>
    public string место { get; private set; } = "магазин на Заречной";

    /// <summary>Товары в порядке файла.</summary>
    public IReadOnlyList<Товар> товары => _товары;

    /// <summary>На сколько пустеет полка за штуку из шкафа.</summary>
    public double истощение { get; private set; }

    /// <summary>Сколько часов очереди до прилавка.</summary>
    public double очередь_часы { get; private set; }

    /// <summary>Работает ли сегодня: пока работает у соседей и на полках
    /// ещё что-то есть.</summary>
    public bool Открыт(House h) => h.магазины;

    /// <summary>Наценка этого дня — та же, что у соседей. До метели (пролог,
    /// дом ещё на нулевом дне) цены обычные: наценки нет, а не скидка.</summary>
    public static double Наценка(House h) => 1.0 + h.B["магазин_наценка_в_день"] * Math.Max(0, h.day - 1);

    /// <summary>Цена штуки сегодня, в тысячах: ресурс — по балансу дома, вещь — своя,
    /// с той же наценкой; в копейках, чтобы деньги не крошились.</summary>
    public double Цена(House h, Товар т)
        => Math.Round((т.ресурс is string р ? h.B.Таблица("магазин_цена")[р] : т.цена) * Наценка(h), 2);

    /// <summary>Сколько ещё можно купить: вещи — сколько осталось на складе;
    /// ресурсы — пока полка не опустела до дна места.</summary>
    public int Осталось(House h, Товар т)
    {
        if (т.предмет is not null)
            return Math.Max(0, т.всего - _продано.GetValueOrDefault(т.id));
        double полка = h.богатство_места(место) - h.B["вылазка_минимум_богатства"];
        return Math.Max(0, (int)Math.Floor(полка / Math.Max(1e-9, истощение) + 1e-9));
    }

    /// <summary>Сколько у героя денег сегодня: карта (пока живы банки) и наличные.</summary>
    public static double Кошелёк(House h, NPC я) => Улица.кошелёк(h, я);

    /// <summary>
    /// Купить штуку. Ресурс — в тару (нет тары — в пакет из магазина);
    /// не влезло — не куплено. Вещь — в снаряжение. Платит сперва картой,
    /// потом наличными. Полка пустеет, дом считает принесённое и потраченное
    /// тем же счётом, что у соседей.
    /// </summary>
    public Покупка Купить(House h, NPC я, Товар т, РучкиПетли ручки, Инструменты каталог)
    {
        if (!Открыт(h))
            return new Покупка(false, 0, 0, "магазин закрыт");
        if (Осталось(h, т) <= 0)
            return new Покупка(false, 0, 0, "кончилось");
        double цена = Цена(h, т);
        double карта = h.банки ? я.счёт : 0.0;
        double наличные = я.stock.Взять("деньги", 0.0);
        if (цена > карта + наличные + 1e-9)
            return new Покупка(false, 0, 0, "не хватает денег");

        if (т.ресурс is string р)
        {
            я.ноша ??= new Ноша();
            var тара = я.ноша.тара ?? Тара.ПАКЕТ;
            if (я.ноша.свободно(тара, ручки) < 1.0 - 1e-9)
                return new Покупка(false, 0, 0, "не влезет: тара полна");
            var одна = Словари.Числа();
            одна[р] = 1.0;
            я.ноша.Положить(тара, одна, ручки);
            h.stats["принесено_" + р] = h.stats.Взять("принесено_" + р, 0.0) + 1;
            h.места[место] = Math.Max(h.B["вылазка_минимум_богатства"],
                                      h.богатство_места(место) - истощение);
        }
        else if (т.предмет is string id)
        {
            if (я.снаряжение is not { } с)
                return new Покупка(false, 0, 0, "некуда взять");
            if (с.Есть(id))
                return new Покупка(false, 0, 0, "такое уже есть");
            if (с.Нельзя_взять(id, каталог) is string нельзя)
                return new Покупка(false, 0, 0, нельзя);
            с.Подобрать(id, каталог);
            _продано[т.id] = _продано.GetValueOrDefault(т.id) + 1;
        }

        double картой = Math.Min(карта, цена);
        double налом = цена - картой;
        я.счёт = Math.Max(0.0, я.счёт - картой);
        if (я.счёт < 0.005)
            я.счёт = 0.0;                   // остаток меньше пятака — это уже не деньги
        if (налом > 0)
            Ресурсы.Spend(h, я, "деньги", налом);
        h.stats["потрачено_картой"] = h.stats.Взять("потрачено_картой", 0.0) + картой;
        h.stats["потрачено_налом"] = h.stats.Взять("потрачено_налом", 0.0) + налом;
        return new Покупка(true, картой, налом);
    }

    /// <summary>
    /// Украсть (задание автора, п. 16; ГДД 9): взять с полки и не заплатить —
    /// в тару, на виду, или в карман вне времени: вещь исчезает из рук,
    /// заметить труднее, но заметивший видел чудо. Заметят ли — продавщица
    /// и те, кто в очереди (`кража_заметят_*`); бросок — исход, из `h.rng`.
    /// Заметили — ничего не взято: что будет дальше, решает вызывающий
    /// (до метели — полиция, в метель — выгнали и запомнили).
    /// </summary>
    public Кража Украсть(House h, NPC я, Товар т, bool в_карман, int в_очереди,
                         РучкиПетли ручки, Инструменты каталог)
    {
        if (!Открыт(h))
            return new Кража(false, false, в_карман, "магазин закрыт");
        if (Осталось(h, т) <= 0)
            return new Кража(false, false, в_карман, "кончилось");
        if (т.ресурс is string р0)
        {
            if (в_карман)
            {
                if (я.карман is not { } к || к.свободно < 1.0 - 1e-9)
                    return new Кража(false, false, true, "в кармане нет места");
            }
            else
            {
                я.ноша ??= new Ноша();
                var тара = я.ноша.тара ?? Тара.ПАКЕТ;
                if (я.ноша.свободно(тара, ручки) < 1.0 - 1e-9)
                    return new Кража(false, false, false, "не влезет: тара полна");
            }
        }
        else if (т.предмет is string id0)
        {
            if (я.снаряжение is not { } с0)
                return new Кража(false, false, в_карман, "некуда взять");
            if (с0.Есть(id0) || я.карман?.инструменты.Contains(id0) == true)
                return new Кража(false, false, в_карман, "такое уже есть");
            if (в_карман && (я.карман is not { } к || Карман.Вес(id0, каталог, ручки) > к.свободно + 1e-9))
                return new Кража(false, false, true, "в кармане нет места");
            if (!в_карман && с0.Нельзя_взять(id0, каталог) is string нельзя)
                return new Кража(false, false, false, нельзя);
        }
        double база = в_карман ? ручки["кража_заметят_карман"] : ручки["кража_заметят_тара"];
        double шанс = Math.Min(0.9, база + Math.Max(0, в_очереди) * ручки["кража_заметят_за_свидетеля"]);
        if (h.rng.Chance(шанс))
            return new Кража(false, true, в_карман);

        if (т.ресурс is string р)
        {
            if (в_карман)
                я.карман!.Положить_найденное(р, 1.0);
            else
            {
                var тара = я.ноша!.тара ?? Тара.ПАКЕТ;
                var одна = Словари.Числа();
                одна[р] = 1.0;
                я.ноша.Положить(тара, одна, ручки);
            }
            h.stats["принесено_" + р] = h.stats.Взять("принесено_" + р, 0.0) + 1;
            h.stats["украдено_" + р] = h.stats.Взять("украдено_" + р, 0.0) + 1;
            h.места[место] = Math.Max(h.B["вылазка_минимум_богатства"],
                                      h.богатство_места(место) - истощение);
        }
        else if (т.предмет is string id)
        {
            я.снаряжение!.Подобрать(id, каталог);
            if (в_карман)
                я.карман!.Спрятать(я, id, каталог, ручки);
            _продано[т.id] = _продано.GetValueOrDefault(т.id) + 1;
        }
        return new Кража(true, false, в_карман);
    }

    /// <summary>Полка пустеет от чужих покупок — сосед, поверивший, что будет
    /// метель, выгреб своё (беседа в прологе).</summary>
    public void Истощить(House h, int штук)
        => h.места[место] = Math.Max(h.B["вылазка_минимум_богатства"],
                                     h.богатство_места(место) - истощение * Math.Max(0, штук));

    public static Магазин Прочитать(string каталог, Инструменты? предметы = null)
    {
        var м = new Магазин();
        using var поток = File.OpenRead(Path.Combine(каталог, "магазин.json"));
        using var док = JsonDocument.Parse(поток);
        var корень = док.RootElement;
        м.место = корень.GetProperty("место").GetString()!;
        м.истощение = корень.GetProperty("истощение_за_штуку").GetDouble();
        м.очередь_часы = корень.GetProperty("очередь_часы").GetDouble();
        var ids = new HashSet<string>(StringComparer.Ordinal);
        foreach (var т in корень.GetProperty("товары").EnumerateArray())
        {
            string id = т.GetProperty("id").GetString()!;
            if (!ids.Add(id))
                throw new InvalidDataException($"магазин.json: товар «{id}» дважды");
            string? ресурс = т.TryGetProperty("ресурс", out var р) ? р.GetString() : null;
            string? предмет = т.TryGetProperty("предмет", out var п) ? п.GetString() : null;
            if ((ресурс is null) == (предмет is null))
                throw new InvalidDataException($"магазин.json: «{id}» — либо ресурс, либо предмет");
            if (ресурс is not null && !Ресурсы.ВСЕ.Contains(ресурс, StringComparer.Ordinal))
                throw new InvalidDataException($"магазин.json: «{id}» — ресурса «{ресурс}» в доме нет");
            if (предмет is not null && предметы is not null && !предметы.в_руках.ContainsKey(предмет))
                throw new InvalidDataException($"магазин.json: «{id}» — предмета «{предмет}» в каталоге нет");
            double цена = т.TryGetProperty("цена", out var ц) ? ц.GetDouble() : 0.0;
            int всего = т.TryGetProperty("всего", out var в) ? в.GetInt32() : 0;
            if (предмет is not null && (цена <= 0 || всего <= 0))
                throw new InvalidDataException($"магазин.json: у «{id}» нужны цена и сколько на складе");
            м._товары.Add(new Товар(id, ресурс, предмет, цена, всего));
        }
        return м;
    }

    // ------------------------------------------------------------ сохранение игры

    public System.Text.Json.Nodes.JsonObject Сложить()
        => Карман.Числа_в(_продано.Select(п => new KeyValuePair<string, double>(п.Key, п.Value)));

    public void Разложить(System.Text.Json.Nodes.JsonObject о)
    {
        _продано.Clear();
        foreach (var (к, v) in о)
            _продано[к] = (int)v!.GetValue<double>();
    }
}
