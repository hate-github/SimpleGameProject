// Бомбоубежище гражданской обороны под пустырём (ГДД 20: «бункер — возможный
// путь одиночки: пережить метель там, натаскав запасы. Это путь со своей
// ценой — ходки под наблюдением, одиночество, худшие концовки»; ГДД 22,
// «Одиночка»; задание автора, п. 10).
//
// Найти вход — дело знатоков и снега (`Округа.Искать_бункер`), и знание
// о нём переходит в следующую жизнь (решение автора). Здесь — что внутри
// и чем за это платят:
//
//   · **гермодверь** прикипела с восьмидесятых: открыть — монтировкой
//     на штурвал (замок «гермодверь» в каталоге инструментов) или руками —
//     долго, редко и в кровь. Открыта — до конца жизни;
//   · **тепло** — земля: под ней ровные плюс восемь, как ни мети
//     (`IПриют`, как в участке). Это холод, а не тепло — дому комфортно
//     с двенадцати, и две недели на восьми не пережить (первая версия
//     ставила шесть без печки, и живая игра умерла от холода на тринадцатый
//     день). Буржуйка в зале греет за топливо — его тоже носят с собой;
//   · **запас** — НЗ гражданской обороны (галеты, вода в баке, аптечка)
//     и то, что герой натаскал сам: выложил из ноши — лежит здесь, мимо
//     дома, и дом его не видит;
//   · **вентиляция** — фильтровентиляционный агрегат с ручным приводом:
//     не крутил за день — ночь в спёртом воздухе стоит здоровья;
//   · **ходки под наблюдением** — уходить за ворота с полной тарой видно
//     из окон. Заметивший решает, что у героя есть что носить (как сумки
//     в прологе); заметивший не в первый раз идёт по следу и знает, где
//     бункер, — и ночью, пока героя там нет, уносит часть запаса к себе;
//   · **одиночество** — под землёй соприкоснуться не с кем, и дневник
//     рассудка считает эти дни сам (`Дневник.одиноких`);
//   · **концовка** — пересидевший метель под землёй — «Одиночка»
//     (`Концовки`, ручка `одиночка_ночей`).
//
// Всё это живёт в округе героя: без игрока бункера нет, и дом считает,
// как считал. Все броски — свой генератор от зерна (`Округа.Бросок`),
// мимо `h.rng`. Дом меняется в одном месте — у того, кто унёс запас,
// прибавляется в шкафу; это случается только в игре, как смерть от болезни.

using System.Text.Json;

namespace Дом.Ядро;

/// <summary>Числа бункера из `data/мир.json`, «бункер».</summary>
public sealed record ДанныеБункера(
    string имя,
    double градусов,
    double печь_градусов,
    double печь_топлива,
    string замок,
    double руками_часов,
    double руками_шанс,
    double руками_урон,
    IReadOnlyDictionary<string, double> запас,
    double вентиляция_часов,
    double духота_урон,
    double заметят,
    double заметили_вес,
    int выследят,
    double унесут_шанс,
    double унесут_доля)
{
    public static ДанныеБункера Прочитать(JsonElement б)
    {
        var д = б.GetProperty("дверь");
        var п = б.GetProperty("печь");
        var р = д.GetProperty("руками");
        var в = б.GetProperty("вентиляция");
        var х = б.GetProperty("ходки");
        var запас = new Dictionary<string, double>(StringComparer.Ordinal);
        foreach (var x in б.GetProperty("запас").EnumerateObject())
        {
            if (!Ресурсы.ВСЕ.Contains(x.Name, StringComparer.Ordinal))
                throw new InvalidDataException($"мир.json: в запасе бункера «{x.Name}» — такого ресурса в доме нет");
            запас[x.Name] = x.Value.GetDouble();
        }
        var данные = new ДанныеБункера(
            б.GetProperty("имя").GetString()!,
            б.GetProperty("градусов").GetDouble(),
            п.GetProperty("градусов").GetDouble(),
            п.GetProperty("топлива").GetDouble(),
            д.GetProperty("замок").GetString()!,
            р.GetProperty("часов").GetDouble(),
            р.GetProperty("шанс").GetDouble(),
            р.GetProperty("урон").GetDouble(),
            запас,
            в.GetProperty("часов").GetDouble(),
            в.GetProperty("урон").GetDouble(),
            х.GetProperty("заметят").GetDouble(),
            х.GetProperty("вес").GetDouble(),
            х.GetProperty("выследят").GetInt32(),
            х.GetProperty("унесут_шанс").GetDouble(),
            х.GetProperty("унесут_доля").GetDouble());
        if (данные.выследят < 1 || данные.унесут_доля is <= 0 or > 1 || данные.заметят is < 0 or > 1)
            throw new InvalidDataException("мир.json: бункер — «выследят» от одной ходки, доли и шансы от нуля до единицы");
        return данные;
    }
}

/// <summary>Чем кончилась попытка открыть гермодверь.</summary>
public sealed record Штурвал(bool открыл, double часов, string чем, string весть);

public sealed class Бункер : IПриют
{
    public ДанныеБункера данные { get; }
    private readonly long _зерно;
    private readonly Словарь<string, double> _запас = Словари.Числа();
    private int _вентилирован = int.MinValue;
    private int _печь_день = int.MinValue;
    private int _ходок;
    private readonly Dictionary<string, int> _заметил = new(StringComparer.Ordinal);
    private readonly HashSet<string> _знают = new(StringComparer.Ordinal);
    private readonly Словарь<string, double> _пропало = Словари.Числа();
    private readonly Queue<string> _вести = new();
    private readonly object _замок = new();

    public Бункер(ДанныеБункера д, long зерно)
    {
        данные = д;
        _зерно = зерно;
        foreach (var (р, сколько) in д.запас.OrderBy(п => п.Key, StringComparer.Ordinal))
            _запас[р] = сколько;
    }

    /// <summary>Гермодверь открыта — до конца жизни.</summary>
    public bool открыт { get; private set; }

    /// <summary>Герой под землёй: греется здесь.</summary>
    public bool внутри { get; private set; }

    /// <summary>Сколько ночей он провёл под землёй.</summary>
    public int ночей { get; private set; }

    public IReadOnlyList<string> запас_что => _запас.Ключи;
    public double В_запасе(string р) => _запас.Взять(р, 0.0);
    public double запас_всего => Util.Sum(_запас.Ключи.Select(к => _запас[к]));

    /// <summary>Кто из соседей выследил, где бункер. Герою этого не видно:
    /// он узнаёт только пропажу.</summary>
    public IReadOnlyCollection<string> знают => _знают;

    public bool Вентилирован(int день) => _вентилирован == день;

    public bool Печь_топится(int день) => _печь_день == день;

    // ------------------------------------------------------------ приют

    public double? Температура(House h, NPC кто)
        => внутри ? данные.градусов + (Печь_топится(h.day) ? данные.печь_градусов : 0.0) : null;

    /// <summary>Спустился в бункер: дальше греется здесь.</summary>
    public void Спустился(NPC я)
    {
        внутри = true;
        я.приют = this;
    }

    /// <summary>Поднялся наверх — домой или куда ещё.</summary>
    public void Поднялся(NPC я)
    {
        внутри = false;
        if (ReferenceEquals(я.приют, this))
            я.приют = null;
    }

    // ------------------------------------------------------------ гермодверь

    /// <summary>Чем открывать: инструмент при себе, который берёт «гермодверь»,
    /// лучший по шансу; нет — руками (null).</summary>
    public string? Чем_открыть(NPC я, Инструменты каталог)
        => я.снаряжение?.с_собой
            .Where(id => Приём_(id, каталог) is not null)
            .OrderByDescending(id => Приём_(id, каталог)!.шанс)
            .ThenBy(id => id, StringComparer.Ordinal)
            .FirstOrDefault();

    private Приём? Приём_(string id, Инструменты каталог)
        => каталог.все.TryGetValue(id, out var и) ? и.Берёт(данные.замок) : null;

    public double Часов_открыть(House h, string? инструмент, Инструменты каталог)
        => инструмент is string и && Приём_(и, каталог) is { } п ? Взлом.часы(h, п) : данные.руками_часов;

    /// <summary>
    /// Попытка провернуть штурвал: часы уже ушли делом. Инструментом — шанс
    /// по замку (мерка работы, как взлом), руками — `руками_шанс` и кровь.
    /// Бросок — исход, из `h.rng`, как у взлома и камеры.
    /// </summary>
    public Штурвал Открыть(House h, NPC я, string? инструмент, Инструменты каталог, РучкиПетли ручки)
    {
        if (открыт)
            return new Штурвал(true, 0, "", "гермодверь и так открыта");
        double часов = Часов_открыть(h, инструмент, каталог);
        if (инструмент is string и && Приём_(и, каталог) is { } п)
        {
            string чем = каталог.все[и].чем;
            if (!h.rng.Chance(Взлом.шанс(h, я, ручки, п)))
                return new Штурвал(false, часов, чем, $"{чем} на штурвал — не идёт, прикипел; ещё раз");
            открыт = true;
            return new Штурвал(true, часов, чем, $"{чем} на штурвал — пошёл, со скрипом; гермодверь открыта");
        }
        я.health = Math.Max(1.0, я.health - данные.руками_урон);
        if (!h.rng.Chance(данные.руками_шанс))
            return new Штурвал(false, часов, "руками", "штурвал руками не провернуть — только содрал ладони");
        открыт = true;
        return new Штурвал(true, часов, "руками", "штурвал поддался на четверть оборота, потом пошёл; гермодверь открыта");
    }

    // ------------------------------------------------------------ запас

    /// <summary>Поесть или попить из запаса — порцию, как дома. false —
    /// нечего или дверь ещё закрыта.</summary>
    public bool Поесть(House h, NPC я, string ресурс)
    {
        if (!открыт || _запас.Взять(ресурс, 0.0) < 1.0)
            return false;
        _запас[ресурс] = _запас.Взять(ресурс, 0.0) - 1.0;
        Участок.Съесть(h, я, ресурс);
        return true;
    }

    /// <summary>Выложить из ноши всё — сюда, мимо дома. Что выложено.</summary>
    public Словарь<string, double> Выложить(NPC я)
    {
        var было = Словари.Числа();
        if (!открыт || я.ноша is not { пусто: false } ноша)
            return было;
        foreach (var р in ноша.ресурсы.ToList())
        {
            было[р] = ноша.Сколько(р);
            _запас[р] = _запас.Взять(р, 0.0) + ноша.Сколько(р);
        }
        ноша.Обнулить();
        return было;
    }

    /// <summary>Взять из запаса в тару — унести. Сколько влезло.</summary>
    public double Взять(NPC я, string ресурс, double сколько, РучкиПетли ручки)
    {
        if (!открыт)
            return 0.0;
        я.ноша ??= new Ноша();
        var тара = я.ноша.тара ?? Тара.ПАКЕТ;
        сколько = Math.Min(сколько, Math.Min(_запас.Взять(ресурс, 0.0), я.ноша.свободно(тара, ручки)));
        if (сколько <= 0.0)
            return 0.0;
        var взять = Словари.Числа();
        взять[ресурс] = сколько;
        я.ноша.Положить(тара, взять, ручки);
        _запас[ресурс] = _запас.Взять(ресурс, 0.0) - сколько;
        return сколько;
    }

    /// <summary>Затопить буржуйку на сегодня — топливо из запаса.</summary>
    public string? Затопить(House h)
    {
        if (!открыт)
            return "буржуйка за гермодверью";
        if (Печь_топится(h.day))
            return "буржуйка уже топится";
        if (_запас.Взять("топливо", 0.0) < данные.печь_топлива - 1e-9)
            return "топить нечем: топливо носят с собой";
        _запас["топливо"] = _запас.Взять("топливо", 0.0) - данные.печь_топлива;
        _печь_день = h.day;
        return null;
    }

    // ------------------------------------------------------------ вентиляция

    /// <summary>Прокрутил привод — воздуха хватит до утра.</summary>
    public void Вентилировать(int день) => _вентилирован = день;

    // ------------------------------------------------------------ ходки

    /// <summary>
    /// Герой уходит за ворота к бункеру с полной тарой. Кто дома, тот
    /// с шансом `заметят` видит его из окна: решает, что у героя есть что
    /// носить (сведения о его запасах, как сумки в прологе), и считает
    /// ходки; заметивший `выследят` раз идёт по следу и знает, где бункер.
    /// Возвращает заметивших — герой видит только, что в окне кто-то стоял.
    /// </summary>
    public List<NPC> Ходка(House h, NPC я)
    {
        var заметили = new List<NPC>();
        if (я.ноша is not { пусто: false } ноша)
            return заметили;
        int ходка = _ходок++;
        foreach (var p in h.others(я).OrderBy(p => p.id, StringComparer.Ordinal))
        {
            if (!p.здесь() || p.away
                || Округа.Бросок(_зерно, $"ходка{ходка}", p.id, h.day) >= данные.заметят)
                continue;
            foreach (var р in ноша.ресурсы.OrderBy(к => к, StringComparer.Ordinal))
                Социальное.note_signal(p, я.id, р, я.stock.Взять(р, 0.0) + ноша.Сколько(р), данные.заметили_вес);   // правда: видно: нёс на глазах
            _заметил[p.id] = _заметил.GetValueOrDefault(p.id) + 1;
            if (_заметил[p.id] >= данные.выследят)
                _знают.Add(p.id);
            заметили.Add(p);
        }
        return заметили;
    }

    // ------------------------------------------------------------ ночь

    /// <summary>Подписаться на конец дня: ночь под землёй и ночные гости.</summary>
    public void Слушать(House h, string герой)
        => h.hooks.on_day.Add(дом =>
        {
            if (дом.get(герой) is NPC я)
                Конец_дня(дом, я);
        });

    /// <summary>
    /// Конец дня. Герой под землёй — ночь засчитана, и без вентиляции она
    /// стоит здоровья. Героя там нет — кто выследил бункер, тот с шансом
    /// приходит и уносит долю каждого запаса к себе в шкаф.
    /// </summary>
    public void Конец_дня(House h, NPC я)
    {
        if (!я.alive)
            return;
        if (внутри)
        {
            ночей++;
            if (!Вентилирован(h.day))
            {
                я.health = Math.Max(1.0, я.health - данные.духота_урон);
                Сказать("ночь в спёртом воздухе: голова тяжёлая, в груди давит — привод вентиляции не крутил");
            }
            return;
        }
        foreach (var id in _знают.OrderBy(x => x, StringComparer.Ordinal))
        {
            if (h.живой(id) is not NPC вор || !вор.здесь() || запас_всего < 1.0
                || Округа.Бросок(_зерно, "унести", id, h.day) >= данные.унесут_шанс)
                continue;
            foreach (var р in _запас.Ключи.ToList())
            {
                double взял = Math.Floor(_запас[р] * данные.унесут_доля);
                if (взял < 1.0)
                    continue;
                _запас[р] -= взял;
                вор.stock[р] = вор.stock.Взять(р, 0.0) + взял;
                lock (_замок)
                    _пропало[р] = _пропало.Взять(р, 0.0) + взял;
            }
        }
    }

    private void Сказать(string что)
    {
        lock (_замок)
            _вести.Enqueue(что);
    }

    /// <summary>Что сказать герою — по одному; нет — null.</summary>
    public string? Весть()
    {
        lock (_замок)
            return _вести.Count > 0 ? _вести.Dequeue() : null;
    }

    /// <summary>Что пропало, пока его не было, — герой видит, когда спустится;
    /// после этого список пуст.</summary>
    public Словарь<string, double> Пропажи()
    {
        lock (_замок)
        {
            var было = Словари.Числа();
            foreach (var р in _пропало.Ключи)
                было[р] = _пропало[р];
            _пропало.Очистить();
            return было;
        }
    }

    // ------------------------------------------------------------ сохранение игры

    public System.Text.Json.Nodes.JsonObject Сложить()
    {
        var заметил = new System.Text.Json.Nodes.JsonObject();
        foreach (var (кто, н) in _заметил.OrderBy(п => п.Key, StringComparer.Ordinal))
            заметил[кто] = н;
        lock (_замок)
            return new()
            {
                ["открыт"] = открыт,
                ["внутри"] = внутри,
                ["ночей"] = ночей,
                ["вентилирован"] = _вентилирован,
                ["печь_день"] = _печь_день,
                ["ходок"] = _ходок,
                ["запас"] = Карман.Числа_в(_запас.Ключи.Select(к => new KeyValuePair<string, double>(к, _запас[к]))),
                ["заметил"] = заметил,
                ["знают"] = new System.Text.Json.Nodes.JsonArray(_знают.OrderBy(x => x, StringComparer.Ordinal)
                    .Select(x => (System.Text.Json.Nodes.JsonNode?)x).ToArray()),
                ["пропало"] = Карман.Числа_в(_пропало.Ключи.Select(к => new KeyValuePair<string, double>(к, _пропало[к]))),
                ["вести"] = new System.Text.Json.Nodes.JsonArray(_вести.Select(x => (System.Text.Json.Nodes.JsonNode?)x).ToArray()),
            };
    }

    /// <summary>Разложить и снова греть героя здесь, если он под землёй.</summary>
    public void Разложить(System.Text.Json.Nodes.JsonObject о, NPC я)
    {
        открыт = о["открыт"]!.GetValue<bool>();
        внутри = о["внутри"]!.GetValue<bool>();
        ночей = о["ночей"]!.GetValue<int>();
        _вентилирован = о["вентилирован"]!.GetValue<int>();
        _печь_день = о["печь_день"]!.GetValue<int>();
        _ходок = о["ходок"]!.GetValue<int>();
        _запас.Очистить();
        foreach (var (к, v) in о["запас"]!.AsObject())
            _запас[к] = v!.GetValue<double>();
        _заметил.Clear();
        foreach (var (к, v) in о["заметил"]!.AsObject())
            _заметил[к] = v!.GetValue<int>();
        _знают.Clear();
        foreach (var x in о["знают"]!.AsArray())
            _знают.Add(x!.GetValue<string>());
        lock (_замок)
        {
            _пропало.Очистить();
            foreach (var (к, v) in о["пропало"]!.AsObject())
                _пропало[к] = v!.GetValue<double>();
            _вести.Clear();
            foreach (var x in о["вести"]!.AsArray())
                _вести.Enqueue(x!.GetValue<string>());
        }
        if (внутри)
            я.приют = this;
        else if (ReferenceEquals(я.приют, this))
            я.приют = null;
    }
}
