// Промзона «Вектор-3» как место (задание автора, пп. 6–7: «основа для скрытых
// объектов и историй мира… в дальнейшем эта локация должна использоваться
// как часть исследования мира»; «опасные зоны»; ГДД 20: «в локации —
// ресурсы, знания (записки, инструкции)»).
//
// Раньше промзона была походом с исходом: два часа у ворот и бросок —
// задело или нет, а знание Аркадия просто делило шанс. Теперь это
// территория с корпусами, и каждый — свой выбор:
//
//   · **обыскать корпус** — часы, находка по своей таблице и одна на жизнь:
//     обшаренный корпус пуст;
//   · **опасные корпуса** (ферментация, виварий) — там и находка лучше
//     (лекарства), и там задевает: консервация нарушена метелью. Задетый
//     дальше болеет по правилам `Заражение`;
//   · **знание о корпусах** не уменьшает бросок, а даёт выбор: знаешь,
//     какие обходить, — обходишь. Узнают его у Аркадия или в журнале
//     дежурного в заводоуправлении, и оно переходит в следующую жизнь
//     (`Наследие.знания`), как бункер;
//   · **записки** — история места: журнал дежурного (что случилось
//     с консервацией), памятка лаборанта в виварии (как течёт болезнь).
//     Прочитанное — знание, как у знатоков.
//
// Двери подсказывают и без знания: пломба сорвана, из щели тянет —
// внимательный заметит. Всё живёт в округе героя; броски — от зерна мира
// (`Округа.Бросок`), мимо `h.rng`.

using System.Text.Json;

namespace Дом.Ядро;

/// <summary>Корпус промзоны: что там, сколько обыскивать, опасен ли, что
/// там можно прочитать и что это знание.</summary>
public sealed record Корпус(
    int номер,
    string имя,
    double часов,
    bool опасен,
    string дверь,
    IReadOnlyDictionary<string, (int от, int до)> находка,
    string? записка,
    string? узнаёшь);

/// <summary>Числа промзоны из `data/мир.json`, «вектор».</summary>
public sealed record ДанныеВектора(string имя, double задеть, IReadOnlyList<Корпус> корпуса)
{
    public static ДанныеВектора Прочитать(JsonElement в)
    {
        var корпуса = new List<Корпус>();
        foreach (var к in в.GetProperty("корпуса").EnumerateArray())
        {
            var находка = new Dictionary<string, (int, int)>(StringComparer.Ordinal);
            foreach (var п in к.GetProperty("находка").EnumerateObject())
            {
                if (!Ресурсы.ВСЕ.Contains(п.Name, StringComparer.Ordinal))
                    throw new InvalidDataException($"мир.json: в корпусе находка «{п.Name}» — такого ресурса в доме нет");
                var пара = п.Value.EnumerateArray().Select(x => x.GetInt32()).ToList();
                if (пара.Count != 2 || пара[0] < 0 || пара[1] < пара[0])
                    throw new InvalidDataException($"мир.json: находка «{п.Name}» — от и до, не меньше нуля");
                находка[п.Name] = (пара[0], пара[1]);
            }
            корпуса.Add(new Корпус(
                к.GetProperty("номер").GetInt32(),
                к.GetProperty("имя").GetString()!,
                к.GetProperty("часов").GetDouble(),
                к.GetProperty("опасен").GetBoolean(),
                к.GetProperty("дверь").GetString()!,
                находка,
                к.TryGetProperty("записка", out var з) ? з.GetString() : null,
                к.TryGetProperty("узнаёшь", out var у) ? у.GetString() : null));
        }
        if (корпуса.Count == 0 || корпуса.Select(к => к.номер).Distinct().Count() != корпуса.Count)
            throw new InvalidDataException("мир.json: у промзоны нужны корпуса с разными номерами");
        if (корпуса.Any(к => (к.записка is null) != (к.узнаёшь is null)))
            throw new InvalidDataException("мир.json: записка в корпусе — вместе с тем, что из неё узнаёшь");
        return new ДанныеВектора(в.GetProperty("имя").GetString()!, в.GetProperty("задеть").GetDouble(), корпуса);
    }
}

/// <summary>Чем кончился обыск корпуса.</summary>
public sealed record ОбыскКорпуса(
    Корпус корпус,
    Словарь<string, double> нашёл,
    Словарь<string, double> унёс,
    bool задело,
    bool обшарен,
    string? записка,
    string? узнал);

public sealed class Вектор
{
    public ДанныеВектора данные { get; }
    private readonly long _зерно;
    private readonly SortedSet<int> _обшарены = new();

    public Вектор(ДанныеВектора д, long зерно)
    {
        данные = д;
        _зерно = зерно;
    }

    public Корпус? Корпус_(int номер) => данные.корпуса.FirstOrDefault(к => к.номер == номер);

    /// <summary>Обшарен ли корпус в этой жизни.</summary>
    public bool Обшарен(int номер) => _обшарены.Contains(номер);

    public IReadOnlyCollection<int> обшарены => _обшарены;

    /// <summary>Сколько часов на месте хотя бы на один корпус.</summary>
    public double часов_меньше_всего => данные.корпуса.Min(к => к.часов);

    /// <summary>
    /// Обыскать корпус: часы уже ушли делом. Находка — по таблице корпуса
    /// бросками от зерна, в тару (что не влезло — там и осталось, и корпус
    /// всё равно обшарен). Опасный корпус задевает с шансом «задеть».
    /// Записка — знание в округу. Обшаренный — пуст, но задеть может и там:
    /// воздух тот же.
    /// </summary>
    public ОбыскКорпуса Обыскать(House h, NPC я, int номер, Округа о, РучкиПетли ручки)
    {
        var к = Корпус_(номер) ?? throw new ArgumentException($"корпуса {номер} нет");
        var нашёл = Словари.Числа();
        var унёс = Словари.Числа();
        bool был = !_обшарены.Add(номер);
        string? узнал = null;
        if (!был)
        {
            int i = 0;
            foreach (var (что, (от, до)) in к.находка.OrderBy(п => п.Key, StringComparer.Ordinal))
            {
                double сколько = от + Math.Floor(
                    Округа.Бросок(_зерно, $"корпус{номер}_{i++}", я.id, h.day) * (до - от + 1));
                if (сколько > 0)
                    нашёл[что] = сколько;
            }
            if (нашёл.Ключи.Count > 0)
            {
                я.ноша ??= new Ноша();
                унёс = я.ноша.Положить(я.ноша.тара ?? Тара.РЮКЗАК, нашёл, ручки);
                foreach (var р in унёс.Ключи)
                    h.stats["принесено_" + р] = h.stats.Взять("принесено_" + р, 0.0) + унёс[р];
            }
            if (к.узнаёшь is string что_узнал && !о.Знает(что_узнал))
            {
                о.Узнал(что_узнал);
                узнал = что_узнал;
            }
        }
        bool задело = к.опасен
                      && Округа.Бросок(_зерно, $"задело{номер}", я.id, h.day) < данные.задеть
                      && о.заражение.Задеть(я.id, h.day);
        return new ОбыскКорпуса(к, нашёл, унёс, задело, был, был ? null : к.записка, узнал);
    }

    // ------------------------------------------------------------ сохранение игры

    public System.Text.Json.Nodes.JsonObject Сложить() => new()
    {
        ["обшарены"] = new System.Text.Json.Nodes.JsonArray(_обшарены.Select(н => (System.Text.Json.Nodes.JsonNode?)н).ToArray()),
    };

    public void Разложить(System.Text.Json.Nodes.JsonObject о)
    {
        _обшарены.Clear();
        foreach (var x in о["обшарены"]!.AsArray())
            _обшарены.Add(x!.GetValue<int>());
    }
}
