// Вопрос игроку как данные, а не как готовый текст.
//
// До этого шов отдавал человеку строку и список строк: консоли этого хватало,
// потому что она их и печатает. Экрану — нет. Экрану нужно, какой это вопрос
// (член перечисления, а не слово), какие варианты (что именно выбирается,
// а не как оно подписано), сколько каждый весит и почему.
//
// Поэтому `Человек` теперь строит одну запись — `ВопросИгроку` — и отдаёт её
// тому, кто спрашивает. Строчный вид остался ровно тем же и делается из этой
// же записи: консоль печатает `заголовок` и `строки`, и стенограмма обязана
// совпасть знак в знак с прототипом (проверка «консоль» и тридцать дней
// приёмки этапа 2 — про это).
//
// Запись живёт в ядре, а не в `Дом.Вид`, по той же причине, по какой шов
// живёт в ядре: правило одно для всех (ГДД 13). Вопрос — это то, что дом
// спрашивает у жильца; экран лишь его показывает.

namespace Дом.Ядро;

/// <summary>
/// Один вариант в вопросе игроку.
///
/// <c>что</c> — то самое значение, которое вернётся решающему: пара
/// «действие и цель» для дня, вид ночи с целью для ночи, строка для ответа
/// и выбора. Экран его не разбирает и не подменяет — он его показывает
/// и возвращает обратно.
/// </summary>
public sealed record ВариантИгроку(
    object? что,
    double вес,
    string строка)              // как эту строку печатает консоль
{
    /// <summary>Ключ действия, если это вопрос дня: чем экран может
    /// выбрать значок. Для прочих вопросов — сам ответ строкой.</summary>
    public string ключ => что switch
    {
        ValueTuple<string, object?> п => п.Item1,
        string с => с,
        _ => "",
    };

    /// <summary>Кого или что этот вариант касается: жилец, квартира,
    /// кладовка, место вылазки. Экран подсвечивает по нему план подъезда.</summary>
    public object? цель => что is ValueTuple<string, object?> п ? п.Item2 : null;
}

/// <summary>
/// Вопрос, заданный человеку: всё, что нужно и консоли, и экрану.
///
/// Варианты идут <b>в порядке убывания веса</b> — в том самом, в котором
/// их печатает консоль и по которому игрок отвечает номером. Порядок здесь
/// часть договора: экран не вправе пересортировать список, иначе номер
/// перестанет значить то же самое (навык godot-boundary — «не решает
/// за игрока, не фильтрует варианты, не сортирует их иначе»).
/// </summary>
public sealed record ВопросИгроку(
    int день,
    string кто,                 // id жильца, а не сам жилец: запись переживает смерть и сейв
    Вопрос вопрос,
    string заголовок,           // «день 3, Оксана: что делать» плюс хвосты
    IReadOnlyList<ВариантИгроку> варианты,
    Самочувствие? самочувствие,
    Корзина? корзина)
{
    /// <summary>Строки вариантов — то, что консоль печатает нумерованным
    /// списком.</summary>
    public List<string> строки => варианты.Select(в => в.строка).ToList();

    /// <summary>Ответ по номеру, с тем же зажимом в границы, что был в шве:
    /// мимо списка — ближайший край, а не исключение.</summary>
    public object? Ответ(int номер)
        => варианты.Count == 0
           ? null
           : варианты[Math.Max(0, Math.Min(номер, варианты.Count - 1))].что;
}
