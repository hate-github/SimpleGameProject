// Перенос house/meeting.py — пока только то, без чего не считается сбор:
// оценка собрания и её слагаемые.
//
// Само собрание (кто вышел, о чём говорили, чем кончилось) переезжает
// на этапе 1д. `оценка` приехала раньше потому, что её зовёт раздел `_себя`:
// «позвать дом на площадку» — такой же вариант хода, как любой другой.

namespace Дом.Ядро;

public static class Площадка
{
    /// <summary>
    /// Тот, про кого дом уже всё узнал и ещё не решил. Момент проходит: если
    /// за несколько дней не собрались, дальше живут как жили.
    /// </summary>
    public static NPC? ждут_приговора(House h)
    {
        var з = h.приговор_нужен;
        if (з is null)
            return null;
        if (h.day - з.день > h.B["приговор_срок"])
        {
            h.приговор_нужен = null;
            return null;
        }
        var кого = h.живой(з.кто);
        if (кого is null)
        {
            h.приговор_нужен = null;
            return null;
        }
        return кого;
    }

    /// <summary>Тот, о ком в доме уже всё известно: людоед или пойманный
    /// дважды вор.</summary>
    public static (NPC? кто, double вес) приговорённый(House h, NPC npc)
    {
        NPC? худший = null;
        double вес = 0.0;
        var ждут = ждут_приговора(h);
        foreach (var p in h.others(npc))
        {
            double w = 0.0;
            if (p.раскрыт)
                w += 3.0;
            w += Math.Max(0.0, p.поймали - 1) * 1.5;
            w += p.под_подозрением * 1.5;
            if (ReferenceEquals(ждут, p))
                w += 3.0;              // дом уже узнал и ждёт решения
            w += npc.hate.Взять(p.id, 0.0) / 60.0;
            if (w > вес)
            {
                худший = p;
                вес = w;
            }
        }
        return вес >= h.B["собрание_приговор_порог"] ? (худший, вес) : (null, 0.0);
    }

    /// <summary>Кому из них хуже всего со своим теплом и у кого лучше всего
    /// печка.</summary>
    public static (NPC? греет, List<(NPC, double)> мёрзнут) холоднее_всех(
        House h, IReadOnlyList<NPC> участники)
    {
        NPC? греет = null;
        var мёрзнут = new List<(NPC, double)>();
        double лучшее = -99.0;
        foreach (var p in участники)
        {
            double своя = h.flat_temp(h.flats[p.apt], burning: true, powered: h.power_on);
            double если_топит = h.flat_temp(h.flats[p.apt],
                burning: Социальное.своя_топится(h, p), powered: h.power_on);
            if (своя > лучшее && h.flats[p.apt].shelter.Взять("буржуйка", 0.0) != 0.0)
            {
                греет = p;
                лучшее = своя;
            }
            мёрзнут.Add((p, если_топит));
        }
        return (греет, мёрзнут);
    }

    /// <summary>Что этому человеку есть смысл выносить на площадку.</summary>
    public static List<(string тема, double острота)> темы(House h, NPC npc)
    {
        var b = h.B;
        var @out = new List<(string, double)>();
        var живые = h.alive();

        // общее дежурство: после того, как в доме уже что-то случилось
        double остро = Социальное.recent_incidents(h, 6) * 1.2 + npc.panic / 30.0
                       + npc.обокрали * 1.2 - 1.0;
        @out.Add(("дежурство", остро));

        // общий котёл: топить одну квартиру вместо пятнадцати
        var (греет, мёрзнут) = холоднее_всех(h, живые);
        if (греет is not null)
        {
            // смотрят не только на сегодня: метель с каждым днём злее.
            // Иначе дом складывается в один котёл на двадцатый день,
            // когда греть уже некого
            double вперёд = b["температура_падение_в_день"] * b["собрание_котёл_вперёд"];
            double холод = Util.Sum(мёрзнут.Select(
                п => Math.Max(0.0, b["комфортная_температура"] - п.Item2 + вперёд)));
            @out.Add(("котёл", холод * b["собрание_котёл_вес"] - 1.0));
        }

        // приговор: выгнать вора или людоеда — решением людей, а не автоматом
        var (кого, вес) = приговорённый(h, npc);
        if (кого is not null)
            @out.Add(("приговор", вес * 1.6));

        // разделить пустую квартиру: кто занимает, кто разбирает
        if (h.пустые().Count > 0)
        {
            double нужда = 0.0;
            var своя = h.flats[npc.apt];
            foreach (var f in h.пустые())
                нужда = Math.Max(нужда,
                    h.ценность_жилья(f, npc) - h.ценность_жилья(своя, npc));
            // у скольких, по его сведениям, нет досок: чужой шкаф он не видит,
            // а оценку имеет
            нужда += Util.Sum(живые.Where(p => npc.believed(p.id, "материалы") < 2)
                                   .Select(_ => 1.0));
            @out.Add(("квартира", нужда * 0.9 - 0.5));
        }

        // не пускать чужих: общее дело, и повод для него приходит с улицы
        double порыв = h.day - h.календарь.укрепление_порыв <= 3 ? 1.0 : 0.0;
        if (h.day - h.календарь.подъезд_заколочен > b["дверь_подъезда_дней"])
            @out.Add(("дверь_подъезда", порыв * 4.5 + npc.panic / 25.0 - 1.2));
        return @out;
    }

    /// <summary>
    /// Насколько эти люди готовы сорваться на крик вместо разговора. Злость
    /// берётся средняя по парам, а не самая громкая: один заклятый враг
    /// в доме есть всегда, и по нему собрание не судят.
    /// </summary>
    public static double жар_ссоры(House h, IReadOnlyList<NPC> люди)
    {
        var кто = люди.Where(p => p.здесь()).ToList();
        var пары = new List<double>();
        foreach (var a in кто)
            foreach (var c in кто)
                if (!string.Equals(a.id, c.id, StringComparison.Ordinal))
                    пары.Add(a.hate.Взять(c.id, 0.0));   // правда: видно: на лестнице кричат, и слышно это всем
        if (пары.Count == 0)
            return 0.0;
        double злость = Util.Sum(пары) / пары.Count / 100.0;
        double жар = злость * 2.0
                     + Util.Sum(кто.Select(p => p.t01("вспыльчивость"))) / кто.Count * 0.7;
        return жар * (1.0 + (1.0 - Util.Sum(кто.Select(p => p.normalcy)) / кто.Count));  // правда: видно: по человеку видно, что он поплыл
    }

    /// <summary>
    /// Насколько, по его собственному счёту, дом его послушает. Не среднее
    /// чужое доверие — чужих мыслей не видно, — а среднее из того, что он
    /// знает сам о каждом.
    /// </summary>
    public static double доверие_дома(House h, NPC npc)
    {
        var другие = h.others(npc);
        if (другие.Count == 0)
            return 0.0;
        return Util.Sum(другие.Select(o => npc.расположение_ко_мне(o.id))) / другие.Count;
    }

    /// <summary>Насколько этому человеку сейчас хочется собрать дом.
    /// 0 — незачем.</summary>
    public static double оценка(House h, NPC npc)
    {
        var b = h.B;
        if (h.alive().Count < b["собрание_минимум"])
            return 0.0;
        if (h.day - h.календарь.последнее_собрание < b["собрание_перерыв"])
            return 0.0;
        double порог = b["собрание_доверие"];
        if (ждут_приговора(h) is not null)
            // когда дом ждёт решения про своего, зовут не по любви к зовущему
            порог -= b["собрание_доверие_приговор"];
        if (доверие_дома(h, npc) < порог)
            return 0.0;
        double острота = 0.0;
        bool есть = false;
        foreach (var (_, о) in темы(h, npc))
        {
            if (!есть || о > острота)
                острота = о;
            есть = true;
        }
        if (!есть || острота <= 0)
            return 0.0;
        // и то, чего у зовущего не было вовсе: понимание, что дом на взводе.
        // 70 % собраний срывались в крик, а после срыва дом хуже, чем до, —
        // то есть позвать было ошибкой, которую человек не мог предвидеть
        double рискованно = жар_ссоры(h, h.alive()) * b["собрание_вес_напряжения"];
        // смелый и общительный зовут и на взводе: им кажется, что они
        // справятся, и половину времени они правы
        рискованно *= Util.Clamp(1.4 - npc.t01("храбрость") * 0.5
                                 - npc.t01("общительность") * 0.3, 0.3, 1.4);
        // общительный зовёт легче, замкнутый — только когда припёрло
        return острота + npc.t01("общительность") * 2.0 - npc.t01("жадность")
               - рискованно - b["собрание_решимость"];
    }

    /// <summary>Кто по расписанию должен не спать этой ночью. null —
    /// расписания нет.</summary>
    public static NPC? чья_ночь(House h)
    {
        var д = h.дежурство;
        if (д is null || h.day > д.до)
            return null;
        var очередь = д.очередь
            .Where(i => h.живой(i) is not null && h.get(i)!.dependents == 0).ToList();
        if (очередь.Count == 0)
            return null;
        return h.get(очередь[(h.day - д.начало) % очередь.Count]);
    }

    /// <summary>
    /// Утром: вышел ли вчерашний дежурный. Нарушивший виноват перед всеми.
    ///
    /// Это и есть разница между обещанием одному человеку и обязательством
    /// перед домом: за сорванную ночь злятся все, а не один сосед.
    /// </summary>
    public static void проверить_дежурство(House h)
    {
        var b = h.B;
        string? кто_id = h.ожидает.дежурил_вчера;
        h.ожидает.дежурил_вчера = null;
        if (string.IsNullOrEmpty(кто_id))
            return;
        var кто = h.живой(кто_id);
        if (кто is null)
            return;
        if (кто.дежурил_ночь == h.day - 1)
        {
            foreach (var p in h.others(кто))
                Социальное.adjust(p, кто.id, trust: b["дежурство_доверие"], hate: -3);
            h.bump("дежурств_по_расписанию");
            return;
        }
        foreach (var p in h.others(кто))
            Социальное.adjust(p, кто.id, trust: -b["дежурство_доверие"] * 1.5,
                              hate: b["дежурство_ненависть"]);
        h.bump("дежурство_нарушено");
        h.journal.line($"{кто.@short} {Util.Vb(кто.sex, "проспал")} свою ночь. "
                       + "Об этом сказали все и сразу.", 2);
    }
}
