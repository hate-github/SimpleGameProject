        new Место("двор и мусорки",      "во двор и по мусоркам", 0.6, 0.55, 0.35, 0.4, 1.00, 1.60, 0.15, false, "вылазка_двор", null),
        new Место("соседние подъезды",   "по соседним подъездам", 1.0, 1.00, 0.50, 1.0, 1.00, 1.10, 0.45, false, "вылазка_чужое", null),
        new Место("гаражи за домом",     "в гаражи за домом",     1.5, 1.50, 0.90, 1.5, 0.95, 0.85, 0.60, false, "вылазка_чужое", "гараж"),
        new Место("магазин на Заречной", "в магазин на Заречной", 2.1, 2.10, 1.40, 1.0, 0.00, 0.55, 2.00, true,  "вылазка",       null),
    };

    /// <summary>Стоит ли на этом месте чужой замок.</summary>
    public static bool чужое_место(Место м) => м.мерка == "вылазка_чужое";

    /// <summary>Сколько времени займёт спуск в погреб или ходка в гараж.</summary>
    public static double часы_кладовой(House h, Кладовая к)
    {
        double v = h.B.Таблица("кладовая_часы")[к.вид.Текст()];
        return v * (к.вид == ВидКладовой.ГАРАЖ ? погода_часы(h) : 1.0);
    }

    /// <summary>
    /// Можно ли этому человеку сегодня туда дойти. Погреб — внутри дома:
    /// ни мороз, ни буран, ни ребёнок на руках его не закрывают, и в этом вся
    /// его ценность. Гараж закрывается тем же, чем и вылазка.
    /// </summary>
    public static bool кладовая_доступна(House h, NPC npc, Кладовая к, double? часов = null)
    {
        if (часов is not null && часы_кладовой(h, к) > часов.Value + 0.001)
            return false;
        if (к.вид == ВидКладовой.ГАРАЖ)
        {
            if (npc.dependents != 0
                && h.B.Таблица("кладовая_часы")["гараж"] > h.B["ребёнок_предел_часов"])
                return false;
            if (h.outside <= npc.мороз_предел(h.B) || npc.warmth <= 32 || npc.health <= 45)
                return false;
        }
        return true;
    }

    /// <summary>Чужая ли это кладовка для него — и есть ли там ещё что брать.</summary>
    public static bool не_свой(House h, NPC npc, Кладовая к)
        => !h.есть_ключ(npc, к) && !к.пусто();

    /// <summary>Сорвать замок и вынести. Дольше, чем зайти своим ключом.</summary>
    public static double часы_вскрытия(House h, Кладовая к)
        => часы_кладовой(h, к) + h.B["кладовая_вскрытие_часы"];

    /// <summary>
    /// К какому чужому замку он пойдёт, если пойдёт. Выбирает по хозяину,
    /// а не по содержимому: что лежит за чужой дверью, человек не знает —
    /// он знает только, что дверь есть и чья она.
    /// </summary>
    public static Кладовая? чужая_кладовая(House h, NPC npc, double? часов = null)
    {
        Кладовая? лучшая = null;
        double? оценка = null;
        foreach (var к in h.кладовые.Значения.OrderBy(x => x.id, StringComparer.Ordinal))
        {
            if (!h.знает_кладовую(npc, к))
                continue;
            if (!не_свой(h, npc, к) || !кладовая_доступна(h, npc, к, часов))
                continue;
            if (часов is not null && часы_вскрытия(h, к) > часов.Value + 0.001)
                continue;
            var хозяин = h.хозяин_кладовой(к);
            double s = хозяин is not null ? npc.loot_value(хозяин.id) : 1.0;
            if (оценка is null || s > оценка)
            {
                лучшая = к;
                оценка = s;
            }
        }
        return лучшая;
    }

    /// <summary>
    /// Сорвать замок с чужой кладовки. Возвращает то, что вынес. Замок сорван,
    /// и с этого дня туда ходят все, кто знает: это важнее самой добычи —
    /// сорванный замок превращает частный запас в общий пирог.
    /// </summary>
    public static Словарь<string, double> вскрыть_кладовую(House h, NPC вор, Кладовая к,
                                                            bool вслух = true)
    {
        var b = h.B;
        bool впервые = !к.вскрыта;
        к.вскрыта = true;
        var хозяин = h.хозяин_кладовой(к);
        var got = Словари.Числа();
        foreach (var res in к.stock.Ключи.OrderBy(x => x, StringComparer.Ordinal))
        {
            double было = к.stock[res];
            double take = Math.Min(было, b["кладовая_за_раз"]);
            if (take > 0)
            {
                к.stock[res] = было - take;
                вор.stock[res] = вор.stock.Взять(res, 0.0) + take;
                got[res] = take;
            }
        }
        if (к.тулуп && вор.одежда < b["одежда_максимум"])
        {
            к.тулуп = false;
            вор.одежда = (int)b["одежда_максимум"];
            got["тулуп"] = 1;
        }
        var взял = Конфликт.подобрать_оружие(h, вор, к, вслух: вслух);
        if (взял is not null)
            got[взял] = 1;
        к.ходок += 1;
        if (впервые)
        {
            h.bump("вскрытых_кладовых");
            h.событие(ВидСобытия.ВСКРЫТИЕ, кто: вор.id, что: к.вид.Текст(), где: к.apt);
            h.bump("вскрыто_" + (вслух ? "умыслом" : "попутно"));
            if (!h.stats.Есть("первое_вскрытие"))
                h.stats["первое_вскрытие"] = h.day;
        }
        // у кладовки может быть живой хозяин — и тогда это не находка, а повод.
        // Узнаёт он не сразу: замок в подвале срывают тихо
        if (хозяин is not null && !string.Equals(хозяин.id, вор.id, StringComparison.Ordinal)
            && хозяин.ключи_кладовых.Contains(к.id))
            h.ожидает.вскрытые_кладовые.Add((вор.id, к.id));
        Социальное.переступил(h, вор, "вскрыть_кладовую");
        return got;
    }

    /// <summary>
    /// Понесёт ли человек это к себе в квартиру прямо сейчас. Из погреба
    /// не выгребают всё разом: наверху запас можно украсть, а внизу за замком
    /// он лежит. Оттого человек выглядит бедным в квартире, оставаясь богатым
    /// в подвале — и оттого же не делится.
    /// </summary>
    public static bool нужно_наверх(House h, NPC npc, string res, Баланс b)
    {
        double срок = Math.Min(Math.Max(4.0, npc.horizon), b["кладовая_поднимает_дней"]);
        if (res is "еда" or "вода")
            return npc.days_of(res) < срок;
        if (res == "топливо")
            return npc.топит_сам() && npc.days_of(res) < срок;
        if (res == "лекарства")
            return npc.stock.Взять(res, 0.0) < b["магазин_аптечка"];
        if (res == "материалы")
            return npc.stock.Взять(res, 0.0) < b["магазин_материалы"];
        if (res == "патроны")
            return Таблицы.ОГНЕСТРЕЛ.Contains(npc.weapon)
                   && npc.stock.Взять(res, 0.0) < b["магазин_патроны"];
        return npc.stock.Взять(res, 0.0) < 1.0;
    }

    /// <summary>
    /// Поднять из своего погреба или привезти из своего гаража. Не добыча,
    /// а перекладывание: эти банки лежали в доме с первого дня.
    /// </summary>
    public static void _из_кладовой(House h, NPC npc, Кладовая к, double dur)
    {
        var b = h.B;
        var got = Словари.Числа();
        foreach (var res in к.stock.Ключи.OrderBy(x => x, StringComparer.Ordinal))
        {
            double было = к.stock[res];
            if (!нужно_наверх(h, npc, res, b))
                continue;
            double take = Math.Min(было, b["кладовая_за_раз"]);
            if (take > 0)
            {
                к.stock[res] = было - take;
                npc.stock[res] = npc.stock.Взять(res, 0.0) + take;
                got[res] = take;
            }
        }
        // старый тулуп на гвозде и топор в углу — там же, где и всё остальное
        if (к.тулуп && npc.одежда < b["одежда_максимум"])
        {
            к.тулуп = false;
            npc.одежда = (int)b["одежда_максимум"];
            got["тулуп"] = 1;
            h.bump("тулупов_из_кладовой");
        }
        var взял = Конфликт.подобрать_оружие(h, npc, к);
        if (взял is not null)
            got[взял] = 1;
        к.ходок += 1;
        npc.rest = Util.Clamp(npc.rest - 2);
        h.bump("ходок_в_кладовую");
        h.bump("ходок_" + к.вид.Текст());

        string если = got.Count > 0
            ? string.Join(", ", got.Select(п => $"{п.Key} {Текст.G(п.Value)}"))
            : "пусто";
        // «свой» — только если кладовка приписана к его собственным стенам
        bool свой = к.apt == npc.apt;
        string чей = свой ? "в свой погреб"
            : (к.id != null && npc.ключи_кладовых.Contains(к.id)
                ? $"в погреб кв.{к.apt} — по чужому ключу"
                : $"в погреб кв.{к.apt} — тот, что вскрыли");
        string txt;
        if (к.вид == ВидКладовой.ПОГРЕБ)
            txt = $"{npc.@short} {Util.Vb(npc.sex, "спустился")} {чей}: {если}";
        else
        {
            // гараж — это улица со всем, что к ней прилагается
            double тепло_одежды = 1.0 - b["одежда_холод"] * npc.одежда;
            npc.warmth = Util.Clamp(npc.warmth - b["вылазка_холод_за_час"] * dur * тепло_одежды
                                    * (1.0 + Math.Max(0.0, -h.outside - 12) * 0.03));
            npc.день_вылазки = h.day;      // его видели с пакетами
            string куда = свой ? "в свой гараж"
                : (npc.ключи_кладовых.Contains(к.id)
                    ? $"в гараж кв.{к.apt} — по чужому ключу"
                    : $"в гараж кв.{к.apt} — тот, что вскрыли");
            txt = $"{npc.@short} {Util.Vb(npc.sex, "сходил")} {куда}: {если}";
            if (h.rng.Chance(b["вылазка_шанс_встречи"] * Мир.улица_злая(h)))
            {
                npc.panic = Util.Clamp(npc.panic + 8);
                txt += "; у гаражей кто-то ходил между рядами";
            }
            Социальное.emit(h, npc, 2, "возвращение", night: false);
        }
        h.journal.line(txt + ".", 1);
        // сосед ходит в подвал и возвращается не с пустыми руками — это и есть
        // та асимметрия, которую должно быть видно с лестницы
        if (got.Count > 0)
            foreach (var other in h.others(npc))
                if (h.rng.Chance(b["кладовая_заметность"]))
                {
                    Социальное.adjust(other, npc.id, aware: 10);
                    Социальное.note_signal(other, npc.id, "еда",
                        other.believed(npc.id, "еда") + got.Взять("еда", 0.0), 0.5);
                }
    }

    /// <summary>
    /// Сколько единиц человек вообще возьмёт отсюда сегодня. Не «сколько там
    /// лежит»: из погреба поднимают нужное, а не всё.
    /// </summary>
    public static double сколько_поднимет(House h, NPC npc, Кладовая к, Баланс b)
    {
        var части = new List<double>();
        foreach (var (res, было) in к.stock)   // правда: видно: своя кладовка — знает наизусть
            if (было > 0 && нужно_наверх(h, npc, res, b))
                части.Add(Math.Min(было, b["кладовая_за_раз"]));
        double v = Util.Sum(части);
        if (к.тулуп && npc.одежда < b["одежда_максимум"])
            v += 2.0;
        if (к.оружие.Count > 0)
        {
            double лучшее = к.оружие.Max(w => Таблицы.ОРУЖИЕ_ВЕС[w]);
            if (лучшее > Таблицы.ОРУЖИЕ_ВЕС[npc.weapon])
                v += 2.0;
        }
        return v;
    }

    /// <summary>
    /// В какую из своих кладовок он пойдёт: где нужнее и куда ближе. Свою
    /// человек знает наизусть — это единственное место в мире, о котором
    /// у него точные сведения.
    /// </summary>
    public static Кладовая? выбрать_кладовую(House h, NPC npc, double? часов = null)
    {
        Кладовая? лучшая = null;
        double оценка = 0.0;
        foreach (var к in h.мои_кладовые(npc))
        {
            if (к.пусто() || !кладовая_доступна(h, npc, к, часов))
                continue;
            double сколько = сколько_поднимет(h, npc, к, h.B);
            if (сколько <= 0)
                continue;                  // спускаться не за чем
            double s = сколько / (1.0 + часы_кладовой(h, к));
            if (s > оценка)
            {
                лучшая = к;
                оценка = s;
            }
        }
        return лучшая;
    }

    /// <summary>
    /// Чем этот человек может заплатить в магазине сегодня. Пока живы банки,
    /// карту принимают наравне с наличными; после — только то, что лежит дома.
    /// В этом вся разница между бумажными и цифровыми деньгами: бумажные
    /// можно украсть, но их нельзя отключить.
    /// </summary>
    public static double кошелёк(House h, NPC npc)
        => (h.банки ? npc.счёт : 0.0) + npc.stock.Взять("деньги", 0.0);

    /// <summary>
    /// Чего человеку не хватает — в том порядке, в каком он берёт это с полки.
    /// Возвращает список, а не одну позицию: человек, которому не хватило
    /// на банку тушёнки, не уходит из магазина ни с чем — он берёт воду.
    /// </summary>
    public static List<string> _что_купить(House h, NPC npc)
    {
        var b = h.B;
        double горизонт = Math.Max(4.0, npc.horizon);
        var хочу = new List<(double вес, string res)>();
        foreach (var res in new[] { "еда", "вода" })
            if (npc.days_of(res) < горизонт)
                хочу.Add((npc.days_of(res) / горизонт, res));
        if (npc.топит_сам() && npc.days_of("топливо") < горизонт)
        {
            // без печки дрова покупают неохотно: жечь их пока не в чем
            double штраф = npc.shelter.Взять("буржуйка", 0.0) != 0.0 ? 0.0 : 0.4;
            хочу.Add((npc.days_of("топливо") / горизонт + штраф, "топливо"));
        }
        if (npc.stock.Взять("лекарства", 0.0) < b["магазин_аптечка"])
            хочу.Add((0.6, "лекарства"));
        if (npc.stock.Взять("материалы", 0.0) < b["магазин_материалы"])
            хочу.Add((0.7, "материалы"));
        // патроны берёт только тот, кому есть чем стрелять
        if (Таблицы.ОГНЕСТРЕЛ.Contains(npc.weapon)
            && npc.stock.Взять("патроны", 0.0) < b["магазин_патроны"])
            хочу.Add((0.65, "патроны"));
        // sorted() в Python сравнивает кортежи: сперва вес, при равенстве — имя
        return хочу.OrderBy(x => x.вес).ThenBy(x => x.res, StringComparer.Ordinal)
                   .Select(x => x.res).ToList();
    }

    /// <summary>
    /// Магазин, пока он работает (GDD 18): не находят, а покупают. Возвращает
    /// (что взято, сколько ушло с карты, сколько наличными).
    /// </summary>
    public static (Словарь<string, double> got, double картой, double налом)
        _купить(House h, NPC npc, Место м)
    {
        var b = h.B;
        double осталось = h.богатство_места(м.имя);
        double наценка = 1.0 + b["магазин_наценка_в_день"] * (h.day - 1);
        var цены = b.Таблица("магазин_цена");
        double карта = h.банки ? npc.счёт : 0.0;
        double наличные = npc.stock.Взять("деньги", 0.0);
        double потолок = b["магазин_унос_макс"] * осталось;
        var got = Словари.Числа();
        double картой = 0.0, налом = 0.0;

        // Сначала карта, потом бумага: наличные берегут — их примут и завтра
        bool Платим(double цена)
        {
            цена = Math.Round(цена, 2);    // цены в копейках, чтобы деньги не крошились
            if (цена > карта + наличные + 1e-9)
                return false;
            double с_карты = Math.Min(карта, цена);
            карта -= с_карты;
            картой += с_карты;
            наличные -= цена - с_карты;
            налом += цена - с_карты;
            return true;
        }

        while (Util.Sum(got.Where(п => п.Key != "тулуп").Select(п => п.Value)) < потолок)
        {
            // берёт самое нужное, на что хватает: не хватило на банку — взял воду
            string? res = null;
            foreach (var r in _что_купить(h, npc))
                if (цены[r] * наценка <= карта + наличные + 1e-9)
                {
                    res = r;
                    break;
                }
            if (res is null || !Платим(цены[res] * наценка))
                break;
            got[res] = got.Взять(res, 0.0) + 1;
            npc.stock[res] = npc.stock.Взять(res, 0.0) + 1;
            h.stats["принесено_" + res] = h.stats.Взять("принесено_" + res, 0.0) + 1;
        }
        // тулуп с вешалки у входа: дорого, но это ещё неделя открытой улицы
        if (потолок >= 1.0 && npc.одежда < b["одежда_максимум"]
            && Платим(b["магазин_цена_тулупа"] * наценка))
        {
            npc.одежда = (int)b["одежда_максимум"];
            got["тулуп"] = 1;
            h.bump("тулупов_куплено");
        }

        npc.счёт = Math.Max(0.0, npc.счёт - картой);
        if (npc.счёт < 0.005)
            npc.счёт = 0.0;               // остаток меньше пятака — это уже не деньги
        if (налом > 0)
            Ресурсы.Spend(h, npc, "деньги", налом);
        h.stats["потрачено_картой"] = h.stats.Взять("потрачено_картой", 0.0) + картой;
        h.stats["потрачено_налом"] = h.stats.Взять("потрачено_налом", 0.0) + налом;
        return (got, картой, налом);
    }

    /// <summary>
    /// Множитель ко времени вылазки: в затишье дорога легче, по снегу —
    /// дольше. Дальние места закрываются сами собой — не потому, что туда
    /// нельзя, а потому, что до вечера не успеть.
    /// </summary>
    public static double погода_часы(House h)
    {
        double k = h.режим == Режим.ЗАТИШЬЕ ? h.B["затишье_часы"] : 1.0;
        return k * (1.0 + h.снег * h.B["снег_дорога"]);
    }

    /// <summary>Сколько времени займёт самая короткая ходка в это место.</summary>
    public static double минимум_часов(House h, Место м)
    {
        if (м.магазин && h.магазины)
            return h.B["магазин_часы_дороги"] * погода_часы(h);
        return h.B["вылазка_часы_мин"] * м.часы * погода_часы(h);
    }

    /// <summary>
    /// Можно ли этому человеку сегодня дойти до этого места. Два предела,
    /// и оба жёсткие: ребёнок на руках и остаток дня.
    /// </summary>
    public static bool место_доступно(House h, NPC npc, Место м, double? часов = null)
    {
        if (npc.dependents != 0 && м.часы > h.B["ребёнок_предел_часов"])
            return false;
        // в работающий магазин с пустым кошельком не ходят: там витрина,
        // а взять нельзя, и человек это знает, не выходя из подъезда
        if (м.магазин && h.магазины)
        {
            var нужное = _что_купить(h, npc);
            if (нужное.Count == 0)
                return false;
            double наценка = 1.0 + h.B["магазин_наценка_в_день"] * (h.day - 1);
            double дешёвое = нужное.Min(r => h.B.Таблица("магазин_цена")[r]);
            if (кошелёк(h, npc) < дешёвое * наценка)
                return false;
        }
        if (часов is not null && минимум_часов(h, м) > часов.Value + 0.001)
            return false;
        return true;
    }

    /// <summary>
    /// Чего это место стоит вот этому человеку — по его сведениям. Отдельно
    /// от выбора, потому что спрашивают дважды: сначала «стоит ли вообще
    /// выходить», потом «куда».
    /// </summary>
    public static double оценка_места(House h, NPC npc, Место м)
    {
        var b = h.B;
        double богатство = м.богатство;
        if (м.магазин && h.магазины)
            // пока в магазине продают, а не берут, богатство полки решает
            // меньше, чем кошелёк
            богатство *= Util.Clamp(кошелёк(h, npc) / b["магазин_кошелёк_норма"], 0.0, 1.0);
        double s = богатство * npc.знаю_место(м.имя)
                   * (1.0 + npc.desperation() * b["вылазка_дальше_за_нужду"]);
        // человек боится обеих опасностей сразу: и дороги, и тех, кого встретит
        s -= (м.дорога + м.угроза) * (b["вылазка_осторожность"] * (1.4 - npc.t01("храбрость")));
        // а мороз пугает только длинной дорогой
        s -= м.дорога * Math.Max(0.0, -h.outside - 18) * 0.15;
        s -= npc.dependents != 0 ? м.часы * 0.25 : 0.0;
        // рыться в мусорках, пока за углом магазин, — поступок из другой жизни
        s -= м.дичь * npc.normalcy * b["вылазка_дичь_вес"];
        return s;
    }

    /// <summary>
    /// Куда пойти: смелость и нужда толкают дальше, мороз и раны — ближе.
    /// Возвращает null, если идти сегодня некуда, — и тогда варианта «вылазка»
    /// просто не будет.
    /// </summary>
    public static Место? выбрать_место(House h, NPC npc, double? часов = null,
                                       bool без_магазина = false)
    {
        Место? лучшее = null;
        double? оценка = null;
        foreach (var м in МЕСТА)
        {
            if (без_магазина && м.магазин)
                continue;
            if (!место_доступно(h, npc, м, часов))
                continue;
            double s = оценка_места(h, npc, м);
            if (оценка is null || s > оценка)
            {
                лучшее = м;
                оценка = s;
            }
        }
        return лучшее;
    }
}

/// <summary>Форматирование чисел так, как их печатает Python.</summary>
public static class Текст
{
    /// <summary>`{v:g}` — «3», «0.5», «1.25».</summary>
    public static string G(double v)
        => v.ToString("G6", System.Globalization.CultureInfo.InvariantCulture);
}
