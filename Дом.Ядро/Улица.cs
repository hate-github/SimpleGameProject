/// <summary>
/// GDD 20: «выбор ведёт в отдельную небольшую локацию». Отдельных локаций
/// в прототипе нет, но выбор «ближе и беднее или дальше и опаснее» — есть,
/// и именно он и был главным, чего вылазке не хватало.
/// </summary>
public sealed record Место(
    string имя, string куда, double часы, double богатство, double дорога,
    double угроза, double дичь, double карман, double район, bool магазин,
    string мерка, string? кладовки);

public static partial class Улица
{
    // «дичь» — насколько дико туда идти, пока жизнь ещё похожа на прежнюю.
    // Истощение считается дважды: «карман» — как быстро место кончается
    // от СВОИХ рук, «район» — сколько за день уносят чужие. Отсюда порядок
    // вылазок: сначала кончается богатое и общее, последним — бедное и своё.
    //
    // Опасность тоже не одна: «дорога» — лёд, темнота и расстояние (от неё
    // ломают ногу), «угроза» — люди (от них отнимают пакет). Пока это было
    // одним числом, магазин на Заречной оказывался самым опасным местом
    // в мире просто потому, что он дальше всех.
    public static readonly IReadOnlyList<Место> МЕСТА = new[]
