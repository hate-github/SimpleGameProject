// Перенос house/street.py, `_outing`: сама вылазка (GDD 20).
//
// Единственный источник новых ресурсов. Место и время дороги решены до выхода,
// вместе с самим решением выйти, и приходят сюда готовыми.

namespace Дом.Ядро;

public static partial class Улица
{
    /// <summary>
    /// Вылазка. <paramref name="спутник"/> — второй, который согласился пойти.
    /// Тогда это не два выхода, а один: место вычерпывается один раз, добыча
    /// делится по тому, кто сколько донёс, во дворе не подходят к двоим,
    /// а сломанную ногу доводят до дома. Единственное место в модели, где дело
    /// делают вдвоём.
    /// </summary>
    public static void _outing(House h, NPC npc, double dur, Место м, NPC? спутник = null)
    {
        h.hooks.Зов_outing(h, npc, dur, м, спутник);
        Вылазка(h, npc, dur, м, спутник);
        h.hooks.Зов_после_outing(h, npc, dur, м, спутник);
    }

    private static void Вылазка(House h, NPC npc, double dur, Место м, NPC? спутник)
    {
        var b = h.B;
        npc.away = true;
        bool вдвоём = спутник is not null;
        if (вдвоём)
            спутник!.away = true;
        var ходоки = вдвоём ? new List<NPC> { npc, спутник! } : new List<NPC> { npc };

        // чем человек несёт: целостью, силой и тем, что на нём надето. Хромой
        // с перебитой рукой донесёт меньше, и добыча разойдётся по рукам сама
        static double Ноша(NPC x)
        {
            double n = 0.5 + x.health / 100.0 + x.одежда * 0.25;
            return Math.Max(0.25, n * Math.Max(0.35, 1.0 - 0.25 * x.injuries.Count));
        }
        double доля_ноши = вдвоём ? Ноша(npc) / (Ноша(npc) + Ноша(спутник!)) : 1.0;
        string место = м.имя;
        double богатство_к = м.богатство;
        // люди — одно, лёд и темнота — другое, и считаются они врозь
        double danger = Мир.outing_danger(h) * м.угроза;
        double осталось = h.богатство_места(место);

        // чужой замок — свой поступок, и человек засчитывает его себе сам.
        // Дом при этом ничего не видит: слышно только «вернулся с пакетами»,
        // а куда он ходил, не видел никто
        if (чужое_место(м))
        {
            Социальное.переступил(h, npc, "вылазка_чужое");
            h.bump("вылазок_в_чужое");
            if (вдвоём)
                // позвавший привёл второго к чужому замку, и это поступок обоих
                Социальное.переступил(h, спутник!, "вылазка_чужое");
        }

        bool покупка = м.магазин && h.магазины;
        double картой = 0.0, налом = 0.0;
        Словарь<string, double> got;
        if (покупка)
            (got, картой, налом) = _купить(h, npc, м);
        else
        {
            // сколько ходил — столько и принёс. Раньше часы и добыча бросались
            // независимо, и выходило, что один ходил четырнадцать часов ради
            // трёх банок, а другой за девять приносил девять
            double ожидаемо = (b["вылазка_часы_мин"] + b["вылазка_часы_макс"]) / 2.0
                              * м.часы * погода_часы(h);
            double за_время = Util.Clamp(dur / Math.Max(0.5, ожидаемо), 0.45, 1.6);
            double take = b["вылазка_добыча_база"] * богатство_к * осталось * h.scav_richness
                          * за_время * h.rng.Uni(0.65, 1.25);
            take *= 0.8 + ходоки.Max(x => x.t01("храбрость")) * 0.5;
            // вдвоём выносят больше, чем один, но меньше, чем два по отдельности:
            // руки лишние, а место одно, и вычерпывается оно тоже один раз
            if (вдвоём)
                take *= b["вдвоём_добыча"];
            // в затишье не только легче идти, но и больше видно под снегом
            if (h.режим == Режим.ЗАТИШЬЕ)
                take *= b["затишье_добыча"];
            // охотник умеет ходить по зимнему лесу и знает, где смотреть
            if (npc.skills.Contains("охотник", StringComparer.Ordinal))
                take *= 1.0 + b["охотник_добыча"];
            got = Словари.Числа();
            // что человек подберёт, зависит и от того, что ему пригодится.
            // Пачку патронов, из которых нечем стрелять, безоружный возьмёт —
            // но не вместо банки
            var состав = new List<(string, double)>();
            foreach (var (r, w) in b.Таблица("вылазка_состав"))
                состав.Add((r, w * (r == "патроны"
                    && !Таблицы.ОГНЕСТРЕЛ.Contains(npc.weapon)
                        ? b["патроны_безоружному"] : 1.0)));
            int сколько_раз = (int)take + (h.rng.Chance(take % 1) ? 1 : 0);
            for (int i = 0; i < сколько_раз; i++)
            {
                string res = h.rng.Weighted(состав)!;
                got[res] = got.Взять(res, 0.0) + 1;
                // делится не поровну, а по тому, кто сколько донёс: целый
                // и сильный берёт больше, хромой — меньше
                var кому = !вдвоём || h.rng.Chance(доля_ноши) ? npc : спутник!;
                кому.stock[res] = кому.stock.Взять(res, 0.0) + 1;
                h.stats["принесено_" + res] = h.stats.Взять("принесено_" + res, 0.0) + 1;
            }
            // настоящая зимняя одежда — вещь, которую находят: тулуп с чужой
            // вешалки, армейский бушлат в гараже
            NPC мёрзнет = ходоки[0];
            foreach (var x in ходоки)
                if (x.одежда < мёрзнет.одежда)
                    мёрзнет = x;
            if (мёрзнет.одежда < b["одежда_максимум"]
                && h.rng.Chance(b["шанс_найти_тулуп"] * богатство_к))
            {
                мёрзнет.одежда = (int)b["одежда_максимум"];
                got["тулуп"] = 1;
                h.bump("тулупов_найдено");
            }
            // оружие в доме почти всё было в доме с первого дня. Улица даёт
            // мелочь и редко, и только там, где опаснее. Ружья на улице
            // не бывает: винтовка в этой игре одна
            if (h.rng.Chance(b["шанс_найти_оружие"] * м.угроза))
            {
                var пары = b.Таблица("улица_оружие").Select(п => (п.Key, п.Value)).ToList();
                string чем = h.rng.Weighted(пары)!;
                if (Конфликт.вооружиться(h, npc, чем, вслух: false) is not null)
                {
                    got[чем] = 1;
                    h.bump("оружия_найдено");
                }
            }
            // гаражи за домом — один ряд, и часть боксов в нём принадлежит
            // этому же подъезду. Рано или поздно сорванный замок оказывается
            // соседским, и вылазка «в никуда» превращается в повод с именем
            var свои = h.кладовые.Значения.OrderBy(x => x.id, StringComparer.Ordinal)
                .Where(к => м.кладовки is not null
                            && string.Equals(к.вид.Текст(), м.кладовки, StringComparison.Ordinal)
                            && не_свой(h, npc, к)).ToList();
            if (свои.Count > 0 && h.rng.Chance(b["гараж_попал_на_соседский"]))
            {
                var к = h.rng.Pick(свои)!;
                var взято = вскрыть_кладовую(h, npc, к, вслух: false);
                foreach (var (r, v) in взято)
                    got[r] = got.Взять(r, 0.0) + v;
            }
        }
        // вычерпывается именно это место, а не «район вообще»
        h.места[место] = Math.Max(b["вылазка_минимум_богатства"],
            осталось - b["вылазка_истощение_за_ход"] * м.карман
                       * (вдвоём ? b["вдвоём_истощение"] : 1.0));
        foreach (var x in ходоки)
            x.места[место] = h.места[место];    // сходил — знает точно
        // и заодно узнал, кто говорил, что тут пусто (GDD 14)
        if (h.места[место] > b["вылазка_пусто_порог"])
            foreach (var кто in h.others(npc))
                Социальное.проверить_ложь(h, кто, npc, "место", место);

        var отморозили = new List<NPC>();
        foreach (var x in ходоки)
        {
            double тепло_одежды = 1.0 - b["одежда_холод"] * x.одежда;
            x.warmth = Util.Clamp(x.warmth - b["вылазка_холод_за_час"] * dur * тепло_одежды
                                  * (1.0 + Math.Max(0.0, -h.outside - 12) * 0.03));
            // у самого порога куртка уже не держит: пальцы белеют за час
            if (h.outside < x.мороз_предел(b) + b["выход_на_грани"]
                && !x.hurt("обморож") && h.rng.Chance(b["обморожение_на_грани"]))
            {
                x.injuries.Add(h.rng.Pick(new[] { "обморожение рук", "обморожение ног" })!);
                x.health = Util.Clamp(x.health - h.rng.Uni(5, 12));
                отморозили.Add(x);
            }
            x.rest = Util.Clamp(x.rest - 6);
        }

        // пустое место — новость, которую в тот же вечер знает весь подъезд.
        // Без неё каждый узнавал бы про каждое место собственными ногами
        bool новость = h.места[место] <= b["вылазка_пусто_порог"]
                       && h.others(npc).Any(o => o.знаю_место(место) > b["вылазка_пусто_порог"]);
        if (новость)
            foreach (var o in h.others(npc))
                o.места[место] = h.места[место];

        string добыча = got.Count > 0
            ? string.Join(", ", got.Select(п => $"{п.Key} {Текст.G(п.Value)}"))
            : "пусто";
        string txt;
        if (покупка)
        {
            txt = $"{npc.@short} {Util.Vb(npc.sex, "отстоял")} очередь в магазине "
                  + $"на Заречной ({dur:F0} ч): ";
            if (got.Count > 0)
            {
                txt += добыча;
                var чем = new List<string>();
                if (картой != 0.0)
                    чем.Add($"картой {Текст.G(картой)}");
                if (налом != 0.0)
                    чем.Add($"налом {Текст.G(налом)}");
                txt += " — " + string.Join(", ", чем);
            }
            else if (кошелёк(h, npc) < 1.0)
                txt += "ни с чем: платить нечем";
            else
                txt += "пусто: на полках уже ничего";
        }
        else if (вдвоём)
            // кто кого позвал, сказано здесь же: отдельной строкой про сговор
            // это было бы два сообщения об одном и том же
            txt = $"{npc.@short} {Util.Vb(npc.sex, "позвал")} {спутник!.form("acc")} — "
                  + $"ходили вдвоём {м.куда} ({dur:F0} ч): " + добыча;
        else
            txt = $"{npc.@short} {Util.Vb(npc.sex, "ходил")} {м.куда} ({dur:F0} ч): " + добыча;
        foreach (var x in отморозили)
        {
            // имя ставится только когда их двое: в одиночной строке подлежащее
            // и так известно
            string кто = вдвоём ? $"{x.@short} " : "";
            txt += $"; {кто}{(x.sex == "ж" ? "отморозила" : "отморозил")} пальцы на таком морозе";
        }
        if (новость)
            txt += $"; {Util.Vb(npc.sex, "сказал")} потом, что туда больше незачем — всё вынесли";

        // ногу ломают не о людей, а о лёд под снегом в темноте
        foreach (var x in ходоки)
        {
            double hurt_risk = b["вылазка_шанс_травмы"] * м.дорога * Мир.дорожные_условия(h);
            if (x.skills.Contains("охотник", StringComparer.Ordinal))
                hurt_risk *= b["охотник_травма"];
            if (h.rng.Chance(hurt_risk))
            {
                string inj = h.rng.Pick(new[]
                    { "ушиб ноги", "порез руки", "перелом ноги", "ушиб руки" })!;
                x.injuries.Add(inj);
                // сломанную ногу вдвоём доводят до дома: та же травма,
                // но за ней не полдня на льду
                double урон = h.rng.Uni(8, 20) * (вдвоём ? b["вдвоём_травма_урон"] : 1.0);
                x.health = Util.Clamp(x.health - урон);
                h.bump("травм_на_вылазке");
                if (вдвоём)
                {
                    var второй = ReferenceEquals(x, npc) ? спутник! : npc;
                    txt += $"; {x.@short} {Util.Vb(x.sex, "вернулся")} с травмой ({inj}), "
                           + $"{второй.@short} {Util.Vb(второй.sex, "дотащил")}";
                }
                else
                    txt += $"; {Util.Vb(x.sex, "вернулся")} с травмой ({inj})";
            }
        }
        if (h.rng.Chance(b["вылазка_шанс_встречи"] * danger * Мир.улица_злая(h)))
        {
            h.bump("встреч_на_вылазке");
            // к двоим во дворе не подходят. Это и есть главное, ради чего
            // зовут с собой: не добыча, а то, что её не отнимут
            bool отнимут = h.rng.Chance(0.5)
                           && !(вдвоём && h.rng.Chance(b["вдвоём_отпугнули"]));
            if (отнимут)
            {
                var lost = npc.stock.Where(п => п.Value > 0).Select(п => п.Key).ToList();
                string? res = lost.Count > 0 ? h.rng.Pick(lost) : null;
                if (res is not null)
                {
                    double had = npc.stock[res];
                    npc.stock[res] = Math.Max(0, had - h.rng.Rint(1, 2));
                    // это единственное место, где ресурс уходит из мира
                    // насовсем; без счётчика баланс дома не сходится
                    h.stats["потеряно_" + res] = h.stats.Взять("потеряно_" + res, 0.0)
                                                 + (had - npc.stock[res]);
                }
                foreach (var x in ходоки)
                    x.panic = Util.Clamp(x.panic + 15);
                h.bump(вдвоём ? "отнято_во_дворе_вдвоём" : "отнято_во_дворе");
                txt += "; во дворе отняли часть добычи";
            }
            else
            {
                foreach (var x in ходоки)
                    x.panic = Util.Clamp(x.panic + 8);
                txt += вдвоём ? "; во дворе к ним приглядывались, но не подошли"
                              : "; на обратном пути кто-то шёл следом";
            }
        }

        // квартира стоит пустой, пока хозяин не вернулся к своему следующему
        // делу: `away` снимается не здесь, иначе «пока хозяина нет»
        // не видит никто и дневная кража недостижима (GDD 12.5)
        foreach (var x in ходоки)
            x.день_вылазки = h.day;     // его видели с пакетами
        h.journal.line(txt, 1);
        // возвращение с пакетами видно всем (GDD 13)
        Социальное.emit(h, npc, 2, "возвращение", night: false);
        if (вдвоём)
        {
            // у этого события нет зрителей: есть двое, полдня на льду и то,
            // что они принесли домой вместе
            Социальное.сблизились(h, npc, спутник, b["близость_за_вылазку"]);
            // и доверие — тоже, и вот это в модели ново. Здесь свидетелей нет:
            // то, каким он оказался на льду, знает один человек в доме
            foreach (var (a, c) in new[] { (npc, спутник!), (спутник!, npc) })
            {
                Социальное.adjust(a, c.id, trust: b["доверие_за_вылазку"], hate: -4.0);
                a.mood = Util.Clamp(a.mood + 4);
            }
            h.bump("вылазок_вдвоём");
        }
        if (got.Count > 0)
            foreach (var x in ходоки)
                foreach (var other in h.others(x))
                    if (h.rng.Chance(0.35 + 0.1 * (2 - Math.Min(2, h.floor_gap(x, other)))))
                    {
                        Социальное.adjust(other, x.id, aware: 14);
                        // с пакетами видели обоих, но у каждого свой пакет
                        double доля = ReferenceEquals(x, npc) ? доля_ноши : 1.0 - доля_ноши;
                        Социальное.note_signal(other, x.id, "еда",
                            other.believed(x.id, "еда") + got.Взять("еда", 0.0) * доля, 0.5);
                    }
    }
}
