// Перенос house/physiology.py: что делают с телом сутки метели (GDD 6).
//
// Расход сытости и жажды, тепло комнаты, настроение и его потолок,
// обморожение, болезнь, урон и восстановление, паника и её дно — и смерть,
// когда здоровье кончилось. Зовётся из движка дважды на человека: до ночи
// в общей комнате и после ребёнка, потому что таков был порядок абзацев,
// а порядок здесь — это порядок `rng`.

namespace Дом.Ядро;

public static class Физиология
{
    /// <summary>
    /// Сутки тела до общей комнаты: расход, привычка к оружию, тепло,
    /// настроение и его потолок. Возвращает температуру комнаты — её же
    /// потом получает ребёнок. <paramref name="infra"/> — сколько всего
    /// в доме отключено, считается один раз на дом.
    /// </summary>
    public static double расход_и_тепло(House h, NPC p, int infra)
    {
        var b = h.B;
        double work = p.часы_работы;
        double drain = b["расход_сытости"] + work * b["расход_сытости_за_час_работы"];
        if (p.warmth < 40)
            drain += b["расход_сытости_на_холоде"];
        p.satiety = Util.Clamp(p.satiety - drain);
        p.hydration = Util.Clamp(p.hydration - b["расход_жажды"]);

        // к оружию привыкают тем, что носят его: каждый день понемногу
        if (p.weapon != Оружие.НЕТ)
        {
            string имя = p.weapon.Текст();
            double своё = Таблицы.СВОЙСКОЕ.TryGetValue(p.weapon, out var с) ? с : 0.0;
            double было = p.рука.Взять(имя, своё);
            p.рука[имя] = Util.Clamp(было + b["рука_за_день"], 0.0, 1.0);
        }

        double room = h.room_temp(p);
        p.warmth = Util.Clamp(
            p.warmth + (room - b["комфортная_температура"]) * b["тепло_за_градус"]);

        double comfort = (p.satiety + p.hydration + p.warmth + p.rest) / 4.0;
        p.mood = Util.Clamp(p.mood + (comfort - 55) * b["настроение_от_комфорта"]
                            - p.panic * 0.035 + b["настроение_метель"]);
        if (p.день_разговора != h.day)
            p.mood = Util.Clamp(p.mood + b["настроение_одиночество"]);

        // у настроения есть потолок, и он опускается вместе с домом. Без него
        // шкала была двоичной: прибавки от разговоров, отдыха и быта прижимали
        // её к сотне, и на десятый день метели — без отопления, воды и света —
        // медиана держалась на 92. Устроено ровно как дно паники ниже:
        // не мгновенный вычет, а уровень, к которому тянет.
        //
        // Причины разделены нарочно. Отключения и холод в комнате — это про
        // быт; темнота и отсутствие связи — про одиночество, и потому идут
        // отдельными слагаемыми (свой генератор от темноты спасает).
        double потолок = 100.0 - infra * b["настроение_потолок_отключение"];
        потолок -= Math.Max(0.0, b["настроение_терпимо_градусов"] - room)
                   * b["настроение_потолок_холод"];
        if (!h.powered(p))
            потолок -= b["настроение_потолок_темнота"];
        if (h.network <= 0)
            потолок -= b["настроение_потолок_без_связи"];
        потолок = Util.Clamp(потолок);
        if (p.mood > потолок)
            p.mood = Util.Clamp(p.mood - (p.mood - потолок) * b["настроение_потолок_притяжение"]);
        return room;
    }

    /// <summary>Сутки тела после ребёнка: обморожение, болезнь, урон
    /// и восстановление, паника, смерть.</summary>
    public static void износ(House h, NPC p, int infra)
    {
        var b = h.B;
        // обморожение — это про холод, а не про случайный пик на улице (GDD 6.2)
        if (p.warmth < b["критичный_порог"] && !p.hurt("обморож")
            && h.rng.Chance(b["обморожение_шанс"]))
        {
            p.injuries.Add(h.rng.Pick(new[] { "обморожение рук", "обморожение ног" })!);
            h.journal.line($"{p.@short} {Util.Vb(p.sex, "отморозил")} пальцы.", 1);
        }
        // болезнь от холода
        if (p.sick is null && p.warmth < 32 && h.rng.Chance(b["болезнь_шанс_на_холоде"]))
        {
            p.sick = "простуда";
            h.journal.line($"{p.label()} {Util.Vb(p.sex, "закашлял")}.", 1);
        }

        double dmg = 0.0;
        foreach (var v in new[] { p.satiety, p.hydration, p.warmth, p.rest })
            if (v < b["критичный_порог"])
                dmg += (b["критичный_порог"] - v) * b["здоровье_за_критичное"];
        dmg += p.injuries.Count * b["травма_урон_в_день"];
        if (p.sick is not null)
            dmg += b["болезнь_урон_в_день"];
        // урон и восстановление считаются отдельно, а не «или-или»: пока
        // регенерация стояла в elif, больной не мог поправиться в принципе,
        // потому что болезнь всегда даёт урон (GDD 6.2 обещает четыре пути
        // лечения, а работал один — аптечка)
        if (dmg > 0)
            p.health = Util.Clamp(p.health - dmg);
        if (Math.Min(Math.Min(p.satiety, p.hydration), Math.Min(p.warmth, p.rest))
            > b["порог_восстановления"])
            p.health = Util.Clamp(p.health + b["здоровье_восстановление"]);
        if (p.injuries.Count > 0 && p.health > 40 && h.rng.Chance(b["рана_заживает"]))
            p.injuries.RemoveAt(p.injuries.Count - 1);   // раны всё-таки затягиваются
        // болезнь проходит сама — в тепле, в сытости и выспавшись (GDD 6.2)
        if (p.sick is not null)
        {
            double шанс = b["болезнь_проходит"];
            if (p.warmth > 55 && p.rest > 60 && p.satiety > 45)
                шанс *= b["болезнь_проходит_в_тепле"];
            if (h.rng.Chance(шанс))
            {
                p.sick = null;
                h.journal.line($"{p.@short} {Util.Vb(p.sex, "отлежался")} — жар спал.", 1);
            }
        }

        // паника растёт и от настоящей нужды, и от веры, что не хватит
        // (GDD 12.3: паника — это «вера, что скоро всё кончится»). Спад
        // глушится отчаянием: человек, который неделю не ел, не успокаивается
        // сам собой. Пугает и то, что кончается, и то, что сейчас плохо:
        // холод, боль, жар. Отчаяние считает только запасы, поэтому
        // физическую часть приходится назвать здесь отдельно — иначе
        // промёрзший человек успокаивался бы ровно потому, что шкаф у него полон
        double нужда = Math.Max(p.desperation(), p.невмоготу());
        double спад = b["паника_спад_в_день"] * (0.4 + 0.6 * p.mood / 100.0)
                      * (1.0 - b["паника_не_спадает_в_нужде"] * нужда);
        Социальное.add_panic(p, b["паника_от_отчаяния"]
                                * Math.Max(нужда, p.insecurity() * 0.85) - спад);
        // у тревоги есть дно, и оно поднимается само: двадцатый день метели
        // без света, воды и новостей пугает независимо от того, что в шкафу
        double floor = Math.Min(b["паника_дно_потолок"],
                                h.day * b["паника_дно_за_день"]
                                + infra * b["паника_дно_за_отключение"]);
        floor *= 0.6 + 0.08 * p.trait("вспыльчивость");
        if (p.panic < floor)
            p.panic += (floor - p.panic) * b["паника_дно_притяжение"];

        if (p.health <= 0)
        {
            string причина = причина_смерти(p);
            Конфликт.умер(h, p, причина,
                          строка: $"† {p.name} {(p.sex == "ж" ? "умерла" : "умер")}. {причина}.");
        }
    }

    /// <summary>Отчего именно человек умер — по самой провалившейся
    /// потребности.</summary>
    public static string причина_смерти(NPC p)
    {
        // min() в Python берёт первого из равных — порядок пар значим
        var пары = new (double v, string имя)[]
        {
            (p.satiety, "голод"), (p.hydration, "обезвоживание"),
            (p.warmth, "холод"), (p.rest, "истощение"),
        };
        var worst = пары[0];
        for (int i = 1; i < пары.Length; i++)
            if (пары[i].v < worst.v)
                worst = пары[i];
        if (p.injuries.Count > 0 && worst.v > 20)
            return Util.Vb(p.sex, "умер") + " от невылеченных ран";
        if (p.sick is not null && worst.v > 20)
            return Util.Vb(p.sex, "умер") + " от болезни без лечения";
        return worst.имя;
    }
}
