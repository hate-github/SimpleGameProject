    /// <summary>Смерть ребёнка на руках (GDD 12.6).</summary>
    public static void смерть_ребёнка(House h, NPC p, Ребёнок р)
        => throw new NotImplementedException(
            $"conflict.смерть_ребёнка переезжает на этапе 1д: {р.имя} у {p.id}");
}
