// Перенос house/services.py: что можно заказать у того, у кого руки, почём
// и как сдаётся работа (GDD 18).
//
// Генератора в справочнике нет нарочно. Его не заказывают: в метель это
// не покупка, а положение — у кого гудит и светится окно, тот в глазах
// подъезда богат, и к его двери идут не с деньгами.

namespace Дом.Ядро;

/// <summary>Что можно заказать. «умения» двойное: они же определяют, кто
/// мастер, и то, кому заказывать незачем — своими руками дешевле.</summary>
public sealed record Услуга(string[] умения, string мат, string поле, int потолок, bool своё);

public static class Услуги
{
    public static readonly Словарь<string, Услуга> УСЛУГИ = Собрать();

    private static Словарь<string, Услуга> Собрать()
    {
        var у = Словари.Строкой<Услуга>();
        у["буржуйка"] = new(new[] { "слесарь", "электрик" }, "буржуйка_материалы",
                            "буржуйка", 1, true);
        у["листы"] = new(new[] { "слесарь", "электрик" }, "листы_материалы",
                         "листы", 2, false);
        у["звукоизоляция"] = new(new[] { "слесарь" }, "звукоизоляция_материалы",
                                 "звукоизоляция", 1, false);
        у["стены"] = new(new[] { "слесарь" }, "стены_материалы", "стены", 2, false);
        return у;
    }

    // как называется работа, когда о ней договариваются: «сделает буржуйку»
    public static readonly IReadOnlyDictionary<string, string> УСЛУГА_ВИН =
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["буржуйка"] = "сделает буржуйку",
            ["листы"] = "прибьёт листы на дверь",
            ["звукоизоляция"] = "заглушит генератор",
            ["стены"] = "протянет арматуру",
        };

    // и как она называется, когда сделана
    public static readonly IReadOnlyDictionary<string, string> УСЛУГА_РАБОТА =
        new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["буржуйка"] = "буржуйку",
            ["листы"] = "стальные листы на дверь",
            ["звукоизоляция"] = "звукоизоляцию",
            ["стены"] = "арматуру по стенам",
        };

    /// <summary>Чем человек может расплатиться за работу: едой и дровами
    /// (GDD 18).</summary>
    public static double кошелёк_за_работу(NPC npc)
        => npc.stock.Взять("еда", 0.0) + npc.stock.Взять("топливо", 0.0);

    /// <summary>
    /// Чего стоит работа. GDD 18: «после дня 0 услуги дороже вещей». Цена
    /// растёт не от дефицита ресурса, а от беды покупателя — это единственное
    /// место в модели, где так. У кого вчера ломали дверь, тот заплатит
    /// за стальные листы вдвое: он платит не за железо, а за то, чтобы дожить
    /// до утра.
    /// </summary>
    public static double цена_услуги(House h, NPC заказчик, NPC мастер, string что,
                                     Баланс b, bool материал_заказчика = true)
    {
        double цена = b.Таблица("услуга_цена")[что];
        цена *= 1.0 + мастер.t01("жадность") * b["услуга_за_жадность"];
        // беда покупателя: паника, происшествия в доме и дыры в его стенах
        double беда = Util.Clamp(заказчик.panic / 100.0 + 0.15 * h.where(заказчик).дыр(),
                                 0.0, 1.5);   // правда: видно: мастер видит и лицо заказчика, и его дверь
        цена *= 1.0 + беда * b["услуга_за_нужду"];
        цена *= Math.Max(0.5, 1.0 - мастер.trust.Взять(заказчик.id, 3.0) * b["услуга_за_доверие"]);
        if (!материал_заказчика)
            цена += b[УСЛУГИ[что].мат] * b["услуга_за_доску"];
        return цена;
    }

    /// <summary>
    /// Есть ли у кого-нибудь из этих людей то, из чего собирают генератор.
    /// Из семи досок двигатель не собирается: движок один на весь дом, лежит
    /// он в погребе у слесаря, и всё, что делает электрик, — приводит его
    /// в чувство и подключает.
    /// </summary>
    public static bool есть_движок(params NPC?[] кто)
    {
        foreach (var p in кто)
            if (p is not null && p.stock.Взять("движок", 0.0) >= 1.0)
                return true;
        return false;
    }

    /// <summary>
    /// Зачем этому человеку генератор — и зачем он ему сегодня (GDD 15).
    /// Считается из того, что генератор на самом деле даст: обогреватель без
    /// электричества — мёртвый ящик, снег на нём топят, когда топить больше
    /// не на чем, а свет в окне — это настроение.
    /// </summary>
    public static double нужен_генератор(House h, NPC npc, Flat flat, double cold_pressure)
    {
        var b = h.B;
        double s = b["генератор_за_свет"] + cold_pressure * b["генератор_за_холод"];
        if (flat.shelter.Взять("обогреватель", 0.0) != 0.0)
            s += b["генератор_за_обогреватель"];
        if (!h.water_on && flat.shelter.Взять("буржуйка", 0.0) == 0.0)
            s += b["генератор_за_снег"];
        if (h.power_on)
            // пока розетки живы, генератор — не нужда, а запасливость
            s *= b["генератор_загодя"];
        return s;
    }

    /// <summary>
    /// Что этот человек заказал бы вот у этого мастера и насколько сильно
    /// хочет. Одно место на оценку и на исполнение: пока их было два, человек
    /// считал одно, а делал другое.
    /// </summary>
    public static (string? что, double оценка) что_заказать(
        House h, NPC npc, NPC мастер, Баланс b, double cold_pressure, double fear)
    {
        var flat = h.where(npc);
        string? лучшее = null;
        double оценка = 0.0;
        foreach (var (что, у) in УСЛУГИ)
        {
            // своими руками дешевле: заказывают то, чего сам не умеешь
            if (у.умения.Any(u => npc.skills.Contains(u, StringComparer.Ordinal)))
                continue;
            if (!у.умения.Any(u => мастер.skills.Contains(u, StringComparer.Ordinal)))
                continue;
            if (flat.shelter.Взять(у.поле, 0.0) >= у.потолок)
                continue;
            if (что == "буржуйка" && !npc.топит_сам())
                continue;      // гость греется хозяйской печкой, своя ему не нужна
            if (что == "звукоизоляция" && flat.shelter.Взять("генератор", 0.0) == 0.0)
                continue;      // глушить нечего
            if (что == "генератор" && !есть_движок(npc, мастер))
                continue;      // из досок двигатель не собрать
            double s = что switch
            {
                "буржуйка" => cold_pressure * 7.0,
                "генератор" => нужен_генератор(h, npc, flat, cold_pressure),
                "листы" => fear * 4.0,
                "звукоизоляция" => fear * 2.0,
                "стены" => fear * 5.0 - 1.0 + flat.дыр() * b["заказ_за_пролом"],
                _ => throw new KeyNotFoundException(что),
            };
            // ключ постройки для мерки нормальности: у генератора он свой
            string ключ = что == "генератор" ? "генератор_собрать" : что;
            s *= Характер.norm_gate(npc, ключ, b);
            if (s > оценка)
            {
                лучшее = что;
                оценка = s;
            }
        }
        return (лучшее, оценка);
    }

    /// <summary>
    /// Решает мастер: руки у него одни, и работа стоит того, что за неё дают.
    /// Больше нуля — берётся.
    /// </summary>
    public static double возьмётся_за_заказ(House h, NPC мастер, NPC заказчик,
                                            double цена, Баланс b)
    {
        double готов = мастер.t01("лояльность") * 4.0
                       + мастер.trust.Взять(заказчик.id, 3.0) * 0.6
                       + мастер.t01("жадность") * 2.0        // это заработок
                       + цена * b["услуга_соблазн"]          // и тем больший, чем выше цена
                       - мастер.hate.Взять(заказчик.id, 0.0) / 15.0
                       - (1.0 - Math.Min(1.0, мастер.secure("еда"))) * 2.0;
        return готов - b["печь_согласие"];
    }

    /// <summary>
    /// Уговор с мастером: что, почём, чьи доски, и берётся ли он (GDD 18).
    /// Возвращает строку журнала; null — дело не состоялось.
    /// </summary>
    public static string? заказать(House h, NPC npc, NPC мастер, double cold_pressure,
                                   double fear, string? что = null)
    {
        var b = h.B;
        string? said = null;
        if (что is null)
        {
            // вызов мимо сбора: дом ходом дня передаёт решённое (Корзина.детали)
            h.bump("пересчётов_в_исполнении");
            (что, _) = что_заказать(h, npc, мастер, b, cold_pressure, fear);
        }
        if (что is null)
            return null;                   // пока он шёл, надобность отпала
        double мат = b[УСЛУГИ[что].мат];
        if (Math.Max(npc.stock.Взять("материалы", 0.0),
                     мастер.stock.Взять("материалы", 0.0)) < мат)
        {
            // досок нет ни у того, ни у другого. Заказчик шёл по оценке чужого
            // шкафа и ошибся — теперь знает точно: мастер показал пустой угол
            Социальное.note_signal(npc, мастер.id, "материалы",
                мастер.stock.Взять("материалы", 0.0), 0.7);   // правда: видно: мастер показал угол
            h.bump("заказов_без_досок");
            return $"{npc.@short} {Util.Vb(npc.sex, "пришёл")} к {мастер.form("dat")} заказать "
                   + $"{УСЛУГА_РАБОТА[что]} — а досок нет ни у кого";
        }
        // чьи доски — решается здесь, до цены, потому что от этого цена
        // и зависит. Пока доплату за материал прибавляли при сдаче,
        // объявленная цена не совпадала с взятой
        var чей = npc.stock.Взять("материалы", 0.0) >= мат ? npc : мастер;
        double цена = цена_услуги(h, npc, мастер, что, b, ReferenceEquals(чей, npc));
        // движок для генератора — та же история, что и доски, только вещь
        // в доме одна. Кто его принёс, тот и не платит за него
        NPC? чей_движок = null;
        if (что == "генератор")
        {
            чей_движок = есть_движок(npc) ? npc : мастер;
            if (!есть_движок(чей_движок))
                return null;               // пока он шёл, движок ушёл из рук
            if (ReferenceEquals(чей_движок, мастер))
                цена += b["услуга_за_движок"];
        }
        if (h.мастер_занят.Есть(мастер.id))
            said = $"{мастер.@short} и рад бы, да {Util.Vb(мастер.sex, "занят")}: "
                   + $"работа уже делается не {npc.form("dat")}";
        else if (Решение.по_правилу(h, мастер, Вопрос.ВЗЯТЬСЯ_ЗА_ЗАКАЗ, "взяться", "отказать",
                                    возьмётся_за_заказ(h, мастер, npc, цена, b)))
        {
            int срок = (int)b["печь_срок"]
                       - (мастер.skills.Contains("слесарь", StringComparer.Ordinal) ? 1 : 0);
            // доски откладывают сразу и в сторону — в угол у мастера. Пока
            // материал ждали до срока, заказы срывались не по злому умыслу,
            // а потому что доски уходили в печку, и мастер оказывался
            // нарушившим слово, не сделав ничего
            var склад = h.flats[мастер.apt];
            чей.stock["материалы"] = чей.stock.Взять("материалы", 0.0) - мат;
            склад.stock["материалы"] = склад.stock.Взять("материалы", 0.0) + мат;
            if (чей_движок is not null)
            {
                чей_движок.stock["движок"] = чей_движок.stock.Взять("движок", 0.0) - 1.0;
                склад.stock["движок"] = склад.stock.Взять("движок", 0.0) + 1.0;
            }
            h.заказы[npc.id] = new Заказ
            {
                мастер = мастер.id, что = что, готово = h.day + срок, цена = цена,
                материал_заказчика = ReferenceEquals(чей, npc),
            };
            h.мастер_занят[мастер.id] = npc.id;
            Социальное.adjust(npc, мастер.id, trust: 0.8);
            // это и есть обещание «сделать»: с этого дня у мастера есть срок
            Социальное.обещать(h, мастер, npc, "сделать", что, дней: срок + 1);
            said = $"{npc.@short} {Util.Vb(npc.sex, "сговорился")} с {мастер.form("ins")}: "
                   + $"{УСЛУГА_ВИН[что]} за {срок} дн., цена {цена:F0}";
        }
        else
        {
            Социальное.adjust(npc, мастер.id, trust: -0.4);
            said = $"{мастер.@short} не {Util.Vb(мастер.sex, "взялся")} за работу "
                   + $"{npc.form("dat")} — руки нужны самому";
        }
        return said;
    }

    /// <summary>Утро: мастер отдаёт готовую работу и берёт своё (GDD 18).</summary>
    public static void готовые_заказы(House h)
    {
        foreach (var p in h.alive())
        {
            if (!h.заказы.TryGetValue(p.id, out var заказ) || h.day < заказ.готово)
                continue;
            var мастер = h.живой(заказ.мастер);
            if (мастер is null)
            {
                h.заказы.Убрать(p.id);
                h.мастер_занят.Убрать(заказ.мастер);
                continue;
            }
            string что = заказ.что;
            var у = УСЛУГИ[что];
            double нужно = h.B[у.мат];
            // доски отложены в угол у мастера ещё при уговоре. Если угол
            // растащили — работает из своего
            var склад = h.flats[мастер.apt];
            double отложено = Math.Min(нужно, склад.stock.Взять("материалы", 0.0));
            if (отложено >= нужно)
            {
                склад.stock["материалы"] -= нужно;
                мастер.stock["материалы"] = мастер.stock.Взять("материалы", 0.0) + нужно;
            }
            else if (мастер.stock.Взять("материалы", 0.0) < нужно)
                continue;                  // нет материала — заказ ждёт
            if (что == "генератор")
            {
                // движок ждал в том же углу. Если угол растащили — работа
                // стоит: собирать больше не из чего
                if (склад.stock.Взять("движок", 0.0) < 1.0)
                    continue;
                склад.stock["движок"] -= 1.0;
                мастер.stock["движок"] = мастер.stock.Взять("движок", 0.0) + 1.0;
            }
            // цена — та, о которой договорились, включая доски мастера
            double цена = заказ.цена;
            var плата = Словари.Числа();
            foreach (var res in new[] { "еда", "топливо" })
            {
                double уже = Util.Sum(плата.Значения);
                double берём = Math.Min(цена - уже, p.stock.Взять(res, 0.0));
                if (берём > 0)
                {
                    p.stock[res] -= берём;
                    мастер.stock[res] = мастер.stock.Взять(res, 0.0) + берём;
                    плата[res] = берём;
                }
            }
            if (Util.Sum(плата.Значения) < цена * 0.5)
                continue;                  // заказчику нечем платить — ждёт
            Ресурсы.Spend(h, мастер, "материалы", нужно);
            if (что == "генератор")
                Ресурсы.Spend(h, мастер, "движок", 1.0);
            var flat = h.where(p);
            if (что is "буржуйка" or "генератор")
                flat.shelter[у.поле] = 1.0;
            else
                flat.shelter[у.поле] = flat.shelter.Взять(у.поле, 0.0) + 1;
            flat.вложено += нужно;
            h.заказы.Убрать(p.id);
            h.мастер_занят.Убрать(мастер.id);
            Социальное.adjust(p, мастер.id, trust: 2.0, hate: -10);
            Социальное.adjust(мастер, p.id, trust: 1.0);
            Социальное.сдержал(h, мастер, p, "сделать", что);
            h.bump("работ_на_заказ");
            h.bump("заказ_" + что);
            h.journal.line($"{мастер.@short} {Util.Vb(мастер.sex, "сделал")} {p.form("dat")} "
                + $"{УСЛУГА_РАБОТА[что]}. Расплатились: "
                + string.Join(", ", плата.Select(п => $"{п.Key} {Текст.G(Math.Round(п.Value, 1))}"))
                + ".", 2);
            h.note($"{мастер.@short}: работа {p.form("dat")} ({что})");
        }
    }

    /// <summary>
    /// Возьмёт ли медик за работу и сколько (GDD 18: услуги — тоже товар).
    /// Даром она лечит своих, детей и тех, кому платить нечем: отказать
    /// она всё равно не может — уже пришла и уже открыла аптечку. Но помнит,
    /// кто не заплатил, и в следующий раз идёт не сразу.
    /// </summary>
    public static Словарь<string, double>? плата_за_лечение(House h, NPC медик,
                                                             NPC больной, Баланс b)
    {
        // решает не жадность, а собственный шкаф и то, на сколько жизнь уже
        // не та. Медик в этом доме один и по замыслу самый лояльный человек
        // в нём: если считать по жадности, платить ему не будут никогда
        double просит = медик.t01("жадность") * 2.0
                        + (1.0 - Math.Min(1.0, медик.secure("еда"))) * b["лечение_плата_нужда"]
                        + (1.0 - медик.normalcy) * b["лечение_плата_нормальность"]
                        - медик.t01("лояльность") * 1.5
                        - медик.trust.Взять(больной.id, 3.0) * 0.2;
        if (медик.allies.Contains(больной.id))
            просит -= 2.0;
        if (больной.dependents != 0)
            просит -= 1.5;             // к матери с ребёнком с прейскурантом не ходят
        if (просит < b["лечение_плата_порог"])
            return null;
        // цена растёт с бедой: за перевязку в первый день и за жар
        // на двадцатый платят разное
        double цена = b["лечение_цена"] * (1.0 + больной.невмоготу() * b["услуга_за_нужду"]);
        var плата = Словари.Числа();
        foreach (var res in new[] { "еда", "топливо" })
        {
            double уже = Util.Sum(плата.Значения);
            double берём = Math.Min(цена - уже, больной.stock.Взять(res, 0.0));
            if (берём > 0)
            {
                больной.stock[res] -= берём;
                медик.stock[res] = медик.stock.Взять(res, 0.0) + берём;
                плата[res] = берём;
            }
        }
        if (Util.Sum(плата.Значения) < цена * 0.5)
        {
            // нечем. Лечить она всё равно будет, но запомнит
            медик.ask_record(больной.id).не_заплатил += 1.0;
            h.bump("лечений_в_долг");
            return плата;
        }
        h.bump("лечений_за_плату");
        return плата;
    }
}
