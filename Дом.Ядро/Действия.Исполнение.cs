// Перенос house/actions.py, строки 1759–1915 и 3080–3168: один ход человека
// от выбора до эпилога.
//
// Ход устроен в три слоя, и слои эти разные по смыслу. `choose_and_do` —
// собрать варианты и спросить решающего. `execute` — довести выбранное
// до исполнителя, отсекая по дороге всё, что случается на пороге: засаду
// на площадке, пустую кладовку, некуда идти, провал стройки. И `_эпилог` —
// то, что дом узнаёт о сделанном: строка, шум за стеной, суд соседей
// и сдвиг нормальности.
//
// Сорок девять исполнителей лежат отдельно (`Действия.Исполнители.*`)
// и регистрируются в общем справочнике: полнота сверяется со справочником
// действий, как в прототипе.

namespace Дом.Ядро;

/// <summary>
/// Чем кончилось исполнение: действие состоялось или сорвалось на пороге.
/// Дом это не читает; читают наблюдатели — пока `execute` молчал, покрытие
/// считало выполненным и то, что не случилось.
/// </summary>
public enum Исход { СДЕЛАНО, СОРВАНО }

public static partial class Действия
{
    /// <summary>
    /// Все исполнители заводятся один раз, при первом обращении к классу.
    /// В прототипе это делают декораторы при импорте модуля; здесь —
    /// статический конструктор, и он же сверяет полноту.
    /// </summary>
    static Действия()
    {
        ЗарегистрироватьБыт();
        ЗарегистрироватьСоседей();
        ЗарегистрироватьУлицу();
        // Полнота: у каждого действия справочника есть исполнитель, у каждого
        // исполнителя — запись. Проверяется здесь, а не прогоном: справочник
        // про действия не знает (иначе цикл), а покрытие заметило бы ветку
        // без записи только через десятки прогонов
        var без_исполнителя = Каталог.COST.Ключи
            .Where(k => !ИСПОЛНИТЕЛИ.ContainsKey(k))
            .OrderBy(k => k, StringComparer.Ordinal).ToList();
        var без_записи = ИСПОЛНИТЕЛИ.Keys
            .Where(k => !Каталог.COST.Есть(k))
            .OrderBy(k => k, StringComparer.Ordinal).ToList();
        if (без_исполнителя.Count > 0 || без_записи.Count > 0)
            throw new InvalidOperationException("Действия и исполнители разошлись:"
                + (без_исполнителя.Count > 0
                   ? $" без исполнителя — {string.Join(", ", без_исполнителя)};" : "")
                + (без_записи.Count > 0
                   ? $" без записи в справочнике — {string.Join(", ", без_записи)};" : ""));
    }

    /// <summary>
    /// Ключ действия → исполнитель. Возвращает текст главной строки хода
    /// (или null), дальше — общий для всех эпилог. Один исполнитель
    /// на каждое действие справочника.
    /// </summary>
    public static readonly Dictionary<string, Func<House, NPC, object?, double, object?, object?>>
        ИСПОЛНИТЕЛИ = new(StringComparer.Ordinal);

    /// <summary>У каких действий исполнитель принимает решение сбора.</summary>
    public static readonly HashSet<string> С_ДЕТАЛЯМИ = new(StringComparer.Ordinal);

    /// <summary>
    /// Исполнитель вернул это, когда дело не состоялось и дому нечего
    /// слышать: «пока он шёл, надобность отпала». Эпилога тогда нет.
    /// </summary>
    public static readonly object НЕ_СОСТОЯЛОСЬ = new();

    /// <summary>
    /// А это — когда дело состоялось, но эпилог не нужен: строку и шум
    /// исполнитель дал сам (лечение ребёнка) или человека в доме уже нет
    /// (ушёл к школе). Оба случая прикрывались `НЕ_СОСТОЯЛОСЬ`, и покрытие
    /// считало бы их сорванными.
    /// </summary>
    public static readonly object СДЕЛАНО_МОЛЧА = new();

    /// <summary>
    /// Зарегистрировать исполнителя действия.
    ///
    /// <paramref name="детали"/> — исполнитель принимает пятым аргументом то,
    /// что решил сбор: какую услугу заказать, чем поделиться, что просить.
    /// Тогда он не считает это заново.
    /// </summary>
    public static void исполняет(string key,
        Func<House, NPC, object?, double, object?, object?> f, bool детали = false)
    {
        if (ИСПОЛНИТЕЛИ.ContainsKey(key))
            throw new InvalidOperationException($"исполнитель «{key}» уже есть");
        ИСПОЛНИТЕЛИ[key] = f;
        if (детали)
            С_ДЕТАЛЯМИ.Add(key);
    }

    /// <summary>Исполнитель без деталей — обёртка, чтобы не писать лишний
    /// аргумент в сорока девяти местах.</summary>
    public static void исполняет(string key, Func<House, NPC, object?, double, object?> f)
        => исполняет(key, (h, npc, target, spent, _) => f(h, npc, target, spent));

    /// <summary>Один ход одного человека. true, если действие совершено.</summary>
    public static bool choose_and_do(House h, NPC npc)
    {
        npc.away = false;          // раз он снова берётся за дело — значит, он дома
        var корзина = gather(h, npc);
        // если ничего толкового не осталось — день на этом и заканчивается.
        // Без этого порога человек от нечего делать идёт разбирать чужую квартиру
        var opts = корзина.варианты.Where(в => в.оценка > h.B["порог_действия"]).ToList();
        if (opts.Count == 0)
            return false;
        // выбор — за решающим жильца: NPC берёт мягко по оценкам, игрок
        // и скрипт — по-своему. Корзина идёт следом: в ней объяснение
        var выбор = (npc.решающий as Решающий)!.день(h, npc, opts, корзина);
        if (выбор is null)
            return false;
        var (key, target) = выбор.Value;
        // весь ход печатается с его часами: и само действие, и то, что оно
        // за собой потянуло. Часы личные — встал он в свой час и потратил своё
        h.journal.час = npc.часы_вслух();
        try
        {
            корзина.детали.TryGetValue(new КлючЦели(key, target), out var детали);
            // и то, что решено внутри действия, — вместе с ним: человек делает
            // то, что выбрал, а не то, что пересчиталось у чужой двери
            execute(h, npc, key, target, детали);
        }
        finally
        {
            h.journal.час = null;
        }
        return true;
    }

    /// <summary>
    /// Не поджидает ли кого-то на площадке — и не он ли эта цель.
    ///
    /// Долгий выход (вылазка, погреб) ловится почти наверняка: человека нет
    /// полдня, и вернётся он этой же лестницей. Короткий шаг к соседу —
    /// как повезёт: на площадке можно и разминуться.
    /// </summary>
    public static NPC? засада_ждёт(House h, NPC npc, string key, object? target)
    {
        string? кто_id = h.сутки.караулят.Взять(npc.id, null);
        if (string.IsNullOrEmpty(кто_id))
            return null;
        bool вышел = Каталог.ВЫХОД_НА_ПЛОЩАДКУ.Contains(key)
                     || target is NPC || target is Flat;
        if (!вышел)
            return null;
        var ждущий = h.живой(кто_id);
        if (ждущий is null || ждущий.away)
            return null;
        double шанс = Каталог.ВЫХОД_НА_ПЛОЩАДКУ.Contains(key)
                      ? h.B["засада_ловит_вылазку"] : h.B["засада_ловит_соседа"];
        return h.rng.Chance(шанс) ? ждущий : null;
    }

    /// <summary>
    /// Напечатать главную строку хода сразу, а не в конце.
    ///
    /// Нужно там, где поступок сам вызывает другие строки: улаженную обиду,
    /// разоблачённый наговор, плату за работу. Иначе в журнале сначала
    /// «взял то, что принёс, и кивнул», а следом — то, что он принёс.
    /// </summary>
    public static void сказать_сразу(House h, string key, string? текст)
    {
        if (!string.IsNullOrEmpty(текст))
            h.journal.line(текст!, Каталог.NOTABLE.Взять(key, 0));
    }

    /// <summary>Что дом узнаёт о сделанном: строка в журнал, шум за стеной,
    /// суд и нормальность.</summary>
    public static void _эпилог(House h, NPC npc, string key, string? said, double spent = 0.0)
    {
        var b = h.B;
        var (lvl, kind) = Каталог.COST[key];
        if (!string.IsNullOrEmpty(said))
            h.journal.line(said!, Каталог.NOTABLE.Взять(key, 0));
        if (lvl != 0 && !string.IsNullOrEmpty(kind))
        {
            var heard = Социальное.emit(h, npc, lvl, kind!, night: false);
            // дом судит и то, что просто услышал за стеной. Крупное — кражу,
            // отъём, людоедство — судят по месту и своими числами; здесь быт,
            // который раньше не судил никто, и оттого половина ценностей
            // в данных не срабатывала: гул генератора всю ночь не значил
            // ничего даже для того, кто «не терпит шум»
            if (Каталог.СУД.Есть(key) && heard.Count > 0)
            {
                var суд = Каталог.СУД.Взять(key, null!);
                var (ключ_н, ключ_д) = (суд.ненависть, суд.доверие);
                // тот, кто сидит у той же печки, не судит её как чужой шум
                // за стеной: это общий огонь и общий генератор
                var судьи = heard.Where(w => !h.под_одной_крышей(npc, w)).ToList();
                if (судьи.Count > 0)
                    Социальное.judge(h, npc, Каталог.ТЕГИ.Взять(key, Array.Empty<string>()),
                        hate: string.IsNullOrEmpty(ключ_н) ? 0.0 : b[ключ_н!],
                        trust: string.IsNullOrEmpty(ключ_д) ? 0.0 : b[ключ_д!],
                        witnesses: судьи);
            }
            double вес = Каталог.НОРМА.Взять(key, 0.0);
            if (вес >= b["нормальность_дикость_порог"])
            {
                // сосед заколотил дверь — значит, так уже можно. Но вес берётся
                // из НОРМА этого поступка, а не считается за единицу: дверь
                // весит меньше, чем разобранная чужая квартира, а та — меньше,
                // чем отъём на лестнице
                Социальное.громкое(h);
                Социальное.переступил(h, npc, key);
                foreach (var w in heard)
                    Социальное.видел(h, w, вес * b["нормальность_за_чужой_пример"], кто: npc);
            }
            else if (Каталог.ОБЫЧНОЕ.Contains(key) && npc.нормальность_пол >= b["опора_пол"])
                // и обратный ход: тот, кто на виду делает обычные вещи,
                // держит дом
                foreach (var w in heard)
                    Социальное.держится(h, w, кто: npc);
            if (heard.Count > 0 && lvl >= 3)
                h.journal.line("   (слышали: "
                    + string.Join(", ", heard.Select(p => p.@short)) + ")", 0);
        }
    }

    /// <summary>
    /// Сделать выбранное. <paramref name="детали"/> — что именно решено
    /// в сборе, если у действия есть выбор внутри: какую услугу заказать,
    /// чем поделиться, что просить. Исполнитель получает их пятым аргументом,
    /// если объявлен с деталями, и тогда ничего не пересчитывает.
    /// </summary>
    public static Исход execute(House h, NPC npc, string key, object? target,
                                object? детали = null)
    {
        var b = h.B;
        double spent = hours(key, npc, b);

        // человек, который увидел на площадке чужого, сегодня уже никуда не идёт
        if (Каталог.ВЫХОД_НА_ПЛОЩАДКУ.Contains(key)
            && h.сутки.не_выходить.Взять(npc.id, -1) == h.day)
        {
            mark(h, npc, key, target);
            return Исход.СОРВАНО;
        }
        var ждущий = засада_ждёт(h, npc, key, target);
        if (ждущий is not null)
        {
            h.сутки.караулят.Убрать(npc.id);
            npc.time_left -= Math.Min(npc.time_left, 1.0);
            Конфликт.засада(h, ждущий, npc);
            return Исход.СОРВАНО;
        }
        if (string.Equals(key, "вылазка", StringComparison.Ordinal))
        {
            // место выбрано в сборе вместе с самим решением выйти и пришло
            // сюда целью. Дорога стоит времени, и оно уже учтено в воротах
            var м = target as Место;
            if (м is null)
                м = Улица.выбрать_место(h, npc, часов: npc.time_left);
            if (м is null)
            {
                // идти некуда. Отмечаем, чтобы тот же вариант не предлагался
                // заново весь оставшийся день, и выходим, не тратя часов
                mark(h, npc, key, null);
                return Исход.СОРВАНО;
            }
            target = м;
            if (м.магазин && h.магазины)
                // в работающий магазин не «ходят полдня»: дошёл, отстоял
                // очередь, взял, сколько хватило денег и сколько унёс,
                // вернулся. Пока время считалось общей формулой вылазки,
                // поход за тушёнкой в первый день метели стоил тринадцать
                // часов — полтора суток в очереди
                spent = Math.Min(b["магазин_часы_дороги"] * Улица.погода_часы(h)
                                 + h.rng.Uni(0.0, b["магазин_часы_очереди"])
                                   * (1.0 + b["магазин_очередь_за_день"] * (h.day - 1)),
                                 npc.time_left);
            else
                spent = Math.Min(h.rng.Uni(b["вылазка_часы_мин"], b["вылазка_часы_макс"])
                                 * м.часы * Улица.погода_часы(h), npc.time_left);
        }
        else if (string.Equals(key, "уйти", StringComparison.Ordinal))
            // дорога съедает весь остаток дня, чем бы она ни кончилась
            spent = npc.time_left;
        else if (string.Equals(key, "кладовая", StringComparison.Ordinal))
        {
            var к = target as Кладовая;
            if (к is null || к.пусто())
            {
                mark(h, npc, key, target);
                return Исход.СОРВАНО;   // пока он шёл, там уже ничего не осталось
            }
            spent = Math.Min(Улица.часы_кладовой(h, к), npc.time_left);
        }
        else if (string.Equals(key, "вскрыть_кладовую", StringComparison.Ordinal))
        {
            var к = target as Кладовая;
            if (к is null || к.пусто() || h.есть_ключ(npc, к))
            {
                mark(h, npc, key, target);
                return Исход.СОРВАНО;   // уже вскрыли до него, или брать нечего
            }
            spent = Math.Min(Улица.часы_вскрытия(h, к), npc.time_left);
        }
        npc.time_left -= spent;
        mark(h, npc, key, target);
        npc.часы_работы += СЧИТАЕТСЯ_РАБОТОЙ.Contains(key) ? spent : 0;
        var (lvl, kind) = Каталог.COST[key];

        // у работы есть шанс провала (GDD 7: «провал — потеря материалов,
        // травма руки»)
        if (Каталог.СТРОЙКА.Есть(key) && !h.rng.Chance(npc.success(b)))
        {
            string мат_ключ = Каталог.ПОСТРОЙКИ.Есть(key)
                ? Каталог.ПОСТРОЙКИ.Взять(key, null!).материалы
                : МАТЕРИАЛЫ_ПОСТРОЙКИ.Взять(key, "");
            double потеря = b[мат_ключ] * b["провал_доля_материалов"];
            Ресурсы.Spend(h, npc, "материалы", потеря);
            npc.mood = Util.Clamp(npc.mood - 5);
            string текст = $"{npc.@short} {Util.Vb(npc.sex, "взялся")} за "
                           + $"{Каталог.СТРОЙКА.Взять(key, "")}, но "
                           + $"{Util.Vb(npc.sex, "испортил")} материал";
            if (h.rng.Chance(b["провал_шанс_травмы"]))
            {
                npc.injuries.Add(h.rng.Pick(new[] { "ушиб руки", "порез руки" })!);
                npc.health = Util.Clamp(npc.health - h.rng.Uni(4, 10));
                текст += $" и {Util.Vb(npc.sex, "рассадил")} руку";
            }
            h.journal.line(текст + ".", 1);
            if (lvl != 0 && !string.IsNullOrEmpty(kind))
                Социальное.emit(h, npc, lvl, kind!, night: false);
            return Исход.СДЕЛАНО;           // взялся и испортил — но взялся
        }

        var исполнитель = ИСПОЛНИТЕЛИ[key];
        object? said = С_ДЕТАЛЯМИ.Contains(key)
            ? исполнитель(h, npc, target, spent, детали)
            : исполнитель(h, npc, target, spent, null);
        if (ReferenceEquals(said, НЕ_СОСТОЯЛОСЬ))
            return Исход.СОРВАНО;
        if (ReferenceEquals(said, СДЕЛАНО_МОЛЧА))
            return Исход.СДЕЛАНО;
        _эпилог(h, npc, key, said as string, spent);
        return Исход.СДЕЛАНО;
    }

    /// <summary>Что считается работой для счётчика часов.</summary>
    private static readonly HashSet<string> СЧИТАЕТСЯ_РАБОТОЙ =
        new(StringComparer.Ordinal) { "утепление", "дверь", "буржуйка", "разбор", "вылазка" };

    /// <summary>Три постройки, которых нет в общей таблице: их материалы
    /// названы отдельными ручками.</summary>
    private static readonly Словарь<string, string> МАТЕРИАЛЫ_ПОСТРОЙКИ = Материалы();

    private static Словарь<string, string> Материалы()
    {
        var т = Словари.Строкой<string>();
        т["утепление"] = "утепление_материалы";
        т["дверь"] = "дверь_материалы";
        т["буржуйка"] = "буржуйка_материалы";
        return т;
    }
}
