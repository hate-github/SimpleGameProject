// Звуки того, что делает герой и что он слышит (записи автора
// из «референсы/звуки/готовые», 27.09: выстрел, осечка, перезарядка,
// топор, удар, жарка, резка, ссора, стук в дверь).
//
// Громкость за стеной — дело симуляции, и здесь она не придумывается:
// что герой услышал, ядро уже решило (`Социальное.emit` — этажи, стены,
// буран, спит ли он) и записало ему в память «слышал — кто — что». Узел
// только проигрывает это у двери того, кто шумел: ссору, выстрел, топор
// разбора, удары взлома, жарку у соседа. Не услышал — не звучит; в участке
// подъезда не слышно вовсе (кого нет в доме, тот не слышит).
//
// Своё — без места: перезарядка, когда берёшь ствол в руки; топор, когда
// ломаешь мебель; жарка, когда ешь у горящей печки; удар, когда тебя
// ранили в драке (обморожение и ожог — не удар). Стук — у двери: к тебе
// пришли с просьбой, на собрание, с ребёнком — стучат в твою; сам пришёл
// к соседу — в его. Дверь деревянная, а крепкая или обитая листами —
// металлическая.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    private int _память_услышано = -1;          // сколько записей памяти героя уже прозвучало
    private int _ран_было = -1;                 // сколько ран было на прошлом вопросе
    private ВопросИгроку? _стучали_на;          // на какой вопрос уже стучали

    /// <summary>Что услышанное звучит чем: вид шума ядра → запись, громкость
    /// (дБ) и кусок длинной записи в секундах (0 — целиком).</summary>
    private static readonly Dictionary<string, (string звук, float дб, float секунд)> СЛЫШНО =
        new(System.StringComparer.Ordinal)
        {
            ["ссора"] = ("ссора", -3f, 6f),
            ["выстрел"] = ("выстрел_пистолет", 3f, 0f),
            ["разбор"] = ("топор_2", -4f, 5f),
            ["взлом"] = ("удар_по_металлу", -2f, 0f),
            ["пролом"] = ("удар_по_металлу", 0f, 0f),
            ["готовка"] = ("жарка", -12f, 5f),
        };

    /// <summary>Сколько услышанного звучит на одном вопросе — не больше.</summary>
    private const int СЛЫШНО_РАЗОМ = 3;

    /// <summary>С чем приходят к двери героя и стучат.</summary>
    private static readonly HashSet<Вопрос> СТУЧАТ = new()
    {
        Вопрос.ОТКРЫТЬ_ДВЕРЬ, Вопрос.ВПУСТИТЬ_МЕДИКА, Вопрос.ПУСТИТЬ_К_СЕБЕ,
        Вопрос.ВЗЯТЬ_РЕБЁНКА_НА_НОЧЬ, Вопрос.ВЫЙТИ_НА_СОБРАНИЕ,
    };

    /// <summary>Новая жизнь или поднятая из сохранения: счёт услышанного
    /// и ран — с неё, иначе прежняя память прозвучала бы разом.</summary>
    private void Звуки_сначала()
    {
        _память_услышано = -1;
        _ран_было = -1;
        _стучали_на = null;
    }

    /// <summary>
    /// На каждом новом вопросе, пока дом спит: к нему стучат; что он услышал
    /// с прошлого вопроса сегодня — у двери того, кто шумел (ночное, пока
    /// спал, утром не звучит); ранили — удар.
    /// </summary>
    private void Звуки_вопроса(ВопросИгроку в)
    {
        if (_партия is null)
            return;
        var h = _партия.сеанс.дом;
        var я = _партия.сеанс.я;
        if (!ReferenceEquals(в, _стучали_на) && СТУЧАТ.Contains(в.вопрос))
        {
            _стучали_на = в;
            Стук(я.apt);
        }
        var память = я.memory;
        if (_память_услышано < 0 || _память_услышано > память.Count)
            _память_услышано = память.Count;          // первая жизнь вопроса или память старела
        var было = new HashSet<(string, string)>();
        for (int i = _память_услышано; i < память.Count && было.Count < СЛЫШНО_РАЗОМ; i++)
        {
            var з = память[i];
            if (з.вид != Вид.СЛЫШАЛ || з.день != h.day || з.что is not string что
                || !СЛЫШНО.TryGetValue(что, out var звук)
                || !было.Add((что, з.кто)) || h.get(з.кто) is not NPC кто)
                continue;
            if (_мир.УДвери(h.where(кто).apt) is Vector3 место)
                Звук_у(звук.звук, место + new Vector3(0, 1.2f, 0), звук.дб, звук.секунд);
        }
        _память_услышано = память.Count;
        // ранили в драке: ушиб, порез, перелом — удар; огнестрел — выстрел
        if (_ран_было >= 0 && я.injuries.Count > _ран_было)
            foreach (var рана in я.injuries.Skip(_ран_было))
            {
                if (рана.Contains("огнестрел", System.StringComparison.Ordinal))
                    Звуки.Сыграть(_звук, "выстрел_пистолет", 2f);
                else if (рана.Contains("ушиб", System.StringComparison.Ordinal)
                         || рана.Contains("порез", System.StringComparison.Ordinal)
                         || рана.Contains("перелом", System.StringComparison.Ordinal))
                    Звуки.Сыграть(_звук, "удар", 0f);
            }
        _ран_было = я.injuries.Count;
    }

    /// <summary>Звук в точке мира: разовый — целиком, длинный — куском.</summary>
    private void Звук_у(string имя, Vector3 где, float дб = 0f, float секунд = 0f)
    {
        if (Звуки.Взять(имя) is not { } поток)
            return;
        var п = Звуки.Точка(_звук, имя, где, громкость: дб, размер: 4f, дальше_не: 40f);
        Звуки.Пустить(п, поток, дб, секунд);
    }

    /// <summary>Стук в дверь квартиры: деревянная — глухо, крепкая или
    /// обитая листами — металлом.</summary>
    private void Стук(int кв)
    {
        if (_партия is null || _мир.УДвери(кв) is not Vector3 место)
            return;
        bool металл = _партия.сеанс.дом.flats.TryGetValue(кв, out var f)
                      && (f.shelter.Взять("листы", 0.0) > 0 || f.shelter.Взять("дверь", 0.0) >= 2);
        Звук_у(металл ? "стук_металл" : "стук_дерево", место + new Vector3(0, 1.2f, 0), 0f);
    }

    /// <summary>Взял ствол в руки — передёрнул затвор.</summary>
    private void Перезарядка(string что)
    {
        if (что is "пистолет" or "винтовка" or "дробовик")
            Звуки.Сыграть(_звук, $"перезарядка_{что}", -2f);
    }

    /// <summary>Поел у горящей печки — жарится, пару секунд.</summary>
    private void Жарка() => Звуки.Сыграть(_звук, "жарка", -6f, 4f);

    /// <summary>У двери участка: чем кончилось — звуками. Не открыл и выдержала —
    /// удары ломом; выломали — удары и стекло; с оружием — затвор (попятились)
    /// или выстрел; без патронов — щелчок; драка — удары.</summary>
    private void Звуки_гостей(Встреча как, ИтогВстречи итог, bool ствол, bool патроны, Vector3? у_двери)
    {
        Vector3 где = у_двери ?? _герой.GlobalPosition;
        var очередь = new List<(double через, System.Action что)>();
        if (как == Встреча.НЕ_ОТКРЫВАТЬ || итог.ворвались)
        {
            очередь.Add((0.0, () => Звук_у("удар_по_металлу", где, 0f)));
            очередь.Add((0.7, () => Звук_у("удар_по_металлу", где, 0f)));
            if (итог.ворвались)
                очередь.Add((1.4, () => Звук_у("стекло", где, -2f)));
        }
        double т = очередь.Count > 0 ? 2.0 : 0.0;
        if (как == Встреча.ВСТРЕТИТЬ && ствол && !патроны)
            очередь.Add((т, () => Звуки.Сыграть(_звук, "осечка", 0f)));
        if (итог.весть.Contains("выстрелил", System.StringComparison.Ordinal))
            очередь.Add((т + 0.3, () => Звуки.Сыграть(_звук, "выстрел_пистолет", 3f)));
        else if (итог.весть.Contains("попятились", System.StringComparison.Ordinal) && ствол)
            очередь.Add((т, () => Перезарядка(_партия?.сеанс.я.weapon switch
            {
                Оружие.ДРОБОВИК => "дробовик",
                Оружие.ВИНТОВКА => "винтовка",
                _ => "пистолет",
            })));
        if (итог.весть.Contains("сцепились", System.StringComparison.Ordinal)
            || итог.весть.Contains("избили", System.StringComparison.Ordinal))
        {
            очередь.Add((т + 0.4, () => Звуки.Сыграть(_звук, "удар", 0f)));
            очередь.Add((т + 0.9, () => Звуки.Сыграть(_звук, "удар", -2f)));
        }
        foreach (var (через, что) in очередь)
        {
            if (через <= 0)
                что();
            else
                GetTree().CreateTimer(через).Timeout += что;
        }
    }
}
