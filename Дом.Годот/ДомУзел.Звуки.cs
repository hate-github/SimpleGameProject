// Звуки того, что герой слышит и делает (записи автора, `звуки/ЧИТАЙ.md`).
//
// Что звучит и у какой двери — решает `Дом.Экран.Слух`: слой без движка,
// его сверяет консоль (раздел «звуки»). Здесь — только где это в мире
// и когда:
//   · на каждом новом вопросе — что слышно с прошлого: шум за стеной
//     (память героя «слышал»), события, крик на лестнице, свои раны,
//     сообщение в чате; стучат в его дверь;
//   · его ответ — звуки его дела: поел, попил, затопил, строит, разбирает;
//     открыл на стук;
//   · раз в полминуты — кашель и плач (`Слух.Фон`): свой — всегда, сосед
//     на лестнице — от фигуры, за дверью — только на этаже героя;
//   · дверь соседа открылась на разговор и закрылась, когда герой отошёл;
//     до метели в дверь звонят, в метель — стучат.
// Громкость за стеной — дело симуляции: что герой услышал, ядро уже
// решило, и узел этого не пересчитывает.

using Godot;
using Дом.Ядро;
using Дом.Экран;

namespace Дом.Годот;

public partial class ДомУзел
{
    private int _память_услышано = -1;          // сколько записей памяти героя уже прозвучало
    private int _строк_услышано = -1;           // сколько строк ленты уже прочитано на слух
    private int _ран_было = -1;                 // сколько ран было на прошлом вопросе
    private ВопросИгроку? _стучали_на;          // на какой вопрос уже стучали
    private int _звук_n;                        // какой из вариантов записи — по очереди
    private double _фон_через = 20.0;           // секунд до следующего кашля или плача
    private int? _дверь_беседы;                 // у чьей двери открыли на разговор

    /// <summary>Номер варианта записи: подряд одинаковые не звучат.</summary>
    private int Следующий() => _звук_n++;

    /// <summary>Новая жизнь или поднятая из сохранения: счёт услышанного,
    /// ран и строк — с неё, иначе прежняя память прозвучала бы разом.</summary>
    private void Звуки_сначала()
    {
        _память_услышано = -1;
        _строк_услышано = -1;
        _ран_было = -1;
        _стучали_на = null;
        _дверь_беседы = null;
        _фон_через = 20.0;
    }

    /// <summary>
    /// На каждом новом вопросе, пока дом спит: к нему стучат; что слышно
    /// с прошлого вопроса — у двери, где было (`Слух.Новое`); новое
    /// сообщение в чате — телефон пискнул.
    /// </summary>
    private void Звуки_вопроса(ВопросИгроку в)
    {
        if (_партия is null)
            return;
        var h = _партия.сеанс.дом;
        var я = _партия.сеанс.я;
        if (!ReferenceEquals(в, _стучали_на) && Слух.СТУЧАТ.Contains(в.вопрос))
        {
            _стучали_на = в;
            Стук(Слух.Своя_дверь(h, я));
        }
        var память = я.memory;
        var события = _партия.сеанс.события;
        int строк = _партия.сеанс.СтрокВЛенте;
        // первый вопрос жизни — или список стал короче (память старела): с него
        if (_память_услышано < 0 || _память_услышано > память.Count)
            _память_услышано = память.Count;
        if (_строк_услышано < 0 || _строк_услышано > строк)
            _строк_услышано = строк;
        if (_ран_было < 0 || _ран_было > я.injuries.Count)
            _ран_было = я.injuries.Count;
        if (_событий_услышано > события.Count)
            _событий_услышано = события.Count;
        var строки = _партия.сеанс.ЛентаПосле(_строк_услышано);
        Пустить(Слух.Новое(h, я,
                           память.Skip(_память_услышано).ToList(),
                           события.Skip(_событий_услышано).ToList(),
                           строки,
                           я.injuries.Skip(_ран_было).ToList()));
        if (Слух.Сообщений(я, строки) > 0)
            Уведомление();
        _память_услышано = память.Count;
        _событий_услышано = события.Count;
        _строк_услышано += строки.Count;
        _ран_было = я.injuries.Count;
    }

    /// <summary>Ответ героя — звуки его дела (зовётся, пока дом спит, до ответа).</summary>
    private void Звуки_ответа(ВопросИгроку в, int номер)
    {
        if (_партия is null)
            return;
        Пустить(Слух.Ответ(_партия.сеанс.дом, _партия.сеанс.я, в, номер, Следующий()));
    }

    /// <summary>Своё дело в участке, в убежище, по распорядку: те же звуки,
    /// что у дела дома (<paramref name="ключ"/> — ключ справочника или «дрова»).</summary>
    private void Своё_дело(string ключ, bool печь = false)
        => Пустить(Слух.Дело(ключ, печь, Следующий()));

    /// <summary>Отзвуки — каждый через свою задержку.</summary>
    private void Пустить(IReadOnlyList<Отзвук> отзвуки)
    {
        foreach (var о in отзвуки)
        {
            var это = о;
            if (это.через <= 0)
                Прозвучать(это);
            else
                GetTree().CreateTimer(это.через).Timeout += () => Прозвучать(это);
        }
    }

    /// <summary>У двери — точкой в мире; без места — у самого героя.</summary>
    private void Прозвучать(Отзвук о)
    {
        if (о.квартира is not int кв)
            Звуки.Сыграть(_звук, о.запись, о.дб, о.секунд);
        else if (_мир.УДвери(кв) is Vector3 место)
            Звук_у(о.запись, место + new Vector3(0, 1.2f, 0), о.дб, о.секунд);
    }

    /// <summary>Звук в точке мира: разовый — целиком, длинный — куском.</summary>
    private void Звук_у(string имя, Vector3 где, float дб = 0f, float секунд = 0f)
    {
        if (Звуки.Взять(имя) is not { } поток)
            return;
        var п = Звуки.Точка(_звук, имя, где, громкость: дб, размер: 4f, дальше_не: 40f);
        Звуки.Пустить(п, поток, дб, секунд);
    }

    /// <summary>Стук в дверь квартиры: деревянная — глухо, крепкая или
    /// обитая листами — металлом.</summary>
    private void Стук(int кв)
    {
        if (_партия is null || _мир.УДвери(кв) is not Vector3 место)
            return;
        Звук_у(Слух.Стук(_партия.сеанс.дом, кв), место + new Vector3(0, 1.2f, 0));
    }

    /// <summary>Звонок в дверь: до метели свет есть — звонят, а не стучат.</summary>
    private void Звонок(int кв)
    {
        if (_мир.УДвери(кв) is Vector3 место)
            Звук_у("звонок", место + new Vector3(0, 1.6f, 0), -2f);
    }

    /// <summary>Телефон пискнул: сообщение в чате, СМС банка, курьер.</summary>
    private void Уведомление() => Звуки.Сыграть(_звук, "уведомление", -4f);

    /// <summary>Сосед открыл на разговор: дверь открывается после стука
    /// и закроется, когда герой отойдёт (окно беседы закрыто).</summary>
    private void Открыл_сосед(int кв, double через)
    {
        _дверь_беседы = кв;
        Пустить(new[] { new Отзвук("дверь_открыть", кв, -2f, через: через) });
    }

    /// <summary>Окно закрыто — если это была беседа у двери, дверь закрылась.</summary>
    private void Беседа_кончилась()
    {
        if (_дверь_беседы is not int кв)
            return;
        _дверь_беседы = null;
        Пустить(new[] { new Отзвук("дверь_закрыть", кв, -2f, через: 0.3) });
    }

    /// <summary>Взял ствол в руки — передёрнул затвор.</summary>
    private void Перезарядка(string что)
    {
        if (Слух.Перезарядка(что) is string запись)
            Звуки.Сыграть(_звук, запись, -2f);
    }

    /// <summary>Какой ствол у героя — словом, как в руках.</summary>
    private static string Ствол(Оружие w) => w switch
    {
        Оружие.ДРОБОВИК => "дробовик",
        Оружие.ВИНТОВКА => "винтовка",
        _ => "пистолет",
    };

    /// <summary>
    /// Раз в полминуты — кашель или плач (`Слух.Фон`): свой кашель — всегда;
    /// сосед на лестнице — от фигуры, если рядом; за дверью — только
    /// на этаже, где стоит герой. Дом читается, только пока спит.
    /// </summary>
    private void Фон_кадр(double delta)
    {
        if (_партия is null || !Дом_спит)
            return;
        _фон_через -= delta;
        if (_фон_через > 0)
            return;
        _фон_через = 18.0 + GD.Randf() * 24.0;
        var голоса = Слух.Фон(_партия.сеанс.дом, _партия.сеанс.я);
        if (голоса.Count == 0)
            return;
        var где_я = _герой.GlobalPosition;
        int? этаж = _мир.ВДоме(где_я) ? Mathf.FloorToInt((где_я.Y + 0.6f) / Мир.ЭТАЖ) + 1 : null;
        var слышно = new List<(Голосок г, Vector3? где)>();
        foreach (var г in голоса)
        {
            if (г.квартира is not int кв)
                слышно.Add((г, null));
            else if (_мир.Где_сосед(г.кто) is Vector3 фигура && фигура.DistanceTo(где_я) < 14f)
                слышно.Add((г, фигура));
            else if (этаж is int э && Мир.Этаж(кв) == э && _мир.УДвери(кв) is Vector3 дверь)
                слышно.Add((г, дверь + new Vector3(0, 1.2f, 0)));
        }
        if (слышно.Count == 0)
            return;
        var (кто, место) = слышно[(int)(GD.Randi() % (uint)слышно.Count)];
        string запись = кто.записи[(int)(GD.Randi() % (uint)кто.записи.Count)];
        if (место is Vector3 м)
            Звук_у(запись, м, кто.дб);
        else
            Звуки.Сыграть(_звук, запись, кто.дб);
    }

    /// <summary>У двери участка: чем кончилось — звуками. Не открыл и выдержала —
    /// удары ломом; выломали — удары и стекло; с оружием — затвор (попятились)
    /// или выстрел своего ствола; без патронов — щелчок; драка — удары.</summary>
    private void Звуки_гостей(Встреча как, ИтогВстречи итог, bool ствол, bool патроны, Vector3? у_двери)
    {
        Vector3 где = у_двери ?? _герой.GlobalPosition;
        var оружие = _партия?.сеанс.я.weapon ?? Оружие.НЕТ;
        var очередь = new List<(double через, System.Action что)>();
        if (как == Встреча.НЕ_ОТКРЫВАТЬ || итог.ворвались)
        {
            // дверь участка железная
            очередь.Add((0.0, () => Звук_у("удар_по_металлу", где, 0f)));
            очередь.Add((0.7, () => Звук_у("удар_по_металлу", где, 0f)));
            if (итог.ворвались)
                очередь.Add((1.4, () => Звук_у("стекло", где, -2f)));
        }
        double т = очередь.Count > 0 ? 2.0 : 0.0;
        if (как == Встреча.ВСТРЕТИТЬ && ствол && !патроны)
            очередь.Add((т, () => Звуки.Сыграть(_звук, "осечка", 0f)));
        if (итог.весть.Contains("выстрелил", System.StringComparison.Ordinal))
            очередь.Add((т + 0.3, () => Звуки.Сыграть(_звук, Слух.Выстрел(оружие), 3f)));
        else if (итог.весть.Contains("попятились", System.StringComparison.Ordinal) && ствол)
            очередь.Add((т, () => Перезарядка(Ствол(оружие))));
        if (итог.весть.Contains("сцепились", System.StringComparison.Ordinal)
            || итог.весть.Contains("избили", System.StringComparison.Ordinal))
        {
            очередь.Add((т + 0.4, () => Звуки.Сыграть(_звук, "удар", 0f)));
            очередь.Add((т + 0.9, () => Звуки.Сыграть(_звук, "удар", -2f)));
        }
        foreach (var (через, что) in очередь)
        {
            if (через <= 0)
                что();
            else
                GetTree().CreateTimer(через).Timeout += что;
        }
    }
}
