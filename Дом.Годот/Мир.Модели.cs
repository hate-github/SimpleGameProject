// Модели автора в мире (сентябрь 2026, `модели/еда/`, `модели/двор/`):
// еда на полках и урны со скамейками во дворе.
//
// В каждом файле еды лежат **варианты одного предмета в одной точке**:
// у хлеба — целый, половина, ломоть, свежий и в плесени; у банок —
// закрытая, открытая полная, половина, пустая, свежая и просроченная.
// Поэтому меш выбирается **по имени варианта** («beef unopen fresh»,
// «full fresh»), а не по номеру: порядок деталей в файле — порядок
// экспорта, и художник вправе его поменять. Имя — договор, как у гаража
// (`модели/ЧИТАЙ.md`).
//
// Размер задаётся в метрах по большей стороне — банка десять сантиметров,
// батон двадцать восемь, — а сколько это в единицах модели, мир
// спрашивает у неё сам: шкала у каждого файла своя (урна в модели
// больше скамейки), а вверх у всех Z, как у прежних.
//
// Порчи еды в доме нет, и испорченные варианты пока не показываются:
// они импортированы и ждут механики, которая скажет, что еда
// испортилась.

using Godot;

namespace Дом.Годот;

public partial class Мир
{
    /// <summary>Еда на полки: модель, вариант (часть имени меша), размер по
    /// большей стороне в метрах, поворот вокруг вертикали (хлеб — поперёк
    /// полки). Порядок — чередование на полке.</summary>
    private static readonly (string путь, string меш, float размер, float поворот)[] ЕДА =
    {
        ("res://модели/еда/Canned beef.fbx", "beef unopen fresh", 0.10f, 0),
        ("res://модели/еда/Loaf.fbx", "full fresh", 0.28f, 90),
        ("res://модели/еда/Canned sprats.fbx", "sprats unopen fresh", 0.10f, 0),
        ("res://модели/еда/Canned pork.fbx", "pork unopen fresh", 0.10f, 0),
        ("res://модели/еда/Black bread.fbx", "full fresh", 0.22f, 90),
        ("res://модели/еда/Canned condensed milk.fbx", "condensed milk unopen", 0.09f, 0),
    };

    /// <summary>Банки — то, что лежит в НЗ бункера.</summary>
    private static readonly int[] КОНСЕРВЫ = { 0, 3, 2, 5 };

    private const string УРНА = "res://модели/двор/Trash can.fbx";
    private const string СКАМЕЙКА = "res://модели/двор/Bench.fbx";

    // меш и его рамка по (путь, вариант): сцену модели не разворачивать
    // на каждую банку — их на полках магазина полторы сотни
    private static readonly Dictionary<(string, string, bool), (Mesh меш, Aabb рамка)?> _меши = new();

    /// <param name="двусторонне">Рисовать грани с обеих сторон. Для
    /// вывернутых моделей (витрина: «НАИЗНАНКУ» — скамейка и обе урны,
    /// сентябрь 2026): односторонне у них видна изнанка — дальняя стенка
    /// сквозь ближнюю. С обеих сторон Godot у обратной грани сам
    /// переворачивает нормаль, и свет ложится правильно. Копия меша —
    /// одна на все урны, не на каждую.</param>
    private static (Mesh меш, Aabb рамка)? Меш_модели(string путь, string вариант, bool двусторонне = false)
    {
        if (_меши.TryGetValue((путь, вариант, двусторонне), out var есть))
            return есть;
        (Mesh, Aabb)? найдено = null;
        var сцена = ResourceLoader.Exists(путь) ? GD.Load<PackedScene>(путь) : null;
        if (сцена is not null)
        {
            var образец = сцена.Instantiate<Node3D>();
            var меши = new List<MeshInstance3D>();
            Найти(образец, меши);
            var м = меши.FirstOrDefault(x => x.Name.ToString().Contains(вариант, StringComparison.OrdinalIgnoreCase));
            if (м?.Mesh is { } меш)
            {
                if (двусторонне)
                {
                    var копия = (Mesh)меш.Duplicate();
                    for (int п = 0; п < копия.GetSurfaceCount(); п++)
                        if (м.GetActiveMaterial(п) is BaseMaterial3D мат)
                        {
                            var с_обеих = (BaseMaterial3D)мат.Duplicate();
                            с_обеих.CullMode = BaseMaterial3D.CullModeEnum.Disabled;
                            копия.SurfaceSetMaterial(п, с_обеих);
                        }
                    меш = копия;
                }
                найдено = (меш, меш.GetAabb());
            }
            образец.Free();
        }
        _меши[(путь, вариант, двусторонне)] = найдено;
        return найдено;
    }

    /// <summary>
    /// Вещь из модели автора: вариант по имени, большая сторона —
    /// <paramref name="размер"/> метров, низ — на <paramref name="где"/>.Y,
    /// середина — над <paramref name="где"/> (не там, где у модели ноль:
    /// на полке банки встают по разметке, а не по тому, как их выгрузили).
    /// Z-вверх модели → Y-вверх мира. <paramref name="форма"/> — твёрдая
    /// (урна, скамейка): коробка по рамке модели, в метрах мира, а не
    /// внутри масштаба — тела под масштабом Godot считает плохо.
    /// Нет модели — null, и зовущий ставит заглушку.
    /// </summary>
    private Node3D? Вещь_модели(string путь, string вариант, float размер, Vector3 где, float поворот,
                                bool форма = false, bool двусторонне = false)
    {
        if (Меш_модели(путь, вариант, двусторонне) is not { } м)
            return null;
        var рамка = м.рамка;
        float больше = Math.Max(рамка.Size.X, Math.Max(рамка.Size.Y, рамка.Size.Z));
        if (больше <= 1e-6f)
            return null;
        float масштаб = размер / больше;
        var середина = рамка.GetCenter();
        var узел = new Node3D
        {
            RotationDegrees = new Vector3(-90, поворот, 0),
            Scale = Vector3.One * масштаб,
            Position = где,
        };
        узел.AddChild(new MeshInstance3D
        {
            Mesh = м.меш,
            Position = new Vector3(-середина.X, -середина.Y, -рамка.Position.Z),
        });
        AddChild(узел);
        if (форма)
        {
            // после поворота местная Y модели лежит вдоль мировой Z
            var размеры = new Vector3(рамка.Size.X, рамка.Size.Z, рамка.Size.Y) * масштаб;
            var тело = new StaticBody3D
            {
                Position = где with { Y = где.Y + размеры.Y / 2 },
                RotationDegrees = new Vector3(0, поворот, 0),
            };
            тело.AddChild(new CollisionShape3D { Shape = new BoxShape3D { Size = размеры } });
            AddChild(тело);
        }
        return узел;
    }

    /// <summary>Еда номер <paramref name="номер"/> из чередования — моделью;
    /// нет модели — коробочка цвета еды, как было.</summary>
    private Node3D Еда_на_место(int номер, Vector3 где, float поворот = 0)
    {
        var (путь, меш, размер, свой) = ЕДА[((номер % ЕДА.Length) + ЕДА.Length) % ЕДА.Length];
        return Вещь_модели(путь, меш, размер, где, свой + поворот)
               ?? Меш(Материал(new Color("#8a6a4a"), 0.6f), new Vector3(0.12f, 0.16f, 0.12f),
                      где with { Y = где.Y + 0.08f });
    }

    /// <summary>
    /// Выкладка одного товара на полке, что тянется вдоль X: поперёк —
    /// сколько влезет в <paramref name="ширина"/>, но не больше четырёх;
    /// вглубь — две банки или один хлеб (хлеб лежит поперёк доски, вдоль Z).
    /// <paramref name="где"/> — середина выкладки на доске. Банки чуть
    /// повёрнуты каждая по-своему: ровный строй этикеток читается как
    /// текстура, а не как полка. <paramref name="консервы"/> — только банки
    /// (НЗ в бункере).
    /// </summary>
    private void Выкладка(int номер, Vector3 где, float ширина, bool консервы = false)
    {
        int какой = консервы
            ? КОНСЕРВЫ[((номер % КОНСЕРВЫ.Length) + КОНСЕРВЫ.Length) % КОНСЕРВЫ.Length]
            : ((номер % ЕДА.Length) + ЕДА.Length) % ЕДА.Length;
        bool хлеб = ЕДА[какой].поворот != 0;
        float шаг = хлеб ? 0.14f : 0.115f;
        int поперёк = Math.Clamp((int)(ширина / шаг), 1, 4);
        int вглубь = хлеб ? 1 : 2;
        for (int а = 0; а < поперёк; а++)
            for (int б = 0; б < вглубь; б++)
            {
                var сдвиг = new Vector3((а - (поперёк - 1) / 2f) * шаг, 0, (б - (вглубь - 1) / 2f) * 0.12f);
                float поворот = хлеб ? -90 : ((номер * 7 + а * 37 + б * 53) % 41) - 20;
                Еда_на_место(какой, где + сдвиг, поворот);
            }
    }

    // ---------- двор: урны и скамейки ----------

    private readonly List<(Node3D полная, Node3D пустая)> _урны = new();

    /// <summary>
    /// Урны и скамейки по гнёздам сцены (`урна…`, `скамейка…`): место
    /// и поворот из точки, размер — из её масштаба по Y (1 — урна
    /// в 0.8 м, скамейка в метр восемьдесят). Твёрдые: сквозь них не ходят,
    /// и соседи обходят их по сетке. Скамейка при повороте 0 стоит
    /// спинкой к дому (спинка у модели по −Y, после поворота — по +Z).
    /// У урны два вида в одной рамке — полная и выгребленная; какой
    /// показывать, решает двор в доме (`Урны_обшарены`).
    /// </summary>
    private void Двор_вещи()
    {
        _урны.Clear();
        foreach (var (_, где) in Гнёзда("урна"))
        {
            float поворот = Mathf.RadToDeg(где.Basis.Orthonormalized().GetEuler().Y);
            float размер = 0.8f * Math.Max(0.2f, где.Basis.Scale.Y);
            var полная = Вещь_модели(УРНА, "not looted", размер, где.Origin, поворот,
                                     форма: true, двусторонне: true);
            if (полная is null)
                continue;
            // «can looted», а не «looted»: второе есть и в «not looted»
            var пустая = Вещь_модели(УРНА, "can looted", размер, где.Origin, поворот, двусторонне: true);
            if (пустая is null)
                continue;
            пустая.Visible = false;
            _урны.Add((полная, пустая));
        }
        foreach (var (_, где) in Гнёзда("скамейка"))
            Вещь_модели(СКАМЕЙКА, "Bench", 1.8f * Math.Max(0.2f, где.Basis.Scale.Y), где.Origin,
                        Mathf.RadToDeg(где.Basis.Orthonormalized().GetEuler().Y),
                        форма: true, двусторонне: true);
    }

    /// <summary>Двор выгребли — урны перевёрнуты и пусты (вид «looted»).</summary>
    public void Урны_обшарены(bool да)
    {
        foreach (var (полная, пустая) in _урны)
        {
            полная.Visible = !да;
            пустая.Visible = да;
        }
    }
}
