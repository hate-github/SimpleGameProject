// Бомбоубежище гражданской обороны под пустырём (ГДД 20, 22): тамбур
// с лазом наверх, гермодверь со штурвалом, зал — нары, стеллаж с запасом,
// буржуйка, фильтровентиляционный агрегат с ручным приводом.
//
// Отдельная комната далеко от двора, как магазин и участок, — сюда
// переносит поход, если герой знает вход. Считать бункер — дело
// `Дом.Ядро.Бункер`; здесь только бетон, гермодверь и места, у которых
// что-то делается. Гермодверь твёрдая, пока её не открыли
// (`Гермодверь_открыта`): до того из тамбура в зал не пройти.
//
// Всё — коробки: моделей бункера у проекта нет, и места под них
// (нары, стеллаж, агрегат, буржуйка) — те же `Предмет`ы, что встанут
// под модели автора.

using Godot;

namespace Дом.Годот;

public partial class Мир
{
    /// <summary>Где бункер — далеко от двора, магазина и участка, и ниже
    /// земли двора: земля там не должна пройти сквозь пол зала.</summary>
    private static readonly Vector3 БУНКЕР = new(0, -60, 300);
    private const float БУН_Ш = 10f, БУН_Г = 6f, БУН_В = 2.4f, ТАМБУР_Г = 3f;

    public Предмет? Гермодверь { get; private set; }
    public Предмет? НарыБункера { get; private set; }
    public Предмет? ЗапасБункера { get; private set; }
    public Предмет? ПечьБункера { get; private set; }
    public Предмет? ВентиляцияБункера { get; private set; }
    public Предмет? ЛазБункера { get; private set; }

    /// <summary>Где встаёт спустившийся: в тамбуре, лицом к гермодвери.</summary>
    public Vector3 ВходБункера => БУНКЕР + new Vector3(0, 0.1f, БУН_Г / 2 + ТАМБУР_Г - 0.9f);

    /// <summary>Где проснётся живущий под землёй — у нар.</summary>
    public Vector3 У_нар_бункера => БУНКЕР + new Vector3(-3.0f, 0.1f, -0.5f);

    /// <summary>Он ли под землёй — в зале или в тамбуре.</summary>
    public bool ВБункере(Vector3 где)
        => Math.Abs(где.X - БУНКЕР.X) < БУН_Ш / 2 + 0.5f
           && где.Z > БУНКЕР.Z - БУН_Г / 2 - 0.5f && где.Z < БУНКЕР.Z + БУН_Г / 2 + ТАМБУР_Г + 0.5f
           && где.Y > БУНКЕР.Y - 1 && где.Y < БУНКЕР.Y + БУН_В + 1;

    private StaticBody3D? _гермодверь;
    private Vector3 _гермодверь_закрыта;

    /// <summary>Гермодверь открыли — отошла к стене, пройти можно.</summary>
    public void Гермодверь_открыта(bool да)
    {
        if (_гермодверь is null)
            return;
        _гермодверь.Position = да ? _гермодверь_закрыта + new Vector3(0.75f, 0, 0.55f) : _гермодверь_закрыта;
        _гермодверь.Rotation = да ? new Vector3(0, Mathf.Pi / 2, 0) : Vector3.Zero;
        _гермодверь.CollisionLayer = да ? 0u : 1u;
    }

    /// <summary>Тамбур, гермодверь, зал с нарами, стеллажом, буржуйкой
    /// и агрегатом вентиляции; лаз наверх.</summary>
    private void Бункер_построить()
    {
        var бетон = Материал(new Color("#4e4c47"), 0.95f);
        var пол = Материал(new Color("#2e2c28"), 0.9f);
        var краска = Материал(new Color("#4a5a48"), 0.7f);          // зелёная краска ГО
        var металл = Материал(new Color("#565c60"), 0.5f);
        var ржавчина = Материал(new Color("#6a4a34"), 0.8f);
        var доска = Материал(new Color("#56462f"), 0.9f);
        Vector3 О(float x, float y, float z) => БУНКЕР + new Vector3(x, y, z);
        float ш = БУН_Ш / 2, г = БУН_Г / 2, т = ТАМБУР_Г;

        // зал
        Коробка(пол, new Vector3(БУН_Ш + 0.4f, 0.2f, БУН_Г + т + 0.4f), О(0, -0.1f, т / 2));
        Коробка(бетон, new Vector3(БУН_Ш + 0.4f, 0.3f, БУН_Г + т + 0.4f), О(0, БУН_В + 0.15f, т / 2));
        Коробка(бетон, new Vector3(0.3f, БУН_В, БУН_Г), О(-ш - 0.15f, БУН_В / 2, 0));
        Коробка(бетон, new Vector3(0.3f, БУН_В, БУН_Г), О(ш + 0.15f, БУН_В / 2, 0));
        Коробка(бетон, new Vector3(БУН_Ш, БУН_В, 0.3f), О(0, БУН_В / 2, -г - 0.15f));
        // стена между залом и тамбуром — с проёмом под гермодверь
        Коробка(бетон, new Vector3(ш - 0.6f, БУН_В, 0.4f), О(-(ш + 0.6f) / 2, БУН_В / 2, г));
        Коробка(бетон, new Vector3(ш - 0.6f, БУН_В, 0.4f), О((ш + 0.6f) / 2, БУН_В / 2, г));
        Коробка(бетон, new Vector3(1.2f, БУН_В - 1.9f, 0.4f), О(0, 1.9f + (БУН_В - 1.9f) / 2, г));
        // тамбур: 2.4 в ширину
        Коробка(бетон, new Vector3(0.3f, БУН_В, т), О(-1.35f, БУН_В / 2, г + т / 2));
        Коробка(бетон, new Vector3(0.3f, БУН_В, т), О(1.35f, БУН_В / 2, г + т / 2));
        Коробка(бетон, new Vector3(2.4f, БУН_В, 0.3f), О(0, БУН_В / 2, г + т + 0.15f));

        // гермодверь со штурвалом: плита в проёме, пока не открыли
        _гермодверь_закрыта = О(0, 0.95f, г + 0.28f);
        _гермодверь = Коробка(краска, new Vector3(1.2f, 1.9f, 0.16f), _гермодверь_закрыта);
        _гермодверь.Name = "гермодверь";
        var штурвал = new MeshInstance3D
        {
            Mesh = new TorusMesh { InnerRadius = 0.18f, OuterRadius = 0.24f },
            MaterialOverride = ржавчина,
            Position = new Vector3(0, 0.1f, 0.12f),
            Rotation = new Vector3(Mathf.Pi / 2, 0, 0),
        };
        _гермодверь.AddChild(штурвал);
        Гермодверь = Предмет.Вокруг(this, new Aabb(О(-0.7f, 0, г + 0.2f), new Vector3(1.4f, 1.9f, 0.5f)),
                                    0.05f, "гермодверь_бункера");

        // лаз наверх: скобы в стене тамбура
        for (int i = 0; i < 6; i++)
            Меш(металл, new Vector3(0.5f, 0.04f, 0.04f), О(0, 0.3f + i * 0.35f, г + т - 0.05f));
        ЛазБункера = Предмет.Вокруг(this, new Aabb(О(-0.5f, 0, г + т - 0.5f), new Vector3(1.0f, БУН_В, 0.5f)),
                                    0.05f, "лаз_бункера");

        // нары в два яруса у левой стены
        for (int ярус = 0; ярус < 2; ярус++)
            Коробка(доска, new Vector3(0.9f, 0.08f, 2.0f), О(-ш + 0.55f, 0.45f + ярус * 0.95f, -0.5f));
        Коробка(металл, new Vector3(0.06f, 1.5f, 0.06f), О(-ш + 0.12f, 0.75f, -1.45f));
        Коробка(металл, new Vector3(0.06f, 1.5f, 0.06f), О(-ш + 0.98f, 0.75f, 0.45f));
        НарыБункера = Предмет.Вокруг(this, new Aabb(О(-ш + 0.1f, 0, -1.5f), new Vector3(1.0f, 1.5f, 2.0f)),
                                     0.05f, "нары_бункера");

        // стеллаж с НЗ у задней стены и бак с технической водой рядом
        Коробка(доска, new Vector3(3.0f, 1.9f, 0.5f), О(0, 0.95f, -г + 0.3f));
        for (int ряд = 0; ряд < 3; ряд++)
            for (int i = 0; i < 5; i++)
                Меш(Материал(ЦВЕТА_ТОВАРА[(i + 2 * ряд) % ЦВЕТА_ТОВАРА.Length], 0.85f),
                    new Vector3(0.45f, 0.3f, 0.35f), О(-1.0f + i * 0.5f, 0.3f + ряд * 0.6f, -г + 0.62f));
        var бак = new MeshInstance3D
        {
            Mesh = new CylinderMesh { TopRadius = 0.45f, BottomRadius = 0.45f, Height = 1.4f },
            MaterialOverride = краска,
            Position = О(2.2f, 0.7f, -г + 0.6f),
        };
        AddChild(бак);
        ЗапасБункера = Предмет.Вокруг(this, new Aabb(О(-1.5f, 0, -г + 0.1f), new Vector3(4.3f, 1.9f, 1.0f)),
                                      0.05f, "запас_бункера");

        // буржуйка у правой стены, труба — в вентиляционный короб
        Коробка(металл, new Vector3(0.6f, 0.8f, 0.6f), О(ш - 0.6f, 0.4f, 1.3f));
        Меш(металл, new Vector3(0.14f, БУН_В - 0.8f, 0.14f), О(ш - 0.6f, 0.8f + (БУН_В - 0.8f) / 2, 1.3f));
        ПечьБункера = Предмет.Вокруг(this, new Aabb(О(ш - 0.95f, 0, 0.95f), new Vector3(0.7f, 0.9f, 0.7f)),
                                     0.1f, "печь_бункера");

        // фильтровентиляционный агрегат с рукоятью привода
        Коробка(краска, new Vector3(0.9f, 1.3f, 1.2f), О(ш - 0.6f, 0.65f, -1.4f));
        Меш(ржавчина, new Vector3(0.05f, 0.05f, 0.5f), О(ш - 1.1f, 0.9f, -1.4f));
        Меш(металл, new Vector3(0.3f, 0.3f, 1.8f), О(ш - 0.6f, БУН_В - 0.2f, -1.2f));
        ВентиляцияБункера = Предмет.Вокруг(this, new Aabb(О(ш - 1.2f, 0, -2.05f), new Vector3(1.1f, 1.3f, 1.3f)),
                                           0.05f, "вентиляция_бункера");

        // аварийный свет: в зале и в тамбуре, тускло
        AddChild(new OmniLight3D
        {
            Position = О(0, БУН_В - 0.3f, 0),
            LightColor = new Color("#e0c890"),
            LightEnergy = 0.45f,
            OmniRange = 9f,
        });
        AddChild(new OmniLight3D
        {
            Position = О(0, БУН_В - 0.3f, г + т / 2),
            LightColor = new Color("#e0c890"),
            LightEnergy = 0.3f,
            OmniRange = 4f,
        });
        AddChild(new Label3D
        {
            Text = "УБЕЖИЩЕ № 14",
            FontSize = 72,
            PixelSize = 0.004f,
            Modulate = new Color("#c8c0a0"),
            Position = О(0, 2.12f, г + 0.21f),
            Shaded = false,
        });
    }
}
