// Без сознания — день для героя кончился (`Дом.Ядро.Положения`,
// `Дом.Экран.Беспамятство`). Пока так, герой ничего не делает сам: ответы
// дому с клавиш и из телефона не идут (`Ответить` отказывает), карман
// не открывается. А день проматывается — как у распорядка, по полчаса
// за шаг, и дом живёт эти часы; обратились к герою — отвечает молчанием
// (`Беспамятство.Ответ`), ночью спит. Очнулся — утро после побоев или
// здоровье снова выше порога — всё опять его.
//
// Первая версия этого не делала: положение запирало взгляд и ноги, а день
// шёл сам, минута за секунду, — до ночи пятнадцать минут взаперти, и при
// этом мысли дому отвечались: герой без сознания лечил сам себя сколько
// угодно раз (автор, 28.09.2026).

using Godot;
using Дом.Экран;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    private bool _отвечаю_за_героя;     // ответ за героя без сознания — не с клавиш

    /// <summary>Каждый кадр: без сознания и дом ждёт героя — шаг дня или ответ молчанием.</summary>
    private void Беспамятство_кадр()
    {
        if (_положение != Положение.БЕЗ_СОЗНАНИЯ || _партия is null || _пролог is not null || _дело.занят)
            return;
        if (_партия.Ждёт() is not { } в)
            return;                         // дом считает — ждать
        var я = _партия.сеанс.я;
        if (!я.alive)
            return;
        if (_распорядок is not null)
            Встать_из_распорядка("без сознания");
        int номер = Беспамятство.Ответ(в);
        if (номер < 0)
        {
            // день: полчаса прожить, дом проходит их; день кончился — дом сам спросит про ночь
            Прожить(System.Math.Min(ШАГ_РАСПОРЯДКА, я.time_left));
            Прошло(тихо: true);
            return;
        }
        GD.Print($"[без сознания] {Дом.Ядро.Вопросы.Все[в.вопрос]}: {в.варианты[номер].ключ}");
        _отвечаю_за_героя = true;
        try
        {
            Ответить(номер, играть: false);
        }
        finally
        {
            _отвечаю_за_героя = false;
        }
    }

    /// <summary>Без сознания отвечает не игрок: клавиши и телефон молчат.</summary>
    private bool Без_сознания_молчит()
    {
        if (_отвечаю_за_героя || _положение != Положение.БЕЗ_СОЗНАНИЯ)
            return false;
        Сказать(_положение.Текст());
        return true;
    }
}
