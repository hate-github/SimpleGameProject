// Герой от первого лица (ГДД 23).
//
// Ходит, смотрит, стучит в двери. Ничего не решает: подойти к двери —
// это не ответ на вопрос, а способ его задать. Что случится дальше,
// по-прежнему решает дом.
//
// Тело здесь тоже читается (ГДД 23): замёрзший идёт медленнее, у голодного
// шатается взгляд. Числа для этого приходят из `Дом.Экран.Подача` —
// те же самые, что красят края экрана, и другого источника у них нет.
//
// Шаги звучат по тому, на чём он стоит: снег, бетон, доски (`Шаги`,
// `Поверхность`). Поверхность приходит от тела под ногами — того же
// касания, которое цикл столкновений раньше просто пропускал.
//
// Мышь захватывается, пока никакой экран не открыт: телефон, карта,
// настройки и развёрнутый список вариантов отпускают её обратно, потому
// что в них тыкают курсором. Свёрнутый лист вопроса — не отпускает:
// при нём ходят.
//
// Ходьба — действия из настроек (`Управление`), а не буквы: какие клавиши
// ведут вперёд, решает игрок. Чувствительность мыши и инверсию ставит
// корневой узел — тоже из настроек.

using Godot;
using Дом.Экран;

namespace Дом.Годот;

public partial class Герой : CharacterBody3D
{
	/// <summary>Шаг обычного человека — не бегуна.</summary>
	[Export] public float Шаг { get; set; } = 2.4f;

	[Export] public float Чувствительность { get; set; } = 0.0022f;

	/// <summary>Множитель к чувствительности и инверсия взгляда по вертикали —
	/// из настроек (Esc).</summary>
	public float Множитель_мыши { get; set; } = 1f;
	public bool Инверсия_мыши { get; set; }

	private Camera3D _глаза = null!;
	private double _часы;

	/// <summary>Насколько плохо телу: замедляет и качает взгляд.
	/// Ставится корневым узлом из `Подача.Видно`.</summary>
	public double Дрожь { get; set; }

	/// <summary>Замедление от усталости и холода (ГДД 23).</summary>
	public double Тяжесть { get; set; }

	/// <summary>Ходить и вертеть головой можно, только когда не открыт
	/// ни один экран.</summary>
	public bool Свободен { get; set; } = true;

	/// <summary>
	/// Скован: экран не открыт, но ни шагу, ни поворота головы — идёт долгое
	/// дело (взлом, обыск), героя держат или он без сознания. Мышь при этом
	/// остаётся захваченной: камера и дело за неё не спорят, потому что
	/// камера стоит (задание автора, п. 5). Прицел остаётся на вещи, и дело
	/// не срывается оттого, что рука дрогнула.
	/// </summary>
	public bool Скован { get; set; }

	/// <summary>На что смотрит — квартира под прицелом или ничего.</summary>
	public int? Перед_дверью { get; private set; }

	/// <summary>Смотрит ли на входную дверь подъезда.</summary>
	public bool Перед_выходом { get; private set; }

	/// <summary>На какой предмет смотрит: замок, ящик, дверь погреба, верстак.
	/// Кладовые — гаражи и погреба — говорят только предметами.</summary>
	public Предмет? Перед_предметом { get; private set; }

	/// <summary>Обо что упёрся в этом кадре — имя узла, если упёрся.
	///
	/// Заведено потому, что трижды за перенос «герой не идёт» разбиралось
	/// по кадрам и трижды неверно, а `GetSlideCollision` называл виновника
	/// с первого раза. Читается при включённой слежке.</summary>
	public string Помеха { get; private set; } = "";

	public Camera3D глаза => _глаза;

	/// <summary>Как звучат шаги: разброс высоты и шанс скрипа досок.
	/// Ставятся до того, как герой встал в мир.</summary>
	public float Разброс_шагов { get; set; } = 0.03f;
	public float Скрип_шагов { get; set; } = 0.08f;

	/// <summary>По чему он идёт — поверхность тела под ногами.</summary>
	public string Под_ногами { get; private set; } = Поверхность.БЕТОН;

	private Шаги _шаги = null!;
	private float _путь;
	private const float ШАГ_ДЛИНА = 0.85f;     // метров пути на шаг

	public override void _Ready()
	{
		// Мебель кладовых лежит на своём слое: в неё упираются, но луч
		// сквозь неё видит, иначе коробку на верстаке не выбрать.
		CollisionMask = 1 | Хранилище.СЛОЙ_МЕБЕЛИ;

		var форма = new CollisionShape3D
		{
			Shape = new CapsuleShape3D { Height = 1.75f, Radius = 0.3f },
			Position = new Vector3(0, 0.875f, 0),
		};
		AddChild(форма);

		_глаза = new Camera3D
		{
			Position = new Vector3(0, 1.62f, 0),   // рост глаз, не макушки
			Fov = 72,
			Far = 60,
		};
		AddChild(_глаза);

		_луч = new RayCast3D
		{
			TargetPosition = new Vector3(0, 0, -2.2f),  // рука дотянется
			Enabled = true,
			// своя дверь распахнута, и вместо створки в проёме стоит
			// область: тело в нём не пропустило бы человека домой
			CollideWithAreas = true,
		};
		_глаза.AddChild(_луч);

		_шаги = new Шаги
		{
			Name = "шаги",
			Разброс = Разброс_шагов,
			СкрипШанс = Скрип_шагов,
		};
		AddChild(_шаги);

		Input.MouseMode = Input.MouseModeEnum.Captured;
	}

	private RayCast3D _луч = null!;

	/// <summary>Выпрямить взгляд: не вверх и не в пол. Зовётся, когда
	/// человека ставят на новое место, — иначе он смотрит туда же, куда
	/// смотрел в конце прошлой жизни.</summary>
	public void Прямо()
	{
		if (_глаза is not null)
			_глаза.Rotation = Vector3.Zero;
		_с_захвата = 0;
	}

	/// <summary>
	/// Сколько секунд назад захватили мышь.
	///
	/// Первое движение после захвата — не движение: система уводит курсор
	/// в середину окна, и разница приходит сразу на пол-экрана. Взгляд
	/// от этого разворачивает в потолок, и было это видно каждый раз,
	/// когда игра стартовала не по щелчку в окно.
	/// </summary>
	private double _с_захвата;

	private void Следить_за_захватом(double delta)
	{
		bool взята = Input.MouseMode == Input.MouseModeEnum.Captured;
		_с_захвата = взята ? _с_захвата + delta : 0;
	}

	public override void _UnhandledInput(InputEvent e)
	{
		// Esc мышь здесь больше не отпускает: он открывает настройки
		// (корневой узел), и выйти из игры можно оттуда
		if (e is InputEventMouseMotion м && Свободен && !Скован && _с_захвата > 0.25
			&& Input.MouseMode == Input.MouseModeEnum.Captured)
		{
			float к = Чувствительность * Множитель_мыши;
			RotateY(-м.Relative.X * к);
			_глаза.RotateX((Инверсия_мыши ? 1f : -1f) * м.Relative.Y * к);
			_глаза.Rotation = new Vector3(
				Mathf.Clamp(_глаза.Rotation.X, -1.4f, 1.4f), 0, 0);
		}
	}

	public override void _PhysicsProcess(double delta)
	{
		_часы += delta;
		Следить_за_захватом(delta);

		var v = Velocity;
		v.Y -= 12.0f * (float)delta;                   // тяжесть

		if (Свободен && !Скован)
		{
			var куда = Vector2.Zero;
			if (Управление.Зажато(Клавиши.ВПЕРЁД)) куда.Y -= 1;
			if (Управление.Зажато(Клавиши.НАЗАД)) куда.Y += 1;
			if (Управление.Зажато(Клавиши.ВЛЕВО)) куда.X -= 1;
			if (Управление.Зажато(Клавиши.ВПРАВО)) куда.X += 1;
			куда = куда.Normalized();

			// замёрзший и усталый идёт медленнее — это и есть «замедление»
			float скорость = Шаг * (float)(1.0 - 0.45 * Тяжесть);
			var шаг = (Transform.Basis * new Vector3(куда.X, 0, куда.Y))
					  .Normalized() * скорость;
			v.X = шаг.X;
			v.Z = шаг.Z;
		}
		else
		{
			v.X = 0;
			v.Z = 0;
		}

		Velocity = v;
		UpDirection = Vector3.Up;
		FloorMaxAngle = Mathf.DegToRad(60);            // по ступеням лезем сами
		MoveAndSlide();

		// Пол под ногами — тоже касание, и в списке он всегда. Помеха —
		// это то, что стоит поперёк: у него нормаль почти горизонтальна.
		Помеха = "";
		for (int i = 0; i < GetSlideCollisionCount(); i++)
		{
			var с = GetSlideCollision(i);
			if (Mathf.Abs(с.GetNormal().Y) > 0.7f)
			{
				Под_ногами = Поверхность.Чья(с.GetCollider());
				continue;
			}
			if (с.GetCollider() is Node кто)
				Помеха = Помеха.Length == 0 ? кто.Name.ToString()
										   : Помеха + "," + кто.Name;
		}

		// шаг — на каждые ШАГ_ДЛИНА пути по полу; тронулся — первый почти сразу
		float по_земле = new Vector2(Velocity.X, Velocity.Z).Length();
		if (IsOnFloor() && по_земле > 0.3f)
		{
			_путь += по_земле * (float)delta;
			if (_путь >= ШАГ_ДЛИНА)
			{
				_путь -= ШАГ_ДЛИНА;
				_шаги.Шагнуть(Под_ногами);
			}
		}
		else
			_путь = ШАГ_ДЛИНА * 0.7f;

		// взгляд качает от холода и паники: мелко и медленно, не тряской
		float кач = (float)Дрожь * 0.012f;
		_глаза.Position = new Vector3(
			Mathf.Sin((float)_часы * 1.7f) * кач,
			1.62f + Mathf.Sin((float)_часы * 2.3f) * кач,
			0);

		Перед_дверью = null;
		Перед_выходом = false;
		Перед_предметом = null;
		if (_луч.IsColliding() && _луч.GetCollider() is Предмет предмет)
			Перед_предметом = предмет;
		else if (_луч.IsColliding() && _луч.GetCollider() is Node узел)
		{
			string имя = узел.Name.ToString();
			if (имя.StartsWith("дверь", StringComparison.Ordinal)
				&& int.TryParse(имя[5..], out int кв))
				Перед_дверью = кв;
			else if (имя == "выход")
				Перед_выходом = true;
		}
	}
}
