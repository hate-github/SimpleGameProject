// Шаги героя: по чему идёт — так и звучит (записи и разметка поверхностей —
// в `Звуки.cs`).
//
// Высота шага — своя, записанная: разброс только на пару процентов, чтобы
// два шага подряд не были копией друг друга. Первая версия гуляла на ±8%,
// а доски опускала ещё на десятую-пятую, — и шаг звучал замедленной
// плёнкой. Разница между досками и бетоном — в громкости и скрипе,
// а не в высоте.
//
// Доски скрипят редко: скрип на каждом третьем шаге читался не как старый
// пол, а как пол, который вот-вот провалится. Теперь — примерно раз
// на дюжину шагов и не чаще раза в несколько секунд.

using Godot;

namespace Дом.Годот;

/// <summary>Шаги героя: одна нога — один источник, чтобы долгий
/// снежный шаг не обрывался следующим.</summary>
public partial class Шаги : Node
{
    private readonly AudioStreamPlayer[] _ноги = new AudioStreamPlayer[2];
    private AudioStreamPlayer _скрип = null!;
    private int _нога;
    private double _со_скрипа = 999;
    private readonly RandomNumberGenerator _кость = new();

    // где в записи удар — с этого места и играем
    private const float УДАР_ПОЛ = 0.44f;
    private const float УДАР_СНЕГ_1 = 0.40f;
    private const float УДАР_СНЕГ_2 = 0.20f;
    private const float УДАР_СКРИП = 0.08f;

    private const double СКРИП_ПАУЗА = 4.0;    // секунд между скрипами — не меньше

    /// <summary>Громкость шагов целиком, в децибелах.</summary>
    public float Громкость { get; set; } = 0f;

    /// <summary>На сколько долей шаг может уйти выше или ниже записи.</summary>
    public float Разброс { get; set; } = 0.03f;

    /// <summary>С каким шансом скрипит доска под шагом (после паузы).</summary>
    public float СкрипШанс { get; set; } = 0.08f;

    public override void _Ready()
    {
        for (int i = 0; i < _ноги.Length; i++)
        {
            _ноги[i] = new AudioStreamPlayer { Name = $"нога{i}", Bus = Шины.ШАГИ };
            AddChild(_ноги[i]);
        }
        _скрип = new AudioStreamPlayer
        {
            Name = "скрип",
            Stream = Звуки.Взять("шаги_скрип"),
            Bus = Шины.ШАГИ,
        };
        AddChild(_скрип);
        _кость.Randomize();
    }

    public override void _Process(double delta) => _со_скрипа += delta;

    public void Шагнуть(string поверхность)
    {
        var нога = _ноги[_нога];
        _нога = (_нога + 1) % _ноги.Length;
        switch (поверхность)
        {
            case Поверхность.СНЕГ:
                bool первый = _нога == 0;
                Играть(нога, Звуки.Взять(первый ? "шаги_снег_1" : "шаги_снег_2"),
                       первый ? УДАР_СНЕГ_1 : УДАР_СНЕГ_2, -2f);
                break;
            case Поверхность.ДЕРЕВО:
                // старые доски: шаг глуше, и изредка скрипят
                Играть(нога, Звуки.Взять("шаги_пол"), УДАР_ПОЛ, -8f);
                if (_со_скрипа >= СКРИП_ПАУЗА && _кость.Randf() < СкрипШанс)
                {
                    Играть(_скрип, _скрип.Stream, УДАР_СКРИП, -12f);
                    _со_скрипа = 0;
                }
                break;
            default:
                Играть(нога, Звуки.Взять("шаги_пол"), УДАР_ПОЛ, -5f);
                break;
        }
    }

    private void Играть(AudioStreamPlayer кем, AudioStream? что, float откуда, float громкость)
    {
        if (что is null)
            return;
        кем.Stream = что;
        кем.VolumeDb = громкость + Громкость + _кость.RandfRange(-1.5f, 1.5f);
        кем.PitchScale = 1f + _кость.RandfRange(-Разброс, Разброс);
        кем.Play(откуда);
    }
}
