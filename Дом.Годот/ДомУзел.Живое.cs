    /// <summary>
    /// Посмотреть на печь: тепло ли в комнате, горит ли, не сквозит ли —
    /// своя комната, тут знание полное (`Подача.Внутри`); мысли печи —
    /// кнопками, как у матраса и полки.
    /// </summary>
    private void К_печи()
    {
        if (_партия is null || !Дом_спит)
            return;
        var к = Подача.Внутри(_партия.прогон.h, _партия.сеанс.я);
        string Градусы(double г) => $"{(г >= 0 ? "+" : "−")}{System.Math.Abs(г):0}°";
        // до метели дом не идёт и мороза в нём нет: топят, как всегда
        var слова = _пролог is not null
            ? new List<string> { "Батареи тёплые — до метели ещё топят исправно. Печь пока ни к чему." }
            : new List<string>
        {
            !к.печь ? $"Печки нет — только батарея, и та ледяная. В комнате {Градусы(к.градусов)}."
            : к.топится ? $"Печь гудит, по комнате тянет теплом — {Градусы(к.градусов)}."
            : $"Печь холодная. В комнате {Градусы(к.градусов)}.",
        };
        if (_пролог is null && к.градусов < 5)
            слова.Add("Изо рта пар; пальцы стынут, стоит снять перчатки.");
        if (к.дыр > 0)
            слова.Add("Из пролома сквозит — тепло уходит в подъезд.");
        if (к.утепление >= 2)
            слова.Add("Окно и дверь заткнуты в несколько слоёв — держит.");
        var строки = new List<СтрокаОкна>();
