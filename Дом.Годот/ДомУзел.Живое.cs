        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        if (_беседы.Мысль_дома(Подача.Внутри(h, я), Рассудок.Где(_наследие.рассудок, _ручки), Зерно, h.day,
                               Раз("дома", "мысль")) is not string мысль)
            return;
        _дома_след = сейчас + 120.0;
        На_ходу("— " + мысль, 4.5);
    }

    /// <summary>Проба: выйти и войти к себе (только песочница) — мысль о комнате; ответ — строка.</summary>
    public string Проба_дома()
    {
        if (!Пути.Песочница)
            return "не песочница";
        _был_дома = false;
        _дома_след = 0;
        _на_ходу_ещё = 0;
        if (_мир.ДомаЛи(_герой.GlobalPosition))
            Мысль_дома_кадр();
        return _на_ходу?.Text ?? "";
    }

    /// <summary>Строка на ходу — внизу экрана, над часами: не спорит ни с вестью,
    /// ни с подсказкой прицела.</summary>
    private void На_ходу(string что, double секунд = 5.0)
    {
        if (_на_ходу is null)
        {
            _на_ходу = new Label
            {
                HorizontalAlignment = HorizontalAlignment.Center,
                AutowrapMode = TextServer.AutowrapMode.WordSmart,
                MouseFilter = Control.MouseFilterEnum.Ignore,
            };
            _на_ходу.AddThemeColorOverride("font_color", new Color("#d9cfb8"));
            _на_ходу.AddThemeColorOverride("font_outline_color", new Color(0, 0, 0, 0.85f));
            _на_ходу.AddThemeConstantOverride("outline_size", 4);
            _на_ходу.AddThemeFontSizeOverride("font_size", 17);
            _панели.AddChild(_на_ходу);
        }
        _на_ходу.Text = что;
        _на_ходу_ещё = секунд;
    }
