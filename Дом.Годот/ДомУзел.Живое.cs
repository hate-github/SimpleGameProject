    /// <summary>Поставить героя в шаге от ближайшего соседа в подъезде (любой
    /// этаж) и забыть, кто когда говорил: следующий кадр он заговорит сам.</summary>
    public string Проба_мимоходом()
    {
        if (!Пути.Песочница)
            return "не песочница";
        if (_мир.Ближний(_герой.GlobalPosition, 200f, любой_этаж: true) is not { } ф)
            return "в подъезде никого";
        _окно.Убрать();
        var к_нему = ф.GlobalPosition + new Vector3(0.9f, 0.05f, 0.9f);
        _герой.GlobalPosition = к_нему;
        _герой.Прямо();
        _мимо_молчит.Clear();
        _мимо_след = 0;
        return ф.id;
    }

    /// <summary>Сосед с этажа героя заболевает (только песочница), записки
    /// перевешиваются сразу, герой встаёт лицом к его двери.</summary>
    public string Проба_записка()
    {
        if (!Пути.Песочница)
            return "не песочница";
        if (_партия is null || !Дом_спит || Округа_ is not { } о || _беседы is null)
            return "дом не спит";
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        if (h.others(я).Where(p => p.здесь() && p.floor == я.floor && p.apt != я.apt)
                      .OrderBy(p => p.apt).FirstOrDefault() is not NPC с)
            return "на этаже некого";
        var болезни = new JsonObject { [с.id] = new JsonObject { ["стадия"] = "БОЛЕН", ["с_дня"] = h.day, ["до_дня"] = h.day + 3 } };
        о.заражение.Разложить(new JsonObject { ["болезни"] = болезни, ["посчитан_день"] = h.day - 1 });
        _записки = _беседы.Записки(h, я, _двери_снаружи, о.заражение, Зерно);
        _мир.Записки(_записки);
        if (_мир.Дверь_где(с.apt) is var (перед, дверь))
        {
            _окно.Убрать();
            _герой.GlobalPosition = перед + new Vector3(0, 0.05f, 0);
            var к = дверь - перед;
            _герой.Rotation = new Vector3(0, Mathf.Atan2(-к.X, -к.Z), 0);
            _герой.Прямо();
        }
        return $"кв.{с.apt}: {_записки.FirstOrDefault(з => з.квартира == с.apt)?.текст}";
    }

    /// <summary>Что сейчас сказано на ходу (строка внизу экрана).</summary>
    public string Проба_на_ходу() => !Пути.Песочница ? "не песочница" : _на_ходу?.Text ?? "";

    /// <summary>Строка на ходу — внизу экрана, над часами: не спорит ни с вестью,
    /// ни с подсказкой прицела.</summary>
    private void На_ходу(string что)
    {
        if (_на_ходу is null)
        {
            _на_ходу = new Label
            {
                HorizontalAlignment = HorizontalAlignment.Center,
                AutowrapMode = TextServer.AutowrapMode.WordSmart,
                MouseFilter = Control.MouseFilterEnum.Ignore,
            };
            _на_ходу.AddThemeColorOverride("font_color", new Color("#d9cfb8"));
            _на_ходу.AddThemeColorOverride("font_outline_color", new Color(0, 0, 0, 0.85f));
            _на_ходу.AddThemeConstantOverride("outline_size", 4);
            _на_ходу.AddThemeFontSizeOverride("font_size", 17);
            _панели.AddChild(_на_ходу);
        }
        _на_ходу.Text = что;
        _на_ходу_ещё = 5.0;
    }
