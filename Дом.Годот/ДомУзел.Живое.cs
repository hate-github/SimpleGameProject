    /// <summary>Постучать без дела в дверь <paramref name="кв"/>: что ответили.</summary>
    public string Проба_стук(int кв)
    {
        if (!Пути.Песочница)
            return "не песочница";
        _окно.Убрать();
        return Стук_без_дела(кв) is { } о ? $"{о.что}: {о.слова}{(о.слышно is string с ? " | " + с : "")}" : "дом не спит";
    }

    /// <summary>Дверь без дела: окно выбора — постучать, послушать, отойти.</summary>
    public string Проба_дверь(int кв)
    {
        if (!Пути.Песочница)
            return "не песочница";
        _окно.Убрать();
        У_двери_без_дела(кв);
        return _окно.открыт ? "дверь" : "окно не открылось";
    }

    /// <summary>Постоять у двери <paramref name="кв"/> тихо: что услышано (окно — когда дом уснёт).</summary>
    public string Проба_слушать(int кв)
    {
        if (!Пути.Песочница)
            return "не песочница";
        _окно.Убрать();
        return Подслушать(кв) is { } п ? string.Join(" | ", п.строки) + (п.о_еде.Count > 0 ? " | о еде: " + string.Join(", ", п.о_еде.Select(е => е.кто)) : "")
                                       : "нельзя: дом не спит на вопросе дня";
    }

