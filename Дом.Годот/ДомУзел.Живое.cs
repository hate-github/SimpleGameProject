    /// <summary>
    /// Стук в дверь, к которой дом ничего не положил: не «сейчас сюда
    /// незачем», а то, что за дверью, — тишина, сон, кашель, «чего надо»,
    /// цепочка или «заходи как-нибудь» (`Беседы.За_дверью`). Свой
    /// и знакомый открывают — с ними можно перекинуться словом о быте:
    /// те же реплики беседы, но без разговора дома — ни доверия, ни сплетен.
    /// </summary>
    private ОтветДвери? Стук_без_дела(int кв)
    {
        if (_беседы is null || _партия is null || !Дом_спит)
            return null;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        double час = я.час();
        bool опять = _стук_был.TryGetValue(кв, out var был) && час >= был && час - был < 0.5;
        _стук_был[кв] = час;
        var о = _беседы.За_дверью(h, я, кв, Подача.Кто_где(h, я, _партия.сеанс.хроника),
                                  Двери_у_двери().FirstOrDefault(д => д.квартира == кв), час,
                                  Округа_?.заражение, опять, Зерно, Раз($"кв{кв}", "стук"));
        if (!о.открыл || о.кто is not NPC сосед)
        {
            Сказать(о.слова + (о.слышно is string за ? "  " + за : ""));
            return о;
        }
        Открыл_сосед(кв, 1.4);
        string слышно = о.слышно is string с ? "\n\n" + с : "";
        bool по_быту = о.что is ЗаДверью.СВОЙ or ЗаДверью.ЗНАКОМЫЙ;
        _окно.Показать(Заголовок_двери(сосед, кв), () => о.слова + слышно + Мысль_о(сосед),
            () =>
            {
                var строки = new List<СтрокаОкна>();
                if (по_быту)
                    строки.Add(new СтрокаОкна("спросить, как жизнь", true, () => Как_жизнь(сосед, кв)));
                строки.Add(new СтрокаОкна("отойти", true, () => _окно.Убрать()));
                return строки;
            },
            лицо: сосед.id);
        Мышь();
        return о;
    }

    /// <summary>
    /// Дверь, к которой дом ничего не положил: постучать — или постоять тихо
    /// и послушать, чем там живут (четверть часа; только на вопросе дня).
    /// </summary>
    private void У_двери_без_дела(int кв)
    {
        _окно.Показать($"КВ.{кв}", () => "За дверью — чужая жизнь.",
            () => new[]
            {
                new СтрокаОкна("постучать", true, () =>
                {
                    _окно.Убрать();
                    Стук_без_дела(кв);
                }),
                new СтрокаОкна("постоять тихо, послушать — ≈15 мин", День_героя, () => Подслушать(кв)),
                new СтрокаОкна("отойти", true, () => _окно.Убрать()),
            });
        Мышь();
    }

    /// <summary>
    /// Постоять у двери тихо: что за ней говорят (`Беседы.Подслушать`). Что
    /// услышано о еде — в сведения героя о соседе (`Социальное.note_signal`,
    /// как от сплетни): после этого и мена, и просьба знают, у кого есть.
    /// Четверть часа — поступком героя (дом живёт); что услышано — окном,
    /// когда дом снова уснёт на вопросе дня.
    /// </summary>
    private Подслушано? Подслушать(int кв)
    {
        if (_беседы is null || _партия is null || !Дом_спит || !Можно_тут())
            return null;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        var п = _беседы.Подслушать(h, я, кв, Подача.Кто_где(h, я, _партия.сеанс.хроника), я.час(),
                                   Округа_?.заражение, Зерно, Раз($"кв{кв}", "слушать"));
        foreach (var (кто, еды) in п.о_еде)
            Социальное.note_signal(я, кто, "еда", еды, 0.6);
        int день = _партия.Ждёт()?.день ?? h.day;
        Сделать_тут(new Сделано(true, 0.25, $"постоял{(я.sex == "ж" ? "а" : "")} у кв.{кв}, прислушиваясь"));
        _когда_уснёт.Enqueue((день, () =>
        {
            _окно.Показать($"У ДВЕРИ КВ.{кв}", () => string.Join("\n", п.строки),
                () => new[] { new СтрокаОкна("отойти", true, () => _окно.Убрать()) });
            Мышь();
        }));
        return п;
    }

    /// <summary>Свой или знакомый открыл — слово о быте: реплика беседы, без разговора дома.</summary>
    private void Как_жизнь(NPC сосед, int кв)
    {
        if (_беседы is null || _партия is null || !Дом_спит)
            return;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        string ответ = _беседы.Ответ(h, я, сосед, "быт", false, new Слепок(я.memory.Count), _летопись,
                                     Зерно, Раз(сосед.id, "быт_у_двери"), Вести(сосед));
        _окно.Показать(Заголовок_двери(сосед, кв), () => $"«{ответ}»",
            () => new[] { new СтрокаОкна("кивнуть и отойти", true, () => _окно.Убрать()) },
            лицо: сосед.id);
        Мышь();
    }

    /// <summary>Что говорит окно: выглянуть, и здесь же мысли окна.</summary>
    private string У_окна()
    {
        var номера = Номера(а => а.вид == ВидАдреса.ДОМА && а.вещь == Вещь.ОКНО);
        string мысли = "";
        if (_на_экране is not null && номера.Count > 0)
            мысли = "\nздесь же: " + string.Join(", ", номера.Take(3).Select(
                        i => Коротко(_на_экране.варианты[i].строка) + (i == _цель ? " ← цель" : "")))
                    + (номера.Count > 3 ? "…" : "");
        return $"окно во двор\n{Жми}  выглянуть{мысли}";
    }

    /// <summary>
    /// Выглянуть в окно: погода, снег, зарево над городом и кто во дворе
    /// (`Беседы.Из_окна`); мысли, которые делаются у окна, — кнопками.
    /// До метели — обычный двор.
    /// </summary>
    private void К_окну()
    {
        if (_беседы is null || _партия is null || !Дом_спит)
            return;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        var вид = _беседы.Из_окна(h, я, Подача.Кто_где(h, я, _партия.сеанс.хроника),
                                  _пролог is null ? _летопись : null, я.час(), Зерно, Раз(я.id, "окно"),
                                  до_метели: _пролог is not null);
        var строки = new List<СтрокаОкна>();
        if (_на_экране is { } в)
            foreach (int i in Номера(а => а.вид == ВидАдреса.ДОМА && а.вещь == Вещь.ОКНО))
            {
                int n = i;                   // замыкание берёт копию
                строки.Add(new СтрокаОкна(Коротко(в.варианты[n].строка), true, () =>
                {
                    _окно.Убрать();
                    Ответить(n);
                }));
            }
        строки.Add(new СтрокаОкна("отойти от окна", true, () => _окно.Убрать()));
        _окно.Показать("ОКНО", () => string.Join("\n", вид), () => строки);
        Мышь();
    }

    /// <summary>Что говорит печь: посмотреть, и здесь же её мысли.</summary>
    private string У_печи()
