    /// <summary>
    /// Стук в дверь, к которой дом ничего не положил: не «сейчас сюда
    /// незачем», а то, что за дверью, — тишина, сон, кашель, «чего надо»,
    /// цепочка или «заходи как-нибудь» (`Беседы.За_дверью`). Свой
    /// и знакомый открывают — с ними можно перекинуться словом о быте:
    /// те же реплики беседы, но без разговора дома — ни доверия, ни сплетен.
    /// </summary>
    private ОтветДвери? Стук_без_дела(int кв)
    {
        if (_беседы is null || _партия is null || !Дом_спит)
            return null;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        double час = я.час();
        bool опять = _стук_был.TryGetValue(кв, out var был) && час >= был && час - был < 0.5;
        _стук_был[кв] = час;
        var о = _беседы.За_дверью(h, я, кв, Подача.Кто_где(h, я, _партия.сеанс.хроника),
                                  Двери_у_двери().FirstOrDefault(д => д.квартира == кв), час,
                                  Округа_?.заражение, опять, Зерно, Раз($"кв{кв}", "стук"));
        if (!о.открыл || о.кто is not NPC сосед)
        {
            Сказать(о.слова + (о.слышно is string за ? "  " + за : ""));
            return о;
        }
        Открыл_сосед(кв, 1.4);
        string слышно = о.слышно is string с ? "\n\n" + с : "";
        bool по_быту = о.что is ЗаДверью.СВОЙ or ЗаДверью.ЗНАКОМЫЙ;
        _окно.Показать(Заголовок_двери(сосед, кв), () => о.слова + слышно + Мысль_о(сосед),
            () =>
            {
                var строки = new List<СтрокаОкна>();
                if (по_быту)
                {
                    строки.Add(new СтрокаОкна("спросить, как жизнь", true, () => Как_жизнь(сосед, кв)));
                    строки.Add(new СтрокаОкна("спросить, что слышно", true, () => Что_слышно(сосед, кв)));
                }
                строки.Add(new СтрокаОкна("отойти", true, () => _окно.Убрать()));
                return строки;
            },
            лицо: сосед.id);
        Мышь();
        return о;
    }

