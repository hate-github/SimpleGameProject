    /// <summary>Что говорит окно: выглянуть, и здесь же мысли окна.</summary>
    private string У_окна()
    {
        var номера = Номера(а => а.вид == ВидАдреса.ДОМА && а.вещь == Вещь.ОКНО);
        string мысли = "";
        if (_на_экране is not null && номера.Count > 0)
            мысли = "\nздесь же: " + string.Join(", ", номера.Take(3).Select(
                        i => Коротко(_на_экране.варианты[i].строка) + (i == _цель ? " ← цель" : "")))
                    + (номера.Count > 3 ? "…" : "");
