    /// <summary>Кто хозяин за этой дверью сейчас (живёт здесь, первым — прописанный),
    /// или null: никто не живёт. Дом читается, только пока спит.</summary>
    private NPC? Живёт_за_дверью(int кв)
    {
        if (_партия is null || !Дом_спит)
            return null;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        return h.alive().Where(p => p != я && h.хозяин_жилья(p).apt == кв)
                        .OrderBy(p => p.apt == кв ? 0 : 1).ThenBy(p => p.id, System.StringComparer.Ordinal)
                        .FirstOrDefault();
    }

    /// <summary>
    /// Записка на чужой двери (`ЗапискаГероя.СОСЕДУ`): позвать хозяина поговорить,
    /// меняться или предложить помощь. Читает её он один — и к герою идёт охотнее
    /// (`ЗапискаГероя.Поправка_соседу` в сборе дома); висит день, когда написана,
    /// и следующий. Времени не стоит.
    /// </summary>
    private void Записка_соседу(int кв)
    {
        if (_беседы is null || _партия is null || !Дом_спит || Живёт_за_дверью(кв) is not NPC хозяин)
            return;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        string Текст(string вид) => _беседы.записка_соседу[вид]
            .Replace("{кв}", h.хозяин_жилья(я).apt.ToString(System.Globalization.CultureInfo.InvariantCulture), System.StringComparison.Ordinal);
        _окно.Показать($"ЗАПИСКА НА КВ.{кв}",
            () => "Прочтёт хозяин — и, может, зайдёт сам. Провисит до завтрашнего вечера.",
            () => ЗапискаГероя.СОСЕДУ.Select(вид => new СтрокаОкна($"«{Текст(вид)}»", true, () =>
                {
                    (я.записки_соседям ??= new(System.StringComparer.Ordinal))[хозяин.id] =
                        new ЗапискаСоседу(вид, h.day + ЗапискаГероя.СОСЕДУ_ДНЕЙ);
                    _записки = _беседы.Записки(h, я, Двери_для_записок(), Округа_?.заражение, Зерно);
                    _мир.Записки(_записки);
                    _окно.Убрать();
                    Сказать($"на двери кв.{кв} записка: «{Текст(вид)}»");
                }))
                .Append(new СтрокаОкна("передумать", true, () => _окно.Убрать()))
                .ToList());
        Мышь();
    }

    /// <summary>
