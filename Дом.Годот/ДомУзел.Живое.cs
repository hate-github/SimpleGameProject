        foreach (var (кто, еды) in п.о_еде)
            Социальное.note_signal(я, кто, "еда", еды, 0.6);
        int день = _партия.Ждёт()?.день ?? h.day;
        Сделать_тут(new Сделано(true, 0.25, $"постоял{(я.sex == "ж" ? "а" : "")} у кв.{кв}, прислушиваясь"));
