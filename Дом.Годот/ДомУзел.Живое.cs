    /// <summary>
    /// Посмотреть на печь: тепло ли в комнате, горит ли, не сквозит ли —
    /// своя комната, тут знание полное (`Подача.Внутри`); мысли печи —
    /// кнопками, как у матраса и полки.
    /// </summary>
    private void К_печи()
    {
        if (_партия is null || !Дом_спит)
            return;
        var к = Подача.Внутри(_партия.прогон.h, _партия.сеанс.я);
        string Градусы(double г) => $"{(г >= 0 ? "+" : "−")}{System.Math.Abs(г):0}°";
        var слова = new List<string>
        {
            !к.печь ? $"Печки нет — только батарея, и та ледяная. В комнате {Градусы(к.градусов)}."
            : к.топится ? $"Печь гудит, по комнате тянет теплом — {Градусы(к.градусов)}."
            : $"Печь холодная. В комнате {Градусы(к.градусов)}.",
        };
        if (к.градусов < 5)
            слова.Add("Изо рта пар; пальцы стынут, стоит снять перчатки.");
        if (к.дыр > 0)
            слова.Add("Из пролома сквозит — тепло уходит в подъезд.");
        if (к.утепление >= 2)
            слова.Add("Окно и дверь заткнуты в несколько слоёв — держит.");
        var строки = new List<СтрокаОкна>();
        if (_на_экране is { } в)
            foreach (int i in Номера(а => а.вид == ВидАдреса.ДОМА && а.вещь == Вещь.ПЕЧЬ))
            {
                int n = i;                   // замыкание берёт копию
                строки.Add(new СтрокаОкна(Коротко(в.варианты[n].строка), true, () =>
                {
                    _окно.Убрать();
                    Ответить(n);
                }));
            }
        строки.Add(new СтрокаОкна("отойти", true, () => _окно.Убрать()));
        _окно.Показать("ПЕЧЬ", () => string.Join("\n", слова), () => строки);
        Мышь();
    }

    /// <summary>
    /// Соседи говорят на ходу: подошёл ближе двух шагов к стоящему в подъезде —
    /// он бросает строку о том, что его давит (`Беседы.Мимоходом`). Один и тот
    /// же человек — не чаще раза в минуту с лишним, разом — не хором. Дом
    /// читается, только пока спит; строка — внизу экрана, с именем, как его
    /// знает герой.
    /// </summary>
    private void Мимоходом_кадр(Vector3 где_он, double delta)
    {
        if (_на_ходу is not null && _на_ходу_ещё > 0)
        {
            _на_ходу_ещё -= delta;
            // внизу, над строкой часов: посередине экрана — подсказка прицела
            float ширина = _панели.Size.X * 0.7f;
            _на_ходу.Position = new Vector2((_панели.Size.X - ширина) / 2, _панели.Size.Y - 96);
            _на_ходу.Size = new Vector2(ширина, 30);
            _на_ходу.Modulate = new Color(1, 1, 1, (float)System.Math.Clamp(_на_ходу_ещё, 0, 1));
            if (_на_ходу_ещё <= 0)
                _на_ходу.Text = "";
        }
        double сейчас = Time.GetTicksMsec() / 1000.0;
        if (сейчас < _мимо_след || _беседы is null || _партия is null || !Дом_спит
            || _окно.открыт || !_герой.Свободен)
            return;
        _мимо_след = сейчас + 0.5;                      // оглядываться дважды в секунду
        if (_мир.Ближний(где_он, 2.2f) is not { } ф)
            return;
        if (_мимо_молчит.TryGetValue(ф.id, out var до) && сейчас < до)
            return;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        if (h.живой(ф.id) is not NPC с)
            return;
        var в = _в_подъезде.FirstOrDefault(x => x.id == с.id);
        string? слова = _беседы.Мимоходом(h, я, с, в?.где ?? Где.НаПлощадке, в?.квартира ?? с.apt, я.час(),
                                          Округа_?.заражение, Зерно, Раз(с.id, "мимо"));
        _мимо_молчит[с.id] = сейчас + 75;               // не повторяет одно и то же каждую минуту
        if (слова is null)
            return;
        _мимо_след = сейчас + 6;                        // и не говорят хором
        На_ходу(Как_зовут(с) + ": «" + слова + "»");
    }

