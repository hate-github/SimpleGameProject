// Промзона «Вектор-3» в движке (задание автора, пп. 6–7). Считает всё
// `Дом.Ядро.Вектор`; здесь — что под прицелом у дверей корпусов и у
// проходной, обыск делом и записка окном.
//
// Опасность корпуса подсказывает дверь — и без знания (пломба сорвана,
// тянет сладковатым). Знание (Аркадий или журнал дежурного) говорит это
// прямо. Задело ли — герой не знает: в опасном корпусе пахнет всегда,
// а болезнь покажет себя сама.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    private Вектор? Вектор_ => Округа_?.вектор;

    /// <summary>Места промзоны: двери корпусов и проходная. Зовётся из `Завести`.</summary>
    private void Вектор_завести()
    {
        foreach (var (номер, дверь) in _мир.ДвериКорпусов)
        {
            int н = номер;                   // замыкание берёт копию
            дверь.Подсказка = () => У_корпуса(н);
            дверь.Действие = () => Обыскать_корпус(н, дверь);
        }
        if (_мир.Проходная is { } проходная)
        {
            проходная.Подсказка = () => $"проходная, будка вахтёра пуста\n{Жми}  домой"
                                        + (_в_походе is { } п ? $" (≈{Часы_текстом(Часы_домой(п))} ч)" : "");
            проходная.Действие = Из_промзоны;
        }
    }

    /// <summary>Пришёл в промзону: за проходной, лицом к корпусам. Поход
    /// не кончен — ночь застанет здесь, утром герой у ворот двора.</summary>
    private void В_промзону()
    {
        _герой.GlobalPosition = _мир.ВходВектора;
        _герой.Rotation = Vector3.Zero;
        _герой.Прямо();
        int обшарено = Вектор_?.обшарены.Count ?? 0;
        Сказать("«Вектор-3»: забор из плит, проходная без сторожа, пять корпусов под снегом"
                + (обшарено > 0 ? $" · обшарено {обшарено}" : ""));
    }

    private string У_корпуса(int номер)
    {
        if (Вектор_ is not { } в || в.Корпус_(номер) is not { } к || Округа_ is not { } о)
            return $"корпус {номер}";
        // две строки: длиннее подсказка налезает на строку вести под ней
        string знаю = к.опасен && о.Знает("вектор_корпуса") ? " · обходить: там язва" : "";
        return $"корпус {номер}, {к.имя}: {к.дверь}{знаю}\n"
               + (в.Обшарен(номер) ? "обшарен — пусто" : $"{Жми}  обыскать (≈{Часы_текстом(к.часов)} ч)");
    }

    /// <summary>Обыскать корпус — делом, часы кусками; находка — в тару,
    /// записка — окном; опасный корпус может задеть.</summary>
    private void Обыскать_корпус(int номер, Предмет дверь)
    {
        if (Вектор_ is not { } в || в.Корпус_(номер) is not { } к || Округа_ is not { } о || _партия is null)
            return;
        if (в.Обшарен(номер))
        {
            Сказать($"корпус {номер} обшарен — пусто");
            return;
        }
        if (!Можно_в_поход())
            return;
        Дорога(дверь, $"обыскиваю: {к.имя}", к.часов, () =>
        {
            if (_партия is null)
                return;
            var р = в.Обыскать(_партия.прогон.h, _партия.сеанс.я, номер, о, _ручки);
            string унёс = р.унёс.Ключи.Count == 0 ? "ничего не унёс"
                : "унёс: " + string.Join(", ", р.унёс.Ключи.OrderBy(x => x, System.StringComparer.Ordinal)
                                                  .Select(x => $"{x} {Текст.G(р.унёс[x])}"));
            string не_влезло = р.нашёл.Ключи.Any(x => р.нашёл[x] > р.унёс.Взять(x, 0.0) + 1e-9)
                ? " (не всё влезло в тару)" : "";
            Сказать($"{к.имя}: {унёс}{не_влезло}" + (к.опасен ? " · внутри пахло сладковато — одежда пропахла" : ""));
            if (р.записка is string записка)
            {
                _окно.Показать("ЗАПИСКА", () => записка,
                               () => new[] { new СтрокаОкна("понял", true, () => _окно.Убрать()) });
                Мышь();
            }
        });
    }

    /// <summary>Проходная: дорога домой — делом, к воротам двора.</summary>
    private void Из_промзоны()
    {
        if (_в_походе is not { } п || _мир.Проходная is not { } проходная)
        {
            _герой.GlobalPosition = _мир.У_ворот;
            return;
        }
        if (!Можно_в_поход())
            return;
        Дорога(проходная, "дорога домой", Часы_домой(п), () => Вернуться(п, "вернулся из промзоны к дому"));
    }
}
