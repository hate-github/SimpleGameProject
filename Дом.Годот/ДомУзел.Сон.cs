// Сон в движке (просьба автора, 28.09.2026: «когда день кончается, я могу
// спать в любом месте по кнопке — это неправильно»). Правило — `Дом.Ядро.Сон`.
//
// Ночь больше не окно посередине: её мысли — в телефоне, как у дня, и у каждой
// место (`Места`): спать — в постели (дома матрас, в участке и в убежище
// нары), дежурить — на своей площадке, против соседа — у его двери. Время
// ночью идёт, как днём (минута за секунду): дойти до постели. Час после
// конца дня — запас; лёг позже — недосып, утром он ложится на героя
// (`Сон.Утро`): бодрость ниже, а то и проспал будильник. Не лёг вовсе — через
// три часа уснул, где стоял. Ночь застала в пути — спит, где застала:
// постели там нет, и не надо. Распорядок и беспамятство ложатся сами.
//
// До метели так же: дом не идёт и ночь не спрашивает, но день кончается
// (`_ночь_пролога`), и окно «спать» больше не выскакивает где попало —
// ложатся у матраса (или на нарах участка), иначе недосып.

using Godot;
using Дом.Экран;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    private double _поздно;                 // часов после конца дня, а герой не лёг
    private int _ночь_дня = int.MinValue;    // какой ночи счёт «поздно»
    private Недосып? _недосып;               // лёг поздно — утром на героя
    private int _недосып_дня = int.MinValue; // после какой ночи
    private bool _у_постели;                 // «спать» выбрано у постели
    private bool _ночь_пролога;              // до метели день кончился, а герой не лёг

    /// <summary>Ночь ли: дом спросил про ночь — или до метели кончился день.</summary>
    private bool Ночь_сейчас => _на_экране is { вопрос: Вопрос.НОЧЬ } || _ночь_пролога;

    /// <summary>До метели день кончился: сказать и начать счёт «поздно».
    /// Ложатся сами — у матраса.</summary>
    private void Пролог_день_кончился()
    {
        if (_ночь_пролога)
            return;
        _ночь_пролога = true;
        _поздно = 0.0;
        Сказать("день кончился — пора спать: до постели час, потом не выспишься");
    }

    /// <summary>
    /// Каждый кадр: ночь пришла, а герой не лёг — копится «поздно» (тем же
    /// ходом времени, что и день); в пути — спит сразу; совсем не лёг —
    /// уснул, где стоял.
    /// </summary>
    private void Сон_кадр(double delta)
    {
        if (_партия is null || _ход is null)
            return;
        if (_пролог is not null)
        {
            if (!_ночь_пролога || _окно.открыт)
                return;
            _поздно += delta * _ход.Скорость(Темп_сейчас());
            if (_в_походе is { } поход)
            {
                _дело.Прервать();
                Вернуться(поход, "ночь застала в пути — ты у ворот двора");
                Пролог_спать(без_недосыпа: true);
            }
            else if (Сон.Уснул_где_стоял(_поздно, _ручки) && !_дело.занят)
                Пролог_спать("глаза закрылись сами — уснул, где стоял");
            return;
        }
        if (_партия.Ждёт() is not { вопрос: Вопрос.НОЧЬ } в)
            return;
        if (в.день != _ночь_дня)
        {
            _ночь_дня = в.день;
            _поздно = 0.0;
            if (_в_походе is null && _распорядок is null && _положение != Положение.БЕЗ_СОЗНАНИЯ)
                Сказать("день кончился — пора спать: в постель (дома матрас), до неё час; "
                        + "дежурить — на площадке");
        }
        _поздно += delta * _ход.Скорость(Темп_сейчас());
        if (_в_походе is not null)
            Лечь(в, "ночь застала в пути — спишь, где застала", без_недосыпа: true);
        else if (Сон.Уснул_где_стоял(_поздно, _ручки))
            Лечь(в, "глаза закрылись сами — уснул, где стоял");
    }

    /// <summary>Недосып этой ночи: сколько лёг позже запаса — и проспит ли.</summary>
    private Недосып Недосып_ночи(int день)
        => Сон.Лёг(_поздно, _ручки, Округа.Бросок(_партия!.прогон.seed, "проспал", _партия.сеанс.я.id, день));

    /// <summary>
    /// До метели лечь: недосып — если день уже кончился и лёг позже запаса;
    /// дальше — как было: утро следующего дня подготовки или метель.
    /// </summary>
    private void Пролог_спать(string? весть = null, bool без_недосыпа = false)
    {
        if (_пролог is null || _партия is null)
            return;
        _окно.Убрать();
        var н = _ночь_пролога && !без_недосыпа ? Недосып_ночи(_пролог.день) : Недосып.НЕТ;
        _недосып = н;
        _недосып_дня = _пролог.день;
        GD.Print($"[сон] до метели лёг, поздно {_поздно:0.00} ч: недосып {н.часов:0.00}, проспит {н.проспал:0.00}");
        _ночь_пролога = false;
        _поздно = 0.0;
        if (весть is not null)
            Сказать(весть);
        if (_пролог.Ночь())
        {
            Пролог_утро();
            Сохраниться(_партия);             // сон — сохранение (ГДД 24)
        }
        else
            Метель_пришла();
        Мышь();
    }

    /// <summary>
    /// Лечь спать: ответ «спать» дому и недосып на утро, если лёг позже
    /// запаса. <paramref name="весть"/> — что сказать (нет — сказать самому).
    /// </summary>
    private void Лечь(ВопросИгроку в, string? весть = null, bool без_недосыпа = false, bool тихо = false)
    {
        int номер = Номер_варианта(в, Места.СПАТЬ);
        if (номер < 0 || _партия is null)
            return;
        var я = _партия.сеанс.я;
        var н = без_недосыпа ? Недосып.НЕТ : Недосып_ночи(в.день);
        _недосып = н;
        _недосып_дня = в.день;
        string когда = ХодВремени.Часы((_ход?.час ?? я.час()) + _поздно);
        GD.Print($"[сон] лёг в {когда}, поздно {_поздно:0.00} ч: недосып {н.часов:0.00}, проспит {н.проспал:0.00}");
        _поздно = 0.0;
        _ход?.Сбросить();                     // ночное ожидание — не долг утра: его уже взял недосып
        if (!тихо)
            Сказать(весть ?? (н.есть ? $"лёг в {когда} — поздно: не выспишься" : "лёг спать"));
        _у_постели = true;
        try
        {
            Ответить(номер, играть: false);
        }
        finally
        {
            _у_постели = false;
        }
    }

    /// <summary>Лечь у постели — из окна матраса или нар.</summary>
    private void Лечь_у_постели()
    {
        if (_пролог is not null)
            Пролог_спать();
        else if (_партия?.Ждёт() is { вопрос: Вопрос.НОЧЬ } в)
        {
            _окно.Убрать();
            Лечь(в);
        }
    }

    /// <summary>Строка «лечь спать» для окна нар — только ночью.</summary>
    private IEnumerable<СтрокаОкна> Строка_сна()
    {
        if (Ночь_сейчас)
            yield return new СтрокаОкна("лечь спать", true, Лечь_у_постели);
    }

    /// <summary>«Спать» — только у постели: с клавиш, из телефона и откуда
    /// угодно ещё не ложатся. Распорядок, беспамятство и сон в пути
    /// ложатся сами (<see cref="Лечь"/>).</summary>
    private bool Спать_не_здесь(int номер)
    {
        if (_у_постели || _отвечаю_за_героя || _партия?.Ждёт() is not { вопрос: Вопрос.НОЧЬ } в
            || номер < 0 || номер >= в.варианты.Count
            || !string.Equals(в.варианты[номер].ключ, Места.СПАТЬ, System.StringComparison.Ordinal))
            return false;
        Сказать("спать — в постели: дома на матрасе, в участке и в убежище на нарах");
        return true;
    }

    /// <summary>
    /// Утро: недосып прошлой ночи — на героя, до первого его дела. Зовётся
    /// на новом вопросе, пока дом спит, и утром дня подготовки. Только
    /// на вопросе дня: утром дом может сперва спросить о ночном (нашли вора,
    /// пропажа) — часы дня героя тогда ещё не выданы, и «проспал» вычитать
    /// не из чего: утро выдало бы их заново, целиком (нашла проверка «сон»).
    /// </summary>
    private void Сон_утро(ВопросИгроку? в)
    {
        if (_недосып is not { } н || _партия is null
            || в is not null && (в.вопрос != Вопрос.ЧТО_ДЕЛАТЬ || в.день <= _недосып_дня))
            return;
        _недосып = null;
        if (!н.есть)
            return;
        Сон.Утро(_партия.сеанс.я, н, _партия.сеанс.дом.B);
        Сказать(н.проспал > 0
            ? $"проспал будильник — встал на {Часы_текстом(н.проспал)} ч позже, и всё равно не выспался"
            : $"не выспался — лёг на {Часы_текстом(н.часов)} ч позже, чем стоило");
    }

    /// <summary>Часы ночью: конец дня плюс сколько не ложится, и сколько
    /// ещё можно без недосыпа. Null — не ночь.</summary>
    private string? Часы_ночью()
    {
        if (!Ночь_сейчас || _ход is null || _ход.час <= 0.0)
            return null;
        double запас = Сон.Запас(_ручки) - _поздно;
        return $"{ХодВремени.Часы(_ход.час + _поздно)} · "
               + (запас > 0 ? $"пора спать — лечь бы в ближайшие {Текст.Ф(запас, 1)} ч" : "поздно — не выспишься");
    }
}
