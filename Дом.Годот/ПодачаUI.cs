// Что видно телом (ГДД 23): красные края, потемнение, дрожь, дыхание.
//
// Ни одной картинки и ни одной модели: всё рисуется шейдером прямо
// из чисел, которые считает `Дом.Экран.Подача`. Это не «пока сойдёт»,
// а честное разделение: когда придёт художник, он поменяет здесь материалы
// и меши, а откуда берётся краснота краёв — не поменяет никто, потому
// что это симуляция, а не оформление.
//
// Тумана и снега здесь **больше нет**, и это не потеря, а переезд. В первой,
// панельной версии игра была плоской, и метель приходилось рисовать плёнкой
// поверх экрана. В объёме она настоящая: туман стоит в воздухе
// (`Обстановка3D`), снег летит за окном частицами. Плёнка поверх всего
// этого не добавляла метели — она белила картинку до ровного молока,
// и подъезда за ней не было видно вовсе.
//
// Остаётся здесь только то, чего в мире нет и быть не может: не то,
// что снаружи, а то, что с телом. Края краснеют не у подъезда — у глаз.
//
// Чего здесь нет: low poly интерьеров, мягкого освещения, узнаваемо
// постсоветских комнат. Это работа художника, и подделывать её кодом
// нельзя — можно только оставить для неё место и не занять его собой.
//
// Слой лежит поверх всего и не ловит мышь: он показывает состояние,
// а не принимает ввод.

using Godot;
using Дом.Экран;

namespace Дом.Годот;

public partial class ПодачаUI : Control
{
    private ColorRect _края = null!;
    private Обстановка _что = new(0, 0, 0, 0, 0.6, 0.55, 1);
    private double _часы;

    /// <summary>Куда трясти: узел, который дрожит вместе с героем.
    /// Ставится корневым — дрожит весь верхний ряд, а не подача.</summary>
    public Control? Трясти { get; set; }

    private Vector2 _где;

    public override void _Ready()
    {
        MouseFilter = MouseFilterEnum.Ignore;

        // Размер берётся у вьюпорта прямо, а не якорями. `Control`, который
        // висит прямым ребёнком обычного `Node`, размера от окна не получает:
        // якоря считает раскладка родителя, а у `Node` её нет. Первый заход
        // это и показал — слой был (0, 0), и метели не было видно вовсе,
        // хотя шейдеры компилировались и параметры ставились
        По_окну();
        GetViewport().SizeChanged += По_окну;

        // ---- края: краснота и потемнение ----
        _края = Слой(КРАЯ_ШЕЙДЕР);
    }

    private void По_окну()
    {
        Position = Vector2.Zero;
        Size = GetViewportRect().Size;
        foreach (var узел in GetChildren())
            if (узел is Control к)
            {
                к.Position = Vector2.Zero;
                к.Size = Size;
            }
    }

    private ColorRect Слой(string код)
    {
        var шейдер = new Shader { Code = код };
        var материал = new ShaderMaterial { Shader = шейдер };
        var слой = new ColorRect
        {
            Material = материал,
            MouseFilter = MouseFilterEnum.Ignore,
            Color = new Color(1, 1, 1, 1),
        };
        AddChild(слой);
        слой.Position = Vector2.Zero;
        слой.Size = Size;
        return слой;
    }

    public void Обновить(Обстановка что)
    {
        _что = что;
        Ставить(_края, "red", что.краснота);
        Ставить(_края, "dark", что.темнота);
        Ставить(_края, "light", что.свет);
    }

    private static void Ставить(ColorRect где, string имя, double v)
        => ((ShaderMaterial)где.Material).SetShaderParameter(имя, (float)v);

    public override void _Process(double delta)
    {
        _часы += delta;

        // дыхание — медленное, дрожь — быстрая и мелкая. Обе из тела,
        // а не из таймера настроения: человек дрожит, потому что замёрз
        Ставить(_края, "breath",
                _что.дыхание * (0.5 + 0.5 * Mathf.Sin((float)_часы * 1.1f)));

        if (Трясти is null)
            return;
        if (_где == Vector2.Zero)
            _где = Трясти.Position;
        float сила = (float)_что.дрожь * 2.4f;
        Трясти.Position = _где + new Vector2(
            Mathf.Sin((float)_часы * 37.0f) * сила,
            Mathf.Cos((float)_часы * 41.0f) * сила);
    }

    /// <summary>
    /// Края: красная виньетка и потемнение (ГДД 4, 23).
    ///
    /// Полосок нет — есть края. Чем ближе к смерти, тем сильнее они
    /// краснеют и тем меньше остаётся видно; при этом ничто не мигает
    /// и не мелькает: тревога должна нарастать, а не привлекать внимание.
    /// </summary>
    private const string КРАЯ_ШЕЙДЕР = """
        shader_type canvas_item;
        uniform float red = 0.0;
        uniform float dark = 0.0;
        uniform float breath = 0.0;
        uniform float light = 1.0;

        void fragment() {
            vec2 p = SCREEN_UV - vec2(0.5);
            float edge = smoothstep(0.22, 0.72, length(p) * 1.35);

            float r = edge * red * (0.55 + 0.45 * breath);
            float d = edge * dark * 0.9 + (1.0 - light) * 0.35;

            vec3 c = mix(vec3(0.0), vec3(0.42, 0.03, 0.03),
                         r / max(r + d, 0.0001));
            COLOR = vec4(c, clamp(r + d, 0.0, 0.92));
        }
        """;
}
