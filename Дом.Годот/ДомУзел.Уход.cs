// Выход посреди дня в движке (ГДД 24: «выход из игры сохраняет прогресс;
// загрузить „раньше“ нельзя»). Правило — `Дом.Экран.Уход`.
//
// Уходят тремя дорогами — «В главное меню» и «Выйти из игры» в настройках
// и крестиком окна, — и все три идут через `Уйти`. В метель, если герой
// с последнего сна что-то делал, дом доживает день без него: экран «ТЫ
// УХОДИШЬ» без кнопки, а за ним — шаги по полчаса и ответы молчанием, как
// без сознания (`Беспамятство_кадр`), ночью — сон. Сохранение пишет, как
// всегда, наблюдатель конца дня (`Сохраниться`); вопрос о следующем дне —
// знак, что оно легло, и тогда уход идёт дальше: в меню или из игры.
// До метели — лечь, где стоял: утро сохраняется само (`Пролог_спать`).
//
// Жизнь может кончиться, пока дом доживает день: героя без него убили или
// метель прошла. Тогда уход не мигает разбором на кадр, а идёт обычной
// дорогой — «ЖИЗНЬ КОНЧИЛАСЬ», разбор, — и только кнопка разбора уводит
// туда, куда уходили (`_после_итога`): ушедший узнаёт, что с ним стало.
//
// «Делал ли что-то» — `_ходил`: часы героя или ответ дому с последнего
// сохранения. Без него «Продолжить» и тут же выйти стоило бы целого дня.

using Godot;
using Дом.Экран;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    private volatile bool _ходил;           // тратил часы или отвечал дому с последнего сохранения
    private System.Action? _уход;           // куда уйти, когда дом доживёт день; null — не уходим
    private int _уход_день;                 // в какой день ушли
    private ulong _уход_с;                  // когда, мс: дом завис — не держать игру вечно
    private string _уход_строка = "";
    private System.Action? _после_итога;    // жизнь кончилась, пока уходили: куда ведёт кнопка разбора

    /// <summary>Дом доживает день дольше этого — уйти как есть (сохранение — прошлого сна).</summary>
    private const ulong УХОД_НЕ_ДОЛЬШЕ_МС = 90_000;

    /// <summary>
    /// Уйти из идущей жизни — в меню или из игры (<paramref name="дальше"/>):
    /// сразу, если доживать нечего; до метели — лечь спать; в метель — когда
    /// дом доживёт день без героя и запишет сон.
    /// </summary>
    private void Уйти(System.Action дальше)
    {
        if (_уход is not null)
            return;                         // уже уходим — второй раз ждёт того же
        if (_партия is null || _итог_показан)
        {
            дальше();
            return;
        }
        switch (Уход.Как(_пролог is not null, _ходил, _выбыл || _партия.кончилась))
        {
            case КакУйти.СПАТЬ:
                _дело.Прервать();
                if (_в_походе is { } поход)
                    Вернуться(поход, $"ты {Util.Vb(_партия.сеанс.я.sex, "ушёл")} — ночь застала у ворот двора");
                GD.Print("[уход] до метели: лёг, где стоял");
                Пролог_спать(без_недосыпа: true);
                дальше();
                return;
            case КакУйти.ДОЖИТЬ:
                Начать_уход(дальше);
                return;
            default:
                дальше();
                return;
        }
    }

    /// <summary>Экран «ТЫ УХОДИШЬ» — и дальше день доживает `Уход_кадр`.</summary>
    private void Начать_уход(System.Action дальше)
    {
        _уход = дальше;
        _уход_день = _партия?.Ждёт()?.день ?? _мир_день;
        _уход_с = Time.GetTicksMsec();
        _уход_строка = "";
        _дело.Прервать();
        _окно.Убрать();
        _находка.Убрать();
        _верстак.Убрать();
        _карман.Убрать();
        _карта.Убрать();
        _вопрос.Убрать();
        Закрыть_панели(null);
        _распорядок = null;
        if (_распорядок_строка is not null)
            _распорядок_строка.Text = "";
        _подсказка.Text = "";
        GD.Print($"[уход] день {_уход_день}: дом доживает его без героя");
        Строка_ухода();
        Мышь();
    }

    /// <summary>Каждый кадр, пока уходим: шаг дня или ответ молчанием — до сна.</summary>
    private void Уход_кадр()
    {
        if (_уход is not { } дальше || _партия is null)
            return;
        var (шаг, номер) = Уход.Шаг(_партия.Ждёт(), _уход_день, _выбыл || _партия.кончилась);
        if (шаг == ШагУхода.ЖДАТЬ && Time.GetTicksMsec() - _уход_с > УХОД_НЕ_ДОЛЬШЕ_МС)
        {
            GD.PrintErr("[уход] дом не дожил день — ухожу с прошлым сохранением");
            шаг = ШагУхода.ГОТОВО;
        }
        switch (шаг)
        {
            case ШагУхода.ЖДАТЬ:
                return;                     // дом считает
            case ШагУхода.ГОТОВО:
                GD.Print("[уход] сон записан — ухожу");
                _уход = null;
                _переход.Убрать();
                // не посреди кадра: дальше бросают партию, а кадр её ещё читает
                Callable.From(дальше).CallDeferred();
                return;
            case ШагУхода.КОНЧИЛАСЬ:
                // жизнь кончилась без героя — погиб или метель прошла. Уйти сразу
                // значило бы мигнуть разбором на кадр: ушедший так и не узнал бы,
                // что с ним стало. Дальше — как всегда («ЖИЗНЬ КОНЧИЛАСЬ», пока дом
                // доживает метель, потом разбор), а кнопка разбора уводит туда,
                // куда уходили
                GD.Print("[уход] жизнь кончилась без героя — разбор, потом ухожу");
                _уход = null;
                _после_итога = дальше;
                _переход.Убрать();
                return;
        }
        Строка_ухода();
        if (шаг == ШагУхода.ПРОЖИТЬ)
        {
            Прожить(System.Math.Min(Уход.ШАГ, _партия.сеанс.я.time_left));
            Прошло(тихо: true);
            return;
        }
        _отвечаю_за_героя = true;
        try
        {
            Ответить(номер, играть: false);
        }
        finally
        {
            _отвечаю_за_героя = false;
        }
    }

    /// <summary>Экран без кнопки: что происходит и который час.</summary>
    private void Строка_ухода()
    {
        if (_партия is null)
            return;
        string час = _партия.Ждёт() is null ? _уход_строка : ХодВремени.Часы(_партия.сеанс.я.час());
        if (час == _уход_строка && _переход.Visible)
            return;
        _уход_строка = час;
        _переход.Ждать("ТЫ УХОДИШЬ", new[]
        {
            "",
            "день доживут без тебя: ты ничего не делаешь сам, к двери не выходишь, ночью спишь",
            "жизнь сохранится во сне — переиграть этот день нельзя",
            "",
            час.Length > 0 ? $"день {_уход_день} · {час}" : $"день {_уход_день}",
        });
    }

    /// <summary>Пока уходим, клавиши не значат ничего — и Esc тоже.</summary>
    private bool Уходим => _уход is not null;

    /// <summary>
    /// Проба ухода. «ходил» — прожить два часа дня (как стоял); «уйти» — в меню
    /// тем же путём, что из настроек; «умереть» — уйти и погибнуть, пока дом
    /// доживает день; «разбор» — что на экране разбора жизни; «итог» — открыто
    /// ли меню и какой день в сохранении. Только в песочнице.
    /// </summary>
    public string Проба_уход(string что)
    {
        if (!Пути.Песочница)
            return "не песочница";
        switch (что)
        {
            case "ходил":
                if (_партия?.Ждёт() is not { вопрос: Вопрос.ЧТО_ДЕЛАТЬ } в)
                    return "дом не ждёт вопроса дня";
                Прожить(2.0);
                Прошло(тихо: true);
                return $"ходил: день {в.день}";
            case "уйти":
                Из_игры_в_меню();
                return _уход is not null ? $"уходим: день {_уход_день}" : "сразу";
            case "умереть":
                // уйти посреди дня — и погибнуть, пока дом доживает его без тебя
                if (_партия?.Ждёт() is not { вопрос: Вопрос.ЧТО_ДЕЛАТЬ })
                    return "дом не ждёт вопроса дня";
                _ходил = true;
                Из_игры_в_меню();
                if (_уход is null)
                    return "сразу";
                Конфликт.умер(_партия.прогон.h, _партия.сеанс.я, "проба: погиб, пока тебя не было");
                _партия.Пропустить();
                return $"умер, уходя: день {_уход_день}";
            case "разбор":
                return _итог_показан && _переход.Visible ? "разбор" : "разбора нет";
            case "итог":
                var з = Пути.ЕстьЖизнь ? СохранениеИгры.Заголовок(СохранениеИгры.Прочитать(Пути.Жизнь)) : null;
                string жизнь = з is null ? "сохранения нет"
                    : $"сохранён день {з.день}" + (з.пролог ? $", до метели {з.пролог_день}" : "");
                return $"{(_уход is not null ? "ещё уходим" : _главное.открыт ? "меню" : "в игре")}; {жизнь}"
                       + (_партия is null ? "" : $"; дом: день {_партия.сеанс.дом.day}");
            default:
                return "ходил | уйти | умереть | разбор | итог";
        }
    }
}
