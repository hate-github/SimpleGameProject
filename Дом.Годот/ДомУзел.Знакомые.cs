// Как герой называет соседей (`Дом.Ядро.Знакомство`): герой новой игры
// знает их в лицо и по дверям, а имя — только познакомившись. Здесь —
// помощники экрана: имя или «сосед из кв.14», заголовок окна у двери
// и то, как сосед представляется, когда знакомятся.

using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    /// <summary>Как герой называет соседа — по имени, если знаком, иначе
    /// «сосед из кв.14»; падеж — как у `NPC.form`.</summary>
    private string Как_зовут(NPC p, string падеж = "short")
        => _партия is null ? p.form(падеж) : Знакомство.Как_зовут(_партия.сеанс.дом, _партия.сеанс.я, p, падеж);

    /// <summary>Заголовок окна у двери: «ВАЛЕНТИНА ИВАНОВНА, КВ.7» — или «СОСЕДКА, КВ.7».</summary>
    private string Заголовок_двери(NPC с, int кв)
    {
        bool знаю = _партия is null || Знакомство.Знает(_партия.сеанс.дом, _партия.сеанс.я, с);
        return $"{(знаю ? с.name : Знакомство.Сосед(с)).ToUpperInvariant()}, КВ.{кв}";
    }

    /// <summary>Познакомились только что — сосед называется, прежде чем ответить.</summary>
    private string Представился(NPC с, bool знал)
    {
        if (знал || _партия is null || !Знакомство.Знает(_партия.сеанс.дом, _партия.сеанс.я, с))
            return "";
        return $"Меня {с.@short} зовут, кстати. ";
    }
}
