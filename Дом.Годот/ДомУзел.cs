    /// <summary>Главное меню: что продолжится и что забудется новой игрой.</summary>
    private void В_меню(string весть = "")
    {
        string? продолжить = null;
        if (Пути.ЕстьЖизнь)
        {
            try
            {
                продолжить = Подпись(СохранениеИгры.Заголовок(СохранениеИгры.Прочитать(Пути.Жизнь)));
            }
            catch (System.Exception e)
            {
                весть = $"сохранение не читается: {e.Message}";
            }
        }
        // жизнь кончилась, петля — нет: продолжить значит начать следующую
        if (продолжить is null && _игра is not null && !_петля.оборвалась)
            продолжить = $"{Имя_игры()} · жизнь {_наследие.жизней + 1}, с первого утра";
        _главное.Показать(продолжить, Забудется(), весть);
        Мышь();
    }

    private string Имя_игры() => _игра?.герой?.имя ?? _игра?.кто ?? "";

    /// <summary>Под «Продолжить»: кто и где остановился.</summary>
    private string Подпись(ЗаголовокСохранения з)
    {
        string кто = з.герой?.имя ?? з.кто;
        string где = з.пролог ? $"до метели {Дни_до(з.пролог_день)}"
                   : з.день == 0 ? "утро первого дня метели"
                   : $"метель, прожито дней: {з.день}";
        return $"{кто} · жизнь {_наследие.жизней + 1} · {где}";
    }

    /// <summary>Что сотрёт новая игра — или null, если нечего.</summary>
    private string? Забудется()
    {
        int n = _наследие.жизней;
        string прожитые = $"{n} {ГлавноеМенюUI.Штук(n, "жизнь", "жизни", "жизней")} — очки, записи, карман и знания";
        return (n > 0, Пути.ЕстьЖизнь) switch
        {
            (true, true) => $"{прожитые}, и недожитая {n + 1}-я",
            (true, false) => прожитые,
            (false, true) => "недожитая первая жизнь",
            _ => null,
        };
    }

    /// <summary>«Продолжить»: жизнь из файла — или следующая жизнь петли.</summary>
    private void Продолжить_игру()
    {
        if (!Пути.ЕстьЖизнь)
        {
            if (_игра is null)
                return;
            _главное.Убрать();
            Монолог();
            return;
        }
        System.Text.Json.Nodes.JsonObject сейв;
        try
        {
            сейв = СохранениеИгры.Прочитать(Пути.Жизнь);
            var з = СохранениеИгры.Заголовок(сейв);
            // кем и где — из самого сохранения: файл петли мог пропасть
            _игра = new ИграГероя(з.герой, з.кто, з.зерно);
            _главное.Убрать();
