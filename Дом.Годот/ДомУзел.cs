    /// <summary>
    /// Мир за стенами на утро этого дня (задание автора, п. 9): летопись
    /// сворачивает события к дню, мир красит места. Что случилось ровно
    /// сегодня — вестью: зарево видно из окна, дым — со двора. Первый день
    /// жизни вести не даёт: мир только построен, и так было всегда.
    /// </summary>
    private void Мир_на_день(int день)
    {
        if (день == _мир_день)
            return;
        var с = _летопись.На(день, Зерно);
        _мир.Мир_на(с);
        // дверь подъезда завалило снаружи — во двор через окно на втором этаже
        bool завал = _летопись.Дверь_завалена(день, Зерно);
        if (завал && !_мир.Завалено && _мир_день >= 0)
            Сказать("дверь подъезда завалило снаружи — во двор теперь через окно на площадке второго этажа");
        _мир.Дверь_завалена(завал);
        if (_мир_день >= 0)
        {
            // следы (вход в бункер замело) не объявляются: это узнают,
            // сходив, — иначе весть выдала бы место тому, кто о нём не слышал
            var вести = с.Сегодня.Where(э => э.следы is null)
                .Select(э => $"{_летопись.места[э.место]}: {Весть(э)}").ToList();
            if (вести.Count > 0)
                Сказать(string.Join(" · ", вести));
        }
        _мир_день = день;
    }

    private static string Весть(СобытиеМира э) => э.здание switch
    {
