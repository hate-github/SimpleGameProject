    /// партия — та и пишет: брошенная не перезапишет новую игру.
    /// </summary>
    private void Сохраниться(Партия чья)
    {
        if (!ReferenceEquals(_партия, чья) || _игра is null)
            return;
        var я = чья.сеанс.я;
        if (!я.alive)
            return;                        // умер — сохранять нечего, файл сотрёт итог
        try
        {
            var о = СохранениеИгры.Сложить(_игра.герой, _игра.кто, чья.прогон, _петля, _магазин, _пролог);
            СохранениеИгры.Записать(о, Пути.Жизнь);
        }
        catch (System.Exception e)
        {
            GD.PrintErr($"сохранение: {e.Message}");
        }
    }

