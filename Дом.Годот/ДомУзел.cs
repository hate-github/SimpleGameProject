    /// <summary>Прилавок: сперва очередь — делом, как дорога; отстоял —
    /// окно покупок. Покупка меняет дом, и окно ставит время на паузу.</summary>
    private void К_прилавку()
    {
        if (_магазин is not { } м || _мир.Прилавок is not { } прилавок || !Можно_в_поход())
            return;
        var h = _партия!.прогон.h;
        var я = _партия.сеанс.я;
        if (!м.Открыт(h))
        {
            Сказать("торговли больше нет: полки пусты, касса закрыта");
            return;
        }
        if (Округа_?.выгнан_из_магазина == true)
        {
            Сказать("продавщица отворачивается: вору здесь не продают");
            return;
        }
        if (!_отстоял)
        {
            Дорога(прилавок, "очередь", м.очередь_часы, () =>
            {
                _отстоял = true;
                Сказать("очередь дошла");
            });
            return;
        }
        _окно.Показать("ПРИЛАВОК",
            () =>
            {
                string карта = h.банки ? $"на карте {Текст.G(Текст.Округлить(я.счёт, 2))}" : "карта не работает";
                string нал = $"наличными {Текст.G(Текст.Округлить(я.stock.Взять("деньги", 0.0), 2))}";
                string тара = я.ноша is { тара: Тара т } н
                    ? $"{т.Текст()}: {Текст.G(Текст.Округлить(н.занято, 1))} из {Текст.G(т.мест(_ручки))}"
                    : "тары нет — дадут пакет";
                return $"Цены в тысячах, на {h.day}-й день метели дороже вчерашнего. {карта}, {нал}. {тара}.";
            },
            () => м.товары.Select(т =>
            {
                int осталось = м.Осталось(h, т);
                string имя = т.предмет is string id && _инструменты.в_руках.TryGetValue(id, out var в) ? в.имя : т.id;
                string строка = $"{имя} — {Текст.G(м.Цена(h, т))}"
                                + (т.предмет is not null ? $"  (на складе {осталось})" : осталось <= 0 ? "  (кончилось)" : "");
                return new СтрокаОкна(строка, осталось > 0, () =>
                {
                    var п = м.Купить(h, я, т, _ручки, _инструменты);
                    _окно.Весть(п.взято
                        ? $"купил: {имя}" + (п.картой > 0 ? $" · картой {Текст.G(Текст.Округлить(п.картой, 2))}" : "")
                                          + (п.налом > 0 ? $" · налом {Текст.G(Текст.Округлить(п.налом, 2))}" : "")
                        : $"{имя}: {п.почему}");
                });
            }).Append(new СтрокаОкна("украсть…", true, Украсть_окно)).ToList());
        Мышь();
    }

    /// <summary>
    /// Руки и движение героя в кадре. Что в руках — из снаряжения (оно
    /// только у игрока, дом его не трогает) или инструмент идущего дела;
    /// движение — `Анимации.Героя` по положению, делу и шагу. Пока рука
    /// опускается (Unequip), предмет в ней остаётся — уберётся по концу.
    /// </summary>
    private void Руки_в_кадре()
    {
        if (_партия is null)
            return;
        var а = _герой.аниматор;
        if (а.сейчас.что != Анимация.Unequip)
            _герой.руки.Держать(Ношение.Героя(_партия.сеанс.я, _инструменты, _дело.в_руках));
        а.Играть(Анимации.Героя(_положение, _дело.движение, _герой.Идёт && _герой.Свободен));
    }

    /// <summary>Можно ли сейчас что-то делать руками: дом спит (читается
    /// оружие героя), дела нет, экран не открыт, и положение позволяет.</summary>
    private bool Руки_свободны()
    {
        if (!Дом_спит || _дело.занят || !_герой.Свободен)
            return false;
        if (!Положения.Можно_делать(_положение))
        {
            Сказать(_положение.Текст());
            return false;
        }
        return true;
