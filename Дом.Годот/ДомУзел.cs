    /// <summary>Подойти к полке: экран кармана у полки, с её мыслями.
    /// Мысль делается как у любого места — ответом дому, но уже после того,
    /// как экран закрылся: пока он открыт, время стоит.</summary>
    private void К_полке()
    {
        var дела = new List<(string, System.Action)>();
        if (_на_экране is { } в)
            foreach (int i in Номера(а => а.вид == ВидАдреса.ДОМА && а.вещь == Вещь.ПОЛКА))
