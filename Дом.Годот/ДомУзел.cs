    /// <summary>Стартовый монолог и то, что герой помнит (ГДД 4, 10).</summary>
    private void Монолог()
    {
        var н = _петля.Начать();
        var строки = new List<string> { "", н.монолог, "" };
        if (н.можно_уйти)
            строки.Add("(можно просто не вставать)");
        foreach (var з in н.записи.TakeLast(6))
            строки.Add("· " + з.текст);
        if (н.записи.Count > 6)
            строки.Add($"· …и ещё {н.записи.Count - 6} заметок в телефоне");
        foreach (var о in н.отголоски.TakeLast(3))
            строки.Add($"~ кв{о.квартира}: {о.текст}");
        // что он знает о мире вокруг дома из прошлых жизней — дело на эту
        if (_наследие.знания.Count > 0)
            строки.Add("помню: " + string.Join("; ", Помню_словами(_наследие.знания)));

        _переход.Показать($"ЖИЗНЬ {н.номер}", строки, _ => Завести(), ряды: Ряды_навыков());
    }

    /// <summary>
    /// Очки навыков — тратить здесь, между жизнями (ГДД 8.2): три навыка,
    /// уровень и что он даёт, кнопка «поднять». Наследие пишется сразу —
    /// вышел из игры, не начав жизни, а вложенное осталось.
    /// Пусто — если очков нет и ничего не поднято: первая жизнь.
    /// </summary>
    private System.Func<IReadOnlyList<(string, string?, bool, System.Action?)>>? Ряды_навыков()
    {
        bool есть_что = _наследие.очки > 0
                        || System.Enum.GetValues<Навык>().Any(х => _наследие.Уровень(х) > 0);
        if (!есть_что)
            return null;
        int цена = (int)_ручки["очков_на_уровень"];
        int предел = (int)_ручки["уровней_навыка"];
        return () =>
        {
            var ряды = new List<(string, string?, bool, System.Action?)>
            {
                ($"очков навыков: {_наследие.очки} · уровень стоит {цена}", null, false, null),
            };
            foreach (var навык in System.Enum.GetValues<Навык>())
            {
                var н = навык;
                int ур = _наследие.Уровень(н);
                ряды.Add(($"{Навыки.Имя(н)} {ур}/{предел} — {Навыки.Что_даёт(н, ур, _ручки)}",
                          ур >= предел ? "предел" : $"поднять ({цена})",
                          ур < предел && _наследие.очки >= цена,
                          () =>
                          {
                              if (_наследие.Поднять(н, _ручки))
                                  Хранение.Записать(_наследие, Пути.Наследие);
                          }));
            }
            return ряды;
        };
    }

    private bool _лез;          // только что пролез в окно — пока не отойдёт, обратно не лезет

    /// <summary>
    /// Дверь подъезда завалена — во двор и обратно лезут окном площадки
    /// второго этажа: подошёл к окну вплотную — вылез на козырёк и съехал
    /// по сугробу; упёрся со двора в сугроб у двери — забрался на козырёк
    /// и в окно. Само, как сама открывается незаваленная дверь.
    /// </summary>
    private void Окно_во_двор(Vector3 где)
    {
        bool у_окна = _мир.У_окна_изнутри(где), у_сугроба = _мир.У_сугроба_снаружи(где);
        if (!у_окна && !у_сугроба)
        {
            _лез = false;
            return;
        }
        if (_лез || !_герой.Свободен || _дело.занят)
            return;
        _лез = true;
        if (у_окна)
        {
            _герой.GlobalPosition = _мир.За_окном;
            _герой.Rotation = Vector3.Zero;                  // спиной к дому
            Сказать("вылез в окно на козырёк и съехал по сугробу во двор");
        }
        else
        {
            _герой.GlobalPosition = _мир.У_окна_внутри;
            _герой.Rotation = new Vector3(0, Mathf.Pi, 0);    // лицом в подъезд
            Сказать("по сугробу на козырёк — и в окно, на площадку второго этажа");
        }
        _герой.Прямо();
    }

    /// <summary>Знания о мире (`Наследие.знания`) — словами монолога.</summary>
    private static IEnumerable<string> Помню_словами(IEnumerable<string> знания)
    {
        foreach (var з in знания)
            yield return з switch
            {
                "вектор_есть" => "промзона «Вектор-3» за школой, за железкой",
                "вектор_корпуса" => "третий и пятый корпуса обходить",
                "вектор_болезнь" => "оттуда язва — к кашляющему не подходить",
                "бункер_слух" => "где-то в районе есть бункер",
                "бункер_район" => "бункер — на пустыре за котельной, успеть до снега",
                "бункер_вход" => "вход в бункер — у бетонных будок вентиляции",
                _ when з.StartsWith(Округа.МАСТЕР, System.StringComparison.Ordinal)
                    => $"{з[Округа.МАСТЕР.Length..]} делает себе снегоступы",
                _ => з,
            };
    }

    /// <summary>Завести жизнь: новую — или поднятую из сохранения.</summary>
    private void Завести(System.Text.Json.Nodes.JsonObject? сейв = null)
    {
        _игра ??= new ИграГероя(null, Кто.Length > 0 ? Кто : "оксана", Зерно != 0 ? Зерно : 42);
        var игра = _игра;
        var прогон = сейв is not null
            ? СохранениеИгры.Прогон_из(сейв, Пути.Данные)
            : new Прогон(Пути.Данные, seed: игра.зерно, days: Дней,
                         жильцы: игра.герой is { } профиль
                             ? npcs => Дом.Ядро.Герой.Заселить(npcs, профиль, Пути.Данные)
                             : null);
        _петля.Слушать(прогон, _кто);
        _партия = new Партия(прогон, _кто);
        // сохраняться каждую ночь метели: конец дня, после наблюдателей петли
        // (они заведены раньше), на потоке дома — дом стоит на границе дня
        var партия_жизни = _партия;
        прогон.h.hooks.on_day.Add(_ => Сохраниться(партия_жизни));

        // подъезд строится по дому: расселение решает, где какая дверь.
        // Прежний мир — сперва вон из дерева, потом освободить: `QueueFree`
        // держит узел до конца кадра, и новая «дверь9» рядом со старой
        // получала от Godot свободное имя — «дверь29». Прицел читает номер
        // квартиры из имени, и со второй жизни двери были чужими
        foreach (var узел in _мир.GetChildren())
        {
            _мир.RemoveChild(узел);
            узел.QueueFree();
        }
        int своя = _партия.сеанс.я.apt;
        _мир.Построить(прогон.h, своя);
        _верстак.Убрать();
        _дело.Прервать();
        _находка.Убрать();
        _событий_услышано = 0;
        _был_в_доме = true;
        _пронести = false;
        foreach (var х in _мир.Хранилища)
        {
            // Кладовая ходит в дом сама, но только через эти ниточки:
            // что за дом, можно ли его сейчас трогать, куда говорить
            х.Дом = () => _партия is null ? null : (_партия.сеанс.дом, _партия.сеанс.я);
            х.МожноМенять = () => Дом_спит;
            // до метели чужого не трогают: кругом люди, а поимку разбирает
            // ход дома, которого ещё нет
            х.МожноПоступать = () => _пролог is null && _партия?.Ждёт()?.вопрос == Вопрос.ЧТО_ДЕЛАТЬ;
            х.Нельзя_сейчас = () => _пролог is not null
                ? "до метели чужое не трогают — кругом люди, и хозяин в двух шагах" : null;
            х.Прошло = Прошло;
            х.Найдено = (добыча, где, взять, оставить) =>
            {
                var я = _партия!.сеанс.я;
                _находка.Показать(добыча, я.ноша ?? new Ноша(), я.карман, _ручки,
                                  тара => { взять(тара); Мышь(); },
                                  () => { оставить(); Мышь(); }, где);
                Мышь();
            };
            х.Сказать = Сказать;
            х.Ручки = () => _ручки;
            х.Каталог = () => _инструменты;
            х.Как_герой = () => _положение;
            х.Начать = (дело, цель) => _дело.Начать(дело, цель, _партия?.сеанс.дом.day ?? 0);
            х.Сыграно = () => (_дело.играл, _дело.качество);
            х.ГдеГерой = () => _герой.GlobalPosition;
            string? id = х.кладовая?.id;
            х.Цель = () => id is not null && _цель is int ц && ц < _адреса.Count
                           && _адреса[ц] is { вид: ВидАдреса.КЛАДОВАЯ } а && а.кладовая == id;
            х.Обновить(1.0);        // дом ещё не пошёл — читать можно
        }
        foreach (var г in _мир.Гаражи)
        {
            var гараж = г;                   // замыкание берёт копию
            // на верстаке лежат инструменты: взять — значит унести чужое
            гараж.на_верстаке.Clear();
            гараж.на_верстаке.AddRange(_инструменты.верстак);
            гараж.ОткрытьВерстак = () =>
            {
                _верстак.Показать(
                    гараж.на_верстаке.Select(id => (id, _инструменты.все[id].имя)).ToList(),
                    id =>
                    {
                        if (_партия?.сеанс.я.снаряжение is not { } с || !гараж.на_верстаке.Contains(id))
                            return;
                        // тяжёлое — в руки, и второго тяжёлого не взять
                        if (с.Нельзя_взять(id, _инструменты) is string нельзя)
                        {
                            Сказать(нельзя);
                            return;
                        }
                        гараж.на_верстаке.Remove(id);
                        с.Подобрать(id, _инструменты);
                        Сказать($"взял {_инструменты.все[id].имя} — это чужое"
                                + (с.в_руках == id ? "; тяжёлое — в руках" : ""));
                    });
                Мышь();
            };
        }
        _в_мире = _мир.Хранилища.Select(х => х.кладовая?.id).OfType<string>()
                      .ToHashSet(System.StringComparer.Ordinal);
        foreach (var (вещь, где) in _мир.Вещи)
        {
            var эта = вещь;                  // замыкание берёт копию
