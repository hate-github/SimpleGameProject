    /// <summary>Можно ли сейчас пойти или купить: дом спит на вопросе дня,
    /// дела нет, и герой на ногах.</summary>
    private bool Можно_в_поход()
    {
        if (_партия?.Ждёт() is not { вопрос: Вопрос.ЧТО_ДЕЛАТЬ })
        {
            Сказать("сейчас не до этого — сначала ответь дому");
            return false;
        }
        if (_дело.занят)
            return false;
        if (!Положения.Можно_делать(_положение) || !Положения.Может_ходить(_положение))
        {
            Сказать(_положение.Текст());
            return false;
        }
        return true;
    }

    /// <summary>Ворота: куда можно сегодня — только туда, о чём герой знает;
    /// что закрыто, сказано почему.</summary>
    private void К_воротам()
    {
        if (!Можно_в_поход() || Округа_ is not { } о)
            return;
        var h = _партия!.прогон.h;
        var я = _партия.сеанс.я;
        _окно.Показать("ЗА ВОРОТА",
            () =>
            {
                string снег = Улица_словом(о.Улица(h, Округа.ДОРОГА));
                return $"На улице {снег}. " + (о.Есть_у(h, я) ? "Снегоступы на тебе." : "Снегоступов нет.")
                       + $"  До ночи {Часы_текстом(я.time_left)} ч.";
            },
            () => о.летопись.походы
                .Where(п => п.знать is null || о.Знает(п.знать))
                .Select(п =>
                {
                    string? нельзя = о.Нельзя(h, я, п, Там_часов(п, о));
                    string строка = $"{п.имя} — {Часы_текстом(о.Часы_дороги(h, я, п))} ч в один конец, "
                                    + Улица_словом(о.Улица(h, п.улица))
                                    + (нельзя is null ? "" : $"  ·  {нельзя}");
                    return new СтрокаОкна(строка, нельзя is null, () => Пойти(п));
                }).ToList());
        Мышь();
    }

    /// <summary>Пойти: дорога — дело кусками, как взлом; соседи в это время
    /// живут своё, квартира пуста. Дошёл — магазин или то, что там.</summary>
    private void Пойти(Поход п)
    {
        _окно.Убрать();
        if (!Можно_в_поход() || Округа_ is not { } о || _мир.Ворота is not { } ворота)
            return;
        var h = _партия!.прогон.h;
        var я = _партия.сеанс.я;
        if (о.Нельзя(h, я, п) is string нельзя)
        {
            Сказать(нельзя);
            return;
        }
        _в_походе = п;
        _день_похода = h.day;
        Дорога(ворота, $"дорога: {п.имя}", о.Часы_дороги(h, я, п), () => Дошёл(п),
               прервано: () =>
               {
                   _в_походе = null;
                   Сказать("вернулся с полпути");
               });
    }

    /// <summary>Дорога делом: часы кусками, квартира пуста, в конце — дальше.</summary>
    private void Дорога(Предмет где, string слово, double часов, System.Action дошёл,
                        System.Action? прервано = null)
    {
        int кусков = ХодВремени.Кусков(_ручки, часов);
        double секунд = ХодВремени.Секунд_дела(_ручки, часов);
        bool Кусок(int номер)
        {
            if (_партия?.Ждёт() is not { вопрос: Вопрос.ЧТО_ДЕЛАТЬ })
                return false;
            ХодВремени.Прожить(_партия.сеанс.я, часов / кусков);
            Прошло();
            return true;
        }
        _дело.Начать(new Долгое(слово, секунд,
                                готово: () =>
                                {
                                    if (Кусок(кусков))
                                        дошёл();
                                },
                                прервано: прервано,
                                кусков: кусков,
                                кусок: Кусок,
                                часов: часов,
                                движение: new Движение(Анимация.Walk)),
                     где, _партия?.сеанс.дом.day ?? 0);
    }

    /// <summary>Дошёл: в магазин — туда; прочее — чем кончилось на месте.</summary>
    private void Дошёл(Поход п)
    {
        if (п.вид == "магазин")
        {
            _отстоял = false;
            _герой.GlobalPosition = _мир.ВходМагазина;
            _герой.Rotation = Vector3.Zero;             // лицом к прилавку
            _герой.Прямо();
            Сказать(_магазин is not null && _партия is not null && _магазин.Открыт(_партия.прогон.h)
                ? "магазин на Заречной: к прилавку очередь"
                : "магазин на Заречной: двери настежь, полки пусты — торговли больше нет");
            return;
        }
        Исход_похода(п);
    }

    /// <summary>Сколько часов на месте: очередь в магазине, корпуса промзоны,
    /// поиски на пустыре.</summary>
    private double Там_часов(Поход п, Округа о) => п.вид switch
    {
        "магазин" => _магазин?.очередь_часы ?? 0.0,
        "промзона" => о.заражение.данные.промзона_часов,
        "бункер" => о.летопись.бункер.часов,
        _ => 0.0,
    };

    /// <summary>
    /// Поход без своего места в мире — промзона, район бункера: на месте —
    /// дело (часы кусками, у ворот, как дорога), потом что вышло, потом
    /// дорога назад.
    /// </summary>
    private void Исход_похода(Поход п)
    {
        if (Округа_ is not { } о || _мир.Ворота is not { } ворота)
        {
            Вернуться(п, $"{п.имя}: сходил и вернулся");
            return;
        }
        var h = _партия!.прогон.h;
        var я = _партия.сеанс.я;
        string что = п.вид == "промзона" ? "корпуса «Вектора»" : "пустырь за котельной";
        Дорога(ворота, что, Там_часов(п, о), () =>
        {
            string весть;
            if (п.вид == "промзона")
            {
