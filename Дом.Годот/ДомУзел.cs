    /// <summary>
    /// Клавиши (по умолчанию): J — журнал, T — телефон, P — подъезд,
    /// Q — состояние, E — постучать в дверь под прицелом. Карта и карман
    /// открываются сами (M и I), список вариантов разворачивается пробелом.
    /// Какая клавиша за каким действием, решает игрок; Esc — настройки.
    ///
    /// Действие стоит первым нарочно: это единственная клавиша, которая
    /// не открывает экран, а делает ход. Всё остальное — способы посмотреть.
    /// </summary>
    public override void _UnhandledInput(InputEvent e)
    {
        // в главном меню игры нет: Esc — назад с экрана нового человека,
        // остальное ему не адресовано
        if (_главное.открыт)
        {
            if (e is InputEventKey { Pressed: true, Echo: false, Keycode: Key.Escape } && _главное.Esc())
                GetViewport().SetInputAsHandled();
            return;
        }
        if (e is InputEventKey { Pressed: true, Echo: false, Keycode: Key.Escape })
        {
            // Esc посреди дела — бросить его, а не открыть поверх настройки
            if (_дело.занят)
                _дело.Прервать();
            else
                Esc();
        }
        else if (Управление.Нажато(e, Клавиши.ДЕЙСТВИЕ))
            Постучать();
        else if (Управление.Нажато(e, Клавиши.РУКИ))
            В_руки();
        else if (Управление.Нажато(e, Клавиши.СМЕНИТЬ))
            Сменить();
        else if (Экран_по(e) is System.Action открыть)
        {
            if (Нельзя_открыть() is string почему)
            {
                if (почему.Length > 0)
                    Сказать(почему);
            }
            else
                открыть();
        }
        else
            return;
        GetViewport().SetInputAsHandled();
    }

    /// <summary>Какой экран открывает эта клавиша — или ничего.</summary>
    private System.Action? Экран_по(InputEvent e)
    {
        if (Управление.Нажато(e, Клавиши.ЖУРНАЛ))
            return () => Панель(_журнал);
        if (Управление.Нажато(e, Клавиши.ТЕЛЕФОН))
            return () =>
            {
                _телефон.Обновить();
                Панель(_телефон);
            };
        if (Управление.Нажато(e, Клавиши.СПИСОК))
            return () =>
            {
                // мысли: телефон сразу на них
                _телефон.Обновить();
                _телефон.К_мыслям();
                Панель(_телефон);
            };
        if (Управление.Нажато(e, Клавиши.ПОДЪЕЗД))
            return () =>
            {
                _подъезд.Обновить();
                Панель(_подъезд);
            };
        if (Управление.Нажато(e, Клавиши.СОСТОЯНИЕ))
            return () =>
            {
                _состояние.Обновить();
                Панель(_состояние);
            };
        if (Управление.Нажато(e, Клавиши.КАРМАН))
            return () =>
            {
                Закрыть_панели(null);
                _карман.Показать();
            };
        if (Управление.Нажато(e, Клавиши.КАРТА))
            return () =>
            {
                Закрыть_панели(null);
                _карта.Показать();
            };
        return null;
    }

    /// <summary>
    /// Почему сейчас нельзя открыть экран — или ничего, если можно. Пустая
    /// строка — нельзя, но молча: открыто своё окно, и клавиши ловит оно.
    ///
    /// Один узел решает за все экраны (задание автора, п. 1): карман раньше
    /// ловил свою клавишу сам и открывался посреди взлома поверх шкалы,
    /// а корневой узел об этом и не знал.
    /// </summary>
    private string? Нельзя_открыть()
    {
        if (_дело.занят)
            return "руки заняты — сначала закончи или брось дело "
                   + $"({Управление.В_скобках(Клавиши.ДЕЙСТВИЕ)} или [Esc])";
        if (_находка.открыт)
            return "сначала реши, в чём нести найденное";
        if (_верстак.открыт || _карман.открыт || _карта.открыта || _переход.Visible
            || _окно.открыт || _главное.открыт)
            return "";
        return null;
    }

    /// <summary>Закрыть все панели, кроме этой: экран на экран не ложится.</summary>
    private void Закрыть_панели(Control? кроме)
    {
        foreach (var п in new Control[] { _журнал, _телефон, _подъезд, _состояние })
            if (!ReferenceEquals(п, кроме))
                п.Visible = false;
    }

    /// <summary>
    /// Esc: сперва закрыть открытые панели — и только если открыто ничего,
    /// настройки. Карман, карта, верстак и развёрнутый список закрываются
    /// по Esc сами и до этого узла его не пропускают.
    /// </summary>
    private void Esc()
    {
        var открыты = new Control[] { _журнал, _телефон, _подъезд, _состояние }
            .Where(п => п.Visible).ToList();
        if (открыты.Count == 0)
        {
            _меню.Открыть();
            return;
        }
        foreach (var п in открыты)
            п.Visible = false;
        Мышь();
    }

    private void Панель(Control какая)
    {
        Закрыть_панели(какая);
        какая.Visible = !какая.Visible;
        Мышь();
    }

    /// <summary>
    /// Мышь захвачена, пока не открыт ни один экран: в подъезде её нет,
    /// а в телефоне она нужна.
    ///
    /// Лист вопроса экраном не считается — в этом вся разница. Пока он
    /// висит в углу, человек ходит, смотрит и может ответить, подойдя
    /// к двери. Останавливает его только развёрнутый список: там тридцать
    /// строк с весами, и по ним тычут мышью.
    /// </summary>
    private void Мышь()
    {
        bool занят = _меню.открыт || _главное.открыт || _находка.открыт
                     || _вопрос.Развёрнут || _карман.открыт || _карта.открыта
                     || _верстак.открыт || _окно.открыт
                     || _переход.Visible || _телефон.Visible || _журнал.Visible
                     || _подъезд.Visible || _состояние.Visible;
        _герой.Свободен = !занят;
        // Скован: экран не открыт, но ни шага, ни поворота — идёт дело,
        // держат, без сознания. Мышь при этом остаётся за делом, а не
        // за камерой (задание автора, п. 5)
        _герой.Скован = _дело.занят || !Положения.Может_ходить(_положение);
        // курсор — экранам и делу, которому он нужен (мини-игра)
        var нужно = занят || _дело.нужна_мышь ? Input.MouseModeEnum.Visible
                                              : Input.MouseModeEnum.Captured;
        // только когда меняется: узел зовёт это каждый кадр, а повторный
        // захват мыши рвёт взгляд
        if (Input.MouseMode != нужно)
            Input.MouseMode = нужно;
    }
