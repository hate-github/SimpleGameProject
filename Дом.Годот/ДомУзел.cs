    /// <summary>Стартовый монолог и то, что герой помнит (ГДД 4, 10).</summary>
    private void Монолог()
    {
        var н = _петля.Начать();
        var строки = new List<string> { "", н.монолог, "" };
        if (н.очки > 0)
            строки.Add($"очков навыков: {н.очки} · карман на {н.карман}");
        if (н.можно_уйти)
            строки.Add("(можно просто не вставать)");
        foreach (var з in н.записи.TakeLast(6))
            строки.Add("· " + з.текст);
        if (н.записи.Count > 6)
            строки.Add($"· …и ещё {н.записи.Count - 6} заметок в телефоне");
        foreach (var о in н.отголоски.TakeLast(3))
            строки.Add($"~ кв{о.квартира}: {о.текст}");

        _переход.Показать($"ЖИЗНЬ {н.номер}", строки, _ => Завести());
    }

    private void Завести()
    {
        var прогон = new Прогон(Пути.Данные, seed: Зерно, days: Дней);
        _петля.Слушать(прогон, Кто);
        _партия = new Партия(прогон, Кто);

        // подъезд строится по дому: расселение решает, где какая дверь
        foreach (var узел in _мир.GetChildren())
            узел.QueueFree();
        int своя = _партия.сеанс.я.apt;
        _мир.Построить(прогон.h, своя);
        _верстак.Убрать();
        _дело.Прервать();
        _находка.Убрать();
        _событий_услышано = 0;
        _был_в_доме = true;
        _пронести = false;
        foreach (var х in _мир.Хранилища)
        {
            // Кладовая ходит в дом сама, но только через эти ниточки:
            // что за дом, можно ли его сейчас трогать, куда говорить
            х.Дом = () => _партия is null ? null : (_партия.сеанс.дом, _партия.сеанс.я);
            х.МожноМенять = () => _партия?.Ждёт() is not null;
            х.МожноПоступать = () => _партия?.Ждёт()?.вопрос == Вопрос.ЧТО_ДЕЛАТЬ;
            х.Прошло = Прошло;
            х.Найдено = (добыча, где, взять, оставить) =>
            {
                var я = _партия!.сеанс.я;
                _находка.Показать(добыча, я.ноша ?? new Ноша(), я.карман, _ручки,
                                  тара => { взять(тара); Мышь(); },
                                  () => { оставить(); Мышь(); }, где);
                Мышь();
            };
            х.Сказать = Сказать;
            х.Ручки = () => _ручки;
            х.Каталог = () => _инструменты;
            х.Как_герой = () => _положение;
            х.Начать = (дело, цель) => _дело.Начать(дело, цель, _партия?.сеанс.дом.day ?? 0);
            х.ГдеГерой = () => _герой.GlobalPosition;
            string? id = х.кладовая?.id;
            х.Цель = () => id is not null && _цель is int ц && ц < _адреса.Count
                           && _адреса[ц] is { вид: ВидАдреса.КЛАДОВАЯ } а && а.кладовая == id;
            х.Обновить(1.0);        // дом ещё не пошёл — читать можно
        }
        foreach (var г in _мир.Гаражи)
        {
            var гараж = г;                   // замыкание берёт копию
            // на верстаке лежат инструменты: взять — значит унести чужое
            гараж.на_верстаке.Clear();
            гараж.на_верстаке.AddRange(_инструменты.верстак);
            гараж.ОткрытьВерстак = () =>
            {
                _верстак.Показать(
                    гараж.на_верстаке.Select(id => (id, _инструменты.все[id].имя)).ToList(),
                    id =>
                    {
                        if (_партия?.сеанс.я.снаряжение is not { } с || !гараж.на_верстаке.Contains(id))
                            return;
                        // тяжёлое — в руки, и второго тяжёлого не взять
                        if (с.Нельзя_взять(id, _инструменты) is string нельзя)
                        {
                            Сказать(нельзя);
                            return;
                        }
                        гараж.на_верстаке.Remove(id);
                        с.Подобрать(id, _инструменты);
                        Сказать($"взял {_инструменты.все[id].имя} — это чужое"
                                + (с.в_руках == id ? "; тяжёлое — в руках" : ""));
                    });
                Мышь();
            };
        }
        _в_мире = _мир.Хранилища.Select(х => х.кладовая?.id).OfType<string>()
                      .ToHashSet(System.StringComparer.Ordinal);
        foreach (var (вещь, где) in _мир.Вещи)
        {
            var эта = вещь;                  // замыкание берёт копию
            if (эта == Вещь.ПОЛКА)
            {
                // полка — шкаф квартиры в мире: у неё перекладывают
                // из кармана и в карман, и там же её мысли
                где.Подсказка = У_полки;
                где.Действие = К_полке;
                continue;
            }
            где.Подсказка = () => У_вещи(эта);
            где.Действие = () => Сделать(Номера(а => а.вид == ВидАдреса.ДОМА && а.вещь == эта));
        }
        _цель = null;
        _цель_имя = null;
        _цель_строка.Text = "";
        _герой.Position = _мир.Начало(своя);
        _герой.Rotation = new Vector3(0, Мир.Поворот(своя), 0);
        _герой.Прямо();
        _подъезд.Сеанс = _партия.сеанс;
        _подъезд.Наследие = _наследие;
        _состояние.Сеанс = _партия.сеанс;
        _телефон.Сеанс = _партия.сеанс;
        _телефон.Наследие = _наследие;
        _карман.Сеанс = _партия.сеанс;
        _карман.Каталог = () => _инструменты;
        _положение = Положение.НОРМА;
        _ход?.Сбросить();
        _тикает = false;
        _час_вопроса = 0.0;
        _последнее_в_руках = null;
        _в_походе = null;
        _отстоял = false;
        try
        {
            _магазин = Магазин.Прочитать(Пути.Данные, _инструменты);
        }
        catch (System.Exception e)
        {
            _магазин = null;
            GD.PrintErr($"магазин.json: {e.Message}");
        }
        if (_мир.Ворота is { } ворота)
        {
            ворота.Подсказка = У_ворот;
            ворота.Действие = К_воротам;
        }
        if (_мир.Прилавок is { } прилавок)
        {
            прилавок.Подсказка = У_прилавка;
            прилавок.Действие = К_прилавку;
        }
        if (_мир.ДверьМагазина is { } дверь)
        {
            дверь.Подсказка = () => $"дверь на улицу\n{Жми}  домой"
                                    + (_в_походе is { } п ? $" (≈{Часы_текстом(Часы_домой(п))} ч)" : "");
            дверь.Действие = Домой;
        }
        _мир_день = -1;                    // мир построен заново — целый
        _карта.Сеанс = _партия.сеанс;
        _показано = 0;
        _на_экране = null;
        _итог_показан = false;
        _мир.Отголоски(_наследие.отголоски.Select(о => о.квартира).ToHashSet());
        _журнал.Новая($"Зерно {Зерно}. Вы — {_партия.сеанс.я.name}, "
                      + $"кв.{_партия.сеанс.я.apt}: {_партия.сеанс.я.role}.");
        _партия.Начать();
    }

    /// <summary>
    /// Экран смерти (ГДД 4): причина, сколько прожито, что перенесётся.
    ///
    /// Рассудок числом не показывается: только тем, из чего он сложился.
    /// Шкала, которую видно числом, перестаёт быть скрытой характеристикой
    /// и становится ещё одной полоской.
    /// </summary>
    private void Итог()
    {
        if (_итог_показан || _партия is null)
            return;
        _итог_показан = true;

        if (_партия.беда is not null)
        {
            _журнал.Шапка($"дом упал: {_партия.беда.Message}");
            GD.PrintErr(_партия.беда);
            return;
        }

        var дом = _партия.прогон.h;
        var ж = _петля.Закрыть(_партия.прогон, Кто);
        var р = Концовки.Какая(дом, Кто, _наследие, _ручки);
        Хранение.Записать(_наследие, Пути.Наследие);
        GD.Print($"[жизнь {ж.номер}] {р.имя}: {р.почему}; "
                 + $"{ж.прожито} дн, очков {ж.начислено} (всего {_наследие.очки})");

        var строки = new List<string>
        {
            "",
            р.почему,
            "",
            $"прожито дней: {ж.прожито}   ·   лучшая жизнь: {_наследие.рекорд}",
            $"очков за жизнь: {ж.начислено}   ·   всего: {_наследие.очки}",
            "",
        };
        if (ж.вклады.Count > 0)
            строки.Add("что осталось: " + string.Join(", ", ж.вклады
                .OrderByDescending(в => System.Math.Abs(в.сколько))
                .Take(4).Select(в => в.за_что)));
        if (ж.новые_записи.Count > 0)
            строки.Add($"записано в телефон: {ж.новые_записи.Count}");
        if (ж.новые_отголоски.Count > 0)
            строки.Add($"мест, которые будут помниться: {ж.новые_отголоски.Count}");
        // «заставка только с ними» (ГДД 22): кто остался — поимённо
        if (р.дожило > 0)
            строки.Add("остались: " + string.Join(", ", Концовки.Кто_остался(дом)));

        _партия.Dispose();
        _партия = null;

        _переход.Показать(р.имя.ToUpperInvariant(), строки, _ => Дальше());
    }

    /// <summary>«Дожил» или «дожила»: в русской игре род обязан
    /// согласовываться, и он приходит вместе с итогом жизни.</summary>
    private static string Дожил(Жизнь ж) => Util.Vb(ж.пол, "дожил");

