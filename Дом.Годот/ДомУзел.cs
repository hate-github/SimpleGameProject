// Корень сцены: один узел, который водит петлю и раздаёт её экранам.
//
// Делает он четыре вещи, и ни одной больше:
//   · держит наследие и петлю, читая их с диска и записывая обратно;
//   · заводит жизнь и пускает дом на своём потоке (`Дом.Экран.Партия`);
//   · в каждом кадре смотрит, не спросил ли дом чего-нибудь;
//   · между жизнями показывает монолог и разбор.
//
// Ни нужд, ни памяти, ни знания, ни решений здесь нет и быть не может.
// Если ради интерфейса захочется положить решение в узел — значит,
// не хватает адаптера, а не архитектуры (навык godot-boundary).
//
// Интерфейс собирается кодом, а не сценой, и это выбор, а не лень.
// Сцену нельзя ни собрать, ни проверить без редактора; код узлов проверяется
// обычным `dotnet build`. Когда в редакторе дойдут руки, любой из этих
// экранов разбирается в `.tscn` без единой правки логики — она вся
// в `Дом.Экран` и `Дом.Ядро/Петля`, куда сцены не заглядывают.

using Godot;
using Дом.Экран;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел : Node
{
    /// <summary>Кем играем и какую метель. Позже это придёт с экрана
    /// выбора; пока — то же умолчание, что у консольной игры.</summary>
    [Export] public string Кто { get; set; } = "оксана";

    /// <summary>Зерно у всех жизней петли одно: мир и соседи проживают те же
    /// дни заново (ГДД 3). Расходится жизнь не календарём, а тем, что герой
    /// делает иначе.</summary>
    [Export] public long Зерно { get; set; } = 42;

    [Export] public int Дней { get; set; } = 30;

    /// <summary>Сколько жизней подряд. Ноль — пока не оборвётся петля.</summary>
    [Export] public int Жизней { get; set; } = 0;

    private Наследие _наследие = null!;
    private РучкиПетли _ручки = null!;
    private Дом.Ядро.Петля _петля = null!;

    private Партия? _партия;
    private ВопросUI _вопрос = null!;
    private ЖурналUI _журнал = null!;
    private СостояниеUI _состояние = null!;
    private ПодъездUI _подъезд = null!;
    private ТелефонUI _телефон = null!;
    private ПереходUI _переход = null!;
    private КарманUI _карман = null!;

    private int _показано;             // сколько строк ленты уже на экране
    private ВопросИгроку? _на_экране;
    private bool _итог_показан;

    public override void _Ready()
    {
        Собрать();
        try
        {
            _ручки = РучкиПетли.Прочитать(Пути.Данные);
            _наследие = Пути.ЕстьНаследие ? Хранение.Прочитать(Пути.Наследие)
                                          : new Наследие();
            _петля = new Дом.Ядро.Петля(_наследие, _ручки);
            Монолог();
        }
        catch (System.Exception e)
        {
            // молча погасший дом — худшее, что может случиться с игроком
            _журнал.Шапка($"не завелось: {e.Message}");
            GD.PrintErr(e);
        }
    }

    // ---------- между жизнями ----------

    /// <summary>Стартовый монолог и то, что герой помнит (ГДД 4, 10).</summary>
    private void Монолог()
    {
        var н = _петля.Начать();
        var строки = new List<string> { "", н.монолог, "" };
        if (н.очки > 0)
            строки.Add($"очков навыков: {н.очки} · карман на {н.карман}");
        if (н.можно_уйти)
            строки.Add("(можно просто не вставать)");
        foreach (var з in н.записи.TakeLast(6))
            строки.Add("· " + з.текст);
        if (н.записи.Count > 6)
            строки.Add($"· …и ещё {н.записи.Count - 6} заметок в телефоне");
        foreach (var о in н.отголоски.TakeLast(3))
            строки.Add($"~ кв{о.квартира}: {о.текст}");

        _переход.Показать($"ЖИЗНЬ {н.номер}", строки, _ => Завести());
    }

    private void Завести()
    {
        var прогон = new Прогон(Пути.Данные, seed: Зерно, days: Дней);
        _петля.Слушать(прогон, Кто);
        _партия = new Партия(прогон, Кто);
        _подъезд.Сеанс = _партия.сеанс;
        _подъезд.Наследие = _наследие;
        _состояние.Сеанс = _партия.сеанс;
        _телефон.Сеанс = _партия.сеанс;
        _телефон.Наследие = _наследие;
        _карман.Сеанс = _партия.сеанс;
        _показано = 0;
        _на_экране = null;
        _итог_показан = false;
        _журнал.Новая($"Зерно {Зерно}. Вы — {_партия.сеанс.я.name}, "
                      + $"кв.{_партия.сеанс.я.apt}: {_партия.сеанс.я.role}.");
        _партия.Начать();
    }

    /// <summary>
    /// Экран смерти (ГДД 4): причина, сколько прожито, что перенесётся.
    ///
    /// Рассудок числом не показывается: только тем, из чего он сложился.
    /// Шкала, которую видно числом, перестаёт быть скрытой характеристикой
    /// и становится ещё одной полоской.
    /// </summary>
    private void Итог()
    {
        if (_итог_показан || _партия is null)
            return;
        _итог_показан = true;

        if (_партия.беда is not null)
        {
            _журнал.Шапка($"дом упал: {_партия.беда.Message}");
            GD.PrintErr(_партия.беда);
            return;
        }

        var ж = _петля.Закрыть(_партия.прогон, Кто);
        Хранение.Записать(_наследие, Пути.Наследие);
        GD.Print($"[жизнь {ж.номер}] {(ж.дожил ? Дожил(ж) : ж.причина)}, "
                 + $"{ж.прожито} дн, очков {ж.начислено} (всего {_наследие.очки})");

        var строки = new List<string>
        {
            "",
            $"прожито дней: {ж.прожито}   ·   лучшая жизнь: {_наследие.рекорд}",
            $"очков за жизнь: {ж.начислено}   ·   всего: {_наследие.очки}",
            "",
        };
        if (ж.вклады.Count > 0)
            строки.Add("что осталось: " + string.Join(", ", ж.вклады
                .OrderByDescending(в => System.Math.Abs(в.сколько))
                .Take(4).Select(в => в.за_что)));
        if (ж.новые_записи.Count > 0)
            строки.Add($"записано в телефон: {ж.новые_записи.Count}");
        if (ж.новые_отголоски.Count > 0)
            строки.Add($"мест, которые будут помниться: {ж.новые_отголоски.Count}");

        _партия.Dispose();
        _партия = null;

        _переход.Показать(
            ж.дожил ? $"Жизнь {ж.номер}: {Дожил(ж)} до конца метели."
                    : $"Жизнь {ж.номер}: {ж.причина}. День {ж.день_смерти}.",
            строки, _ => Дальше());
    }

    /// <summary>«Дожил» или «дожила»: в русской игре род обязан
    /// согласовываться, и он приходит вместе с итогом жизни.</summary>
    private static string Дожил(Жизнь ж) => Util.Vb(ж.пол, "дожил");

    /// <summary>Следующая жизнь — или конец петли.</summary>
    private void Дальше()
    {
        if (_петля.оборвалась)
        {
            Оборвалась();
            return;
        }
        if (Жизней > 0 && _наследие.жизней >= Жизней)
        {
            _переход.Показать("Хватит на сегодня.",
                new[] { "", $"прожито жизней: {_наследие.жизней}" }, _ => { });
            return;
        }
        Монолог();
    }

    /// <summary>
    /// Точка невозврата (ГДД 11): «Он перестал возвращаться».
    ///
    /// Поле для слова — то самое граффити сумасшедшего пророка. Самого
    /// граффити в мире пока нет нигде, поэтому принимается любое непустое:
    /// место в механике занято, а надпись появится вместе с локациями.
    /// </summary>
    private void Оборвалась()
    {
        _переход.Показать("Он перестал возвращаться.",
            new[]
            {
                "",
                "Если ты видел слово — набери его.",
                "Пусто — начать новую петлю новым человеком: без памяти,",
                "без очков.",
            },
            слово =>
            {
                if (слово.Length > 0)
                {
                    _наследие.нирвана = true;
                    Хранение.Записать(_наследие, Пути.Наследие);
                    Монолог();
                }
                else
                {
                    _наследие = new Наследие();
                    Хранение.Записать(_наследие, Пути.Наследие);
                    _петля = new Дом.Ядро.Петля(_наследие, _ручки);
                    Монолог();
                }
            },
            спросить_слово: true);
    }

    // ---------- жизнь ----------

    public override void _Process(double delta)
    {
        if (_партия is null)
            return;

        // новые строки ленты — на экран. Именно новые: ленту пополняет
        // поток дома прямо сейчас, и копировать её целиком каждый кадр
        // было бы и дорого, и незачем
        foreach (var с in _партия.сеанс.ЛентаПосле(_показано))
        {
            _журнал.Строка(с);
            _показано++;
        }

        // вопрос — если он появился и ещё не показан
        var в = _партия.Ждёт();
        if (!ReferenceEquals(в, _на_экране))
        {
            _на_экране = в;
            if (в is not null)
            {
                _состояние.Обновить();
                _подъезд.Обновить();
                _телефон.Обновить();
                _вопрос.Показать(в, Ответить);
            }
            else
                _вопрос.Убрать();
        }

        if (_партия.кончилась && _на_экране is null)
            Итог();
    }

    private void Ответить(int номер)
    {
        if (_карман.открыт)
            return;             // пока карман открыт, отвечать нечем
        _вопрос.Убрать();
        _партия?.Ответить(номер);
    }

    public override void _ExitTree() => _партия?.Dispose();

    /// <summary>Разложить экраны. Слева подъезд, посередине лента, справа
    /// состояние и телефон, снизу вопрос — снизу потому, что на него
    /// смотрят чаще всего. Переход между жизнями ложится поверх всего.</summary>
    private void Собрать()
    {
        var корень = new VBoxContainer { AnchorRight = 1, AnchorBottom = 1 };
        корень.SetAnchorsPreset(Control.LayoutPreset.FullRect);
        AddChild(корень);

        var верх = new HBoxContainer
        {
            SizeFlagsVertical = Control.SizeFlags.ExpandFill,
        };
        корень.AddChild(верх);

        _подъезд = new ПодъездUI { CustomMinimumSize = new Vector2(260, 0) };
        верх.AddChild(_подъезд);

        _журнал = new ЖурналUI
        {
            SizeFlagsHorizontal = Control.SizeFlags.ExpandFill,
        };
        верх.AddChild(_журнал);

        var справа = new VBoxContainer { CustomMinimumSize = new Vector2(320, 0) };
        верх.AddChild(справа);

        _состояние = new СостояниеUI
        {
            SizeFlagsVertical = Control.SizeFlags.ExpandFill,
        };
        справа.AddChild(_состояние);

        _телефон = new ТелефонUI
        {
            CustomMinimumSize = new Vector2(0, 220),
        };
        справа.AddChild(_телефон);

        _вопрос = new ВопросUI();
        корень.AddChild(_вопрос);

        _переход = new ПереходUI();
        AddChild(_переход);          // поверх всего, а не внутри столбца

        _карман = new КарманUI();
        AddChild(_карман);
    }
}
