    }

    // ---------- жизнь ----------

    private double _слежка;
    private double _весть_ещё;         // сколько секунд ещё висит весть
    private float _весть_у;            // её место, когда окна вопроса нет
    private int _событий_услышано;     // сколько событий дома уже прозвучало

    public override void _Process(double delta)
    {
        if (_партия is null)
            return;

        // новые строки ленты — на экран. Именно новые: ленту пополняет
        // поток дома прямо сейчас, и копировать её целиком каждый кадр
        // было бы и дорого, и незачем
        foreach (var с in _партия.сеанс.ЛентаПосле(_показано))
        {
            _журнал.Строка(с);
            _показано++;
        }

        // метель держится за окном — а во дворе идёт вокруг тебя;
        // дверь подъезда открывается, когда к ней подходят
        var где_он = _герой.GlobalPosition;
        _воздух.Следом(_мир.Снаружи(где_он));
        bool на_улице = _мир.ВоДворе(где_он);
        _воздух.НаУлице(на_улице);
        _звук.НаУлице(на_улице);
        _мир.ДверьПодъезда(где_он, delta);
        Ноша_в_кадре(где_он);
        if (Следить)
        {
            if (Input.IsPhysicalKeyPressed(Key.K))          // клавиша: перенос для отладки, только со слежкой
                _герой.GlobalPosition = new Vector3(0.3f, 0.05f, Мир.У_ПОРОГА);
            else if (Input.IsPhysicalKeyPressed(Key.L))     // клавиша: перенос для отладки, только со слежкой
                _герой.GlobalPosition = _мир.УПриямка;
        }
        if (Следить && (_слежка += delta) > 0.5)
        {
            _слежка = 0;
            GD.Print($"[где] {где_он.X:F2} {где_он.Y:F2} {где_он.Z:F2} "
                     + $"курс {Mathf.RadToDeg(_герой.Rotation.Y):F0} "
                     + (_мир.ВоДворе(где_он) ? "двор" : "дом")
                     + (_герой.Помеха.Length > 0 ? " упёрся:" + _герой.Помеха : "")
                     + " | "
                     + Под_прицелом().Replace((char)10, '/'));
        }
        // кто держит мышь и шаг: экраны, дело, положение героя. Каждый
        // кадр — потому что экраны закрываются и сами (карта, верстак),
        // а корневой узел об этом не слышит
        Мышь();
        // подсказка прицела — про мир: открыт экран или окно вопроса,
        // и она молчит, иначе её строки ложатся поверх чужих кнопок.
        // Пока дом живёт шаг времени, подсказка прежняя: иначе раз в дюжину
        // секунд она мигала бы «сюда сейчас незачем»
        if (!(_тикает && _партия.Ждёт() is null))
            _подсказка.Text = _герой.Свободен ? Под_прицелом() : "";
        _прицел.Visible = _герой.Свободен;
        // долгое дело идёт, пока герой свободен и дом спит на вопросе;
        // между кусками — пока дом снова не уснёт на вопросе дня
        _дело.Кадр(delta, _герой.Перед_предметом,
                   _герой.Свободен && _партия.Ждёт() is not null,
                   _партия.Ждёт()?.вопрос == Вопрос.ЧТО_ДЕЛАТЬ);
        if (_дело.занят)
            _подсказка.Text = "";
        Время(delta);
        Руки_в_кадре();
        if (_весть_ещё > 0)
        {
            // окно вопроса стоит посередине, и весть о поступке ложилась
            // на его нижний край: пока оно открыто, весть уходит под него
            _весть.Position = new Vector2(_весть.Position.X,
                _вопрос.Развёрнут
                    ? Mathf.Min(_вопрос.Position.Y + _вопрос.Size.Y + 10,
                                _панели.Size.Y - 70)
                    : _весть_у);
            _весть_ещё -= delta;
            _весть.Modulate = new Color(1, 1, 1, (float)System.Math.Clamp(_весть_ещё, 0, 1));
            if (_весть_ещё <= 0)
                _весть.Text = "";
        }

        // вопрос — если он появился и ещё не показан
        var в = _партия.Ждёт();
        if (!ReferenceEquals(в, _на_экране))
        {
            _на_экране = в;
            if (в is not null)
            {
                _тикает = false;
                Мир_на_день(в.день);
                // ночь застала в походе — утром герой у ворот
                if (_в_походе is { } поход && в.день != _день_похода)
                {
                    Вернуться(поход, "ночь застала в пути — утром ты у ворот двора");
                    _дело.Прервать();
                }
                // ночь прошла посреди дела — дело брошено: утром герой
                // не продолжает бить по замку, у которого стоял вчера
                if (_дело.занят && в.день != _дело.день)
                    _дело.Прервать();
                // Ночь ношу не трогает: что несут, то при герое и утром
                // (задание автора, п. 3). Первая версия разбирала её «дома»
                // на ночном вопросе, где бы герой ни стоял, — и пакет,
                // набранный в погребе перед сном, утром оказывался в шкафу.
                // Разгружает ношу только порог своей квартиры (`Ноша_в_кадре`)
                _состояние.Обновить();
                _подъезд.Обновить();
                _телефон.Обновить();
                // подача считается с ходом, а не с кадром: дом стоит
                // на вопросе, и читать его сейчас безопасно
                var дом_ = _партия.сеанс.дом;
                var видно = Дом.Экран.Подача.Видно(дом_, _партия.сеанс.я);
                _подача.Обновить(видно);
                _звук.Обновить(
                    Дом.Экран.Подача.Слышно(дом_, _партия.сеанс.я,
                                            _партия.сеанс.лента),
                    кв => _мир.УДвери(кв));
                // что случилось с прошлого вопроса — прозвучит у той двери
                var события = _партия.сеанс.события;
                if (события.Count > _событий_услышано)
                    _звук.События(события.Skip(_событий_услышано).ToList(),
                                  кв => _мир.УДвери(кв));
                _событий_услышано = события.Count;
                _воздух.Обновить(видно);
                _мир.Освещение(видно.свет);
                foreach (var х in _мир.Хранилища)
                    х.Обновить(видно.свет);
                _герой.Дрожь = видно.дрожь;
                _положение = Положения.Героя(дом_, _партия.сеанс.я, _ручки);
                _час_вопроса = _партия.сеанс.я.час();
                _до_ночи_вопроса = _партия.сеанс.Состояние().часов_до_ночи;
                // раненый идёт медленно — как смертельно уставший
                _герой.Тяжесть = _положение == Положение.РАНЕН
                    ? System.Math.Max(видно.дыхание, 0.6) : видно.дыхание;

                // у какого варианта какая дверь — считается один раз на вопрос
                // и здесь же, пока дом спит: `Подача.Дверь` читает дом
                _план_вопроса = _партия.сеанс.План();

                // что двери говорят сегодня: свет, копоть, сорванный замок.
                // Считает это `Дом.Экран`, узел только красит
                _двери_снаружи = Дом.Экран.Подача.Снаружи(
                    дом_, _партия.сеанс.Квартиры());
                _мир.Обновить(_двери_снаружи);
                _мир.Дома(Дом.Экран.Подача.Внутри(дом_, _партия.сеанс.я));

                // кто сейчас на лестнице. Тоже снимок хода, а не кадра:
                // время в доме идёт только когда игрок тратит свои часы,
                // и между двумя вопросами на площадке не меняется ничего
                // Кто где — все, не только видимые: пропавший с лестницы
                // идёт к своей двери или к выходу, пришедший — от них же
                var кто_где = Дом.Экран.Подача.Кто_где(дом_, _партия.сеанс.я, _партия.сеанс.хроника);
                _в_подъезде = _партия.сеанс.В_подъезде();
                // застали на стуке — пришедший и позванные бегут к герою;
                // отмечаются раньше расстановки, иначе расстановка уведёт
                // их домой (в хронике их на лестнице нет) и они раздвоятся
                if (_партия.сеанс.я.застали is { } з && з.день == дом_.day)
                    _мир.К_герою(new[] { з.кто }.Concat(з.держат ?? System.Array.Empty<string>())
                        .Select(дом_.живой).OfType<NPC>()
                        .Select(п => (п.id, п.@short,
                                      Ношение.Предмет(_инструменты, _инструменты.Оружие_в_руки(п.weapon))))
                        .ToList(), _герой.GlobalPosition);
                else
                    _мир.Отпустить();
                _мир.Соседи(кто_где, _герой.GlobalPosition,
                            Ношение.Соседей(дом_, _в_подъезде, _инструменты));
                Рассказ_знатока();
                // кто сейчас в магазине — в очереди у прилавка
                if (_магазин is not null)
                    _мир.Покупатели(кто_где.Where(с => с.где == Дом.Экран.Где.ЗаПорогом
                                                       && с.место == _магазин.место).ToList());
                // оружие могли отнять — из рук выпадает то, чего больше нет
                _партия.сеанс.я.снаряжение?.Сверить(_партия.сеанс.я, _инструменты);

                // где делается каждая мысль — после хроники и по ней:
                // сосед, стоящий у чужой двери, и отвечает у той двери,
                // а не у своей пустой
                _адреса = Места.Адреса(дом_, _партия.сеанс.я, в, _партия.сеанс.хроника, _в_мире);
                var как = _адреса.Select(а => Места.Как(дом_, _партия.сеанс.я, а)).ToList();
                _телефон.Мысли(в, как);
                Нацелиться(в, как);

                Телом(видно);
                // кто перед тобой и о чём спрашивают — словами, пока дом спит
                _вопрос.Показать(в, Разговор.Прочитать(дом_, _партия.сеанс.я, в), Ответить);
                Мышь();
            }
            else
            {
                _вопрос.Убрать();
                _адреса = System.Array.Empty<Адрес?>();
                _план_вопроса = System.Array.Empty<ЖилецНаПлане>();
                _телефон.Мысли(null, System.Array.Empty<string>());
                Мышь();
            }
        }

        // разворот списка меняет и мышь, и свободу ходить, а нажимают
        // на него в самом  — узел о нём узнаёт только так
        if (_вопрос.Развёрнут != _разворот)
        {
            _разворот = _вопрос.Развёрнут;
            Мышь();
        }

        int мыслей = _на_экране is { вопрос: Вопрос.ЧТО_ДЕЛАТЬ } д ? д.варианты.Count : 0;
        _мысли_строка.Text = мыслей > 0 && !_телефон.Visible
            ? $"мысли: {мыслей} — {Управление.В_скобках(Клавиши.СПИСОК)}"
            : "";

        if (_партия.кончилась && _на_экране is null)
            Итог();
    }

    /// <summary>
    /// Выбранная мысль переживает новый вопрос, если в нём есть мысль
    /// с тем же именем: пока герой возился в гараже, дом спросил заново,
    /// а есть по-прежнему хочется.
    /// </summary>
    private void Нацелиться(ВопросИгроку в, IReadOnlyList<string> как)
    {
        _цель = null;
        if (_цель_имя is not null && в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
            for (int i = 0; i < в.варианты.Count; i++)
                if (Коротко(в.варианты[i].строка) == _цель_имя)
                {
                    _цель = i;
                    _цель_где = как[i];
                    break;
                }
        _цель_строка.Text = _цель is null ? "" : $"цель: {_цель_имя} — {_цель_где}";
    }

    /// <summary>В телефоне выбрали мысль — закрепить её.</summary>
    private void Выбрана_мысль(int номер, string где)
    {
        if (_на_экране is null || номер >= _на_экране.варианты.Count)
            return;
        _цель = номер;
        _цель_имя = Коротко(_на_экране.варианты[номер].строка);
        int тире = где.IndexOf(" — ", System.StringComparison.Ordinal);
        _цель_где = тире >= 0 ? где[(тире + 3)..] : где;
        _цель_строка.Text = $"цель: {_цель_имя} — {_цель_где}";
    }

    /// <summary>Номера мыслей, чьё место подходит, — в порядке вопроса.</summary>
    private List<int> Номера(System.Func<Адрес, bool> подходит)
    {
        var @out = new List<int>();
        for (int i = 0; i < _адреса.Count; i++)
            if (_адреса[i] is { } а && подходит(а))
                @out.Add(i);
        return @out;
    }

    /// <summary>Какую из мыслей места сделать: выбранную, если она здесь,
    /// иначе ту, что дом взвесил выше.</summary>
    private int? Которую(IReadOnlyList<int> номера)
        => номера.Count == 0 ? null
         : _цель is int ц && номера.Contains(ц) ? ц : номера[0];

    private void Сделать(IReadOnlyList<int> номера)
    {
        if (_на_экране is null || Которую(номера) is not int n)
            return;
        Ответить(n);
    }

    /// <summary>Что писать под прицелом у места: что здесь сделается
    /// по клавише и что ещё здесь можно.</summary>
    private string Здесь(string что, IReadOnlyList<int> номера, string незачем)
    {
        if (_на_экране is null || Которую(номера) is not int n)
            return $"{что}\n{незачем}";
        var в = _на_экране.варианты;
        string первый = Коротко(в[n].строка) + (n == _цель ? "  ← цель" : "");
        var прочие = номера.Where(i => i != n).ToList();
        string хвост = прочие.Count == 0 ? ""
            : $"   (ещё {прочие.Count}: "
              + string.Join(", ", прочие.Take(3).Select(i => Коротко(в[i].строка)))
              + (прочие.Count > 3 ? "…" : "") + " — выбрать в телефоне)";
        return $"{что}\n{Жми}  {первый}{хвост}";
    }

    private string У_вещи(Вещь вещь)
        => Здесь(вещь.Текст(),
                 Номера(а => а.вид == ВидАдреса.ДОМА && а.вещь == вещь),
                 "сейчас здесь незачем");

    /// <summary>Что говорит полка: здесь перекладывают вещи, и здесь же
    /// делаются её мысли — на экране полки.</summary>
    private string У_полки()
