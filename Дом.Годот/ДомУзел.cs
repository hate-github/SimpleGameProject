        _панели.AddChild(_находка);

        _переход = new ПереходUI();
        _панели.AddChild(_переход);

        _подача = new ПодачаUI();
        _панели.AddChild(_подача);
        _панели.MoveChild(_подача, _переход.GetIndex());

        // главное меню — поверх мира и экрана между жизнями, под настройками:
        // настройки открываются и из него
        _главное = new ГлавноеМенюUI
        {
            Продолжить = Продолжить_игру,
            Начать = Новая_игра,
        };
        _главное.Настройки = () => _меню.Открыть();
        _панели.AddChild(_главное);

        // настройки — поверх всего, даже экрана между жизнями: Esc
        // открывает их откуда угодно
        _меню = new НастройкиUI
        {
            Настройки = _настройки,
            Закрыт = Мышь,
            Применено = После_настроек,
            В_меню = () => _главное.открыт ? null : Из_игры_в_меню,
        };
        _панели.AddChild(_меню);

        _звук = new ЗвукUI();
        AddChild(_звук);

        // Раскладка — последней, когда всё уже стоит. Первая версия звала её
        // сразу после фильтра, раньше прицела, подсказки, вести и шкалы дела:
        // до первой смены размера окна они висели в левом верхнем углу,
        // а у прицела и шкалы не было размера вовсе
        По_окну();
        GetViewport().SizeChanged += По_окну;
    }

