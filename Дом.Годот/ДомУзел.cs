    /// при себе); держит — убрать. Тяжёлое не спрятать.</summary>
    private void В_руки()
    {
        if (!Руки_свободны() || _партия!.сеанс.я.снаряжение is not { } с)
            return;
        var я = _партия.сеанс.я;
        if (с.в_руках is string держит)
        {
            if (с.Убрать(_инструменты) is string нельзя)
            {
                Сказать(нельзя);
                return;
            }
            var было = Ношение.Предмет(_инструменты, держит);
            _герой.аниматор.Разово(new Движение(Анимация.Unequip, было.ассет));
            Сказать($"убрал: {Имя_в_руках(держит)}");
            return;
        }
        var можно = с.Можно_держать(я, _инструменты);
        string? что = _последнее_в_руках is string п && можно.Contains(п) ? п : можно.FirstOrDefault();
        if (что is null)
        {
            Сказать("в руки взять нечего: инструменты — дома у полки");
            return;
        }
        Достать(с, что);
    }

    /// <summary>R: взять в руки следующее из того, что при себе.</summary>
    private void Сменить()
    {
        if (!Руки_свободны() || _партия!.сеанс.я.снаряжение is not { } с)
            return;
        var я = _партия.сеанс.я;
        var можно = с.Можно_держать(я, _инструменты);
        if (можно.Count == 0)
        {
            Сказать("в руки взять нечего: инструменты — дома у полки");
            return;
        }
        int i = с.в_руках is string держит ? можно.ToList().IndexOf(держит) : -1;
        Достать(с, можно[(i + 1) % можно.Count]);
    }

    private void Достать(Снаряжение с, string что)
    {
        var я = _партия!.сеанс.я;
        if (с.в_руках == что)
            return;
        if (с.Достать(что, я, _инструменты) is string нельзя)
        {
            Сказать(нельзя);
            return;
        }
        _последнее_в_руках = что;
        var р = Ношение.Героя(я, _инструменты);
        _герой.руки.Держать(р);
        _герой.аниматор.Разово(new Движение(Анимация.Equip, р.ассет));
        Сказать($"в руках: {Имя_в_руках(что)}" + (р.тяжёлый ? " — тяжёлое, не спрятать" : ""));
    }

