        if (!Можно_в_поход())
            return;
        Дорога(дверь, "дорога домой", Часы_домой(п), () => Вернуться(п, "вернулся к дому"));
    }

    /// <summary>Вернуться к воротам двора: дом слышит возвращение, поход кончен.</summary>
    private void Вернуться(Поход п, string весть)
    {
        _герой.GlobalPosition = _мир.У_ворот;
        _герой.Rotation = new Vector3(0, Mathf.Pi, 0);  // лицом к дому
        _герой.Прямо();
        if (Дом_спит && Округа_ is { } о)
        {
            о.Вернулся(_партия!.прогон.h, _партия.сеанс.я, п);
            _партия.сеанс.я.away = false;
        }
        _в_походе = null;
        _отстоял = false;
        Сказать(весть);
    }

