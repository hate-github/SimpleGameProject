    private double _слежка;
    private double _весть_ещё;         // сколько секунд ещё висит весть
    private float _весть_у;            // её место, когда окна вопроса нет
    private int _событий_услышано;     // сколько событий дома уже прозвучало

    public override void _Process(double delta)
    {
        if (_партия is null)
            return;

        // новые строки ленты — на экран. Именно новые: ленту пополняет
        // поток дома прямо сейчас, и копировать её целиком каждый кадр
        // было бы и дорого, и незачем
        foreach (var с in _партия.сеанс.ЛентаПосле(_показано))
        {
            _журнал.Строка(с);
            _показано++;
        }

        // метель держится за окном — а во дворе идёт вокруг тебя;
        // дверь подъезда открывается, когда к ней подходят
        var где_он = _герой.GlobalPosition;
        _воздух.Следом(_мир.Снаружи(где_он));
        bool на_улице = _мир.ВоДворе(где_он);
        _воздух.НаУлице(на_улице);
        _звук.НаУлице(на_улице);
        _мир.ДверьПодъезда(где_он, delta);
        Окно_во_двор(где_он);
        Ноша_в_кадре(где_он);
        if (Следить)
        {
            if (Input.IsPhysicalKeyPressed(Key.K))          // клавиша: перенос для отладки, только со слежкой
                _герой.GlobalPosition = new Vector3(0.3f, 0.05f, Мир.У_ПОРОГА);
            else if (Input.IsPhysicalKeyPressed(Key.L))     // клавиша: перенос для отладки, только со слежкой
                _герой.GlobalPosition = _мир.УПриямка;
        }
        if (Следить && (_слежка += delta) > 0.5)
        {
            _слежка = 0;
            GD.Print($"[где] {где_он.X:F2} {где_он.Y:F2} {где_он.Z:F2} "
                     + $"курс {Mathf.RadToDeg(_герой.Rotation.Y):F0} "
                     + (_мир.ВоДворе(где_он) ? "двор" : "дом")
                     + (_герой.Помеха.Length > 0 ? " упёрся:" + _герой.Помеха : "")
                     + " | "
                     + Под_прицелом().Replace((char)10, '/'));
        }
        // кто держит мышь и шаг: экраны, дело, положение героя. Каждый
        // кадр — потому что экраны закрываются и сами (карта, верстак),
        // а корневой узел об этом не слышит
        Мышь();
        // подсказка прицела — про мир: открыт экран или окно вопроса,
        // и она молчит, иначе её строки ложатся поверх чужих кнопок.
        // Пока дом живёт шаг времени, подсказка прежняя: иначе раз в дюжину
        // секунд она мигала бы «сюда сейчас незачем»
        if (!(_тикает && _партия.Ждёт() is null))
            _подсказка.Text = _герой.Свободен ? Под_прицелом() : "";
        _прицел.Visible = _герой.Свободен;
        // долгое дело идёт, пока герой свободен и дом спит на вопросе;
        // между кусками — пока дом снова не уснёт на вопросе дня
        _дело.Кадр(delta, _герой.Перед_предметом,
                   _герой.Свободен && Дом_спит,
                   День_героя);
        if (_дело.занят)
            _подсказка.Text = "";
        Время(delta);
        Руки_в_кадре();
        if (_весть_ещё > 0)
        {
            // окно вопроса стоит посередине, и весть о поступке ложилась
            // на его нижний край: пока оно открыто, весть уходит под него
            _весть.Position = new Vector2(_весть.Position.X,
                _вопрос.Развёрнут
                    ? Mathf.Min(_вопрос.Position.Y + _вопрос.Size.Y + 10,
                                _панели.Size.Y - 70)
                    : _весть_у);
            _весть_ещё -= delta;
            _весть.Modulate = new Color(1, 1, 1, (float)System.Math.Clamp(_весть_ещё, 0, 1));
            if (_весть_ещё <= 0)
                _весть.Text = "";
        }

        // вопрос — если он появился и ещё не показан
        var в = _партия.Ждёт();
        if (!ReferenceEquals(в, _на_экране))
        {
            _на_экране = в;
            if (в is not null)
            {
                _тикает = false;
                Мир_на_день(в.день);
                // ночь застала в походе — утром герой у ворот
                if (_в_походе is { } поход && в.день != _день_похода)
                {
                    Вернуться(поход, "ночь застала в пути — утром ты у ворот двора");
                    _дело.Прервать();
                }
                // ночь прошла посреди дела — дело брошено: утром герой
                // не продолжает бить по замку, у которого стоял вчера
                if (_дело.занят && в.день != _дело.день)
                    _дело.Прервать();
                // дом уснул на вопросе дня — что ждало этого, идёт сейчас;
                // вчерашнее выбрасывается
                if (в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
                    while (_когда_уснёт.Count > 0)
                    {
                        var (день, что) = _когда_уснёт.Dequeue();
                        if (день == в.день)
                            что();
                    }
                // Ночь ношу не трогает: что несут, то при герое и утром
                // (задание автора, п. 3). Первая версия разбирала её «дома»
                // на ночном вопросе, где бы герой ни стоял, — и пакет,
                // набранный в погребе перед сном, утром оказывался в шкафу.
                // Разгружает ношу только порог своей квартиры (`Ноша_в_кадре`)
                _состояние.Обновить();
                _подъезд.Обновить();
                _телефон.Обновить();
                // подача считается с ходом, а не с кадром: дом стоит
                // на вопросе, и читать его сейчас безопасно
                var дом_ = _партия.сеанс.дом;
                var видно = Дом.Экран.Подача.Видно(дом_, _партия.сеанс.я);
                _подача.Обновить(видно);
                _звук.Обновить(
                    Дом.Экран.Подача.Слышно(дом_, _партия.сеанс.я,
                                            _партия.сеанс.лента),
                    кв => _мир.УДвери(кв));
                // что случилось с прошлого вопроса — прозвучит у той двери
                var события = _партия.сеанс.события;
                if (события.Count > _событий_услышано)
                    _звук.События(события.Skip(_событий_услышано).ToList(),
                                  кв => _мир.УДвери(кв));
                _событий_услышано = события.Count;
                _воздух.Обновить(видно);
                _мир.Освещение(видно.свет);
                foreach (var х in _мир.Хранилища)
                    х.Обновить(видно.свет);
                _герой.Дрожь = видно.дрожь;
                _положение = Положения.Героя(дом_, _партия.сеанс.я, _ручки);
                _час_вопроса = _партия.сеанс.я.час();
                _до_ночи_вопроса = _партия.сеанс.Состояние().часов_до_ночи;
                // раненый идёт медленно — как смертельно уставший
                _герой.Тяжесть = _положение == Положение.РАНЕН
                    ? System.Math.Max(видно.дыхание, 0.6) : видно.дыхание;

                // у какого варианта какая дверь — считается один раз на вопрос
                // и здесь же, пока дом спит: `Подача.Дверь` читает дом
                _план_вопроса = _партия.сеанс.План();

                // что двери говорят сегодня: свет, копоть, сорванный замок.
                // Считает это `Дом.Экран`, узел только красит
                _двери_снаружи = Дом.Экран.Подача.Снаружи(
                    дом_, _партия.сеанс.Квартиры());
                _мир.Обновить(_двери_снаружи);
                _мир.Дома(Дом.Экран.Подача.Внутри(дом_, _партия.сеанс.я));

                // кто сейчас на лестнице. Тоже снимок хода, а не кадра:
                // время в доме идёт только когда игрок тратит свои часы,
                // и между двумя вопросами на площадке не меняется ничего
                // Кто где — все, не только видимые: пропавший с лестницы
                // идёт к своей двери или к выходу, пришедший — от них же
                var кто_где = Дом.Экран.Подача.Кто_где(дом_, _партия.сеанс.я, _партия.сеанс.хроника);
                _в_подъезде = _партия.сеанс.В_подъезде();
                // застали на стуке — пришедший и позванные бегут к герою;
                // отмечаются раньше расстановки, иначе расстановка уведёт
                // их домой (в хронике их на лестнице нет) и они раздвоятся
                if (_партия.сеанс.я.застали is { } з && з.день == дом_.day)
                    _мир.К_герою(new[] { з.кто }.Concat(з.держат ?? System.Array.Empty<string>())
                        .Select(дом_.живой).OfType<NPC>()
                        .Select(п => (п.id, п.@short,
                                      Ношение.Предмет(_инструменты, _инструменты.Оружие_в_руки(п.weapon))))
                        .ToList(), _герой.GlobalPosition);
                else
                    _мир.Отпустить();
                _мир.Соседи(кто_где, _герой.GlobalPosition,
                            Ношение.Соседей(дом_, _в_подъезде, _инструменты));
                Беседа_ответ(в);
                Рассказ_знатока();
                Весть_бункера();
                // кто сейчас в магазине — в очереди у прилавка
                if (_магазин is not null)
                {
                    _в_очереди = кто_где.Where(с => с.где == Дом.Экран.Где.ЗаПорогом
                                                    && с.место == _магазин.место).ToList();
                    _мир.Покупатели(_в_очереди);
                }
                // оружие могли отнять — из рук выпадает то, чего больше нет
                _партия.сеанс.я.снаряжение?.Сверить(_партия.сеанс.я, _инструменты);

                // где делается каждая мысль — после хроники и по ней:
                // сосед, стоящий у чужой двери, и отвечает у той двери,
                // а не у своей пустой
                _адреса = Места.Адреса(дом_, _партия.сеанс.я, в, _партия.сеанс.хроника, _в_мире);
                var как = _адреса.Select(а => Места.Как(дом_, _партия.сеанс.я, а)).ToList();
                _телефон.Мысли(в, как);
                Нацелиться(в, как);

                Телом(видно);
                // кто перед тобой и о чём спрашивают — словами, пока дом спит
                _вопрос.Показать(в, Разговор.Прочитать(дом_, _партия.сеанс.я, в), Ответить);
                Мышь();
            }
            else
            {
                _вопрос.Убрать();
                _адреса = System.Array.Empty<Адрес?>();
                _план_вопроса = System.Array.Empty<ЖилецНаПлане>();
                _телефон.Мысли(null, System.Array.Empty<string>());
                Мышь();
            }
        }

        // разворот списка меняет и мышь, и свободу ходить, а нажимают
        // на него в самом  — узел о нём узнаёт только так
        if (_вопрос.Развёрнут != _разворот)
        {
            _разворот = _вопрос.Развёрнут;
            Мышь();
        }

        int мыслей = _на_экране is { вопрос: Вопрос.ЧТО_ДЕЛАТЬ } д ? д.варианты.Count : 0;
        _мысли_строка.Text = мыслей > 0 && !_телефон.Visible
            ? $"мысли: {мыслей} — {Управление.В_скобках(Клавиши.СПИСОК)}"
            : "";

        if (_партия.кончилась && _на_экране is null)
            Итог();
    }

    /// <summary>
    /// Выбранная мысль переживает новый вопрос, если в нём есть мысль
    /// с тем же именем: пока герой возился в гараже, дом спросил заново,
    /// а есть по-прежнему хочется.
    /// </summary>
    private void Нацелиться(ВопросИгроку в, IReadOnlyList<string> как)
    {
        _цель = null;
        if (_цель_имя is not null && в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
            for (int i = 0; i < в.варианты.Count; i++)
                if (Коротко(в.варианты[i].строка) == _цель_имя)
                {
                    _цель = i;
                    _цель_где = как[i];
                    break;
                }
        _цель_строка.Text = _цель is null ? "" : $"цель: {_цель_имя} — {_цель_где}";
    }

    /// <summary>В телефоне выбрали мысль — закрепить её.</summary>
    private void Выбрана_мысль(int номер, string где)
    {
        if (_на_экране is null || номер >= _на_экране.варианты.Count)
            return;
        _цель = номер;
        _цель_имя = Коротко(_на_экране.варианты[номер].строка);
        int тире = где.IndexOf(" — ", System.StringComparison.Ordinal);
        _цель_где = тире >= 0 ? где[(тире + 3)..] : где;
        _цель_строка.Text = $"цель: {_цель_имя} — {_цель_где}";
    }

    /// <summary>Номера мыслей, чьё место подходит, — в порядке вопроса.</summary>
    private List<int> Номера(System.Func<Адрес, bool> подходит)
    {
        var @out = new List<int>();
        for (int i = 0; i < _адреса.Count; i++)
            if (_адреса[i] is { } а && подходит(а))
                @out.Add(i);
        return @out;
    }

    /// <summary>Какую из мыслей места сделать: выбранную, если она здесь,
    /// иначе ту, что дом взвесил выше.</summary>
    private int? Которую(IReadOnlyList<int> номера)
        => номера.Count == 0 ? null
         : _цель is int ц && номера.Contains(ц) ? ц : номера[0];

    private void Сделать(IReadOnlyList<int> номера)
    {
        if (_на_экране is null || Которую(номера) is not int n)
            return;
        Ответить(n);
    }

    /// <summary>Что писать под прицелом у места: что здесь сделается
    /// по клавише и что ещё здесь можно.</summary>
    private string Здесь(string что, IReadOnlyList<int> номера, string незачем)
    {
        if (_на_экране is null || Которую(номера) is not int n)
            return $"{что}\n{незачем}";
        var в = _на_экране.варианты;
        string первый = Коротко(в[n].строка) + (n == _цель ? "  ← цель" : "");
        var прочие = номера.Where(i => i != n).ToList();
        string хвост = прочие.Count == 0 ? ""
            : $"   (ещё {прочие.Count}: "
              + string.Join(", ", прочие.Take(3).Select(i => Коротко(в[i].строка)))
              + (прочие.Count > 3 ? "…" : "") + " — выбрать в телефоне)";
        return $"{что}\n{Жми}  {первый}{хвост}";
    }

    private string У_вещи(Вещь вещь)
        => Здесь(вещь.Текст(),
                 Номера(а => а.вид == ВидАдреса.ДОМА && а.вещь == вещь),
                 "сейчас здесь незачем");

    /// <summary>Что говорит полка: здесь перекладывают вещи, и здесь же
    /// делаются её мысли — на экране полки.</summary>
    private string У_полки()
    {
        var номера = Номера(а => а.вид == ВидАдреса.ДОМА && а.вещь == Вещь.ПОЛКА);
        string мысли = "";
        if (_на_экране is not null && номера.Count > 0)
            мысли = "\nздесь же: " + string.Join(", ", номера.Take(3).Select(
                        i => Коротко(_на_экране.варианты[i].строка) + (i == _цель ? " ← цель" : "")))
                    + (номера.Count > 3 ? "…" : "");
        return $"полка — шкаф квартиры\n{Жми}  разложить вещи, взять в карман{мысли}";
    }

    /// <summary>Подойти к полке: экран кармана у полки, с её мыслями.
    /// Мысль делается как у любого места — ответом дому, но уже после того,
    /// как экран закрылся: пока он открыт, время стоит.</summary>
    private void К_полке()
    {
        var дела = new List<(string, System.Action)>();
        if (_на_экране is { } в)
            foreach (int i in Номера(а => а.вид == ВидАдреса.ДОМА && а.вещь == Вещь.ПОЛКА))
            {
                int n = i;                   // замыкание берёт копию
                дела.Add((Коротко(в.варианты[n].строка) + (n == _цель ? "   ← цель" : ""),
                          () => Ответить(n)));
            }
        // знает, где бункер, — у полки можно собрать туда в дорогу
        if (Бункер_известен)
            дела.Add(("собрать в дорогу — в убежище…", Собрать_в_дорогу));
        _карман.Показать(у_полки: true, дела);
    }

    /// <summary>Карман открылся или закрылся. Закрылся у полки — полка
    /// показывает шкаф заново: вещи могли уйти в карман и вернуться.</summary>
    private void Карман_сменился()
    {
        Мышь();
        // пока карман открыт, мир на паузе и кадр не считается: подсказку
        // прицела гасим здесь, иначе она так и висит поверх экрана
        if (_карман.открыт)
        {
            _подсказка.Text = "";
            _прицел.Visible = false;
        }
        if (!_карман.открыт && Дом_спит)
            _мир.Дома(Дом.Экран.Подача.Внутри(_партия.сеанс.дом, _партия.сеанс.я));
    }

    /// <summary>
    /// Номера мыслей у двери этой квартиры. У своей двери — ещё и то,
    /// что делается у неё: изнутри — вход и стены, снаружи — площадка
    /// (собрание, лестница).
    /// </summary>
    private List<int> Номера_к_двери(int кв)
    {
        bool своя = _партия is not null && кв == _партия.сеанс.я.apt;
        bool дома = _мир.ДомаЛи(_герой.GlobalPosition);
        return Номера(а => а.К_двери(кв)
            || (своя && дома && а.вид == ВидАдреса.ДОМА && а.вещь == Вещь.ДВЕРЬ)
            || (своя && !дома && а.вид == ВидАдреса.ПЛОЩАДКА));
    }

    /// <summary>
    /// Что под прицелом: чья это дверь, что о хозяине известно и что
    /// с ним можно сделать прямо сейчас.
    ///
    /// Считается по снимкам, снятым в тот момент, когда дом задал вопрос,
    /// а не по дому. Разница не в скорости: подсказка обновляется каждый
    /// кадр, а дом в это время может считать на своём потоке, и читать
    /// его тогда нельзя — это то же правило, из-за которого лента заперта
    /// замком. Первая версия звала `Сеанс.План()` прямо отсюда.
    ///
    /// Имя и занятие берутся из плана подъезда, то есть из того же, что
    /// видит сосед. Шкаф и чувства сюда не попадают — для них есть телефон
    /// и знание.
    ///
    /// Вторая строка — то, ради чего затевалась вся эта геометрия: не «что
    /// можно сделать вообще», а какие из **уже собранных домом** вариантов
    /// ведут к этой двери. Ничего не добавляется и не отбирается: номера
    /// те же, что в листе, и первый из них — тот, что дом взвесил выше.
    /// </summary>
    private string Под_прицелом()
    {
        if (_партия is null)
            return "";
        if (_герой.Перед_предметом is Предмет предмет)
            return предмет.Подсказка();
        if (_герой.Перед_выходом)
            return У_выхода();
        if (_герой.Перед_дверью is not int кв)
            return "";
        var ж = _план_вопроса.FirstOrDefault(x => x.квартира == кв);
        string кто = ж is null
            ? $"кв.{кв} — пусто"
            : ж.здесь
              ? $"кв.{кв} — {ж.имя}, {ж.роль}"
              : $"кв.{кв} — {ж.имя}, †{(ж.причина is not null ? " " + ж.причина : "")}";

        кто += Видно_у_двери(кв);

        return Здесь(кто, Номера_к_двери(кв), "сюда сейчас незачем");
    }

    /// <summary>
    /// Что видно у самой двери — словами к тому, что уже видно глазом.
    ///
    /// Копоть, сорванный замок и щель света дверь показывает сама; здесь
    /// они названы, потому что «дверь чуть темнее» без подписи читается
    /// как игра света, а не как «здесь горело».
    ///
    /// Отголосок прошлой жизни (ГДД 10) — единственное, чего в мире нет
    /// и быть не может: зарубка на косяке видна, а что она значит, помнит
    /// только тот, кто здесь уже был.
    /// </summary>
    private string Видно_у_двери(int кв)
    {
        var что = _двери_снаружи.FirstOrDefault(д => д.квартира == кв);
        var слова = new List<string>();
        if (что is not null)
        {
            if (что.разобрана) слова.Add("разобрана");
            else if (что.взломана) слова.Add("замок сорван");
            if (что.горело) слова.Add("пахнет гарью");
            if (что.тело) слова.Add("хозяин так и остался внутри");
            else if (!что.живут) слова.Add("пусто");
            if (что.свет) слова.Add("из-под двери светит");
        }
        var болезнь = Округа_?.заражение;
        var гости = _в_подъезде
            .Where(с => с.квартира == кв && с.где == Дом.Экран.Где.УДвери)
            .Select(с => с.имя + (болезнь?.Заразен(с.id) == true ? " (кашляет)" : "")).ToList();
        if (гости.Count > 0)
            слова.Add("здесь же " + string.Join(" и ", гости));
        var эхо = _наследие?.отголоски.LastOrDefault(о => о.квартира == кв);
        if (эхо is not null)
            слова.Add($"на косяке зарубка: {эхо.текст}");
        return слова.Count == 0 ? "" : "  ·  " + string.Join("; ", слова);
    }

    /// <summary>
    /// Что говорит входная дверь подъезда: куда сегодня можно пойти.
    ///
    /// Список не придумывается здесь и не отбирается — это те же вылазки,
    /// что дом положил в вопрос, и в том же порядке. Дверь только собирает
    /// их в одном месте: выбор «ближе и беднее или дальше и опаснее»
    /// делается у порога, одетым, а не посреди площадки листанием списка.
    /// </summary>
    private string У_выхода()
        => Здесь(_мир.Завалено ? "окно во двор — дверь завалило" : "дверь во двор",
                 Номера(а => а.вид == ВидАдреса.ВЫХОД), "сегодня выходить незачем");

    /// <summary>Строка варианта без веса: в подсказке он занимает половину
    /// места и ничего не добавляет — вес виден в телефоне.</summary>
    private static string Коротко(string строка)
    {
        int i = строка.IndexOf("  ", System.StringComparison.Ordinal);
        return i > 0 ? строка[..i].TrimEnd() : строка;
    }

    /// <summary>Клавиша действия, как её пишут подсказки: «[E]», пока игрок
    /// не назначил другую.</summary>
    private static string Жми => Управление.В_скобках(Клавиши.ДЕЙСТВИЕ);

    /// <summary>Постучать в дверь под прицелом: ответить мыслью, которая
    /// к ней ведёт, — выбранной в телефоне, если она здесь, иначе той,
    /// которую дом взвесил выше прочих, а не той, что удобнее интерфейсу.</summary>
    private void Постучать()
    {
        // E посреди долгого дела — бросить его
        if (_дело.занят)
        {
            _дело.Прервать();
            return;
        }
        // держат или без сознания — руки не свои
        if (!Положения.Может_ходить(_положение))
        {
            Сказать(_положение.Текст());
            return;
        }
        // Предмет — поступок самого героя, а не ответ дому: вопроса
        // для него ждать не надо. Что из этого трогает дом, предмет
        // проверяет сам
        if (_герой.Перед_предметом is Предмет предмет)
        {
            if (_герой.Свободен)
                предмет.Действие();
            return;
        }
        if (_пролог is not null)
        {
            if (_герой.Перед_выходом)
                Сказать("до метели город живёт как жил — за покупками за ворота двора, в магазин");
            else if (_герой.Перед_дверью is int кв_пролог && _партия is not null
                     && кв_пролог != _партия.сеанс.я.apt)
                Беседа_пролог(кв_пролог);
            return;
        }
        if (_на_экране is null)
            return;
        if (_герой.Перед_выходом)
            Сделать(Номера(а => а.вид == ВидАдреса.ВЫХОД));
        else if (_герой.Перед_дверью is int кв)
        {
            // выбранная в телефоне мысль к этой двери — делается сразу;
            // иначе у чужой двери — окно: поговорить о чём, попросить, меняться
            var к_двери = Номера_к_двери(кв);
            bool своя = _партия is not null && кв == _партия.сеанс.я.apt;
            if (своя || (_цель is int ц && к_двери.Contains(ц)) || _беседы is null)
                Сделать(к_двери);
            else
                Беседа_метель(кв);
        }
    }

    /// <summary>Что с телом — одной строкой внизу экрана, всегда.
    /// Это и есть «экран без полосок» (ГДД 23): не шкала, а то, что
    /// человек про себя знает и без шкалы.</summary>
    private void Телом(Дом.Экран.Обстановка видно)
    {
        if (_партия is null)
            return;
        var слова = Дом.Экран.Подача.Телом(_партия.сеанс.я).ToList();
        // болезнь с «Вектора» — то, что человек про себя знает: знобит, жар
        if (Округа_?.заражение.Стадия(_партия.сеанс.я.id) is { } стадия
            && Болезнь_словом(стадия) is string болен)
            слова.Insert(0, болен);
        // в каком виде герой — прежде всего остального
        if (_положение.Текст() is { Length: > 0 } положение)
            слова.Insert(0, положение);
        _телом_начало = слова.Count == 0 ? "" : string.Join(" · ", слова.Take(3)) + "        ";
        _телом_цвет = new Color("#c8b48a") with { A = (float)(0.55 + 0.45 * видно.краснота) };
        _телом.AddThemeColorOverride("font_color", _телом_цвет);
        Часы_над_телом();
    }

