// Корень сцены: один узел, который водит петлю и раздаёт её экранам.
//
// Делает он четыре вещи, и ни одной больше:
//   · держит наследие и петлю, читая их с диска и записывая обратно;
//   · заводит жизнь и пускает дом на своём потоке (`Дом.Экран.Партия`);
//   · в каждом кадре смотрит, не спросил ли дом чего-нибудь;
//   · между жизнями показывает монолог и разбор.
//
// Ни нужд, ни памяти, ни знания, ни решений здесь нет и быть не может.
// Если ради интерфейса захочется положить решение в узел — значит,
// не хватает адаптера, а не архитектуры (навык godot-boundary).
//
// Игра — от первого лица (ГДД 23). Первая версия этого узла была панелью
// на весь экран: журнал слева, список вариантов снизу, чёрный фон. Так
// оно и читалось — консолью с кнопками, а не игрой. Теперь посередине
// экрана подъезд, по которому ходят, а панели ушли поверх и по клавишам:
// состояние на Q, журнал на J, телефон на T, план на P, карта на M,
// карман на I. Ходят на WASD, стучат в дверь на E. Это умолчания:
// клавиши назначает игрок в настройках (Esc), и узлы спрашивают
// не букву, а действие (`Управление`).
//
// Esc сперва закрывает то, что открыто, и только потом открывает
// настройки. Настройки читаются раньше, чем собирается сцена: действия
// ввода и шины звука должны быть, когда их спросит первый узел.
//
// Что осталось прежним: ни один узел ничего не решает. Дом спрашивает
// через тот же шов, ответы идут через ту же `Партия`, и подойти к двери —
// это способ задать вопрос, а не ответить на него.
//
// **Походы** (задание автора, пп. 6, 10, 13): ворота в проезде вала —
// куда пойти выбирает герой (`Округа.Нельзя`, `Часы_дороги`), дорога идёт
// делом кусками; магазин — отдельная комната с очередью и прилавком
// (`Магазин`), дверь магазина — дорога домой. Пока герой в походе —
// и вообще не в подъезде (двор, гараж, подвал), — квартира пуста
// (`away`): дом это видит, как у соседа на вылазке.
//
// **Соседи ходят** (задание автора, п. 26): на каждом вопросе `Подача.Кто_где`
// говорит, где каждый в этот час, и `Мир.Соседи` ведёт фигуры по сетке
// навигации — от своей двери, от входа, к следующей двери, домой.
// Застали на стуке — пришедшие бегут к герою (`Мир.К_герою`).
//
// **Что в руках — видно** (задание автора, пп. 21–23). F достаёт или
// убирает, R берёт другое (`Снаряжение.в_руках`); тяжёлое не спрятать.
// Пока идёт дело, в руках его инструмент, и рука играет его движение
// (`Анимации.Героя`). У фигур на лестнице руки считает `Ношение.Соседей`
// по делу, за которым человек стоит, — тем же узлом `Руки3D`.
//
// **Время идёт само** (задание автора, пп. 24–25; `ХодВремени`). Узел
// каждый кадр решает темп — обычно, разговор, дело, стоит — и копит часы
// дня; накопился шаг, дом спит на вопросе дня — герой прожил шаг, ничего
// не делая, и дом пропускает его ход (`Прошло`), а соседи живут своё.
// Дом по-прежнему считает ходами, и жизнь зависит от отданных часов,
// а не от частоты кадров. Часы героя — строкой над телом, каждый кадр.
//
// Вопрос дня — мысли героя в телефоне (`Дом.Экран.Места`): где делается
// каждая, считается раз на вопрос, и у места клавиша действия отвечает
// тем, что дом предложил там сделать, — выбранной в телефоне мыслью,
// если она здесь, иначе той, что дом взвесил выше. Прочие вопросы —
// окном посередине (`ВопросUI`).
//
// **Меню, новый человек, «Продолжить»** (задание автора, пп. 19–20). Игра
// начинается с главного меню (`ГлавноеМенюUI`), новая игра — с экрана
// нового человека: имя даёт игрок, остальное задано (`data/герой.json`,
// шестнадцатый жилец только в игре — `Герой.Заселить`). Кем и в каком мире
// идёт петля — `user://игра.json` (`ИграГероя`): все жизни одного человека
// проходят в одной метели. Текущая жизнь сохраняется при каждом сне
// (`user://жизнь.json`, `СохранениеИгры`): ночью пролога — здесь же, ночью
// метели — наблюдателем `on_day` на потоке дома, после наблюдателей петли,
// пока дом стоит на границе дня. Жизнь кончилась — файла нет. «Продолжить»
// поднимает жизнь из файла, а без него — следующую жизнь той же петли.
// Выход в меню посреди жизни бросает партию (`Партия.Бросить`): поток дома
// кончается, а не спит на вопросе с целым домом в памяти.
//
// Интерфейс собирается кодом, а не сценой, и это выбор, а не лень.
// Сцену нельзя ни собрать, ни проверить без редактора; код узлов проверяется
// обычным `dotnet build`. Когда в редакторе дойдут руки, любой из этих
// экранов разбирается в `.tscn` без единой правки логики — она вся
// в `Дом.Экран` и `Дом.Ядро/Петля`, куда сцены не заглядывают.

