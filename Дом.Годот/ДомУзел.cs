    public override void _Ready()
    {
        // настройки — до сцены: узлы спрашивают действия ввода с первого
        // кадра, а звук без заведённой шины играет мимо своей громкости
        _настройки = Настроить.Прочитать();
        Настроить.Всё(_настройки, GetViewport());
        Собрать();
        После_настроек();
        try
        {
            _ручки = РучкиПетли.Прочитать(Пути.Данные);
            _ход = new ХодВремени(_ручки);
            _летопись = Летопись.Прочитать(Пути.Данные);
            _пророк = Пророк.Прочитать(Пути.Данные);
            _инструменты = Инструменты.Прочитать(Пути.Данные);
            _наследие = Пути.ЕстьНаследие ? Хранение.Прочитать(Пути.Наследие)
                                          : new Наследие();
            _петля = new Дом.Ядро.Петля(_наследие, _ручки, _пророк, _инструменты, _летопись);
            _главное.Шаблон = Дом.Ядро.Герой.Шаблон(Пути.Данные);
            string весть = "";
            try
            {
                _игра = Пути.ЕстьИгра ? ИграГероя.Прочитать(Пути.Игра) : null;
            }
            catch (System.Exception e)
            {
                // сломанный файл петли — не повод не пускать в игру: новая игра его перепишет
                _игра = null;
                весть = $"файл петли не читается: {e.Message}";
            }
            В_меню(весть);
        }
        catch (System.Exception e)
        {
            // молча погасший дом — худшее, что может случиться с игроком
            _журнал.Шапка($"не завелось: {e.Message}");
            GD.PrintErr(e);
        }
    }

