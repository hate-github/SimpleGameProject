                                    + Улица_словом(о.Улица(h, п.улица))
                                    + (нельзя is null ? "" : $"  ·  {нельзя}");
                    return new СтрокаОкна(строка, нельзя is null, () => Пойти(п));
                }).ToList());
        Мышь();
    }

    /// <summary>Пойти: дорога — дело кусками, как взлом; соседи в это время
    /// живут своё, квартира пуста. Дошёл — магазин или то, что там.</summary>
    private void Пойти(Поход п)
    {
        _окно.Убрать();
        if (!Можно_в_поход() || Округа_ is not { } о || _мир.Ворота is not { } ворота)
            return;
        var h = _партия!.прогон.h;
        var я = _партия.сеанс.я;
        if (о.Нельзя(h, я, п, Там_часов(п, о)) is string нельзя)
        {
            Сказать(нельзя);
            return;
        }
        _в_походе = п;
        _день_похода = h.day;
        if (п.вид == "бункер")
            Ходка_к_бункеру();
        Дорога(ворота, $"дорога: {п.имя}", о.Часы_дороги(h, я, п), () => Дошёл(п),
               прервано: () =>
               {
                   _в_походе = null;
                   Сказать("вернулся с полпути");
               });
    }

    /// <summary>Дорога делом: часы кусками, квартира пуста, в конце — дальше,
    /// когда дом проживёт последний кусок и уснёт.</summary>
    private void Дорога(Предмет где, string слово, double часов, System.Action дошёл,
                        System.Action? прервано = null, МиниИгра? мини = null)
    {
        // мини-игра — пока навык ниже порога; её качество зовущий берёт
        // в итоге через `Как_сыграно`
        bool играть = мини is { } м_ && _партия is not null && МиниИгры.Нужна(_партия.сеанс.я, м_, _ручки);
        int кусков = ХодВремени.Кусков(_ручки, часов);
        double секунд = ХодВремени.Секунд_дела(_ручки, часов);
        bool Кусок(int номер)
        {
            if (!День_героя)
                return false;
            ХодВремени.Прожить(_партия.сеанс.я, часов / кусков);
            Прошло();
            return true;
        }
        _дело.Начать(new Долгое(слово, секунд,
                                готово: () =>
                                {
                                    int день = _партия?.сеанс.дом.day ?? 0;
                                    // как сыграно — сейчас: итог исполнится, когда дом
                                    // уснёт, и новое дело к тому времени может начаться
                                    var сыграно = (_дело.играл, _дело.качество);
                                    if (!Кусок(кусков))
                                        return;
                                    void Итог()
                                    {
                                        _сыграно = сыграно;
                                        дошёл();
                                    }
                                    // в прологе дома нет — ждать некого
                                    if (_пролог is not null)
                                        Итог();
                                    else
                                        _когда_уснёт.Enqueue((день, Итог));
                                },
                                прервано: прервано,
                                кусков: кусков,
                                кусок: Кусок,
                                часов: часов,
                                движение: new Движение(Анимация.Walk),
                                мышь: играть,
                                мини: играть ? мини : null,
                                зона: мини is { } м2 && _партия is not null
                                    ? МиниИгры.Зона(_партия.сеанс.я, м2, _ручки) : 0.22),
                     где, _партия?.сеанс.дом.day ?? 0);
    }

    /// <summary>Дошёл: в магазин — туда; прочее — чем кончилось на месте.</summary>
    private void Дошёл(Поход п)
    {
        if (п.вид == "участок" && Участок_ is { } у && _партия is not null)
        {
            // в метель там никого: дверь открыта, камера пуста
            _в_походе = null;
            у.Пришёл(_партия.сеанс.я);
            _герой.GlobalPosition = _мир.ВходУчастка;
            _герой.Rotation = Vector3.Zero;
            _герой.Прямо();
            Сказать("отделение полиции: дверь не заперта, дежурных нет, в дежурке холодно");
            return;
        }
        if (п.вид == "бункер" && Бункер_известен)
        {
            В_бункер();
            return;
        }
        if (п.вид == "промзона" && Вектор_ is not null)
        {
            В_промзону();
            return;
        }
        if (п.вид == "магазин")
        {
            _отстоял = false;
            _герой.GlobalPosition = _мир.ВходМагазина;
            _герой.Rotation = Vector3.Zero;             // лицом к прилавку
            _герой.Прямо();
            Сказать(_магазин is not null && _партия is not null && _магазин.Открыт(_партия.прогон.h)
                ? "магазин на Заречной: к прилавку очередь"
                : "магазин на Заречной: двери настежь, полки пусты — торговли больше нет");
            return;
        }
        Исход_похода(п);
    }

    /// <summary>Сколько часов на месте: очередь в магазине, корпуса промзоны,
    /// поиски на пустыре.</summary>
    private double Там_часов(Поход п, Округа о) => п.вид switch
    {
        "магазин" => _магазин?.очередь_часы ?? 0.0,
        "промзона" => о.вектор?.часов_меньше_всего ?? 0.0,
        "бункер" => Бункер_известен ? 0.0 : о.летопись.бункер.часов,
        _ => 0.0,
    };

    /// <summary>
    /// Поход без своего места в мире — поиски бункера на пустыре: на месте —
    /// дело (часы кусками, у ворот, как дорога), потом что вышло, потом
    /// дорога назад. Нашёл вход — сразу вниз.
    /// </summary>
    private void Исход_похода(Поход п)
    {
        if (Округа_ is not { } о || _мир.Ворота is not { } ворота)
        {
            Вернуться(п, $"{п.имя}: сходил и вернулся");
            return;
        }
        var h = _партия!.прогон.h;
        var я = _партия.сеанс.я;
        Дорога(ворота, "пустырь за котельной", Там_часов(п, о), () =>
        {
            var (нашёл, замело) = о.Искать_бункер(h, я, тратить: false);
            string весть = замело ? "снег по пояс: ни будок, ни входа — всё замело"
                         : нашёл ? "нашёл: бетонные будки вентиляции и оголовок входа под снегом"
                         : "ходил по пустырю — будок не нашёл";
            if (п.вид == "бункер" && Бункер_известен)
            {
                В_бункер($"{п.имя}: {весть}");
                return;
            }
            Сказать($"{п.имя}: {весть}");
            Дорога(ворота, "дорога домой", Часы_домой(п), () => Вернуться(п, $"вернулся: {весть}"));
        });
    }

    /// <summary>Что лежит на карте со слов знатоков (и найденное самим).</summary>
    private IReadOnlyList<string> Отметки_на_карте()
    {
        if (Округа_ is not { } о)
            return System.Array.Empty<string>();
        var @out = new List<string>();
        if (о.Знает("вектор_есть"))
            @out.Add("промзона «Вектор-3» — за школой, за железкой (Аркадий)"
                     + (о.Знает("вектор_корпуса") ? "; третий и пятый корпуса обходить" : ""));
        if (Вектор_ is { обшарены.Count: > 0 } вектор)
            @out.Add("в промзоне обшарены корпуса: " + string.Join(", ", вектор.обшарены));
        if (о.Знает("вектор_болезнь"))
            @out.Add("болезнь оттуда — язва: знобит, жар, кровь в кашле; к кашляющему не подходить");
        if (о.Знает("бункер_вход"))
            @out.Add("вход в бункер — оголовок у бетонных будок вентиляции на пустыре (нашёл сам)"
                     + (Бункер_ is { открыт: true } б
                         ? $"; гермодверь открыта, в запасе {Текст.G(Текст.Округлить(б.запас_всего, 1))}"
                           + (б.ночей > 0 ? $", ночей под землёй — {б.ночей}" : "")
                         : ""));
        else if (о.Знает("бункер_район"))
            @out.Add("бункер — где-то на пустыре за котельной, у старых гаражей (Сергей, примерно)");
        else if (о.Знает("бункер_слух"))
            @out.Add("бункер с холодной войны — где-то в районе (Сергей, слух)");
        return @out;
    }

