        Здание.СГОРЕЛО => "выгорело дотла",
        Здание.РАЗРУШЕНО => "рухнуло",
        _ => э.вид switch
        {
            ВидСобытияМира.СНЕГОПАД => "замело",
            _ => "что-то случилось",
        },
    };

    /// <summary>
    /// Ход времени в кадре (задание автора, пп. 24–25). Темп — по тому,
    /// что открыто: дело — своё время, карман и карта — стоит, окно вопроса,
    /// телефон и журнал — почти как в жизни, иначе — минута дня за секунду.
    /// Накопился шаг, дом спит на вопросе дня, дела нет — герой прожил шаг,
    /// ничего не делая, и дом живёт дальше. Карман и настройки ставят
    /// на паузу всё дерево, и сюда кадр тогда не доходит вовсе.
    /// </summary>
    private void Время(double delta)
    {
        if (_ход is null || _партия is null)
            return;
        if (_пролог is not null)
        {
            // до метели дом не считает: часы — только героя, и кончились —
            // ночь, следующий день подготовки
            _ход.Кадр(delta, Темп_сейчас());
            var я = _партия.сеанс.я;
            if (!_дело.занят && !_находка.открыт && _ход.Шаг() is double ш)
                ХодВремени.Прожить(я, ш);
            if (я.time_left < 0.3 && !_дело.занят)
                Пролог_ночь();
            Часы_над_телом();
            return;
        }
        _ход.Кадр(delta, Темп_сейчас());
        if (!_дело.занят && !_находка.открыт
            && _партия.Ждёт() is { вопрос: Вопрос.ЧТО_ДЕЛАТЬ }
            && _ход.Шаг() is double шаг)
        {
            ХодВремени.Прожить(_партия.сеанс.я, шаг);
            Прошло(тихо: true);
        }
        Часы_над_телом();
    }

    private Темп Темп_сейчас()
    {
        if (_дело.занят)
            return Темп.ДЕЛО;
        if (_находка.открыт || _карта.открыта || _верстак.открыт || _переход.Visible
            || _карман.открыт || _окно.открыт)
            return Темп.СТОИТ;
        if (_на_экране is { вопрос: not Вопрос.ЧТО_ДЕЛАТЬ } || _телефон.Visible || _журнал.Visible
            || _состояние.Visible || _подъезд.Visible || _вопрос.Развёрнут)
            return Темп.РАЗГОВОР;
        return Темп.ОБЫЧНО;
    }

    /// <summary>
    /// Герой сделал своё сам — взломал, обыскал, — и часы ушли: дом идёт
    /// дальше. Соседи в эти часы живут своё, а вопрос дня придёт заново,
    /// уже с новым временем, новыми людьми на лестнице и новым шкафом.
    /// </summary>
    private void Прошло() => Прошло(тихо: false);

    /// <param name="тихо">Шаг времени, а не поступок: подсказка и план
    /// подъезда остаются прежними, пока дом не спросит снова, — это снимки,
    /// читать их можно. Номера мыслей гаснут всегда: они от старого вопроса.</param>
    private void Прошло(bool тихо)
    {
        // Не в подъезде — не дома: в походе, во дворе, в гараже, в подвале
        // у погреба. Дом это видит, как у соседа на вылазке: к двери
        // поговорить не приходят, квартира пуста. Иначе сосед заводил
        // разговор «через дверь» с тем, кто в это время ломал погреб.
        // Ход героя снимает `away` у него самого, поэтому — перед каждым;
        // ночь снимает у всех
        if (_партия?.Ждёт() is not null
            && (_в_походе is not null || !_мир.ВПодъезде(_герой.GlobalPosition)))
            _партия.сеанс.я.away = true;
        if (_партия is null || !_партия.Пропустить())
            return;
        _вопрос.Убрать();
        _адреса = System.Array.Empty<Адрес?>();
        _тикает = тихо;
        if (!тихо)
        {
            _план_вопроса = System.Array.Empty<ЖилецНаПлане>();
            _подсказка.Text = "";
        }
        Мышь();
    }

    /// <summary>
    /// Ноша в кадре: что несёт — строкой; вошёл в дом с полной тарой —
    /// дом слышит; дошёл до своей квартиры — тара разгружается сама.
    /// Дом трогается только пока спит: вошёл, пока он считал, — шум
    /// прозвучит, как только уснёт.
    /// </summary>
    private void Ноша_в_кадре(Vector3 где)
    {
        var ноша = _партия?.сеанс.я.ноша;
        if (ноша is null)
        {
            _ноша.Text = "";
            return;
        }
        _ноша.Text = ноша.пусто || ноша.тара is not Тара т
            ? ""
            : $"{т.Где()} {Текст.G(Текст.Округлить(ноша.занято, 1))} из {Текст.G(т.мест(_ручки))}: "
              + ноша + (ноша.в_дорогу ? " — собрано в дорогу: выложить в убежище, у стеллажа"
                                     : " — дома разложится у порога");

        bool в_доме = _мир.ВДоме(где);
        if (в_доме && !_был_в_доме && !ноша.пусто)
            _пронести = true;
        _был_в_доме = в_доме;

        bool спит = Дом_спит;
        if (_пронести && спит)
        {
            _пронести = false;
            if (!ноша.пусто && ноша.тара is Тара тара)
            {
                var что = ноша.ресурсы.ToDictionary(р => р, р => ноша.Сколько(р), System.StringComparer.Ordinal);
                double доля = ноша.занято / System.Math.Max(0.001, тара.мест(_ручки));
                var слышали = ноша.Пронести(_партия!.сеанс.дом, _партия.сеанс.я, _ручки);
                // до метели кто слышал — запомнил, что он таскает (п. 15)
                _пролог?.Пронёс(слышали, что, доля);
                Сказать(тара switch
                {
                    Тара.ПАКЕТ => "пакеты шуршат на весь подъезд",
                    Тара.СУМКА => "сумка глухо стукает о перила",
                    _ => "рюкзак за спиной почти не слышно",
                });
            }
        }
        if (!ноша.пусто && !ноша.в_дорогу && спит && _мир.ДомаЛи(где))
            Разгрузить("разложил дома");
    }

    /// <summary>Тару — в шкаф, и полка это покажет. Только пока дом спит.</summary>
    private void Разгрузить(string как)
    {
        if (_партия?.сеанс.я.ноша is not { пусто: false } ноша || !Дом_спит)
            return;
        var я = _партия.сеанс.я;
        var тара = ноша.тара;
        var было = ноша.Разгрузить(я);
        Сказать($"{как}{(тара is Тара т ? " " + т.Текст() : "")}: "
                + string.Join(", ", было.Ключи
                    .OrderBy(р => р, System.StringComparer.Ordinal)
                    .Select(р => $"{р} {Текст.G(Текст.Округлить(было[р], 1))}")));
        _мир.Дома(Дом.Экран.Подача.Внутри(_партия.сеанс.дом, _партия.сеанс.я));
    }

    private void Ответить(int номер)
    {
        if (_карман.открыт || _карта.открыта || _верстак.открыт || _находка.открыт)
            return;             // пока открыт карман, карта, верстак или находка, отвечать нечем
        if (_дело.занят && !_дело.ждёт)
            return;             // итог куска ляжет в дом — он должен спать, пока шкала бежит
        _вопрос.Убрать();
        _адреса = System.Array.Empty<Адрес?>();
        _план_вопроса = System.Array.Empty<ЖилецНаПлане>();
        _подсказка.Text = "";
        if (номер == _цель)
        {
            // выбранная мысль сделана — цели больше нет
            _цель = null;
            _цель_имя = null;
            _цель_строка.Text = "";
        }
        _партия?.Ответить(номер);
        Мышь();
    }

