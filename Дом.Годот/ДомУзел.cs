    /// <summary>Из участка домой — дорога по сегодняшнему снегу, к воротам двора.</summary>
    private void Из_участка()
    {
        if (Участок_ is not { } у || у.где != ВУчастке.УЧАСТОК || _мир.ДверьУчастка is not { } дверь
            || Поход_участка() is not { } п || Округа_ is not { } о || !Можно_в_поход())
            return;
        var h = _партия!.прогон.h;
        var я = _партия.сеанс.я;
        // в одну сторону: замело без снегоступов — не пройти, не хватит дня — не дойти
        double часов = о.Часы_дороги(h, я, п);
        if (!о.летопись.Пройти(п.улица, h.day, о.зерно, о.Есть_у(h, я)))
        {
            Сказать("замело — без снегоступов не дойти; снегоступы, если были, — в вещдоках");
            return;
        }
        if (я.time_left < часов - 1e-9)
        {
            Сказать($"до ночи не дойти: нужно {Часы_текстом(часов)} ч — переждать до утра");
            return;
        }
        Дорога(дверь, "дорога домой", часов, () =>
        {
            у.Ушёл(я);
            Вернуться(п, "вернулся из участка к дому");
        });
    }

