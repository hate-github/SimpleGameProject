// Корень сцены: один узел, который водит петлю и раздаёт её экранам.
//
// Делает он четыре вещи, и ни одной больше:
//   · держит наследие и петлю, читая их с диска и записывая обратно;
//   · заводит жизнь и пускает дом на своём потоке (`Дом.Экран.Партия`);
//   · в каждом кадре смотрит, не спросил ли дом чего-нибудь;
//   · между жизнями показывает монолог и разбор.
//
// Ни нужд, ни памяти, ни знания, ни решений здесь нет и быть не может.
// Если ради интерфейса захочется положить решение в узел — значит,
// не хватает адаптера, а не архитектуры (навык godot-boundary).
//
// Игра — от первого лица (ГДД 23). Первая версия этого узла была панелью
// на весь экран: журнал слева, список вариантов снизу, чёрный фон. Так
// оно и читалось — консолью с кнопками, а не игрой. Теперь посередине
// экрана подъезд, по которому ходят, а панели ушли поверх и по клавишам:
// состояние на Q, журнал на J, телефон на T, план на P, карта на M,
// карман на I. Ходят на WASD, стучат в дверь на E.
//
// Что осталось прежним: ни один узел ничего не решает. Дом спрашивает
// через тот же шов, ответы идут через ту же `Партия`, и подойти к двери —
// это способ задать вопрос, а не ответить на него.
//
// Интерфейс собирается кодом, а не сценой, и это выбор, а не лень.
// Сцену нельзя ни собрать, ни проверить без редактора; код узлов проверяется
// обычным `dotnet build`. Когда в редакторе дойдут руки, любой из этих
// экранов разбирается в `.tscn` без единой правки логики — она вся
// в `Дом.Экран` и `Дом.Ядро/Петля`, куда сцены не заглядывают.

