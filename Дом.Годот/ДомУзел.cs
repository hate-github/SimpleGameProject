    public override void _Ready()
    {
        Собрать();
        try
        {
            _ручки = РучкиПетли.Прочитать(Пути.Данные);
            _пророк = Пророк.Прочитать(Пути.Данные);
            _наследие = Пути.ЕстьНаследие ? Хранение.Прочитать(Пути.Наследие)
                                          : new Наследие();
            _петля = new Дом.Ядро.Петля(_наследие, _ручки, _пророк);
            Монолог();
        }
        catch (System.Exception e)
        {
            // молча погасший дом — худшее, что может случиться с игроком
            _журнал.Шапка($"не завелось: {e.Message}");
            GD.PrintErr(e);
        }
    }

    // ---------- между жизнями ----------

    /// <summary>Стартовый монолог и то, что герой помнит (ГДД 4, 10).</summary>
    private void Монолог()
    {
        var н = _петля.Начать();
        var строки = new List<string> { "", н.монолог, "" };
        if (н.очки > 0)
            строки.Add($"очков навыков: {н.очки} · карман на {н.карман}");
        if (н.можно_уйти)
            строки.Add("(можно просто не вставать)");
        foreach (var з in н.записи.TakeLast(6))
            строки.Add("· " + з.текст);
        if (н.записи.Count > 6)
            строки.Add($"· …и ещё {н.записи.Count - 6} заметок в телефоне");
        foreach (var о in н.отголоски.TakeLast(3))
            строки.Add($"~ кв{о.квартира}: {о.текст}");

        _переход.Показать($"ЖИЗНЬ {н.номер}", строки, _ => Завести());
    }

    private void Завести()
    {
        var прогон = new Прогон(Пути.Данные, seed: Зерно, days: Дней);
        _петля.Слушать(прогон, Кто);
        _партия = new Партия(прогон, Кто);

        // подъезд строится по дому: расселение решает, где какая дверь
        foreach (var узел in _мир.GetChildren())
            узел.QueueFree();
        _мир.Построить(прогон.h);
        int своя = _партия.сеанс.я.apt;
        _герой.Position = _мир.Начало(своя);
        _герой.Rotation = new Vector3(0, Мир.Поворот(своя), 0);
        _герой.Прямо();
        _подъезд.Сеанс = _партия.сеанс;
        _подъезд.Наследие = _наследие;
        _состояние.Сеанс = _партия.сеанс;
        _телефон.Сеанс = _партия.сеанс;
        _телефон.Наследие = _наследие;
        _карман.Сеанс = _партия.сеанс;
        _карта.Сеанс = _партия.сеанс;
        _показано = 0;
        _на_экране = null;
        _итог_показан = false;
        _мир.Отголоски(_наследие.отголоски.Select(о => о.квартира).ToHashSet());
        _журнал.Новая($"Зерно {Зерно}. Вы — {_партия.сеанс.я.name}, "
                      + $"кв.{_партия.сеанс.я.apt}: {_партия.сеанс.я.role}.");
        _партия.Начать();
    }

    /// <summary>
    /// Экран смерти (ГДД 4): причина, сколько прожито, что перенесётся.
    ///
    /// Рассудок числом не показывается: только тем, из чего он сложился.
    /// Шкала, которую видно числом, перестаёт быть скрытой характеристикой
    /// и становится ещё одной полоской.
    /// </summary>
    private void Итог()
    {
        if (_итог_показан || _партия is null)
            return;
        _итог_показан = true;

        if (_партия.беда is not null)
        {
            _журнал.Шапка($"дом упал: {_партия.беда.Message}");
            GD.PrintErr(_партия.беда);
            return;
        }

        var дом = _партия.прогон.h;
        var ж = _петля.Закрыть(_партия.прогон, Кто);
        var р = Концовки.Какая(дом, Кто, _наследие, _ручки);
        Хранение.Записать(_наследие, Пути.Наследие);
        GD.Print($"[жизнь {ж.номер}] {р.имя}: {р.почему}; "
                 + $"{ж.прожито} дн, очков {ж.начислено} (всего {_наследие.очки})");

        var строки = new List<string>
        {
            "",
            р.почему,
            "",
            $"прожито дней: {ж.прожито}   ·   лучшая жизнь: {_наследие.рекорд}",
            $"очков за жизнь: {ж.начислено}   ·   всего: {_наследие.очки}",
            "",
        };
        if (ж.вклады.Count > 0)
            строки.Add("что осталось: " + string.Join(", ", ж.вклады
                .OrderByDescending(в => System.Math.Abs(в.сколько))
                .Take(4).Select(в => в.за_что)));
        if (ж.новые_записи.Count > 0)
            строки.Add($"записано в телефон: {ж.новые_записи.Count}");
        if (ж.новые_отголоски.Count > 0)
            строки.Add($"мест, которые будут помниться: {ж.новые_отголоски.Count}");
        // «заставка только с ними» (ГДД 22): кто остался — поимённо
        if (р.дожило > 0)
            строки.Add("остались: " + string.Join(", ", Концовки.Кто_остался(дом)));

        _партия.Dispose();
        _партия = null;

        _переход.Показать(р.имя.ToUpperInvariant(), строки, _ => Дальше());
    }

    /// <summary>«Дожил» или «дожила»: в русской игре род обязан
    /// согласовываться, и он приходит вместе с итогом жизни.</summary>
    private static string Дожил(Жизнь ж) => Util.Vb(ж.пол, "дожил");

    /// <summary>Следующая жизнь — или конец петли.</summary>
    private void Дальше()
    {
        if (_петля.оборвалась)
        {
            Оборвалась();
            return;
        }
        if (Жизней > 0 && _наследие.жизней >= Жизней)
        {
            _переход.Показать("Хватит на сегодня.",
                new[] { "", $"прожито жизней: {_наследие.жизней}" }, _ => { });
            return;
        }
        Монолог();
    }

    /// <summary>
    /// Точка невозврата (ГДД 11): «Он перестал возвращаться».
    ///
    /// Поле для слова — то самое граффити сумасшедшего пророка. Самого
    /// граффити в мире пока нет нигде, поэтому принимается любое непустое:
    /// место в механике занято, а надпись появится вместе с локациями.
    /// </summary>
    private void Оборвалась()
    {
        _переход.Показать("Он перестал возвращаться.",
            new[]
            {
                "",
                _наследие.знает_слово
                    ? "Ты видел это на стене. Набери."
                    : "Если ты видел слово — набери его.",
                "Пусто — начать новую петлю новым человеком: без памяти,",
                "без очков.",
            },
            слово =>
            {
                if (_пророк.Сошлось(слово))
                {
                    _наследие.нирвана = true;
                    Хранение.Записать(_наследие, Пути.Наследие);
                    Монолог();
                }
                else
                {
                    _наследие = new Наследие();
                    Хранение.Записать(_наследие, Пути.Наследие);
                    _петля = new Дом.Ядро.Петля(_наследие, _ручки, _пророк);
                    Монолог();
                }
            },
            спросить_слово: true);
    }

    // ---------- жизнь ----------

    public override void _Process(double delta)
    {
        if (_партия is null)
            return;

        // новые строки ленты — на экран. Именно новые: ленту пополняет
        // поток дома прямо сейчас, и копировать её целиком каждый кадр
        // было бы и дорого, и незачем
        foreach (var с in _партия.сеанс.ЛентаПосле(_показано))
        {
            _журнал.Строка(с);
            _показано++;
        }

        // метель держится за окном, подсказка — под прицелом
        _воздух.Следом(Мир.Снаружи(_герой.Position));
        _подсказка.Text = Под_прицелом();
        _прицел.Visible = _герой.Свободен;

        // вопрос — если он появился и ещё не показан
        var в = _партия.Ждёт();
        if (!ReferenceEquals(в, _на_экране))
        {
            _на_экране = в;
            if (в is not null)
            {
                _состояние.Обновить();
                _подъезд.Обновить();
                _телефон.Обновить();
                // подача считается с ходом, а не с кадром: дом стоит
                // на вопросе, и читать его сейчас безопасно
                var дом_ = _партия.сеанс.дом;
                var видно = Дом.Экран.Подача.Видно(дом_, _партия.сеанс.я);
                _подача.Обновить(видно);
                _звук.Обновить(Дом.Экран.Подача.Слышно(
                    дом_, _партия.сеанс.я, _партия.сеанс.лента));
                _воздух.Обновить(видно);
                _мир.Освещение(видно.свет);
                _герой.Дрожь = видно.дрожь;
                _герой.Тяжесть = видно.дыхание;

                // у какого варианта какая дверь — считается один раз на вопрос
                // и здесь же, пока дом спит: `Подача.Дверь` читает дом
                _двери_вопроса = в.варианты
                    .Select(x => Дом.Экран.Подача.Дверь(дом_, x)).ToList();
                _план_вопроса = _партия.сеанс.План();

                // что двери говорят сегодня: свет, копоть, сорванный замок.
                // Считает это `Дом.Экран`, узел только красит
                _двери_снаружи = Дом.Экран.Подача.Снаружи(
                    дом_, _партия.сеанс.Квартиры());
                _мир.Обновить(_двери_снаружи);

                Телом(видно);
                _вопрос.Показать(в, _двери_вопроса, Ответить);
                Мышь();
            }
            else
            {
                _вопрос.Убрать();
                _двери_вопроса = System.Array.Empty<int?>();
                _план_вопроса = System.Array.Empty<ЖилецНаПлане>();
                Мышь();
            }
        }

        // разворот списка меняет и мышь, и свободу ходить, а нажимают
        // на него в самом  — узел о нём узнаёт только так
        if (_вопрос.Развёрнут != _разворот)
        {
            _разворот = _вопрос.Развёрнут;
            Мышь();
        }

        if (_партия.кончилась && _на_экране is null)
            Итог();
    }

    /// <summary>
    /// Что под прицелом: чья это дверь, что о хозяине известно и что
    /// с ним можно сделать прямо сейчас.
    ///
    /// Считается по снимкам, снятым в тот момент, когда дом задал вопрос,
    /// а не по дому. Разница не в скорости: подсказка обновляется каждый
    /// кадр, а дом в это время может считать на своём потоке, и читать
    /// его тогда нельзя — это то же правило, из-за которого лента заперта
    /// замком. Первая версия звала `Сеанс.План()` прямо отсюда.
    ///
    /// Имя и занятие берутся из плана подъезда, то есть из того же, что
    /// видит сосед. Шкаф и чувства сюда не попадают — для них есть телефон
    /// и знание.
    ///
    /// Вторая строка — то, ради чего затевалась вся эта геометрия: не «что
    /// можно сделать вообще», а какие из **уже собранных домом** вариантов
    /// ведут к этой двери. Ничего не добавляется и не отбирается: номера
    /// те же, что в листе, и первый из них — тот, что дом взвесил выше.
    /// </summary>
    private string Под_прицелом()
    {
        if (_партия is null || _герой.Перед_дверью is not int кв)
            return "";
        var ж = _план_вопроса.FirstOrDefault(x => x.квартира == кв);
        string кто = ж is null
            ? $"кв.{кв} — пусто"
            : ж.здесь
              ? $"кв.{кв} — {ж.имя}, {ж.роль}"
              : $"кв.{кв} — {ж.имя}, †{(ж.причина is not null ? " " + ж.причина : "")}";

        кто += Видно_у_двери(кв);

        var номера = Номера_к_двери(кв);
        if (номера.Count == 0)
            return кто + "\nсюда сейчас незачем";
        var в = _на_экране!.варианты;
        string первый = в[номера[0]].строка.Split("  ")[0].TrimEnd();
        string хвост = номера.Count > 1 ? $"   (ещё {номера.Count - 1}: "
                       + string.Join(", ", номера.Skip(1).Take(4)) + ")" : "";
        return $"{кто}\n[E]  {первый}{хвост}";
    }

    /// <summary>
    /// Что видно у самой двери — словами к тому, что уже видно глазом.
    ///
    /// Копоть, сорванный замок и щель света дверь показывает сама; здесь
    /// они названы, потому что «дверь чуть темнее» без подписи читается
    /// как игра света, а не как «здесь горело».
    ///
    /// Отголосок прошлой жизни (ГДД 10) — единственное, чего в мире нет
    /// и быть не может: зарубка на косяке видна, а что она значит, помнит
    /// только тот, кто здесь уже был.
    /// </summary>
    private string Видно_у_двери(int кв)
    {
        var что = _двери_снаружи.FirstOrDefault(д => д.квартира == кв);
        var слова = new List<string>();
        if (что is not null)
        {
            if (что.разобрана) слова.Add("разобрана");
            else if (что.взломана) слова.Add("замок сорван");
            if (что.горело) слова.Add("пахнет гарью");
            if (что.тело) слова.Add("хозяин так и остался внутри");
            else if (!что.живут) слова.Add("пусто");
            if (что.свет) слова.Add("из-под двери светит");
        }
        var эхо = _наследие?.отголоски.LastOrDefault(о => о.квартира == кв);
        if (эхо is not null)
            слова.Add($"на косяке зарубка: {эхо.текст}");
        return слова.Count == 0 ? "" : "  ·  " + string.Join("; ", слова);
    }

    /// <summary>Номера вариантов, ведущих к этой двери. Считаются
    /// по разу на вопрос: сам расчёт читает дом, а дом читать можно
    /// только пока он спит на вопросе.</summary>
    private List<int> Номера_к_двери(int кв)
    {
        var @out = new List<int>();
        for (int i = 0; i < _двери_вопроса.Count; i++)
            if (_двери_вопроса[i] == кв)
                @out.Add(i);
        return @out;
    }

    /// <summary>Постучать в дверь под прицелом: ответить первым из тех
    /// вариантов, что к ней ведут. «Первым» — значит тем, который дом
    /// взвесил выше прочих, а не тем, который удобнее интерфейсу.</summary>
    private void Постучать()
    {
        if (_на_экране is null || _герой.Перед_дверью is not int кв)
            return;
        var номера = Номера_к_двери(кв);
        if (номера.Count > 0)
            Ответить(номера[0]);
    }

    /// <summary>Что с телом — одной строкой внизу экрана, всегда.
    /// Это и есть «экран без полосок» (ГДД 23): не шкала, а то, что
    /// человек про себя знает и без шкалы.</summary>
    private void Телом(Дом.Экран.Обстановка видно)
    {
        if (_партия is null)
            return;
        var слова = Дом.Экран.Подача.Телом(_партия.сеанс.я);
        var с = _партия.сеанс.Состояние();
        _телом.Text = слова.Count == 0
            ? $"часов до ночи {Текст.Ф(с.часов_до_ночи, 1)}"
            : string.Join(" · ", слова.Take(3))
              + $"        часов до ночи {Текст.Ф(с.часов_до_ночи, 1)}";
        _телом.AddThemeColorOverride("font_color",
            new Color("#c8b48a") with { A = (float)(0.55 + 0.45 * видно.краснота) });
    }

    private void Ответить(int номер)
    {
        if (_карман.открыт || _карта.открыта)
            return;             // пока открыт карман или карта, отвечать нечем
        _вопрос.Убрать();
        _двери_вопроса = System.Array.Empty<int?>();
        _план_вопроса = System.Array.Empty<ЖилецНаПлане>();
        _подсказка.Text = "";
        _партия?.Ответить(номер);
        Мышь();
    }

    public override void _ExitTree() => _партия?.Dispose();

    /// <summary>
    /// Разложить игру: посередине подъезд, поверх — панели по клавишам.
    ///
    /// Панели больше не занимают экран: они прячутся и вызываются, потому
    /// что игрок смотрит на дом, а не на список строк. Вопрос — исключение:
    /// он приходит сам, когда дом спрашивает, но и он лежит листом в углу
    /// и никого не держит.
    /// </summary>
    private void Собрать()
    {
        // ---- мир ----
        _воздух = new Обстановка3D();
        AddChild(_воздух);

        _мир = new Мир();
        AddChild(_мир);

        _герой = new Герой();
        AddChild(_герой);

        // ---- панели поверх ----
        _панели = new Control { MouseFilter = Control.MouseFilterEnum.Ignore };
        AddChild(_панели);
        По_окну();
        GetViewport().SizeChanged += По_окну;

        _журнал = new ЖурналUI
        {
            Visible = false,
            Position = new Vector2(16, 16),
            Size = new Vector2(560, 420),
        };
        _панели.AddChild(_журнал);

        _подъезд = new ПодъездUI
        {
            Visible = false,
            Position = new Vector2(16, 16),
            Size = new Vector2(420, 620),
        };
        _панели.AddChild(_подъезд);

        // Состояние спрятано за клавишу, а не висит в углу, и это не вкус.
        // Пока оно висело, экран читался как приборная доска: список запасов
        // слева, список вариантов снизу, подъезд где-то между ними. То, что
        // человек знает про себя всегда, ушло в одну строку внизу (`_телом`);
        // остальное — цифры шкафа и догадки о соседях — открывается на Q,
        // потому что это не ощущение, а сведения.
        _состояние = new СостояниеUI
        {
            Visible = false,
            Position = new Vector2(16, 16),
            Size = new Vector2(360, 420),
        };
        _панели.AddChild(_состояние);

        _телефон = new ТелефонUI
        {
            Visible = false,
            Position = new Vector2(16, 16),
            Size = new Vector2(520, 460),
        };
        _панели.AddChild(_телефон);

        // Лист вопроса — в нижнем левом углу, растёт вверх от него.
        // Якоря, а не числа: список то в десять строк, то в тридцать,
        // и высоту его считает раскладка, а не узел.
        // Куда лечь, вопрос считает сам: высота списка зависит от числа
        // строк, а строки приходят от дома, а не от раскладки.
        _вопрос = new ВопросUI();
        _панели.AddChild(_вопрос);

        _карман = new КарманUI();
        _панели.AddChild(_карман);

        _карта = new КартаUI();
        _панели.AddChild(_карта);

        // прицел: точка в середине экрана. Без неё непонятно, на какую
        // дверь смотришь, — а «смотришь на дверь» здесь значит «можешь
        // в неё постучать»
        _прицел = new ColorRect
        {
            Color = new Color(0.85f, 0.83f, 0.76f, 0.55f),
            MouseFilter = Control.MouseFilterEnum.Ignore,
        };
        _панели.AddChild(_прицел);

        // подсказка под прицелом: «кв.9 — Лида, врач» и что с ней можно
        _подсказка = new Label
        {
            HorizontalAlignment = HorizontalAlignment.Center,
            MouseFilter = Control.MouseFilterEnum.Ignore,
        };
        _подсказка.AddThemeColorOverride("font_color", new Color("#e8e2d0"));
        _панели.AddChild(_подсказка);

        // что с телом — одной строкой понизу, всегда (ГДД 23)
        _телом = new Label
        {
            HorizontalAlignment = HorizontalAlignment.Center,
            MouseFilter = Control.MouseFilterEnum.Ignore,
        };
        _панели.AddChild(_телом);

        _переход = new ПереходUI();
        _панели.AddChild(_переход);

        _подача = new ПодачаUI();
        _панели.AddChild(_подача);
        _панели.MoveChild(_подача, _переход.GetIndex());

        _звук = new ЗвукUI();
        AddChild(_звук);
    }

    private void По_окну()
    {
        var р = GetViewport().GetVisibleRect().Size;
        _панели.Position = Vector2.Zero;
        _панели.Size = р;
        if (_прицел is not null)
        {
            _прицел.Position = new Vector2(р.X / 2 - 2, р.Y / 2 - 2);
            _прицел.Size = new Vector2(4, 4);
        }
        if (_подсказка is not null)
        {
            _подсказка.Position = new Vector2(0, р.Y * 0.54f);
            _подсказка.Size = new Vector2(р.X, 52);
        }
        if (_телом is not null)
        {
            _телом.Position = new Vector2(0, р.Y - 30);
            _телом.Size = new Vector2(р.X, 24);
        }
    }

    /// <summary>
    /// Клавиши: J — журнал, T — телефон, P — подъезд, Q — состояние,
    /// E — постучать в дверь под прицелом. Карта и карман открываются
    /// сами (M и I), список вариантов разворачивается пробелом.
    ///
    /// E стоит первым нарочно: это единственная клавиша, которая не
    /// открывает экран, а делает ход. Всё остальное — способы посмотреть.
    /// </summary>
    public override void _UnhandledInput(InputEvent e)
    {
        if (e is not InputEventKey к || !к.Pressed || к.Echo)
            return;
        switch (к.Keycode)
        {
            case Key.E: Постучать(); break;
            case Key.J: Панель(_журнал); break;
            case Key.T: _телефон.Обновить(); Панель(_телефон); break;
            case Key.P: _подъезд.Обновить(); Панель(_подъезд); break;
            case Key.Q: _состояние.Обновить(); Панель(_состояние); break;
            default: return;
        }
        GetViewport().SetInputAsHandled();
    }

    private void Панель(Control какая)
    {
        какая.Visible = !какая.Visible;
        if (какая.Visible)
            _вопрос.Свернуть();
        Мышь();
    }

    /// <summary>
    /// Мышь захвачена, пока не открыт ни один экран: в подъезде её нет,
    /// а в телефоне она нужна.
    ///
    /// Лист вопроса экраном не считается — в этом вся разница. Пока он
    /// висит в углу, человек ходит, смотрит и может ответить, подойдя
    /// к двери. Останавливает его только развёрнутый список: там тридцать
    /// строк с весами, и по ним тычут мышью.
    /// </summary>
    private void Мышь()
    {
        bool занят = _вопрос.Развёрнут || _карман.открыт || _карта.открыта
                     || _переход.Visible || _телефон.Visible || _журнал.Visible
                     || _подъезд.Visible || _состояние.Visible;
        _герой.Свободен = !занят;
        Input.MouseMode = занят ? Input.MouseModeEnum.Visible
                                : Input.MouseModeEnum.Captured;
    }
