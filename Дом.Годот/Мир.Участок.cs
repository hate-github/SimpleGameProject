// Полицейский участок (задание автора, пп. 16–18): камера, дежурка, кладовая,
// оружейная, вещдоки, выход на улицу.
//
// Отдельная комната далеко от двора, как магазин, — сюда переносит
// задержание или поход. Считать участок — дело `Дом.Ядро.Участок`; здесь
// только стены, решётка камеры и места, у которых что-то делается.
// Решётка твёрдая, пока камера заперта: выйти из неё можно, только
// сломав дверь (`Камера_открыта`).

using Godot;

namespace Дом.Годот;

public partial class Мир
{
    /// <summary>Где стоит участок — далеко от двора и от магазина.</summary>
    private static readonly Vector3 УЧАСТОК = new(-300, 0, 0);
    private const float УЧ_Ш = 12f, УЧ_Г = 9f, УЧ_В = 3.0f;

    public Предмет? ДверьКамеры { get; private set; }
    public Предмет? Нары { get; private set; }
    public Предмет? КладоваяУчастка { get; private set; }
    public Предмет? Оружейная { get; private set; }
    public Предмет? Вещдоки { get; private set; }
    public Предмет? Печка { get; private set; }
    public Предмет? ДверьУчастка { get; private set; }

    /// <summary>Где сидит задержанный — в камере, лицом к решётке.</summary>
    public Vector3 ВКамере => УЧАСТОК + new Vector3(-4.3f, 0.1f, -3.0f);

    /// <summary>Где встаёт вошедший с улицы — у двери, лицом внутрь.</summary>
    public Vector3 ВходУчастка => УЧАСТОК + new Vector3(0, 0.1f, УЧ_Г / 2 - 1.2f);

    /// <summary>Он ли в участке.</summary>
    public bool ВУчастке(Vector3 где)
        => Math.Abs(где.X - УЧАСТОК.X) < УЧ_Ш / 2 + 0.5f
           && Math.Abs(где.Z - УЧАСТОК.Z) < УЧ_Г / 2 + 0.5f
           && где.Y > -1 && где.Y < УЧ_В + 1;

    private Node3D? _решётка;

    /// <summary>Решётку камеры сломали — пройти можно; или заперли снова.</summary>
    public void Камера_открыта(bool да)
    {
        if (_решётка is null)
            return;
        _решётка.Visible = !да;
        _решётка.ProcessMode = да ? ProcessModeEnum.Disabled : ProcessModeEnum.Inherit;
        if (_решётка is StaticBody3D тело)
            тело.CollisionLayer = да ? 0u : 1u;
    }

    /// <summary>Стены, камера, дежурка, кладовая, оружейная, вещдоки, выход.</summary>
    private void Участок_построить()
    {
        var бетон = Материал(new Color("#5a5650"), 0.95f);
        var пол = Материал(new Color("#34302b"), 0.9f);
        var краска = Материал(new Color("#3c4a52"), 0.8f);
        var металл = Материал(new Color("#5a6066"), 0.5f);
        var доска = Материал(new Color("#5a4a36"), 0.9f);
        Vector3 О(float x, float y, float z) => УЧАСТОК + new Vector3(x, y, z);
        float ш = УЧ_Ш / 2, г = УЧ_Г / 2;

        Коробка(пол, new Vector3(УЧ_Ш + 0.4f, 0.2f, УЧ_Г + 0.4f), О(0, -0.1f, 0));
        Коробка(бетон, new Vector3(УЧ_Ш + 0.4f, 0.2f, УЧ_Г + 0.4f), О(0, УЧ_В + 0.1f, 0));
        Коробка(бетон, new Vector3(0.2f, УЧ_В, УЧ_Г), О(-ш - 0.1f, УЧ_В / 2, 0));
        Коробка(бетон, new Vector3(0.2f, УЧ_В, УЧ_Г), О(ш + 0.1f, УЧ_В / 2, 0));
        Коробка(бетон, new Vector3(УЧ_Ш, УЧ_В, 0.2f), О(0, УЧ_В / 2, -г - 0.1f));
        // передняя стена с дверью посередине
        Коробка(бетон, new Vector3(ш - 0.6f, УЧ_В, 0.2f), О(-(ш + 0.6f) / 2, УЧ_В / 2, г + 0.1f));
        Коробка(бетон, new Vector3(ш - 0.6f, УЧ_В, 0.2f), О((ш + 0.6f) / 2, УЧ_В / 2, г + 0.1f));
        Коробка(бетон, new Vector3(1.2f, 0.9f, 0.2f), О(0, УЧ_В - 0.45f, г + 0.1f));
        Коробка(краска, new Vector3(1.2f, УЧ_В - 0.9f, 0.1f), О(0, (УЧ_В - 0.9f) / 2, г + 0.2f));
        ДверьУчастка = Предмет.Вокруг(this, new Aabb(О(-0.7f, 0, г - 0.4f), new Vector3(1.4f, 2.1f, 0.6f)),
                                      0.05f, "дверь_участка");

        // камера в дальнем углу: стена справа и спереди, решётчатая дверь
        Коробка(бетон, new Vector3(0.2f, УЧ_В, 3.5f), О(-2.5f, УЧ_В / 2, -г + 1.75f));
        Коробка(бетон, new Vector3(1.2f, УЧ_В, 0.2f), О(-5.4f, УЧ_В / 2, -1.0f));
        Коробка(бетон, new Vector3(1.3f, УЧ_В, 0.2f), О(-3.15f, УЧ_В / 2, -1.0f));
        Коробка(бетон, new Vector3(1.0f, УЧ_В - 2.1f, 0.2f), О(-4.3f, 2.1f + (УЧ_В - 2.1f) / 2, -1.0f));
        var решётка = Коробка(металл, new Vector3(1.0f, 2.1f, 0.08f), О(-4.3f, 1.05f, -1.0f));
        решётка.Name = "решётка_камеры";
        for (int i = 0; i < 6; i++)
            Меш(металл, new Vector3(0.03f, 2.1f, 0.03f), О(-4.72f + i * 0.17f, 1.05f, -0.95f));
        _решётка = решётка;
        ДверьКамеры = Предмет.Вокруг(this, new Aabb(О(-4.8f, 0, -1.35f), new Vector3(1.0f, 2.1f, 0.3f)),
                                     0.05f, "дверь_камеры");
        Коробка(доска, new Vector3(0.8f, 0.45f, 2.0f), О(-5.5f, 0.225f, -2.8f));
        Нары = Предмет.Вокруг(this, new Aabb(О(-5.9f, 0, -3.8f), new Vector3(0.8f, 0.6f, 2.0f)),
                              0.05f, "нары");

        // дежурка: стол, печка-буржуйка
        Коробка(доска, new Vector3(1.6f, 0.8f, 0.8f), О(2.5f, 0.4f, -1.0f));
        Коробка(металл, new Vector3(0.7f, 1.0f, 0.7f), О(4.6f, 0.5f, -3.5f));
        Меш(металл, new Vector3(0.15f, УЧ_В - 1.0f, 0.15f), О(4.6f, 1.0f + (УЧ_В - 1.0f) / 2, -3.5f));
        Печка = Предмет.Вокруг(this, new Aabb(О(4.25f, 0, -3.85f), new Vector3(0.7f, 1.1f, 0.7f)),
                               0.1f, "печка_участка");

        // кладовая у задней стены: стеллаж с коробками
        Коробка(доска, new Vector3(3.0f, 2.0f, 0.5f), О(0.5f, 1.0f, -г + 0.3f));
        for (int ряд = 0; ряд < 3; ряд++)
            for (int i = 0; i < 5; i++)
                Меш(Материал(ЦВЕТА_ТОВАРА[(i + ряд) % ЦВЕТА_ТОВАРА.Length], 0.8f),
                    new Vector3(0.45f, 0.35f, 0.35f), О(-0.5f + i * 0.5f, 0.3f + ряд * 0.65f, -г + 0.62f));
        КладоваяУчастка = Предмет.Вокруг(this, new Aabb(О(-1.0f, 0, -г + 0.1f), new Vector3(3.0f, 2.0f, 0.9f)),
                                         0.05f, "кладовая_участка");

        // оружейная — железный шкаф; вещдоки — шкаф у входа
        Коробка(металл, new Vector3(0.6f, 2.0f, 1.5f), О(ш - 0.4f, 1.0f, 0.5f));
        Оружейная = Предмет.Вокруг(this, new Aabb(О(ш - 1.0f, 0, -0.25f), new Vector3(0.9f, 2.0f, 1.5f)),
                                   0.05f, "оружейная");
        Коробка(краска, new Vector3(0.6f, 1.8f, 1.2f), О(-ш + 0.4f, 0.9f, 2.5f));
        Вещдоки = Предмет.Вокруг(this, new Aabb(О(-ш + 0.1f, 0, 1.9f), new Vector3(0.9f, 1.8f, 1.2f)),
                                 0.05f, "вещдоки");

        AddChild(new OmniLight3D
        {
            Position = О(0, УЧ_В - 0.3f, 0),
            LightColor = new Color("#d8e0e6"),
            LightEnergy = 0.8f,
            OmniRange = 12f,
        });
        AddChild(new Label3D
        {
            Text = "ПОЛИЦИЯ",
            FontSize = 96,
            PixelSize = 0.004f,
            Modulate = new Color("#c8d0d8"),
            Position = О(0, УЧ_В - 0.35f, г - 0.05f),
            Rotation = new Vector3(0, Mathf.Pi, 0),
            Shaded = false,
        });
    }
}
