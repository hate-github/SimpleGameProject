// Кладовая в мире: замок, ящики и обыск (ГДД 7, 12).
//
// Гараж во дворе и погреб в подвале — это `Кладовая` из `npcs.json`,
// со своими запасами, замком и ключом у хозяина, и **своего учёта у них
// нет**: ящики пустеют, когда пустеет кладовая, замок сорван, когда она
// вскрыта. Стены и дверь у них разные (`Гараж`, `Погреб`), а замок, ящики
// и цена обыска общие — и живут здесь, чтобы разъехаться было негде.
//
// Взломать замок и обыскать ящик — поступки героя, а не ответы на вопрос
// дома, как и карман: делаются только пока дом спит на вопросе, функциями
// самого дома, и не сразу — через шкалу долгого дела (`ДелоUI`).
//   · Замок — `Взлом.попытка`, и **только инструментом**: голыми руками
//     навесной замок не сорвать (задание автора, п. 4). Чем ломать, решает
//     то, что при герое: молоток из дома бьёт полтора часа и слышен на весь
//     подвал, болторез с чужого верстака перекусывает дужку за двадцать
//     минут почти беззвучно (`data/инструменты.json`). Нет подходящего —
//     дело не начинается, и подсказка говорит, чем этот замок берут.
//     Ранен, держат, без сознания — не ломает вовсе (`Положения`).
//     По замку бьют — дом слышит, и в первые дни на стук спускаются:
//     застали — замок цел, а поимка разбирается ходом дома (вопрос
//     «бежать?» придёт окном), и дом запомнит вора.
//     Взлом идёт кусками (`ХодВремени.Кусков`, `Взлом.кусок`): полтора часа
//     молотком — пять кусков за десять секунд шкалы, и после каждого дом
//     живёт эти минуты. Спустились на стук второго куска — дело кончилось
//     на втором, а не после всех полутора часов.
//   · Ящик — `Обыск.коробка`: часы дня и доля того, что осталось,
//     на все полные ящики. Найденное не ложится в шкаф: игрок решает,
//     в чём его нести (карман вне времени, пакеты, сумка, рюкзак —
//     `Дом.Ядро.Ноша`), и что не влезло, остаётся в ящике.
//   · Оба поступка стоят часов, и после них дом идёт дальше (`Прошло`):
//     соседи в эти часы живут своё, а вопрос дня приходит заново.
//     Поэтому они берутся только на вопросе дня, а не на просьбе соседа.
//   · Сорванный замок можно повесить обратно — для вида: запертым он
//     от этого не станет, и дом по-прежнему знает, что кладовая вскрыта.
//     Свой замок снимается и вешается ключом, без всякого дела.
//
// Мысли «сходить в кладовую» и «вскрыть кладовую» у такой кладовой
// клавишей не отвечаются: они говорят, куда идти (`Дом.Экран.Места`),
// а делается всё здесь, руками. Иначе банки оказывались бы дома раньше
// героя — ровно то, от чего гараж и уходил.

using Godot;
using Дом.Экран;
using Дом.Ядро;

namespace Дом.Годот;

public abstract partial class Хранилище : Node3D
{
    /// <summary>Слой тел, которые мешают ходить, но не мешают прицелу:
    /// верстак, полка, ящики, барьер над ямой. Иначе ящик за ними было бы
    /// не выбрать — луч упирался бы в них самих.</summary>
    public const uint СЛОЙ_МЕБЕЛИ = 4;

    private const double КАЖДЫЙ_УДАР = 0.75;   // как часто бьют по замку

    // сколько часов ушло на идущий взлом: куски отдаются по одному
    private double _ушло;

    // ---- связь с домом и героем: ставит корневой узел ----
    public System.Func<(House дом, NPC я)?> Дом { get; set; } = () => null;
    public System.Func<bool> МожноМенять { get; set; } = () => false;

    /// <summary>Дом спит на вопросе дня: можно делать то, что стоит часов.
    /// На просьбу соседа или ночь «я пока взломаю замок» не ответ.</summary>
    public System.Func<bool> МожноПоступать { get; set; } = () => false;

    /// <summary>Почему поступать нельзя, если причина не «дом ждёт ответа»
    /// (до метели — кругом люди). Нет — обычная отповедь.</summary>
    public System.Func<string?> Нельзя_сейчас { get; set; } = () => null;

    /// <summary>Поступок стоил часов — дому пора идти дальше.</summary>
    public System.Action Прошло { get; set; } = () => { };

    /// <summary>Ящик обыскан: спросить, в чём нести найденное.
    /// Второй аргумент — где нашлось («в ящике»), третий — «взять»
    /// (тара или null — карман вне времени), четвёртый — «оставить».</summary>
    public System.Action<Добыча, string, System.Action<Тара?>, System.Action> Найдено { get; set; }
        = (_, _, _, оставить) => оставить();

    public System.Func<РучкиПетли?> Ручки { get; set; } = () => null;

    /// <summary>Каталог инструментов и замков.</summary>
    public System.Func<Инструменты> Каталог { get; set; } = () => Инструменты.НИКАКИХ;

    /// <summary>В каком виде герой — снимок на последнем вопросе.</summary>
    public System.Func<Положение> Как_герой { get; set; } = () => Положение.НОРМА;
    public System.Action<string> Сказать { get; set; } = _ => { };
    public System.Action<Долгое, Предмет> Начать { get; set; } = (_, _) => { };

    /// <summary>Шла ли в деле мини-игра и как сыграно (`ДелоUI`).</summary>
    public System.Func<(bool играл, double качество)> Сыграно { get; set; } = () => (false, 0.5);
    public System.Func<Vector3> ГдеГерой { get; set; } = () => new Vector3(1e6f, 0, 0);

    /// <summary>Сюда ли ведёт мысль, выбранная в телефоне. Тогда подсказка
    /// у замка и двери так и говорит: пришёл.</summary>
    public System.Func<bool> Цель { get; set; } = () => false;

    /// <summary>Какая кладовая дома — это хранилище.</summary>
    public Кладовая? кладовая { get; set; }

    // Снимок дома на последнем вопросе. Подсказку зовут каждый кадр,
    // а дом в это время может считать ход, и читать его тогда нельзя.
    // Поэтому подсказка смотрит сюда, а в дом ходят только действия —
    // и только пока он спит на вопросе.
    protected bool _доступ, _вскрыта;
    private bool _вскрыта_было;
    protected bool _замок_висит = true;
    protected double _сеть = 1.0;

    /// <summary>Замок: виден, пока висит.</summary>
    protected Node3D? _замок;
    protected readonly List<Коробка> _коробки = new();
    protected AudioStreamPlayer3D? _звук_замка, _звук_коробки;
    protected readonly RandomNumberGenerator _кость = new();

    /// <summary>Ящик (в гараже — коробки): полный и пустой вид, место
    /// и как он зовётся в подсказке.</summary>
    protected sealed class Коробка
    {
        public Node3D? полная, пустая;
        public bool пуста;
        public bool достать = true;      // на дне ямы — видна, но не достать
        public Vector3 где;
        public string имя = "";
        public string название = "коробки";
        public string внутри = "в коробке";
    }

    /// <summary>Чья это кладовая — первая строка подсказок.</summary>
    protected abstract string Чей();

    /// <summary>Первая строка подсказки: чья кладовая, что с замком
    /// и — если сюда ведёт выбранная мысль — что пришёл.</summary>
    protected string Шапка(string хвост = "")
        => Чей() + хвост + (Цель() ? "  ← цель" : "");

    /// <summary>Клавиша действия, как её пишут подсказки: «[E]», пока игрок
    /// не назначил другую.</summary>
    protected static string Жми => Управление.В_скобках(Клавиши.ДЕЙСТВИЕ);

    /// <summary>
    /// Сверить с домом. Зовётся на каждом вопросе, пока дом спит:
    /// пока герой ходил, хозяин мог сам сходить за своим, а сосед —
    /// сорвать замок, и кладовая должна это показать.
    /// </summary>
    public void Обновить(double сеть)
    {
        _сеть = сеть;
        if (кладовая is { } к)
        {
            _вскрыта = к.вскрыта;
            _доступ = Дом() is { } д && д.дом.есть_ключ(д.я, к);
            // сорвали только что — замка на петлях больше нет, кто бы ни сорвал
            if (_вскрыта && !_вскрыта_было)
                _замок_висит = false;
            _вскрыта_было = _вскрыта;
            if (к.пусто())
                foreach (var коробка in _коробки)
                    коробка.пуста = true;
        }
        Показать();
    }

    /// <summary>Показать снимок: какие ящики пусты, висит ли замок.
    /// В дом не ходит.</summary>
    protected virtual void Показать()
    {
        if (_замок is not null)
            _замок.Visible = _замок_висит;
        foreach (var к in _коробки)
        {
            if (к.полная is not null) к.полная.Visible = !к.пуста;
            if (к.пустая is not null) к.пустая.Visible = к.пуста;
        }
    }

    // ------------------------------------------------------------ замок

    protected string ЗамокПодсказка()
    {
        if (кладовая is null)
            return _замок_висит ? $"{Шапка()}\n{Жми}  снять замок" : $"{Шапка()}\n{Жми}  повесить замок";
        if (_замок_висит)
        {
            if (_вскрыта)
                return $"{Шапка(" — замок сорван, висит для вида")}\n{Жми}  снять";
            if (_доступ)
                return $"{Шапка(" — ключ у тебя")}\n{Жми}  отпереть";
            return $"{Шапка(" — на замке")}\n{Как_взломать()}";
        }
        if (_вскрыта)
            return $"{Шапка(" — замок сорван")}\n{Жми}  повесить для вида";
        return $"{Шапка(" — не заперт")}\n{Жми}  запереть";
    }

    protected void ЗамокДействие(Предмет замок)
    {
        if (!_замок_висит)
        {
            _замок_висит = true;
            Показать();
            Сказать(_вскрыта ? "повесил сорванный замок — для вида, он не заперт"
                             : "запер");
            Играть(_звук_замка, "удар_по_металлу", громче: -10f);
            return;
        }
        if (кладовая is null || Дом() is not { } д || _вскрыта || _доступ)
        {
            // свой ключ или сорванный замок: снимается без всякого дела
            _замок_висит = false;
            Показать();
            Сказать(_вскрыта ? "снял сорванный замок" : "отпер своим ключом");
            Играть(_звук_замка, "удар_по_металлу", громче: -10f);
            return;
        }
        // чужой и целый — взлом: дело, и оно может не выйти
        if (Нельзя() is string почему)
        {
            Сказать(почему);
            return;
        }
        if (!Положения.Можно_ломать(Как_герой()))
        {
            Сказать($"{Как_герой().Текст()} — замок сейчас не сорвать");
            return;
        }
        var ручки = Ручки();
        if (ручки is null)
            return;
        if (Взлом.чем(д.я, кладовая, Каталог()) is not { } чем)
        {
            Сказать($"голыми руками замок не сорвать — нужен {Чем_берут()}");
            return;
        }
        var (инструмент, приём) = чем;
        if (!Взлом.успеет(д.дом, д.я, приём))
        {
            Сказать($"до ночи не успеть: на замок {инструмент.чем} нужно "
                    + $"{Текст.G(Текст.Округлить(Взлом.часы(д.дом, приём), 1))} ч");
            return;
        }
        // Шкала длится по часам дела (полтора часа — десять секунд) и идёт
        // кусками: после каждого куска дом живёт его минуты (`ХодВремени`)
        double часов = Взлом.часы(д.дом, приём);
        double секунд = ХодВремени.Секунд_дела(ручки, часов);
        int кусков = ХодВремени.Кусков(ручки, часов);
        bool громко = приём.шум >= 2;
        double удар = 0;
        _ушло = 0;
        // мини-игра «Взлом» — пока Смекалка ниже порога; с порога дело идёт само
        bool играть = МиниИгры.Нужна(д.я, МиниИгра.ВЗЛОМ, ручки);
        Начать(new Долгое(инструмент.имя, секунд,
                          готово: () => Кусок_взлома(ручки, инструмент, приём, кусков, кусков),
                          прервано: () => Сказать(_ушло > 0
                              ? $"бросил замок · ушло {Текст.G(Текст.Округлить(_ушло, 1))} ч"
                              : "бросил замок"),
                          идёт: прошло =>
                          {
                              // громкий инструмент бьёт, тихий — один щелчок в конце
                              if (прошло < удар || (!громко && прошло < секунд * 0.8))
                                  return;
                              удар = громко ? прошло + КАЖДЫЙ_УДАР : double.MaxValue;
                              Играть(_звук_замка, "удар_по_металлу", громче: громко ? 0f : -14f);
                          },
                          кусков: кусков,
                          кусок: номер => Кусок_взлома(ручки, инструмент, приём, номер, кусков),
                          часов: часов,
                          движение: Анимации.Ломать(инструмент),
                          в_руках: инструмент.id,
                          мышь: играть,
                          мини: играть ? МиниИгра.ВЗЛОМ : null,
                          зона: МиниИгры.Зона(д.я, МиниИгра.ВЗЛОМ, ручки)),
               замок);
    }

    /// <summary>Вторая строка подсказки у чужого замка: чем его возьмёт
    /// то, что при герое, — или чего не хватает.</summary>
    private string Как_взломать()
    {
        var положение = Как_герой();
        if (!Положения.Можно_ломать(положение))
            return $"{положение.Текст()} — не сорвать";
        if (кладовая is null || Дом() is not { } д
            || Взлом.чем(д.я, кладовая, Каталог()) is not { } чем)
            return $"голыми руками не сорвать — нужен {Чем_берут()}";
        var (инструмент, приём) = чем;
        string громкость = приём.шум switch
        {
            0 => "беззвучно",
            1 => "тихо",
            2 => "слышно",
            _ => "громко — стук услышат, могут застать",
        };
        return $"{Жми}  {инструмент.как} {инструмент.чем} "
               + $"(≈{Текст.G(Текст.Округлить(Взлом.часы(д.дом, приём), 1))} ч, {громкость})";
    }

    /// <summary>«болторез или молоток» — чем этот замок берут вообще.</summary>
    private string Чем_берут()
    {
        var какими = кладовая is null
            ? new List<Инструмент>()
            : Взлом.чем_берут(кладовая, Каталог()).ToList();
        return какими.Count == 0 ? "инструмент" : string.Join(" или ", какими.Select(и => и.имя));
    }

    /// <summary>
    /// Кусок взлома: его часы и его стук — в дом, и дом живёт дальше.
    /// Застали — дело кончилось здесь (false), поимку разберёт ход дома.
    /// Последний кусок решает замок. Пока кусок кладётся, дом обязан спать
    /// на вопросе дня — шкала зовёт кусок только тогда.
    /// </summary>
    private bool Кусок_взлома(РучкиПетли ручки, Инструмент инструмент, Приём приём,
                              int номер, int кусков)
    {
        if (кладовая is not { } к || Дом() is not { } д || !МожноПоступать())
            return false;
        var (играл, как) = Сыграно();
        double качество = играл ? как : МиниИгры.Само(д.я, МиниИгра.ВЗЛОМ, ручки);
        var п = Взлом.кусок(д.дом, д.я, к, ручки, инструмент, приём, номер, кусков, качество);
        _ушло += п.часы;
        string сыграно = играл ? $" · {МиниИгры.Словами(качество)}" : "";
        string часы = $"ушло {Текст.G(Текст.Округлить(_ушло, 1))} ч";
        if (п.застал is string кто && д.дом.get(кто) is { } ловец)
        {
            Обновить(_сеть);
            Сказать($"на стук {Util.Vb(ловец.sex, "спустился")} {ловец.@short} — "
                    + $"тебя застали у замка · {часы}");
            Прошло();
            return false;
        }
        if (п.идёт)
        {
            // часы куска ушли — дом живёт их, пока шкала ждёт
            Прошло();
            return true;
        }
        Обновить(_сеть);                // сорван — замок слетит с петель здесь
        if (п.удалась)
            Сказать($"сорвал замок: {Чей()} · {часы}{сыграно}");
        else
            Сказать($"замок не поддался · {часы}{сыграно}"
                    + (п.травма is null ? "" : $" · {п.травма}"));
        // часы ушли — дом идёт дальше, и соседи в эти часы живут своё
        Прошло();
        return false;
    }

    /// <summary>Почему сейчас нельзя делать то, что стоит часов, —
    /// или ничего, если можно.</summary>
    private string? Нельзя()
    {
        if (!МожноМенять())
            return "дом ещё считает ход — подожди";
        if (!МожноПоступать())
            return Нельзя_сейчас() ?? "сейчас не до этого — сначала ответь дому";
        return null;
    }

    // ------------------------------------------------------------ ящики

    private void Опустошить(int i)
    {
        _коробки[i].пуста = true;
        Показать();
    }

    protected string КоробкаПодсказка(int i)
        => _коробки[i].пуста ? $"{_коробки[i].название} — пусто"
                             : $"{_коробки[i].название}\n{Жми}  обыскать";

    protected void КоробкаДействие(int i, Предмет цель)
    {
        if (_коробки[i].пуста)
            return;
        if (кладовая is null || Дом() is null)
        {
            Опустошить(i);
            return;
        }
        if (Нельзя() is string почему)
        {
            Сказать(почему);
            return;
        }
        if (!Положения.Можно_делать(Как_герой()))
        {
            Сказать(Как_герой().Текст());
            return;
        }
        if (Ручки() is { } ручки && Дом() is { } д
            && кладовая is { } к && !Обыск.успеет(д.дом, д.я, к, ручки))
        {
            Сказать($"до ночи не успеть: на обыск нужно "
                    + $"{Текст.G(Текст.Округлить(Обыск.часы(д.дом, к, ручки), 1))} ч");
            return;
        }
        if (_звук_коробки is not null)
        {
            _звук_коробки.Position = _коробки[i].где;
            // запись длинная — берём из неё кусок с случайного места
            Играть(_звук_коробки, "коробка", откуда: _кость.RandfRange(0f, 7.5f));
        }
        // Обыск короче куска — одним куском: часы уходят в конце шкалы
        double часов_обыска = Ручки() is { } р && кладовая is { } кл && Дом() is { } дм
            ? Обыск.часы(дм.дом, кл, р) : 0.0;
        double секунд_обыска = Ручки() is { } р2 ? ХодВремени.Секунд_дела(р2, часов_обыска) : 2.5;
        Начать(new Долгое("обыск", секунд_обыска,
                          готово: () =>
                          {
                              _звук_коробки?.Stop();
                              Обыскать(i);
                          },
                          прервано: () => _звук_коробки?.Stop(),
                          часов: часов_обыска,
                          движение: Анимации.Обыскивать()),
               цель);
    }

    /// <summary>
    /// Обыскать ящик: часы уходят сразу, найденное вынимается
    /// и ждёт, куда его положат (`Найдено` — окно находки). Что не влезло,
    /// остаётся в кладовой, и ящик тогда не пустеет: иначе остаток
    /// лежал бы в кладовой, а достать его было бы неоткуда.
    /// </summary>
    private void Обыскать(int i)
    {
        if (кладовая is not { } к || Дом() is not { } д || !МожноПоступать()
            || Ручки() is not { } ручки)
            return;
        if (к.пусто())
        {
            Обновить(_сеть);        // пустая кладовая гасит все ящики
            Сказать("пусто — всё уже вынесли");
            return;
        }
        // Доля — на все полные ящики, и на тот, что на дне ямы, тоже:
        // его не достать, но его доля там и лежит
        int полных = _коробки.Count(х => !х.пуста);
        var добыча = Обыск.коробка(д.дом, д.я, к, полных, ручки);
        string часы = $"ушло {Текст.G(Текст.Округлить(добыча.часы, 1))} ч";
        string внутри = _коробки[i].внутри;
        if (добыча.вещи.Ключи.Count == 0)
        {
            Обыск.оставить(д.дом, д.я, к, добыча);
            Опустошить(i);
            Обновить(_сеть);
            Сказать((добыча.надето.Count > 0
                        ? "надел: " + string.Join(", ", добыча.надето)
                        : "пусто") + $" · {часы}");
            Прошло();
            return;
        }
        double всего = добыча.вещи.Ключи.Sum(р => добыча.вещи[р]);
        Найдено(добыча, внутри,
            тара =>
            {
                var взято = Обыск.унести(д.дом, д.я, к, добыча, тара, ручки);
                double унёс = взято.Ключи.Sum(р => взято[р]);
                if (унёс >= всего - 1e-9)
                    Опустошить(i);
                Обновить(_сеть);
                string куда = тара is Тара т ? т.Куда() : "в карман вне времени";
                Сказать(взято.Ключи.Count == 0
                    ? $"не влезло — осталось {внутри} · {часы}"
                    : $"{куда}: {Вынесено(взято)}"
                      + (унёс < всего - 1e-9 ? " · остальное не влезло" : "")
                      + $" · {часы}");
                Прошло();
            },
            () =>
            {
                Обыск.оставить(д.дом, д.я, к, добыча);
                Обновить(_сеть);
                Сказать($"оставил {внутри} · {часы}");
                Прошло();
            });
    }

    private static string Вынесено(Словарь<string, double> взято)
        => string.Join(", ", взято.Ключи
               .OrderBy(р => р, StringComparer.Ordinal)
               .Select(р => $"{р} {Текст.G(Текст.Округлить(взято[р], 1))}"));

    // ------------------------------------------------------------ звук

    /// <summary>Источник звука в кладовой; своя громкость запоминается,
    /// чтобы тише-громче считалось от неё, а не от прошлого раза.</summary>
    protected AudioStreamPlayer3D Звук(string имя, Vector3 где, float громкость, float размер,
                                       float дальше_не = 25f, bool петля = false)
    {
        var п = Звуки.Точка(this, имя, где, громкость, размер, дальше_не, петля);
        п.SetMeta(ГРОМКОСТЬ, громкость);
        return п;
    }

    // ключ метаданных — латиницей: другие Godot не принимает
    private const string ГРОМКОСТЬ = "volume";

    /// <summary>Сыграть запись: с места <paramref name="откуда"/>, громче
    /// своей громкости на <paramref name="громче"/> и на <paramref name="высота"/>
    /// от записанной высоты — с разбросом в пару процентов.</summary>
    protected void Играть(AudioStreamPlayer3D? кем, string что, float откуда = 0f,
                          float громче = 0f, float высота = 1f)
    {
        if (кем is null || Звуки.Взять(что) is not { } поток)
            return;
        кем.Stream = поток;
        кем.PitchScale = высота * _кость.RandfRange(0.94f, 1.06f);
        кем.VolumeDb = (float)кем.GetMeta(ГРОМКОСТЬ, 0f).AsDouble() + громче;
        кем.Play(откуда);
    }
