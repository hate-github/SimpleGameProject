// Сервисы до метели в телефоне (просьба автора: микрозайм или кредит —
// «деньги получить максимально быстро»; доставка — пицца, бургер,
// картошка фри, газировка, «с начала метели перестают работать»).
// Правила — `Дом.Ядро.Сервисы`; здесь — вкладка «сервисы»: деньги,
// займы и меню; часы заявки; курьер, который звонит, когда герой дома;
// утро (банк решил) и метель (заказ отменён, связь пропала).

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    private Сервисы? Сервисы_ => Округа_?.сервисы;

    /// <summary>Работают, пока город живёт обычной жизнью — в прологе.</summary>
    private bool Сервисы_работают => _пролог is { идёт: true };

    private int _день_сервисов = int.MinValue;     // в какой день метели уже напоминали
    private bool _курьер_ждёт;                       // пакет у двери — уже сказано

    /// <summary>Что показать во вкладке «сервисы»: деньги, долги, заказ — шапкой;
    /// займы и меню — строками (без дела — подпись раздела).</summary>
    private (string шапка, IReadOnlyList<СтрокаОкна> строки) Сервисы_строки()
    {
        var строки = new List<СтрокаОкна>();
        if (Сервисы_ is not { } с || _партия is null)
            return ("сервисов нет", строки);
        var h = _партия.сеанс.дом;
        var я = _партия.сеанс.я;
        bool работают = Сервисы_работают;
        int день = _пролог?.день ?? h.day;
        var шапка = new List<string>
        {
            $"На карте {Текст.G(Текст.Округлить(я.счёт, 2))} тыс." + (h.банки ? "" : " (банки не работают)")
            + $" · наличными {Текст.G(Текст.Округлить(я.stock.Взять("деньги", 0.0), 2))} тыс.",
        };
        if (!работают)
            шапка.Add("Метель: банк не отвечает, курьеры не ездят.");
        foreach (var д in с.долги)
        {
            var займ = с.данные.займы.First(з => з.id == д.займ);
            int осталось = д.срок - день;
            шапка.Add($"Долг — {займ.имя}: {Текст.G(Текст.Округлить(д.Вернуть(Math.Max(день, д.срок)), 1))} тыс."
                      + (осталось > 0 ? $", платёж через {осталось} дн." : ", срок платежа прошёл"));
        }
        if (с.заказ is { } з)
            шапка.Add($"Курьер везёт: {string.Join(", ", з.еда.Select(Имя_еды))} — к {ХодВремени.Часы(з.к_часу)}"
                      + (_курьер_ждёт ? " · пакет ждёт у двери" : ""));

        строки.Add(new СтрокаОкна("ЗАЙМЫ", true, null));
        foreach (var займ in с.данные.займы)
        {
            string? нельзя = с.Нельзя(займ, я, работают);
            var взять = займ;
            строки.Add(new СтрокаОкна($"{займ.имя} — {займ.условия}" + (нельзя is null ? "" : $"  ·  {нельзя}"),
                                      нельзя is null, () => Взять_займ(взять)));
        }
        строки.Add(new СтрокаОкна($"ДОСТАВКА ЕДЫ — картой, курьер через {Часы_текстом(с.данные.доставка_часов)} ч", true, null));
        foreach (var блюдо in с.данные.меню)
        {
            string? нельзя = с.Нельзя(блюдо, h, я, работают);
            var б = блюдо;
            строки.Add(new СтрокаОкна($"{Имя_еды(блюдо.еда)} — {Текст.G(блюдо.цена)} тыс."
                                      + (нельзя is null ? "" : $"  ·  {нельзя}"),
                                      нельзя is null, () => Заказать(б)));
        }
        return (string.Join("\n", шапка), строки);
    }

    private string Имя_еды(string id) => _еда?.Есть(id) == true ? _еда[id].имя : id;

    /// <summary>Займ: заявка стоит часов дня героя.</summary>
    private void Взять_займ(Займ займ)
    {
        if (Сервисы_ is not { } с || _партия is null || !Дом_спит)
            return;
        var я = _партия.сеанс.я;
        var сделано = с.Взять(я, займ, _пролог?.день ?? _партия.сеанс.дом.day, Сервисы_работают);
        if (сделано.да)
            ХодВремени.Прожить(я, сделано.часов);
        GD.Print($"[сервисы] {сделано.весть}");
        Сказать(сделано.весть);
    }

    private void Заказать(Блюдо блюдо)
    {
        if (Сервисы_ is not { } с || _партия is null || !Дом_спит)
            return;
        var сделано = с.Заказать(_партия.сеанс.дом, _партия.сеанс.я, блюдо, Сервисы_работают,
                                 _пролог?.день ?? _партия.сеанс.дом.day);
        GD.Print($"[сервисы] {Имя_еды(блюдо.еда)}: {сделано.весть}");
        Сказать(сделано.да ? $"{Имя_еды(блюдо.еда)}: {сделано.весть}" : сделано.весть);
    }

    /// <summary>Каждый шаг времени в прологе: курьер приехал — если герой в доме
    /// (в квартире или в подъезде: курьер поднимается по лестнице и звонит),
    /// пакет на полку; нет — ждёт у двери квартиры.</summary>
    private void Доставка_кадр()
    {
        if (Сервисы_ is not { заказ: { } з } с || _партия is null || _пролог is null)
            return;
        var я = _партия.сеанс.я;
        if (я.час() < з.к_часу - 1e-9)
            return;
        var где = _герой.GlobalPosition;
        bool дома = _мир.ДомаЛи(где) || _мир.ВПодъезде(где);
        if (с.Привезти(я, я.час(), дома, Продукты.У(я)) is { } привезли)
        {
            _курьер_ждёт = false;
            GD.Print($"[сервисы] привезли: {string.Join(", ", привезли)}");
            Сказать($"звонок в дверь — курьер: {string.Join(", ", привезли.Select(Имя_еды))} · пакет на полке");
            Освежить_видно(_партия.сеанс.дом);
            _телефон.Сервисы_обновить();
        }
        else if (!_курьер_ждёт)
        {
            _курьер_ждёт = true;
            Сказать("СМС: «Курьер у подъезда — вас нет дома. Пакет оставил у двери квартиры»");
        }
    }

    /// <summary>Утро дня пролога — банк решил по вчерашним заявкам.</summary>
    private string Сервисы_утро(int день)
    {
        if (Сервисы_ is not { } с || _партия is null)
            return "";
        var вести = с.Утро(_партия.сеанс.я, день, _партия.сеанс.дом.банки);
        return вести.Count == 0 ? "" : " · " + string.Join(" · ", вести);
    }

    /// <summary>Пришла метель: заказ отменён, банк решил по вчерашней заявке.</summary>
    private string Сервисы_метель()
    {
        if (Сервисы_ is not { } с || _партия is null)
            return "";
        var вести = new List<string>();
        if (с.Метель(_партия.сеанс.я) is string отмена)
            вести.Add(отмена);
        _курьер_ждёт = false;
        вести.AddRange(с.Утро(_партия.сеанс.я, 0, _партия.сеанс.дом.банки));
        _день_сервисов = 0;
        return вести.Count == 0 ? "" : " · " + string.Join(" · ", вести);
    }

    /// <summary>В метель, раз в день — напоминание о платеже (дом спит на вопросе).</summary>
    private void Вести_сервисов()
    {
        if (Сервисы_ is not { } с || _партия is null || _пролог is not null)
            return;
        int день = _партия.сеанс.дом.day;
        if (день == _день_сервисов)
            return;
        _день_сервисов = день;
        foreach (var весть in с.Утро(_партия.сеанс.я, день, _партия.сеанс.дом.банки))
            Сказать(весть);
    }
}
