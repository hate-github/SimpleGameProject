// Итог дня на экране (ГДД 4.4): после сна — окно со сводкой за сутки.
// Что в ней и почему без имён — `Дом.Экран/ИтогДня.cs`; узел только решает,
// когда её показать: на первом вопросе нового дня, пока дом спит.
//
// Окно встаёт посередине, как прочие. Две оговорки: без сознания и по
// распорядку «день за днём» оно не встаёт — первое некому читать, второе
// разбудило бы героя каждое утро, — и сводка уходит только в ленту J.
// В ленту она пишется всегда: это и есть след дня, который потом перечитывают.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Годот;

public partial class ДомУзел
{
    private int _итог_утра = -1;          // какому дню сводка уже показана

    /// <summary>Утро нового дня метели: сводка за прошедшие сутки.</summary>
    private void Итог_утра(ВопросИгроку в)
    {
        if (_партия is null || _пролог is not null || в.вопрос != Вопрос.ЧТО_ДЕЛАТЬ
            || в.день == _итог_утра)
            return;
        _итог_утра = в.день;
        if (_партия.сеанс.Утро() is not { } итог)
            return;
        _журнал.Шапка($"итог дня {итог.день}: {string.Join("; ", итог.строки)}");
        if (_распорядок is { до: ДоКогда.ДНИ } || Без_сознания_молчит())
        {
            Сказать($"итог дня {итог.день} — в журнале ({Управление.В_скобках(Клавиши.ЖУРНАЛ)})");
            return;
        }
        _окно.Показать($"ИТОГ ДНЯ {итог.день}",
            () => string.Join("\n", итог.строки),
            () => new[] { new СтрокаОкна("дальше", true, () => _окно.Убрать()) });
        Мышь();
    }
}
