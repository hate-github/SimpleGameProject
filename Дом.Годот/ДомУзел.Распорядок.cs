// Распорядок в движке (просьба автора: «поставить распорядок дня — поел,
// попил, затопил печь — чтобы выжить; он прерывается, если случилось что-то,
// что героя касается»). Правило — `Дом.Ядро.Распорядок`; здесь — как оно
// исполняется: где герой живёт, чем здесь едят и топят, и как идёт время.
//
// Начинается у постели — нар в участке и в убежище, матраса дома: переждать
// два часа, до вечера, до утра или день за днём. Пока распорядок идёт, герой
// скован, а время летит шагами по полчаса: дом проживает их, как прожил бы
// стоящего героя. Дела — те же, что руками: в участке и в убежище — из запаса
// и у печки (`Убежище`), дома — мыслями дома («поесть», «попить», «топить»),
// которые дом и так предлагает, когда пора. Ночью — «спать», если распорядок
// до утра или на дни.
//
// Встаёт он сам (дом спросил не «что делать», с героем что-то случилось,
// стало плохо, кончилось чем жить, вышло время) или по Esc и клавише
// действия — и говорит, почему встал и что успел.

using Godot;
using Дом.Экран;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    private sealed class ПоРаспорядку
    {
        public ДоКогда до;
        public double часов;          // для ЧАСЫ
        public double прожито;
        public int с_дня;
        public int событий;
        public double здоровье;
        public readonly Dictionary<Привычка, int> сделано = new();
    }

    private ПоРаспорядку? _распорядок;
    private Label? _распорядок_строка;

    /// <summary>Шаг, которым распорядок пропускает время, — полчаса.</summary>
    private const double ШАГ_РАСПОРЯДКА = 0.5;

    /// <summary>Строки окна у постели: переждать и жить по распорядку.</summary>
    private IEnumerable<СтрокаОкна> Строки_распорядка()
    {
        yield return new СтрокаОкна("переждать два часа", true, () => Начать_распорядок(ДоКогда.ЧАСЫ, 2.0));
        yield return new СтрокаОкна("переждать до вечера", true, () => Начать_распорядок(ДоКогда.ВЕЧЕР));
        yield return new СтрокаОкна("прожить до утра — и переночевать", true, () => Начать_распорядок(ДоКогда.УТРО));
        yield return new СтрокаОкна("жить по распорядку — пока что-нибудь не случится", true,
                                    () => Начать_распорядок(ДоКогда.ДНИ));
    }

    /// <summary>Что распорядок умеет здесь — словами для окна.</summary>
    private string Распорядок_словами()
        => Убежище_здесь() is not null
            ? "По распорядку: пьёшь, когда хочется пить (кончилась вода — топишь снег), ешь, когда голоден, "
              + "топишь, когда холодно" + (Бункер_здесь() ? ", к вечеру крутишь вентиляцию" : ", кончилось топливо — ломаешь мебель") + ". "
              + "Встаёшь, если к тебе пришли или что-то случилось."
            : "По распорядку: ешь, пьёшь и топишь, когда дом предлагает (голод, жажда, холод). "
              + "Встаёшь, если к тебе пришли или что-то случилось.";

    /// <summary>Где живёт по распорядку: убежище (участок, бункер) — или null: дома.</summary>
    private IУбежище? Убежище_здесь()
    {
        if (Участок_ is { Доступно: true } у && _мир.ВУчастке(_герой.GlobalPosition))
            return у;
        if (Бункер_ is { открыт: true, внутри: true } б)
            return б;
        return null;
    }

    private bool Бункер_здесь() => Убежище_здесь() is Бункер;

    /// <summary>Начать: только пока дом ждёт ответа на вопрос дня и дела нет.</summary>
    private void Начать_распорядок(ДоКогда до, double часов = 0)
    {
        _окно.Убрать();
        if (_пролог is not null)
        {
            // до метели дом не идёт — пропускать нечего и некому прервать
            Сказать("до метели — живёшь сам; распорядок — с метелью");
            return;
        }
        if (_партия is null || !Можно_в_поход())
            return;
        if (Убежище_здесь() is null && !_мир.ДомаЛи(_герой.GlobalPosition))
        {
            Сказать("жить по распорядку можно дома, в участке или в убежище — у постели");
            return;
        }
        var я = _партия.сеанс.я;
        _распорядок = new ПоРаспорядку
        {
            до = до,
            часов = часов,
            с_дня = _партия.сеанс.дом.day,
            событий = _партия.сеанс.события.Count,
            здоровье = я.health,
        };
        Сказать(до switch
        {
            ДоКогда.ЧАСЫ => $"пережидаю {Часы_текстом(часов)} ч — Esc или {Управление.Имя(Клавиши.ДЕЙСТВИЕ)}: встать",
            ДоКогда.ВЕЧЕР => $"до вечера — по распорядку; Esc или {Управление.Имя(Клавиши.ДЕЙСТВИЕ)}: встать",
            ДоКогда.УТРО => $"до утра — по распорядку; Esc или {Управление.Имя(Клавиши.ДЕЙСТВИЕ)}: встать",
            _ => $"живу по распорядку, пока что-нибудь не случится; Esc или {Управление.Имя(Клавиши.ДЕЙСТВИЕ)}: встать",
        });
        Мышь();
    }

    /// <summary>Встать: сказать почему и что успел.</summary>
    private void Встать_из_распорядка(string почему)
    {
        if (_распорядок is not { } р)
            return;
        _распорядок = null;
        if (_распорядок_строка is not null)
            _распорядок_строка.Text = "";
        var сделал = р.сделано.Where(п => п.Value > 0 && п.Key != Привычка.ЖДАТЬ)
            .Select(п => п.Value > 1 ? $"{п.Key.Текст()} ×{п.Value}" : п.Key.Текст()).ToList();
        string весть = $"{почему} · прожито {Часы_текстом(р.прожито)} ч"
                       + (сделал.Count > 0 ? " · " + string.Join(", ", сделал) : "");
        GD.Print($"[распорядок] встал: {весть}");
        Сказать(весть);
        Мышь();
    }

    /// <summary>Каждый кадр: если дом ждёт героя — один шаг распорядка.</summary>
    private void Распорядок_кадр()
    {
        if (_распорядок is not { } р || _партия is null)
            return;
        // экран поверх (рассказ знатока, находка) — человеку читать, а не спать
        if (_окно.открыт || _находка.открыт || _переход.Visible || _меню.открыт)
        {
            Встать_из_распорядка("отвлекли");
            return;
        }
        if (_дело.занят || _партия.Ждёт() is not { } в)
            return;                         // дом считает — ждать
        // дом спит — теперь его можно читать
        Строка_распорядка(р);
        var h = _партия.сеанс.дом;
        var я = _партия.сеанс.я;
        if (!я.alive)
        {
            Встать_из_распорядка("всё");
            return;
        }
        if (в.вопрос == Вопрос.НОЧЬ)
        {
            int спать = Номер_варианта(в, "спать");
            if (р.до is ДоКогда.УТРО or ДоКогда.ДНИ && спать >= 0)
            {
                р.сделано[Привычка.ЖДАТЬ] = р.сделано.GetValueOrDefault(Привычка.ЖДАТЬ) + 1;
                Ответить(спать, играть: false);
            }
            else
                Встать_из_распорядка("стемнело — ночь");
            return;
        }
        if (Дом.Ядро.Распорядок.Своё(в.вопрос) && в.варианты.Count > 0)
        {
            // «за что взяться» — вопрос себе: ответить, как ответил бы сосед
            int лучший = Дом.Ядро.Распорядок.Лучший(в.варианты);
            GD.Print($"[распорядок] {Дом.Ядро.Вопросы.Все[в.вопрос]}: {Коротко(в.варианты[лучший].строка)}");
            Ответить(лучший, играть: false);
            return;
        }
        if (в.вопрос != Вопрос.ЧТО_ДЕЛАТЬ)
        {
            Встать_из_распорядка($"к тебе обращаются: {Дом.Ядро.Вопросы.Все[в.вопрос]}");
            return;
        }
        // докуда
        if (р.до == ДоКогда.УТРО && в.день > р.с_дня)
        {
            Встать_из_распорядка("утро");
            return;
        }
        if (р.до == ДоКогда.ЧАСЫ && р.прожито >= р.часов - 1e-9)
        {
            Встать_из_распорядка($"прошло {Часы_текстом(р.часов)} ч");
            return;
        }
        if (р.до == ДоКогда.ВЕЧЕР && я.time_left < 0.05)
        {
            Встать_из_распорядка("вечер");
            return;
        }
        var у = Убежище_здесь();
        bool Можно(Привычка п) => Можно_привычку(п, у, в, h, я);
        var новые = _партия.сеанс.события.Skip(р.событий).ToList();
        if (Дом.Ядро.Распорядок.Встать(я, новые, р.здоровье, Можно) is string почему)
        {
            Встать_из_распорядка(почему);
            return;
        }
        var быт = new Быт(я.satiety, я.hydration, h.room_temp(я),
                          у?.Печь_топится(h.day) ?? я.burning,
                          у is Бункер б && !б.Вентилирован(h.day),
                          ((я.час() % 24) + 24) % 24);
        var что = Дом.Ядро.Распорядок.Что(быт, Можно);
        if (что != Привычка.ЖДАТЬ && Сделать_привычку(что, у, в, h, я, р))
            return;
        // ждать: полчаса прожить, дом проходит их; день кончился — дом сам спросит про ночь
        double шаг = Math.Min(ШАГ_РАСПОРЯДКА, я.time_left);
        if (р.до == ДоКогда.ЧАСЫ)
            шаг = Math.Min(шаг, Math.Max(0.0, р.часов - р.прожито));
        р.прожито += Прожить(шаг);
        р.сделано[Привычка.ЖДАТЬ] = р.сделано.GetValueOrDefault(Привычка.ЖДАТЬ) + 1;
        Прошло(тихо: true);
    }

    /// <summary>Номер варианта с таким ключом действия — или −1.</summary>
    private static int Номер_варианта(ВопросИгроку в, string ключ)
    {
        for (int i = 0; i < в.варианты.Count; i++)
            if (string.Equals(в.варианты[i].ключ, ключ, StringComparison.Ordinal))
                return i;
        return -1;
    }

    private static string? Ключ_дома(Привычка п) => п switch
    {
        Привычка.ПОПИТЬ => "попить",
        Привычка.ПОЕСТЬ => "поесть",
        Привычка.ЗАТОПИТЬ => "топить",
        Привычка.СНЕГ => "топить_снег",
        _ => null,
    };

    /// <summary>Есть ли чем: в убежище — запас и топливо, дома — мысль дома.</summary>
    private bool Можно_привычку(Привычка п, IУбежище? у, ВопросИгроку в, House h, NPC я)
    {
        if (у is null)
            return Ключ_дома(п) is string ключ && Номер_варианта(в, ключ) >= 0;
        double топлива = у.В_запасе(Убежище.ТОПЛИВО);
        return п switch
        {
            Привычка.ПОПИТЬ => у.В_запасе(Убежище.ВОДА) >= 0.05,
            Привычка.ПОЕСТЬ => у.В_запасе(Убежище.ЕДА) >= 0.05,
            Привычка.ЗАТОПИТЬ => !у.Печь_топится(h.day) && топлива >= у.топлива_на_день - 1e-9,
            Привычка.СНЕГ => у.Печь_топится(h.day)
                ? топлива >= h.B["снег_топливо"] * h.B["снег_на_горящей_печке"] - 1e-9
                : топлива >= у.топлива_на_день - 1e-9,
            Привычка.ДРОВА => у is Участок уч && уч.мебели_осталось > 0,
            Привычка.ВЕНТИЛЯЦИЯ => у is Бункер б && !б.Вентилирован(h.day),
            _ => false,
        };
    }

    /// <summary>Сделать привычку. false — не вышло (ждать).</summary>
    private bool Сделать_привычку(Привычка п, IУбежище? у, ВопросИгроку в, House h, NPC я, ПоРаспорядку р)
    {
        if (у is null)
        {
            // дома — мыслью дома: дом сам исполнит и проживёт её часы
            if (Ключ_дома(п) is not string ключ)
                return false;
            int номер = Номер_варианта(в, ключ);
            if (номер < 0)
                return false;
            р.прожито += Действия.hours(ключ, я, h.B);
            р.сделано[п] = р.сделано.GetValueOrDefault(п) + 1;
            Ответить(номер, играть: false);
            return true;
        }
        Сделано с = п switch
        {
            Привычка.ПОПИТЬ => Убежище.Попить(h, я, у),
            Привычка.ПОЕСТЬ => Убежище.Поесть(h, я, у),
            Привычка.ЗАТОПИТЬ => Убежище.Затопить(h, я, у),
            Привычка.СНЕГ => Убежище.Снег(h, я, у),
            Привычка.ДРОВА when у is Участок уч => уч.Разобрать_мебель(h),
            Привычка.ВЕНТИЛЯЦИЯ when у is Бункер б => Вентилировать_(h, я, б),
            _ => new Сделано(false, 0, ""),
        };
        if (!с.да)
            return false;
        // те же звуки, что у дела дома: жарка у печки, топор, спичка
        if ((Ключ_дома(п) ?? (п == Привычка.ДРОВА ? "дрова" : null)) is string дело)
            Своё_дело(дело, у.Печь_топится(h.day));
        р.прожито += Прожить(с.часов);
        р.сделано[п] = р.сделано.GetValueOrDefault(п) + 1;
        Прошло(тихо: true);
        return true;
    }

    private static Сделано Вентилировать_(House h, NPC я, Бункер б)
    {
        б.Вентилировать(h.day);
        return new Сделано(true, б.данные.вентиляция_часов, "покрутил вентиляцию");
    }

    /// <summary>Строка над экраном: что за распорядок, час, тело, тепло.</summary>
    private void Строка_распорядка(ПоРаспорядку р)
    {
        if (_распорядок_строка is null)
        {
            _распорядок_строка = new Label
            {
                HorizontalAlignment = HorizontalAlignment.Center,
                MouseFilter = Control.MouseFilterEnum.Ignore,
            };
            _распорядок_строка.AddThemeColorOverride("font_color", new Color("#e8d8a8"));
            _распорядок_строка.AddThemeColorOverride("font_outline_color", new Color(0, 0, 0, 0.85f));
            _распорядок_строка.AddThemeConstantOverride("outline_size", 4);
            _распорядок_строка.AddThemeFontSizeOverride("font_size", 18);
            _панели.AddChild(_распорядок_строка);
        }
        var размер = _панели.Size;
        _распорядок_строка.Position = new Vector2(0, размер.Y * 0.18f);
        _распорядок_строка.Size = new Vector2(размер.X, 30);
        if (_партия is null)
            return;
        var я = _партия.сеанс.я;
        string до = р.до switch
        {
            ДоКогда.ЧАСЫ => $"пережидаю {Часы_текстом(р.часов)} ч",
            ДоКогда.ВЕЧЕР => "до вечера",
            ДоКогда.УТРО => "до утра",
            _ => "день за днём",
        };
        _распорядок_строка.Text = $"РАСПОРЯДОК · {до} · день {_партия.сеанс.дом.day} · {ХодВремени.Часы(я.час())}"
                                  + $" · сытость {Текст.G(Math.Round(я.satiety))} · вода {Текст.G(Math.Round(я.hydration))}"
                                  + $" · {Текст.G(Math.Round(_партия.сеанс.дом.room_temp(я)))}°"
                                  + $"   (Esc / {Управление.Имя(Клавиши.ДЕЙСТВИЕ)} — встать)";
    }
}
