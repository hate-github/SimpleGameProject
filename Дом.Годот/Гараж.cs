// Гараж во дворе: модель автора, ворота на замке, коробки, верстак, лампа.
//
// Гараж в доме уже был — кладовая «гараж13» в `npcs.json`, со своими
// запасами и замком, — но стоял он только в данных. Здесь он стоит
// в мире, и **это та же самая кладовая**: коробки пустеют, когда пустеет
// она, замок сорван, когда она вскрыта. Своего учёта у гаража нет.
//
// Взломать замок и обыскать коробку — поступки героя, а не ответы на вопрос
// дома, как и карман: делаются только пока дом спит на вопросе, функциями
// самого дома, и не сразу — через шкалу долгого дела (`ДелоUI`).
//   · Замок — `Взлом.попытка`: полтора часа дня, и замок может не поддаться.
//   · Коробка — `Улица.взять_коробку`: доля того, что осталось, на все
//     полные коробки.
//   · Сорванный замок можно повесить обратно — для вида: запертым он
//     от этого не станет, и дом по-прежнему знает, что кладовая вскрыта.
//     Свой замок снимается и вешается ключом, без всякого дела.
//
// Открывается одна левая створка, и не настежь, а на треть: проход есть,
// а человека створка не сметает. Пока она движется, у неё нет формы;
// твёрдой она становится, когда остановилась и в ней никто не стоит.
//
// Модель — сцена, а не меш: деталей восемнадцать, створка вращается
// вокруг своей петли, и держать всё вместе удобнее сценой. Скина в ней
// нет, и потому то, что случилось с лопатой (сцена тащила скелет
// и разлеталась веером), здесь не грозит.
//
// Масштаб приходит из гнезда: модель сделана без оглядки на метры
// (ворота 5.6 единицы в высоту).
//
// Какая сторона детали видна, решают нормали. У стен и ворот снаружи
// и изнутри разные текстуры — ржавчина снаружи, серое и зелёное внутри, —
// их рисуем одной стороной, как в модели. Остальное рисуется с обеих
// сторон, а формы у всех двусторонние. Так гараж переживает вывернутые
// грани: в первой модели внутрь смотрела часть лестницы, петель и полки,
// и они выглядели полыми, во второй — всё, и через одностороннюю форму
// пола герой провалился бы.
//
// В яму под полом не спускаются: над открытой её частью стоит невидимый
// барьер. Настил, лестница и коробка на дне — как в модели.

