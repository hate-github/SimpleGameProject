    /// <summary>Источник звука в гараже; своя громкость запоминается,
    /// чтобы тише-громче считалось от неё, а не от прошлого раза.</summary>
    private AudioStreamPlayer3D Звук(string имя, Vector3 где, float громкость, float размер,
                                     float дальше_не = 25f, bool петля = false)
    {
        var п = Звуки.Точка(this, имя, где, громкость, размер, дальше_не, петля);
        п.SetMeta(ГРОМКОСТЬ, громкость);
        return п;
    }

    // ключ метаданных — латиницей: другие Godot не принимает
    private const string ГРОМКОСТЬ = "volume";

    private void Играть(AudioStreamPlayer3D? кем, string что, float откуда = 0f,
                        float громче = 0f)
    {
        if (кем is null || Звуки.Взять(что) is not { } поток)
            return;
        кем.Stream = поток;
        кем.PitchScale = _кость.RandfRange(0.94f, 1.06f);
        кем.VolumeDb = (float)кем.GetMeta(ГРОМКОСТЬ, 0f).AsDouble() + громче;
        кем.Play(откуда);
    }
