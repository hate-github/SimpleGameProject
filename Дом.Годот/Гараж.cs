    public const string МОДЕЛЬ = "res://модели/гараж/garage.fbx";

    /// <summary>Слой тел, которые мешают ходить, но не мешают прицелу:
    /// верстак, полка и барьер над ямой. Иначе коробки за ними было бы
    /// не выбрать — луч упирался бы в них самих.</summary>
    public const uint СЛОЙ_МЕБЕЛИ = 4;

    /// <summary>Детали, у которых сторона что-то значит: снаружи одна
    /// текстура, изнутри другая. Их рисуем одной стороной, как в модели.</summary>
    private static readonly HashSet<string> ОДНОСТОРОННИЕ = new(StringComparer.Ordinal)
    {
        "garage walls", "garage door left", "garage door right",
    };

    private const float РАСПАХ = 35f;          // на сколько градусов открывается створка
    private const float СКОРОСТЬ = 1.4f;       // долей распаха в секунду
    private const double СЕКУНД_ВЗЛОМА = 4.5;  // полтора часа дня — за четыре с половиной секунды
    private const double СЕКУНД_ОБЫСКА = 2.5;
    private const double КАЖДЫЙ_УДАР = 0.75;   // как часто бьют по замку

