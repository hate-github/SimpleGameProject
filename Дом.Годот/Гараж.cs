    public Vector3 ПередВоротами(float y)
        => ToGlobal(new Vector3(0, 0, _пол.End.Z + 9.0f)) with { Y = y };

    /// <summary>
    /// Собрать гараж из модели. Возвращает false, если модели нет:
    /// тогда во дворе просто пусто, а мир строится дальше.
    /// </summary>
    public bool Собрать(float масштаб)
    {
        var сцена = ResourceLoader.Exists(МОДЕЛЬ) ? GD.Load<PackedScene>(МОДЕЛЬ) : null;
        if (сцена is null)
        {
            GD.PrintErr($"нет модели гаража {МОДЕЛЬ}");
            return false;
        }
        _кость.Randomize();
        _модель = сцена.Instantiate<Node3D>();
        _модель.Scale = Vector3.One * масштаб;
        AddChild(_модель);

        var части = new Dictionary<string, MeshInstance3D>(StringComparer.Ordinal);
        foreach (var у in _модель.GetChildren())
            if (у is MeshInstance3D м)
                части[у.Name.ToString().ToLowerInvariant()] = м;

        MeshInstance3D? Часть(string имя) => части.GetValueOrDefault(имя);
        Aabb Габарит(MeshInstance3D м) => _модель.Transform * (м.Transform * м.GetAabb());

        // ---- стороны: всё, кроме стен и ворот, — с обеих ----
        foreach (var (имя, м) in части)
            if (!ОДНОСТОРОННИЕ.Contains(имя))
                Двусторонне(м);

        // ---- стены, пол, настил: форма, в которую упираются ----
        if (Часть("garage walls") is { } стены_м)
            Форма(стены_м, 1, выпуклая: false, Поверхность.БЕТОН);
        if (Часть("floor") is { } пол_м)
            Форма(пол_м, 1, выпуклая: false, Поверхность.БЕТОН);
        if (Часть("plywood") is { } настил_м)
            Форма(настил_м, 1, выпуклая: false, Поверхность.ДЕРЕВО);
        foreach (var имя in new[] { "workbench", "shelf" })
            if (Часть(имя) is { } м)
                Форма(м, СЛОЙ_МЕБЕЛИ, выпуклая: false, Поверхность.ДЕРЕВО);
        // правая створка не открывается вовсе: форма у неё постоянная
        if (Часть("garage door right") is { } правая)
            Форма(правая, 1, выпуклая: true, Поверхность.БЕТОН);

        var пол = Часть("floor");
        if (пол is not null)
            _пол = Габарит(пол);
        if (Часть("garage walls") is { } стены)
            _крыша = Габарит(стены).End.Y;

        // ---- яма: барьер над той её частью, что не под настилом ----
        if (пол is not null && Проём(пол) is Aabb проём)
        {
            var настил = Часть("plywood");
            Барьер(проём, настил is null ? null : настил.Transform * настил.GetAabb(), масштаб);
        }

        // ---- левая створка, её ручка и замок ----
        // Замок висит между створками, ручка — у внутреннего края левой
        // створки, чуть выше. Прицелы им разведены по высоте: граница —
        // посередине между верхом замка и низом ручки.
        float м_ед = 1f / масштаб;                 // метр в единицах модели
        _створка_меш = Часть("garage door left");
        _замок = Часть("lock(locked)");
        Aabb? ручка = _створка_меш is null ? null : Ручка(_створка_меш);
        Aabb? замок_м = _замок is null ? null : _замок.Transform * _замок.GetAabb();
        float межа = (замок_м, ручка) switch
        {
            (Aabb з, Aabb р) => (з.End.Y + р.Position.Y) / 2,
            (Aabb з, null) => з.End.Y,
            (null, Aabb р) => р.Position.Y,
            _ => 0,
        };

        if (_створка_меш is not null && ручка is Aabb р_)
        {
            _створка0 = _створка_меш.Transform;
            Форма(_створка_меш, 1, выпуклая: true, Поверхность.БЕТОН);
            _створка_тело = _створка_меш.GetChildren().OfType<StaticBody3D>().FirstOrDefault();

            // прицел ручки — в осях самой створки: он поворачивается вместе
            // с ней и находится там, где ручка, — открыта створка или нет
            var мишень = new Aabb(
                new Vector3(р_.Position.X - 0.03f * м_ед, межа, р_.Position.Z - 0.30f * м_ед),
                new Vector3(р_.Size.X + 0.08f * м_ед, р_.End.Y + 0.06f * м_ед - межа,
                            р_.Size.Z + 0.45f * м_ед));
            var цель = Предмет.Вокруг(_створка_меш, _створка0.AffineInverse() * мишень, 0,
                                      "ручка_ворот");
            цель.Подсказка = РучкаПодсказка;
            цель.Действие = РучкаДействие;
            _звук_створки = Звук("ворота_1", р_.GetCenter() * масштаб, -2f, 3f);
        }

        if (_замок is not null && замок_м is Aabb з_)
        {
            // Замок крошечный, поэтому прицел ему раздут — и по толщине тоже,
            // в обе стороны от ворот: иначе изнутри луч упирается в створку
            // раньше, чем в него, и из закрытого гаража не выйти
            var мишень = new Aabb(
                new Vector3(з_.Position.X - 0.05f * м_ед, з_.Position.Y - 0.05f * м_ед,
                            з_.Position.Z - 0.30f * м_ед),
                new Vector3(з_.Size.X + 0.10f * м_ед,
                            межа - (з_.Position.Y - 0.05f * м_ед),
                            з_.Size.Z + 0.45f * м_ед));
            _замок_цель = Предмет.Вокруг(this, _модель.Transform * мишень, 0, "замок_гаража");
            _замок_цель.Подсказка = ЗамокПодсказка;
            var замок_цель = _замок_цель;
            _замок_цель.Действие = () => ЗамокДействие(замок_цель);
            _звук_замка = Звук("удар_по_металлу", _модель.Transform * з_.GetCenter(), -4f, 2.5f);
        }

        // ---- коробки: у каждой пары полная и пустая ----
        foreach (var (имя, м) in части)
        {
            bool полная = имя.StartsWith("boxes(not_looted)", StringComparison.Ordinal);
            bool пустая = имя.StartsWith("boxes(looted)", StringComparison.Ordinal);
            if (!полная && !пустая)
                continue;
            string хвост = имя[(имя.IndexOf(')') + 1)..];
            var к = _коробки.FirstOrDefault(х => х.имя == хвост);
            if (к is null)
                _коробки.Add(к = new Коробка { имя = хвост });
            if (полная) к.полная = м;
            else к.пустая = м;
        }
        _коробки.Sort((а, б) => string.CompareOrdinal(а.имя, б.имя));
        for (int i = 0; i < _коробки.Count; i++)
        {
            var к = _коробки[i];
            var габарит = к.полная is not null ? Габарит(к.полная) : Габарит(к.пустая!);
            if (к.полная is not null && к.пустая is not null)
                габарит = габарит.Merge(Габарит(к.пустая));
            к.где = габарит.GetCenter();
            // коробка на дне ямы: видна сверху, но рукой до неё не достать
            к.достать = габарит.End.Y > -0.05f;
            if (!к.достать)
                continue;
            int номер = i;
            var цель = Предмет.Вокруг(this, габарит, 0.08f, $"коробка_гаража{i}");
            цель.Подсказка = () => КоробкаПодсказка(номер);
            цель.Действие = () => КоробкаДействие(номер, цель);
        }
        _звук_коробки = Звук("коробка", _пол.GetCenter(), -3f, 2f);

        // ---- верстак: прицел только на верхней трети — ниже коробки ----
        if (Часть("workbench") is { } верстак)
        {
            var г = Габарит(верстак);
            var верх = new Aabb(г.Position + new Vector3(0, г.Size.Y * 0.66f, 0),
                                new Vector3(г.Size.X, г.Size.Y * 0.34f, г.Size.Z));
            var цель = Предмет.Вокруг(this, верх, 0.05f, "верстак");
            цель.Подсказка = () => "верстак\n[E]  открыть";
            цель.Действие = () => ОткрытьВерстак();
        }

        // ---- лампа и выключатель ----
        if (Часть("lamp") is { } лампа)
        {
            var г = Габарит(лампа);
            var где = г.GetCenter() - new Vector3(0, г.Size.Y * 0.6f, 0);
            _лампа = new OmniLight3D
            {
                Position = где,
                LightColor = new Color("#ffe2b0"),
                // на весь гараж и не дальше: при 0.41 — шесть метров
                OmniRange = 14.5f * масштаб,
                // без тени лампа светит сквозь стены — на снег вокруг
                ShadowEnabled = true,
                Name = "лампа_гаража",
            };
            AddChild(_лампа);
            _гул_лампы = Звук("лампа", где, -16f, 1.2f, дальше_не: 8f, петля: true);
        }
        if (Часть("lamp switch") is { } щиток)
        {
            var г = Габарит(щиток);
            var цель = Предмет.Вокруг(this, г, 0.3f, "выключатель",
                                      new Vector3(-0.1f, 0, 0));
            цель.Подсказка = () => (_лампа_вкл ? "свет включён" : "свет выключен")
                                   + (_сеть < 0.2 ? " — но тока нет" : "")
                                   + "\n[E]  щёлкнуть";
            цель.Действие = Щёлкнуть;
            _звук_щелчка = Звук("выключатель", г.GetCenter(), -6f, 1.5f);
        }

        Показать();
        return true;
    }

    /// <summary>
    /// Проём ямы в полу, в осях модели. Верх пола — кольцо: снаружи углы
    /// блока, внутри углы проёма; внутренние и есть проём. Ямы нет —
    /// нет и проёма.
    /// </summary>
    private static Aabb? Проём(MeshInstance3D пол)
    {
        var блок = пол.Transform * пол.GetAabb();
        Aabb? проём = null;
        var сетка = пол.Mesh;
        for (int s = 0; s < сетка.GetSurfaceCount(); s++)
            foreach (var в in сетка.SurfaceGetArrays(s)[(int)Mesh.ArrayType.Vertex].AsVector3Array())
            {
                var т = пол.Transform * в;
                bool на_верху = Mathf.Abs(т.Y - блок.End.Y) < 0.01f;
                bool внутри = т.X > блок.Position.X + 0.01f && т.X < блок.End.X - 0.01f
                              && т.Z > блок.Position.Z + 0.01f && т.Z < блок.End.Z - 0.01f;
                if (на_верху && внутри)
                    проём = проём is Aabb п ? п.Expand(т) : new Aabb(т, Vector3.Zero);
            }
        return проём;
    }

    /// <summary>
    /// Ручка створки, в осях модели: то, что торчит из её наружной
    /// половины. Ворота смотрят в +Z модели, ручка — наружу. Выступов нет —
    /// середина створки.
    /// </summary>
    private static Aabb Ручка(MeshInstance3D створка)
    {
        var т = створка.Transform;
        var габ = т * створка.GetAabb();
        float порог = габ.Position.Z + габ.Size.Z * 0.5f;
        Aabb? ручка = null;
        var сетка = створка.Mesh;
        for (int s = 0; s < сетка.GetSurfaceCount(); s++)
            foreach (var в in сетка.SurfaceGetArrays(s)[(int)Mesh.ArrayType.Vertex].AsVector3Array())
            {
                var м = т * в;
                if (м.Z > порог)
                    ручка = ручка is Aabb р ? р.Expand(м) : new Aabb(м, Vector3.Zero);
            }
        return ручка ?? new Aabb(габ.GetCenter(), Vector3.Zero);
    }

    /// <summary>
    /// Невидимый барьер над открытой частью ямы. Настил в модели накрывает
    /// яму не целиком — у лестницы оставлен спуск, — и чтобы туда не падали,
    /// над спуском стоит стенка выше пояса. Слой мебели: в неё упираются,
    /// а прицел сквозь неё видит. Щель уже полуметра барьера не получает:
    /// в неё не провалиться, а проход она перегородила бы.
    /// </summary>
    private void Барьер(Aabb проём, Aabb? настил, float масштаб)
    {
        const float ВЫСОТА = 1.2f;       // в метрах
        var открыто = new List<Rect2>
        {
            new(проём.Position.X, проём.Position.Z, проём.Size.X, проём.Size.Z),
        };
        if (настил is Aabb н)
        {
            var лист = new Rect2(н.Position.X, н.Position.Z, н.Size.X, н.Size.Z);
            открыто = открыто.SelectMany(к => Мир.Вычесть(к, лист)).ToList();
        }
        float высота = ВЫСОТА / масштаб;
        int номер = 0;
        foreach (var к in открыто)
        {
            if (Mathf.Min(к.Size.X, к.Size.Y) * масштаб < 0.5f)
                continue;
            var тело = new StaticBody3D
            {
                Name = $"барьер_ямы{номер++}",
                CollisionLayer = СЛОЙ_МЕБЕЛИ,
                CollisionMask = 0,
            };
            тело.AddChild(new CollisionShape3D
            {
                Shape = new BoxShape3D { Size = new Vector3(к.Size.X, высота, к.Size.Y) },
                Position = new Vector3(к.GetCenter().X, проём.Position.Y + высота / 2,
                                       к.GetCenter().Y),
            });
            _модель!.AddChild(тело);
        }
    }

    /// <summary>Рисовать деталь с обеих сторон — своими копиями материалов:
    /// материалы у деталей общие (петли и стены — один), а стены должны
    /// остаться односторонними.</summary>
    private static void Двусторонне(MeshInstance3D м)
    {
        for (int s = 0; s < м.Mesh.GetSurfaceCount(); s++)
            if (м.GetActiveMaterial(s) is BaseMaterial3D мат)
            {
                var копия = (BaseMaterial3D)мат.Duplicate();
                копия.CullMode = BaseMaterial3D.CullModeEnum.Disabled;
                м.SetSurfaceOverrideMaterial(s, копия);
            }
    }

    /// <summary>Поставить форму по мешу и сказать, по чему по ней ходят.
    /// Выпуклая — для створок: они двигаются, а вогнутая форма у движущегося
    /// тела ведёт себя плохо. Вогнутая — с обеих сторон: у вывернутой детали
    /// лицо смотрит внутрь, и односторонняя форма пропускала бы сквозь пол.</summary>
    private static void Форма(MeshInstance3D м, uint слой, bool выпуклая, string поверхность)
    {
        if (выпуклая)
            м.CreateConvexCollision();
        else
            м.CreateTrimeshCollision();
        foreach (var у in м.GetChildren())
            if (у is StaticBody3D тело)
            {
                тело.CollisionLayer = слой;
                тело.CollisionMask = 0;
                Поверхность.Пометить(тело, поверхность);
                foreach (var ф in тело.GetChildren())
                    if (ф is CollisionShape3D { Shape: ConcavePolygonShape3D вогнутая })
                        вогнутая.BackfaceCollision = true;
            }
    }

    /// <summary>
    /// Сверить гараж с домом. Зовётся на каждом вопросе, пока дом спит:
    /// пока герой ходил, хозяин мог сам спуститься за своим, а сосед —
    /// сорвать замок, и гараж должен это показать.
    /// </summary>
    public void Обновить(double сеть)
    {
        _сеть = сеть;
        if (кладовая is { } к)
        {
            _вскрыта = к.вскрыта;
            _доступ = Дом() is { } д && д.дом.есть_ключ(д.я, к);
            if (Дом() is { } дом)
                _часы_взлома = Взлом.часы(дом.дом);
            // сорвали только что — замка на петлях больше нет, кто бы ни сорвал
            if (_вскрыта && !_вскрыта_было)
                _замок_висит = false;
            _вскрыта_было = _вскрыта;
            if (к.пусто())
                foreach (var коробка in _коробки)
                    коробка.пуста = true;
        }
        Показать();
    }

    /// <summary>Показать снимок: какие коробки пусты, висит ли замок,
    /// горит ли лампа. В дом не ходит.</summary>
    private void Показать()
    {
        if (_замок is not null)
            _замок.Visible = _замок_висит;
        foreach (var к in _коробки)
        {
            if (к.полная is not null) к.полная.Visible = !к.пуста;
            if (к.пустая is not null) к.пустая.Visible = к.пуста;
        }
        bool горит = _лампа_вкл && _сеть >= 0.2;
        if (_лампа is not null)
            _лампа.LightEnergy = _лампа_вкл
                ? (float)(1.4 * System.Math.Clamp(_сеть, 0, 1))
                : 0f;
        if (_гул_лампы is not null && горит != _гул_лампы.Playing)
        {
            if (горит) _гул_лампы.Play();
            else _гул_лампы.Stop();
        }
    }

    public override void _Process(double delta)
    {
        if (!Mathf.IsEqualApprox(_створка, _цель))
        {
            // пока створка движется, формы у неё нет: иначе она сметает
            // стоящего рядом человека
            if (_створка_тело is not null)
                _створка_тело.CollisionLayer = 0;
            _створка = Mathf.MoveToward(_створка, _цель, (float)delta * СКОРОСТЬ);
            // Петля левой створки — на её внешнем краю (+X модели), створка
            // уходит от петли к середине. Наружу (+Z) она выходит поворотом
            // на положительный угол.
            float угол = Mathf.DegToRad(РАСПАХ) * _створка;
            if (_створка_меш is not null)
                _створка_меш.Transform = new Transform3D(
                    new Basis(Vector3.Up, угол) * _створка0.Basis, _створка0.Origin);
            if (Mathf.IsEqualApprox(_створка, _цель))
            {
                _ждёт_твёрдости = true;
                Показать();
            }
        }
        if (_ждёт_твёрдости && _створка_тело is not null && !ГеройВСтворке())
        {
            _створка_тело.CollisionLayer = 1;
            _ждёт_твёрдости = false;
        }
        // замок висит на закрытых воротах; открыты — прицел на нём не держится
        if (_замок_цель is not null)
            _замок_цель.Активен = _цель == 0 && _створка == 0;
    }

    /// <summary>Стоит ли человек там, где створка: по её рамке в осях
    /// гаража, с запасом на толщину человека.</summary>
    private bool ГеройВСтворке()
    {
        if (_створка_меш is null || _модель is null)
            return false;
        var г = _модель.Transform * (_створка_меш.Transform * _створка_меш.GetAabb());
        var где = ToLocal(ГдеГерой());
        const float ЗАПАС = 0.35f;
        return где.X > г.Position.X - ЗАПАС && где.X < г.End.X + ЗАПАС
               && где.Z > г.Position.Z - ЗАПАС && где.Z < г.End.Z + ЗАПАС
               && где.Y < г.End.Y && где.Y + 1.75f > г.Position.Y;
    }

    // ------------------------------------------------------------ створка

    private string Чей() => кладовая is null ? "гараж" : $"гараж кв.{кладовая.apt}";

    private string РучкаПодсказка()
    {
        if (_замок_висит)
            return $"{Чей()} — на воротах замок";
        return _цель > 0 ? "дверь\n[E]  прикрыть" : "дверь\n[E]  открыть";
    }

    private void РучкаДействие()
    {
        if (_замок_висит)
        {
            Сказать("сначала замок");
            return;
        }
        _цель = _цель > 0 ? 0 : 1;
        Играть(_звук_створки, $"ворота_{_кость.RandiRange(1, 3)}");
    }

    // ------------------------------------------------------------ замок

    private string ЗамокПодсказка()
    {
        if (кладовая is null)
            return _замок_висит ? $"{Чей()}\n[E]  снять замок" : $"{Чей()}\n[E]  повесить замок";
        if (_замок_висит)
        {
            if (_вскрыта)
                return $"{Чей()} — замок сорван, висит для вида\n[E]  снять";
            if (_доступ)
                return $"{Чей()} — ключ у тебя\n[E]  отпереть";
            return $"{Чей()} — на замке\n[E]  взломать (≈{Текст.G(Текст.Округлить(_часы_взлома, 1))} ч)";
        }
        if (_вскрыта)
            return $"{Чей()} — замок сорван\n[E]  повесить для вида";
        return $"{Чей()} — не заперт\n[E]  запереть";
    }

    private void ЗамокДействие(Предмет замок)
    {
        if (!_замок_висит)
        {
            _замок_висит = true;
            Показать();
            Сказать(_вскрыта ? "повесил сорванный замок — для вида, он не заперт"
                             : "запер");
            Играть(_звук_замка, "удар_по_металлу", громче: -10f);
            return;
        }
        if (кладовая is not { } к || Дом() is not { } д || _вскрыта || _доступ)
        {
            // свой ключ или сорванный замок: снимается без всякого дела
            _замок_висит = false;
            Показать();
            Сказать(_вскрыта ? "снял сорванный замок" : "отпер своим ключом");
            Играть(_звук_замка, "удар_по_металлу", громче: -10f);
            return;
        }
        // чужой и целый — взлом: дело, и оно может не выйти
        if (!МожноМенять())
        {
            Сказать("дом ещё считает ход — подожди");
            return;
        }
        var ручки = Ручки();
        if (ручки is null)
            return;
        if (!Взлом.успеет(д.дом, д.я))
        {
            Сказать($"до ночи не успеть: на замок нужно {Текст.G(Взлом.часы(д.дом))} ч");
            return;
        }
        double удар = 0;
        Начать(new Долгое("взлом", СЕКУНД_ВЗЛОМА,
                          готово: () => Взломать(ручки),
                          прервано: () => Сказать("бросил замок"),
                          идёт: прошло =>
                          {
                              if (прошло < удар)
                                  return;
                              удар = прошло + КАЖДЫЙ_УДАР;
                              Играть(_звук_замка, "удар_по_металлу");
                          }),
               замок);
    }

    private void Взломать(РучкиПетли ручки)
    {
        if (кладовая is not { } к || Дом() is not { } д || !МожноМенять())
            return;
        var п = Взлом.попытка(д.дом, д.я, к, ручки);
        Обновить(_сеть);                // сорван — замок слетит с петель здесь
        string часы = $"ушло {Текст.G(Текст.Округлить(п.часы, 1))} ч";
        if (п.удалась)
            Сказать($"сорвал замок: {Чей()} — {часы}");
        else
            Сказать($"замок не поддался — {часы}"
                    + (п.травма is null ? "" : $", {п.травма}"));
    }

    // ------------------------------------------------------------ коробки

    private void Опустошить(int i)
    {
        _коробки[i].пуста = true;
        Показать();
    }

    private string КоробкаПодсказка(int i)
        => _коробки[i].пуста ? "коробки — пусто" : "коробки\n[E]  обыскать";

    private void КоробкаДействие(int i, Предмет цель)
    {
        if (_коробки[i].пуста)
            return;
        if (кладовая is null || Дом() is null)
        {
            Опустошить(i);
            return;
        }
        if (!МожноМенять())
        {
            Сказать("дом ещё считает ход — подожди");
            return;
        }
        if (_звук_коробки is not null)
        {
            _звук_коробки.Position = _коробки[i].где;
            // запись длинная — берём из неё кусок с случайного места
            Играть(_звук_коробки, "коробка", откуда: _кость.RandfRange(0f, 7.5f));
        }
        Начать(new Долгое("обыск", СЕКУНД_ОБЫСКА,
                          готово: () =>
                          {
                              _звук_коробки?.Stop();
                              Обыскать(i);
                          },
                          прервано: () => _звук_коробки?.Stop()),
               цель);
    }

    private void Обыскать(int i)
    {
        if (кладовая is not { } к || Дом() is not { } д || !МожноМенять())
            return;
        if (к.пусто())
        {
            Обновить(_сеть);        // пустая кладовая гасит все коробки
            Сказать("пусто — всё уже вынесли");
            return;
        }
        // Доля — на все полные коробки, и на ту, что на дне ямы, тоже:
        // её не достать, но её доля там и лежит
        int полных = _коробки.Count(х => !х.пуста);
        var взято = Улица.взять_коробку(д.дом, д.я, к, полных);
        Опустошить(i);
        Обновить(_сеть);
        Сказать((взято.Count == 0 ? "пусто" : "взял") + Вынесено(взято));
    }

    private static string Вынесено(Словарь<string, double> взято)
        => взято.Count == 0
           ? ""
           : ": " + string.Join(", ", взято.Ключи
               .OrderBy(р => р, StringComparer.Ordinal)
               .Select(р => $"{р} {Текст.G(Текст.Округлить(взято[р], 1))}"));

