// Гараж во дворе: модель автора, ворота на замке, коробки, верстак, лампа.
//
// Гараж в доме уже был — кладовая «гараж13» в `npcs.json`, со своими
// запасами и замком, — но стоял он только в данных. Здесь он стоит
// в мире, и **это та же самая кладовая**: коробки пустеют, когда пустеет
// она, замок сорван, когда она вскрыта. Своего учёта у гаража нет.
//
// Брать из коробки — поступок героя, а не ответ на вопрос дома, как
// и карман: делается только пока дом спит на вопросе, и делается
// функциями самого дома. Чужой гараж — `Улица.вскрыть_кладовую`: одна
// коробка — одна ходка, со всем, что за этим следует в доме (событие,
// хозяин узнает, «переступил»). Свой — `Улица._из_кладовой`. Сколько
// за раз, решает ручка дома `кладовая_за_раз`, а не этот файл.
//
// Модель — сцена, а не меш: деталей восемнадцать, створки должны
// вращаться вокруг своих петель, и держать их вместе удобнее сценой.
// Скина в ней нет, и потому то, что случилось с лопатой (сцена тащила
// скелет и разлеталась веером), здесь не грозит.
//
// Масштаб приходит из гнезда: модель сделана без оглядки на метры
// (ворота 5.6 единицы в высоту), и множитель подобран так, чтобы
// в яму под полом можно было спуститься в рост.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

public partial class Гараж : Node3D
{
    public const string МОДЕЛЬ = "res://модели/гараж/garage.fbx";

    /// <summary>Слой тел, которые мешают ходить, но не мешают прицелу:
    /// верстак и полка. Иначе коробки на них было бы не выбрать —
    /// луч упирался бы в сам верстак.</summary>
    public const uint СЛОЙ_МЕБЕЛИ = 4;

    // ---- связь с домом: ставит корневой узел ----
    public System.Func<(House дом, NPC я)?> Дом { get; set; } = () => null;
    public System.Func<bool> МожноМенять { get; set; } = () => false;
    public System.Action<string> Сказать { get; set; } = _ => { };
    public System.Action ОткрытьВерстак { get; set; } = () => { };
    public System.Action<Vector3> Перенести { get; set; } = _ => { };
    public System.Func<Vector3> ГдеГерой { get; set; } = () => Vector3.Zero;

    /// <summary>Какая кладовая дома — этот гараж.</summary>
    public Кладовая? кладовая { get; set; }

    private Node3D? _модель;
    private MeshInstance3D? _лево, _право, _замок;
    private Transform3D _лево0, _право0;
    private float _створка;          // 0 — закрыты, 1 — распахнуты
    private float _цель;
    private readonly List<Коробка> _коробки = new();
    private OmniLight3D? _лампа;
    private bool _лампа_вкл = true;
    private double _сеть = 1.0;

    // Снимок дома на последнем вопросе. Подсказку зовут каждый кадр,
    // а дом в это время может считать ход, и читать его тогда нельзя.
    // Поэтому подсказка смотрит сюда, а в дом ходят только действия —
    // и только пока он спит на вопросе.
    private bool _доступ, _вскрыта;
    private Vector3 _низ, _верх;     // куда ставит лестница
    private Aabb _пол;               // габарит пола — под ним яма
    private float _крыша = 4;        // высота стен: выше — уже не в гараже

    private const float РАСПАХ = 100f;   // на сколько градусов открываются створки

    private sealed class Коробка
    {
        public MeshInstance3D? полная, пустая;
        public bool пуста;
        public string имя = "";
    }

    /// <summary>Сколько места занимает гараж на земле, в осях родителя.
    /// Под ним яма, и земли двора там быть не должно.</summary>
    public Rect2 След()
    {
        var а = Transform * _пол;
        return new Rect2(а.Position.X, а.Position.Z, а.Size.X, а.Size.Z);
    }

    /// <summary>Внутри ли точка мира: между стенами, от дна ямы до крыши.</summary>
    public bool Внутри(Vector3 где)
    {
        var л = ToLocal(где);
        return л.X > _пол.Position.X && л.X < _пол.End.X
               && л.Z > _пол.Position.Z && л.Z < _пол.End.Z
               && л.Y > _пол.Position.Y - 0.5f && л.Y < _крыша;
    }

    /// <summary>Точка мира перед воротами, на этой высоте: оттуда
    /// метель видна в открытые ворота и не идёт сквозь крышу.</summary>
    public Vector3 ПередВоротами(float y)
        => ToGlobal(new Vector3(0, 0, _пол.End.Z + 9.0f)) with { Y = y };

    /// <summary>
    /// Собрать гараж из модели. Возвращает false, если модели нет:
    /// тогда во дворе просто пусто, а мир строится дальше.
    /// </summary>
    public bool Собрать(float масштаб)
    {
        var сцена = ResourceLoader.Exists(МОДЕЛЬ) ? GD.Load<PackedScene>(МОДЕЛЬ) : null;
        if (сцена is null)
        {
            GD.PrintErr($"нет модели гаража {МОДЕЛЬ}");
            return false;
        }
        _модель = сцена.Instantiate<Node3D>();
        _модель.Scale = Vector3.One * масштаб;
        AddChild(_модель);

        var части = new Dictionary<string, MeshInstance3D>(StringComparer.Ordinal);
        foreach (var у in _модель.GetChildren())
            if (у is MeshInstance3D м)
                части[у.Name.ToString().ToLowerInvariant()] = м;

        MeshInstance3D? Часть(string имя) => части.GetValueOrDefault(имя);
        Aabb Габарит(MeshInstance3D м) => _модель.Transform * (м.Transform * м.GetAabb());

        // ---- стены, пол, настил: форма, в которую упираются ----
        foreach (var имя in new[] { "garage walls", "floor", "plywood" })
            if (Часть(имя) is { } м)
                Форма(м, 1, выпуклая: false);
        foreach (var имя in new[] { "workbench", "shelf" })
            if (Часть(имя) is { } м)
                Форма(м, СЛОЙ_МЕБЕЛИ, выпуклая: false);

        if (Часть("floor") is { } пол)
            _пол = Габарит(пол);
        if (Часть("garage walls") is { } стены)
            _крыша = Габарит(стены).End.Y;

        // ---- ворота: вращаются вокруг своих петель ----
        _лево = Часть("garage door left");
        _право = Часть("garage door right");
        if (_лево is not null)
        {
            _лево0 = _лево.Transform;
            Форма(_лево, 1, выпуклая: true);
        }
        if (_право is not null)
        {
            _право0 = _право.Transform;
            Форма(_право, 1, выпуклая: true);
        }

        // ---- замок: крошечный, поэтому прицел ему раздут — и по толщине
        // тоже, на полметра в обе стороны от ворот: иначе изнутри луч
        // упирается в створку раньше, чем в него, и из закрытого гаража
        // не выйти ----
        _замок = Часть("lock(locked)");
        if (_замок is not null)
        {
            var ц = Габарит(_замок).GetCenter();
            var з = Предмет.Вокруг(this, new Aabb(ц - new Vector3(0.35f, 0.35f, 0.5f),
                                                  new Vector3(0.7f, 0.7f, 1.0f)),
                                   0, "замок_гаража");
            з.Подсказка = ЗамокПодсказка;
            з.Действие = ЗамокДействие;
        }

        // ---- коробки: у каждой пары полная и пустая ----
        foreach (var (имя, м) in части)
        {
            bool полная = имя.StartsWith("boxes(not_looted)", StringComparison.Ordinal);
            bool пустая = имя.StartsWith("boxes(looted)", StringComparison.Ordinal);
            if (!полная && !пустая)
                continue;
            string хвост = имя[(имя.IndexOf(')') + 1)..];
            var к = _коробки.FirstOrDefault(х => х.имя == хвост);
            if (к is null)
                _коробки.Add(к = new Коробка { имя = хвост });
            if (полная) к.полная = м;
            else к.пустая = м;
        }
        _коробки.Sort((а, б) => string.CompareOrdinal(а.имя, б.имя));
        for (int i = 0; i < _коробки.Count; i++)
        {
            var к = _коробки[i];
            var габарит = к.полная is not null ? Габарит(к.полная) : Габарит(к.пустая!);
            if (к.полная is not null && к.пустая is not null)
                габарит = габарит.Merge(Габарит(к.пустая));
            int номер = i;
            var цель = Предмет.Вокруг(this, габарит, 0.08f, $"коробка_гаража{i}");
            цель.Подсказка = () => КоробкаПодсказка(номер);
            цель.Действие = () => КоробкаДействие(номер);
        }

        // ---- верстак: прицел только на верхней трети — ниже коробки ----
        if (Часть("workbench") is { } верстак)
        {
            var г = Габарит(верстак);
            var верх = new Aabb(г.Position + new Vector3(0, г.Size.Y * 0.66f, 0),
                                new Vector3(г.Size.X, г.Size.Y * 0.34f, г.Size.Z));
            var цель = Предмет.Вокруг(this, верх, 0.05f, "верстак");
            цель.Подсказка = () => "верстак\n[E]  открыть";
            цель.Действие = () => ОткрытьВерстак();
        }

        // ---- лампа и выключатель ----
        if (Часть("lamp") is { } лампа)
        {
            var г = Габарит(лампа);
            _лампа = new OmniLight3D
            {
                Position = г.GetCenter() - new Vector3(0, г.Size.Y * 0.6f, 0),
                LightColor = new Color("#ffe2b0"),
                OmniRange = 8.0f,
                // без тени лампа светит сквозь стены — на снег вокруг
                ShadowEnabled = true,
                Name = "лампа_гаража",
            };
            AddChild(_лампа);
        }
        if (Часть("lamp switch") is { } щиток)
        {
            var г = Габарит(щиток);
            var цель = Предмет.Вокруг(this, г, 0.3f, "выключатель",
                                      new Vector3(-0.1f, 0, 0));
            цель.Подсказка = () => (_лампа_вкл ? "свет включён" : "свет выключен")
                                   + (_сеть < 0.2 ? " — но тока нет" : "")
                                   + "\n[E]  щёлкнуть";
            цель.Действие = Щёлкнуть;
        }

        // ---- лестница в яму ----
        // Ставит не к самой лестнице: у её подножия стоит коробка, и
        // человек оказывался в ней по пояс. Вниз — за край настила,
        // под него, где яма уже свободна; наверх — на настил над тем же
        // местом.
        if (Часть("ladder") is { } лестница)
        {
            var г = Габарит(лестница);
            float к_середине = _пол.GetCenter().Z > г.GetCenter().Z ? 1 : -1;
            float край = Часть("plywood") is { } настил
                ? (к_середине > 0 ? Габарит(настил).Position.Z : Габарит(настил).End.Z)
                : г.GetCenter().Z + к_середине * 1.1f;
            _низ = new Vector3(г.GetCenter().X, г.Position.Y + 0.05f,
                               край + к_середине * 0.5f);
            _верх = new Vector3(г.GetCenter().X, 0.08f, край + к_середине * 0.5f);
            var цель = Предмет.Вокруг(this, г, 0.1f, "лестница_гаража");
            цель.Подсказка = () => (ВЯме() ? "лестница наверх" : "лестница в яму")
                                   + "\n[E]  " + (ВЯме() ? "подняться" : "спуститься");
            цель.Действие = () => Перенести(ToGlobal(ВЯме() ? _верх : _низ));
        }

        Показать();
        return true;
    }

    /// <summary>Поставить форму по мешу. Выпуклая — для створок: они
    /// двигаются, а вогнутая форма у движущегося тела ведёт себя плохо.</summary>
    private static void Форма(MeshInstance3D м, uint слой, bool выпуклая)
    {
        if (выпуклая)
            м.CreateConvexCollision();
        else
            м.CreateTrimeshCollision();
        foreach (var у in м.GetChildren())
            if (у is StaticBody3D тело)
            {
                тело.CollisionLayer = слой;
                тело.CollisionMask = 0;
            }
    }

    private bool ВЯме() => ToLocal(ГдеГерой()).Y < -0.8f;

    /// <summary>
    /// Сверить гараж с домом. Зовётся на каждом вопросе, пока дом спит:
    /// пока герой ходил, хозяин мог сам спуститься за своим, и коробки
    /// должны это показать.
    /// </summary>
    public void Обновить(double сеть)
    {
        _сеть = сеть;
        if (кладовая is { } к)
        {
            _вскрыта = к.вскрыта;
            _доступ = Дом() is { } д && д.дом.есть_ключ(д.я, к);
            if (к.пусто())
                foreach (var коробка in _коробки)
                    коробка.пуста = true;
        }
        Показать();
    }

    /// <summary>Показать снимок: какие коробки пусты, висит ли замок,
    /// горит ли лампа. В дом не ходит.</summary>
    private void Показать()
    {
        if (_замок is not null)
            _замок.Visible = !_вскрыта && _цель == 0 && _створка == 0;
        foreach (var к in _коробки)
        {
            if (к.полная is not null) к.полная.Visible = !к.пуста;
            if (к.пустая is not null) к.пустая.Visible = к.пуста;
        }
        if (_лампа is not null)
            _лампа.LightEnergy = _лампа_вкл
                ? (float)(1.4 * System.Math.Clamp(_сеть, 0, 1))
                : 0f;
    }

    public override void _Process(double delta)
    {
        if (Mathf.IsEqualApprox(_створка, _цель))
            return;
        _створка = Mathf.MoveToward(_створка, _цель, (float)delta * 1.2f);
        float угол = Mathf.DegToRad(РАСПАХ) * _створка;
        // Петля левой створки — на её внешнем краю (+X модели), створка
        // уходит от петли к середине. Наружу (+Z) она выходит поворотом
        // на положительный угол; правая — на отрицательный.
        if (_лево is not null)
            _лево.Transform = new Transform3D(new Basis(Vector3.Up, угол) * _лево0.Basis,
                                              _лево0.Origin);
        if (_право is not null)
            _право.Transform = new Transform3D(new Basis(Vector3.Up, -угол) * _право0.Basis,
                                               _право0.Origin);
        if (Mathf.IsEqualApprox(_створка, _цель))
            Показать();
    }

    // ------------------------------------------------------------ замок

    private string Чей() => кладовая is null ? "гараж" : $"гараж кв.{кладовая.apt}";

    private string ЗамокПодсказка()
    {
        if (_цель > 0)
            return $"{Чей()}\n[E]  прикрыть ворота";
        if (кладовая is null)
            return $"{Чей()}\n[E]  открыть";
        if (_вскрыта)
            return $"{Чей()} — замок сорван\n[E]  открыть";
        if (_доступ)
            return $"{Чей()} — ключ у тебя\n[E]  отпереть";
        return $"{Чей()} — на замке\n[E]  сорвать замок";
    }

    private void ЗамокДействие()
    {
        if (_цель > 0)
        {
            _цель = 0;
            return;             // замок повиснет, когда створки сойдутся
        }
        if (кладовая is { } к && !_доступ && Дом() is { } д)
        {
            if (!МожноМенять())
            {
                Сказать("дом ещё считает ход — подожди");
                return;
            }
            // Срывают замок функцией дома, а она не только срывает,
            // но и выносит одну ходку: так в доме устроено вскрытие.
            // Вынесенное легло из ближней к воротам коробки.
            var взято = Улица.вскрыть_кладовую(д.дом, д.я, к);
            Обновить(_сеть);
            Опустошить(ПерваяПолная());
            Сказать($"сорвал замок: {Чей()}" + Вынесено(взято));
        }
        _цель = 1;
        Показать();
    }

    // ------------------------------------------------------------ коробки

    private int ПерваяПолная()
    {
        for (int i = 0; i < _коробки.Count; i++)
            if (!_коробки[i].пуста)
                return i;
        return -1;
    }

    private void Опустошить(int i)
    {
        if (i >= 0)
            _коробки[i].пуста = true;
        Показать();
    }

    private string КоробкаПодсказка(int i)
    {
        if (_коробки[i].пуста)
            return "коробки — пусто";
        if (_цель == 0)
            return "коробки — ворота закрыты";
        return "коробки\n[E]  обыскать";
    }

    private void КоробкаДействие(int i)
    {
        if (_коробки[i].пуста || _цель == 0)
            return;
        var к = кладовая;
        if (к is null || Дом() is not { } д)
        {
            Опустошить(i);
            return;
        }
        if (!МожноМенять())
        {
            Сказать("дом ещё считает ход — подожди");
            return;
        }
        if (к.пусто())
        {
            Опустошить(i);
            Сказать("пусто — всё уже вынесли");
            return;
        }
        Словарь<string, double> взято;
        if (д.дом.есть_ключ(д.я, к))
        {
            // Своё не выносят, а поднимают наверх — сколько нужно; туда же
            // попадает и чужое, когда замок уже сорван. Когда нужды нет,
            // дом и сам не спускается (`Улица.выбрать_кладовую`) — и коробка
            // тогда остаётся полной, а отдых не тратится.
            if (Улица.сколько_поднимет(д.дом, д.я, к, д.дом.B) <= 0)
            {
                Сказать("сейчас отсюда ничего не нужно — наверху хватает");
                return;
            }
            var было = Снимок(д.я);
            int одежда = д.я.одежда;
            var оружие = д.я.weapon;
            Улица._из_кладовой(д.дом, д.я, к, 0.0);
            взято = Разница(было, д.я);
            if (д.я.одежда != одежда)
                взято["тулуп"] = 1;
            if (д.я.weapon != оружие)
                взято[д.я.weapon.Текст()] = 1;
        }
        else
            взято = Улица.вскрыть_кладовую(д.дом, д.я, к);
        Обновить(_сеть);
        Опустошить(i);
        Сказать((взято.Count == 0 ? "ничего нужного" : "взял") + Вынесено(взято));
    }

    private static Словарь<string, double> Снимок(NPC я)
    {
        var с = Словари.Числа();
        foreach (var р in я.stock.Ключи)
            с[р] = я.stock[р];
        return с;
    }

    private static Словарь<string, double> Разница(Словарь<string, double> было, NPC я)
    {
        var с = Словари.Числа();
        foreach (var р in я.stock.Ключи)
        {
            double d = я.stock[р] - было.Взять(р, 0.0);
            if (d > 1e-9)
                с[р] = d;
        }
        return с;
    }

    private static string Вынесено(Словарь<string, double> взято)
        => взято.Count == 0
           ? ""
           : ": " + string.Join(", ", взято.Ключи
               .OrderBy(р => р, StringComparer.Ordinal)
               .Select(р => $"{р} {Текст.G(Текст.Округлить(взято[р], 1))}"));

    // ------------------------------------------------------------ свет

    private void Щёлкнуть()
    {
        _лампа_вкл = !_лампа_вкл;
        Показать();
        if (_лампа_вкл && _сеть < 0.2)
            Сказать("щёлкнул — света нет, в доме нет тока");
    }
}
