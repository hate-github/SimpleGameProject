// Бункер в движке (ГДД 20, 22: путь одиночки). Считает всё `Дом.Ядро.Бункер`;
// здесь — что под прицелом и что по клавише действия у гермодвери, нар,
// стеллажа, буржуйки, агрегата вентиляции и лаза, и сборы в дорогу у полки.
//
// Как в участке: всё трогается, только пока дом спит на вопросе, долгое —
// делом кусками (`Дорога`), исход — когда дом проживёт эти часы и уснёт.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    private Бункер? Бункер_ => Округа_?.бункер;

    private Поход? Поход_бункера() => Округа_?.летопись.походы.FirstOrDefault(п => п.вид == "бункер");

    /// <summary>Знает ли герой вход, и есть ли куда спускаться.</summary>
    private bool Бункер_известен => Бункер_ is not null && Округа_?.Знает("бункер_вход") == true;

    // тара, в которую собирают в дорогу, пока ноша пуста
    private Тара _тара_сборов = Тара.РЮКЗАК;

    /// <summary>Места бункера: подсказки и действия. Зовётся из `Завести`.</summary>
    private void Бункер_завести()
    {
        _мир.Гермодверь_открыта(false);
        if (_мир.Гермодверь is { } гд)
        {
            гд.Подсказка = У_гермодвери;
            гд.Действие = К_гермодвери;
        }
        if (_мир.НарыБункера is { } нары)
        {
            нары.Подсказка = () => $"нары\n{Жми}  поесть, попить из кармана; лечь";
            нары.Действие = () => К_нарам_где(нары);
        }
        if (_мир.ЗапасБункера is { } запас)
        {
            запас.Подсказка = () => Бункер_ is { открыт: true } б
                ? $"стеллаж НЗ и бак с водой — в запасе {Текст.G(Текст.Округлить(б.запас_всего, 1))}\n{Жми}  открыть"
                : "стеллаж за гермодверью";
            запас.Действие = К_запасу_бункера;
        }
        if (_мир.ПечьБункера is { } печь)
        {
            печь.Подсказка = () => Бункер_ is { } б && _партия is not null && б.Печь_топится(_партия.прогон.h.day)
                ? "буржуйка — топится"
                : $"буржуйка\n{Жми}  затопить на день ({Текст.G(Бункер_?.данные.печь_топлива ?? 0)} топлива из запаса)";
            печь.Действие = () =>
            {
                if (Бункер_ is { } б && _партия is not null && Дом_спит)
                    Сказать(б.Затопить(_партия.прогон.h) ?? "затопил буржуйку — до вечера в зале тепло");
            };
        }
        if (_мир.ВентиляцияБункера is { } вент)
        {
            вент.Подсказка = () => Бункер_ is { } б && _партия is not null && б.Вентилирован(_партия.прогон.h.day)
                ? "фильтровентиляционный агрегат — сегодня прокручен, воздуха до утра хватит"
                : $"фильтровентиляционный агрегат, ручной привод\n{Жми}  крутить "
                  + $"(≈{Часы_текстом(Бункер_?.данные.вентиляция_часов ?? 1.0)} ч) — иначе ночь в спёртом воздухе";
            вент.Действие = К_вентиляции;
        }
        if (_мир.ЛазБункера is { } лаз)
        {
            лаз.Подсказка = У_лаза;
            лаз.Действие = Из_бункера;
        }
    }

    /// <summary>Пришёл к бункеру, вход в который знает: вниз по скобам, в тамбур.
    /// Что пропало, пока его не было, — видно сразу.</summary>
    private void В_бункер(string весть = "")
    {
        if (Бункер_ is not { } б || _партия is null)
            return;
        _в_походе = null;
        б.Спустился(_партия.сеанс.я);
        _мир.Гермодверь_открыта(б.открыт);
        _герой.GlobalPosition = _мир.ВходБункера;
        _герой.Rotation = Vector3.Zero;             // лицом к гермодвери
        _герой.Прямо();
        var пропало = б.Пропажи();
        string что = пропало.Ключи.Count == 0 ? ""
            : " · здесь кто-то был: нет " + string.Join(", ", пропало.Ключи.OrderBy(к => к, System.StringComparer.Ordinal)
                                                   .Select(к => $"{к} {Текст.G(пропало[к])}"))
              + "; следы на снегу — к нашему дому";
        Сказать((весть.Length > 0 ? весть + " · " : "")
                + (б.открыт ? "спустился в убежище: сухо, тихо, плюс восемь"
                            : "спустился в тамбур убежища: гермодверь, штурвал в рыжей ржавчине")
                + что);
    }

    /// <summary>Утро (или подъём из сохранения) под землёй — у нар.</summary>
    private bool Проснулся_в_бункере()
    {
        if (Бункер_ is not { внутри: true } б)
            return false;
        _мир.Гермодверь_открыта(б.открыт);
        _герой.GlobalPosition = б.открыт ? _мир.У_нар_бункера : _мир.ВходБункера;
        _герой.Rotation = Vector3.Zero;
        _герой.Прямо();
        return true;
    }

    private string У_гермодвери()
    {
        if (Бункер_ is not { } б || _партия is null)
            return "гермодверь";
        if (б.открыт)
            return "гермодверь — открыта";
        var я = _партия.сеанс.я;
        string? чем = б.Чем_открыть(я, _инструменты);
        double часов = б.Часов_открыть(_партия.прогон.h, чем, _инструменты);
        return чем is string и
            ? $"гермодверь — штурвал прикипел\n{Жми}  провернуть: {_инструменты.все[и].чем} на штурвал (≈{Часы_текстом(часов)} ч)"
            : $"гермодверь — штурвал прикипел, рычага при себе нет (монтировка)\n"
              + $"{Жми}  проворачивать руками (≈{Часы_текстом(часов)} ч, в кровь)";
    }

    /// <summary>Провернуть штурвал — делом: монтировкой быстрее и вернее,
    /// руками долго и в кровь; исход — когда дом проживёт эти часы.</summary>
    private void К_гермодвери()
    {
        if (Бункер_ is not { } б || _мир.Гермодверь is not { } дверь || _партия is null)
            return;
        if (б.открыт)
        {
            Сказать("гермодверь открыта — зал за ней");
            return;
        }
        if (!Можно_в_поход())
            return;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        string? чем = б.Чем_открыть(я, _инструменты);
        Дорога(дверь, чем is null ? "проворачиваю штурвал руками" : "проворачиваю штурвал", б.Часов_открыть(h, чем, _инструменты), () =>
        {
            var ш = б.Открыть(h, я, чем, _инструменты, _ручки, Как_сыграно(МиниИгра.ВЗЛОМ));
            _мир.Гермодверь_открыта(б.открыт);
            Сказать(ш.весть + Сыграно_словами());
        }, мини: МиниИгра.ВЗЛОМ);
    }

    /// <summary>Нары — в участке и в бункере одни: поесть и попить из кармана,
    /// лечь переждать.</summary>
    private void К_нарам_где(Предмет нары)
    {
        if (_партия is null || !Дом_спит)
            return;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        double В_кармане(string р) => я.карман?.Сколько(р) ?? 0.0;
        _окно.Показать("НАРЫ",
            () => $"Сытость {Текст.G(Текст.Округлить(я.satiety, 0))}, жажда {Текст.G(Текст.Округлить(100 - я.hydration, 0))}. "
                  + $"В кармане еды {Текст.G(В_кармане("еда"))}, воды {Текст.G(В_кармане("вода"))}.",
            () => new[]
            {
                new СтрокаОкна("съесть из кармана", В_кармане("еда") >= 1, () =>
                    _окно.Весть(Участок.Из_кармана(h, я, "еда") ? "поел" : "нечего")),
                new СтрокаОкна("попить из кармана", В_кармане("вода") >= 1, () =>
                    _окно.Весть(Участок.Из_кармана(h, я, "вода") ? "попил" : "нечего")),
                new СтрокаОкна("лечь — переждать четыре часа", true, () =>
                {
                    _окно.Убрать();
                    if (Можно_в_поход())
                        Дорога(нары, "лежу на нарах", 4.0, () => Сказать("отлежался"));
                }),
            });
        Мышь();
    }

    /// <summary>Стеллаж и бак: поесть, попить, выложить принесённое, взять с собой.</summary>
    private void К_запасу_бункера()
    {
        if (Бункер_ is not { } б || _партия is null || !Дом_спит)
            return;
        if (!б.открыт)
        {
            Сказать("стеллаж за гермодверью");
            return;
        }
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        _окно.Показать("ЗАПАС УБЕЖИЩА",
            () => "Галеты в жестяных коробках, бак технической воды, аптечка ГО — и что принёс сам: "
                  + (б.запас_что.Count == 0 ? "пусто" : string.Join(", ", б.запас_что
                      .Where(р => б.В_запасе(р) > 1e-9)
                      .Select(р => $"{р} {Текст.G(Текст.Округлить(б.В_запасе(р), 1))}")))
                  + ". " + (я.ноша is { пусто: false, тара: Тара т } н
                      ? $"{т.Текст()}: {н}."
                      : "Тара пуста."),
            () =>
            {
                var строки = new List<СтрокаОкна>
                {
                    new("поесть", б.В_запасе("еда") >= 1, () => _окно.Весть(б.Поесть(h, я, "еда") ? "поел" : "нечего")),
                    new("попить", б.В_запасе("вода") >= 1, () => _окно.Весть(б.Поесть(h, я, "вода") ? "попил" : "нечего")),
                    new("выложить всё принесённое", я.ноша is { пусто: false }, () =>
                    {
                        var было = б.Выложить(я);
                        _окно.Весть("выложил: " + string.Join(", ", было.Ключи.OrderBy(к => к, System.StringComparer.Ordinal)
                                                                       .Select(к => $"{к} {Текст.G(было[к])}")));
                    }),
                };
                foreach (var р in б.запас_что.ToList())
                {
                    string ресурс = р;
                    double есть = б.В_запасе(ресурс);
                    строки.Add(new СтрокаОкна($"взять с собой: {ресурс} (есть {Текст.G(Текст.Округлить(есть, 1))})", есть >= 1, () =>
                    {
                        double взял = б.Взять(я, ресурс, 1.0, _ручки);
                        _окно.Весть(взял > 0 ? $"взял: {ресурс}" : "не влезет");
                    }));
                }
                return строки;
            });
        Мышь();
    }

    /// <summary>Крутить привод вентиляции — делом.</summary>
    private void К_вентиляции()
    {
        if (Бункер_ is not { } б || _мир.ВентиляцияБункера is not { } агрегат || _партия is null)
            return;
        if (!б.открыт)
        {
            Сказать("агрегат за гермодверью");
            return;
        }
        if (б.Вентилирован(_партия.прогон.h.day))
        {
            Сказать("сегодня прокручен — воздуха до утра хватит");
            return;
        }
        if (!Можно_в_поход())
            return;
        Дорога(агрегат, "кручу привод вентиляции", б.данные.вентиляция_часов, () =>
        {
            if (_партия is null)
                return;
            б.Вентилировать(_партия.прогон.h.day);
            Сказать("прокрутил привод: в воздуховоде зашуршало, воздуха до утра хватит");
        });
    }

    private string У_лаза()
    {
        if (Поход_бункера() is not { } п || _партия is null || Округа_ is not { } о)
            return "лаз наверх";
        return $"лаз наверх, скобы в бетоне\n{Жми}  домой (≈{Часы_текстом(о.Часы_дороги(_партия.прогон.h, _партия.сеанс.я, п))} ч)";
    }

    /// <summary>Наверх и домой — дорога по сегодняшнему снегу, к воротам двора.
    /// Замело без снегоступов — под землёй и оставаться.</summary>
    private void Из_бункера()
    {
        if (Бункер_ is not { } б || _мир.ЛазБункера is not { } лаз || Поход_бункера() is not { } п
            || Округа_ is not { } о || !Можно_в_поход())
            return;
        var h = _партия!.прогон.h;
        var я = _партия.сеанс.я;
        double часов = о.Часы_дороги(h, я, п);
        if (!о.летопись.Пройти(п.улица, h.day, о.зерно, о.Есть_у(h, я)))
        {
            Сказать("наверху замело по пояс — без снегоступов до дома не дойти");
            return;
        }
        if (я.time_left < часов - 1e-9)
        {
            Сказать($"до ночи не дойти: нужно {Часы_текстом(часов)} ч — переночевать здесь");
            return;
        }
        Дорога(лаз, "дорога домой", часов, () =>
        {
            б.Поднялся(я);
            Вернуться(п, "вернулся из убежища к дому");
        });
    }

    /// <summary>Что ядро бункера хочет сказать (ночь в духоте) — когда дом спит.</summary>
    private void Весть_бункера()
    {
        if (Бункер_?.Весть() is string весть)
            Сказать(весть);
    }

    /// <summary>Уходя к бункеру с полной тарой — ходка под наблюдением.</summary>
    private void Ходка_к_бункеру()
    {
        if (Бункер_ is not { } б || _партия is null || _партия.сеанс.я.ноша is not { пусто: false })
            return;
        if (б.Ходка(_партия.прогон.h, _партия.сеанс.я).Count > 0)
            Сказать("уходя, оглянулся: в окне дома кто-то стоял и смотрел вслед");
    }

    // ---------- сборы в дорогу у полки ----------

    /// <summary>Собрать из своего шкафа в тару — к бункеру. Собранное у своего
    /// порога само не разгружается; разобрать — здесь же.</summary>
    private void Собрать_в_дорогу()
    {
        if (_партия is null || !Дом_спит)
            return;
        var я = _партия.сеанс.я;
        _окно.Показать("В ДОРОГУ",
            () =>
            {
                var ноша = я.ноша;
                var тара = ноша?.тара ?? _тара_сборов;
                string в_таре = ноша is { пусто: false } н
                    ? $"{тара.Текст()}: {н} — {Текст.G(Текст.Округлить(н.занято, 1))} из {Текст.G(тара.мест(_ручки))}"
                    : $"{тара.Текст()} пуст{(тара == Тара.СУМКА ? "а" : "")} — до {Текст.G(тара.мест(_ручки))}";
                return "Что нести в убежище. Полная тара шумит в подъезде, а уходить с ней за ворота "
                       + $"видно из окон. {в_таре}.";
            },
            () =>
            {
                var ноша = я.ноша ??= new Ноша();
                var тара = ноша.тара ?? _тара_сборов;
                var строки = new List<СтрокаОкна>();
                if (ноша.пусто)
                    строки.Add(new СтрокаОкна($"тара: {тара.Текст()} — сменить", true, () =>
                    {
                        int i = Тары.ВСЕ.ToList().IndexOf(_тара_сборов);
                        _тара_сборов = Тары.ВСЕ[(i + 1) % Тары.ВСЕ.Count];
                    }));
                foreach (var р in я.stock.Ключи.OrderBy(x => x, System.StringComparer.Ordinal).ToList())
                {
                    string ресурс = р;
                    double дома = я.stock.Взять(ресурс, 0.0);
                    if (дома < 1.0)
                        continue;
                    строки.Add(new СтрокаОкна($"{ресурс} — {тара.Куда()} (дома {Текст.G(Текст.Округлить(дома, 1))})",
                        ноша.свободно(тара, _ручки) >= 1.0 - 1e-9, () =>
                        {
                            double взял = ноша.Собрать(я, тара, ресурс, 1.0, _ручки);
                            _окно.Весть(взял > 0 ? $"положил: {ресурс}" : "не влезет");
                        }));
                }
                if (ноша is { пусто: false, в_дорогу: true })
                    строки.Add(new СтрокаОкна("разобрать обратно на полку", true, () =>
                    {
                        _окно.Убрать();
                        Разгрузить("разобрал");
                    }));
                return строки;
            });
        Мышь();
    }
}
