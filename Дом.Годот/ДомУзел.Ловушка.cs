// Ловушка у своей двери (ГДД 15, уровень 4): поставить, взвести заново,
// узнать, кто попался. Что можно и что бывает — ядро (`Петля/Ловушка.cs`);
// здесь только строки окна своей двери, весть герою и проволока у порога.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    /// <summary>
    /// Строки ловушки в окне своей двери: стоит — что с ней; сработала — кто
    /// попался и взвести снова; нет — поставить (серым, если нельзя, с причиной).
    /// </summary>
    private IEnumerable<СтрокаОкна> Ловушка_у_двери(House h, NPC я)
    {
        var лов = Округа_?.ловушка;
        if (лов is { взведена: true })
        {
            yield return new СтрокаОкна("у порога изнутри ловушка — взведена", false, null);
            yield break;
        }
        if (лов?.попались.LastOrDefault() is { } последний)
            yield return new СтрокаОкна($"ловушка сработала ({Кто_попался(h, я, последний)}) — спущена", false, null);
        string? нельзя = Ловушка.Нельзя(h, я, _ручки);
        string что = лов is null ? "поставить ловушку у порога" : "взвести ловушку снова";
        yield return new СтрокаОкна(нельзя is null
                                        ? $"{что} (≈{Часы_текстом(Ловушка.Часы(_ручки))} ч)"
                                        : $"{что} — {нельзя}",
                                    нельзя is null, Поставить_ловушку);
    }

    /// <summary>Кто попался — как его знает герой; не видел — «кто — не видно».</summary>
    private static string Кто_попался(House h, NPC я, Попался п)
        => п.узнал && h.people.TryGetValue(п.кто, out var кто)
            ? Знакомство.Как_зовут(h, я, кто)
            : "кто — не видно, на пороге кровь";

    /// <summary>Поставить или взвести: часы — поступком героя, пока дом спит.</summary>
    private void Поставить_ловушку()
    {
        if (_партия is null || !Дом_спит || !Можно_тут())
            return;
        var я = _партия.сеанс.я;
        bool была = Округа_?.ловушка is not null;
        if (Ловушка.Поставить(_партия.прогон.h, я, _ручки) is not { } л)
            return;
        _мир.Ловушка_у(л.квартира);
        Сделать_тут(new Сделано(true, Ловушка.Часы(_ручки),
                                $"{(была ? "взвёл" : "поставил")}{(я.sex == "ж" ? "а" : "")} ловушку у порога — "
                                + "кто войдёт без спросу, попадётся; гостю, который стучит, она не страшна"));
    }

    /// <summary>На вопросе: проволока у порога, пока взведена.</summary>
    private void Ловушка_вопроса()
        => _мир.Ловушка_у(Округа_?.ловушка is { взведена: true } л ? л.квартира : null);

    /// <summary>
    /// Кто попался с прошлого раза — герою словами, когда он в доме:
    /// на участке и в походе о ловушке не узнать.
    /// </summary>
    private void Весть_ловушки()
    {
        if (_партия is null || !Дом_спит || _в_походе is not null || Округа_?.ловушка is not { } лов)
            return;
        var я = _партия.сеанс.я;
        if (я.нет_в_доме())
            return;
        var новые = лов.Новые();
        if (новые.Count == 0)
            return;
        var h = _партия.прогон.h;
        Сказать("у порога сработала ловушка: "
                + string.Join("; ", новые.Select(п => п.узнал && h.people.TryGetValue(п.кто, out var кто)
                    ? $"{Знакомство.Как_зовут(h, я, кто)} — {(кто.sex == "ж" ? "ушла" : "ушёл")}, хромая"
                    : "кто-то ушёл, хромая, — на пороге кровь"))
                + " · взвести снова — у своей двери");
    }

    /// <summary>Проба: дать герою материалы и дело механика и открыть окно
    /// своей двери. Только в песочнице.</summary>
    public string Проба_ловушка_дать()
    {
        if (!Пути.Песочница || _партия is null || !Дом_спит)
            return "не песочница или дом не спит";
        var я = _партия.сеанс.я;
        я.stock["материалы"] = я.stock.Взять("материалы", 0.0) + _ручки["ловушка_материалы"];
        Округа_?.Узнал(Ловушка.МЕХАНИК);
        _окно.Убрать();
        Своя_дверь();
        return _окно.открыт ? "своя дверь" : "окно не открылось";
    }

    /// <summary>Проба: сосед лезет к герою ночным вором — и весть герою.
    /// Только в песочнице.</summary>
    public string Проба_ловушка_вор()
    {
        if (!Пути.Песочница || _партия is null || !Дом_спит)
            return "не песочница или дом не спит";
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        if (h.others(я).FirstOrDefault(п => п.здесь() && п.apt != я.apt) is not { } вор)
            return "некому лезть";
        Конфликт.steal(h, вор, я);
        Ловушка_вопроса();
        Весть_ловушки();
        return _весть.Text;
    }

    /// <summary>Проба: что с ловушкой. Только в песочнице.</summary>
    public string Проба_ловушка()
    {
        if (!Пути.Песочница || _партия is null || !Дом_спит)
            return "не песочница или дом не спит";
        if (Округа_?.ловушка is not { } л)
            return "ловушки нет";
        return $"у кв.{л.квартира}, {(л.взведена ? "взведена" : "спущена")}, попались {л.попались.Count}"
               + (л.попались.LastOrDefault() is { } п ? $": {п.кто} ({п.дело}, день {п.день})" : "");
    }
}
