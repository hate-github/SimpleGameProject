    /// <summary>Коробка стен: две боковые, задняя и торцевая с окнами.
    /// Строятся на всю высоту сразу, а не по этажу: окно на промежуточной
    /// площадке пересекает перекрытие, и по этажам его не собрать.</summary>
    private void Стены(StandardMaterial3D бетон, float высота, int этажей)
    {
        float глубина = ПЕРЁД - ЗАД;
        float середина = (ЗАД + ПЕРЁД) / 2;

        foreach (float сторона in new[] { -1f, 1f })
        {
            float x = сторона * (ШИРИНА + 0.1f);
            if (сторона != Сторона(_своя))
            {
                Коробка(бетон, new Vector3(0.2f, высота, глубина),
                        new Vector3(x, высота / 2, середина));
                continue;
            }
            Проём(бетон, x, высота, глубина, середина);
        }
        Коробка(бетон, new Vector3(ШИРИНА * 2 + 0.4f, высота, 0.2f),
                new Vector3(0, высота / 2, ЗАД - 0.1f));

        Торец(бетон, высота, этажей);
    }

    /// <summary>
    /// Торцевая стена с окнами — то самое место, ради которого всё это
    /// и строится: в подъезде метель видно только отсюда.
    ///
    /// Окно приходится на промежуточную площадку и на высоту глаз того,
    /// кто на ней стоит. Стекло сделано твёрдым: дыра в стене без него —
    /// это дыра, в которую выходят.
    /// </summary>
    private void Торец(StandardMaterial3D бетон, float высота, int этажей)
    {
        const float ОКНО = 0.85f;                      // полширины окна
        float z = ПЕРЁД + 0.1f;
        float простенок = ШИРИНА + 0.2f - ОКНО;
        float край = (ШИРИНА + 0.2f + ОКНО) / 2;

        // простенки по краям — во всю высоту
        Коробка(бетон, new Vector3(простенок, высота, 0.2f),
                new Vector3(-край, высота / 2, z));
        Коробка(бетон, new Vector3(простенок, высота, 0.2f),
                new Vector3(край, высота / 2, z));

        // между простенками — пояса кладки, окна между ними
        var стекло = new StandardMaterial3D
        {
            AlbedoColor = new Color(0.72f, 0.78f, 0.84f, 0.14f),
            Transparency = BaseMaterial3D.TransparencyEnum.Alpha,
            Roughness = 0.35f,
        };
        float низ = 0;
        for (int э = 1; э <= этажей; э++)
        {
            float дно = ЭТАЖ * (э - 1) + 2.2f;
            float верх = Mathf.Min(ЭТАЖ * (э - 1) + 3.4f, высота);
            if (дно >= высота - 0.3f)
                break;
            Коробка(бетон, new Vector3(ОКНО * 2, дно - низ, 0.2f),
                    new Vector3(0, (низ + дно) / 2, z));
            Коробка(стекло, new Vector3(ОКНО * 2, верх - дно, 0.06f),
                    new Vector3(0, (дно + верх) / 2, z));
            низ = верх;
        }
        if (низ < высота)
            Коробка(бетон, new Vector3(ОКНО * 2, высота - низ, 0.2f),
                    new Vector3(0, (низ + высота) / 2, z));
    }

    /// <summary>Четыре двери на площадку: две слева, две справа.</summary>
    private void Двери(House h, int э, float y)
    {
        for (int i = 0; i < 4; i++)
        {
            int кв = (э - 1) * 4 + i + 1;
            if (!h.flats.Есть(кв))
                continue;
            float сторона = Сторона(кв);
            float в_дом = -сторона;
            float z = Глубина(кв);
            var место = new Vector3(сторона * (ШИРИНА - 0.07f), y + 1.05f, z);
            // своя краска на каждую дверь: общий материал перекрасить
            // нельзя, перекрасятся все двадцать разом
            var краска = Материал(ДЕРЕВО, 0.7f);
            StaticBody3D узел;
            if (кв == _своя)
            {
                // Своя дверь распахнута: это твоя дверь, ты в неё входишь.
                // Створка стоит вдоль стены уже внутри квартиры, а место,
                // куда смотрит луч, — просто область в проёме: тело в нём
                // не пропустило бы человека, а прицел по нему работает
                // ровно так же (`RayCast3D.CollideWithAreas`).
                // Створка уходит **внутрь квартиры**, а не на площадку.
                // Первый заход поставил её по `в_дом`, то есть в подъезд,
                // и она встала поперёк дороги: герой упирался в собственную
                // открытую дверь и никуда не шёл.
                // Размер задан по осям прямо, без поворота. Поворот
                // на узле не применился к форме, и створка так и осталась
                // стоять поперёк проёма — то есть закрытой, только внутри
                // квартиры. Развёрнутая дверь — это просто доска вдоль
                // стены, и проще написать её вдоль стены.
                var створка = new Vector3(0.95f, 2.1f, 0.14f);
                узел = new StaticBody3D
                {
                    Position = место + new Vector3(-в_дом * 0.55f, 0, 0.55f),
                };
                узел.AddChild(new MeshInstance3D
                {
                    Mesh = new BoxMesh { Size = створка },
                    MaterialOverride = краска,
                });
                узел.AddChild(new CollisionShape3D
                {
                    Shape = new BoxShape3D { Size = створка },
                });
                AddChild(узел);

                var прицел = new Area3D
                {
                    Position = место,
                    Name = $"дверь{кв}",
                };
                прицел.AddChild(new CollisionShape3D
                {
                    Shape = new BoxShape3D
                        { Size = new Vector3(0.14f, 2.1f, 0.95f) },
                });
                AddChild(прицел);
                Табличка(прицел, кв, в_дом);
            }
            else
            {
                узел = Коробка(краска, new Vector3(0.14f, 2.1f, 0.95f), место);
                узел.Name = $"дверь{кв}";
                Табличка(узел, кв, в_дом);
            }
            _двери.Add(new ДверьКвартиры(
                кв, узел, new Vector3(место.X + в_дом * 0.9f, y, z),
                в_дом, краска, Щель(место, в_дом), Зарубка(место, в_дом)));
        }
    }

    /// <summary>
    /// Входная дверь подъезда — единственный выход из дома.
    ///
    /// Стоит она в задней стене первого этажа, и за ней двор. Ходить туда
    /// нельзя: двор построен как вид из окна, а не как место. Дверь нужна
