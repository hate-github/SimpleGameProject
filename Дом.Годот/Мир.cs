    /// <summary>Коробка стен: две боковые, задняя и торцевая с окнами.
    /// Строятся на всю высоту сразу, а не по этажу: окно на промежуточной
    /// площадке пересекает перекрытие, и по этажам его не собрать.</summary>
    /// <summary>
    /// Задняя стена с проёмом входной двери на первом этаже.
    ///
    /// До того она была сплошной плитой во всю высоту: выход был обозначен
    /// створкой на стене и областью для прицела, а пройти сквозь него было
    /// нельзя. Теперь это настоящий проём, и двор за ним — место.
    /// </summary>
    private void ЗадняяСтена(StandardMaterial3D бетон, float высота)
    {
        float z = ЗАД - 0.1f;
        float ширина = ШИРИНА * 2 + 0.4f;
        float край = (ширина - ПРОЁМ_ШИРИНА) / 2;
        int этажей = (int)Math.Round(высота / ЭТАЖ);

        // первый этаж: по бокам от дверного проёма
        foreach (float с in new[] { -1f, 1f })
            Коробка(бетон, new Vector3(край, ПРОЁМ_ВЕРХ, 0.2f),
                    new Vector3(с * (ширина - край) / 2, ПРОЁМ_ВЕРХ / 2, z));
        // от притолоки до второго этажа — сплошняком
        Коробка(бетон, new Vector3(ширина, ЭТАЖ - ПРОЁМ_ВЕРХ, 0.2f),
                new Vector3(0, (ПРОЁМ_ВЕРХ + ЭТАЖ) / 2, z));

        // Выше — по окну на этаж. Дом со двора должен читаться домом:
        // без окон это глухая плита, и всё, ради чего во двор выходят,
        // упирается в неё.
        const float ОКНО_Ш = 1.3f, ОКНО_НИЗ = 1.15f, ОКНО_ВЕРХ = 2.15f;
        float бок = (ширина - ОКНО_Ш) / 2;
        for (int э = 2; э <= этажей; э++)
        {
            float y = ЭТАЖ * (э - 1);
            Коробка(бетон, new Vector3(ширина, ОКНО_НИЗ, 0.2f),
                    new Vector3(0, y + ОКНО_НИЗ / 2, z));
            foreach (float с in new[] { -1f, 1f })
                Коробка(бетон, new Vector3(бок, ОКНО_ВЕРХ - ОКНО_НИЗ, 0.2f),
                        new Vector3(с * (ширина - бок) / 2,
                                    y + (ОКНО_НИЗ + ОКНО_ВЕРХ) / 2, z));
            Коробка(бетон, new Vector3(ширина, ЭТАЖ - ОКНО_ВЕРХ, 0.2f),
                    new Vector3(0, y + (ОКНО_ВЕРХ + ЭТАЖ) / 2, z));
            // стекло: дыра в стене без него — дыра, в которую выходят
            Коробка(Стекло(), new Vector3(ОКНО_Ш, ОКНО_ВЕРХ - ОКНО_НИЗ, 0.05f),
                    new Vector3(0, y + (ОКНО_НИЗ + ОКНО_ВЕРХ) / 2, z));
        }
        // парапет над верхним этажом
        Коробка(бетон, new Vector3(ширина, 0.5f, 0.3f),
                new Vector3(0, высота + 0.25f, z));
    }

    private static StandardMaterial3D Стекло() => new()
    {
        AlbedoColor = new Color(0.72f, 0.78f, 0.84f, 0.14f),
        Transparency = BaseMaterial3D.TransparencyEnum.Alpha,
        Roughness = 0.35f,
    };

    private const float ПРОЁМ_ШИРИНА = 1.2f;
    private const float ПРОЁМ_ВЕРХ = 2.15f;

    /// <summary>Четыре двери на площадку: две слева, две справа.</summary>
    private void Двери(House h, int э, float y)
    {
        for (int i = 0; i < 4; i++)
        {
            int кв = (э - 1) * 4 + i + 1;
            if (!h.flats.Есть(кв))
                continue;
            float сторона = Сторона(кв);
            float в_дом = -сторона;
            float z = Глубина(кв);
            var место = new Vector3(сторона * (ШИРИНА - 0.07f), y + 1.05f, z);
            // своя краска на каждую дверь: общий материал перекрасить
            // нельзя, перекрасятся все двадцать разом
            var краска = Материал(ДЕРЕВО, 0.7f);
            StaticBody3D узел;
            if (кв == _своя)
            {
                // Своя дверь распахнута: это твоя дверь, ты в неё входишь.
                // Створка стоит вдоль стены уже внутри квартиры, а место,
                // куда смотрит луч, — просто область в проёме: тело в нём
                // не пропустило бы человека, а прицел по нему работает
                // ровно так же (`RayCast3D.CollideWithAreas`).
                // Створка уходит **внутрь квартиры**, а не на площадку.
                // Первый заход поставил её по `в_дом`, то есть в подъезд,
                // и она встала поперёк дороги: герой упирался в собственную
                // открытую дверь и никуда не шёл.
                // Размер задан по осям прямо, без поворота. Поворот
                // на узле не применился к форме, и створка так и осталась
                // стоять поперёк проёма — то есть закрытой, только внутри
                // квартиры. Развёрнутая дверь — это просто доска вдоль
                // стены, и проще написать её вдоль стены.
                var створка = new Vector3(0.95f, 2.1f, 0.14f);
                узел = new StaticBody3D
                {
                    Position = место + new Vector3(-в_дом * 0.55f, 0, 0.55f),
                };
                узел.AddChild(new MeshInstance3D
                {
                    Mesh = new BoxMesh { Size = створка },
                    MaterialOverride = краска,
                });
                узел.AddChild(new CollisionShape3D
                {
                    Shape = new BoxShape3D { Size = створка },
                });
                AddChild(узел);

                var прицел = new Area3D
                {
                    Position = место,
                    Name = $"дверь{кв}",
                };
                прицел.AddChild(new CollisionShape3D
                {
                    Shape = new BoxShape3D
                        { Size = new Vector3(0.14f, 2.1f, 0.95f) },
                });
                AddChild(прицел);
                Табличка(прицел, кв, в_дом);
            }
            else
            {
                узел = Коробка(краска, new Vector3(0.14f, 2.1f, 0.95f), место);
                узел.Name = $"дверь{кв}";
                Табличка(узел, кв, в_дом);
            }
            _двери.Add(new ДверьКвартиры(
                кв, узел, new Vector3(место.X + в_дом * 0.9f, y, z),
                в_дом, краска, Щель(место, в_дом), Зарубка(место, в_дом)));
        }
    }

    /// <summary>
    /// Входная дверь подъезда — единственный выход из дома.
    ///
    /// Стоит она в задней стене первого этажа, и за ней двор — теперь
    /// настоящий: в стене проём, и в него выходят ногами. Дверь при этом
    /// осталась и местом вопроса: вылазка — это выбор «ближе и беднее
    /// или дальше и опаснее», и делать его надо там, где стоят одетым
    /// у порога, а не листая список посреди площадки.
    ///
    /// Створка открывается сама, когда к ней подходят, и закрывается,
    /// когда отходят. Держать её нараспашку было бы враньём: на дворе
    /// тридцать два мороза, и подъезд выстыл бы за ночь. Держать её
    /// закрытой и пускать сквозь — враньём вдвойне.
    ///
    /// Прицел — область, а не тело: тело в проёме не дало бы ни подойти
    /// вплотную, ни пройти, а луч видит область так же
    /// (`RayCast3D.CollideWithAreas`).
    /// </summary>
    private void Выход(float y)
    {
        var краска = Материал(new Color("#4a4238"), 0.85f);
        float пол_ширины = ПРОЁМ_ШИРИНА / 2;
        float xв = _этаж?.Гнездо("выход")?.Origin.X ?? 0.0f;

        // петля у края проёма: створка висит на ней и на ней же вертится.
        // Коробка сама себя центрирует, поэтому лист сдвинут на полширины
        _петля = new Node3D { Position = new Vector3(xв - пол_ширины, y, ЗАД) };
        AddChild(_петля);
        var лист = new StaticBody3D
        {
            Position = new Vector3(пол_ширины, ПРОЁМ_ВЕРХ / 2, 0),
        };
        var размер = new Vector3(ПРОЁМ_ШИРИНА, ПРОЁМ_ВЕРХ, 0.1f);
        лист.AddChild(new MeshInstance3D
        {
            Mesh = new BoxMesh { Size = размер },
            MaterialOverride = краска,
        });
        лист.AddChild(new CollisionShape3D { Shape = new BoxShape3D { Size = размер } });
        _петля.AddChild(лист);

        var прицел = new Area3D
        {
            Position = new Vector3(xв, y + ПРОЁМ_ВЕРХ / 2, ЗАД),
            Name = "выход",
        };
        // область в самом проёме: вылазка спрашивается и с порога,
        // и со двора — куда идти, решают там, где стоят одетым
        прицел.AddChild(new CollisionShape3D
        {
            Shape = new BoxShape3D
                { Size = new Vector3(ПРОЁМ_ШИРИНА, ПРОЁМ_ВЕРХ, 0.5f) },
        });
        AddChild(прицел);

        AddChild(new Label3D
        {
            Text = "во двор",
            FontSize = 64,
            PixelSize = 0.0032f,
            Modulate = new Color("#b8b0a0"),
            Billboard = BaseMaterial3D.BillboardModeEnum.Disabled,
            Position = new Vector3(0, y + ПРОЁМ_ВЕРХ + 0.18f, ЗАД + 0.14f),
            DoubleSided = true,
            Shaded = false,
        });

        // козырёк над крыльцом: под ним не метёт, и издали видно, где вход
        Коробка(Материал(new Color("#2f2c28"), 0.9f),
                new Vector3(2.6f, 0.14f, 1.5f),
                new Vector3(0, y + ПРОЁМ_ВЕРХ + 0.5f, ЗАД - 0.75f));
        foreach (float с in new[] { -1f, 1f })
            Коробка(Материал(new Color("#3a3732"), 0.9f),
                    new Vector3(0.12f, ПРОЁМ_ВЕРХ + 0.5f, 0.12f),
                    new Vector3(с * 1.15f, y + (ПРОЁМ_ВЕРХ + 0.5f) / 2, ЗАД - 1.4f));
    }

    private Node3D? _петля;
    private float _створка;          // насколько открыта, 0…1

    /// <summary>
    /// Открыть дверь подъезда, если к ней подошли, и закрыть, если отошли.
    /// Зовётся каждый кадр: это единственное в мире, что движется само.
    /// </summary>
    public void ДверьПодъезда(Vector3 герой, double шаг)
    {
        if (_петля is null)
            return;
        var порог = _петля.Position with { Y = герой.Y };
        bool рядом = герой.DistanceTo(порог) < 2.2f;
        _створка = Mathf.MoveToward(_створка, рядом ? 1 : 0, (float)шаг * 2.2f);
        // наружу, а не внутрь: открытая внутрь створка встала бы ровно
        // на порог, где и стоит тот, кто её открыл
        _петля.RotationDegrees = new Vector3(0, 95 * _створка, 0);
    }

    /// <summary>
    /// Габариты дома коробками — для справки в редакторе: расставлять двор
    /// вслепую нельзя, надо видеть, где стена. Считаются из тех же констант,
    /// что и сам дом, и потому разъехаться с ним не могут.
    /// </summary>
    public static IReadOnlyList<(Vector3 размер, Vector3 где)> Габариты(int этажей)
    {
        float h = ЭТАЖ * этажей;
        return new List<(Vector3, Vector3)>
        {
            (new Vector3(ДЛИНА * 2, h, ГЛУБИНА * 2), new Vector3(0, h / 2, 0)),
        };
    }

    /// <summary>Где стоят у выхода — оттуда и решают, идти ли.</summary>
    public Vector3 УВыхода => new(0, 0, ЗАД + 1.0f);

    /// <summary>
    /// Он ли уже во дворе.
    ///
    /// Двор начинается за задней стеной — но за ней же, сбоку, лежат
    /// дальние комнаты своей квартиры, и метель в них не идёт. Поэтому
    /// одной глубины мало: квартира вычитается своей полосой.
    /// </summary>
    public bool ВоДворе(Vector3 где)
    {
        if (где.Z > ЗАД - 0.3f)
            return false;
        bool в_квартире = Math.Abs(где.X) > ШИРИНА
                          && где.X * Сторона(_своя) > 0
                          && где.Z > ЗАДЬ - 0.3f;
        return !в_квартире;
    }

    /// <summary>
    /// Лестница на этаж: марш налево вверх, промежуточная площадка
    /// с окном, марш направо вверх — и ты на следующем этаже.
    ///
    /// Ступени только видимые. Твёрдый здесь пандус: `CharacterBody3D`
    /// на уступ не залезает сам, и по честным ступеням человек упирается
    /// в первую же и стоит.
    /// </summary>
    private void Лестница(StandardMaterial3D ступень, StandardMaterial3D пол,
                          float y)
    {
        float половина = ЭТАЖ / 2;
        float ширина = ШИРИНА - 0.1f;
        float х = (ШИРИНА + 0.1f) / 2;

        // Марши идут по гнёздам `марш1` и `марш2`: у гнезда значимы
        // место (низ марша), сторона шахты и длина пробега по Z.
        // Промежуточная площадка строится тут же — её в заготовке нет,
        // потому что в подвале она такая же, а заготовка одна.
        var (x1, от1, до1) = Пробег("марш1", -х, ШАГ_ВВЕРХ, ПОВОРОТ);
        var (x2, от2, до2) = Пробег("марш2", х, ПОВОРОТ, ШАГ_ВВЕРХ);

        Марш(ступень, x1, ширина, y, от1, до1);
        Коробка(пол, new Vector3(ШИРИНА * 2, 0.2f, ПЕРЁД - ПОВОРОТ),
                new Vector3(0, y + половина - 0.1f, (ПОВОРОТ + ПЕРЁД) / 2));
        Марш(ступень, x2, ширина, y + половина, от2, до2);
    }

    /// <summary>Откуда и докуда идёт марш: из гнезда, а нет гнезда —
    /// из запасных чисел.</summary>
    private (float x, float от, float до) Пробег(string гнездо, float x,
                                                 float от, float до)
    {
        if (_этаж?.Гнездо(гнездо) is not Transform3D г)
            return (x, от, до);
        float длина = г.Basis.Scale.Z;
        float знак = Mathf.Cos(г.Basis.GetEuler().Y) >= 0 ? 1 : -1;
        return (г.Origin.X, г.Origin.Z, г.Origin.Z + знак * длина);
    }

    /// <summary>Один марш: девять видимых ступеней и невидимый пандус.</summary>
    private void Марш(StandardMaterial3D материал, float x, float ширина,
                      float y, float откуда, float куда)
    {
        float подъём = ЭТАЖ / 2 / СТУПЕНЕЙ;
        float проступь = (куда - откуда) / СТУПЕНЕЙ;
        for (int с = 0; с < СТУПЕНЕЙ; с++)
        {
            float верх = y + подъём * (с + 1);
            Меш(материал,
                new Vector3(ширина, подъём + 0.06f, Mathf.Abs(проступь)),
                new Vector3(x, верх - (подъём + 0.06f) / 2,
                            откуда + проступь * (с + 0.5f)));
        }

        // пандус вдоль марша: по нему и идут
        float пробег = куда - откуда;
        float длина = Mathf.Sqrt(пробег * пробег + ЭТАЖ / 2 * (ЭТАЖ / 2));
        float угол = Mathf.Atan2(ЭТАЖ / 2, пробег);
        var пандус = new StaticBody3D
        {
            Position = new Vector3(x, y + ЭТАЖ / 4 - 0.12f, (откуда + куда) / 2),
            Rotation = new Vector3(-угол, 0, 0),
        };
        пандус.AddChild(new CollisionShape3D
        {
            Shape = new BoxShape3D { Size = new Vector3(ширина, 0.2f, длина) },
        });
        AddChild(пандус);
    }

    /// <summary>
    /// Своя квартира — двухкомнатная хрущёвка за своей дверью.
    ///
    /// Только своя: у соседей за дверьми ничего нет и быть не должно.
    /// Не из экономии — из правила. Чужая комната это чужая правда,
    /// и построить её значит однажды показать её игроку.
    ///
    /// Планировка с референса (`референсы/планировка подъезда.PNG`):
    /// прихожая сразу за дверью, кухня к наружной стене, санузел
    /// и кладовка прижаты к лестнице общим стояком, комнаты **смежные** —
    /// в дальнюю попадают только через проходную. Метраж хрущёвский:
    /// кухня 5.3, санузел 3.1, комнаты 11.2 и 14.3.
    ///
    /// Всё, что здесь меняется, приходит из `Дом.Экран.Подача.Внутри`:
    /// печь горит, если топится; на полке столько банок, сколько в шкафу;
    /// окно забито досками, если в стенах пролом.
    /// </summary>
    private void Квартира(StandardMaterial3D бетон, StandardMaterial3D пол, float y)
    {
        float с = Сторона(_своя);
        var обои = Материал(new Color("#4a4038"), 0.95f);
        var доска = Материал(new Color("#5a4a36"), 0.9f);

        // пол и потолок на всю квартиру
        float глубина = ПЕРЕДЬ - ЗАДЬ;
        Коробка(пол, new Vector3(ГЛУБЬ, 0.2f, глубина),
                Точка(с, ГЛУБЬ / 2, y - 0.1f, (ЗАДЬ + ПЕРЕДЬ) / 2));
        Коробка(обои, new Vector3(ГЛУБЬ, 0.2f, глубина),
                Точка(с, ГЛУБЬ / 2, y + ПОТОЛОК + 0.1f, (ЗАДЬ + ПЕРЕДЬ) / 2));
        // порог: между площадкой и прихожей лежит толщина стены
        Коробка(пол, new Vector3(0.7f, 0.2f, 1.1f),
                Точка(с, -0.05f, y - 0.1f, Глубина(_своя)));

        // наружные стены; окна вырезаны сразу, а не нарисованы поверх
        const float НАРУЖНАЯ = 0.22f;
        СтенаZ(бетон, с, ГЛУБЬ + 0.11f, ЗАДЬ, ПЕРЕДЬ, y, НАРУЖНАЯ);
        СтенаX(бетон, с, ЗАДЬ - 0.11f, 0, ГЛУБЬ, y, НАРУЖНАЯ,
               Оконный(1.2f, 1.2f), Оконный(4.2f, 1.6f));
        СтенаX(бетон, с, ПЕРЕДЬ + 0.11f, 0, ГЛУБЬ, y, НАРУЖНАЯ,
               Оконный(4.2f, 1.6f));
        СтенаZ(бетон, с, -0.11f, ЗАДЬ, ЗАД, y, НАРУЖНАЯ);

        // перегородки
        СтенаX(обои, с, -2.3f, 0, ПОЛОСА, y, ПЕРЕГОРОДКА, Дверной(1.2f, 0.8f));
        СтенаX(обои, с, 0.2f, 0, ПОЛОСА, y, ПЕРЕГОРОДКА,
               Дверной(0.65f, 0.7f), Дверной(1.85f, 0.7f));
        СтенаZ(обои, с, 1.3f, 0.2f, ПЕРЕДЬ, y, ПЕРЕГОРОДКА);
        СтенаZ(обои, с, ПОЛОСА, ЗАДЬ, ПЕРЕДЬ, y, ПЕРЕГОРОДКА, Дверной(-0.9f, 0.8f));
        СтенаX(обои, с, -1.4f, ПОЛОСА, ГЛУБЬ, y, ПЕРЕГОРОДКА, Дверной(4.2f, 0.8f));

        // стёкла в вырезанные проёмы
        Окно(с, ЗАДЬ - 0.11f, 1.2f, 1.2f, y);
        Окно(с, ЗАДЬ - 0.11f, 4.2f, 1.6f, y);
        Окно(с, ПЕРЕДЬ + 0.11f, 4.2f, 1.6f, y);

        // печь в прихожей, полка в проходной, матрас в дальней комнате
        _печь = Коробка(Материал(new Color("#2b2723"), 0.8f),
                        new Vector3(0.55f, 0.75f, 0.45f),
                        Точка(с, 0.45f, y + 0.375f, -1.9f));
        _огонь = new OmniLight3D
        {
            Position = Точка(с, 0.45f, y + 0.55f, -1.9f),
            LightColor = new Color("#ff9a40"),
            LightEnergy = 0.0f,
            OmniRange = 5.0f,
        };
        AddChild(_огонь);

        Полка(доска, с, y);

        Меш(Материал(new Color("#5b4a4a"), 0.95f),
            new Vector3(1.9f, 0.18f, 0.85f), Точка(с, 4.6f, y + 0.09f, -3.6f));

        // лопата в углу прихожей — из прошлых работ автора
        Модель("res://модели/лопата.fbx", Точка(с, 0.28f, y, -2.15f),
               поворот: 25, высота: 1.35f);

        _лампочка = new OmniLight3D
        {
            Position = Точка(с, 3.2f, y + ПОТОЛОК - 0.25f, 0.0f),
            LightColor = new Color("#ffe0b0"),
            LightEnergy = 0.0f,
            OmniRange = 10.0f,
        };
        AddChild(_лампочка);
    }

    // Размеры квартиры. Местная система: `lx` — вглубь от лестницы,
    // `z` — как в мире. Сторона (левая или правая) входит множителем,
    // и потому одна и та же раскладка годится обеим.
    private const float ГЛУБЬ = 6.53f;       // от лестницы до наружной стены
    private const float ПОЛОСА = 2.4f;       // ближняя полоса: быт
    private const float ЗАДЬ = -5.54f;       // задняя стена квартиры
    private const float ПЕРЕДЬ = 5.54f;      // фасад
    private const float ПОТОЛОК = ЭТАЖ - 0.2f;
    private const float ПЕРЕГОРОДКА = 0.12f;

    private static Vector3 Точка(float с, float lx, float y, float z)
        => new(с * (ШИРИНА + 0.2f + lx), y, z);

    /// <summary>Проём в стене: где по её длине, какой ширины и от какой
    /// высоты до какой. Дверь — от пола, окно — от подоконника.</summary>
    private readonly record struct Дыра(float где, float ширина,
                                        float низ, float верх);

    private static Дыра Дверной(float где, float ширина)
        => new(где, ширина, 0, 2.0f);

    private static Дыра Оконный(float где, float ширина)
        => new(где, ширина, ПОДОКОННИК, ПЕРЕМЫЧКА);

    private const float ПОДОКОННИК = 0.85f;
    private const float ПЕРЕМЫЧКА = 2.1f;

    /// <summary>
    /// Разложить стену с проёмами на куски.
    ///
    /// Дыру надо **вырезать**, а не нарисовать поверх: первая версия окна
    /// клала стекло на глухую стену, и окон в квартире не было вовсе,
    /// хотя стекло стояло и блестело. Здесь один и тот же код и для двери,
    /// и для окна.
    ///
    /// Все куски выходят положительной длины по построению — и это не
    /// придирка: коробка отрицательного размера в Godot просто не строится,
    /// движок пишет об этом в лог, а на экране остаётся мусор, по которому
    /// причину не угадать. Один раз это стоило половины вечера.
    /// </summary>
    private void Куски(float от, float до, IReadOnlyList<Дыра> дыры,
                       Action<float, float, float, float> кусок)
    {
        float край = от;
        foreach (var д in дыры.OrderBy(x => x.где))
        {
            float а = д.где - д.ширина / 2, б = д.где + д.ширина / 2;
            if (а > край)
                кусок((край + а) / 2, а - край, ПОТОЛОК / 2, ПОТОЛОК);
            if (д.низ > 0)
                кусок(д.где, д.ширина, д.низ / 2, д.низ);
            if (д.верх < ПОТОЛОК)
                кусок(д.где, д.ширина, (д.верх + ПОТОЛОК) / 2, ПОТОЛОК - д.верх);
            край = б;
        }
        if (край < до)
            кусок((край + до) / 2, до - край, ПОТОЛОК / 2, ПОТОЛОК);
    }

    /// <summary>Стена вдоль Z (поперёк квартиры), на местном отступе `lx`.</summary>
    private void СтенаZ(StandardMaterial3D м, float с, float lx, float от,
                        float до, float y, float толщина, params Дыра[] дыры)
        => Куски(от, до, дыры, (цz, длина, цy, высота) =>
            Коробка(м, new Vector3(толщина, высота, длина),
                    Точка(с, lx, y + цy, цz)));

    /// <summary>Стена поперёк Z (вдоль квартиры), на глубине `z`.</summary>
    private void СтенаX(StandardMaterial3D м, float с, float z, float от,
                        float до, float y, float толщина, params Дыра[] дыры)
        => Куски(от, до, дыры, (цx, длина, цy, высота) =>
            Коробка(м, new Vector3(длина, высота, толщина),
                    Точка(с, цx, y + цy, z)));

    /// <summary>Стекло и доски в уже вырезанный оконный проём. Доски
    /// появляются, когда в стенах пролом (ГДД 16).</summary>
    private void Окно(float с, float z, float lx, float ширина, float y)
    {
        Коробка(new StandardMaterial3D
        {
            AlbedoColor = new Color(0.72f, 0.78f, 0.84f, 0.14f),
            Transparency = BaseMaterial3D.TransparencyEnum.Alpha,
            Roughness = 0.35f,
        }, new Vector3(ширина, ПЕРЕМЫЧКА - ПОДОКОННИК, 0.05f),
           Точка(с, lx, y + (ПОДОКОННИК + ПЕРЕМЫЧКА) / 2, z));

        _доски ??= new List<MeshInstance3D>();
        for (int i = 0; i < 3; i++)
        {
            var д = new MeshInstance3D
            {
                Mesh = new BoxMesh
                    { Size = new Vector3(ширина + 0.2f, 0.22f, 0.07f) },
                MaterialOverride = Материал(new Color("#4a3a26"), 0.95f),
                Position = Точка(с, lx, y + ПОДОКОННИК + 0.22f + i * 0.42f, z)
                           + new Vector3(0, 0, z < 0 ? 0.16f : -0.16f),
                Visible = false,
            };
            AddChild(д);
            _доски.Add(д);
        }
    }

    /// <summary>Полка в проходной: по ряду на ресурс, банок столько,
    /// сколько в шкафу.</summary>
    private void Полка(StandardMaterial3D доска, float с, float y)
    {
        float lx = ГЛУБЬ - 0.35f;
        for (int ряд = 0; ряд < РЕСУРСЫ.Length; ряд++)
        {
            float ly = 0.45f + ряд * 0.33f;
            Меш(доска, new Vector3(0.4f, 0.05f, 2.2f), Точка(с, lx, y + ly, 0.9f));
            var полка = new List<MeshInstance3D>();
            for (int i = 0; i < 8; i++)
            {
                var банка = new MeshInstance3D
                {
                    Mesh = new BoxMesh { Size = new Vector3(0.12f, 0.16f, 0.12f) },
                    MaterialOverride = Материал(РЕСУРС[ряд], 0.6f),
                    Position = Точка(с, lx, y + ly + 0.105f, -0.05f + i * 0.27f),
                    Visible = false,
                };
                AddChild(банка);
                полка.Add(банка);
            }
            _полки.Add(полка);
        }
    }

    /// <summary>Что дома: печь, свет, полка, забитое окно.</summary>
    public void Дома(Дом.Экран.Комната что)
    {
        if (_огонь is null)
            return;
        _огонь.LightEnergy = что.топится ? 2.6f : (что.печь ? 0.2f : 0.0f);
        if (_лампочка is not null)
            _лампочка.LightEnergy = что.свет ? 2.4f : 0.0f;

        for (int ряд = 0; ряд < _полки.Count; ряд++)
        {
            double сколько = что.шкаф
                .Where(з => з.ресурс == РЕСУРСЫ[ряд])
                .Select(з => з.сколько).DefaultIfEmpty(0).First();
            for (int i = 0; i < _полки[ряд].Count; i++)
                _полки[ряд][i].Visible = i < сколько;
        }

        foreach (var д in _доски ?? new List<MeshInstance3D>())
            д.Visible = что.дыр > 0;
    }

    private int _своя = 1;
    private StaticBody3D? _печь;
    private OmniLight3D? _огонь;
    private OmniLight3D? _лампочка;
    private List<MeshInstance3D>? _доски;
    private readonly List<List<MeshInstance3D>> _полки = new();

    private const float КОМНАТА = 5.0f;

    /// <summary>По полке на ресурс, в том же порядке, в каком их печатает
    /// состояние. Порядок здесь — договор с `Дом.Экран`: строки шкафа
    /// приходят отсортированными, и полка ищет свою по имени, а не
    /// по номеру.</summary>
    private static readonly string[] РЕСУРСЫ =
        { "вода", "деньги", "еда", "лекарства", "материалы", "топливо" };

    private static readonly Color[] РЕСУРС =
    {
        new("#6a8ea8"), new("#8a8a6a"), new("#8a6a4a"),
        new("#a86a6a"), new("#7a7a80"), new("#5a4a38"),
    };

    /// <summary>
    /// Щель света понизу. Единственное, что видно снаружи о чужом тепле:
    /// у соседа работает генератор — значит, из-под двери светит.
    /// </summary>
    private MeshInstance3D Щель(Vector3 дверь, float в_дом)
    {
        var м = new MeshInstance3D
        {
            Mesh = new BoxMesh { Size = new Vector3(0.05f, 0.03f, 0.85f) },
            MaterialOverride = new StandardMaterial3D
            {
                AlbedoColor = new Color("#ffd79a"),
                EmissionEnabled = true,
                Emission = new Color("#ffd79a"),
                EmissionEnergyMultiplier = 2.0f,
                ShadingMode = BaseMaterial3D.ShadingModeEnum.Unshaded,
