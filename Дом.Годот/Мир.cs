    /// <summary>
    /// Точки расстановки из `двор.tscn` — то, что автор двигает в редакторе.
    ///
    /// Дом строится по данным (`npcs.json` решает, где какая дверь), и
    /// двигать его мышью нельзя: сдвинется расселение — разъедется всё.
    /// А двор по данным не строится, и раньше его вещи стояли числами прямо
    /// в этом файле — то есть поправить дерево можно было только правкой
    /// кода и пересборкой.
    ///
    /// Теперь их место живёт в сцене. Мир читает **только положение,
    /// поворот и размер** точки; чем она станет, решает её имя:
    ///
    ///   · `погреб6`, `гараж13` — кладовая с таким `id` из данных дома.
    ///     Имени нет в доме — точка не годится, и об этом пишется в лог;
    ///     кладовая, которой не нашлось точки, встаёт в запасной ряд;
    ///   · `дерево…` — мёртвое дерево; высота берётся из `scale.Y`,
    ///     а какое из трёх — из последней цифры имени;
    ///   · `сугроб…` — сугроб; размер берётся из `scale` прямо в метрах.
    ///
    /// Точек можно добавлять сколько угодно: имена читаются по началу,
    /// а не по списку. Сцены нет или она пуста — двор строится по запасной
    /// расстановке, той же, что была в коде.
    /// </summary>
    private readonly List<(string имя, Transform3D где)> _точки = new();

    private const string ДВОР_СЦЕНА = "res://двор.tscn";

    private void Точки()
    {
        _точки.Clear();
        var сцена = ResourceLoader.Exists(ДВОР_СЦЕНА)
                    ? GD.Load<PackedScene>(ДВОР_СЦЕНА) : null;
        if (сцена is null)
            return;
        var корень = сцена.Instantiate<Node3D>();
        foreach (var у in корень.GetChildren())
            if (у is Node3D точка)
                _точки.Add((точка.Name.ToString(), точка.Transform));
        корень.QueueFree();
        // одна строка в лог, и она нужна: подвинув что-то в редакторе,
        // первым делом хочется знать, что игра это прочла
        GD.Print($"двор: {_точки.Count} точек из {ДВОР_СЦЕНА}");
    }

    /// <summary>Точки, чьё имя начинается на это слово, — по порядку сцены.</summary>
    private IEnumerable<(string имя, Transform3D где)> Точки(string начало)
        => _точки.Where(т => т.имя.StartsWith(начало, StringComparison.Ordinal));

    /// <summary>Высота коробки по её масштабу: точка в сцене растягивается
    /// мышью, и растянутой она и станет.</summary>
    private static Vector3 Размер(Transform3D где) => где.Basis.Scale;

    private static float Угол(Transform3D где)
        => Mathf.RadToDeg(где.Basis.GetEuler().Y);

    // -------------------------------------------------------- заготовки

    /// <summary>
    /// Прочитанная сцена-заготовка: коробки и гнёзда.
    ///
    /// Уговор один на все заготовки: **коробка становится стеной, точка —
    /// гнездом**. У коробки берётся размер меша, помноженный на масштаб
    /// узла, — значит её тянут мышью, и такой она и встанет. У точки
    /// значимы место и поворот, а чем она станет, решает имя.
    ///
    /// Материал выбирается по началу имени: `пол…`, `ступень…`, `обои…`,
    /// `доска…`, `стекло…`, `снег…`, всё прочее — бетон. Имя, начинающееся
    /// на `вид`, ставится без формы: сквозь него ходят.
    /// </summary>
    private sealed class Заготовка
    {
        public readonly List<(string имя, Vector3 размер, Transform3D где)> коробки
            = new();
        public readonly List<(string имя, Transform3D где)> гнёзда = new();

        public bool Пуста => коробки.Count == 0 && гнёзда.Count == 0;

        public Transform3D? Гнездо(string имя)
        {
            foreach (var (и, где) in гнёзда)
                if (string.Equals(и, имя, StringComparison.Ordinal))
                    return где;
            return null;
        }
    }

    private static Заготовка Прочитать(string путь)
    {
        var з = new Заготовка();
        if (!ResourceLoader.Exists(путь))
        {
            GD.PrintErr($"нет заготовки {путь}");
            return з;
        }
        var сцена = GD.Load<PackedScene>(путь);
        if (сцена is null)
            return з;
        var к = сцена.Instantiate<Node3D>();
        Разобрать(к, Transform3D.Identity, з);
        к.QueueFree();
        GD.Print($"{путь}: {з.коробки.Count} коробок, {з.гнёзда.Count} гнёзд");
        return з;
    }

    private static void Разобрать(Node узел, Transform3D выше, Заготовка з)
    {
        foreach (var у in узел.GetChildren())
        {
            if (у is not Node3D т)
                continue;
            var где = выше * т.Transform;
            if (т is MeshInstance3D м && м.Mesh is BoxMesh к)
                з.коробки.Add((т.Name.ToString(), к.Size * где.Basis.Scale, где));
            else if (т is Marker3D)
                з.гнёзда.Add((т.Name.ToString(), где));
            Разобрать(т, где, з);
        }
    }

    /// <summary>
    /// Поставить коробки заготовки, подняв их на высоту этажа.
    ///
    /// `без` — начало имени, которое на этот раз не ставится: на верхнем
    /// этаже не нужны куски марша, которого там нет.
    /// </summary>
    private void Поставить(Заготовка з, float y, string? без = null)
    {
        foreach (var (имя, размер, где) in з.коробки)
        {
            if (без is not null && имя.StartsWith(без, StringComparison.Ordinal))
                continue;
            if (размер.X <= 0 || размер.Y <= 0 || размер.Z <= 0)
            {
                // Godot такую коробку не строит, пишет об этом в свой лог
                // и продолжает; на экране остаётся мусор, по которому
                // причину не угадать. Лучше сказать прямо и своими словами
                GD.PrintErr($"заготовка: у «{имя}» размер {размер} — не коробка");
                continue;
            }
            var точка = где.Origin with { Y = где.Origin.Y + y };
            float угол = Mathf.RadToDeg(где.Basis.GetEuler().Y);
            if (имя.StartsWith("вид", StringComparison.Ordinal))
                Меш(Краска(имя), размер, точка);
            else
                Куча(Краска(имя), размер, точка, угол);
        }
    }

    /// <summary>Из чего сделана коробка — по началу её имени.</summary>
    private StandardMaterial3D Краска(string имя)
    {
        string и = имя.StartsWith("вид", StringComparison.Ordinal) ? имя[3..] : имя;
        и = и.TrimStart('_');
        if (и.StartsWith("пол", StringComparison.Ordinal))
            return Материал(new Color("#2b2926"), 0.9f);
        if (и.StartsWith("ступень", StringComparison.Ordinal))
            return Материал(new Color("#4a4843"), 0.9f);
        if (и.StartsWith("обои", StringComparison.Ordinal))
            return Материал(new Color("#4a4038"), 0.95f);
        if (и.StartsWith("доска", StringComparison.Ordinal))
            return Материал(new Color("#5a4a36"), 0.9f);
        if (и.StartsWith("стекло", StringComparison.Ordinal))
            return Стекло();
        if (и.StartsWith("снег", StringComparison.Ordinal))
            return Материал(new Color("#b4bcc2"), 1.0f);
        return Материал(new Color("#3a3a36"), 0.95f);
    }

    private static StandardMaterial3D Материал(Color цвет, float шершавость)
        => new()
        {
            AlbedoColor = цвет,
            Roughness = шершавость,
            Metallic = 0.0f,
        };
