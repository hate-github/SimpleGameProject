// Подъезд и квартира (ГДД 15, 23): хрущёвская секция, пять этажей.
//
// Это не декорация к диалоговому окну. Игра — от первого лица: человек
// стоит на своей площадке, выходит к лестнице, поднимается, стучится
// в чужую дверь. Всё, что до сих пор было списком строк, здесь становится
// местом, по которому ходят.
//
// Геометрия строится **из данных дома**, а не лежит в сцене: этажи
// и квартиры берутся из `npcs.json`. Сдвинется расселение — сдвинется
// и дом, и это не удобство, а то же правило, что везде: одно место правды.
//
// **Планировка настоящая, а не «похожая».** Секция 1-464 (референс лежит
// рядом с проектом, `референсы/планировка подъезда.PNG`): лестничная
// клетка посередине, четыре квартиры вокруг неё, кухни у наружных стен,
// санузлы прижаты к лестнице общим стояком.
//
// Числа хрущёвки, и каждое из них — характер, а не мелочь:
//
//   · **потолок 2.6 м** (этаж 2.8). Полметра разницы с обычными тремя —
//     это и есть хрущёвка: низко, и это чувствуется до того, как
//     посмотришь на мебель;
//   · **площадка 2.9 × 2.2 м** на четыре двери. Тесно; разойтись вдвоём
//     можно, втроём уже нет;
//   · **два марша по восемь ступеней** — три метра одним маршем в такую
//     шахту не влезают;
//   · **кухня 5.3 м², санузел совмещённый 3.1, комнаты смежные** (11.2
//     проходит только через 14.3) — то самое, из-за чего в этих квартирах
//     невозможно разъехаться, не поссорившись.
//
// Первая версия ставила один марш в двадцать ступеней на всю глубину
// площадки: получалась отвесная стена, занимавшая почти весь пол, —
// герой оказывался внутри неё и видел ровный серый цвет.
//
// Ходить по ступеням тоже пришлось чинить. `CharacterBody3D` в Godot 4
// сам на уступ не залезает — упирается и стоит. Поэтому ступени здесь
// **видимые, но не твёрдые**, а идёт человек по невидимому пандусу вдоль
// марша. Приём известный; записан потому, что глядя на сцену его не видно.
//
// **Коробка отрицательного размера не строится.** Godot пишет об этом
// в лог и оставляет на экране мусор, по которому причину не угадать:
// при первой хрущёвской переделке окно осталось шире шахты, простенки
// ушли в минус, и полвечера ушло на разглядывание кадров, хотя движок
// всё это время писал `set_size ... box_shape_3d.cpp`. Отсюда правило:
// **сначала лог движка, потом скриншот** — и все куски стен считаются
// так, чтобы длина выходила положительной по построению (`Куски`).
//
// Low poly здесь буквальный: коробки и один материал на вид поверхности.
// Ни одной модели, ни одной текстуры — их сделает художник, и заменит он
// меши, а не то, где какая дверь. Пока это серый бетон, и он честнее
// картинки, которой нет.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

/// <summary>
/// Дверь квартиры: к ней подходят, в неё стучат, и она рассказывает.
///
/// Всё, что здесь хранится сверх узла, — это чем дверь **говорит**:
/// своя краска (общий материал перекрасить нельзя — перекрасятся все
/// двадцать), щель света понизу и зарубка на косяке от прошлой жизни.
/// </summary>
public sealed record ДверьКвартиры(
    int квартира,
    StaticBody3D узел,
    Vector3 перед,
    float в_дом,
    StandardMaterial3D краска,
    MeshInstance3D щель,
    MeshInstance3D зарубка);

public partial class Мир : Node3D
{
    /// <summary>Высота этажа. Три метра — чтобы лестница читалась,
    /// и чтобы человек не бился головой.</summary>
    public const float ЭТАЖ = 2.8f;

    // Размеры секции — по плану автора (серия 1-464, оси 1–7 и А–В):
    // 16.8 на 11.52 метра. Первая сборка была 15.7 на 7.5, то есть
    // вчетверо меньше по площади этажа, и квартиры выходили по 25 м²
    // вместо хрущёвских сорока.
    private const float ДЛИНА = 8.4f;        // полдлины секции по X
    private const float ГЛУБИНА = 5.76f;     // полглубины секции по Z

    private const float ШИРИНА = 1.45f;      // полширины шахты
    private const float ЗАД = -5.56f;        // задняя стена площадки, она же вход

    /// <summary>Где порог входной двери — для отладочного переноса.</summary>
    public const float У_ПОРОГА = ЗАД + 1.4f;
    private const float ШАГ_ВВЕРХ = -2.70f;  // где кончается площадка, начинается марш
    private const float ПОВОРОТ = -0.54f;    // где марш переходит в промежуточную
    private const float ПЕРЁД = 0.56f;       // передняя стена шахты
    private const int СТУПЕНЕЙ = 8;         // на марш; два марша на этаж

    private readonly List<ДверьКвартиры> _двери = new();
    private readonly List<OmniLight3D> _лампы = new();

    public IReadOnlyList<ДверьКвартиры> двери => _двери;

    /// <summary>
    /// Где стоит человек в начале: он только что вышел из своей квартиры,
    /// стоит у своей двери спиной к ней.
    ///
    /// Не в середине площадки: середина ничего не говорит. У своей двери
    /// в кадр попадают напротив — две чужие двери с номерами, справа или
    /// слева — проём лестницы, за спиной — своя. Это и есть первое, что
    /// игра должна сказать без единого слова: ты в подъезде, и вокруг
    /// живут люди.
    /// </summary>
    public Vector3 Начало(int квартира)
        => new(Сторона(квартира) * 0.7f,
               ЭТАЖ * (Этаж(квартира) - 1) + 0.15f,
               Глубина(квартира));

    /// <summary>Куда смотрит в начале: поперёк площадки, от своей двери.
    /// Godot считает «вперёд» вдоль −Z, поэтому взгляд вдоль +X — это
    /// поворот на −90°.</summary>
    public static float Поворот(int квартира)
        => Сторона(квартира) < 0 ? -Mathf.Pi / 2 : Mathf.Pi / 2;

    /// <summary>По какой стене дверь: слева (−1) или справа (+1).</summary>
    private static float Сторона(int квартира) => (квартира - 1) % 4 < 2 ? -1 : 1;

    /// <summary>
    /// Где по глубине стоит дверь этой квартиры — из гнезда заготовки.
    ///
    /// Четыре гнезда на этаж, `дверь0`…`дверь3`, и порядок их значим:
    /// первые два — по левой стене, вторые два — по правой, как и считает
    /// <see cref="Сторона"/>. Гнезда нет — берётся запасное число,
    /// чтобы дом строился и без сцены.
    /// </summary>
    private float Глубина(int квартира)
        => _этаж?.Гнездо($"дверь{(квартира - 1) % 4}")?.Origin.Z
           ?? ((квартира - 1) % 4 % 2 == 0 ? ЗАД + 0.7f : ЗАД + 1.9f);

    private Заготовка? _этаж;

    private const string ЭТАЖ_СЦЕНА = "res://этаж.tscn";

    /// <summary>Точка за окном на высоте героя: туда ставится метель.
    /// Снег должен лететь снаружи, а не сквозь стены, — иначе он читается
    /// не как буран, а как грязь на камере.</summary>
    public Vector3 Снаружи(Vector3 где)
        => ВоДворе(где)
           ? где with { Y = где.Y + 11.0f }     // во дворе метель вокруг тебя
           : new Vector3(0.0f, где.Y + 6.0f, ПЕРЁД + 7.0f);

    public static int Этаж(int квартира) => (квартира - 1) / 4 + 1;

    /// <summary>Построить подъезд по дому. `своя` — квартира героя:
    /// у неё одной дверь открыта и за ней есть комната.</summary>
    public void Построить(House h, int своя)
    {
        _двери.Clear();
        _лампы.Clear();
        _своя = своя;
        _полки.Clear();
        Точки();

        int этажей = h.flats.Значения.Select(f => f.floor).DefaultIfEmpty(5).Max();
        float высота = ЭТАЖ * этажей;

        var бетон = Материал(new Color("#3a3a36"), 0.95f);
        var пол = Материал(new Color("#2b2926"), 0.9f);
        var ступень = Материал(new Color("#4a4843"), 0.9f);

        // Подъезд — не числа в этом файле, а заготовка `этаж.tscn`: стены,
        // плиты и гнёзда дверей, которые двигают мышью в редакторе.
        // Из данных приходит одно — **какой номер за какой дверью**;
        // это расселение, и его руками не двигают.
        _этаж = Прочитать(ЭТАЖ_СЦЕНА);
        ЗадняяСтена(бетон, высота);

        for (int э = 1; э <= этажей; э++)
        {
            float y = ЭТАЖ * (э - 1);

            // На верхнем этаже марша вверх нет — значит нет и того,
            // что к нему относится
            Поставить(_этаж, y, э == этажей ? "марш" : null);

            Двери(h, э, y);
            if (э == 1)
                Выход(y);

            if (Этаж(_своя) == э)
                Квартира(бетон, пол, y);

            if (э < этажей)
                Лестница(ступень, пол, y);
            else                                     // крыша над последним
                Коробка(бетон, new Vector3(ШИРИНА * 2, 0.2f, ПЕРЁД - ЗАД),
                        new Vector3(0, y + ЭТАЖ + 0.1f, (ЗАД + ПЕРЁД) / 2));

            Лампа(э, y);
        }

        Оболочка(бетон, этажей);
        Подвал(h, бетон, пол, ступень);
        Двор();
        Гаражи();
    }

    /// <summary>
    /// Подвал: лестница вниз и погреба за отдельными дверьми.
    ///
    /// Это не выдумка ради места, а то, что дом про себя говорит сам.
    /// `balance.json`, `_кладовые`: «Погреб в подвале и гараж за домом…
    /// Погреб внутри дома — туда спускаются и в буран, и с ребёнком
    /// на руках; гараж — это улица». Симуляция так и считает: часы гаража
    /// умножаются на погоду, часы погреба нет; гараж закрывается тем же,
    /// чем вылазка, погреб не закрывается ничем.
    ///
    /// Первая версия поставила и то и другое во дворе — то есть построила
    /// мир против того, что в данных написано словами. Гаражи уехали
    /// в кооператив за домом (туда ходят вылазкой, `Улица.МЕСТА`),
    /// а погреба спустились сюда.
    ///
    /// Лестница вниз — та же, что вверх, только на этаж ниже: её второй
    /// марш заканчивается у края площадки первого этажа, и потому спуск
    /// получается сам собой, без отдельной дыры в перекрытии.
    /// </summary>
    private void Подвал(House h, StandardMaterial3D бетон, StandardMaterial3D пол,
                        StandardMaterial3D ступень)
    {
        float y = -ЭТАЖ;

        // пол подвала и стены вокруг шахты
        Коробка(пол, new Vector3(ШИРИНА * 2, 0.2f, ПЕРЁД - ЗАД),
                new Vector3(0, y - 0.1f, (ЗАД + ПЕРЁД) / 2));
        foreach (float с in new[] { -1f, 1f })
            СтенаПодвала(бетон, с, y);
        Коробка(бетон, new Vector3(ШИРИНА * 2 + 0.4f, ЭТАЖ, 0.2f),
                new Vector3(0, y + ЭТАЖ / 2, ЗАД - 0.1f));
        Коробка(бетон, new Vector3(ШИРИНА * 2 + 0.4f, ЭТАЖ, 0.2f),
                new Vector3(0, y + ЭТАЖ / 2, ПЕРЁД + 0.1f));

        Лестница(ступень, пол, y);

        // Две лампочки под потолком, и тусклее, чем на площадке. Совсем
        // темнить нельзя: номер квартиры на двери должен читаться, иначе
        // погреба неотличимы друг от друга и подойти «к своему» невозможно.
        foreach (float z in new[] { ЗАД + 1.2f, ЗАД + 3.4f })
            AddChild(new OmniLight3D
            {
                Position = new Vector3(0, y + ЭТАЖ - 0.4f, z),
                LightColor = new Color("#ffd49a"),
                LightEnergy = 1.0f,
                OmniRange = 7.5f,
            });

        // погреба по стенам коридора: по одному на каждый из данных дома
        var погреба = h.кладовые.Значения
            .Where(к => к.вид == ВидКладовой.ПОГРЕБ)
            .OrderBy(к => к.apt).ToList();
        for (int i = 0; i < погреба.Count; i++)
        {
            float с = i % 2 == 0 ? -1 : 1;
            float z = ЗАД + 0.9f + (i / 2) * 1.5f;
            ДверьПогреба(погреба[i], с, y, z);
        }
    }

    /// <summary>Боковая стена подвала — глухая, без проёма в квартиру:
    /// внизу квартир нет, там чужие замки.</summary>
    private void СтенаПодвала(StandardMaterial3D бетон, float с, float y)
        => Коробка(бетон, new Vector3(0.2f, ЭТАЖ, ПЕРЁД - ЗАД),
                   new Vector3(с * (ШИРИНА + 0.1f), y + ЭТАЖ / 2,
                               (ЗАД + ПЕРЁД) / 2));

    /// <summary>
    /// Дверь погреба: узкая, из досок, с номером квартиры.
    ///
    /// Работает она ровно как квартирная — тело с именем, по которому
    /// луч её узнаёт. Ключ от неё у хозяина, и это решает симуляция,
    /// а не дверь: подойти можно к любой, откроется своя.
    /// </summary>
    private void ДверьПогреба(Кладовая к, float с, float y, float z)
    {
        var доска = Материал(new Color("#5a4a36"), 0.9f);
        var место = new Vector3(с * (ШИРИНА - 0.07f), y + 0.95f, z);
        var узел = Коробка(доска, new Vector3(0.12f, 1.9f, 0.8f), место);
        узел.Name = $"кладовая{к.id}";

        узел.AddChild(new Label3D
        {
            Text = к.apt.ToString(System.Globalization.CultureInfo.InvariantCulture),
            FontSize = 96,
            PixelSize = 0.0026f,
            Modulate = new Color("#cfc6b0"),
            Billboard = BaseMaterial3D.BillboardModeEnum.Disabled,
            Position = new Vector3(-с * 0.09f, 0.62f, 0),
            RotationDegrees = new Vector3(0, -с * 90, 0),
            DoubleSided = true,
            Shaded = false,
        });
    }

    /// <summary>
    /// Гаражный кооператив за домом — видом, а не местом.
    ///
    /// В симуляции гараж это улица: ходят туда вылазкой («гаражи за домом»
    /// в `Улица.МЕСТА`), и потому подойти к нему ногами со двора нельзя —
    /// двор кончается сугробами. Но ряд ворот за ними виден, и этого
    /// довольно: место, куда ходят, должно быть видно.
    /// </summary>
    private void Гаражи()
    {
        var кирпич = Материал(new Color("#6a5348"), 0.95f);
        var снег = Материал(new Color("#b4bcc2"), 1.0f);
        var ворота = new[]
        {
            new Color("#7a3b2e"), new Color("#8a5a34"), new Color("#5a6470"),
            new Color("#6a4038"), new Color("#96622f"), new Color("#4a5560"),
        };

        const float Z = -17.5f;
        const float ШИР = 3.2f, ГЛУБ = 6.0f, ВЫС = 2.6f;
        for (int i = 0; i < 9; i++)
        {
            float x = -12.8f + i * ШИР;
            Меш(кирпич, new Vector3(ШИР - 0.06f, ВЫС, ГЛУБ),
                new Vector3(x, ВЫС / 2, Z));
            Меш(снег, new Vector3(ШИР + 0.1f, 0.2f, ГЛУБ + 0.2f),
                new Vector3(x, ВЫС + 0.1f, Z));
            Меш(Материал(ворота[i % ворота.Length], 0.8f),
                new Vector3(ШИР - 0.85f, ВЫС - 0.5f, 0.1f),
                new Vector3(x, (ВЫС - 0.5f) / 2, Z + ГЛУБ / 2 + 0.06f));
        }
    }


    /// <summary>
    /// Наружные стены дома — те, что видно со двора.
    ///
    /// Внутри построена **только своя квартира**, и это правило остаётся:
    /// чужая комната — чужая правда. Но пока во двор нельзя было выйти,
    /// из этого следовало, что дома снаружи нет вовсе: одна квартира
    /// висела в воздухе сбоку от лестничной шахты, и всё.
    ///
    /// Оболочка — не чужие квартиры, а наружные плоскости дома: их видит
    /// всякий, кто стоит во дворе, и знания о соседях в них нет ни грамма.
    /// Окна тёмные и непрозрачные: что за ними, узнают, постучав.
    /// Свой этаж пропускается — там стоят настоящие стены, и вторые
    /// в тех же плоскостях мерцали бы.
    /// </summary>
    private void Оболочка(StandardMaterial3D бетон, int этажей)
    {
        var стекло = Материал(new Color("#16181a"), 0.5f);
        float глубина = ПЕРЕДЬ - ЗАДЬ;

        foreach (float с in new[] { -1f, 1f })
            for (int э = 1; э <= этажей; э++)
            {
                float y = ЭТАЖ * (э - 1);
                if (с == Сторона(_своя) && э == Этаж(_своя))
                    continue;

                // перекрытие и наружные стены — те же, что у своей квартиры
                Коробка(бетон, new Vector3(ГЛУБЬ, 0.2f, глубина),
                        Точка(с, ГЛУБЬ / 2, y - 0.1f, (ЗАДЬ + ПЕРЕДЬ) / 2));
                СтенаZ(бетон, с, ГЛУБЬ + 0.11f, ЗАДЬ, ПЕРЕДЬ, y, 0.22f);
                СтенаX(бетон, с, ЗАДЬ - 0.11f, 0, ГЛУБЬ, y, 0.22f,
                       Оконный(1.2f, 1.2f), Оконный(4.2f, 1.6f));
                СтенаX(бетон, с, ПЕРЕДЬ + 0.11f, 0, ГЛУБЬ, y, 0.22f,
                       Оконный(4.2f, 1.6f));
                СтенаZ(бетон, с, -0.11f, ЗАДЬ, ЗАД, y, 0.22f);

                foreach (var (z, lx, ш) in new (float, float, float)[]
                         { (ЗАДЬ - 0.11f, 1.2f, 1.2f), (ЗАДЬ - 0.11f, 4.2f, 1.6f),
                           (ПЕРЕДЬ + 0.11f, 4.2f, 1.6f) })
                    Коробка(стекло, new Vector3(ш, ПЕРЕМЫЧКА - ПОДОКОННИК, 0.05f),
                            Точка(с, lx, y + (ПОДОКОННИК + ПЕРЕМЫЧКА) / 2, z));
            }

        // крыша над крыльями
        foreach (float с in new[] { -1f, 1f })
            Коробка(бетон, new Vector3(ГЛУБЬ + 0.22f, 0.24f, глубина + 0.22f),
                    Точка(с, ГЛУБЬ / 2, ЭТАЖ * этажей + 0.12f,
                          (ЗАДЬ + ПЕРЕДЬ) / 2));
    }

    /// <summary>
    /// Двор: земля и мёртвые деревья за окнами.
    ///
    /// Ходить туда нельзя — двора как места ещё нет, и выхода из подъезда
    /// тоже. Но смотреть в окно на голый двор в метель можно, и это уже
    /// половина того, зачем окно нужно. Деревья стоят редко: в буран
    /// дальше двадцати метров всё равно ничего не видно.
    /// </summary>
    private void Двор()
    {
        // Земля твёрдая: раньше это был один меш без формы — смотреть
        // из окна на него можно было, встать на него нельзя.
        //
        // И она снежная, а не земляная. Снегу намело по порог — потому
        // и крыльца нет: за тридцать дней бурана двор поднялся до уровня
        // пола. Цвет холодный и тусклый: чистого белого в метель не бывает,
        // света нет вовсе.
        Земля(Материал(new Color("#8e969c"), 1.0f));

        // утоптанный пятачок под козырьком: тут ходят, и снег сбит до грязи
        Коробка(Материал(new Color("#5a5c5a"), 1.0f),
                new Vector3(3.2f, 0.1f, 2.6f), new Vector3(0, -0.05f, ЗАД - 1.3f));

        Сугробы();
        Деревья();
    }

    /// <summary>Мёртвые деревья во дворе — по точкам сцены, а если сцены
    /// нет, по запасной расстановке. Ближе двенадцати метров к дому их
    /// не ставят: разлёт ветвей метров девять, и в пяти они прошивают
    /// стену и висят посреди комнаты.</summary>
    private void Деревья()
    {
        // Запасная расстановка — только если сцены нет вовсе. Иначе
        // удалённое в редакторе дерево возвращалось бы обратно, и убрать
        // его было бы нельзя: пустой список читался бы как «нет сцены».
        if (_точки.Count > 0)
        {
            foreach (var (имя, где) in Точки("дерево"))
            {
                int какое = имя.Length > 0 && char.IsDigit(имя[^1])
                            ? (имя[^1] - '0') % 3 : 0;
                Модель("res://модели/деревья_мёртвые.fbx",
                       где.Origin, поворот: Угол(где),
                       высота: 4.2f * Math.Max(0.2f, Размер(где).Y), какое: какое);
            }
            return;
        }
        var запас = new (float x, float z)[]
        {
            (4.0f, 17.0f), (-8.0f, 21.0f), (15.0f, 14.0f), (-17.0f, 12.0f),
            (-6.0f, -18.0f), (13.0f, -17.0f), (21.0f, 2.0f), (-21.0f, -5.0f),
        };
        int i = 0;
        foreach (var (x, z) in запас)
        {
            Модель("res://модели/деревья_мёртвые.fbx", new Vector3(x, 0, z),
                   поворот: 37 * i, высота: 4.2f + (i % 3) * 0.7f, какое: i % 3);
            i++;
        }
    }

    /// <summary>
    /// Земля двора — четырьмя плитами вокруг шахты, а не одной на всё.
    ///
    /// Под домом подвал, и плита во весь двор залила бы его: восемьдесят
    /// метров земли на высоте пола проходят ровно там, где лестница уходит
    /// вниз. Вырез приходится на шахту целиком — он внутри дома, и снаружи
    /// его не видно.
    /// </summary>
    private void Земля(StandardMaterial3D земля)
    {
        const float К = 40.0f;                       // полразмера двора
        float x0 = ШИРИНА + 0.3f, z0 = ЗАД - 0.3f, z1 = ПЕРЁД + 0.3f;

        Коробка(земля, new Vector3(К * 2, 0.2f, К + z0),
                new Vector3(0, -0.11f, (-К + z0) / 2));
        Коробка(земля, new Vector3(К * 2, 0.2f, К - z1),
                new Vector3(0, -0.11f, (z1 + К) / 2));
        foreach (float с in new[] { -1f, 1f })
            Коробка(земля, new Vector3(К - x0, 0.2f, z1 - z0),
                    new Vector3(с * (К + x0) / 2, -0.11f, (z0 + z1) / 2));
    }

    /// <summary>
    /// Кольцо сугробов вокруг двора.
    ///
    /// Границу двору ставить чем-то надо: восемьдесят метров ровного поля
    /// в метель — это не двор, а пустота, по которой уходят и не
    /// возвращаются. Невидимая стена соврала бы; сугроб выше человека
    /// на тридцатый день бурана — не соврёт. За ним видны деревья,
    /// и потому кольцо не читается как коробка.
    /// </summary>
    private void Сугробы()
    {
        var снег = Материал(new Color("#b4bcc2"), 1.0f);
        const float ДВОР = 13.0f;       // полуширина двора
        int i = 0;

        // Кольцо набирается кусками разной высоты и в разворот: один
        // длинный ящик читается стеной, а сугроб — не стена. Высота ходит
        // от полутора до двух с половиной метров: перелезть нельзя,
        // но и не отвес.
        foreach (float с in new[] { -1f, 1f })
            for (float t_ = -ДВОР - 1; t_ <= ДВОР + 1; t_ += 2.4f)
            {
                float h1 = 1.5f + 0.32f * ((i * 7) % 4);
                float h2 = 1.5f + 0.32f * ((i * 5 + 2) % 4);
                Куча(снег, new Vector3(2.9f, h1, 2.6f),
                     new Vector3(t_, h1 / 2 - 0.7f, с * ДВОР), 11 * (i % 5));
                Куча(снег, new Vector3(2.6f, h2, 2.9f),
                     new Vector3(с * ДВОР, h2 / 2 - 0.7f, t_), 9 * (i % 4));
                i++;
            }

        // Намело и к стенам — но эти кучи уже расставляются мышью:
        // кольцо держит границу и потому считается, а что лежит внутри
        // двора, автор раскладывает сам.
        if (_точки.Count > 0)
        {
            foreach (var (_, где) in Точки("сугроб"))
            {
                var р = Размер(где);
                Куча(снег, р, где.Origin with { Y = где.Origin.Y + р.Y / 2 },
                     Угол(где));
            }
            return;
        }
        foreach (var (x, z, ш, в) in new (float, float, float, float)[]
                 { (-4.2f, ЗАД - 0.9f, 3.4f, 1.3f), (4.2f, ЗАД - 0.9f, 3.4f, 1.1f),
                   (-2.6f, ЗАД - 2.6f, 1.6f, 0.6f), (2.9f, ЗАД - 2.2f, 1.4f, 0.5f) })
            Куча(снег, new Vector3(ш, в, 1.6f), new Vector3(x, в / 2 - 0.25f, z), 7);
    }

    /// <summary>Сугроб: коробка, повёрнутая вокруг своей оси. Поворот
    /// на узле, а не в размере, — форме он применяется вместе с узлом.</summary>
    private void Куча(StandardMaterial3D м, Vector3 размер, Vector3 где, float угол)
    {
        var к = Коробка(м, размер, где);
        к.RotationDegrees = new Vector3(0, угол, 0);
    }

    /// <summary>
    /// Поставить модель из `модели/` — нужной высоты и на землю.
    ///
    /// Берётся **меш**, а не сцена целиком. Разница не в удобстве: сцена
    /// тащит за собой узлы, скины и привязку к скелету, и лопата, стоило
    /// поставить её сценой, разлеталась веером треугольников — при том
    /// что деревья из того же конвейера вставали нормально. Чистый
    /// `MeshInstance3D` с той же мешью ничего этого не тащит.
    ///
    /// Ни множитель, ни смещение не подобраны на глаз: мир **спрашивает
    /// у модели, какая она**, и считает их сам. Модели пришли в сотых
    /// долях метра (дерево 0.102, лопата 0.139) и вверх у них Z, а не Y;
    /// считать это руками — значит ошибиться при первой же замене модели.
    ///
    /// `какое` выбирает один меш из сцены. В файле деревьев их три,
    /// и лежат они **в одной точке**: поставить сцену целиком значит
    /// поставить три сросшихся ствола, а восемь таких «деревьев» — это
    /// двадцать четыре, торчащих друг из друга. Так и вышло с первого раза.
    /// </summary>
    private void Модель(string путь, Vector3 где, float поворот, float высота,
                        int какое = -1)
    {
        var сцена = GD.Load<PackedScene>(путь);
        if (сцена is null)
            return;                     // нет модели — мир строится и без неё
        var образец = сцена.Instantiate<Node3D>();
        var меши = new List<MeshInstance3D>();
        Найти(образец, меши);
        if (какое >= 0 && меши.Count > 0)
            меши = new List<MeshInstance3D> { меши[какое % меши.Count] };
        if (меши.Count == 0)
        {
            образец.QueueFree();
            return;
        }

        // сколько модель занимает в своих осях
        Aabb? общий = null;
        foreach (var м in меши)
        {
            var а = м.GetAabb();
            общий = общий is null ? а : общий.Value.Merge(а);
        }
        var рамка = общий!.Value;
        if (рамка.Size.Z <= 0.0001f)
        {
            образец.QueueFree();
            return;
        }

        // Z-вверх → Y-вверх: поворот на −90° по X. После него местная Z
        // становится мировой высотой, а местный низ — это `рамка.Position.Z`
        float масштаб = высота / рамка.Size.Z;
        var где_то = new Node3D
        {
            RotationDegrees = new Vector3(-90, поворот, 0),
            Scale = Vector3.One * масштаб,
            Position = где with { Y = где.Y - рамка.Position.Z * масштаб },
        };
        foreach (var м in меши)
            // без MaterialOverride: у меша свои материалы по поверхностям,
            // и подменять их одним значит красить черенок цветом лезвия
            где_то.AddChild(new MeshInstance3D { Mesh = м.Mesh });
        AddChild(где_то);
        образец.QueueFree();
    }

    private static void Найти(Node где, List<MeshInstance3D> куда)
    {
        if (где is MeshInstance3D м)
            куда.Add(м);
        foreach (var д in где.GetChildren())
            Найти(д, куда);
    }

