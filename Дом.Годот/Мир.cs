    /// <summary>Где стоят у этой двери — то место, откуда в неё стучат
    /// и откуда из неё слышно. Ничего нет — значит такой двери в доме
    /// не построено.</summary>
    public Vector3? УДвери(int квартира)
        => _двери.FirstOrDefault(д => д.квартира == квартира)?.перед;

    /// <summary>Свет в подъезде: гаснет вместе с домом.</summary>
    public void Освещение(double сколько)
    {
        foreach (var л in _лампы)
            л.LightEnergy = (float)(0.20 + 1.05 * сколько);
    }

