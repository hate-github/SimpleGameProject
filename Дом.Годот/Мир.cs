// Подъезд как место (ГДД 15, 23): пять этажей, двадцать дверей, лестница.
//
// Это не декорация к диалоговому окну. Игра — от первого лица: человек
// стоит на своей площадке, выходит к лестнице, поднимается, стучится
// в чужую дверь. Всё, что до сих пор было списком строк, здесь становится
// местом, по которому ходят.
//
// Геометрия строится **из данных дома**, а не лежит в сцене: этажи
// и квартиры берутся из `npcs.json`. Сдвинется расселение — сдвинется
// и дом, и это не удобство, а то же правило, что везде: одно место правды.
//
// Планировка — обычная советская: площадка с четырьмя дверями, за ней
// шахта, в шахте два марша через промежуточную площадку, в торце окно.
// Первая версия ставила один марш в двадцать ступеней на всю глубину
// площадки: получалась отвесная стена, занимавшая почти весь пол, —
// герой оказывался внутри неё и видел ровный серый цвет. Два марша
// нужны не для красоты: три метра одним маршем в такую шахту не влезают.
//
// Ходить по ступеням тоже пришлось чинить. `CharacterBody3D` в Godot 4
// сам на уступ не залезает — упирается и стоит. Поэтому ступени здесь
// **видимые, но не твёрдые**, а идёт человек по невидимому пандусу вдоль
// марша. Приём известный; записан потому, что глядя на сцену его не видно.
//
// Low poly здесь буквальный: коробки и один материал на вид поверхности.
// Ни одной модели, ни одной текстуры — их сделает художник, и заменит он
// меши, а не то, где какая дверь. Пока это серый бетон, и он честнее
// картинки, которой нет.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

/// <summary>
/// Дверь квартиры: к ней подходят, в неё стучат, и она рассказывает.
///
/// Всё, что здесь хранится сверх узла, — это чем дверь **говорит**:
/// своя краска (общий материал перекрасить нельзя — перекрасятся все
/// двадцать), щель света понизу и зарубка на косяке от прошлой жизни.
/// </summary>
public sealed record ДверьКвартиры(
    int квартира,
    StaticBody3D узел,
    Vector3 перед,
    float в_дом,
    StandardMaterial3D краска,
    MeshInstance3D щель,
    MeshInstance3D зарубка);

public partial class Мир : Node3D
{
    /// <summary>Высота этажа. Три метра — чтобы лестница читалась,
    /// и чтобы человек не бился головой.</summary>
    public const float ЭТАЖ = 3.0f;

    private const float ШИРИНА = 3.2f;      // полширины шахты
    private const float ЗАД = -2.6f;        // задняя стена площадки
    private const float ШАГ_ВВЕРХ = 0.8f;   // где кончается площадка, начинается марш
    private const float ПОВОРОТ = 3.5f;     // где марш переходит в промежуточную
    private const float ПЕРЁД = 4.6f;       // торцевая стена с окном
    private const int СТУПЕНЕЙ = 9;         // на марш; два марша на этаж

    private readonly List<ДверьКвартиры> _двери = new();
    private readonly List<OmniLight3D> _лампы = new();

    public IReadOnlyList<ДверьКвартиры> двери => _двери;

    /// <summary>
    /// Где стоит человек в начале: он только что вышел из своей квартиры,
    /// стоит у своей двери спиной к ней.
    ///
    /// Не в середине площадки: середина ничего не говорит. У своей двери
    /// в кадр попадают напротив — две чужие двери с номерами, справа или
    /// слева — проём лестницы, за спиной — своя. Это и есть первое, что
    /// игра должна сказать без единого слова: ты в подъезде, и вокруг
    /// живут люди.
    /// </summary>
    public Vector3 Начало(int квартира)
        => new(Сторона(квартира) * (ШИРИНА - 1.05f),
               ЭТАЖ * (Этаж(квартира) - 1) + 0.15f,
               Глубина(квартира));

    /// <summary>Куда смотрит в начале: поперёк площадки, от своей двери.
    /// Godot считает «вперёд» вдоль −Z, поэтому взгляд вдоль +X — это
    /// поворот на −90°.</summary>
    public static float Поворот(int квартира)
        => Сторона(квартира) < 0 ? -Mathf.Pi / 2 : Mathf.Pi / 2;

    /// <summary>По какой стене дверь: слева (−1) или справа (+1).</summary>
    private static float Сторона(int квартира) => (квартира - 1) % 4 < 2 ? -1 : 1;

    /// <summary>Ближе к задней стене или ближе к лестнице.</summary>
    private static float Глубина(int квартира)
        => (квартира - 1) % 4 % 2 == 0 ? -1.85f : -0.35f;

    /// <summary>Точка за окном на высоте героя: туда ставится метель.
    /// Снег должен лететь снаружи, а не сквозь стены, — иначе он читается
    /// не как буран, а как грязь на камере.</summary>
    public static Vector3 Снаружи(Vector3 где)
        => new(0.0f, где.Y + 6.0f, ПЕРЁД + 7.0f);

    public static int Этаж(int квартира) => (квартира - 1) / 4 + 1;

    /// <summary>Построить подъезд по дому. `своя` — квартира героя:
    /// у неё одной дверь открыта и за ней есть комната.</summary>
    public void Построить(House h, int своя)
    {
        _двери.Clear();
        _лампы.Clear();
        _своя = своя;
        _полки.Clear();

        int этажей = h.flats.Значения.Select(f => f.floor).DefaultIfEmpty(5).Max();
        float высота = ЭТАЖ * этажей;

        var бетон = Материал(new Color("#3a3a36"), 0.95f);
        var пол = Материал(new Color("#2b2926"), 0.9f);
        var ступень = Материал(new Color("#4a4843"), 0.9f);

        Стены(бетон, высота, этажей);

        for (int э = 1; э <= этажей; э++)
        {
            float y = ЭТАЖ * (э - 1);

            // площадка с дверями; на первом этаже пол лежит и под лестницей
            float до = э == 1 ? ПЕРЁД : ШАГ_ВВЕРХ;
            Коробка(пол, new Vector3(ШИРИНА * 2, 0.2f, до - ЗАД),
                    new Vector3(0, y - 0.1f, (ЗАД + до) / 2));

            Двери(h, э, y);

            if (Этаж(_своя) == э)
                Квартира(бетон, пол, y);

            if (э < этажей)
                Лестница(ступень, пол, y);
            else                                     // крыша над последним
                Коробка(бетон, new Vector3(ШИРИНА * 2, 0.2f, ПЕРЁД - ЗАД),
                        new Vector3(0, y + ЭТАЖ + 0.1f, (ЗАД + ПЕРЁД) / 2));

            Лампа(э, y);
        }
    }

    // ---------- части ----------

    /// <summary>Коробка стен: две боковые, задняя и торцевая с окнами.
    /// Строятся на всю высоту сразу, а не по этажу: окно на промежуточной
    /// площадке пересекает перекрытие, и по этажам его не собрать.</summary>
    private void Стены(StandardMaterial3D бетон, float высота, int этажей)
    {
        float глубина = ПЕРЁД - ЗАД;
        float середина = (ЗАД + ПЕРЁД) / 2;

        foreach (float сторона in new[] { -1f, 1f })
        {
            float x = сторона * (ШИРИНА + 0.1f);
            if (сторона != Сторона(_своя))
            {
                Коробка(бетон, new Vector3(0.2f, высота, глубина),
                        new Vector3(x, высота / 2, середина));
                continue;
            }
            Проём(бетон, x, высота, глубина, середина);
        }
        Коробка(бетон, new Vector3(ШИРИНА * 2 + 0.4f, высота, 0.2f),
                new Vector3(0, высота / 2, ЗАД - 0.1f));

        Торец(бетон, высота, этажей);
    }

    /// <summary>
    /// Торцевая стена с окнами — то самое место, ради которого всё это
    /// и строится: в подъезде метель видно только отсюда.
    ///
    /// Окно приходится на промежуточную площадку и на высоту глаз того,
    /// кто на ней стоит. Стекло сделано твёрдым: дыра в стене без него —
    /// это дыра, в которую выходят.
    /// </summary>
    private void Торец(StandardMaterial3D бетон, float высота, int этажей)
    {
        const float ОКНО = 1.8f;                       // полширины окна
        float z = ПЕРЁД + 0.1f;
        float простенок = ШИРИНА + 0.2f - ОКНО;
        float край = (ШИРИНА + 0.2f + ОКНО) / 2;

        // простенки по краям — во всю высоту
        Коробка(бетон, new Vector3(простенок, высота, 0.2f),
                new Vector3(-край, высота / 2, z));
        Коробка(бетон, new Vector3(простенок, высота, 0.2f),
                new Vector3(край, высота / 2, z));

        // между простенками — пояса кладки, окна между ними
        var стекло = new StandardMaterial3D
        {
            AlbedoColor = new Color(0.72f, 0.78f, 0.84f, 0.14f),
            Transparency = BaseMaterial3D.TransparencyEnum.Alpha,
            Roughness = 0.35f,
        };
        float низ = 0;
        for (int э = 1; э <= этажей; э++)
        {
            float дно = ЭТАЖ * (э - 1) + 2.2f;
            float верх = Mathf.Min(ЭТАЖ * (э - 1) + 3.4f, высота);
            if (дно >= высота - 0.3f)
                break;
            Коробка(бетон, new Vector3(ОКНО * 2, дно - низ, 0.2f),
                    new Vector3(0, (низ + дно) / 2, z));
            Коробка(стекло, new Vector3(ОКНО * 2, верх - дно, 0.06f),
                    new Vector3(0, (дно + верх) / 2, z));
            низ = верх;
        }
        if (низ < высота)
            Коробка(бетон, new Vector3(ОКНО * 2, высота - низ, 0.2f),
                    new Vector3(0, (низ + высота) / 2, z));
    }

    /// <summary>Четыре двери на площадку: две слева, две справа.</summary>
    private void Двери(House h, int э, float y)
    {
        for (int i = 0; i < 4; i++)
        {
            int кв = (э - 1) * 4 + i + 1;
            if (!h.flats.Есть(кв))
                continue;
            float сторона = Сторона(кв);
            float в_дом = -сторона;
            float z = Глубина(кв);
            var место = new Vector3(сторона * (ШИРИНА - 0.07f), y + 1.05f, z);
            // своя краска на каждую дверь: общий материал перекрасить
            // нельзя, перекрасятся все двадцать разом
            var краска = Материал(ДЕРЕВО, 0.7f);
            StaticBody3D узел;
            if (кв == _своя)
            {
                // Своя дверь распахнута: это твоя дверь, ты в неё входишь.
                // Створка стоит вдоль стены уже внутри квартиры, а место,
                // куда смотрит луч, — просто область в проёме: тело в нём
                // не пропустило бы человека, а прицел по нему работает
                // ровно так же (`RayCast3D.CollideWithAreas`).
                // Створка уходит **внутрь квартиры**, а не на площадку.
                // Первый заход поставил её по `в_дом`, то есть в подъезд,
                // и она встала поперёк дороги: герой упирался в собственную
                // открытую дверь и никуда не шёл.
                // Размер задан по осям прямо, без поворота. Поворот
                // на узле не применился к форме, и створка так и осталась
                // стоять поперёк проёма — то есть закрытой, только внутри
                // квартиры. Развёрнутая дверь — это просто доска вдоль
                // стены, и проще написать её вдоль стены.
                var створка = new Vector3(0.95f, 2.1f, 0.14f);
                узел = new StaticBody3D
                {
                    Position = место + new Vector3(-в_дом * 0.55f, 0, 0.55f),
                };
                узел.AddChild(new MeshInstance3D
                {
                    Mesh = new BoxMesh { Size = створка },
                    MaterialOverride = краска,
                });
                узел.AddChild(new CollisionShape3D
                {
                    Shape = new BoxShape3D { Size = створка },
                });
                AddChild(узел);

                var прицел = new Area3D
                {
                    Position = место,
                    Name = $"дверь{кв}",
                };
                прицел.AddChild(new CollisionShape3D
                {
                    Shape = new BoxShape3D
                        { Size = new Vector3(0.14f, 2.1f, 0.95f) },
                });
                AddChild(прицел);
                Табличка(прицел, кв, в_дом);
            }
            else
            {
                узел = Коробка(краска, new Vector3(0.14f, 2.1f, 0.95f), место);
                узел.Name = $"дверь{кв}";
                Табличка(узел, кв, в_дом);
            }
            _двери.Add(new ДверьКвартиры(
                кв, узел, new Vector3(место.X + в_дом * 0.9f, y, z),
                в_дом, краска, Щель(место, в_дом), Зарубка(место, в_дом)));
        }
    }

    /// <summary>
    /// Лестница на этаж: марш налево вверх, промежуточная площадка
    /// с окном, марш направо вверх — и ты на следующем этаже.
    ///
    /// Ступени только видимые. Твёрдый здесь пандус: `CharacterBody3D`
    /// на уступ не залезает сам, и по честным ступеням человек упирается
    /// в первую же и стоит.
    /// </summary>
    private void Лестница(StandardMaterial3D ступень, StandardMaterial3D пол,
                          float y)
    {
        float половина = ЭТАЖ / 2;
        float ширина = ШИРИНА - 0.1f;
        float х = (ШИРИНА + 0.1f) / 2;

        Марш(ступень, -х, ширина, y, ШАГ_ВВЕРХ, ПОВОРОТ);
        Коробка(пол, new Vector3(ШИРИНА * 2, 0.2f, ПЕРЁД - ПОВОРОТ),
                new Vector3(0, y + половина - 0.1f, (ПОВОРОТ + ПЕРЁД) / 2));
        Марш(ступень, х, ширина, y + половина, ПОВОРОТ, ШАГ_ВВЕРХ);
    }

    /// <summary>Один марш: девять видимых ступеней и невидимый пандус.</summary>
    private void Марш(StandardMaterial3D материал, float x, float ширина,
                      float y, float откуда, float куда)
    {
        float подъём = ЭТАЖ / 2 / СТУПЕНЕЙ;
        float проступь = (куда - откуда) / СТУПЕНЕЙ;
        for (int с = 0; с < СТУПЕНЕЙ; с++)
        {
            float верх = y + подъём * (с + 1);
            Меш(материал,
                new Vector3(ширина, подъём + 0.06f, Mathf.Abs(проступь)),
                new Vector3(x, верх - (подъём + 0.06f) / 2,
                            откуда + проступь * (с + 0.5f)));
        }

        // пандус вдоль марша: по нему и идут
        float пробег = куда - откуда;
        float длина = Mathf.Sqrt(пробег * пробег + ЭТАЖ / 2 * (ЭТАЖ / 2));
        float угол = Mathf.Atan2(ЭТАЖ / 2, пробег);
        var пандус = new StaticBody3D
        {
            Position = new Vector3(x, y + ЭТАЖ / 4 - 0.12f, (откуда + куда) / 2),
            Rotation = new Vector3(-угол, 0, 0),
        };
        пандус.AddChild(new CollisionShape3D
        {
            Shape = new BoxShape3D { Size = new Vector3(ширина, 0.2f, длина) },
        });
        AddChild(пандус);
    }

    /// <summary>
    /// Боковая стена с проёмом в свою квартиру: куски вокруг дыры вместо
    /// одного целого.
    ///
    /// Порог опущен на восемь сантиметров ниже пола, и это не украшение.
    /// Низ капсулы героя стоит ровно на уровне пола; кусок стены, который
    /// кончается там же, Godot засчитывает как касание стены — и человек
    /// упирается в проём, стоя посреди него. Восемь сантиметров разводят
    /// их, а дыру под порогом закрывает сам порог.
    /// </summary>
    private void Проём(StandardMaterial3D бетон, float x, float высота,
                       float глубина, float середина)
    {
        float y0 = ЭТАЖ * (Этаж(_своя) - 1);
        float z = Глубина(_своя);
        const float ПОЛОВИНА = 0.55f;      // полширины проёма
        const float ВЕРХ = 2.1f;           // высота проёма
        const float ЗАЗОР = 0.08f;         // насколько порог ниже пола

        float низ = y0 - ЗАЗОР;

        // всё, что ниже порога, и всё, что выше притолоки
        if (низ > 0)
            Коробка(бетон, new Vector3(0.2f, низ, глубина),
                    new Vector3(x, низ / 2, середина));
        Коробка(бетон, new Vector3(0.2f, высота - y0 - ВЕРХ, глубина),
                new Vector3(x, (y0 + ВЕРХ + высота) / 2, середина));

        // по бокам от проёма — от порога до притолоки
        foreach (var (от, до) in new[] { (ЗАД, z - ПОЛОВИНА), (z + ПОЛОВИНА, ПЕРЁД) })
            Коробка(бетон, new Vector3(0.2f, y0 + ВЕРХ - низ, до - от),
                    new Vector3(x, (низ + y0 + ВЕРХ) / 2, (от + до) / 2));
    }

    /// <summary>
    /// Своя квартира — одна комната за своей дверью.
    ///
    /// Только своя: у соседей за дверьми ничего нет и быть не должно.
    /// Не из экономии — из правила. Чужая комната это чужая правда,
    /// и построить её значит однажды показать её игроку.
    ///
    /// Всё, что здесь стоит, приходит из `Дом.Экран.Подача.Внутри`:
    /// печь горит, если топится; на полке столько банок, сколько в шкафу;
    /// в окне метель, а если окно проломлено — оно забито досками.
    /// </summary>
    private void Квартира(StandardMaterial3D бетон, StandardMaterial3D пол, float y)
    {
        float сторона = Сторона(_своя);
        float z = Глубина(_своя);
        float x0 = сторона * (ШИРИНА + 0.2f);          // внешняя грань стены
        float x1 = x0 + сторона * КОМНАТА;              // дальняя стена
        float xс = (x0 + x1) / 2;
        float zс = z;

        var обои = Материал(new Color("#4a4038"), 0.95f);

        Коробка(пол, new Vector3(КОМНАТА, 0.2f, КОМНАТА),
                new Vector3(xс, y - 0.1f, zс));
        // порог: между площадкой и комнатой лежит толщина стены, и без
        // этой полоски под ногами там дыра в полу
        Коробка(пол, new Vector3(0.7f, 0.2f, 1.3f),
                new Vector3(сторона * (ШИРИНА + 0.15f), y - 0.1f, zс));
        Коробка(бетон, new Vector3(КОМНАТА, 0.2f, КОМНАТА),
                new Vector3(xс, y + ЭТАЖ - 0.1f, zс));
        Коробка(обои, new Vector3(КОМНАТА, ЭТАЖ, 0.2f),
                new Vector3(xс, y + ЭТАЖ / 2, zс - КОМНАТА / 2));
        Коробка(обои, new Vector3(КОМНАТА, ЭТАЖ, 0.2f),
                new Vector3(xс, y + ЭТАЖ / 2, zс + КОМНАТА / 2));

        // дальняя стена — с окном во двор
        Окно(обои, x1, y, zс);

        // печь у стены
        _печь = Коробка(Материал(new Color("#2b2723"), 0.8f),
                        new Vector3(0.6f, 0.8f, 0.5f),
                        new Vector3(xс - сторона * 1.4f, y + 0.4f, zс - 1.5f));
        _огонь = new OmniLight3D
        {
            Position = new Vector3(xс - сторона * 1.4f, y + 0.55f, zс - 1.5f),
            LightColor = new Color("#ff9a40"),
            LightEnergy = 0.0f,
            OmniRange = 5.0f,
        };
        AddChild(_огонь);

        // Полка у боковой стены, а не у окна: у окна ей не место, там
        // свет и метель. По коробке на единицу запаса, шесть рядов —
        // по ряду на ресурс, в том же порядке, в каком их печатает
        // состояние.
        var доска = Материал(new Color("#5a4a36"), 0.9f);
        float zп = zс + КОМНАТА / 2 - 0.35f;
        for (int ряд = 0; ряд < РЕСУРСЫ.Length; ряд++)
        {
            float yр = y + 0.45f + ряд * 0.38f;
            Меш(доска, new Vector3(2.9f, 0.06f, 0.4f),
                new Vector3(xс, yр, zп));
            var ряд_полок = new List<MeshInstance3D>();
            for (int i = 0; i < 8; i++)
            {
                var банка = new MeshInstance3D
                {
                    Mesh = new BoxMesh { Size = new Vector3(0.13f, 0.17f, 0.13f) },
                    MaterialOverride = Материал(РЕСУРС[ряд], 0.6f),
                    Position = new Vector3(xс - 1.3f + i * 0.35f,
                                           yр + 0.115f, zп),
                    Visible = false,
                };
                AddChild(банка);
                ряд_полок.Add(банка);
            }
            _полки.Add(ряд_полок);
        }

        // матрас на полу — спать здесь
        Меш(Материал(new Color("#5b4a4a"), 0.95f),
            new Vector3(1.9f, 0.18f, 0.8f),
            new Vector3(xс + сторона * 0.9f, y + 0.09f, zс - 1.6f));

        _лампочка = new OmniLight3D
        {
            Position = new Vector3(xс, y + ЭТАЖ - 0.4f, zс),
            LightColor = new Color("#ffe0b0"),
            LightEnergy = 0.0f,
            OmniRange = 9.0f,
        };
        AddChild(_лампочка);
    }

    /// <summary>Окно во двор: за ним метель. Забивается досками, когда
    /// в стене пролом, — то же окно, только уже не окно.</summary>
    private void Окно(StandardMaterial3D обои, float x, float y, float z)
    {
        const float ОКНО = 1.3f;
        float край = (КОМНАТА + ОКНО) / 2;
        Коробка(обои, new Vector3(0.2f, ЭТАЖ, (КОМНАТА - ОКНО) / 2),
                new Vector3(x, y + ЭТАЖ / 2, z - край / 2 - ОКНО / 4));
        Коробка(обои, new Vector3(0.2f, ЭТАЖ, (КОМНАТА - ОКНО) / 2),
                new Vector3(x, y + ЭТАЖ / 2, z + край / 2 + ОКНО / 4));
        Коробка(обои, new Vector3(0.2f, 1.0f, ОКНО),
                new Vector3(x, y + 0.5f, z));
        Коробка(обои, new Vector3(0.2f, ЭТАЖ - 2.3f, ОКНО),
                new Vector3(x, y + 2.3f + (ЭТАЖ - 2.3f) / 2, z));

        var стекло = new StandardMaterial3D
        {
            AlbedoColor = new Color(0.72f, 0.78f, 0.84f, 0.14f),
            Transparency = BaseMaterial3D.TransparencyEnum.Alpha,
            Roughness = 0.35f,
        };
        Коробка(стекло, new Vector3(0.06f, 1.3f, ОКНО),
                new Vector3(x, y + 1.65f, z));

        _доски = new List<MeshInstance3D>();
        for (int i = 0; i < 4; i++)
        {
            var д = new MeshInstance3D
            {
                Mesh = new BoxMesh { Size = new Vector3(0.08f, 0.22f, ОКНО + 0.2f) },
                MaterialOverride = Материал(new Color("#4a3a26"), 0.95f),
                Position = new Vector3(x - Mathf.Sign(x) * 0.12f,
                                       y + 1.15f + i * 0.34f, z),
                Visible = false,
            };
            AddChild(д);
            _доски.Add(д);
        }
    }

    /// <summary>Что дома: печь, свет, полка, забитое окно.</summary>
    public void Дома(Дом.Экран.Комната что)
    {
        if (_огонь is null)
            return;
        _огонь.LightEnergy = что.топится ? 2.6f : (что.печь ? 0.2f : 0.0f);
        if (_лампочка is not null)
            _лампочка.LightEnergy = что.свет ? 2.4f : 0.0f;

        for (int ряд = 0; ряд < _полки.Count; ряд++)
        {
            double сколько = что.шкаф
                .Where(з => з.ресурс == РЕСУРСЫ[ряд])
                .Select(з => з.сколько).DefaultIfEmpty(0).First();
            for (int i = 0; i < _полки[ряд].Count; i++)
                _полки[ряд][i].Visible = i < сколько;
        }

        foreach (var д in _доски ?? new List<MeshInstance3D>())
            д.Visible = что.дыр > 0;
    }

    private int _своя = 1;
    private StaticBody3D? _печь;
    private OmniLight3D? _огонь;
    private OmniLight3D? _лампочка;
    private List<MeshInstance3D>? _доски;
    private readonly List<List<MeshInstance3D>> _полки = new();

    private const float КОМНАТА = 5.0f;

    /// <summary>По полке на ресурс, в том же порядке, в каком их печатает
    /// состояние. Порядок здесь — договор с `Дом.Экран`: строки шкафа
    /// приходят отсортированными, и полка ищет свою по имени, а не
    /// по номеру.</summary>
    private static readonly string[] РЕСУРСЫ =
        { "вода", "деньги", "еда", "лекарства", "материалы", "топливо" };

    private static readonly Color[] РЕСУРС =
    {
        new("#6a8ea8"), new("#8a8a6a"), new("#8a6a4a"),
        new("#a86a6a"), new("#7a7a80"), new("#5a4a38"),
    };

    /// <summary>
    /// Щель света понизу. Единственное, что видно снаружи о чужом тепле:
    /// у соседа работает генератор — значит, из-под двери светит.
