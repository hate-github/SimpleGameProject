    /// <summary>
    /// Что двери говорят сегодня.
    ///
    /// Считается не здесь: `Дом.Экран.Подача.Снаружи` решает, что видно
    /// с площадки, и потому это проверяется из консоли. Узлу остаётся
    /// краска, щель и угол — и ни одного собственного решения.
    /// </summary>
    public void Обновить(IReadOnlyList<Дом.Экран.ДверьСнаружи> что)
    {
        var по_номеру = что.ToDictionary(д => д.квартира);
        foreach (var д in _двери)
        {
            if (!по_номеру.TryGetValue(д.квартира, out var с))
                continue;

            д.краска.AlbedoColor =
                с.горело ? КОПОТЬ
                : с.разобрана ? ГОЛО
                : с.живут ? ДЕРЕВО
                : ПУСТО;
            д.щель.Visible = с.свет;

            // сорванный замок виден тем, что дверь больше не закрывается
            д.узел.RotationDegrees = new Vector3(
                0, с.взломана || с.разобрана ? д.в_дом * 11 : 0, 0);
        }
    }

    /// <summary>
    /// Кто сейчас стоит в подъезде.
    ///
    /// Фигуры — не жизнь сама по себе, а снимок хода: дом посчитал, что
    /// в этот час такой-то стоит у такой-то двери, и здесь это видно.
    /// Двигаться они не двигаются, и правильно: время в доме идёт только
    /// когда игрок тратит свои часы. Захочешь застать соседа на лестнице —
    /// приходи в тот час, когда он там, а не жди у двери.
    ///
    /// Кого нет в списке — того и нет в подъезде: он дома за дверью или
    /// вовсе за порогом. Решает это `Дом.Экран.Подача.В_подъезде`,
    /// и потому это проверяется из консоли, а не глазами.
    ///
    /// Фигура не ставится вплотную к игроку. Они твёрдые — сквозь соседа
    /// не пройти, иначе вся затея не стоит ничего, — а поставленная
    /// в занятое место твёрдая фигура выталкивает героя в стену.
    /// </summary>
    public void Соседи(IReadOnlyList<Дом.Экран.ВПодъезде> кто, Vector3 герой)
    {
        _соседи ??= Узел("соседи");
        foreach (var у in _соседи.GetChildren())
            у.QueueFree();

        var занято = new Dictionary<int, int>();
        foreach (var с in кто)
        {
            var д = _двери.FirstOrDefault(x => x.квартира == с.квартира);
            float y = ЭТАЖ * (с.этаж - 1);
            занято.TryGetValue(с.квартира, out int сколько);
            занято[с.квартира] = сколько + 1;
            // второй у той же двери встаёт рядом, а не в первого
            float вбок = сколько * 0.55f;

            Vector3 где;
            float лицом;
            if (с.где == Дом.Экран.Где.УДвери && д is not null)
            {
                // сбоку от косяка, а не в проёме: человек у двери стоит
                // рядом с ней, и номер квартиры из-за него видно
                float к_середине = д.перед.Z < (ЗАД + ШАГ_ВВЕРХ) / 2 ? 1 : -1;
                где = new Vector3(д.перед.X + д.в_дом * 0.35f, y,
                                  д.перед.Z + к_середине * (0.62f + вбок));
                лицом = д.в_дом > 0 ? 90 : -90;      // лицом к створке
            }
            else
            {
                // площадка: посреди пролёта, лицом к лестнице
                где = new Vector3(вбок - 0.4f, y, (ЗАД + ШАГ_ВВЕРХ) / 2);
                лицом = 180;
            }
            // фигура носит имя той двери, у которой стоит: она заслоняет
            // створку, и без этого подойти к двери, где кто-то стоит, было
            // бы нельзя. Смотреть на человека и смотреть на его дверь —
            // в подъезде одно и то же
            // Твёрдость — только если герой не стоит в этом же месте.
            // Площадка хрущёвки — 2.9 на 2.2 метра на четыре двери, и все,
            // кто у них стоит, вместе с тобой туда не помещаются, не
            // соприкасаясь. Выбор был между «сквозь соседа не пройти»
            // и «соседа у своей двери не увидеть вовсе» — а не увидеть
            // хуже: гость у твоей двери и есть самый нужный случай.
            bool вплотную = где.DistanceTo(герой with { Y = где.Y }) < 0.6f;
            Фигура(где, лицом, с.id, с.имя, $"дверь{с.квартира}", !вплотную);
        }
    }

