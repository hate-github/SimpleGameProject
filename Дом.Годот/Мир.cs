    private StaticBody3D Коробка(StandardMaterial3D материал, Vector3 размер,
                                 Vector3 где)
    {
        var тело = new StaticBody3D { Position = где };
        тело.AddChild(new MeshInstance3D
        {
            Mesh = new BoxMesh { Size = размер },
            MaterialOverride = материал,
        });
        тело.AddChild(new CollisionShape3D
        {
            Shape = new BoxShape3D { Size = размер },
        });
        AddChild(тело);
        return тело;
    }

    /// <summary>Только видимое, без твёрдости: ступени и мелочь.</summary>
    private void Меш(StandardMaterial3D материал, Vector3 размер, Vector3 где)
        => AddChild(new MeshInstance3D
        {
            Mesh = new BoxMesh { Size = размер },
            MaterialOverride = материал,
            Position = где,
        });

    // -------------------------------------------------------- заготовка

    /// <summary>
    /// Прочитанная сцена: коробки и гнёзда.
    ///
    /// Уговор простой: **коробка становится стеной, точка — гнездом**.
    /// У коробки берётся размер меша, помноженный на масштаб узла, —
    /// значит её тянут мышью, и такой она и встанет. У точки значимы
    /// место, поворот и масштаб, а чем она станет, решает имя.
    ///
    /// `группа` — имя узла первого уровня, в котором коробка лежит:
    /// по нему мир пропускает ту квартиру, на месте которой стоит своя.
    ///
    /// Материал выбирается по началу имени: `пол…`, `ступень…`, `обои…`,
    /// `доска…`, `стекло…`, `снег…`, всё прочее — бетон. Имя, начинающееся
    /// на `вид`, ставится без формы: сквозь него ходят.
    /// </summary>
    private sealed class Заготовка
    {
        public readonly List<(string имя, string группа, Vector3 размер,
                              Transform3D где)> коробки = new();
        public readonly List<(string имя, Transform3D где)> гнёзда = new();

        public bool Пуста => коробки.Count == 0 && гнёзда.Count == 0;

        public Transform3D? Гнездо(string имя)
        {
            foreach (var (и, где) in гнёзда)
                if (string.Equals(и, имя, StringComparison.Ordinal))
                    return где;
            return null;
        }
    }

    private static Заготовка Прочитать(string путь)
    {
        var з = new Заготовка();
        if (!ResourceLoader.Exists(путь))
        {
            GD.PrintErr($"нет сцены {путь}");
            return з;
        }
        var сцена = GD.Load<PackedScene>(путь);
        if (сцена is null)
            return з;
        var к = сцена.Instantiate<Node3D>();
        Разобрать(к, Transform3D.Identity, з, "");
        к.QueueFree();
        GD.Print($"{путь}: {з.коробки.Count} коробок, {з.гнёзда.Count} гнёзд");
        return з;
    }

    private static void Разобрать(Node узел, Transform3D выше, Заготовка з,
                                  string группа)
    {
        foreach (var у in узел.GetChildren())
        {
            if (у is not Node3D т)
                continue;
            var где = выше * т.Transform;
            string имя = т.Name.ToString();
            if (т is MeshInstance3D м && м.Mesh is BoxMesh к)
                з.коробки.Add((имя, группа, к.Size * где.Basis.Scale, где));
            else if (т is Marker3D)
                з.гнёзда.Add((имя, где));
            Разобрать(т, где, з, группа.Length == 0 ? имя : группа);
        }
    }

    /// <summary>Поставить коробки сцены. `без` — группа, которую на этот
    /// раз не ставим: на её месте стоит заготовка своей квартиры.</summary>
    private void Поставить(Заготовка з, float y, string? без = null)
    {
        foreach (var (имя, группа, размер, где) in з.коробки)
        {
            if (без is not null && группа == без)
                continue;
            if (размер.X <= 0 || размер.Y <= 0 || размер.Z <= 0)
            {
                // Godot такую коробку не строит, пишет об этом в свой лог
                // и продолжает; на экране остаётся мусор, по которому
                // причину не угадать. Лучше сказать прямо и своими словами
                GD.PrintErr($"сцена: у «{имя}» размер {размер} — не коробка");
                continue;
            }
            var точка = где.Origin with { Y = где.Origin.Y + y };
            float угол = Mathf.RadToDeg(где.Basis.GetEuler().Y);
            if (имя.StartsWith("вид", StringComparison.Ordinal))
                Меш(Краска(имя), размер, точка);
            else
                Куча(Краска(имя), размер, точка, угол).Name = имя;
        }
    }

    /// <summary>Из чего сделана коробка — по началу её имени.</summary>
    private StandardMaterial3D Краска(string имя)
    {
        string и = имя.StartsWith("вид", StringComparison.Ordinal) ? имя[3..] : имя;
        и = и.TrimStart('_');
        if (и.StartsWith("пол", StringComparison.Ordinal))
            return Материал(new Color("#2b2926"), 0.9f);
        if (и.StartsWith("ступень", StringComparison.Ordinal))
            return Материал(new Color("#4a4843"), 0.9f);
        if (и.StartsWith("обои", StringComparison.Ordinal))
            return Материал(new Color("#4a4038"), 0.95f);
        if (и.StartsWith("доска", StringComparison.Ordinal))
            return Материал(new Color("#5a4a36"), 0.9f);
        if (и.StartsWith("стекло", StringComparison.Ordinal))
            return Стекло();
        if (и.StartsWith("снег", StringComparison.Ordinal))
            return Материал(new Color("#b4bcc2"), 1.0f);
        if (и.StartsWith("гараж", StringComparison.Ordinal))
            return Материал(new Color("#6a5348"), 0.95f);
        return Материал(new Color("#3a3a36"), 0.95f);
    }

    private static StandardMaterial3D Материал(Color цвет, float шершавость)
        => new()
        {
            AlbedoColor = цвет,
            Roughness = шершавость,
            Metallic = 0.0f,
        };
