// Подъезд как место (ГДД 15, 23): пять этажей, двадцать дверей, лестница.
//
// Это не декорация к диалоговому окну. Игра — от первого лица: человек
// стоит на своей площадке, выходит к лестнице, поднимается, стучится
// в чужую дверь. Всё, что до сих пор было списком строк, здесь становится
// местом, по которому ходят.
//
// Геометрия строится **из данных дома**, а не лежит в сцене: этажи
// и квартиры берутся из `npcs.json`. Сдвинется расселение — сдвинется
// и дом, и это не удобство, а то же правило, что везде: одно место правды.
//
// Планировка — обычная советская: площадка с четырьмя дверями, за ней
// шахта, в шахте два марша через промежуточную площадку, в торце окно.
// Первая версия ставила один марш в двадцать ступеней на всю глубину
// площадки: получалась отвесная стена, занимавшая почти весь пол, —
// герой оказывался внутри неё и видел ровный серый цвет. Два марша
// нужны не для красоты: три метра одним маршем в такую шахту не влезают.
//
// Ходить по ступеням тоже пришлось чинить. `CharacterBody3D` в Godot 4
// сам на уступ не залезает — упирается и стоит. Поэтому ступени здесь
// **видимые, но не твёрдые**, а идёт человек по невидимому пандусу вдоль
// марша. Приём известный; записан потому, что глядя на сцену его не видно.
//
// Low poly здесь буквальный: коробки и один материал на вид поверхности.
// Ни одной модели, ни одной текстуры — их сделает художник, и заменит он
// меши, а не то, где какая дверь. Пока это серый бетон, и он честнее
// картинки, которой нет.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

/// <summary>Дверь квартиры: к ней подходят и в неё стучат.</summary>
public sealed record ДверьКвартиры(int квартира, Node3D узел, Vector3 перед);

public partial class Мир : Node3D
{
    /// <summary>Высота этажа. Три метра — чтобы лестница читалась,
    /// и чтобы человек не бился головой.</summary>
    public const float ЭТАЖ = 3.0f;

    private const float ШИРИНА = 3.2f;      // полширины шахты
    private const float ЗАД = -2.6f;        // задняя стена площадки
    private const float ШАГ_ВВЕРХ = 0.8f;   // где кончается площадка, начинается марш
    private const float ПОВОРОТ = 3.5f;     // где марш переходит в промежуточную
    private const float ПЕРЁД = 4.6f;       // торцевая стена с окном
    private const int СТУПЕНЕЙ = 9;         // на марш; два марша на этаж

    private readonly List<ДверьКвартиры> _двери = new();
    private readonly List<OmniLight3D> _лампы = new();

    public IReadOnlyList<ДверьКвартиры> двери => _двери;

    /// <summary>
    /// Где стоит человек в начале: он только что вышел из своей квартиры,
    /// стоит у своей двери спиной к ней.
    ///
    /// Не в середине площадки: середина ничего не говорит. У своей двери
    /// в кадр попадают напротив — две чужие двери с номерами, справа или
    /// слева — проём лестницы, за спиной — своя. Это и есть первое, что
    /// игра должна сказать без единого слова: ты в подъезде, и вокруг
    /// живут люди.
    /// </summary>
    public Vector3 Начало(int квартира)
        => new(Сторона(квартира) * (ШИРИНА - 1.05f),
               ЭТАЖ * (Этаж(квартира) - 1) + 0.15f,
               Глубина(квартира));

    /// <summary>Куда смотрит в начале: поперёк площадки, от своей двери.
    /// Godot считает «вперёд» вдоль −Z, поэтому взгляд вдоль +X — это
    /// поворот на −90°.</summary>
    public static float Поворот(int квартира)
        => Сторона(квартира) < 0 ? -Mathf.Pi / 2 : Mathf.Pi / 2;

    /// <summary>По какой стене дверь: слева (−1) или справа (+1).</summary>
    private static float Сторона(int квартира) => (квартира - 1) % 4 < 2 ? -1 : 1;

    /// <summary>Ближе к задней стене или ближе к лестнице.</summary>
    private static float Глубина(int квартира)
        => (квартира - 1) % 4 % 2 == 0 ? -1.85f : -0.35f;

    /// <summary>Точка за окном на высоте героя: туда ставится метель.
    /// Снег должен лететь снаружи, а не сквозь стены, — иначе он читается
    /// не как буран, а как грязь на камере.</summary>
    public static Vector3 Снаружи(Vector3 где)
        => new(0.0f, где.Y + 6.0f, ПЕРЁД + 7.0f);

    public static int Этаж(int квартира) => (квартира - 1) / 4 + 1;

    /// <summary>Построить подъезд по дому.</summary>
    public void Построить(House h)
    {
        _двери.Clear();
        _лампы.Clear();

        int этажей = h.flats.Значения.Select(f => f.floor).DefaultIfEmpty(5).Max();
        float высота = ЭТАЖ * этажей;

        var бетон = Материал(new Color("#3a3a36"), 0.95f);
        var пол = Материал(new Color("#2b2926"), 0.9f);
        var дверь = Материал(new Color("#6b4a2c"), 0.7f);
        var ступень = Материал(new Color("#4a4843"), 0.9f);

        Стены(бетон, высота, этажей);

        for (int э = 1; э <= этажей; э++)
        {
            float y = ЭТАЖ * (э - 1);

            // площадка с дверями; на первом этаже пол лежит и под лестницей
            float до = э == 1 ? ПЕРЁД : ШАГ_ВВЕРХ;
            Коробка(пол, new Vector3(ШИРИНА * 2, 0.2f, до - ЗАД),
                    new Vector3(0, y - 0.1f, (ЗАД + до) / 2));

            Двери(h, дверь, э, y);

            if (э < этажей)
                Лестница(ступень, пол, y);
            else                                     // крыша над последним
                Коробка(бетон, new Vector3(ШИРИНА * 2, 0.2f, ПЕРЁД - ЗАД),
                        new Vector3(0, y + ЭТАЖ + 0.1f, (ЗАД + ПЕРЁД) / 2));

            Лампа(э, y);
        }
    }

    // ---------- части ----------

    /// <summary>Коробка стен: две боковые, задняя и торцевая с окнами.
    /// Строятся на всю высоту сразу, а не по этажу: окно на промежуточной
    /// площадке пересекает перекрытие, и по этажам его не собрать.</summary>
    private void Стены(StandardMaterial3D бетон, float высота, int этажей)
    {
        float глубина = ПЕРЁД - ЗАД;
        float середина = (ЗАД + ПЕРЁД) / 2;

        Коробка(бетон, new Vector3(0.2f, высота, глубина),
                new Vector3(-ШИРИНА - 0.1f, высота / 2, середина));
        Коробка(бетон, new Vector3(0.2f, высота, глубина),
                new Vector3(ШИРИНА + 0.1f, высота / 2, середина));
        Коробка(бетон, new Vector3(ШИРИНА * 2 + 0.4f, высота, 0.2f),
                new Vector3(0, высота / 2, ЗАД - 0.1f));

        Торец(бетон, высота, этажей);
    }

    /// <summary>
    /// Торцевая стена с окнами — то самое место, ради которого всё это
    /// и строится: в подъезде метель видно только отсюда.
    ///
    /// Окно приходится на промежуточную площадку и на высоту глаз того,
    /// кто на ней стоит. Стекло сделано твёрдым: дыра в стене без него —
    /// это дыра, в которую выходят.
    /// </summary>
    private void Торец(StandardMaterial3D бетон, float высота, int этажей)
    {
        const float ОКНО = 1.8f;                       // полширины окна
        float z = ПЕРЁД + 0.1f;
        float простенок = ШИРИНА + 0.2f - ОКНО;
        float край = (ШИРИНА + 0.2f + ОКНО) / 2;

        // простенки по краям — во всю высоту
        Коробка(бетон, new Vector3(простенок, высота, 0.2f),
                new Vector3(-край, высота / 2, z));
        Коробка(бетон, new Vector3(простенок, высота, 0.2f),
                new Vector3(край, высота / 2, z));

        // между простенками — пояса кладки, окна между ними
        var стекло = new StandardMaterial3D
        {
            AlbedoColor = new Color(0.72f, 0.78f, 0.84f, 0.14f),
            Transparency = BaseMaterial3D.TransparencyEnum.Alpha,
            Roughness = 0.35f,
        };
        float низ = 0;
        for (int э = 1; э <= этажей; э++)
        {
            float дно = ЭТАЖ * (э - 1) + 2.2f;
            float верх = Mathf.Min(ЭТАЖ * (э - 1) + 3.4f, высота);
            if (дно >= высота - 0.3f)
                break;
            Коробка(бетон, new Vector3(ОКНО * 2, дно - низ, 0.2f),
                    new Vector3(0, (низ + дно) / 2, z));
            Коробка(стекло, new Vector3(ОКНО * 2, верх - дно, 0.06f),
                    new Vector3(0, (дно + верх) / 2, z));
            низ = верх;
        }
        if (низ < высота)
            Коробка(бетон, new Vector3(ОКНО * 2, высота - низ, 0.2f),
                    new Vector3(0, (низ + высота) / 2, z));
    }

    /// <summary>Четыре двери на площадку: две слева, две справа.</summary>
    private void Двери(House h, StandardMaterial3D материал, int э, float y)
    {
        for (int i = 0; i < 4; i++)
        {
            int кв = (э - 1) * 4 + i + 1;
            if (!h.flats.Есть(кв))
                continue;
            float сторона = Сторона(кв);
            float в_дом = -сторона;
            float z = Глубина(кв);
            var место = new Vector3(сторона * (ШИРИНА - 0.07f), y + 1.05f, z);
            var узел = Коробка(материал, new Vector3(0.14f, 2.1f, 0.95f), место);
            узел.Name = $"дверь{кв}";
            Табличка(узел, кв, в_дом);
            _двери.Add(new ДверьКвартиры(
                кв, узел, new Vector3(место.X + в_дом * 0.9f, y, z)));
        }
    }

    /// <summary>
    /// Лестница на этаж: марш налево вверх, промежуточная площадка
    /// с окном, марш направо вверх — и ты на следующем этаже.
    ///
    /// Ступени только видимые. Твёрдый здесь пандус: `CharacterBody3D`
    /// на уступ не залезает сам, и по честным ступеням человек упирается
    /// в первую же и стоит.
    /// </summary>
    private void Лестница(StandardMaterial3D ступень, StandardMaterial3D пол,
                          float y)
    {
        float половина = ЭТАЖ / 2;
        float ширина = ШИРИНА - 0.1f;
        float х = (ШИРИНА + 0.1f) / 2;

        Марш(ступень, -х, ширина, y, ШАГ_ВВЕРХ, ПОВОРОТ);
        Коробка(пол, new Vector3(ШИРИНА * 2, 0.2f, ПЕРЁД - ПОВОРОТ),
                new Vector3(0, y + половина - 0.1f, (ПОВОРОТ + ПЕРЁД) / 2));
        Марш(ступень, х, ширина, y + половина, ПОВОРОТ, ШАГ_ВВЕРХ);
    }

    /// <summary>Один марш: девять видимых ступеней и невидимый пандус.</summary>
    private void Марш(StandardMaterial3D материал, float x, float ширина,
                      float y, float откуда, float куда)
    {
        float подъём = ЭТАЖ / 2 / СТУПЕНЕЙ;
        float проступь = (куда - откуда) / СТУПЕНЕЙ;
        for (int с = 0; с < СТУПЕНЕЙ; с++)
        {
            float верх = y + подъём * (с + 1);
            Меш(материал,
                new Vector3(ширина, подъём + 0.06f, Mathf.Abs(проступь)),
                new Vector3(x, верх - (подъём + 0.06f) / 2,
                            откуда + проступь * (с + 0.5f)));
        }

        // пандус вдоль марша: по нему и идут
        float пробег = куда - откуда;
        float длина = Mathf.Sqrt(пробег * пробег + ЭТАЖ / 2 * (ЭТАЖ / 2));
        float угол = Mathf.Atan2(ЭТАЖ / 2, пробег);
        var пандус = new StaticBody3D
        {
            Position = new Vector3(x, y + ЭТАЖ / 4 - 0.12f, (откуда + куда) / 2),
            Rotation = new Vector3(-угол, 0, 0),
        };
        пандус.AddChild(new CollisionShape3D
        {
            Shape = new BoxShape3D { Size = new Vector3(ширина, 0.2f, длина) },
        });
        AddChild(пандус);
    }

    /// <summary>Номер квартиры на двери. Читается как есть: подъезд —
    /// это место, где номера написаны краской.</summary>
    private static void Табличка(Node3D дверь, int кв, float в_дом)
    {
        дверь.AddChild(new Label3D
        {
            Text = кв.ToString(System.Globalization.CultureInfo.InvariantCulture),
            FontSize = 128,
            PixelSize = 0.0035f,
            Modulate = new Color("#d8d0bc"),
            Billboard = BaseMaterial3D.BillboardModeEnum.Disabled,
            Position = new Vector3(в_дом * 0.10f, 0.78f, 0),
            RotationDegrees = new Vector3(0, в_дом * 90, 0),
            DoubleSided = true,
            Shaded = false,
        });
    }

    /// <summary>Лампочка на площадку. Одна и тусклая: в подъезде так
    /// и есть, а когда света нет — гасят их все разом.</summary>
    private void Лампа(int э, float y)
    {
        var л = new OmniLight3D
        {
            Position = new Vector3(0, y + ЭТАЖ - 0.45f, -0.9f),
            LightColor = new Color("#ffdca8"),
            LightEnergy = 1.1f,
            OmniRange = 9.0f,
            Name = $"лампа{э}",
        };
        AddChild(л);
        _лампы.Add(л);
    }

    /// <summary>Свет в подъезде: гаснет вместе с домом.</summary>
    public void Освещение(double сколько)
    {
        foreach (var л in _лампы)
            л.LightEnergy = (float)(0.20 + 1.05 * сколько);
    }

    // ---------- кирпичи ----------

    private StaticBody3D Коробка(StandardMaterial3D материал, Vector3 размер,
                                 Vector3 где)
    {
        var тело = new StaticBody3D { Position = где };
        тело.AddChild(new MeshInstance3D
        {
            Mesh = new BoxMesh { Size = размер },
            MaterialOverride = материал,
        });
        тело.AddChild(new CollisionShape3D
        {
            Shape = new BoxShape3D { Size = размер },
        });
        AddChild(тело);
        return тело;
    }

    /// <summary>Только видимое, без твёрдости: ступени и мелочь.</summary>
    private void Меш(StandardMaterial3D материал, Vector3 размер, Vector3 где)
        => AddChild(new MeshInstance3D
        {
            Mesh = new BoxMesh { Size = размер },
            MaterialOverride = материал,
            Position = где,
        });

    private static StandardMaterial3D Материал(Color цвет, float шершавость)
        => new()
        {
            AlbedoColor = цвет,
            Roughness = шершавость,
            Metallic = 0.0f,
        };
}
