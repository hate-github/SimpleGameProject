// Походы героя (задание автора, пп. 6, 10, 13): ворота в город и магазин.
//
// Ворота — в проезде заднего вала (гнездо `выход_в_город` двора): отсюда
// герой уходит сам, куда выберет, — в магазин, в промзону, искать бункер.
// Это не вылазка: вылазку делает дом, как соседу, и место выбирает он;
// поход выбирает герой, и дорога идёт делом — кусками, пока дом живёт.
//
// Магазин — отдельная комната далеко от двора, куда героя переносит дорога:
// прилавок, полки, продавщица за прилавком и те из соседей, кто в этот час
// стоит в очереди (хроника: вылазка в магазин). Считать покупку — дело
// `Дом.Ядро.Магазин`; здесь только стены, прилавок и дверь.

using Godot;
using Дом.Экран;

namespace Дом.Годот;

public partial class Мир
{
    /// <summary>Где стоит магазин — далеко от двора, чтобы метель и дом
    /// до него не доставали.</summary>
    private static readonly Vector3 МАГАЗИН = new(300, 0, 0);
    private const float МАГАЗИН_Ш = 10f, МАГАЗИН_Г = 8f, МАГАЗИН_В = 3.2f;

    /// <summary>Ворота в город — то, что под прицелом у проезда.</summary>
    public Предмет? Ворота { get; private set; }

    /// <summary>Прилавок и дверь магазина.</summary>
    public Предмет? Прилавок { get; private set; }
    public Предмет? ДверьМагазина { get; private set; }

    /// <summary>Где стоит герой, вернувшись из похода, — у ворот, лицом к дому.</summary>
    public Vector3 У_ворот { get; private set; } = new(-1, 0.1f, -19.5f);

    /// <summary>Где встаёт герой, войдя в магазин.</summary>
    public Vector3 ВходМагазина => МАГАЗИН + new Vector3(0, 0.1f, МАГАЗИН_Г / 2 - 1.2f);

    /// <summary>Он ли в магазине.</summary>
    public bool ВМагазине(Vector3 где)
        => Math.Abs(где.X - МАГАЗИН.X) < МАГАЗИН_Ш / 2 + 0.5f
           && Math.Abs(где.Z - МАГАЗИН.Z) < МАГАЗИН_Г / 2 + 0.5f
           && где.Y > -1 && где.Y < МАГАЗИН_В + 1;

    private Node3D? _покупатели;

    /// <summary>Ворота в проезде вала: знак и область под прицелом.</summary>
    private void Походы_ворота()
    {
        var г = _дом?.Гнездо("выход_в_город")?.Origin ?? new Vector3(-1, 0, -21.5f);
        У_ворот = г + new Vector3(0, 0.1f, 2.0f);
        // столб с табличкой: ворот как таковых давно нет, есть проезд
        var столб = new MeshInstance3D
        {
            Mesh = new BoxMesh { Size = new Vector3(0.12f, 1.8f, 0.12f) },
            MaterialOverride = Материал(new Color("#3a3228"), 0.9f),
            Position = г + new Vector3(1.6f, 0.9f, 0),
        };
        AddChild(столб);
        AddChild(new Label3D
        {
            Text = "в город →",
            FontSize = 96,
            PixelSize = 0.004f,
            Modulate = new Color("#d8d0bc"),
            Position = г + new Vector3(1.6f, 1.9f, 0.1f),
            Billboard = BaseMaterial3D.BillboardModeEnum.Enabled,
            Shaded = false,
        });
        Ворота = Предмет.Вокруг(this, new Aabb(г + new Vector3(-2.5f, 0, -0.5f), new Vector3(5, 2.4f, 1.0f)),
                                0.1f, "ворота_в_город");
    }

    /// <summary>
    /// Магазин: пол, стены, потолок, прилавок, полки с товаром, продавщица,
    /// лампа; дверь — на передней стене, у неё герой и стоит, войдя.
    /// </summary>
    private void Походы_магазин()
    {
        var бетон = Материал(new Color("#4b4740"), 0.95f);
        var пол = Материал(new Color("#2e2a26"), 0.9f);
        var доска = Материал(new Color("#5a4a36"), 0.9f);
        Vector3 О(float x, float y, float z) => МАГАЗИН + new Vector3(x, y, z);
        float ш = МАГАЗИН_Ш / 2, г = МАГАЗИН_Г / 2;
        Коробка(пол, new Vector3(МАГАЗИН_Ш + 0.4f, 0.2f, МАГАЗИН_Г + 0.4f), О(0, -0.1f, 0));
        Коробка(бетон, new Vector3(МАГАЗИН_Ш + 0.4f, 0.2f, МАГАЗИН_Г + 0.4f), О(0, МАГАЗИН_В + 0.1f, 0));
        Коробка(бетон, new Vector3(0.2f, МАГАЗИН_В, МАГАЗИН_Г), О(-ш - 0.1f, МАГАЗИН_В / 2, 0));
        Коробка(бетон, new Vector3(0.2f, МАГАЗИН_В, МАГАЗИН_Г), О(ш + 0.1f, МАГАЗИН_В / 2, 0));
        Коробка(бетон, new Vector3(МАГАЗИН_Ш, МАГАЗИН_В, 0.2f), О(0, МАГАЗИН_В / 2, -г - 0.1f));
        // передняя стена с дверью посередине
        Коробка(бетон, new Vector3(ш - 0.6f, МАГАЗИН_В, 0.2f), О(-(ш + 0.6f) / 2, МАГАЗИН_В / 2, г + 0.1f));
        Коробка(бетон, new Vector3(ш - 0.6f, МАГАЗИН_В, 0.2f), О((ш + 0.6f) / 2, МАГАЗИН_В / 2, г + 0.1f));
        Коробка(Материал(new Color("#3a3a36"), 0.95f), new Vector3(1.2f, 0.9f, 0.2f), О(0, МАГАЗИН_В - 0.45f, г + 0.1f));
        var створка = Коробка(Материал(new Color("#4a4238"), 0.85f), new Vector3(1.2f, МАГАЗИН_В - 0.9f, 0.1f),
                              О(0, (МАГАЗИН_В - 0.9f) / 2, г + 0.2f));
        створка.Name = "дверь_магазина_створка";
        ДверьМагазина = Предмет.Вокруг(this, new Aabb(О(-0.7f, 0, г - 0.4f), new Vector3(1.4f, 2.3f, 0.6f)),
                                       0.05f, "дверь_магазина");
        // прилавок поперёк, за ним полки у задней стены
        Коробка(доска, new Vector3(6.0f, 1.0f, 0.7f), О(0, 0.5f, -1.2f));
        Прилавок = Предмет.Вокруг(this, new Aabb(О(-3.0f, 0.9f, -1.6f), new Vector3(6.0f, 0.4f, 0.9f)),
                                  0.1f, "прилавок");
        for (int ряд = 0; ряд < 3; ряд++)
        {
            Коробка(доска, new Vector3(8.0f, 0.06f, 0.5f), О(0, 0.5f + ряд * 0.7f, -г + 0.35f));
            // товар — модели еды автора, по выкладке на место
            for (int i = 0; i < 10; i++)
                Выкладка(i + 2 * ряд, О(-3.6f + i * 0.8f, 0.53f + ряд * 0.7f, -г + 0.35f), 0.6f);
        }
        // продавщица за прилавком
        var продавщица = Сосед3D.Собрать("продавщица", "продавщица", new Color("#6a3a3a"), new Color("#8a6f56"));
        AddChild(продавщица);
        продавщица.Встать(О(0.4f, 0, -2.1f), 0, "продавщица", твёрдый: true);
        var л = new OmniLight3D
        {
            Position = О(0, МАГАЗИН_В - 0.3f, 0),
            LightColor = new Color("#f2e6c8"),
            LightEnergy = 1.3f,
            OmniRange = 11f,
        };
        AddChild(л);
        _покупатели = null;
    }

    private static readonly Color[] ЦВЕТА_ТОВАРА =
    {
        new("#8a3a2a"), new("#3a5a8a"), new("#8a7a3a"), new("#3a7a4a"), new("#6a4a7a"),
    };

    /// <summary>
    /// Кто из соседей сейчас в магазине — по хронике: ушёл за порог вылазкой
    /// в этот магазин. Стоят очередью у прилавка; ходить им тут некуда.
    /// </summary>
    public void Покупатели(IReadOnlyList<СоседГде> кто)
    {
        _покупатели?.QueueFree();
        _покупатели = new Node3D { Name = "покупатели" };
        AddChild(_покупатели);
        int i = 0;
        foreach (var с in кто)
        {
            var ф = Сосед3D.Собрать(с.id, с.имя, Пальто(с.id), new Color("#8a6f56"));
            _покупатели.AddChild(ф);
            ф.Встать(МАГАЗИН + new Vector3(-1.5f + i * 0.8f, 0, 0.2f + i * 0.25f), 180,
                     $"покупатель_{с.id}", твёрдый: true);
            i++;
        }
    }
}
