// Доска объявлений у входа (импровизация 17.11.2026): что на ней висит —
// `Беседы.Объявления`, снимок вопроса, пока дом спит; подсказка у доски —
// первое объявление, E — все. Объявление о мене соседи пишут сами о своём
// шкафе, и прочитавший герой это знает: `note_signal` с весом 0.5 (слух — 0.3,
// подслушанное — 0.6) — и мена потом знает, у кого что есть.

using Godot;
using Дом.Ядро;
using Дом.Экран;

namespace Дом.Годот;

public partial class ДомУзел
{
    // что висит на доске — снимок вопроса (`Беседы.Объявления`)
    private IReadOnlyList<Объявление> _объявления = System.Array.Empty<Объявление>();

    // какие объявления о мене герой уже прочёл (день, кто, что): второй раз знание не копится
    private readonly HashSet<(int день, string кто, string что)> _прочёл = new();

    /// <summary>Перевесить доску: снимок вопроса, пока дом спит (до метели дом
    /// не идёт — тогда на доске только бумажка с осени).</summary>
    private void Доска_вопроса(House дом_)
    {
        if (_беседы is null || _партия is null)
            return;
        _объявления = _беседы.Объявления(дом_, _партия.сеанс.я, Округа_?.заражение, Зерно, до_метели: _пролог is not null);
        _мир.Объявления(_объявления.Select(о => о.текст).ToList());
    }

    private string У_доски()
    {
        // до метели вопросов нет, а дом не идёт — доску читают сразу
        if (_пролог is not null && _объявления.Count == 0 && _партия is not null)
            Доска_вопроса(_партия.прогон.h);
        return _объявления.Count == 0
            ? "доска объявлений — пустая"
            : $"доска объявлений: «{_объявления[0].текст}»"
              + (_объявления.Count > 1 ? $" и ещё {_объявления.Count - 1}" : "")
              + $"\n{Жми}  читать";
    }

    /// <summary>Прочитать доску: все объявления окном. Объявление о мене — знание
    /// о шкафе того, кто его повесил.</summary>
    private void К_доске()
    {
        if (_партия is null)
            return;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        if (Дом_спит)
            foreach (var о in _объявления)
                if (о.кто is string кто && о.ресурс is string что && _прочёл.Add((h.day, кто, что)))
                    Социальное.note_signal(я, кто, что, о.сколько, 0.5);
        _окно.Показать("ДОСКА ОБЪЯВЛЕНИЙ",
            () => _объявления.Count == 0 ? "Пусто — только кнопки от прошлых бумажек."
                                         : string.Join("\n\n", _объявления.Select(о => "— " + о.текст)),
            () => new[] { new СтрокаОкна("отойти", true, () => _окно.Убрать()) });
        Мышь();
    }

    /// <summary>Проба: доска — перевесить и встать перед ней (только песочница);
    /// ответ — объявления.</summary>
    public string Проба_доска()
    {
        if (!Пути.Песочница)
            return "не песочница";
        if (_партия is null || !Дом_спит)
            return "дом не спит";
        Доска_вопроса(_партия.прогон.h);
        if (_мир.Доска is { } доска)
        {
            _окно.Убрать();
            _герой.GlobalPosition = доска.GlobalPosition + new Vector3(0, -1.45f + 0.05f, 1.2f);
            _герой.Rotation = Vector3.Zero;
            _герой.Прямо();
        }
        return string.Join(" | ", _объявления.Select(о => о.текст));
    }

    /// <summary>Проба: жилец двери <paramref name="кв"/> умер сегодня (только песочница,
    /// без разбора дома — ради свечи), свечи перевешиваются, герой встаёт к двери.</summary>
    public string Проба_помин(int кв)
    {
        if (!Пути.Песочница)
            return "не песочница";
        if (_партия is null || !Дом_спит)
            return "дом не спит";
        var h = _партия.прогон.h;
        if (h.alive().FirstOrDefault(p => p.apt == кв && p != _партия.сеанс.я) is not NPC кто)
            return "за дверью никого";
        кто.alive = false;
        кто.died_day = h.day;
        _план_вопроса = _партия.сеанс.План();
        var свечи = Беседы.Свечи(_план_вопроса, h.day);
        _мир.Свечи(свечи);
        Проба_к_двери(кв);
        return $"свечи: {string.Join(", ", свечи)}";
    }

    /// <summary>Проба: прочитать доску (только песочница) — окно открыто?</summary>
    public string Проба_читать_доску()
    {
        if (!Пути.Песочница)
            return "не песочница";
        К_доске();
        return _окно.открыт ? "окно" : "окно не открылось";
    }
}
