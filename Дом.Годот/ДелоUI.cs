// Долгое дело: взлом, обыск — то, что делается не мгновенно.
//
// Посреди экрана, сразу под прицелом, — полоса, которая заполняется,
// и в ней слово с бегущими точками («взлом.», «взлом..», «взлом...»);
// под полосой — как бросить. Пока дело идёт, герой скован: ни шагу,
// ни поворота головы (`Герой.Скован`), экраны не открываются, и мышь
// остаётся за делом, а не за камерой (задание автора, пп. 1 и 5: карман
// открывался посреди взлома и ложился поверх шкалы). Бросить — клавиша
// действия или Esc; ничего не случилось.
//
// Дело, которому нужен курсор (мини-игра), говорит об этом само
// (`Долгое.мышь`): тогда корневой узел отпускает мышь на время дела,
// а камера по-прежнему стоит.
//
// **Мини-игра «Взлом» — удержание в зоне** (ГДД 7; `Дом.Ядро.МиниИгры`).
// Под полосой — дорожка, по ней плавает светлая зона, метка идёт за мышью;
// качество — доля времени, что метка была в зоне, пока шкала шла. Ширину
// зоны даёт ядро (Смекалка до третьего уровня — шире), и с третьего игры
// нет вовсе: дело идёт само, как раньше. Качество отдаётся ядру числом:
// половина — «как обычно», прежний бросок.
//
// Первая версия ставила слово и тонкую черту над подсказкой, но корневой
// узел раскладывал экран раньше, чем шкала появлялась, — и слово висело
// в левом верхнем углу, а черты не было видно вовсе (у неё не было
// размера). Теперь шкала раскладывается и сама, по размеру родителя.
//
// Итог дела меняет дом, а менять его можно, только пока он спит на вопросе.
// Поэтому, пока шкала бежит, ответить на вопрос нельзя (`ДомУзел.Ответить`):
// дом не проснётся посреди куска, и итог ляжет в спящий дом.
//
// **Дело идёт кусками** (задание автора, п. 24; `ХодВремени.Кусков`).
// Шкала делится на куски, и на границе куска дело отдаёт дому его часы
// (`Долгое.кусок`): дом просыпается, соседи живут эти часы, и шкала ждёт,
// пока он снова уснёт на вопросе дня. Спросил дом другое — стучат в дверь,
// застали — шкала стоит, пока не ответишь; ответ в это время можно дать.
// Кусок сказал «хватит» (застали на стуке) — дело кончилось. Долгое дело
// ускоряет время: полтора часа дня за десять секунд шкалы.

using Godot;
using Дом.Экран;

namespace Дом.Годот;

/// <summary>Что делается долго: слово для шкалы, сколько секунд, что
/// сделать в конце, что — если прервали, что — пока идёт (прошло секунд),
/// нужен ли делу курсор, на сколько кусков оно дробится и что сделать
/// на границе куска (номер куска; false — дело кончилось, дальше не идти),
/// сколько в нём часов дня — для часов над телом, как оно выглядит
/// (движение для аниматора, п. 21) и что при нём в руках (инструмент дела).
/// Последний кусок — это <paramref name="готово"/>.</summary>
public sealed record Долгое(string слово, double секунд, System.Action готово,
                            System.Action? прервано = null,
                            System.Action<double>? идёт = null,
                            bool мышь = false,
                            int кусков = 1,
                            System.Func<int, bool>? кусок = null,
                            double часов = 0.0,
                            Движение? движение = null,
                            string? в_руках = null,
                            Дом.Ядро.МиниИгра? мини = null,
                            double зона = 0.22);

public partial class ДелоUI : Control
{
    private Panel _рамка = null!;
    private ColorRect _шкала = null!;
    private Label _слово = null!;
    private Label _как_бросить = null!;
    private Долгое? _дело;
    private Предмет? _цель;
    private double _прошло;
    private double _без_взгляда;
    private int _сделано;          // сколько кусков уже отдано дому
    private bool _ждёт;            // кусок отдан — ждём, пока дом снова уснёт

    // мини-игра: дорожка, зона, метка; сколько секунд метка была в зоне из скольких
    private ColorRect _дорожка = null!;
    private ColorRect _зона = null!;
    private ColorRect _метка = null!;
    private double _в_зоне, _играно, _фаза;
    private float _где_метка = 0.5f, _где_зона = 0.5f;
    private const float ДОРОЖКА = 14;

    private const double ТОЧКИ = 0.3;       // как часто прибавляется точка
    private const double ТЕРПЕНИЕ = 0.25;   // сколько можно не смотреть на вещь

    private const float ШИРИНА = 320;
    private const float ВЫСОТА = 30;
    private const float ОТ_ПРИЦЕЛА = 24;    // полоса — сразу под точкой прицела

    public bool занят => _дело is not null;

    /// <summary>Кусок отдан дому, и шкала стоит, пока он живёт своё. В это
    /// время на вопрос ответить можно: кусок уже лёг в дом.</summary>
    public bool ждёт => _дело is not null && _ждёт;

    /// <summary>Как выглядит идущее дело — движение для аниматора героя.</summary>
    public Движение? движение => _дело?.движение;

    /// <summary>Что в руках, пока идёт дело: его инструмент.</summary>
    public string? в_руках => _дело?.в_руках;

    /// <summary>Сколько часов дня прошло в деле, но ещё не отдано дому.</summary>
    public double часов_не_отдано => не_отдано * (_дело?.часов ?? 0.0);

    /// <summary>В какой день дело начато: ночь посреди дела его обрывает.</summary>
    public int день { get; private set; }

    /// <summary>Какая доля дела прошла, но ещё не отдана дому, — в долях
    /// всего дела. Для часов над телом: они идут и посреди куска.</summary>
    public double не_отдано
    {
        get
        {
            if (_дело is null || _дело.секунд <= 0)
                return 0.0;
            double доля = System.Math.Clamp(_прошло / _дело.секунд, 0.0, 1.0);
            return System.Math.Max(0.0, доля - _сделано / (double)System.Math.Max(1, _дело.кусков));
        }
    }

    /// <summary>Нужен ли идущему делу курсор (мини-игра), а не захваченная мышь.</summary>
    public bool нужна_мышь => _дело?.мышь ?? false;

    /// <summary>Шла ли в последнем (или идущем) деле мини-игра.</summary>
    public bool играл { get; private set; }

    /// <summary>Как сыграно в последнем деле: доля времени в зоне;
    /// половина — если не играли вовсе. Живёт и после конца дела — его
    /// читает итог.</summary>
    public double качество => _играно > 0 ? _в_зоне / _играно : 0.5;

