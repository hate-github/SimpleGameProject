// Камера на пролёт (ГДД 15, уровень 3): повесить над своей дверью, писать
// площадку на каждом вопросе, показать запись в телефоне. Что можно и что
// видно — ядро (`Петля/Камера.cs`) и экран (`Дом.Экран.КамераГероя`); здесь
// только кнопки, коробочка над дверью и вкладка.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    /// <summary>
    /// Строка камеры в окне своей двери: висит — что с ней; есть при себе
    /// или дома — повесить (серым, если нельзя, с причиной); нет — ничего.
    /// </summary>
    private СтрокаОкна? Камера_у_двери(House h, NPC я)
    {
        if (Округа_?.камера is { } кам)
            return new СтрокаОкна($"над дверью камера — {(кам.Работает(h) ? "пишет" : "без тока не пишет")}; запись — в телефоне",
                                  false, null);
        if (я.снаряжение is not { } с || !(с.Есть(Камера.ПРЕДМЕТ) || с.дома.Contains(Камера.ПРЕДМЕТ)))
            return null;
        string? нельзя = Камера.Нельзя(h, я, _ручки);
        return new СтрокаОкна(нельзя is null
                                  ? $"повесить камеру над дверью (≈{Часы_текстом(Камера.Часы(_ручки))} ч)"
                                  : $"повесить камеру — {нельзя}",
                              нельзя is null, Повесить_камеру);
    }

    /// <summary>Повесить камеру: часы — поступком героя, пока дом спит.</summary>
    private void Повесить_камеру()
    {
        if (_партия is null || !Дом_спит || !Можно_тут())
            return;
        var я = _партия.сеанс.я;
        if (Камера.Повесить(_партия.прогон.h, я, _ручки) is not { } к)
            return;
        _мир.Камера_над(к.квартира);
        Сделать_тут(new Сделано(true, Камера.Часы(_ручки),
                                $"повесил{(я.sex == "ж" ? "а" : "")} камеру над дверью — запись в телефоне, пока есть ток"));
    }

    /// <summary>
    /// На вопросе: камера пишет то, что видно с её места, — вчерашнее (вечер мог
    /// пройти без вопросов) и сегодняшнее; ток меряется сегодняшний. И висит
    /// над той дверью, где её повесили, — новая жизнь её снимает.
    /// </summary>
    private void Камера_вопроса(House h)
    {
        var кам = Округа_?.камера;
        _мир.Камера_над(кам?.квартира);
        if (кам is null || _партия is null)
            return;
        foreach (int день in new[] { h.day - 1, h.day })
            кам.Записать(h, Дом.Экран.КамераГероя.Снять(_партия.сеанс.хроника, день), _партия.сеанс.я.id);
    }

    /// <summary>Проба: дать герою камеру, материалы и дело электрика и открыть
    /// окно своей двери. Только в песочнице.</summary>
    public string Проба_камера_дать()
    {
        if (!Пути.Песочница || _партия is null || !Дом_спит)
            return "не песочница или дом не спит";
        var я = _партия.сеанс.я;
        я.снаряжение?.Подобрать(Камера.ПРЕДМЕТ, _инструменты);
        я.stock["материалы"] = я.stock.Взять("материалы", 0.0) + _ручки["камера_материалы"];
        Округа_?.Узнал(Камера.ЭЛЕКТРИК);
        _окно.Убрать();
        Своя_дверь();
        return _окно.открыт ? "своя дверь" : "окно не открылось";
    }

    /// <summary>Проба: что с камерой; телефон — на её вкладке. Только в песочнице.</summary>
    public string Проба_камера()
    {
        if (!Пути.Песочница || _партия is null || !Дом_спит)
            return "не песочница или дом не спит";
        if (Округа_?.камера is not { } к)
            return "камеры нет";
        // короткий путь к метели телефон не заряжает — пробе нужен живой
        string заряд = "";
        if (Округа_ is { } о && о.телефон.сел)
        {
            о.телефон.Разложить(new System.Text.Json.Nodes.JsonObject { ["заряд"] = 100.0 });
            заряд = " (телефон сел — заряжен пробой)";
        }
        if (!_телефон.открыт)
            Телефон(false);
        _телефон.Обновить();
        _телефон.К_камере();
        var з = Камера_запись();
        return $"висит кв.{к.квартира}, этаж {к.этаж}, {(к.Работает(_партия.прогон.h) ? "пишет" : "без тока")}, "
               + $"кадров {к.кадры.Count}, строк {з?.строки.Count ?? -1}"
               + (з?.строки.FirstOrDefault() is { } с ? $": {с.текст}" : "") + заряд;
    }

    /// <summary>Что во вкладке «камера» — или null: камеры нет, вкладки тоже.
    /// Читает дом — только пока он спит.</summary>
    private (string шапка, IReadOnlyList<Дом.Экран.СтрокаКамеры> строки)? Камера_запись()
    {
        if (Округа_?.камера is not { } кам || _партия is null || !Дом_спит)
            return null;
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        return (Дом.Экран.КамераГероя.Шапка(h, кам),
                Дом.Экран.КамераГероя.Запись(h, я, кам, я.час()));
    }
}
