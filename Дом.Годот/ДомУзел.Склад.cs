// Склады вне дома вещами (замечание автора: «пока еду не вытащил из кладовой
// участка, у неё по сути нет срока годности»). Правило — `Продукты`
// (места УЧАСТОК и УБЕЖИЩЕ): банки там свои, со своим возрастом, и стареют.
// Здесь — как это видно в окне кладовой и стеллажа: что лежит и какой
// свежести, одной строкой.

using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    /// <summary>Еда на складе вещами — что там и какой свежести; сверено,
    /// пока дом спит. Склада в учёте нет — пусто.</summary>
    private string Склад_словами(IУбежище у)
    {
        if (_партия is null || Продукты.У(_партия.сеанс.я) is not { } п || п.Место(у) is not МестоЕды м)
            return "";
        п.Сверить(_партия.сеанс.дом, _партия.сеанс.я);
        var вещи = п.В(м);
        if (вещи.Count == 0)
            return " Еды не осталось.";
        var что = вещи.GroupBy(x => x.вид)
            .OrderBy(г => п.Вид(г.First()).имя, System.StringComparer.Ordinal)
            .Select(г =>
            {
                var вид = п.Вид(г.First());
                int просрочено = г.Count(x => п.Свежесть(x) == Свежесть.ПРОСРОЧЕНА);
                int испорчено = г.Count(x => п.Свежесть(x) == Свежесть.ИСПОРЧЕНА);
                var хвост = new List<string>();
                if (просрочено > 0)
                    хвост.Add($"просрочено {просрочено}");
                if (испорчено > 0)
                    хвост.Add($"{вид.испорчен} {испорчено}");
                return $"{вид.имя.ToLowerInvariant()} {г.Count()}"
                       + (хвост.Count > 0 ? $" ({string.Join(", ", хвост)})" : "");
            });
        return " Еда: " + string.Join(", ", что) + ".";
    }
}
