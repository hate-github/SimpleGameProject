// Мини-игра «Разговор» в движке (ГДД 7). Что считается — `Дом.Ядро/Петля/Реплики.cs`;
// узел ставит окно с тремя репликами и считает секунды.
//
// Играется перед ответом дому «поговорить» — у двери в метель (тема беседы)
// или мыслью из телефона: окно посередине с лицом соседа, реплики в случайном
// порядке, под ними — сколько секунд осталось. Выбрал — как сыграно ложится
// герою в `сыграно`, и ответ уходит дому; время вышло — промолчал, ответ тоже
// уходит; закрыл окно — разговор не начат. Смекалка с третьего уровня — игры
// нет, выходит «само» (`МиниИгры.Само`), как у «Взлома».

using Godot;
using Дом.Ядро;
using Дом.Экран;

namespace Дом.Годот;

public partial class ДомУзел
{
    /// <summary>Идущая реплика: номер ответа дому, собеседник, сколько секунд.</summary>
    private sealed class РепликаИгра
    {
        public required int номер;
        public required NPC с;
        public required double всего;
        public required Вопрос вопрос;        // на какой вопрос дома ответ
        public bool ложь;                      // врёт — «отвод подозрений»
        public bool торг;                      // мена — торг
        public bool просьба;                   // просьба — убеждение
        public double осталось;
    }

    private РепликаИгра? _реплика_игра;

    /// <summary>Перед разговором дома — выбрать, как говорить; <paramref name="ложь"/> —
    /// как соврать (ответ «соврать», ГДД 7: «отвод подозрений»).</summary>
    private void Разговор_перед_делом(int номер, NPC с, bool ложь = false, bool торг = false,
                                      bool просьба = false)
    {
        if (_партия?.Ждёт() is not { } вопрос_дома)
            return;
        double всего = Реплики.Секунд(_ручки);
        _реплика_игра = new РепликаИгра { номер = номер, с = с, всего = всего, осталось = всего,
                                          вопрос = вопрос_дома.вопрос, ложь = ложь, торг = торг,
                                          просьба = просьба };
        var тоны = Реплики.На_выбор(_наследие.нирвана, Рассудок.Цинизм(_наследие.рассудок, _ручки))
            .OrderBy(_ => GD.Randi())              // порядок — не подсказка
            .ToList();
        // помнит из прошлых разговоров (и жизней), каким тоном с ним выходит
        string помнит = Реплики.Помнит(з => Округа_?.Знает(з) == true, с) is { } тон
            ? $"\nпомнишь: {(с.sex == "ж" ? "с ней" : "с ним")} — {Реплики.Кратко(тон)}" : "";
        // Смекалка видит по лицу, каким тоном с ним выходит (ГДД 14)
        var я = _партия.сеанс.я;
        if (Реплики.Видно_по_нему(с, я, _ручки) is { } видно)
            помнит += $"\n{видно}";
        string она = с.sex == "ж" ? "а" : "";
        _окно.Показать($"{(ложь ? "СОВРАТЬ" : торг ? "ТОРГ" : просьба ? "ПРОСЬБА" : "РАЗГОВОР")} — {Как_зовут(с).ToUpperInvariant()}",
            () => (ложь ? $"Как соврать, чтобы поверил{она}? Решай сразу: пауза — тоже ответ."
                   : торг ? $"Как сторговаться, чтобы взял{она}? Решай сразу: пауза — тоже ответ."
                   : просьба ? $"Как попросить, чтобы дал{она}? Решай сразу: пауза — тоже ответ."
                        : $"Как {(с.sex == "ж" ? "с ней" : "с ним")} говорить? Решай сразу: пауза — тоже ответ.") + помнит,
            // в плохом настроении добрая реплика не идёт с языка (ГДД 14): серая
            () => тоны.Select(т => Реплики.Не_идёт(т, я.mood, _ручки) is { } нельзя
                      ? new СтрокаОкна($"{Реплики.Слова(т)} — {нельзя}", false, null)
                      : new СтрокаОкна(Реплики.Слова(т), true, () => Реплика_выбрана(т))).ToList(),
            лицо: с.id);
        Мышь();
    }

    /// <summary>Каждый кадр: секунды на реплику; окно закрыли — разговора нет.</summary>
    private void Реплика_кадр(double delta)
    {
        if (_реплика_игра is not { } и)
            return;
        if (!_окно.открыт)
        {
            _реплика_игра = null;
            Сказать("не стал говорить");
            return;
        }
        и.осталось -= delta;
        if (и.осталось <= 0)
        {
            Реплика_выбрана(null);
            return;
        }
        _окно.Весть($"осталось {Mathf.CeilToInt((float)и.осталось)} с");
    }

    /// <summary>Реплика выбрана (null — время вышло): как сыграно — герою,
    /// ответ — дому.</summary>
    private void Реплика_выбрана(Тон? т)
    {
        if (_реплика_игра is not { } и || _партия is null)
            return;
        _реплика_игра = null;
        _окно.Убрать();
        if (_партия.Ждёт() is not { } вопрос_дома || вопрос_дома.вопрос != и.вопрос)
            return;
        double к = Реплики.Качество(и.с, т, и.осталось / и.всего);
        if (и.ложь)
        {
            // соврал неубедительно — не поверил; ложь всё равно сказана
            string она = и.с.sex == "ж" ? "а" : "";
            if (Реплики.Ложь_провалена(к))
                Реплики.Не_поверил(и.с, _партия.сеанс.я, _ручки);
            Сказать(Реплики.Ложь_провалена(к) ? $"не поверил{она} — видно по лицу" : $"кажется, поверил{она}");
            Ответить(и.номер, играть: false);
            return;
        }
        _партия.сеанс.я.сыграно = МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, к, _ручки);
        // торг не тем тоном — сосед недоволен ещё до того, как ответил на мену
        bool сорван = и.торг && Реплики.Торг_сорван(к);
        if (сорван)
            Реплики.Торг_сорвался(и.с, _партия.сеанс.я, _ручки);
        // просил не так — тоже: обиделся до того, как ответил
        bool не_так = и.просьба && Реплики.Торг_сорван(к);
        if (не_так)
            Реплики.Просьба_сорвалась(и.с, _партия.сеанс.я, _ручки);
        // попал в его тон — запомнил: это знание переживёт жизнь (ГДД 10)
        if (т is { } тон && Реплики.Запомнить(тон, к))
            Округа_?.Узнал(Реплики.Знание(и.с, тон));
        Сказать(т is null ? "промолчал — пауза затянулась"
                : сорван ? "давил не тем — торг не задался"
                : не_так ? "просил не так — не понравилось"
                : Реплики.Итог(к));
        Ответить(и.номер, играть: false);
    }
}
