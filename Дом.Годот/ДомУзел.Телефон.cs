// Телефон героя в движке (ГДД 19): заряд, сеть, «провести время».
// Что считается — `Дом.Ядро/Петля/Телефон.cs`; узел знает то, чего не знает
// ядро: где герой стоит (у розетки он только дома) и который час на его часах.
//
// Свет и сеть дома читаются, только пока дом спит на вопросе (`Свет_и_сеть`),
// и живут снимком до следующего: правило то же, что у плана и подсказок.
// До метели дом не идёт — свет есть, сеть полная.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    private bool _свет_дома = true;          // есть ли свет у героя — снимок на вопросе
    private double _сеть_дома = 1.0;         // `House.network` — снимок на вопросе

    private Дом.Ядро.Телефон? Телефон_ => Округа_?.телефон;

    /// <summary>Свет и сеть — пока дом спит: на вопросе дома.</summary>
    private void Свет_и_сеть(House дом)
    {
        var я = _партия!.сеанс.я;
        _свет_дома = дом.powered(я);
        _сеть_дома = дом.network;
    }

    /// <summary>Часы героя от начала: день × 24 + час на его часах — или
    /// null, если часов ещё нет.</summary>
    private double? Часы_героя_всего()
    {
        if (_ход is null || _ход.час <= 0.0 || _партия is null)
            return null;
        double? ч = Ночь_сейчас ? _ход.час + _поздно : _ход.На_часах(_дело.часов_не_отдано)?.час;
        if (ч is null)
            return null;
        return Дом.Ядро.Телефон.Часы(_пролог?.день, _партия.сеанс.дом.day, ч.Value);
    }

    /// <summary>Каждый кадр: заряд к часам героя. У розетки — дома, при свете
    /// (до метели свет есть всегда).</summary>
    private void Телефон_кадр()
    {
        if (Телефон_ is not { } т || Часы_героя_всего() is not double сейчас)
            return;
        bool свет = _пролог is not null || _свет_дома;
        bool у_розетки = свет && _мир.ДомаЛи(_герой.GlobalPosition);
        т.Сверить(сейчас, у_розетки, _телефон.открыт, _ручки);
    }

    /// <summary>Строка состояния: палки сети и заряд.</summary>
    private string Сеть_телефона()
    {
        if (Телефон_ is not { } т)
            return "";
        if (т.сел)
            return "сел";
        int палок = Дом.Ядро.Телефон.Палок(_пролог is not null ? 1.0 : _сеть_дома);
        string сеть = палок == 0 ? "нет сети" : "▂▄▆█"[..палок] + new string('·', 4 - палок);
        return $"{сеть}  {Текст.G(System.Math.Floor(т.заряд))}%";
    }

    /// <summary>«Провести время» (ГДД 19): только когда герой распоряжается
    /// днём; час проживается, дом в нём живёт.</summary>
    private void Провести_время()
    {
        if (_партия is null || Телефон_ is not { } т || !Можно_тут())
            return;
        var с = т.Провести_время(_партия.сеанс.я, _ручки);
        if (!с.да)
        {
            Сказать(с.весть);
            return;
        }
        Сделать_тут(с);
    }
}
