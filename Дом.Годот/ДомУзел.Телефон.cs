// Телефон героя в движке (ГДД 19): заряд, сеть, «провести время»,
// «написать в чат» (ГДД 14).
// Что считается — `Дом.Ядро/Петля/Телефон.cs`; узел знает то, чего не знает
// ядро: где герой стоит (у розетки он только дома) и который час на его часах.
//
// Свет и сеть дома читаются, только пока дом спит на вопросе (`Свет_и_сеть`),
// и живут снимком до следующего: правило то же, что у плана и подсказок.
// До метели дом не идёт — свет есть, сеть полная.

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    private bool _свет_дома = true;          // есть ли свет у героя — снимок на вопросе
    private double _сеть_дома = 1.0;         // `House.network` — снимок на вопросе
    private int? _сеть_день;                  // последний день метели со связью — снимок на вопросе

    private Дом.Ядро.Телефон? Телефон_ => Округа_?.телефон;

    /// <summary>Свет и сеть — пока дом спит: на вопросе дома.</summary>
    private void Свет_и_сеть(House дом)
    {
        var я = _партия!.сеанс.я;
        _свет_дома = дом.powered(я);
        _сеть_дома = дом.network;
        if (дом.network > 0)
            _сеть_день = дом.day;
    }

    /// <summary>Лента новостей телефона (ГДД 19): до метели — летопись
    /// по сегодня, в метель — и события дня, пока ловила сеть.</summary>
    private IReadOnlyList<Дом.Экран.Новость> Новости_телефона()
    {
        if (_партия is null)
            return System.Array.Empty<Дом.Экран.Новость>();
        int сегодня = _пролог?.день ?? _партия.сеанс.дом.day;
        var до = Дом.Экран.Новости.Из_летописи(_летопись, -10, _пролог is not null ? сегодня : -1);
        return Дом.Экран.Новости.Лента(до, _партия.сеанс.лента, _пролог is null ? _сеть_день : null, сегодня);
    }

    /// <summary>Часы героя от начала: день × 24 + час на его часах — или
    /// null, если часов ещё нет.</summary>
    private double? Часы_героя_всего()
    {
        if (_ход is null || _ход.час <= 0.0 || _партия is null)
            return null;
        double? ч = Ночь_сейчас ? _ход.час + _поздно : _ход.На_часах(_дело.часов_не_отдано)?.час;
        if (ч is null)
            return null;
        return Дом.Ядро.Телефон.Часы(_пролог?.день, _партия.сеанс.дом.day, ч.Value);
    }

    /// <summary>Каждый кадр: заряд к часам героя. У розетки — дома, при свете
    /// (до метели свет есть всегда).</summary>
    private void Телефон_кадр()
    {
        if (Телефон_ is not { } т || Часы_героя_всего() is not double сейчас)
            return;
        bool свет = _пролог is not null || _свет_дома;
        bool у_розетки = свет && _мир.ДомаЛи(_герой.GlobalPosition);
        т.Сверить(сейчас, у_розетки, _телефон.открыт, _ручки);
    }

    /// <summary>Строка состояния: палки сети и заряд.</summary>
    private string Сеть_телефона()
    {
        if (Телефон_ is not { } т)
            return "";
        if (т.сел)
            return "сел";
        int палок = Дом.Ядро.Телефон.Палок(_пролог is not null ? 1.0 : _сеть_дома);
        string сеть = палок == 0 ? "нет сети" : "▂▄▆█"[..палок] + new string('·', 4 - палок);
        return $"{сеть}  {Текст.G(System.Math.Floor(т.заряд))}%";
    }

    private System.Text.Json.JsonElement? _шаблоны_чата;   // строки «чат» lines.json — читаются раз

    /// <summary>Почему сейчас не написать в чат — или null. Дом читается
    /// только во сне на вопросе дня; до метели чата дома нет (ГДД 14:
    /// «создаётся в день 0»).</summary>
    private string? Чат_нельзя()
    {
        if (_партия is null || Телефон_ is not { } т)
            return "чата нет";
        if (_пролог is not null)
            return "чат дома заведут, когда начнётся";
        if (!День_героя || _дело.занят)
            return "сейчас не до этого";
        return ЧатГероя.Нельзя(_партия.прогон.h, _партия.сеанс.я, т, _ручки);
    }

    /// <summary>Кого можно назвать в «кто это был?»: кто в доме, кроме героя,
    /// по квартирам — как герой его зовёт (имя или «сосед из кв.N»).</summary>
    private IReadOnlyList<(string id, string имя)> Соседи_для_чата()
    {
        if (_партия is null || _пролог is not null || !День_героя)
            return System.Array.Empty<(string, string)>();
        var h = _партия.прогон.h;
        var я = _партия.сеанс.я;
        return h.alive()
            .Where(о => о.здесь() && !string.Equals(о.id, я.id, System.StringComparison.Ordinal))
            .OrderBy(о => о.apt)
            .Select(о => (о.id, Знакомство.Как_зовут(h, я, о)))
            .ToList();
    }

    /// <summary>«Написать в чат» (ГДД 14): только когда герой распоряжается
    /// днём; реплика ложится в чат, пока дом спит, минуты проживаются.</summary>
    private void Написать_в_чат(string тема, string? кого)
    {
        if (_партия is null || Телефон_ is not { } т || Округа_ is not { } о || _пролог is not null || !Можно_тут())
            return;
        var h = _партия.прогон.h;
        _шаблоны_чата ??= ЧатГероя.Шаблоны(Пути.Данные);
        var н = ЧатГероя.Написать(h, _партия.сеанс.я, т, _ручки, _шаблоны_чата.Value, тема,
                                  кого is null ? null : h.get(кого), о.зерно);
        if (!н.да)
        {
            Сказать(н.весть);
            return;
        }
        _телефон.Обновить();       // реплика героя — в чат, пока дом спит
        Сделать_тут(new Сделано(true, н.часов, н.весть));
    }

    /// <summary>«Провести время» (ГДД 19): только когда герой распоряжается
    /// днём; час проживается, дом в нём живёт.</summary>
    private void Провести_время()
    {
        if (_партия is null || Телефон_ is not { } т || !Можно_тут())
            return;
        var с = т.Провести_время(_партия.сеанс.я, _ручки);
        if (!с.да)
        {
            Сказать(с.весть);
            return;
        }
        Сделать_тут(с);
    }
}
