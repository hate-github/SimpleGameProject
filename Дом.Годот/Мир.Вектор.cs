// Промзона «Вектор-3» (задание автора, пп. 6–7): забор, проходная без
// сторожа, пять корпусов вокруг заметённой площадки. Двери корпусов —
// `Предмет`ы: у каждой подсказка (номер, что за корпус, что видно у двери)
// и обыск делом. Считать обыск — дело `Дом.Ядро.Вектор`; здесь только
// забор, коробки корпусов и их двери.
//
// Под открытым небом, как двор: снег и ветер здесь те же. Далеко от двора,
// магазина, участка и бункера — сюда переносит поход.

using Godot;

namespace Дом.Годот;

public partial class Мир
{
    private static readonly Vector3 ВЕКТОР = new(300, 0, 300);
    private const float ВЕК_Ш = 50f, ВЕК_Г = 40f;

    /// <summary>Двери корпусов по номеру.</summary>
    public IReadOnlyDictionary<int, Предмет> ДвериКорпусов => _двери_корпусов;
    private readonly Dictionary<int, Предмет> _двери_корпусов = new();

    /// <summary>Проходная — дорога домой.</summary>
    public Предмет? Проходная { get; private set; }

    /// <summary>Где встаёт пришедший: за проходной, лицом к корпусам.</summary>
    public Vector3 ВходВектора => ВЕКТОР + new Vector3(0, 0.1f, ВЕК_Г / 2 - 3.5f);

    /// <summary>Он ли в промзоне.</summary>
    public bool ВВекторе(Vector3 где)
        => Math.Abs(где.X - ВЕКТОР.X) < ВЕК_Ш / 2 + 1 && Math.Abs(где.Z - ВЕКТОР.Z) < ВЕК_Г / 2 + 1
           && где.Y > -1 && где.Y < 20;

    // корпус: номер, середина, размер и какой стороной дверь к площадке (+X, −X, +Z)
    private static readonly (int номер, Vector3 где, Vector3 размер, Vector3 к_площадке)[] КОРПУСА =
    {
        (1, new(-16, 0, 7), new(9, 7, 9), Vector3.Right),
        (2, new(-16, 0, -9), new(9, 5, 11), Vector3.Right),
        (3, new(0, 0, -14), new(14, 9, 8), Vector3.Back),
        (4, new(16, 0, -9), new(9, 10, 9), Vector3.Left),
        (5, new(16, 0, 7), new(9, 5, 11), Vector3.Left),
    };

    /// <summary>Земля, забор, корпуса с дверями и табличками, проходная.</summary>
    private void Вектор_построить()
    {
        _двери_корпусов.Clear();
        var снег = Материал(new Color("#c8ccd0"), 1.0f);
        var бетон = Материал(new Color("#6a6862"), 0.95f);
        var кирпич = Материал(new Color("#6e4a3c"), 0.95f);
        var железо = Материал(new Color("#3c3f42"), 0.6f);
        var тьма = Материал(new Color("#141414"), 1.0f);
        Vector3 О(float x, float y, float z) => ВЕКТОР + new Vector3(x, y, z);
        float ш = ВЕК_Ш / 2, г = ВЕК_Г / 2;

        // заметённая площадка и забор из плит, в южной стороне — проходная
        Коробка(снег, new Vector3(ВЕК_Ш + 4, 0.4f, ВЕК_Г + 4), О(0, -0.2f, 0));
        Коробка(бетон, new Vector3(ВЕК_Ш, 2.4f, 0.2f), О(0, 1.2f, -г));
        Коробка(бетон, new Vector3(0.2f, 2.4f, ВЕК_Г), О(-ш, 1.2f, 0));
        Коробка(бетон, new Vector3(0.2f, 2.4f, ВЕК_Г), О(ш, 1.2f, 0));
        Коробка(бетон, new Vector3(ш - 1.5f, 2.4f, 0.2f), О(-(ш + 1.5f) / 2, 1.2f, г));
        Коробка(бетон, new Vector3(ш - 1.5f, 2.4f, 0.2f), О((ш + 1.5f) / 2, 1.2f, г));
        Коробка(кирпич, new Vector3(3.0f, 2.8f, 2.4f), О(-3.2f, 1.4f, г - 1.2f));     // будка вахтёра
        Меш(железо, new Vector3(3.0f, 0.1f, 0.1f), О(0, 1.1f, г + 0.05f));            // шлагбаум, поднятый набок
        Проходная = Предмет.Вокруг(this, new Aabb(О(-1.5f, 0, г - 0.6f), new Vector3(3.0f, 2.4f, 1.2f)),
                                   0.05f, "проходная_вектора");
        AddChild(new Label3D
        {
            Text = "НПО «ВЕКТОР-3»",
            FontSize = 96,
            PixelSize = 0.006f,
            Modulate = new Color("#b8b0a0"),
            Position = О(-3.2f, 3.2f, г - 2.45f),
            Rotation = new Vector3(0, Mathf.Pi, 0),
            Shaded = false,
        });

        foreach (var (номер, где, размер, к) in КОРПУСА)
        {
            var середина = О(где.X, размер.Y / 2, где.Z);
            Коробка(номер == 1 ? бетон : кирпич, размер, середина);
            if (номер == 4)          // котельная с трубой
                Коробка(кирпич, new Vector3(1.4f, 12f, 1.4f), О(где.X + 2.5f, 6f, где.Z - 2.5f));
            // дверь — на стороне к площадке
            var полу = размер / 2;
            var у_двери = к.X != 0
                ? О(где.X + к.X * (полу.X + 0.06f), 1.1f, где.Z)
                : О(где.X, 1.1f, где.Z + к.Z * (полу.Z + 0.06f));
            var створка = к.X != 0 ? new Vector3(0.12f, 2.2f, 1.6f) : new Vector3(1.6f, 2.2f, 0.12f);
            Меш(тьма, створка, у_двери);
            var область = к.X != 0 ? new Vector3(1.2f, 2.2f, 2.0f) : new Vector3(2.0f, 2.2f, 1.2f);
            // область у двери — от земли, чуть наружу: на неё и смотрит прицел
            var низ = new Vector3(у_двери.X, ВЕКТОР.Y, у_двери.Z) + к * 0.5f;
            var дверь = Предмет.Вокруг(this, new Aabb(низ - new Vector3(область.X / 2, 0, область.Z / 2), область),
                                       0.05f, $"корпус_{номер}");
            _двери_корпусов[номер] = дверь;
            AddChild(new Label3D
            {
                Text = $"КОРПУС {номер}",
                FontSize = 64,
                PixelSize = 0.006f,
                Modulate = new Color("#d0c8b8"),
                Position = у_двери + new Vector3(0, 1.7f, 0) + к * 0.08f,
                // табличкой к площадке: Label3D смотрит вдоль +Z
                Rotation = new Vector3(0, к.X > 0 ? Mathf.Pi / 2 : к.X < 0 ? -Mathf.Pi / 2 : 0, 0),
                Shaded = false,
            });
        }
    }
}
