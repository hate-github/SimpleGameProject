// Гости участка (просьба автора: «к нему в участок пришли люди, чтобы
// ограбить» — и распорядок от этого встаёт). Правило — `Участок`
// (`Ходка`, `Конец_дня`, `Встретить`); здесь — как это видно герою:
// в окне дома кто-то стоял, пока он нёс сумки; на рассвете колотят
// в дверь дежурки — окно с ответом; пришёл в участок, а кладовая
// выгребена — «здесь кто-то был».

using Godot;
using Дом.Ядро;

namespace Дом.Годот;

public partial class ДомУзел
{
    /// <summary>Каждый кадр: к участку пришли, пока герой там, — встать
    /// из распорядка и спросить героя. Только пока дом спит на вопросе.</summary>
    private void Гости_кадр()
    {
        if (Участок_ is not { визит: { } в } у || _партия is null || _партия.Ждёт() is null
            || _окно.открыт || _находка.открыт || _переход.Visible || _меню.открыт || _дело.занят)
            return;
        var h = _партия.сеанс.дом;
        var я = _партия.сеанс.я;
        if (у.где != ВУчастке.УЧАСТОК)
        {
            // ушёл раньше, чем постучали, — возьмут без него
            у.Встретить(h, я, Встреча.ОТДАТЬ);
            return;
        }
        string кто = Кто_пришёл(h, в);
        if (_распорядок is not null)
            Встать_из_распорядка($"к участку пришли: {кто}");
        Окно_гостей(у, в, кто);
    }

    /// <summary>Окно у двери дежурки: поделиться, не открыть, встретить в дверях.</summary>
    private void Окно_гостей(Участок у, Визит в, string кто)
    {
        var я = _партия!.сеанс.я;
        int сколько = в.кто.Count;
        string встретить = я.weapon != Оружие.НЕТ
            ? $"встретить в дверях — в руках {я.weapon.Текст()}"
            : "встретить в дверях — с голыми руками";
        _окно.Показать("У ДВЕРИ УЧАСТКА",
            () => $"Рассвет. В железную дверь дежурки колотят: {кто}"
                  + (сколько > 1 ? $" — их {Сколько_человек(сколько)}" : "") + ". "
                  + "«Открывай! Знаем, что у тебя тут склад, — поделись по-хорошему».\n"
                  + $"В кладовой: {Кладовая_словами(у)}.",
            () => new[]
            {
                new СтрокаОкна("открыть и поделиться — отдать часть запаса", true,
                               () => Встретить_гостей(у, Встреча.ОТДАТЬ, кто)),
                new СтрокаОкна("не открывать — дверь железная, пусть ломают", true,
                               () => Встретить_гостей(у, Встреча.НЕ_ОТКРЫВАТЬ, кто)),
                new СтрокаОкна(встретить, true, () => Встретить_гостей(у, Встреча.ВСТРЕТИТЬ, кто)),
            });
        Мышь();
    }

    private void Встретить_гостей(Участок у, Встреча как, string кто)
    {
        _окно.Убрать();
        if (_партия is null || _партия.Ждёт() is null)
            return;
        var h = _партия.сеанс.дом;
        var итог = у.Встретить(h, _партия.сеанс.я, как);
        GD.Print($"[гости] {кто}: {как} → {итог.весть}");
        Сказать($"{кто}: {итог.весть}");
        Освежить_видно(h);
    }

    /// <summary>Кто стучит — как их знает герой.</summary>
    private string Кто_пришёл(House h, Визит в)
    {
        var имена = в.кто.Select(id => h.get(id)).OfType<NPC>().Select(p => Как_зовут(p)).ToList();
        return имена.Count switch
        {
            0 => "кто-то",
            1 => имена[0],
            _ => string.Join(", ", имена.Take(имена.Count - 1)) + " и " + имена[^1],
        };
    }

    private static string Сколько_человек(int н) => н switch
    {
        2 => "двое",
        3 => "трое",
        4 => "четверо",
        _ => $"{н}",
    };

    private static string Кладовая_словами(Участок у)
    {
        var есть = у.кладовая_что.Where(р => у.В_кладовой(р) >= 0.05)
            .Select(р => $"{р} {Текст.G(Текст.Округлить(у.В_кладовой(р), 1))}").ToList();
        return есть.Count == 0 ? "пусто" : string.Join(", ", есть);
    }

    /// <summary>Ходка к участку с полной тарой — под наблюдением из окон.</summary>
    private void Ходка_к_участку()
    {
        if (Участок_ is not { } у || _партия is null || _партия.сеанс.я.ноша is not { пусто: false })
            return;
        if (у.Ходка(_партия.прогон.h, _партия.сеанс.я).Count > 0)
            Сказать("уходя, оглянулся: в окне дома кто-то стоял и смотрел вслед");
    }

    /// <summary>Вернулся от участка с полной тарой — под наблюдением; хвост вести.</summary>
    private string Ходка_от_участка()
    {
        if (Участок_ is not { } у || _партия is null || _партия.сеанс.я.ноша is not { пусто: false })
            return "";
        return у.Ходка(_партия.прогон.h, _партия.сеанс.я).Count > 0
            ? " · в окне дома кто-то стоял — смотрел на твои сумки"
            : "";
    }

    /// <summary>Пришёл в участок: что пропало, пока его не было, — видно сразу.</summary>
    private string Пропажи_участка()
    {
        if (Участок_ is not { } у)
            return "";
        var пропало = у.Пропажи();
        return пропало.Ключи.Count == 0 ? ""
            : " · здесь кто-то был: в кладовой нет "
              + string.Join(", ", пропало.Ключи.OrderBy(к => к, System.StringComparer.Ordinal)
                                       .Select(к => $"{к} {Текст.G(пропало[к])}"))
              + "; следы на снегу — к нашему дому";
    }

    /// <summary>Как герой называет соседа.</summary>
    private static string Как_зовут(NPC p) => p.@short;

    /// <summary>Что ядро участка хочет сказать (слышал из камеры) — когда дом спит.</summary>
    private void Весть_участка()
    {
        if (Участок_?.Весть() is string весть)
            Сказать(весть);
    }
}
