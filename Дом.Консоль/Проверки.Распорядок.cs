// Проверка распорядка (просьба автора: жить днями, не разыгрывая каждый час,
// и вставать, когда что-то случилось; `Петля/Распорядок.cs`).
//
//  1. **Что делать.** По срочности: жажда раньше голода, голод раньше
//     холода; воды нет — топить снег; нечем — ждать; вентиляция — к вечеру
//     и только если сегодня не крутил.
//  2. **Когда встать.** Событие, где герой кто или кому, — встать с его
//     словами; чужое событие — нет; здоровье упало — встать; есть и пить
//     нечего — встать. Свои вопросы (замысел, «соврать») — ответить лучшим,
//     дверь, налёт, просьба — будят.
//  3. **Живой игрой.** Героиня в участке живёт по распорядку две недели,
//     ничего не делая руками: ест, пьёт, топит, а воды нарочно мало — и она
//     топит снег; кончилось топливо — ломает мебель. Жива, и снег топила.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Распорядок_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);

        // ---- 1. что делать ----
        bool Всё(Привычка _) => true;
        bool Без_воды(Привычка п) => п != Привычка.ПОПИТЬ;
        bool Ничего(Привычка _) => false;
        var случаи = new (string имя, Быт быт, Func<Привычка, bool> можно, Привычка ждём)[]
        {
            ("жажда и голод", new Быт(20, 20, 5, false, false, 10), Всё, Привычка.ПОПИТЬ),
            ("голод", new Быт(20, 90, 5, false, false, 10), Всё, Привычка.ПОЕСТЬ),
            ("холодно", new Быт(90, 90, 5, false, false, 10), Всё, Привычка.ЗАТОПИТЬ),
            ("холодно, но топится", new Быт(90, 90, 5, true, false, 10), Всё, Привычка.ЖДАТЬ),
            ("жажда, воды нет", new Быт(90, 20, 20, false, false, 10), Без_воды, Привычка.СНЕГ),
            ("жажда, ничего нет", new Быт(90, 20, 20, false, false, 10), Ничего, Привычка.ЖДАТЬ),
            ("холодно, топлива нет", new Быт(90, 90, 5, false, false, 10), п => п == Привычка.ДРОВА, Привычка.ДРОВА),
            ("вентиляция утром", new Быт(90, 90, 20, true, true, 9), Всё, Привычка.ЖДАТЬ),
            ("вентиляция вечером", new Быт(90, 90, 20, true, true, 19), Всё, Привычка.ВЕНТИЛЯЦИЯ),
            ("всё хорошо", new Быт(90, 90, 20, false, false, 12), Всё, Привычка.ЖДАТЬ),
        };
        foreach (var (имя, быт, можно, ждём) in случаи)
            if (Распорядок.Что(быт, можно) != ждём)
                плохо.Add($"распорядок, «{имя}»: {Распорядок.Что(быт, можно)}, а надо {ждём}");

        // ---- 2. когда встать ----
        if (!Распорядок.Своё(Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ) || !Распорядок.Своё(Вопрос.СОВРАТЬ)
            || Распорядок.Своё(Вопрос.ОТКРЫТЬ_ДВЕРЬ) || Распорядок.Своё(Вопрос.ПОЙТИ_В_НАЛЁТ) || Распорядок.Своё(Вопрос.ДАТЬ_ИЗ_СВОЕГО))
            плохо.Add("свои вопросы распорядка — не те: замысел и «соврать» — свои, дверь, налёт и просьба — будят");
        if (Распорядок.Лучший(new[] { new ВариантИгроку("а", 0.2, "а"), new ВариантИгроку("б", 0.7, "б"), new ВариантИгроку("в", 0.1, "в") }) != 1)
            плохо.Add("на свой вопрос распорядок отвечает не лучшим");
        {
            var прогон = new Прогон(Пути.Данные, seed: 5, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            var я = прогон.h.people["оксана"];
            var сосед = прогон.h.people.Значения.First(p => p.id != я.id);
            var ко_мне = new[] { new Событие(1, ВидСобытия.КРАЖА, кто: сосед.id, кому: я.id) };
            var чужое = new[] { new Событие(1, ВидСобытия.КРАЖА, кто: сосед.id, кому: "кто-то") };
            if (Распорядок.Встать(я, ко_мне, я.health, Всё) is not string почему || !почему.Contains(ВидСобытия.КРАЖА.Текст(), StringComparison.Ordinal))
                плохо.Add("у героя украли — а распорядок не встал (или не сказал, что случилось)");
            if (Распорядок.Встать(я, чужое, я.health, Всё) is string зря)
                плохо.Add($"украли у соседа — а распорядок героя встал: «{зря}»");
            // его нет в доме: квартиру вскрыли — он не знает; у участка стучат — знает
            var дома_вскрыли = new[] { new Событие(1, ВидСобытия.КРАЖА, кто: сосед.id, кому: я.id, где: я.apt) };
            var у_участка = new[] { new Событие(1, ВидСобытия.НАЛЁТ, кто: сосед.id, кому: я.id) };
            я.вне_дома = true;
            if (Распорядок.Встать(я, дома_вскрыли, я.health, Всё) is string не_знал)
                плохо.Add($"героя нет в доме, а распорядок встал от того, что случилось дома: «{не_знал}»");
            if (Распорядок.Встать(я, у_участка, я.health, Всё) is null)
                плохо.Add("героя нет в доме, к нему самому пришли — а распорядок не встал");
            я.вне_дома = false;
            if (Распорядок.Встать(я, Array.Empty<Событие>(), я.health + Распорядок.ПЛОХО + 1, Всё) is null)
                плохо.Add("здоровье упало — а распорядок не встал");
            я.satiety = 10;
            if (Распорядок.Встать(я, Array.Empty<Событие>(), я.health, Без_воды) is not null)
                плохо.Add("голоден, еда есть — а распорядок встал");
            if (Распорядок.Встать(я, Array.Empty<Событие>(), я.health, Ничего) is null)
                плохо.Add("голоден и есть нечего — а распорядок не встал");
        }

        // ---- 3. живой игрой ----
        string живой_итог;
        {
            const string КТО = "оксана";
            const int ДНЕЙ = 14;
            var прогон = new Прогон(Пути.Данные, seed: 3, days: ДНЕЙ);
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, КТО);
            var h = прогон.h;
            var я = h.people[КТО];
            var у = Округа.У(h)!.участок!;
            у.Пришёл(я);
            у.Изъять(Убежище.ВОДА, у.В_запасе(Убежище.ВОДА) - 3);    // воды мало — пусть топит снег
            я.решающий = new Скрипт(new Dictionary<Вопрос, string> { [Вопрос.СОВРАТЬ] = "сказать правду" });
            var сделано = new Dictionary<Привычка, int>();
            // вопросы, для которых надо стоять в подъезде: позвали в налёт,
            // на собрание, на крик, к двери — из участка их задавать некому
            var чужие = new Dictionary<Вопрос, int>();
            int? умерла = null;
            using (var партия = new Партия(прогон, КТО))
            {
                партия.Начать();
                var в = партия.Дождаться();
                while (в is not null)
                {
                    int ответ = 0;
                    if (!я.alive)
                        умерла ??= h.day;
                    if (в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
                    {
                        bool Можно(Привычка п) => п switch
                        {
                            Привычка.ПОПИТЬ => у.В_запасе(Убежище.ВОДА) >= 0.05,
                            Привычка.ПОЕСТЬ => у.В_запасе(Убежище.ЕДА) >= 0.05,
                            Привычка.ЗАТОПИТЬ => !у.Печь_топится(h.day) && у.В_запасе(Убежище.ТОПЛИВО) >= у.топлива_на_день,
                            Привычка.СНЕГ => у.В_запасе(Убежище.ТОПЛИВО) >= у.топлива_на_день,
                            Привычка.ДРОВА => у.мебели_осталось > 0,
                            _ => false,
                        };
                        var быт = new Быт(я.satiety, я.hydration, h.room_temp(я), у.Печь_топится(h.day), false,
                                          ((я.час() % 24) + 24) % 24);
                        var что = Распорядок.Что(быт, Можно);
                        Сделано с = что switch
                        {
                            Привычка.ПОПИТЬ => Убежище.Попить(h, я, у),
                            Привычка.ПОЕСТЬ => Убежище.Поесть(h, я, у),
                            Привычка.ЗАТОПИТЬ => Убежище.Затопить(h, я, у),
                            Привычка.СНЕГ => Убежище.Снег(h, я, у),
                            Привычка.ДРОВА => у.Разобрать_мебель(h),
                            _ => new Сделано(false, 0, ""),
                        };
                        double часов = с.да ? с.часов : Math.Min(0.5, я.time_left);
                        if (с.да)
                            сделано[что] = сделано.GetValueOrDefault(что) + 1;
                        я.time_left -= Math.Min(часов, я.time_left);
                        ответ = ВопросИгроку.САМ;
                    }
                    else if (в.вопрос == Вопрос.НОЧЬ)
                    {
                        ответ = Math.Max(0, в.варианты.ToList().FindIndex(x => x.ключ == "спать"));
                        if (в.варианты.Count > 1)
                            чужие[Вопрос.НОЧЬ] = чужие.GetValueOrDefault(Вопрос.НОЧЬ) + 1;
                    }
                    else if (!Распорядок.Своё(в.вопрос))
                        чужие[в.вопрос] = чужие.GetValueOrDefault(в.вопрос) + 1;
                    партия.Ответить(ответ);
                    в = партия.Дождаться();
                }
            }
            if (умерла is not null || !я.alive)
                плохо.Add($"по распорядку в участке умерла на {умерла ?? h.day}-й день");
            if (чужие.Count > 0)
                плохо.Add("героиня в участке, а дом её спрашивал как стоящую в подъезде: "
                          + string.Join(", ", чужие.OrderBy(п => п.Key).Select(п => $"{Дом.Ядро.Вопросы.Все[п.Key]} ×{п.Value}"))
                          + (чужие.ContainsKey(Вопрос.НОЧЬ) ? " (ночью — не только «спать»)" : ""));
            if (сделано.GetValueOrDefault(Привычка.СНЕГ) == 0)
                плохо.Add("воды было мало — а снег по распорядку не топили ни разу");
            // порция — почти двое суток сытости: за две недели шесть-семь раз
            if (сделано.GetValueOrDefault(Привычка.ПОЕСТЬ) < ДНЕЙ / 3 || сделано.GetValueOrDefault(Привычка.ЗАТОПИТЬ) == 0)
                плохо.Add($"по распорядку за {ДНЕЙ} дней: поела {сделано.GetValueOrDefault(Привычка.ПОЕСТЬ)}, топила {сделано.GetValueOrDefault(Привычка.ЗАТОПИТЬ)} — мало");
            живой_итог = $"{ДНЕЙ} дней в участке без рук: {(я.alive ? "жива" : "умерла")}, здоровье {Текст.G(Math.Round(я.health))}; "
                         + string.Join(", ", сделано.OrderBy(п => п.Key).Select(п => $"{п.Key.Текст()} {п.Value}"))
                         + $"; в кладовой еды {Текст.G(Текст.Округлить(у.В_запасе(Убежище.ЕДА), 1))}, "
                         + $"воды {Текст.G(Текст.Округлить(у.В_запасе(Убежище.ВОДА), 1))}, топлива {Текст.G(Текст.Округлить(у.В_запасе(Убежище.ТОПЛИВО), 1))}";
        }

        w($"  что делать: {случаи.Length} случаев — по срочности");
        w($"  живой игрой: {живой_итог}");
        return плохо;
    }
}
