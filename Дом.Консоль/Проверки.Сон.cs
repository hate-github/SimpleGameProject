// Проверка сна героя (`Дом.Ядро/Петля/Сон.cs`, движок — `ДомУзел.Сон`):
// спать ложатся в постель, а лёг поздно — недосып (просьба автора, 28.09.2026).
//
//  1. **Правило.** Час после конца дня — запас: лёг в нём — ничего; позже —
//     недоспал ровно на столько; проспал будильник — с шансом по недосыпу
//     и не больше двух часов; через три часа — уснул, где стоял.
//  2. **Утро в живом доме.** Та же ночь дважды: лёг вовремя — и лёг на два
//     с половиной часа позже; наутро у второго бодрости меньше ровно на
//     полтора часа сна, и день короче на столько, на сколько проспал.
//  3. **Место.** «Спать» — у матраса, «дежурить» — на площадке.
//  4. **Узел.** Ночь — не окно (ВопросUI её не показывает) и не разговор
//     (время идёт, как днём: дойти до постели); ответ «спать» не у постели
//     отказывает; счёт «поздно» зовётся каждый кадр; утро кладёт недосып;
//     до метели день кончается счётом, а не окном «спать» где попало.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Сон_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);

        // ---- 1. правило ----
        string Н(Недосып н) => $"{Текст.Ф(н.часов, 2)}/{Текст.Ф(н.проспал, 2)}";
        var случаи = new (double поздно, double бросок, string ждём)[]
        {
            (0.5, 0.0, "0.00/0.00"),       // в запасе
            (1.0, 0.0, "0.00/0.00"),       // ровно запас
            (2.0, 0.99, "1.00/0.00"),      // недоспал час, будильник услышал
            (2.0, 0.1, "1.00/1.00"),       // недоспал час и проспал его
            (5.0, 0.0, "4.00/2.00"),       // проспал — не больше двух часов
        };
        foreach (var (поздно, бросок, ждём) in случаи)
            if (Н(Сон.Лёг(поздно, ручки, бросок)) != ждём)
                плохо.Add($"лёг через {поздно} ч (бросок {бросок}) — недосып/проспал {Н(Сон.Лёг(поздно, ручки, бросок))}, а надо {ждём}");
        if (Сон.Уснул_где_стоял(2.99, ручки) || !Сон.Уснул_где_стоял(3.0, ручки))
            плохо.Add("уснул где стоял: не через три часа после конца дня");

        // ---- 2. утро в живом доме ----
        string утро_итог = "—";
        (double rest, double time_left, double сон_за_час)? Ночь(double поздно)
        {
            var прогон = new Прогон(Пути.Данные, seed: 31, days: 3);
            using var партия = new Партия(прогон, "лида");
            var h = прогон.h;
            var я = партия.сеанс.я;
            партия.Начать();
            var в = партия.Дождаться();
            Недосып? н = null;
            int день_ночи = -1;
            (double, double, double)? итог = null;
            int шагов = 0;
            while (в is not null && шагов++ < 2000)
            {
                if (в.вопрос == Вопрос.НОЧЬ && н is null)
                {
                    int спать = Enumerable.Range(0, в.варианты.Count)
                        .FirstOrDefault(i => в.варианты[i].ключ == Места.СПАТЬ, -1);
                    if (спать < 0)
                    {
                        плохо.Add("ночью дом не предложил герою «спать»");
                        break;
                    }
                    н = Сон.Лёг(поздно, ручки, 0.0);
                    день_ночи = в.день;
                    партия.Ответить(спать);
                }
                else if (н is not null && в.день > день_ночи && в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
                {
                    Сон.Утро(я, н, h.B);
                    итог = (я.rest, я.time_left, h.B["сон_за_час"]);
                    break;
                }
                else if (в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
                {
                    ХодВремени.Прожить(я, Math.Min(1.0, я.time_left));
                    партия.Пропустить();
                }
                else
                    партия.Ответить(0);
                в = партия.Дождаться();
            }
            while (в is not null)
            {
                партия.Ответить(0);
                в = партия.Дождаться();
            }
            партия.Досидеть();
            return итог;
        }
        var вовремя = Ночь(0.5);
        var поздно_ = Ночь(2.5);
        if (вовремя is null || поздно_ is null)
            плохо.Add("живая ночь не дошла до утра");
        else
        {
            var ждём = Сон.Лёг(2.5, ручки, 0.0);
            double меньше_бодрости = вовремя.Value.rest - поздно_.Value.rest;
            double короче = вовремя.Value.time_left - поздно_.Value.time_left;
            double надо_бодрости = Math.Min(вовремя.Value.rest, ждём.часов * вовремя.Value.сон_за_час);
            if (Math.Abs(меньше_бодрости - надо_бодрости) > 1e-6)
                плохо.Add($"лёг на 2.5 ч позже — бодрости меньше на {Текст.Ф(меньше_бодрости, 2)}, а надо на {Текст.Ф(надо_бодрости, 2)}");
            if (Math.Abs(короче - ждём.проспал) > 1e-6)
                плохо.Add($"проспал {Текст.Ф(ждём.проспал, 2)} ч — а день короче на {Текст.Ф(короче, 2)}");
            утро_итог = $"лёг на 2.5 ч позже: бодрости −{Текст.Ф(меньше_бодрости, 1)}, день короче на {Текст.Ф(короче, 1)} ч";
        }

        // ---- 3. место ----
        {
            var прогон = new Прогон(Пути.Данные, seed: 5, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            var h = прогон.h;
            var я = h.people["оксана"];
            var пусто = new Dictionary<string, int>(StringComparer.Ordinal);
            var нет = new HashSet<string>(StringComparer.Ordinal);
            var спать = Места.Где(h, я, new ВариантИгроку(Места.СПАТЬ, 1.0, Места.СПАТЬ), пусто, нет);
            var дежурить = Места.Где(h, я, new ВариантИгроку(Места.ДЕЖУРИТЬ, 1.0, Места.ДЕЖУРИТЬ), пусто, нет);
            if (спать is not { вид: ВидАдреса.ДОМА, вещь: Вещь.МАТРАС })
                плохо.Add($"«спать» — не у матраса, а {спать?.вид.ToString() ?? "нигде"}");
            if (дежурить is not { вид: ВидАдреса.ПЛОЩАДКА })
                плохо.Add($"«дежурить» — не на площадке, а {дежурить?.вид.ToString() ?? "нигде"}");
        }

        // ---- 4. узел ----
        string Файл(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя));
        var узел = Файл("ДомУзел.cs");
        var окно = Файл("ВопросUI.cs");
        var сон = Файл("ДомУзел.Сон.cs");
        var требования = new (string где, string текст, string беда)[]
        {
            ("ВопросUI", "Visible = в.вопрос is not (Вопрос.ЧТО_ДЕЛАТЬ or Вопрос.НОЧЬ);",
             "ночь снова окном — «спать» нажимается где угодно"),
            ("ДомУзел", "_на_экране is { вопрос: not (Вопрос.ЧТО_ДЕЛАТЬ or Вопрос.НОЧЬ) }",
             "ночью время идёт, как в разговоре, — до постели не дойти"),
            ("ДомУзел", "if (Спать_не_здесь(номер))", "«спать» отвечается не у постели"),
            ("ДомУзел", "Сон_кадр(delta);", "счёт «поздно» не зовётся — уснуть, где стоял, нельзя"),
            ("ДомУзел", "Сон_утро(в);", "недосып не ложится утром"),
            ("ДомУзел", "Сон_утро(null);", "до метели недосып не ложится утром"),
            ("ДомУзел", "Пролог_день_кончился();", "до метели день кончается окном «спать» где попало"),
            ("ДомУзел.Сон", "в.вопрос != Вопрос.ЧТО_ДЕЛАТЬ || в.день <= _недосып_дня",
             "недосып ложится не на вопросе дня — «проспал» теряется: утро выдаёт часы заново"),
        };
        foreach (var (где, текст, беда) in требования)
            if (!(где switch { "ВопросUI" => окно, "ДомУзел.Сон" => сон, _ => узел }).Contains(текст, StringComparison.Ordinal))
                плохо.Add($"{где}: {беда}");

        w($"  запас {Текст.Ф(Сон.Запас(ручки), 1)} ч, случаев правила {случаи.Length}; {утро_итог}");
        return плохо;
    }
}
