// Проверка рассудка в разговорах и того, что его держит (ГДД 11).
//
//  1. **Отстранение.** «Отказывается от части диалогов („бессмысленно“),
//     не предупреждает соседей»: быт, расспросы и метель — нет; слухи, город,
//     болезнь — да; на тревоге — всё как было.
//  2. **Тревога.** «Появляются циничные варианты»: с тревоги в «Разговоре»
//     есть циничная реплика; сильному она почти своя, доброму — обида.
//  3. **Что держит.** «Музыка/развлечения с телефона»: часы в телефоне —
//     вклад «развлекался» со знаком минус; часы едут в сейв и обратно.
//  4. **Экран.** Двери — до метели и в метель — спрашивают рассудок о теме;
//     «Разговор» — о цинизме (скан).

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> РассудокВРечи_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);

        // ---- 1. отстранение ----
        foreach (var тема in new[] { "быт", "о_себе", "метель" })
            if (!Рассудок.Отказывается(9.0, ручки, тема) || Рассудок.Отказывается(5.0, ручки, тема))
                плохо.Add($"рассудок: «{тема}» — на отстранении не отказывается (или отказывается уже на тревоге)");
        foreach (var тема in new[] { "слухи", "город", "болезнь" })
            if (Рассудок.Отказывается(9.0, ручки, тема))
                плохо.Add($"рассудок: «{тема}» на отстранении — «бессмысленно», а это о деле, не о жизни");

        // ---- 2. тревога: цинизм ----
        string цинизм_итог;
        {
            if (Рассудок.Цинизм(3.9, ручки) || !Рассудок.Цинизм(4.0, ручки))
                плохо.Add("рассудок: циничные реплики — не с тревоги");
            if (Реплики.На_выбор(false, false).Contains(Тон.ЦИНИЗМ) || !Реплики.На_выбор(false, true).Contains(Тон.ЦИНИЗМ))
                плохо.Add("рассудок: циничная реплика — не только с тревоги");
            var п = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            var люди = п.h.people.Значения.ToList();
            var сильный = люди.FirstOrDefault(x => x.ценит("сила"));
            var добрый = люди.FirstOrDefault(x => x.ценит("щедрость") || x.ценит("ребёнок"));
            var прочий = люди.FirstOrDefault(x => !x.ценит("сила") && !x.ценит("щедрость") && !x.ценит("ребёнок"));
            if (сильный is null || добрый is null || прочий is null)
            {
                плохо.Add("рассудок: в доме нет сильного, доброго или прочего — цинизм проверять не на ком");
                цинизм_итог = "—";
            }
            else
            {
                double с = Реплики.Качество(сильный, Тон.ЦИНИЗМ, 1.0), д = Реплики.Качество(добрый, Тон.ЦИНИЗМ, 1.0),
                       п_ = Реплики.Качество(прочий, Тон.ЦИНИЗМ, 1.0);
                if (!(с > 0.5 && д < 0.2 && п_ < 0.5))
                    плохо.Add($"рассудок: цинизм — сильному {с}, доброму {д}, прочим {п_}");
                цинизм_итог = $"сильному {Текст.G(с)}, доброму {Текст.G(д)}, прочим {Текст.G(п_)}";
            }
        }

        // ---- 3. что держит: телефон ----
        string держит_итог;
        {
            var профиль = new ПрофильГероя("Андрей");
            var п = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null),
                               жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            new Дом.Ядро.Петля(new Наследие(), ручки,
                               инструменты: Дом.Ядро.Инструменты.Прочитать(Пути.Данные),
                               летопись: Летопись.Прочитать(Пути.Данные)).Слушать(п, Герой.ID);
            var я = п.h.people[Герой.ID];
            var т = Округа.У(п.h)!.телефон;
            if (Рассудок.Вклады(п.h, я, ручки).Any(в => в.за_что == "развлекался"))
                плохо.Add("рассудок: в телефоне не сидел — а «развлекался» есть");
            т.Провести_время(я, ручки);
            т.Провести_время(я, ручки);
            var вклад = Рассудок.Вклады(п.h, я, ручки).FirstOrDefault(в => в.за_что == "развлекался");
            double ждём = -2 * ручки["телефон_провести_время_часов"] * ручки["держит_развлечение"];
            if (вклад is null || Math.Abs(вклад.сколько - ждём) > 1e-9)
                плохо.Add($"рассудок: два часа в телефоне — «развлекался» {вклад?.сколько}, а надо {ждём}");
            var сейв = Округа.У(п.h)!.Сложить();
            var т2 = new Телефон();
            т2.Разложить(сейв["телефон"] as System.Text.Json.Nodes.JsonObject);
            if (Math.Abs(т2.часов_провёл - т.часов_провёл) > 1e-9)
                плохо.Add($"рассудок: часы в телефоне после сейва — {т2.часов_провёл}, а было {т.часов_провёл}");
            держит_итог = $"два часа в телефоне — «развлекался» {Текст.Знак(вклад?.сколько ?? 0, 2)}";
        }

        // ---- 4. экран ----
        {
            string Файл(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя));
            string узел = Файл("ДомУзел.cs"), игра = Файл("ДомУзел.РазговорИгра.cs");
            if (узел.Split("Рассудок.Отказывается(_наследие.рассудок, _ручки,").Length - 1 < 2)
                плохо.Add("рассудок: у двери (до метели или в метель) темы не спрашивают рассудок");
            if (!игра.Contains("Рассудок.Цинизм(_наследие.рассудок, _ручки)", StringComparison.Ordinal))
                плохо.Add("рассудок: «Разговор» не знает о цинизме");
        }

        w($"  цинизм: {цинизм_итог}");
        w($"  держит: {держит_итог}");
        return плохо;
    }
}
