// Проверка ловушки у своей двери (ГДД 15, уровень 4: «ловушки»; требования —
// «знания „Механик“ и „Строитель“, „Смекалка“ 4»; `Дом.Ядро/Петля/Ловушка.cs`):
//
//  1. **Откуда.** Знание «механик» рассказывает Руслан.
//  2. **Кто поставит.** Без Смекалки и знания — «не разобраться»; Смекалка
//     от порога или знание от Руслана — можно, если хватает материалов;
//     слесарь — сам умеет.
//  3. **Поставить.** Материалы из шкафа ровно на ручку; стоит у своей двери,
//     взведена; вторую поверх не поставить.
//  4. **Вор.** Ночной вор у двери героя попадается: ушёл ни с чем, ранен
//     на ручку, боится этой двери; ловушка спущена, герой дома — знает кто.
//     Спущенная не срабатывает; взвести — тем же трудом.
//  5. **Не убивает.** Слабого ловушка не добивает.
//  6. **Без героя.** Не дома — не знает кто, и журнал имени не называет.
//  7. **Сохранение.** Ловушка, кто попался и что показано — переживают
//     сохранение округи.
//  8. **Где срабатывает.** Пустая квартира — ночами по-настоящему: первый
//     вскрывший попадается, шкаф цел. Кража, налёт (пролом двери и вынос),
//     пустая квартира — по исходнику, и только там: гость, который стучит,
//     не входит. Налёт ночами не гоняется: в нём спрашивают героя.
//  9. **Узел.** Ставится у своей двери, видна у порога, весть герою.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Ловушка_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var профиль = new ПрофильГероя("Андрей");
        (House h, NPC я, Округа о) Жизнь()
        {
            var прогон = new Прогон(Пути.Данные, seed: 7, days: 1, журнал: new Журнал(0, false, TextWriter.Null),
                                    жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            var петля = new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л);
            петля.Слушать(прогон, Герой.ID);
            return (прогон.h, прогон.h.people[Герой.ID], Округа.У(прогон.h)!);
        }

        // ---- 1. откуда ----
        if (л.знатоки.FirstOrDefault(з => з.кто == "руслан")?.ступени.Any(с => с.узнаёшь == Ловушка.МЕХАНИК) != true)
            плохо.Add("Руслан не рассказывает дело механика — без Смекалки 4 ловушку не поставить никому");

        int порог = (int)ручки["ловушка_смекалка"];
        double материалов = ручки["ловушка_материалы"];
        double урон = ручки["ловушка_урон"];
        string итог;
        {
            var (h, я, о) = Жизнь();

            // ---- 2. кто поставит ----
            я.stock["материалы"] = материалов + 1;
            я.умения!.наследие.уровни[Навык.СМЕКАЛКА] = 0;
            if (Ловушка.Нельзя(h, я, ручки) is not string не_умеет || !не_умеет.Contains("не разобраться", StringComparison.Ordinal))
                плохо.Add("Смекалка 0 и не механик — а ловушку поставить можно");
            я.умения.наследие.уровни[Навык.СМЕКАЛКА] = порог - 1;
            if (Ловушка.Нельзя(h, я, ручки) is null)
                плохо.Add($"Смекалка {порог - 1} (порог {порог}) — а ловушку поставить можно");
            я.умения.наследие.уровни[Навык.СМЕКАЛКА] = порог;
            if (Ловушка.Нельзя(h, я, ручки) is string нельзя)
                плохо.Add($"Смекалка {порог} — а ловушку не поставить: {нельзя}");
            я.stock["материалы"] = материалов * 0.5;
            if (Ловушка.Нельзя(h, я, ручки) is not string мало || !мало.Contains("материалов", StringComparison.Ordinal))
                плохо.Add("материалов вполовину меньше нужного — а ловушку поставить можно");
            я.умения.наследие.уровни[Навык.СМЕКАЛКА] = 0;
            я.stock["материалы"] = материалов + 1;
            я.skills.Add(Ловушка.СЛЕСАРЬ);
            if (Ловушка.Нельзя(h, я, ручки) is string слесарь)
                плохо.Add($"слесарь — а ловушку не поставить: {слесарь}");
            я.skills.Remove(Ловушка.СЛЕСАРЬ);
            var руслан = h.people["руслан"];
            руслан.trust[я.id] = 3.3;
            о.Пришёл_к(h, я, руслан);
            if (!о.Знает(Ловушка.МЕХАНИК))
                плохо.Add("к Руслану пришли по-доброму — дело механика не узнали");
            else if (Ловушка.Нельзя(h, я, ручки) is string без_смекалки)
                плохо.Add($"знает дело механика — а ловушку не поставить: {без_смекалки}");

            // ---- 3. поставить ----
            double было = я.stock["материалы"];
            var лов = Ловушка.Поставить(h, я, ручки);
            if (лов is null)
            {
                плохо.Add("ловушку не поставить, хотя всё есть");
                return плохо;
            }
            if (Math.Abs(я.stock["материалы"] - (было - материалов)) > 1e-9)
                плохо.Add($"материалов было {было}, стало {я.stock["материалы"]} — ждали минус {материалов}");
            if (о.ловушка != лов || лов.квартира != я.apt || !лов.взведена)
                плохо.Add($"ловушка не у своей двери или не взведена: кв.{лов.квартира}, {лов.взведена}");
            if (Ловушка.Нельзя(h, я, ручки) is not string вторая || !вторая.Contains("уже", StringComparison.Ordinal)
                || Ловушка.Поставить(h, я, ручки) is not null)
                плохо.Add("вторая ловушка встала поверх взведённой");

            // ---- 4. вор ----
            var вор = h.others(я).First(п => п.здесь() && п.apt != я.apt && п.health > 60);
            я.stock["еда"] = 10.0;
            double еды = я.stock["еда"];
            double здоровье = вор.health;
            var (исход, унёс) = Конфликт.steal(h, вор, я);
            if (исход != Конфликт.ИсходКражи.ОТПУГНУЛИ || унёс.Count > 0 || Math.Abs(я.stock["еда"] - еды) > 1e-9)
                плохо.Add($"вор у взведённой ловушки: {исход}, унёс {унёс.Count} — ждали «ушёл ни с чем»");
            if (!вор.injuries.Contains(Ловушка.РАНА, StringComparer.Ordinal)
                || Math.Abs(вор.health - Math.Max(здоровье - урон, Ловушка.ПОЛ_ЗДОРОВЬЯ)) > 1e-9)
                плохо.Add($"попавшийся не ранен как надо: раны [{string.Join(", ", вор.injuries)}], здоровье {здоровье} → {вор.health}");
            if (вор.боится(я.id) <= 0)
                плохо.Add("попавшийся не боится этой двери");
            if (лов.взведена || лов.попались.Count != 1 || лов.попались[0] is not { узнал: true } п || п.кто != вор.id || п.дело != "кража")
                плохо.Add($"после вора ловушка: взведена {лов.взведена}, попались {лов.попались.Count}");
            if (лов.Новые().Count != 1 || лов.Новые().Count != 0)
                плохо.Add("весть о попавшемся показывается не по разу");
            if (лов.Сработала(h, вор, я, "кража") is not null)
                плохо.Add("спущенная ловушка сработала второй раз");
            я.stock["материалы"] = материалов;
            if (Ловушка.Поставить(h, я, ручки) != лов || !лов.взведена || я.stock["материалы"] > 1e-9)
                плохо.Add("сработавшую не взвести тем же трудом");
            итог = $"поставить: Смекалка {порог} или знание Руслана, материалов {материалов}; "
                   + $"вор {вор.@short}: здоровье {здоровье:F0} → {вор.health:F0}, ушёл ни с чем";

            // ---- 5. не убивает ----
            var слабый = h.others(я).First(п => п.здесь() && п.apt != я.apt && п.id != вор.id);
            слабый.health = 5.0;
            лов.Сработала(h, слабый, я, "кража");
            if (слабый.health < 5.0 - 1e-9 || !слабый.alive)
                плохо.Add($"ловушка добила слабого: здоровье 5 → {слабый.health}");

            // ---- 6. без героя ----
            я.stock["материалы"] = материалов;
            Ловушка.Поставить(h, я, ручки);
            var третий = h.others(я).First(п => п.здесь() && п.apt != я.apt && п.id != вор.id && п.id != слабый.id);
            я.away = true;
            string? строка = лов.Сработала(h, третий, я, "пустая");
            я.away = false;
            if (строка is null || строка.Contains(третий.@short, StringComparison.Ordinal)
                || лов.попались.Count == 0 || лов.попались[^1].узнал)
                плохо.Add($"героя нет дома — а он знает, кто попался: «{строка}»");

            // ---- 7. сохранение ----
            var (_, я2, о2) = Жизнь();
            о2.Разложить(о.Сложить(), я2);
            if (о2.ловушка is not { } л2 || л2.квартира != лов.квартира || л2.взведена != лов.взведена
                || !л2.попались.SequenceEqual(лов.попались) || Math.Abs(л2.урон - лов.урон) > 1e-9)
                плохо.Add("ловушка или кто попался не пережили сохранения");
            else if (л2.Новые().Count != 2)
                плохо.Add("после сохранения показанное и непоказанное перепутались");
        }

        // ---- 8. где срабатывает ----
        // пустая квартира: герой в участке, соседи голодные — первый, кто
        // вскроет, попадается, и из шкафа не уходит ничего
        if (л.пустая_квартира is { } пк)
        {
            var (h, я, о) = Жизнь();
            о.участок!.Пришёл(я);
            foreach (var с in h.others(я))
                с.stock["еда"] = 0;
            я.stock["еда"] = 20;
            я.stock["материалы"] = материалов;
            я.skills.Add(Ловушка.СЛЕСАРЬ);
            var лов = Ловушка.Поставить(h, я, ручки);
            if (лов is null)
            {
                плохо.Add("слесарь со всеми материалами — а ловушку не поставить");
                return плохо;
            }
            for (int ночь = 3; ночь < 3 + пк.дней + 10 && лов.взведена; ночь++)
            {
                h.day = ночь;
                о.Пустая_квартира(h, я);
            }
            if (лов.взведена || лов.попались.Count != 1 || лов.попались[0] is not { дело: "пустая", узнал: false })
                плохо.Add($"квартиру без героя вскрывали — а ловушка: взведена {лов.взведена}, попались {лов.попались.Count}");
            else if (я.stock["еда"] < 20 - 1e-9 || о.Вынесли().Count != 0)
                плохо.Add("вскрывший пустую квартиру попался — а из шкафа всё равно вынесли");
        }
        string Ядро(string файл) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Ядро", файл));
        string ядро_всё = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Ядро"), "*.cs", SearchOption.AllDirectories)
                                                 .Where(ф => !ф.Contains(Path.DirectorySeparatorChar + "obj" + Path.DirectorySeparatorChar))
                                                 .Select(File.ReadAllText));
        foreach (var (файл, текст, беда) in new[]
                 {
                     ("Конфликт.Кража.cs", "ловушка?.Сработала(h, thief, target, \"кража\")", "вор не попадается"),
                     ("Конфликт.Осада.cs", "ловушка?.Сработала(h, leader, target, \"налёт\")", "налёт не попадается"),
                     (Path.Combine("Петля", "Округа.cs"), "ловушка?.Сработала(h, p, я, \"пустая\")", "вскрывший пустую квартиру не попадается"),
                 })
            if (!Ядро(файл).Contains(текст, StringComparison.Ordinal))
                плохо.Add($"ядро: {беда}");
        int мест = System.Text.RegularExpressions.Regex.Matches(ядро_всё, @"\.Сработала\(").Count;
        if (мест != 4)
            плохо.Add($"ловушку зовут в {мест} местах ядра — ждали четыре (кража, два в налёте, пустая квартира): гость не должен в неё попадать");

        // ---- 9. узел ----
        string узел = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Годот"), "*.cs").Select(File.ReadAllText));
        foreach (var (текст, беда) in new[]
                 {
                     ("строки.AddRange(Ловушка_у_двери(_партия.прогон.h, я));", "у своей двери ловушку не поставить"),
                     ("Ловушка.Поставить(_партия.прогон.h, я, _ручки)", "кнопка ловушки её не ставит"),
                     ("Сделать_тут(new Сделано(true, Ловушка.Часы(_ручки),", "ловушку ставят, не тратя часов"),
                     ("Ловушка_вопроса();", "ловушки не видно у порога"),
                     ("Весть_ловушки();", "герою не говорят, кто попался"),
                 })
            if (!узел.Contains(текст, StringComparison.Ordinal))
                плохо.Add($"узел: {беда}");

        w("  " + итог);
        return плохо;
    }
}
