// Проверка камеры на пролёт (ГДД 15, уровень 3: «камера на пролёт»; требования —
// «знание „Электрик“ или „Смекалка“ 3, материалы»; `Дом.Ядро/Петля/Камера.cs`,
// `Дом.Экран/КамераГероя.cs`):
//
//  1. **Откуда.** Камеру продают в строительном (только до метели), она есть
//     в каталоге предметов; знание «электрик» рассказывает Виктор.
//  2. **Кто повесит.** Без камеры — нельзя; без Смекалки и знания — «не
//     разобраться»; со Смекалкой от порога или со знанием от Виктора —
//     можно, если хватает материалов.
//  3. **Повесить.** Камера уходит из снаряжения, материалы — из шкафа ровно
//     на ручку; висит над своей дверью, видит свой этаж; вторую не повесить.
//  4. **Запись.** Пишет ходы у дверей своего этажа после того, как повесили,
//     без героя и по разу; без тока — ничего, со своим генератором — пишет.
//  5. **Слова.** Незнакомый — «сосед из кв.N», знакомый — по имени; кража —
//     «возился с замком», у своей двери — пометка; будущего нет, кто ещё
//     стоит — «и сейчас там»; свежее сверху, позавчерашнего нет.
//  6. **Кадры из хроники.** Сосед пошёл к соседу — кадр у двери того.
//  7. **Сохранение.** Камера и запись переживают сохранение округи.
//  8. **Узел.** Пишет на вопросе, вешается у своей двери, показывается
//     в телефоне.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Камера_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        // герой новой игры: соседей он знает по дверям, а не по именам
        var профиль = new ПрофильГероя("Андрей");
        (House h, NPC я, Округа о) Жизнь()
        {
            var прогон = new Прогон(Пути.Данные, seed: 7, days: 1, журнал: new Журнал(0, false, TextWriter.Null),
                                    жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            var петля = new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л);
            петля.Слушать(прогон, Герой.ID);
            return (прогон.h, прогон.h.people[Герой.ID], Округа.У(прогон.h)!);
        }

        // ---- 1. откуда ----
        var строймаг = Магазин.Прочитать(Пути.Данные, каталог, "строймаг.json");
        if (!строймаг.товары.Any(т => т.предмет == Камера.ПРЕДМЕТ) || !строймаг.до_метели)
            плохо.Add("камеру не купить в строительном до метели");
        if (!каталог.в_руках.ContainsKey(Камера.ПРЕДМЕТ))
            плохо.Add("камеры нет в каталоге предметов");
        var виктор_знает = л.знатоки.FirstOrDefault(з => з.кто == "виктор")?.ступени
                            .Any(с => с.узнаёшь == Камера.ЭЛЕКТРИК) == true;
        if (!виктор_знает)
            плохо.Add("Виктор не рассказывает дело электрика — без Смекалки камеру не повесить никому");

        // ---- 2. кто повесит ----
        int порог = (int)ручки["камера_смекалка"];
        double материалов = ручки["камера_материалы"];
        string итог;
        {
            var (h, я, о) = Жизнь();
            я.stock["материалы"] = материалов + 1;
            string? нет_камеры = Камера.Нельзя(h, я, ручки);
            if (нет_камеры is null)
                плохо.Add("камеры нет ни при себе, ни дома — а повесить можно");
            я.снаряжение!.Подобрать(Камера.ПРЕДМЕТ, каталог);
            string? не_умеет = Камера.Нельзя(h, я, ручки);
            if (не_умеет is null || !не_умеет.Contains("не разобраться", StringComparison.Ordinal))
                плохо.Add($"Смекалка 0 и не электрик — а «{не_умеет ?? "можно"}»");
            я.умения!.наследие.уровни[Навык.СМЕКАЛКА] = порог - 1;
            if (Камера.Нельзя(h, я, ручки) is null)
                плохо.Add($"Смекалка {порог - 1} (порог {порог}) — а камеру повесить можно");
            я.умения.наследие.уровни[Навык.СМЕКАЛКА] = порог;
            if (Камера.Нельзя(h, я, ручки) is string нельзя)
                плохо.Add($"Смекалка {порог} — а камеру не повесить: {нельзя}");
            я.stock["материалы"] = материалов * 0.5;
            if (Камера.Нельзя(h, я, ручки) is not string мало || !мало.Contains("материалов", StringComparison.Ordinal))
                плохо.Add("материалов вполовину меньше нужного — а камеру повесить можно");
            // знание от Виктора — без Смекалки
            я.умения.наследие.уровни[Навык.СМЕКАЛКА] = 0;
            я.stock["материалы"] = материалов + 1;
            var виктор = h.people["виктор"];
            виктор.trust[я.id] = 3.3;
            о.Пришёл_к(h, я, виктор);
            if (!о.Знает(Камера.ЭЛЕКТРИК))
                плохо.Add("к Виктору пришли по-доброму — дело электрика не узнали");
            else if (Камера.Нельзя(h, я, ручки) is string без_смекалки)
                плохо.Add($"знает дело электрика — а камеру не повесить: {без_смекалки}");

            // ---- 3. повесить ----
            double было = я.stock["материалы"];
            var к = Камера.Повесить(h, я, ручки);
            if (к is null)
            {
                плохо.Add("камеру не повесить, хотя всё есть");
                return плохо;
            }
            if (Math.Abs(я.stock["материалы"] - (было - материалов)) > 1e-9)
                плохо.Add($"материалов было {было}, стало {я.stock["материалы"]} — ждали минус {материалов}");
            if (я.снаряжение.Есть(Камера.ПРЕДМЕТ) || я.снаряжение.дома.Contains(Камера.ПРЕДМЕТ))
                плохо.Add("камеру повесили — а она всё ещё в снаряжении");
            if (о.камера != к || к.квартира != я.apt || к.этаж != h.flats[я.apt].floor || к.с_дня != h.day)
                плохо.Add($"камера висит не там: кв.{к.квартира}, этаж {к.этаж}, с дня {к.с_дня}");
            я.снаряжение.Подобрать(Камера.ПРЕДМЕТ, каталог);
            if (Камера.Нельзя(h, я, ручки) is not string вторая || !вторая.Contains("уже", StringComparison.Ordinal)
                || Камера.Повесить(h, я, ручки) is not null)
                плохо.Add("вторая камера повесилась поверх первой");

            // ---- 4. запись ----
            int этаж = к.этаж;
            var сосед_этажа = h.flats.Значения.First(ф => ф.floor == этаж && ф.apt != я.apt).apt;
            var чужой_этаж = h.flats.Значения.First(ф => ф.floor != этаж).apt;
            var кто = h.people.Значения.First(п => п.id != я.id && п.id != "виктор");
            double час = к.с_часа;
            var кадры = new[]
            {
                new КадрКамеры(h.day, час + 1, час + 2, кто.id, сосед_этажа, "разговор"),   // видно
                new КадрКамеры(h.day, час + 1, час + 2, кто.id, сосед_этажа, "разговор"),   // тот же — второй раз
                new КадрКамеры(h.day, час + 1.5, час + 2, кто.id, чужой_этаж, "разговор"),  // другой этаж
                new КадрКамеры(h.day, час + 2, час + 3, я.id, сосед_этажа, "разговор"),     // сам герой
                new КадрКамеры(h.day, час - 1, час - 0.5, кто.id, я.apt, "кража_днём"),     // до того, как повесили
                new КадрКамеры(h.day, час + 3, час + 4, кто.id, я.apt, "кража_днём"),       // у своей двери
            };
            h.power_on = true;
            int легло = к.Записать(h, кадры, я.id);
            if (легло != 2 || к.кадры.Count != 2)
                плохо.Add($"из шести кадров на плёнку легло {легло} (всего {к.кадры.Count}) — ждали два: у соседа по этажу и у своей двери");
            h.power_on = false;
            h.flats[к.квартира].shelter["питание"] = h.day - 1;
            var без_тока = new КадрКамеры(h.day, час + 4, час + 5, кто.id, сосед_этажа, "обмен");
            if (к.Работает(h) || к.Записать(h, new[] { без_тока }, я.id) != 0)
                плохо.Add("тока нет — а камера пишет");
            h.flats[к.квартира].shelter["питание"] = h.day;
            if (!к.Работает(h) || к.Записать(h, new[] { без_тока }, я.id) != 1)
                плохо.Add("свой генератор сегодня — а камера не пишет");

            // ---- 5. слова ----
            var строки = КамераГероя.Запись(h, я, к, час + 3.5);
            string незнакомый = Знакомство.Незнакомый(кто);
            if (строки.Count != 2)
                плохо.Add($"на записи к часу {час + 3.5:F1} — {строки.Count} строк, ждали две (обмен ещё не начался)");
            else
            {
                bool она = кто.sex == "ж";
                if (!строки[0].у_своей || !строки[0].текст.Contains(она ? "возилась с замком твоей двери" : "возился с замком твоей двери", StringComparison.Ordinal)
                    || !строки[0].текст.Contains("и сейчас там", StringComparison.Ordinal))
                    плохо.Add($"свежая строка — не кража у своей двери, которая идёт сейчас: «{строки[0].текст}»");
                if (строки[1].у_своей || !строки[1].текст.Contains($"{(она ? "стучала" : "стучал")} в кв.{сосед_этажа}", StringComparison.Ordinal))
                    плохо.Add($"вторая строка — не стук к соседу: «{строки[1].текст}»");
                if (!строки[1].текст.Contains(незнакомый, StringComparison.Ordinal))
                    плохо.Add($"незнакомого соседа запись называет не «{незнакомый}»: «{строки[1].текст}»");
            }
            о.Узнал(Знакомство.ИМЯ + кто.id);
            if (КамераГероя.Запись(h, я, к, час + 3.5).FirstOrDefault() is { } знакомый
                && !знакомый.текст.Contains(кто.@short, StringComparison.Ordinal))
                плохо.Add($"знакомого соседа запись не называет по имени: «{знакомый.текст}»");
            h.day += 2;
            if (КамераГероя.Запись(h, я, к, 12.0).Count != 0)
                плохо.Add("позавчерашнее всё ещё на записи");
            h.day -= 2;
            итог = $"повесить: Смекалка {порог} или знание Виктора, материалов {материалов}; "
                   + $"из шести кадров легло два, без тока — ни одного; свежая строка: «{строки.FirstOrDefault()?.текст}»";

            // ---- 7. сохранение ----
            var (h2, я2, о2) = Жизнь();
            о2.Разложить(о.Сложить(), я2);
            if (о2.камера is not { } к2 || к2.квартира != к.квартира || к2.кадры.Count != к.кадры.Count
                || !к2.кадры.SequenceEqual(к.кадры))
                плохо.Add("камера или запись не пережили сохранения");
        }

        // ---- 6. кадры из хроники ----
        {
            var прогон = new Прогон(Пути.Данные, seed: 1, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            var h = прогон.h;
            var х = new Хроника(h);
            var гость = h.people["оксана"];
            var хозяин = h.others(гость).First(п => п.здесь() && п.apt != гость.apt);
            Действия.execute(h, гость, "разговор", хозяин);
            var снято = КамераГероя.Снять(х, h.day).ToList();
            if (!снято.Any(к => к.кто == гость.id && к.кв == h.хозяин_жилья(хозяин).apt && к.ключ == "разговор"))
                плохо.Add($"сосед ходил к соседу — в кадрах хроники этого нет ({снято.Count} кадров)");
        }

        // ---- 8. узел ----
        string узел = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Годот"), "*.cs").Select(File.ReadAllText));
        string дом_узел = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "ДомУзел.cs"));
        if (!дом_узел.Contains("Камера_вопроса(дом_);", StringComparison.Ordinal))
            плохо.Add("узел: камера не пишет на вопросе");
        foreach (var (текст, беда) in new[]
                 {
                     ("_телефон.Камера_дай = Камера_запись;", "запись камеры не видна в телефоне"),
                     ("Камера_у_двери(_партия.прогон.h, я)", "у своей двери камеру не повесить"),
                     ("Камера.Повесить(_партия.прогон.h, я, _ручки)", "кнопка камеры её не вешает"),
                     ("Сделать_тут(new Сделано(true, Камера.Часы(_ручки),", "камеру вешают, не тратя часов"),
                     ("Камера_обновить();", "вкладка камеры не обновляется"),
                     ("_мир.Камера_над(кам?.квартира);", "камеры не видно над дверью"),
                 })
            if (!узел.Contains(текст, StringComparison.Ordinal))
                плохо.Add($"узел: {беда}");

        w("  " + итог);
        return плохо;
    }
}
