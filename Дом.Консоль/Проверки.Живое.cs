            // зарево — в дни, когда в городе что-то горит, и ни в какие другие
            // (все тридцать дней: сгоревшее на следующий день уже не горит)
            string? зарево = null;
            for (int д = 1; д <= 30; д++)
            {
                h.day = д;
                string? в_этот = б.Из_окна(h, я, new List<СоседГде>(), л, 13, 5, 0).FirstOrDefault(с => Из("окно", "зарево", с, я, я));
                bool горит = л.На(д, 5).здания.Values.Any(з => з == Здание.ГОРИТ);
                if (горит && в_этот is null)
                    плохо.Add($"на {д}-й день в городе горит — а зарева из окна не видно");
                if (!горит && в_этот is not null)
                    плохо.Add($"на {д}-й день ничего не горит — а из окна зарево: «{в_этот}»");
                зарево ??= в_этот;
            }
            int строк = 0;
            foreach (var режим in new[] { Режим.БУРАН, Режим.МЕТЕЛЬ, Режим.ЗАТИШЬЕ })
                foreach (double час in new[] { 3.0, 9.0, 14.0, 21.0 })
                    for (int раз = 0; раз < 3; раз++)
                    {
                        h.режим = режим;
                        foreach (var с in б.Из_окна(h, я, у_гаражей, л, час, 5, раз))
                        {
                            строк++;
                            if (Разметка(с))
                                плохо.Add($"в виде из окна осталась разметка: {с}");
                        }
                    }
            h.day = 4;
            h.снег = 0;
            h.режим = Режим.МЕТЕЛЬ;
            окно_итог = $"затишье: {string.Join(" ", тихо)}; {строк} строк без разметки"
                        + (зарево is not null ? $"; зарево: «{зарево}»" : "; зарева за 30 дней не было");
        }

        // ---- 7. подслушать ----
        string слух_итог;
        {
            var (h, я, о) = Жизнь();
            h.day = 4;
            var з = о.заражение;
            var нина = h.people["нина"];
            var толик = h.people["толик"];
            var валя = h.people["валя"];
            СоседГде Дома(NPC p) => new(p.id, p.@short, Где.Дома, p.apt, 1, "", h.хозяин_жилья(p).apt, 1);
            List<СоседГде> Все() => h.others(я).Where(p => p.alive).Select(Дома).ToList();
            Подслушано Слушать(NPC у, List<СоседГде>? кто_где = null, double час = 14)
                => Чисто(h, () => б.Подслушать(h, я, h.хозяин_жилья(у).apt, кто_где ?? Все(), час, з, 5, 0), "подслушивание");
            bool Сказано(Подслушано п, string список, NPC кто)
                => п.строки.Any(с => б.Живое("подслушать", список).Any(т => Похоже(т, с, кто, я)));
            var все = new List<Подслушано>();
            // никого и ночь
            var никого_нет = Слушать(нина, Все().Where(с => с.id != нина.id).ToList());
            if (!Сказано(никого_нет, "тихо", я))
                плохо.Add($"у Нины никого нет дома — а за дверью слышно: {string.Join(" / ", никого_нет.строки)}");
            var ночью = Слушать(нина, час: 2);
            if (!Сказано(ночью, "спят", я))
                плохо.Add($"два часа ночи — а у Нины не спят: {string.Join(" / ", ночью.строки)}");
            // замысел: уйти
            var было_у_нины = нина.замысел;
            нина.замысел = new Замысел { вид = "уйти", с_дня = h.day };
            var уйти = Слушать(нина);
            все.Add(уйти);
            if (!Сказано(уйти, "уйти", нина))
                плохо.Add($"Нина задумала уйти — а за дверью о другом: {string.Join(" / ", уйти.строки)}");
            if (!уйти.строки.Any(с => с.Contains(нина.form("gen"), StringComparison.Ordinal)))
                плохо.Add($"героиня знает Нину — а голос не подписан её именем: {string.Join(" / ", уйти.строки)}");
            нина.замысел = было_у_нины;
            // замысел против героини: слух пустить — с номером её квартиры
            var было_у_толика = толик.замысел;
            толик.замысел = new Замысел { вид = "рассорить", с_дня = h.day, враг = я.id };
            var на_неё = Слушать(толик);
            все.Add(на_неё);
            if (!Сказано(на_неё, "на_героя", толик) || !на_неё.строки.Any(с => с.Contains(я.apt.ToString(), StringComparison.Ordinal)))
                плохо.Add($"Толик задумал ославить героиню — а за дверью этого не слышно: {string.Join(" / ", на_неё.строки)}");
            толик.замысел = было_у_толика;
            // злость
            if (толик.замысел is null)
            {
                толик.hate[я.id] = 60;
                var зло = Слушать(толик);
                все.Add(зло);
                if (!Сказано(зло, "о_герое", толик))
                    плохо.Add($"Толик героиню ненавидит — а за дверью о другом: {string.Join(" / ", зло.строки)}");
                толик.hate.Убрать(я.id);
            }
            // голод и полный шкаф — и героиня узнаёт о еде
            if (валя.замысел is null)
            {
                double сыта = валя.satiety, еды = валя.stock.Взять("еда", 0.0);
                валя.satiety = 20;
                var голод = Слушать(валя);
                все.Add(голод);
                if (!Сказано(голод, "голод", валя) || !голод.о_еде.Any(е => е.кто == валя.id))
                    плохо.Add($"Валя голодает — а за дверью не о голоде или героиня о её еде ничего не узнала: {string.Join(" / ", голод.строки)}");
                валя.satiety = 85;
                валя.stock["еда"] = 20;
                var шкаф = Слушать(валя);
                все.Add(шкаф);
                if (!Сказано(шкаф, "запасы", валя) || !шкаф.о_еде.Any(е => е.кто == валя.id && е.еды >= 20))
                    плохо.Add($"у Вали полный шкаф — а за дверью не о нём или героиня не узнала сколько: {string.Join(" / ", шкаф.строки)}");
                валя.satiety = сыта;
                валя.stock["еда"] = еды;
            }
            else
                плохо.Add($"у Вали замысел «{валя.замысел.вид}» — проверка голода и шкафа ни к чему");
            int строк = 0;
            foreach (var с in h.others(я).Where(p => p.alive))
                for (int раз = 0; раз < 3; раз++)
                    foreach (var стр in б.Подслушать(h, я, h.хозяин_жилья(с).apt, Все(), 14, з, 5, раз).строки)
                    {
                        строк++;
                        if (Разметка(стр))
                            плохо.Add($"в подслушанном осталась разметка ({с.id}): {стр}");
                    }
            слух_итог = $"{string.Join(" / ", уйти.строки)}; {string.Join(" / ", на_неё.строки)}; {строк} строк без разметки";
        }

        // ---- 8. записки на дверях ----
        string записки_итог;
        {
            var (h, я, о) = Жизнь();
            h.day = 4;
            var з = о.заражение;
            var нина = h.people["нина"];
            var валя = h.people["валя"];
            var пётр = h.people["пётр"];
            var игорь = h.people["игорь"];
            List<ДверьСнаружи> Двери(int? тело = null) => h.flats.Select(п => п.Key).OrderBy(к => к)
                .Select(к => new ДверьСнаружи(к, true, false, к == тело, false, false, false)).ToList();
            IReadOnlyList<Записка> Записки(int? тело = null) => Чисто(h, () => б.Записки(h, я, Двери(тело), з, 5), "записки на дверях");
            Записка? На(IReadOnlyList<Записка> з_, int кв) => з_.FirstOrDefault(х => х.квартира == кв);
            // крест мелом
            var с_телом = Записки(игорь.apt);
            if (На(с_телом, игорь.apt) is not { чем: Чем.МЕЛ } крест || !крест.текст.Contains('†'))
                плохо.Add($"у Игоря хозяин остался внутри — а на двери нет креста: {На(с_телом, игорь.apt)}");
            // съехала к Вале
            string? было = нина.living_with;
            нина.living_with = валя.id;
            var съехала = Записки();
            нина.living_with = было;
            if (На(съехала, нина.apt) is not { чем: Чем.БУМАГА } где
                || !где.текст.Contains(валя.form("gen").ToUpperInvariant(), StringComparison.Ordinal)
                || !где.текст.Contains(валя.apt.ToString(), StringComparison.Ordinal))
                плохо.Add($"Нина живёт у Вали — а на её двери не написано, где искать: {На(съехала, нина.apt)}");
            // больной
            Болеют(h, з, ("пётр", Стадия.БОЛЕН), (я.id, Стадия.БОЛЕН));
            var больны = Записки();
            if (На(больны, пётр.apt) is null || !б.Живое("записки", "болеют").Contains(На(больны, пётр.apt)!.текст))
                плохо.Add($"Пётр болен — а на его двери не «болеем»: {На(больны, пётр.apt)}");
            if (На(больны, я.apt) is { } своя)
                плохо.Add($"на своей двери героини — записка «{своя.текст}»: её пишет не дом");
            Болеют(h, з);
            // последнее отдаст: с третьего дня и пока есть еда
            if (!валя.пунктики.Contains("последнее_отдаст"))
                плохо.Add("у Вали нет пунктика «последнее_отдаст» — записку некому писать");
            else
            {
                double еды = валя.stock.Взять("еда", 0.0);
                валя.stock["еда"] = 5;
                if (На(Записки(), валя.apt) is null)
                    плохо.Add("четвёртый день, у Вали есть еда — а записки «стучите» нет");
                h.day = 1;
                if (На(Записки(), валя.apt) is { } рано)
                    плохо.Add($"первый день метели — а Валя уже зовёт: «{рано.текст}»");
                h.day = 4;
                валя.stock["еда"] = 0;
                if (На(Записки(), валя.apt) is { } пусто_у_вали)
                    плохо.Add($"у Вали кончилась еда — а записка «{пусто_у_вали.текст}» висит");
                валя.stock["еда"] = еды;
            }
            foreach (var з_ in съехала.Concat(больны).Concat(с_телом))
                if (Разметка(з_.текст))
                    плохо.Add($"в записке осталась разметка: {з_.текст}");
            записки_итог = string.Join("; ", съехала.Concat(с_телом).Concat(больны).Select(х => $"кв.{х.квартира}: {х.текст}").Distinct().Take(5));
        }

        // ---- 5. узел ----
        string узел = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Годот"), "*.cs").Select(File.ReadAllText));
        var требования = new (string текст, string беда)[]
        {
            ("_беседы.За_дверью(", "стук без дела не отвечает — снова «сейчас сюда незачем»"),
            ("_беседы.Мимоходом(", "соседи на ходу молчат — подъезд немой"),
            ("_беседы.Из_окна(", "окно не показывает, что за ним"),
            ("_беседы.Подслушать(", "у двери без дела нельзя постоять и послушать"),
            ("_мир.Записки(_записки)", "записки на дверях не вешаются в мире"),
            ("на двери записка: «", "подсказка у двери не читает записку"),
            ("Социальное.note_signal(я, кто, \"еда\", еды", "подслушанное о еде не ложится в сведения героя — мена и просьба о нём не знают"),
            ("У_двери_без_дела(кв);", "дверь без дела сразу стучит — постоять тихо нельзя"),
        };
        foreach (var (текст, беда) in требования)
            if (!узел.Contains(текст, StringComparison.Ordinal))
                плохо.Add($"узел: {беда}");
        if (узел.Contains("Сказать(\"сейчас сюда незачем\")", StringComparison.Ordinal))
            плохо.Add("узел: стук в дверь без дела всё ещё кончается «сейчас сюда незачем»");
        // на ходу дом читается только пока спит
        int где_мимо = узел.IndexOf("_беседы.Мимоходом(", StringComparison.Ordinal);
        if (где_мимо >= 0)
        {
            int начало = узел.LastIndexOf("private void ", где_мимо, StringComparison.Ordinal);
            if (начало < 0 || !узел[начало..где_мимо].Contains("Дом_спит", StringComparison.Ordinal))
                плохо.Add("узел: соседи говорят на ходу, не проверив, что дом спит, — дом читается посреди хода");
        }

        w($"  на ходу: {ходом_итог}");
        w($"  у двери: {дверь_итог}");
        w($"  из окна: {окно_итог}");
        w($"  подслушано: {слух_итог}");
        w($"  записки: {записки_итог}");
        return плохо;
    }
