// Проверка живого подъезда (`Дом.Экран/Живое.cs`, импровизация 17.11.2026):
// что соседи говорят на ходу, что отвечает дверь на стук без дела и что
// видно из окна.
//
//  1. **Слова есть.** Каждый список трёх разделов `разговоры.json` не пуст:
//     пустой уронил бы реплику на индексе −1 (падение — не краснота, поэтому
//     дальше пункт не идёт).
//  2. **На ходу.** Злой — зло или молчит; больной с «Вектора» — кашляет;
//     голодный — о голоде (пороги — `Беседы.Нужда`); стоящий у чужой двери —
//     к кому пришёл, по имени; после смерти в доме — о мёртвом; сытый
//     и спокойный — без жалоб. Ни в одной реплике двух героев о каждом
//     соседе нет разметки.
//  3. **У двери.** Пустая квартира — пусто, с телом — тело, разобранная —
//     разобрана; живут, но ушли — тишина и никто не ответил; ночью — спят;
//     больной и злой не открывают; второй стук подряд — злятся (свой — нет);
//     у двери уже стоят — занят; чужой открывает на цепочку, свой — настежь;
//     за дверью слышно кашель больного и плач голодного ребёнка. Разметки нет.
//  4. **Из окна.** Буран — двора не видно; в затишье соседа у гаражей видно
//     и называют по имени; ночь без света — темно; сугробы — когда снега
//     больше метра; зарево — когда в городе горит. Разметки нет.
//  5. **Узел.** Стук без дела отвечает `За_дверью`, а не «незачем»; соседи
//     говорят на ходу только пока дом спит; окно показывает `Из_окна`;
//     у двери без дела можно постоять тихо — `Подслушать`, и услышанное
//     о еде ложится в сведения героя.
//  7. **Подслушать.** Дома никого — тихо, ночью — спят; кто дома, говорит
//     о своём замысле (уйти), о замысле против героя (с номером его
//     квартиры), о злости на него, о голоде и о полном шкафе — и о еде герой
//     узнаёт (о ком и сколько); голос подписан именем, если герой его знает.
//     Разметки нет, дом не тронут.
//  8. **Записки на дверях.** Где хозяин остался внутри — мелом крест; все
//     съехали к соседу — «мы у такого-то», с его квартирой; больной —
//     «болеем»; у той, кто последнее отдаст, — «стучите», с третьего дня
//     и пока у неё есть еда; на своей двери — ничего, даже когда героиня
//     больна. Разметки нет, дом не тронут.
//  6. **Только слова.** Пункты 2–4 не трогают дом: снимок дома до и после
//     одинаков.

