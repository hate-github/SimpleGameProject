            if (злых == 0)
                плохо.Add("Толик героиню ненавидит — и за восемь встреч не сказал ни слова: злой должен и огрызаться");
            толик.hate.Убрать(я.id);
            // больной с «Вектора»
            Болеют(h, з, ("пётр", Стадия.БОЛЕН));
            string? кашель = б.Мимоходом(h, я, пётр, Где.НаПлощадке, пётр.apt, 14, з, 5, 0);
            if (кашель is null || !Из("мимоходом", "болен", кашель, пётр, я))
                плохо.Add($"Пётр болен — а на ходу не кашляет: «{кашель}»");
            Болеют(h, з);
            // голодный — о голоде
            валя.satiety = 8;
            var о_голоде = Enumerable.Range(0, 8)
                .Select(р => Чисто(h, () => б.Мимоходом(h, я, валя, Где.НаПлощадке, валя.apt, 14, з, 5, р), "реплика на ходу"))
                .OfType<string>().ToList();
