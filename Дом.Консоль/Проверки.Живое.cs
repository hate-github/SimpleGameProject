        bool Из(string раздел, string список, string реплика, NPC говорит, NPC я)
            => б.Живое(раздел, список).Any(т => Похоже(т, реплика, говорит, я));
        // реплика из списка — с подстановками: сравнивается то, что вокруг них
        static bool Похоже(string шаблон, string реплика, NPC говорит, NPC я)
        {
            string т = Беседы.Слова(шаблон, говорит, я);
