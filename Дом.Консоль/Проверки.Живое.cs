                .Select(к => new ДверьСнаружи(к, true, false, к == тело, false, false, false)).ToList();
            IReadOnlyList<Записка> Записки(int? тело = null) => Чисто(h, () => б.Записки(h, я, Двери(тело), з, 5), "записки на дверях");
            Записка? На(IReadOnlyList<Записка> з_, int кв) => з_.FirstOrDefault(х => х.квартира == кв);
            // крест мелом
            var с_телом = Записки(игорь.apt);
            if (На(с_телом, игорь.apt) is not { чем: Чем.МЕЛ } крест || !крест.текст.Contains('†'))
                плохо.Add($"у Игоря хозяин остался внутри — а на двери нет креста: {На(с_телом, игорь.apt)}");
            // съехала к Вале
            string? было = нина.living_with;
            нина.living_with = валя.id;
            var съехала = Записки();
            нина.living_with = было;
            if (На(съехала, нина.apt) is not { чем: Чем.БУМАГА } где
                || !где.текст.Contains(валя.form("gen").ToUpperInvariant(), StringComparison.Ordinal)
                || !где.текст.Contains(валя.apt.ToString(), StringComparison.Ordinal))
                плохо.Add($"Нина живёт у Вали — а на её двери не написано, где искать: {На(съехала, нина.apt)}");
            // больной
            Болеют(h, з, ("пётр", Стадия.БОЛЕН), (я.id, Стадия.БОЛЕН));
            var больны = Записки();
            if (На(больны, пётр.apt) is null || !б.Живое("записки", "болеют").Contains(На(больны, пётр.apt)!.текст))
                плохо.Add($"Пётр болен — а на его двери не «болеем»: {На(больны, пётр.apt)}");
            if (На(больны, я.apt) is { } своя)
                плохо.Add($"на своей двери героини — записка «{своя.текст}»: её пишет не дом");
            Болеют(h, з);
            // последнее отдаст: с третьего дня и пока есть еда
            if (!валя.пунктики.Contains("последнее_отдаст"))
                плохо.Add("у Вали нет пунктика «последнее_отдаст» — записку некому писать");
            else
            {
                double еды = валя.stock.Взять("еда", 0.0);
                валя.stock["еда"] = 5;
                if (На(Записки(), валя.apt) is null)
                    плохо.Add("четвёртый день, у Вали есть еда — а записки «стучите» нет");
                h.day = 1;
                if (На(Записки(), валя.apt) is { } рано)
                    плохо.Add($"первый день метели — а Валя уже зовёт: «{рано.текст}»");
                h.day = 4;
                валя.stock["еда"] = 0;
                if (На(Записки(), валя.apt) is { } пусто_у_вали)
                    плохо.Add($"у Вали кончилась еда — а записка «{пусто_у_вали.текст}» висит");
                валя.stock["еда"] = еды;
            }
            foreach (var з_ in съехала.Concat(больны).Concat(с_телом))
                if (Разметка(з_.текст))
                    плохо.Add($"в записке осталась разметка: {з_.текст}");
            записки_итог = string.Join("; ", съехала.Concat(с_телом).Concat(больны).Select(х => $"кв.{х.квартира}: {х.текст}").Distinct().Take(5));
        }

        // ---- 9. у чужой двери ----
        string у_двери_итог;
        {
            var (h, я, о) = Жизнь();
            h.day = 4;
            var валя = h.people["валя"];
            var нина = h.people["нина"];
            int кв = h.хозяин_жилья(нина).apt;
            СоседГде Дома(NPC p) => new(p.id, p.@short, Где.Дома, p.apt, 1, "", h.хозяин_жилья(p).apt, 1);
            var все = h.others(я).Where(p => p.alive).Select(Дома).ToList();
            string? просьба = Чисто(h, () => б.У_двери(h, я, валя, кв, "попросить", все, 5, 0), "разговор у двери");
            if (просьба is null || !просьба.Contains(валя.@short) || !просьба.Contains(нина.@short)
                || !б.Живое("у_двери", "попросить_гость").Any(т => просьба.Contains(Беседы.Слова(т, валя, я)))
                || !б.Живое("у_двери", "попросить_хозяин").Any(т => просьба.Contains(Беседы.Слова(т, нина, я))))
                плохо.Add($"Валя у двери Нины просит — а слышно не это: «{просьба}»");
            var без_нины = все.Select(с => с.id == нина.id ? с with { где = Где.ЗаПорогом } : с).ToList();
            string? тишина = б.У_двери(h, я, валя, кв, "попросить", без_нины, 5, 0);
            if (тишина is null || !б.Живое("у_двери", "нет_дома").Any(т => тишина.Contains(т)) || тишина.Contains(нина.@short))
                плохо.Add($"Нины нет дома — а за её дверью отвечают: «{тишина}»");
            try
            {
                if (б.У_двери(h, я, валя, кв, "разбор", все, 5, 0) is { } лишнее)
                    плохо.Add($"разбор — не разговор у двери, а слышно: «{лишнее}»");
            }
            catch (KeyNotFoundException)
            {
                плохо.Add("разбор — не разговор у двери, а реплику для него ищут в списках и падают: дело не из тех, что слышно на площадке");
            }
            foreach (var ключ in Беседы.У_ДВЕРИ)
                for (int р = 0; р < 3; р++)
                    if (б.У_двери(h, я, валя, кв, ключ, все, 5, р) is string с_ && Разметка(с_))
                        плохо.Add($"в разговоре у двери ({ключ}) осталась разметка: {с_}");
            у_двери_итог = $"{просьба}; {тишина}";
        }

        // ---- 10. записка героя ----
        string записка_итог;
        {
            var (h, я, о) = Жизнь();
            h.day = 4;
            string без = Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(h));
            я.записка = "болею";
            if (Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(h)) != без)
                плохо.Add("записка героини попала в снимок дома — эталон бы разошёлся");
            я.записка = null;
            double? Оценка(NPC кто, string ключ)
                => Действия.gather(h, кто).варианты
                       .Where(в => в.что.key == ключ && ReferenceEquals(в.что.target, я))
                       .Select(в => (double?)в.оценка).FirstOrDefault();
            var нина = h.people["нина"];
            int проверено = 0;
            foreach (var вид in ЗапискаГероя.ВИДЫ)
                foreach (var ключ in new[] { "разговор", "попросить", "обмен" })
                {
                    я.записка = null;
                    double? до = Оценка(нина, ключ);
                    я.записка = вид;
                    double? после = Оценка(нина, ключ);
                    я.записка = null;
                    if (до is null && после is null)
                        continue;
                    проверено++;
                    // поправка идёт сквозь характер (`Корзина.add`): минус — дело
                    // дешевле или вовсе вычеркнуто (оценка не выше нуля), плюс —
                    // дороже или появилось, ноль — как было
                    double ждём = ЗапискаГероя.Поправка(вид, ключ);
                    bool верно = ждём == 0 ? после == до
                               : ждём < 0 ? после is null || (до is not null && после < до)
                               : после is not null && (до is null || после > до);
                    if (!верно)
                        плохо.Add($"записка «{вид}»: «{ключ}» Нины к героине был {до?.ToString() ?? "—"}, стал {после?.ToString() ?? "—"}, а поправка {Текст.G(ждём)}");
                }
            if (проверено < 8)
                плохо.Add($"у Нины к героине в корзине мало дел — записку проверили на {проверено} из 12");
            // «болею» вычёркивает или режет сильнее «не стучать»
            я.записка = "не_стучать";
            double? вежливо = Оценка(нина, "разговор");
            я.записка = "болею";
            double? страшно = Оценка(нина, "разговор");
            я.записка = null;
            if (страшно is not null && (вежливо is null || страшно >= вежливо))
                плохо.Add($"«болею» держит Нину от разговора слабее, чем «не стучать»: {страшно} против {вежливо?.ToString() ?? "—"}");
            // на своей двери — записка героини
            я.записка = "меняю";
            var двери = h.flats.Select(п => п.Key).OrderBy(к => к)
                               .Select(к => new ДверьСнаружи(к, true, false, false, false, false, false)).ToList();
            var своя = б.Записки(h, я, двери, о.заражение, 5).FirstOrDefault(з_ => з_.квартира == h.хозяин_жилья(я).apt);
            if (своя is null || своя.текст != б.записка_героя["меняю"])
                плохо.Add($"героиня написала «меняю» — а на её двери: «{своя?.текст}»");
            я.записка = null;
            // о записке говорят на ходу
            я.записка = "меняю";
            var о_записке = Enumerable.Range(0, 14).Select(р => б.Мимоходом(h, я, нина, Где.НаПлощадке, нина.apt, 14, о.заражение, 5, р))
                                      .OfType<string>().ToList();
            я.записка = null;
            if (!о_записке.Any(р => Из("мимоходом", "записка_меняю", р, нина, я)))
                плохо.Add($"на двери героини «меняюсь» — а Нина на ходу о записке ни слова: {string.Join(" / ", о_записке.Take(4))}");
            foreach (var вид in ЗапискаГероя.ВИДЫ)
                if (!б.записка_героя.ContainsKey(вид))
                    плохо.Add($"записки «{вид}» нет в разговоры.json — на двери пусто");
            string ядро = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Ядро", "Действия.Сбор.Люди.cs"));
            int мест = System.Text.RegularExpressions.Regex.Matches(ядро, @"ЗапискаГероя\.Поправка\(t\.записка").Count;
            if (мест != 3)
                плохо.Add($"записку читают в {мест} местах сбора, а должны в трёх: разговор, просьба, мена");
            string сейв = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Ядро", "Петля", "СохранениеИгры.cs"));
            if (!сейв.Contains("[\"записка\"] = я.записка", StringComparison.Ordinal)
                || !сейв.Contains("я.записка = и[\"записка\"]", StringComparison.Ordinal))
                плохо.Add("сохранение игры не помнит записку героя — после загрузки дверь чистая");
            записка_итог = $"поправок проверено {проверено}; на своей двери: «{своя?.текст}»";
        }

        // ---- 11. мысль героя у двери ----
        string мысль_итог;
        {
            var (h, я, _) = Жизнь();
            ДверьСнаружи Дверь(bool тело = false, bool свет = false, bool взломана = false)
                => new(7, true, свет, тело, false, взломана, false);
            bool Из_мыслей(string список, string? м) => м is not null && б.Живое("мысли_героя", список).Any(т => Беседы.Слова(т, я, я) == м);
            var крест = б.Мысль_у_двери(я, Дверь(тело: true, свет: true), null, Порог.ОБЫЧНО, 5, 4);
            if (!Из_мыслей("тело_обычно", крест))
                плохо.Add($"у двери крест и свет — а героиня думает не о мёртвом: «{крест}»");
            var холодно = б.Мысль_у_двери(я, Дверь(тело: true), null, Порог.ТРЕВОГА, 5, 4);
            if (!Из_мыслей("тело_холодно", холодно))
                плохо.Add($"рассудок на тревоге — а о мёртвом героиня думает по-прежнему: «{холодно}»");
            var больны = б.Мысль_у_двери(я, Дверь(), new Записка(7, б.Живое("записки", "болеют")[0], Чем.БУМАГА), Порог.ОБЫЧНО, 5, 4);
            if (!Из_мыслей("болеют_обычно", больны))
                плохо.Add($"на двери «болеем» — а героиня не думает о болезни: «{больны}»");
            if (б.Мысль_у_двери(я, Дверь(), null, Порог.ОБЫЧНО, 5, 4) is { } лишняя)
                плохо.Add($"обычная дверь — а героиня о ней думает: «{лишняя}»");
            foreach (var порог in new[] { Порог.ОБЫЧНО, Порог.ТРЕВОГА, Порог.ОТСТРАНЕНИЕ })
                foreach (var д in new[] { Дверь(тело: true), Дверь(свет: true), Дверь(взломана: true), new ДверьСнаружи(7, false, false, false, true, false, true), new ДверьСнаружи(7, true, false, false, true, false, false) })
                    for (int день = 1; день <= 4; день++)
                        if (б.Мысль_у_двери(я, д, null, порог, 5, день) is string м && Разметка(м))
                            плохо.Add($"в мысли героини осталась разметка: {м}");
            мысль_итог = $"«{крест}» / на тревоге: «{холодно}» / «{больны}»";
        }

        // ---- 5. узел ----
        string узел = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Годот"), "*.cs").Select(File.ReadAllText));
        var требования = new (string текст, string беда)[]
        {
            ("_беседы.За_дверью(", "стук без дела не отвечает — снова «сейчас сюда незачем»"),
            ("_беседы.Мимоходом(", "соседи на ходу молчат — подъезд немой"),
            ("_беседы.Из_окна(", "окно не показывает, что за ним"),
            ("_беседы.Подслушать(", "у двери без дела нельзя постоять и послушать"),
            ("_мир.Записки(_записки)", "записки на дверях не вешаются в мире"),
            ("_беседы.У_двери(", "у чужой двери соседи молчат — разговор не слышно"),
            ("_мир.Взгляды(где_он)", "соседи не поворачиваются к подошедшему герою — стоят истуканами"),
            ("Своя_дверь();", "у своей двери нельзя оставить записку"),
            ("я.записка = вид;", "записка героя не пишется на дверь"),
            ("_беседы.Мысль_у_двери(", "у тяжёлой двери героиня ни о чём не думает"),
            ("Мысль_кадр();", "мысль у двери не спрашивается каждый кадр — героиня молчит"),
            ("_мир.Во_дворе(кто_где);", "кто на вылазке во дворе, того во дворе нет — окно его видит, а выйдешь — пусто"),
            ("на двери записка: «", "подсказка у двери не читает записку"),
            ("Социальное.note_signal(я, кто, \"еда\", еды", "подслушанное о еде не ложится в сведения героя — мена и просьба о нём не знают"),
            ("У_двери_без_дела(кв);", "дверь без дела сразу стучит — постоять тихо нельзя"),
        };
        foreach (var (текст, беда) in требования)
            if (!узел.Contains(текст, StringComparison.Ordinal))
                плохо.Add($"узел: {беда}");
        if (узел.Contains("Сказать(\"сейчас сюда незачем\")", StringComparison.Ordinal))
            плохо.Add("узел: стук в дверь без дела всё ещё кончается «сейчас сюда незачем»");
        // на ходу дом читается только пока спит
        int где_мимо = узел.IndexOf("_беседы.Мимоходом(", StringComparison.Ordinal);
        if (где_мимо >= 0)
        {
            int начало = узел.LastIndexOf("private void ", где_мимо, StringComparison.Ordinal);
            if (начало < 0 || !узел[начало..где_мимо].Contains("Дом_спит", StringComparison.Ordinal))
                плохо.Add("узел: соседи говорят на ходу, не проверив, что дом спит, — дом читается посреди хода");
        }

        w($"  на ходу: {ходом_итог}");
        w($"  у двери: {дверь_итог}");
        w($"  из окна: {окно_итог}");
        w($"  подслушано: {слух_итог}");
        w($"  записки: {записки_итог}");
        w($"  у чужой двери: {у_двери_итог}");
        w($"  записка героини: {записка_итог}");
        w($"  мысли у двери: {мысль_итог}");
        return плохо;
    }
