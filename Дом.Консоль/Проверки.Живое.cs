            List<СоседГде> Все(Где где_оксаны) => h.others(я).Where(p => p.alive)
                .Select(p => p.id == оксана.id ? Где_(p, где_оксаны, кв) : Где_(p, Где.Дома, h.хозяин_жилья(p).apt)).ToList();
            ОтветДвери Стук(List<СоседГде> кто_где, double час, bool опять = false, ДверьСнаружи? снаружи = null, int раз = 0)
