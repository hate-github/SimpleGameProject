                плохо.Add($"Игорь умер сегодня — а Нина за десять встреч о нём ни слова: {string.Join(" / ", о_смерти)}");
            игорь.alive = true;
            игорь.died_day = null;

            // разметки нет: два героя, все соседи, все положения
