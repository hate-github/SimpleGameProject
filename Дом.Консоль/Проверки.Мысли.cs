// Проверка мест мыслей (`Дом.Экран/Места.cs`): у каждой мысли есть место.
//
// Вопрос дня больше не висит списком на экране — он в телефоне, а отвечают
// на него ногами, у места. Мысль, которой не нашлось места, ответить
// нечем, и дом встал бы на вопросе навсегда. Поэтому:
//
//  1. **Раскладка справочника закрыта.** Каждое действие — ровно в одном
//     списке (дома у вещи, на площадке, у выхода, у пустых квартир,
//     у квартир с телом, по цели), и в списках нет того, чего нет
//     в справочнике. Ночные поступки в справочник дня не входят: их
//     спрашивает ночь — окном, а не мыслью.
//  2. **Каждая мысль, которую дом предложил за три жизни по восемь дней,
//     получила место**, и место не пустое: у «разобрать» есть пустые
//     квартиры, у «вынести» — квартиры с телом. Действие «по цели» без цели
//     и домашнее с целью — тоже беда: раскладка разошлась со сбором.
//     Места считаются дважды — будто все кладовые стоят в мире и будто
//     ни одной: какие стоят, решает сцена движка, а место должно найтись
//     при любой.
//  3. **У каждого места есть подсказка «как»** — телефон её показывает.
//  4. **Кладовая в мире — сама себе место.** Мысль о ней ведёт к ней самой
//     (там отпирают или взламывают и обыскивают руками), а о кладовой,
//     которой в мире нет, — к выходу, как вылазка. С чем идут, говорит
//     мысль: «вскрыть» — ломать замок, «сходить» — открыть; подсказка
//     говорит то же. Обе мысли ставятся и руками — в трёх жизнях
//     «вскрыть» может и не случиться, а ветка должна исполниться.

using Дом.Экран;
using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> МестаМыслей_(Action<string> w)
    {
        var плохо = new List<string>();

        // ---- 1. раскладка закрыта ----
        var в_справочнике = Дом.Ядро.Каталог.ДЕЙСТВИЯ.Select(д => д.key).ToHashSet(StringComparer.Ordinal);
        var разложено = Места.Раскладка().ToList();
        foreach (var г in разложено.GroupBy(р => р.ключ, StringComparer.Ordinal))
        {
            if (г.Count() > 1)
                плохо.Add($"«{г.Key}» разложено дважды: {string.Join(", ", г.Select(р => р.список))}");
            if (!в_справочнике.Contains(г.Key))
                плохо.Add($"«{г.Key}» ({г.First().список}) — такого действия в справочнике нет");
        }
        var в_раскладке = разложено.Select(р => р.ключ).ToHashSet(StringComparer.Ordinal);
        foreach (var к in в_справочнике.OrderBy(x => x, StringComparer.Ordinal))
            if (!в_раскладке.Contains(к))
                плохо.Add($"«{к}» не разложено: где делать такую мысль, не сказано");
        if (!в_справочнике.Contains(Места.ВЗЛОМ))
            плохо.Add($"мысль о взломе кладовой зовётся «{Места.ВЗЛОМ}», а в справочнике такой нет");

        // ---- 2, 3 и 4. мысли трёх жизней ----
        var беды = new SortedSet<string>(StringComparer.Ordinal);
        var видов = new SortedDictionary<ВидАдреса, int>();
        var ключей = new HashSet<string>(StringComparer.Ordinal);
        var никаких = new HashSet<string>(StringComparer.Ordinal);
        int мыслей = 0, вопросов = 0, о_кладовых = 0;

        // Одна мысль — два места: при всех кладовых в мире и ни при одной
        void Сверить(House h, NPC я, ВариантИгроку вар, IReadOnlySet<string> все,
                     IReadOnlyDictionary<string, int> у_двери, bool руками = false)
        {
            var а = Места.Где(h, я, вар, у_двери, все);
            var б = Места.Где(h, я, вар, у_двери, никаких);
            if (а is null || б is null)
            {
                беды.Add($"мысли «{Разбор.имя(вар.что)}» некуда нести"
                         + (а is null ? "" : " (когда кладовых в мире нет)"));
                return;
            }
            if (!руками)
                видов[а.вид] = видов.GetValueOrDefault(а.вид) + 1;
            foreach (var м in new[] { а, б })
            {
                if (м.вид == ВидАдреса.ДВЕРИ && м.квартиры.Count == 0)
                    беды.Add($"«{вар.ключ}»: подходящих квартир нет, а мысль есть");
                if (Места.Как(h, я, м).Length == 0)
                    беды.Add($"«{вар.ключ}»: место есть, а как туда попасть — не сказано");
            }
            if (вар.цель is not Кладовая к)
            {
                if (а.вид == ВидАдреса.КЛАДОВАЯ || б.вид == ВидАдреса.КЛАДОВАЯ)
                    беды.Add($"«{вар.ключ}» без кладовой ведёт к кладовой");
                return;
            }
            о_кладовых++;
            bool взлом = вар.ключ == Места.ВЗЛОМ;
            if (а.вид != ВидАдреса.КЛАДОВАЯ || а.кладовая != к.id)
                беды.Add($"«{вар.ключ}» о кладовой {к.id}, что стоит в мире, ведёт не к ней: "
                         + $"{а.вид} {а.кладовая}");
            else if (а.взлом != взлом)
                беды.Add($"«{вар.ключ}» у {к.id}: идут {(а.взлом ? "ломать" : "открывать")}, "
                         + $"а мысль {(взлом ? "о взломе" : "не о взломе")}");
            if (б.вид != ВидАдреса.ВЫХОД)
                беды.Add($"«{вар.ключ}» о кладовой {к.id}, которой в мире нет, ведёт не к выходу: {б.вид}");
            string как = Места.Как(h, я, а);
            string ждём = к.вид == ВидКладовой.ПОГРЕБ ? "подвал" : "двор";
            if (!как.Contains(ждём, StringComparison.Ordinal))
                беды.Add($"«{вар.ключ}» у {к.id}: подсказка не говорит, где это ({ждём}): «{как}»");
            if (как.Contains("взломать", StringComparison.Ordinal) != взлом)
                беды.Add($"«{вар.ключ}» у {к.id}: подсказка «{как}» — "
                         + (взлом ? "а ломать не велит" : "а велит ломать"));
        }

        foreach (long зерно in new long[] { 11, 23, 42 })
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 8,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            var h = прогон.h;
            var я = h.people["оксана"];
            var все = h.кладовые.Значения.Select(к => к.id).ToHashSet(StringComparer.Ordinal);
            var никого = new Dictionary<string, int>(StringComparer.Ordinal);

            // руками — обе мысли о каждой кладовой, до того как дом пошёл
            foreach (var к in h.кладовые.Значения.OrderBy(к => к.id, StringComparer.Ordinal))
                foreach (string ключ in new[] { "кладовая", Места.ВЗЛОМ })
                    Сверить(h, я, new ВариантИгроку((ключ, (object?)к), 1.0, ключ), все, никого,
                            руками: true);

            int k = 0;
            я.решающий = new Человек((ВопросИгроку в) =>
            {
                if (в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
                {
                    вопросов++;
                    foreach (var вар in в.варианты)
                    {
                        мыслей++;
                        ключей.Add(вар.ключ);
                        bool с_целью = вар.цель is not null;
                        if (Места.ПО_ЦЕЛИ.Contains(вар.ключ) && !с_целью)
                            беды.Add($"«{вар.ключ}» разложено «по цели», а пришло без цели");
                        if (!Места.ПО_ЦЕЛИ.Contains(вар.ключ) && с_целью)
                            беды.Add($"«{вар.ключ}» пришло с целью, а разложено не «по цели»");
                        Сверить(h, я, вар, все, никого);
                    }
                }
                return new[] { 0, 1, 0, 2, 3 }[k++ % 5];
            });
            прогон.run();
        }
        плохо.AddRange(беды);
        if (вопросов == 0 || ключей.Count < 10)
            плохо.Add($"за три жизни мыслей почти не было ({ключей.Count} видов) — проверять не на чем");
        if (!ключей.Contains("кладовая"))
            плохо.Add("за три жизни ни одной мысли сходить в кладовую — места кладовых не проверены жизнью");

        w($"  раскладка: {в_справочнике.Count} действий справочника, каждое на своём месте");
        w($"  мысли: {мыслей} за {вопросов} вопросов, {ключей.Count} видов — "
          + string.Join(", ", видов.Select(в => $"{в.Key.ToString().ToLowerInvariant()} {в.Value}")));
        w($"  о кладовых: {о_кладовых} мыслей — в мире ведут к себе, без мира к выходу");
        return плохо;
    }
}
