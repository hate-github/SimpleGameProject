// Проверка заражения, знатоков и бункера (задание автора, пп. 6–8, 10;
// `Дом.Ядро/Петля/Заражение.cs`, `Округа.cs`, `data/мир.json`).
//
//  1. **Стадии как в задании.** Задетый наутро заболевает (или обошлось);
//     от заражения до смерти — три-пять дней, всегда; больной и тяжёлый
//     теряют здоровье; смерть — общей смертью дома.
//  2. **Передаётся.** Больной заразен: кто встречался с ним лицом к лицу,
//     задет с шансом; заражённый, но ещё не больной, — не заразен.
//  3. **Промзона.** Кто не знает, какие корпуса обходить, задевается часто;
//     кто знает — редко, но и уносит меньше. Находка — в тару.
//  4. **Знатоки.** Аркадий говорит по ступеням, одну за раз, и только тому,
//     кому доверяет; рассказ идёт от разговора героя — через исполнение
//     дела, а не руками. Пётр про снегоступы — с пятого дня, и тогда
//     героя к ним тянет.
//  5. **Бункер.** Пока следы видны (до четвёртого дня), найти можно; замело —
//     нельзя, сколько ни ходи.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Заражение_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        (House h, NPC я, Округа о) Жизнь(long зерно = 7, string кто = "лида")
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л)
                .Слушать(прогон, кто);
            return (прогон.h, прогон.h.people[кто], Округа.У(прогон.h)!);
        }

        // ---- 1. стадии ----
        string стадии_итог;
        {
            int задетых = 0, заболели = 0, умерли = 0;
            var сроки = new List<int>();
            for (long зерно = 1; зерно <= 60; зерно++)
            {
                var (h, я, о) = Жизнь(зерно);
                var з = о.заражение;
                h.day = 2;
                я.health = 100;
                з.Задеть(я.id, 2);
                задетых++;
                int? заражён = null, умер = null;
                double здоровье_больным = -1;
                for (int день = 2; день <= 12 && я.alive; день++)
                {
                    h.day = день;
                    var было = з.Стадия(я.id);
                    double до = я.health;
                    з.Конец_дня(h);
                    var стало = з.Стадия(я.id);
                    if (стало == Стадия.ЗАРАЖЁН && заражён is null)
                        заражён = день + 1;
                    if (было == Стадия.БОЛЕН && я.alive && здоровье_больным < 0)
                        здоровье_больным = до - я.health;
                    if (!я.alive)
                        умер = день + 1;
                    if (стало == Стадия.ЗДОРОВ && было == Стадия.ЗАДЕТ)
                        break;
                }
                if (заражён is null)
                {
                    if (!я.alive)
                        плохо.Add($"зерно {зерно}: не заразившись, умер от болезни");
                    continue;
                }
                заболели++;
                if (умер is not int смерть)
                {
                    плохо.Add($"зерно {зерно}: заражён на {заражён}-й день — и жив на двенадцатый");
                    continue;
                }
                умерли++;
                сроки.Add(смерть - заражён.Value);
                if (смерть - заражён.Value is < 3 or > 5)
                    плохо.Add($"зерно {зерно}: от заражения до смерти {смерть - заражён.Value} дн., а по заданию три-пять");
                if (здоровье_больным <= 0)
                    плохо.Add($"зерно {зерно}: больной не потерял здоровья за день");
                if (я.cause != "болезнь с «Вектора»")
                    плохо.Add($"зерно {зерно}: умер от «{я.cause}», а не от болезни");
            }
            double доля = заболели / (double)задетых;
            if (Math.Abs(доля - л.заражение.задетый_заболеет) > 0.12)
                плохо.Add($"из задетых заболели {заболели} из {задетых} — а шанс {л.заражение.задетый_заболеет}");
            if (заболели != умерли)
                плохо.Add($"заболели {заболели}, умерли {умерли} — болезнь смертельна всегда");
            стадии_итог = $"задеты {задетых}, заболели {заболели}, умерли все {умерли}; от заражения до смерти "
                          + (сроки.Count > 0 ? $"{сроки.Min()}–{сроки.Max()} дн." : "—");
        }

        // ---- 2. передача ----
        string передача_итог;
        {
            int от_больного = 0, от_заражённого = 0, от_соседа = 0;
            const int РАЗ = 200;
            for (long зерно = 1; зерно <= РАЗ; зерно++)
            {
                var (h, я, о) = Жизнь(зерно);
                var сосед = h.people.Значения.First(п => п.id != я.id && !h.под_одной_крышей(п, я));
                var з = о.заражение;
                h.day = 3;
                // герой болен: подгоняем стадию через задевание и дни
                з.Задеть(я.id, 1);
                for (int д = 1; д <= 3 && з.Стадия(я.id) != Стадия.БОЛЕН; д++)
                {
                    h.day = д;
                    з.Конец_дня(h);
                }
                if (з.Стадия(я.id) == Стадия.БОЛЕН)
                {
                    h.day = 10;
                    з.Встретились(я.id, сосед.id);
                    з.Конец_дня(h);
                    if (з.Стадия(сосед.id) != Стадия.ЗДОРОВ)
                        от_больного++;
                }
                // и в обратную сторону: болен сосед — задет герой
                var (h3, я3, о3) = Жизнь(зерно);
                var с3 = h3.people[сосед.id];
                о3.заражение.Задеть(с3.id, 1);
                for (int д = 1; д <= 3 && о3.заражение.Стадия(с3.id) != Стадия.БОЛЕН; д++)
                {
                    h3.day = д;
                    о3.заражение.Конец_дня(h3);
                }
                if (о3.заражение.Стадия(с3.id) == Стадия.БОЛЕН)
                {
                    h3.day = 10;
                    о3.заражение.Встретились(с3.id, я3.id);
                    о3.заражение.Конец_дня(h3);
                    if (о3.заражение.Стадия(я3.id) != Стадия.ЗДОРОВ)
                        от_соседа++;
                }
                // заражённый, но не больной
                var (h2, я2, о2) = Жизнь(зерно);
                var с2 = h2.people[сосед.id];
                о2.заражение.Задеть(я2.id, 1);
                h2.day = 1;
                о2.заражение.Конец_дня(h2);
                if (о2.заражение.Стадия(я2.id) == Стадия.ЗАРАЖЁН)
                {
                    h2.day = 2;
                    о2.заражение.Встретились(я2.id, с2.id);
                    о2.заражение.Конец_дня(h2);
                    if (о2.заражение.Стадия(с2.id) != Стадия.ЗДОРОВ)
                        от_заражённого++;
                }
            }
            if (от_больного == 0)
                плохо.Add("больной встречался с соседом двести раз — и ни разу не задел");
            if (от_соседа == 0)
                плохо.Add("больной сосед встречался с героем двести раз — и ни разу не задел: передача в одну сторону");
            if (от_заражённого != 0)
                плохо.Add($"заражённый, но ещё не больной, задел соседа {от_заражённого} раз — он не заразен");
            передача_итог = $"больной герой задел соседа {от_больного} раз, больной сосед героя — {от_соседа}, "
                            + $"заражённый — {от_заражённого}";
        }

        // ---- 3. промзона ----
        string промзона_итог;
        {
            int задело_не_зная = 0, задело_зная = 0;
            double унёс_не_зная = 0, унёс_зная = 0;
            const int РАЗ = 100;
            for (long зерно = 1; зерно <= РАЗ; зерно++)
            {
                var (h, я, о) = Жизнь(зерно);
                h.day = 2;
                я.time_left = 16;
                var а = о.заражение.В_промзону(h, я, знаю_корпуса: false, ручки);
                if (а.задело) задело_не_зная++;
                унёс_не_зная += а.унёс.Ключи.Sum(к => а.унёс[к]);
                if (Math.Abs(я.time_left - (16 - л.заражение.промзона_часов)) > 1e-9)
                    плохо.Add($"в промзоне ушло {16 - я.time_left} ч, а должно {л.заражение.промзона_часов}");
                var (h2, я2, о2) = Жизнь(зерно);
                h2.day = 2;
                var б = о2.заражение.В_промзону(h2, я2, знаю_корпуса: true, ручки);
                if (б.задело) задело_зная++;
                унёс_зная += б.унёс.Ключи.Sum(к => б.унёс[к]);
                if (а.унёс.Ключи.Count > 0 && (я.ноша?.пусто ?? true))
                    плохо.Add("из промзоны унёс — а тара пуста");
            }
            if (задело_не_зная <= задело_зная * 2)
                плохо.Add($"не зная корпусов, задело {задело_не_зная} раз, зная — {задело_зная}: знание не бережёт");
            if (унёс_зная >= унёс_не_зная)
                плохо.Add("обходя опасные корпуса, уносят не меньше — знанию нечего стоить");
            промзона_итог = $"задело: не зная корпусов {задело_не_зная} из {РАЗ}, зная {задело_зная}; "
                            + $"унёс {Текст.G(унёс_не_зная)} и {Текст.G(унёс_зная)}";
        }

        // ---- 4. знатоки ----
        string знатоки_итог;
        {
            var (h, я, о) = Жизнь(3);
            var аркадий = h.people["аркадий"];
            h.day = 2;
            аркадий.trust[я.id] = 3.0;
            Действия.execute(h, я, "разговор", аркадий);
            int после_первого = о.Рассказано("аркадий");
            аркадий.trust[я.id] = 3.5;
            Действия.execute(h, я, "разговор", аркадий);
            bool про_вектор = о.Знает("вектор_есть");
            var рассказ = о.Рассказ();
            аркадий.trust[я.id] = 3.8;
            Действия.execute(h, я, "разговор", аркадий);
            int при_3_8 = о.Рассказано("аркадий");
            аркадий.trust[я.id] = 6.0;
            Действия.execute(h, я, "разговор", аркадий);
            int при_6 = о.Рассказано("аркадий");
            if (после_первого != 0)
                плохо.Add("Аркадий рассказал про «Вектор» незнакомому — при доверии три");
            if (!про_вектор || рассказ is not { кто: "аркадий" })
                плохо.Add("при доверии 3.5 Аркадий так и не сказал про промзону");
            if (при_3_8 != 1)
                плохо.Add($"при доверии 3.8 Аркадий сказал {при_3_8} ступени — вторая только с 4.2");
            if (при_6 != 2)
                плохо.Add($"при доверии 6 за один разговор Аркадий сказал до {при_6} ступеней — по одной за раз");
            // отнять — не повод рассказывать, даже тому, кому доверяешь.
            // Исполнением это не проверить: отъём сам роняет доверие ниже
            // любой ступени, и проверка прошла бы вхолостую. Поэтому
            // наблюдателям отдаётся само дело, а доверие остаётся прежним
            var (h2, я2, о2) = Жизнь(4);
            h2.day = 2;
            var аркадий2 = h2.people["аркадий"];
            аркадий2.trust[я2.id] = 10.0;
            foreach (string враждебное in new[] { "отнять", "кража_днём", "выгнать" })
                foreach (var f in h2.hooks.after_execute)
                    f(h2, я2, враждебное, аркадий2, null, Исход.СДЕЛАНО);
            int напрямую = о2.Рассказано("аркадий");
            if (напрямую != 0)
                плохо.Add("герой пришёл к Аркадию отнимать, красть, выгонять — а тот рассказал про «Вектор»");
            // и то же доверие при разговоре — рассказ есть: иначе ноль выше ничего не значит
            foreach (var f in h2.hooks.after_execute)
                f(h2, я2, "разговор", аркадий2, null, Исход.СДЕЛАНО);
            if (о2.Рассказано("аркадий") != 1)
                плохо.Add("при доверии 10 разговор с Аркадием не дал рассказа — проверка отъёма вхолостую");
            // Пётр и снегоступы
            var пётр = h.people["пётр"];
            h.day = 4;
            Действия.execute(h, я, "разговор", пётр);
            bool рано = о.Рассказано("пётр") > 0;
            h.day = 5;
            Действия.execute(h, я, "разговор", пётр);
            if (рано || о.Рассказано("пётр") != 1)
                плохо.Add($"Пётр про снегоступы: на четвёртый день {(рано ? "рассказал" : "молчит")}, на пятый — "
                          + $"{(о.Рассказано("пётр") == 1 ? "рассказал" : "молчит")}");
            я.снаряжение!.Положить_насовсем(Округа.СНЕГОСТУПЫ);
            if (о.Тянет(h, я, пётр) <= 0)
                плохо.Add("Пётр сказал про снегоступы — а героя к ним не тянет");
            знатоки_итог = $"Аркадий: при 3.0 — ничего, 3.5 — промзона, 3.8 — {при_3_8}, 6.0 — {при_6} ступени "
                           + $"(по одной); Пётр — с пятого дня; на отъём — {напрямую}";
        }

        // ---- 5. бункер ----
        string бункер_итог;
        {
            int нашли = 0, в_замёт = 0;
            const int РАЗ = 100;
            for (long зерно = 1; зерно <= РАЗ; зерно++)
            {
                var (h, я, о) = Жизнь(зерно);
                h.day = 3;
                var (нашёл, замело) = о.Искать_бункер(h, я);
                if (замело)
                    плохо.Add("на третий день бункер уже замело — а видно его до четвёртого");
                if (нашёл)
                {
                    нашли++;
                    if (!о.Знает("бункер_вход"))
                        плохо.Add("нашёл вход в бункер — и не знает, где он");
                }
                var (h2, я2, о2) = Жизнь(зерно);
                h2.day = 4;
                var (нашёл4, замело4) = о2.Искать_бункер(h2, я2);
                if (нашёл4 || !замело4)
                    в_замёт++;
            }
            if (нашли == 0 || Math.Abs(нашли / (double)РАЗ - л.бункер.найти) > 0.15)
                плохо.Add($"на третий день нашли бункер {нашли} раз из {РАЗ} — а шанс {л.бункер.найти}");
            if (в_замёт > 0)
                плохо.Add($"на четвёртый день бункер находили {в_замёт} раз — а его замело");
            бункер_итог = $"третий день — нашли {нашли} из {РАЗ}; четвёртый — замело, ни разу";
        }

        w($"  стадии: {стадии_итог}");
        w($"  передача: {передача_итог}");
        w($"  промзона: {промзона_итог}");
        w($"  знатоки: {знатоки_итог}");
        w($"  бункер: {бункер_итог}");
        return плохо;
    }
}
