// Проверка заражения, знатоков и бункера (задание автора, пп. 6–8, 10;
// `Дом.Ядро/Петля/Заражение.cs`, `Округа.cs`, `data/мир.json`).
//
//  1. **Стадии как в задании.** Задетый наутро заболевает (или обошлось);
//     от заражения до смерти — три-пять дней, всегда; больной и тяжёлый
//     теряют здоровье; смерть — общей смертью дома.
//  2. **Передаётся.** Больной заразен: кто встречался с ним лицом к лицу,
//     задет с шансом; заражённый, но ещё не больной, — не заразен.
//  2б. **Встречи и постель.** Встреча — ровно те дела, чьи исполнители
//     сводят двоих (`Социальное.встретились`): присматриваться к квартире
//     или обокрасть пустую — не встреча. Больной после своего дела на ногах
//     не дольше своей доли дня. И живой игрой: героиня, принёсшая болезнь,
//     не выкашивает дом — первая версия уносила шесть–одиннадцать соседей.
//  3. **Промзона.** Кто не знает, какие корпуса обходить, задевается часто;
//     кто знает — редко, но и уносит меньше. Находка — в тару.
//  4. **Знатоки.** Аркадий говорит по ступеням, одну за раз, и только тому,
//     кому доверяет (пороги — из `мир.json`, проверка сверяет правило);
//     рассказ идёт от разговора героя — через исполнение дела, а не руками.
//     Пётр про снегоступы — с пятого дня, и тогда героя к ним тянет.
//     И **досягаемость**: честный герой, который по-доброму ходит
//     к знатокам, узнаёт район бункера раньше, чем его заметёт, и про
//     промзону — к третьему дню. Первые пороги стояли «на глаз» и почти
//     не открывались — это сверка того, что ступени лежат на той шкале,
//     на которой в доме растёт доверие.
//  5. **Бункер.** Пока следы видны (до четвёртого дня), найти можно; замело —
//     нельзя, сколько ни ходи.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Заражение_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        (House h, NPC я, Округа о) Жизнь(long зерно = 7, string кто = "лида")
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л)
                .Слушать(прогон, кто);
            return (прогон.h, прогон.h.people[кто], Округа.У(прогон.h)!);
        }

        // ---- 1. стадии ----
        string стадии_итог;
        {
            int задетых = 0, заболели = 0, умерли = 0;
            var сроки = new List<int>();
            for (long зерно = 1; зерно <= 60; зерно++)
            {
                var (h, я, о) = Жизнь(зерно);
                var з = о.заражение;
                h.day = 2;
                я.health = 100;
                з.Задеть(я.id, 2);
                задетых++;
                int? заражён = null, умер = null;
                double здоровье_больным = -1;
                for (int день = 2; день <= 12 && я.alive; день++)
                {
                    h.day = день;
                    var было = з.Стадия(я.id);
                    double до = я.health;
                    з.Конец_дня(h);
                    var стало = з.Стадия(я.id);
                    if (стало == Стадия.ЗАРАЖЁН && заражён is null)
                        заражён = день + 1;
                    if (было == Стадия.БОЛЕН && я.alive && здоровье_больным < 0)
                        здоровье_больным = до - я.health;
                    if (!я.alive)
                        умер = день + 1;
                    if (стало == Стадия.ЗДОРОВ && было == Стадия.ЗАДЕТ)
                        break;
                }
                if (заражён is null)
                {
                    if (!я.alive)
                        плохо.Add($"зерно {зерно}: не заразившись, умер от болезни");
                    continue;
                }
                заболели++;
                if (умер is not int смерть)
                {
                    плохо.Add($"зерно {зерно}: заражён на {заражён}-й день — и жив на двенадцатый");
                    continue;
                }
                умерли++;
                сроки.Add(смерть - заражён.Value);
                if (смерть - заражён.Value is < 3 or > 5)
                    плохо.Add($"зерно {зерно}: от заражения до смерти {смерть - заражён.Value} дн., а по заданию три-пять");
                if (здоровье_больным <= 0)
                    плохо.Add($"зерно {зерно}: больной не потерял здоровья за день");
                if (я.cause != "болезнь с «Вектора»")
                    плохо.Add($"зерно {зерно}: умер от «{я.cause}», а не от болезни");
            }
            double доля = заболели / (double)задетых;
            if (Math.Abs(доля - л.заражение.задетый_заболеет) > 0.12)
                плохо.Add($"из задетых заболели {заболели} из {задетых} — а шанс {л.заражение.задетый_заболеет}");
            if (заболели != умерли)
                плохо.Add($"заболели {заболели}, умерли {умерли} — болезнь смертельна всегда");
            стадии_итог = $"задеты {задетых}, заболели {заболели}, умерли все {умерли}; от заражения до смерти "
                          + (сроки.Count > 0 ? $"{сроки.Min()}–{сроки.Max()} дн." : "—");
        }

        // ---- 2. передача ----
        string передача_итог;
        {
            int от_больного = 0, от_заражённого = 0, от_соседа = 0;
            const int РАЗ = 200;
            for (long зерно = 1; зерно <= РАЗ; зерно++)
            {
                var (h, я, о) = Жизнь(зерно);
                var сосед = h.people.Значения.First(п => п.id != я.id && !h.под_одной_крышей(п, я));
                var з = о.заражение;
                h.day = 3;
                // герой болен: подгоняем стадию через задевание и дни
                з.Задеть(я.id, 1);
                for (int д = 1; д <= 3 && з.Стадия(я.id) != Стадия.БОЛЕН; д++)
                {
                    h.day = д;
                    з.Конец_дня(h);
                }
                if (з.Стадия(я.id) == Стадия.БОЛЕН)
                {
                    h.day = 10;
                    з.Встретились(я.id, сосед.id);
                    з.Конец_дня(h);
                    if (з.Стадия(сосед.id) != Стадия.ЗДОРОВ)
                        от_больного++;
                }
                // и в обратную сторону: болен сосед — задет герой
                var (h3, я3, о3) = Жизнь(зерно);
                var с3 = h3.people[сосед.id];
                о3.заражение.Задеть(с3.id, 1);
                for (int д = 1; д <= 3 && о3.заражение.Стадия(с3.id) != Стадия.БОЛЕН; д++)
                {
                    h3.day = д;
                    о3.заражение.Конец_дня(h3);
                }
                if (о3.заражение.Стадия(с3.id) == Стадия.БОЛЕН)
                {
                    h3.day = 10;
                    о3.заражение.Встретились(с3.id, я3.id);
                    о3.заражение.Конец_дня(h3);
                    if (о3.заражение.Стадия(я3.id) != Стадия.ЗДОРОВ)
                        от_соседа++;
                }
                // заражённый, но не больной
                var (h2, я2, о2) = Жизнь(зерно);
                var с2 = h2.people[сосед.id];
                о2.заражение.Задеть(я2.id, 1);
                h2.day = 1;
                о2.заражение.Конец_дня(h2);
                if (о2.заражение.Стадия(я2.id) == Стадия.ЗАРАЖЁН)
                {
                    h2.day = 2;
                    о2.заражение.Встретились(я2.id, с2.id);
                    о2.заражение.Конец_дня(h2);
                    if (о2.заражение.Стадия(с2.id) != Стадия.ЗДОРОВ)
                        от_заражённого++;
                }
            }
            if (от_больного == 0)
                плохо.Add("больной встречался с соседом двести раз — и ни разу не задел");
            if (от_соседа == 0)
                плохо.Add("больной сосед встречался с героем двести раз — и ни разу не задел: передача в одну сторону");
            if (от_заражённого != 0)
                плохо.Add($"заражённый, но ещё не больной, задел соседа {от_заражённого} раз — он не заразен");
            передача_итог = $"больной герой задел соседа {от_больного} раз, больной сосед героя — {от_соседа}, "
                            + $"заражённый — {от_заражённого}";
        }

        // ---- 2б. встречи, постель, эпидемия ----
        string встречи_итог, эпидемия_итог;
        {
            // встреча — ровно те исполнители, что сами сводят двоих
            // (`Социальное.встретились`): сверка с исходниками в обе стороны
            var сводят = new SortedSet<string>(StringComparer.Ordinal);
            foreach (var файл in Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Ядро"), "Действия.Исполнители*.cs"))
                foreach (var кусок in File.ReadAllText(файл).Split("исполняет(\"").Skip(1))
                    if (кусок.Contains("Социальное.встретились(", StringComparison.Ordinal))
                        сводят.Add(кусок[..кусок.IndexOf('"')]);
            foreach (var к in сводят.Where(к => !Дом.Ядро.Заражение.ЛИЦОМ_К_ЛИЦУ.Contains(к)))
                плохо.Add($"исполнитель «{к}» сводит двоих лицом к лицу — а болезнь при нём не передаётся");
            foreach (var к in Дом.Ядро.Заражение.ЛИЦОМ_К_ЛИЦУ.Where(к => !сводят.Contains(к)))
                плохо.Add($"«{к}» в списке встреч заражения — а его исполнитель никого не сводит");

            // больной сосед; к нему приходят разными делами — наблюдателям
            // отдаётся само дело, и считается, от чего героя задело
            var по_делу = new Dictionary<string, int>(StringComparer.Ordinal);
            const int РАЗ = 120;
            foreach (string ключ in new[] { "разговор", "наблюдение", "кража_днём" })
            {
                int задело = 0;
                for (long зерно = 1; зерно <= РАЗ; зерно++)
                {
                    var (h, я, о) = Жизнь(зерно);
                    var сосед = h.people.Значения.First(п => п.id != я.id && !h.под_одной_крышей(п, я));
                    о.заражение.Задеть(сосед.id, 1);
                    for (int д = 1; д <= 3 && о.заражение.Стадия(сосед.id) != Стадия.БОЛЕН; д++)
                    {
                        h.day = д;
                        о.заражение.Конец_дня(h);
                    }
                    if (о.заражение.Стадия(сосед.id) != Стадия.БОЛЕН)
                        continue;
                    h.day = 10;
                    // обокрасть можно только пустую квартиру — хозяин в отлучке
                    сосед.away = ключ == "кража_днём";
                    foreach (var f in h.hooks.after_execute)
                        f(h, я, ключ, сосед, null, Исход.СДЕЛАНО);
                    сосед.away = false;
                    о.заражение.Конец_дня(h);
                    if (о.заражение.Стадия(я.id) != Стадия.ЗДОРОВ)
                        задело++;
                }
                по_делу[ключ] = задело;
            }
            if (по_делу["разговор"] == 0)
                плохо.Add($"поговорил с больным {РАЗ} раз — и ни разу не задело: наблюдатель встреч не пишет");
            if (по_делу["наблюдение"] != 0)
                плохо.Add($"присматривался к квартире больного — и задело {по_делу["наблюдение"]} раз: это не встреча");
            if (по_делу["кража_днём"] != 0)
                плохо.Add($"обокрал пустую квартиру больного — и задело {по_делу["кража_днём"]} раз: хозяина не было дома");

            // постель: после своего дела больной на ногах не дольше своей доли
            var доли = new List<string>();
            foreach (var (стадия, доля) in л.заражение.на_ногах.OrderBy(п => п.Key))
            {
                // задетый может и не заболеть: зёрна перебираются, пока не дойдёт
                House h = null!;
                NPC я = null!, сосед = null!;
                bool дошёл = false;
                for (long зерно = 1; зерно <= 20 && !дошёл; зерно++)
                {
                    Округа о;
                    (h, я, о) = Жизнь(зерно);
                    сосед = h.people.Значения.First(п => п.id != я.id);
                    о.заражение.Задеть(сосед.id, 1);
                    for (int д = 1; д <= 8 && о.заражение.Стадия(сосед.id) != стадия && сосед.alive; д++)
                    {
                        h.day = д;
                        о.заражение.Конец_дня(h);
                    }
                    дошёл = о.заражение.Стадия(сосед.id) == стадия;
                }
                if (!дошёл)
                {
                    плохо.Add($"за двадцать зёрен никто не дошёл до стадии {стадия} — постель не проверить");
                    continue;
                }
                double день = h.B["часов_бодрствования"];
                сосед.time_left = день - 1.0;            // час уже прожит
                foreach (var f in h.hooks.after_execute)
                    f(h, сосед, "разговор", я, null, Исход.СДЕЛАНО);
                double осталось = сосед.time_left;
                if (осталось > день * доля - 1.0 + 1e-9)
                    плохо.Add($"{стадия}: после дела на ногах ещё {Текст.G(осталось)} ч из {Текст.G(день)} — "
                              + $"а доля {Текст.G(доля)}: больной не слёг");
                доли.Add($"{стадия.ToString().ToLowerInvariant()} — осталось {Текст.G(Текст.Округлить(осталось, 1))} ч");
            }
            встречи_итог = $"список встреч = исполнителям ({сводят.Count}); от больного задело: разговором "
                           + $"{по_делу["разговор"]} из {РАЗ}, присматриваясь {по_делу["наблюдение"]}, "
                           + $"обокрав пустую {по_делу["кража_днём"]}; постель: {string.Join(", ", доли)}";

            // эпидемия живой игрой: героиня задета на второй день и живёт
            // обычно — дом не вымирает (замер и ориентир — в `мир.json`)
            var умерли = new List<int>();
            for (long зерно = 1; зерно <= 3; зерно++)
                умерли.Add(Эпидемия_(зерно, 14, ручки, каталог, л));
            if (умерли.Sum() > 12)
                плохо.Add($"героиня принесла болезнь — и за две недели от неё умерло {string.Join("/", умерли)} соседей "
                          + "на трёх зёрнах: одна вылазка выкашивает дом");
            эпидемия_итог = $"героиня задета на второй день — соседей умерло от болезни {string.Join("/", умерли)} "
                            + "за две недели (не больше четырёх в среднем)";
        }

        // ---- 3. промзона ----
        string промзона_итог;
        {
            int задело_не_зная = 0, задело_зная = 0;
            double унёс_не_зная = 0, унёс_зная = 0;
            const int РАЗ = 100;
            for (long зерно = 1; зерно <= РАЗ; зерно++)
            {
                var (h, я, о) = Жизнь(зерно);
                h.day = 2;
                я.time_left = 16;
                var а = о.заражение.В_промзону(h, я, знаю_корпуса: false, ручки);
                if (а.задело) задело_не_зная++;
                унёс_не_зная += а.унёс.Ключи.Sum(к => а.унёс[к]);
                if (Math.Abs(я.time_left - (16 - л.заражение.промзона_часов)) > 1e-9)
                    плохо.Add($"в промзоне ушло {16 - я.time_left} ч, а должно {л.заражение.промзона_часов}");
                var (h2, я2, о2) = Жизнь(зерно);
                h2.day = 2;
                var б = о2.заражение.В_промзону(h2, я2, знаю_корпуса: true, ручки);
                if (б.задело) задело_зная++;
                унёс_зная += б.унёс.Ключи.Sum(к => б.унёс[к]);
                if (а.унёс.Ключи.Count > 0 && (я.ноша?.пусто ?? true))
                    плохо.Add("из промзоны унёс — а тара пуста");
            }
            if (задело_не_зная <= задело_зная * 2)
                плохо.Add($"не зная корпусов, задело {задело_не_зная} раз, зная — {задело_зная}: знание не бережёт");
            if (унёс_зная >= унёс_не_зная)
                плохо.Add("обходя опасные корпуса, уносят не меньше — знанию нечего стоить");
            промзона_итог = $"задело: не зная корпусов {задело_не_зная} из {РАЗ}, зная {задело_зная}; "
                            + $"унёс {Текст.G(унёс_не_зная)} и {Текст.G(унёс_зная)}";
        }

        // ---- 4. знатоки ----
        string знатоки_итог;
        {
            // пороги — из данных: проверка сверяет правило, а не числа
            var ступени = л.знатоки.First(з => з.кто == "аркадий").ступени;
            double первая = ступени[0].доверие, вторая = ступени[1].доверие;
            var (h, я, о) = Жизнь(3);
            var аркадий = h.people["аркадий"];
            h.day = 2;
            // само дело доверия не меняет: наблюдателям отдаётся разговор
            // при заданном доверии. Что рассказ приходит от исполнения —
            // ниже, отдельной жизнью
            void Пришла(House дом, NPC кто, string ключ, NPC к_кому, double доверие)
            {
                к_кому.trust[кто.id] = доверие;
                foreach (var f in дом.hooks.after_execute)
                    f(дом, кто, ключ, к_кому, null, Исход.СДЕЛАНО);
            }
            Пришла(h, я, "разговор", аркадий, первая - 0.01);
            int ниже_первой = о.Рассказано("аркадий");
            Пришла(h, я, "разговор", аркадий, первая);
            bool про_вектор = о.Знает("вектор_есть");
            var рассказ = о.Рассказ();
            Пришла(h, я, "разговор", аркадий, (первая + вторая) / 2);
            int между = о.Рассказано("аркадий");
            Пришла(h, я, "разговор", аркадий, ступени.Max(с => с.доверие) + 1.0);
            int с_запасом = о.Рассказано("аркадий");
            if (ниже_первой != 0)
                плохо.Add($"Аркадий рассказал про «Вектор» при доверии {Текст.G(первая - 0.01)} — ниже первой ступени");
            if (!про_вектор || рассказ is not { кто: "аркадий" })
                плохо.Add($"при доверии {Текст.G(первая)} Аркадий так и не сказал про промзону");
            if (между != 1)
                плохо.Add($"между первой и второй ступенью Аркадий сказал {между} ступени");
            if (с_запасом != 2)
                плохо.Add($"при доверии выше всех ступеней за один приход Аркадий сказал до {с_запасом} ступеней — по одной за раз");
            // от исполнения: настоящий разговор героя, доверие с запасом
            var (h3, я3, о3) = Жизнь(5);
            h3.day = 2;
            h3.people["аркадий"].trust[я3.id] = первая + 0.5;
            Действия.execute(h3, я3, "разговор", h3.people["аркадий"]);
            if (о3.Рассказано("аркадий") != 1)
                плохо.Add("герой поговорил с Аркадием по-настоящему — а рассказа нет: наблюдатель не на исполнении");
            // отнять — не повод рассказывать, даже тому, кому доверяешь.
            // Исполнением это не проверить: отъём сам роняет доверие ниже
            // любой ступени, и проверка прошла бы вхолостую. Поэтому
            // наблюдателям отдаётся само дело, а доверие остаётся прежним
            var (h2, я2, о2) = Жизнь(4);
            h2.day = 2;
            var аркадий2 = h2.people["аркадий"];
            foreach (string враждебное in new[] { "отнять", "кража_днём", "выгнать" })
                Пришла(h2, я2, враждебное, аркадий2, 10.0);
            int напрямую = о2.Рассказано("аркадий");
            if (напрямую != 0)
                плохо.Add("герой пришёл к Аркадию отнимать, красть, выгонять — а тот рассказал про «Вектор»");
            // и то же доверие при разговоре — рассказ есть: иначе ноль выше ничего не значит
            Пришла(h2, я2, "разговор", аркадий2, 10.0);
            if (о2.Рассказано("аркадий") != 1)
                плохо.Add("при доверии 10 разговор с Аркадием не дал рассказа — проверка отъёма вхолостую");
            // Пётр и снегоступы
            var пётр = h.people["пётр"];
            h.day = 4;
            Действия.execute(h, я, "разговор", пётр);
            bool рано = о.Рассказано("пётр") > 0;
            h.day = 5;
            Действия.execute(h, я, "разговор", пётр);
            if (рано || о.Рассказано("пётр") != 1)
                плохо.Add($"Пётр про снегоступы: на четвёртый день {(рано ? "рассказал" : "молчит")}, на пятый — "
                          + $"{(о.Рассказано("пётр") == 1 ? "рассказал" : "молчит")}");
            я.снаряжение!.Положить_насовсем(Округа.СНЕГОСТУПЫ);
            if (о.Тянет(h, я, пётр) <= 0)
                плохо.Add("Пётр сказал про снегоступы — а героя к ним не тянет");

            // досягаемость: живая игра, честный и мирный герой
            var дни_района = new List<string>();
            var дни_вектора = new List<string>();
            for (long зерно = 1; зерно <= 3; зерно++)
            {
                int замело = Enumerable.Range(1, 12)
                    .FirstOrDefault(д => л.На(д, зерно).Следы("район_бункера") == Следы.ЗАМЕЛО, 13);
                var (район, вектор) = Дружелюбный_(зерно, 3, ручки, каталог, л);
                дни_района.Add(район?.ToString() ?? "—");
                дни_вектора.Add(вектор?.ToString() ?? "—");
                if (район is null || район >= замело)
                    плохо.Add($"зерно {зерно}: честный герой каждый день по-доброму ходит к Сергею — "
                              + $"а район бункера узнал {(район is null ? "не за три дня" : $"на {район}-й день")}, "
                              + $"замело на {замело}-й: ступени не на той шкале, на которой растёт доверие");
                if (вектор is null)
                    плохо.Add($"зерно {зерно}: три дня по-доброму к Аркадию — а про промзону ни слова");
            }
            знатоки_итог = $"Аркадий: ниже {Текст.G(первая)} — ничего, на пороге — промзона, между — {между}, "
                           + $"с запасом — {с_запасом} (по одной); Пётр — с пятого дня; на отъём — {напрямую}; "
                           + $"живой игрой район бункера на {string.Join("/", дни_района)}-й день, "
                           + $"промзона на {string.Join("/", дни_вектора)}-й";
        }

        // ---- 5. бункер ----
        string бункер_итог;
        {
            int нашли = 0, в_замёт = 0;
            const int РАЗ = 100;
            for (long зерно = 1; зерно <= РАЗ; зерно++)
            {
                var (h, я, о) = Жизнь(зерно);
                h.day = 3;
                var (нашёл, замело) = о.Искать_бункер(h, я);
                if (замело)
                    плохо.Add("на третий день бункер уже замело — а видно его до четвёртого");
                if (нашёл)
                {
                    нашли++;
                    if (!о.Знает("бункер_вход"))
                        плохо.Add("нашёл вход в бункер — и не знает, где он");
                }
                var (h2, я2, о2) = Жизнь(зерно);
                h2.day = 4;
                var (нашёл4, замело4) = о2.Искать_бункер(h2, я2);
                if (нашёл4 || !замело4)
                    в_замёт++;
            }
            if (нашли == 0 || Math.Abs(нашли / (double)РАЗ - л.бункер.найти) > 0.15)
                плохо.Add($"на третий день нашли бункер {нашли} раз из {РАЗ} — а шанс {л.бункер.найти}");
            if (в_замёт > 0)
                плохо.Add($"на четвёртый день бункер находили {в_замёт} раз — а его замело");
            бункер_итог = $"третий день — нашли {нашли} из {РАЗ}; четвёртый — замело, ни разу";
        }

        w($"  стадии: {стадии_итог}");
        w($"  передача: {передача_итог}");
        w($"  встречи: {встречи_итог}");
        w($"  эпидемия: {эпидемия_итог}");
        w($"  промзона: {промзона_итог}");
        w($"  знатоки: {знатоки_итог}");
        w($"  бункер: {бункер_итог}");
        return плохо;
    }

    /// <summary>
    /// Честный и мирный герой (Оксана) живёт <paramref name="дней"/> дней
    /// и по-доброму ходит к знатокам — разговор, мена, поделиться, по два
    /// раза в день к каждому; прочее время стоит (ход «сам»), на «соврать»
    /// говорит правду. Возвращает, в какой день он узнал район бункера
    /// и про промзону (null — не узнал).
    /// </summary>
    private static (int? район, int? вектор) Дружелюбный_(long зерно, int дней, РучкиПетли ручки,
                                                         Дом.Ядро.Инструменты каталог, Летопись л)
    {
        const string ГЕРОЙ = "оксана";
        var прогон = new Прогон(Пути.Данные, seed: зерно, days: дней);
        new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, ГЕРОЙ);
        var о = Округа.У(прогон.h)!;
        using var партия = new Партия(прогон, ГЕРОЙ);
        string[] знатоки = { "аркадий", "сергей", "пётр" };
        string[] по_доброму = { "поделиться", "разговор", "обмен" };
        int? район = null, вектор = null;
        int день = 0;
        var визиты = new Dictionary<string, int>(StringComparer.Ordinal);
        партия.Начать();
        var в = партия.Дождаться();
        while (в is not null)
        {
            if (в.день != день)
            {
                день = в.день;
                визиты.Clear();
            }
            int ответ = 0;
            if (в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
            {
                ответ = ВопросИгроку.САМ;
                foreach (string ключ in по_доброму)
                {
                    for (int i = 0; i < в.варианты.Count && ответ == ВопросИгроку.САМ; i++)
                        if (в.варианты[i].что is ValueTuple<string, object?> (var к, NPC t)
                            && к == ключ && знатоки.Contains(t.id) && визиты.GetValueOrDefault(t.id) < 2)
                        {
                            визиты[t.id] = визиты.GetValueOrDefault(t.id) + 1;
                            ответ = i;
                        }
                    if (ответ != ВопросИгроку.САМ)
                        break;
                }
                if (ответ == ВопросИгроку.САМ)
                {
                    var я = прогон.h.people[ГЕРОЙ];
                    я.time_left -= Math.Min(0.5, я.time_left);
                }
            }
            else
                for (int i = 0; i < в.варианты.Count; i++)
                    if (в.варианты[i].что is "сказать правду")
                        ответ = i;
            партия.Ответить(ответ);
            if (район is null && о.Знает("бункер_район"))
                район = в.день;
            if (вектор is null && о.Знает("вектор_есть"))
                вектор = в.день;
            в = партия.Дождаться();
        }
        партия.Досидеть();
        return (район, вектор);
    }

    /// <summary>
    /// Эпидемия живой игрой: Оксана задета на второй день и живёт
    /// обычно — берётся за первое, что не вражда, на «соврать» говорит
    /// правду. Возвращает, сколько соседей умерло от болезни за
    /// <paramref name="дней"/> дней. Тот же замер, что в `мир.json`.
    /// </summary>
    private static int Эпидемия_(long зерно, int дней, РучкиПетли ручки,
                                 Дом.Ядро.Инструменты каталог, Летопись л)
    {
        const string ГЕРОЙ = "оксана";
        string[] вражда = { "отнять", "кража_днём", "выгнать", "подкараулить", "шепнуть", "налёт",
                            "обобрать", "убить_соседа", "разобрать", "вскрыть_кладовую", "донести" };
        var прогон = new Прогон(Пути.Данные, seed: зерно, days: дней);
        new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, ГЕРОЙ);
        var о = Округа.У(прогон.h)!;
        using var партия = new Партия(прогон, ГЕРОЙ);
        bool задета = false;
        партия.Начать();
        var в = партия.Дождаться();
        while (в is not null)
        {
            if (!задета && в.день >= 2)
                задета = о.заражение.Задеть(ГЕРОЙ, в.день) || true;
            int ответ = 0;
            if (в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
            {
                for (int i = в.варианты.Count - 1; i >= 0; i--)
                    if (!(в.варианты[i].что is ValueTuple<string, object?> (var к, _) && вражда.Contains(к)))
                        ответ = i;
            }
            else
                for (int i = 0; i < в.варианты.Count; i++)
                    if (в.варианты[i].что is "сказать правду")
                        ответ = i;
            партия.Ответить(ответ);
            в = партия.Дождаться();
        }
        партия.Досидеть();
        return прогон.h.people.Значения.Count(п => п.id != ГЕРОЙ && !п.alive
                                                 && (п.cause ?? "").Contains("Вектора", StringComparison.Ordinal));
    }
