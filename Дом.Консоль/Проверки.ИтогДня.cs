// Проверка итога дня (ГДД 4.4; `Дом.Экран/ИтогДня.cs`).
//
//  1. **Когда.** Первое утро — сводки нет: прошлого утра не было; то же утро
//     второй раз — нет; следующее — есть.
//  2. **Запасы и тепло.** Шкаф сдвинулся — сводка называет на сколько;
//     в квартире — градусы.
//  3. **Что заметили — без имён.** Один слышал возвращение — «кто-то видел»;
//     трое учуяли — «несколько соседей учуяли»; шаги не считаются; то, что
//     было до прошлого утра, — не сюда; ни одного имени соседа. Глаголы —
//     в роде героя (жилица: «вернулась»).
//  4. **Чат и состояние.** Новые сообщения чата за сутки; «голоднее»,
//     «устал» — словами.
//  5. **Живой дом.** Три утра подряд — две сводки, в каждой запасы и тепло,
//     без имён.
//  6. **Экран.** Узел зовёт сводку на первом вопросе дня и в распорядке
//     «день за днём»; окно — «ИТОГ ДНЯ» (скан).

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> ИтогДня_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var профиль = new ПрофильГероя("Андрей");
        var честный = new Скрипт(new Dictionary<Вопрос, string> { [Вопрос.СОВРАТЬ] = "сказать правду" });

        (Прогон, Сеанс) Дом_героя(int дней)
        {
            var п = new Прогон(Пути.Данные, seed: 3, days: дней,
                               журнал: new Журнал(0, false, TextWriter.Null),
                               жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(п, Герой.ID);
            var с = new Сеанс(п.h, Герой.ID);
            п.h.journal = new ЛентаЖурнал(с);
            п.h.people[Герой.ID].решающий = честный;
            return (п, с);
        }

        // имя в любом падеже и id — без оглядки на регистр: «аркадий» в начале
        // строки — та же утечка, что «Аркадий»
        bool Без_имён(House дом, NPC я, IEnumerable<string> строки, out string? чьё)
        {
            foreach (var с in строки)
                foreach (var сосед in дом.others(я))
                    foreach (var ф in new[] { "name", "short", "gen", "dat", "acc", "ins" }
                                 .Select(сосед.form).Append(сосед.id))
                    {
                        if (ф.Length > 0 && System.Text.RegularExpressions.Regex.IsMatch(
                                с, $@"(?<!\p{{L}}){System.Text.RegularExpressions.Regex.Escape(ф)}(?!\p{{L}})",
                                System.Text.RegularExpressions.RegexOptions.IgnoreCase))
                        {
                            чьё = $"«{ф}» в «{с}»";
                            return false;
                        }
                    }
            чьё = null;
            return true;
        }

        // ---- 1–4. одни сутки руками ----
        string сводка_итог;
        {
            var (прогон, сеанс) = Дом_героя(3);
            var h = прогон.h;
            var я = h.people[Герой.ID];
            var чужие = h.others(я).Where(p => p.здесь()).OrderBy(p => p.apt).ToList();
            h.day = 1;
            я.stock["еда"] = 5;
            я.stock["топливо"] = 3;
            я.satiety = 70;
            я.rest = 80;
            if (сеанс.Утро() is not null)
                плохо.Add("итог дня: первое утро — а сводка уже есть, хотя прошлого утра не было");
            if (сеанс.Утро() is not null)
                плохо.Add("итог дня: то же утро — сводка второй раз");

            я.stock["еда"] = 3;
            я.stock["топливо"] = 3.5;
            я.satiety = 50;
            я.rest = 60;
            чужие[0].memory.Add(new Память { день = 1, вид = Вид.СЛЫШАЛ, кто = я.id, что = "возвращение" });
            чужие[0].memory.Add(new Память { день = 1, вид = Вид.СЛЫШАЛ, кто = я.id, что = "шаги" });
            чужие[1].memory.Add(new Память { день = 0, вид = Вид.СЛЫШАЛ, кто = я.id, что = "возвращение" });
            foreach (var с in чужие.Skip(1).Take(3))
                с.memory.Add(new Память { день = 1, вид = Вид.УЧУЯЛ, кто = я.id });
            сеанс.Строка("  [чат] Лида: Кто-нибудь знает, когда включат отопление?", 1, false, null, ВидСтроки.ЧАТ);
            сеанс.Строка("  [чат] Валя: Не выбрасывайте картон.", 1, false, null, ВидСтроки.ЧАТ);
            h.day = 2;
            var итог = сеанс.Утро();
            if (итог is null)
            {
                плохо.Add("итог дня: новое утро — а сводки нет");
                сводка_итог = "—";
            }
            else
            {
                var с = итог.строки;
                string все = string.Join(" · ", с);
                if (итог.день != 1)
                    плохо.Add($"итог дня: сводка за день {итог.день}, а прожит первый");
                if (!с.Any(x => x.StartsWith("запасы:", StringComparison.Ordinal)
                                && x.Contains("еда -2", StringComparison.Ordinal)
                                && x.Contains("топливо +0.5", StringComparison.Ordinal)))
                    плохо.Add($"итог дня: запасы не названы как есть (еда −2, топливо +0.5): {все}");
                if (!с.Any(x => x.StartsWith("в квартире ", StringComparison.Ordinal) && x.Contains('°')))
                    плохо.Add($"итог дня: нет тепла в квартире: {все}");
                if (!с.Contains("кто-то видел, как ты вернулся с улицы с пакетами"))
                    плохо.Add($"итог дня: один видел возвращение — а сводка не «кто-то видел…» (или посчитала вчерашнее): {все}");
                if (!с.Contains("несколько соседей учуяли запах еды из твоей квартиры"))
                    плохо.Add($"итог дня: трое учуяли — а сводка не «несколько соседей учуяли…»: {все}");
                if (с.Any(x => x.Contains("шаг", StringComparison.Ordinal)))
                    плохо.Add($"итог дня: шаги на лестнице попали в сводку: {все}");
                if (!с.Contains("в чате — 2 новых сообщения"))
                    плохо.Add($"итог дня: чат за сутки не посчитан: {все}");
                if (!с.Any(x => x.StartsWith("ты: ", StringComparison.Ordinal)
                                && x.Contains("голоднее", StringComparison.Ordinal)
                                && x.Contains("устал", StringComparison.Ordinal)))
                    плохо.Add($"итог дня: перемены в теле не названы: {все}");
                if (!Без_имён(h, я, с, out var чьё))
                    плохо.Add($"итог дня: в сводке имя соседа — {чьё}");
                сводка_итог = все;
            }

            // мысль утра — по порогу рассудка, первой строкой (ГДД 11); тошно — к ней
            {
                h.day = 3;
                я.mood = 60;
                var с_мыслью = сеанс.Утро(Порог.ТРЕВОГА);
                if (с_мыслью is null || !с_мыслью.строки[0].StartsWith("— ", StringComparison.Ordinal)
                    || !Сеанс.МЫСЛИ_УТРА[Порог.ТРЕВОГА].Any(м => с_мыслью.строки[0] == "— " + м))
                    плохо.Add($"итог дня: первой строкой нет мысли тревоги: {с_мыслью?.строки.FirstOrDefault()}");
                var разные = Enum.GetValues<Порог>().Select(п => Сеанс.Мысль_утра(п, 4, 60)).Distinct().Count();
                if (разные != 4)
                    плохо.Add($"итог дня: мыслей утра по четырём порогам — {разные} разных");
                if (!Сеанс.Мысль_утра(Порог.ОБЫЧНО, 4, 10).Contains("тошно", StringComparison.Ordinal)
                    || Сеанс.Мысль_утра(Порог.ОБЫЧНО, 4, 60).Contains("тошно", StringComparison.Ordinal))
                    плохо.Add("итог дня: «тошно» — не по настроению");
            }

            // жилица — в своём роде
            var жилица = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            var с_ж = new Сеанс(жилица.h, "оксана");
            var она = жилица.h.people["оксана"];
            жилица.h.others(она).First().memory.Add(new Память { день = 1, вид = Вид.СЛЫШАЛ, кто = она.id, что = "возвращение" });
            if (!с_ж.Заметили(1, 2).Contains("кто-то видел, как ты вернулась с улицы с пакетами"))
                плохо.Add($"итог дня: жилице — не в её роде: {string.Join(" · ", с_ж.Заметили(1, 2))}");
        }

        // ---- 5. живой дом ----
        string живой_итог;
        {
            var (п5, с5) = Дом_героя(3);
            var сводки = new List<ИтогДня?>();
            п5.h.hooks.on_day.Add(_ => сводки.Add(с5.Утро()));
            п5.run();
            var есть = сводки.Where(x => x is not null).Select(x => x!).ToList();
            var я5 = п5.h.people[Герой.ID];
            if (сводки.Count != 3 || сводки[0] is not null || есть.Count != 2)
                плохо.Add($"итог дня: три утра живого дома — сводок {есть.Count} из {сводки.Count}, а должно 2 (первое утро — без)");
            foreach (var и in есть)
            {
                if (!и.строки.Any(x => x.StartsWith("запасы:", StringComparison.Ordinal))
                    || !и.строки.Any(x => x.StartsWith("в квартире ", StringComparison.Ordinal)))
                    плохо.Add($"итог дня: в живом доме сводка дня {и.день} без запасов или тепла");
                if (!Без_имён(п5.h, я5, и.строки, out var чьё))
                    плохо.Add($"итог дня: в живом доме в сводке имя соседа — {чьё}");
            }
            живой_итог = есть.Count > 0
                ? $"{есть.Count} сводки; день {есть[^1].день}: {string.Join(" · ", есть[^1].строки)}"
                : "—";
        }

        // ---- 6. экран ----
        {
            string Файл(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя));
            string узел = Файл("ДомУзел.cs"), распорядок = Файл("ДомУзел.Распорядок.cs"), окно = Файл("ДомУзел.ИтогДня.cs");
            if (!узел.Contains("Итог_утра(в);", StringComparison.Ordinal)
                || !распорядок.Contains("Итог_утра(в);", StringComparison.Ordinal))
                плохо.Add("итог дня: узел не зовёт сводку утром — на вопросе дня или в распорядке «день за днём»");
            if (!окно.Contains("сеанс.Утро(Рассудок.Где(_наследие.рассудок, _ручки))", StringComparison.Ordinal)
                || !окно.Contains("\"ИТОГ ДНЯ", StringComparison.Ordinal))
                плохо.Add("итог дня: окно сводки не берёт её у сеанса");
        }

        w($"  сводка: {сводка_итог}");
        w($"  живой дом: {живой_итог}");
        return плохо;
    }
}
