// Проверка людей: клипы Mixamo в именах игры (`Дом.Экран.Анимации.ЛЮДИ`,
// модель — `Дом.Годот/Люди.cs`, файлы — `Дом.Годот/модели/люди`).
//
//  1. **Имя.** Клип — движение из списка (`Анимация`), а после «_» —
//     предмет из данных (ассет в `инструменты.json`) или лестница:
//     иначе аниматор такого имени не спросит никогда.
//  2. **Файлы.** Каждый файл таблицы лежит в папке людей, и лишних там
//     нет: всё, что лежит, — клип или тело (`Дом.Экран.Тела`).
//  3. **Сосед не играет заглушку.** Всё, что `Анимации.Соседа` может
//     вернуть (каждое дело с каждым предметом и без, идёт и спешит), находит
//     клип — с предметом или без.
//  4. **Шаг.** Помечены шагом ровно Walk, Run и Injured, с лестницей и без:
//     из них вынимается ход вперёд, и по ним подгоняется скорость ног;
//     помеченный удар стоял бы на месте, не помеченный шаг уезжал бы.
//  5. **Тело.** Файл тела — FBX из Mixamo, и таблица `Тела` о нём не врёт:
//     сетка тела и каждая вещь — сетки файла, лишних сеток нет (лишняя
//     оделась бы на всех); каждая зона есть среди материалов тела, каждый
//     материал тела — в зонах (не названный остался бы некрашеным); под
//     верхней вещью есть что прятать — кофта. Как покрасится каждый
//     материал вещи — печатается: серое — цветом соседа, цветное — своим.
//     Правило серого — случаями (эталонный серый, почти чёрный, цветной),
//     узел — требованиями: кофта под верхом прячется, клипы переводятся
//     в рост тела, краска — тем же правилом, цвета соседа — от имени.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Люди_(Action<string> w)
    {
        var плохо = new List<string>();
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var ассеты = каталог.в_руках.Values.Select(в => в.ассет).ToHashSet(StringComparer.Ordinal);
        var клипы = Анимации.ЛЮДИ.Select(к => к.клип).ToHashSet(StringComparer.Ordinal);

        // ---- 1. имя ----
        if (клипы.Count != Анимации.ЛЮДИ.Count)
            плохо.Add("в таблице людей клип назван дважды");
        foreach (var к in Анимации.ЛЮДИ)
        {
            var части = к.клип.Split('_', 2);
            if (!Enum.TryParse<Анимация>(части[0], out var движение) || движение.ToString() != части[0])
                плохо.Add($"клип «{к.клип}»: «{части[0]}» — не движение из списка");
            else if (части.Length == 2 && части[1] != Анимации.ЛЕСТНИЦА && !ассеты.Contains(части[1]))
                плохо.Add($"клип «{к.клип}»: «{части[1]}» — ни предмет из данных, ни лестница");
        }

        // ---- 2. файлы ----
        string папка = Path.Combine(Пути.Корень, "Дом.Годот", "модели", "люди");
        var лежат = Directory.Exists(папка)
            ? Directory.GetFiles(папка, "*.fbx").Select(Path.GetFileNameWithoutExtension).OfType<string>()
                       .ToHashSet(StringComparer.Ordinal)
            : new HashSet<string>(StringComparer.Ordinal);
        var нужны = Анимации.ЛЮДИ.Select(к => к.файл).ToHashSet(StringComparer.Ordinal);
        foreach (var нет in нужны.Except(лежат).OrderBy(x => x, StringComparer.Ordinal))
            плохо.Add($"клипа ждут из «{нет}.fbx», а файла в модели/люди нет");
        foreach (var лишний in лежат.Except(нужны).Except(Тела.ВСЕ.Select(т => т.файл))
                                     .OrderBy(x => x, StringComparer.Ordinal))
            плохо.Add($"«{лишний}.fbx» лежит в модели/люди, а не стал ни клипом, ни телом");
        foreach (var тело in Тела.ВСЕ)
            if (!лежат.Contains(тело.файл))
                плохо.Add($"тело «{тело.файл}.fbx» — в таблице, а в модели/люди его нет");
        if (!Анимации.ЛЮДИ.Any(к => к.клип == nameof(Анимация.Idle)))
            плохо.Add("нет Idle — клипа, которым сосед стоит");

        // ---- 3. сосед не играет заглушку ----
        var руки = new List<Руки> { Руки.ПУСТЫ };
        руки.AddRange(каталог.в_руках.Values.Select(в => new Руки(в.id, в.ассет, в.тяжёлый)));
        var ключи = new[] { "отнять", "кража_днём", "разбор", "тело", "разговор" };
        var без_клипа = new SortedSet<string>(StringComparer.Ordinal);
        int движений = 0;
        foreach (string ключ in ключи)
            foreach (var р in руки)
                foreach (var (идёт, спешит) in new[] { (false, false), (true, false), (true, true) })
                {
                    var д = Анимации.Соседа(ключ, р, идёт, спешит);
                    движений++;
                    if (!Анимации.Клипы(д).Any(клипы.Contains))
                        без_клипа.Add(д.ToString());
                }
        foreach (var д in без_клипа)
            плохо.Add($"сосед делает {д} — а клипа нет, играет заглушка");
        // шаг вверх по лестнице тоже находит клип
        foreach (var шаг in new[] { Анимация.Walk, Анимация.Run })
            if (!Анимации.Клипы(new Движение(шаг, Анимации.ЛЕСТНИЦА)).Any(клипы.Contains))
                плохо.Add($"{шаг} по лестнице — клипа нет");

        // ---- 4. шаг ----
        foreach (var к in Анимации.ЛЮДИ)
        {
            string движение = к.клип.Split('_')[0];
            bool должен = движение is nameof(Анимация.Walk) or nameof(Анимация.Run) or nameof(Анимация.Injured);
            if (к.шаг != должен)
                плохо.Add($"клип «{к.клип}» {(к.шаг ? "помечен шагом, а это не шаг" : "— шаг, а не помечен")}");
        }

        // ---- 5. тело ----
        var краски = new List<string>();
        foreach (var тело in Тела.ВСЕ)
        {
            string файл = Path.Combine(папка, тело.файл + ".fbx");
            if (!File.Exists(файл))
                continue;           // уже сказано в п. 2
            Dictionary<string, СеткаFbx> сетки;
            try
            {
                сетки = Fbx.Сетки(файл).ToDictionary(с => с.имя, StringComparer.Ordinal);
            }
            catch (Exception e) when (e is InvalidDataException or IndexOutOfRangeException or ArgumentException
                                          or InvalidOperationException or InvalidCastException)
            {
                плохо.Add($"{тело.файл}: FBX не читается — {e.Message}");
                continue;
            }
            var названы = тело.вещи.Select(в => в.сетка).Append(тело.сетка).ToHashSet(StringComparer.Ordinal);
            foreach (var лишняя in сетки.Keys.Except(названы).OrderBy(x => x, StringComparer.Ordinal))
                плохо.Add($"{тело.файл}: сетка «{лишняя}» в файле, а в таблице тела её нет — оделась бы на всех");
            if (!сетки.TryGetValue(тело.сетка, out var сетка_тела))
                плохо.Add($"{тело.файл}: сетки тела «{тело.сетка}» в файле нет");
            else
            {
                var материалы = сетка_тела.материалы.Select(м => м.имя).ToHashSet(StringComparer.Ordinal);
                foreach (var нет in тело.зоны.Keys.Except(материалы).OrderBy(x => x, StringComparer.Ordinal))
                    плохо.Add($"{тело.файл}: зоны «{нет}» среди материалов тела нет");
                foreach (var без in материалы.Except(тело.зоны.Keys).OrderBy(x => x, StringComparer.Ordinal))
                    плохо.Add($"{тело.файл}: материал тела «{без}» — не зона, красить его нечем");
            }
            if (тело.вещи.Any(в => в.краска == Краска.ВЕРХ) && !тело.под_верхом.Any())
                плохо.Add($"{тело.файл}: верхняя вещь есть, а кофты под ней нет — тело проткнёт ткань");
            foreach (var вещь in тело.вещи)
            {
                if (!сетки.TryGetValue(вещь.сетка, out var сетка_вещи))
                {
                    плохо.Add($"{тело.файл}: вещи «{вещь.сетка}» в файле нет");
                    continue;
                }
                var как = сетка_вещи.материалы.Select(м =>
                {
                    var (краска, доля) = Тела.Покраска(вещь.краска, м.r, м.g, м.b);
                    return краска == Краска.СВОЯ ? $"{м.имя} — свой" : $"{м.имя} — цвет соседа ×{Текст.Ф(доля, 2)}";
                });
                краски.Add($"{вещь.сетка}: {string.Join(", ", как)}");
            }
        }

        // правило серого — случаями: эталон даёт ровно цвет соседа, почти чёрный —
        // почти чёрный, цветное остаётся своим
        var случаи = new (double r, double g, double b, Краска ждём, double доля)[]
        {
            (0.8, 0.8, 0.8, Краска.ВЕРХ, 1.0),
            (0.055, 0.055, 0.055, Краска.ВЕРХ, 0.069),
            (0.31, 0.31, 0.31, Краска.ВЕРХ, 0.388),
            (0.8, 0.77, 0.45, Краска.СВОЯ, 1.0),
            (0.8, 0.6, 0.41, Краска.СВОЯ, 1.0),
        };
        foreach (var (r, g, b, ждём, доля) in случаи)
        {
            var (краска, д) = Тела.Покраска(Краска.ВЕРХ, r, g, b);
            if (краска != ждём || Math.Abs(д - доля) > 0.001)
                плохо.Add($"правило серого: цвет ({r}, {g}, {b}) — {краска} ×{Текст.Ф(д, 3)}, а надо {ждём} ×{Текст.Ф(доля, 3)}");
        }
        // узел: то, без чего тело в куртке ломается, а консоль бы не заметила
        string Код(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя + ".cs"));
        var узел = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["Люди"] = Код("Люди"),
            ["Сосед3D"] = Код("Сосед3D"),
        };
        var требования = new (string где, string текст, string беда)[]
        {
            ("Люди", "ТЕЛО.под_верхом", "кофта под курткой не прячется — тело протыкает ткань на ходу"),
            ("Люди", "На_тело(клип, бёдра,", "клипы старого скелета не переведены в рост тела — бёдра в воздухе, кости тянутся к длинам 11-метровой модели"),
            ("Люди", "Тела.Покраска(", "вещь красится не правилом серого из Дом.Экран — консоль сверяет одно, движок красит другое"),
            ("Люди", "меш.Visible = false;", "сетка не из таблицы не прячется — надевается на всех"),
            ("Сосед3D", "Люди.Цвета_соседа(id,", "цвета соседа не от имени — сосед меняется в лице от жизни к жизни"),
        };
        foreach (var (где, текст, беда) in требования)
            if (!узел[где].Contains(текст, StringComparison.Ordinal))
                плохо.Add($"{где}: {беда}");

        w($"  клипов {Анимации.ЛЮДИ.Count} из {нужны.Count} файлов, в папке {лежат.Count}; "
          + $"движений соседа проверено {движений}, без клипа {без_клипа.Count}; тел {Тела.ВСЕ.Count}; "
          + $"случаев серого {случаи.Length}");
        foreach (var к in краски)
            w($"  {к}");
        return плохо;
    }
}
