// Проверка «уход посреди дня» (`Дом.Экран/Уход.cs`, движок — `ДомУзел.Уход`;
// ГДД 24: «выход из игры сохраняет прогресс; загрузить „раньше“ нельзя»).
//
//  1. **Как уйти.** Сразу — если с последнего сна герой ничего не делал или
//     жизнь кончилась; до метели — лечь; в метель — дожить день.
//  2. **Шаг.** Дом считает — ждать; вопрос дня — прожить полчаса; прочее —
//     молчанием, ночью — спать; вопрос о следующем дне — готово (сон записан);
//     жизнь кончилась — итог.
//  3. **Живой дом.** Герой новой игры проживает полдня сам, потом уходит:
//     дом доживает день по правилу, сам герой не берётся ни за одно дело,
//     конец дня (сохранение) — ровно один и в тот же день, следующий вопрос —
//     о следующем дне.
//  4. **Узел.** Все три выхода (меню, «Выйти из игры», крестик окна) идут
//     через `Уйти`; «ходил» ставят ответ и часы, снимает — сохранение;
//     уход зовётся каждый кадр; пока уходим, клавиши молчат; свёрнутая
//     жизнь гасит строки внизу экрана (под меню висела весть дожитого дня).

using System.Text.RegularExpressions;
using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Уход_(Action<string> w)
    {
        var плохо = new List<string>();

        // ---- 1. как уйти ----
        var как = new (bool пролог, bool ходил, bool кончилась, КакУйти ждём)[]
        {
            (false, false, false, КакУйти.СРАЗУ),
            (false, true, false, КакУйти.ДОЖИТЬ),
            (true, true, false, КакУйти.СПАТЬ),
            (true, false, false, КакУйти.СРАЗУ),
            (false, true, true, КакУйти.СРАЗУ),
            (true, true, true, КакУйти.СРАЗУ),
        };
        foreach (var (пролог, ходил, кончилась, ждём) in как)
            if (Уход.Как(пролог, ходил, кончилась) is var к && к != ждём)
                плохо.Add($"уйти {(пролог ? "до метели" : "в метель")}, {(ходил ? "ходил" : "не ходил")}"
                          + $"{(кончилась ? ", жизнь кончилась" : "")} — {к}, а надо {ждём}");

        // ---- 2. шаг ----
        ВопросИгроку В(int день, Вопрос вопрос, params string[] ключи)
            => new(день, Герой.ID, вопрос, "", ключи.Select((к, i) => new ВариантИгроку(к, ключи.Length - i, к)).ToList(), null, null);
        string Словами((ШагУхода шаг, int номер) ш, ВопросИгроку? в)
            => ш.шаг == ШагУхода.ОТВЕТИТЬ && в is not null ? $"ОТВЕТИТЬ {в.варианты[ш.номер].ключ}" : ш.шаг.ToString();
        var шаги = new (ВопросИгроку? в, bool кончилась, string ждём)[]
        {
            (null, false, "ЖДАТЬ"),
            (В(3, Вопрос.ЧТО_ДЕЛАТЬ, "поесть", "топить"), false, "ПРОЖИТЬ"),
            (В(3, Вопрос.ОТКРЫТЬ_ДВЕРЬ, "открыть", "через дверь"), false, "ОТВЕТИТЬ через дверь"),
            (В(3, Вопрос.ДАТЬ_ИЗ_СВОЕГО, "дать", "отказать"), false, "ОТВЕТИТЬ отказать"),
            (В(3, Вопрос.НОЧЬ, "дежурить", "спать"), false, "ОТВЕТИТЬ спать"),
            (В(4, Вопрос.ЧТО_ДЕЛАТЬ, "поесть"), false, "ГОТОВО"),
            (В(4, Вопрос.ДРАТЬСЯ_С_ВОРОМ, "драться", "отпустить"), false, "ГОТОВО"),
            (null, true, "КОНЧИЛАСЬ"),
            (В(3, Вопрос.ЧТО_ДЕЛАТЬ, "поесть"), true, "КОНЧИЛАСЬ"),
        };
        foreach (var (в, кончилась, ждём) in шаги)
        {
            string есть = Словами(Уход.Шаг(в, 3, кончилась), в);
            if (есть != ждём)
                плохо.Add($"уход с 3-го дня: на {(в is null ? "«считает»" : $"{в.вопрос} дня {в.день}")}"
                          + $"{(кончилась ? " (кончилась)" : "")} — {есть}, а надо {ждём}");
        }

        // ---- 3. живой дом ----
        string живой_итог = "—";
        {
            var профиль = new ПрофильГероя("Андрей", "м");
            var прогон = new Прогон(Пути.Данные, seed: 17, days: 4,
                                    жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            using var партия = new Партия(прогон, Герой.ID);
            var h = прогон.h;
            var я = партия.сеанс.я;
            bool уходим = false;
            var концы_дня = new List<int>();
            var дела_после = new List<string>();
            h.hooks.on_day.Add(дом =>
            {
                if (уходим)
                    концы_дня.Add(дом.day);
            });
            h.hooks.after_execute.Add((_, кто, ключ, _, _, _) =>
            {
                if (уходим && ReferenceEquals(кто, я))
                    дела_после.Add(ключ);
            });
            партия.Начать();
            // сам: три дела дня (верхней мыслью), на прочее — молча, чтобы
            // герой не погиб раньше, чем уйдёт
            int сделал = 0, шагов = 0;
            var в = партия.Дождаться();
            while (в is not null && сделал < 3 && шагов++ < 200)
            {
                int номер = в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ ? 0 : Math.Max(0, Беспамятство.Ответ(в));
                if (в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
                    сделал++;
                партия.Ответить(номер);
                в = партия.Дождаться();
            }
            if (в is not { вопрос: Вопрос.ЧТО_ДЕЛАТЬ })
            {
                плохо.Add($"живой дом: герой не дошёл до четвёртого дела ({в?.вопрос.ToString() ?? "партия кончилась"})");
                return плохо;
            }
            // ушёл посреди дня
            int с_дня = в.день;
            double час_ухода = я.час();
            уходим = true;
            шагов = 0;
            int прожито = 0;
            var ответы = new SortedSet<string>(StringComparer.Ordinal);
            ШагУхода конец = ШагУхода.ЖДАТЬ;
            ВопросИгроку? на_конце = null;
            while (шагов++ < 1000)
            {
                var (шаг, номер) = Уход.Шаг(в, с_дня, партия.кончилась);
                if (шаг is ШагУхода.ГОТОВО or ШагУхода.КОНЧИЛАСЬ)
                {
                    конец = шаг;
                    на_конце = в;
                    break;
                }
                if (шаг == ШагУхода.ПРОЖИТЬ)
                {
                    ХодВремени.Прожить(я, Math.Min(Уход.ШАГ, я.time_left));
                    if (!партия.Пропустить())
                    {
                        плохо.Add("уход: партия не пропустила вопрос дня");
                        break;
                    }
                    прожито++;
                }
                else if (шаг == ШагУхода.ОТВЕТИТЬ)
                {
                    ответы.Add($"{в!.вопрос}→{в.варианты[номер].ключ}");
                    партия.Ответить(номер);
                }
                в = партия.Дождаться();
            }
            уходим = false;
            if (конец != ШагУхода.ГОТОВО)
                плохо.Add($"уход с дня {с_дня}: дом не дожил день до сна — {конец} после {шагов} шагов"
                          + (я.здесь() ? "" : $" (герой выбыл: {я.cause})"));
            else
            {
                if (на_конце?.день != с_дня + 1)
                    плохо.Add($"уход: готово на вопросе дня {на_конце?.день}, а ушли в {с_дня}-й");
                if (концы_дня.Count != 1 || концы_дня[0] != с_дня)
                    плохо.Add($"уход с дня {с_дня}: концов дня (сохранений) за уход — [{string.Join(", ", концы_дня)}], "
                              + "а надо ровно один, этого дня");
            }
            if (дела_после.Count > 0)
                плохо.Add($"ушедший герой сам взялся за дела: {string.Join(", ", дела_после)}");
            if (!ответы.Any(о => о.StartsWith("НОЧЬ→спать", StringComparison.Ordinal)))
                плохо.Add($"уход: ночью ушедший не спал (ответы: {string.Join(", ", ответы)})");
            if (прожито == 0)
                плохо.Add("уход: день не проматывался — ни одного шага");
            живой_итог = $"ушёл в день {с_дня}, {ХодВремени.Часы(час_ухода)} после трёх дел: дом дожил день за {шагов} шагов "
                         + $"(полчаса — {прожито}), концы дня [{string.Join(", ", концы_дня)}], дел героя {дела_после.Count}; "
                         + $"ответы: {string.Join(", ", ответы)}";
            while (в is not null)
            {
                партия.Ответить(Math.Max(0, Беспамятство.Ответ(в)));
                в = партия.Дождаться();
            }
            партия.Досидеть();
        }

        // ---- 4. узел ----
        string узел = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Годот"), "ДомУзел*.cs")
                                                 .Select(File.ReadAllText));
        string Тело(string заголовок)
        {
            int i = узел.IndexOf(заголовок, StringComparison.Ordinal);
            if (i < 0)
                return "";
            int j = узел.IndexOf("\n    }\n", i, StringComparison.Ordinal);
            return j < 0 ? узел[i..] : узел[i..j];
        }
        var требования = new (string где, string что, string беда)[]
        {
            ("private void Из_игры_в_меню()", "Уйти(", "в главное меню уходят мимо `Уйти` — день переигрывается"),
            ("private void Выйти_из_игры()", "Уйти(", "из игры уходят мимо `Уйти` — день переигрывается"),
            ("public override void _Notification(int what)", "Выйти_из_игры();", "крестик окна закрывает игру мимо `Уйти`"),
            ("private void Сохраниться(Партия чья)", "_ходил = false", "сохранение не снимает «ходил» — выход сразу после сна стоит дня"),
            ("private double Прожить(double часы)", "_ходил = true", "часы героя не ставят «ходил» — уйдёт сразу и переиграет день"),
            ("private void Ответить(int номер, bool играть)", "_ходил = true", "ответ дому не ставит «ходил» — уйдёт сразу и переиграет день"),
            ("private void Уйти(System.Action дальше)", "Уход.Как(", "узел решает, как уйти, не по правилу `Уход.Как`"),
            ("private void Уход_кадр()", "Уход.Шаг(", "узел доживает день не по правилу `Уход.Шаг`"),
            ("private void Уход_кадр()", "CallDeferred()", "уход бросает партию посреди кадра — кадр дальше читает брошенную"),
            ("public override void _UnhandledInput(InputEvent e)", "Уходим", "пока дом доживает день за ушедшего, клавиши работают"),
            ("public override void _Process(double delta)", "Уход_кадр();", "уход не зовётся каждый кадр — день стоит, игра не закрывается"),
            ("private void Свернуть_жизнь()", "_на_ходу.Text = \"\"", "строка «на ходу» дожитого дня висит под главным меню"),
            ("private void Свернуть_жизнь()", "_весть.Text = \"\"", "весть дожитого дня висит под главным меню"),
        };
        foreach (var (где, что, беда) in требования)
            if (!Тело(где).Contains(что, StringComparison.Ordinal))
                плохо.Add($"узел: {беда}");
        int выходов = Regex.Matches(узел, @"GetTree\(\)\.Quit\(\)").Count;
        if (выходов != 1)
            плохо.Add($"узел: GetTree().Quit() в {выходов} местах — выходить из игры можно только через `Выйти_из_игры`");
        string настройки = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "НастройкиUI.cs"));
        if (!Regex.IsMatch(настройки, @"if \(Выход is \{ \} выход\)\s*выход\(\);"))
            плохо.Add("настройки: «Выйти из игры» закрывает игру мимо узла — день переигрывается");
        if (!узел.Contains("Выход = Выйти_из_игры", StringComparison.Ordinal))
            плохо.Add("узел не отдаёт настройкам свой выход");

        w($"  как уйти: {как.Length} случаев, шаг: {шаги.Length}; узел: {требования.Length} требований");
        w($"  {живой_итог}");
        return плохо;
    }
}
