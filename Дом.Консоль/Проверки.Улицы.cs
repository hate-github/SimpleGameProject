// Проверка улиц и снегоступов (задание автора, пп. 11–12;
// `Дом.Ядро/Петля/Летопись.cs`, `Округа.cs`, `data/мир.json`).
//
//  1. **Улицы заметает по дням.** До магазина — чисто, снег, глубокий снег
//     (со снегопада четвёртого дня), завалено с седьмого; двор не заметает
//     никогда; дальнее — раньше. Завалено — без снегоступов не пройти.
//  2. **Только у героя.** Заметённая дорога закрывает место герою
//     (`Улица.место_доступно`); в снегоступах — открыта. Соседу — как было:
//     у него нет улиц, и дом считает его дорогу своим снегом.
//  3. **Кто знает о снегоступах.** Сосед — если слышал, как герой вернулся
//     в день, когда без снегоступов туда не пройти; герой о мастере —
//     по его рассказу. Мастера делают снегоступы со своего дня.
//  4. **Тянутся отнять.** Знающий сосед получает на лестнице вариант
//     «отнять» у героя там, где без снегоступов его бы не было, — в самом
//     сборе вариантов; отъём уносит снегоступы.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Улицы_(Action<string> w)
    {
        var плохо = new List<string>();
        var л = Летопись.Прочитать(Пути.Данные);
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        const long ЗЕРНО = 42;
        const string МАГАЗИН = "магазин на Заречной";

        // ---- 1. по дням ----
        var дни = Enumerable.Range(1, 9).Select(д => л.Улица(МАГАЗИН, д, ЗЕРНО)).ToList();
        var надо = new[]
        {
            СостояниеУлицы.ЧИСТО, СостояниеУлицы.ЧИСТО, СостояниеУлицы.СНЕГ,
            СостояниеУлицы.ГЛУБОКИЙ_СНЕГ, СостояниеУлицы.ГЛУБОКИЙ_СНЕГ, СостояниеУлицы.ГЛУБОКИЙ_СНЕГ,
            СостояниеУлицы.ЗАВАЛЕНО, СостояниеУлицы.ЗАВАЛЕНО, СостояниеУлицы.ЗАВАЛЕНО,
        };
        if (!дни.SequenceEqual(надо))
            плохо.Add($"дорога к магазину по дням: {string.Join(", ", дни)}, а по данным — {string.Join(", ", надо)}");
        for (int д = 1; д <= 30; д++)
            if (л.Улица("двор и мусорки", д, ЗЕРНО) != СостояниеУлицы.ЧИСТО)
            {
                плохо.Add($"двор на {д}-й день заметён — а он не улица");
                break;
            }
        if (л.Улица("промзона", 5, ЗЕРНО) <= л.Улица(МАГАЗИН, 5, ЗЕРНО))
            плохо.Add("дальнюю промзону заметает не раньше магазина");
        if (л.Пройти(МАГАЗИН, 7, ЗЕРНО, снегоступы: false) || !л.Пройти(МАГАЗИН, 7, ЗЕРНО, снегоступы: true))
            плохо.Add("завал седьмого дня: без снегоступов проходим или в снегоступах — нет");
        if (!л.Пройти(МАГАЗИН, 6, ЗЕРНО, снегоступы: false))
            плохо.Add("глубокий снег шестого дня закрыл дорогу без снегоступов — рано");
        if (л.Часы_дороги(СостояниеУлицы.ГЛУБОКИЙ_СНЕГ, false) <= л.Часы_дороги(СостояниеУлицы.ЧИСТО, false))
            плохо.Add("по глубокому снегу идти не дольше, чем по чистому");

        // дом, петля с летописью: у героя есть улицы
        (House h, NPC я) Жизнь(long зерно = 7, string кто = "оксана")
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л)
                .Слушать(прогон, кто);
            return (прогон.h, прогон.h.people[кто]);
        }
        var магазин = Улица.МЕСТА.First(м => м.магазин);

        // ---- 2. только у героя ----
        string герой_итог;
        {
            // Лида: у Оксаны на руках ребёнок, и магазин ей далёк и без снега
            var (h, я) = Жизнь(кто: "лида");
            h.day = 7;
            h.магазины = true;
            я.счёт = 50;
            // магазин нужен и по карману: пустой шкаф — иначе он закрыт
            // и без снега, и проверка прошла бы вхолостую
            я.stock["еда"] = 0;
            я.stock["вода"] = 0;
            bool без = Улица.место_доступно(h, я, магазин);
            я.снаряжение!.Подобрать(Округа.СНЕГОСТУПЫ, каталог);
            bool в_них = Улица.место_доступно(h, я, магазин);
            if (без)
                плохо.Add("седьмой день, завал — а герою без снегоступов магазин доступен");
            if (!в_них)
                плохо.Add("в снегоступах заваленная дорога всё равно закрыта");
            if (я.снаряжение.Можно_держать(я, каталог).Contains(Округа.СНЕГОСТУПЫ))
                плохо.Add("снегоступы можно взять в руки — а их носят на ногах");
            // сосед — как в доме без петли
            var (h0, _) = (new Прогон(Пути.Данные, seed: 7, days: 1,
                                      журнал: new Журнал(0, false, TextWriter.Null)).h, 0);
            h0.day = 7;
            var сосед = h.people.Значения.First(п => п.id != я.id);
            var сосед0 = h0.people[сосед.id];
            if (сосед.улицы is not null)
                плохо.Add($"у соседа {сосед.id} есть улицы — округа видна не только герою");
            foreach (var м in Улица.МЕСТА)
                if (Улица.место_доступно(h, сосед, м) != Улица.место_доступно(h0, сосед0, м))
                    плохо.Add($"соседу {сосед.id} «{м.имя}» доступно иначе, чем в доме без петли");
            герой_итог = $"седьмой день: герою магазин без снегоступов — {(без ? "открыт" : "закрыт")}, "
                         + $"в снегоступах — {(в_них ? "открыт" : "закрыт")}; соседям — как без петли";
        }

        // ---- 3 и 4. кто знает и кто тянется ----
        string тяга_итог;
        {
            var (h, я) = Жизнь();
            var о = Округа.У(h)!;
            h.day = 7;
            я.снаряжение!.Подобрать(Округа.СНЕГОСТУПЫ, каталог);
            // тот, кто сильнее героя и не живёт с ним
            var сосед = h.people.Значения.Where(п => п.id != я.id && !h.под_одной_крышей(п, я))
                          .OrderByDescending(п => п.power()).First();
            if (о.Тянет(h, сосед, я) != 0.0)
                плохо.Add("сосед тянется к снегоступам героя, ничего о них не зная");
            сосед.memory.Add(new Память { день = 7, вид = Вид.СЛЫШАЛ, кто = я.id, что = "возвращение" });
            if (о.Тянет(h, сосед, я) != 0.0)
                плохо.Add("сосед слышал, как герой вернулся, — а герой не ходил по завалу; тянуться не к чему");
            о.Ходил_на_снегоступах(7);
            double тянет = о.Тянет(h, сосед, я);
            if (тянет <= 0.0)
                плохо.Add("сосед слышал, как герой вернулся в день завала, — и не знает о снегоступах");
            var мастер = h.people["пётр"];
            h.day = 4;
            bool рано = о.Есть_у(h, мастер);
            h.day = 7;
            if (рано || !о.Есть_у(h, мастер))
                плохо.Add($"Пётр делает снегоступы с пятого дня, а на четвёртом они {(рано ? "есть" : "—")}, на седьмом — {(о.Есть_у(h, мастер) ? "есть" : "нет")}");
            я.снаряжение.Положить_насовсем(Округа.СНЕГОСТУПЫ);
            if (о.Тянет(h, я, мастер) != 0.0)
                плохо.Add("герой тянется к снегоступам Петра, не зная о них");
            о.Герой_узнал("пётр");
            if (о.Тянет(h, я, мастер) <= 0.0)
                плохо.Add("Пётр сам сказал про снегоступы — а герою к ним не тянет");
            я.снаряжение.Подобрать(Округа.СНЕГОСТУПЫ, каталог);

            // сбор вариантов: отнять у героя появляется из-за снегоступов
            bool Есть_отнять()
            {
                var к = Действия.gather(h, сосед);
                return к.варианты.Any(в => в.что.key == "отнять" && ReferenceEquals(в.что.target, я));
            }
            сосед.hate[я.id] = 40;                       // повод есть и без снегоступов
            сосед.memory.Add(new Память { день = 7, вид = Вид.СЛЫШАЛ, кто = я.id, что = "возвращение" });
            // что у героя в шкафу, сосед думает скудно: грабить нечего
            foreach (var р in new[] { "еда", "топливо", "лекарства" })
                сосед.сведения_о(я.id).est[р] = 0.0;
            bool с_ними = Есть_отнять();
            я.снаряжение.Положить_насовсем(Округа.СНЕГОСТУПЫ);
            bool без_них = Есть_отнять();
            я.снаряжение.Подобрать(Округа.СНЕГОСТУПЫ, каталог);
            if (!с_ними || без_них)
                плохо.Add($"вариант «отнять» у героя: со снегоступами — {(с_ними ? "есть" : "нет")}, "
                          + $"без — {(без_них ? "есть" : "нет")}: тяга не работает в сборе");
            // и сама мера: у героя есть что взять и без снегоступов — со снегоступами
            // тянет сильнее
            double? Мера()
            {
                var к = Действия.gather(h, сосед);
                foreach (var в in к.варианты)
                    if (в.что.key == "отнять" && ReferenceEquals(в.что.target, я))
                        return в.оценка;
                return null;
            }
            сосед.сведения_о(я.id).est["еда"] = 12.0;
            double? мера_с = Мера();
            я.снаряжение.Положить_насовсем(Округа.СНЕГОСТУПЫ);
            double? мера_без = Мера();
            я.снаряжение.Подобрать(Округа.СНЕГОСТУПЫ, каталог);
            if (мера_с is null || мера_без is null || мера_с <= мера_без + 1e-9)
                плохо.Add($"мера отъёма: со снегоступами {мера_с?.ToString("F2") ?? "—"}, "
                          + $"без — {мера_без?.ToString("F2") ?? "—"}: тяга не прибавилась");

            // отъём уносит снегоступы — ищем зерно, где отдали или отбили
            int унесли = 0, попыток = 0;
            for (long зерно = 1; зерно <= 40 && унесли == 0; зерно++)
            {
                var (h2, я2) = Жизнь(зерно);
                var о2 = Округа.У(h2)!;
                h2.day = 7;
                я2.снаряжение!.Подобрать(Округа.СНЕГОСТУПЫ, каталог);
                var с2 = h2.people[сосед.id];
                с2.memory.Add(new Память { день = 7, вид = Вид.СЛЫШАЛ, кто = я2.id, что = "возвращение" });
                о2.Ходил_на_снегоступах(7);
                попыток++;
                Действия.execute(h2, с2, "отнять", я2);
                if (!я2.снаряжение.Есть(Округа.СНЕГОСТУПЫ))
                {
                    унесли++;
                    if (!о2.Есть_у(h2, с2))
                        плохо.Add("снегоступы у героя отняли — а у отнявшего их нет");
                    // отняли лицом к лицу: герой знает у кого — и его тянет вернуть
                    if (о2.Тянет(h2, я2, с2) <= 0)
                        плохо.Add("у героя отняли снегоступы на лестнице — а он не знает, у кого они, "
                                  + "и забрать их обратно его не тянет");
                }
            }
            if (унесли == 0)
                плохо.Add($"за {попыток} отъёмов снегоступы не унесли ни разу");
            тяга_итог = $"тяга {Текст.Ф(тянет, 1)} при завале; отнять у героя — только со снегоступами, "
                        + $"мера {Текст.Ф(мера_без ?? 0, 1)} → {Текст.Ф(мера_с ?? 0, 1)}; унесли на {попыток}-м отъёме";
        }

        w($"  дорога к магазину: {string.Join(", ", дни.Select(д => д.ToString().ToLowerInvariant()))}");
        w($"  герой: {герой_итог}");
        w($"  снегоступы: {тяга_итог}");
        return плохо;
    }
}
