// Проверка настроек (Esc): файл, клавиши, разрешения, громкость —
// и то, что игра их действительно слушает.
//
//  1. **Умолчания — прежние клавиши.** До настроек игра жила на WASD, E,
//     пробеле, Q, J, T, P, M и I, и пальцы игрока помнят именно их.
//     У каждого действия своя клавиша, и ни одна не занята игрой.
//  2. **Файл туда и обратно.** Настройки, отличные от умолчаний в каждом
//     поле, записываются и читаются без замечаний и без потерь; кириллица
//     в файле читается глазом.
//  3. **Сломанный файл игру не останавливает.** Мусор, чужие типы,
//     значения за краем, неизвестные действия и каналы, одна клавиша
//     на двоих, Esc на карте — каждое чинится умолчанием и называется
//     замечанием; ни одно не бросает, и ни одно не чинится молча.
//  4. **Переназначение не теряет клавиш.** Занятая клавиша меняется
//     местами, а не отнимается; Esc и цифры не отдаются; после четырёхсот
//     переназначений наугад у действий нет общей клавиши.
//  5. **Разрешения.** В окне — только то, что помещается на стол вместе
//     с рамкой; на весь экран — доли экрана с его же сторонами.
//  6. **Громкость**: половина — минус шесть децибел, ноль — тишина.
//  7. **Игра слушает настройки.** Каждое действие кто-то в `Дом.Годот`
//     спрашивает: действие, которого никто не спрашивает, — ручка без
//     замера, на экране есть, в игре нет. Ни одна буква не зашита мимо
//     настроек (исключение — строка с пометкой «клавиша: причина»),
//     и ни одна подсказка не называет клавишу буквой: после переназначения
//     она бы врала. У каждого канала громкости своя шина.

using System.Reflection;
using System.Text.RegularExpressions;
using Дом.Экран;
using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Настройки_(Action<string> w)
    {
        var плохо = new List<string>();
        // прежние клавиши и две новые: F — достать или убрать из рук,
        // R — взять в руки другое (задание автора, п. 22)
        const string БЫЛО = "W S A D E Space Q J T P M I F R";

        static string Клавишами(Настройки н)
            => string.Join(" ", Клавиши.ВСЕ.Select(п => н.Клавиша(п.ключ)));
        static List<string> Двойные(Настройки н)
            => Клавиши.ВСЕ.Select(п => н.Клавиша(п.ключ)).Where(к => к.Length > 0)
                     .GroupBy(к => к, StringComparer.Ordinal)
                     .Where(г => г.Count() > 1).Select(г => г.Key).ToList();
        static int Назначено(Настройки н)
            => Клавиши.ВСЕ.Count(п => н.Клавиша(п.ключ).Length > 0);
        string ПоУмолчанию = new Настройки().ВJson();

        // ---- 1. умолчания — прежние клавиши ----
        {
            var н = new Настройки();
            if (Клавишами(н) != БЫЛО)
                плохо.Add($"умолчания разошлись с прежними клавишами: {Клавишами(н)} вместо {БЫЛО}");
            foreach (var п in Клавиши.ВСЕ)
                if (Клавиши.Занята(п.клавиша) || Клавиши.Мышью(п.клавиша) || п.клавиша.Length == 0)
                    плохо.Add($"«{п.подпись}» по умолчанию на «{п.клавиша}» — её нельзя или нечем нажать");
            foreach (var к in Двойные(н))
                плохо.Add($"по умолчанию {к} у двух действий");
            if (Клавиши.ВСЕ.Select(п => п.ключ).Distinct(StringComparer.Ordinal).Count() != Клавиши.ВСЕ.Count)
                плохо.Add("у двух действий один ключ");
            if (н.Починить() is { Count: > 0 } починено)
                плохо.Add($"умолчания пришлось чинить: {починено[0]}");
            foreach (var к in Громкость.ВСЕ)
                if (н.Уровень(к.ключ) != 1.0)
                    плохо.Add($"громкость «{к.подпись}» по умолчанию {н.Уровень(к.ключ)}, а не полная");
            if (н.режим != Разрешения.ОКНО || н.окно != Настройки.ОКНО || н.чёткость != 1.0
                || !н.синхронизация || н.чувствительность != 1.0 || н.инверсия)
                плохо.Add($"экран и мышь по умолчанию не те: {н.режим}, {н.окно}, чёткость {н.чёткость}, "
                          + $"синхронизация {н.синхронизация}, мышь ×{н.чувствительность}, инверсия {н.инверсия}");
            w($"  умолчания: {Клавишами(н)}; окно {н.окно}, громкость полная");
        }

        // ---- 2. файл туда и обратно ----
        {
            var н = new Настройки();
            н.Назначить(Клавиши.ВПЕРЁД, "Up");
            н.Назначить(Клавиши.ДЕЙСТВИЕ, "ПКМ");
            н.Назначить(Клавиши.КАРТА, "Tab");
            н.чувствительность = 1.75;
            н.инверсия = true;
            н.режим = Разрешения.БЕЗ_РАМКИ;
            н.окно = new Размер(1600, 900);
            н.чёткость = 0.75;
            н.синхронизация = false;
            н.Уровень(Громкость.ОБЩАЯ, 0.5);
            н.Уровень(Громкость.МЕТЕЛЬ, 0.667);
            н.Уровень(Громкость.ШАГИ, 0.0);
            н.Уровень(Громкость.ФОН, 0.25);

            // проверка трогает каждое поле: иначе поле, которое не пишется,
            // вернулось бы умолчанием и совпало само
            var умолч = new Настройки();
            var поля = new (string имя, bool отличается)[]
            {
                ("чувствительность", н.чувствительность != умолч.чувствительность),
                ("инверсия", н.инверсия != умолч.инверсия),
                ("режим", н.режим != умолч.режим),
                ("окно", н.окно != умолч.окно),
                ("чёткость", н.чёткость != умолч.чёткость),
                ("синхронизация", н.синхронизация != умолч.синхронизация),
            };
            foreach (var (имя, отличается) in поля.Concat(Громкость.ВСЕ.Select(
                         к => (к.ключ, н.Уровень(к.ключ) != умолч.Уровень(к.ключ)))))
                if (!отличается)
                    плохо.Add($"проверка файла не трогает «{имя}»");

            string файл = н.ВJson();
            var замечания = new List<string>();
            var снова = Настройки.ИзJson(файл, замечания);

            // Сверяется прочитанное с исходным, поле в поле, — а не файл
            // с файлом. Второй файл пишет тот же писатель, и поле, которое
            // он теряет, теряется оба раза одинаково: порча «инверсия
            // не пишется» так и прошла зелёной
            var разошлось = new List<string>();
            void Сверить(string имя, object было, object стало)
            {
                if (!Equals(было, стало))
                    разошлось.Add($"{имя}: {было} → {стало}");
            }
            foreach (var п in Клавиши.ВСЕ)
                Сверить(п.ключ, н.Клавиша(п.ключ), снова.Клавиша(п.ключ));
            Сверить("чувствительность", н.чувствительность, снова.чувствительность);
            Сверить("инверсия", н.инверсия, снова.инверсия);
            Сверить("режим", н.режим, снова.режим);
            Сверить("окно", н.окно, снова.окно);
            Сверить("чёткость", н.чёткость, снова.чёткость);
            Сверить("синхронизация", н.синхронизация, снова.синхронизация);
            foreach (var к in Громкость.ВСЕ)
                Сверить(к.ключ, н.Уровень(к.ключ), снова.Уровень(к.ключ));
            if (разошлось.Count > 0)
                плохо.Add($"файл туда и обратно не сошёлся: {string.Join("; ", разошлось)}");
            if (снова.ВJson() != файл)
                плохо.Add("перечитанные настройки пишутся другим файлом");
            if (замечания.Count > 0)
                плохо.Add($"чистый файл прочитан с замечаниями: {замечания[0]}");
            if (!файл.Contains("\"вперёд\": \"Up\"", StringComparison.Ordinal)
                || !файл.Contains("\"окно\": \"1600×900\"", StringComparison.Ordinal))
                плохо.Add("файл не читается глазом: ключи и размеры не записаны как есть");
            if (Клавишами(снова) == БЫЛО)
                плохо.Add("переназначенные клавиши вернулись умолчаниями");
            w($"  файл: {файл.Split('\n').Length} строк, туда и обратно без потерь и замечаний");
        }

        // ---- 3. сломанный файл игру не останавливает ----
        {
            // что за файл; ждать ли замечаний; что должно выйти
            var случаи = new (string что, string файл, bool замечать, Func<Настройки, string?> беда)[]
            {
                ("мусор", "это не json {", true,
                    н => н.ВJson() == ПоУмолчанию ? null : "вышло не умолчание"),
                ("массив", "[1, 2]", true,
                    н => н.ВJson() == ПоУмолчанию ? null : "вышло не умолчание"),
                ("пустые настройки", """{"версия": 1}""", false,
                    н => н.ВJson() == ПоУмолчанию ? null : "вышло не умолчание"),
                ("без версии", """{"экран": {"синхронизация": false}}""", true,
                    н => н.синхронизация ? "поле без версии не прочитано" : null),
                ("версия из будущего", """{"версия": 99, "экран": {"синхронизация": false}}""", true,
                    н => н.синхронизация ? "понятное поле новой версии не прочитано" : null),
                ("чувствительность словом", """{"версия": 1, "управление": {"чувствительность": "много"}}""", true,
                    н => н.чувствительность == 1.0 ? null : $"чувствительность {н.чувствительность}"),
                ("чувствительность за краем", """{"версия": 1, "управление": {"чувствительность": 40}}""", true,
                    н => н.чувствительность == Настройки.МЫШЬ_ДО ? null : $"чувствительность {н.чувствительность}"),
                ("инверсия строкой", """{"версия": 1, "управление": {"инверсия": "да"}}""", true,
                    н => н.инверсия ? "«да» строкой принято за истину" : null),
                ("громкость за краем", """{"версия": 1, "громкость": {"метель": 7, "фон": -1}}""", true,
                    н => н.Уровень(Громкость.МЕТЕЛЬ) == 1.0 && н.Уровень(Громкость.ФОН) == 0.0
                        ? null : $"метель {н.Уровень(Громкость.МЕТЕЛЬ)}, фон {н.Уровень(Громкость.ФОН)}"),
                ("чужой канал", """{"версия": 1, "громкость": {"музыка": 0.3}}""", true,
                    н => н.ВJson() == ПоУмолчанию ? null : "чужой канал что-то сдвинул"),
                ("окно словом", """{"версия": 1, "экран": {"окно": "огромное"}}""", true,
                    н => н.окно == Настройки.ОКНО ? null : $"окно {н.окно}"),
                ("окно в точку", """{"версия": 1, "экран": {"окно": "1×1"}}""", true,
                    н => н.окно == Настройки.ОКНО ? null : $"окно {н.окно}"),
                ("чёткость мала", """{"версия": 1, "экран": {"чёткость": 0.1}}""", true,
                    н => н.чёткость == Настройки.ЧЁТКОСТЬ_ОТ ? null : $"чёткость {н.чёткость}"),
                ("режим чужой", """{"версия": 1, "экран": {"режим": "кинотеатр"}}""", true,
                    н => н.режим == Разрешения.ОКНО ? null : $"режим {н.режим}"),
                ("экран строкой", """{"версия": 1, "экран": "большой"}""", true,
                    н => н.ВJson() == ПоУмолчанию ? null : "вышло не умолчание"),
                ("неизвестное действие", """{"версия": 1, "управление": {"клавиши": {"прыжок": "F"}}}""", true,
                    н => Клавишами(н) == БЫЛО ? null : $"клавиши {Клавишами(н)}"),
                ("клавиша числом", """{"версия": 1, "управление": {"клавиши": {"вперёд": 5}}}""", true,
                    н => н.Клавиша(Клавиши.ВПЕРЁД) == "W" ? null : $"вперёд — «{н.Клавиша(Клавиши.ВПЕРЁД)}»"),
                ("одна клавиша на двоих", """{"версия": 1, "управление": {"клавиши": {"вперёд": "E", "действие": "E"}}}""", true,
                    н => н.Клавиша(Клавиши.ВПЕРЁД) == "E" && н.Клавиша(Клавиши.ДЕЙСТВИЕ) == ""
                         && Двойные(н).Count == 0 ? null : $"клавиши {Клавишами(н)}"),
                ("Esc на карте", """{"версия": 1, "управление": {"клавиши": {"карта": "Escape"}}}""", true,
                    н => н.Клавиша(Клавиши.КАРТА) == "M" ? null : $"карта — «{н.Клавиша(Клавиши.КАРТА)}»"),
                ("цифра на журнале", """{"версия": 1, "управление": {"клавиши": {"журнал": "Kp 5"}}}""", true,
                    н => н.Клавиша(Клавиши.ЖУРНАЛ) == "J" ? null : $"журнал — «{н.Клавиша(Клавиши.ЖУРНАЛ)}»"),
                // действия, которого в файле нет (пришло позже файла), умолчание
                // уже занято выбором игрока: выбор игрока важнее
                ("умолчание занято", """{"версия": 1, "управление": {"клавиши": {"вперёд": "M"}}}""", true,
                    н => н.Клавиша(Клавиши.ВПЕРЁД) == "M" && н.Клавиша(Клавиши.КАРТА) == ""
                         && н.Клавиша(Клавиши.КАРМАН) == "I" && Двойные(н).Count == 0
                         ? null : $"клавиши {Клавишами(н)}"),
                ("без клавиши — выбор", """{"версия": 1, "управление": {"клавиши": {"журнал": ""}}}""", false,
                    н => н.Клавиша(Клавиши.ЖУРНАЛ) == "" ? null : $"журнал получил «{н.Клавиша(Клавиши.ЖУРНАЛ)}»"),
                ("ключ дважды", """{"версия": 1, "версия": 1}""", true,
                    н => н.ВJson() == ПоУмолчанию ? null : "вышло не умолчание"),
            };
            foreach (var (что, файл, замечать, беда) in случаи)
            {
                var замечания = new List<string>();
                Настройки н;
                try
                {
                    н = Настройки.ИзJson(файл, замечания);
                }
                catch (Exception e)
                {
                    плохо.Add($"файл «{что}»: чтение бросило {e.GetType().Name} — игра бы не запустилась");
                    continue;
                }
                if (беда(н) is string б)
                    плохо.Add($"файл «{что}»: {б}");
                if (замечать && замечания.Count == 0)
                    плохо.Add($"файл «{что}»: починено молча");
                if (!замечать && замечания.Count > 0)
                    плохо.Add($"файл «{что}»: лишнее замечание — {замечания[0]}");
                if (Двойные(н).Count > 0)
                    плохо.Add($"файл «{что}»: после чтения у двух действий одна клавиша");
            }
            var спорный = new List<string>();
            Настройки.ИзJson("""{"версия": 1, "управление": {"клавиши": {"вперёд": "E", "действие": "E"}}}""", спорный);
            if (!спорный.Any(з => з.Contains("уже у «вперёд»", StringComparison.Ordinal)))
                плохо.Add($"спор за клавишу не называет, у кого она: {string.Join("; ", спорный)}");
            w($"  сломанный файл: {случаи.Length} случаев, ни один не бросает и не чинится молча; "
              + $"спор за E: {спорный.FirstOrDefault() ?? "—"}");
        }

        // ---- 4. переназначение не теряет клавиш ----
        {
            var н = new Настройки();
            void Ждать(bool вышло, string иначе)
            {
                if (!вышло)
                    плохо.Add($"переназначение: {иначе}");
            }

            var и = н.Назначить(Клавиши.ВПЕРЁД, "Up");
            Ждать(и.принято && и.обмен is null && н.Клавиша(Клавиши.ВПЕРЁД) == "Up",
                  "вперёд на свободную «Up» не встало");
            Ждать(Клавиши.ВСЕ.All(п => н.Клавиша(п.ключ) != "W"), "W осталась за кем-то");

            и = н.Назначить(Клавиши.НАЗАД, "E");
            Ждать(и.принято && и.обмен == Клавиши.ДЕЙСТВИЕ && н.Клавиша(Клавиши.НАЗАД) == "E"
                  && н.Клавиша(Клавиши.ДЕЙСТВИЕ) == "S",
                  $"занятая E не поменялась местами: назад {н.Клавиша(Клавиши.НАЗАД)}, "
                  + $"действие {н.Клавиша(Клавиши.ДЕЙСТВИЕ)}, обмен с {и.обмен ?? "никем"}");

            string до = Клавишами(н);
            foreach (var (кому, что) in new[]
                     {
                         (Клавиши.КАРТА, "Escape"), (Клавиши.ЖУРНАЛ, "5"), (Клавиши.ЖУРНАЛ, "0"),
                         (Клавиши.ЖУРНАЛ, "Kp 5"), (Клавиши.ТЕЛЕФОН, ""), ("прыжок", "F"),
                     })
            {
                и = н.Назначить(кому, что);
                Ждать(!и.принято && и.почему is not null && Клавишами(н) == до,
                      $"«{что}» отдано «{кому}»: {Клавишами(н)}");
            }
            и = н.Назначить(Клавиши.ТЕЛЕФОН, "T");
            Ждать(и.принято && и.обмен is null && Клавишами(н) == до, "своя же клавиша сдвинула чужие");
            и = н.Назначить(Клавиши.ДЕЙСТВИЕ, "ПКМ");
            Ждать(и.принято && н.Клавиша(Клавиши.ДЕЙСТВИЕ) == "ПКМ", "кнопка мыши не встала");

            // цепочка наугад: общей клавиши не появляется, ни одна не теряется
            var кость = new Random(7);
            string[] клавиши = { "W", "A", "S", "D", "E", "Q", "F", "R", "Space", "Tab", "Shift",
                                 "ЛКМ", "ПКМ", "Up", "1", "Escape", "Kp 3" };
            int шагов = 0;
            for (; шагов < 400; шагов++)
            {
                int было = Назначено(н);
                var п = Клавиши.ВСЕ[кость.Next(Клавиши.ВСЕ.Count)];
                н.Назначить(п.ключ, клавиши[кость.Next(клавиши.Length)]);
                if (Двойные(н) is { Count: > 0 } двойные)
                {
                    плохо.Add($"переназначение: после {шагов + 1} шагов {двойные[0]} у двух действий");
                    break;
                }
                if (Назначено(н) < было)
                {
                    плохо.Add($"переназначение: после {шагов + 1} шагов действие потеряло клавишу");
                    break;
                }
            }
            Ждать(Клавиши.ВСЕ.All(п => !Клавиши.Занята(н.Клавиша(п.ключ))),
                  "цепочка отдала Esc или цифру");

            // неизвестную движку клавишу чинит тот, кто знает имена
            var з = new List<string>();
            var ч = Настройки.ИзJson(
                """{"версия": 1, "управление": {"клавиши": {"вперёд": "Щ", "назад": "ПКМ"}}}""", з);
            var ещё = ч.Починить(к => к == "Space" || (к.Length == 1 && к[0] is >= 'A' and <= 'Z'));
            Ждать(ч.Клавиша(Клавиши.ВПЕРЁД) == "W" && ещё.Count == 1,
                  $"незнакомая движку «Щ» осталась: вперёд «{ч.Клавиша(Клавиши.ВПЕРЁД)}», замечаний {ещё.Count}");
            Ждать(ч.Клавиша(Клавиши.НАЗАД) == "ПКМ", "кнопку мыши судили как клавишу");
            w($"  переназначение: занятая меняется местами, Esc и цифры не отдаются; "
              + $"{шагов} шагов наугад без общей клавиши: {Клавишами(н)}");
        }

        // ---- 5. разрешения ----
        {
            var стол = new Размер(1920, 1040);           // экран 1920×1080 без панели задач
            var окна = Разрешения.Для_окна(стол);
            foreach (var р in окна)
                if (р.ширина + Разрешения.РАМКА_ШИРИНА > стол.ширина
                    || р.высота + Разрешения.РАМКА_ВЫСОТА > стол.высота)
                    плохо.Add($"окно {р} с рамкой не помещается на стол {стол}");
            if (!окна.Contains(Настройки.ОКНО))
                плохо.Add($"окна по умолчанию {Настройки.ОКНО} нет в списке");
            if (!окна.Contains(new Размер(1600, 900)))
                плохо.Add("1600×900 помещается на стол, а в списке его нет");
            if (окна[Разрешения.Ближайший(окна, Настройки.ОКНО)] != Настройки.ОКНО)
                плохо.Add("ближайшим к окну по умолчанию выбрано другое");
            if (окна[Разрешения.Ближайший(окна, new Размер(3840, 2160))] != окна[^1])
                плохо.Add("к слишком большому окну выбрано не самое большое из влезающих");

            // На столе 1920×1040 рамка ничего не решает: ни один обычный размер
            // не попадает между 1000 и 1040 по высоте. Решает она без панели
            // задач: окно во весь экран там уже не окно — заголовок за краем
            var без_панели = Разрешения.Для_окна(new Размер(1920, 1080));
            if (без_панели.Contains(new Размер(1920, 1080)) || без_панели.Contains(new Размер(1680, 1050)))
                плохо.Add("на столе 1920×1080 предложено окно, чей заголовок уйдёт за край: "
                          + string.Join(", ", без_панели));

            var крошка = new Размер(800, 560);
            var малые = Разрешения.Для_окна(крошка);
            if (малые.Count == 0 || малые.Any(р => р.ширина + Разрешения.РАМКА_ШИРИНА > крошка.ширина
                                                  || р.высота + Разрешения.РАМКА_ВЫСОТА > крошка.высота))
                плохо.Add($"на столе {крошка} окну некуда встать: {string.Join(", ", малые)}");

            var экран = new Размер(1920, 1080);
            var картинки = Разрешения.Для_экрана(экран);
            if (картинки.Count != Разрешения.ДОЛИ.Count || картинки[0] != экран)
                плохо.Add($"на весь экран первым должен идти сам экран: {string.Join(", ", картинки)}");
            foreach (var р in картинки)
            {
                if (р.ширина % 2 != 0 || р.высота % 2 != 0)
                    плохо.Add($"картинка {р} с нечётной стороной");
                if (Math.Abs((double)р.ширина / р.высота - 16.0 / 9.0) > 0.01)
                    плохо.Add($"картинка {р} не 16:9, как экран");
            }
            if (!картинки.Contains(new Размер(1280, 720)) || !картинки.Contains(new Размер(960, 540)))
                плохо.Add($"на весь экран нет 1280×720 и 960×540: {string.Join(", ", картинки)}");
            for (int i = 1; i < Разрешения.ДОЛИ.Count; i++)
                if (Разрешения.ДОЛИ[i] >= Разрешения.ДОЛИ[i - 1] || Разрешения.ДОЛИ[i] < Настройки.ЧЁТКОСТЬ_ОТ)
                    плохо.Add($"доли экрана не убывают до предела: {string.Join(", ", Разрешения.ДОЛИ)}");
            if (Разрешения.ДОЛИ[Разрешения.Ближайшая_доля(0.74)] != 0.75)
                плохо.Add("ближайшей к 0.74 выбрана не 0.75");
            w($"  разрешения: окно на столе {стол} — {окна.Count} размеров, от {окна[0]} до {окна[^1]}; "
              + $"на весь экран — {string.Join(", ", картинки)}");
        }

        // ---- 6. громкость ----
        {
            if (Math.Abs(Громкость.Децибелы(1.0)) > 1e-9)
                плохо.Add($"полная громкость — {Громкость.Децибелы(1.0)} дБ, а не ноль");
            if (Math.Abs(Громкость.Децибелы(0.5) + 6.0206) > 0.001)
                плохо.Add($"половина громкости — {Громкость.Децибелы(0.5)} дБ, а не минус шесть");
            if (Громкость.Децибелы(0.0) != Громкость.ТИШИНА_ДБ)
                плохо.Add("ноль громкости — не тишина");
            if (Громкость.Децибелы(2.0) > 0)
                плохо.Add("громкость выше записи");
            double прежде = Громкость.ТИШИНА_ДБ;
            for (int i = 1; i <= 100; i++)
            {
                double д = Громкость.Децибелы(i / 100.0);
                if (д < прежде)
                {
                    плохо.Add($"громкость не растёт: {i}% тише, чем {i - 1}%");
                    break;
                }
                прежде = д;
            }
            if (Громкость.ВСЕ.Select(к => к.ключ).Distinct(StringComparer.Ordinal).Count() != Громкость.ВСЕ.Count)
                плохо.Add("у двух каналов один ключ");
            w($"  громкость: 100% — 0 дБ, 50% — {Текст.Ф(Громкость.Децибелы(0.5), 2)} дБ, "
              + $"2/3 — {Текст.Ф(Громкость.Децибелы(2.0 / 3.0), 2)} дБ, 0% — тишина");
        }

        // ---- 7. игра слушает настройки ----
        {
            string годот = Path.Combine(Пути.Корень, "Дом.Годот");
            var файлы = Directory.EnumerateFiles(годот, "*.cs", SearchOption.TopDirectoryOnly)
                                 .OrderBy(ф => ф, StringComparer.Ordinal)
                                 .ToDictionary(ф => Path.GetFileName(ф), File.ReadAllLines);
            var разрезано = файлы.ToDictionary(
                ф => ф.Key, ф => ф.Value.Select(Разрезать).ToArray());

            // а) каждое действие кто-то спрашивает
            var действия = Константы(typeof(Клавиши));
            int спрошено = 0;
            foreach (var п in Клавиши.ВСЕ)
            {
                if (!действия.TryGetValue(п.ключ, out var имя))
                {
                    плохо.Add($"у действия «{п.ключ}» нет имени в Клавиши");
                    continue;
                }
                var вопрос = new Regex($@"(Нажато|Зажато)\([^)]*\bКлавиши\.{имя}\b");
                if (разрезано.Values.Any(строки => строки.Any(с => вопрос.IsMatch(с.код))))
                    спрошено++;
                else
                    плохо.Add($"«{п.подпись}» есть в настройках, но игра его не спрашивает "
                              + $"(Нажато или Зажато с Клавиши.{имя})");
            }

            // б) буквы мимо настроек; в) подсказки буквой
            var буква = new Regex(@"\bKey\.([A-Z]|Space)\b");
            var литерал = new Regex(@"""(?:[^""\\]|\\.)*""");
            var названа = new Regex(@"\[(?:[A-Z]|Space)\]|\((?:[A-Z]|Space)\)");
            int пометок = 0;
            foreach (var (имя_файла, строки) in разрезано)
                for (int i = 0; i < строки.Length; i++)
                {
                    var (код, заметка) = строки[i];
                    if (буква.IsMatch(код))
                    {
                        if (заметка.Contains("клавиша:", StringComparison.Ordinal))
                            пометок++;
                        else
                            плохо.Add($"{имя_файла}:{i + 1}: клавиша зашита мимо настроек — "
                                      + файлы[имя_файла][i].Trim());
                    }
                    foreach (Match л in литерал.Matches(код))
                        if (названа.IsMatch(л.Value)
                            || л.Value.Contains("пробел", StringComparison.OrdinalIgnoreCase))
                            плохо.Add($"{имя_файла}:{i + 1}: подсказка называет клавишу словом — "
                                      + $"после переназначения соврёт: {л.Value}");
                }

            // г) у каждого канала громкости своя шина
            string звуки = string.Join("\n", разрезано["Звуки.cs"].Select(с => с.код));
            var каналы = Константы(typeof(Громкость));
            foreach (var к in Громкость.ВСЕ)
                if (!каналы.TryGetValue(к.ключ, out var имя)
                    || !звуки.Contains($"Громкость.{имя} =>", StringComparison.Ordinal))
                    плохо.Add($"у канала «{к.подпись}» нет шины в Звуки.cs");

            w($"  игра слушает: спрошено {спрошено} действий из {Клавиши.ВСЕ.Count}, "
              + $"букв с пометкой «клавиша:» — {пометок}, у {Громкость.ВСЕ.Count} каналов свои шины; "
              + $"файлов {файлы.Count}");
        }

        return плохо;
    }

    /// <summary>Строковые константы типа: значение → имя поля.</summary>
    private static Dictionary<string, string> Константы(Type тип)
        => тип.GetFields(BindingFlags.Public | BindingFlags.Static)
              .Where(f => f.IsLiteral && f.FieldType == typeof(string))
              .ToDictionary(f => (string)f.GetRawConstantValue()!, f => f.Name, StringComparer.Ordinal);

    /// <summary>
    /// Код и комментарий строки порознь. Комментарий начинается с двух
    /// косых вне строки и вне символа: `"res://звуки"` — это путь, а не
    /// комментарий, и резать по первым двум косым значило бы потерять
    /// половину строки кода.
    /// </summary>
    private static (string код, string заметка) Разрезать(string с)
    {
        bool в_строке = false;
        for (int i = 0; i < с.Length; i++)
        {
            char ч = с[i];
            if (в_строке)
            {
                if (ч == '\\')
                    i++;
                else if (ч == '"')
                    в_строке = false;
            }
            else if (ч == '"')
                в_строке = true;
            else if (ч == '\'')
            {
                int конец = с.IndexOf('\'', i + (i + 1 < с.Length && с[i + 1] == '\\' ? 3 : 2));
                if (конец > 0)
                    i = конец;
            }
            else if (ч == '/' && i + 1 < с.Length && с[i + 1] == '/')
                return (с[..i], с[i..]);
        }
        return (с, "");
    }
