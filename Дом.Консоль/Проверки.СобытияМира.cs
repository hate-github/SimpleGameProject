// Проверка летописи мира (`Дом.Ядро/Петля/Летопись.cs`, `data/мир.json`,
// задание автора, п. 9): события, привязанные к дню.
//
//  1. **Мир на день — свёртка событий.** Место таково, каким его сделало
//     последнее случившееся к этому утру событие; раньше своего дня
//     не случается ничего, и «сегодня» — ровно события этого дня.
//  2. **Один мир — одна история.** Две летописи и два вызова дают одно
//     и то же; шанс события бросается своим генератором от зерна и имени
//     (FNV-1a — не `GetHashCode`, который в .NET свой в каждом процессе),
//     и доля случившихся близка к шансу.
//  3. **Цепочка.** Сгореть может только то, что горело: «после» держится
//     на всех зёрнах и во все дни.
//  4. **Данные закрыты.** Место, которого нет, событие дважды, последствие,
//     которого некому применить, шанс мимо единицы, «после» того, чего
//     нет, — ошибка чтения, а не молчаливая строка.
//  5. **У каждого горящего места есть узел.** Соседний подъезд — группа
//     `секцияN` в `локация.tscn`, далёкое здание — гнездо `здание_<имя>`.
//     Место без узла горело бы в данных и нигде на экране. «Город» (все
//     дороги разом, для снегопада) — не здание, узла ему не нужно.

using System.Text;
using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> СобытияМира_(Action<string> w)
    {
        var плохо = new List<string>();
        var л = Летопись.Прочитать(Пути.Данные);
        const long ЗЕРНО = 42;

        // ---- 1. мир на день — свёртка ----
        var строки = new List<string>();
        int последний = л.события.Select(э => э.день).DefaultIfEmpty(1).Max() + 1;
        for (int день = 1; день <= последний; день++)
        {
            var с = л.На(день, ЗЕРНО);
            if (с.день != день)
                плохо.Add($"мир на день {день} говорит, что он на день {с.день}");
            foreach (var э in с.случились)
                if (э.день > день)
                    плохо.Add($"день {день}: «{э.id}» случилось раньше своего дня ({э.день})");
            foreach (var место in л.места.Keys)
            {
                var последнее = л.события
                    .Select((э, i) => (э, i))
                    .Where(x => x.э.место == место && x.э.день <= день && x.э.здание is not null
                                && л.Случится(x.э, ЗЕРНО))
                    .OrderBy(x => x.э.день).ThenBy(x => x.i)
                    .Select(x => x.э).LastOrDefault();
                var надо = последнее?.здание ?? Здание.ЦЕЛО;
                if (с.Здание(место) != надо)
                    плохо.Add($"день {день}: {место} — {с.Здание(место)}, а по событиям {надо}");
            }
            var сегодня = с.Сегодня.Select(э => э.id).ToList();
            var надо_сегодня = л.события.Where(э => э.день == день && л.Случится(э, ЗЕРНО))
                                .Select(э => э.id).ToList();
            if (!сегодня.SequenceEqual(надо_сегодня))
                плохо.Add($"день {день}: «сегодня» — [{string.Join(", ", сегодня)}], "
                          + $"а случилось [{string.Join(", ", надо_сегодня)}]");
            if (сегодня.Count > 0)
                строки.Add($"{день}: " + string.Join(", ", с.Сегодня.Select(
                    э => $"{э.место} {э.здание?.ToString().ToLowerInvariant()}")));
        }
        if (л.На(1, ЗЕРНО).здания.Values.Any(з => з != Здание.ЦЕЛО)
            && !л.события.Any(э => э.день <= 1))
            плохо.Add("в первый день мир уже не целый, хотя событий на него нет");

        // ---- 2. один мир — одна история ----
        var л2 = Летопись.Прочитать(Пути.Данные);
        for (int день = 1; день <= последний; день++)
            for (long зерно = 1; зерно <= 30; зерно++)
            {
                var а = л.На(день, зерно);
                var б = л2.На(день, зерно);
                if (!а.случились.Select(э => э.id).SequenceEqual(б.случились.Select(э => э.id)))
                {
                    плохо.Add($"день {день}, зерно {зерно}: две летописи рассказали разное");
                    goto дальше;
                }
            }
        дальше:
        string шанс_итог = "шансовых событий нет";
        foreach (var э in л.события.Where(э => э.шанс < 1.0 && э.шанс > 0.0 && э.после is null))
        {
            int было = 0;
            const int ЗЁРЕН = 400;
            for (long зерно = 1; зерно <= ЗЁРЕН; зерно++)
            {
                bool да = л.Случится(э, зерно);
                if (да)
                    было++;
                if (да != new Rng(Fnv(зерно, э.id)).Chance(э.шанс))
                {
                    плохо.Add($"«{э.id}» на зерне {зерно}: бросок не от зерна и имени — "
                              + "в другом запуске мир горел бы иначе");
                    break;
                }
            }
            double доля = было / (double)ЗЁРЕН;
            if (Math.Abs(доля - э.шанс) > 0.08)
                плохо.Add($"«{э.id}» с шансом {Текст.G(э.шанс)} случилось на {Текст.Ф(доля, 2)} зёрен");
            шанс_итог = $"«{э.id}» (шанс {Текст.G(э.шанс)}) случилось на {было} из {ЗЁРЕН} зёрен";
        }

        // ---- 3. цепочка ----
        int цепочек = 0;
        foreach (var э in л.события.Where(э => э.после is not null))
        {
            цепочек++;
            for (long зерно = 1; зерно <= 200; зерно++)
            {
                var то = л.события.First(x => x.id == э.после);
                if (л.Случится(э, зерно) && !л.Случится(то, зерно))
                {
                    плохо.Add($"«{э.id}» случилось на зерне {зерно}, а «{то.id}», после которого "
                              + "оно идёт, — нет");
                    break;
                }
            }
        }

        // ---- 4. данные закрыты ----
        string исходник = File.ReadAllText(Path.Combine(Пути.Данные, "мир.json"));
        var порчи = new (string что, string было, string стало)[]
        {
            ("место, которого нет", "\"место\": \"котельная\",    \"вид\": \"пожар\",      \"последствия\": { \"здание\": \"горит\" } }",
                                    "\"место\": \"баня\",    \"вид\": \"пожар\",      \"последствия\": { \"здание\": \"горит\" } }"),
            ("событие дважды", "\"id\": \"котельная_сгорела\"", "\"id\": \"котельная_горит\""),
            ("последствие некому применить", "\"последствия\": { \"здание\": \"горит\" }, \"шанс\": 0.7",
                                              "\"последствия\": { \"жилец\": \"исчез\" }, \"шанс\": 0.7"),
            ("шанс мимо единицы", "\"шанс\": 0.7", "\"шанс\": 1.7"),
            ("после того, чего нет", "\"после\": \"котельная_горит\"", "\"после\": \"котельная_тлеет\""),
            ("вида нет", "\"вид\": \"разрушение\"", "\"вид\": \"землетрясение\""),
            ("здание так не бывает", "\"здание\": \"разрушено\"", "\"здание\": \"оплавлено\""),
        };
        var папка = Path.Combine(Path.GetTempPath(), "дом_мир_" + Environment.ProcessId);
        Directory.CreateDirectory(папка);
        int поймано = 0;
        try
        {
            foreach (var (что, было, стало) in порчи)
            {
                if (!исходник.Contains(было, StringComparison.Ordinal))
                {
                    плохо.Add($"порча данных «{что}» не нашла, что портить — образец устарел");
                    continue;
                }
                File.WriteAllText(Path.Combine(папка, "мир.json"),
                                  исходник.Replace(было, стало), new UTF8Encoding(false));
                try
                {
                    Летопись.Прочитать(папка);
                    плохо.Add($"мир.json с ошибкой «{что}» прочитался молча");
                }
                catch (InvalidDataException)
                {
                    поймано++;
                }
            }
        }
        finally
        {
            Directory.Delete(папка, true);
        }

        // ---- 5. у каждого места есть узел ----
        string сцена = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "локация.tscn"));
        // узел нужен тому месту, которое видно: у которого событие меняет
        // здание. «Город» — все дороги разом — не здание, узла у него нет
        foreach (var место in л.события.Where(э => э.здание is not null).Select(э => э.место).Distinct())
        {
            string узел = место.StartsWith("секция", StringComparison.Ordinal)
                ? $"[node name=\"{место}\" type=\"Node3D\""
                : $"[node name=\"здание_{место}\" type=\"Marker3D\"";
            if (!сцена.Contains(узел, StringComparison.Ordinal))
                плохо.Add($"место «{место}» есть в мир.json, а в локация.tscn нет узла {узел}]");
        }

        w($"  летопись: {л.места.Count} мест, {л.события.Count} событий, цепочек {цепочек}");
        w($"  зерно {ЗЕРНО}: " + string.Join("; ", строки));
        w($"  шанс: {шанс_итог}");
        w($"  данные: {поймано} ошибок из {порчи.Length} пойманы при чтении; у всех мест есть узел в сцене");
        return плохо;
    }

    /// <summary>FNV-1a по зерну и имени — независимо от летописи: так
    /// проверка видит, что бросок заведён от них, а не от чего-то
    /// процессного.</summary>
    private static long Fnv(long зерно, string id)
    {
        ulong h = 14695981039346656037UL;
        foreach (byte b in BitConverter.GetBytes(зерно).Concat(Encoding.UTF8.GetBytes(id)))
        {
            h ^= b;
            h *= 1099511628211UL;
        }
        return (long)(h & 0x7fffffffffffffffUL);
    }
}
