// Проверка бункера (ГДД 20, 22; `Дом.Ядро/Петля/Бункер.cs`, `data/мир.json`,
// «бункер»; замок «гермодверь» в `data/инструменты.json`).
//
//  1. **Гермодверь.** Монтировкой на штурвал открывают чаще, чем руками;
//     руками — всякий раз в кровь; открыта — открыта.
//  2. **Тепло и запас.** Под землёй ровные градусы, а сосед греется, как
//     грелся; выложенное из ноши лежит в запасе, ест он той же порцией,
//     что дома; поднялся — греется снова дома.
//  3. **Ходки под наблюдением.** С полной тарой замечают с шансом из данных,
//     с пустыми руками — никогда; заметивший не раз знает, где бункер,
//     и думает, что у героя есть что носить. Кто знает вход, идёт туда
//     с ночёвкой: хватает дороги в один конец, а не туда и обратно.
//  4. **Ночь.** Под землёй — ночь засчитана, без вентиляции она стоит
//     здоровья; героя нет — выследивший уносит долю запаса к себе в шкаф,
//     и герой видит пропажу; героя там — не уносят.
//  5. **Живой игрой**: две недели под землёй с запасом, печкой и
//     вентиляцией — жив, ночей четырнадцать, дни одинокие, концовка
//     «Одиночка»; без вентиляции — здоровья меньше; без печки — холод
//     (первая версия, плюс шесть без печки, умирала на тринадцатый день —
//     бункер без тепла не убежище); девять ночей — ещё не одиночка.
//  6. **Сохранение**: жизнь под землёй, прерванная и продолженная,
//     догоняет непрерывную — дом, бункер, ночные гости.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Бункер_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        const string КТО = "оксана";
        if (л.убежище is not { } д)
        {
            плохо.Add("в мир.json у бункера нет того, что внутри");
            return плохо;
        }
        if (каталог.все["монтировка"].Берёт(д.замок) is null)
            плохо.Add($"монтировка не берёт «{д.замок}» — гермодверь открывается только руками");
        (House h, NPC я, Бункер б) Жизнь(long зерно = 7, int дней = 1)
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: дней,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, КТО);
            return (прогон.h, прогон.h.people[КТО], Округа.У(прогон.h)!.бункер!);
        }

        // ---- 1. гермодверь ----
        string дверь_итог;
        {
            int монтировкой = 0, руками = 0, кровь = 0;
            const int РАЗ = 200;
            for (long зерно = 1; зерно <= РАЗ; зерно++)
            {
                var (h1, я1, б1) = Жизнь(зерно);
                я1.снаряжение!.Подобрать("монтировка", каталог);
                if (б1.Чем_открыть(я1, каталог) != "монтировка")
                {
                    плохо.Add("монтировка при себе — а открывать предлагают руками");
                    break;
                }
                if (б1.Открыть(h1, я1, "монтировка", каталог, ручки).открыл)
                    монтировкой++;
                var (h2, я2, б2) = Жизнь(зерно);
                double здоровье = я2.health;
                if (б2.Открыть(h2, я2, б2.Чем_открыть(я2, каталог), каталог, ручки).открыл)
                    руками++;
                if (я2.health < здоровье - 1e-9)
                    кровь++;
            }
            if (монтировкой <= руками * 2)
                плохо.Add($"монтировкой открывают {монтировкой} раз из {РАЗ}, руками {руками} — инструмент почти не помогает");
            if (Math.Abs(руками / (double)РАЗ - д.руками_шанс) > 0.07)
                плохо.Add($"руками открыли {руками} раз из {РАЗ} — а шанс {Текст.G(д.руками_шанс)}");
            if (кровь != РАЗ)
                плохо.Add($"руками крутили {РАЗ} раз, а ладони содрали {кровь}");
            var (h3, я3, б3) = Жизнь(4);
            for (int i = 0; i < 60 && !б3.открыт; i++)
                б3.Открыть(h3, я3, null, каталог, ручки);
            if (!б3.открыт || !б3.Открыть(h3, я3, null, каталог, ручки).открыл)
                плохо.Add("открытая гермодверь не осталась открытой");
            дверь_итог = $"из {РАЗ} попыток: монтировкой {монтировкой}, руками {руками} (в кровь — {кровь})";
        }

        // ---- 2. тепло и запас ----
        string запас_итог;
        {
            var (h, я, б) = Жизнь(5);
            var сосед = h.others(я).First();
            double соседу = h.room_temp(сосед), дома = h.room_temp(я);
            if (б.Поесть(h, я, "еда"))
                плохо.Add("поел из запаса за закрытой гермодверью");
            б.Спустился(я);
            if (Math.Abs(h.room_temp(я) - д.градусов) > 1e-9)
                плохо.Add($"под землёй {Текст.G(h.room_temp(я))}° — а должно быть {Текст.G(д.градусов)}°");
            if (Math.Abs(h.room_temp(сосед) - соседу) > 1e-9)
                плохо.Add("герой под землёй — а у соседа поменялась комната");
            for (int i = 0; i < 60 && !б.открыт; i++)
                б.Открыть(h, я, null, каталог, ручки);
            я.ноша = new Ноша();
            var сумка = Словари.Числа();
            сумка["еда"] = 4;
            сумка["топливо"] = 2;
            я.ноша.Положить(Тара.СУМКА, сумка, ручки);
            double еды = б.В_запасе("еда");
            var выложил = б.Выложить(я);
            if (!я.ноша.пусто || Math.Abs(б.В_запасе("еда") - еды - 4) > 1e-9 || б.В_запасе("топливо") < 2 - 1e-9
                || выложил.Взять("еда", 0.0) < 4 - 1e-9)
                плохо.Add("выложенное из сумки не легло в запас бункера");
            я.satiety = 20;
            double порция = Действия.порция(h, я, h.B);
            б.Поесть(h, я, "еда");
            if (Math.Abs(я.satiety - Math.Min(100, 20 + порция)) > 1e-6 || Math.Abs(б.В_запасе("еда") - еды - 3) > 1e-9)
                плохо.Add($"поел из запаса: сытость {Текст.G(я.satiety)}, а дома порция дала бы {Текст.G(20 + порция)}");
            double взял = б.Взять(я, "вода", 2, ручки);
            if (взял < 2 - 1e-9 || я.ноша.Сколько("вода") < 2 - 1e-9)
                плохо.Add("из запаса не взять воды в тару");
            б.Поднялся(я);
            if (я.приют is not null || Math.Abs(h.room_temp(я) - дома) > 1e-9)
                плохо.Add("поднялся наверх — а греется всё ещё под землёй");
            запас_итог = $"под землёй {Текст.G(д.градусов)}° (дома {Текст.G(Текст.Округлить(дома, 1))}°); "
                         + $"НЗ: {string.Join(", ", д.запас.OrderBy(п => п.Key, StringComparer.Ordinal).Select(п => $"{п.Key} {Текст.G(п.Value)}"))}";
        }

        // ---- 3. ходки под наблюдением ----
        string ходки_итог;
        {
            var (h, я, б) = Жизнь(11);
            var пустые = б.Ходка(h, я);
            if (пустые.Count > 0)
                плохо.Add("с пустыми руками ушёл к бункеру — а его заметили");
            int ходок = 0, замечено = 0, дома_было = 0;
            я.ноша = new Ноша();
            var сумка = Словари.Числа();
            сумка["еда"] = 3;
            я.ноша.Положить(Тара.СУМКА, сумка, ручки);
            for (int i = 0; i < 40; i++)
            {
                дома_было += h.others(я).Count(p => p.здесь() && !p.away);
                замечено += б.Ходка(h, я).Count;
                ходок++;
            }
            double доля = замечено / (double)Math.Max(1, дома_было);
            if (Math.Abs(доля - д.заметят) > 0.06)
                плохо.Add($"ходки замечают в доле {Текст.G(Текст.Округлить(доля, 3))} — а шанс {Текст.G(д.заметят)}");
            if (б.знают.Count == 0)
                плохо.Add($"за {ходок} ходок никто не выследил бункер");
            var выследил = б.знают.Count > 0 ? h.people[б.знают.OrderBy(x => x, StringComparer.Ordinal).First()] : null;
            if (выследил is not null && выследил.believed(я.id, "еда") <= я.stock.Взять("еда", 0.0) - 1e-9)
                плохо.Add($"{выследил.id} видел, как носили еду, — а думает, что у героя её не больше, чем было");
            // дорога с ночёвкой: знаешь вход — хватит дойти, не знаешь — обернуться
            var о = Округа.У(h)!;
            var поход = о.летопись.походы.First(п => п.вид == "бункер");
            о.Узнал("бункер_район");
            double в_один = о.Часы_дороги(h, я, поход);
            я.time_left = в_один * 1.5 + о.летопись.бункер.часов;
            bool искать_нельзя = о.Нельзя(h, я, поход, о.летопись.бункер.часов) is not null;
            о.Узнал("бункер_вход");
            я.time_left = в_один * 1.5;
            string? с_ночёвкой = о.Нельзя(h, я, поход, 0.0);
            if (!искать_нельзя || с_ночёвкой is not null)
                плохо.Add($"к бункеру с ночёвкой: искать — {(искать_нельзя ? "нельзя" : "можно")} (а надо обернуться), "
                          + $"знаешь вход — {с_ночёвкой ?? "можно"}");
            ходки_итог = $"{ходок} ходок с сумкой: замечено {замечено} раз из {дома_было} окон ({Текст.G(Текст.Округлить(доля, 2))}), "
                         + $"выследили бункер {б.знают.Count}; знаешь вход — идут с ночёвкой";
        }

        // ---- 4. ночь: духота и ночные гости ----
        string ночь_итог;
        {
            var (h, я, б) = Жизнь(13);
            б.Спустился(я);
            double здоровье = я.health;
            б.Конец_дня(h, я);
            if (я.health > здоровье - д.духота_урон + 1e-9 || б.Весть() is null || б.ночей != 1)
                плохо.Add("ночь под землёй без вентиляции не стоила здоровья (или о ней не сказано)");
            здоровье = я.health;
            б.Вентилировать(h.day);
            б.Конец_дня(h, я);
            if (я.health < здоровье - 1e-9 || б.ночей != 2)
                плохо.Add("ночь под землёй с вентиляцией стоила здоровья");

            // выследил — уносит, пока героя нет; героя там — не уносит
            var (h2, я2, б2) = Жизнь(13);
            я2.ноша = new Ноша();
            var сумка = Словари.Числа();
            сумка["еда"] = 3;
            я2.ноша.Положить(Тара.СУМКА, сумка, ручки);
            for (int i = 0; i < 60 && б2.знают.Count == 0; i++)
                б2.Ходка(h2, я2);
            // никто не выследил — ночных гостей не проверить; это краснота,
            // а не падение: упавшая проверка своего не говорит
            string? вор_id = б2.знают.OrderBy(x => x, StringComparer.Ordinal).FirstOrDefault();
            if (вор_id is null)
            {
                плохо.Add("за шестьдесят ходок бункер не выследил никто — ночных гостей не проверить");
                вор_id = h2.others(я2).First().id;
            }
            var вор = h2.people[вор_id];
            б2.Спустился(я2);
            double было = б2.запас_всего;
            for (int день = 0; день < 20; день++)
            {
                h2.day = день;
                б2.Вентилировать(день);
                б2.Конец_дня(h2, я2);
            }
            if (б2.запас_всего < было - 1e-9)
                плохо.Add("герой ночевал под землёй — а запас унесли у него из-под носа");
            б2.Поднялся(я2);
            var у_вора = h2.people.Значения.ToDictionary(p => p.id, p => (Словарь<string, double>)Словари.Числа(), StringComparer.Ordinal);
            foreach (var p in h2.people.Значения)
                foreach (var р in p.stock.Ключи)
                    у_вора[p.id][р] = p.stock.Взять(р, 0.0);
            int ночей_до = 0;
            for (int день = 20; день < 40 && б2.запас_всего >= было - 1e-9; день++, ночей_до++)
            {
                h2.day = день;
                б2.Конец_дня(h2, я2);
            }
            var пропало = б2.Пропажи();
            if (б2.запас_всего >= было - 1e-9)
                плохо.Add($"{вор_id} выследил бункер, а за двадцать ночей без героя не унёс ничего");
            else if (пропало.Ключи.Count == 0)
                плохо.Add("запас унесли — а герой пропажи не увидит");
            else
            {
                // всё унесённое — у кого-то из выследивших в шкафу, и ровно столько
                foreach (var р in пропало.Ключи)
                {
                    double прибыло = б2.знают.Sum(id => h2.people[id].stock.Взять(р, 0.0) - у_вора[id].Взять(р, 0.0));
                    if (Math.Abs(прибыло - пропало[р]) > 1e-9)
                        плохо.Add($"из бункера унесли {р} {Текст.G(пропало[р])}, а в шкафах выследивших прибыло {Текст.G(прибыло)}");
                }
            }
            if (б2.Пропажи().Ключи.Count > 0)
                плохо.Add("пропажу показали дважды");
            ночь_итог = $"без вентиляции ночь стоит {Текст.G(д.духота_урон)} здоровья; "
                        + $"выследивший ({вор_id}) унёс на {ночей_до + 1}-ю ночь без героя: "
                        + string.Join(", ", пропало.Ключи.OrderBy(к => к, StringComparer.Ordinal)
                                                   .Select(к => $"{к} {Текст.G(пропало[к])}"));
        }

        // ---- 5. живой игрой ----
        var с_вент = Под_землёй_(3, 14, true, true, ручки, каталог, л);
        var без_вент = Под_землёй_(3, 14, false, true, ручки, каталог, л);
        var без_печи = Под_землёй_(3, 14, true, false, ручки, каталог, л);
        if (с_вент.умер is not null)
            плохо.Add($"две недели под землёй с запасом и вентиляцией — умер на {с_вент.умер}-й день ({с_вент.от})");
        if (с_вент.ночей != 14)
            плохо.Add($"две недели под землёй — а ночей насчитано {с_вент.ночей}");
        if (с_вент.концовка != Концовка.ОДИНОЧКА && с_вент.умер is null)
            плохо.Add($"пересидел две недели в бункере — а концовка «{с_вент.концовка}»");
        if (с_вент.одиноких < 12)
            плохо.Add($"две недели под землёй — а одиноких дней в дневнике {с_вент.одиноких}");
        if (без_вент.здоровье >= с_вент.здоровье - 1e-9)
            плохо.Add($"без вентиляции здоровья не меньше ({Текст.G(без_вент.здоровье)} против {Текст.G(с_вент.здоровье)})");
        if (без_печи.умер is null && без_печи.тепло >= с_вент.тепло - 1e-9)
            плохо.Add($"без печки под землёй не холоднее (тепло {Текст.G(без_печи.тепло)} против {Текст.G(с_вент.тепло)})");
        var девять = Под_землёй_(3, 9, true, true, ручки, каталог, л);
        if (девять.концовка == Концовка.ОДИНОЧКА && девять.соседей > 0)
            плохо.Add("девять ночей под землёй — уже «Одиночка», хотя ручка просит больше");
        string живой_итог = $"две недели с вентиляцией — {(с_вент.умер is null ? "жив" : $"умер на {с_вент.умер}-й")}, "
                            + $"здоровье {Текст.G(Текст.Округлить(с_вент.здоровье, 0))}, одиноких дней {с_вент.одиноких}, "
                            + $"концовка «{с_вент.концовка}»; без вентиляции — здоровье {Текст.G(Текст.Округлить(без_вент.здоровье, 0))}; "
                            + $"без печки — {(без_печи.умер is null ? $"жив, тепло {Текст.G(Текст.Округлить(без_печи.тепло, 0))} против {Текст.G(Текст.Округлить(с_вент.тепло, 0))}" : $"умер на {без_печи.умер}-й ({без_печи.от})")}; "
                            + $"девять ночей — «{девять.концовка}»";

        // ---- 6. сохранение с героем под землёй ----
        string сохранение_итог;
        {
            const int ДНЕЙ = 6, ПРЕРВАТЬ = 3;
            // четыре ночи под землёй — и сохраняются под землёй, — потом
            // наверх: ночные гости приходят уже после сохранения. Тот же
            // поступок и у продолженной жизни: поступки игрока в сохранении
            // не живут, их делает игрок заново
            void Наверх_на_четвёртый(Прогон прогон)
                => прогон.h.hooks.on_day.Insert(0, дом =>
                {
                    if (дом.day == 4)
                        Округа.У(дом)!.бункер!.Поднялся(дом.people[КТО]);
                });
            (Прогон прогон, Дом.Ядро.Петля петля) Подготовить()
            {
                var прогон = new Прогон(Пути.Данные, seed: 17, days: ДНЕЙ,
                                        журнал: new Журнал(0, false, TextWriter.Null));
                var петля = new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л);
                петля.Слушать(прогон, КТО);
                var я = прогон.h.people[КТО];
                я.решающий = new Скрипт(new Dictionary<Вопрос, string> { [Вопрос.СОВРАТЬ] = "сказать правду" });
                var б = Округа.У(прогон.h)!.бункер!;
                я.ноша = new Ноша();
                var сумка = Словари.Числа();
                сумка["еда"] = 3;
                я.ноша.Положить(Тара.СУМКА, сумка, ручки);
                for (int i = 0; i < 60 && б.знают.Count == 0; i++)
                    б.Ходка(прогон.h, я);
                for (int i = 0; i < 60 && !б.открыт; i++)
                    б.Открыть(прогон.h, я, null, каталог, ручки);
                б.Выложить(я);
                Наверх_на_четвёртый(прогон);
                б.Спустился(я);
                return (прогон, петля);
            }
            var (подряд, петля_а) = Подготовить();
            подряд.run();
            var (прерванный, петля_б) = Подготовить();
            System.Text.Json.Nodes.JsonObject? сейв = null;
            прерванный.h.hooks.on_day.Add(дом =>
            {
                if (дом.day == ПРЕРВАТЬ)
                    сейв = Дом.Ядро.СохранениеИгры.Сложить(null, КТО, прерванный, петля_б, null, null);
            });
            прерванный.run();
            var продолженный = Дом.Ядро.СохранениеИгры.Прогон_из(сейв!, Пути.Данные, new Журнал(0, false, TextWriter.Null));
            var петля_в = new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л);
            петля_в.Слушать(продолженный, КТО);
            Дом.Ядро.СохранениеИгры.Разложить(сейв!, продолженный, петля_в, null);
            Наверх_на_четвёртый(продолженный);
            продолженный.h.people[КТО].решающий = new Скрипт(new Dictionary<Вопрос, string> { [Вопрос.СОВРАТЬ] = "сказать правду" });
            продолженный.Дальше();
            if (Снимок.Текстом(Снимок.Собранный(подряд.h)) != Снимок.Текстом(Снимок.Собранный(продолженный.h)))
                плохо.Add("жизнь с бункером, продолженная из сохранения, разошлась с непрерывной: дом другой");
            var ба = Округа.У(подряд.h)!.бункер!;
            var бв = Округа.У(продолженный.h)!.бункер!;
            if (ба.Сложить().ToJsonString() != бв.Сложить().ToJsonString())
                плохо.Add("бункер после продолжения другой: запас, ночи, кто знает");
            if (Округа.У(прерванный.h) is not null && сейв!["округа"]!["бункер"]!["внутри"]!.GetValue<bool>() != true)
                плохо.Add("сохранялись, когда герой под землёй, — а в сохранении он наверху");
            сохранение_итог = $"четыре ночи под землёй (сохранились там), потом наверх; прервана на {ПРЕРВАТЬ}-м, "
                              + $"дожита до {продолженный.h.day}-го как непрерывная; в запасе к концу {Текст.G(ба.запас_всего)}";
        }

        w($"  гермодверь: {дверь_итог}");
        w($"  тепло и запас: {запас_итог}");
        w($"  ходки: {ходки_итог}");
        w($"  ночь: {ночь_итог}");
        w($"  живой игрой: {живой_итог}");
        w($"  сохранение: {сохранение_итог}");
        return плохо;
    }

    private sealed record ПодЗемлёй(int? умер, string? от, int ночей, double здоровье, double тепло,
                                    int одиноких, Концовка концовка, int соседей);

    /// <summary>
    /// Живой игрой: Оксана с первого дня под землёй — гермодверь открыта,
    /// в запасе НЗ и принесённое (десять еды, десять воды, восемь топлива), —
    /// и живёт <paramref name="дней"/> дней: дома не бывает (в отлучке), ест
    /// и пьёт из запаса, <paramref name="вентилировать"/> — крутит привод
    /// каждый день, <paramref name="топить"/> — топит буржуйку. Концовка —
    /// как у игры, по итогу жизни.
    /// </summary>
    private static ПодЗемлёй Под_землёй_(long зерно, int дней, bool вентилировать, bool топить,
                                          РучкиПетли ручки, Дом.Ядро.Инструменты каталог, Летопись л)
    {
        const string ГЕРОЙ = "оксана";
        var прогон = new Прогон(Пути.Данные, seed: зерно, days: дней);
        var наследие = new Наследие();
        var петля = new Дом.Ядро.Петля(наследие, ручки, инструменты: каталог, летопись: л);
        петля.Слушать(прогон, ГЕРОЙ);
        var б = Округа.У(прогон.h)!.бункер!;
        var я = прогон.h.people[ГЕРОЙ];
        for (int i = 0; i < 60 && !б.открыт; i++)
            б.Открыть(прогон.h, я, null, каталог, ручки);
        я.health = 100;
        б.Спустился(я);
        // принесённое — ходками в рюкзаке, как у игрока
        foreach (var (что, всего) in new[] { ("еда", 10.0), ("вода", 10.0), ("топливо", 8.0) })
            for (double осталось = всего; осталось > 1e-9;)
            {
                я.ноша = new Ноша();
                var взять = Словари.Числа();
                взять[что] = осталось;
                double влезло = я.ноша.Положить(Тара.РЮКЗАК, взять, ручки).Взять(что, 0.0);
                if (влезло <= 0.0)
                    throw new InvalidOperationException("в рюкзак не влезает ничего — живая игра не та");
                б.Выложить(я);
                осталось -= влезло;
            }
        using var партия = new Партия(прогон, ГЕРОЙ);
        int ел_день = -1;
        партия.Начать();
        var в = партия.Дождаться();
        while (в is not null)
        {
            var h = прогон.h;
            int ответ = 0;
            if (в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
            {
                я.away = true;          // не в подъезде — для дома его нет дома, как в игре
                if (ел_день != в.день)
                {
                    ел_день = в.день;
                    if (вентилировать)
                        б.Вентилировать(h.day);
                    if (топить)
                        б.Затопить(h);
                    if (я.satiety < 70) б.Поесть(h, я, "еда");
                    if (я.hydration < 70) б.Поесть(h, я, "вода");
                }
                ответ = ВопросИгроку.САМ;
                я.time_left -= Math.Min(1.0, я.time_left);
            }
            else
                for (int i = 0; i < в.варианты.Count; i++)
                    if (в.варианты[i].что is "сказать правду")
                        ответ = i;
            партия.Ответить(ответ);
            в = партия.Дождаться();
        }
        партия.Досидеть();
        int одиноких = петля.Сложить_жизнь()["дневник"]!["одиноких"]!.GetValue<int>();
        var р = Концовки.Какая(прогон.h, ГЕРОЙ, наследие, ручки);
        int соседей = прогон.h.others(я).Count(p => p.здесь());
        return new ПодЗемлёй(я.alive ? null : я.died_day, я.alive ? null : я.cause, б.ночей, я.health, я.warmth,
                             одиноких, р.какая, соседей);
    }
