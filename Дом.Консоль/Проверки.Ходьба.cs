// Проверка ходьбы соседей (задание автора, п. 26): кто где в этот час —
// и что движок ведёт фигуры, а не ставит их.
//
//  1. **Кто где — все.** Каждый живой сосед в доме, кроме героя, ровно
//     один раз; дом — дверь того, у кого он живёт; ничем не занят — дома.
//     Видимые — те же, что `В_подъезде`, в том же порядке: расстановка
//     лестницы не сдвинулась.
//  2. **Лестница живёт.** Время идёт само, и на вопросах дня, взятых шагами
//     времени, соседи переходят: приходят от своей двери и с улицы,
//     переходят от двери к двери, уходят домой и на улицу. Каждый такой
//     переход движок проходит ногами, и печатается, сколько их за день.
//  3. **Застали — видно, кто.** Пока поимка разбирается, у героя записано,
//     кто застал и кого позвали: от этой записи бегут к герою.
//  4. **Не телепорт.** Расстановка соседей в движке зовёт путь по сетке
//     навигации и идёт по нему; встать на место сразу можно только когда
//     пути нет (сетка не готова, дойти нельзя).

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Ходьба_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);

        // ---- 1 и 2. кто где, и как это меняется день ----
        string день_итог = "—";
        {
            var прогон = new Прогон(Пути.Данные, seed: 11, days: 2);
            using var партия = new Партия(прогон, "оксана");
            var h = прогон.h;
            var я = партия.сеанс.я;
            var ход = new ХодВремени(ручки);
            партия.Начать();
            var в = партия.Дождаться();
            int день0 = -1, вопросов = 0;
            int от_двери = 0, с_улицы = 0, к_двери = 0, домой = 0, на_улицу = 0;
            Dictionary<string, СоседГде>? было = null;
            while (в is not null)
            {
                if (в.вопрос != Вопрос.ЧТО_ДЕЛАТЬ)
                {
                    партия.Ответить(0);
                    в = партия.Дождаться();
                    continue;
                }
                if (день0 < 0)
                    день0 = в.день;
                if (в.день != день0)
                    break;
                вопросов++;
                var все = Подача.Кто_где(h, я, партия.сеанс.хроника);
                var видны = Подача.В_подъезде(h, я, партия.сеанс.хроника);
                // все — ровно один раз
                var здесь = h.people.Значения.Where(п => п.id != я.id && п.здесь()).Select(п => п.id)
                              .OrderBy(x => x, StringComparer.Ordinal).ToList();
                var есть = все.Select(с => с.id).OrderBy(x => x, StringComparer.Ordinal).ToList();
                if (!здесь.SequenceEqual(есть))
                    плохо.Add($"вопрос {вопросов}: «кто где» — [{string.Join(", ", есть)}], "
                              + $"а в доме [{string.Join(", ", здесь)}]");
                foreach (var с in все)
                    if (h.get(с.id) is { } п && с.дом != h.хозяин_жилья(п).apt)
                        плохо.Add($"вопрос {вопросов}: дом {с.id} — кв.{с.дом}, а живёт он у кв.{h.хозяин_жилья(п).apt}");
                // независимо от «кто где» — прямо по хронике: у чьей двери
                // стоит, куда пришёл, дома ли
                foreach (var с in все)
                {
                    var х = партия.сеанс.хроника.Ход_в(с.id, h.day, я.час());
                    var где = х?.где ?? Где.Дома;
                    if (где != с.где)
                        плохо.Add($"вопрос {вопросов}: {с.id} по хронике {где}, а в «кто где» {с.где}");
                    else if (где == Где.УДвери && х!.квартира != с.квартира)
                        плохо.Add($"вопрос {вопросов}: {с.id} пришёл к кв.{х.квартира}, а стоит у кв.{с.квартира}");
                }
                var из_всех = все.Where(с => с.виден)
                    .Select(с => new ВПодъезде(с.id, с.имя, с.где, с.квартира, с.этаж, с.ключ)).ToList();
                if (!из_всех.SequenceEqual(видны))
                    плохо.Add($"вопрос {вопросов}: видимые из «кто где» разошлись с лестницей");
                // переходы
                if (было is not null)
                    foreach (var с in все)
                    {
                        if (!было.TryGetValue(с.id, out var б))
                            continue;
                        if (!б.виден && с.виден)
                        {
                            if (б.где == Где.ЗаПорогом) с_улицы++;
                            else от_двери++;
                        }
                        else if (б.виден && с.виден && б.квартира != с.квартира)
                            к_двери++;
                        else if (б.виден && !с.виден)
                        {
                            if (с.где == Где.ЗаПорогом) на_улицу++;
                            else домой++;
                        }
                    }
                было = все.ToDictionary(с => с.id, StringComparer.Ordinal);
                // шаг времени: герой стоит, дом живёт
                ход.Кадр(ход.шаг / ход.Скорость(Темп.ОБЫЧНО), Темп.ОБЫЧНО);
                ХодВремени.Прожить(я, ход.Шаг() ?? ход.шаг);
                if (!партия.Пропустить())
                    break;
                в = партия.Дождаться();
            }
            while (в is not null)
            {
                партия.Ответить(0);
                в = партия.Дождаться();
            }
            партия.Досидеть();
            int переходов = от_двери + с_улицы + к_двери + домой + на_улицу;
            if (переходов == 0)
                плохо.Add($"за {вопросов} вопросов дня на лестнице никто никуда не шёл — ходить нечего");
            if (от_двери + с_улицы == 0 || домой + на_улицу == 0)
                плохо.Add($"за день на лестницу приходили {от_двери + с_улицы} раз, уходили {домой + на_улицу} — "
                          + "приход и уход должны быть оба");
            день_итог = $"{вопросов} вопросов дня: пришли от своей двери {от_двери}, с улицы {с_улицы}, "
                        + $"перешли к другой двери {к_двери}, ушли домой {домой}, на улицу {на_улицу}";
        }

        // ---- 3. застали — видно, кто ----
        string поимка_итог = "—";
        {
            var прогон = new Прогон(Пути.Данные, seed: 5, days: 1);
            using var партия = new Партия(прогон, "оксана");
            var h = прогон.h;
            var я = партия.сеанс.я;
            партия.Начать();
            var в = партия.Дождаться();
            while (в is not null && в.вопрос != Вопрос.ЧТО_ДЕЛАТЬ)
            {
                партия.Ответить(0);
                в = партия.Дождаться();
            }
            if (в is null)
                плохо.Add("за день партия ни разу не спросила, что делать");
            else
            {
                var к = h.кладовые.Значения.First(x => x.вид == ВидКладовой.ПОГРЕБ && !h.есть_ключ(я, x));
                var ловец = h.others(я).Where(п => п.здесь() && !п.away).OrderBy(п => п.id, StringComparer.Ordinal).First();
                я.застали = new Застали(ловец.id, к.id, new[] { ловец.id }, h.day);
                партия.Пропустить();
                var поймали = партия.Дождаться();
                bool видно = поймали is not null && поймали.вопрос != Вопрос.ЧТО_ДЕЛАТЬ
                             && я.застали is { } з && з.кто == ловец.id;
                if (поймали is not null && поймали.вопрос != Вопрос.ЧТО_ДЕЛАТЬ && !видно)
                    плохо.Add("героя спрашивают о поимке, а записи, кто застал, уже нет — бежать к герою некому");
                поимка_итог = видно
                    ? $"на вопросе «{поймали!.вопрос}» записано: застал {ловец.@short} — он и бежит"
                    : $"вопроса о поимке не было ({поймали?.вопрос.ToString() ?? "дом кончился"})";
                в = поймали;
            }
            while (в is not null)
            {
                партия.Ответить(0);
                в = партия.Дождаться();
            }
            партия.Досидеть();
        }

        // ---- 4. не телепорт ----
        {
            string мир = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "Мир.cs")).Replace("\r\n", "\n");
            int от = мир.IndexOf("    public void Соседи(", StringComparison.Ordinal);
            int до = от < 0 ? -1 : мир.IndexOf("\n    }\n", от, StringComparison.Ordinal);
            if (от < 0 || до < 0)
                плохо.Add("в Мир.cs не нашлась расстановка соседей — сканер смотрит не туда");
            else
            {
                string соседи = мир[от..до];
                int путей = System.Text.RegularExpressions.Regex.Matches(соседи, @"_навигация\?\.Путь\(").Count;
                int идут = System.Text.RegularExpressions.Regex.Matches(соседи, @"\.Идти\(").Count;
                if (путей < 3 || идут < 3)
                    плохо.Add($"расстановка соседей спрашивает путь {путей} раз и ведёт по нему {идут} — "
                              + "приход, переход и уход должны идти ногами");
                if (соседи.Contains(".Position = где", StringComparison.Ordinal))
                    плохо.Add("расстановка ставит соседа на место (`Position = где`) — телепорт вместо ходьбы");
            }
            string сосед = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "Сосед3D.cs"));
            if (!сосед.Contains("_PhysicsProcess", StringComparison.Ordinal)
                || !сосед.Contains("_путь[_точка]", StringComparison.Ordinal))
                плохо.Add("фигура соседа не идёт по точкам пути — нечем ходить");
            string сетка = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "Навигация.cs"));
            if (!сетка.Contains("NavigationServer3D.MapGetPath", StringComparison.Ordinal))
                плохо.Add("путь считается не навигацией Godot");
        }

        w($"  день: {день_итог}");
        w($"  поимка: {поимка_итог}");
        return плохо;
    }
}
