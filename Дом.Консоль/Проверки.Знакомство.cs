// Проверка знакомства (вопрос автора: «если игровой персонаж не знает, как
// зовут NPC, то как он с ними может пытаться общаться?»;
// `Дом.Ядро/Петля/Знакомство.cs`).
//
//  1. **Новый человек никого не знает.** Герой новой игры видит соседей
//     «сосед из кв.N» / «соседка из кв.N» — и в падежах; себя — по имени.
//     Жилец, за которого играют, знает всех.
//  2. **Лицом к лицу — знакомятся.** Разговор героя с соседом — имя
//     известно; сосед пришёл к герою сам (просьба) — тоже; отнял
//     на лестнице — нет.
//  3. **Экран говорит так же.** План подъезда, «что я знаю о соседях»,
//     кто где на лестнице и окно вопроса — незнакомый без имени,
//     знакомый — по имени.
//  4. **Помнит в петле.** Знакомство — знание округи: переживает сейв
//     и переходит в наследие.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Знакомство_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var профиль = new ПрофильГероя("Андрей");
        var честный = new Скрипт(new Dictionary<Вопрос, string> { [Вопрос.СОВРАТЬ] = "сказать правду" });
        var наследие = new Наследие();
        var прогон = new Прогон(Пути.Данные, seed: 3, days: 3,
                                журнал: new Журнал(0, false, TextWriter.Null),
                                жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
        new Дом.Ядро.Петля(наследие, ручки, инструменты: каталог, летопись: л).Слушать(прогон, Герой.ID);
        var h = прогон.h;
        var я = h.people[Герой.ID];
        я.решающий = честный;
        var чужие = h.others(я).Where(p => p.здесь()).OrderBy(p => p.apt).ToList();

        // ---- 1. новый человек никого не знает ----
        foreach (var с in чужие)
            if (Знакомство.Знает(h, я, с))
                плохо.Add($"новый человек уже знает, как зовут {с.id}");
        var она = чужие.First(p => p.sex == "ж");
        var он = чужие.First(p => p.sex == "м");
        var падежи = new (NPC кто, string падеж, string ждём)[]
        {
            (она, "short", $"соседка из кв.{она.apt}"),
            (она, "acc", $"соседку из кв.{она.apt}"),
            (она, "ins", $"соседкой из кв.{она.apt}"),
            (он, "gen", $"соседа из кв.{он.apt}"),
            (он, "dat", $"соседу из кв.{он.apt}"),
        };
        foreach (var (кто, падеж, ждём) in падежи)
            if (Знакомство.Как_зовут(h, я, кто, падеж) != ждём)
                плохо.Add($"незнакомый {кто.id} ({падеж}): «{Знакомство.Как_зовут(h, я, кто, падеж)}», а надо «{ждём}»");
        if (Знакомство.Как_зовут(h, я, я) != я.@short)
            плохо.Add("себя герой не знает по имени");
        {
            var жилец = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(жилец, "оксана");
            var оксана = жилец.h.people["оксана"];
            if (жилец.h.others(оксана).Any(с => !Знакомство.Знает(жилец.h, оксана, с)))
                плохо.Add("играют за жилицу — а она кого-то в своём доме не знает по имени");
        }

        // ---- 2. лицом к лицу ----
        var собеседник = он;
        var итог_разговора = Действия.execute(h, я, "разговор", собеседник);
        if (итог_разговора == Исход.СДЕЛАНО && !Знакомство.Знает(h, я, собеседник))
            плохо.Add("поговорил с соседом — а как зовут, так и не знает");
        var проситель = чужие.First(p => p.id != собеседник.id && p.sex == "ж");
        var итог_просьбы = Действия.execute(h, проситель, "попросить", я, "еда");
        if (итог_просьбы == Исход.СДЕЛАНО && !Знакомство.Знает(h, я, проситель))
            плохо.Add("соседка пришла к герою просить — а не назвалась");
        var грабитель = чужие.First(p => p.id != собеседник.id && p.id != проситель.id && p.sex == "м");
        я.stock["еда"] = 5;
        Действия.execute(h, грабитель, "отнять", я);
        if (Знакомство.Знает(h, я, грабитель))
            плохо.Add("отняли на лестнице — а грабитель при этом представился");

        // ---- 3. экран ----
        var сеанс = new Сеанс(h, Герой.ID);
        if (чужие.FirstOrDefault(p => !Знакомство.Знает(h, я, p)) is not NPC незнакомый)
        {
            плохо.Add("незнакомых не осталось — экрану не на ком показать «сосед из кв.N»");
            return плохо;
        }
        var план = сеанс.План();
        string Имя_на_плане(NPC p) => план.First(ж => ж.id == p.id).имя;
        if (Имя_на_плане(незнакомый) != Знакомство.Сосед(незнакомый)
            || (Знакомство.Знает(h, я, собеседник) && Имя_на_плане(собеседник) != собеседник.@short)
            || Имя_на_плане(я) != я.@short)
            плохо.Add($"план подъезда: незнакомый «{Имя_на_плане(незнакомый)}», знакомый «{Имя_на_плане(собеседник)}», сам «{Имя_на_плане(я)}»");
        if (сеанс.Знание().FirstOrDefault(с => с.id == незнакомый.id) is { } з && з.имя != Знакомство.Незнакомый(незнакомый))
            плохо.Add($"«что я знаю о соседях»: незнакомый назван «{з.имя}»");
        if (Подача.Кто_где(h, я, сеанс.хроника).FirstOrDefault(с => с.id == незнакомый.id) is { } г
            && г.имя != Знакомство.Незнакомый(незнакомый))
            плохо.Add($"на лестнице незнакомый назван «{г.имя}»");
        var вопрос = new ВопросИгроку(h.day, я.id, Вопрос.ДАТЬ_ИЗ_СВОЕГО, "", new[] { new ВариантИгроку("дать", 1.0, "дать") },
                                      null, null, незнакомый.id, new Суть("просьба", "еда"));
        var сцена = Разговор.Прочитать(h, я, вопрос);
        if (сцена.кто.Contains(незнакомый.@short, StringComparison.Ordinal)
            || сцена.что.Contains(незнакомый.@short, StringComparison.Ordinal))
            плохо.Add($"окно вопроса называет незнакомого по имени: «{сцена.кто}» — «{сцена.что}»");

        // ---- 4. помнит в петле ----
        var о = Округа.У(h)!;
        var сейв = о.Сложить();
        var ещё = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null),
                             жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
        new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(ещё, Герой.ID);
        Округа.У(ещё.h)!.Разложить(System.Text.Json.Nodes.JsonNode.Parse(сейв.ToJsonString())!.AsObject(), ещё.h.people[Герой.ID]);
        if (Знакомство.Знает(h, я, собеседник) && !Знакомство.Знает(ещё.h, ещё.h.people[Герой.ID], ещё.h.people[собеседник.id]))
            плохо.Add("после сейва забылось, кого как зовут");
        if (Знакомство.Знает(h, я, собеседник)
            && !о.Помнит().Contains(Знакомство.ИМЯ + собеседник.id, StringComparer.Ordinal))
            плохо.Add("знакомство не уходит в наследие — в следующей жизни имени не вспомнить");

        int знакомых = h.others(я).Count(с => Знакомство.Знает(h, я, с));
        w($"  новый человек: соседи — «{Знакомство.Как_зовут(h, я, незнакомый)}»; разговор {итог_разговора}, "
          + $"просьба {итог_просьбы}; знаком теперь с {знакомых}: "
          + string.Join(", ", h.others(я).Where(с => Знакомство.Знает(h, я, с)).Select(с => с.@short)));
        w($"  окно вопроса: «{сцена.кто}» — «{сцена.что}»");
        return плохо;
    }
}
