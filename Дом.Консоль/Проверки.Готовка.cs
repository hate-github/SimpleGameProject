// Проверка готовки у своей печи (`Дом.Ядро/Петля/Готовка.cs`, этап 4 плана еды):
//
//  1. **Каталог.** Рецепты есть; блюдо каждого — продукт, его порции — сумма
//     того, что идёт в котёл; блюдо насыщает полной порцией и греет.
//  2. **Печь не топится** — не готовят, и ничего не тронуто.
//  3. **Жарят и варят.** Сырое снимается с полки на долю рецепта, блюдо
//     ложится туда же на те же порции: число еды шкафа прежнее, закон слоя
//     держится; на суп уходит вода из шкафа.
//  4. **Доля.** Картошки на полрецепта — полпорции блюда; меньше четверти —
//     не готовят и говорят, чего мало.
//  5. **Едят.** Блюдо сытнее сырого во столько, во сколько сырое хуже
//     (`сырым`), горячее в день готовки греет, суп ещё и поит.
//  6. **Как сыграно.** У рецептов есть мини-игры (жарят — нарезка и жарка,
//     варят — нарезка и варка). Плохо сыграно — подгорело: блюда меньше
//     на `подгорело_теряется`, число шкафа убыло ровно на столько же, закон
//     слоя цел, настроение упало; на славу — блюдо полное, настроение
//     выросло; как обычно — ни того ни другого.
//  7. **Порог.** Мини-игра есть, пока Смекалка ниже `мини_игра_исчезает`;
//     с порога — нет, а само сготовлено не хуже обычного.
//  8. **Овощи и замена.** Морковь, свёкла, капуста — овощи, сырыми хуже
//     блюда, лежат в погребах и продаются в магазине. Борщ — из пяти овощей,
//     число шкафа прежнее. Картошка с тушёнкой берёт любую тушёнку
//     («свинина|говядина»), без неё говорит «тушёнка»; банку, взятую
//     не целиком, вскрыли — остаток початый.
//  9. **Угощение.** Дом передал соседу порцию от героя, а на полке
//     сегодняшний борщ — ушёл он: соседу тепло (`греет` на долю блюда),
//     настроение и доверие к герою сверх обычной помощи; закон слоя цел,
//     герою есть что сказать. Горячего нет — ничего не меняется. Через
//     исполнителя дома «поделиться» — то же самое.
// 10. **Узел.** Рецепты — кнопками у печи, готовят с полки своей комнаты,
//     мини-игры рецепта по очереди, качество — среднее; полка
//     перерисовывается.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Готовка_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var еда = КаталогЕды.Прочитать(Пути.Данные);
        if (еда is null)
        {
            плохо.Add("нет data/еда.json — готовить не из чего");
            return плохо;
        }

        // ---- 1. каталог ----
        if (еда.рецепты.Count < 2)
            плохо.Add($"рецептов {еда.рецепты.Count} — ждали жареную картошку и суп");
        foreach (var р in еда.рецепты)
        {
            var б = еда[р.блюдо];
            if (Math.Abs(б.сырым - 1.0) > 1e-9)
                плохо.Add($"блюдо «{б.имя}» насыщает не полной порцией ({б.сырым}) — готовить незачем");
            if (б.греет <= 0)
                плохо.Add($"блюдо «{б.имя}» горячим не греет");
            if (!р.из.Any(x => Рецепт.Варианты(x.вид).Any(в => еда[в].сырым < 1.0)))
                плохо.Add($"в рецепте «{б.имя}» нет ничего, что сырым хуже, — блюдо не лучше сырого");
        }
        var жарить = еда.рецепты.FirstOrDefault(р => р.блюдо == "жареная_картошка");
        var суп = еда.рецепты.FirstOrDefault(р => р.блюдо == "суп");
        if (жарить is null || суп is null)
        {
            плохо.Add("нет рецепта жареной картошки или супа — дальше проверять нечем");
            return плохо;
        }

        var прогон = new Прогон(Пути.Данные, seed: 5, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
        new Дом.Ядро.Петля(new Наследие(), ручки, еда: еда).Слушать(прогон, "оксана");
        var h = прогон.h;
        var я = h.people["оксана"];
        var п = Продукты.У(я)!;
        string? Закон()
        {
            foreach (var м in Продукты.МЕСТА)
                if (Math.Abs(п.Сумма(м) - Продукты.Число(я, м)) > 1e-5)
                    return $"{м}: вещей на {Текст.Ф(п.Сумма(м), 3)}, а у дома {Текст.Ф(Продукты.Число(я, м), 3)}";
            return null;
        }
        // полка: только то, что положим сами
        void Очистить()
        {
            foreach (var x in п.В(МестоЕды.ПОЛКА).ToList())
                п.Убрать(x);
            я.stock["еда"] = 0;
        }
        void Положить(string вид)
        {
            var x = п.Новая(вид);
            п.Положить(МестоЕды.ПОЛКА, x);
            я.stock["еда"] = я.stock.Взять("еда", 0.0) + x.единиц;
        }
        double Блюда(string вид) => Util.Sum(п.В(МестоЕды.ПОЛКА).Where(x => x.вид == вид).Select(x => x.единиц));

        // ---- 2. печь не топится ----
        Очистить();
        Положить("картошка");
        я.stock["вода"] = 3;
        var холодно = п.Приготовить(h, я, жарить, топится: false);
        if (холодно.почему_нет is null || холодно.порций > 0 || Math.Abs(п.Свежего("картошка") - 1.0) > 1e-9)
            плохо.Add($"печь не топится — а картошку пожарили: {холодно}");

        // ---- 3. жарят и варят ----
        Положить("картошка");
        Положить("лук");
        double еды_до = я.stock.Взять("еда", 0.0);
        var жарено = п.Приготовить(h, я, жарить, топится: true);
        if (жарено.почему_нет is not null || Math.Abs(жарено.порций - 1.0) > 1e-9 || Math.Abs(Блюда("жареная_картошка") - 1.0) > 1e-9)
            плохо.Add($"на полке две картошки, печь топится — а жарено не на порцию: {жарено}, на полке {Блюда("жареная_картошка")}");
        if (Math.Abs(п.Свежего("картошка") - 1.0) > 1e-9)
            плохо.Add($"после жарки картошки на полке {п.Свежего("картошка")}, ждали одну");
        var сварено = п.Приготовить(h, я, суп, топится: true);
        if (сварено.почему_нет is not null || Math.Abs(сварено.порций - 0.75) > 1e-9 || Math.Abs(я.stock.Взять("вода", 0.0) - 2.0) > 1e-9)
            плохо.Add($"суп: {сварено}, воды в шкафу {я.stock.Взять("вода", 0.0)} — ждали 0.75 порции и воды 2");
        if (Math.Abs(я.stock.Взять("еда", 0.0) - еды_до) > 1e-9)
            плохо.Add($"еды в шкафу было {еды_до}, после готовки {я.stock.Взять("еда", 0.0)} — готовка не должна менять число");
        if (Закон() is string закон)
            плохо.Add($"после готовки закон слоя сломан: {закон}");

        // ---- 4. доля ----
        // картошки осталось 0.5 — жарят полпорции
        var пол = п.Приготовить(h, я, жарить, топится: true);
        if (пол.почему_нет is not null || Math.Abs(пол.порций - 0.5) > 1e-9 || Math.Abs(пол.доля - 0.5) > 1e-9)
            плохо.Add($"картошки на полрецепта — а жарено {пол}");
        var нечего = п.Приготовить(h, я, жарить, топится: true);
        if (нечего.почему_нет is null || нечего.порций > 0)
            плохо.Add($"картошки нет — а жарено {нечего}");
        if (Закон() is string закон2)
            плохо.Add($"после доли закон слоя сломан: {закон2}");

        // ---- 5. едят ----
        я.satiety = 10;
        я.warmth = 30;
        if (п.В(МестоЕды.ПОЛКА).FirstOrDefault(x => x.вид == "жареная_картошка") is not { } блюдо
            || п.В(МестоЕды.ПОЛКА).FirstOrDefault(x => x.вид == "суп") is not { } миска)
        {
            плохо.Add("на полке нет сготовленного — есть нечего");
            return плохо;
        }
        var съел = п.Съесть(h, я, блюдо);
        double порция = Действия.порция(h, я, h.B);
        if (Math.Abs(съел.сытости - порция * съел.единиц) > 1e-6 && !съел.отравился)
            плохо.Add($"жареной картошки съедено {съел.единиц} порций — а сытости {съел.сытости}, ждали полную {порция * съел.единиц}");
        if (я.warmth <= 30)
            плохо.Add("съела горячее в день готовки — а теплее не стало");
        я.satiety = 10;
        я.hydration = 20;
        п.Съесть(h, я, миска);
        if (я.hydration <= 20)
            плохо.Add("съела суп — а жажда та же");
        Положить("картошка");
        я.satiety = 10;
        var сырая = п.Съесть(h, я, п.В(МестоЕды.ПОЛКА).First(x => x.вид == "картошка"));
        if (сырая.единиц > 0 && сырая.сытости / сырая.единиц >= порция * 0.99)
            плохо.Add($"сырая картошка насыщает как блюдо: {сырая.сытости / сырая.единиц} за порцию");
        if (Закон() is string закон3)
            плохо.Add($"после еды закон слоя сломан: {закон3}");

        // ---- 6. как сыграно ----
        var ч = еда.готовка;
        if (!жарить.игры.SequenceEqual(new[] { ИграГотовки.НАРЕЗКА, ИграГотовки.ЖАРКА })
            || !суп.игры.SequenceEqual(new[] { ИграГотовки.НАРЕЗКА, ИграГотовки.ВАРКА }))
            плохо.Add($"мини-игры рецептов: жарить — {string.Join(",", жарить.игры)}, суп — {string.Join(",", суп.игры)}; ждали нарезку и жарку, нарезку и варку");
        if (!(ч.подгорело_ниже < 0.5 && 0.5 < ч.на_славу_выше && ч.подгорело_теряется > 0 && ч.подгорело_теряется < 1
              && ч.доверие_за_горячее > 0))
            плохо.Add($"числа готовки не по смыслу: {ч} — половина должна быть «как обычно»");
        var исходы = new List<string>();
        foreach (var (качество, итог) in new[] { (0.1, "подгорело"), (0.5, "как обычно"), (0.95, "на славу") })
        {
            Очистить();
            Положить("картошка");
            я.mood = 50;
            var с = п.Приготовить(h, я, жарить, топится: true, качество);
            double ждали_порций = итог == "подгорело" ? 1.0 - ч.подгорело_теряется : 1.0;
            double ждали_настроения = 50 + (итог switch { "подгорело" => ч.настроение_подгорело, "на славу" => ч.настроение_на_славу, _ => 0.0 });
            исходы.Add($"{Текст.Ф(качество, 2)} — {с.итог} ({Текст.Ф(с.порций, 2)})");
            if (с.итог != итог || Math.Abs(с.порций - ждали_порций) > 1e-9 || Math.Abs(Блюда("жареная_картошка") - ждали_порций) > 1e-9)
                плохо.Add($"сыграно на {качество}: {с}, на полке {Блюда("жареная_картошка")} — ждали «{итог}» и {ждали_порций} порций");
            if (Math.Abs(я.stock.Взять("еда", 0.0) - ждали_порций) > 1e-9)
                плохо.Add($"сыграно на {качество}: еды в шкафу {я.stock.Взять("еда", 0.0)}, ждали {ждали_порций} — подгоревшее не убыло из числа");
            if (Math.Abs(я.mood - ждали_настроения) > 1e-9)
                плохо.Add($"сыграно на {качество}: настроение {я.mood}, ждали {ждали_настроения}");
            if (Закон() is string закон4)
                плохо.Add($"сыграно на {качество}: закон слоя сломан: {закон4}");
        }

        // ---- 7. порог ----
        int порог = (int)ручки["мини_игра_исчезает"];
        var умения = я.умения;
        if (умения is null)
            плохо.Add("у героя нет наследия — порог мини-игры не проверить");
        else
        {
            int было = умения.наследие.Уровень(Навык.СМЕКАЛКА);
            умения.наследие.уровни[Навык.СМЕКАЛКА] = порог - 1;
            if (!Готовка.Играть(я, ручки))
                плохо.Add($"Смекалка {порог - 1} (порог {порог}) — а мини-игры готовки нет");
            умения.наследие.уровни[Навык.СМЕКАЛКА] = порог;
            if (Готовка.Играть(я, ручки))
                плохо.Add($"Смекалка {порог} (порог {порог}) — а мини-игра готовки всё ещё есть");
            if (Готовка.Само(я, ручки) <= 0.5)
                плохо.Add($"с порога готовится само на {Готовка.Само(я, ручки)} — не лучше обычного");
            умения.наследие.уровни[Навык.СМЕКАЛКА] = было;
        }
        var сосед = h.others(я).First();
        if (Готовка.Играть(сосед, ручки) || Готовка.Само(сосед, ручки) != 0.5)
            плохо.Add("у соседа мини-игра готовки — а соседи не играют");

        // ---- 8. овощи и замена ----
        var магазин = File.ReadAllText(Path.Combine(Пути.Данные, "магазин.json"));
        foreach (string вид in new[] { "морковь", "свёкла", "капуста" })
        {
            if (!еда.Есть(вид) || еда[вид].род != РодЕды.ОВОЩ || еда[вид].сырым >= 1.0)
            {
                плохо.Add($"«{вид}» — не овощ или сырым не хуже блюда");
                continue;
            }
            if (!еда.Откуда("погреб").Any(x => x.вид == вид && x.вес > 0))
                плохо.Add($"«{вид}» в погребах не бывает");
            if (!магазин.Contains($"\"продукт\": \"{вид}\"", StringComparison.Ordinal))
                плохо.Add($"«{вид}» в магазине не продаётся");
        }
        var борщ = еда.рецепты.FirstOrDefault(р => р.блюдо == "борщ");
        var с_тушёнкой = еда.рецепты.FirstOrDefault(р => р.блюдо == "картошка_с_тушёнкой");
        string овощи_итог = "";
        if (борщ is null || с_тушёнкой is null || !еда.рецепты.Any(р => р.блюдо == "щи"))
            плохо.Add("нет борща, щей или картошки с тушёнкой");
        else
        {
            Очистить();
            foreach (string вид in new[] { "свёкла", "капуста", "картошка", "морковь", "лук" })
                Положить(вид);
            я.stock["вода"] = 3;
            double было = я.stock.Взять("еда", 0.0);
            var б = п.Приготовить(h, я, борщ, топится: true);
            if (б.почему_нет is not null || Math.Abs(б.порций - 1.25) > 1e-9 || Math.Abs(я.stock.Взять("еда", 0.0) - было) > 1e-9)
                плохо.Add($"борщ из пяти овощей: {б}, еды {я.stock.Взять("еда", 0.0)} (было {было}) — ждали 1.25 порции и то же число");

            // тушёнки нет — говорят «тушёнка»; есть только говяжья — годится
            Очистить();
            Положить("картошка");
            var без = п.Приготовить(h, я, с_тушёнкой, топится: true);
            if (без.почему_нет != "на полке мало: тушёнка")
                плохо.Add($"картошка без тушёнки: {без} — ждали «на полке мало: тушёнка»");
            Положить("говядина");
            var т = п.Приготовить(h, я, с_тушёнкой, топится: true);
            if (т.почему_нет is not null || Math.Abs(т.порций - 1.75) > 1e-9 || п.В(МестоЕды.ПОЛКА).Any(x => x.вид == "говядина"))
                плохо.Add($"картошка с говяжьей тушёнкой: {т} — ждали 1.75 порции и банку в котле");
            // картошки на две трети рецепта (полкартошки ушло в суп) — банка
            // в котёл не вся, остаток вскрыт
            Очистить();
            Положить("картошка");
            Положить("лук");
            я.stock["вода"] = 3;
            п.Приготовить(h, я, суп, топится: true);
            Положить("свинина");
            var пт = п.Приготовить(h, я, с_тушёнкой, топится: true);
            var банка = п.В(МестоЕды.ПОЛКА).FirstOrDefault(x => x.вид == "свинина");
            if (пт.почему_нет is not null || Math.Abs(пт.доля - 2.0 / 3) > 1e-9 || банка is null
                || Math.Abs(банка.единиц - 1.0 / 3) > 1e-9 || !банка.открыт)
                плохо.Add($"две трети рецепта с тушёнкой: {пт}, банка {(банка is null ? "нет" : $"{банка.единиц}, открыта {банка.открыт}")} — ждали треть банки початой");
            if (Закон() is string закон5)
                плохо.Add($"после борща и тушёнки закон слоя сломан: {закон5}");
            овощи_итог = $"; борщ {Текст.Ф(б.порций, 2)}, без тушёнки — «{без.почему_нет}», две трети — в банке {Текст.Ф(банка?.единиц ?? 0, 2)}, початая";
        }

        // ---- 9. угощение ----
        string угощение_итог = "";
        if (борщ is not null)
        {
            var т = h.others(я).First(x => !x.away);
            п.Забрать_угощения();
            // горячего нет — банку дом снимет сверкой, слой молчит
            Очистить();
            Положить("свинина");
            я.stock["еда"] -= 1.0;
            т.warmth = 30;
            т.mood = 50;
            т.trust[я.id] = 3.0;
            if (п.Угостить(h, я, т, 1.0) is not null || т.warmth != 30 || т.mood != 50 || т.trust[я.id] != 3.0)
                плохо.Add("угостил банкой — а слой считает её горячим");
            п.Сверить(h, я);
            // сегодняшний борщ
            Очистить();
            foreach (string вид in new[] { "свёкла", "капуста", "картошка", "морковь", "лук" })
                Положить(вид);
            я.stock["вода"] = 3;
            п.Приготовить(h, я, борщ, топится: true);
            double до_борща = Блюда("борщ");
            я.stock["еда"] -= 1.0;           // дом передал порцию числом
            var у = п.Угостить(h, я, т, 1.0);
            double доверия = ч.доверие_за_горячее * (1.0 - 3.0 / 11.0);
            if (у is null || у.вид != "борщ" || Math.Abs(у.порций - 1.0) > 1e-9 || Math.Abs(Блюда("борщ") - (до_борща - 1.0)) > 1e-9)
                плохо.Add($"угостил борщом: {у}, борща на полке {Блюда("борщ")} (было {до_борща}) — ждали порцию борща");
            else
            {
                if (Math.Abs(т.warmth - (30 + еда["борщ"].греет / еда["борщ"].единиц)) > 1e-9)
                    плохо.Add($"соседу горячий борщ — тепла {т.warmth}, ждали {30 + еда["борщ"].греет / еда["борщ"].единиц}");
                if (Math.Abs(т.mood - (50 + еда["борщ"].настроение)) > 1e-9)
                    плохо.Add($"соседу горячий борщ — настроение {т.mood}, ждали {50 + еда["борщ"].настроение}");
                if (Math.Abs(т.trust[я.id] - (3.0 + доверия)) > 1e-9)
                    плохо.Add($"соседу горячий борщ — доверие {т.trust[я.id]}, ждали {3.0 + доверия}");
                if (!у.весть.Contains("борщ ещё с печи", StringComparison.Ordinal) || п.Забрать_угощения().Count != 1)
                    плохо.Add($"угостил — а герою не сказать: «{у.весть}»");
            }
            if (Закон() is string закон6)
                плохо.Add($"после угощения закон слоя сломан: {закон6}");
            // через дом: «поделиться» от героя — слушатель слоя слышит
            я.stock["еда"] = Util.Sum(п.В(МестоЕды.ПОЛКА).Select(x => x.единиц));
            Положить("свинина");
            double борща_было = Блюда("борщ");
            Действия.execute(h, я, "поделиться", т, "еда");
            var через_дом = п.Забрать_угощения();
            if (через_дом.Count != 1 || Блюда("борщ") >= борща_было - 1e-9)
                плохо.Add($"герой поделился через дом — угощений {через_дом.Count}, борща {Блюда("борщ")} (было {борща_было}): слой не слышит");
            п.Сверить(h, я);
            if (Закон() is string закон7)
                плохо.Add($"после «поделиться» закон слоя сломан: {закон7}");
            // вчерашний борщ уже не горячий — им не угощают (последним:
            // день слоя уходит вперёд)
            Очистить();
            foreach (string вид in new[] { "свёкла", "капуста", "картошка", "морковь", "лук" })
                Положить(вид);
            я.stock["вода"] = 3;
            п.Приготовить(h, я, борщ, топится: true);
            // сосед поделился с соседом — героева миска (свежая) тут ни при чём
            var другой = h.others(я).First(x => !x.away && x.id != т.id);
            т.stock["еда"] = 2;
            double борща_до_чужой = Блюда("борщ");
            Действия.execute(h, т, "поделиться", другой, "еда");
            if (п.Забрать_угощения().Count > 0 || Math.Abs(Блюда("борщ") - борща_до_чужой) > 1e-9)
                плохо.Add("сосед поделился с соседом — а с полки героя ушло горячее");
            п.Состарить(h.day + 1, я);
            я.stock["еда"] -= 1.0;
            if (п.Угостить(h, я, т, 1.0) is { } вчерашний)
                плохо.Add($"вчерашним борщом угостили как горячим: {вчерашний}");
            угощение_итог = $"; угостил: «{у?.весть}», доверие +{Текст.Ф(доверия, 2)}";
        }

        // ---- 10. узел ----
        string узел = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Годот"), "*.cs").Select(File.ReadAllText));
        foreach (var (текст, беда) in new[]
                 {
                     ("продукты.каталог.рецепты", "у печи нет рецептов — готовить нечем"),
                     ("() => Готовить(рецепт)", "рецепт у печи не нажимается"),
                     ("Готовка.Играть(я, _ручки)", "мини-игры готовки не спрашивают Смекалку"),
                     ("Приготовить(рецепт, Готовка.Само(я, _ручки))", "без мини-игры готовят не по Смекалке"),
                     ("продукты.Забрать_угощения() is { Count: > 0 } угощения", "герою не говорят, что угостил горячим"),
                     ("Приготовить(рецепт, сыграно.Average())", "качество готовки — не среднее по мини-играм"),
                     ("продукты.Приготовить(h, я, рецепт, Подача.Внутри(h, _партия.сеанс.я).топится, качество)", "готовят не по своей печи или сыгранное не доходит до готовки"),
                 })
            if (!узел.Contains(текст, StringComparison.Ordinal))
                плохо.Add($"узел: {беда}");

        w($"  рецептов {еда.рецепты.Count}: жарено {Текст.Ф(жарено.порций, 2)}, сварено {Текст.Ф(сварено.порций, 2)}, "
          + $"полрецепта — {Текст.Ф(пол.порций, 2)}; не топится — «{холодно.почему_нет}»; нечего — «{нечего.почему_нет}»; "
          + $"сытость за порцию: блюдо {Текст.Ф(порция, 1)}, сырая {Текст.Ф(сырая.единиц > 0 ? сырая.сытости / сырая.единиц : 0, 1)}; "
          + $"сыграно: {string.Join(", ", исходы)}{овощи_итог}{угощение_итог}");
        return плохо;
    }
