// Проверка готовки у своей печи (`Дом.Ядро/Петля/Готовка.cs`, этап 4 плана еды):
//
//  1. **Каталог.** Рецепты есть; блюдо каждого — продукт, его порции — сумма
//     того, что идёт в котёл; блюдо насыщает полной порцией и греет.
//  2. **Печь не топится** — не готовят, и ничего не тронуто.
//  3. **Жарят и варят.** Сырое снимается с полки на долю рецепта, блюдо
//     ложится туда же на те же порции: число еды шкафа прежнее, закон слоя
//     держится; на суп уходит вода из шкафа.
//  4. **Доля.** Картошки на полрецепта — полпорции блюда; меньше четверти —
//     не готовят и говорят, чего мало.
//  5. **Едят.** Блюдо сытнее сырого во столько, во сколько сырое хуже
//     (`сырым`), горячее в день готовки греет, суп ещё и поит.
//  6. **Узел.** Рецепты — кнопками у печи, готовят с полки своей комнаты,
//     полка перерисовывается.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Готовка_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var еда = КаталогЕды.Прочитать(Пути.Данные);
        if (еда is null)
        {
            плохо.Add("нет data/еда.json — готовить не из чего");
            return плохо;
        }

        // ---- 1. каталог ----
        if (еда.рецепты.Count < 2)
            плохо.Add($"рецептов {еда.рецепты.Count} — ждали жареную картошку и суп");
        foreach (var р in еда.рецепты)
        {
            var б = еда[р.блюдо];
            if (Math.Abs(б.сырым - 1.0) > 1e-9)
                плохо.Add($"блюдо «{б.имя}» насыщает не полной порцией ({б.сырым}) — готовить незачем");
            if (б.греет <= 0)
                плохо.Add($"блюдо «{б.имя}» горячим не греет");
            if (!р.из.Any(x => еда[x.вид].сырым < 1.0))
                плохо.Add($"в рецепте «{б.имя}» нет ничего, что сырым хуже, — блюдо не лучше сырого");
        }
        var жарить = еда.рецепты.FirstOrDefault(р => р.блюдо == "жареная_картошка");
        var суп = еда.рецепты.FirstOrDefault(р => р.блюдо == "суп");
        if (жарить is null || суп is null)
        {
            плохо.Add("нет рецепта жареной картошки или супа — дальше проверять нечем");
            return плохо;
        }

        var прогон = new Прогон(Пути.Данные, seed: 5, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
        new Дом.Ядро.Петля(new Наследие(), ручки, еда: еда).Слушать(прогон, "оксана");
        var h = прогон.h;
        var я = h.people["оксана"];
        var п = Продукты.У(я)!;
        string? Закон()
        {
            foreach (var м in Продукты.МЕСТА)
                if (Math.Abs(п.Сумма(м) - Продукты.Число(я, м)) > 1e-5)
                    return $"{м}: вещей на {Текст.Ф(п.Сумма(м), 3)}, а у дома {Текст.Ф(Продукты.Число(я, м), 3)}";
            return null;
        }
        // полка: только то, что положим сами
        void Очистить()
        {
            foreach (var x in п.В(МестоЕды.ПОЛКА).ToList())
                п.Убрать(x);
            я.stock["еда"] = 0;
        }
        void Положить(string вид)
        {
            var x = п.Новая(вид);
            п.Положить(МестоЕды.ПОЛКА, x);
            я.stock["еда"] = я.stock.Взять("еда", 0.0) + x.единиц;
        }
        double Блюда(string вид) => Util.Sum(п.В(МестоЕды.ПОЛКА).Where(x => x.вид == вид).Select(x => x.единиц));

        // ---- 2. печь не топится ----
        Очистить();
        Положить("картошка");
        я.stock["вода"] = 3;
        var холодно = п.Приготовить(h, я, жарить, топится: false);
        if (холодно.почему_нет is null || холодно.порций > 0 || Math.Abs(п.Свежего("картошка") - 1.0) > 1e-9)
            плохо.Add($"печь не топится — а картошку пожарили: {холодно}");

        // ---- 3. жарят и варят ----
        Положить("картошка");
        Положить("лук");
        double еды_до = я.stock.Взять("еда", 0.0);
        var жарено = п.Приготовить(h, я, жарить, топится: true);
        if (жарено.почему_нет is not null || Math.Abs(жарено.порций - 1.0) > 1e-9 || Math.Abs(Блюда("жареная_картошка") - 1.0) > 1e-9)
            плохо.Add($"на полке две картошки, печь топится — а жарено не на порцию: {жарено}, на полке {Блюда("жареная_картошка")}");
        if (Math.Abs(п.Свежего("картошка") - 1.0) > 1e-9)
            плохо.Add($"после жарки картошки на полке {п.Свежего("картошка")}, ждали одну");
        var сварено = п.Приготовить(h, я, суп, топится: true);
        if (сварено.почему_нет is not null || Math.Abs(сварено.порций - 0.75) > 1e-9 || Math.Abs(я.stock.Взять("вода", 0.0) - 2.0) > 1e-9)
            плохо.Add($"суп: {сварено}, воды в шкафу {я.stock.Взять("вода", 0.0)} — ждали 0.75 порции и воды 2");
        if (Math.Abs(я.stock.Взять("еда", 0.0) - еды_до) > 1e-9)
            плохо.Add($"еды в шкафу было {еды_до}, после готовки {я.stock.Взять("еда", 0.0)} — готовка не должна менять число");
        if (Закон() is string закон)
            плохо.Add($"после готовки закон слоя сломан: {закон}");

        // ---- 4. доля ----
        // картошки осталось 0.5 — жарят полпорции
        var пол = п.Приготовить(h, я, жарить, топится: true);
        if (пол.почему_нет is not null || Math.Abs(пол.порций - 0.5) > 1e-9 || Math.Abs(пол.доля - 0.5) > 1e-9)
            плохо.Add($"картошки на полрецепта — а жарено {пол}");
        var нечего = п.Приготовить(h, я, жарить, топится: true);
        if (нечего.почему_нет is null || нечего.порций > 0)
            плохо.Add($"картошки нет — а жарено {нечего}");
        if (Закон() is string закон2)
            плохо.Add($"после доли закон слоя сломан: {закон2}");

        // ---- 5. едят ----
        я.satiety = 10;
        я.warmth = 30;
        if (п.В(МестоЕды.ПОЛКА).FirstOrDefault(x => x.вид == "жареная_картошка") is not { } блюдо
            || п.В(МестоЕды.ПОЛКА).FirstOrDefault(x => x.вид == "суп") is not { } миска)
        {
            плохо.Add("на полке нет сготовленного — есть нечего");
            return плохо;
        }
        var съел = п.Съесть(h, я, блюдо);
        double порция = Действия.порция(h, я, h.B);
        if (Math.Abs(съел.сытости - порция * съел.единиц) > 1e-6 && !съел.отравился)
            плохо.Add($"жареной картошки съедено {съел.единиц} порций — а сытости {съел.сытости}, ждали полную {порция * съел.единиц}");
        if (я.warmth <= 30)
            плохо.Add("съела горячее в день готовки — а теплее не стало");
        я.satiety = 10;
        я.hydration = 20;
        п.Съесть(h, я, миска);
        if (я.hydration <= 20)
            плохо.Add("съела суп — а жажда та же");
        Положить("картошка");
        я.satiety = 10;
        var сырая = п.Съесть(h, я, п.В(МестоЕды.ПОЛКА).First(x => x.вид == "картошка"));
        if (сырая.единиц > 0 && сырая.сытости / сырая.единиц >= порция * 0.99)
            плохо.Add($"сырая картошка насыщает как блюдо: {сырая.сытости / сырая.единиц} за порцию");
        if (Закон() is string закон3)
            плохо.Add($"после еды закон слоя сломан: {закон3}");

        // ---- 6. узел ----
        string узел = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Годот"), "*.cs").Select(File.ReadAllText));
        foreach (var (текст, беда) in new[]
                 {
                     ("продукты.каталог.рецепты", "у печи нет рецептов — готовить нечем"),
                     ("продукты.Приготовить(h, я, рецепт, Подача.Внутри(h, _партия.сеанс.я).топится)", "готовят не по своей печи"),
                     ("() => Приготовить(рецепт)", "рецепт у печи не нажимается"),
                 })
            if (!узел.Contains(текст, StringComparison.Ordinal))
                плохо.Add($"узел: {беда}");

        w($"  рецептов {еда.рецепты.Count}: жарено {Текст.Ф(жарено.порций, 2)}, сварено {Текст.Ф(сварено.порций, 2)}, "
          + $"полрецепта — {Текст.Ф(пол.порций, 2)}; не топится — «{холодно.почему_нет}»; нечего — «{нечего.почему_нет}»; "
          + $"сытость за порцию: блюдо {Текст.Ф(порция, 1)}, сырая {Текст.Ф(сырая.единиц > 0 ? сырая.сытости / сырая.единиц : 0, 1)}");
        return плохо;
    }
}
