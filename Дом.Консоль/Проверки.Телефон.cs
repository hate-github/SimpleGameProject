// Проверка телефона героя (ГДД 19; `Дом.Ядро/Петля/Телефон.cs`).
//
//  1. **Заряд.** Первая сверка только запоминает часы; сам садится медленно,
//     в руке — быстро, у розетки заряжается, не выше ста и не ниже нуля;
//     часы назад — ничего не меняется; сел — `сел`.
//  2. **Провести время.** Есть заряд — час, минус заряд, плюс настроение;
//     сел или не хватает — нельзя, и ничего не меняется.
//  3. **Сеть.** Палки по `House.network`: ноль — «нет сети», дальше по
//     четвертям; в живом доме сеть тает к «день_потери_связи» и не растёт.
//  4. **Сохранение.** Заряд едет в сейв округи и обратно; в старом сейве
//     телефона нет — полный.
//  5. **Экран.** Узел сверяет заряд каждый кадр и ведёт «провести время»
//     через дела на месте; сел — вкладки приложений прячутся, мысли остаются;
//     чат — глазами героя (скан).

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Телефон_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        double разряд = ручки["телефон_разряд_в_час"], в_руке = ручки["телефон_разряд_в_руке_в_час"];
        double заряд_в_час = ручки["телефон_заряд_в_час"];
        bool Рядом(double а, double б) => Math.Abs(а - б) < 1e-9;

        // ---- 1. заряд ----
        string заряд_итог;
        {
            var т = new Телефон();
            т.Сверить(10, у_розетки: false, в_руке: false, ручки);
            if (!Рядом(т.заряд, 100))
                плохо.Add($"телефон: первая сверка уже потратила заряд — {т.заряд}");
            т.Сверить(20, false, false, ручки);
            double сам = т.заряд;
            т.Сверить(22, false, true, ручки);
            double рука = т.заряд;
            т.Сверить(23, true, false, ручки);
            double зарядился = т.заряд;
            т.Сверить(22, false, true, ручки);
            double назад = т.заряд;
            т.Сверить(400, false, false, ручки);
            if (!Рядом(сам, 100 - 10 * разряд))
                плохо.Add($"телефон: за 10 ч сам сел до {сам}, а надо {100 - 10 * разряд}");
            if (!Рядом(рука, сам - 2 * в_руке))
                плохо.Add($"телефон: 2 ч в руке — {рука}, а надо {сам - 2 * в_руке}");
            if (!Рядом(зарядился, Math.Min(100, рука + заряд_в_час)))
                плохо.Add($"телефон: час у розетки — {зарядился}, а надо {Math.Min(100, рука + заряд_в_час)}");
            if (!Рядом(назад, зарядился))
                плохо.Add("телефон: часы пошли назад — а заряд изменился");
            if (!т.сел || т.заряд < 0)
                плохо.Add($"телефон: 377 ч без розетки — заряд {т.заряд}, а должен сесть в ноль");
            т.Сверить(500, true, false, ручки);
            if (!Рядом(т.заряд, 100))
                плохо.Add($"телефон: сто часов у розетки — {т.заряд}, а выше ста не бывает и ниже — тоже");
            заряд_итог = $"сам за 10 ч — {Текст.G(сам)}%, в руке 2 ч — {Текст.G(рука)}%, "
                         + $"час у розетки — {Текст.G(зарядился)}%; без розетки — сел";
        }

        // ---- 1б. часы: из пролога в метель — без пропавших суток ----
        {
            double ночь = Телефон.Часы(-1, 0, 23.0), утро = Телефон.Часы(null, 1, 8.0);
            double утро_пролога = Телефон.Часы(-2, 0, 8.0), второе = Телефон.Часы(-1, 0, 8.0);
            if (!Рядом(утро - ночь, 9.0) || !Рядом(второе - утро_пролога, 24.0)
                || !Рядом(Телефон.Часы(null, 2, 8.0) - утро, 24.0))
                плохо.Add($"телефон: часы героя рвутся — ночь пролога {ночь}, утро метели {утро}: "
                          + "между ними должно быть 9 ч, между днями — 24");
        }

        // ---- 2. провести время ----
        string время_итог;
        {
            var т = new Телефон();
            var я = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null))
                    .h.people["оксана"];
            я.mood = 40;
            т.Сверить(0, false, false, ручки);
            т.Сверить(1000, false, false, ручки);       // сел
            var нельзя = т.Провести_время(я, ручки);
            if (нельзя.да || !Рядом(я.mood, 40))
                плохо.Add("телефон: сел — а время в нём провести можно (или настроение выросло)");
            else if (!нельзя.весть.Contains("сел", StringComparison.Ordinal))
                плохо.Add($"телефон: сел — а говорит «{нельзя.весть}», не что сел");
            т.Сверить(1000 + 50.0 / заряд_в_час, true, false, ручки);  // до 50%
            double было = т.заряд;
            var можно = т.Провести_время(я, ручки);
            if (!можно.да || !Рядом(можно.часов, ручки["телефон_провести_время_часов"])
                || !Рядом(т.заряд, было - ручки["телефон_провести_время_заряд"])
                || !Рядом(я.mood, 40 + ручки["телефон_провести_время_настроение"]))
                плохо.Add($"телефон: провести время — {можно.да}, {можно.часов} ч, заряд {было} → {т.заряд}, настроение {я.mood}");
            // мало заряда — нельзя
            т.Сверить(2000, false, false, ручки);
            т.Сверить(2000 + 5.0 / заряд_в_час, true, false, ручки);   // 5%
            double пять = т.заряд;
            if (т.Провести_время(я, ручки).да || !Рядом(т.заряд, пять))
                плохо.Add($"телефон: {Текст.G(пять)}% — а час в телефоне провести можно");
            время_итог = $"«{можно.весть}»: {Текст.G(было)}% → {Текст.G(было - ручки["телефон_провести_время_заряд"])}%, "
                         + $"настроение +{Текст.G(ручки["телефон_провести_время_настроение"])}; сел или 5% — нельзя";
        }

        // ---- 3. сеть ----
        string сеть_итог;
        {
            var ждём = new (double сеть, int палок)[] { (0, 0), (0.01, 1), (0.25, 1), (0.26, 2), (0.5, 2), (0.75, 3), (0.76, 4), (1, 4) };
            foreach (var (с, п) in ждём)
                if (Телефон.Палок(с) != п)
                    плохо.Add($"телефон: сеть {с} — палок {Телефон.Палок(с)}, а надо {п}");
            var прогон = new Прогон(Пути.Данные, seed: 3, days: 12, журнал: new Журнал(0, false, TextWriter.Null));
            var по_дням = new List<int>();
            прогон.h.hooks.on_day.Add(дом => по_дням.Add(Телефон.Палок(дом.network)));
            прогон.run();
            int нет_с = по_дням.FindIndex(п => п == 0) + 1;
            bool тает = по_дням.Zip(по_дням.Skip(1)).All(п => п.Second <= п.First);
            if (!тает)
                плохо.Add($"телефон: сеть в живом доме то тает, то растёт: {string.Join(" ", по_дням)}");
            if (нет_с == 0 || нет_с > (int)прогон.h.B["день_потери_связи"] + 1)
                плохо.Add($"телефон: к дню {(int)прогон.h.B["день_потери_связи"]} сеть не пропала: {string.Join(" ", по_дням)}");
            сеть_итог = $"палки по дням: {string.Join(" ", по_дням)}; нет сети с дня {нет_с}";
        }

        // ---- 4. сохранение ----
        {
            var профиль = new ПрофильГероя("Андрей");
            var п = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null),
                               жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            new Дом.Ядро.Петля(new Наследие(), ручки,
                               инструменты: Дом.Ядро.Инструменты.Прочитать(Пути.Данные),
                               летопись: Летопись.Прочитать(Пути.Данные)).Слушать(п, Герой.ID);
            var о = Округа.У(п.h)!;
            var я = п.h.people[Герой.ID];
            о.телефон.Сверить(0, false, false, ручки);
            о.телефон.Сверить(10, false, true, ручки);
            double было = о.телефон.заряд;
            var сейв = о.Сложить();
            о.телефон.Сверить(20, true, false, ручки);
            о.Разложить(сейв, я);
            if (!Рядом(о.телефон.заряд, было))
                плохо.Add($"телефон: заряд {было} после сейва вернулся как {о.телефон.заряд}");
            сейв.Remove("телефон");
            о.Разложить(сейв, я);
            if (!Рядом(о.телефон.заряд, 100))
                плохо.Add("телефон: в старом сейве телефона нет — а заряд не полный");
        }

        // ---- 5. экран ----
        {
            string Файл(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя));
            string узел = Файл("ДомУзел.cs"), т_узел = Файл("ДомУзел.Телефон.cs"), ui = Файл("ТелефонUI.cs");
            if (!узел.Contains("Телефон_кадр();", StringComparison.Ordinal)
                || !т_узел.Contains("т.Сверить(сейчас, у_розетки, _телефон.открыт, _ручки);", StringComparison.Ordinal)
                || !т_узел.Contains("Дом.Ядро.Телефон.Часы(_пролог?.день, _партия.сеанс.дом.day, ч.Value)", StringComparison.Ordinal))
                плохо.Add("телефон: узел не сверяет заряд с часами героя каждый кадр");
            if (!т_узел.Contains("Сделать_тут(с);", StringComparison.Ordinal)
                || !т_узел.Contains("Можно_тут()", StringComparison.Ordinal))
                плохо.Add("телефон: «провести время» мимо дел на месте — час не проживается или дом не спрашивают");
            if (!ui.Contains("_вкладки.SetTabHidden(i, сел);", StringComparison.Ordinal))
                плохо.Add("телефон: сел — а приложения на месте");
            if (!ui.Contains("с.ДляГероя.Replace(\"  [чат] \"", StringComparison.Ordinal))
                плохо.Add("телефон: чат — не глазами героя (имена незнакомых)");
        }

        w($"  заряд: {заряд_итог}");
        w($"  провести время: {время_итог}");
        w($"  сеть: {сеть_итог}");
        return плохо;
    }
}
