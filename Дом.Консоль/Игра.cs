// Перенос играть.py: прожить метель за одного из жильцов — руками, в консоли.
//
// Зачем это, если есть прогон: прогон показывает, что дом делает сам. Здесь
// за одного из пятнадцати решает человек — тем же швом, что и NPC
// (`Решающий`), по тем же правилам и с теми же оценками. Это и есть проверка,
// ради которой шов делался: пройти тридцать дней и не встретить места,
// где игра решает за тебя.
//
// Отличий от прогона два, и оба про то, чтобы можно было играть: журнал
// печатается сразу, а не в конце дня — иначе отвечать пришлось бы вслепую;
// и перед вопросом печатается своё состояние.
//
// Три экрана — состояние, план подъезда, знание о соседях — консоль больше
// не считает сама: их складывает `Дом.Экран.Сеанс`, а печатает
// `Дом.Экран.Печать`. Здесь остались ввод, справки и разбор ответа, то есть
// ровно консольное. Godot возьмёт те же записи и нарисует их иначе —
// и если запись потеряет поле, это покраснеет здесь, в стенограмме,
// а не всплывёт на сцене.

using Дом.Экран;
using Дом.Ядро;

namespace Дом.Консоль;

/// <summary>
/// Журнал, который печатает строку сразу.
///
/// Обычный копит день и выкладывает его в конце — для чтения потом это
/// правильно, для игры нет: вопрос «что делать» приходит посреди дня,
/// и до ответа игрок должен знать, что уже случилось. Заголовок дня
/// печатается перед первой строкой этого дня.
/// </summary>
public sealed class ЖивойЖурнал : Журнал
{
    private int? _день;

    public House? дом { get; set; }

    public ЖивойЖурнал(int verbosity, bool secrets, TextWriter поток)
        : base(verbosity, secrets, поток)
    {
    }

    private int Порог() => verbosity == 0 ? 2 : (verbosity == 1 ? 1 : 0);

    /// <summary>Заголовок дня — перед первой строкой этого дня, а не в конце.</summary>
    public void Шапка()
    {
        if (дом is null || _день == дом.day)
            return;
        _день = дом.day;
        w();
        w(шапка_дня(дом));
    }

    public override void line(string текст, int заметность, bool hidden)
    {
        if (hidden && !secrets)
            return;
        if (заметность < Порог())
            return;
        Шапка();
        w("  " + (час is not null ? $"{час} {текст}" : текст));
    }

    /// <summary>
    /// День уже напечатан по строчке — печатать нечего, только шапку,
    /// если за весь день не случилось ни строки.
    ///
    /// Событие дня, секрет и чат при этом не показываются вовсе: они идут
    /// в буфер (`event`, `secret`, `chat` достаются от обычного журнала),
    /// а буфер здесь только чистится. Это поведение прототипа, перенесённое
    /// как есть; в список правок после переезда — играющий не видит
    /// ни «Метель. Синоптики говорят…», ни чата соседей.
    /// </summary>
    public override void flush_day(House h)
    {
        дом = h;
        Шапка();
        buf.Clear();
    }
}

public static class Игра
{
    /// <summary>
    /// Сколько вариантов показывать сразу: у жильца в доме на пятнадцать
    /// их бывает и тридцать, и читать их все каждый ход невозможно.
    /// Остальные — по «всё».
    /// </summary>
    private const int КОРОТКИЙ_СПИСОК = 12;

    /// <summary>Как он себя чувствует и что у него есть — одной строкой
    /// перед вопросом.</summary>
    public static string строка_состояния(Сеанс сеанс)
        => Печать.Состояние(сеанс.Состояние());

    /// <summary>Кто ещё жив, где живёт и каким кажется — то, что игрок видит
    /// и так.</summary>
    public static string дом_коротко(Сеанс сеанс)
        => Печать.План(сеанс.План());

    /// <summary>Что я знаю о соседях: оценка шкафа и насколько я вообще
    /// в курсе.</summary>
    public static string знание(Сеанс сеанс)
        => Печать.Знание(сеанс.Знание());

    /// <summary>
    /// Тот самый «спросить(вопрос, строки) → номер», которого ждёт `Человек`.
    ///
    /// Всё, что он печатает, идёт в тот же поток, что и журнал: иначе строки
    /// перемешаются не в том порядке, в каком случились.
    /// </summary>
    public static Func<ВопросИгроку, int> спросить(
        Сеанс сеанс, ЖивойЖурнал журнал, TextReader ввод, TextWriter вывод)
    {
        void П(string s = "") => вывод.Write(s + "\n");
        return вопрос =>
        {
            var строки = вопрос.строки;
            // заголовок дня — до вопроса: игрок должен знать, какое сегодня
            // число и сколько на улице, прежде чем решать
            журнал.Шапка();
            П();
            П(new string('┈', 74));
            П(вопрос.заголовок);
            П(строка_состояния(сеанс));

            void Показать(int сколько)
            {
                for (int i = 0; i < Math.Min(сколько, строки.Count); i++)
                    П($"  {i}. {строки[i]}");
                if (сколько < строки.Count)
                    П($"  … и ещё {строки.Count - сколько} — «всё»");
            }

            Показать(КОРОТКИЙ_СПИСОК);
            while (true)
            {
                вывод.Write("> ");
                string? сырое = ввод.ReadLine();
                if (сырое is null)
                    return 0;
                string ответ = сырое.Trim().ToLowerInvariant();
                if (ответ is "в" or "выход" or "q")
                {
                    П("Вышел из игры.");
                    throw new ВыходИзИгры();
                }
                if (ответ is "?" or "дом")
                {
                    П(дом_коротко(сеанс));
                    continue;
                }
                if (ответ is "я" or "я?")
                {
                    П(строка_состояния(сеанс));
                    continue;
                }
                if (ответ is "т" or "соседи")
                {
                    П(знание(сеанс));
                    continue;
                }
                if (ответ is "всё" or "все" or "*")
                {
                    Показать(строки.Count);
                    continue;
                }
                if (ответ.Length > 0 && ответ.All(char.IsDigit)
                    && int.TryParse(ответ, out int n) && n < строки.Count)
                    return n;
                П("  номер варианта, или: всё — весь список, ? — дом, "
                  + "я — состояние, т — что знаю о соседях, в — выход");
            }
        };
    }
}

