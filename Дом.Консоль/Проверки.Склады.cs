// Проверка складов вне дома (замечание автора: «пока еду не вытащил из
// кладовой участка, у неё по сути нет срока годности»; `Продукты`,
// места УЧАСТОК и УБЕЖИЩЕ, `Убежище.Поесть`).
//
//  1. **Склад — место учёта.** Кладовая участка и запас убежища заведены,
//     их еда — вещи «оттуда» (у полиции — своё, в убежище — НЗ), и сумма
//     вещей — число склада.
//  2. **Стареет.** Прошло десять дней — вещи на складе на десять дней старше.
//  3. **Уходит теми же вещами.** Взял в сумку — в сумке те же вещи с тем же
//     возрастом; выложил — вернулись.
//  4. **Съесть — вещь.** Сперва свежая, просроченная банка раньше
//     испорченного; испорченное — когда больше нечего. Запах из участка
//     до подъезда не доходит.
//  5. **Закон держится**, когда из склада уносят (гости); сейв помнит склад.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Склады_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var еда = КаталогЕды.Прочитать(Пути.Данные);
        if (еда is null || л.участок is null || л.убежище is null)
        {
            плохо.Add("нет еда.json или участка и убежища в мир.json");
            return плохо;
        }
        (House h, NPC я, Продукты п, Участок у, Бункер б) Жизнь(long зерно = 7)
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 40, журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л, еда: еда).Слушать(прогон, "оксана");
            прогон.h.day = 3;
            var я = прогон.h.people["оксана"];
            var о = Округа.У(прогон.h)!;
            return (прогон.h, я, Продукты.У(я)!, о.участок!, о.бункер!);
        }
        string? Закон(Продукты п, NPC я)
        {
            foreach (var м in Продукты.МЕСТА)
                if (Math.Abs(п.Сумма(м) - Продукты.Число(я, м)) > 1e-5)
                    return $"{м}: вещей {Текст.Ф(п.Сумма(м), 3)}, числом {Текст.Ф(Продукты.Число(я, м), 3)}";
            return null;
        }

        // ---- 1. склад — место учёта ----
        string склад_итог;
        {
            var (h, я, п, у, б) = Жизнь();
            if (п.Место(у) != МестоЕды.УЧАСТОК || п.Место(б) != МестоЕды.УБЕЖИЩЕ)
                плохо.Add("склады не заведены: кладовая участка и запас убежища — не места учёта");
            п.Сверить(h, я);
            if (Закон(п, я) is string беда)
                плохо.Add($"после первой сверки закон не сошёлся: {беда}");
            var из_участка = еда.Откуда("участок").Where(x => x.вес > 0).Select(x => x.вид).ToHashSet(StringComparer.Ordinal);
            var из_убежища = еда.Откуда("убежище").Where(x => x.вес > 0).Select(x => x.вид).ToHashSet(StringComparer.Ordinal);
            if (п.В(МестоЕды.УЧАСТОК).Count == 0 || п.В(МестоЕды.УЧАСТОК).Any(x => !из_участка.Contains(x.вид)))
                плохо.Add("в кладовой участка нет вещей — или лежат не те, что бывают у полиции");
            if (п.В(МестоЕды.УБЕЖИЩЕ).Count == 0 || п.В(МестоЕды.УБЕЖИЩЕ).Any(x => !из_убежища.Contains(x.вид)))
                плохо.Add("в запасе убежища нет вещей — или лежат не те, что бывают в НЗ");
            int просрочено = п.В(МестоЕды.УБЕЖИЩЕ).Count(x => п.Свежесть(x) != Свежесть.СВЕЖАЯ);
            склад_итог = $"участок: {п.В(МестоЕды.УЧАСТОК).Count} вещей на {Текст.G(Текст.Округлить(п.Сумма(МестоЕды.УЧАСТОК), 1))} порций; "
                         + $"убежище: {п.В(МестоЕды.УБЕЖИЩЕ).Count} вещей, не свежих {просрочено}";
        }

        // ---- 2 и 3. стареет; уходит и возвращается теми же вещами ----
        {
            var (h, я, п, у, _) = Жизнь();
            п.Сверить(h, я);
            var было = п.В(МестоЕды.УЧАСТОК).ToDictionary(x => x.номер, x => x.возраст);
            h.day += 10;
            п.Сверить(h, я);
            if (п.В(МестоЕды.УЧАСТОК).Any(x => было.TryGetValue(x.номер, out var в) && Math.Abs(x.возраст - в - 10) > 1e-9))
                плохо.Add("десять дней прошло — а еда в кладовой участка не постарела на десять дней");
            у.Пришёл(я);
            var возраст = п.В(МестоЕды.УЧАСТОК).ToDictionary(x => x.номер, x => x.возраст);
            double взял = у.Взять(я, "еда", 3.0, ручки);
            п.Сверить(h, я);
            var в_ноше = п.В(МестоЕды.НОША);
            if (взял <= 0 || в_ноше.Count == 0
                || в_ноше.Any(x => !возраст.ContainsKey(x.номер) && x.единиц > 0.99 * еда[x.вид].единиц))
                плохо.Add("взял из кладовой в сумку — а в сумке новые вещи, а не те, что лежали в кладовой");
            if (в_ноше.Any(x => возраст.TryGetValue(x.номер, out var в) && Math.Abs(x.возраст - в) > 1e-9))
                плохо.Add("вещь из кладовой в сумке помолодела");
            var номера_ноши = в_ноше.Select(x => x.номер).ToHashSet();
            у.Выложить(я);
            п.Сверить(h, я);
            if (!номера_ноши.All(н => п.В(МестоЕды.УЧАСТОК).Any(x => x.номер == н)))
                плохо.Add("выложил принесённое в кладовую — а там другие вещи");
            if (Закон(п, я) is string беда)
                плохо.Add($"взять и выложить: закон не сошёлся: {беда}");
        }

        // ---- 4. съесть — вещь: сперва свежая ----
        string съесть_итог;
        {
            var (h, я, п, у, _) = Жизнь();
            у.Пришёл(я);
            п.Сверить(h, я);
            h.day += 1000;                          // всё в кладовой давно не свежее
            п.Сверить(h, я);
            var свежая = п.Новая("свинина");
            п.Положить(МестоЕды.УЧАСТОК, свежая);
            у.Добавить("еда", свежая.единиц);
            if (!ReferenceEquals(п.Что_съесть(МестоЕды.УЧАСТОК), свежая))
                плохо.Add("в кладовой есть свежая банка — а съесть собираются старую");
            int учуяли = h.others(я).Sum(с => с.memory.Count(з => з.вид == Вид.УЧУЯЛ));
            я.satiety = 10;
            var поел = Убежище.Поесть(h, я, у);
            if (!поел.да || п.В(МестоЕды.УЧАСТОК).Contains(свежая) && свежая.единиц > 0.01)
                плохо.Add($"поел из кладовой — а свежая банка на месте ({поел.весть})");
            if (h.others(я).Sum(с => с.memory.Count(з => з.вид == Вид.УЧУЯЛ)) > учуяли)
                плохо.Add("поел в участке — а соседи в доме учуяли запах");
            var дальше = п.Что_съесть(МестоЕды.УЧАСТОК);
            bool есть_просроченная = п.В(МестоЕды.УЧАСТОК).Any(x => п.Свежесть(x) == Свежесть.ПРОСРОЧЕНА);
            if (дальше is not null && есть_просроченная && п.Свежесть(дальше) == Свежесть.ИСПОРЧЕНА)
                плохо.Add("есть просроченная банка — а берут испорченное");
            // остались одни испорченные — едят и их, с риском
            foreach (var x in п.В(МестоЕды.УЧАСТОК).Where(x => п.Свежесть(x) != Свежесть.ИСПОРЧЕНА).ToList())
            {
                п.Убрать(x);
                у.Изъять("еда", x.единиц);
            }
            string испорченное = "—";
            if (п.В(МестоЕды.УЧАСТОК).Count > 0)
            {
                я.satiety = 10;
                var с = Убежище.Поесть(h, я, у);
                if (!с.да)
                    плохо.Add($"голоден, в кладовой только испорченное — и не съел: {с.весть}");
                испорченное = с.весть;
            }
            if (Закон(п, я) is string беда)
                плохо.Add($"съесть из кладовой: закон не сошёлся: {беда}");
            съесть_итог = $"свежая первой: {поел.весть}; одни испорченные: {испорченное}";
        }

        // ---- 5. уносят гости; сейв ----
        {
            var (h, я, п, у, б) = Жизнь();
            п.Сверить(h, я);
            у.Изъять("еда", 7.0);
            б.Изъять("еда", 2.0);
            п.Сверить(h, я);
            if (Закон(п, я) is string беда)
                плохо.Add($"из склада унесли — закон не сошёлся: {беда}");
            var сейв = System.Text.Json.Nodes.JsonNode.Parse(п.Сложить().ToJsonString())!.AsObject();
            var (_, я2, _, _, _) = Жизнь(13);
            var п2 = Продукты.Завести(я2, еда, 13);
            п2.Разложить(сейв);
            if (п2.В(МестоЕды.УЧАСТОК).Count != п.В(МестоЕды.УЧАСТОК).Count
                || п2.В(МестоЕды.УБЕЖИЩЕ).Count != п.В(МестоЕды.УБЕЖИЩЕ).Count)
                плохо.Add("после сейва склады пусты или не те");
        }

        w($"  склады: {склад_итог}");
        w($"  съесть: {съесть_итог}");
        return плохо;
    }
}
