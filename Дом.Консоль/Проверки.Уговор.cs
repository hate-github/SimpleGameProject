// Проверка убеждения (ГДД 7: мини-игра «Разговор» — «убеждение, торг, отвод
// подозрений»; провал — падение доверия). Перед просьбой — реплика на время,
// итог сдвигает решение соседа «дать ли».
//
//  1. **Сдвиг.** Половина — ровно ноль; ноль и единица — на «мини_уговор_сила»
//     ниже и выше; растёт с качеством. У других игр — ноль.
//  2. **Соседи.** Без уговоров мерка «дать ли» та же бит в бит — эталон цел.
//  3. **Живая просьба.** Настоящий `_ask` на пограничной просьбе: без уговоров
//     и «как обычно» — один исход; удачные уговоры дают там, где отказали бы,
//     неудачные — отказывают там, где дали бы.
//  4. **Провал** роняет доверие соседа. **Экран и ядро** — скан.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Уговор_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        double сила = ручки["мини_уговор_сила"];

        // ---- 1. сдвиг ----
        if (сила <= 0.0)
            плохо.Add($"уговор: сила {Текст.G(сила)} — уговоры ничего не решают");
        if (МиниИгры.Уговор(0.5, ручки) != 0.0
            || Math.Abs(МиниИгры.Уговор(1.0, ручки) - сила) > 1e-12
            || Math.Abs(МиниИгры.Уговор(0.0, ручки) + сила) > 1e-12
            || !(МиниИгры.Уговор(0.25, ручки) < МиниИгры.Уговор(0.75, ручки)))
            плохо.Add("уговор: сдвиг не тот — половина не ноль, края не на силу или не растёт");
        if (МиниИгры.Какая("попросить") != МиниИгра.РАЗГОВОР)
            плохо.Add("уговор: перед просьбой нет «Разговора»");
        foreach (var м in new[] { МиниИгра.РЕМОНТ, МиниИгра.ВЗЛОМ, МиниИгра.РАБОТА })
            if (МиниИгры.Сыграно_для(м, 1.0, ручки).уговор != 0.0)
                плохо.Add($"уговор: «{м}» сдвигает просьбу");

        // ---- 2. соседи: мерка та же бит в бит ----
        var профиль = new ПрофильГероя("Андрей");
        Прогон Дом_()
        {
            var пп = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null),
                                жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            Подготовить_мену(пп.h, пп.h.people[Герой.ID]);   // герою нужно — есть о чём просить
            return пп;
        }
        var п = Дом_();
        var h = п.h;
        var я = h.people[Герой.ID];
        foreach (double x in new[] { -3.7, -0.0, 0.0, 2.5 })
            foreach (var кто in h.others(я).Take(3).Append(я))
                if (BitConverter.DoubleToInt64Bits(Поправки.Уговор_игры(кто, x)) != BitConverter.DoubleToInt64Bits(x))
                    плохо.Add($"уговор: без игры мерка {Текст.G(x)} у {кто.id} сдвинулась");

        // ---- 3. живая просьба ----
        string живая_итог;
        {
            string[] ЧТО = { "еда", "вода", "топливо" };
            // кандидаты — по мерке «открыл»: открыть ли, хозяин решает монетой
            // (`Решение.монета`), и какой вышла дверь, видно по исходу `_ask`
            List<(string кто, string что)> Кандидаты(Func<double, bool> годится)
                => h.others(я).Where(x => x.здесь() && !h.под_одной_крышей(x, я))
                    .SelectMany(t => ЧТО.Where(р => t.stock.Взять(р, 0.0) >= 2.0
                                                    && годится(Действия.даст_ли(h, t, я, р, false, h.B)))
                                        .Select(р => (t.id, р)))
                    .Take(6).ToList();
            string Исход(string кто, string что, double? качество)
            {
                var пп = Дом_();
                var яя = пп.h.people[Герой.ID];
                яя.сыграно = качество is double к ? МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, к, ручки) : null;
                return Действия._ask(пп.h, яя, пп.h.people[кто], что);
            }
            bool Дали(string s) => s.Contains("— дали", StringComparison.Ordinal);
            bool Открыли(string s) => !s.Contains("через дверь", StringComparison.Ordinal)
                                      && !s.Contains("драка", StringComparison.Ordinal);
            var мерки = h.others(я).Where(x => x.здесь() && !h.под_одной_крышей(x, я))
                .SelectMany(t => ЧТО.Where(р => t.stock.Взять(р, 0.0) >= 2.0)
                    .Select(р => (t.id, р, о: Действия.даст_ли(h, t, я, р, false, h.B))))
                .OrderBy(x => Math.Abs(x.о)).Take(6).ToList();
            w($"  ближайшие мерки «дать ли» (дверь открыта): {string.Join("; ", мерки.Select(x => $"{x.id} {x.р} {Текст.G(Текст.Округлить(x.о, 2))}"))}");
            var части = new List<string>();
            bool нашлось = false;
            foreach (var (кто, что) in Кандидаты(м => м < -0.05 && м > -сила + 0.05))
            {
                string без = Исход(кто, что, null);
                if (!Открыли(без))
                    continue;
                string обычно = Исход(кто, что, 0.5), лучше = Исход(кто, что, 1.0);
                if (Дали(без) || обычно != без || !Дали(лучше))
                    плохо.Add($"уговор: пограничная просьба — без уговоров «{без}», как обычно «{обычно}», удачные «{лучше}»");
                части.Add($"удачные: «{без}» → «{лучше}»");
                нашлось = true;
                break;
            }
            if (!нашлось)
                плохо.Add("уговор: в доме нет пограничной просьбы с открытой дверью, которую решают удачные уговоры");
            нашлось = false;
            foreach (var (кто, что) in Кандидаты(м => м > 0.05 && м < сила - 0.05))
            {
                string без = Исход(кто, что, null);
                if (!Открыли(без))
                    continue;
                string хуже = Исход(кто, что, 0.0);
                if (!Дали(без) || Дали(хуже))
                    плохо.Add($"уговор: пограничная просьба — без уговоров «{без}», неудачные «{хуже}»");
                части.Add($"неудачные: «{без}» → «{хуже}»");
                нашлось = true;
                break;
            }
            if (!нашлось)
                плохо.Add("уговор: в доме нет пограничной просьбы с открытой дверью, которую ломают неудачные уговоры");
            живая_итог = string.Join("; ", части);
        }

        // ---- 4. провал, экран и ядро ----
        string провал_итог;
        {
            var кому = h.others(я).First(x => x.здесь());
            double было = кому.trust.Взять(я.id, 3.0);
            Реплики.Просьба_сорвалась(кому, я, ручки);
            double стало = кому.trust.Взять(я.id, 3.0);
            if (!(стало < было))
                плохо.Add($"уговор: просил не так — а доверие {кому.id} не упало");
            провал_итог = $"доверие {Текст.G(Текст.Округлить(было, 2))} → {Текст.G(Текст.Округлить(стало, 2))}";

            string просьба = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Ядро", "Действия.Просьба.cs"));
            if (!просьба.Contains("Поправки.Уговор_игры(npc, даст_ли(h, target, npc, res, через_дверь, b))", StringComparison.Ordinal))
                плохо.Add("уговор: просьба решается мимо уговоров");
            string Файл(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя));
            string узел = Файл("ДомУзел.cs"), игра = Файл("ДомУзел.РазговорИгра.cs");
            if (!узел.Contains("просьба: дело_дома.Item1 == \"попросить\");", StringComparison.Ordinal))
                плохо.Add("уговор: ответ «попросить» идёт мимо реплики на время");
            if (!игра.Contains("bool не_так = и.просьба && Реплики.Торг_сорван(к);", StringComparison.Ordinal)
                || !игра.Contains("Реплики.Просьба_сорвалась(и.с, _партия.сеанс.я, _ручки);", StringComparison.Ordinal))
                плохо.Add("уговор: неудачные уговоры ничего не значат");
        }

        w($"  живая просьба: {живая_итог}");
        w($"  провал: {провал_итог}");
        return плохо;
    }
}
