// Проверка ноши и хода «сам»: найденное несут, а не переносят, и время
// идёт от поступков, а не только от ответов.
//
//  1. **Ход «сам».** Ответ `ВопросИгроку.САМ` на вопрос дня: дом
//     не исполняет ничего, и день идёт дальше. Через партию: часы,
//     потраченные поступком, сдвигают часы героя, соседи в эти часы
//     ходят, и вопрос приходит новый. На любой другой вопрос «сам» —
//     обычный номер мимо списка, а партия пропуска не принимает.
//     Автор так и заметил: взлом не тратил ни часа, а день стоял.
//  2. **Обыск стоит часов** — `обыск_часы`, в гараже помноженные
//     на погоду, в погребе — нет; не успеть до ночи — не берётся.
//  3. **Найденное не в шкафу.** Пока несут, шкаф героя не меняется;
//     дома тара разгружается вся и сразу.
//  4. **Тара** — место и шум по ручкам, и одно покупается другим: чем
//     громче тара, тем больше в неё влезает, и ни одна не лучше прочих
//     во всём (первая раскладка дала рюкзаку и то и другое — и выбор
//     опустел); что не влезло — в кладовой;
//     начатую тару не меняют; в карман — мимо шкафа, сколько влезет;
//     без тары и без кармана не уносится ничего.
//  5. **Шум.** Пакет слышат чаще рюкзака; кто услышал, помнит
//     «возвращение» того, кто нёс; пустую тару не слышно.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Ноша_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        static House Дом_(TextWriter? куда = null)
            => new Прогон(Пути.Данные, seed: 1, days: 1,
                          журнал: new Журнал(1, false, куда ?? TextWriter.Null)).h;
        static double Всего(Словарь<string, double> з) => з.Ключи.Sum(к => з[к]);

        // ---- 1. ход «сам» ----
        string сам_итог;
        {
            // напрямую: решающий отвечает «сам» — дом не делает ничего
            var лог = new StringWriter();
            var h = Дом_(лог);
            var я = h.people["оксана"];
            я.решающий = new Человек((ВопросИгроку _) => ВопросИгроку.САМ);
            double было = я.time_left;
            int строк = лог.ToString().Length;
            if (!Действия.choose_and_do(h, я))
                плохо.Add("ход «сам» кончил герою день, а должен был пропустить ход");
            if (я.time_left != было)
                плохо.Add($"ход «сам» потратил {было - я.time_left} ч — дом что-то исполнил");
            if (лог.ToString().Length != строк)
                плохо.Add("ход «сам» оставил строку в журнале — дом что-то исполнил");

            // на другой вопрос «сам» — номер мимо списка: ближайший край
            var с = new Ситуация
            {
                вопрос = Вопрос.ДАТЬ_ИЗ_СВОЕГО,
                варианты = new() { ("дать", 0.7), ("отказать", 0.3) },
                склонность = 0.7,
            };
            string? ответ = ((Решающий)я.решающий).ответ(h, я, с);
            if (ответ != "дать")
                плохо.Add($"«сам» на просьбу соседа дал «{ответ}», а не ближайший край");
            try
            {
                string? тема = ((Решающий)я.решающий).выбор(h, я, Вопрос.О_ЧЁМ_ГОВОРИТЬ,
                    new[] { ("погода", 0.6), ("еда", 0.4) });
                if (тема != "погода")
                    плохо.Add($"«сам» на выборе темы дал «{тема}», а не ближайший край");
            }
            catch (Exception e)
            {
                плохо.Add($"«сам» на выборе темы уронил решение: {e.GetType().Name}");
            }
        }
        {
            // через партию: поступок на три часа — и соседи в эти часы ходят
            const double ЧАСОВ = 3.0;
            var прогон = new Прогон(Пути.Данные, seed: 31, days: 2);
            using var партия = new Дом.Экран.Партия(прогон, "лида");
            партия.Начать();
            var в0 = партия.Дождаться();
            while (в0 is not null && в0.вопрос != Вопрос.ЧТО_ДЕЛАТЬ)
            {
                партия.Ответить(0);
                в0 = партия.Дождаться();
            }
            if (в0 is null)
            {
                плохо.Add("за два дня партия ни разу не спросила, что делать");
                сам_итог = "—";
            }
            else
            {
                var h = партия.сеанс.дом;
                var я = партия.сеанс.я;
                double т0 = я.time_left, ч0 = я.час();
                double другие0 = h.alive().Where(p => p.id != я.id).Sum(p => p.time_left);
                я.time_left -= ЧАСОВ;             // поступок, пока дом спит
                if (!партия.Пропустить())
                    плохо.Add("партия не пропустила ход на вопросе дня");
                var в1 = партия.Дождаться();
                сам_итог = "дом кончился";
                if (в1 is null)
                    плохо.Add("после пропуска хода дом кончился");
                else
                {
                    double другие1 = h.alive().Where(p => p.id != я.id).Sum(p => p.time_left);
                    if (ReferenceEquals(в1, в0))
                        плохо.Add("после пропуска хода тот же вопрос");
                    if (другие1 >= другие0)
                        плохо.Add("пока герой возился, соседи не сделали ни шага — время не пошло");
                    if (в1.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
                    {
                        if (Math.Abs(я.time_left - (т0 - ЧАСОВ)) > 1e-9)
                            плохо.Add($"после пропуска у героя {Текст.Ф(я.time_left, 2)} ч, "
                                      + $"а должно {Текст.Ф(т0 - ЧАСОВ, 2)}");
                        if (Math.Abs(я.час() - (ч0 + ЧАСОВ)) > 1e-9)
                            плохо.Add($"часы героя {Текст.Ф(я.час(), 2)}, "
                                      + $"а после поступка должны быть {Текст.Ф(ч0 + ЧАСОВ, 2)}");
                    }
                    сам_итог = $"герой {Текст.Ф(ч0, 1)} → {Текст.Ф(я.час(), 1)} ч, "
                               + $"соседи прожили {Текст.Ф(другие0 - другие1, 1)} ч";
                }
                while (в1 is not null)
                {
                    партия.Ответить(0);
                    в1 = партия.Дождаться();
                }
                партия.Досидеть();
            }
            if (партия.Пропустить())
                плохо.Add("партия пропустила ход, когда её никто не спрашивал");
        }

        // ---- 2. обыск стоит часов ----
        string часы_итог;
        {
            var h = Дом_();
            var гараж = h.кладовые["гараж13"];
            var погреб = h.кладовые.Значения.First(x => x.вид == ВидКладовой.ПОГРЕБ);
            var я = h.people["оксана"];
            double база = ручки["обыск_часы"];
            if (Math.Abs(Обыск.часы(h, погреб, ручки) - база) > 1e-12)
                плохо.Add($"коробка в погребе стоит {Обыск.часы(h, погреб, ручки)} ч, "
                          + $"а погода туда не доходит — должна {база}");
            double тихо = Обыск.часы(h, гараж, ручки);
            h.снег += 1.0;
            double по_снегу = Обыск.часы(h, гараж, ручки);
            if (Math.Abs(по_снегу - база * Улица.погода_часы(h)) > 1e-12 || по_снегу <= тихо)
                плохо.Add($"гараж по снегу — {Текст.Ф(по_снегу, 3)} ч против {Текст.Ф(тихо, 3)}: "
                          + "погода не растягивает обыск");
            я.time_left = 16.0;
            var д = Обыск.коробка(h, я, гараж, 3, ручки);
            if (Math.Abs(я.time_left - (16.0 - по_снегу)) > 1e-9 || д.часы != по_снегу)
                плохо.Add($"коробка заняла {Текст.Ф(16.0 - я.time_left, 3)} ч, "
                          + $"а должна {Текст.Ф(по_снегу, 3)}");
            Обыск.оставить(h, я, гараж, д);
            я.time_left = по_снегу - 0.01;
            if (Обыск.успеет(h, я, гараж, ручки))
                плохо.Add("до ночи меньше, чем нужно на коробку, а обыск берётся");
            часы_итог = $"коробка — {Текст.Ф(база, 2)} ч, в гараже по снегу — {Текст.Ф(по_снегу, 2)}";
        }

        // тара, в которую влезает больше всех, и та, в которую меньше:
        // проверка не должна зависеть от того, какая из них какая
        var большая = Тары.ВСЕ.OrderByDescending(т => т.мест(ручки)).First();
        var малая = Тары.ВСЕ.OrderBy(т => т.мест(ручки)).First();
        var другая = Тары.ВСЕ.First(т => т != малая);

        // ---- 3. найденное не в шкафу ----
        {
            var h = Дом_();
            var к = h.кладовые["гараж13"];
            var я = h.people["оксана"];
            я.ноша = new Ноша();
            к.stock.Очистить();
            к.stock["топливо"] = 5;
            к.stock["материалы"] = 4;
            var шкаф = new Словарь<string, double>(я.stock);
            for (int коробок = 3; коробок >= 1; коробок--)
            {
                var д = Обыск.коробка(h, я, к, коробок, ручки);
                Обыск.унести(h, я, к, д, большая, ручки);
                if (Строкой(я.stock) != Строкой(шкаф))
                {
                    плохо.Add("найденное оказалось в шкафу раньше, чем герой дошёл до дома");
                    break;
                }
            }
            if (большая.мест(ручки) < 9)
                плохо.Add($"в самую большую тару ({большая.Текст()}) не влезает и девяти — "
                          + "проверка переноса целиком не про что");
            if (!к.пусто())
                плохо.Add($"три коробки — {большая.Куда()}, а в кладовой осталось «{Строкой(к.stock)}»");
            if (я.ноша.Сколько("топливо") != 5 || я.ноша.Сколько("материалы") != 4
                || я.ноша.тара != большая)
                плохо.Add($"{большая.Где()} «{я.ноша}», а несли топливо 5 и материалы 4");
            var разложено = я.ноша.Разгрузить(я);
            if (я.stock.Взять("топливо", 0.0) - шкаф.Взять("топливо", 0.0) != 5
                || я.stock.Взять("материалы", 0.0) - шкаф.Взять("материалы", 0.0) != 4
                || Всего(разложено) != 9)
                плохо.Add($"разгрузили «{Строкой(разложено)}», а в шкаф пришло не 5 и 4");
            if (!я.ноша.пусто || я.ноша.тара is not null)
                плохо.Add("после разгрузки тара не освободилась");
        }

        // ---- 4. тара: место, одна за раз, карман ----
        string тара_итог;
        {
            var мест = Тары.ВСЕ.Select(т => т.мест(ручки)).ToList();
            var шум = Тары.ВСЕ.Select(т => т.шум(ручки)).ToList();
            // тара, которая и вмещает не меньше, и шумит не громче другой,
            // делает ту, другую, ненужной
            foreach (var а in Тары.ВСЕ)
                foreach (var б in Тары.ВСЕ)
                    if (а != б && а.мест(ручки) >= б.мест(ручки) && а.шум(ручки) <= б.шум(ручки))
                        плохо.Add($"{а.Текст()} ({а.мест(ручки)} места, шум {а.шум(ручки)}) "
                                  + $"во всём не хуже, чем {б.Текст()} ({б.мест(ручки)}, "
                                  + $"шум {б.шум(ручки)}) — выбирать не из чего");

            var h = Дом_();
            var к = h.кладовые["гараж13"];
            var я = h.people["оксана"];
            я.ноша = new Ноша();
            я.карман = null;
            к.stock.Очистить();
            к.stock["топливо"] = 5;
            к.stock["материалы"] = 4;
            к.stock["еда"] = 3;
            double в_мире = Всего(к.stock);
            var шкаф = new Словарь<string, double>(я.stock);

            // малая тара полна — остаток в кладовой
            if (малая.мест(ручки) >= в_мире)
                плохо.Add($"в самую малую тару ({малая.Текст()}) влезает всё — "
                          + "проверка переполнения не про что");
            var д = Обыск.коробка(h, я, к, 1, ручки);
            var взято = Обыск.унести(h, я, к, д, малая, ручки);
            if (Math.Abs(Всего(взято) - малая.мест(ручки)) > 1e-9)
                плохо.Add($"{малая.Куда()} легло {Всего(взято)}, а влезает {малая.мест(ручки)}");
            if (Math.Abs(Всего(к.stock) + я.ноша.занято - в_мире) > 1e-9)
                плохо.Add($"не влезшее потерялось: в кладовой {Всего(к.stock)}, "
                          + $"{малая.Где()} {я.ноша.занято}, а было {в_мире}");

            // начатую тару не меняют
            д = Обыск.коробка(h, я, к, 1, ручки);
            взято = Обыск.унести(h, я, к, д, другая, ручки);
            if (взято.Ключи.Count > 0 || я.ноша.тара != малая)
                плохо.Add($"в начатую тару ({малая.Текст()}) подложили другую: взято «{Строкой(взято)}»");

            // без тары и без кармана не уносится ничего
            double осталось = Всего(к.stock);
            д = Обыск.коробка(h, я, к, 1, ручки);
            взято = Обыск.унести(h, я, к, д, null, ручки);
            if (взято.Ключи.Count > 0 || Math.Abs(Всего(к.stock) - осталось) > 1e-9)
                плохо.Add("без тары и без кармана что-то унесли");

            // в карман — мимо шкафа, сколько влезет
            я.карман = new Карман(new Умения(new Наследие(), ручки));
            д = Обыск.коробка(h, я, к, 1, ручки);
            взято = Обыск.унести(h, я, к, д, null, ручки);
            if (Math.Abs(Всего(взято) - Math.Min(осталось, я.карман.предел)) > 1e-9
                || Math.Abs(я.карман.занято - Всего(взято)) > 1e-9)
                плохо.Add($"в карман легло {Всего(взято)} (в кармане {я.карман.занято}), "
                          + $"а влезало {Math.Min(осталось, я.карман.предел)}");
            if (Строкой(я.stock) != Строкой(шкаф))
                плохо.Add("найденное в карман легло в шкаф");
            if (Math.Abs(Всего(к.stock) + я.ноша.занято + я.карман.занято - в_мире) > 1e-9)
                плохо.Add("кладовая, пакет и карман вместе не сходятся с тем, что было");
            тара_итог = string.Join(", ", Тары.ВСЕ.Select(т => $"{т.Текст()} {т.мест(ручки)}/шум {т.шум(ручки)}"))
                        + $"; карман {я.карман.предел}";
        }

        // ---- 5. шум ----
        string шум_итог;
        {
            var h = Дом_();
            var я = h.people["оксана"];
            int Слышали(Тара т, int раз)
            {
                var н = new Ноша();
                var вещи = Словари.Числа();
                вещи["еда"] = 1;
                н.Положить(т, вещи, ручки);
                int всего = 0;
                for (int i = 0; i < раз; i++)
                    всего += н.Пронести(h, я, ручки).Count;
                return всего;
            }
            const int РАЗ = 200;
            int пакет = Слышали(Тара.ПАКЕТ, РАЗ);
            int рюкзак = Слышали(Тара.РЮКЗАК, РАЗ);
            if (пакет <= рюкзак)
                плохо.Add($"пакет услышали {пакет} раз, рюкзак — {рюкзак}: пакет не громче");
            if (new Ноша().Пронести(h, я, ручки).Count != 0)
                плохо.Add("пустую тару услышали");
            bool помнят = h.alive().Any(p => p.memory.Any(
                м => м.вид == Вид.СЛЫШАЛ && м.кто == я.id && м.что == "возвращение"));
            if (!помнят)
                плохо.Add("ношу слышали, а никто не запомнил, что герой вернулся с улицы");
            шум_итог = $"за {РАЗ} проходов услышали: пакет — {пакет}, рюкзак — {рюкзак}";
        }

        w($"  ход «сам»: {сам_итог}");
        w($"  обыск: {часы_итог}");
        w($"  тара: {тара_итог}; найденное дома — только после разгрузки");
        w($"  шум: {шум_итог}");
        return плохо;
    }
}
