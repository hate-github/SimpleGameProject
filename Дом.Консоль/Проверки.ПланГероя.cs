// Проверка плана подъезда глазами героя (просьба автора: «убери из плана
// подъезда то, чего герой знать не может»; `Дом.Экран/ПланГероя.cs`).
//
//  1. **Кто.** Незнакомый — «сосед» без занятия; познакомился — имя и занятие.
//  2. **Умершие.** Умер, а герой не знает — на плане жив, у своей двери,
//     в «не здесь» его нет; узнал — в «не здесь», с днём и причиной.
//  3. **Двери.** Не был на этаже — пометок нет; был — есть; дверь потом
//     изменилась — на плане как видел, пока не увидит снова.
//  4. **События.** Тихое чужое — нет; громкое, пока он в доме, — да;
//     громкое, пока он в участке, — нет; с ним, пока его не было, — нет,
//     вернулся — да; слышал про того, кто это делал, в тот день — да.
//     Правда дома (`Квартиры`, `ВКвартире`) — прежняя: по ней рисуются двери.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> ПланГероя_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var профиль = new ПрофильГероя("Андрей");
        var прогон = new Прогон(Пути.Данные, seed: 5, days: 10,
                                журнал: new Журнал(0, false, TextWriter.Null),
                                жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
        new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, Герой.ID);
        var h = прогон.h;
        h.day = 3;
        var я = h.people[Герой.ID];
        var о = Округа.У(h)!;
        var сеанс = new Сеанс(h, Герой.ID);
        var чужие = h.others(я).Where(p => p.здесь()).OrderBy(p => p.id, StringComparer.Ordinal).ToList();
        КвартираГероя Кв(int apt) => сеанс.План_героя().First(к => к.номер == apt);

        // ---- 1. кто ----
        var икс = чужие[0];
        var был = Кв(икс.apt);
        if (был.кто != Знакомство.Сосед(икс) || был.роль.Length > 0)
            плохо.Add($"незнакомый на плане: «{был.кто}» — «{был.роль}»; а надо просто «{Знакомство.Сосед(икс)}»");
        о.Узнал(Знакомство.ИМЯ + икс.id);
        var стал = Кв(икс.apt);
        if (стал.кто != икс.@short || стал.роль != икс.role)
            плохо.Add($"знакомый на плане без имени или занятия: «{стал.кто}» — «{стал.роль}»");

        // ---- 2. умершие ----
        var игрек = чужие.First(p => p.id != икс.id && string.IsNullOrEmpty(p.living_with) && p.guests.Count == 0);
        игрек.alive = false;
        игрек.died_day = h.day;
        игрек.cause = "замёрз";
        if (Кв(игрек.apt).кто is null || сеанс.Выбыли_героя().Any(в => в.квартира == игрек.apt))
            плохо.Add("сосед умер, а герой об этом не знает, — а на плане его квартира пуста или он в «не здесь»");
        я.знает_о_смерти.Add(игрек.id);
        var выбыл = сеанс.Выбыли_героя().FirstOrDefault(в => в.квартира == игрек.apt);
        if (выбыл is null || выбыл.день != h.day || выбыл.причина != "замёрз"
            || Кв(игрек.apt).кто is not null && h.people.Значения.Count(p => p.здесь() && h.хозяин_жилья(p).apt == игрек.apt) == 0)
            плохо.Add("герой узнал о смерти — а в «не здесь» соседа нет (или квартира на плане всё ещё его)");

        // ---- 3. двери ----
        var дверь = h.flats.Значения.First(f => f.apt != я.apt && f.floor != я.floor && !f.открыта);
        дверь.открыта = true;
        if (Кв(дверь.apt).метки.Contains("открыта"))
            плохо.Add("на этаже не был — а про сорванный замок знает");
        сеанс.Увидел_этаж(дверь.floor);
        if (!Кв(дверь.apt).метки.Contains("открыта"))
            плохо.Add("был на этаже, видел сорванный замок — а на плане его нет");
        дверь.открыта = false;
        if (!Кв(дверь.apt).метки.Contains("открыта"))
            плохо.Add("дверь починили без него — а план уже знает");
        сеанс.Увидел_этаж(дверь.floor);
        if (Кв(дверь.apt).метки.Contains("открыта"))
            плохо.Add("увидел починенную дверь — а на плане замок всё сорван");

        // ---- 4. события ----
        var а = чужие.First(p => p.здесь() && p.id != икс.id);
        var б = чужие.First(p => p.здесь() && p.id != а.id && p.id != икс.id);
        var в_ = чужие.First(p => p.здесь() && p.id != а.id && p.id != б.id && p.id != икс.id);
        bool Знает(ВидСобытия вид, int где) => Кв(где).события.Any(с => с.вид == вид);
        h.событие(ВидСобытия.КРАЖА, кто: а.id, кому: б.id, где: б.apt);
        bool тихое = Знает(ВидСобытия.КРАЖА, б.apt);
        h.событие(ВидСобытия.НАЛЁТ, кто: а.id, кому: б.id, где: б.apt);
        bool громкое = Знает(ВидСобытия.НАЛЁТ, б.apt);
        о.участок!.Пришёл(я);
        h.событие(ВидСобытия.НАЛЁТ, кто: а.id, кому: в_.id, где: в_.apt);
        bool громкое_без = Знает(ВидСобытия.НАЛЁТ, в_.apt);
        h.событие(ВидСобытия.КРАЖА, кто: а.id, кому: я.id, где: я.apt);
        bool у_него_без = Знает(ВидСобытия.КРАЖА, я.apt);
        о.участок.Ушёл(я);
        bool у_него_вернулся = Знает(ВидСобытия.КРАЖА, я.apt);
        h.событие(ВидСобытия.ОБМЕН, кто: в_.id, кому: б.id, где: б.apt);
        bool до_слуха = Знает(ВидСобытия.ОБМЕН, б.apt);
        я.memory.Add(new Память { день = h.day, вид = Вид.СЛЫШАЛ, кто = в_.id, что = "шаги" });
        bool слышал = Знает(ВидСобытия.ОБМЕН, б.apt);
        if (тихое)
            плохо.Add("чужая тихая кража — а на плане она есть");
        if (!громкое)
            плохо.Add("налёт в подъезде, пока герой дома, — а на плане его нет");
        if (громкое_без)
            плохо.Add("налёт, пока герой в участке, — а на плане он есть");
        if (у_него_без)
            плохо.Add("его квартиру обокрали, пока он в участке, — а план уже знает");
        if (!у_него_вернулся)
            плохо.Add("вернулся — а про кражу у себя план молчит");
        if (до_слуха || !слышал)
            плохо.Add($"чужой обмен: до слуха {(до_слуха ? "уже знает" : "не знает")}, услышал — {(слышал ? "знает" : "всё не знает")}");
        // правда дома — прежняя: по ней рисуются двери и печатает консоль
        if (!сеанс.ВКвартире(б.apt).Any(с => с.вид == ВидСобытия.КРАЖА)
            || сеанс.Квартиры().First(к => к.номер == дверь.apt).открыта != дверь.открыта)
            плохо.Add("правда дома (`ВКвартире`, `Квартиры`) перестала быть правдой");

        w($"  незнакомый — «{был.кто}», знакомый — «{стал.кто} — {стал.роль}»; умерший без ведома — жив на плане, узнал — «{выбыл?.имя} — † день {выбыл?.день}»");
        w($"  события: тихое чужое {(тихое ? "видно" : "нет")}, налёт дома {(громкое ? "видно" : "нет")}, налёт из участка {(громкое_без ? "видно" : "нет")}, "
          + $"кража у него без него {(у_него_без ? "видно" : "нет")} → вернулся {(у_него_вернулся ? "видно" : "нет")}, услышал {(слышал ? "видно" : "нет")}");
        return плохо;
    }
}
