// Проверка торга (ГДД 7: мини-игра «Разговор» — «убеждение, торг, отвод
// подозрений»; провал — падение доверия).
//
//  1. **Множитель.** Половина — ровно единица; ноль и единица — на
//     `мини_торг_сила` ниже и выше; растёт с качеством. У соседей, без игры
//     и у других игр — единица.
//  2. **Мена.** Выгода мены для соседа (`Действия.Выгода_мены`) — его цена
//     предложенного, умноженная на торг, минус цена отданного: в живом доме
//     есть пара, где без торга сосед отказал бы, а после удачного — взял бы,
//     и пара наоборот. «Как обычно» — бит в бит прежняя выгода.
//  2б. **Живая мена.** После подготовки пробы (`Подготовить_мену`) мена
//     находится; живые сделки соседу выгодны с запасом больше силы торга —
//     торг решает пограничные. Пограничная делается из живой (у соседа меньше
//     отдаваемого), и настоящий `_trade` даёт: без торга и «как обычно» —
//     взял, после сорванного — отказал.
//  3. **Провал.** Сорванный торг (порог — как у лжи) роняет доверие соседа.
//  4. **Ядро и экран.** `_trade` считает выгоду через `Выгода_мены`; ответ
//     «обмен» идёт через реплику с флагом торга; срыв зовёт `Торг_сорвался` (скан).

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Торг_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        double сила = ручки["мини_торг_сила"];

        // ---- 1. множитель ----
        if (сила <= 0.0 || сила >= 1.0)
            плохо.Add($"торг: сила {Текст.G(сила)} — вне (0, 1): торг или ничего не решает, или переворачивает цену");
        if (МиниИгры.Торг(0.5, ручки) != 1.0
            || Math.Abs(МиниИгры.Торг(1.0, ручки) - (1.0 + сила)) > 1e-12
            || Math.Abs(МиниИгры.Торг(0.0, ручки) - (1.0 - сила)) > 1e-12
            || !(МиниИгры.Торг(0.25, ручки) < МиниИгры.Торг(0.75, ручки)))
            плохо.Add("торг: множитель не тот — половина не единица, края не на силу или не растёт");
        if (МиниИгры.Какая("обмен") != МиниИгра.РАЗГОВОР)
            плохо.Add("торг: перед меной нет «Разговора»");
        foreach (var м in new[] { МиниИгра.РЕМОНТ, МиниИгра.ВЗЛОМ, МиниИгра.РАБОТА })
            if (МиниИгры.Сыграно_для(м, 1.0, ручки).торг != 1.0)
                плохо.Add($"торг: «{м}» двигает цену мены");

        var профиль = new ПрофильГероя("Андрей");
        var п = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null),
                           жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
        var h = п.h;
        var я = h.people[Герой.ID];
        var соседи = h.others(я).Where(x => x.здесь()).ToList();
        if (соседи.Any(x => Поправки.Торг_игры(x) != 1.0) || Поправки.Торг_игры(я) != 1.0)
            плохо.Add("торг: без игры (или у соседа) торг не единица");

        // ---- 2. мена ----
        (string кто, string что, string за)? вверх = null, вниз = null;
        int пар = 0, разошлось = 0;
        foreach (var b in соседи)
            foreach (var give in Действия.TRADABLE)
                foreach (var get_ in Действия.TRADABLE)
                {
                    if (string.Equals(give, get_, StringComparison.Ordinal))
                        continue;
                    пар++;
                    я.сыграно = null;
                    double без = Действия.Выгода_мены(я, b, give, 1.0, get_, 1.0);
                    double прежде = Социальное.value_of(b, give, 1.0) - Социальное.value_of(b, get_, 1.0);
                    я.сыграно = МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, 0.5, ручки);
                    double обычно = Действия.Выгода_мены(я, b, give, 1.0, get_, 1.0);
                    я.сыграно = МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, 1.0, ручки);
                    double лучше = Действия.Выгода_мены(я, b, give, 1.0, get_, 1.0);
                    я.сыграно = МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, 0.0, ручки);
                    double хуже = Действия.Выгода_мены(я, b, give, 1.0, get_, 1.0);
                    if (без != прежде || обычно != прежде)
                        разошлось++;
                    if (вверх is null && без <= 0.0 && лучше > 0.0)
                        вверх = (b.id, give, get_);
                    if (вниз is null && без > 0.0 && хуже <= 0.0)
                        вниз = (b.id, give, get_);
                }
        я.сыграно = null;
        if (разошлось > 0)
            плохо.Add($"торг: без игры или «как обычно» выгода мены не прежняя — в {разошлось} парах из {пар}");
        if (вверх is null)
            плохо.Add($"торг: ни в одной из {пар} пар удачный торг не уговаривает — он ничего не решает");
        if (вниз is null)
            плохо.Add($"торг: ни в одной из {пар} пар сорванный торг не отваживает");

        // ---- 2б. живая мена: та же подготовка, что у пробы (`ДомУзел.Проба_мена`) ----
        string живая_итог;
        {
            Прогон Готовый()
            {
                var пп = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null),
                                    жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
                var hh = пп.h;
                var яя = hh.people[Герой.ID];
                Подготовить_мену(hh, яя);
                return пп;
            }
            var п0 = Готовый();
            var я0 = п0.h.people[Герой.ID];
            var сделки = п0.h.others(я0).Where(x => x.здесь())
                .Select(x => (x, сделка: Действия.find_deal(п0.h, я0, x)))
                .Where(x => x.сделка is not null).ToList();
            if (сделки.Count == 0)
                плохо.Add("торг: после подготовки пробы мены нет ни с кем — проба до торга не дойдёт");
            // Сделки, которые мена выбирает, соседу выгодны с запасом (сейчас
            // больше силы торга), и торг их не решает — он решает пограничные.
            // Пограничную делаем из живой: у соседа меньше того, что он отдаёт, —
            // и отданное он ставит выше. Сосед и сделка те же, `_trade` — настоящий
            if (сделки.Count == 0)
                живая_итог = "сделок нет";
            else
            {
                var (b0, сд) = сделки[0];
                var ((give, gn), (get_, tn)) = сд!.Value;
                double исходно = b0.stock.Взять(get_, 0.0);
                double? Запас(double у_него)
                {
                    b0.stock[get_] = у_него;
                    double цена = Социальное.value_of(b0, give, gn);
                    double m = цена > 0 ? (цена - Социальное.value_of(b0, get_, tn)) / цена : double.NaN;
                    b0.stock[get_] = исходно;
                    return double.IsNaN(m) ? null : m;
                }
                double? ломает = null, уговаривает = null;
                var пройдено = new List<string>();
                for (double у = исходно; у >= tn + 0.01; у = у > tn + 1.0 ? у * 0.92 : у - 0.05)
                {
                    if (пройдено.Count < 400 && Запас(у) is double mm)
                        пройдено.Add($"{Текст.G(Текст.Округлить(у, 2))}:{Текст.G(Текст.Округлить(mm, 2))}");
                    if (Запас(у) is not double m)
                        continue;
                    if (ломает is null && m > 0.02 && m < сила - 0.02)
                        ломает = у;
                    if (уговаривает is null && m < -0.02 && m > -сила + 0.02)
                        уговаривает = у;
                }
                string Исход(double у_него, double? качество)
                {
                    var пп = Готовый();
                    var яя = пп.h.people[Герой.ID];
                    var бб = пп.h.people[b0.id];
                    бб.stock[get_] = у_него;
                    яя.сыграно = качество is double к ? МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, к, ручки) : null;
                    return Действия._trade(пп.h, яя, бб) ?? "нечего";
                }
                bool Взял(string s) => !s.Contains("не стал", StringComparison.Ordinal) && !s.Contains("нечего", StringComparison.Ordinal);
                var части = new List<string>();
                if (ломает is double л)
                {
                    string без = Исход(л, null), обычно = Исход(л, 0.5), хуже = Исход(л, 0.0);
                    if (!Взял(без) || обычно != без || Взял(хуже))
                        плохо.Add($"торг: пограничная сделка — без торга «{без}», как обычно «{обычно}», сорванный «{хуже}»");
                    части.Add($"сорванный: «{без}» → «{хуже}»");
                }
                else
                    плохо.Add($"торг: у {b0.id} не вышло пограничной сделки, которую ломает сорванный торг");
                if (уговаривает is double у2)
                {
                    string без = Исход(у2, null), лучше = Исход(у2, 1.0);
                    if (Взял(без) || !Взял(лучше))
                        плохо.Add($"торг: пограничная сделка — без торга «{без}», удачный «{лучше}»");
                    части.Add($"удачный: «{без}» → «{лучше}»");
                }
                // обратное (удачный торг уговаривает) доказано на парах в п. 2:
                // у живой сделки цена ступенчатая, и в нужное окно она не попадает
                if (ломает is null)
                    w($"  {b0.id}: {give} за {get_}, у него {get_} → запас: {string.Join(" ", пройдено.Take(40))}");
                живая_итог = $"сделок {сделки.Count}; " + string.Join("; ", части);
            }
        }

        // ---- 3. провал ----
        string провал_итог;
        {
            var кому = соседи[0];
            double было = кому.trust.Взять(я.id, 3.0);
            Реплики.Торг_сорвался(кому, я, ручки);
            double стало = кому.trust.Взять(я.id, 3.0);
            if (!(стало < было))
                плохо.Add($"торг: сорвался — а доверие {кому.id} не упало ({Текст.G(было)} → {Текст.G(стало)})");
            if (!Реплики.Торг_сорван(0.3) || Реплики.Торг_сорван(0.6)
                || Реплики.Торг_сорван(0.44) != Реплики.Ложь_провалена(0.44))
                плохо.Add("торг: порог срыва не тот, что у лжи");
            провал_итог = $"доверие {Текст.G(Текст.Округлить(было, 2))} → {Текст.G(Текст.Округлить(стало, 2))}";
        }

        // ---- 4. ядро и экран ----
        {
            string просьба = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Ядро", "Действия.Просьба.cs"));
            if (!просьба.Contains("double их = Выгода_мены(a, b_npc, give, gn, get_, tn);", StringComparison.Ordinal))
                плохо.Add("торг: мена считает выгоду мимо торга");
            string Файл(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя));
            string узел = Файл("ДомУзел.cs"), игра = Файл("ДомУзел.РазговорИгра.cs");
            if (!узел.Contains("Разговор_перед_делом(номер, с_разговора, торг: дело_дома.Item1 == \"обмен\");", StringComparison.Ordinal))
                плохо.Add("торг: ответ «обмен» идёт мимо реплики на время");
            if (!игра.Contains("bool сорван = и.торг && Реплики.Торг_сорван(к);", StringComparison.Ordinal)
                || !игра.Contains("Реплики.Торг_сорвался(и.с, _партия.сеанс.я, _ручки);", StringComparison.Ordinal))
                плохо.Add("торг: сорванный торг ничего не значит");
        }

        w($"  уговаривает: {(вверх is { } в ? $"{в.кто} — {в.что} за {в.за}" : "—")}; отваживает: {(вниз is { } н ? $"{н.кто} — {н.что} за {н.за}" : "—")} (пар {пар})");
        w($"  живая мена: {живая_итог}");
        w($"  провал: {провал_итог}");
        return плохо;
    }

    /// <summary>Подготовка мены, та же, что у пробы в движке (`ДомУзел.Проба_мена`):
    /// дров с избытком, своих еды и воды нет, чужие шкафы видел.</summary>
    public static void Подготовить_мену(House h, NPC я)
    {
        я.stock["топливо"] = 60.0;
        я.stock["еда"] = 0.0;
        я.stock["вода"] = 0.0;
        foreach (var с in h.others(я).Where(с => с.здесь()))
        {
            я.memory.Add(new Память { день = h.day, вид = Вид.СМОТРЕЛ, кто = с.id });
            foreach (var р in Действия.TRADABLE)
                Социальное.note_signal(я, с.id, р, с.stock.Взять(р, 0.0), 1.0);
        }
    }
}
