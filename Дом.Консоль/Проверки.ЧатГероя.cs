// Проверка «написать в чат» (ГДД 14: «игрок выбирает тему, затем действие
// в теме»; «реплика в общем чате действует на всех, кто ещё в сети»).
//
//  1. **Дом не пишет за героя.** Отчаявшийся и самый общительный герой без
//     флага пишет просьбу сам (`Чат.daily_chat`), с флагом `пишет_сам` — нет;
//     соседи пишут, как писали.
//  2. **Последствия — соседские.** Реплика героя делает с прочитавшими то же,
//     что `Чат.Последствия`: просьба — осведомлённость и паника, тоска —
//     настроение, подозрение — «назвали вором» названного; не прочёл — как был.
//     Кто прочёл — мимо `h.rng`.
//  3. **Кого назвать.** Знает имя — по имени или квартире, не знает — только
//     по квартире; без названного — нельзя.
//  4. **Когда нельзя.** Раз в день; сети нет; телефон сел. Заряд снимается,
//     день написанного переживает сейв.
//  5. **Экран.** Узел ставит флаг до того, как дом пошёл, и пишет, пока дом
//     спит; телефон берёт темы из ядра (скан).

using System.Text.Json;
using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    /// <summary>Журнал, который помнит, кто писал в чат.</summary>
    private sealed class ЖурналЧата : Журнал
    {
        public readonly List<string> писали = new();
        public ЖурналЧата() : base(0, false, TextWriter.Null) { }
        public override void chat(string кто, string текст)
        {
            писали.Add(кто);
            base.chat(кто, текст);
        }
    }

    public static List<string> ЧатГероя_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var профиль = new ПрофильГероя("Андрей");
        var честный = new Скрипт(new Dictionary<Вопрос, string> { [Вопрос.СОВРАТЬ] = "сказать правду" });
        JsonElement lines;
        using (var док = JsonDocument.Parse(File.ReadAllText(Path.Combine(Пути.Данные, "lines.json"))))
            lines = док.RootElement.Clone();
        var шаблоны = ЧатГероя.Шаблоны(Пути.Данные);

        Прогон Дом_героя(ЖурналЧата? журнал = null)
        {
            var п = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: журнал ?? new ЖурналЧата(),
                               жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(п, Герой.ID);
            п.h.people[Герой.ID].решающий = честный;
            п.run();
            return п;
        }

        // ---- 1. дом не пишет за героя ----
        string сам_итог;
        {
            (bool герой_писал, int соседей) Раз(bool пишет_сам)
            {
                var ж = new ЖурналЧата();
                var п = Дом_героя(ж);
                var я = п.h.people[Герой.ID];
                я.пишет_сам = пишет_сам;
                я.traits["общительность"] = 10.0;        // пишет первым
                я.stock["еда"] = 0.0;                    // и пишет просьбу
                я.stock["вода"] = 0.0;
                ж.писали.Clear();
                Чат.daily_chat(п.h, lines);
                return (ж.писали.Contains(я.@short), ж.писали.Count(к => к != я.@short));
            }
            var без = Раз(false);
            var с = Раз(true);
            if (!без.герой_писал)
                плохо.Add("чат героя: отчаявшийся общительный герой и без флага не пишет — проверять нечего");
            if (с.герой_писал)
                плохо.Add("чат героя: с `пишет_сам` дом всё равно пишет за героя");
            if (с.соседей == 0)
                плохо.Add("чат героя: с флагом героя замолчал и весь чат");
            сам_итог = $"без флага герой пишет сам: {(без.герой_писал ? "да" : "нет")}, с флагом — "
                       + $"{(с.герой_писал ? "да" : "нет")}, соседских реплик {с.соседей}";
        }

        // ---- 2. последствия — соседские ----
        string последствия_итог;
        {
            var п = Дом_героя();
            var h = п.h;
            var я = h.people[Герой.ID];
            var о = Округа.У(h)!;
            var чужие = h.others(я).Where(x => x.здесь()).ToList();
            var aware = чужие.ToDictionary(x => x.id, x => x.сведения_о(я.id).aware);
            var паника = чужие.ToDictionary(x => x.id, x => x.panic);
            ulong rng_до = h.rng.Состояние;
            var н = ЧатГероя.Написать(h, я, о.телефон, ручки, шаблоны, "просьба", null, о.зерно);
            if (!н.да || н.текст is null)
                плохо.Add($"чат героя: просьба не написалась — «{н.весть}»");
            if (h.rng.Состояние != rng_до)
                плохо.Add("чат героя: реплика героя бросает `h.rng` — кто прочёл, решает зерно мира");
            var прочли = чужие.Where(x => Округа.Бросок(о.зерно, "чат:прочёл", x.id, h.day) < h.network).ToList();
            var не_прочли = чужие.Except(прочли).ToList();
            if (прочли.Count == 0 || не_прочли.Count == 0)
                плохо.Add($"чат героя: прочли {прочли.Count}, не прочли {не_прочли.Count} — сравнивать не с чем");
            foreach (var x in прочли)
                if (x.сведения_о(я.id).aware <= aware[x.id] && aware[x.id] < 100.0 - 1e-9)
                    плохо.Add($"чат героя: {x.id} прочёл просьбу, а о нужде героя знает не больше");
            foreach (var x in не_прочли)
                if (Math.Abs(x.сведения_о(я.id).aware - aware[x.id]) > 1e-9 || Math.Abs(x.panic - паника[x.id]) > 1e-9)
                    плохо.Add($"чат героя: {x.id} просьбу не прочёл, а что-то узнал");
            if (я.день_разговора != h.day)
                плохо.Add("чат героя: написал — а дом считает, что сегодня он ни с кем не говорил");
            if (Math.Abs(о.телефон.заряд - (100.0 - ручки["телефон_написать_заряд"])) > 1e-9)
                плохо.Add($"чат героя: заряд после реплики {о.телефон.заряд}, а надо {100.0 - ручки["телефон_написать_заряд"]}");
            if (Math.Abs(н.часов - ручки["телефон_написать_часов"]) > 1e-9)
                плохо.Add($"чат героя: реплика стоит {н.часов} ч, а ручка — {ручки["телефон_написать_часов"]}");

            // та же реплика соседской функцией на таком же доме — тот же дом
            var п2 = Дом_героя();
            var я2 = п2.h.people[Герой.ID];
            var прочли2 = п2.h.others(я2).Where(x => x.здесь() && прочли.Any(y => y.id == x.id)).ToList();
            п2.h.journal.chat(я2.@short, н.текст ?? "");
            Чат.Последствия(п2.h, я2, "просьба", я2, прочли2);
            foreach (var x in прочли)
            {
                var x2 = п2.h.people[x.id];
                if (Math.Abs(x.сведения_о(я.id).aware - x2.сведения_о(я2.id).aware) > 1e-9
                    || Math.Abs(x.panic - x2.panic) > 1e-9
                    || Math.Abs(x.believed(я.id, "еда") - x2.believed(я2.id, "еда")) > 1e-9)
                    плохо.Add($"чат героя: {x.id} после реплики героя не тот, что после соседской");
            }
            последствия_итог = $"просьбу прочли {прочли.Count} из {чужие.Count}, «{н.текст}»";
        }

        // ---- 2б. тоска и подозрение ----
        string подозрение_итог = "—";
        {
            var п = Дом_героя();
            var h = п.h;
            var я = h.people[Герой.ID];
            var о = Округа.У(h)!;
            var чужие = h.others(я).Where(x => x.здесь()).ToList();
            var прочли = чужие.Where(x => Округа.Бросок(о.зерно, "чат:прочёл", x.id, h.day) < h.network).ToList();
            var настроение = чужие.ToDictionary(x => x.id, x => x.mood);
            var н = ЧатГероя.Написать(h, я, о.телефон, ручки, шаблоны, "тоска", null, о.зерно);
            if (!н.да)
                плохо.Add($"чат героя: тоска не написалась — «{н.весть}»");
            foreach (var x in прочли)
                if (x.mood < настроение[x.id] + ручки_дома(h, "чат_настроение") - 1e-9 && настроение[x.id] < 100.0 - ручки_дома(h, "чат_настроение"))
                    плохо.Add($"чат героя: {x.id} прочёл тоску, а настроение не поднялось");

            // назавтра — подозрение о соседе, которого герой не знает по имени
            var п3 = Дом_героя();
            var h3 = п3.h;
            var я3 = h3.people[Герой.ID];
            var о3 = Округа.У(h3)!;
            var кого = h3.others(я3).Where(x => x.здесь()).OrderBy(x => x.apt).First();
            var слова_без = ЧатГероя.Слова(h3, шаблоны, "подозрение", false);
            if (слова_без.Count == 0 || слова_без.Any(s => s.Contains("{кто}", StringComparison.Ordinal)
                                                           || !s.Contains("{кв}", StringComparison.Ordinal)))
                плохо.Add("чат героя: не зная имени, можно назвать по имени (или никого не назвать)");
            var слова_с = ЧатГероя.Слова(h3, шаблоны, "подозрение", true);
            if (слова_с.Count == 0 || слова_с.Any(s => !s.Contains("{кто}", StringComparison.Ordinal)
                                                       && !s.Contains("{кв}", StringComparison.Ordinal)))
                плохо.Add("чат героя: в подозрении есть слова, что никого не называют");
            var без_имени = ЧатГероя.Написать(h3, я3, о3.телефон, ручки, шаблоны, "подозрение", null, о3.зерно);
            if (без_имени.да)
                плохо.Add("чат героя: подозрение без названного написалось");
            if (Знакомство.Знает(h3, я3, кого))
                плохо.Add($"чат героя: свежий герой уже знает имя {кого.id} — проверка «по квартире» вхолостую");
            int помнили = h3.others(я3).Sum(x => x.memory.Count(з => з.вид == Вид.НАЗВАЛИ_ВОРОМ && з.кто == кого.id));
            var н3 = ЧатГероя.Написать(h3, я3, о3.телефон, ручки, шаблоны, "подозрение", кого, о3.зерно);
            if (!н3.да || н3.текст is null)
                плохо.Add($"чат героя: подозрение о {кого.id} не написалось — «{н3.весть}»");
            else
            {
                if (!н3.текст.Contains($"кв.{кого.apt}", StringComparison.Ordinal)
                    || н3.текст.Contains(кого.@short, StringComparison.Ordinal))
                    плохо.Add($"чат героя: имени не знает, а назвал не по квартире — «{н3.текст}»");
                var прочли3 = h3.others(я3).Where(x => x.здесь() && Округа.Бросок(о3.зерно, "чат:прочёл", x.id, h3.day) < h3.network).ToList();
                int помнят = h3.others(я3).Sum(x => x.memory.Count(з => з.вид == Вид.НАЗВАЛИ_ВОРОМ && з.кто == кого.id));
                if (помнят - помнили != прочли3.Count(x => x.id != кого.id) + (прочли3.Any(x => x.id == кого.id) ? 1 : 0))
                    плохо.Add($"чат героя: «назвали вором» запомнили {помнят - помнили}, а прочли {прочли3.Count}");
                // знает имя — по имени (или квартире)
                var п4 = Дом_героя();
                var h4 = п4.h;
                var я4 = h4.people[Герой.ID];
                var о4 = Округа.У(h4)!;
                var кого4 = h4.people[кого.id];
                о4.Узнал(Знакомство.ИМЯ + кого4.id);
                var н4 = ЧатГероя.Написать(h4, я4, о4.телефон, ручки, шаблоны, "подозрение", кого4, о4.зерно);
                if (!н4.да || н4.текст is null
                    || !(н4.текст.Contains(кого4.@short, StringComparison.Ordinal) || н4.текст.Contains($"кв.{кого4.apt}", StringComparison.Ordinal)))
                    плохо.Add($"чат героя: имя знает, а реплика никого не называет — «{н4.текст}»");
                подозрение_итог = $"не знает имени — «{н3.текст}»; знает — «{н4.текст}»";
            }
        }

        // ---- 4. когда нельзя ----
        string нельзя_итог;
        {
            var п = Дом_героя();
            var h = п.h;
            var я = h.people[Герой.ID];
            var о = Округа.У(h)!;
            var т = о.телефон;
            ЧатГероя.Написать(h, я, т, ручки, шаблоны, "быт", null, о.зерно);
            var второй = ЧатГероя.Написать(h, я, т, ручки, шаблоны, "быт", null, о.зерно);
            if (второй.да)
                плохо.Add("чат героя: в один день написал дважды");
            var сейв = о.Сложить();
            var т2 = new Дом.Ядро.Телефон();
            т2.Разложить(сейв["телефон"] as System.Text.Json.Nodes.JsonObject);
            if (т2.написал_день != h.day)
                плохо.Add($"чат героя: после сейва «писал» в день {т2.написал_день}, а писал в {h.day}");
            var старый = new Дом.Ядро.Телефон();
            старый.Разложить(new System.Text.Json.Nodes.JsonObject { ["заряд"] = 50.0 });
            if (старый.написал_день == h.day)
                плохо.Add("чат героя: старый сейв без «написал» запрещает писать сегодня");

            var п2 = Дом_героя();
            var я2 = п2.h.people[Герой.ID];
            var о2 = Округа.У(п2.h)!;
            п2.h.network = 0.0;
            string? без_сети = ЧатГероя.Нельзя(п2.h, я2, о2.телефон, ручки);
            if (без_сети is null || ЧатГероя.Написать(п2.h, я2, о2.телефон, ручки, шаблоны, "быт", null, о2.зерно).да)
                плохо.Add("чат героя: сети нет — а написал");
            п2.h.network = 1.0;
            var сел = new Дом.Ядро.Телефон();
            сел.Разложить(new System.Text.Json.Nodes.JsonObject { ["заряд"] = 0.0 });
            string? без_заряда = ЧатГероя.Нельзя(п2.h, я2, сел, ручки);
            if (без_заряда is null || !без_заряда.Contains("сел", StringComparison.Ordinal))
                плохо.Add($"чат героя: телефон сел — а написать можно (или причина не та: «{без_заряда}»)");
            нельзя_итог = $"второй раз — «{второй.весть}»; без сети — «{без_сети}»; сел — «{без_заряда}»";
        }

        // ---- 5. экран ----
        {
            string Файл(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя));
            string узел = Файл("ДомУзел.cs"), тел = Файл("ДомУзел.Телефон.cs"), ui = Файл("ТелефонUI.cs");
            int флаг = узел.IndexOf("_партия.сеанс.я.пишет_сам = true;", StringComparison.Ordinal);
            int пошёл = узел.IndexOf("_партия.Начать(", StringComparison.Ordinal);
            if (флаг < 0 || пошёл < 0 || флаг > пошёл)
                плохо.Add("чат героя: узел не ставит `пишет_сам` до того, как дом пошёл");
            int дописал = тел.IndexOf("_телефон.Обновить();       // реплика героя — в чат, пока дом спит", StringComparison.Ordinal);
            int прожил = тел.IndexOf("Сделать_тут(new Сделано(true, н.часов, н.весть));", StringComparison.Ordinal);
            if (!тел.Contains("ЧатГероя.Написать(", StringComparison.Ordinal) || дописал < 0 || прожил < 0 || дописал > прожил)
                плохо.Add("чат героя: узел пишет в чат не пока дом спит (или не пишет вовсе)");
            if (!тел.Contains("if (!День_героя || _дело.занят)", StringComparison.Ordinal))
                плохо.Add("чат героя: «можно ли написать» читает дом, когда он не спит на вопросе дня");
            if (!ui.Contains("foreach (var (т, подпись) in ЧатГероя.ТЕМЫ)", StringComparison.Ordinal))
                плохо.Add("чат героя: темы в телефоне — не из ядра");
            string чат = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Ядро", "Чат.cs"));
            if (!чат.Contains("Последствия(h, p, key, who, слышат);", StringComparison.Ordinal)
                || !чат.Contains("if (p.пишет_сам)", StringComparison.Ordinal))
                плохо.Add("чат героя: чат соседей считает последствия не той функцией (или пишет за героя)");
        }

        w($"  сам: {сам_итог}");
        w($"  последствия: {последствия_итог}");
        w($"  подозрение: {подозрение_итог}");
        w($"  нельзя: {нельзя_итог}");
        return плохо;
    }

    private static double ручки_дома(House h, string ключ) => h.B[ключ];
}
