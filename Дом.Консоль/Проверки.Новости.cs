// Проверка новостей в телефоне (ГДД 19; `Дом.Экран/Новости.cs`).
//
//  1. **Сборка.** До метели — новости летописи по дням; в метель — события
//     дня (◆), пока ловит сеть; после последнего дня со связью — ни одного,
//     и последней строкой «сети нет»; ходы и чат — не новости.
//  2. **Летопись.** Новости дней подготовки — из `мир.json`, по порядку.
//  3. **Живой дом.** Двенадцать дней: события есть, но не позже последнего
//     дня со связью, а он — до «день_потери_связи».
//  4. **Экран.** Вкладка «новости» в телефоне, лента — у узла (скан).

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Новости_(Action<string> w)
    {
        var плохо = new List<string>();
        var л = Летопись.Прочитать(Пути.Данные);

        // ---- 1. сборка ----
        {
            var до = new[] { new Новость(-2, "штормовое"), new Новость(-3, "холодный фронт") };
            var лента = new[]
            {
                new СтрокаЛенты(1, null, "◆ Метель.", 2, false, ВидСтроки.СОБЫТИЕ),
                new СтрокаЛенты(1, "08:00", "Оксана поела", 0, false),
                new СтрокаЛенты(1, null, "  [чат] Валя: есть вода", 1, false, ВидСтроки.ЧАТ),
                new СтрокаЛенты(3, null, "◇ Котельная встала.", 2, false, ВидСтроки.СОБЫТИЕ),
                new СтрокаЛенты(5, null, "◆ Трассу перекрыли.", 2, false, ВидСтроки.СОБЫТИЕ),
            };
            var до_метели = Новости.Лента(до, лента, null, -2);
            if (до_метели.Count != 2 || до_метели[0].день != -3)
                плохо.Add($"новости: до метели — не летопись по порядку: {string.Join(" | ", до_метели.Select(н => н.день + " " + н.текст))}");
            var с_сетью = Новости.Лента(до, лента, 3, 5);
            var тексты = с_сетью.Select(н => н.текст).ToList();
            if (!тексты.Contains("Метель.") || !тексты.Contains("Котельная встала.") || тексты.Contains("Трассу перекрыли."))
                плохо.Add($"новости: в метель — не события дня до последнего дня со связью: {string.Join(" | ", тексты)}");
            if (тексты.Any(т => т.Contains("поела", StringComparison.Ordinal) || т.Contains("чат", StringComparison.Ordinal)))
                плохо.Add("новости: ходы и чат попали в новости");
            if (тексты.LastOrDefault() != Новости.ОБОРВАЛОСЬ || тексты.Count(т => т == Новости.ОБОРВАЛОСЬ) != 1)
                плохо.Add("новости: сеть пропала — а последней строкой не сказано, что новостей больше не будет");
            if (Новости.Лента(до, лента, 5, 5).Any(н => н.текст == Новости.ОБОРВАЛОСЬ))
                плохо.Add("новости: сеть есть — а новости «кончились»");
        }

        // ---- 2. летопись ----
        var пролог = Новости.Из_летописи(л, -10, -1).ToList();
        if (пролог.Count == 0 || пролог.Zip(пролог.Skip(1)).Any(п => п.Second.день <= п.First.день))
            плохо.Add($"новости: летопись дней подготовки — {пролог.Count}, не по порядку или пусто");

        // ---- 3. живой дом ----
        string живой_итог;
        {
            var прогон = new Прогон(Пути.Данные, seed: 3, days: 12, журнал: new Журнал(0, false, TextWriter.Null));
            var сеанс = new Сеанс(прогон.h, "оксана");
            прогон.h.journal = new ЛентаЖурнал(сеанс);
            int последний = 0;
            прогон.h.hooks.on_day.Add(дом => { if (дом.network > 0) последний = дом.day; });
            прогон.run();
            var лента = Новости.Лента(пролог, сеанс.лента, последний, прогон.h.day);
            var метель = лента.Where(н => н.день > 0 && н.текст != Новости.ОБОРВАЛОСЬ).ToList();
            if (метель.Count == 0)
                плохо.Add("новости: за двенадцать дней ни одного события дня — проверять нечего");
            if (метель.Any(н => н.день > последний))
                плохо.Add($"новости: событие дня после последнего дня со связью ({последний})");
            if (последний > (int)прогон.h.B["день_потери_связи"])
                плохо.Add($"новости: связь была до дня {последний}, а пропадает к {(int)прогон.h.B["день_потери_связи"]}");
            живой_итог = $"до метели {пролог.Count}, в метель {метель.Count} (по день {последний}), "
                         + $"дальше — «{лента.Last().текст}»";
        }

        // ---- 4. экран ----
        {
            string Файл(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя));
            string ui = Файл("ТелефонUI.cs"), т_узел = Файл("ДомУзел.Телефон.cs"), узел = Файл("ДомУзел.cs");
            if (!ui.Contains("Страница(\"новости\")", StringComparison.Ordinal)
                || !ui.Contains("Новости_дай?.Invoke()", StringComparison.Ordinal))
                плохо.Add("новости: в телефоне нет вкладки новостей");
            if (!узел.Contains("Новости_дай = Новости_телефона", StringComparison.Ordinal)
                || !т_узел.Contains("_сеть_день = дом.day", StringComparison.Ordinal))
                плохо.Add("новости: узел не даёт телефону ленту или не помнит последний день со связью");
            // снимок света и сети — до того, как телефон перерисуется на вопросе:
            // иначе новости метели отставали на вопрос (нашла проба через MCP)
            if (!узел.Replace("\r\n", "\n").Contains(
                    "Свет_и_сеть(_партия.сеанс.дом);\n                _телефон.Обновить();", StringComparison.Ordinal))
                плохо.Add("новости: телефон перерисовывается на вопросе раньше, чем узел снял сеть дома");
        }

        w($"  живой дом: {живой_итог}");
        return плохо;
    }
}
