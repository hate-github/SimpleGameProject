// Проверка кражи и полицейского участка (задание автора, пп. 16–18;
// `Дом.Ядро/Петля/Участок.cs`, `Магазин.Украсть`, `Карман`, `data/мир.json`).
//
//  1. **Кража.** Взятое в тару замечают чаще, чем спрятанное в карман вне
//     времени, и тем чаще, чем больше людей в очереди; заметили — не взято
//     ничего; не заметили — взято, и полка пустеет, как от покупки.
//  2. **Карман держит вещи.** Инструмент прячется в карман и вынимается;
//     тяжёлое занимает больше; смерть обнуляет и вещи.
//  3. **Задержание.** Сумка и снаряжение — в вещдоки, карман — при себе;
//     герой в камере и греется там, а соседи — как прежде.
//  4. **Побег.** Монтировкой из кармана — с шансом взлома, руками — редко
//     и с кровью.
//  5. **Живой игрой**: запертая без ничего героиня умирает от холода
//     и жажды; с едой и водой в кармане живёт дольше; свободная в участке
//     с печкой и кладовой — переживает две недели (п. 17: не случайный конец,
//     а по тому, что при себе).
//  6. **Участок как убежище**: кладовая кормит той же порцией, что дом,
//     печка греет за топливо, оружейная даёт оружие жильцу, вещдоки
//     возвращают своё.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Участок_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        const string КТО = "оксана";
        (House h, NPC я, Округа о) Жизнь(long зерно = 7)
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, КТО);
            return (прогон.h, прогон.h.people[КТО], Округа.У(прогон.h)!);
        }
        if (л.участок is null)
        {
            плохо.Add("в мир.json нет участка");
            return плохо;
        }

        // ---- 1. кража ----
        string кража_итог;
        {
            var м = Магазин.Прочитать(Пути.Данные, каталог);
            var еда = м.товары.First(т => т.ресурс == "еда");
            int Заметили(bool в_карман, int в_очереди)
            {
                int раз = 0;
                for (long зерно = 1; зерно <= 200; зерно++)
                {
                    var (h, я, _) = Жизнь(зерно);
                    var к = м.Украсть(h, я, еда, в_карман, в_очереди, ручки, каталог);
                    if (к.заметили)
                        раз++;
                }
                return раз;
            }
            int тара = Заметили(false, 0), карман = Заметили(true, 0), при_людях = Заметили(false, 3);
            if (Math.Abs(тара / 200.0 - ручки["кража_заметят_тара"]) > 0.1)
                плохо.Add($"кражу в тару заметили {тара} раз из 200 — а шанс {Текст.G(ручки["кража_заметят_тара"])}");
            if (карман >= тара)
                плохо.Add($"в карман вне времени замечают не реже, чем в сумку ({карман} против {тара})");
            if (при_людях <= тара)
                плохо.Add("при трёх соседях в очереди кражу замечают не чаще, чем без них");
            // исходы: заметили — ничего; нет — взято и полка пустеет
            bool было_заметили = false, было_взято = false;
            for (long зерно = 1; зерно <= 60 && !(было_заметили && было_взято); зерно++)
            {
                var (h, я, _) = Жизнь(зерно);
                h.магазины = true;
                double полка = h.богатство_места(м.место);
                var к = м.Украсть(h, я, еда, true, 0, ручки, каталог);
                if (к.заметили)
                {
                    было_заметили = true;
                    if (я.карман!.Сколько("еда") > 0 || h.богатство_места(м.место) < полка - 1e-12)
                        плохо.Add("кражу заметили — а вещь всё равно взята");
                }
                else if (к.взято)
                {
                    было_взято = true;
                    if (я.карман!.Сколько("еда") < 1.0 - 1e-9)
                        плохо.Add("украл в карман — а в кармане пусто");
                    if (h.богатство_места(м.место) >= полка - 1e-12)
                        плохо.Add("украл — а полка магазина не опустела");
                }
            }
            if (!было_заметили || !было_взято)
                плохо.Add("за 60 краж не было то ли удачной, то ли пойманной — исходы не проверить");
            кража_итог = $"из 200 заметили: в сумку {тара}, в карман {карман}, в сумку при троих в очереди {при_людях}";
        }

        // ---- 2. карман держит вещи ----
        string карман_итог;
        {
            var (_, я, _) = Жизнь(3);
            я.снаряжение!.Подобрать("монтировка", каталог);
            double было = я.карман!.занято;
            string? нельзя = я.карман.Спрятать(я, "монтировка", каталог, ручки);
            if (нельзя is not null || я.снаряжение.Есть("монтировка") || !я.карман.инструменты.Contains("монтировка"))
                плохо.Add($"монтировка не спряталась в карман: {нельзя ?? "осталась при себе"}");
            double тяжёлое = я.карман.занято - было;
            if (Math.Abs(тяжёлое - ручки["карман_тяжёлое"]) > 1e-9)
                плохо.Add($"монтировка заняла в кармане {Текст.G(тяжёлое)} — а тяжёлое весит {Текст.G(ручки["карман_тяжёлое"])}");
            if (я.карман.Вынуть(я, "монтировка", каталог) is string не_вынул || !я.снаряжение.Есть("монтировка"))
                плохо.Add("монтировку не вынуть из кармана");
            я.карман.Спрятать(я, "монтировка", каталог, ручки);
            я.карман.Обнулить();
            if (я.карман.инструменты.Count > 0)
                плохо.Add("смерть не обнулила вещи в кармане");
            карман_итог = $"монтировка в кармане занимает {Текст.G(тяжёлое)} из {Текст.G(я.карман.предел)}";
        }

        // ---- 3 и 4. задержание и побег ----
        string побег_итог;
        {
            var (h, я, о) = Жизнь(5);
            var у = о.участок!;
            var сосед = h.others(я).First();
            double соседу_было = h.room_temp(сосед);
            double дома = h.room_temp(я);
            я.ноша = new Ноша();
            var сумка = Словари.Числа();
            сумка["еда"] = 3;
            я.ноша.Положить(Тара.СУМКА, сумка, ручки);
            я.снаряжение!.Подобрать("монтировка", каталог);
            я.карман!.Положить_найденное("вода", 2);
            у.Задержать(я);
            if (у.где != ВУчастке.КАМЕРА)
                плохо.Add("задержали — а герой не в камере");
            if (!я.ноша.пусто || я.снаряжение.Есть("монтировка"))
                плохо.Add("задержали — а сумка и монтировка остались при нём");
            if (у.В_вещдоках("еда") < 3 - 1e-9 || !у.отобрано.Contains("монтировка"))
                плохо.Add("отобранное не легло в вещдоки");
            if (я.карман.Сколько("вода") < 2 - 1e-9)
                плохо.Add("задержали — и отобрали карман вне времени");
            if (Math.Abs(h.room_temp(я) - л.участок.камера_градусов) > 1e-9)
                плохо.Add($"в камере героиня греется, как дома: {Текст.G(h.room_temp(я))}° вместо {Текст.G(л.участок.камера_градусов)}°");
            if (Math.Abs(h.room_temp(сосед) - соседу_было) > 1e-9)
                плохо.Add("героиня в камере — а у соседа поменялась комната");

            // монтировка из кармана и руками — долей удач на зёрнах
            int монтировкой = 0, руками = 0, кровь = 0;
            const int РАЗ = 200;
            for (long зерно = 1; зерно <= РАЗ; зерно++)
            {
                var (h1, я1, о1) = Жизнь(зерно);
                я1.снаряжение!.Подобрать("монтировка", каталог);
                я1.карман!.Спрятать(я1, "монтировка", каталог, ручки);
                о1.участок!.Задержать(я1);
                я1.карман.Вынуть(я1, "монтировка", каталог);
                var чем = о1.участок.Чем_ломать(я1, каталог);
                if (чем != "монтировка")
                {
                    плохо.Add($"монтировка из кармана — а ломать предлагают {чем ?? "руками"}");
                    break;
                }
                if (о1.участок.Ломать(h1, я1, чем, каталог, ручки).вышел)
                    монтировкой++;
                var (h2, я2, о2) = Жизнь(зерно);
                о2.участок!.Задержать(я2);
                double здоровье = я2.health;
                if (о2.участок.Ломать(h2, я2, о2.участок.Чем_ломать(я2, каталог), каталог, ручки).вышел)
                    руками++;
                if (я2.health < здоровье - 1e-9)
                    кровь++;
            }
            if (монтировкой <= руками * 3)
                плохо.Add($"монтировкой выходят {монтировкой} раз из {РАЗ}, руками {руками} — инструмент почти не помогает");
            if (Math.Abs(руками / (double)РАЗ - л.участок.руками_шанс) > 0.05)
                плохо.Add($"руками вышли {руками} раз из {РАЗ} — а шанс {Текст.G(л.участок.руками_шанс)}");
            if (кровь != РАЗ)
                плохо.Add($"голыми руками ломали {РАЗ} раз, а кровь была {кровь}");
            побег_итог = $"в камере {Текст.G(h.room_temp(я))}° (дома было {Текст.G(Текст.Округлить(дома, 1))}°); "
                         + $"из {РАЗ} попыток: монтировкой {монтировкой}, руками {руками}";
        }

        // ---- 5. живой игрой ----
        var (пусто_день, пусто_от) = Камера_(1, 10, 0, false, ручки, каталог, л);
        var (с_водой_день, _) = Камера_(1, 10, 3, false, ручки, каталог, л);
        var (свободна_день, _) = Камера_(1, 14, 0, true, ручки, каталог, л);
        if (пусто_день is null)
            плохо.Add("запертая без еды, воды и тепла героиня пережила десять дней — камера не страшна");
        if (с_водой_день is not null && пусто_день is not null && с_водой_день <= пусто_день)
            плохо.Add($"с едой и водой в кармане в камере умирают не позже, чем без них (день {с_водой_день} и {пусто_день})");
        if (свободна_день is not null)
            плохо.Add($"свободная в участке — печка, кладовая — умерла на {свободна_день}-й день: остаться там нельзя");
        string живой_итог = $"заперта без ничего — умерла на {пусто_день?.ToString() ?? "—"}-й день ({пусто_от}); "
                            + $"с тремя едой и водой в кармане — на {с_водой_день?.ToString() ?? "—"}-й; "
                            + $"свободна, печка и кладовая — {(свободна_день is null ? "жива две недели" : $"умерла на {свободна_день}-й")}";

        // ---- 6. убежище ----
        string убежище_итог;
        {
            var (h, я, о) = Жизнь(9);
            var у = о.участок!;
            я.снаряжение!.Подобрать("монтировка", каталог);
            у.Задержать(я);
            if (у.Поесть(h, я, "еда"))
                плохо.Add("из камеры поел из кладовой участка — а она за дверью");
            // вышел
            я.снаряжение.Подобрать("монтировка", каталог);
            for (int i = 0; i < 40 && у.где == ВУчастке.КАМЕРА; i++)
                у.Ломать(h, я, "монтировка", каталог, ручки);
            я.satiety = 20;
            double кладовая = у.В_кладовой("еда");
            у.Поесть(h, я, "еда");
            double дома_порция = Действия.порция(h, я, h.B);
            if (Math.Abs(я.satiety - Math.Min(100, 20 + дома_порция)) > 1e-6 || у.В_кладовой("еда") != кладовая - 1)
                плохо.Add($"поел из кладовой: сытость {Текст.G(я.satiety)}, а дома порция дала бы {Текст.G(20 + дома_порция)}");
            double без_печи = h.room_temp(я);
            string? печь = у.Затопить(h);
            double с_печью = h.room_temp(я);
            if (печь is not null || с_печью <= без_печи)
                плохо.Add($"печка в дежурке не греет: {печь ?? $"{Текст.G(без_печи)}° → {Текст.G(с_печью)}°"}");
            string? оружие = у.Вооружиться(я, "пистолет", каталог, ручки);
            if (оружие is not null || я.weapon != Оружие.ПИСТОЛЕТ)
                плохо.Add($"из оружейной не взять пистолет: {оружие ?? я.weapon.ToString()}");
            int вернулось = у.Забрать_своё(я, каталог, ручки);
            if (!я.снаряжение.Есть("монтировка") && вернулось == 0)
                плохо.Add("вещдоки не вернули своё");
            у.Ушёл(я);
            if (я.приют is not null)
                плохо.Add("ушёл из участка — а греется всё ещё там");
            убежище_итог = $"участок {Текст.G(без_печи)}°, с печкой {Текст.G(с_печью)}°; пистолет — оружие жильца; "
                           + $"поел той же порцией, что дома";
        }

        w($"  кража: {кража_итог}");
        w($"  карман: {карман_итог}");
        w($"  побег: {побег_итог}");
        w($"  живой игрой: {живой_итог}");
        w($"  убежище: {убежище_итог}");
        return плохо;
    }

    /// <summary>
    /// Живой игрой: Оксану задержали до метели (в кармане — <paramref name="в_кармане"/>
    /// еды и воды), и она живёт <paramref name="дней"/> дней: запертой — стоит,
    /// ест и пьёт из кармана, когда голодна; <paramref name="свободна"/> — в участке,
    /// каждый день топит печку и ест из кладовой. Возвращает день смерти (null —
    /// жива) и причину.
    /// </summary>
    private static (int? день, string? от) Камера_(long зерно, int дней, int в_кармане, bool свободна,
                                                  РучкиПетли ручки, Дом.Ядро.Инструменты каталог, Летопись л)
    {
        const string ГЕРОЙ = "оксана";
        var прогон = new Прогон(Пути.Данные, seed: зерно, days: дней);
        new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, ГЕРОЙ);
        var о = Округа.У(прогон.h)!;
        var у = о.участок!;
        var я = прогон.h.people[ГЕРОЙ];
        я.карман!.Положить_найденное("еда", в_кармане);
        я.карман.Положить_найденное("вода", в_кармане);
        у.Задержать(я);
        if (свободна)
        {
            я.снаряжение!.Подобрать("монтировка", каталог);
            for (int i = 0; i < 60 && у.где == ВУчастке.КАМЕРА; i++)
                у.Ломать(прогон.h, я, "монтировка", каталог, ручки);
        }
        using var партия = new Партия(прогон, ГЕРОЙ);
        int ел_день = 0;
        партия.Начать();
        var в = партия.Дождаться();
        while (в is not null)
        {
            var h = прогон.h;
            int ответ = 0;
            if (в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ)
            {
                // дома не бывает: ни печи, ни шкафа — только то, что здесь
                if (ел_день != в.день)
                {
                    ел_день = в.день;
                    if (свободна)
                    {
                        у.Затопить(h);
                        у.Поесть(h, я, "еда");
                        у.Поесть(h, я, "вода");
                    }
                    else
                    {
                        if (я.satiety < 60) Участок.Из_кармана(h, я, "еда");
                        if (я.hydration < 60) Участок.Из_кармана(h, я, "вода");
                    }
                }
                ответ = ВопросИгроку.САМ;
                я.time_left -= Math.Min(1.0, я.time_left);
            }
            else
                for (int i = 0; i < в.варианты.Count; i++)
                    if (в.варианты[i].что is "сказать правду")
                        ответ = i;
            партия.Ответить(ответ);
            в = партия.Дождаться();
        }
        партия.Досидеть();
        return я.alive ? (null, null) : (я.died_day, я.cause);
    }
}
