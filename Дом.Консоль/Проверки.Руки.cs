// Проверка рук и анимаций (задание автора, пп. 21–23): что в руках —
// у героя и у соседа, и что играет аниматор.
//
//  1. **Каталог закрыт.** У каждого оружия есть предмет в руках, у каждого
//     предмета — ассет латиницей, один на предмет: по нему автор кладёт
//     модель и клип. Тяжёлые — монтировка и топор-инструмент.
//  2. **Руки героя.** Достать можно только то, что при себе; лёгкое
//     прячется, оружие прячется всегда (даже топор у пояса), тяжёлое —
//     нет: взятое, оно в руках, второго тяжёлого не взять, пока первое
//     не положено дома. Отняли оружие — из рук выпало. R идёт по кругу.
//  3. **Что в руках, тем и ломают**, если оно берёт замок; иначе — самым
//     тихим, как было.
//  4. **Руки соседа** — по делу, за которым он стоит на лестнице: отнять —
//     оружие наголо, разбор — монтировка, разговор — пусто; одичавший
//     носит оружие всегда. Дела из данных — дневные действия справочника:
//     хроника пишет только их (налёт и дежурство — ночные поступки).
//  5. **Анимации.** Список закрыт и совпадает с заданием; клип ищется
//     «с предметом», потом без него; держат — Restrained даже посреди дела,
//     ранен — Injured, дело — своё движение, идёт — Walk. У каждого
//     движения есть заглушка в аниматоре движка.
//  6. **Одна система на двоих.** Руки и аниматор фигуры соседа — те же
//     узлы, что у героя (`Руки3D`, `Аниматор`), а не своя копия.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Руки_(Action<string> w)
    {
        var плохо = new List<string>();
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        static House Дом_(long зерно = 1)
            => new Прогон(Пути.Данные, seed: зерно, days: 1,
                          журнал: new Журнал(0, false, TextWriter.Null)).h;

        // ---- 1. каталог закрыт ----
        foreach (var о in Enum.GetValues<Оружие>())
            if (о != Оружие.НЕТ && каталог.Оружие_в_руки(о) is null)
                плохо.Add($"у оружия {о} нет предмета в руках");
        if (каталог.Оружие_в_руки(Оружие.НЕТ) is not null)
            плохо.Add("у безоружного что-то в руках");
        var тяжёлые = каталог.все.Values.Where(и => и.тяжёлый).Select(и => и.id).OrderBy(x => x, StringComparer.Ordinal).ToList();
        if (!тяжёлые.SequenceEqual(new[] { "монтировка", "топор" }))
            плохо.Add($"тяжёлые инструменты — [{string.Join(", ", тяжёлые)}], а по заданию — монтировка и топор");
        if (каталог.в_руках.Values.Select(в => в.ассет).Distinct().Count() != каталог.в_руках.Count)
            плохо.Add("у двух предметов один ассет — модель одного встанет в руки другому");

        // ---- 2. руки героя ----
        string руки_итог;
        {
            var h = Дом_();
            var я = h.people["оксана"];
            я.weapon = Оружие.НОЖ;
            var с = new Снаряжение(new[] { "молоток", "болторез" });
            я.снаряжение = с;
            if (с.Достать("молоток", я, каталог) is null)
                плохо.Add("достал в руки молоток, который лежит дома");
            с.Взять("молоток", каталог);
            с.Взять("болторез", каталог);
            if (с.в_руках is not null)
                плохо.Add($"взял с собой лёгкое — а оно сразу в руках ({с.в_руках})");
            if (с.Достать("молоток", я, каталог) is string нет1 || с.в_руках != "молоток")
                плохо.Add("молоток при себе, а достать его не вышло");
            if (с.Убрать(каталог) is not null || с.в_руках is not null)
                плохо.Add("лёгкий молоток не убрался из рук");
            if (с.Достать("нож", я, каталог) is not null || с.в_руках != "нож")
                плохо.Add("оружие при себе, а в руки его не взять");
            if (с.Убрать(каталог) is not null)
                плохо.Add("оружие не спрятать — а прячется оно всегда");
            // круг: пусто → болторез → молоток → нож → пусто
            var круг = new List<string?>();
            for (int i = 0; i < 4; i++)
            {
                с.Следующее(я, каталог);
                круг.Add(с.в_руках);
            }
            if (!круг.SequenceEqual(new string?[] { "болторез", "молоток", "нож", null }))
                плохо.Add($"R идёт не по кругу: {string.Join(" → ", круг.Select(x => x ?? "пусто"))}");
            // тяжёлое
            с.Достать("молоток", я, каталог);
            if (!с.Подобрать("монтировка", каталог) || с.в_руках != "монтировка")
                плохо.Add($"подобрал монтировку — а в руках {с.в_руках ?? "пусто"}: тяжёлое не спрятать");
            if (с.Убрать(каталог) is null || с.в_руках != "монтировка")
                плохо.Add("тяжёлую монтировку убрали из рук — спрятали то, что не спрятать");
            if (с.Достать("молоток", я, каталог) is null)
                плохо.Add("с монтировкой в руках достали молоток — тяжёлое выпустили из рук");
            if (с.Следующее(я, каталог) is null)
                плохо.Add("с монтировкой в руках R сменило предмет");
            if (с.Нельзя_взять("топор", каталог) is null || с.Подобрать("топор", каталог))
                плохо.Add("взяли второе тяжёлое, пока первое в руках");
            с.Положить("монтировка");
            if (с.в_руках is not null)
                плохо.Add("положил монтировку дома — а она всё ещё в руках");
            if (!с.Подобрать("топор", каталог) || с.в_руках != "топор")
                плохо.Add("положил тяжёлое — а второе тяжёлое всё равно не взять");
            // топор у пояса — оружие, прячется
            var с2 = new Снаряжение();
            я.снаряжение = с2;
            я.weapon = Оружие.ТОПОР;
            if (с2.Достать("топор", я, каталог) is not null || с2.Убрать(каталог) is not null)
                плохо.Add("топор у пояса (оружие) не достать или не спрятать");
            с2.Достать("топор", я, каталог);
            я.weapon = Оружие.НЕТ;
            с2.Сверить(я, каталог);
            if (с2.в_руках is not null)
                плохо.Add("оружие отняли — а в руках оно так и осталось");
            руки_итог = $"круг R: {string.Join(" → ", круг.Select(x => x ?? "пусто"))}; "
                        + "тяжёлое (монтировка, топор) не спрятать и второго не взять";
        }

        // ---- 3. что в руках, тем и ломают ----
        string взлом_итог;
        {
            var h = Дом_();
            var я = h.people["оксана"];
            я.weapon = Оружие.НОЖ;
            var с = new Снаряжение(new[] { "молоток", "болторез" });
            я.снаряжение = с;
            с.Взять("молоток", каталог);
            с.Взять("болторез", каталог);
            var к = h.кладовые.Значения.First(x => x.вид == ВидКладовой.ПОГРЕБ);
            string Чем() => Взлом.чем(я, к, каталог)?.инструмент.id ?? "ничем";
            string пусто = Чем();
            с.Достать("молоток", я, каталог);
            string молотком = Чем();
            с.Достать("нож", я, каталог);
            string ножом = Чем();
            if (пусто != "болторез")
                плохо.Add($"с пустыми руками ломают «{пусто}», а должны самым тихим — болторезом");
            if (молотком != "молоток")
                плохо.Add($"в руках молоток, а ломают «{молотком}» — герой сам выбрал, чем ломать");
            if (ножом != "болторез")
                плохо.Add($"в руках нож (замков не берёт), а ломают «{ножом}», а не самым тихим");
            взлом_итог = $"пусто — {пусто}, в руках молоток — {молотком}, в руках нож — {ножом}";
        }

        // ---- 4. руки соседа ----
        string соседи_итог;
        {
            var h = Дом_();
            var п = h.people.Значения.First(x => x.id != "оксана");
            п.weapon = Оружие.ТОПОР;
            п.normalcy = 0.9;
            string Р(string ключ) => Ношение.Соседа(п, ключ, каталог).предмет ?? "пусто";
            string налёт = Р("отнять"), разговор = Р("разговор"), разбор = Р("разбор");
            п.normalcy = 0.1;
            string одичал = Р("разговор");
            п.weapon = Оружие.НЕТ;
            п.normalcy = 0.9;
            string без = Р("отнять");
            if (налёт != "топор")
                плохо.Add($"сосед с топором пришёл отнимать — а в руках «{налёт}»");
            if (разговор != "пусто")
                плохо.Add($"сосед пришёл поговорить — а в руках «{разговор}»");
            if (разбор != "монтировка")
                плохо.Add($"сосед разбирает квартиру — а в руках «{разбор}»");
            if (одичал != "топор")
                плохо.Add("одичавший сосед прячет топор — а носит его открыто");
            if (без != "пусто")
                плохо.Add($"безоружный пришёл отнимать — а в руках «{без}»");
            var действия = Дом.Ядро.Каталог.ДЕЙСТВИЯ.Select(д => д.key).ToHashSet(StringComparer.Ordinal);
            foreach (var к in каталог.соседи.оружие_наголо.Concat(каталог.соседи.дело.Keys))
                if (!действия.Contains(к))
                    плохо.Add($"руки соседей: «{к}» — не действие справочника");
            соседи_итог = $"отнять — {налёт}, разговор — {разговор}, разбор — {разбор}, "
                          + $"одичавший на разговоре — {одичал}, безоружный отнимает — {без}";
        }

        // ---- 5. анимации ----
        string анимации_итог;
        {
            var по_заданию = new[] { "Idle", "Walk", "Run", "Interact", "Loot", "Attack", "BreakLock",
                                     "UseTool", "Equip", "Unequip", "Injured", "Restrained" };
            var есть = Enum.GetNames<Анимация>();
            if (!есть.SequenceEqual(по_заданию))
                плохо.Add($"анимации — [{string.Join(", ", есть)}], а в задании — [{string.Join(", ", по_заданию)}]");
            var клипы = Анимации.Клипы(new Движение(Анимация.BreakLock, "Crowbar"));
            if (!клипы.SequenceEqual(new[] { "BreakLock_Crowbar", "BreakLock" }))
                плохо.Add($"клипы взлома монтировкой ищутся как [{string.Join(", ", клипы)}]");
            if (!Анимации.Клипы(new Движение(Анимация.Idle)).SequenceEqual(new[] { "Idle" }))
                плохо.Add("клип без предмета ищется не по одному имени");
            var молоток = каталог.все["молоток"];
            var взлом = Анимации.Ломать(молоток);
            void Ждать(Движение есть_, Анимация надо, string? ассет, string что)
            {
                if (есть_.что != надо || есть_.ассет != ассет)
                    плохо.Add($"{что}: {есть_}, а должно {new Движение(надо, ассет)}");
            }
            Ждать(Анимации.Героя(Положение.НОРМА, null, false), Анимация.Idle, null, "герой стоит");
            Ждать(Анимации.Героя(Положение.НОРМА, null, true), Анимация.Walk, null, "герой идёт");
            Ждать(Анимации.Героя(Положение.НОРМА, взлом, false), Анимация.BreakLock, "Hammer", "герой ломает молотком");
            Ждать(Анимации.Героя(Положение.СКРУТИЛИ, взлом, false), Анимация.Restrained, null, "героя держат посреди взлома");
            Ждать(Анимации.Героя(Положение.РАНЕН, null, true), Анимация.Injured, null, "раненый герой");
            Ждать(Анимации.Героя(Положение.РАНЕН, Анимации.Обыскивать(), false), Анимация.Loot, null, "раненый обыскивает");
            var топор = Ношение.Предмет(каталог, "топор");
            var монтировка = Ношение.Предмет(каталог, "монтировка", тяжёлый: true);
            Ждать(Анимации.Соседа("разговор", Руки.ПУСТЫ, идёт: true), Анимация.Walk, null, "сосед идёт");
            Ждать(Анимации.Соседа("разговор", Руки.ПУСТЫ, идёт: true, спешит: true), Анимация.Run, null, "сосед спешит на стук");
            Ждать(Анимации.Соседа("отнять", топор, идёт: false), Анимация.Attack, "Axe", "отнимает с топором");
            Ждать(Анимации.Соседа("кража_днём", монтировка, идёт: false), Анимация.BreakLock, "Crowbar", "ломает дверь днём");
            Ждать(Анимации.Соседа("разбор", монтировка, идёт: false), Анимация.UseTool, "Crowbar", "разбор монтировкой");
            Ждать(Анимации.Соседа("разговор", Руки.ПУСТЫ, идёт: false), Анимация.Idle, null, "сосед говорит");
            // у каждого движения — заглушка руки в аниматоре движка: ищется
            // в самой заглушке руки, а не во всём файле — имя встречается
            // и в качании тела, и там оно руку не двигает
            string аниматор = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "Аниматор.cs"));
            int от = аниматор.IndexOf(") Рукой()", StringComparison.Ordinal);
            int до = от < 0 ? -1 : аниматор.IndexOf(") Телом()", от, StringComparison.Ordinal);
            if (от < 0 || до < 0)
                плохо.Add("в Аниматор.cs не нашлось заглушек Рукой() и Телом() — сканер смотрит не туда");
            else
            {
                string рукой = аниматор[от..до];
                foreach (var имя in есть)
                    if (!рукой.Contains($"Анимация.{имя}", StringComparison.Ordinal))
                        плохо.Add($"у движения {имя} нет заглушки руки в Аниматор.cs — сыграть нечего");
            }
            // руки героя: дело — его инструмент, тяжёлое — тяжёлое
            {
                var h = Дом_();
                var я = h.people["оксана"];
                var с = new Снаряжение();
                я.снаряжение = с;
                с.Подобрать("монтировка", каталог);
                if (Ношение.Героя(я, каталог) is not { предмет: "монтировка", ассет: "Crowbar", тяжёлый: true })
                    плохо.Add("в руках героя монтировка, а показывают другое или не тяжёлой");
                if (Ношение.Героя(я, каталог, "молоток").предмет != "молоток")
                    плохо.Add("идёт взлом молотком — а в руках не молоток");
            }
            анимации_итог = $"{есть.Length} движений, клип взлома монтировкой — {string.Join(" → ", клипы)}";
        }

        // ---- 6. одна система на двоих ----
        {
            string мир = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "Мир.cs"));
            string герой = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "Герой.cs"));
            foreach (var (узел, где, текст) in new[] { ("Руки3D", "Мир.cs", мир), ("Аниматор", "Мир.cs", мир),
                                                        ("Руки3D", "Герой.cs", герой), ("Аниматор", "Герой.cs", герой) })
                if (!текст.Contains($"new {узел}", StringComparison.Ordinal))
                    плохо.Add($"в {где} нет `new {узел}` — руки героя и соседа разошлись в две системы");
        }

        w($"  герой: {руки_итог}");
        w($"  взлом: {взлом_итог}");
        w($"  соседи: {соседи_итог}");
        w($"  анимации: {анимации_итог}");
        return плохо;
    }
}
