// Проверка лиц вопросов (`Дом.Экран/Разговор.cs`): у вопроса-ситуации
// есть тот, кто спрашивает, и то, о чём речь.
//
// Автор увидел окно, в котором стояло только «Оксана», «соврать»
// и «сказать правду», и сказал: ни с кем разговор, ни о чём — непонятно.
// Заголовок вопроса называл героя, а не собеседника, потому что ядро
// ничего другого и не отдавало. Теперь отдаёт, и это сверяется:
//
//  1. **Ядро говорит, с кем и о чём.** Каждый вызов `Решение.монета`
//     и `Решение.по_правилу` в ядре несёт `с_кем:` и `суть:`. Где
//     собеседник неизвестен (сосед слышит стук, но не видит, кто ломает),
//     это сказано явным `с_кем: null` — молчания нет нигде.
//  2. **У каждого вопроса есть свои слова.** Ни один член перечисления
//     не показывается голым заголовком: у всех, кроме вопроса дня,
//     текст свой.
//  3. **Три жизни.** Каждый вопрос-ситуация, который дом задал за три
//     жизни, назвал собеседника и суть; окно получило имя, фразу
//     и по подписи на каждый вариант — в том же порядке и числе.
//     Заглушки вроде «кто-то» и «что-нибудь» в словах не остаются:
//     они значат, что контекст до экрана не доехал.

using System.Text.RegularExpressions;
using Дом.Экран;
using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    /// <summary>Заглушки: если такое слово доехало до экрана, значит,
    /// ядро не сказало, с кем разговор или о чём.</summary>
    private static readonly string[] ЗАГЛУШКИ = { "кто-то", "что-то", "что-нибудь", "чего-нибудь" };

    public static List<string> ЛицаВопросов_(Action<string> w)
    {
        var плохо = new List<string>();

        // ---- 1. каждый вопрос ядра несёт, с кем и о чём ----
        int вызовов = 0;
        foreach (string файл in Directory.EnumerateFiles(
                     Path.Combine(Пути.Корень, "Дом.Ядро"), "*.cs", SearchOption.AllDirectories))
        {
            if (string.Equals(Path.GetFileName(файл), "Решение.cs", StringComparison.Ordinal))
                continue;                       // сами определения
            string текст = File.ReadAllText(файл);
            foreach (Match m in Regex.Matches(текст, @"Решение\.(монета|по_правилу)\("))
            {
                int i = m.Index + m.Length, глубина = 1;
                while (i < текст.Length && глубина > 0)
                {
                    if (текст[i] == '(') глубина++;
                    else if (текст[i] == ')') глубина--;
                    i++;
                }
                string вызов = текст[m.Index..i];
                вызовов++;
                string вопрос = Regex.Match(вызов, @"Вопрос\.(\w+)").Groups[1].Value;
                string где = $"{Path.GetFileName(файл)}:{текст[..m.Index].Count(c => c == '\n') + 1}";
                if (!вызов.Contains("с_кем:", StringComparison.Ordinal))
                    плохо.Add($"{где} «{вопрос}» не говорит, с кем разговор");
                if (!вызов.Contains("суть:", StringComparison.Ordinal))
                    плохо.Add($"{где} «{вопрос}» не говорит, о чём речь");
            }
        }
        if (вызовов < 30)
            плохо.Add($"вопросов-ситуаций в ядре нашлось {вызовов} — сканер смотрит не туда");

        // ---- 2. у каждого вопроса свои слова ----
        var дом = new Прогон(Пути.Данные, seed: 1, days: 1,
                             журнал: new Журнал(0, false, TextWriter.Null)).h;
        var кто_то = дом.people["оксана"];
        foreach (var (вопрос, заголовок) in Дом.Ядро.Вопросы.Все)
        {
            var пустой = new ВопросИгроку(1, кто_то.id, вопрос, "",
                                          System.Array.Empty<ВариантИгроку>(), null, null);
            string что = Разговор.Что(дом, кто_то, пустой, null);
            if (string.IsNullOrWhiteSpace(что))
                плохо.Add($"у вопроса «{заголовок}» нет слов вовсе");
            else if (вопрос is not (Вопрос.ЧТО_ДЕЛАТЬ or Вопрос.ДЕНЬ)
                     && string.Equals(что, заголовок, StringComparison.Ordinal))
                плохо.Add($"у вопроса «{заголовок}» нет своих слов — окно покажет заголовок");
        }

        // ---- 3. три жизни ----
        var беды = new SortedSet<string>(StringComparer.Ordinal);
        var видов = new SortedDictionary<string, int>(StringComparer.Ordinal);
        int вопросов = 0;
        foreach (long зерно in new long[] { 11, 23, 42 })
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 12,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            var h = прогон.h;
            var я = h.people["оксана"];
            int k = 0;
            я.решающий = new Человек((ВопросИгроку в) =>
            {
                if (в.вопрос != Вопрос.ЧТО_ДЕЛАТЬ)
                {
                    вопросов++;
                    видов[Дом.Ядро.Вопросы.Текст(в.вопрос)] = видов.GetValueOrDefault(Дом.Ядро.Вопросы.Текст(в.вопрос)) + 1;
                    var сцена = Разговор.Прочитать(h, я, в);
                    bool нужен = !Разговор.БЕЗ_СОБЕСЕДНИКА.Contains(в.вопрос);
                    string имя = Дом.Ядро.Вопросы.Текст(в.вопрос);
                    if (нужен && (в.с_кем is null || h.get(в.с_кем) is null))
                        беды.Add($"«{имя}»: не сказано, с кем разговор");
                    if (нужен && в.суть is null)
                        беды.Add($"«{имя}»: не сказано, о чём речь");
                    if (нужен && сцена.кто.Length == 0)
                        беды.Add($"«{имя}»: окно не называет собеседника");
                    if (string.IsNullOrWhiteSpace(сцена.что))
                        беды.Add($"«{имя}»: окно не говорит, что происходит");
                    foreach (string з in ЗАГЛУШКИ)
                        if (сцена.что.Contains(з, StringComparison.Ordinal))
                            беды.Add($"«{имя}»: в словах осталась заглушка «{з}» — "
                                     + "контекст до экрана не доехал");
                    if (сцена.ответы.Count != в.варианты.Count)
                        беды.Add($"«{имя}»: подписей {сцена.ответы.Count}, "
                                 + $"а вариантов {в.варианты.Count}");
                    else
                        for (int i = 0; i < в.варианты.Count; i++)
                        {
                            if (сцена.ответы[i].Length == 0)
                                беды.Add($"«{имя}»: вариант {i} без подписи");
                            if (в.варианты[i].что is string ответ
                                && !сцена.ответы[i].StartsWith(
                                       Разговор.Подпись(в.вопрос, в.суть, ответ),
                                       StringComparison.Ordinal))
                                беды.Add($"«{имя}»: подпись варианта {i} не та");
                        }
                }
                return new[] { 0, 1, 1, 0, 2 }[k++ % 5];
            });
            прогон.run();
        }
        плохо.AddRange(беды);
        if (видов.Count < 5)
            плохо.Add($"за три жизни вопросов-ситуаций всего {видов.Count} видов — "
                      + "проверять не на чем");

        w($"  ядро: {вызовов} вопросов-ситуаций, у каждого сказано, с кем и о чём");
        w($"  три жизни: {вопросов} вопросов, {видов.Count} видов — "
          + string.Join(", ", видов.Take(6).Select(в => $"{в.Key} {в.Value}"))
          + (видов.Count > 6 ? ", …" : ""));
        return плохо;
    }
}
