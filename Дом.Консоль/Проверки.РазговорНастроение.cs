// Проверка «Разговора» по настроению и Смекалке (ГДД 14: «настроение героя
// ограничивает варианты: в плохом настроении недоступны поддерживающие
// реплики»; «скрытые варианты открываются Смекалкой и памятью»).
//
//  1. **Настроение.** Ниже порога добрая реплика не идёт с языка, выше — идёт;
//     порог — тот же, что «тошно» итога дня. Прочие тоны настроение не трогает.
//  2. **Смекалка.** Ниже «разговор_подсказка_смекалка» по соседу ничего
//     не видно, с неё — каким тоном с ним выходит (его тон), и подсказка
//     живёт ниже порога, с которого реплики нет вовсе.
//  3. **Экран.** Окно реплики спрашивает и то и другое (скан).

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> РазговорНастроение_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);

        // ---- 1. настроение ----
        double порог = ручки["разговор_добро_настроение"];
        if (Math.Abs(порог - Сеанс.ТОШНО) > 1e-9)
            плохо.Add($"разговор: доброе слово не идёт ниже {Текст.G(порог)}, а «тошно» итога дня — ниже {Текст.G(Сеанс.ТОШНО)}");
        if (Реплики.Не_идёт(Тон.ДОБРО, порог - 1.0, ручки) is null)
            плохо.Add("разговор: самому тошно — а добрая реплика идёт");
        if (Реплики.Не_идёт(Тон.ДОБРО, порог + 1.0, ручки) is not null)
            плохо.Add("разговор: не тошно — а добрая реплика не идёт");
        foreach (var т in Enum.GetValues<Тон>().Where(т => т != Тон.ДОБРО))
            if (Реплики.Не_идёт(т, 0.0, ручки) is not null)
                плохо.Add($"разговор: «{Реплики.Кратко(т)}» не идёт в плохом настроении — а ГДД закрывает только поддерживающие");

        // ---- 2. смекалка ----
        string смекалка_итог;
        {
            int с_уровня = (int)ручки["разговор_подсказка_смекалка"];
            if (с_уровня < 1 || с_уровня >= (int)ручки["мини_игра_исчезает"])
                плохо.Add($"разговор: подсказка Смекалки с {с_уровня}-го уровня — а реплика живёт до {(int)ручки["мини_игра_исчезает"]}-го");
            var п = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null),
                               жильцы: npcs => Герой.Заселить(npcs, new ПрофильГероя("Андрей"), Пути.Данные));
            var я = п.h.people[Герой.ID];
            var с = п.h.others(я).First(x => x.здесь());
            string? При(int уровень)
            {
                var н = new Наследие();
                н.уровни[Навык.СМЕКАЛКА] = уровень;
                я.умения = new Умения(н, ручки);
                return Реплики.Видно_по_нему(с, я, ручки);
            }
            string? ниже = При(с_уровня - 1), с_него = При(с_уровня);
            я.умения = null;
            if (ниже is not null)
                плохо.Add($"разговор: на Смекалке {с_уровня - 1} по соседу уже видно — «{ниже}»");
            if (с_него is null || !с_него.Contains(Реплики.Кратко(Реплики.Свой(с)), StringComparison.Ordinal))
                плохо.Add($"разговор: на Смекалке {с_уровня} по соседу не видно его тона — «{с_него}»");
            if (Реплики.Видно_по_нему(с, я, ручки) is not null)
                плохо.Add("разговор: без наследия (у соседа) Смекалка что-то видит");
            смекалка_итог = $"{с.id}: на {с_уровня - 1} — ничего, на {с_уровня} — «{с_него}»";
        }

        // ---- 3. экран ----
        {
            string игра = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "ДомУзел.РазговорИгра.cs"));
            if (!игра.Contains("Реплики.Не_идёт(т, я.mood, _ручки) is { } нельзя", StringComparison.Ordinal))
                плохо.Add("разговор: окно реплики не спрашивает настроение героя");
            if (!игра.Contains("if (Реплики.Видно_по_нему(с, я, _ручки) is { } видно)", StringComparison.Ordinal)
                || !игра.Contains("помнит += $\"\\n{видно}\";", StringComparison.Ordinal))
                плохо.Add("разговор: окно реплики не спрашивает Смекалку (или молчит о том, что она видит)");
        }

        w($"  настроение: доброе слово не идёт ниже {Текст.G(порог)}");
        w($"  смекалка: {смекалка_итог}");
        return плохо;
    }
}
