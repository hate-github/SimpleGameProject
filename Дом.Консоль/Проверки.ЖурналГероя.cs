// Проверка ленты дня глазами героя (обзор 27.10, пункт 3: журнал J был
// всевидящим рассказчиком; `Дом.Экран/ЗнаниеЛенты.cs`).
//
//  1. **Чужое дело.** Сосед занёс банку соседу — герой не знает; занёс
//     герою — знает (лицом к лицу); то же, пока героя нет в доме, — нет;
//     дело того, с кем он живёт под одной крышей, — знает; учуял сам
//     (запись `УЧУЯЛ` за это дело) — знает, без хвоста «Учуяли: …»;
//     только слышал шум (`СЛЫШАЛ`) — нет.
//  2. **Своё.** Своё дело — знает, и всё, что напечатано внутри него.
//  3. **Рассказчик.** Событие дня и чат знают все, секрет — никто,
//     «(слышали: …)» — никто; хвост «(а это был не он)» в знаемой строке
//     срезан.
//  4. **Имена.** Новый человек видит незнакомого «сосед из кв.N» — в падеже,
//     с заглавной в начале строки; познакомился — по имени.
//  5. **Живой дом.** Пять дней жизни на ленте: герой знает меньше, чем
//     напечатано, но не ноль; «за день заметил» — только своё.
//  6. **Экран.** ЖурналUI прячет незнаемое; целиком — только с галочкой
//     «лента целиком» (не «Следить»: слежка в сцене включена всегда).

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> ЖурналГероя_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var профиль = new ПрофильГероя("Андрей");
        var честный = new Скрипт(new Dictionary<Вопрос, string> { [Вопрос.СОВРАТЬ] = "сказать правду" });

        (Прогон, Сеанс) Дом_героя(int дней)
        {
            var п = new Прогон(Пути.Данные, seed: 3, days: дней,
                               журнал: new Журнал(0, false, TextWriter.Null),
                               жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(п, Герой.ID);
            var с = new Сеанс(п.h, Герой.ID);
            п.h.journal = new ЛентаЖурнал(с);
            п.h.people[Герой.ID].решающий = честный;
            return (п, с);
        }

        var (прогон, сеанс) = Дом_героя(3);
        var h = прогон.h;
        var я = h.people[Герой.ID];
        var чужие = h.others(я).Where(p => p.здесь() && string.IsNullOrEmpty(p.living_with) && p.guests.Count == 0)
                     .OrderBy(p => p.apt).ToList();
        int было = сеанс.СтрокВЛенте;
        List<СтрокаЛенты> Новые()
        {
            var н = сеанс.ЛентаПосле(было).ToList();
            было = сеанс.СтрокВЛенте;
            return н;
        }
        string Строки(List<СтрокаЛенты> с) => string.Join(" / ", с.Select(x => x.текст.Trim()));

        // ---- 1. чужое дело ----
        var а = чужие[0];
        var б = чужие.First(p => p.id != а.id && !h.под_одной_крышей(p, я));
        string занёс_итог;
        {
            а.stock["еда"] = 5;
            Действия.execute(h, а, "поделиться", б, "еда");
            var чужое = Новые();
            if (чужое.Count == 0)
                плохо.Add("журнал героя: «поделиться» соседа с соседом не напечатал ни строки — проверять нечего");
            else if (чужое.Any(с => с.знает))
                плохо.Add($"журнал героя: сосед занёс банку соседу — а герой это знает: {Строки(чужое)}");

            Действия.execute(h, а, "поделиться", я, "еда");
            var мне = Новые();
            if (мне.Count == 0 || !мне.Any(с => с.знает))
                плохо.Add($"журнал героя: сосед занёс банку герою — а герой этого не знает: {Строки(мне)}");
            // и в ленте она его глазами: имени того, кто пришёл, он ещё не знал
            else if (мне.Where(с => с.знает).Any(с => с.ДляГероя.Contains(а.@short, StringComparison.Ordinal)))
                плохо.Add($"журнал героя: в ленте строка не его глазами — имя незнакомого: {Строки(мне)}");

            я.вне_дома = true;
            Действия.execute(h, а, "поделиться", я, "еда");
            var без_меня = Новые();
            я.вне_дома = false;
            if (без_меня.Count == 0 || без_меня.Any(с => с.знает))
                плохо.Add($"журнал героя: героя нет в доме — а он знает, кто приходил к его двери: {Строки(без_меня)}");

            // под одной крышей: живёт у героя — его дела у героя на глазах
            var в = чужие.First(p => p.id != а.id && p.id != б.id);
            var г = чужие.First(p => p.id != а.id && p.id != б.id && p.id != в.id && !h.под_одной_крышей(p, я));
            в.living_with = я.id;
            я.guests.Add(в.id);
            в.stock["еда"] = 5;
            Действия.execute(h, в, "поделиться", г, "еда");
            var у_меня = Новые();
            в.living_with = null;
            я.guests.Remove(в.id);
            if (у_меня.Count == 0 || !у_меня.Any(с => с.знает))
                плохо.Add($"журнал героя: сосед, живущий у героя, занёс банку — а герой не видел: {Строки(у_меня)}");
            занёс_итог = $"соседу — {чужое.Count(с => !с.знает)} из {чужое.Count} скрыто; "
                         + $"герою — «{мне.FirstOrDefault(с => с.знает)?.ДляГероя.Trim()}»; "
                         + $"без него — скрыто; от живущего у него — видел";
        }

        // ---- 1б. учуял сам — знает; слышал шум — нет ----
        string учуял_итог;
        {
            var е = чужие.First(p => p.id != а.id && p.id != б.id && !h.под_одной_крышей(p, я));
            string запах = $"По подъезду тянет едой из кв.{е.apt}. Учуяли: {я.@short}, {а.@short}.";
            void Дело(Action внутри)
            {
                foreach (var f in h.hooks.on_execute)
                    f(h, е, "поесть", null, null);
                внутри();
                foreach (var f in h.hooks.after_execute)
                    f(h, е, "поесть", null, null, Исход.СДЕЛАНО);
            }
            Дело(() => сеанс.Строка(запах, 1, false, null));
            Дело(() =>
            {
                я.memory.Add(new Память { день = h.day, вид = Вид.СЛЫШАЛ, кто = е.id });
                сеанс.Строка(запах, 1, false, null);
            });
            Дело(() =>
            {
                я.memory.Add(new Память { день = h.day, вид = Вид.УЧУЯЛ, кто = е.id });
                сеанс.Строка(запах, 1, false, null);
            });
            var з = Новые();
            string ждём = $"По подъезду тянет едой из кв.{е.apt}.";
            if (з.Count != 3 || з[0].знает || з[1].знает)
                плохо.Add("журнал героя: чужая готовка — герой знает, хотя не учуял (или только слышал шум)");
            else if (!з[2].знает || з[2].ДляГероя != ждём)
                плохо.Add($"журнал героя: учуял сам — «{(з[2].знает ? з[2].ДляГероя : "не знает")}», а надо «{ждём}»");
            учуял_итог = з.Count == 3 ? $"«{з[2].ДляГероя}»" : "—";
        }

        // ---- 2. своё дело — и что внутри него ----
        {
            foreach (var f in h.hooks.on_execute)
                f(h, я, "быт", null, null);
            // сосед влез в его дело (засада, поимка): внутри своего — знает
            foreach (var f in h.hooks.on_execute)
                f(h, а, "попросить", б, null);
            сеанс.Строка($"{а.@short} что-то сказал {б.form("dat")} за спиной.", 1, false, null);
            foreach (var f in h.hooks.after_execute)
                f(h, а, "попросить", б, null, Исход.СДЕЛАНО);
            сеанс.Строка("У печки стало теплее.", 1, false, null);
            foreach (var f in h.hooks.after_execute)
                f(h, я, "быт", null, null, Исход.СДЕЛАНО);
            сеанс.Строка("У печки стало теплее.", 1, false, null);
            var своё = Новые();
            if (своё.Count != 3 || !своё[0].знает || !своё[1].знает)
                плохо.Add($"журнал героя: внутри своего дела герой не знает напечатанного: {Строки(своё)}");
            else if (своё[2].знает)
                плохо.Add("журнал героя: дело кончилось — а строка без него всё ещё считается его");
        }

        // ---- 3. рассказчик ----
        {
            if (!сеанс.Знает_строку("◆ Метель.", ВидСтроки.СОБЫТИЕ) || !сеанс.Знает_строку("  [чат] Лида: есть вода", ВидСтроки.ЧАТ))
                плохо.Add("журнал героя: событие дня или чат — а герой не знает");
            if (сеанс.Знает_строку("    ⌁ Толик украл", ВидСтроки.СЕКРЕТ))
                плохо.Add("журнал героя: секрет дома знает герой");
            // строка о нём: с его имени или парой, где он второй, — но не с чужого
            // имени, которое начинается так же
            if (!Сеанс.Про_меня($"{а.@short} и {я.@short} договорились держаться вместе.", я)
                || !Сеанс.Про_меня($"{я.@short} и {а.@short} договорились держаться вместе.", я)
                || Сеанс.Про_меня($"{я.@short}ка поел.", я)
                || Сеанс.Про_меня($"{а.@short} и {я.@short}ка договорились.", я)
                || Сеанс.Про_меня($"{а.@short} заметил: {я.@short} вернулся с пакетами.", я))
                плохо.Add("журнал героя: «строка о нём» узнаётся не по началу строки");
            if (сеанс.Знает_строку($"   (слышали: {я.@short}, {а.@short})", ВидСтроки.ХОД))
                плохо.Add("журнал героя: «(слышали: …)» знает герой — а это знает только рассказчик");
            string уверен = $"{я.@short} {Util.Vb(я.sex, "уверен")}, что это {а.@short}. (а это был не он)";
            string? глазами = сеанс.Его_глазами(уверен);
            if (!сеанс.Знает_строку(уверен, ВидСтроки.ХОД) || глазами is null
                || глазами.Contains("(а это", StringComparison.Ordinal))
                плохо.Add($"журнал героя: «уверен, что это …» — герою «{глазами}», а хвост рассказчика должен уйти");
        }

        // ---- 4. имена ----
        string имена_итог;
        {
            // тот, с кем он ещё не встречался (с «а» он уже знаком: банку занёс)
            var д = чужие.First(p => !Знакомство.Знает(h, я, p));
            string строка = $"{д.@short} сам занёс банку {я.form("dat")}";
            string? до = сеанс.Его_глазами(строка);
            string ждём = char.ToUpperInvariant(Знакомство.Незнакомый(д)[0]) + Знакомство.Незнакомый(д)[1..];
            if (до is null || !до.StartsWith(ждём, StringComparison.Ordinal) || до.Contains(д.@short, StringComparison.Ordinal))
                плохо.Add($"журнал героя: незнакомый сосед в начале строки — «{до}», а надо «{ждём} …»");
            string в_падеже = $"{я.@short} попросил у {д.form("gen")} воды";
            string? род = сеанс.Его_глазами(в_падеже);
            if (род is null || !род.Contains(Знакомство.Незнакомый(д, "gen"), StringComparison.Ordinal))
                плохо.Add($"журнал героя: незнакомый в родительном — «{род}»");
            Округа.У(h)!.Узнал(Знакомство.ИМЯ + д.id);
            if (сеанс.Его_глазами(строка) is not null)
                плохо.Add("журнал героя: познакомился — а в строке всё ещё «сосед из кв.N»");
            имена_итог = $"«{до}», «{род}» → по имени, когда познакомились";
        }

        // ---- 5. живой дом ----
        string живой_итог;
        {
            var (п5, с5) = Дом_героя(5);
            п5.run();
            var лента = с5.лента;
            var ходы = лента.Where(с => с.вид == ВидСтроки.ХОД).ToList();
            int знает = ходы.Count(с => с.знает);
            var заметил = ходы.Where(с => с.текст.Contains(" за день заметил", StringComparison.Ordinal)).ToList();
            string имя = п5.h.people[Герой.ID].@short;
            var чужое_заметил = заметил.Where(с => с.знает != с.текст.TrimStart().StartsWith(имя + " ", StringComparison.Ordinal)).ToList();
            if (ходы.Count == 0 || знает == 0 || знает == ходы.Count)
                плохо.Add($"журнал героя: за пять дней из {ходы.Count} строк герой знает {знает} — а должно быть «не всё и не ничего»");
            if (заметил.Count == 0)
                плохо.Add("журнал героя: за пять дней ни одного «за день заметил» — проверять нечего");
            if (чужое_заметил.Count > 0)
                плохо.Add($"журнал героя: «за день заметил» — не только своё: «{чужое_заметил[0].текст.Trim()}»");
            if (ходы.Any(с => с.знает && с.текст.Contains("(слышали: ", StringComparison.Ordinal)))
                плохо.Add("журнал героя: в живом доме герой знает «(слышали: …)»");
            if (лента.Any(с => с.вид == ВидСтроки.СОБЫТИЕ && !с.знает))
                плохо.Add("журнал героя: событие дня скрыто от героя");
            int глазами = ходы.Count(с => с.знает && с.глазами is not null);
            живой_итог = $"5 дн: из {ходы.Count} строк ходов герой знает {знает}, "
                         + $"«за день заметил» — {заметил.Count(с => с.знает)} своих из {заметил.Count}; "
                         + $"его глазами переписано {глазами}";
        }

        // ---- 6. экран ----
        {
            string ui = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "ЖурналUI.cs"));
            string узел = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "ДомУзел.cs"));
            if (!ui.Contains("if (!с.знает && !Всё)", StringComparison.Ordinal)
                || !ui.Contains("с.ДляГероя", StringComparison.Ordinal))
                плохо.Add("журнал героя: ЖурналUI показывает строки, которых герой не знает, или не его глазами");
            if (!узел.Contains("Всё = ЛентаЦеликом", StringComparison.Ordinal))
                плохо.Add("журнал героя: галочка «лента целиком» не доходит до ЖурналUI");
        }

        w($"  чужое дело: {занёс_итог}");
        w($"  учуял сам: {учуял_итог}; не учуял или только слышал шум — скрыто");
        w($"  имена: {имена_итог}");
        w($"  живой дом: {живой_итог}");
        return плохо;
    }
}
