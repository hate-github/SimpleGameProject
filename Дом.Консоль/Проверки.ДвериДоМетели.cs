// Проверка подписей у дверей до метели и между жизнями (проба через MCP,
// 27.10: в прологе каждая дверь читалась «пусто», а у двери висело то, что
// осталось от прошлой жизни — «из-под двери светит»).
//
//  1. **До метели — живьём.** Подпись берёт план подъезда и вид дверей
//     у самого дома: он не идёт, читать его можно всегда; в метель — снимок
//     на вопросе, как было.
//  2. **Новая жизнь — с чистого.** Снимки прошлой жизни сбрасываются.
//  3. **Свежий дом.** У дверей свежего дома нет ни копоти, ни сорванных
//     замков, ни разобранных квартир, ни тел.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> ДвериДоМетели_(Action<string> w)
    {
        var плохо = new List<string>();
        string узел = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "ДомУзел.cs"));

        // ---- 1. до метели — живьём ----
        if (!узел.Contains("var ж = своя ? null : План_у_двери().FirstOrDefault(", StringComparison.Ordinal)
            || !узел.Contains("var что = Двери_у_двери().FirstOrDefault(", StringComparison.Ordinal)
            || !узел.Contains("=> _пролог is not null && _партия is not null ? _партия.сеанс.План() : _план_вопроса;", StringComparison.Ordinal))
            плохо.Add("двери: подпись до метели берёт снимок вопроса — а вопросов до метели нет («пусто»)");

        // ---- 2. новая жизнь — с чистого ----
        if (!узел.Contains("_двери_снаружи = System.Array.Empty<ДверьСнаружи>();", StringComparison.Ordinal))
            плохо.Add("двери: новая жизнь не сбрасывает вид дверей прошлой");

        // ---- 3. свежий дом ----
        var прогон = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
        var сеанс = new Сеанс(прогон.h, "оксана");
        var снаружи = Подача.Снаружи(прогон.h, сеанс.Квартиры());
        var грязные = снаружи.Where(д => д.разобрана || д.взломана || д.горело || д.тело).Select(д => д.квартира).ToList();
        if (грязные.Count > 0)
            плохо.Add($"двери: у свежего дома уже есть следы — кв. {string.Join(", ", грязные)}");
        var план = сеанс.План();
        if (план.Count == 0 || план.Any(ж => !ж.здесь))
            плохо.Add("двери: план свежего дома пуст или в нём выбывшие");

        w($"  свежий дом: дверей {снаружи.Count}, следов нет; жильцов на плане {план.Count}");
        return плохо;
    }
}
