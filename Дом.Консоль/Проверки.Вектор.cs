// Проверка промзоны «Вектор-3» как места (задание автора, пп. 6–7;
// `Дом.Ядро/Петля/Вектор.cs`, `data/мир.json`, «вектор»).
//
//  1. **Данные не врут друг другу.** Опасны ровно те корпуса, что называют
//     Аркадий и журнал дежурного, — третий и пятый; иначе знание, которое
//     переходит из жизни в жизнь, водит героя не туда.
//  2. **Обыск.** Находка в пределах таблицы и в таре; второй раз корпус пуст.
//  3. **Опасные корпуса.** В безопасных не задевает никогда, в опасных —
//     с шансом из данных; задетый болеет по правилам болезни.
//  4. **Записки.** Журнал в заводоуправлении — «какие корпуса обходить»,
//     памятка в виварии — «как течёт болезнь»; знание в округе и потом
//     в наследии; второй раз записку не дают.
//  5. **Цена знания.** Лекарства лежат только в опасных корпусах: знание
//     бережёт — и тогда их брать негде, кроме как рискнуть.
//  6. **Сохранение.** Обшаренные корпуса переживают сохранение.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Вектор_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        const string КТО = "лида";
        if (л.вектор is not { } д)
        {
            плохо.Add("в мир.json нет промзоны «вектор»");
            return плохо;
        }
        (Прогон прогон, NPC я, Округа о, Дом.Ядро.Петля петля, Наследие наследие) Жизнь(long зерно = 7)
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            var наследие = new Наследие();
            var петля = new Дом.Ядро.Петля(наследие, ручки, инструменты: каталог, летопись: л);
            петля.Слушать(прогон, КТО);
            return (прогон, прогон.h.people[КТО], Округа.У(прогон.h)!, петля, наследие);
        }

        // ---- 1. данные ----
        var опасные = д.корпуса.Where(к => к.опасен).Select(к => к.номер).OrderBy(н => н).ToList();
        if (!опасные.SequenceEqual(new[] { 3, 5 }))
            плохо.Add($"опасны корпуса {string.Join(", ", опасные)} — а Аркадий велит обходить третий и пятый");
        var говорит = л.знатоки.SelectMany(з => з.ступени).FirstOrDefault(с => с.узнаёшь == "вектор_корпуса")?.говорит ?? "";
        if (!говорит.Contains("трет", StringComparison.OrdinalIgnoreCase) || !говорит.Contains("пят", StringComparison.OrdinalIgnoreCase))
            плохо.Add("Аркадий про корпуса говорит не «третий и пятый» — знание и данные разошлись");
        var журнал = д.корпуса.FirstOrDefault(к => к.узнаёшь == "вектор_корпуса");
        if (журнал is null || опасные.Any(н => !журнал.записка!.Contains($"корпус {н}", StringComparison.OrdinalIgnoreCase)))
            плохо.Add("журнал дежурного не называет опасные корпуса — а из него это узнают");

        // ---- 2 и 3. обыск и опасные корпуса ----
        string обыск_итог;
        {
            const int РАЗ = 100;
            var задело = new Dictionary<int, int>();
            var унесено = new Dictionary<int, double>();
            foreach (var к in д.корпуса)
            {
                задело[к.номер] = 0;
                унесено[к.номер] = 0;
                for (long зерно = 1; зерно <= РАЗ; зерно++)
                {
                    var (прогон, я, о, _, _) = Жизнь(зерно);
                    прогон.h.day = 2;
                    var р = о.вектор!.Обыскать(прогон.h, я, к.номер, о, ручки);
                    if (р.задело)
                    {
                        задело[к.номер]++;
                        if (о.заражение.Стадия(я.id) != Стадия.ЗАДЕТ)
                            плохо.Add($"корпус {к.номер}: задело — а болезнь не началась");
                    }
                    foreach (var (что, (от, до)) in к.находка)
                        if (р.нашёл.Взять(что, 0.0) < от - 1e-9 || р.нашёл.Взять(что, 0.0) > до + 1e-9)
                        {
                            плохо.Add($"корпус {к.номер}: нашёл {что} {Текст.G(р.нашёл.Взять(что, 0.0))} — а в нём от {от} до {до}");
                            break;
                        }
                    foreach (var что in р.унёс.Ключи)
                        if (я.ноша is null || я.ноша.Сколько(что) < р.унёс[что] - 1e-9)
                            плохо.Add($"корпус {к.номер}: унёс {что} — а в таре его нет");
                    унесено[к.номер] += р.унёс.Ключи.Sum(что => р.унёс[что]);
                    var второй = о.вектор.Обыскать(прогон.h, я, к.номер, о, ручки);
                    if (!второй.обшарен || второй.нашёл.Ключи.Count > 0)
                    {
                        плохо.Add($"корпус {к.номер} обыскали второй раз — и снова нашли");
                        break;
                    }
                }
                if (!к.опасен && задело[к.номер] > 0)
                    плохо.Add($"безопасный корпус {к.номер} задел {задело[к.номер]} раз из {РАЗ}");
                if (к.опасен && Math.Abs(задело[к.номер] / (double)РАЗ - д.задеть) > 0.1)
                    плохо.Add($"опасный корпус {к.номер} задел {задело[к.номер]} раз из {РАЗ} — а шанс {Текст.G(д.задеть)}");
            }
            обыск_итог = string.Join("; ", д.корпуса.Select(к =>
                $"{к.номер} ({к.имя}{(к.опасен ? ", опасен" : "")}): унесено {Текст.G(унесено[к.номер])}, задело {задело[к.номер]}"));
        }

        // ---- 4. записки ----
        string записки_итог;
        {
            var (прогон, я, о, петля, наследие) = Жизнь(5);
            прогон.h.day = 1;
            var узнано = new List<string>();
            foreach (var к in д.корпуса.Where(к => к.записка is not null))
            {
                var р = о.вектор!.Обыскать(прогон.h, я, к.номер, о, ручки);
                if (р.записка != к.записка || р.узнал != к.узнаёшь || !о.Знает(к.узнаёшь!))
                    плохо.Add($"в корпусе {к.номер} записку не прочитали или знание «{к.узнаёшь}» не легло в округу");
                if (о.вектор.Обыскать(прогон.h, я, к.номер, о, ручки).записка is not null)
                    плохо.Add($"записку в корпусе {к.номер} дали прочитать дважды");
                узнано.Add(к.узнаёшь!);
            }
            петля.Закрыть(прогон, КТО);
            foreach (var что in узнано)
                if (!наследие.знания.Contains(что))
                    плохо.Add($"прочитанное в промзоне («{что}») не перешло в наследие");
            записки_итог = $"прочитано: {string.Join(", ", узнано)} — и в наследии";
        }

        // ---- 5. цена знания ----
        var с_лекарствами = д.корпуса.Where(к => к.находка.ContainsKey("лекарства")).ToList();
        if (с_лекарствами.Count == 0 || с_лекарствами.Any(к => !к.опасен))
            плохо.Add("лекарства лежат не только в опасных корпусах — знанию нечего стоить");

        // ---- 6. сохранение ----
        {
            var (прогон, я, о, _, _) = Жизнь(9);
            о.вектор!.Обыскать(прогон.h, я, 2, о, ручки);
            о.вектор.Обыскать(прогон.h, я, 4, о, ручки);
            var (прогон2, _, о2, _, _) = Жизнь(9);
            о2.вектор!.Разложить(о.вектор.Сложить());
            if (!о2.вектор.Обшарен(2) || !о2.вектор.Обшарен(4) || о2.вектор.Обшарен(1))
                плохо.Add("обшаренные корпуса не пережили сохранения");
        }

        w($"  корпуса: опасны {string.Join(" и ", опасные)} — как у Аркадия и в журнале дежурного; "
          + $"лекарства — только в опасных ({string.Join(", ", с_лекарствами.Select(к => к.номер))})");
        w($"  обыск ({100} жизней на корпус): {обыск_итог}");
        w($"  записки: {записки_итог}");
        return плохо;
    }
}
