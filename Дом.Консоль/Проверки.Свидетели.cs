// Проверка свидетелей кармана (ГДД 9: «предмет исчезает из мира в момент
// помещения в инвентарь. Если это видит NPC — максимальное подозрение
// к игроку и уникальная реплика свидетеля»; `Карман.Подозрение`).
//
//  1. **Подозрение.** Видевший знает о герое всё, что можно знать
//     (осведомлённость до предела), считает, что у того не меньше
//     исчезнувшего, и помнит вывод («догадался»). Не видевший — как был.
//  2. **Реплика.** Видевший скажет об этом при встрече — один раз; это
//     переживает сейв.
//  3. **Экран.** Карман и полка зовут подозрение, у двери свидетель говорит
//     до метели и в метель (скан).

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Свидетели_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var профиль = new ПрофильГероя("Андрей");
        var п = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null),
                           жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
        new Дом.Ядро.Петля(new Наследие(), ручки,
                           инструменты: Дом.Ядро.Инструменты.Прочитать(Пути.Данные),
                           летопись: Летопись.Прочитать(Пути.Данные)).Слушать(п, Герой.ID);
        var h = п.h;
        var я = h.people[Герой.ID];
        var о = Округа.У(h)!;
        я.умения ??= new Умения(new Наследие(), ручки);
        я.карман = new Карман(я.умения);
        я.stock["еда"] = 5.0;
        var чужие = h.others(я).Where(x => x.здесь() && string.IsNullOrEmpty(x.living_with) && x.guests.Count == 0).ToList();
        var видел = чужие[0];
        var не_видел = чужие[1];
        видел.living_with = я.id;
        я.guests.Add(видел.id);

        double знал = видел.сведения_о(я.id).aware, думал = видел.believed(я.id, "еда");
        double знал_другой = не_видел.сведения_о(я.id).aware;
        int помнил = видел.memory.Count;

        // ---- 1. подозрение ----
        var видели = я.карман.Положить(h, я, "еда", 2.0);
        Карман.Подозрение(h, я, видели);
        string итог;
        {
            double знает = видел.сведения_о(я.id).aware, думает = видел.believed(я.id, "еда");
            if (!видели.Any(в => в.кто == видел.id))
                плохо.Add("свидетели: сосед под одной крышей не увидел, как вещь исчезла — проверять нечего");
            if (знает < 99.999)
                плохо.Add($"свидетели: видевший знает о герое {Текст.G(знает)} из ста — а по ГДД 9 подозрение максимальное");
            if (Math.Abs(думает - (думал + 2.0)) > 1e-9)
                плохо.Add($"свидетели: видевший думает, что еды у героя {Текст.G(думает)}, а видел, как исчезло две сверх {Текст.G(думал)}");
            if (!видел.memory.Skip(помнил).Any(з => з.вид == Вид.ДОГАДАЛСЯ && з.кто == я.id))
                плохо.Add("свидетели: видевший ничего не запомнил");
            if (Math.Abs(не_видел.сведения_о(я.id).aware - знал_другой) > 1e-9)
                плохо.Add("свидетели: не видевший тоже стал подозревать");
            итог = $"осведомлённость {Текст.G(знал)} → {Текст.G(знает)}, еды «у него» {Текст.G(думал)} → {Текст.G(думает)}";
        }

        // ---- 2. реплика: один раз, и сквозь сейв ----
        if (о.Скажет_о_чуде(не_видел.id))
            плохо.Add("свидетели: не видевший говорит о чуде");
        if (!о.Скажет_о_чуде(видел.id))
            плохо.Add("свидетели: видевший при встрече молчит");
        var сейв = о.Сложить();
        о.Разложить(сейв, я);
        if (о.Скажет_о_чуде(видел.id))
            плохо.Add("свидетели: о чуде говорит второй раз (или сейв забыл, что уже говорил)");
        сейв.Remove("видели_чудо");
        сейв.Remove("сказали_о_чуде");
        о.Разложить(сейв, я);   // старый сейв — свидетелей не было

        // ---- 3. экран ----
        {
            string Файл(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя));
            string ui = Файл("КарманUI.cs"), узел = Файл("ДомУзел.cs");
            if (ui.Split("Карман.Подозрение(Сеанс.дом, Сеанс.я, видели);").Length - 1 < 2)
                плохо.Add("свидетели: карман или полка кладут вещь, а подозрения нет");
            if (узел.Split("+ Чудо_говорит(с)").Length - 1 < 2)
                плохо.Add("свидетели: у двери свидетель молчит — до метели или в метель");
        }

        w($"  видевший: {итог}");
        return плохо;
    }
}
