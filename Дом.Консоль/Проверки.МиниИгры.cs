// Проверка мини-игр (ГДД 7, 8.1; `Дом.Ядро/Петля/МиниИгры.cs`, «мини_…»
// в `data/петля.json`).
//
//  1. **Правила.** Качество половина — прежний шанс, бросок в бросок;
//     ноль — хуже, единица — лучше, и между — не убывает. Сыграно плохо —
//     на ступень шумнее.
//  2. **Навык снимает игру.** Смекалка ниже третьего уровня — игра есть,
//     и зона шире с каждым уровнем; с третьего — игры нет, и «само» растёт.
//     У соседей игры нет вовсе, и само — половина: их броски не тронуты.
//  3. **Взлом замка живьём.** Одни и те же зёрна: сыграно «как обычно» —
//     те же исходы, что без мини-игры; плохо — удач меньше и стук слышат
//     чаще; хорошо — удач больше.
//  4. **Решётка и гермодверь** — тот же «Взлом»: руками при хорошей игре
//     выходит чаще, чем при плохой.
//  5. **Слова для экрана навыков** на каждом уровне — и Смекалка с третьего
//     говорит, что игры нет.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> МиниИгры_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        const string КТО = "оксана";

        // ---- 1. правила ----
        foreach (double шанс in new[] { 0.1, 0.4, 0.8 })
        {
            if (МиниИгры.Шанс(шанс, 0.5, ручки) != шанс)
                плохо.Add($"качество половина — а шанс {Текст.G(шанс)} стал {Текст.G(МиниИгры.Шанс(шанс, 0.5, ручки))}");
            double было = -1;
            for (int i = 0; i <= 10; i++)
            {
                double с = МиниИгры.Шанс(шанс, i / 10.0, ручки);
                if (с < было - 1e-12)
                    плохо.Add($"шанс {Текст.G(шанс)} убывает с качеством на {i / 10.0}");
                было = с;
            }
            if (МиниИгры.Шанс(шанс, 0.0, ручки) >= шанс || МиниИгры.Шанс(шанс, 1.0, ручки) <= шанс && шанс < 0.95)
                плохо.Add($"плохая игра не хуже или хорошая не лучше при шансе {Текст.G(шанс)}");
        }
        if (МиниИгры.Шум(2, 0.1, ручки) != 3 || МиниИгры.Шум(2, 0.5, ручки) != 2 || МиниИгры.Шум(0, 0.1, ручки) != 1)
            плохо.Add("сыграно плохо — а стук не громче (или громче при обычной игре)");

        // ---- 2. навык снимает игру ----
        string навык_итог;
        NPC Герой_(int смекалка, House h)
        {
            var н = new Наследие { очки = 1000 };
            for (int i = 0; i < смекалка; i++)
                н.Поднять(Навык.СМЕКАЛКА, ручки);
            var я = h.people[КТО];
            я.умения = new Умения(н, ручки);
            return я;
        }
        {
            var прогон = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            var h = прогон.h;
            var сосед = h.others(h.people[КТО]).First();
            if (МиниИгры.Нужна(сосед, МиниИгра.ВЗЛОМ, ручки) || МиниИгры.Само(сосед, МиниИгра.ВЗЛОМ, ручки) != 0.5)
                плохо.Add("у соседа мини-игра — а соседи не играют, и их бросок должен остаться прежним");
            int порог = (int)ручки["мини_игра_исчезает"];
            var строки = new List<string>();
            double зона_было = 0, само_было = 0;
            for (int ур = 0; ур <= (int)ручки["уровней_навыка"]; ур++)
            {
                var я = Герой_(ур, h);
                bool нужна = МиниИгры.Нужна(я, МиниИгра.ВЗЛОМ, ручки);
                double зона = МиниИгры.Зона(я, МиниИгра.ВЗЛОМ, ручки), само = МиниИгры.Само(я, МиниИгра.ВЗЛОМ, ручки);
                if (нужна != (ур < порог))
                    плохо.Add($"Смекалка {ур}: мини-игра {(нужна ? "есть" : "нет")} — а исчезать ей с {порог}-го");
                if (нужна && зона <= зона_было)
                    плохо.Add($"Смекалка {ур}: зона не шире, чем уровнем ниже");
                if (!нужна && (само <= 0.5 || само < само_было))
                    плохо.Add($"Смекалка {ур}: без игры выходит как сыгранное на {Текст.G(само)} — не лучше обычного");
                if (МиниИгры.Навык(МиниИгра.ВЗЛОМ) != Навык.СМЕКАЛКА)
                    плохо.Add("«Взлом» снимает не Смекалка (ГДД 8.1)");
                зона_было = зона;
                само_было = нужна ? 0 : само;
                строки.Add(нужна ? $"{ур}: игра, зона {Текст.G(Текст.Округлить(зона, 2))}" : $"{ур}: само {Текст.G(Текст.Округлить(само, 2))}");
            }
            навык_итог = string.Join("; ", строки);
        }

        // ---- 3. взлом замка живьём ----
        string взлом_итог;
        {
            var молоток = каталог.все["молоток"];
            var приём = молоток.Берёт("навесной")!;
            const int РАЗ = 300;
            int[] удач = new int[3];
            int[] слышали = new int[3];
            int разошлось = 0;
            var качества = new[] { 0.0, 0.5, 1.0 };
            for (long зерно = 1; зерно <= РАЗ; зерно++)
            {
                Попытка? обычно_без = null;
                for (int q = 0; q < 3; q++)
                {
                    var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
                    var h = прогон.h;
                    var я = h.people[КТО];
                    я.time_left = 16;
                    var к = h.кладовые["погреб1"];
                    var п = Взлом.попытка(h, я, к, ручки, молоток, приём, качество: качества[q]);
                    if (п.удалась) удач[q]++;
                    слышали[q] += п.слышали?.Count ?? 0;
                    if (q == 1)
                    {
                        // тот же дом без мини-игры — обязан дать тот же исход
                        var прогон2 = new Прогон(Пути.Данные, seed: зерно, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
                        var я2 = прогон2.h.people[КТО];
                        я2.time_left = 16;
                        обычно_без = Взлом.попытка(прогон2.h, я2, прогон2.h.кладовые["погреб1"], ручки, молоток, приём);
                        if (обычно_без.удалась != п.удалась || (обычно_без.слышали?.Count ?? 0) != (п.слышали?.Count ?? 0)
                            || обычно_без.застал != п.застал)
                            разошлось++;
                    }
                }
            }
            if (разошлось > 0)
                плохо.Add($"сыграно «как обычно» — а исход разошёлся с прежним броском на {разошлось} зёрнах из {РАЗ}");
            if (!(удач[0] < удач[1] && удач[1] < удач[2]))
                плохо.Add($"удач при плохой, обычной и хорошей игре: {удач[0]}, {удач[1]}, {удач[2]} — а должно расти");
            if (слышали[0] <= слышали[1])
                плохо.Add($"при плохой игре стук слышали {слышали[0]} раз, при обычной {слышали[1]} — не громче");
            взлом_итог = $"молотком по погребу, {РАЗ} зёрен: удач {удач[0]} / {удач[1]} / {удач[2]} "
                         + $"(плохо / как обычно / хорошо), слышали стук {слышали[0]} / {слышали[1]} / {слышали[2]}; "
                         + "«как обычно» — прежний бросок на всех зёрнах";
        }

        // ---- 4. решётка и гермодверь ----
        string руками_итог;
        {
            const int РАЗ = 300;
            int камера_плохо = 0, камера_хорошо = 0, дверь_плохо = 0, дверь_хорошо = 0;
            for (long зерно = 1; зерно <= РАЗ; зерно++)
                foreach (bool хорошо in new[] { false, true })
                {
                    var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
                    new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, КТО);
                    var о = Округа.У(прогон.h)!;
                    var я = прогон.h.people[КТО];
                    о.участок!.Задержать(я);
                    bool вышел = о.участок.Ломать(прогон.h, я, null, каталог, ручки, хорошо ? 1.0 : 0.0).вышел;
                    bool открыл = о.бункер!.Открыть(прогон.h, я, null, каталог, ручки, хорошо ? 1.0 : 0.0).открыл;
                    if (хорошо) { if (вышел) камера_хорошо++; if (открыл) дверь_хорошо++; }
                    else { if (вышел) камера_плохо++; if (открыл) дверь_плохо++; }
                }
            if (камера_хорошо <= камера_плохо || дверь_хорошо <= дверь_плохо)
                плохо.Add($"руками при хорошей игре не чаще: решётка {камера_плохо} → {камера_хорошо}, гермодверь {дверь_плохо} → {дверь_хорошо}");
            руками_итог = $"руками из {РАЗ}: решётка {камера_плохо} → {камера_хорошо}, гермодверь {дверь_плохо} → {дверь_хорошо} (плохо → хорошо)";
        }

        // ---- 5. слова для экрана навыков ----
        foreach (var н in Enum.GetValues<Навык>())
            for (int ур = 0; ур <= (int)ручки["уровней_навыка"]; ур++)
                if (Навыки.Что_даёт(н, ур, ручки).Length == 0)
                    плохо.Add($"{Навыки.Имя(н)} {ур}: экрану навыков нечего сказать");
        if (!Навыки.Что_даёт(Навык.СМЕКАЛКА, (int)ручки["мини_игра_исчезает"], ручки).Contains("без мини-игры", StringComparison.Ordinal))
            плохо.Add("Смекалка на пороге — а экран навыков не говорит, что игры больше нет");

        w($"  Смекалка: {навык_итог}");
        w($"  взлом: {взлом_итог}");
        w($"  решётка и гермодверь: {руками_итог}");
        return плохо;
    }
}
