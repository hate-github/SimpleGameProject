// Проверка «род героя» (`Дом.Ядро/Петля/Род.cs`): героем бывает и героиня,
// а вести о том, что герой сделал сам, долго писались в мужском роде —
// «взял: топор», «уснул, где стоял», «сорвал замок», итог распорядка
// «попил ×3, поел ×2». Нашла живая проба, а не проверка: ни один раздел
// рода не читал.
//
//  1. **Глагол.** `Род.Глагол` склоняет, как `Util.Vb`, и знает неправильные
//     глаголы героя, которых нет в таблице ядра («лёг» — «легла», не «лёга»).
//  2. **Слова.** Итог распорядка и вклады в рассудок на экране разбора —
//     в роде героя; метка вклада остаётся ключом.
//  3. **Исходники.** Строка, которая уходит игроку (`Сказать`, `Весть`,
//     `Сделано`, `Дорога_домой` …), не держит голого глагола героя из списка:
//     только через `Я(…)`, `Род.Глагол(…)` или `Util.Vb(…)`. Глагол
//     о другом человеке — пометка «род: причина» на той же строке.

using System.Text.RegularExpressions;
using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    /// <summary>Глаголы героя, которые бывают в вестях о его делах.</summary>
    private static readonly string[] ГЛАГОЛЫ_ГЕРОЯ =
    (
        "взял положил выложил вынул купил сорвал снял отпер надел оставил щёлкнул разложил "
        + "спустился вернулся оглянулся уснул лёг проспал выспался поел попил затопил натопил "
        + "разломал заказал посидел промолчал давил просил съел понял унёс принёс нашёл ходил "
        + "сходил таскал пересидел выстрелил отбился содрал задел замялся попал покрутил дожил "
        + "остался встал"
    ).Split(' ');

    /// <summary>Вызовы, чьи строки читает игрок, и присваивания вести.</summary>
    private static readonly Regex СТОКИ_ВЕСТЕЙ = new(
        @"\b(Сказать|Весть|Вернуться|Дорога_домой|Сделано|ИтогВстречи|Пролог_спать|Лечь|Разгрузить"
        + @"|СтрокаОкна|Встать_из_распорядка|Штурвал)\(|\b\w*весть\s*=[^=>]");

    public static List<string> Род_(Action<string> w)
    {
        var плохо = new List<string>();

        // ---- 1. глагол ----
        var глаголы = new (string пол, string слово, string ждём)[]
        {
            ("ж", "взял", "взяла"), ("ж", "лёг", "легла"), ("ж", "отпер", "отперла"),
            ("ж", "оглянулся", "оглянулась"), ("ж", "ушёл", "ушла"), ("ж", "унёс", "унесла"),
            ("м", "лёг", "лёг"), ("м", "взял", "взял"), ("", "отпер", "отпер"),
        };
        foreach (var (пол, слово, ждём) in глаголы)
            if (Род.Глагол(пол, слово) is var г && г != ждём)
                плохо.Add($"«{слово}» в роде «{пол}» — «{г}», а надо «{ждём}»");
        w($"  глагол: {глаголы.Length} случаев, «лёг» у героини — «{Род.Глагол("ж", "лёг")}»");

        // ---- 2. слова ----
        foreach (var п in Enum.GetValues<Привычка>())
            if (п.Текст("ж") == п.Текст("м"))
                плохо.Add($"итог распорядка «{п.Текст("м")}» у героини тот же — род не ставится");
        var вклады = new[] { "видел расправу", "убил в бою", "был один", "развлекался", "помогал" };
        foreach (var за_что in вклады)
            if (Рассудок.Словами(new ВкладВРассудок(за_что, 1.0), "ж") == за_что)
                плохо.Add($"вклад «{за_что}» на разборе героини — в мужском роде");
        if (Рассудок.Словами(new ВкладВРассудок("своя смерть", 1.0), "ж") != "своя смерть"
            || Рассудок.Словами(new ВкладВРассудок("убил в бою", 1.0), "м") != "убил в бою")
            плохо.Add("вклад без рода или о герое-мужчине переписан — метка должна остаться как есть");
        w($"  слова: распорядок героини — {string.Join(", ", Enum.GetValues<Привычка>().Select(п => п.Текст("ж")))}; "
          + $"разбор — {Рассудок.Словами(new ВкладВРассудок("был один", 1.0), "ж")}");

        // ---- 3. исходники ----
        var слово_ = new Regex(@"(?<![А-Яа-яЁё])(" + string.Join("|", ГЛАГОЛЫ_ГЕРОЯ) + @")(?![А-Яа-яЁё])");
        var род = new Regex(@"(\bЯ|Род\.Глагол|Util\.Vb)\([^()]*\)");
        var строка = new Regex(@"""((?:[^""\\]|\\.)*)""");
        var дыра = new Regex(@"\{[^{}]*\}");
        var папки = new[] { "Дом.Годот", "Дом.Экран", Path.Combine("Дом.Ядро", "Петля") };
        int файлов = 0, вызовов = 0;
        foreach (var папка in папки)
            foreach (var ф in Directory.GetFiles(Path.Combine(Пути.Корень, папка), "*.cs").OrderBy(x => x, StringComparer.Ordinal))
            {
                файлов++;
                int ещё = 0;        // строка вызова и две её продолжения
                var строки = File.ReadAllLines(ф);
                for (int i = 0; i < строки.Length; i++)
                {
                    string с = строки[i];
                    string т = с.Trim();
                    if (т.StartsWith("//", StringComparison.Ordinal) || т.Contains("GD.Print", StringComparison.Ordinal))
                        continue;
                    if (СТОКИ_ВЕСТЕЙ.IsMatch(с))
                    {
                        ещё = 3;
                        вызовов++;
                    }
                    else if (ещё == 0)
                        continue;
                    ещё--;
                    if (с.Contains("род:", StringComparison.Ordinal))
                        continue;
                    foreach (Match м in строка.Matches(род.Replace(с, "")))
                        if (слово_.Match(дыра.Replace(м.Groups[1].Value, "")) is { Success: true } г)
                        {
                            плохо.Add($"{Path.Combine(папка, Path.GetFileName(ф))}:{i + 1}: «{г.Value}» игроку без рода героя — {т}");
                            break;
                        }
                }
            }
        w($"  исходники: {файлов} файлов, {вызовов} вызовов со строками игроку, глаголов в списке {ГЛАГОЛЫ_ГЕРОЯ.Length}");
        return плохо;
    }
}
