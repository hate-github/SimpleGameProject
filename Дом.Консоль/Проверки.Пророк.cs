// Проверка реплик пророка (ГДД 12.6: «его реплики меняются в зависимости
// от рассудка игрока — этого не замечает никто, кроме них двоих»;
// `Дом.Ядро/Петля/Пророк.cs`, `data/пророк.json`).
//
//  1. **Когда.** В первой жизни — ничего; дальше — по порогу рассудка
//     (обычно, тревога, отстранение), в нирване — своё, и в первой тоже.
//  2. **По кругу.** Строки идут по счёту разговоров, без броска.
//  3. **Данные.** Реплики на все четыре состояния; состояние, которого нет, —
//     файл не читается.
//  4. **Кто.** Пророк в доме один — тот, кто «знал заранее»; у двери его
//     реплика идёт следом за приветствием, до метели и в метель (скан).

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Пророк_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var п = Пророк.Прочитать(Пути.Данные);
        string? Сказал(int жизней, double рассудок, bool нирвана, int раз = 0)
            => п.Реплика(new Наследие { жизней = жизней, рассудок = рассудок, нирвана = нирвана }, ручки, раз);

        // ---- 1. когда ----
        if (Сказал(0, 0, false) is { } рано)
            плохо.Add($"пророк: в первой жизни уже говорит своё — «{рано}»");
        var по_порогам = new[] { Сказал(1, 1, false), Сказал(1, 5, false), Сказал(1, 9, false), Сказал(1, 1, true) };
        if (по_порогам.Any(р => р is null) || по_порогам.Distinct().Count() != 4)
            плохо.Add($"пророк: обычно, тревога, отстранение и нирвана — не четыре разные реплики: {string.Join(" | ", по_порогам)}");
        if (Сказал(0, 0, true) is null)
            плохо.Add("пророк: нирвана в первой жизни петли — а он молчит");

        // ---- 2. по кругу ----
        if (Сказал(2, 5, false, 0) == Сказал(2, 5, false, 1) || Сказал(2, 5, false, 0) != Сказал(2, 5, false, 2))
            плохо.Add("пророк: реплики не идут по кругу по счёту разговоров");

        // ---- 3. данные ----
        {
            string папка = Path.Combine(Path.GetTempPath(), "пророк_проверка_" + Environment.ProcessId);
            Directory.CreateDirectory(папка);
            try
            {
                string текст = File.ReadAllText(Path.Combine(Пути.Данные, "пророк.json"))
                                   .Replace("\"тревога\":", "\"паника\":", StringComparison.Ordinal);
                File.WriteAllText(Path.Combine(папка, "пророк.json"), текст);
                bool упал = false;
                try { Пророк.Прочитать(папка); }
                catch (InvalidDataException) { упал = true; }
                if (!упал)
                    плохо.Add("пророк: реплики на состояние, которого нет («паника»), — а файл читается");
            }
            finally
            {
                Directory.Delete(папка, true);
            }
        }

        // ---- 4. кто ----
        {
            var прогон = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            var пророки = прогон.h.people.Значения.Where(x => x.пунктики.Contains("знал_заранее")).ToList();
            if (пророки.Count != 1)
                плохо.Add($"пророк: «знал заранее» у {пророки.Count} жильцов, а пророк один");
            string узел = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "ДомУзел.cs"));
            if (узел.Split("+ Пророк_говорит(с)").Length - 1 < 2
                || !узел.Contains("с.пунктики.Contains(\"знал_заранее\")", StringComparison.Ordinal))
                плохо.Add("пророк: у двери его реплики нет — до метели или в метель");
        }

        w($"  обычно: «{по_порогам[0]}»");
        w($"  отстранение: «{по_порогам[2]}»; нирвана: «{по_порогам[3]}»");
        return плохо;
    }
}
