// Проверка гаража: замок отдельно от добычи, коробка — доля.
//
// Игрок срывает замок и обыскивает коробки по одной. Для этого в доме
// две функции, которых нет в прототипе, — `Улица.сорвать_замок`
// и `Улица.взять_коробку`, — и проверять их надо числом:
//
//  1. **Замок — без добычи.** Кладовая вскрыта, дом об этом знает
//     (событие, хозяин со временем узнает), а запасы и ходки не тронуты.
//     Сорванный второй раз замок нового вскрытия не даёт.
//  2. **Коробка — доля того, что осталось.** Пять и четыре на три
//     коробки — два и два, потом два и один, потом остаток. Всё, что
//     ушло из кладовой, пришло к герою, и последняя коробка кладовую
//     опустошает. Первая версия гаража выносила ходку сразу с замком,
//     и игроку казалось, что коробки пустеют все разом.
//  3. **Сосед по-прежнему выносит ходку.** `вскрыть_кладовую` делит
//     с игроком только хвост — событие и вину — и за раз уносит
//     `кладовая_за_раз`, как раньше. Порядок её действий сверяет эталон.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Гараж_(Action<string> w)
    {
        var плохо = new List<string>();
        static House Дом_() => new Прогон(Пути.Данные, seed: 1, days: 1,
                                          журнал: new Журнал(0, false, TextWriter.Null)).h;
        static int Вскрытий(House h) => h.события.Count(с => с.вид == ВидСобытия.ВСКРЫТИЕ);

        // ---- 1. замок без добычи ----
        {
            var h = Дом_();
            var к = h.кладовые["гараж13"];
            var я = h.people["оксана"];
            var хозяин = h.хозяин_кладовой(к);
            string в_кладовой = Строкой(к.stock);
            string у_меня = Строкой(я.stock);
            int ходок = к.ходок;
            int вскрытий = Вскрытий(h);

            Улица.сорвать_замок(h, я, к);
            if (!к.вскрыта)
                плохо.Add("замок сорван, а кладовая не вскрыта");
            if (Строкой(к.stock) != в_кладовой)
                плохо.Add($"сорвали замок — и из кладовой ушло: {в_кладовой} → {Строкой(к.stock)}");
            if (Строкой(я.stock) != у_меня)
                плохо.Add($"сорвали замок — и герою пришло: {у_меня} → {Строкой(я.stock)}");
            if (к.ходок != ходок)
                плохо.Add($"замок сорван без добычи, а ходок стало {к.ходок}");
            int после = Вскрытий(h);
            if (после != вскрытий + 1)
                плохо.Add($"вскрытий в событиях {вскрытий} → {после}, а должно прибавиться одно");
            if (хозяин is null)
                плохо.Add("у гаража 13 нет хозяина — проверять некого");
            else if (!h.ожидает.вскрытые_кладовые.Contains((я.id, к.id)))
                плохо.Add($"хозяин ({хозяин.id}) так и не узнает о сорванном замке");

            Улица.сорвать_замок(h, я, к);
            if (Вскрытий(h) != после)
                плохо.Add("сорванный замок сорвали второй раз — и дом записал новое вскрытие");
            w($"  замок: вскрыт, в кладовой по-прежнему {в_кладовой}; "
              + $"узнает {хозяин?.id ?? "никто"}");
        }

        // ---- 2. коробка — доля того, что осталось ----
        {
            var h = Дом_();
            var к = h.кладовые["гараж13"];
            var я = h.people["оксана"];
            к.stock.Очистить();
            к.stock["топливо"] = 5;
            к.stock["материалы"] = 4;
            double топливо = я.stock.Взять("топливо", 0.0);
            double материалы = я.stock.Взять("материалы", 0.0);

            var ждём = new (int коробок, double топливо, double материалы)[]
            {
                (3, 2, 2), (2, 2, 1), (1, 1, 1),
            };
            foreach (var (коробок, т, м) in ждём)
            {
                var взято = Улица.взять_коробку(h, я, к, коробок);
                if (взято.Взять("топливо", 0.0) != т || взято.Взять("материалы", 0.0) != м)
                    плохо.Add($"коробка, когда полных {коробок}: взято «{Строкой(взято)}», "
                              + $"а ждали топливо {т}, материалы {м}");
            }
            if (!к.пусто())
                плохо.Add($"последняя коробка взята, а в кладовой осталось «{Строкой(к.stock)}»");
            if (я.stock.Взять("топливо", 0.0) - топливо != 5
                || я.stock.Взять("материалы", 0.0) - материалы != 4)
                плохо.Add("из кладовой ушло 5 и 4, а герою пришло "
                          + $"{я.stock.Взять("топливо", 0.0) - топливо} "
                          + $"и {я.stock.Взять("материалы", 0.0) - материалы}");
            w("  коробки: 5 и 4 на три — 2/2, 2/1, 1/1, кладовая пуста");
        }

        // ---- 3. сосед по-прежнему выносит ходку ----
        {
            var h = Дом_();
            var к = h.кладовые["гараж13"];
            var вор = h.people["оксана"];
            double за_раз = h.B["кладовая_за_раз"];
            var было = new Словарь<string, double>(к.stock);
            var взято = Улица.вскрыть_кладовую(h, вор, к);
            foreach (var р in было.Ключи)
            {
                double ждём = Math.Min(было[р], за_раз);
                if (взято.Взять(р, 0.0) != ждём)
                    плохо.Add($"сосед вынес {р} {взято.Взять(р, 0.0)}, а за ходку положено {ждём}");
            }
            if (к.ходок != 1)
                плохо.Add($"сосед сходил один раз, а ходок {к.ходок}");
            if (!к.вскрыта || Вскрытий(h) != 1)
                плохо.Add("сосед сорвал замок, а дом этого не заметил");
            w($"  сосед: одна ходка — «{Строкой(взято)}»");
        }
        return плохо;
    }

    private static string Строкой(Словарь<string, double> запасы)
        => string.Join(", ", запасы.Ключи
            .OrderBy(р => р, StringComparer.Ordinal)
            .Where(р => запасы[р] != 0)
            .Select(р => $"{р} {Текст.G(запасы[р])}"));
}
