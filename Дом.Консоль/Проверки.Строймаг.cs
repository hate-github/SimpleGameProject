// Проверка строительного на Заречной (ГДД 15: «строительный магазин в фазе
// подготовки: купить или украсть через инвентарь»; ГДД 18: «продуктовый
// и строительный магазины работают до дня 0»; `data/строймаг.json`,
// тот же класс `Дом.Ядро/Петля/Магазин.cs`):
//
//  1. **Каталог.** Продаёт материалы, топливо и инструмент; болтореза нет
//     (он только в чужом гараже). У каждой строки — склад штуками: у дома
//     этого места нет. Продавец — свой.
//  2. **Только до метели.** В прологе (день дома ноль) открыт, с первого
//     дня закрыт: покупка не идёт, поход за ворота сказан закрытым.
//  3. **Покупка.** Доски — в тару, как в продуктовом, дом считает
//     принесённое; склад убывает штуками, а место в доме не трогается —
//     соседям не меньше. Склад кончился — «кончилось».
//  4. **Кража.** Украденное тоже со склада, а не с полки дома.
//  5. **Сохранение.** Сколько продано — переживает сохранение и загрузку.
//  6. **Продуктовый не тронут.** У него ресурсы по-прежнему с полки дома.
//  7. **Узел.** Прилавок и дверь строительного заведены, поход ведёт туда.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Строймаг_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        Прогон? последний = null;
        Дом.Ядро.Петля? последняя_петля = null;
        (House h, NPC я) Жизнь(string кто = "лида")
        {
            var прогон = new Прогон(Пути.Данные, seed: 7, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            var петля = new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л);
            петля.Слушать(прогон, кто);
            (последний, последняя_петля) = (прогон, петля);
            return (прогон.h, прогон.h.people[кто]);
        }

        // ---- 1. каталог ----
        var с = Магазин.Прочитать(Пути.Данные, каталог, "строймаг.json");
        if (!с.до_метели || с.продавец == "продавщица")
            плохо.Add($"строительный: до метели — {с.до_метели}, за прилавком — «{с.продавец}»; ждали свой прилавок до метели");
        var доски = с.товары.FirstOrDefault(т => т.ресурс == "материалы");
        if (доски is null || !с.товары.Any(т => т.ресурс == "топливо") || !с.товары.Any(т => т.предмет == "молоток"))
        {
            плохо.Add("в строительном нет материалов, топлива или молотка");
            return плохо;
        }
        if (с.товары.Any(т => т.предмет == "болторез"))
            плохо.Add("строительный продаёт болторез — а он только в чужом гараже");
        if (с.товары.Any(т => т.всего <= 0))
            плохо.Add("у строки строительного нет склада — значит, полка дома, а у дома этого места нет");

        // ---- 2. только до метели ----
        {
            var (h, я) = Жизнь();
            h.day = 0;
            if (!с.Открыт(h))
                плохо.Add("до метели строительный закрыт");
            h.day = 1;
            я.счёт = 10;
            я.ноша = new Ноша();
            if (с.Открыт(h) || с.Купить(h, я, доски, ручки, каталог).взято)
                плохо.Add("в первый день метели строительный торгует");
            var поход = л.походы.FirstOrDefault(п => п.вид == "строительный");
            if (поход is null)
                плохо.Add("в походах нет строительного — за ворота не дойти");
            else if (Округа.У(h) is { } о && о.Нельзя(h, я, поход) is not string закрыт)
                плохо.Add("в метель поход в строительный открыт — а там ставни на замке");
            else if (Округа.У(h) is { } о2)
            {
                h.day = 0;
                if (о2.Нельзя(h, я, поход) is string нельзя)
                    плохо.Add($"до метели в строительный не пойти: {нельзя}");
            }
        }

        // ---- 3. покупка ----
        string итог;
        {
            var (h, я) = Жизнь();
            var см = Магазин.Прочитать(Пути.Данные, каталог, "строймаг.json");
            h.day = 0;
            я.счёт = 100;
            я.stock["деньги"] = 0;
            я.ноша = new Ноша();
            var места = h.места.ToDictionary(п => п.Key, п => п.Value, StringComparer.Ordinal);
            double принесено = h.stats.Взять("принесено_материалы", 0.0);
            int было = см.Осталось(h, доски);
            var п = см.Купить(h, я, доски, ручки, каталог);
            if (!п.взято || Math.Abs(я.ноша.Сколько("материалы") - доски.единиц) > 1e-9)
                плохо.Add($"доски не купить или не в таре: {п.почему}, в таре {я.ноша.Сколько("материалы")}");
            if (см.Осталось(h, доски) != было - 1)
                плохо.Add($"купил доски — на складе было {было}, стало {см.Осталось(h, доски)}");
            if (h.stats.Взять("принесено_материалы", 0.0) != принесено + доски.единиц)
                плохо.Add("покупку в строительном дом не посчитал принесённой");
            if (места.Count != h.места.Count || места.Any(м => Math.Abs(h.места[м.Key] - м.Value) > 1e-12))
                плохо.Add("герой купил в строительном — а у дома опустело какое-то место: соседям меньше");
            // склад кончился
            я.ноша = new Ноша();
            for (int i = 0; i < 40 && см.Осталось(h, доски) > 0; i++)
            {
                if (!см.Купить(h, я, доски, ручки, каталог).взято)
                    я.ноша = new Ноша();          // тара полна — новая, склад считать дальше
            }
            var последняя = см.Купить(h, я, доски, ручки, каталог);
            if (последняя.взято || последняя.почему != "кончилось")
                плохо.Add($"досок на складе {доски.всего} — а купили сверх: {последняя}");
            // ---- 4. кража ----
            var уголь = см.товары.First(т => т.ресурс == "топливо");
            int угля = см.Осталось(h, уголь);
            я.ноша = new Ноша();
            Кража? к = null;
            for (int i = 0; i < 200 && к is not { взято: true }; i++)
                к = см.Украсть(h, я, уголь, false, 0, ручки, каталог);
            if (к is not { взято: true })
                плохо.Add("уголь из строительного так и не украсть за двести попыток");
            else if (см.Осталось(h, уголь) != угля - 1)
                плохо.Add($"украл уголь — на складе было {угля}, стало {см.Осталось(h, уголь)}");
            if (места.Any(м => Math.Abs(h.места[м.Key] - м.Value) > 1e-12))
                плохо.Add("украл в строительном — а у дома опустело место");

            // ---- 5. сохранение ----
            // сквозь сохранение игры: тем же путём, что узел
            var сейв = СохранениеИгры.Сложить(null, "лида", последний!, последняя_петля!, null, null, см);
            var заново = Магазин.Прочитать(Пути.Данные, каталог, "строймаг.json");
            var (h2, _) = Жизнь();
            СохранениеИгры.Разложить(сейв, последний!, последняя_петля!, null, заново);
            if (заново.Осталось(h, доски) != см.Осталось(h, доски) || заново.Осталось(h, уголь) != см.Осталось(h, уголь))
                плохо.Add("проданное в строительном не пережило сохранения");
            итог = $"до метели открыт, в метель закрыт; досок на складе {доски.всего}, после всех покупок — {см.Осталось(h, доски)}; "
                   + $"угля было {угля}, после кражи — {см.Осталось(h, уголь)}; за прилавком — {см.продавец}";
        }

        // ---- 6. продуктовый не тронут ----
        {
            var (h, я) = Жизнь();
            var м = Магазин.Прочитать(Пути.Данные, каталог);
            h.day = 1;
            h.магазины = true;
            я.счёт = 10;
            я.ноша = new Ноша();
            var вода = м.товары.First(т => т.ресурс == "вода");
            double полка = h.богатство_места(м.место);
            м.Купить(h, я, вода, ручки, каталог);
            if (h.богатство_места(м.место) >= полка - 1e-12 || м.до_метели)
                плохо.Add("продуктовый перестал брать с полки дома или закрылся с метелью");
        }

        // ---- 7. узел ----
        string узел = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Годот"), "*.cs").Select(File.ReadAllText));
        foreach (var (текст, беда) in new[]
                 {
                     ("Магазин.Прочитать(Пути.Данные, _инструменты, \"строймаг.json\")", "узел не читает строительный"),
                     ("К_прилавку(_строймаг, прилавок_с)", "прилавок строительного не продаёт"),
                     ("_мир.ДверьМагазина, _мир.ДверьСтройки", "из строительного не уйти домой"),
                     ("_герой.GlobalPosition = _мир.ВходСтройки", "поход не приводит в строительный"),
                     ("СохранениеИгры.Сложить(_игра.герой, _игра.кто, чья.прогон, _петля, _магазин, _пролог, _строймаг)", "строительный не сохраняется"),
                     ("СохранениеИгры.Разложить(сейв, прогон, _петля, _магазин, _строймаг)", "строительный не загружается"),
                     ("Походы_строительный();", "в мире нет строительного"),
                 })
            if (!узел.Contains(текст, StringComparison.Ordinal))
                плохо.Add($"узел: {беда}");

        w("  " + итог);
        return плохо;
    }
}
