// Проверка пролога — дней подготовки до метели (задание автора, пп. 14–15;
// `Дом.Ядро/Петля/Пролог.cs`, `data/петля.json`).
//
//  1. **Дни.** Пролог начинается за `подготовка_дней` до метели, каждая
//     ночь — день ближе, после последней — метель.
//  2. **Цены до метели обычные**: наценки нет, а не скидка (дом ещё
//     на нулевом дне).
//  3. **Подозрение.** Кто слышал, как герой вносит полную тару, копит
//     подозрение; с метелью оно ложится в его оценку запасов героя —
//     к правде, с весом по тому, сколько видел. Кто не слышал — ничего.
//     Сам пролог не наказывает: ни доверия, ни злобы он не трогает.
//  4. **Эталон цел.** Пролог, в котором ничего не пронесли, не меняет дома:
//     снимок совпадает с домом без пролога.
//  5. **Откат без дублей.** Смерть — новая жизнь с пролога: шкаф героя —
//     как в данных, карман пуст (содержимое не переносится, ГДД 8).

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Пролог_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        const string КТО = "оксана";
        (Прогон прогон, NPC я, Дом.Ядро.Петля петля) Жизнь(long зерно = 7, Наследие? наследие = null)
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            var петля = new Дом.Ядро.Петля(наследие ?? new Наследие(), ручки, инструменты: каталог, летопись: л);
            петля.Слушать(прогон, КТО);
            return (прогон, прогон.h.people[КТО], петля);
        }

        // ---- 1. дни ----
        string дни_итог;
        {
            var п = Пролог.Из(ручки);
            int дней = (int)ручки["подготовка_дней"];
            var шли = new List<int> { п.день };
            int ночей = 0;
            while (п.Ночь())
            {
                шли.Add(п.день);
                if (++ночей > 10)
                    break;
            }
            if (дней < 1)
                плохо.Add("дней подготовки ноль — жизнь начинается сразу с метели, отката за два дня нет");
            if (шли[0] != -дней || шли.Count != дней || шли[^1] != -1)
                плохо.Add($"дни пролога: {string.Join(", ", шли)} — а должно от −{дней} до −1");
            if (п.идёт)
                плохо.Add("после последней ночи пролог не кончился — метель не приходит");
            дни_итог = $"{string.Join(" → ", шли)} → метель";
        }

        // ---- 2. цены до метели ----
        string цены_итог;
        {
            var (прогон, _, _) = Жизнь();
            var h = прогон.h;
            var м = Магазин.Прочитать(Пути.Данные, каталог);
            var еда = м.товары.First(т => т.ресурс == "еда");
            double база = h.B.Таблица("магазин_цена")["еда"];
            double до = м.Цена(h, еда);                 // дом ещё на нулевом дне
            h.day = 1;
            double первый = м.Цена(h, еда);
            h.day = 3;
            double третий = м.Цена(h, еда);
            if (Math.Abs(до - база) > 1e-9)
                плохо.Add($"еда до метели стоит {Текст.G(до)} — а обычная цена {Текст.G(база)}");
            if (третий <= первый)
                плохо.Add("в метель цены не растут");
            цены_итог = $"еда до метели {Текст.G(до)}, в первый день {Текст.G(первый)}, на третий {Текст.G(третий)}";
        }

        // ---- 3. подозрение ----
        string подозрение_итог;
        {
            var (прогон, я, _) = Жизнь(11);
            var h = прогон.h;
            var п = Пролог.Из(ручки);
            // полная тара еды — как принёс бы из магазина
            я.ноша = new Ноша();
            var еда = Словари.Числа();
            еда["еда"] = Тара.СУМКА.мест(ручки);
            я.ноша.Положить(Тара.СУМКА, еда, ручки);
            var что = я.ноша.ресурсы.ToDictionary(р => р, р => я.ноша.Сколько(р), StringComparer.Ordinal);
            var слышали = я.ноша.Пронести(h, я, ручки);
            п.Пронёс(слышали, что, 1.0);
            я.ноша.Разгрузить(я);
            if (слышали.Count == 0)
                плохо.Add("полную сумку внесли в подъезд — и никто не слышал: подозревать некому");
            var видел = слышали.FirstOrDefault();
            var не_видел = h.others(я).FirstOrDefault(p => !слышали.Contains(p));
            double Оценка(NPC p) => p.сведения.TryGetValue(я.id, out var св) ? св.est.Взять("еда", 2.0) : 2.0;
            double до_видел = видел is null ? 0 : Оценка(видел), до_не = не_видел is null ? 0 : Оценка(не_видел);
            double доверие_до = видел?.trust.Взять(я.id, 3.0) ?? 0;
            double злоба_до = видел?.hate.Взять(я.id, 0.0) ?? 0;
            var насторожились = п.Метель(h, я, ручки);
            double правда = я.stock.Взять("еда", 0.0);
            if (видел is not null)
            {
                if (!насторожились.Contains(видел))
                    плохо.Add($"{видел.id} слышал, как героиня внесла сумку, — а не насторожился");
                if (Math.Abs(Оценка(видел) - правда) >= Math.Abs(до_видел - правда) - 1e-9)
                    плохо.Add($"{видел.id} видел сумку — а его оценка запасов героини не сдвинулась к правде "
                              + $"({Текст.G(до_видел)} → {Текст.G(Оценка(видел))}, правда {Текст.G(правда)})");
                if (видел.trust.Взять(я.id, 3.0) != доверие_до || видел.hate.Взять(я.id, 0.0) != злоба_до)
                    плохо.Add("пролог наказал на месте: доверие или злоба видевшего изменились");
            }
            if (не_видел is not null && Оценка(не_видел) != до_не)
                плохо.Add($"{не_видел.id} ничего не видел — а его оценка запасов героини сдвинулась");
            if (п.день != 0)
                плохо.Add("метель пришла — а пролог не на нулевом дне");
            подозрение_итог = $"сумку слышали {слышали.Count}; {видел?.id}: оценка еды {Текст.G(Текст.Округлить(до_видел, 1))} "
                              + $"→ {Текст.G(Текст.Округлить(видел is null ? 0 : Оценка(видел), 1))} (правда {Текст.G(правда)}); "
                              + $"не слышавший — без перемен";
        }

        // ---- 4. эталон цел ----
        {
            var (с_прологом, _, _) = Жизнь(5);
            var п = Пролог.Из(ручки);
            while (п.Ночь()) { }
            п.Метель(с_прологом.h, с_прологом.h.people[КТО], ручки);
            var (без, _, _) = Жизнь(5);
            string а = Снимок.Текстом(Снимок.Собранный(с_прологом.h));
            string б = Снимок.Текстом(Снимок.Собранный(без.h));
            if (а != б)
                плохо.Add("пролог, в котором ничего не пронесли, изменил дом к первому дню метели");
        }

        // ---- 5. откат без дублей ----
        string откат_итог;
        {
            var наследие = new Наследие();
            var (прогон, я, петля) = Жизнь(3, наследие);
            double еды_в_данных = я.stock.Взять("еда", 0.0);
            я.stock["еда"] = еды_в_данных + 20;                     // накупил в прологе
            я.карман!.Положить_найденное("еда", 3);                  // и спрятал в карман
            я.alive = false;
            я.cause = "холод";
            я.died_day = 1;
            петля.Закрыть(прогон, КТО);
            if (я.карман.занято > 0)
                плохо.Add("смерть не обнулила карман — вещи перенесутся в следующую жизнь");
            var (_, я2, _) = Жизнь(3, наследие);
            if (Math.Abs(я2.stock.Взять("еда", 0.0) - еды_в_данных) > 1e-9)
                плохо.Add($"новая жизнь началась с {Текст.G(я2.stock.Взять("еда", 0.0))} еды — а в данных {Текст.G(еды_в_данных)}: "
                          + "накупленное в прошлой жизни продублировалось");
            if (я2.карман!.занято > 0)
                плохо.Add("новая жизнь началась с непустым карманом");
            откат_итог = $"новая жизнь: еды {Текст.G(я2.stock.Взять("еда", 0.0))} (как в данных), карман пуст";
        }

        w($"  дни: {дни_итог}");
        w($"  цены: {цены_итог}");
        w($"  подозрение: {подозрение_итог}");
        w($"  откат: {откат_итог}");
        return плохо;
    }
}
