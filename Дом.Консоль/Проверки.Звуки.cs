// Проверка звуков: что герой слышит и чем это звучит (`Дом.Экран/Слух.cs`,
// записи автора в `Дом.Годот/звуки`).
//
//  1. **Записи.** Закрытый список `Слух.ЗАПИСИ` — это папка: ни пропавшего
//     файла, ни лишнего; у каждой записи строка в `звуки/ЧИТАЙ.md`; каждое
//     имя, которое узлы движка называют строкой в вызове звука, — из списка;
//     и ни одной записи, которую никто не играет.
//  2. **Услышанное.** Звучит только сегодняшнее, не больше трёх разом;
//     шаги молчат; кого нет в доме, тот не слышит подъезда; взлом деревянной
//     двери — топор, железной — металл; выстрел — тем стволом, что у
//     стрелявшего; налёт, слышанный и памятью, и событием, бьёт в дверь
//     один раз; пожар, переезд, прорвались — свои записи.
//  3. **Крик.** Ядро пишет о крике жертвы ровно ту строку, которую ищет
//     слух (сверка с исходником осады); голос по полу — у её двери; вчерашний
//     и из участка не слышен; свой крик — без места.
//  4. **Дела.** Поел у горящей печки — жарка, у холодной — без неё; листы —
//     молоток по металлу, утепление — пила и дерево; открыл на стук — своя
//     дверь, отказал — тихо; все дела справочника звучат только записями
//     из списка.
//  5. **Фон.** Простуженный сосед кашляет у своей двери, голосом своего пола;
//     голодный ребёнок плачет, сытый и в тепле — нет; из участка слышно
//     только себя.
//  6. **Чат.** Чужое сообщение — телефон пискнул, своё — нет.

using System.Text.RegularExpressions;
using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Звуки_(Action<string> w)
    {
        var плохо = new List<string>();
        var список = Слух.ЗАПИСИ.ToHashSet(StringComparer.Ordinal);
        bool Есть(string з) => список.Contains(з);

        // ---- 1. записи ----
        string папка = Path.Combine(Пути.Корень, "Дом.Годот", "звуки");
        var файлы = Directory.GetFiles(папка, "*.mp3")
            .Select(f => Path.GetFileNameWithoutExtension(f)).ToHashSet(StringComparer.Ordinal);
        if (список.Count != Слух.ЗАПИСИ.Count)
            плохо.Add("в Слух.ЗАПИСИ запись названа дважды");
        foreach (var нет in список.Except(файлы).OrderBy(x => x, StringComparer.Ordinal))
            плохо.Add($"запись «{нет}» в списке, а файла звуки/{нет}.mp3 нет");
        foreach (var лишний in файлы.Except(список).OrderBy(x => x, StringComparer.Ordinal))
            плохо.Add($"файл звуки/{лишний}.mp3 лежит, а в Слух.ЗАПИСИ его нет");
        string читай = File.ReadAllText(Path.Combine(папка, "ЧИТАЙ.md"));
        foreach (var з in Слух.ЗАПИСИ.Where(з => !читай.Contains($"`{з}.mp3`", StringComparison.Ordinal)))
            плохо.Add($"у записи «{з}» нет строки в звуки/ЧИТАЙ.md");

        // имена в вызовах звука у узлов движка: строкой — из списка;
        // $"приставка_{…}" — есть записи с этой приставкой
        var вызов = new Regex(@"Звуки\.(Взять|Точка|Сыграть)\(|Звук_у\(|[\s=(]Звук\(""|Играть\(_звук|Звук_двери\(|new Отзвук\(");
        var строка = new Regex(@"(?<![$\w])""([а-яё0-9_]+)""");
        var приставка = new Regex(@"\$""([а-яё_]+)\{");
        var играют = new HashSet<string>(StringComparer.Ordinal);
        var приставки = new HashSet<string>(StringComparer.Ordinal);
        int строк_звука = 0;
        foreach (var файл in Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Годот"), "*.cs"))
            foreach (var с in File.ReadLines(файл))
            {
                if (с.TrimStart().StartsWith("//", StringComparison.Ordinal) || !вызов.IsMatch(с))
                    continue;
                строк_звука++;
                foreach (Match м in строка.Matches(с))
                {
                    string имя = м.Groups[1].Value;
                    играют.Add(имя);
                    if (!Есть(имя))
                        плохо.Add($"{Path.GetFileName(файл)}: звук «{имя}» — такой записи нет");
                }
                foreach (Match м in приставка.Matches(с))
                {
                    приставки.Add(м.Groups[1].Value);
                    if (!список.Any(з => з.StartsWith(м.Groups[1].Value, StringComparison.Ordinal)))
                        плохо.Add($"{Path.GetFileName(файл)}: звук «{м.Groups[1].Value}…» — таких записей нет");
                }
            }
        // что играет сам слух: его строки после списка записей
        string слух = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Экран", "Слух.cs"));
        int после = слух.IndexOf("public const int РАЗОМ", StringComparison.Ordinal);
        if (после < 0)
            плохо.Add("Слух.cs: не нашёл, где кончается список записей (РАЗОМ)");
        else
            foreach (Match м in строка.Matches(слух[после..]))
                if (Есть(м.Groups[1].Value))
                    играют.Add(м.Groups[1].Value);
        var молчат = Слух.ЗАПИСИ.Where(з => !играют.Contains(з)
                                            && !приставки.Any(п => з.StartsWith(п, StringComparison.Ordinal)))
                                 .ToList();
        foreach (var з in молчат)
            плохо.Add($"запись «{з}» лежит, но её не играет никто");

        // ---- дом для случаев ----
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var профиль = new ПрофильГероя("Андрей");
        var прогон = new Прогон(Пути.Данные, seed: 5, days: 10,
                                журнал: new Журнал(0, false, TextWriter.Null),
                                жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
        new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, Герой.ID);
        var h = прогон.h;
        h.day = 3;
        var я = h.people[Герой.ID];
        var о = Округа.У(h)!;
        var чужие = h.others(я).Where(p => p.здесь() && p.дети.Count == 0)
                     .OrderBy(p => p.id, StringComparer.Ordinal).ToList();
        var а = чужие[0];
        var б = чужие[1];
        var в = чужие[2];
        var прозвучало = new List<Отзвук>();                   // всё, что дал слух, — сверить со списком
        var без_событий = Array.Empty<Событие>();
        var без_строк = Array.Empty<СтрокаЛенты>();
        var без_ран = Array.Empty<string>();
        Память Слышал(NPC кто, string что, int день) => new() { день = день, вид = Вид.СЛЫШАЛ, кто = кто.id, что = что };
        IReadOnlyList<Отзвук> Новое(IReadOnlyList<Память> память, IReadOnlyList<Событие>? события = null,
                                    IReadOnlyList<СтрокаЛенты>? строки = null, IReadOnlyList<string>? раны = null)
        {
            var r = Слух.Новое(h, я, память, события ?? без_событий, строки ?? без_строк, раны ?? без_ран);
            прозвучало.AddRange(r);
            return r;
        }
        IReadOnlyList<Отзвук> Слышно(params Память[] п) => Новое(п);
        string Записи(IEnumerable<Отзвук> о_) => string.Join(" ", о_.Select(x => x.запись + (x.квартира is int к ? $"@{к}" : "")));
        var f_а = h.flats[h.where(а).apt];
        double дверь_была = f_а.shelter.Взять("дверь", 0.0), листы_были = f_а.shelter.Взять("листы", 0.0);

        // ---- 2. услышанное ----
        var ссора = Слышно(Слышал(а, "ссора", h.day));
        if (ссора.Count != 1 || ссора[0].запись != "ссора" || ссора[0].квартира != h.where(а).apt)
            плохо.Add($"слышал ссору у {а.id} — а звучит «{Записи(ссора)}», надо «ссора» у его двери");
        if (Слышно(Слышал(а, "ссора", h.day - 1)).Count > 0)
            плохо.Add("вчерашняя ссора (ночью, пока спал) звучит утром");
        if (Слышно(Слышал(а, "шаги", h.day)).Count > 0)
            плохо.Add("шаги за стеной звучат — у шагов без места нет звука");
        var много = Слышно(Слышал(а, "ссора", h.day), Слышал(б, "ссора", h.day), Слышал(в, "ссора", h.day),
                           Слышал(а, "готовка", h.day), Слышал(б, "разбор", h.day));
        if (много.Count != Слух.РАЗОМ)
            плохо.Add($"пять разных шумов разом — звучит {много.Count}, а надо не больше {Слух.РАЗОМ}");
        if (Слышно(Слышал(а, "ссора", h.day), Слышал(а, "ссора", h.day)).Count != 1)
            плохо.Add("одна и та же ссора одного соседа звучит дважды");
        о.участок!.Пришёл(я);
        var из_участка = Слышно(Слышал(а, "ссора", h.day));
        о.участок.Ушёл(я);
        if (из_участка.Count > 0)
            плохо.Add("герой в участке — а ссору в подъезде слышно");

        f_а.shelter["дверь"] = 0;
        f_а.shelter["листы"] = 0;
        var в_дерево = Слышно(Слышал(а, "взлом", h.day));
        f_а.shelter["листы"] = 1;
        var в_железо = Слышно(Слышал(а, "взлом", h.day));
        var молоток_железо = Слышно(Слышал(а, "дверь", h.day));
        f_а.shelter["листы"] = 0;
        var молоток_дерево = Слышно(Слышал(а, "дверь", h.day));
        f_а.shelter["дверь"] = 2;
        var в_крепкую = Слышно(Слышал(а, "взлом", h.day));
        f_а.shelter["дверь"] = дверь_была;
        f_а.shelter["листы"] = листы_были;
        if (в_дерево.Count == 0 || !в_дерево.All(x => x.запись.StartsWith("топор_дверь_", StringComparison.Ordinal)))
            плохо.Add($"ломятся в деревянную дверь — звучит «{Записи(в_дерево)}», надо топор по двери");
        if (в_железо.Count == 0 || !в_железо.All(x => x.запись == "удар_по_металлу")
            || в_крепкую.Count == 0 || !в_крепкую.All(x => x.запись == "удар_по_металлу"))
            плохо.Add($"ломятся в железную дверь — звучит «{Записи(в_железо)}» / «{Записи(в_крепкую)}», надо по металлу");
        if (!молоток_железо.All(x => x.запись.StartsWith("молоток_металл_", StringComparison.Ordinal))
            || !молоток_дерево.All(x => x.запись.StartsWith("молоток_дерево_", StringComparison.Ordinal))
            || молоток_железо.Count == 0 || молоток_дерево.Count == 0)
            плохо.Add($"укрепляют дверь: с листами «{Записи(молоток_железо)}», без — «{Записи(молоток_дерево)}»");

        var ствол = а.weapon;
        var выстрелы = new List<string>();
        foreach (var w_ in new[] { Оружие.ПИСТОЛЕТ, Оружие.ДРОБОВИК, Оружие.ВИНТОВКА })
        {
            а.weapon = w_;
            выстрелы.Add(Записи(Слышно(Слышал(а, "выстрел", h.day))));
        }
        а.weapon = ствол;
        string ждали = $"выстрел_пистолет@{h.where(а).apt}|выстрел_дробовик@{h.where(а).apt}|выстрел_винтовка@{h.where(а).apt}";
        if (string.Join("|", выстрелы) != ждали)
            плохо.Add($"выстрел по стволу: «{string.Join(" | ", выстрелы)}», надо «{ждали.Replace("|", " | ")}»");

        int кв_б = h.where(б).apt;
        var налёт = new Событие(h.day, ВидСобытия.НАЛЁТ, кто: а.id, кому: б.id, где: кв_б);
        var дважды = Новое(new[] { Слышал(б, "взлом", h.day) }, new[] { налёт });
        int ударов_взлома = Слышно(Слышал(б, "взлом", h.day)).Count;
        if (дважды.Count != ударов_взлома)
            плохо.Add($"налёт слышен памятью и событием — ударов {дважды.Count}, а надо {ударов_взлома}: дверь бьют дважды");
        var по_событиям = Новое(Array.Empty<Память>(), new[]
        {
            new Событие(h.day, ВидСобытия.ПОЖАР, где: кв_б),
            new Событие(h.day, ВидСобытия.ПЕРЕЕЗД, кто: а.id, где: кв_б),
            new Событие(h.day, ВидСобытия.ИСХОД, кто: а.id, кому: б.id, что: "ограблен", где: кв_б),
            new Событие(h.day - 1, ВидСобытия.ПЕРЕЕЗД, кто: а.id, где: кв_б),
        });
        if (Записи(по_событиям) != $"пожар@{кв_б} мебель@{кв_б} стекло@{кв_б}")
            плохо.Add($"пожар, переезд, прорвались (и вчерашний переезд) — «{Записи(по_событиям)}»");
        var раны = Новое(Array.Empty<Память>(), раны: new[] { "ушиб", "обморожение рук", "огнестрел" });
        if (Записи(раны) != "удар выстрел_пистолет")
            плохо.Add($"раны героя «ушиб, обморожение, огнестрел» — «{Записи(раны)}», надо «удар выстрел_пистолет»");

        // ---- 3. крик ----
        string осада = Regex.Replace(File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Ядро", "Конфликт.Осада.cs")),
                                     @"""\s*\+\s*\$?""", "");
        if (!осада.Contains("\"закричал\")}" + Слух.КРИК, StringComparison.Ordinal))
            плохо.Add($"ядро (Конфликт.Осада) пишет о крике не «…закричал{Слух.КРИК}» — слух его не узнает");
        СтрокаЛенты Кричал(NPC кто, int день)
            => new(день, null, $"{кто.@short} {Util.Vb(кто.sex, "закричал")}{Слух.КРИК}", 2, false);
        var женщина = чужие.FirstOrDefault(Слух.Женщина);
        var мужчина = чужие.FirstOrDefault(p => !Слух.Женщина(p));
        string крики = "";
        if (женщина is null || мужчина is null)
            плохо.Add("в доме нет соседа или соседки — крик по полу не проверен");
        else
        {
            var к = Новое(Array.Empty<Память>(), строки: new[] { Кричал(женщина, h.day), Кричал(мужчина, h.day), Кричал(мужчина, h.day - 1) });
            крики = Записи(к);
            if (к.Count != 2 || !к[0].запись.StartsWith("крик_ж_", StringComparison.Ordinal) || к[0].квартира != h.where(женщина).apt
                || !к[1].запись.StartsWith("крик_м_", StringComparison.Ordinal) || к[1].квартира != h.where(мужчина).apt)
                плохо.Add($"крики соседки, соседа и вчерашний — «{крики}», надо женский и мужской у их дверей, вчерашнего нет");
            о.участок!.Пришёл(я);
            var к_из_участка = Новое(Array.Empty<Память>(), строки: new[] { Кричал(женщина, h.day) });
            о.участок.Ушёл(я);
            if (к_из_участка.Count > 0)
                плохо.Add("герой в участке — а крик на лестнице слышно");
        }
        var свой = Новое(Array.Empty<Память>(), строки: new[] { Кричал(я, h.day) });
        if (свой.Count != 1 || свой[0].квартира is not null)
            плохо.Add($"закричал сам герой — «{Записи(свой)}», надо свой голос без места");

        // ---- 4. дела ----
        IReadOnlyList<Отзвук> Дело(string ключ, bool печь = false)
        {
            var r = Слух.Дело(ключ, печь, 1);
            прозвучало.AddRange(r);
            return r;
        }
        if (!Дело("поесть", true).Any(x => x.запись == "жарка") || Дело("поесть").Any(x => x.запись == "жарка")
            || !Дело("поесть").Any(x => x.запись.StartsWith("жевание_", StringComparison.Ordinal)))
            плохо.Add($"поел: у горящей печки «{Записи(Дело("поесть", true))}», у холодной «{Записи(Дело("поесть"))}»");
        if (!Дело("листы").All(x => x.запись.StartsWith("молоток_металл_", StringComparison.Ordinal)) || Дело("листы").Count == 0)
            плохо.Add($"листы на дверь — «{Записи(Дело("листы"))}», надо молоток по металлу");
        if (Записи(Дело("утепление")).Split(' ') is not ["пила", var мд] || !мд.StartsWith("молоток_дерево_", StringComparison.Ordinal))
            плохо.Add($"утепление — «{Записи(Дело("утепление"))}», надо пила и молоток по дереву");
        if (!Дело("топить").Any(x => x.запись == "воспламенение") || Дело("отдых").Count > 0)
            плохо.Add($"затопить — «{Записи(Дело("топить"))}», отдых — «{Записи(Дело("отдых"))}»");
        foreach (var ключ in Дом.Ядро.Каталог.COST.Ключи)
        {
            Дело(ключ, true);
            Дело(ключ);
        }
        foreach (var ключ in new[] { "дрова", "топить_снег" })
            Дело(ключ);
        var просят = new ВопросИгроку(h.day, я.id, Вопрос.ОТКРЫТЬ_ДВЕРЬ, "",
            new[] { new ВариантИгроку("открыть", 1.0, "открыть"), new ВариантИгроку("через дверь", 0.0, "через дверь") },
            null, null, а.id);
        var открыл = Слух.Ответ(h, я, просят, 0, 0);
        var не_открыл = Слух.Ответ(h, я, просят, 1, 0);
        прозвучало.AddRange(открыл);
        int своя = Слух.Своя_дверь(h, я);
        if (Записи(открыл) != $"дверь_открыть@{своя} дверь_закрыть@{своя}" || не_открыл.Count > 0)
            плохо.Add($"открыл на стук — «{Записи(открыл)}», через дверь — «{Записи(не_открыл)}»");
        var каталог_еды = КаталогЕды.Прочитать(Пути.Данные)
                          ?? throw new InvalidOperationException("нет data/еда.json — еду не проверить");
        foreach (var вид in каталог_еды.виды)
            foreach (bool закрыта in new[] { true, false })
                прозвучало.AddRange(Слух.Съел(вид, закрыта, 1));
        var банка = каталог_еды.виды.First(x => x.род == РодЕды.БАНКА && x.воды <= 0);
        var газировка = каталог_еды.виды.FirstOrDefault(x => x.воды > 0);
        if (Слух.Съел(банка, true, 0).FirstOrDefault()?.запись != "банка" || Слух.Съел(банка, false, 0).Any(x => x.запись == "банка")
            || газировка is not null && Слух.Съел(газировка, false, 0).Any(x => x.запись.StartsWith("жевание_", StringComparison.Ordinal)))
            плохо.Add("съел из кармана: закрытую банку не открыл, открытую открыл снова или газировку жуют");

        // ---- 5. фон ----
        Голосок? Кашляет(NPC кто) => Слух.Фон(h, я).FirstOrDefault(г => г.кто == кто.id);
        string? болел = а.sick;
        if (Кашляет(а) is not null)
            плохо.Add($"здоровый {а.id} кашляет");
        а.sick = "простуда";
        var кашель = Кашляет(а);
        о.участок!.Пришёл(я);
        var кашель_из_участка = Кашляет(а);
        я.sick = "простуда";
        var свой_кашель = Кашляет(я);
        о.участок.Ушёл(я);
        я.sick = null;
        а.sick = болел;
        string пол = Слух.Женщина(а) ? "кашель_ж_" : "кашель_м_";
        if (кашель is null || кашель.квартира != h.where(а).apt || кашель.записи.Count == 0
            || !кашель.записи.All(з => з.StartsWith(пол, StringComparison.Ordinal)))
            плохо.Add($"простуженный {а.id} — кашель {(кашель is null ? "не слышен" : $"«{string.Join(" ", кашель.записи)}» у кв{кашель.квартира}")}, надо «{пол}…» у его двери");
        if (кашель_из_участка is not null)
            плохо.Add("герой в участке — а кашель соседа слышно");
        if (свой_кашель is null || свой_кашель.квартира is not null)
            плохо.Add("герой простужен — своего кашля нет (или он у двери)");
        var мать = h.people.Значения.FirstOrDefault(p => p.здесь() && p.дети.Count > 0 && !ReferenceEquals(p, я));
        string плач = "";
        if (мать is null)
            плохо.Add("в доме нет ни одного ребёнка — плач не проверен");
        else
        {
            var р = мать.дети[0];
            (double сыт, double тепло, string? болен, string? у) = (р.сытость, р.тепло, р.болен, р.у);
            р.сытость = 85; р.тепло = 80; р.болен = null; р.у = null;
            bool сытый = Слух.Фон(h, я).Any(г => г.записи.Contains("плач"));
            р.сытость = 30;
            var голодный = Слух.Фон(h, я).FirstOrDefault(г => г.записи.Contains("плач"));
            (р.сытость, р.тепло, р.болен, р.у) = (сыт, тепло, болен, у);
            плач = голодный is null ? "нет" : $"у кв{голодный.квартира}";
            if (сытый || голодный is null || голодный.квартира != h.where(мать).apt)
                плохо.Add($"ребёнок {мать.id}: сытый плачет — {сытый}, голодный — {плач}, надо только голодный у кв{h.where(мать).apt}");
        }
        foreach (var г in Слух.Фон(h, я))
            прозвучало.AddRange(г.записи.Select(з => new Отзвук(з, г.квартира)));

        // ---- 6. чат ----
        var чат = new[]
        {
            new СтрокаЛенты(h.day, null, $"  [чат] {а.@short}: есть у кого соль?", 1, false, ВидСтроки.ЧАТ),
            new СтрокаЛенты(h.day, null, $"  [чат] {я.@short}: у меня нет", 1, false, ВидСтроки.ЧАТ),
            new СтрокаЛенты(h.day, null, "Сосед постучал.", 1, false),
        };
        if (Слух.Сообщений(я, чат) != 1)
            плохо.Add($"в чате одно чужое и одно своё сообщение — пискнуло {Слух.Сообщений(я, чат)} раз, надо 1");

        // ---- всё, что дал слух, — из списка ----
        foreach (var x in прозвучало.Select(x => x.запись).Distinct(StringComparer.Ordinal).Where(x => !Есть(x)))
            плохо.Add($"слух даёт запись «{x}», которой нет в списке");
        for (int n = 0; n < 12; n++)
            foreach (var x in new[]
                     {
                         Слух.Кашель(true, n), Слух.Кашель(false, n), Слух.Крик(true, n), Слух.Крик(false, n),
                         Слух.Жевание(n), Слух.Глоток(n), Слух.Налить(n), Слух.Резка(n), Слух.Лом(n),
                         Слух.Топор_по_двери(n), Слух.Молоток(true, n), Слух.Молоток(false, n),
                     }.Where(x => !Есть(x)))
                плохо.Add($"вариант «{x}» — такой записи нет");

        w($"  записей {Слух.ЗАПИСИ.Count}, файлов {файлы.Count}; строк звука в узлах {строк_звука}, молчат {молчат.Count}");
        w($"  взлом: дерево «{Записи(в_дерево)}», железо «{Записи(в_железо)}»; выстрелы «{string.Join(" | ", выстрелы)}»");
        w($"  налёт памятью и событием — ударов {дважды.Count}; крики «{крики}»; кашель {(кашель is null ? "нет" : $"у кв{кашель.квартира}")}, плач {плач}");
        return плохо;
    }
