// Проверка порядка и поиска в кармане (ГДД 9: «список с поиском
// и сортировкой (вес, имя, категория, свежесть)»; `Дом.Экран/Инвентарь.cs`).
//
//  1. **Порядок.** По имени; что испортится раньше; по весу (порциями —
//     ими карман и меряет); по роду — банки, хлеб, овощи.
//  2. **Поиск.** По имени и по состоянию, без оглядки на регистр; пусто —
//     все ячейки.
//  3. **Ячейки.** Род и срок у ячейки — от вещей: живые продукты героя.
//  4. **Экран.** Кнопка порядка и поле «найти…» в кармане, сетка — через
//     порядок (скан).

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> ПорядокЕды_(Action<string> w)
    {
        var плохо = new List<string>();
        ЯчейкаЕды Я(string имя, double порций, РодЕды род, double дней, string состояние = "целая банка")
            => new(МестоЕды.ПОЛКА, имя, имя, 1, new[] { 1 }, Свежесть.СВЕЖАЯ, состояние, порций, "",
                   Array.Empty<string>(), имя, "", род, дней);
        var ячейки = new[]
        {
            Я("Тушёнка", 2, РодЕды.БАНКА, 30), Я("Батон", 1, РодЕды.ХЛЕБ, 2),
            Я("Картофель", 3, РодЕды.ОВОЩ, 10), Я("Шпроты", 1.5, РодЕды.БАНКА, 60, "початая банка"),
        };
        string Порядок(ПорядокЕды п, string? найти = null)
            => string.Join(", ", Инвентарь.Упорядочить(ячейки, п, найти).Select(x => x.имя));

        // ---- 1. порядок ----
        var ждём = new (ПорядокЕды п, string что)[]
        {
            (ПорядокЕды.ИМЯ, "Батон, Картофель, Тушёнка, Шпроты"),
            (ПорядокЕды.СВЕЖЕСТЬ, "Батон, Картофель, Тушёнка, Шпроты"),
            (ПорядокЕды.ВЕС, "Картофель, Тушёнка, Шпроты, Батон"),
            (ПорядокЕды.КАТЕГОРИЯ, "Тушёнка, Шпроты, Батон, Картофель"),
        };
        foreach (var (п, что) in ждём)
            if (Порядок(п) != что)
                плохо.Add($"карман: «{Инвентарь.Словом(п)}» — {Порядок(п)}, а надо {что}");
        // свежесть и имя совпали на этом наборе — развести их отдельно
        var другие = new[] { Я("Батон", 1, РодЕды.ХЛЕБ, 9), Я("Шпроты", 1, РодЕды.БАНКА, 1) };
        if (Инвентарь.Упорядочить(другие, ПорядокЕды.СВЕЖЕСТЬ)[0].имя != "Шпроты")
            плохо.Add("карман: «что испортится раньше» — не по сроку");

        // ---- 2. поиск ----
        if (Порядок(ПорядокЕды.ИМЯ, "бат") != "Батон" || Порядок(ПорядокЕды.ИМЯ, "ПОЧАТ") != "Шпроты"
            || Порядок(ПорядокЕды.ИМЯ, "  ") != ждём[0].что)
            плохо.Add($"карман: поиск — «бат» {Порядок(ПорядокЕды.ИМЯ, "бат")}, «ПОЧАТ» {Порядок(ПорядокЕды.ИМЯ, "ПОЧАТ")}");
        // и строки запасов ищутся тем же правилом
        if (!Инвентарь.Найдено("вода", "ВОД") || Инвентарь.Найдено("вода", "хлеб") || !Инвентарь.Найдено("вода", null))
            плохо.Add("карман: строки запасов ищутся не так, как ячейки");

        // ---- 3. ячейки из живых продуктов ----
        string живые_итог = "—";
        var еда = КаталогЕды.Прочитать(Пути.Данные);
        if (еда is not null)
        {
            var ручки = РучкиПетли.Прочитать(Пути.Данные);
            var прогон = new Прогон(Пути.Данные, seed: 5, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, еда: еда).Слушать(прогон, "оксана");
            var п = Продукты.У(прогон.h.people["оксана"])!;
            var батон = еда.виды.First(в => в.род == РодЕды.ХЛЕБ);
            п.Положить(МестоЕды.КАРМАН, new Продукт(9201, батон.id, батон.единиц, 0));
            var хлеб = Инвентарь.Ячейки(п, МестоЕды.КАРМАН, 45).FirstOrDefault(x => x.вид == батон.id);
            if (хлеб is null || хлеб.род != РодЕды.ХЛЕБ || хлеб.дней_до_порчи >= double.MaxValue || хлеб.дней_до_порчи <= 0)
                плохо.Add($"карман: у ячейки хлеба род {хлеб?.род}, срок {хлеб?.дней_до_порчи} — не от вещи");
            живые_итог = хлеб is null ? "—" : $"{хлеб.имя}: {хлеб.род}, испортится через {Текст.G(Текст.Округлить(хлеб.дней_до_порчи, 1))} дн";
        }

        // ---- 4. экран ----
        string ui = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "КарманUI.cs"));
        if (!ui.Contains("Инвентарь.Упорядочить(Инвентарь.Ячейки(продукты, где, Порция()), _порядок, _найти)", StringComparison.Ordinal)
            || !ui.Contains("PlaceholderText = \"найти…\"", StringComparison.Ordinal)
            || ui.Split("Where(р => Инвентарь.Найдено(р, _найти))").Length - 1 < 3)
            плохо.Add("карман: на экране нет порядка или поиска");

        w($"  по весу: {Порядок(ПорядокЕды.ВЕС)}; по роду: {Порядок(ПорядокЕды.КАТЕГОРИЯ)}");
        w($"  живые: {живые_итог}");
        return плохо;
    }
}
