// Проверка героя новой игры и сохранения посреди жизни (задание автора,
// этап 5, пп. 19–20; `Петля/Герой.cs`, `Петля/СохранениеИгры.cs`, `data/герой.json`).
//
//  1. **Герой.** Мужчина с именем игрока — шестнадцатым жильцом в пустой
//     квартире; падежи имени по правилам; замкнутый (общительность — единица),
//     дому почти не известен, ни с кем не знаком. В прогоне без игрока его нет.
//  2. **Продолжить.** Жизнь, прерванная на границе дня и поднятая из
//     сохранения, дальше идёт так же, как непрерывная: дом (канонический
//     снимок), болезнь, знания, карман, ноша — день в день. И пролог
//     сохраняется со своим днём и подозрениями.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> СохранениеИгры_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var профиль = new ПрофильГероя("Андрей");
        var честный = new Скрипт(new Dictionary<Вопрос, string> { [Вопрос.СОВРАТЬ] = "сказать правду" });

        // ---- 1. герой ----
        string герой_итог;
        {
            foreach (var (имя, падежи) in new[]
                     {
                         ("Иван", "Ивана Ивану Ивана Иваном"), ("Андрей", "Андрея Андрею Андрея Андреем"),
                         ("Игорь", "Игоря Игорю Игоря Игорем"), ("Никита", "Никиты Никите Никиту Никитой"),
                         ("Лука", "Луки Луке Луку Лукой"), ("Илья", "Ильи Илье Илью Ильёй"),
                         ("Саша", "Саши Саше Сашу Сашей"), ("Олег", "Олега Олегу Олега Олегом"),
                     })
            {
                var (р, д, в, т) = Герой.Падежи(имя);
                if ($"{р} {д} {в} {т}" != падежи)
                    плохо.Add($"«{имя}» склоняется как «{р} {д} {в} {т}», а надо «{падежи}»");
            }
            foreach (var (ввод, надо) in new (string, string?)[]
                     {
                         ("  иван ", "Иван"), ("ИВАН", "Иван"), ("анна-мария", "Анна-Мария"), ("Ёжик", "Ёжик"),
                         ("John", null), ("", null), ("И", null), ("Иван1", null), ("Иван Петров", null),
                         ("-Иван", null), ("Константинопольский", null),
                     })
            {
                string? вышло = Герой.Имя(ввод, out var почему);
                if (вышло != надо || (вышло is null) != (почему is not null))
                    плохо.Add($"имя «{ввод}» стало «{вышло ?? "—"}» ({почему ?? "годно"}), а надо «{надо ?? "—"}»");
            }
            var ш = Герой.Шаблон(Пути.Данные);
            if (ш.квартира != 11 || ш.этаж != 3 || ш.роль.Length == 0)
                плохо.Add($"шаблон героя не тот: кв.{ш.квартира}, этаж {ш.этаж}");
            {
                string путь_игры = Path.Combine(Path.GetTempPath(), $"дом_игра_{Environment.ProcessId}.json");
                var игра = ИграГероя.Новая(профиль, 123456789012);
                игра.Записать(путь_игры);
                var снова = ИграГероя.Прочитать(путь_игры);
                File.Delete(путь_игры);
                if (снова != игра)
                    плохо.Add($"игра из файла другая: {снова}");
            }
            var прогон = new Прогон(Пути.Данные, seed: 3, days: 3,
                                    журнал: new Журнал(0, false, TextWriter.Null),
                                    жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            var h = прогон.h;
            if (h.get(Герой.ID) is not NPC я)
            {
                плохо.Add("героя новой игры в доме нет");
                return плохо;
            }
            if (h.people.Ключи.Count() != 16 || я.sex != "м" || я.@short != "Андрей" || я.form("gen") != "Андрея")
                плохо.Add($"герой не тот: жильцов {h.people.Ключи.Count()}, пол {я.sex}, имя {я.@short}, род. {я.form("gen")}");
            if (я.t01("общительность") > 0.15)
                плохо.Add($"герой не замкнутый: общительность {Текст.G(я.t01("общительность"))}");
            foreach (var с in h.others(я))
            {
                if (Math.Abs(с.trust.Взять(я.id, 3.0) - 3.0) > 1e-9 || Math.Abs(я.trust.Взять(с.id, 3.0) - 3.0) > 1e-9)
                {
                    плохо.Add($"герой уже знаком с {с.id}: доверие {Текст.G(с.trust.Взять(я.id, 3.0))} / {Текст.G(я.trust.Взять(с.id, 3.0))}");
                    break;
                }
            }
            var без = new Прогон(Пути.Данные, seed: 3, days: 3, журнал: new Журнал(0, false, TextWriter.Null));
            if (без.h.people.Ключи.Count() != 15 || без.h.get(Герой.ID) is not null)
                плохо.Add("герой новой игры появился и в прогоне без игрока");
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, Герой.ID);
            я.решающий = честный;
            прогон.run();
            герой_итог = $"«{я.name}», кв.{я.apt} ({я.floor} этаж), {я.sex}; жильцов {h.people.Ключи.Count()}; "
                         + $"три дня прожил{(я.alive ? "" : " — и умер")}";
        }

        // ---- 2. продолжить ----
        string продолжить_итог;
        {
            const int ДНЕЙ = 6, ПРЕРВАТЬ = 3;
            (Прогон прогон, Дом.Ядро.Петля петля, Магазин магазин) Жизнь()
            {
                var прогон = new Прогон(Пути.Данные, seed: 11, days: ДНЕЙ,
                                        журнал: new Журнал(0, false, TextWriter.Null),
                                        жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
                var петля = new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л);
                петля.Слушать(прогон, Герой.ID);
                var я = прогон.h.people[Герой.ID];
                я.решающий = честный;
                // что есть только у игрока — чтобы было что терять
                я.карман!.Положить_найденное("еда", 2);
                я.снаряжение!.Подобрать("монтировка", каталог);
                var ноша = Словари.Числа();
                ноша["вода"] = 2;
                (я.ноша ??= new Ноша()).Положить(Тара.СУМКА, ноша, ручки);
                var о = Округа.У(прогон.h)!;
                о.Узнал("вектор_есть");
                // болезнь в доме с первого дня — чтобы она шла через границу сохранения
                foreach (var с in прогон.h.others(я).Take(4))
                    о.заражение.Задеть(с.id, 0);
                // и купленная вещь — склад магазина тоже едет в сохранении
                var м = Магазин.Прочитать(Пути.Данные, каталог);
                var т = м.товары.First(т => т.предмет is not null);
                if (!м.Купить(прогон.h, я, т, ручки, каталог).взято)
                    плохо.Add($"герой не купил «{т.id}» — склад магазина не проверен");
                return (прогон, петля, м);
            }

            var (подряд, петля_а, магазин_а) = Жизнь();
            подряд.run();

            var (прерванный, петля_б, магазин_б) = Жизнь();
            System.Text.Json.Nodes.JsonObject? сейв = null;
            // сохраниться на границе дня — после всех наблюдателей петли, как в игре
            прерванный.h.hooks.on_day.Add(дом =>
            {
                if (дом.day == ПРЕРВАТЬ)
                    сейв = Дом.Ядро.СохранениеИгры.Сложить(профиль, Герой.ID, прерванный, петля_б, магазин_б, null);
            });
            прерванный.run();
            if (сейв is null)
            {
                плохо.Add("сохранение на границе дня не сложилось");
                return плохо;
            }
            // через файл — как в игре
            string путь = Path.Combine(Path.GetTempPath(), $"дом_сохранение_{Environment.ProcessId}.json");
            Дом.Ядро.СохранениеИгры.Записать(сейв, путь);
            var прочитано = Дом.Ядро.СохранениеИгры.Прочитать(путь);
            File.Delete(путь);
            var з = Дом.Ядро.СохранениеИгры.Заголовок(прочитано);
            if (з.герой?.имя != "Андрей" || з.день != ПРЕРВАТЬ || з.зерно != 11)
                плохо.Add($"заголовок сохранения не тот: {з}");

            var продолженный = Дом.Ядро.СохранениеИгры.Прогон_из(прочитано, Пути.Данные, new Журнал(0, false, TextWriter.Null));
            var петля_в = new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л);
            петля_в.Слушать(продолженный, Герой.ID);
            var магазин_в = Магазин.Прочитать(Пути.Данные, каталог);
            var пролог = Дом.Ядро.СохранениеИгры.Разложить(прочитано, продолженный, петля_в, магазин_в);
            продолженный.h.people[Герой.ID].решающий = честный;
            if (пролог is not null)
                плохо.Add("сохранились в метель — а поднялся пролог");
            продолженный.Дальше();

            string а = Снимок.Текстом(Снимок.Собранный(подряд.h));
            string б = Снимок.Текстом(Снимок.Собранный(продолженный.h));
            if (а != б)
                плохо.Add("продолженная из сохранения жизнь разошлась с непрерывной: дом к шестому дню другой");
            string Игрок(Прогон п, Дом.Ядро.Петля пт, Магазин м)
            {
                var я = п.h.people[Герой.ID];
                return $"{Округа.У(п.h)!.Сложить().ToJsonString()} | {я.карман!.Сложить().ToJsonString()} | "
                       + $"{я.ноша?.Сложить().ToJsonString()} | {я.снаряжение!.Сложить().ToJsonString()} | "
                       + $"{м.Сложить().ToJsonString()} | {пт.Сложить_жизнь().ToJsonString()}";
            }
            if (Игрок(подряд, петля_а, магазин_а) != Игрок(продолженный, петля_в, магазин_в))
                плохо.Add("у игрока после продолжения другое: знания, болезнь, карман, ноша, снаряжение, "
                          + "склад магазина или дневник петли");
            var я_п = подряд.h.people[Герой.ID];
            var болезни = Округа.У(подряд.h)!.заражение.болезни.Values;
            int болело_на_сохранении = (прочитано["округа"]!["заражение"]!["болезни"]!.AsObject()).Count;
            if (болело_на_сохранении == 0)
                плохо.Add("болезнь не дошла до сохранения — через границу нечего проверять");
            продолжить_итог = $"прервана на {ПРЕРВАТЬ}-м дне, дожила до {продолженный.h.day}-го как непрерывная; "
                              + $"болезнь на сохранении у {болело_на_сохранении}, к концу умерло от неё "
                              + $"{болезни.Count(б => б.стадия == Стадия.МЁРТВ)}; "
                              + $"в кармане еды {Текст.G(я_п.карман!.Сколько("еда"))}";

            // до метели: дом ещё не пошёл, календаря нет — пролог в сохранении,
            // а метель потом начинается с первого дня, как у непрерывной
            {
                var (до, петля_г, магазин_г) = Жизнь();
                var пролог_г = new Пролог(2);
                var о_до = Дом.Ядро.СохранениеИгры.Сложить(профиль, Герой.ID, до, петля_г, магазин_г, пролог_г);
                var после = Дом.Ядро.СохранениеИгры.Прогон_из(о_до, Пути.Данные, new Журнал(0, false, TextWriter.Null));
                var петля_д = new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л);
                петля_д.Слушать(после, Герой.ID);
                var пролог_д = Дом.Ядро.СохранениеИгры.Разложить(о_до, после, петля_д, Магазин.Прочитать(Пути.Данные, каталог));
                после.h.people[Герой.ID].решающий = честный;
                if (пролог_д is null || пролог_д.день != пролог_г.день)
                    плохо.Add($"сохранение до метели подняло не тот пролог: день {пролог_д?.день.ToString() ?? "—"}");
                if (Дом.Ядро.СохранениеИгры.Заголовок(о_до) is not { пролог: true, день: 0 })
                    плохо.Add("заголовок сохранения до метели не говорит «пролог»");
                до.run();
                после.run();
                if (Снимок.Текстом(Снимок.Собранный(до.h)) != Снимок.Текстом(Снимок.Собранный(после.h)))
                    плохо.Add("метель после сохранения в прологе разошлась с непрерывной");
            }

            // пролог — своим днём и подозрениями
            var п0 = new Пролог(2);
            п0.Ночь();
            п0.Предупредил("тамара", 0.5);
            var п1 = Пролог.Разложить(п0.Сложить());
            if (п1.день != п0.день || Math.Abs(п1.Подозрение("тамара") - 0.5) > 1e-9 || !п1.Предупреждён("тамара"))
                плохо.Add("пролог из сохранения поднялся другим");
        }

        w($"  герой: {герой_итог}");
        w($"  продолжить: {продолжить_итог}");
        return плохо;
    }
}
