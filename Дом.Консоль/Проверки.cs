                    p.panic = 80.0;
                    p.satiety = 6.0;
                }
            if (string.Equals(вид, "богатый", StringComparison.Ordinal))
                ОбстановкаХода(h);
            var ходы = new JsonArray();
            // каждому — до шести ходов подряд, пока есть часы. Это и есть день
            // без утра и вечера: их приносит движок, он приедет следующим
            for (int круг = 0; круг < 6; круг++)
                foreach (var p in h.people.Значения.ToList())
                {
                    if (!p.здесь() || p.time_left <= 0.1)
                        continue;
                    bool сходил = Действия.choose_and_do(h, p);
                    ходы.Add(new JsonArray(p.id, сходил ? 1 : 0));
                }
            // что сегодня делали, уже лежит в снимке (`дом.сутки.сделано`);
            // здесь это же собирается для отчёта проверки
            foreach (var (пара, _) in h.сутки.сделано)
                сделано.Add(пара.Item2);
            сцены[имя] = Дом.Ядро.Снимок.Собранный(h);
            сцены[имя]!["ходы"] = ходы;
            сцены[имя]!["лента"] = Снимок.Округлить(h.rng.Random());
        }

        // ---- и те исполнители, до которых сбор не доводит ----
        //
        // Девятнадцать из сорока восьми: собрание, до которого дом не дозрел,
        // людоедство, до которого не дошло, стройка, которая уже стоит.
        // Их зовут прямо через `execute` — это тот же путь, что у выбранного
        // действия, только выбор сделан рукой, а не мягким жребием
        {
            var h = ДомКонфликта(25);
            ОбстановкаХода(h);
            var все = h.people.Значения;
            foreach (var p in все)
            {
                p.shelter["буржуйка"] = 0;
                p.shelter["утепление"] = 0;
                p.shelter["дверь"] = 0;
                p.stock["мясо"] = 3.0;
                p.time_left = 16.0;
            }
            var прямо = new JsonArray();
            var порядок = new (string ключ, int кто, int цель)[]
            {
                ("поесть_мясо", 0, -1), ("банкомат", 1, -1), ("вытяжка", 2, -1),
                ("буржуйка", 3, -1), ("генератор_собрать", 0, -1), ("генератор", 0, -1),
                ("звукоизоляция", 0, -1), ("стены", 4, -1), ("разбор", 5, -1),
                ("тело", 6, -1), ("вынести", 7, -1), ("проведать", 8, 12),
                ("подкараулить", 9, 10), ("лестница", 10, -1), ("шепнуть", 11, 13),
                ("подбросить", 13, 14), ("кража_днём", 14, 9), ("выгнать", 0, 1),
                ("собрание", 2, -1),
            };
            foreach (var (ключ, кто, цель) in порядок)
            {
                var p = все[кто];
                object? t2 = цель >= 0 ? все[цель] : null;
                var исход = Действия.execute(h, p, ключ, t2);
                прямо.Add(new JsonArray(ключ, p.id, исход.ToString()));
                // считается сделанное, а не попытка: исполнитель, сказавший
                // «не состоялось», проверен только до своего первого `return`
                if (исход == Исход.СДЕЛАНО)
                    сделано.Add(ключ);
                else
                    сорвалось.Add(ключ);
            }
            сцены["исполнители"] = Дом.Ядро.Снимок.Собранный(h);
            сцены["исполнители"]!["прямо"] = прямо;
            сцены["исполнители"]!["лента"] = Снимок.Округлить(h.rng.Random());
        }

        var плохо = new List<string>();
        using var мой = JsonDocument.Parse(сцены.ToJsonString());
        Сравнение.Одинаково(ждём.RootElement, мой.RootElement, "ход", плохо);
        if (плохо.Count > 0)
            foreach (var x in плохо)
                w("  " + x);
        else
        {
            var виды = сделано.Distinct(StringComparer.Ordinal)
                .OrderBy(k => k, StringComparer.Ordinal).ToList();
            w($"  ход дня совпадает с прототипом: пять сцен, {сделано.Count} ходов, "
              + $"{виды.Count} разных действий из {Дом.Ядро.Каталог.COST.Count}");
            w("    сделали: " + string.Join(", ", виды));
            var мимо = сорвалось.Distinct(StringComparer.Ordinal)
                .Where(k => !виды.Contains(k, StringComparer.Ordinal))
                .OrderBy(k => k, StringComparer.Ordinal).ToList();
            if (мимо.Count > 0)
                w("    сорвалось на пороге: " + string.Join(", ", мимо));
        }
        return плохо;
    }

