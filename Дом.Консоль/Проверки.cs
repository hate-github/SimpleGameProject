    /// <summary>
    /// Девять концовок и слово пророка (ГДД 22, 11).
    ///
    /// Обычная метель даёт одну концовку из девяти — «Последние», потому
    /// что норма выживаемости две с половиной из пятнадцати. Восемь
    /// остальных на прогоне не случатся ни разу, и проверять их можно
    /// только поставив дом руками: так же, как проверяются инварианты
    /// и тяжёлые вклады в рассудок.
    ///
    /// Проверяется не «работает», а **что каждое условие даёт свою
    /// концовку и не даёт чужую**: порядок разбора здесь и есть
    /// содержание. Дом, который герой вырезал сам, не должен отчитаться
    /// «домом, который выстоял».
    ///
    /// Слово: до этого этапа принималось любое непустое. Теперь оно одно,
    /// лежит в `data/пророк.json` и **находится только на вылазке** —
    /// проверка идёт туда и убеждается, что до похода герой его не знает,
    /// а после знает.
    /// </summary>
    public static List<string> Концовки_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var пророк = Пророк.Прочитать(Пути.Данные);
        const string КТО = "оксана";

        // ---- каждая концовка из своего условия ----
        House Дом_(Action<House, NPC> поставить)
        {
            var прогон = new Прогон(Пути.Данные, seed: 5, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            поставить(прогон.h, прогон.h.people[КТО]);
            return прогон.h;
        }

        void Убить_всех_кроме(House h, params string[] кого)
        {
            foreach (var p in h.people.Значения)
                if (!кого.Contains(p.id, StringComparer.Ordinal))
                {
                    p.alive = false;
                    p.cause = "холод";
                    p.died_day = 1;
                }
        }

        var случаи = new List<(Концовка ждём, string имя, Action<House, NPC> как)>
        {
            (Концовка.ВСЕ_ЖИВЫ, "все живы", (h, я) => { }),
            (Концовка.СМЕРТЬ, "герой погиб, дом жив",
                (h, я) => { я.alive = false; я.cause = "голод"; я.died_day = 9; }),
            (Концовка.ДОМ_ЗАМЁРЗ, "не дожил никто",
                (h, я) => Убить_всех_кроме(h)),
            (Концовка.ОДИНОЧКА, "дом опустел, а он остался",
                (h, я) => Убить_всех_кроме(h, КТО)),
            (Концовка.ПОСЛЕДНИЕ, "остались втроём",
                (h, я) => Убить_всех_кроме(h, КТО,
                    h.others(я).First().id, h.others(я).Skip(1).First().id)),
            (Концовка.ТЁМНАЯ, "дожил, перебив дом", (h, я) =>
            {
                for (int i = 0; i < (int)ручки["тёмная_убийств"]; i++)
                    h.события.Add(new Событие(1, ВидСобытия.УБИЙСТВО, кто: я.id,
                                              кому: "игорь", что: "убит в драке"));
                Убить_всех_кроме(h, КТО, h.others(я).First().id);
            }),
        };

        var видели = new HashSet<Концовка>();
        foreach (var (ждём, имя, как) in случаи)
        {
            var h = Дом_(как);
            var р = Концовки.Какая(h, КТО, new Наследие(), ручки);
            видели.Add(р.какая);
            if (р.какая != ждём)
                плохо.Add($"«{имя}» дало {р.какая}, а должно {ждём}");
        }

        // «Дом выстоял»: дожило не меньше доли — берём ровно порог
        {
            var h = Дом_((h_, я) =>
            {
                int всего = h_.people.Ключи.Count();
                int оставить = (int)Math.Ceiling(всего * ручки["выстоял_доля"]);
                var кого = h_.people.Значения.Select(p => p.id)
                    .OrderBy(x => x, StringComparer.Ordinal)
                    .Where(id => !string.Equals(id, КТО, StringComparison.Ordinal))
                    .Take(оставить - 1).Append(КТО).ToArray();
                Убить_всех_кроме(h_, кого);
            });
            var р = Концовки.Какая(h, КТО, new Наследие(), ручки);
            видели.Add(р.какая);
            if (р.какая != Концовка.ДОМ_ВЫСТОЯЛ)
                плохо.Add($"«ровно порог выстоявших» дало {р.какая}, "
                          + $"а должно {Концовка.ДОМ_ВЫСТОЯЛ}");
        }

        // рассудок раньше всего: он обрывает петлю, а не жизнь
        {
            var h = Дом_((h_, я) => { });
            var невозврат = new Наследие { рассудок = ручки["порог_невозврата"] };
            var р1 = Концовки.Какая(h, КТО, невозврат, ручки);
            видели.Add(р1.какая);
            if (р1.какая != Концовка.ПЕРЕСТАЛ_ВОЗВРАЩАТЬСЯ)
                плохо.Add($"на точке невозврата дало {р1.какая}");
            невозврат.нирвана = true;
            var р2 = Концовки.Какая(h, КТО, невозврат, ручки);
            видели.Add(р2.какая);
            if (р2.какая != Концовка.НИРВАНА)
                плохо.Add($"в нирване дало {р2.какая}");
        }

        foreach (var к in Enum.GetValues<Концовка>())
            if (!видели.Contains(к))
                плохо.Add($"концовка {к} недостижима ни одним случаем");

        // ---- слово: одно, и находится только сходив ----
        {
            if (пророк.места.Count == 0)
                плохо.Add("у пророка нет ни одной надписи");
            foreach (var м in пророк.места)
                if (!Улица.МЕСТА.Any(x => string.Equals(x.имя, м,
                                                        StringComparison.Ordinal)))
                    плохо.Add($"надпись висит в несуществующем месте: {м}");

            if (!пророк.Сошлось(пророк.слово.ToUpperInvariant()))
                плохо.Add("слово не узнаётся, если набрать его заглавными");
            if (!пророк.Сошлось("  " + пророк.слово + " "))
                плохо.Add("слово не узнаётся с пробелами по краям");
            if (пророк.Сошлось(""))
                плохо.Add("пустая строка принимается за слово");
            if (пророк.Сошлось("не то слово"))
                плохо.Add("за слово принимается что попало");

            var наследие = new Наследие();
            var петля = new Дом.Ядро.Петля(наследие, ручки, пророк);
            var прогон = new Прогон(Пути.Данные, seed: 1, days: 6,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            петля.Слушать(прогон, КТО);
            if (наследие.знает_слово)
                плохо.Add("слово известно ещё до первого дня");
            прогон.run();
            петля.Закрыть(прогон, КТО);
            найдено = наследие.записи.Count(з => з.вид == ВидЗаписи.НАДПИСЬ);
            if (!наследие.знает_слово)
                плохо.Add("за шесть дней вылазок ни одной надписи не нашлось — "
                          + "проверять нечего");
        }

        if (плохо.Count > 0)
            foreach (var x in плохо.Take(6))
                w("  " + x);
        else
        {
            w($"  все {Enum.GetValues<Концовка>().Length} концовок достижимы "
              + "и каждая — из своего условия");
            w($"    слово пророка одно, висит в {пророк.места.Count} местах "
              + $"из {Улица.МЕСТА.Count}; за шесть дней герой прочёл {найдено} "
              + "и теперь его знает");
        }
        return плохо;
    }

    private static int найдено;

    /// <summary>
    /// Подача (ГДД 23): что видно и что слышно.
    ///
    /// Подача — не украшение поверх симуляции, а её чтение, и потому
    /// проверяется как всё остальное: числом. Ни ветра, ни красных краёв
    /// здесь никто не задаёт вручную — они выводятся из погоды и тела,
    /// и значит их можно поставить и посмотреть, что вышло.
    ///
    /// Отдельно сверяется то, ради чего эта проверка и заведена:
    /// **экран без полосок** (ГДД 23). Состояние читается телом —
    /// «сосёт под ложечкой», а не «сыт 34», — и у здорового человека
    /// не читается вовсе.
    /// </summary>
    public static List<string> Подача_(Action<string> w)
    {
        var плохо = new List<string>();
        const string КТО = "оксана";

        House Дом_(Action<House, NPC> поставить)
        {
            var прогон = new Прогон(Пути.Данные, seed: 5, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            поставить(прогон.h, прогон.h.people[КТО]);
            return прогон.h;
        }

        // ---- красные края: от худшей нужды, а не от средней ----
        {
            var h = Дом_((h_, я) =>
            {
                я.satiety = 100; я.hydration = 100; я.warmth = 100; я.health = 100;
                я.rest = 100; я.panic = 0;
            });
            var цел = Дом.Экран.Подача.Видно(h, h.people[КТО]);
            if (цел.краснота != 0.0)
                плохо.Add($"у целого и сытого края краснеют на {цел.краснота}");
            if (Дом.Экран.Подача.Телом(h.people[КТО]).Count != 0)
                плохо.Add("у целого и сытого тело о чём-то говорит");

            var г = Дом_((h_, я) =>
            {
                я.satiety = 5; я.hydration = 100; я.warmth = 100; я.health = 100;
            });
            var голод = Дом.Экран.Подача.Видно(г, г.people[КТО]);
            if (голод.краснота <= 0.5)
                плохо.Add($"умирающий от голода: краснота {Текст.Ф(голод.краснота, 2)}");

            // одной беды довольно: сытый, но замерзающий — та же краснота
            var х = Дом_((h_, я) =>
            {
                я.satiety = 100; я.hydration = 100; я.warmth = 5; я.health = 100;
            });
            var холод = Дом.Экран.Подача.Видно(х, х.people[КТО]);
            if (Math.Abs(холод.краснота - голод.краснота) > 1e-9)
                плохо.Add("краснота считается не от худшей нужды: голод и холод "
                          + "при одинаковой шкале дали разное");
            краснота = голод.краснота;
        }

        // ---- погода: буран — стена, затишье — просвет ----
        {
            double Ветер(Режим р)
            {
                var h = Дом_((h_, я) => h_.режим = р);
                return Дом.Экран.Подача.Слышно(h, h.people[КТО],
                        System.Array.Empty<Дом.Экран.СтрокаЛенты>())
                    .First(г => г.что == Дом.Экран.Звук.ВЕТЕР).громкость;
            }
            double буран = Ветер(Режим.БУРАН);
            double метель = Ветер(Режим.МЕТЕЛЬ);
            double затишье = Ветер(Режим.ЗАТИШЬЕ);
            if (!(буран > метель && метель > затишье))
                плохо.Add($"ветер не по погоде: буран {Текст.Ф(буран, 2)}, "
                          + $"метель {Текст.Ф(метель, 2)}, "
                          + $"затишье {Текст.Ф(затишье, 2)}");
            ветер = $"{Текст.Ф(буран, 2)}/{Текст.Ф(метель, 2)}/{Текст.Ф(затишье, 2)}";

            var б = Дом_((h_, я) => h_.режим = Режим.БУРАН);
            var з = Дом_((h_, я) => h_.режим = Режим.ЗАТИШЬЕ);
            if (Дом.Экран.Подача.Видно(б, б.people[КТО]).снег
                <= Дом.Экран.Подача.Видно(з, з.people[КТО]).снег)
                плохо.Add("в буран снега не больше, чем в затишье");
        }

        // ---- гул: только если у соседа генератор и он не заглушен ----
        {
            int Гулов(Action<House, NPC> поставить)
            {
                var h = Дом_(поставить);
                return Дом.Экран.Подача.Слышно(h, h.people[КТО],
                        System.Array.Empty<Дом.Экран.СтрокаЛенты>())
                    .Count(г => г.что == Дом.Экран.Звук.ГУЛ_ГЕНЕРАТОРА);
            }
            // Считается ОТ исходного дома, а не от нуля: один генератор
            // в доме стоит с самого начала (кв14 по данным), и проверка,
            // ждавшая тишины, краснела на пустом месте — виновата была
            // она, а не гул
            int было_ = Гулов((h, я) => { });
            if (было_ == 0)
                плохо.Add("в доме нет ни одного генератора — проверять нечего");
            if (Гулов((h, я) => h.others(я).First().shelter["генератор"] = 1)
                != было_ + 1)
                плохо.Add("сосед завёл генератор, а гула не прибавилось");
            if (Гулов((h, я) =>
                {
                    foreach (var о in h.people.Значения)
                        о.shelter["звукоизоляция"] = 1;
                }) != 0)
                плохо.Add("весь дом заглушился, а гул остался");
            if (Гулов((h, я) =>
                {
                    foreach (var о in h.people.Значения)
                        if (о.shelter.Взять("генератор", 0.0) != 0.0)
                            о.alive = false;
                }) != 0)
                плохо.Add("генератор гудит у мёртвого");
            гулов = было_;

            // ---- гул принадлежит квартире, а не человеку ----
            IReadOnlyList<Дом.Экран.Голос> Голоса(Action<House, NPC> поставить)
            {
                var прогон = new Прогон(Пути.Данные, seed: 5, days: 1,
                                        журнал: new Журнал(0, false, TextWriter.Null));
                поставить(прогон.h, прогон.h.people[КТО]);
                return Дом.Экран.Подача.Слышно(
                    прогон.h, прогон.h.people[КТО],
                    System.Array.Empty<Дом.Экран.СтрокаЛенты>());
            }

            // у ветра адреса нет, у гула — есть
            var все = Голоса((h, я) => { });
            if (все.Any(г => г.что == Дом.Экран.Звук.ВЕТЕР && г.квартира is not null))
                плохо.Add("у ветра завёлся адрес — он идёт отовсюду");
            if (все.Any(г => г.что == Дом.Экран.Звук.ГУЛ_ГЕНЕРАТОРА
                             && г.квартира is null))
                плохо.Add("гул без адреса — его некуда поставить");
            // Дальше всё меряется от квартиры, из которой идёт гул. Если
            // адреса нет, мерить не по чему — и надо **сказать это и уйти**,
            // а не падать: упавшая проверка не краснеет, она молчит,
            // и порча, уронившая её, выглядит пойманной, хотя не поймана.
            var первый = все.FirstOrDefault(
                г => г.что == Дом.Экран.Звук.ГУЛ_ГЕНЕРАТОРА);
            гул_кв = первый?.квартира ?? 0;
            if (гул_кв > 0)
            {

            // Двое под одной крышей — один гул, а не два. Генератор стоит
            // в стенах (`NPC.shelter` — это `where(npc).shelter`), и счёт
            // по людям удваивал его каждый раз, когда кто-то переезжал.
            int вдвоём = Голоса((h, я) =>
            {
                var хозяин = h.people.Значения.First(о => о.apt == гул_кв);
                var гость = h.others(хозяин).First(о => о.здесь() && о.id != КТО);
                гость.living_with = хозяин.id;
            }).Count(г => г.что == Дом.Экран.Звук.ГУЛ_ГЕНЕРАТОРА);
            if (вдвоём != было_)
                плохо.Add($"к хозяину генератора переехал сосед, и гулов стало "
                          + $"{вдвоём} вместо {было_}");

            // Переехавший гудит из квартиры хозяина, а не из своей пустой
            var от_гостя = Голоса((h, я) =>
            {
                var хозяин = h.people.Значения.First(о => о.apt == гул_кв);
                var гость = h.others(хозяин).First(о => о.здесь() && о.id != КТО);
                гость.living_with = хозяин.id;
                гость.shelter["звукоизоляция"] = 0;
            }).Where(г => г.что == Дом.Экран.Звук.ГУЛ_ГЕНЕРАТОРА)
              .Select(г => г.квартира).ToList();
            if (от_гостя.Any(кв => кв != гул_кв))
                плохо.Add("гул идёт из квартиры, в которой генератора нет");

            // Слушатель тоже слышит оттуда, где он сам, а не где прописан
            double Слышу(Action<House, NPC> поставить)
                => Голоса(поставить)
                    .Where(г => г.что == Дом.Экран.Звук.ГУЛ_ГЕНЕРАТОРА)
                    .Select(г => г.громкость).DefaultIfEmpty(0).Max();
            double дома = Слышу((h, я) => { });
            double в_гостях = Слышу((h, я) =>
            {
                var хозяин = h.people.Значения.First(о => о.apt == гул_кв);
                я.living_with = хозяин.id;
            });
            if (в_гостях <= дома)
                плохо.Add($"переехал к хозяину генератора, а гул не громче: "
                          + $"{Текст.Ф(в_гостях, 2)} против {Текст.Ф(дома, 2)}");
            гул_ближе = $"{Текст.Ф(дома, 2)}→{Текст.Ф(в_гостях, 2)}";
            }
        }

        // ---- экран без полосок: тело говорит словами ----
        {
            var h = Дом_((h_, я) =>
            {
                я.satiety = 10; я.hydration = 30; я.warmth = 15; я.rest = 25;
                я.health = 55; я.panic = 80;
            });
            var телом = Дом.Экран.Подача.Телом(h.people[КТО]);
            if (телом.Count < 5)
                плохо.Add($"у изведённого человека тело сказало {телом.Count} слов");
            if (телом.Any(с => с.Any(char.IsDigit)))
                плохо.Add("тело говорит числами: «"
                          + телом.First(с => с.Any(char.IsDigit)) + "»");
            словами = телом.Count;
            пример = телом.Count > 0 ? телом[0] : "";
        }

        // ---- адрес варианта: к какой двери он ведёт (игра от первого лица) ----
        {
            var h = Дом_((h_, я) => { });
            var я_ = h.people[КТО];
            var сосед = h.others(я_).First(о => о.apt != я_.apt);
            // кладовка нарочно у другой квартиры: у первой попавшейся
            // адрес совпал с соседским, и проверка порядка сравнивала
            // список сам с собой
            // только погреб: гараж за домом, и адреса в подъезде у него нет
            var кладовка = h.кладовые.Значения.First(
                к => к.apt != сосед.apt && к.вид == ВидКладовой.ПОГРЕБ);

            int? Куда(object? цель)
                => Дом.Экран.Подача.Дверь(h, new ВариантИгроку(("ключ", цель), 1.0, ""));

            if (Куда(сосед) != сосед.apt)
                плохо.Add($"вариант к соседу ведёт не к его двери: "
                          + $"{Куда(сосед)} вместо {сосед.apt}");
            // Кладовка адреса в подъезде не имеет: погреба и гаражи стоят
            // во дворе, и ходят к ним туда. Пока во двор нельзя было выйти,
            // «в погреб кв.6 ходят через кв.6» было правдой; теперь нет
            if (Куда(кладовка) is not null)
                плохо.Add($"кладовка {кладовка.id} ведёт к двери "
                          + $"{Куда(кладовка)}, а стоит она в подвале");
            // пара строится с `object?` вторым — как в движке. Иначе это
            // пара другого типа, и образец `в.цель is Кладовая` её не берёт;
            // ровно эта ловушка уже ловилась ниже, на номерах к двери
            if (Дом.Экран.Подача.Кладовка(
                    new ВариантИгроку(("ключ", (object?)кладовка), 1.0, ""))
                != кладовка.id)
                плохо.Add($"кладовка {кладовка.id} не адресуется сама к себе");
            foreach (var (что, чем) in new (object?, string)[]
                     { (сосед, "сосед"), (h.flats[я_.apt], "квартира"),
                       (null, "пустая цель") })
                if (Дом.Экран.Подача.Кладовка(
                        new ВариантИгроку(("ключ", (object?)что), 1.0, "")) is not null)
                    плохо.Add($"к кладовой ведёт то, что ей не является: {чем}");
            if (Куда(h.flats[я_.apt]) != я_.apt)
                плохо.Add("квартира как цель ведёт не к своей двери");
            if (Куда(null) is not null || Куда("магазин") is not null)
                плохо.Add("у вылазки и у пустой цели нашлась дверь в подъезде");

            // Переехавший числится у той двери, за которой его ищут. Это
            // та самая ловушка, что уже ловилась на плане подъезда: поле
            // `living_with` у гостя висит и после смерти хозяина, а ходят
            // за ним снова к нему самому.
            var хозяин = h.others(я_).First(о => о.apt != сосед.apt && о.apt != я_.apt);
            сосед.living_with = хозяин.id;
            if (Куда(сосед) != хозяин.apt)
                плохо.Add($"переехавший к кв.{хозяин.apt} остался у своей двери "
                          + $"{Куда(сосед)}");
            хозяин.alive = false;
            if (Куда(сосед) != сосед.apt)
                плохо.Add("хозяин умер, а гость всё ещё числится у его двери");
            хозяин.alive = true;
            сосед.living_with = null;

            // Номера — те же и в том же порядке, что видит игрок
            // Пары строятся как в движке — , а не
            // . Разница не косметическая: 
            // разбирает пару образцом, а  — тип-значение, и пара
            // с другим вторым типом ему не подойдёт. Первая версия этой
            // проверки собрала пары «удобнее» и получила пустой ответ там,
            // где в игре всё работает.
            var варианты = new List<ВариантИгроку>
            {
                new(("а", (object?)сосед), 3.0, "разговор"),
                new(("б", (object?)null), 2.0, "банкомат"),
                new(("в", (object?)кладовка), 1.0, "кладовая"),
                new(("г", (object?)сосед), 0.5, "попросить"),
            };
            var вопрос = new ВопросИгроку(1, КТО, Вопрос.ЧТО_ДЕЛАТЬ, "", варианты,
                                          null, null);
            var к_соседу = Дом.Экран.Подача.Кого_к_двери(h, вопрос, сосед.apt);
            if (!к_соседу.SequenceEqual(new[] { 0, 3 }))
                плохо.Add("номера к двери соседа: ["
                          + string.Join(",", к_соседу) + "] вместо [0,3]");
            if (Дом.Экран.Подача.Кого_к_двери(h, вопрос, 999).Count != 0)
                плохо.Add("к несуществующей двери что-то ведёт");
            if (Дом.Экран.Подача.Кого_к_двери(h, null, сосед.apt).Count != 0)
                плохо.Add("без вопроса к двери что-то ведёт");

            var к_складу = Дом.Экран.Подача.Кого_к_кладовой(вопрос, кладовка.id);
            if (!к_складу.SequenceEqual(new[] { 2 }))
                плохо.Add("номера к кладовой: [" + string.Join(",", к_складу)
                          + "] вместо [2]");
            if (Дом.Экран.Подача.Кого_к_кладовой(вопрос, "неттакой").Count != 0)
                плохо.Add("к несуществующей кладовой что-то ведёт");
            if (Дом.Экран.Подача.Кого_к_кладовой(null, кладовка.id).Count != 0)
                плохо.Add("без вопроса к кладовой что-то ведёт");
            адресов = варианты.Count(в =>
                Дом.Экран.Подача.Дверь(h, в) is not null);
        }

        // ---- что видно с площадки: дверь рассказывает ----
        {
            IReadOnlyList<Дом.Экран.ДверьСнаружи> Снаружи(
                Action<House, NPC> поставить)
            {
                var прогон = new Прогон(Пути.Данные, seed: 5, days: 1,
                                        журнал: new Журнал(0, false, TextWriter.Null));
                поставить(прогон.h, прогон.h.people[КТО]);
                var с = new Дом.Экран.Сеанс(прогон.h, КТО);
                return Дом.Экран.Подача.Снаружи(прогон.h, с.Квартиры());
            }

            Дом.Экран.ДверьСнаружи Одна(int кв, Action<House, NPC> поставить)
                => Снаружи(поставить).First(д => д.квартира == кв);

            var исходно = Снаружи((h, я) => { });
            if (исходно.Count < 15)
                плохо.Add($"с площадки видно {исходно.Count} дверей — мало");

            // пустая квартира и жилая различаются
            int жилых = исходно.Count(д => д.живут);
            int пустых = исходно.Count(д => !д.живут);
            if (жилых == 0 || пустых == 0)
                плохо.Add($"двери не различают жилое и пустое: "
                          + $"{жилых} жилых, {пустых} пустых");

            // Свет меряется с обеих сторон, и это не педантизм: в первый
            // день дом ещё под током, и светятся все двери разом. Проверка,
            // искавшая тёмную жилую квартиру, на первом дне не нашла
            // ни одной и упала — виновата была она.
            var под_током = Снаружи((h, я) => h.power_on = true);
            int тёмных = под_током.Count(д => д.живут && !д.свет);
            if (тёмных > 0)
                плохо.Add($"в доме есть свет, а {тёмных} жилых дверей темны");

            var без_тока = Снаружи((h, я) => h.power_on = false);
            if (без_тока.Any(д => д.свет))
                плохо.Add("тока нет и генераторов не заводили, а свет откуда-то есть");

            int сосед_кв = без_тока.First(д => д.живут).квартира;

            // свет без тока — тот же факт, что и гул: работает генератор
            var со_светом = Одна(сосед_кв, (h, я) =>
            {
                h.power_on = false;
                h.flats[сосед_кв].shelter["питание"] = h.day;
            });
            if (!со_светом.свет)
                плохо.Add($"у кв.{сосед_кв} работает генератор, "
                          + "а из-под двери не светит");

            // мёртвый хозяин: свет гаснет, а квартира остаётся с телом
            var мёртвая = Одна(сосед_кв, (h, я) =>
            {
                h.power_on = true;
                var хозяин = h.people.Значения.First(о => о.apt == сосед_кв);
                хозяин.alive = false;
                h.flats[сосед_кв].body = new Тело
                {
                    кто = хозяин.@short, вин = хозяин.@short,
                    падеж = хозяин.@short, день = h.day, порций = 1.0,
                };
            });
            if (мёртвая.живут || мёртвая.свет)
                плохо.Add($"в кв.{сосед_кв} никого, а дверь говорит "
                          + $"живут={мёртвая.живут}, свет={мёртвая.свет}");
            if (!мёртвая.тело)
                плохо.Add("хозяин остался внутри, а дверь об этом молчит");

            // взлом, разбор и гарь
            var взломана = Одна(сосед_кв, (h, я) => h.flats[сосед_кв].открыта = true);
            if (!взломана.взломана)
                плохо.Add("замок сорван, а дверь цела");
            var голая = Одна(сосед_кв, (h, я) => h.flats[сосед_кв].stripped = 3);
            if (!голая.разобрана)
                плохо.Add("квартиру разобрали, а дверь этого не показывает");
            var гарь = Одна(сосед_кв, (h, я) => h.flats[сосед_кв].костёр = h.day);
            if (!гарь.горело)
                плохо.Add("в квартире жгли костёр, а гарью не пахнет");

            // Гость у двери, за которой хозяина нет. В обычном прогоне
            // такого не встретишь, и первая версия проверки эту ветку
            // не исполняла вовсе: пока кто-то у двери гостит, хозяин
            // по правилам `хозяин_жилья` стоит там же. Случай ставится
            // руками — цепочкой: А переехал к Б, а Б потом к В. Тогда
            // у двери Б стоит А, а самого Б там нет.
            var цепочка = Снаружи((h, я) =>
            {
                h.power_on = false;
                var трое = h.people.Значения
                    .Where(о => о.здесь() && о.id != КТО)
                    .OrderBy(о => о.apt).Take(3).ToList();
                трое[0].living_with = трое[1].id;   // А к Б
                трое[1].living_with = трое[2].id;   // Б к В
                h.flats[трое[1].apt].shelter["питание"] = h.day;
                гость_кв = трое[1].apt;
            });
            var у_гостя = цепочка.First(д => д.квартира == гость_кв);
            if (!у_гостя.живут)
                плохо.Add($"у кв.{гость_кв} живёт переехавший, "
                          + "а дверь считает её пустой");
            if (!у_гостя.свет)
                плохо.Add($"в кв.{гость_кв} гость завёл генератор, "
                          + "а из-под двери не светит");

            снаружи = $"{жилых}/{жилых + пустых}";
        }

        // ---- что у меня дома: своя правда, и только своя ----
        {
            Дом.Экран.Комната Дома_(Action<House, NPC> поставить)
            {
                var прогон = new Прогон(Пути.Данные, seed: 5, days: 1,
                                        журнал: new Журнал(0, false, TextWriter.Null));
                поставить(прогон.h, прогон.h.people[КТО]);
                return Дом.Экран.Подача.Внутри(прогон.h, прогон.h.people[КТО]);
            }

            var холодно = Дома_((h, я) => я.burning = false);
            var топлено = Дома_((h, я) =>
            {
                h.where(я).shelter["буржуйка"] = 1;
                я.burning = true;
            });
            if (топлено.градусов <= холодно.градусов)
                плохо.Add($"печь топится, а в комнате не теплее: "
                          + $"{Текст.Ф(топлено.градусов, 1)} против "
                          + $"{Текст.Ф(холодно.градусов, 1)}");
            if (холодно.топится || !топлено.топится)
                плохо.Add("«топится» не следует за печкой");
            if (холодно.печь && !Дома_((h, я) => h.where(я).shelter["буржуйка"] = 0).печь)
                { }
            if (!топлено.печь)
                плохо.Add("буржуйка стоит, а комната о ней не знает");

            // шкаф — свой, без нулей и по алфавиту
            var шкаф = Дома_((h, я) =>
            {
                я.stock["еда"] = 3;
                я.stock["вода"] = 0;
                я.stock["топливо"] = 2;
            }).шкаф;
            if (шкаф.Any(з => з.сколько == 0))
                плохо.Add("в шкафу лежит пустая строка");
            if (!шкаф.Select(з => з.ресурс).SequenceEqual(
                    шкаф.Select(з => з.ресурс).OrderBy(x => x, StringComparer.Ordinal)))
                плохо.Add("шкаф отдан не по алфавиту — полки встанут не туда");

            // дыры, дети, тулуп, свет
            if (Дома_((h, я) => h.where(я).дыры["окно"] = 2).дыр != 2)
                плохо.Add("пролом в окне не виден изнутри");
            if (Дома_((h, я) => h.power_on = false).свет)
                плохо.Add("тока нет, а дома светло");
            if (!Дома_((h, я) => h.power_on = true).свет)
                плохо.Add("ток есть, а дома темно");

            // Переехавший смотрит на комнату хозяина, а не на свою пустую.
            // Ветка отдельная: `where` и `apt` совпадают у всех, кроме него,
            // и подменить одно другим можно, ничего не сломав на прогоне.
            var у_соседа = Дома_((h, я) =>
            {
                var сосед = h.others(я).First(о => о.здесь());
                я.living_with = сосед.id;
                h.flats[сосед.apt].дыры["стена"] = 3;
                h.flats[я.apt].дыры["стена"] = 0;
            });
            if (у_соседа.дыр != 3)
                плохо.Add("переехавший видит свою квартиру, а живёт в чужой");

            комната = $"{Текст.Ф(холодно.градусов, 0)}→{Текст.Ф(топлено.градусов, 0)}";
        }

        // ---- адрес вылазки: дверь подъезда, а не список ----
        {
            var h = Дом_((h_, я) => { });
            var я_ = h.people[КТО];
            var сосед = h.others(я_).First(о => о.здесь());
            var погреб = h.кладовые.Значения.First(к => к.вид == ВидКладовой.ПОГРЕБ);
            var гараж = h.кладовые.Значения.First(к => к.вид == ВидКладовой.ГАРАЖ);
            var место = Улица.МЕСТА[0];

            bool Наружу(object? цель)
                => Дом.Экран.Подача.Наружу(
                       new ВариантИгроку(("ключ", цель), 1.0, ""));

            if (!Наружу(место))
                плохо.Add($"«{место.имя}» — место за порогом, а дверь его не берёт");
            // Гараж — это улица, и так сказано в данных: `balance.json`
            // («гараж — это улица со всем, что к ней прилагается»),
            // `часы_кладовой` множит его на погоду, `место_доступно`
            // закрывает тем же, чем вылазку. Погреб — внутри дома.
            if (!Наружу(гараж))
                плохо.Add($"{гараж.имя} за домом, а дверь подъезда его не берёт");
            foreach (var (что, чем) in new (object?, string)[]
                     { (сосед, "сосед"), (погреб, "погреб"),
                       (h.flats[я_.apt], "квартира"), (null, "пустая цель") })
                if (Наружу(что))
                    плохо.Add($"за порог ведёт то, что за порогом не лежит: {чем}");
            if (Дом.Экран.Подача.Кладовка(
                    new ВариантИгроку(("ключ", (object?)гараж), 1.0, "")) is not null)
                плохо.Add($"{гараж.имя} адресуется сам себе, а он за домом");
            if (Дом.Экран.Подача.Кладовка(
                    new ВариантИгроку(("ключ", (object?)погреб), 1.0, "")) != погреб.id)
                плохо.Add($"{погреб.имя} не адресуется сам себе");

            // номера — те же и в том же порядке, что видит игрок
            var варианты = new List<ВариантИгроку>
            {
                new(("а", (object?)сосед), 3.0, "разговор"),
                new(("вылазка", (object?)Улица.МЕСТА[0]), 2.0, "вылазка → ближнее"),
                new(("б", (object?)null), 1.5, "банкомат"),
                new(("вылазка", (object?)Улица.МЕСТА[1]), 1.0, "вылазка → дальнее"),
            };
            var вопрос = new ВопросИгроку(1, КТО, Вопрос.ЧТО_ДЕЛАТЬ, "", варианты,
                                          null, null);
            var наружу = Дом.Экран.Подача.Кого_наружу(вопрос);
            if (!наружу.SequenceEqual(new[] { 1, 3 }))
                плохо.Add("номера вылазок: [" + string.Join(",", наружу)
                          + "] вместо [1,3]");
            if (Дом.Экран.Подача.Кого_наружу(null).Count != 0)
                плохо.Add("без вопроса из подъезда куда-то ведёт");
            мест = Улица.МЕСТА.Count;
        }

        // ---- граница: «что у меня дома» зовётся только про себя ----
        {
            foreach (string файл in Directory.GetFiles(Пути.Корень, "*.cs",
                                                       SearchOption.AllDirectories))
            {
                if (файл.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}")
                    || файл.Contains($"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}")
                    || файл.EndsWith("Подача.cs", StringComparison.Ordinal))
                    continue;
                foreach (var (строка, н) in File.ReadLines(файл)
                         .Select((с, i) => (с, i + 1)))
                {
                    int k = строка.IndexOf("Подача.Внутри(", StringComparison.Ordinal);
                    // сама эта строка тоже содержит искомое — в кавычках.
                    // Тот же случай, что был у «границы движка» с её
                    // собственным комментарием: сканер находит себя
                    if (k < 0 || (k > 0 && строка[k - 1] == (char)34))
                        continue;
                    string хвост = строка[(k + "Подача.Внутри(".Length)..];
                    if (!хвост.Contains(".я", StringComparison.Ordinal)
