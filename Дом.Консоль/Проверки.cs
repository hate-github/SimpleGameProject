        int живых = 0, событий = 0, дней_всего = 0;
        foreach (long зерно in зёрна)
        {
            var h = Прожить(зерно, дней, out var отпечатки);
            мои[Строка(зерно)] = отпечатки;
            живых += h.alive().Count;
            событий += h.события.Count;
            дней_всего += отпечатки.Count;
