            w($"    драки: {Список("драка", "исходы")}");
            w($"    ночь:  {Список("ночь", "исходы")} (1 — вышло)");
            w($"    осады: {Список("осада", "исходы")}, "
              + $"путей внутрь {сцены["осада"]!["пути"]!.AsArray().Count}");
            w($"    прорыв: {Список("прорыв", "исходы")}");
            int Нет(string сцена) => сцены[сцена]!["жильцы"]!.AsObject()
                .Count(п => п.Value!["alive"]!.GetValue<int>() == 0
                            || п.Value!["exiled"]!.GetValue<int>() == 1);
            w($"    выбытие: не в доме {Нет("выбытие")} из {h_живых}, "
              + $"после прорыва — {Нет("прорыв")}");
        }
        return плохо;
    }

    /// <summary>
    /// Дом, в котором есть чему случиться: оружие в руках, ключи от чужих
    /// дверей, злость, патроны и дежурные. Ровно та же обстановка стоит
    /// в питоновской половине.
    /// </summary>
    private static House ДомКонфликта(long зерно)
    {
        var h = Собрать(out var данные, зерно);
        Мир.build_calendar(h, данные.events, 30);
        for (int д = 0; д < 4; д++)
            Мир.start_of_day(h, данные.events);
        h.режим = Режим.ЗАТИШЬЕ;
        h.снег = 0.7;
        h.first_incident_day = 2;
        var все = h.people.Значения;
        var оружие = new[] { "нет", "нож", "топор", "дубина", "дробовик", "нет", "пистолет" };
        int i = 0;
        foreach (var p in все)
        {
            p.satiety = 12.0 + (i * 17) % 70;
            p.hydration = 15.0 + (i * 23) % 65;
            p.warmth = 18.0 + (i * 7) % 50;
            p.rest = 25.0 + (i * 11) % 60;
            p.health = 45.0 + (i * 5) % 55;
            p.mood = 25.0 + (i * 13) % 55;
            p.panic = 15.0 + (i * 19) % 65;
            p.normalcy = 0.25 + ((i * 9) % 65) / 100.0;
            p.weapon = Слова.Оружие(оружие[i % оружие.Length]);
            p.stock["еда"] = (i * 3) % 11;
            p.stock["вода"] = (i * 5) % 8;
            p.stock["топливо"] = (i * 7) % 9;
            p.stock["материалы"] = (i * 11) % 13;
            p.stock["лекарства"] = i % 3;
            p.stock["патроны"] = i % 4;
            p.stock["деньги"] = 50.0 + (i * 29) % 250;
            p.shelter["дверь"] = i % 4;
            p.shelter["утепление"] = i % 3;
            p.shelter["стены"] = i % 2;
            p.hate[все[(i + 4) % все.Count].id] = 40.0 + (i * 7) % 60;
            p.hate[все[(i + 9) % все.Count].id] = 70.0 + i;
            p.trust[все[(i + 2) % все.Count].id] = 7.0;
            p.близость[все[(i + 1) % все.Count].id] = 4.0 + i % 5;
            if (i % 5 == 0)
                p.ключи.Add(все[(i + 6) % все.Count].apt);
            if (i % 4 == 1)
                p.injuries.Add("ушиб ноги");
            if (i % 6 == 2)
                p.tonight = Ночь.ДЕЖУРИТЬ;
            if (i % 7 == 3)
                p.allies.Add(все[(i + 9) % все.Count].id);
            if (i % 8 == 7)
            {
                p.dependents = 1;
                p.дети.Add(new Ребёнок
                {
                    имя = "Ваня", вин = "Ваню", род = "Вани", твор = "Ваней",
                    сытость = 20.0, тепло = 30.0, здоровье = 60.0,
                });
                p.dependent_name = "Ваня";
                p.dependent_acc = "Ваню";
                p.dependent_gen = "Вани";
                p.dependent_ins = "Ваней";
            }
            foreach (var o in все)
                if (!string.Equals(o.id, p.id, StringComparison.Ordinal))
                    p.сведения_о(o.id).aware = 30.0 + (i * 7) % 50;
            i++;
        }
        return h;
    }

