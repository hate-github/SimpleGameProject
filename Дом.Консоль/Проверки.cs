            string моё = мой.RootElement.GetProperty(пара.Name).GetString() ?? "";
            if (string.Equals(их, моё, StringComparison.Ordinal))
                continue;
            var а = их.Split('\n');
            var б = моё.Split('\n');
            for (int i = 0; i < Math.Max(а.Length, б.Length) && плохо.Count < 6; i++)
            {
