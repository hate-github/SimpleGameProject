        var мои = new JsonObject();
        int строк = 0, знаков = 0;
        foreach (long зерно in new long[] { 1, 4 })
        {
            var писало = new StringWriter { NewLine = "\n" };
            var журнал = new Дом.Ядро.Журнал(verbosity: 2, secrets: true, поток: писало);
