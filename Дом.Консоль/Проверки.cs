                    ["выбор"] = выбор,
                });
            разборы[p.id] = список;
        }

        // и игрок: тот же шов, только вместо оценки — номер строки.
        // Спрашивающий отвечает 0, 1, 2… и на последнем вопросе промахивается
        // мимо конца списка — заодно проверен зажим номера
        var спрошено = new JsonArray();
        var отвечено = new JsonArray();
        {
            var п = h.people.Значения[1];
            int номер = 0;
            п.решающий = new Человек((вопрос, строки) =>
            {
                спрошено.Add(new JsonObject
                {
                    ["вопрос"] = вопрос,
                    ["строки"] = new JsonArray(строки.Select(s => (JsonNode?)s).ToArray()),
                });
                return номер++;
            });
            var чел = (Человек)п.решающий;
            var к = Действия.gather(h, п);
            отвечено.Add(Разбор.имя(чел.день(h, п, к.варианты, к) is { } о
                                    ? ((string, object?))(о.key, о.target) : null));
