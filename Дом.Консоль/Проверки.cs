            отвечено.Add(Решение.монета(h, п, Вопрос.ПУСТИТЬ_К_СЕБЕ, "пустить", "отказать", 0.3)
                         ? "True" : "False");
            отвечено.Add(чел.выбор(h, п, Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ, дела));
        }

        var стало = Дом.Ядро.Снимок.Собранный(h);
        стало["разборы"] = разборы;
        стало["спрошено"] = спрошено;
        стало["отвечено"] = отвечено;
        стало["лента"] = Дом.Ядро.Снимок.Округлить(h.rng.Random());

        var плохо = new List<string>();
        using var мой = JsonDocument.Parse(стало.ToJsonString());
        Сравнение.Одинаково(ждём.RootElement, мой.RootElement, "разбор", плохо);
        if (плохо.Count > 0)
            foreach (var x in плохо)
                w("  " + x);
        else
        {
            // считается не для красоты: проверка обязана доказать, что
            // ветки объяснения исполнились, а не что оба списка пусты
            var все = скрипты.SelectMany(ск => ск.разбор.SelectMany(з => з.строки)).ToList();
            int закрытых = все.Count(s => s.StartsWith("закрыто:", StringComparison.Ordinal));
            int сложено = все.Count(s => s.Contains("   = ", StringComparison.Ordinal));
            int ворот = все.Count(s => s.Contains("нормальность", StringComparison.Ordinal));
            int пусто = все.Count(s => s.Contains("ничего не жмёт", StringComparison.Ordinal));
            w($"  разбор решения совпадает с прототипом: {h.people.Count} жильцов, "
              + $"пять вопросов каждому и шестой первому, {все.Count} строк");
            w($"    из них {сложено} со слагаемыми ({ворот} с воротами нормальности), "
              + $"{закрытых} с закрытыми дверьми, {пусто} «ничего не жмёт»");
            w($"    игроку показано {спрошено.Count} вопроса, ответы сошлись: "
              + string.Join(", ", отвечено.Select(о => о!.GetValue<string>())));
        }
        return плохо;
    }

