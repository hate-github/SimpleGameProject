        }
        if (плохо.Count > 0)
            foreach (var x in плохо)
                w("  " + x);
        else
            w($"  журнал и итог совпадают с прототипом знак в знак: два зерна "
              + $"по восемь дней, {строк} строк, {знаков} знаков");
