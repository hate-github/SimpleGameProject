    /// <summary>
    /// Разбор решения: то, что видит игрок вместо мягкого выбора.
    ///
    /// Единственное место, где текст переезжает раньше своего этапа, —
    /// и не по недосмотру. Разбор и есть шов между домом и интерфейсом
    /// (GDD 13): разойдись он, разойдётся не журнал, а то, по чему игрок
    /// жмёт номер. Поэтому строки сверяются целиком, знак в знак.
    ///
    /// Заодно это проверка форматированию чисел (`Текст.Ф`): «0.12» против
    /// «0.13» на ровной половине — ловушка 4 из `docs/ПОРТ.md` в чистом виде,
    /// и в списке вариантов её видно сразу.
    ///
    /// Спрошены все четыре вопроса шва: день с корзиной за спиной, ночь,
    /// ответ монетой и правилом, и выбор без монеты.
    /// </summary>
    public static List<string> РазборРешения(Action<string> w)
    {
        if (!Оракул.Доступен)
        {
            w("  сверить не с чем: python не найден");
            return new List<string> { "разбор решения не сверен с прототипом" };
        }

        using var ждём = Оракул.Json(РАЗБОР_PY);

        var h = Собрать(out var данные);
        Мир.build_calendar(h, данные.events, 30);
        for (int д = 0; д < 4; д++)
            Мир.start_of_day(h, данные.events);
        ОбстановкаСбора(h);
        foreach (var p in h.people.Значения)
            p.решающий = new Скрипт();

        // 0.125 и 2.675 стоят здесь нарочно: обе половины, на которых
        // «F2» в .NET и `.2f` в Python расходятся
        var ночью = new List<((string, object?), double)>
        {
            ((Ночь.СПАТЬ.Текст(), null), 1.5),
            ((Ночь.ДЕЖУРИТЬ.Текст(), null), 2.25),
            ((Ночь.КРАЖА.Текст(), null), 0.125),
        };
        var дела = new List<(string, double)> { ("тепло", 2.675), ("еда", 0.125) };

        foreach (var p in h.people.Значения)
        {
            var с = (Скрипт)p.решающий!;
            var к = Действия.gather(h, p);
            с.день(h, p, к.варианты, к);
            с.ночь(h, p, ночью, Действия.самочувствие(h, p));
            Решение.монета(h, p, Вопрос.ПУСТИТЬ_К_СЕБЕ, "пустить", "отказать", 0.3);
            Решение.по_правилу(h, p, Вопрос.ОТКРЫТЬ_ДВЕРЬ, "открыть", "не открывать",
                               p.вес_черт("попросить") - 1.0);
            с.выбор(h, p, Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ, дела);
        }

        // у сытого и целого строка самочувствия короткая — «ничего не жмёт».
        // В этой обстановке жмёт у всех пятнадцати, поэтому ветку проходят
        // отдельно: то же самочувствие, обнулённое по восьми названным полям
        {
            var п = h.people.Значения[0];
            var с = Действия.самочувствие(h, п) with
            {
                отчаяние = 0.0, невмоготу = 0.0, зову = 0.0, голод = 0.0,
                жажда = 0.0, холод = 0.0, усталость = 0.0, тревога = 0.0,
            };
            ((Скрипт)п.решающий!).ночь(h, п, ночью, с);
        }

        // решающие берутся здесь: ниже одному из жильцов подменят его
        // на игрока, и разбор скрипта у него уже не спросишь
        var скрипты = h.people.Значения.Select(p => (Скрипт)p.решающий!).ToList();

        var разборы = new JsonObject();
        foreach (var (p, ск) in h.people.Значения.Zip(скрипты))
        {
            var список = new JsonArray();
            foreach (var (день, кто, вопрос, строки, выбор) in ск.разбор)
                список.Add(new JsonObject
                {
                    ["день"] = день,
                    ["кто"] = кто,
                    ["вопрос"] = Дом.Ядро.Вопросы.Текст(вопрос),
                    ["строки"] = new JsonArray(строки.Select(s => (JsonNode?)s).ToArray()),
                    ["выбор"] = выбор,
                });
            разборы[p.id] = список;
        }

        // и игрок: тот же шов, только вместо оценки — номер строки.
        // Спрашивающий отвечает 0, 1, 2… и на последнем вопросе промахивается
        // мимо конца списка — заодно проверен зажим номера
        var спрошено = new JsonArray();
        var отвечено = new JsonArray();
        {
            var п = h.people.Значения[1];
            int номер = 0;
            п.решающий = new Человек((вопрос, строки) =>
            {
                спрошено.Add(new JsonObject
                {
                    ["вопрос"] = вопрос,
                    ["строки"] = new JsonArray(строки.Select(s => (JsonNode?)s).ToArray()),
                });
                return номер++;
            });
            var чел = (Человек)п.решающий;
            var к = Действия.gather(h, п);
            отвечено.Add(Разбор.имя(чел.день(h, п, к.варианты, к) is { } о
                                    ? ((string, object?))(о.key, о.target) : null));
            отвечено.Add(Разбор.имя(чел.ночь(h, п, ночью, Действия.самочувствие(h, п))
                                    is { } н ? ((string, object?))(н.вид, н.кому) : null));
            отвечено.Add(Решение.монета(h, п, Вопрос.ПУСТИТЬ_К_СЕБЕ, "пустить", "отказать", 0.3)
                         ? "True" : "False");
            отвечено.Add(чел.выбор(h, п, Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ, дела));
        }

        var стало = Дом.Ядро.Снимок.Собранный(h);
        стало["разборы"] = разборы;
        стало["спрошено"] = спрошено;
        стало["отвечено"] = отвечено;
        стало["лента"] = Дом.Ядро.Снимок.Округлить(h.rng.Random());

        var плохо = new List<string>();
        using var мой = JsonDocument.Parse(стало.ToJsonString());
        Сравнение.Одинаково(ждём.RootElement, мой.RootElement, "разбор", плохо);
        if (плохо.Count > 0)
            foreach (var x in плохо)
                w("  " + x);
        else
        {
            // считается не для красоты: проверка обязана доказать, что
            // ветки объяснения исполнились, а не что оба списка пусты
            var все = скрипты.SelectMany(ск => ск.разбор.SelectMany(з => з.строки)).ToList();
            int закрытых = все.Count(s => s.StartsWith("закрыто:", StringComparison.Ordinal));
            int сложено = все.Count(s => s.Contains("   = ", StringComparison.Ordinal));
            int ворот = все.Count(s => s.Contains("нормальность", StringComparison.Ordinal));
            int пусто = все.Count(s => s.Contains("ничего не жмёт", StringComparison.Ordinal));
            w($"  разбор решения совпадает с прототипом: {h.people.Count} жильцов, "
              + $"пять вопросов каждому и шестой первому, {все.Count} строк");
            w($"    из них {сложено} со слагаемыми ({ворот} с воротами нормальности), "
              + $"{закрытых} с закрытыми дверьми, {пусто} «ничего не жмёт»");
            w($"    игроку показано {спрошено.Count} вопроса, ответы сошлись: "
              + string.Join(", ", отвечено.Select(о => о!.GetValue<string>())));
        }
        return плохо;
    }

