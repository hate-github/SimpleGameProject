    /// <summary>
    /// Дом, где есть чем заняться: тела в пустых квартирах, замыслы, гости,
    /// долги, материалы на стройку и мёртвый сосед за дверью.
    ///
    /// Без неё двадцать четыре исполнителя из сорока восьми не доставались
    /// никому: сцена «обычный дом» не даёт повода ни разобрать чужую
    /// квартиру, ни вынести тело, ни шепнуть про врага. Проверка тогда
    /// сверяет половину порта и молчит про вторую.
    /// </summary>
    private static void ОбстановкаХода(House h)
    {
        var все = h.people.Значения;
        h.network = 1.0;
        h.water_on = false;
        h.power_on = true;
        h.магазины = true;
        h.банки = true;
        h.банкомат = 4000.0;
        // один умер за своей дверью — за ним пойдут проведать, а квартиру
        // с телом станет чем разбирать и что выносить
        var мёртвый = все[12];
        мёртвый.alive = false;
        мёртвый.died_day = h.day - 3;
        мёртвый.cause = "не проснулся";
        var где = h.flats[мёртвый.apt];
        где.owner_died = мёртвый.id;
        где.body = new Тело
        {
            кто = мёртвый.@short, вин = мёртвый.form("acc"), падеж = мёртвый.form("gen"),
            день = h.day - 3, порций = 8.0,
        };
        // дом знает о смерти: без этого квартира с телом не считается пустой
        // ни для кого (`House.пустые_для`), и «взять тело» с «вынести» уходят
        // с порога, не показав ни строчки
        foreach (var p in все)
            p.знает_о_смерти.Add(мёртвый.id);
        int i = -1;
        foreach (var p in все)
        {
            // счётчик идёт по всем, включая мёртвого: `enumerate` в питоновской
            // половине считает так же, а `continue` стоит после него
            i++;
            if (!p.alive)
                continue;
            p.stock["материалы"] = 40.0;      // хватит на любую стройку
            p.stock["еда"] = 6.0;
            p.stock["движок"] = i % 3 == 0 ? 1.0 : 0.0;
            p.счёт = 900.0;
            p.shelter["буржуйка"] = 1;
            p.shelter["обогреватель"] = i % 2;
            p.нормальность_пол = 0.0;
            p.normalcy = 0.3;                 // ворота дикого не заперты
            p.skills.Add(i % 4 == 0 ? "слесарь" : (i % 4 == 1 ? "медик" : "электрик"));
            h.flats[p.apt].вентиляция = 0.2;  // вытяжку есть смысл чистить
            // у каждого второго долг и замысел: возврат, шёпот и подброс
            if (i % 2 == 0)
            {
                var кому = все[(i + 5) % все.Count];
                p.ask_record(кому.id).должен = 2.0;
                p.ask_record(кому.id).должен_чем = "еда";
                кому.дал[p.id] = 2.0;
            }
            p.замысел = new Замысел
            {
                вид = "свести_счёты", враг = все[(i + 6) % все.Count].id,
                с_дня = h.day - 2,
            };
            p.stock["лекарства"] = 3.0;
        }
        // двое в гостях: будет кому съехать и кого выгнать
        for (int k = 0; k + 1 < все.Count; k += 6)
            if (все[k].alive && все[k + 1].alive)
            {
                все[k + 1].living_with = все[k].id;
                все[k].guests.Add(все[k + 1].id);
                все[k + 1].переехал_день = h.day - 5;
            }
    }

