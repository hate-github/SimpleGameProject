    /// <summary>
    /// Ключи по порядку имени, вглубь, и флаг числом.
    ///
    /// Порядок: в Python это порядок объявления в `dataclass`, в C# — порядок
    /// свойств в частичных классах, и совпадать им незачем; сейв читается
    /// по именам.
    ///
    /// Флаг числом: в прототипе `shelter` держит и `True` (буржуйка есть),
    /// и число (утепление третьего уровня), а в порте это словарь чисел —
    /// типизированный не умеет двух видов сразу. Канонический снимок сводит
    /// флаг к 1/0 своим первым правилом, и состояние на этом сошлось
    /// на всех зёрнах; здесь то же приведение, чтобы сверка сейва мерила
    /// набор полей, а не разницу представления.
    /// </summary>
    private static JsonNode? Отсортировать(JsonNode? узел)
    {
        if (узел is JsonObject о)
        {
            // тег перечисления снимается: в `рука` прототип пишет один
            // и тот же ключ то членом `Оружие`, то голой строкой — потому
            // что таблица огнестрела у него из строк, а оружие в руках
            // из перечисления, и в словаре Python это один ключ. Тег тут
            // не сведения, а след того, кто клал первым
            if (о.ContainsKey("#вид") && о.ContainsKey("знач"))
                return Отсортировать(о["знач"]?.DeepClone());
            var новый = new JsonObject();
            foreach (var ключ in о.Select(п => п.Key)
                         .OrderBy(k => k, StringComparer.Ordinal))
                новый[ключ] = Отсортировать(о[ключ]?.DeepClone());
            return новый;
        }
        if (узел is JsonArray а)
        {
            var новый = new JsonArray();
            foreach (var x in а)
                новый.Add(Отсортировать(x?.DeepClone()));
            return новый;
        }
        if (узел is JsonValue v && v.TryGetValue<bool>(out bool флаг))
            return JsonValue.Create(флаг ? 1 : 0);
        return узел;
    }

