    ///
    /// Восемь сцен, и у каждой свой дом: осада меняет всё, до чего дотянется,
    /// и если считать их одной лентой, первое же расхождение затопит остальные
    /// семь. С отдельными домами расхождение называет свою сцену.
    ///
    /// Сцены нарочно разной природы: чистый счёт без бросков (мерки), чистое
    /// перекладывание вещей, и пять таких, где почти каждая строка — бросок
    /// или вопрос жильцу.
    /// </summary>
    public static List<string> Конфликты(Action<string> w)
    {
        if (!Оракул.Доступен)
        {
            w("  сверить не с чем: python не найден");
            return new List<string> { "конфликт не сверен с прототипом" };
        }

        using var ждём = Оракул.Json(КОНФЛИКТ_PY);
        var сцены = new JsonObject();
        int h_живых = 0;

        // ---- мерки: ни одного броска, чистый счёт ----
        {
            var h = ДомКонфликта(1);
            var все = h.people.Значения;
