    /// <summary>
    /// Прогоны, инварианты и учёт.
    ///
    /// Сводка прожитой жизни — то, чем меряют настройку: кто выжил, от чего
    /// умерли, что насчитали счётчики. Она же тянет за собой две проверки
    /// самого дома: инварианты (запас не уходит в минус, союз не бывает
    /// односторонним) и учёт (было плюс пришло равно осталось плюс ушло).
