    /// правило. Банка, заведшаяся из ниоткуда, проходит все инварианты
    /// и все сверки состояния — потому что состояние-то сойдётся, если
    /// порт заводит её там же, где прототип. Учёт спрашивает другое:
    /// сходится ли мир сам с собой.
    /// </summary>
    public static List<string> Прогоны_(Action<string> w)
    {
        if (!Оракул.Доступен)
        {
            w("  сверить не с чем: python не найден");
            return new List<string> { "прогоны не сверены с прототипом" };
        }

        using var ждём = Оракул.Json(ПРОГОНЫ_PY);
        var мои = new JsonObject();
        int нарушений = 0;
        var итоги = Дом.Ядро.Прогоны.many(Пути.Данные, new long[] { 2, 7, 11 }, 20);
        foreach (var и in итоги)
        {
            var судьбы = new JsonObject();
            foreach (string кто in и.судьбы.Ключи)
            {
                var (день, причина) = и.судьбы.Взять(кто, default);
                судьбы[кто] = new JsonArray(день, причина);
            }
            мои[и.зерно.ToString(System.Globalization.CultureInfo.InvariantCulture)]
                = new JsonObject
                {
                    ["выжило"] = и.выжило,
                    ["ушло"] = и.ушло,
                    ["паника"] = Снимок.Округлить(и.паника),
                    ["имена"] = new JsonArray(и.имена.Select(x => (JsonNode?)x).ToArray()),
                    ["причины"] = new JsonArray(
                        и.причины.Select(x => (JsonNode?)x).ToArray()),
                    ["судьбы"] = судьбы,
                    ["stats"] = ПоИмени(и.stats, v => JsonValue.Create(Снимок.Округлить(v))),
                    ["события"] = ПоИмени(и.события, v => JsonValue.Create(v)),
                    ["богатство"] = Снимок.Округлить(и.богатство),
                    ["нарушения"] = new JsonArray(
                        и.нарушения.Select(x => (JsonNode?)x).ToArray()),
                };
            нарушений += и.нарушения.Count;
        }

        // ---- и то, что инвариант вообще срабатывает ----
        //
        // Пустой список нарушений на исправном доме ничего не доказывает:
        // так же выглядит и проверка, которая ничего не проверяет. Порчей
        // это не берётся — сломать надо обе половины разом, а оракул
        // питоновскую не тронет. Поэтому дом ломается здесь, руками,
        // и от инварианта требуется назвать ровно то, что сломано
        var сломанные = new JsonArray();
        {
            var h = Собрать();
            var первый = h.people.Значения[0];
            var второй = h.people.Значения[1];
            первый.stock["еда"] = -1.0;                  // запас в минусе
            первый.trust[второй.id] = 12.0;              // доверие выше десяти
            второй.allies.Add(первый.id);                // союз в одну сторону
            первый.знает_о_смерти.Add(второй.id);        // знает о смерти живого
            foreach (string нарушение in Дом.Ядро.Инварианты.invariants(h))
                сломанные.Add(нарушение);
        }
        мои["сломанный"] = сломанные;

        // и статистика: те же числа с тем же интервалом
        var v = new[] { 3.0, 5.0, 5.0, 8.0, 13.0, 2.0, 7.0 };
        var (m, пол) = Дом.Ядро.Прогоны.сводка(v);
        мои["статистика"] = new JsonObject
        {
            ["сводка"] = new JsonArray(Снимок.Округлить(m), Снимок.Округлить(пол)),
            ["доля"] = Снимок.Округлить(Дом.Ядро.Прогоны.доля(итоги, "краж")),
            ["причины"] = ПоИмени(Дом.Ядро.Прогоны.причины(итоги), x => JsonValue.Create(x)),
        };

        var плохо = new List<string>();
        using var мой = JsonDocument.Parse(мои.ToJsonString());
        Сравнение.Одинаково(ждём.RootElement, мой.RootElement, "прогоны", плохо);
        if (плохо.Count > 0)
            foreach (var x in плохо.Take(8))
                w("  " + x);
        else
            w($"  прогоны совпадают с прототипом: три жизни по двадцать дней, "
              + $"сводка, инварианты и учёт ({нарушений} нарушений); "
              + $"на сломанном доме инвариант назвал {сломанные.Count}");
        return плохо;
    }

    /// <summary>Словарь объектом, ключи по порядку имени.</summary>
    private static JsonObject ПоИмени<T>(Дом.Ядро.Словарь<string, T> т,
                                         Func<T, JsonNode?> как)
    {
        var о = new JsonObject();
        foreach (string k in т.Ключи.OrderBy(x => x, StringComparer.Ordinal))
            о[k] = как(т.Взять(k, default!));
        return о;
    }

