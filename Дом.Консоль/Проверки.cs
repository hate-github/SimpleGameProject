            p.решающий = new Скрипт();

        // 0.125 и 2.675 стоят здесь нарочно: обе половины, на которых
        // «F2» в .NET и `.2f` в Python расходятся
        var ночью = new List<((string, object?), double)>
        {
            ((Ночь.СПАТЬ.Текст(), null), 1.5),
            ((Ночь.ДЕЖУРИТЬ.Текст(), null), 2.25),
            ((Ночь.КРАЖА.Текст(), null), 0.125),
        };
        var дела = new List<(string, double)> { ("тепло", 2.675), ("еда", 0.125) };

        foreach (var p in h.people.Значения)
        {
            var с = (Скрипт)p.решающий!;
            var к = Действия.gather(h, p);
            с.день(h, p, к.варианты, к);
            с.ночь(h, p, ночью, Действия.самочувствие(h, p));
            Решение.монета(h, p, Вопрос.ПУСТИТЬ_К_СЕБЕ, "пустить", "отказать", 0.3);
            Решение.по_правилу(h, p, Вопрос.ОТКРЫТЬ_ДВЕРЬ, "открыть", "не открывать",
                               p.вес_черт("попросить") - 1.0);
            с.выбор(h, p, Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ, дела);
        }

        // у сытого и целого строка самочувствия короткая — «ничего не жмёт».
        // В этой обстановке жмёт у всех пятнадцати, поэтому ветку проходят
        // отдельно: то же самочувствие, обнулённое по восьми названным полям
        {
            var п = h.people.Значения[0];
            var с = Действия.самочувствие(h, п) with
            {
                отчаяние = 0.0, невмоготу = 0.0, зову = 0.0, голод = 0.0,
                жажда = 0.0, холод = 0.0, усталость = 0.0, тревога = 0.0,
            };
            ((Скрипт)п.решающий!).ночь(h, п, ночью, с);
        }

        // решающие берутся здесь: ниже одному из жильцов подменят его
        // на игрока, и разбор скрипта у него уже не спросишь
        var скрипты = h.people.Значения.Select(p => (Скрипт)p.решающий!).ToList();

        var разборы = new JsonObject();
        foreach (var (p, ск) in h.people.Значения.Zip(скрипты))
        {
            var список = new JsonArray();
            foreach (var (день, кто, вопрос, строки, выбор) in ск.разбор)
                список.Add(new JsonObject
                {
