    /// <summary>
    /// Жизнь дома целыми днями: утро, день, чат, ночь, расчёт суток.
    ///
    /// Приёмка этапа 1г и первая настоящая приёмка порта вообще: всё
    /// остальное сверяло куски, а здесь дом живёт сам. Снимок снимается
