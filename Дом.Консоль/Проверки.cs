    /// <summary>
    /// Генератор случайности против файла-вектора (`data/rng_вектор.json`).
    ///
    /// Вектор — это приёмка переноса: порт обязан воспроизвести те же числа
    /// бит в бит, иначе `data/эталон.json` на нём не сойдётся и переносить
    /// дальше бессмысленно. Производные (`Rint`, тасовка, `Pick`) важнее
    /// самих бросков: они ловят ошибку не в генераторе, а в том, как из него
    /// берут число.
    /// </summary>
    public static List<string> Генератор(Action<string> w)
    {
        using var поток = File.OpenRead(Пути.Файл("rng_вектор.json"));
        using var док = JsonDocument.Parse(поток);
        var зёрна = док.RootElement.GetProperty("зёрна");

        var плохо = new List<string>();
        var список = new List<(long зерно, JsonElement ждём)>();
        foreach (var п in зёрна.EnumerateObject())
            список.Add((long.Parse(п.Name), п.Value));
        список.Sort((a, b) => a.зерно.CompareTo(b.зерно));

        foreach (var (зерно, ждём) in список)
        {
            var r = new Rng(зерно);
            var броски = new uint[10000];
            for (int i = 0; i < броски.Length; i++)
                броски[i] = r.Бросок();

            var rц = new Rng(зерно);
            var rп = new Rng(зерно);
            var азбука = "абвгде".ToCharArray();

            var rint = new int[64];
            for (int i = 0; i < 64; i++)
                rint[i] = rц.Rint(1, 10);

            var pick = new StringBuilder();
            for (int i = 0; i < 32; i++)
                pick.Append(rп.Pick(азбука));

            Сверить(плохо, зерно, "броски_первые_64", ждём,
                ЧислаСтрокой(броски.Take(64).Select(x => (long)x)));
            Сверить(плохо, зерно, "броски_10000_sha256_16", ждём,
                Sha256_16(string.Join(",", броски)));
            Сверить(плохо, зерно, "rint_1_10_первые_64", ждём,
                ЧислаСтрокой(rint.Select(x => (long)x)));
            Сверить(плохо, зерно, "тасовка_0_9", ждём,
                ЧислаСтрокой(new Rng(зерно).Shuffled(Enumerable.Range(0, 10)).Select(x => (long)x)));
            Сверить(плохо, зерно, "pick_из_абвгде_32", ждём, pick.ToString());
        }

        if (плохо.Count > 0)
            foreach (var x in плохо)
                w("  " + x);
        else
            w($"  генератор сходится с вектором на {список.Count} зёрнах " +
              "(10 000 бросков на каждом)");
        return плохо;
    }

    /// <summary>
    /// Числа строкой: `Текст.*` против форматирования Python.
    ///
    /// Ловушка 4 из `docs/ПОРТ.md` — единственная, у которой до сих пор
    /// не было своей проверки: `Текст.Ф` ловился попутно в сборе вариантов,
    /// а `Текст.G` не ловился ничем. Цена этого известна точно: заглавная
    /// «E» в степени пережила всю проверку целиком и всплыла на тридцатом
    /// дне сыгранной руками жизни, когда остаток воды в шкафу стал
    /// 6.21725e-15. Порча, возвращающая ту ошибку, оставляла все
    /// восемнадцать разделов зелёными.
    ///
    /// Числа берутся двумя способами: список ловушек руками (ровные
    /// половины, «чуть больше половины», обе границы степени, минус ноль)
    /// и разброс по величинам от 10⁻¹⁸ до 10¹⁸ — потому что нужный случай
    /// нашёлся не вкусом, а широтой. Числа едут в Python записью «R»:
    /// она круглая, и `float()` на той стороне даёт тот же double бит в бит.
    /// </summary>
    public static List<string> Числа(Action<string> w)
    {
        if (!Оракул.Доступен)
        {
            w("  сверить не с чем: python не найден");
            return new List<string> { "числа не сверены с прототипом" };
        }

        var значения = new List<double>
        {
            // ровные половины: Python сводит к чётному, .NET «F» — от нуля
            0.125, 0.375, 2.5, 3.5, -0.125, -2.5, 0.5, 1.5, 0.05, 0.15,
            // не половины, хотя выглядят ими: решает точное двоичное значение
            3.145, 2.675, 1.005, 1.115, 8.835,
            // границы степени у `g`: −4 и 5 включительно ещё обычной записью
            0.0001, 0.00001, 999999.0, 1000000.0, 123456.0, 1234567.0,
            // то самое число с тридцатого дня и его родня
            6.21725e-15, -6.21725e-15, 1e-18, 4.5e18,
            // целые, ноль и минус ноль
            0.0, -0.0, 1.0, -7.0, 100.0,
            // накопленный мусор
            0.1 + 0.2, 1.0 / 3.0, 2.0 / 3.0, 1e16 + 2.0,
        };

        // разброс по величинам: широта, а не вкус
        var r = new Rng(20260910);
        for (int степень = -18; степень <= 18; степень++)
            for (int i = 0; i < 40; i++)
            {
                double v = r.Random() * Math.Pow(10, степень);
                значения.Add(i % 2 == 0 ? v : -v);
            }

        var впрок = new List<string>();
        foreach (double v in значения)
            впрок.Add(v.ToString("R", System.Globalization.CultureInfo.InvariantCulture));

        var моё = new List<string>();
        foreach (double v in значения)
            моё.Add(string.Join("|",
                Текст.G(v), Текст.Ф(v, 0), Текст.Ф(v, 1), Текст.Ф(v, 2),
                Текст.Знак(v, 1), Текст.Repr(v),
                Текст.Repr(Текст.Округлить(v, 6)), Текст.Справа(v, 8, 1)));

        using var ждём = Оракул.Json(ЧИСЛА_PY.Replace(
            "__ЧИСЛА__", string.Join(",", впрок), StringComparison.Ordinal));
        var их = ждём.RootElement.GetProperty("строки");

        var плохо = new List<string>();
        var имена = new[] { ":g", ":.0f", ":.1f", ":.2f", ":+.1f", "str", "round 6", ":>8.1f" };
        for (int i = 0; i < значения.Count; i++)
        {
            var а = их[i].GetString()!.Split('|');
            var б = моё[i].Split('|');
            for (int k = 0; k < имена.Length; k++)
                if (!string.Equals(а[k], б[k], StringComparison.Ordinal))
                    плохо.Add($"{впрок[i]} через «{имена[k]}»: "
                              + $"прототип «{а[k]}», порт «{б[k]}»");
        }

        if (плохо.Count > 0)
        {
            foreach (var x in плохо.Take(6))
                w("  " + x);
            // сколько всего: одна ошибка на одно число и восемь на все —
            // это разные болезни, и по шести строкам их не различить
            if (плохо.Count > 6)
                w($"  … и ещё {плохо.Count - 6} расхождений "
                  + $"в {плохо.Select(x => x.Split(' ')[0]).Distinct(StringComparer.Ordinal).Count()} числах");
        }
        else
            w($"  числа строкой совпадают с прототипом: {значения.Count} чисел "
              + $"от 10⁻¹⁸ до 10¹⁸ в {имена.Length} видах записи "
              + $"({значения.Count * имена.Length} строк)");
        return плохо;
    }

    private const string ЧИСЛА_PY = """
        # -*- coding: utf-8 -*-
        # Те же числа теми же видами записи, что в Проверки.Числа.
        import json
        числа = [float(s) for s in "__ЧИСЛА__".split(",")]
        строки = ["|".join((
            f"{v:g}", f"{v:.0f}", f"{v:.1f}", f"{v:.2f}", f"{v:+.1f}",
            str(v), str(round(v, 6)), f"{v:>8.1f}",
        )) for v in числа]
        print(json.dumps({"строки": строки}, ensure_ascii=False))
        """;

    /// <summary>
    /// Партия: дом на своём потоке и человек, отвечающий с другого.
    ///
    /// Приёмка мосту (`Дом.Экран.Партия`). Сверяется он не с прототипом,
    /// а сам с собой: одна жизнь играется дважды одним и тем же списком
    /// номеров — сперва в один поток, потом партией, где симуляция спит
    /// на вопросе, пока отвечает другой поток. Дома в конце обязаны
    /// совпасть каноническим снимком до последнего поля.
    ///
    /// Снимком, а не текстом, — принципиально. Мост ломается тихо: потерять
    /// один вопрос, ответить за игрока умолчанием, переставить два ответа
    /// местами. Текст после такого остаётся похожим, снимок — нет.
    ///
    /// Заодно проверяется, что лента собрала то, чего консольная игра
    /// не показывает вовсе: событие дня и чат соседей
    /// (`docs/ПОСЛЕ_ПЕРЕЕЗДА.md`, правка 1).
    /// </summary>
    public static List<string> Партия_(Action<string> w)
    {
        const long ЗЕРНО = 31;
        const int ДНЕЙ = 4;
        const string КТО = "лида";

        var плохо = new List<string>();

        // ---- в один поток ----
        var прямые = new Queue<int>(НОМЕРА);
        var прямой = new Прогон(Пути.Данные, seed: ЗЕРНО, days: ДНЕЙ,
                                журнал: new Журнал(1, false, TextWriter.Null));
        int спрошено = 0;
        прямой.h.people[КТО].решающий = new Человек((ВопросИгроку _) =>
        {
            спрошено++;
            return прямые.Count > 0 ? прямые.Dequeue() : 0;
        });
        прямой.run();

        // ---- партией, на своём потоке ----
        var через_поток = new Queue<int>(НОМЕРА);
        var прогон = new Прогон(Пути.Данные, seed: ЗЕРНО, days: ДНЕЙ);
        using var партия = new Дом.Экран.Партия(прогон, КТО);
        int вопросов = 0;
        партия.Начать();
        while (партия.Дождаться() is ВопросИгроку в)
        {
            вопросов++;
            партия.Ответить(через_поток.Count > 0 ? через_поток.Dequeue() : 0);
        }
        партия.Досидеть();

        // ---- дома обязаны совпасть ----
        string а = Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(прямой.h));
        string б = Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(партия.сеанс.дом));
        if (!string.Equals(а, б, StringComparison.Ordinal))
        {
            int i = 0;
            while (i < а.Length && i < б.Length && а[i] == б[i])
                i++;
            плохо.Add($"дом на потоке разошёлся с домом в один поток на знаке {i}:"
                      + $"\n      один поток: {Вырезка(а, i)}"
                      + $"\n      на потоке:  {Вырезка(б, i)}");
        }
        if (вопросов != спрошено)
            плохо.Add($"вопросов через поток {вопросов}, в один поток {спрошено}");

        // ---- лента собрала и то, чего консоль не печатает ----
        int в_ленте = партия.сеанс.лента.Count;
        int событий = партия.сеанс.Вида(Дом.Экран.ВидСтроки.СОБЫТИЕ).Count;
        int чата = партия.сеанс.Вида(Дом.Экран.ВидСтроки.ЧАТ).Count;
        int ходов = партия.сеанс.Вида(Дом.Экран.ВидСтроки.ХОД).Count;
        if (ходов + событий + чата
            + партия.сеанс.Вида(Дом.Экран.ВидСтроки.СЕКРЕТ).Count != в_ленте)
            плохо.Add("строка ленты неизвестного вида");
        if (событий == 0)
            плохо.Add("в ленте нет события дня — журнал его снова глотает");
        if (чата == 0)
            плохо.Add("в ленте нет чата — журнал его снова глотает");
        if (партия.сеанс.лента.Any(с => с.день < 1 || с.день > ДНЕЙ))
            плохо.Add("в ленте есть строка не из этой метели");

        // ---- три экрана ----
        var состояние = партия.сеанс.Состояние();
        var план = партия.сеанс.План();
        var знание = партия.сеанс.Знание();
        int жильцов = партия.сеанс.дом.people.Ключи.Count();
        if (план.Count != жильцов)
            плохо.Add($"план подъезда: {план.Count} строк на {жильцов} жильцов");
        if (состояние.шкалы.Count != 6)
            плохо.Add($"состояние: {состояние.шкалы.Count} шкал вместо шести");
        if (знание.Any(с => string.Equals(с.id, КТО, StringComparison.Ordinal)))
            плохо.Add("в знании о соседях оказался сам играющий");

        // план по квартирам: их больше, чем жильцов, и каждый живой стоит
        // ровно у одной двери — своей или той, к кому переехал. Ошибиться
        // тут легко и незаметно: переехавший либо задвоится, либо пропадёт
        var квартиры = партия.сеанс.Квартиры();
        if (квартиры.Count != партия.сеанс.дом.flats.Ключи.Count())
            плохо.Add($"квартир на плане {квартиры.Count}, "
                      + $"а в доме {партия.сеанс.дом.flats.Ключи.Count()}");
        var за_дверьми = квартиры
            .SelectMany(к => (к.кто is null
                                  ? Enumerable.Empty<Дом.Экран.ЖилецНаПлане>()
                                  : new[] { к.кто }).Concat(к.гости))
            .Select(ж => ж.id)
            .ToList();
        var живые = план.Where(ж => ж.здесь).Select(ж => ж.id).ToList();
        foreach (var id in живые.Except(за_дверьми, StringComparer.Ordinal))
            плохо.Add($"живой жилец {id} не стоит ни у одной двери");
        foreach (var id in за_дверьми.GroupBy(x => x, StringComparer.Ordinal)
                                     .Where(г => г.Count() > 1).Select(г => г.Key))
            плохо.Add($"жилец {id} стоит сразу у двух дверей");
        int пустых = квартиры.Count(к => к.кто is null);

        // За четыре дня никто ни к кому не переехал — и ветка «жилец
        // за чужой дверью» не исполнилась бы ни разу. Порча, оставляющая
        // переехавшего сразу у двух дверей, при этом остаётся зелёной:
        // проверка проходит, не проверяя. Поэтому пара сводится под одну
        // крышу руками, на доме, который уже отыгран и больше никуда
        // не пойдёт
        var сосед1 = прямой.h.people[КТО];
        var сосед2 = прямой.h.others(сосед1).FirstOrDefault(p => p.здесь());
        if (сосед2 is null)
            плохо.Add("некому съехаться: живых соседей не осталось");
        else
        {
            сосед1.living_with = сосед2.id;
            сосед2.guests.Add(сосед1.id);
            var съехались = new Дом.Экран.Сеанс(прямой.h, КТО).Квартиры();
            var своя = съехались.FirstOrDefault(к => к.номер == сосед1.apt);
            var чужая = съехались.FirstOrDefault(к => к.номер == сосед2.apt);
            if (своя is null || чужая is null)
                плохо.Add($"на плане нет кв{сосед1.apt} или кв{сосед2.apt}");
            else
            {
            if (своя.кто is not null)
                плохо.Add($"переехавший всё ещё числится в своей кв{сосед1.apt}");
            if (!чужая.гости.Any(г => string.Equals(г.id, сосед1.id, StringComparison.Ordinal)))
                плохо.Add($"переехавшего нет в гостях у кв{сосед2.apt}");
            if (чужая.кто is null
                || !string.Equals(чужая.кто.id, сосед2.id, StringComparison.Ordinal))
                плохо.Add($"хозяин кв{сосед2.apt} потерялся, приняв гостя");

            // а теперь хозяин умирает, а поле у гостя остаётся висеть.
            // Он снова у своей двери — потому что `хозяин_жилья` возвращает
            // его самого, и ходить за ним будут именно туда
            сосед2.alive = false;
            var осиротел = new Дом.Экран.Сеанс(прямой.h, КТО).Квартиры();
            var назад = осиротел.FirstOrDefault(к => к.номер == сосед1.apt);
            if (назад?.кто is null
                || !string.Equals(назад.кто.id, сосед1.id, StringComparison.Ordinal))
                плохо.Add($"хозяин умер, а гость не вернулся к своей кв{сосед1.apt}");
            if (осиротел.Any(к => к.гости.Any(
                    г => string.Equals(г.id, сосед1.id, StringComparison.Ordinal))))
                плохо.Add("хозяин умер, а гость всё ещё числится у чужой двери");
            }
        }
        if (партия.сеанс.события.Count == 0)
            плохо.Add("сеанс не поймал ни одного события дома");

        if (плохо.Count > 0)
            foreach (var x in плохо.Take(6))
                w("  " + x);
        else
            w($"  партия совпадает с прогоном в один поток полем в поле: "
              + $"{вопросов} вопросов через поток, {в_ленте} строк в ленте "
              + $"(из них {событий} событий дня и {чата} реплик чата — "
              + $"того, чего консольная игра не печатает), "
              + $"{партия.сеанс.события.Count} событий дома, "
              + $"{знание.Count} соседей в знании, "
              + $"{квартиры.Count} квартир на плане ({пустых} пустых), "
              + "съехавшаяся пара стоит у одной двери, "
              + "а после смерти хозяина гость возвращается к своей");
        return плохо;
    }

    /// <summary>Кусок строки вокруг места расхождения — чтобы было видно,
    /// какое поле уехало, а не только что уехало.</summary>
    private static string Вырезка(string s, int i)
    {
        int н = Math.Max(0, i - 40);
        return s.Substring(н, Math.Min(80, s.Length - н)).Replace('\n', '⏎');
    }

    /// <summary>
    /// Ответы номерами. Не одни нули: ноль — всегда лучший вариант,
    /// и жизнь на одних нулях проверяет только самый верх списка.
    /// Номеров за краем здесь нет нарочно: их зажимает шов, и обе стороны
    /// зажали бы одинаково — проверять было бы нечего.
    /// </summary>
    private static readonly int[] НОМЕРА = Enumerable.Range(0, 400)
        .Select(i => new[] { 0, 1, 0, 2, 0, 0, 3, 1 }[i % 8]).ToArray();

    /// <summary>
    /// Петля: пять жизней подряд и то, что между ними переносится.
    ///
    /// Главное, что здесь доказывается, — <b>петля дом не трогает</b>.
    /// Жизнь, прожитая внутри петли, обязана дать тот же канонический
    /// снимок, что обычный прогон с тем же зерном и теми же ответами.
    /// Если петля хоть раз что-то в доме подкрутит, эталон разойдётся —
    /// и разойдётся не здесь, а через двадцать дней и на другом зерне.
    ///
    /// Дальше — правила ГДД: очки (8.2), три переносимые вещи (8),
    /// телефон из знания игрока (10), пороги рассудка (11), сохранение
    /// только переносимого (24).
    ///
    /// Отдельно сверяются ручки `data/петля.json` в обе стороны: мёртвая
    /// ручка и чтение отсутствующей красят одинаково. Это тот же приём,
    /// которым прототип сторожит `balance.json`, — свой, потому что
    /// о петле прототип не знает и знать не должен.
    /// </summary>
    public static List<string> Петля_(Action<string> w)
    {
        // Зерно выбрано не наугад: на нём героиня гибнет, а в доме умирают
        // соседи. На спокойном зерне половина петли — своя смерть, запись
        // об убийце, отголосок на месте — не исполнялась бы ни разу,
        // и проверка проходила бы, не проверяя
        const long ЗЕРНО = 3;
        const int ДНЕЙ = 15;
        const string КТО = "оксана";

        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        int тяжёлых = 0;
        string знал_смертей = "";

        // ---- ручки: в обе стороны ----
        плохо.AddRange(Ручки(ручки));

        // ---- пять жизней ----
        var наследие = new Наследие();
        var петля = new Дом.Ядро.Петля(наследие, ручки);
        var прожитые = new List<Жизнь>();
        string? первый_снимок = null;

        for (int i = 0; i < 5; i++)
        {
            var начало = петля.Начать();
            if (начало.номер != i + 1)
                плохо.Add($"жизнь {i + 1} назвалась {начало.номер}-й");
            if (начало.монолог.Length == 0)
                плохо.Add($"жизнь {начало.номер}: пустой монолог");

            // одинаковые ответы на каждой жизни — чтобы сравнивать
            // не игру, а петлю
            var ответы = new Queue<int>(Enumerable.Range(0, 400)
                .Select(k => new[] { 0, 1, 0, 2 }[k % 4]));
            var прогон = new Прогон(Пути.Данные, seed: ЗЕРНО, days: ДНЕЙ,
                                    журнал: new Журнал(1, false, TextWriter.Null));
            прогон.h.people[КТО].решающий = new Человек(
                (ВопросИгроку _) => ответы.Count > 0 ? ответы.Dequeue() : 0);
            // дневник подписывается на дом до прогона — и обязан ничего
            // в нём не изменить: это проверяется сравнением с домом,
            // у которого дневника не было вовсе
            петля.Слушать(прогон, КТО);
            прогон.run();

            // снимок ДО того, как петля к дому притронулась
            string до = Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(прогон.h));
            var жизнь = петля.Закрыть(прогон, КТО);
            string после = Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(прогон.h));
            if (!string.Equals(до, после, StringComparison.Ordinal))
                плохо.Add($"жизнь {жизнь.номер}: петля изменила дом, подводя итог");
            первый_снимок ??= до;
            if (!string.Equals(первый_снимок, до, StringComparison.Ordinal))
                плохо.Add($"жизнь {жизнь.номер}: тот же сценарий дал другой дом — "
                          + "петля протекает в следующую жизнь");
            прожитые.Add(жизнь);
        }

        // ---- дом без петли обязан дать то же самое ----
        {
            var ответы = new Queue<int>(Enumerable.Range(0, 400)
                .Select(k => new[] { 0, 1, 0, 2 }[k % 4]));
            var прогон = new Прогон(Пути.Данные, seed: ЗЕРНО, days: ДНЕЙ,
                                    журнал: new Журнал(1, false, TextWriter.Null));
            прогон.h.people[КТО].решающий = new Человек(
                (ВопросИгроку _) => ответы.Count > 0 ? ответы.Dequeue() : 0);
            прогон.run();
            string без = Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(прогон.h));
            if (!string.Equals(первый_снимок, без, StringComparison.Ordinal))
                плохо.Add("дом внутри петли не совпал с домом без петли");
        }

        // ---- очки по правилу ГДД 8.2 ----
        int обучающих = (int)ручки["обучающих_жизней"];
        int рекорд = 0;
        for (int i = 0; i < прожитые.Count; i++)
        {
            int ждём = i < обучающих ? прожитые[i].прожито
                                     : Math.Max(0, прожитые[i].прожито - рекорд);
            if (прожитые[i].начислено != ждём)
                плохо.Add($"жизнь {i + 1}: начислено {прожитые[i].начислено}, "
                          + $"а по правилу {ждём} (прожито {прожитые[i].прожито}, "
                          + $"рекорд был {рекорд})");
            рекорд = Math.Max(рекорд, прожитые[i].прожито);
        }
        if (наследие.очки != прожитые.Sum(ж => ж.начислено))
            плохо.Add($"в наследии {наследие.очки} очков, а начислено "
                      + $"{прожитые.Sum(ж => ж.начислено)}");
        if (наследие.рекорд != рекорд)
            плохо.Add($"рекорд {наследие.рекорд}, а лучшая жизнь {рекорд}");

        // Одинаковые жизни не должны платить дважды: с третьей рекорд
        // не побит, и очков быть не должно. Иначе выгодно переигрывать
        // одно и то же
        if (прожитые.Skip(обучающих).Any(ж => ж.начислено != 0))
            плохо.Add("за повтор той же жизни начислены очки");

        // ---- телефон: только то, что игрок знает ----
        var записи = наследие.записи;
        if (записи.Count == 0)
            плохо.Add("телефон пуст за пять жизней");
        foreach (var з in записи.Where(з => з.вид == ВидЗаписи.ЗАПАС))
            if (з.кто is null)
                плохо.Add("запись о запасе без соседа");

        // Граница знания. Телефон обязан писать только то, что герой знает
        // сам; взять весь `h.события` было бы проще всего — и отдало бы
        // игроку то, чего нет ни у одного жильца. Проверяется тем, что
        // у каждой записи о чужой смерти есть своя запись в памяти,
        // а у каждой оценке чужого шкафа — достаточная осведомлённость
        {
            var ответы = new Queue<int>(Enumerable.Range(0, 400)
                .Select(k => new[] { 0, 1, 0, 2 }[k % 4]));
            // здесь нужно другое зерно: героиня должна выжить и увидеть
            // чужие смерти — иначе проверять границу знания не на чем
            var прогон = new Прогон(Пути.Данные, seed: 17, days: 15,
                                    журнал: new Журнал(1, false, TextWriter.Null));
            прогон.h.people[КТО].решающий = new Человек(
                (ВопросИгроку _) => ответы.Count > 0 ? ответы.Dequeue() : 0);
            прогон.run();
            var сам = прогон.h.people[КТО];
            var один = new Дом.Ядро.Петля(new Наследие(), ручки);
            var ж = один.Закрыть(прогон, КТО);

            int мимо_знания = 0;
            foreach (var з in ж.новые_записи)
            {
                if (з.вид == ВидЗаписи.СМЕРТЬ_СОСЕДА
                    && !сам.memory.Any(м => м.вид == Вид.ВИДЕЛ_УБИЙСТВО
                                            && string.Equals(м.кто, з.кто,
                                                             StringComparison.Ordinal)))
                    мимо_знания++;
                if (з.вид == ВидЗаписи.ЗАПАС && з.кто is not null
                    && сам.сведения_о(з.кто).aware < 50)
                    мимо_знания++;
            }
            if (мимо_знания > 0)
                плохо.Add($"телефон написал {мимо_знания} записей о том, "
                          + "чего герой не знает");

            int умерло = прогон.h.people.Значения.Count(x => !x.здесь());
            int записал = ж.новые_записи.Count(з => з.вид == ВидЗаписи.СМЕРТЬ_СОСЕДА);
            if (записал == 0 && умерло > 0)
                плохо.Add($"в доме не стало {умерло} человек, а телефон "
                          + "не записал ни одной смерти — проверять нечего");
            знал_смертей = $"о {записал} из {умерло} выбывших — об остальных он не знает";
        }

        // ---- три вещи и ничего больше (ГДД 8) ----
        плохо.AddRange(ТриВещи());

        // ---- тяжёлое: чего спокойная жизнь не даёт ----
        //
        // За пять прожитых до конца жизней Оксана никого не убила и сама
        // не умерла — то есть вся тяжёлая половина таблицы не исполнилась
        // ни разу. Проверять её нечем, кроме как поставив случай руками:
        // так же, как инварианты проверяются на нарочно сломанном доме.
        {
            var прогон = new Прогон(Пути.Данные, seed: 3, days: 2,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            var h = прогон.h;
            var я = h.people[КТО];
            var сосед = h.others(я).First();

            // он умер; он видел расправу; он убил троих по-разному;
            // его предал тот, кому он верил
            я.alive = false;
            я.cause = "убита ночью";
            я.died_day = 2;
            я.memory.Add(new Память { день = 1, вид = Вид.ВИДЕЛ_УБИЙСТВО,
                                      кто = сосед.id });
            я.trust[сосед.id] = 8.0;
            я.memory.Add(new Память { день = 1, вид = Вид.ПОЙМАЛ_ВОРА,
                                      кто = сосед.id });
            h.события.Add(new Событие(1, ВидСобытия.УБИЙСТВО, кто: я.id,
                                      кому: сосед.id, что: "убит в драке"));
            h.события.Add(new Событие(1, ВидСобытия.УБИЙСТВО, кто: я.id,
                                      кому: сосед.id, что: "убит безоружным при налёте"));
            h.события.Add(new Событие(2, ВидСобытия.УБИЙСТВО, кто: я.id,
                                      кому: сосед.id, что: "убит ночью, в собственной квартире"));

            var вклады = Рассудок.Вклады(h, я, ручки);
            var по_имени = вклады.ToDictionary(в => в.за_что, в => в.сколько,
                                               StringComparer.Ordinal);
            var ждём = new (string имя, double сколько)[]
            {
                ("своя смерть", ручки["смерть_своя"]),
                ("видел расправу", ручки["смерть_соседа_на_глазах"]),
                ("убил в бою", ручки["убийство_в_бою"]),
                ("убил безоружного", ручки["убийство_безоружного"]),
                ("убил свидетеля", ручки["убийство_свидетеля"]),
                ("предал тот, кому верил", ручки["предательство_доверенного"]),
            };
            foreach (var (имя, сколько) in ждём)
                if (!по_имени.TryGetValue(имя, out double было_) || было_ != сколько)
                    плохо.Add($"тяжёлый вклад «{имя}»: "
                              + (по_имени.ContainsKey(имя)
                                 ? $"{Текст.Ф(по_имени[имя], 2)} вместо {Текст.Ф(сколько, 2)}"
                                 : "не сработал вовсе"));

            // и порядок тяжести из ГДД 11: свидетель тяжелее безоружного,
            // безоружный тяжелее боя
            if (!(ручки["убийство_свидетеля"] > ручки["убийство_безоружного"]
                  && ручки["убийство_безоружного"] > ручки["убийство_в_бою"]
                  && ручки["убийство_в_бою"] > ручки["смерть_соседа_на_глазах"]))
                плохо.Add("порядок тяжести убийств разошёлся с ГДД 11");

            тяжёлых = вклады.Count(в => в.сколько > 0);
            double стало_ = Рассудок.Сложить(0.0, вклады);
            if (Рассудок.Где(стало_, ручки) != Порог.НЕВОЗВРАТ)
                плохо.Add($"такая жизнь дала {Текст.Ф(стало_, 1)} — "
                          + "не хватило даже на точку невозврата");
        }

        // ---- обрыв петли и нирвана ----
        {
            var н = new Наследие { рассудок = ручки["порог_невозврата"] };
            var п = new Дом.Ядро.Петля(н, ручки);
            if (!п.оборвалась)
                плохо.Add("на точке невозврата петля не оборвалась");
            н.нирвана = true;
            if (п.оборвалась)
                плохо.Add("слово пророка не удержало петлю");
            // в нирване рассудок зафиксирован (ГДД 11)
            var прогон2 = new Прогон(Пути.Данные, seed: 3, days: 1,
                                     журнал: new Журнал(0, false, TextWriter.Null));
            прогон2.run();
            double до = н.рассудок;
            п.Закрыть(прогон2, КТО);
            if (н.рассудок != до)
                плохо.Add($"в нирване рассудок сдвинулся: {до} → {н.рассудок}");
        }

        // ---- очки тратятся на уровни ----
        {
            var н = new Наследие { очки = (int)ручки["очков_на_уровень"] };
            if (!н.Поднять(Навык.ФИЗИКА, ручки) || н.Уровень(Навык.ФИЗИКА) != 1)
                плохо.Add("уровень не поднялся, хотя очков хватало");
            if (н.очки != 0)
                плохо.Add($"после подъёма осталось {н.очки} очков вместо нуля");
            if (н.Поднять(Навык.ФИЗИКА, ручки))
                плохо.Add("уровень поднялся без очков");
        }

        // ---- пороги рассудка ----
        var пороги = new List<(double, Порог)>
        {
            (0.0, Порог.ОБЫЧНО), (3.9, Порог.ОБЫЧНО),
            (4.0, Порог.ТРЕВОГА), (7.9, Порог.ТРЕВОГА),
            (8.0, Порог.ОТСТРАНЕНИЕ), (11.9, Порог.ОТСТРАНЕНИЕ),
            (12.0, Порог.НЕВОЗВРАТ), (99.0, Порог.НЕВОЗВРАТ),
        };
        foreach (var (ш, ждём) in пороги)
            if (Рассудок.Где(ш, ручки) != ждём)
                плохо.Add($"рассудок {Текст.Ф(ш, 1)}: порог "
                          + $"{Рассудок.Где(ш, ручки)}, а должен {ждём}");
        if (Рассудок.МожноУйти(7.9, ручки) || !Рассудок.МожноУйти(8.0, ручки))
            плохо.Add("«уйти» появляется не на отстранении");
        if (Рассудок.Сложить(1.0, new[] { new ВкладВРассудок("х", -5.0) }) != 0.0)
            плохо.Add("рассудок ушёл ниже нуля: доброе дело отменило пережитое");

        // монолог меняется с порогом — иначе шкала невидима вовсе
        var монологи = new HashSet<string>(StringComparer.Ordinal);
        foreach (double ш in new[] { 0.0, 5.0, 9.0, 13.0 })
            монологи.Add(Рассудок.Монолог(
                new Наследие { жизней = 1, рассудок = ш }, ручки));
        if (монологи.Count != 4)
            плохо.Add($"монолог различает {монологи.Count} состояния из четырёх");

        // ---- сохранение: полем в поле ----
        var снова = Хранение.Разобрать(Хранение.Сложить(наследие));
        плохо.AddRange(Сверить_наследие(наследие, снова));

        if (плохо.Count > 0)
            foreach (var x in плохо.Take(6))
                w("  " + x);
        else
            w($"  петля совпадает с правилами ГДД: пять жизней по "
              + $"{прожитые[0].прожито} дн, очки {string.Join("+", прожитые.Select(ж => ж.начислено))}"
              + $" = {наследие.очки}, {записи.Count} записей в телефоне, "
              + $"{наследие.отголоски.Count} отголосков; "
              + "дом внутри петли совпал с домом без неё поле в поле");
            w($"    тяжёлых вкладов проверено {тяжёлых}: убийство свидетеля, "
              + "безоружного, в бою, своя смерть, расправа на глазах, предательство");
            w($"    телефон пишет только своё: {знал_смертей}");
            // из чего сложился рассудок: без этого «29.2» — число без причины,
            // а шкала, которой не видно причины, не настраивается
            w($"    рассудок {Текст.Ф(наследие.рассудок, 1)} "
              + $"({Рассудок.Где(наследие.рассудок, ручки)}), за жизнь "
              + $"{Текст.Знак(прожитые[^1].рассудок_стал - прожитые[^1].рассудок_был, 1)}: "
              + string.Join(", ", прожитые[^1].вклады
                  .OrderByDescending(в => Math.Abs(в.сколько))
                  .Select(в => $"{в.за_что} {Текст.Знак(в.сколько, 1)}")));
        return плохо;
    }

    /// <summary>Ручки петли в обе стороны: мёртвая ручка и чтение
    /// отсутствующей. Читается текст `Дом.Ядро/Петля/*.cs` — так же,
    /// как прототип читает `house/*.py`.</summary>
    private static List<string> Ручки(РучкиПетли ручки)
    {
        var плохо = new List<string>();
        var читают = new HashSet<string>(StringComparer.Ordinal);
        var папка = Path.Combine(Пути.Корень, "Дом.Ядро", "Петля");
        foreach (var файл in Directory.EnumerateFiles(папка, "*.cs"))
            foreach (System.Text.RegularExpressions.Match м in
                     System.Text.RegularExpressions.Regex.Matches(
                         File.ReadAllText(файл), @"ручки\[""([^""]+)""\]"))
                читают.Add(м.Groups[1].Value);

        foreach (var к in читают)
            if (!ручки.Есть(к))
                плохо.Add($"код читает ручку, которой нет в петля.json: {к}");
        foreach (var к in ручки.Ключи)
            if (!читают.Contains(к))
                плохо.Add($"мёртвая ручка в петля.json: {к}");
        return плохо;
    }

    /// <summary>
    /// Три вещи и ничего больше (ГДД 8).
    ///
    /// Сторожится не глазом, а составом полей: `Наследие` — единственное,
    /// что переживает смерть, и стоит кому-нибудь добавить туда «ну и
    /// отношения тоже логично сохранить», вторая жизнь перестанет быть
    /// новой. Список полей поэтому закрыт, и новое поле обязано пройти
    /// через эту проверку и через разговор.
    /// </summary>
    private static List<string> ТриВещи()
    {
        var можно = new HashSet<string>(StringComparer.Ordinal)
        {
            "очки", "уровни", "карман",       // навыки и карман вне времени
            "записи", "отголоски",            // память
            "рассудок",                       // не переносимое добро, а след
            "жизней", "рекорд", "нирвана",    // счётчики самой петли
        };
        var есть = typeof(Наследие)
            .GetProperties(System.Reflection.BindingFlags.Public
                           | System.Reflection.BindingFlags.Instance)
            .Select(п => п.Name)
            .ToList();
        var плохо = new List<string>();
        foreach (var имя in есть)
            if (!можно.Contains(имя))
                плохо.Add($"в наследие добавлено поле «{имя}» — "
                          + "четвёртая переносимая вещь (ГДД 8)");
        foreach (var имя in можно)
            if (!есть.Contains(имя, StringComparer.Ordinal))
                плохо.Add($"из наследия пропало поле «{имя}»");
        return плохо;
    }

    private static List<string> Сверить_наследие(Наследие а, Наследие б)
    {
        var плохо = new List<string>();
        void Р(string что, object? x, object? y)
        {
            if (!Equals(x, y))
                плохо.Add($"сейв наследия: {что} {x} → {y}");
        }
        Р("очки", а.очки, б.очки);
        Р("карман", а.карман, б.карман);
        Р("рассудок", а.рассудок, б.рассудок);
        Р("жизней", а.жизней, б.жизней);
        Р("рекорд", а.рекорд, б.рекорд);
        Р("нирвана", а.нирвана, б.нирвана);
        Р("записей", а.записи.Count, б.записи.Count);
        Р("отголосков", а.отголоски.Count, б.отголоски.Count);
        Р("уровней", а.уровни.Count, б.уровни.Count);
        for (int i = 0; i < Math.Min(а.записи.Count, б.записи.Count); i++)
            if (а.записи[i] != б.записи[i])
                плохо.Add($"сейв наследия: запись {i} разошлась");
        for (int i = 0; i < Math.Min(а.отголоски.Count, б.отголоски.Count); i++)
            if (а.отголоски[i] != б.отголоски[i])
                плохо.Add($"сейв наследия: отголосок {i} разошёлся");
        return плохо;
    }

    /// <summary>
    /// Навыки и карман вне времени (ГДД 8.1, 9).
    ///
    /// Две вещи разом, и обе обязательные.
    ///
    /// Первая: **нулевой уровень не меняет ничего.** Дом, где играющему
    /// повешены умения нулевого уровня, обязан дать тот же снимок, что дом
    /// без умений вовсе. Иначе прокачка ломала бы эталон самим фактом
    /// своего существования, и разошлось бы это не здесь, а через двадцать
    /// дней на другом зерне.
    ///
    /// Вторая: **каждый эффект должен кусаться.** Поправка, которая ничего
    /// не меняет, — это не поправка, а строчка в коде; поэтому пятый уровень
    /// сверяется числом, а не «работает».
    ///
    /// Смекалки здесь нет нарочно: в доме ей не за что зацепиться, пока нет
    /// мини-игр (ГДД 7). Ручки у неё тоже нет — см. `data/петля.json`.
    /// </summary>
    public static List<string> Навыки_(Action<string> w)
    {
        const long ЗЕРНО = 11;
        const int ДНЕЙ = 8;
        const string КТО = "оксана";

        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);

        // ---- нулевой уровень не меняет ничего ----
        string Прожить(Наследие? наследие)
        {
            var ответы = new Queue<int>(Enumerable.Range(0, 400)
                .Select(k => new[] { 0, 1, 0, 2 }[k % 4]));
            var прогон = new Прогон(Пути.Данные, seed: ЗЕРНО, days: ДНЕЙ,
                                    журнал: new Журнал(1, false, TextWriter.Null));
            var я = прогон.h.people[КТО];
            я.решающий = new Человек(
                (ВопросИгроку _) => ответы.Count > 0 ? ответы.Dequeue() : 0);
            if (наследие is not null)
            {
                я.умения = new Умения(наследие, ручки);
                я.карман = new Карман(я.умения);
            }
            прогон.run();
            return Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(прогон.h));
        }

        string без = Прожить(null);
        string ноль = Прожить(new Наследие());
        if (!string.Equals(без, ноль, StringComparison.Ordinal))
            плохо.Add("умения нулевого уровня изменили дом");

        // ---- а пятый — обязан изменить ----
        var мастер = new Наследие();
        foreach (var н in Enum.GetValues<Навык>())
            мастер.уровни[н] = (int)ручки["уровней_навыка"];
        string прокачан = Прожить(мастер);
        if (string.Equals(без, прокачан, StringComparison.Ordinal))
            плохо.Add("прокачка до пятого уровня не изменила в доме ничего");

        // ---- каждый эффект по отдельности, числом ----
        {
            var прогон = new Прогон(Пути.Данные, seed: ЗЕРНО, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            var b = прогон.h.B;
            var я = прогон.h.people[КТО];

            // работа, а не любое действие: Физика ускоряет труд, а не
            // разговор и не еду (ГДД 8.1). Ключ берётся из самого списка
            // работ, чтобы проверка не рассыпалась, если список изменится
            string работа = Дом.Ядро.Каталог.РАБОТА
                .OrderBy(к => к, StringComparer.Ordinal).First();

            // состояние ставится ДО всех замеров и больше не трогается:
            // часы работы зависят и от сытости с теплом (`speed`), и если
            // остудить человека между «до» и «после», мерить будешь мороз,
            // а не навык. Один раз уже намерил так — вышло ×0.94 вместо
            // ×0.75, и виновата была проверка, а не поправка
            я.warmth = 20.0;                       // ниже сорока — мороз кусает

            double сила_до = я.power();
            double часы_до = Действия.hours(работа, я, b);
            // Холод меряется НЕ через саму поправку, а через сутки тела:
            // поправку можно посчитать и не применить, и порча, убравшая
            // её из физиологии, один раз так и осталась зелёной. Мерка —
            // сколько сытости съел день у промёрзшего
            double холод_до = Съело(прогон.h, я);
            double часы_после;
            double холод_после;

            я.умения = new Умения(мастер, ручки);
            double сила_после = я.power();
            часы_после = Действия.hours(работа, я, b);
            холод_после = Съело(прогон.h, я);

            int уровней = (int)ручки["уровней_навыка"];
            Сверить_поправку(плохо, "сила в бою", сила_до, сила_после,
                             1.0 + уровней * ручки["физика_сила_за_уровень"]);
            Сверить_поправку(плохо, "часы работы", часы_до, часы_после,
                             1.0 - уровней * ручки["физика_быстрее_за_уровень"]);
            // сутки съедают базу плюс добавку за холод; Устойчивость
            // режет только добавку, поэтому сверяется разница, а не частное
            double добавка = b["расход_сытости_на_холоде"];
            double ждём_меньше = добавка * уровней * ручки["стойкость_холод_за_уровень"];
            double стало_меньше = холод_до - холод_после;
            if (Math.Abs(стало_меньше - ждём_меньше) > 1e-9)
                плохо.Add($"на холоде съело меньше на {Текст.Ф(стало_меньше, 4)}, "
                          + $"а по ручкам должно на {Текст.Ф(ждём_меньше, 4)}");
            эффекты = $"на работе «{работа}»: сила ×{Текст.Ф(сила_после / сила_до, 2)}, "
                    + $"часы ×{Текст.Ф(часы_после / часы_до, 2)}, "
                    + $"мороз съедает на {Текст.Ф(стало_меньше, 2)} меньше "
                    + $"(из {Текст.Ф(добавка, 2)} добавки)";
        }

        // ---- карман: вес, исчезновение из мира, свидетели ----
        {
            var прогон = new Прогон(Пути.Данные, seed: ЗЕРНО, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            var h = прогон.h;
            var я = h.people[КТО];
            я.умения = new Умения(new Наследие(), ручки);
            я.карман = new Карман(я.умения);

            double ждём_вес = ручки["карман_вес"];
            if (Math.Abs(я.карман.предел - ждём_вес) > 1e-9)
                плохо.Add($"пустой карман вмещает {я.карман.предел}, "
                          + $"а по ручкам {ждём_вес}");
            var с_физикой = new Наследие();
            с_физикой.уровни[Навык.ФИЗИКА] = 3;
            double больше = new Карман(new Умения(с_физикой, ручки)).предел;
            if (больше <= ждём_вес)
                плохо.Add("Физика не увеличила карман");

            // вещь исчезает из мира
            я.stock["еда"] = 5.0;
            double было_в_доме = Инварианты.world_total(h, "еда");
            var видели = я.карман.Положить(h, я, "еда", 2.0);
            if (Math.Abs(я.stock.Взять("еда", 0.0) - 3.0) > 1e-9)
                плохо.Add($"после кармана в шкафу {я.stock.Взять("еда", 0.0)}, а ждали 3");
            if (Math.Abs(я.карман.Сколько("еда") - 2.0) > 1e-9)
                плохо.Add($"в кармане {я.карман.Сколько("еда")}, а клали 2");
            double стало_в_доме = Инварианты.world_total(h, "еда");
            if (Math.Abs(было_в_доме - стало_в_доме - 2.0) > 1e-6)
                плохо.Add($"еда не исчезла из мира: было {Текст.Ф(было_в_доме, 2)}, "
                          + $"стало {Текст.Ф(стало_в_доме, 2)} — а должно быть на 2 меньше");

            // свидетель — тот, кто в этой же квартире
            var сосед = h.others(я).First(x => x.здесь());
            сосед.living_with = я.id;
            я.guests.Add(сосед.id);
            видели = я.карман.Положить(h, я, "еда", 1.0);
            if (!видели.Any(в => string.Equals(в.кто, сосед.id, StringComparison.Ordinal)))
                плохо.Add("сосед под одной крышей не увидел, как вещь исчезла");
            свидетелей = видели.Count;

            // сверх предела не влезет
            я.stock["еда"] = 99.0;
            я.карман.Положить(h, я, "еда", 99.0);
            if (я.карман.занято > я.карман.предел + 1e-9)
                плохо.Add($"в карман влезло {Текст.Ф(я.карман.занято, 2)} "
                          + $"при пределе {Текст.Ф(я.карман.предел, 2)}");

            // достать — вернуть в мир
            double до = я.stock.Взять("еда", 0.0);
            double вернули = я.карман.Достать(я, "еда", 1.0);
            if (Math.Abs(я.stock.Взять("еда", 0.0) - до - вернули) > 1e-9)
                плохо.Add("достали из кармана, а в шкафу не прибавилось");

            // и смерть обнуляет
            я.карман.Обнулить();
            if (я.карман.занято != 0.0)
                плохо.Add("карман пережил смерть — а переносится только пустое место");
        }

        if (плохо.Count > 0)
            foreach (var x in плохо.Take(6))
                w("  " + x);
        else
        {
            w($"  навыки и карман совпадают с ГДД: нулевой уровень дом не трогает, "
              + $"пятый — трогает; {эффекты}");
            w($"    карман: вещь исчезает из мира, свидетелей под одной крышей "
              + $"{свидетелей}, за предел не лезет, смерть обнуляет");
        }
        return плохо;
    }

    private static string эффекты = "";
    private static int свидетелей;

    /// <summary>
    /// Сколько сытости съедают сутки у промёрзшего.
    ///
    /// Меряется на копии состояния: сами сутки тела состояние меняют,
    /// и мерить дважды подряд на одном человеке значило бы мерить
    /// вчерашний расход.
    /// </summary>
    private static double Съело(House h, NPC я)
    {
        double сытость = я.satiety, тепло = я.warmth, вода = я.hydration;
        я.warmth = 20.0;                        // ниже сорока — мороз кусает
        я.satiety = 90.0;
        Физиология.расход_и_тепло(h, я, 0);
        double съело = 90.0 - я.satiety;
        я.satiety = сытость;
        я.warmth = тепло;
        я.hydration = вода;
        return съело;
    }

    /// <summary>Поправка обязана и подействовать, и подействовать ровно
    /// на столько, сколько сказано в ручках.</summary>
    private static void Сверить_поправку(List<string> плохо, string что,
                                         double до, double после, double ждём)
    {
        if (до == 0.0)
        {
            плохо.Add($"{что}: не с чем сравнивать, до правки ноль");
            return;
        }
        double стало = после / до;
        if (Math.Abs(стало - ждём) > 1e-9)
            плохо.Add($"{что}: ×{Текст.Ф(стало, 4)}, а по ручкам ×{Текст.Ф(ждём, 4)}");
    }

    /// <summary>
    /// Проект движка: то, что ломается молча.
    ///
    /// У проекта Godot есть три места, где C# и движок должны договориться,
    /// и все три ломаются без единой ошибки сборки:
    ///
    ///   · имя сборки в `project.godot` против `AssemblyName` в csproj —
    ///     разойдутся, и движок не найдёт ни одного скрипта;
    ///   · главная сцена и скрипт, на который она ссылается, — путь
    ///     в `.tscn` движок разрешает сам и молча, файла может не быть;
    ///   · таблица значков против `ВидСобытия` — новый вид события просто
    ///     нарисуется точкой, и никто не заметит.
    ///
    /// Всё это проверяется чтением файлов, а не запуском: Godot для этого
    /// не нужен, а нужен он был бы ровно тогда, когда уже поздно.
    ///
    /// Таблица значков читается текстом, потому что `Дом.Годот` — сборка
    /// над консолью, и ссылаться на неё отсюда нельзя. Это тот же приём,
    /// которым проверяются ручки баланса в прототипе.
    /// </summary>
    public static List<string> Движок(Action<string> w)
    {
        var плохо = new List<string>();
        string корень = Path.Combine(Пути.Корень, "Дом.Годот");

        if (!Directory.Exists(корень))
        {
            w("  проекта движка ещё нет");
            return плохо;
        }

        // ---- имя сборки ----
        string проект = File.ReadAllText(Path.Combine(корень, "project.godot"));
        string csproj = File.ReadAllText(Path.Combine(корень, "Дом.Годот.csproj"));
        string? в_годоте = Между(проект, "project/assembly_name=\"", "\"");
        string? в_csproj = Между(csproj, "<AssemblyName>", "</AssemblyName>");
        if (в_годоте is null)
            плохо.Add("project.godot: не задано dotnet/project/assembly_name");
        else if (!string.Equals(в_годоте, в_csproj, StringComparison.Ordinal))
            плохо.Add($"имя сборки разошлось: в project.godot «{в_годоте}», "
                      + $"в csproj «{в_csproj}»");

        // ---- главная сцена и её скрипт ----
        string? сцена = Между(проект, "run/main_scene=\"res://", "\"");
        if (сцена is null)
            плохо.Add("project.godot: не задана главная сцена");
        else if (!File.Exists(Path.Combine(корень, сцена)))
            плохо.Add($"главной сцены нет на диске: {сцена}");
        else
        {
            string tscn = File.ReadAllText(Path.Combine(корень, сцена));
            int найдено = 0;
            foreach (var кусок in tscn.Split("path=\"res://").Skip(1))
            {
                string путь = кусок.Split('"')[0];
                найдено++;
                if (!File.Exists(Path.Combine(корень, путь)))
                    плохо.Add($"{сцена} ссылается на несуществующий {путь}");
            }
            if (найдено == 0)
                плохо.Add($"{сцена}: ни одной ссылки на скрипт — сцена пустая");
        }

        // ---- значок на каждый вид события ----
        string подъезд = File.ReadAllText(Path.Combine(корень, "ПодъездUI.cs"));
        var без_значка = new List<string>();
        foreach (var вид in Enum.GetNames<Дом.Ядро.ВидСобытия>())
            if (!подъезд.Contains($"ВидСобытия.{вид} =>", StringComparison.Ordinal))
                без_значка.Add(вид);
        if (без_значка.Count > 0)
            плохо.Add($"на плане подъезда нечем нарисовать: "
                      + string.Join(", ", без_значка));

        if (плохо.Count > 0)
            foreach (var x in плохо.Take(6))
                w("  " + x);
        else
            w($"  проект движка сходится с кодом: сборка «{в_годоте}», "
              + $"главная сцена {сцена}, "
              + $"значок на каждый из {Enum.GetNames<Дом.Ядро.ВидСобытия>().Length} "
              + "видов события");
        return плохо;
    }

    /// <summary>Кусок между двумя метками, или ничего, если метки нет.</summary>
    private static string? Между(string где, string от, string до)
    {
        int н = где.IndexOf(от, StringComparison.Ordinal);
        if (н < 0)
            return null;
        н += от.Length;
        int к = где.IndexOf(до, н, StringComparison.Ordinal);
        return к < 0 ? null : где[н..к];
    }

    /// <summary>
    /// Граница движка: в `Дом.Ядро` не должно быть ни одного упоминания
    /// Godot. Проверка дешёвая и стоит здесь потому, что нарушить границу
    /// легче всего случайно — одной строкой `using` (навык godot-boundary).
    /// </summary>
    public static List<string> ГраницаДвижка(Action<string> w)
    {
        var плохо = new List<string>();

        // ---- ни одного упоминания Godot ниже сцены ----
        // «Дом.Экран» стережётся наравне с ядром, и это не перестраховка:
        // весь смысл слоя вида в том, что он считается без движка. Стоит
        // ему потянуть `Godot.Color` ради одной подсветки — и экран
        // перестанет проверяться прогоном в консоли
        int файлов = 0;
        foreach (var сборка in new[] { "Дом.Ядро", "Дом.Экран" })
            foreach (var файл in Directory.EnumerateFiles(
                         Path.Combine(Пути.Корень, сборка), "*.cs", SearchOption.AllDirectories))
            {
                if (файл.Contains($"{Path.DirectorySeparatorChar}obj{Path.DirectorySeparatorChar}") ||
                    файл.Contains($"{Path.DirectorySeparatorChar}bin{Path.DirectorySeparatorChar}"))
                    continue;
                файлов++;
                var строки = File.ReadAllLines(файл);
                for (int i = 0; i < строки.Length; i++)
                {
                    // комментарий отрезается: в этом проекте он документация
                    // (ADR-5) и про границу с движком говорить обязан — иначе
                    // проверка запрещала бы объяснять, что она проверяет.
                    // Зависимостью комментарий не бывает: настоящий
                    // `using Godot;` в комментарии не живёт
                    var s = строки[i];
                    int щель = s.IndexOf("//", StringComparison.Ordinal);
                    var код = щель >= 0 ? s[..щель] : s;
                    if (код.Contains("using Godot", StringComparison.Ordinal) ||
                        код.Contains("Godot.", StringComparison.Ordinal))
                        плохо.Add($"{сборка} знает о Godot: "
                                  + $"{Path.GetFileName(файл)}:{i + 1}: {s.Trim()}");
                }
            }

        // ---- зависимости только вниз ----
        // Ломается это не «using»-ом, а строкой в csproj, и глазом такое
        // не ловится: ссылка вверх собирается и работает, а границы уже нет
        var можно = new Dictionary<string, string[]>(StringComparer.Ordinal)
        {
            ["Дом.Ядро"] = Array.Empty<string>(),
            ["Дом.Экран"] = new[] { "Дом.Ядро" },
            ["Дом.Консоль"] = new[] { "Дом.Ядро", "Дом.Экран" },
            ["Дом.Годот"] = new[] { "Дом.Ядро", "Дом.Экран" },
        };
        int ссылок = 0;
        foreach (var (сборка, разрешено) in можно.OrderBy(п => п.Key, StringComparer.Ordinal))
        {
            var csproj = Path.Combine(Пути.Корень, сборка, сборка + ".csproj");
            if (!File.Exists(csproj))
                continue;                       // Дом.Годот заводится этапом 3
            foreach (var с in File.ReadAllLines(csproj))
            {
                int н = с.IndexOf("ProjectReference Include=", StringComparison.Ordinal);
                if (н < 0)
                    continue;
                ссылок++;
                string имя = Path.GetFileNameWithoutExtension(
                    с[н..].Split('"')[1].Replace('\\', '/'));
