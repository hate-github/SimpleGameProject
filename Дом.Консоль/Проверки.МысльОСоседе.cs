// Проверка мысли героя о собеседнике (ГДД 10; `Дом.Экран/МысльОСоседе.cs`).
//
//  1. **О ком помнит.** Заметка «убийца» — мысль о нём враждебна и без
//     имени; «давал» — помнит доброе; о том, о ком заметок нет, — молчит.
//  2. **Что громче.** Убийца, который когда-то и давал, — всё равно убийца.
//  3. **Тон — от рассудка.** Обычный, тревога, отстранение — три разные
//     мысли об убийце.
//  4. **Род и время.** Убийца-женщина — «убила»; заметка из последней
//     жизни — «в прошлый раз», из давней — «когда-то, в другой жизни».
//  5. **Окно.** Сцена вопроса с наследием несёт мысль, без наследия — нет
//     (консоль печатает как прежде); окно вопроса её показывает (скан).

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> МысльОСоседе_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var прогон = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
        var h = прогон.h;
        var я = h.people["оксана"];
        var он = h.others(я).First(p => p.sex == "м");
        var она = h.others(я).First(p => p.sex == "ж");
        var чужой = h.others(я).First(p => p.id != он.id && p.id != она.id);
        ЗаписьПамяти Запись(int жизнь, ВидЗаписи вид, NPC кто)
            => new(жизнь, 3, вид, кто.id, кто.apt, "—");

        var н = new Наследие { жизней = 2, рассудок = 1.0 };
        н.записи.Add(Запись(1, ВидЗаписи.ПОМОГ, он));
        н.записи.Add(Запись(2, ВидЗаписи.УБИЙЦА, он));
        н.записи.Add(Запись(1, ВидЗаписи.ПОМОГ, она));

        // ---- 1–2. о ком помнит и что громче ----
        string? убийца = МысльОСоседе.О(н, я, он, ручки);
        string? добрая = МысльОСоседе.О(н, я, она, ручки);
        if (убийца is null || !убийца.Contains("убил", StringComparison.Ordinal))
            плохо.Add($"мысль о соседе: убийца (а когда-то и давал) — «{убийца}», а должен быть убийцей");
        if (убийца is not null && (убийца.Contains(он.@short, StringComparison.Ordinal)
                                  || убийца.Contains(он.name, StringComparison.Ordinal)))
            плохо.Add($"мысль о соседе: в мысли имя — «{убийца}»; лицо помнит, имени этой жизни мог не знать");
        if (добрая is null || !добрая.Contains("давала", StringComparison.Ordinal)
                           || !добрая.Contains("просила", StringComparison.Ordinal))
            плохо.Add($"мысль о соседке, которая давала: «{добрая}»");
        if (МысльОСоседе.О(н, я, чужой, ручки) is { } лишняя)
            плохо.Add($"мысль о соседе, о котором заметок нет: «{лишняя}»");

        // ---- 3. тон от рассудка ----
        var тона = new HashSet<string>(StringComparer.Ordinal);
        foreach (double р in new[] { 1.0, 5.0, 9.0 })
        {
            var н_р = new Наследие { жизней = 2, рассудок = р };
            н_р.записи.Add(Запись(2, ВидЗаписи.УБИЙЦА, он));
            if (МысльОСоседе.О(н_р, я, он, ручки) is { } т)
                тона.Add(т);
        }
        if (тона.Count != 3)
            плохо.Add($"мысль об убийце: рассудок 1, 5 и 9 — мыслей разных {тона.Count} из трёх");

        // ---- 4. род и время ----
        var н_она = new Наследие { жизней = 3, рассудок = 1.0 };
        н_она.записи.Add(Запись(1, ВидЗаписи.УБИЙЦА, она));
        string? убила = МысльОСоседе.О(н_она, я, она, ручки);
        if (убила is null || !убила.Contains("убила", StringComparison.Ordinal)
                          || !убила.Contains("другой жизни", StringComparison.Ordinal))
            плохо.Add($"мысль об убийце-женщине из давней жизни: «{убила}»");
        if (убийца is not null && !убийца.Contains("прошлый раз", StringComparison.Ordinal))
            плохо.Add($"мысль об убийце из последней жизни: «{убийца}» — без «в прошлый раз»");

        // ---- 5. окно ----
        string сцена_итог = "—";
        {
            var в = new ВопросИгроку(1, я.id, Вопрос.ОТКРЫТЬ_ДВЕРЬ, "день 1, Оксана: открыть дверь",
                new[] { new ВариантИгроку("открыть", 1.0, "открыть"), new ВариантИгроку("не открывать", 1.0, "не открывать") },
                null, null, с_кем: он.id);
            var с_мыслью = Разговор.Прочитать(h, я, в, н, ручки);
            var без = Разговор.Прочитать(h, я, в);
            if (с_мыслью.мысль is null || без.мысль is not null)
                плохо.Add("мысль о соседе: сцена вопроса с наследием без мысли (или без наследия — с мыслью)");
            сцена_итог = $"{с_мыслью.кто}: «{с_мыслью.мысль}»";
            string ui = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "ВопросUI.cs"));
            string узел = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "ДомУзел.cs"));
            // и у двери — до метели и в метель
            if (узел.Split("+ Мысль_о(с)").Length - 1 < 2)
                плохо.Add("мысль о соседе: у двери (до метели или в метель) её нет");
            if (!ui.Contains("сцена?.мысль", StringComparison.Ordinal)
                || !узел.Contains("Разговор.Прочитать(дом_, _партия.сеанс.я, в, _наследие, _ручки)", StringComparison.Ordinal))
                плохо.Add("мысль о соседе: окно вопроса её не показывает (или узел не даёт наследия)");
        }

        w($"  убийца: «{убийца}»; давала: «{добрая}»; тонов об убийце — {тона.Count}");
        w($"  окно: {сцена_итог}");
        return плохо;
    }
}
