// Проверка хроники: где человек в каждый час своего дня.
//
// Хроника ничего не решает — она выводится из ходов, которые дом посчитал
// сам. Поэтому проверять надо ровно три вещи, и все три числом:
//
//  1. **Часы правильные.** День — лента: первый ход человека начинается
//     в его час подъёма, ходы идут вперёд и не перекрываются, и вместе
//     они не длиннее его бодрствования. Взять час не в том месте (после
//     дела вместо «до») — самая дешёвая ошибка здесь, и она этим ловится.
//  2. **Адрес правильный.** К соседу ходят к той двери, за которой он
//     живёт, а не по прописке. Ровно на этом уже спотыкался гул генератора.
//  3. **Видно тех и только тех, кто в подъезде.** Кто дома — за дверью,
//     кого нет — за порогом. Иначе фигура на площадке станет знанием,
//     которого у жильца нет.
//
// И один замер, без которого всё остальное бессмысленно: **сколько
// человек в среднем видно на лестнице**. Если ноль — механики нет,
// сколько её ни проверяй.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Хроника_(Action<string> w)
    {
        var плохо = new List<string>();
        const long ЗЕРНО = 5;
        const int ДНЕЙ = 6;

        // ---- 1. фикстура: адрес двери и час хода ----
        {
            var прогон = new Прогон(Пути.Данные, seed: 1, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            var h = прогон.h;
            var х = new Хроника(h);
            var я = h.people["оксана"];
            var сосед = h.others(я).First(о => о.здесь() && о.apt != я.apt);
            var хозяин = h.others(я).First(
                о => о.здесь() && о.apt != я.apt && о.apt != сосед.apt);

            double час0 = я.час();
            Действия.execute(h, я, "разговор", сосед);
            var ходы = х.День(я.id, h.day);
            if (ходы.Count != 1)
                плохо.Add($"один разговор — {ходы.Count} ходов в хронике");
            else
            {
                var х1 = ходы[0];
                if (Math.Abs(х1.от - час0) > 1e-9)
                    плохо.Add($"ход начался в {х1.от:F2}, а часы показывали {час0:F2}");
                if (х1.до <= х1.от)
                    плохо.Add($"ход кончился раньше, чем начался: {х1.от:F2}→{х1.до:F2}");
                if (х1.где != Где.УДвери)
                    плохо.Add($"к соседу сходили, а стоят «{х1.где}»");
                if (х1.квартира != сосед.apt)
                    плохо.Add($"стоят у кв.{х1.квартира}, а сосед в кв.{сосед.apt}");
            }

            // переехал: дверь та, за которой он живёт, а не его собственная
            сосед.living_with = хозяин.id;
            Действия.execute(h, я, "разговор", сосед);
            var п = х.День(я.id, h.day).Last();
            if (п.квартира != хозяин.apt)
                плохо.Add($"к переехавшему пришли в кв.{п.квартира}, "
                          + $"а живёт он у кв.{хозяин.apt}");
            сосед.living_with = null;

            // дома: то, что не выводит на площадку, площадкой не считается
            Действия.execute(h, я, "отдых", null);
            var д = х.День(я.id, h.day).Last();
            if (д.где != Где.Дома)
                плохо.Add($"спали дома, а числятся «{д.где}»");
            // собрание — единственное, что ставит человека на площадку
            // просто так, без двери; ради него всё и затевалось
            Действия.execute(h, я, "собрание", null);
            var сб = х.День(я.id, h.day).Last();
            if (сб.где != Где.НаПлощадке)
                плохо.Add($"собрание — на площадке, а числится «{сб.где}»");

            // пустая квартира: цель — не человек, а сама квартира
            var пустая = h.flats.Значения.FirstOrDefault(
                f => f.apt != я.apt && !h.people.Значения.Any(x => x.здесь() && x.apt == f.apt));
            if (пустая is null)
                плохо.Add("в доме нет пустой квартиры — ветку «цель-квартира» не проверить");
            else
            {
                Действия.execute(h, я, "занять", пустая);
                var з = х.День(я.id, h.day).Last();
                if (з.где != Где.УДвери || з.квартира != пустая.apt)
                    плохо.Add($"занять кв.{пустая.apt} — «{з.где}» у кв.{з.квартира}");
            }
            // ход, на который часа не потратили, в хронику не идёт: человек
            // взялся и его завернуло, — он никуда не ходил и нигде не стоял.
            // В живом доме это редкость (четыре раза на двадцать тысяч ходов,
            // зёрна 2 и 42, восемнадцатый день), и потому ставится руками:
            // пустая кладовка заворачивает, не тратя времени
            int было_ходов = х.День(я.id, h.day).Count;
            double часы_до = я.час();
            Действия.execute(h, я, "кладовая", null);
            if (я.час() != часы_до)
                плохо.Add("пустая кладовка отняла часы — фикстура не про то");
            if (х.День(я.id, h.day).Count != было_ходов)
                плохо.Add("ход без потраченного часа попал в хронику");

            w($"    адрес: разговор — у двери кв.{сосед.apt}, "
              + $"с переездом — у кв.{хозяин.apt}, сон — дома, "
              + $"собрание — на площадке, пустая кв.{пустая?.apt} — у её двери, "
              + "завёрнутый ход — никуда");
        }

        // ---- 2. настоящий дом: часы, видимость, замер живости ----
        int видно_всего = 0, спрошено = 0, макс = 0;
        int у_двери = 0, на_площадке = 0, лентой = 0;
        var мест = new Dictionary<Где, int>();
        var в_ходах = new Dictionary<string, int>(StringComparer.Ordinal);
        {
            var прогон = new Прогон(Пути.Данные, seed: ЗЕРНО, days: ДНЕЙ,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            var h = прогон.h;
            var х = new Хроника(h);

            // смотрим глазами того, чей ход: это ровно то положение,
            // в котором дом задаёт вопрос игроку
            h.hooks.on_execute.Add((дом, npc, _, _, _) =>
            {
                var кто = Подача.В_подъезде(дом, npc, х);
                спрошено++;
                видно_всего += кто.Count;
                макс = Math.Max(макс, кто.Count);
                // почему себя в подъезде не видно: свой ход записывается
                // **после** хода, а спрашивают — до, и потому в свой
                // собственный час человек ни в один свой отрезок не попадает
                // (отрезок полуоткрыт: от <= час < до). Защита в `В_подъезде`
                // от этого не лишняя, но покраснеть от её снятия нечему —
                // краснеть будет вот это, если порядок когда-нибудь съедет
                if (х.Ход_в(npc.id, дом.day, npc.час()) is not null)
                    плохо.Add($"{npc.@short} застал сам себя за делом "
                              + "в свой же час — свой ход попал в хронику раньше времени");
                foreach (var с in кто)
                {
                    if (с.id == npc.id)
                        плохо.Add("в подъезде видно самого себя");
                    if (с.где == Где.Дома || с.где == Где.ЗаПорогом)
                        плохо.Add($"«{с.где}» попало в подъезд");
                    var ход = х.Ход_в(с.id, дом.day, npc.час());
                    if (ход is null)
                        плохо.Add($"{с.имя} стоит в подъезде без хода");
                    if (с.где == Где.УДвери) у_двери++; else на_площадке++;
                    if (!дом.flats.Есть(с.квартира))
                        плохо.Add($"фигура у несуществующей кв.{с.квартира}");
                }
            });
            прогон.run();

            // часы: первый ход — в час подъёма, дальше только вперёд
            for (int день = 1; день <= ДНЕЙ; день++)
                foreach (var п in h.people.Значения)
                {
                    var ходы = х.День(п.id, день);
                    в_ходах[п.id] = в_ходах.GetValueOrDefault(п.id) + ходы.Count;
                    if (ходы.Count == 0)
                        continue;
                    double конец = -1;
                    foreach (var ход in ходы)
                    {
                        if (ход.от < конец - 1e-9)
                            плохо.Add($"{п.@short}, день {день}: ход в {ход.от:F2} "
                                      + $"начался раньше конца прошлого ({конец:F2})");
                        if (ход.до < ход.от)
                            плохо.Add($"{п.@short}, день {день}: ход задом наперёд");
                        конец = ход.до;
                    }
                    double сутки = h.B["часов_бодрствования"];
                    if (ходы[^1].до > ходы[0].от + сутки + 1e-6)
                        плохо.Add($"{п.@short}, день {день}: день длиннее "
                                  + $"{сутки} часов бодрствования");
                }

            if (в_ходах.Values.Count(n => n > 0) < h.people.Значения.Count / 2)
                плохо.Add("хроника пуста у половины дома");

            // ветки должны исполняться, а не только проверяться. Три
            // случаются в любом доме каждый день; четвёртая — площадка —
            // это собрание, а собраний за тридцать дней бывает два, и первое
            // на девятнадцатый день (замерено на четырёх зёрнах, везде два).
            // Поэтому её исполняет фикстура выше, а здесь она только считается
            for (int день = 1; день <= ДНЕЙ; день++)
                foreach (var ход in х.Подряд(день))
                    мест[ход.где] = мест.GetValueOrDefault(ход.где) + 1;
            foreach (var г in new[] { Где.Дома, Где.УДвери, Где.ЗаПорогом })
                if (мест.GetValueOrDefault(г) == 0)
                    плохо.Add($"за {ДНЕЙ} дней ни один ход не пришёлся на «{г}»");

            // лента дня: ход достаётся тому, у кого раньше на личных часах,
            // — значит часы начала по всему дому не убывают. Это свойство
            // движка, а не хроники, и потому проверяет её саму: возьми
            // наблюдатель час не в начале хода, а в конце, — и долгая
            // вылазка перескочила бы вперёд соседей
            for (int день = 1; день <= ДНЕЙ; день++)
            {
                var подряд = х.Подряд(день);
                for (int i = 1; i < подряд.Count; i++)
                    if (подряд[i].от < подряд[i - 1].от - 1e-9)
                    {
                        плохо.Add($"день {день}: лента пошла назад — "
                                  + $"{подряд[i - 1].кто} в {подряд[i - 1].от:F2}, "
                                  + $"следом {подряд[i].кто} в {подряд[i].от:F2}");
                        break;
                    }
                лентой += подряд.Count;
            }
        }

        if (спрошено == 0)
            плохо.Add("никого ни разу не спросили — хроника не проверена");
        else if (видно_всего == 0)
            плохо.Add("за шесть дней в подъезде не было видно никого: "
                      + "механика мёртвая");
        w($"    лестница: за {ДНЕЙ} дней {спрошено} ходов, в подъезде "
          + $"в среднем {(double)видно_всего / Math.Max(спрошено, 1):F2} человек, "
          + $"больше всего разом — {макс}; у дверей {у_двери}, "
          + $"на площадке {на_площадке}");
        w($"    часы: ходы идут вперёд и не перекрываются, день не длиннее "
          + $"бодрствования; ходов записано {в_ходах.Values.Sum()}");
        w($"    лента: {лентой} ходов подряд по всему дому, часы начала "
          + "не убывают ни в один из дней");
        w("    места: " + string.Join(", ",
            Enum.GetValues<Где>().Select(г => $"{г} {мест.GetValueOrDefault(г)}"))
          + " — площадку населяют не собрания, а те, кто пришёл к чужой двери");

        // ---- 3. наблюдатель ничего не меняет ----
        {
            string Снимок(bool с_хроникой)
            {
                var прогон = new Прогон(Пути.Данные, seed: 11, days: 4,
                                        журнал: new Журнал(0, false, TextWriter.Null));
                if (с_хроникой)
                {
                    var х = new Хроника(прогон.h);
                    прогон.h.hooks.on_execute.Add(
                        (дом, npc, _, _, _) => Подача.В_подъезде(дом, npc, х));
                }
                прогон.run();
                return Дом.Ядро.Снимок.Текстом(
                    Дом.Ядро.Снимок.Собранный(прогон.h));
            }
            if (!string.Equals(Снимок(true), Снимок(false), StringComparison.Ordinal))
                плохо.Add("дом с хроникой и без неё разошёлся");
            w("    наблюдатель: дом с хроникой и без — один снимок в один знак");
        }

        return плохо;
    }
}
