// Проверка магазина и походов (задание автора, пп. 13, 6, 10;
// `Дом.Ядро/Петля/Магазин.cs`, `Округа.cs`, `data/магазин.json`).
//
//  1. **Тот же магазин, что у соседей.** Цена ресурса — `магазин_цена`
//     дома с той же наценкой дня; вещь — своя цена с той же наценкой.
//     Работает, пока работает у соседей.
//  2. **Покупка.** Ресурс — в тару (нет тары — пакет), вещь — в снаряжение;
//     сперва карта, потом наличные; нет денег, тара полна, склад пуст,
//     такое уже есть — не куплено, и сказано почему. Полка общая: купленное
//     героем вычерпывает место, и дом считает принесённое и потраченное.
//  3. **Поход.** Не знаешь, где это, — не пойти; замело без снегоступов —
//     не пойти; до ночи не обернуться — не пойти. Дорога дольше по снегу
//     и короче в снегоступах по завалу, чем без них по глубокому снегу.
//  4. **Возвращение слышно**, как с вылазки; по завалу — значит,
//     в снегоступах, и кто слышал, знает о них.
//  5. **Соседи в очереди.** Хроника помнит, куда сосед ушёл за порог:
//     в первый день метели в магазин ходят, и видно, кто.
//  6. **Еда — вещами** (замечание автора 01.10.2026: «покупаю еду — она
//     рандомная; не может ломтик хлеба стоить тысячу»). На прилавке нет
//     «порции еды», из которой вещь потом выбирал случай: каждый товар еды —
//     продукт из `еда.json`, с его именем и порциями; цена — цена еды дома
//     на эти порции с наценкой дня. Купил шпроты — в пакете ровно шпроты
//     на их порции, украл батон в карман — в кармане батон, и сверке слоя
//     продуктов досыпать нечего: случай вещь больше не выбирает.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Магазин_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        (House h, NPC я) Жизнь(string кто = "лида", long зерно = 7)
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л)
                .Слушать(прогон, кто);
            return (прогон.h, прогон.h.people[кто]);
        }

        // ---- 1. тот же магазин ----
        var м = Магазин.Прочитать(Пути.Данные, каталог);
        string цены_итог;
        {
            var (h, _) = Жизнь();
            h.day = 3;
            var еда = м.товары.First(т => т.ресурс == "еда");
            var снегоступы = м.товары.First(т => т.предмет == Округа.СНЕГОСТУПЫ);
            double наценка = 1.0 + h.B["магазин_наценка_в_день"] * 2;
            if (Math.Abs(м.Цена(h, еда) - Math.Round(h.B.Таблица("магазин_цена")["еда"] * наценка, 2)) > 1e-9)
                плохо.Add($"еда в магазине героя стоит {м.Цена(h, еда)}, а у соседей — "
                          + $"{Math.Round(h.B.Таблица("магазин_цена")["еда"] * наценка, 2)}");
            if (Math.Abs(м.Цена(h, снегоступы) - Math.Round(снегоступы.цена * наценка, 2)) > 1e-9)
                плохо.Add("у вещи наценка дня не та, что у ресурса");
            h.магазины = false;
            if (м.Открыт(h))
                плохо.Add("у соседей магазин закрылся, а у героя работает");
            цены_итог = $"третий день: еда {Текст.G(м.Цена(h, еда))}, снегоступы {Текст.G(м.Цена(h, снегоступы))} тыс.";
        }

        // ---- 2. покупка ----
        string покупка_итог;
        {
            var (h, я) = Жизнь();
            var мм = Магазин.Прочитать(Пути.Данные, каталог);
            h.day = 1;
            h.магазины = true;
            я.счёт = 5.0;
            я.stock["деньги"] = 3.0;
            я.ноша = new Ноша();
            var еда = мм.товары.First(т => т.ресурс == "еда");
            double полка = h.богатство_места(мм.место);
            double принесено = h.stats.Взять("принесено_еда", 0.0);
            double цена = мм.Цена(h, еда);
            var п = мм.Купить(h, я, еда, ручки, каталог);
            if (!п.взято)
                плохо.Add($"еду не купить при пяти тысячах на карте: {п.почему}");
            if (я.ноша.тара != Тара.ПАКЕТ || Math.Abs(я.ноша.Сколько("еда") - 1.0) > 1e-9)
                плохо.Add($"купленная еда не в пакете: тара {я.ноша.тара}, еды {я.ноша.Сколько("еда")}");
            if (Math.Abs(я.счёт - (5.0 - цена)) > 1e-9 || Math.Abs(я.stock["деньги"] - 3.0) > 1e-9)
                плохо.Add($"заплатил не картой: на карте {я.счёт}, наличных {я.stock["деньги"]}");
            if (h.богатство_места(мм.место) >= полка - 1e-12)
                плохо.Add("герой купил — а полка магазина не опустела: соседям осталось столько же");
            if (h.stats.Взять("принесено_еда", 0.0) != принесено + 1)
                плохо.Add("покупку героя дом не посчитал принесённой — учёт дома не сойдётся");
            // карта кончилась — наличные
            я.счёт = 0.0;
            double нал = я.stock["деньги"];
            мм.Купить(h, я, еда, ручки, каталог);
            if (Math.Abs(я.stock["деньги"] - (нал - мм.Цена(h, еда))) > 1e-9)
                плохо.Add("без денег на карте платят не наличными");
            // нет денег
            я.stock["деньги"] = 0.0;
            var нет = мм.Купить(h, я, еда, ручки, каталог);
            if (нет.взято)
                плохо.Add("купил без денег");
            // вещи: снегоступы, склад, «уже есть»
            я.счёт = 100.0;
            var сн = мм.товары.First(т => т.предмет == Округа.СНЕГОСТУПЫ);
            мм.Купить(h, я, сн, ручки, каталог);
            if (!я.снаряжение!.Есть(Округа.СНЕГОСТУПЫ))
                плохо.Add("купил снегоступы — а их нет");
            if (мм.Купить(h, я, сн, ручки, каталог).взято)
                плохо.Add("купил вторые снегоступы — одни уже на ногах");
            я.снаряжение.Положить_насовсем(Округа.СНЕГОСТУПЫ);
            мм.Купить(h, я, сн, ручки, каталог);
            я.снаряжение.Положить_насовсем(Округа.СНЕГОСТУПЫ);
            var третьи = мм.Купить(h, я, сн, ручки, каталог);
            if (третьи.взято || мм.Осталось(h, сн) != 0)
                плохо.Add($"снегоступов на складе было {сн.всего}, а купили третьи");
            // тара полна
            var полная = new Ноша();
            var много = Словари.Числа();
            много["вода"] = Тара.ПАКЕТ.мест(ручки);
            полная.Положить(Тара.ПАКЕТ, много, ручки);
            я.ноша = полная;
            if (мм.Купить(h, я, еда, ручки, каталог).взято)
                плохо.Add("купил в полный пакет");
            // закрыт
            h.магазины = false;
            я.ноша = new Ноша();
            if (мм.Купить(h, я, еда, ручки, каталог).взято)
                плохо.Add("купил в закрытом магазине");
            покупка_итог = $"еда {Текст.G(цена)} картой → в пакет, полка {Текст.Ф(полка, 3)} → меньше; "
                           + $"снегоступов на складе {сн.всего}, третьи не купить";
        }

        // ---- 3 и 4. поход ----
        string поход_итог;
        {
            var (h, я) = Жизнь();
            var о = Округа.У(h)!;
            var магазин = л.походы.First(п => п.вид == "магазин");
            var промзона = л.походы.First(п => п.вид == "промзона");
            h.day = 4;
            я.time_left = 16;
            if (о.Нельзя(h, я, промзона) is null)
                плохо.Add("в промзону пустили, не зная о ней");
            о.Узнал(промзона.знать!);
            if (о.Нельзя(h, я, промзона) is not null && h.day < 5)
                плохо.Add($"о промзоне знает, улица проходима — а не пустили: {о.Нельзя(h, я, промзона)}");
            double глубокий = о.Часы_дороги(h, я, магазин);
            if (глубокий <= магазин.часы)
                плохо.Add("по глубокому снегу четвёртого дня дорога не дольше, чем по чистому");
            h.day = 7;
            if (о.Нельзя(h, я, магазин) is not string замело || !замело.Contains("замело"))
                плохо.Add($"завал седьмого дня, снегоступов нет — а в магазин пускают: {о.Нельзя(h, я, магазин) ?? "да"}");
            я.снаряжение!.Подобрать(Округа.СНЕГОСТУПЫ, каталог);
            double в_снегоступах = о.Часы_дороги(h, я, магазин);
            if (о.Нельзя(h, я, магазин) is not null)
                плохо.Add($"в снегоступах по завалу в магазин не пускают: {о.Нельзя(h, я, магазин)}");
            я.time_left = 1.0;
            if (о.Нельзя(h, я, магазин) is null)
                плохо.Add("до ночи час — а в поход на несколько часов пускают");
            // возвращение слышно, и по завалу — значит, в снегоступах
            var слышали = h.others(я).Count(п => п.слышал(я.id, "возвращение", h.day));
            о.Вернулся(h, я, магазин);
            var стали = h.others(я).Where(п => п.слышал(я.id, "возвращение", h.day)).ToList();
            if (стали.Count <= слышали)
                плохо.Add("герой вернулся из похода — а возвращения не слышал никто");
            if (стали.Count > 0 && !о.Знает(стали[0], я))
                плохо.Add("герой вернулся по завалу — а слышавший не знает о снегоступах");
            поход_итог = $"до магазина: глубокий снег — {Часы_текстом_(глубокий)} ч, завал в снегоступах — "
                         + $"{Часы_текстом_(в_снегоступах)} ч; возвращение слышали {стали.Count}";
        }

        // ---- 5. соседи в очереди ----
        string очередь_итог = "—";
        {
            var прогон = new Прогон(Пути.Данные, seed: 11, days: 1);
            using var партия = new Партия(прогон, "оксана");
            партия.Начать();
            var в = партия.Дождаться();
            int в_магазин = 0;
            while (в is not null)
            {
                партия.Ответить(0);
                в = партия.Дождаться();
            }
            партия.Досидеть();
            foreach (var п in прогон.h.people.Значения)
                в_магазин += партия.сеанс.хроника.День(п.id, 1)
                    .Count(х => х.где == Где.ЗаПорогом && х.место == м.место);
            if (в_магазин == 0)
                плохо.Add("в первый день метели в магазин не ходил никто — очередь у прилавка пустая всегда");
            очередь_итог = $"в первый день ходок в магазин {в_магазин}";
        }

        // ---- 6. еда — вещами ----
        string еда_итог;
        {
            var кат = КаталогЕды.Прочитать(Пути.Данные)!;
            var мм = Магазин.Прочитать(Пути.Данные, каталог);
            var продукты = мм.товары.Where(т => т.продукт is not null).ToList();
            if (мм.товары.Any(т => т.ресурс == Продукты.ЕДА && т.продукт is null))
                плохо.Add("еду на прилавке продают числом — какая вещь придёт, решит случай");
            if (продукты.Count == 0)
                плохо.Add("на прилавке нет ни одного продукта");
            {
                var (h, _) = Жизнь();
                h.day = 2;
                foreach (var т in продукты)
                {
                    var в = кат.Есть(т.продукт!) ? кат[т.продукт!] : null;
                    if (в is null || Math.Abs(т.единиц - в.единиц) > 1e-9 || т.имя != в.имя)
                        плохо.Add($"товар «{т.id}» не сходится с еда.json: {т.имя}, {т.единиц} порции");
                    double надо = Math.Round(h.B.Таблица("магазин_цена")[Продукты.ЕДА] * т.единиц * Магазин.Наценка(h), 2);
                    if (Math.Abs(мм.Цена(h, т) - надо) > 1e-9)
                        плохо.Add($"{т.имя} стоит {мм.Цена(h, т)} — а еда на её {т.единиц} порции стоит {надо}");
                }
            }
            string купил = "—", украл = "—";
            // купил шпроты — в пакете шпроты
            {
                var (h, я) = Жизнь();
                var пр = Продукты.Завести(я, кат, 77);
                пр.Сверить(h, я);           // полка героя — вещами, как с начала игры
                h.day = 1;
                h.магазины = true;
                я.счёт = 20.0;
                я.ноша = new Ноша();
                var шпроты = продукты.FirstOrDefault(т => т.продукт == "шпроты") ?? продукты[0];
                var п = мм.Купить(h, я, шпроты, ручки, каталог);
                var в_ноше = пр.В(МестоЕды.НОША);
                if (!п.взято || в_ноше.Count != 1 || в_ноше[0].вид != шпроты.продукт
                    || Math.Abs(в_ноше[0].единиц - шпроты.единиц) > 1e-9)
                    плохо.Add($"купил {шпроты.имя} — а в пакете: {(в_ноше.Count == 0 ? "ничего" : string.Join(", ", в_ноше.Select(x => x.вид)))}");
                if (Math.Abs(я.ноша.Сколько(Продукты.ЕДА) - шпроты.единиц) > 1e-9)
                    плохо.Add($"купил {шпроты.имя} на {шпроты.единиц} порции — а еды в пакете {я.ноша.Сколько(Продукты.ЕДА)}");
                double досыпано = пр.Сверить(h, я);
                if (досыпано > 1e-9)
                    плохо.Add($"после покупки сверка досыпала {Текст.G(Текст.Округлить(досыпано, 2))} порции случайной еды");
                купил = $"{шпроты.имя} за {Текст.G(п.картой + п.налом)} → в пакете {шпроты.имя}, досыпано {Текст.G(досыпано)}";
            }
            // украл батон в карман — в кармане батон (не заметили — на одном из зёрен)
            for (long зерно = 1; зерно <= 40 && украл == "—"; зерно++)
            {
                var (h, я) = Жизнь(зерно: зерно);
                var пр = Продукты.Завести(я, кат, 77);
                h.day = 1;
                h.магазины = true;
                я.карман ??= new Карман(new Умения(new Наследие(), ручки));
                пр.Сверить(h, я);
                var батон = продукты.FirstOrDefault(т => т.продукт == "батон") ?? продукты[0];
                var к = мм.Украсть(h, я, батон, true, 0, ручки, каталог);
                if (!к.взято)
                    continue;
                var в_кармане = пр.В(МестоЕды.КАРМАН);
                if (в_кармане.Count != 1 || в_кармане[0].вид != батон.продукт)
                    плохо.Add($"украл {батон.имя} в карман — а в кармане: {(в_кармане.Count == 0 ? "ничего" : string.Join(", ", в_кармане.Select(x => x.вид)))}");
                if (пр.Сверить(h, я) > 1e-9)
                    плохо.Add("после кражи в карман сверка досыпала случайной еды");
                украл = $"{батон.имя} в карман на {зерно}-м зерне";
            }
            if (украл == "—")
                плохо.Add("за сорок зёрен батон в карман не украсть ни разу — кражу проверить не на чем");
            еда_итог = $"{продукты.Count} продуктов; {купил}; украл {украл}";
        }

        w($"  цены: {цены_итог}");
        w($"  покупка: {покупка_итог}");
        w($"  поход: {поход_итог}");
        w($"  очередь: {очередь_итог}");
        w($"  еда вещами: {еда_итог}");
        return плохо;
    }

    private static string Часы_текстом_(double ч) => Текст.G(Текст.Округлить(ч, 2));
}
