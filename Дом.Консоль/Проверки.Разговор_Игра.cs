// Проверка мини-игры «Разговор» (ГДД 7; `Дом.Ядро/Петля/Реплики.cs`).
//
//  1. **Множитель.** Половина — ровно единица; ноль — `мини_разговор_хуже`
//     (меньше нуля); единица — `мини_лучше`; «Разговор» везёт его в шансе
//     `Сыграно`, часы — единица.
//  2. **Дом.** Два одинаковых дома, герой говорит с соседом: без игры
//     доверие соседа растёт как раньше; сыграл провально — падает на столько
//     же; отлично — растёт в `мини_лучше` раз. У соседа, который сам говорит,
//     `сыграно` нет — множитель единица.
//  3. **Тоны.** Свой тон — по тому, что сосед ценит первым; свой быстро —
//     от ¾ до единицы; чужой — половина; задевающий — провал; молчание — хуже
//     обычного; в нирване «знаю» — всегда удаётся и есть только там.
//  4. **Смекалка.** С третьего уровня игры нет — выходит «само».
//  5. **Экран.** Ответ «разговор» идёт через реплику на время (скан).

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Разговор_Игра_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        bool Рядом(double а, double б) => Math.Abs(а - б) < 1e-9;

        // ---- 1. множитель ----
        if (!Рядом(МиниИгры.Доверие(0.5, ручки), 1.0) || МиниИгры.Доверие(0.5, ручки) != 1.0)
            плохо.Add($"разговор: половина — множитель {МиниИгры.Доверие(0.5, ручки)}, а должен быть ровно единица");
        if (!Рядом(МиниИгры.Доверие(0.0, ручки), ручки["мини_разговор_хуже"]) || МиниИгры.Доверие(0.0, ручки) >= 0)
            плохо.Add($"разговор: провал — множитель {МиниИгры.Доверие(0.0, ручки)}, а должен быть меньше нуля (доверие падает)");
        if (!Рядом(МиниИгры.Доверие(1.0, ручки), ручки["мини_лучше"]))
            плохо.Add($"разговор: отлично — множитель {МиниИгры.Доверие(1.0, ручки)}");
        var с_игры = МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, 0.0, ручки);
        if (!Рядом(с_игры.шанс, МиниИгры.Доверие(0.0, ручки)) || !Рядом(с_игры.часы, 1.0))
            плохо.Add("разговор: «Сыграно» везёт не множитель доверия (или часы не единица)");

        // ---- 2. дом ----
        string дом_итог;
        {
            double Прирост(Сыграно? сыграно)
            {
                var п = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
                var я = п.h.people["оксана"];
                // тот, кто доверяет меньше всех: доверие от слов растёт только
                // до потолка знакомства, и у близкого прироста нет вовсе
                var t = п.h.others(я).Where(x => x.здесь())
                         .OrderBy(x => x.trust.Взять(я.id, 3.0)).ThenBy(x => x.id, StringComparer.Ordinal).First();
                double было = t.trust.Взять(я.id, 3.0);
                я.сыграно = сыграно;
                Действия.execute(п.h, я, "разговор", t);
                return t.trust.Взять(я.id, 3.0) - было;
            }
            double обычно = Прирост(null);
            double провал = Прирост(МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, 0.0, ручки));
            double половина = Прирост(МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, 0.5, ручки));
            double отлично = Прирост(МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, 1.0, ручки));
            if (обычно <= 0)
                плохо.Add($"разговор: без игры доверие соседа не выросло ({обычно}) — сравнивать не с чем");
            if (половина != обычно)
                плохо.Add($"разговор: «как обычно» сдвинуло доверие: {обычно} → {половина}");
            // теряется доверие легче, чем набирается (`Социальное.adjust` гасит
            // только прирост), поэтому провал — не зеркало удачи, а просто «упало»
            if (провал >= 0)
                плохо.Add($"разговор: провал — доверие {Текст.Знак(провал, 3)}, а должно упасть");
            if (Math.Abs(отлично - обычно * ручки["мини_лучше"]) > 1e-6)
                плохо.Add($"разговор: отлично — доверие {Текст.Знак(отлично, 3)}, а должно {Текст.G(обычно)}×{ручки["мини_лучше"]}");
            // сосед, который говорит сам, не играет
            var п2 = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            if (п2.h.people.Значения.Any(x => x.сыграно is not null)
                || Поправки.Доверие_игры(п2.h.people["лида"]) != 1.0)
                плохо.Add("разговор: у соседей есть «сыграно» — их доверие от разговора сдвинулось бы");
            дом_итог = $"доверие соседа: без игры {Текст.Знак(обычно, 3)}, провал {Текст.Знак(провал, 3)}, "
                       + $"отлично {Текст.Знак(отлично, 3)}";
        }

        // ---- 3. тоны ----
        string тоны_итог;
        {
            var п = new Прогон(Пути.Данные, seed: 3, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            var люди = п.h.people.Значения.ToList();
            NPC? Кто(Func<NPC, bool> к) => люди.FirstOrDefault(к);
            var добрый = Кто(x => x.values.ценит.FirstOrDefault() is "щедрость" or "ребёнок");
            var деловой = Кто(x => x.values.ценит.FirstOrDefault() is "работа" or "порядок");
            var мирный = Кто(x => x.не_терпит("насилие") && Реплики.Свой(x) != Тон.ТВЁРДО);
            if (добрый is null || деловой is null || мирный is null)
                плохо.Add("разговор: в доме нет соседа, ценящего доброту, дело или не терпящего насилия — проверять не на ком");
            else
            {
                if (Реплики.Свой(добрый) != Тон.ДОБРО || Реплики.Свой(деловой) != Тон.ДЕЛО)
                    плохо.Add($"разговор: свой тон не по ценностям: {добрый.id} — {Реплики.Свой(добрый)}, {деловой.id} — {Реплики.Свой(деловой)}");
                double быстро = Реплики.Качество(добрый, Тон.ДОБРО, 1.0), медленно = Реплики.Качество(добрый, Тон.ДОБРО, 0.0);
                if (!Рядом(быстро, 1.0) || !Рядом(медленно, 0.75))
                    плохо.Add($"разговор: свой тон — {Текст.G(медленно)}…{Текст.G(быстро)}, а надо ¾…1");
                if (!Рядом(Реплики.Качество(добрый, Тон.ДЕЛО, 1.0), 0.5))
                    плохо.Add("разговор: чужой тон — не «как обычно»");
                if (Реплики.Качество(мирный, Тон.ТВЁРДО, 1.0) >= 0.5)
                    плохо.Add($"разговор: твёрдость тому, кто не терпит насилия ({мирный.id}), — не провал");
                if (Реплики.Качество(добрый, null, 0.0) >= 0.5)
                    плохо.Add("разговор: промолчал — а вышло не хуже обычного");
            }
            if (Реплики.На_выбор(false).Contains(Тон.ЗНАЮ) || !Реплики.На_выбор(true).Contains(Тон.ЗНАЮ)
                || добрый is not null && !Рядом(Реплики.Качество(добрый, Тон.ЗНАЮ, 0.0), 1.0))
                плохо.Add("разговор: «сказать то, чего знать было нельзя» — не только в нирване или не всегда удаётся");
            тоны_итог = добрый is null ? "—"
                : $"{добрый.@short} — {Реплики.Свой(добрый)}, {деловой?.@short} — {(деловой is null ? "—" : Реплики.Свой(деловой).ToString())}; "
                  + $"свой быстро {Текст.G(Реплики.Качество(добрый, Тон.ДОБРО, 1.0))}, чужой 0.5, "
                  + $"задел {(мирный is null ? "—" : Текст.G(Реплики.Качество(мирный, Тон.ТВЁРДО, 1.0)))}, молчал {Текст.G(Реплики.Качество(добрый, null, 0.0))}";
        }

        // ---- 4. смекалка ----
        if (!Рядом(МиниИгры.Само_по((int)ручки["мини_игра_исчезает"], ручки), ручки["мини_само"])
            || МиниИгры.Навык(МиниИгра.РАЗГОВОР) != Навык.СМЕКАЛКА)
            плохо.Add("разговор: с порога Смекалки «само» не то (или снимает не Смекалка)");

        // ---- 5. экран ----
        {
            string Файл(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя));
            string узел = Файл("ДомУзел.cs"), игра = Файл("ДомУзел.РазговорИгра.cs");
            if (!узел.Contains("Разговор_перед_делом(номер, с_разговора);", StringComparison.Ordinal)
                || !узел.Contains("Реплика_кадр(delta);", StringComparison.Ordinal))
                плохо.Add("разговор: ответ «разговор» идёт мимо реплики на время");
            if (!игра.Contains("МиниИгры.Сыграно_для(МиниИгра.РАЗГОВОР, к, _ручки)", StringComparison.Ordinal)
                || !игра.Contains("Реплики.Качество(и.с, т, и.осталось / и.всего)", StringComparison.Ordinal))
                плохо.Add("разговор: как сыграно не ложится герою в «сыграно»");
        }

        w($"  дом: {дом_итог}");
        w($"  тоны: {тоны_итог}");
        return плохо;
    }
}
