// Проверка бесед (решение автора: диалоги про быт и слухи, соседи в прологе;
// `Дом.Экран/Беседа.cs`, `data/разговоры.json`).
//
//  1. **Слова есть у всех.** У каждого жильца свои слова о себе (сдержанно
//     и откровенно) и слухи о нём; ни в одной реплике не остаётся разметки
//     рода ни при каком поле героя и говорящего.
//  2. **Пролог — настоящий разговор.** Беседа до метели — тот же
//     «разговор» дома: доверие растёт, и знаток может заговорить ещё
//     до метели (в следующей жизни — «поиск информации», ГДД 4).
//  3. **Слухи в метель — правда разговора.** Сосед, знающий чужие запасы
//     лучше героя, называет того, о ком разговор дома передал сведения.
//  4. **Предупредить о метели.** Знавший заранее — «я ж говорил»;
//     хозяйственный поверил и запасся (полка опустела); прочие не верят;
//     все запомнили, что герой что-то знал; второй раз — «уже говорил».
//  5. **Болезнь в доме** (просьба автора 01.10.2026). Пока никто не болен —
//     темы «о болезни» нет и приветствие прежнее; только заражённого ещё
//     не видно (он и сам не знает). Заболел Пётр — тема есть;
//     Нина с его этажа знает и называет его, Аркадий с первого — нет
//     (знать неоткуда), зато говорит о «Векторе»; встречают осторожно,
//     и своя встречает своими словами; тяжёлого Петра слышит
//     весь подъезд, а сам он отвечает через силу на любую тему; больная
//     Нина — о себе; больную героиню видно в дверях; умерших от болезни
//     знает весь дом. Ни в одной реплике не остаётся разметки, и узел
//     передаёт беседе в метель, что сосед знает о болезни.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Беседы_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var б = Беседы.Прочитать(Пути.Данные);
        var честный = new Скрипт(new Dictionary<Вопрос, string> { [Вопрос.СОВРАТЬ] = "сказать правду" });
        (House h, NPC я, Округа о) Жизнь(long зерно = 7, string кто = "оксана")
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, кто);
            var h = прогон.h;
            h.people[кто].решающий = честный;
            return (h, h.people[кто], Округа.У(h)!);
        }
        static bool Разметка(string s) => s.Contains('{') || s.Contains('}') || s.Contains('[') || s.Contains(']') || s.Contains('|');

        // ---- 1. слова есть у всех ----
        string слова_итог;
        {
            var (h, я, _) = Жизнь();
            foreach (var p in h.people.Значения)
            {
                if (!б.знает_о_себе.Contains(p.id))
                    плохо.Add($"у {p.id} нет слов о себе");
                if (!б.знает_о_ком.Contains(p.id))
                    плохо.Add($"о {p.id} в доме нет ни одного слуха");
            }
            int реплик = 0;
            foreach (var герой in new[] { "оксана", "руслан" })
            {
                var (h2, я2, _) = Жизнь(3, герой);
                foreach (var с in h2.others(я2))
                    foreach (bool пролог in new[] { true, false })
                        foreach (var тема in б.Темы(пролог).Where(т => т.id != "метель"))
                            for (int раз = 0; раз < 3; раз++)
                            {
                                foreach (double доверие in new[] { 1.0, 3.0, 5.0 })
                                {
                                    с.trust[я2.id] = доверие;
                                    string ответ = б.Ответ(h2, я2, с, тема.id, пролог, new Слепок(я2.memory.Count), л, 3, раз)
                                                   + б.Приветствие(я2, с, 3, раз) + б.Прощание(я2, с, 3, раз);
                                    реплик++;
                                    if (Разметка(ответ))
                                    {
                                        плохо.Add($"в реплике осталась разметка ({с.id}, {тема.id}, герой {герой}): {ответ}");
                                        goto дальше;
                                    }
                                }
                            }
                дальше:;
            }
            // род: «{|а}» — по говорящему, «[|а]» — по герою
            var мужчина = h.people.Значения.First(p => p.sex != "ж");
            var женщина = h.people.Значения.First(p => p.sex == "ж");
            if (Беседы.Слова("{м|ж}/[м|ж]", мужчина, женщина) != "м/ж"
                || Беседы.Слова("{м|ж}/[м|ж]", женщина, мужчина) != "ж/м")
                плохо.Add("род в беседе перепутан: говорящий и герой меняются местами");
            слова_итог = $"{h.people.Ключи.Count()} жильцов со словами о себе и слухами; {реплик} реплик без разметки при двух героях";
        }

        // ---- 2. пролог — настоящий разговор ----
        string пролог_итог;
        {
            var (h, я, о) = Жизнь(4);
            var сергей = h.people["сергей"];
            double было = сергей.trust.Взять(я.id, 3.0);
            double часов = я.time_left;
            string? рассказ = null;
            for (int i = 0; i < 4 && рассказ is null; i++)
            {
                Действия.execute(h, я, "разговор", сергей);
                if (о.Рассказ() is { } р)
                    рассказ = р.говорит;
            }
            if (сергей.trust.Взять(я.id, 3.0) <= было)
                плохо.Add("поговорили с Сергеем до метели — доверие не выросло: беседа вхолостую");
            if (я.time_left >= часов)
                плохо.Add("беседа до метели не стоила времени");
            if (рассказ is null)
                плохо.Add("четыре беседы с Сергеем до метели — а про бункер ни слова: знатоки в прологе немы");
            пролог_итог = $"Сергей: доверие {Текст.G(Текст.Округлить(было, 2))} → {Текст.G(Текст.Округлить(сергей.trust.Взять(я.id, 3.0), 2))}"
                          + (рассказ is null ? "" : $"; рассказал: «{рассказ[..Math.Min(40, рассказ.Length)]}…»");
        }

        // ---- 3. слухи в метель — правда разговора ----
        string слухи_итог;
        {
            string? найдено = null;
            for (long зерно = 1; зерно <= 20 && найдено is null; зерно++)
            {
                var (h, я, _) = Жизнь(зерно);
                h.day = 3;
                var валя = h.people["валя"];
                var толик = h.people["толик"];
                валя.trust[я.id] = 6.0;
                я.trust[валя.id] = 6.0;
                Социальное.adjust(валя, толик.id, aware: 100);
                Социальное.note_signal(валя, толик.id, "еда", 12.0, 1.0);
                var до = new Слепок(я.memory.Count);
                Действия.execute(h, я, "разговор", валя);
                bool сказали = я.memory.Skip(до.памяти).Any(м => м.вид == Вид.СКАЗАЛИ && м.кто == толик.id);
                if (!сказали)
                    continue;
                string ответ = б.Ответ(h, я, валя, "слухи", false, до, л, зерно, 0);
                if (!ответ.Contains(толик.form("gen"), StringComparison.Ordinal))
                    плохо.Add($"Валя рассказала героине про запасы Толика — а в словах его нет: «{ответ}»");
                найдено = ответ;
            }
            if (найдено is null)
                плохо.Add("за двадцать зёрен разговор ни разу не передал героине, что Валя знает о Толике");
            слухи_итог = $"Валя: «{найдено}»";
        }

        // ---- 4. предупредить о метели ----
        string метель_итог;
        {
            var (h, я, _) = Жизнь(6);
            var п = Пролог.Из(ручки);
            var м = Магазин.Прочитать(Пути.Данные, каталог);
            var аркадий = h.people["аркадий"];
            var тамара = h.people["тамара"];
            var игорь = h.people["игорь"];
            игорь.trust[я.id] = 3.0;
            double еды_у_тамары = тамара.stock.Взять("еда", 0.0);
            double еды_у_игоря = игорь.stock.Взять("еда", 0.0);
            double полка = h.богатство_места(м.место);
            string а = б.Предупредить(h, я, аркадий, п, м, 6, 0);
            string т = б.Предупредить(h, я, тамара, п, м, 6, 0);
            string и = б.Предупредить(h, я, игорь, п, м, 6, 0);
            string снова = б.Предупредить(h, я, тамара, п, м, 6, 1);
            if (!а.Contains("говорил", StringComparison.Ordinal))
                плохо.Add($"Аркадий знал заранее — а ответил не «я ж говорил»: «{а}»");
            if (тамара.stock.Взять("еда", 0.0) <= еды_у_тамары || h.богатство_места(м.место) >= полка)
                плохо.Add("хозяйственная Тамара поверила — а не запаслась, или полка магазина не опустела");
            if (игорь.stock.Взять("еда", 0.0) != еды_у_игоря)
                плохо.Add("Игорь не поверил — а запасся");
            foreach (var с in new[] { аркадий, тамара, игорь })
                if (п.Подозрение(с.id) <= 0)
                    плохо.Add($"{с.id} услышал о метели от героини — и не задумался, откуда она знает");
            if (тамара.stock.Взять("еда", 0.0) > еды_у_тамары + 3 + 1e-9)
                плохо.Add("второе предупреждение Тамаре снова её запасло");
            метель_итог = $"Аркадий: «{а}» · Тамара: «{т}» (еды {Текст.G(еды_у_тамары)} → {Текст.G(тамара.stock.Взять("еда", 0.0))}) · "
                          + $"Игорь: «{и}» · снова: «{снова}»";
        }

        // ---- 5. болезнь в доме ----
        string болезнь_итог;
        {
            foreach (var список in Беседы.БОЛЕЗНЬ)
            {
                if (б.Болезнь(список).Count == 0)
                    плохо.Add($"о болезни нет слов в списке «{список}»");
                if (Беседы.По_отношению(список))
                    foreach (var отношение in б.отношения)
                        if (б.Болезнь(список, отношение).Count == 0)
                            плохо.Add($"о болезни нет слов в списке «{список}» для отношения «{отношение}»");
            }
            // пустой список уронил бы беседу — сказать это и дальше не жить
            if (плохо.Any(х => х.StartsWith("о болезни нет слов", StringComparison.Ordinal)))
            {
                болезнь_итог = "есть пустые списки — жизнь не гонялась";
                goto болезнь_конец;
            }
            var (h, я, о) = Жизнь(5);
            foreach (var id in б.болезнь_свои)
                if (h.get(id) is null)
                    плохо.Add($"свой взгляд на болезнь у «{id}» — такого жильца нет");
            h.day = 6;
            var з = о.заражение;
            void Болеют(params (string кто, Стадия стадия)[] кто)
            {
                var болезни = new System.Text.Json.Nodes.JsonObject();
                foreach (var (id, ст) in кто)
                    болезни[id] = new System.Text.Json.Nodes.JsonObject
                    {
                        ["стадия"] = ст.ToString(), ["с_дня"] = h.day, ["до_дня"] = h.day + 3,
                    };
                з.Разложить(new System.Text.Json.Nodes.JsonObject { ["болезни"] = болезни, ["посчитан_день"] = h.day - 1 });
            }
            static bool Назван(string текст, NPC p)
                => new[] { p.@short, p.form("gen"), p.form("dat") }.Any(ф => текст.Contains(ф, StringComparison.Ordinal));
            ВестиБолезни Вести(NPC с) => Эпидемия.Вести(h, с, я, з);
            string Ответ(NPC с, string тема) => б.Ответ(h, я, с, тема, false, new Слепок(я.memory.Count), л, 5, 0, Вести(с));
            bool Из(string список, string реплика, NPC с, string? отношение = null)
                => б.Болезнь(список, отношение).Select(т => Беседы.Слова(т, с, я)).Any(т => реплика.Contains(т, StringComparison.Ordinal));
            var нина = h.people["нина"];          // кв.18, пятый этаж
            var пётр = h.people["пётр"];          // кв.19, пятый этаж
            var аркадий = h.people["аркадий"];    // кв.1, первый этаж

            // никто не болен — темы нет, приветствие прежнее
            if (б.Темы(false, Эпидемия.В_доме(h, з)).Any(т => т.id == "болезнь"))
                плохо.Add("в доме никто не болен — а тема «о болезни» есть");
            if (б.Приветствие(я, нина, 5, 0, Вести(нина)) != б.Приветствие(я, нина, 5, 0))
                плохо.Add("никто не болен — а приветствие уже про болезнь");

            // заражённый ещё ничего не чувствует: ни он, ни соседи не знают
            Болеют(("пётр", Стадия.ЗАРАЖЁН));
            if (Эпидемия.В_доме(h, з) || Вести(нина).больные.Count > 0 || Вести(пётр).сам != Стадия.ЗДОРОВ)
                плохо.Add("Пётр только заражён и ничего не чувствует — а о его болезни уже знают");

            // Пётр болен: тема есть; Нина с его этажа знает, Аркадий с первого — нет
            Болеют(("пётр", Стадия.БОЛЕН));
            if (!б.Темы(false, Эпидемия.В_доме(h, з)).Any(т => т.id == "болезнь"))
                плохо.Add("Пётр болен — а темы «о болезни в доме» нет");
            if (б.Темы(true, Эпидемия.В_доме(h, з)).Any(т => т.id == "болезнь"))
                плохо.Add("до метели — а тема о болезни уже есть");
            string у_нины = Ответ(нина, "болезнь");
            string у_аркадия = Ответ(аркадий, "болезнь");
            if (!Вести(нина).больные.Contains(пётр) || !Назван(у_нины, пётр))
                плохо.Add($"Нина живёт на этаже Петра — а о его болезни не знает: «{у_нины}»");
            if (Вести(аркадий).больные.Contains(пётр) || Назван(у_аркадия, пётр))
                плохо.Add($"Аркадий с первого этажа назвал больного Петра с пятого — знать ему неоткуда: «{у_аркадия}»");
            if (!у_аркадия.Contains("Вектор", StringComparison.Ordinal))
                плохо.Add($"Аркадий двадцать лет на «Векторе» — а о болезни молчит о нём: «{у_аркадия}»");
            string привет_нины = б.Приветствие(я, нина, 5, 0, Вести(нина));
            if (!Из("приветствие", привет_нины, нина))
                плохо.Add($"в доме болезнь — а Нина встречает, как всегда: «{привет_нины}»");
            // осторожность — по тому же отношению: своему — свои слова, а не чужого
            double было = нина.trust.Взять(я.id, 3.0);
            нина.trust[я.id] = 5.0;
            string привет_своей = б.Приветствие(я, нина, 5, 0, Вести(нина));
            нина.trust[я.id] = было;
            if (!Из("приветствие", привет_своей, нина, "свой"))
                плохо.Add($"в доме болезнь, Нина героине своя — а встречает не своими словами: «{привет_своей}»");

            // тяжёлого Петра слышит весь подъезд; сам он — почти ничего, на любую тему
            Болеют(("пётр", Стадия.ТЯЖЕЛО));
            if (!Вести(аркадий).больные.Contains(пётр))
                плохо.Add("Пётр тяжело болен — а Аркадий через этажи его не слышит");
            string пётр_быт = Ответ(пётр, "быт");
            if (!Из("тяжело", б.Приветствие(я, пётр, 5, 0, Вести(пётр)), пётр) || !Из("тяжело", пётр_быт, пётр))
                плохо.Add($"Пётр тяжело болен — а говорит о быте как ни в чём не бывало: «{пётр_быт}»");

            // больная Нина — о себе
            Болеют(("нина", Стадия.БОЛЕН));
            string нина_больна = Ответ(нина, "болезнь");
            if (!Из("приветствие_больной", б.Приветствие(я, нина, 5, 0, Вести(нина)), нина)
                || !Из("сам_болен", нина_больна, нина))
                плохо.Add($"Нина больна — а говорит как здоровая: «{нина_больна}»");

            // больную героиню видно в дверях
            Болеют((я.id, Стадия.БОЛЕН));
            string видно = б.Приветствие(я, аркадий, 5, 0, Вести(аркадий));
            if (!Из("герой_болен", видно, аркадий))
                плохо.Add($"героиня больна — а Аркадий в дверях не заметил: «{видно}»");

            // умерших от болезни знает весь дом
            Болеют();
            var валя = h.people["валя"];
            валя.alive = false;
            валя.cause = Заражение.ПРИЧИНА;
            if (!Эпидемия.В_доме(h, з) || !Вести(аркадий).умерли.Contains(валя))
                плохо.Add("Валя умерла от болезни — а дом об этом не знает");
            string об_умерших = Ответ(аркадий, "болезнь");
            if (!об_умерших.Contains("одного", StringComparison.Ordinal) && !Назван(об_умерших, валя))
                плохо.Add($"Валя умерла от болезни — а Аркадий о ней ни слова: «{об_умерших}»");

            // разметки нет: два героя, все соседи, болезнь у них и у героя
            int реплик = 0;
            foreach (var герой in new[] { "оксана", "руслан" })
            {
                var (h2, я2, о2) = Жизнь(5, герой);
                h2.day = 6;
                var з2 = о2.заражение;
                var болезни = new System.Text.Json.Nodes.JsonObject();
                foreach (var (id, ст) in new[] { ("пётр", Стадия.ТЯЖЕЛО), ("нина", Стадия.БОЛЕН), (герой, Стадия.БОЛЕН) })
                    болезни[id] = new System.Text.Json.Nodes.JsonObject { ["стадия"] = ст.ToString(), ["с_дня"] = 6, ["до_дня"] = 9 };
                з2.Разложить(new System.Text.Json.Nodes.JsonObject { ["болезни"] = болезни, ["посчитан_день"] = 5 });
                var валя2 = h2.people["валя"];
                валя2.alive = false;
                валя2.cause = Заражение.ПРИЧИНА;
                foreach (var с in h2.others(я2).Where(p => p.alive))
                {
                    var в = Эпидемия.Вести(h2, с, я2, з2);
                    foreach (var тема in б.Темы(false, true))
                        for (int раз = 0; раз < 4; раз++)
                        {
                            string ответ = б.Ответ(h2, я2, с, тема.id, false, new Слепок(я2.memory.Count), л, 5, раз, в)
                                           + б.Приветствие(я2, с, 5, раз, в);
                            реплик++;
                            if (Разметка(ответ))
                            {
                                плохо.Add($"в реплике о болезни осталась разметка ({с.id}, {тема.id}, герой {герой}): {ответ}");
                                goto дальше_болезнь;
                            }
                        }
                }
            дальше_болезнь:;
            }
            // узел: в метель беседа знает, что знает сосед (приветствие, ответ, темы)
            string узел = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Годот"), "*.cs")
                                                      .Select(File.ReadAllText));
            var вызовы = System.Text.RegularExpressions.Regex.Matches(узел, @"_беседы\.(Приветствие|Ответ|Темы)\(([^;]*)")
                .Select(м => (что: м.Groups[1].Value, как: м.Groups[2].Value)).ToList();
            if (!вызовы.Any(х => х.что == "Приветствие" && х.как.Contains("Вести(")))
                плохо.Add("узел здоровается без вестей о болезни — в метель сосед встретит, как всегда");
            foreach (var в in вызовы.Where(х => х.что == "Ответ" && х.как.Contains(", false,") && !х.как.Contains("Вести(")))
                плохо.Add($"узел зовёт ответ в метель без вестей о болезни: _беседы.Ответ({в.как[..Math.Min(60, в.как.Length)]}…");
            foreach (var в in вызовы.Where(х => х.что == "Темы" && х.как.StartsWith("false", StringComparison.Ordinal)
                                                 && !х.как.Contains("Эпидемия.В_доме(")))
                плохо.Add("узел берёт темы метели без «о болезни в доме»");
            if (!вызовы.Any(х => х.что == "Темы" && х.как.Contains("Эпидемия.В_доме(")))
                плохо.Add("узел нигде не спрашивает, есть ли в доме болезнь, — темы о ней не будет");

            болезнь_итог = $"Нина о Петре: «{у_нины[..Math.Min(70, у_нины.Length)]}…»; Аркадий: «{у_аркадия[..Math.Min(70, у_аркадия.Length)]}…»; "
                           + $"{реплик} реплик о болезни без разметки";
        болезнь_конец:;
        }

        w($"  слова: {слова_итог}");
        w($"  пролог: {пролог_итог}");
        w($"  слухи: {слухи_итог}");
        w($"  метель: {метель_итог}");
        w($"  болезнь: {болезнь_итог}");
        return плохо;
    }
