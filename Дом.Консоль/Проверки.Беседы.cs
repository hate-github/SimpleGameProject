// Проверка бесед (решение автора: диалоги про быт и слухи, соседи в прологе;
// `Дом.Экран/Беседа.cs`, `data/разговоры.json`).
//
//  1. **Слова есть у всех.** У каждого жильца свои слова о себе (сдержанно
//     и откровенно) и слухи о нём; ни в одной реплике не остаётся разметки
//     рода ни при каком поле героя и говорящего.
//  2. **Пролог — настоящий разговор.** Беседа до метели — тот же
//     «разговор» дома: доверие растёт, и знаток может заговорить ещё
//     до метели (в следующей жизни — «поиск информации», ГДД 4).
//  3. **Слухи в метель — правда разговора.** Сосед, знающий чужие запасы
//     лучше героя, называет того, о ком разговор дома передал сведения.
//  4. **Предупредить о метели.** Знавший заранее — «я ж говорил»;
//     хозяйственный поверил и запасся (полка опустела); прочие не верят;
//     все запомнили, что герой что-то знал; второй раз — «уже говорил».

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Беседы_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var б = Беседы.Прочитать(Пути.Данные);
        var честный = new Скрипт(new Dictionary<Вопрос, string> { [Вопрос.СОВРАТЬ] = "сказать правду" });
        (House h, NPC я, Округа о) Жизнь(long зерно = 7, string кто = "оксана")
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, кто);
            var h = прогон.h;
            h.people[кто].решающий = честный;
            return (h, h.people[кто], Округа.У(h)!);
        }
        static bool Разметка(string s) => s.Contains('{') || s.Contains('}') || s.Contains('[') || s.Contains(']') || s.Contains('|');

        // ---- 1. слова есть у всех ----
        string слова_итог;
        {
            var (h, я, _) = Жизнь();
            foreach (var p in h.people.Значения)
            {
                if (!б.знает_о_себе.Contains(p.id))
                    плохо.Add($"у {p.id} нет слов о себе");
                if (!б.знает_о_ком.Contains(p.id))
                    плохо.Add($"о {p.id} в доме нет ни одного слуха");
            }
            int реплик = 0;
            foreach (var герой in new[] { "оксана", "руслан" })
            {
                var (h2, я2, _) = Жизнь(3, герой);
                foreach (var с in h2.others(я2))
                    foreach (bool пролог in new[] { true, false })
                        foreach (var тема in б.Темы(пролог).Where(т => т.id != "метель"))
                            for (int раз = 0; раз < 3; раз++)
                            {
                                foreach (double доверие in new[] { 1.0, 3.0, 5.0 })
                                {
                                    с.trust[я2.id] = доверие;
                                    string ответ = б.Ответ(h2, я2, с, тема.id, пролог, new Слепок(я2.memory.Count), л, 3, раз)
                                                   + б.Приветствие(я2, с, 3, раз) + б.Прощание(я2, с, 3, раз);
                                    реплик++;
                                    if (Разметка(ответ))
                                    {
                                        плохо.Add($"в реплике осталась разметка ({с.id}, {тема.id}, герой {герой}): {ответ}");
                                        goto дальше;
                                    }
                                }
                            }
                дальше:;
            }
            // род: «{|а}» — по говорящему, «[|а]» — по герою
            var мужчина = h.people.Значения.First(p => p.sex != "ж");
            var женщина = h.people.Значения.First(p => p.sex == "ж");
            if (Беседы.Слова("{м|ж}/[м|ж]", мужчина, женщина) != "м/ж"
                || Беседы.Слова("{м|ж}/[м|ж]", женщина, мужчина) != "ж/м")
                плохо.Add("род в беседе перепутан: говорящий и герой меняются местами");
            слова_итог = $"{h.people.Ключи.Count()} жильцов со словами о себе и слухами; {реплик} реплик без разметки при двух героях";
        }

        // ---- 2. пролог — настоящий разговор ----
        string пролог_итог;
        {
            var (h, я, о) = Жизнь(4);
            var сергей = h.people["сергей"];
            double было = сергей.trust.Взять(я.id, 3.0);
            double часов = я.time_left;
            string? рассказ = null;
            for (int i = 0; i < 4 && рассказ is null; i++)
            {
                Действия.execute(h, я, "разговор", сергей);
                if (о.Рассказ() is { } р)
                    рассказ = р.говорит;
            }
            if (сергей.trust.Взять(я.id, 3.0) <= было)
                плохо.Add("поговорили с Сергеем до метели — доверие не выросло: беседа вхолостую");
            if (я.time_left >= часов)
                плохо.Add("беседа до метели не стоила времени");
            if (рассказ is null)
                плохо.Add("четыре беседы с Сергеем до метели — а про бункер ни слова: знатоки в прологе немы");
            пролог_итог = $"Сергей: доверие {Текст.G(Текст.Округлить(было, 2))} → {Текст.G(Текст.Округлить(сергей.trust.Взять(я.id, 3.0), 2))}"
                          + (рассказ is null ? "" : $"; рассказал: «{рассказ[..Math.Min(40, рассказ.Length)]}…»");
        }

        // ---- 3. слухи в метель — правда разговора ----
        string слухи_итог;
        {
            string? найдено = null;
            for (long зерно = 1; зерно <= 20 && найдено is null; зерно++)
            {
                var (h, я, _) = Жизнь(зерно);
                h.day = 3;
                var валя = h.people["валя"];
                var толик = h.people["толик"];
                валя.trust[я.id] = 6.0;
                я.trust[валя.id] = 6.0;
                Социальное.adjust(валя, толик.id, aware: 100);
                Социальное.note_signal(валя, толик.id, "еда", 12.0, 1.0);
                var до = new Слепок(я.memory.Count);
                Действия.execute(h, я, "разговор", валя);
                bool сказали = я.memory.Skip(до.памяти).Any(м => м.вид == Вид.СКАЗАЛИ && м.кто == толик.id);
                if (!сказали)
                    continue;
                string ответ = б.Ответ(h, я, валя, "слухи", false, до, л, зерно, 0);
                if (!ответ.Contains(толик.form("gen"), StringComparison.Ordinal))
                    плохо.Add($"Валя рассказала героине про запасы Толика — а в словах его нет: «{ответ}»");
                найдено = ответ;
            }
            if (найдено is null)
                плохо.Add("за двадцать зёрен разговор ни разу не передал героине, что Валя знает о Толике");
            слухи_итог = $"Валя: «{найдено}»";
        }

        // ---- 4. предупредить о метели ----
        string метель_итог;
        {
            var (h, я, _) = Жизнь(6);
            var п = Пролог.Из(ручки);
            var м = Магазин.Прочитать(Пути.Данные, каталог);
            var аркадий = h.people["аркадий"];
            var тамара = h.people["тамара"];
            var игорь = h.people["игорь"];
            игорь.trust[я.id] = 3.0;
            double еды_у_тамары = тамара.stock.Взять("еда", 0.0);
            double еды_у_игоря = игорь.stock.Взять("еда", 0.0);
            double полка = h.богатство_места(м.место);
            string а = б.Предупредить(h, я, аркадий, п, м, 6, 0);
            string т = б.Предупредить(h, я, тамара, п, м, 6, 0);
            string и = б.Предупредить(h, я, игорь, п, м, 6, 0);
            string снова = б.Предупредить(h, я, тамара, п, м, 6, 1);
            if (!а.Contains("говорил", StringComparison.Ordinal))
                плохо.Add($"Аркадий знал заранее — а ответил не «я ж говорил»: «{а}»");
            if (тамара.stock.Взять("еда", 0.0) <= еды_у_тамары || h.богатство_места(м.место) >= полка)
                плохо.Add("хозяйственная Тамара поверила — а не запаслась, или полка магазина не опустела");
            if (игорь.stock.Взять("еда", 0.0) != еды_у_игоря)
                плохо.Add("Игорь не поверил — а запасся");
            foreach (var с in new[] { аркадий, тамара, игорь })
                if (п.Подозрение(с.id) <= 0)
                    плохо.Add($"{с.id} услышал о метели от героини — и не задумался, откуда она знает");
            if (тамара.stock.Взять("еда", 0.0) > еды_у_тамары + 3 + 1e-9)
                плохо.Add("второе предупреждение Тамаре снова её запасло");
            метель_итог = $"Аркадий: «{а}» · Тамара: «{т}» (еды {Текст.G(еды_у_тамары)} → {Текст.G(тамара.stock.Взять("еда", 0.0))}) · "
                          + $"Игорь: «{и}» · снова: «{снова}»";
        }

        w($"  слова: {слова_итог}");
        w($"  пролог: {пролог_итог}");
        w($"  слухи: {слухи_итог}");
        w($"  метель: {метель_итог}");
        return плохо;
    }
}
