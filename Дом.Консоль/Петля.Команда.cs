// Прожить петлю в консоли: жизнь за жизнью, с экраном смерти между ними.
//
// Это не игра, а первый способ увидеть петлю целиком: что переносится,
// как меняется монолог, когда появляется «уйти» и на какой жизни всё
// обрывается. Приёмка этапа 4 — человеческая («пять жизней подряд, вторая
// интереснее первой»), и её на себе проводят вот отсюда.
//
// Одна жизнь играется ровно так же, как командой `играть`: тот же живой
// журнал, тот же `Решающий.Человек`, тот же ввод. Мост с потоком
// (`Дом.Экран.Партия`) здесь не нужен — он для экрана, который не может
// ждать ответа в кадре; консоль ждать умеет.
//
// Петля о том, как жизнь прожита, не знает вовсе: ей отдают прожитый
// прогон, и она его читает.

using Дом.Экран;
using Дом.Ядро;

namespace Дом.Консоль;

public static class ПетляКоманда
{
    /// <summary>
    /// Прожить несколько жизней подряд.
    ///
    ///   Дом.Консоль петля --жизней 5 --кто оксана --зерно 42
    ///   Дом.Консоль петля --файл наследие.json     — продолжить сохранённое
    /// </summary>
    public static int Играть(Ключи к, TextReader? ввод = null, TextWriter? вывод = null)
    {
        ввод ??= new StreamReader(Console.OpenStandardInput(),
                                  new System.Text.UTF8Encoding(false));
        var поток = вывод ?? new StreamWriter(Console.OpenStandardOutput())
        {
            AutoFlush = true,
            NewLine = "\n",
        };
        void П(string s = "") => поток.Write(s + "\n");

        long зерно = к.Число("зерно") is long з ? з : 42;
        int дней = (int)(к.Число("дней") ?? 30);
        int жизней = (int)(к.Число("жизней") ?? 3);
        string кто = к.Строка("кто") ?? "оксана";
        string? файл = к.Строка("файл");

        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var наследие = файл is not null && File.Exists(файл)
            ? Хранение.Прочитать(файл)
            : new Наследие();
        var петля = new Дом.Ядро.Петля(наследие, ручки);

        for (int i = 0; i < жизней; i++)
        {
            if (петля.оборвалась)
            {
                Оборвалась(П, ввод, наследие);
                if (файл is not null)
                    Хранение.Записать(наследие, файл);
                if (!наследие.нирвана)
                    break;              // новый человек — это новая петля
            }

            var начало = петля.Начать();
            П();
            П(new string('═', 74));
            П($"ЖИЗНЬ {начало.номер}");
            П();
            П("  " + начало.монолог);
            Помнит(П, начало);
            П(new string('═', 74));

            // одна жизнь играется ровно так же, как командой `играть`:
            // консоль синхронна, и мост с потоком ей не нужен — он для
            // экрана, который не может ждать в кадре
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: дней);
            петля.Слушать(прогон, кто);
            var живой = new ЖивойЖурнал(к.Есть("подробно") ? 2 : 1, secrets: false,
                                        поток: поток) { дом = прогон.h };
            прогон.h.journal = живой;
            var сеанс = new Сеанс(прогон.h, кто);
            прогон.h.people[кто].решающий =
                new Человек(Игра.спросить(сеанс, живой, ввод, поток));

            try
            {
                прогон.run();
            }
            catch (ВыходИзИгры)
            {
                П("Вышел из игры.");
                поток.Flush();
                return 0;
            }

            var жизнь = петля.Закрыть(прогон, кто);
            ЭкранСмерти(П, жизнь, наследие, ручки);

            if (файл is not null)
                Хранение.Записать(наследие, файл);
        }

        поток.Flush();
        return 0;
    }

    /// <summary>Что герой помнит с прошлых жизней.</summary>
    private static void Помнит(Action<string> П, Начало н)
    {
        if (н.записи.Count == 0 && н.отголоски.Count == 0)
            return;
        П("");
        if (н.очки > 0)
            П($"  очков навыков: {н.очки}; карман на {н.карман}");
        if (н.можно_уйти)
            П("  (можно просто не вставать)");
        foreach (var з in н.записи.TakeLast(8))
            П($"  · {з.текст}");
        if (н.записи.Count > 8)
            П($"  · …и ещё {н.записи.Count - 8} заметок");
        foreach (var о in н.отголоски.TakeLast(4))
            П($"  ~ кв{о.квартира}: {о.текст}");
    }

    /// <summary>
    /// Экран смерти (ГДД 4): причина, сколько прожито, что перенесётся.
    ///
    /// Рассудок числом не показывается — только тем, из чего он сложился.
    /// Это не украшение: шкала, которую видно числом, перестаёт быть
    /// скрытой характеристикой и становится ещё одной полоской.
    /// </summary>
    private static void ЭкранСмерти(Action<string> П, Жизнь ж, Наследие н,
                                    РучкиПетли ручки)
    {
        П("");
        П(new string('─', 74));
        П(ж.дожил
          ? $"Жизнь {ж.номер}: {Дожил(ж)} до конца метели. {ж.прожито} дн."
          : $"Жизнь {ж.номер}: {ж.причина}. День {ж.день_смерти}.");
        П($"  очков за жизнь: {ж.начислено} (всего {н.очки}); "
          + $"лучшая жизнь — {н.рекорд} дн");
        if (ж.вклады.Count > 0)
        {
            var видно = ж.вклады.OrderByDescending(в => Math.Abs(в.сколько)).Take(4);
            П("  что осталось: " + string.Join(", ", видно.Select(в => в.за_что)));
        }
        if (ж.новые_записи.Count > 0)
            П($"  записано в телефон: {ж.новые_записи.Count}");
        if (ж.новые_отголоски.Count > 0)
            П($"  мест, которые будут помниться: {ж.новые_отголоски.Count}");
        П(new string('─', 74));
    }

    /// <summary>«Дожил» или «дожила»: род приходит вместе с итогом жизни.</summary>
    private static string Дожил(Жизнь ж) => Util.Vb(ж.пол, "дожил");

    /// <summary>
    /// Точка невозврата (ГДД 11): «Он перестал возвращаться».
    ///
    /// Поле для ввода слова — то самое граффити сумасшедшего пророка.
    /// Слова у нас пока нет нигде в мире, поэтому принимается любое
    /// непустое: место в механике занято, а граффити появится вместе
    /// с локациями.
    /// </summary>
    private static void Оборвалась(Action<string> П, TextReader ввод, Наследие н)
    {
        П("");
        П(new string('═', 74));
        П("Он перестал возвращаться.");
        П("");
        П("  Если ты видел слово — набери его.");
        П("  (пусто — начать новую петлю новым человеком: без памяти, без очков)");
        string слово = (ввод.ReadLine() ?? "").Trim();
        if (слово.Length > 0)
        {
            н.нирвана = true;
            П("  …и стало тихо. Рассудок больше не меняется.");
        }
        else
        {
            П("  Другой человек. Тот же дом. Ничего не помнит.");
        }
        П(new string('═', 74));
    }
}
