// Проверка гостей участка (просьба автора: «к нему в участок пришли люди,
// чтобы ограбить»; `Дом.Ядро/Петля/Участок.cs`, «гости» в `data/мир.json`).
//
//  1. **Ходки.** С полной тарой — замечают, и заметивший «выследят» раз
//     знает участок; с пустой — не замечает никто.
//  2. **Без героя.** Пришли — унесли долю каждого запаса поровну себе;
//     герой видит пропажу, когда придёт, — один раз.
//  3. **При герое.** Пришли — ничего не взято, стучат и ждут ответа;
//     «поделиться» — отдана доля, визит снят.
//  4. **Дверь.** Один ломится — держит чаще, трое — реже; выдержала —
//     ничего не взято, у них обида.
//  5. **Встретить.** С пистолетом против двоих отбивается чаще, чем
//     голыми руками против троих; отбился — у них битый и страх;
//     не отбился — избит и обобран. Насмерть — никто.
//  6. **Сами, ночью.** Выследивший приходит концом дня, к герою
//     в участке — визитом; боится героя — не приходит; по завалу — только
//     тот, у кого снегоступы.
//  7. **Сохранение.** Кто знает, что пропало и кто стучит — переживают
//     сейв; старый сейв без гостей читается.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Гости_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        const string КТО = "оксана";
        if (л.участок?.гости is not { } г)
        {
            плохо.Add("в мир.json у участка нет «гостей»");
            return плохо;
        }
        (House h, NPC я, Округа о) Жизнь(long зерно = 7)
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 40,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, КТО);
            прогон.h.day = 3;
            return (прогон.h, прогон.h.people[КТО], Округа.У(прогон.h)!);
        }
        void Нести(NPC я, string р, double сколько)
        {
            я.ноша ??= new Ноша();
            var вещи = Словари.Числа();
            вещи[р] = сколько;
            я.ноша.Положить(Тара.СУМКА, вещи, ручки);
        }
        // все видят и выслеживают с первой ходки — чтобы проверять, что дальше
        var зоркие = л.участок with { гости = г with { заметят = 1.0, выследят = 1 } };

        // ---- 1. ходки ----
        string ходки_итог;
        {
            var (h, я, _) = Жизнь();
            var у = new Участок(л.участок, 7);
            if (у.Ходка(h, я).Count > 0)
                плохо.Add("с пустыми руками к участку — а из окон заметили");
            Нести(я, "еда", 6);
            int заметили = 0, ходок = 0;
            while (у.знают.Count == 0 && ходок < 40)
            {
                заметили += у.Ходка(h, я).Count;
                ходок++;
            }
            if (у.знают.Count == 0)
                плохо.Add($"с полной тарой {ходок} ходок — и никто не выследил участок");
            ходки_итог = $"с полной тарой: за {ходок} ходок заметили {заметили} раз, выследил{(у.знают.Count > 1 ? "и" : "")} "
                         + string.Join(", ", у.знают.OrderBy(x => x, StringComparer.Ordinal));
        }

        // ---- 2. без героя ----
        {
            var (h, я, _) = Жизнь();
            var у = new Участок(зоркие, 7);
            var вор = h.people.Значения.First(p => p.id != я.id && p.здесь());
            double было_еды = у.В_кладовой("еда"), у_вора = вор.stock.Взять("еда", 0.0);
            у.Пришли(h, new[] { вор });
            double взято = было_еды - у.В_кладовой("еда");
            if (у.визит is not null)
                плохо.Add("героя в участке нет — а пришедшие стоят у двери и ждут ответа");
            if (Math.Abs(взято - Math.Floor(было_еды * г.унесут_доля)) > 1e-9
                || Math.Abs(вор.stock.Взять("еда", 0.0) - у_вора - взято) > 1e-9)
                плохо.Add($"без героя унесли еды {Текст.G(взято)} (а доля — {Текст.G(Math.Floor(было_еды * г.унесут_доля))}), "
                          + $"у вора прибавилось {Текст.G(вор.stock.Взять("еда", 0.0) - у_вора)}");
            var пропало = у.Пропажи();
            if (Math.Abs(пропало.Взять("еда", 0.0) - взято) > 1e-9)
                плохо.Add("пришёл в участок — а о пропаже кладовая молчит");
            if (у.Пропажи().Count != 0)
                плохо.Add("о пропаже сказано дважды");
        }

        // ---- 3. при герое: поделиться ----
        {
            var (h, я, _) = Жизнь();
            var у = new Участок(зоркие, 7);
            у.Пришёл(я);
            var гость = h.people.Значения.First(p => p.id != я.id && p.здесь());
            double было = у.В_кладовой("еда"), доверие = гость.trust.Взять(я.id, 3.0);
            у.Пришли(h, new[] { гость });
            if (у.визит is not { } в || в.кто.Count != 1 || у.В_кладовой("еда") < было - 1e-9)
                плохо.Add("герой в участке — а пришедшие не стучат (или взяли без ответа)");
            var итог = у.Встретить(h, я, Встреча.ОТДАТЬ);
            if (у.визит is not null)
                плохо.Add("ответил — а у двери всё ещё стучат");
            if (Math.Abs(было - у.В_кладовой("еда") - Math.Floor(было * г.отдать_доля)) > 1e-9 || итог.отбился)
                плохо.Add($"поделился — а отдано {Текст.G(было - у.В_кладовой("еда"))} (доля — {Текст.G(Math.Floor(было * г.отдать_доля))})");
            if (гость.trust.Взять(я.id, 3.0) <= доверие)
                плохо.Add("поделился — а взявший не помнит добра");
            if (!h.события.Any(с => с.вид == ВидСобытия.НАЛЁТ && с.кому == я.id && с.кто == гость.id))
                плохо.Add("к двери героя приходили — а событием дома это не стало");
        }

        // ---- 4 и 5. дверь и драка — сотня рассветов ----
        const int РАЗ = 200;
        (int держала, int взято) Дверь(int сколько)
        {
            var (h, я, _) = Жизнь();
            var идут = h.people.Значения.Where(p => p.id != я.id && p.здесь()).Take(сколько).ToList();
            int держала = 0, взято = 0;
            for (int i = 0; i < РАЗ; i++)
            {
                foreach (var p in идут.Append(я))
                {
                    p.health = 100;
                    p.injuries.Clear();
                }
                var у = new Участок(зоркие, 1000 + i);
                у.Пришёл(я);
                у.Пришли(h, идут);
                double было = у.запас_всего;
                var итог = у.Встретить(h, я, Встреча.НЕ_ОТКРЫВАТЬ);
                if (!итог.ворвались)
                {
                    держала++;
                    if (у.запас_всего < было - 1e-9)
                        плохо.Add("дверь выдержала — а из кладовой взяли");
                }
                if (у.запас_всего < было - 1e-9)
                    взято++;
            }
            if (идут.All(p => p.обида(я.id) <= 0))
                плохо.Add("не открыл — а у ломившихся ни обиды");
            return (держала, взято);
        }
        var дверь1 = Дверь(1);
        var дверь3 = Дверь(3);
        if (дверь1.держала <= дверь3.держала)
            плохо.Add($"дверь держит одного ({дверь1.держала} из {РАЗ}) не чаще, чем троих ({дверь3.держала})");

        (int отбился, int пятились, int унесли, double здоровье) Встретить(int сколько, Оружие чем)
        {
            var (h, я, _) = Жизнь();
            var идут = h.people.Значения.Where(p => p.id != я.id && p.здесь() && p.weapon == Оружие.НЕТ)
                .Take(сколько).ToList();
            int отбился = 0, пятились = 0, унесли = 0;
            double здоровье = 0;
            for (int i = 0; i < РАЗ; i++)
            {
                foreach (var p in идут.Append(я))
                {
                    p.health = 100;
                    p.injuries.Clear();
                }
                я.weapon = чем;
                if (Таблицы.ОГНЕСТРЕЛ.Contains(чем))
                {
                    я.ноша = null;
                    Нести(я, "патроны", 5);
                }
                var у = new Участок(зоркие, 5000 + i);
                у.Пришёл(я);
                у.Пришли(h, идут);
                double было = у.запас_всего;
                var итог = у.Встретить(h, я, Встреча.ВСТРЕТИТЬ);
                if (итог.отбился)
                    отбился++;
                if (итог.отбился && !итог.весть.Contains("сцепились", StringComparison.Ordinal)
                    && !итог.весть.Contains("выстрелил", StringComparison.Ordinal))
                    пятились++;
                if (у.запас_всего < было - 1e-9)
                {
                    унесли++;
                    if (итог.отбился)
                        плохо.Add("отбился — а из кладовой взяли");
                }
                здоровье += я.health;
                if (!я.alive || идут.Any(p => !p.alive || p.health <= 0))
                    плохо.Add("у двери участка кто-то погиб — а насмерть там не бьют");
            }
            if (отбился > 0 && идут.All(p => p.боится(я.id) <= 0))
                плохо.Add("отбился — а у битых ни страха");
            return (отбился, пятились, унесли, здоровье / РАЗ);
        }
        var с_пистолетом = Встретить(2, Оружие.ПИСТОЛЕТ);
        var голыми = Встретить(3, Оружие.НЕТ);
        if (с_пистолетом.отбился <= голыми.отбился + РАЗ / 5)
            плохо.Add($"с пистолетом против двоих отбился {с_пистолетом.отбился} из {РАЗ} — "
                      + $"не намного чаще, чем голыми руками против троих ({голыми.отбился})");
        if (с_пистолетом.пятились == 0)
            плохо.Add("с пистолетом в дверях — а попятиться не случилось ни разу");
        if (голыми.унесли == 0 || голыми.здоровье >= 99)
            плохо.Add("голыми руками против троих — и ни разу не избили и не обобрали");

        // ---- 6. сами, ночью ----
        string ночи_итог;
        {
            var (h, я, о) = Жизнь();
            var у = new Участок(зоркие, 11);
            Нести(я, "еда", 6);
            у.Ходка(h, я);
            я.ноша = null;
            у.Пришёл(я);
            int ночь = 3, пришли = -1;
            for (; ночь < 7 && пришли < 0; ночь++)
            {
                h.day = ночь;
                у.Конец_дня(h, я, о);
                if (у.визит is not null)
                    пришли = ночь;
            }
            if (у.визит is not { } в)
                плохо.Add($"выследили все {у.знают.Count} — а за четыре ночи никто не пришёл");
            else if (!у.знают.Contains(в.кто[0]) || в.кто.Count > 1 + г.с_собой)
                плохо.Add($"пришёл не выследивший или больше, чем зовут: {string.Join(", ", в.кто)}");
            // боятся героя — не идут
            var у2 = new Участок(зоркие, 11);
            Нести(я, "еда", 6);
            у2.Ходка(h, я);
            я.ноша = null;
            у2.Пришёл(я);
            foreach (var id in у2.знают)
                h.people[id].страх[я.id] = 100;
            for (int д = 3; д < 30; д++)
            {
                h.day = д;
                у2.Конец_дня(h, я, о);
            }
            if (у2.визит is not null)
                плохо.Add("боятся героя до смерти — а всё равно пришли");
            foreach (var id in у2.знают)
                h.people[id].страх[я.id] = 0;
            // по завалу — только в снегоступах
            int по_завалу = 0;
            var в_снегоступах = new HashSet<string>(StringComparer.Ordinal);
            for (int д = 8; д < 40; д++)
            {
                var у3 = new Участок(зоркие, 300 + д);
                h.day = 3;
                Нести(я, "еда", 6);
                у3.Ходка(h, я);
                я.ноша = null;
                у3.Пришёл(я);
                h.day = д;
                у3.Конец_дня(h, я, о);
                if (у3.визит is { } в3)
                {
                    по_завалу++;
                    if (о.Закрыто(h, h.people[в3.кто[0]], "участок"))
                        плохо.Add($"день {д}: к участку пришёл {в3.кто[0]} — а без снегоступов туда не пройти");
                    else
                        в_снегоступах.Add(в3.кто[0]);
                }
            }
            ночи_итог = $"выследили {у.знают.Count}, пришли на {(пришли < 0 ? "—" : пришли.ToString())}-ю ночь; "
                        + $"по завалу приходили {по_завалу} раз — "
                        + (в_снегоступах.Count == 0 ? "никто" : string.Join(", ", в_снегоступах.OrderBy(x => x, StringComparer.Ordinal)));
        }

        // ---- 7. сохранение ----
        {
            var (h, я, _) = Жизнь();
            var у = new Участок(зоркие, 7);
            Нести(я, "еда", 6);
            у.Ходка(h, я);
            я.ноша = null;
            var вор = h.people[у.знают.OrderBy(x => x, StringComparer.Ordinal).First()];
            у.Пришли(h, new[] { вор });          // без героя — пропажа
            у.Пришёл(я);
            у.Пришли(h, new[] { вор });          // при герое — стучат
            var о = у.Сложить();
            var у2 = new Участок(зоркие, 7);
            у2.Разложить(System.Text.Json.Nodes.JsonNode.Parse(о.ToJsonString())!.AsObject(), я);
            if (у2.знают.Count != у.знают.Count || у2.визит?.кто.FirstOrDefault() != вор.id
                || у2.Пропажи().Count == 0)
                плохо.Add("после сейва забылось, кто выследил, кто стучит или что пропало");
            о.Remove("гости");
            var у3 = new Участок(зоркие, 7);
            у3.Разложить(System.Text.Json.Nodes.JsonNode.Parse(о.ToJsonString())!.AsObject(), я);
            if (у3.знают.Count != 0 || у3.визит is not null)
                плохо.Add("старый сейв без гостей — а гости откуда-то есть");
        }

        w($"  ходки: {ходки_итог}");
        w($"  дверь из {РАЗ}: одного держит {дверь1.держала}, троих {дверь3.держала}");
        w($"  встретить из {РАЗ}: с пистолетом против двоих отбился {с_пистолетом.отбился} (из них попятились {с_пистолетом.пятились}), "
          + $"обобран {с_пистолетом.унесли}, здоровье после {Текст.G(Math.Round(с_пистолетом.здоровье))}; "
          + $"голыми руками против троих отбился {голыми.отбился}, обобран {голыми.унесли}, здоровье после {Текст.G(Math.Round(голыми.здоровье))}");
        w($"  сами: {ночи_итог}");
        return плохо;
    }
}
