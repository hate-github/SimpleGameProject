// Проверка инструментов и положения героя (задание автора, пп. 2 и 4).
//
//  1. **Каталог закрыт.** У каждого замка есть чем его взять; таблица
//     автора держится (навесной — болторез или молоток, дверной — отмычка
//     или монтировка, железная дверь — монтировка, ящик — монтировка или
//     топор); на каждой кладовой — замок из каталога; что лежит дома
//     и на верстаке — инструменты из каталога.
//  2. **Одно покупается другим.** На навесном замке болторез тише
//     и быстрее молотка — зато молоток есть дома у всех, а болторез
//     только на чужом верстаке. Инструмент, лучший во всём и лежащий дома,
//     сделал бы выбор пустым.
//  3. **Голыми руками не ломают.** Без инструмента `Взлом.чем` — ничего;
//     молоток, лежащий дома, в подвале не поможет — его берут с собой;
//     из двух подходящих берётся самый тихий; оружие-топор при герое
//     само, но навесной замок им не взять.
//  4. **Инструмент решает часы и шум.** Болторезом взлом короче, и стук
//     за шестьдесят взломов слышат реже, чем молоток.
//  5. **Петля даёт снаряжение** — дома то, что сказано в каталоге,
//     с собой ничего; у соседей его нет. В снимок и сейв оно не входит,
//     как и шум взлома и беспамятство.
//  6. **Положение героя читается из тела и поимок**: норма, подозревают,
//     застали, скрутили, ранен, без сознания — и каждое запрещает то,
//     что должно.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Инструменты_(Action<string> w)
    {
        var плохо = new List<string>();
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        static House Дом_(long зерно = 1)
            => new Прогон(Пути.Данные, seed: зерно, days: 1,
                          журнал: new Журнал(0, false, TextWriter.Null)).h;

        // ---- 1. каталог закрыт ----
        foreach (var (замок, имя) in каталог.замки)
            if (!каталог.Берут(замок).Any())
                плохо.Add($"«{имя}» нечем взять — ни один инструмент его не берёт");
        var таблица = new (string замок, string[] чем)[]
        {
            ("навесной", new[] { "болторез", "молоток" }),
            ("дверной", new[] { "отмычка", "монтировка" }),
            ("железная_дверь", new[] { "монтировка" }),
            ("ящик", new[] { "монтировка", "топор" }),
        };
        foreach (var (замок, чем) in таблица)
        {
            var берут = каталог.Берут(замок).Select(и => и.id).ToHashSet(StringComparer.Ordinal);
            foreach (string id in чем)
                if (!берут.Contains(id))
                    плохо.Add($"по таблице автора «{замок}» берут {id}, а в каталоге — нет");
        }
        var h0 = Дом_();
        foreach (var к in h0.кладовые.Значения)
            if (каталог.Замок(к) is not string з || !каталог.замки.ContainsKey(з))
                плохо.Add($"на {к.id} нет замка из каталога");
        if (каталог.Дома("оксана").Count == 0)
            плохо.Add("дома у героя нет ни одного инструмента — ломать нечем никогда");
        if (каталог.верстак.Count == 0)
            плохо.Add("на верстаке пусто — болторезу неоткуда взяться");

        // ---- 2. одно покупается другим ----
        var болторез = каталог.все["болторез"].Берёт("навесной")!;
        var молоток = каталог.все["молоток"].Берёт("навесной")!;
        if (болторез.шум >= молоток.шум || болторез.часы >= молоток.часы)
            плохо.Add("болторез на навесном замке не тише и не быстрее молотка — зачем он");
        // и сам взлом считает часы по инструменту, а не одни на всех
        if (Взлом.часы(h0, болторез) >= Взлом.часы(h0, молоток))
            плохо.Add($"взлом болторезом идёт {Взлом.часы(h0, болторез)} ч, молотком — "
                      + $"{Взлом.часы(h0, молоток)}: инструмент не решает, сколько возиться");
        if (каталог.Дома("оксана").Contains("болторез", StringComparer.Ordinal))
            плохо.Add("болторез лежит дома — тихий и быстрый взлом даром, выбора нет");
        if (!каталог.Дома("оксана").Contains("молоток", StringComparer.Ordinal))
            плохо.Add("молотка дома нет — а он в любой хрущёвке");
        foreach (var и in каталог.все.Values)
        {
            if (и.Берёт("навесной") is not { } п || и.id == "болторез")
                continue;
            if (п.шум <= болторез.шум && п.часы <= болторез.часы
                && каталог.Дома("оксана").Contains(и.id, StringComparer.Ordinal))
                плохо.Add($"{и.имя} лежит дома и берёт навесной не хуже болтореза во всём");
        }

        // ---- 3. голыми руками не ломают ----
        {
            var h = Дом_();
            var я = h.people["оксана"];
            var погреб = h.кладовые["погреб1"];
            я.weapon = Оружие.НЕТ;
            я.снаряжение = null;
            if (Взлом.чем(я, погреб, каталог) is not null)
                плохо.Add("без снаряжения вовсе нашлось, чем ломать");
            я.снаряжение = new Снаряжение(каталог.Дома(я.id));
            if (Взлом.чем(я, погреб, каталог) is not null)
                плохо.Add("молоток лежит дома, а в подвале им ломают");
            if (!я.снаряжение.Взять("молоток"))
                плохо.Add("молоток из дома не взять");
            if (Взлом.чем(я, погреб, каталог)?.инструмент.id != "молоток")
                плохо.Add("молоток взят с собой, а ломать им нельзя");
            я.снаряжение.Подобрать("болторез");
            if (Взлом.чем(я, погреб, каталог)?.инструмент.id != "болторез")
                плохо.Add("при себе молоток и болторез, а взят не самый тихий");
            if (!я.снаряжение.Положить("молоток") || !я.снаряжение.дома.Contains("молоток"))
                плохо.Add("молоток не положить обратно домой");
            var голый = new Снаряжение();
            я.снаряжение = голый;
            я.weapon = Оружие.ТОПОР;
            if (Взлом.чем(я, погреб, каталог) is not null)
                плохо.Add("топором у пояса ломают навесной замок — по таблице нельзя");
            if (!голый.При_себе(я, каталог).Contains("топор", StringComparer.Ordinal))
                плохо.Add("топор у пояса не считается инструментом при себе");
        }

        // ---- 4. инструмент решает часы и шум ----
        string шум_итог;
        {
            int слышат(string инструмент)
            {
                int всего = 0;
                var и = каталог.все[инструмент];
                var п = и.Берёт("навесной")!;
                for (int i = 0; i < 60; i++)
                {
                    var h = Дом_(700 + i);
                    var я = h.people["оксана"];
                    я.time_left = 16.0;
                    double было = я.time_left;
                    var попытка = Взлом.попытка(h, я, h.кладовые["погреб1"], ручки, и, п);
                    if (Math.Abs((было - я.time_left) - Взлом.часы(h, п)) > 1e-9)
                        плохо.Add($"{и.имя}: взлом занял {было - я.time_left} ч, "
                                  + $"а должен {Взлом.часы(h, п)}");
                    всего += попытка.слышали?.Count ?? 0;
                }
                return всего;
            }
            int от_молотка = слышат("молоток"), от_болтореза = слышат("болторез");
            if (от_болтореза >= от_молотка)
                плохо.Add($"болторез слышат не реже молотка: {от_болтореза} против {от_молотка}");
            шум_итог = $"молоток слышали {от_молотка} раз, болторез {от_болтореза} (на 60 взломов)";
        }

        // ---- 5. петля даёт снаряжение, мимо снимка и сейва ----
        {
            var прогон = new Прогон(Пути.Данные, seed: 5, days: 1,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            var петля = new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог);
            string до = Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(прогон.h));
            string сейв_до = Дом.Ядро.Сохранение.сохранить(прогон.h).ToJsonString();
            петля.Слушать(прогон, "оксана");
            var я = прогон.h.people["оксана"];
            if (я.снаряжение is not { } с)
                плохо.Add("петля не дала герою снаряжения");
            else
            {
                if (!с.дома.SequenceEqual(каталог.Дома("оксана").OrderBy(x => x, StringComparer.Ordinal)))
                    плохо.Add($"дома у героя {string.Join(",", с.дома)}, а по каталогу "
                              + string.Join(",", каталог.Дома("оксана")));
                if (с.с_собой.Count != 0)
                    плохо.Add("герой проснулся с инструментом в руках — его берут дома");
            }
            foreach (var p in прогон.h.others(я))
                if (p.снаряжение is not null)
                    плохо.Add($"снаряжение досталось соседу {p.id}");
            я.снаряжение?.Взять("молоток");
            я.шум_взлома = new ШумВзлома(прогон.h.day, 2);
            я.без_сознания = прогон.h.day;
            if (Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(прогон.h)) != до)
                плохо.Add("снаряжение, шум взлома или беспамятство попали в снимок дома");
            if (Дом.Ядро.Сохранение.сохранить(прогон.h).ToJsonString() != сейв_до)
                плохо.Add("снаряжение, шум взлома или беспамятство попали в сейв");
        }

        // ---- 6. положение героя ----
        var видели = new SortedSet<string>(StringComparer.Ordinal);
        {
            var h = Дом_();
            var я = h.people["оксана"];
            void Ждём(Положение ждём, string когда)
            {
                var есть = Положения.Героя(h, я, ручки);
                видели.Add(есть.ToString());
                if (есть != ждём)
                    плохо.Add($"{когда}: положение {есть}, а ждали {ждём}");
            }
            я.health = 90;
            я.injuries.Clear();
            Ждём(Положение.НОРМА, "целый герой");
            я.шум_взлома = new ШумВзлома(h.day, 1);
            Ждём(Положение.ПОДОЗРЕВАЮТ, "стук сегодня слышали");
            я.шум_взлома = new ШумВзлома(h.day - 1, 3);
            Ждём(Положение.НОРМА, "стук слышали вчера");
            я.застали = new Застали("игорь", "погреб1", Array.Empty<string>(), h.day, 0);
            Ждём(Положение.ЗАСТАЛИ, "застали впервые");
            я.застали = new Застали("игорь", "погреб1", Array.Empty<string>(), h.day, 1);
            Ждём(Положение.СКРУТИЛИ, "застали снова");
            я.застали = null;
            я.injuries.Add("ушиб руки");
            Ждём(Положение.НОРМА, "одна ссадина на руке");
            я.injuries.Add("порез руки");
            Ждём(Положение.РАНЕН, "две раны");
            я.injuries.Clear();
            я.injuries.Add("перелом ноги");
            Ждём(Положение.РАНЕН, "перелом");
            я.injuries.Clear();
            я.health = ручки["ранен_ниже"] - 1;
            Ждём(Положение.РАНЕН, "здоровье ниже порога ран");
            я.health = ручки["без_сознания_ниже"] - 1;
            Ждём(Положение.БЕЗ_СОЗНАНИЯ, "здоровье ниже порога беспамятства");
            я.health = 90;
            я.без_сознания = h.day;
            Ждём(Положение.БЕЗ_СОЗНАНИЯ, "избили до беспамятства сегодня");
            я.без_сознания = h.day - 1;
            Ждём(Положение.НОРМА, "беспамятство было вчера");

            foreach (var п in Enum.GetValues<Положение>())
            {
                bool ломать = Положения.Можно_ломать(п);
                bool ходить = Положения.Может_ходить(п);
                if (ломать != (п is Положение.НОРМА or Положение.ПОДОЗРЕВАЮТ))
                    плохо.Add($"{п}: ломать замок {(ломать ? "можно" : "нельзя")} — не так");
                if (ходить == (п is Положение.БЕЗ_СОЗНАНИЯ or Положение.СКРУТИЛИ))
                    плохо.Add($"{п}: ходить {(ходить ? "можно" : "нельзя")} — не так");
                if (п != Положение.НОРМА && п.Текст().Length == 0)
                    плохо.Add($"{п}: положение не сказано словами");
            }
        }
        if (видели.Count != Enum.GetValues<Положение>().Length)
            плохо.Add($"положений видели {видели.Count} из {Enum.GetValues<Положение>().Length}");

        w($"  каталог: {каталог.все.Count} инструментов на {каталог.замки.Count} замка, "
          + $"дома — {string.Join(", ", каталог.Дома("оксана"))}, на верстаке — "
          + string.Join(", ", каталог.верстак));
        w($"  шум: {шум_итог}");
        w($"  положение: все {видели.Count} видов, и каждое запрещает своё");
        return плохо;
    }
}
