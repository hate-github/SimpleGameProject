// Проверка шума взлома (`Дом.Ядро/Петля/Взлом.cs`): взлом — шаг отчаянный.
//
// Автор сказал прямо: «нельзя просто так взять и взломать чей-то погреб;
// если меня слышали в первые дни, должно случиться что-то плохое». Слышат
// и ловят по правилам дома, а не по особому правилу для игрока:
//
//  1. **Слышат как любой шум** (ГДД 13): в буран дом глохнет, уехавший
//     не слышит вовсе, гараж за домом слышно хуже подвала. Кто услышал,
//     у того в сводке дня стоит «в подвале долго били по замку» — стук,
//     а не имя: кто ломает, из квартиры не видно.
//  2. **В первые дни спускаются.** Пока жизнь похожа на прежнюю
//     (нормальность высокая), на стук выходят и вора застают; когда
//     нормальность падает к своему полу, выходят куда реже. Застали —
//     попытка сорвана: замок цел, часы ушли, поимка записана на героя,
//     и пришёл тот, кто слышал.
//  3. **Поимка разбирается ходом дома** (`Действия.САМ`), а не при взломе:
//     там дом спит на вопросе героя, и спросить его «бежать?» нечем.
//     Всё как у вора, пойманного в квартире: доверие падает, в памяти
//     пришедшего «поймал вора», в доме происшествие, поимок +1, вторая
//     зовёт суд дома. Вопрос «бежать?» приходит герою — с тем, кто
//     застал, и с той кладовой.
//  4. **Запись о поимке — не состояние мира**: её нет ни в снимке,
//     ни в сейве, как кармана и ноши. Вчерашняя запись не разбирается.
//  5. **Второй раз — не как первый** (задание автора, п. 2). Раньше после
//     первой поимки нормальность дома падала, и на повторный стук выходили
//     реже: сосед «переставал реагировать». Теперь дом, который помнит
//     героя вором, спускается не реже, чем в первые дни, даже одичав;
//     а если стук сегодня уже слышали — чаще. Пойманного снова держат:
//     вопрос «сдаться или драться» вместо «бежать», часы уходят, побои;
//     пойманного в третий раз и слабого — до беспамятства, и день для
//     него кончился.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Застали_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        static House Дом_(long зерно)
            => new Прогон(Пути.Данные, seed: зерно, days: 1,
                          журнал: new Журнал(1, false, TextWriter.Null)).h;
        const int СЕРИЯ = 60;
        const string СТУК = "в подвале долго били по замку";
        // ломают молотком: он громкий, и его слышно
        var молоток = Инструменты.Прочитать(Пути.Данные).все["молоток"];
        var приём = молоток.Берёт("навесной")!;

        // ---- 1 и 2. кто слышал и кто спустился ----
        (int слышали, int застали) Серия(string имя, string кладовая, Action<House> как)
        {
            int слышали = 0, застали = 0;
            for (int i = 0; i < СЕРИЯ; i++)
            {
                var h = Дом_(500 + i);
                как(h);
                var я = h.people["оксана"];
                var к = h.кладовые[кладовая];
                double часы = Взлом.часы(h, приём);
                я.time_left = 16.0;
                var п = Взлом.попытка(h, я, к, ручки, молоток, приём);
                if (п.слышали is null)
                {
                    плохо.Add($"{имя}: попытка не сказала, кто слышал");
                    break;
                }
                слышали += п.слышали.Count;
                if (Math.Abs(я.time_left - (16.0 - часы)) > 1e-9)
                {
                    плохо.Add($"{имя}: попытка заняла {16.0 - я.time_left} ч, а должна {часы}");
                    break;
                }
                foreach (string id in п.слышали)
                {
                    var p = h.get(id);
                    if (p is null || p.away)
                        плохо.Add($"{имя}: стук услышал {id}, которого нет дома");
                    else if (к.вид == ВидКладовой.ПОГРЕБ
                             && (!h.ожидает.сводка.Есть(id)
                                 || !h.ожидает.сводка[id].Contains(СТУК, StringComparer.Ordinal)))
                        плохо.Add($"{имя}: {id} слышал стук, а в его сводке дня его нет");
                }
                if (п.застал is null)
                {
                    if (я.застали is not null)
                        плохо.Add($"{имя}: никто не спустился, а поимка записана");
                    continue;
                }
                застали++;
                if (п.удалась || к.вскрыта)
                    плохо.Add($"{имя}: героя застали, а замок всё-таки сорван");
                if (!п.слышали.Contains(п.застал, StringComparer.Ordinal))
                    плохо.Add($"{имя}: спустился {п.застал}, который стука не слышал");
                if (я.застали is not { } з || !string.Equals(з.кто, п.застал, StringComparison.Ordinal)
                    || !string.Equals(з.кладовая, к.id, StringComparison.Ordinal) || з.день != h.day)
                    плохо.Add($"{имя}: застали, а записи о поимке нет или она о другом");
            }
            return (слышали, застали);
        }

        var рано = Серия("первые дни", "погреб1", _ => { });
        var буран = Серия("буран", "погреб1", h => h.режим = Режим.БУРАН);
        var пусто = Серия("дом пуст", "погреб1", h =>
        {
            foreach (var p in h.alive())
                p.away = true;
        });
        var поздно = Серия("одичавший дом", "погреб1", h =>
        {
            foreach (var p in h.alive())
                p.normalcy = p.нормальность_пол;
        });
        var гараж = Серия("гараж", "гараж13", _ => { });
        // дом помнит героя вором и уже одичал после происшествия
        var помнят = Серия("после поимки", "погреб1", h =>
        {
            var я = h.people["оксана"];
            я.поймали = 1;
            foreach (var p in h.others(я))
            {
                p.memory.Add(new Память { день = h.day, вид = Вид.СЛЫШАЛ_О_ВОРЕ, кто = я.id });
                p.normalcy = Math.Max(p.нормальность_пол, p.normalcy - 0.3);
            }
        });
        var настороже = Серия("стук уже слышали", "погреб1", h =>
            h.people["оксана"].шум_взлома = new ШумВзлома(h.day, 1));

        if (рано.застали == 0)
            плохо.Add($"за {СЕРИЯ} взломов в первые дни не спустился никто — "
                      + "взлом ничем не грозит");
        if (поздно.застали >= рано.застали)
            плохо.Add($"в одичавшем доме на стук выходят не реже ({поздно.застали}), "
                      + $"чем в первые дни ({рано.застали}) — нормальность ни при чём");
        if (буран.слышали * 2 >= рано.слышали)
            плохо.Add($"в буран стук слышат почти как в тишину: {буран.слышали} против {рано.слышали}");
        if (пусто.слышали != 0 || пусто.застали != 0)
            плохо.Add($"в пустом доме стук услышали {пусто.слышали} раз");
        if (гараж.слышали >= рано.слышали)
            плохо.Add($"гараж за домом слышно не хуже подвала: {гараж.слышали} против {рано.слышали}");
        if (помнят.застали < рано.застали)
            плохо.Add($"после поимки на стук выходят реже ({помнят.застали}), чем в первые дни "
                      + $"({рано.застали}) — сосед «перестал реагировать»");
        if (настороже.застали <= рано.застали)
            плохо.Add($"стук сегодня уже слышали, а спускаются не чаще ({настороже.застали} "
                      + $"против {рано.застали}) — дом не настороже");

        // ---- 3. поимка разбирается ходом дома ----
        string поимка_итог = "—";
        {
            House? h = null;
            NPC? я = null;
            for (int i = 0; i < 200 && я?.застали is null; i++)
            {
                h = Дом_(900 + i);
                я = h.people["оксана"];
                я.time_left = 16.0;
                Взлом.попытка(h, я, h.кладовые["погреб1"], ручки, молоток, приём);
            }
            if (h is null || я?.застали is null)
                плохо.Add("за двести взломов героя ни разу не застали — поимку проверять не на чем");
            else
            {
                var ловец = h.get(я.застали.кто)!;
                ловец.weapon = Оружие.НЕТ;        // без ствола: «бежать?» спросят героя
                // запись о поимке — не состояние мира
                string с_записью = Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(h));
                string сейв_с = Дом.Ядро.Сохранение.сохранить(h).ToJsonString();
                var запись = я.застали;
                я.застали = null;
                string без_записи = Дом.Ядро.Снимок.Текстом(Дом.Ядро.Снимок.Собранный(h));
                string сейв_без = Дом.Ядро.Сохранение.сохранить(h).ToJsonString();
                я.застали = запись;
                if (!string.Equals(с_записью, без_записи, StringComparison.Ordinal))
                    плохо.Add("запись о поимке попала в снимок дома");
                if (!string.Equals(сейв_с, сейв_без, StringComparison.Ordinal))
                    плохо.Add("запись о поимке попала в сейв");

                double доверие = ловец.trust.Взять(я.id, 3.0);
                int поймали = я.поймали, происшествий = h.incidents;
                var спросили = new List<ВопросИгроку>();
                я.решающий = new Человек((ВопросИгроку в) =>
                {
                    спросили.Add(в);
                    return в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ ? ВопросИгроку.САМ : 1;
                });
                if (!Действия.choose_and_do(h, я))
                    плохо.Add("ход «сам» кончил герою день — поимка не разобралась");
                if (я.застали is not null)
                    плохо.Add("поимку разобрали, а запись осталась");
                // доверие падает на всю цену поимки, а не на один суд дома:
                // порча, зануляющая саму поимку, оставляет его на полпути
                double стало = ловец.trust.Взять(я.id, 3.0);
                if (стало > Math.Max(0.0, доверие - 3.5))
                    плохо.Add($"{ловец.@short} застал вора, а доверие упало только "
                              + $"{доверие:F1} → {стало:F1}");
                if (ловец.hate.Взять(я.id, 0.0) < h.B["ненависть_за_кражу"] * 0.5)
                    плохо.Add($"{ловец.@short} застал вора, а злости всего "
                              + $"{ловец.hate.Взять(я.id, 0.0):F0}");
                if (!ловец.memory.Any(м => м.вид == Вид.ПОЙМАЛ_ВОРА
                                           && string.Equals(м.кто, я.id, StringComparison.Ordinal)))
                    плохо.Add("пришедший не запомнил, кого поймал");
                if (я.поймали != поймали + 1)
                    плохо.Add($"поимок у героя {я.поймали}, а было {поймали}");
                if (h.incidents != происшествий + 1)
                    плохо.Add("поимка у кладовой не стала происшествием в доме");
                var бежать = спросили.FirstOrDefault(в => в.вопрос == Вопрос.БЕЖАТЬ_ОТ_ХОЗЯИНА);
                if (бежать is null)
                    плохо.Add("героя не спросили, бежать ли, — за него решили");
                else
                {
                    if (!string.Equals(бежать.с_кем, ловец.id, StringComparison.Ordinal))
                        плохо.Add($"в вопросе «бежать?» не тот, кто застал: {бежать.с_кем}");
                    if (бежать.суть?.что is not Кладовая кл
                        || !string.Equals(кл.id, "погреб1", StringComparison.Ordinal))
                        плохо.Add("в вопросе «бежать?» не сказано, у какой кладовой застали");
                    var сцена = Дом.Экран.Разговор.Прочитать(h, я, бежать);
                    if (!сцена.кто.Contains(ловец.name, StringComparison.Ordinal))
                        плохо.Add($"окно вопроса не называет того, кто застал: «{сцена.кто}»");
                    if (!сцена.что.Contains("погреба кв.1", StringComparison.Ordinal))
                        плохо.Add($"окно вопроса не говорит, где застали: «{сцена.что}»");
                }
                поимка_итог = $"{ловец.@short} застал у погреба кв.1: доверие "
                              + $"{доверие:F1} → {ловец.trust.Взять(я.id, 3.0):F1}, "
                              + $"поимок {я.поймали}";

                // вторая поимка зовёт суд дома
                я.застали = new Застали(ловец.id, "погреб1", System.Array.Empty<string>(), h.day);
                Взлом.разобрать(h, я);
                if (h.приговор_нужен is null && я.здесь())
                    плохо.Add("вторая поимка не позвала суд дома");

                // вчерашняя запись не разбирается: она уже прожита
                int поймали_вчера = я.поймали;
                int происшествий_вчера = h.incidents;
                я.застали = new Застали(ловец.id, "погреб1", System.Array.Empty<string>(), h.day - 1);
                Взлом.разобрать(h, я);
                if (я.застали is not null)
                    плохо.Add("вчерашняя запись о поимке осталась");
                if (я.поймали != поймали_вчера || h.incidents != происшествий_вчера)
                    плохо.Add("вчерашнюю поимку разобрали сегодня заново");
            }
        }

        // ---- 5. снова пойманного держат ----
        string снова_итог = "—";
        (House h, NPC я)? Поймать(int поймали, double здоровье, long с)
        {
            for (int i = 0; i < 200; i++)
            {
                var h = Дом_(с + i);
                var я = h.people["оксана"];
                я.поймали = поймали;
                я.health = здоровье;
                foreach (var p in h.others(я))
                    p.memory.Add(new Память { день = h.day, вид = Вид.СЛЫШАЛ_О_ВОРЕ, кто = я.id });
                я.time_left = 16.0;
                Взлом.попытка(h, я, h.кладовые["погреб1"], ручки, молоток, приём);
                if (я.застали is not null)
                {
                    h.get(я.застали.кто)!.weapon = Оружие.НЕТ;   // без ствола
                    return (h, я);
                }
            }
            return null;
        }
        List<ВопросИгроку> Разобрать_сдавшись(House h, NPC я)
        {
            var спросили = new List<ВопросИгроку>();
            я.решающий = new Человек((ВопросИгроку в) =>
            {
                спросили.Add(в);
                return в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ ? ВопросИгроку.САМ : 0;   // 0 — «сдаться»
            });
            Действия.choose_and_do(h, я);
            return спросили;
        }
        if (Поймать(1, 90, 1300) is { } второй)
        {
            var (h, я) = второй;
            var з = я.застали!;
            if (з.уровень < 1)
                плохо.Add("поймали второй раз, а уровень поимки прежний");
            if (з.слышали.Count >= 2 && (з.держат is null || з.держат.Count == 0))
                плохо.Add("стук слышали несколько человек, а держать не позвали никого");
            double часы = я.time_left, здоровье = я.health;
            var спросили = Разобрать_сдавшись(h, я);
            if (спросили.Any(в => в.вопрос == Вопрос.БЕЖАТЬ_ОТ_ХОЗЯИНА))
                плохо.Add("поймали второй раз — а спрашивают «бежать?», как в первый");
            var сдаться = спросили.FirstOrDefault(в => в.вопрос == Вопрос.СДАТЬСЯ);
            if (сдаться is null)
                плохо.Add("поймали второй раз — героя не держат (не спросили, сдаться ли)");
            else if (!string.Equals(сдаться.с_кем, з.кто, StringComparison.Ordinal)
                     || сдаться.суть?.тема != "поймали")
                плохо.Add("в вопросе «сдаться?» не тот, кто держит, или не сказано, за что");
            double ушло = часы - я.time_left;
            if (ушло + 1e-9 < Math.Min(ручки["взлом_скрутили_часы"], часы))
                плохо.Add($"героя держали, а часов ушло {ушло:F2}");
            if (я.health > здоровье - ручки["взлом_побои"] + 1e-9)
                плохо.Add($"героя держали, а не побили: здоровье {здоровье:F0} → {я.health:F0}");
            if (!я.injuries.Contains("ушибы", StringComparer.Ordinal))
                плохо.Add("побили, а ушибов нет");
            снова_итог = $"второй раз — держат ({(з.держат?.Count ?? 0) + 1} чел.), "
                         + $"ушло {ушло:F1} ч, здоровье {здоровье:F0} → {я.health:F0}";
        }
        else
            плохо.Add("за двести взломов после поимки героя не застали ни разу");
        if (Поймать(2, 30, 1500) is { } третий)
        {
            var (h, я) = третий;
            Разобрать_сдавшись(h, я);
            if (я.без_сознания != h.day || я.time_left != 0.0)
                плохо.Add($"третья поимка слабого героя — а он в сознании и день идёт "
                          + $"(здоровье {я.health:F0}, часов {я.time_left:F1})");
            if (Положения.Героя(h, я, ручки) != Положение.БЕЗ_СОЗНАНИЯ)
                плохо.Add($"избили до беспамятства, а положение {Положения.Героя(h, я, ручки)}");
            снова_итог += $"; третий раз — {Положения.Героя(h, я, ручки)}";
        }
        else
            плохо.Add("за двести взломов после двух поимок героя не застали ни разу");

        w($"  слышат: в первые дни {рано.слышали} ушей на {СЕРИЯ} взломов, "
          + $"в буран {буран.слышали}, в пустом доме {пусто.слышали}, гараж {гараж.слышали}");
        w($"  спускаются: первые дни {рано.застали} из {СЕРИЯ}, одичавший дом {поздно.застали}, "
          + $"после поимки {помнят.застали}, стук уже слышали {настороже.застали}");
        w($"  поимка: {поимка_итог}");
        w($"  снова: {снова_итог}");
        return плохо;
    }
}
