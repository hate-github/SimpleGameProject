// Проверка сервисов до метели (просьба автора: микрозайм или кредит, чтобы
// деньги получить быстро, и доставка еды — только до метели;
// `Дом.Ядро/Петля/Сервисы.cs`, `data/сервисы.json`).
//
//  1. **Данные.** Читаются; блюда меню — продукты из еда.json; в газировке
//     есть вода.
//  2. **Микрозайм.** Одобрили — деньги на карте сразу, долг растёт по дням;
//     второй в ту же контору — нет; отказали — второй раз не подать;
//     на двухстах жизнях одобряют с тем шансом, что в данных.
//  3. **Кредит в банке.** Заявка — денег сразу нет; наутро решение:
//     одобрили — деньги, если банки живы; банки встали — денег нет.
//  4. **Доставка.** Заказ — с карты; час не настал — не привезли; героя
//     нет дома — ждёт; дома — вещи на полке, и число «еда» в шкафу выросло
//     ровно на их порции (закон полки); газировку пьют от жажды.
//  5. **Метель.** Всё встало: займ не взять, еду не заказать; заказ в пути
//     отменён, деньги вернулись; в день платежа — напоминание, один раз.
//  6. **Сохранение.** Долги, заявки и заказ переживают сейв; старый сейв
//     без сервисов читается.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Сервисы_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var еда = КаталогЕды.Прочитать(Пути.Данные);

        // ---- 1. данные ----
        var данные = ДанныеСервисов.Прочитать(Пути.Данные, еда);
        if (данные is null || еда is null)
        {
            плохо.Add("нет data/сервисы.json или data/еда.json");
            return плохо;
        }
        var мфо = данные.займы.First(з => з.сразу);
        var банк = данные.займы.First(з => !з.сразу);
        Блюдо Блюдо_(string id) => данные.меню.First(б => б.еда == id);
        if (!еда.Есть("газировка") || еда["газировка"].воды <= 0)
            плохо.Add("в газировке нет воды — пить её незачем");

        (House h, NPC я, Сервисы с, Продукты п) Жизнь(long зерно = 7)
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 3, журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л, еда: еда) { сервисы = данные }
                .Слушать(прогон, "оксана");
            var я = прогон.h.people["оксана"];
            return (прогон.h, я, Округа.У(прогон.h)!.сервисы!, Продукты.У(я)!);
        }

        // ---- 2. микрозайм ----
        {
            var (h, я, с, _) = Жизнь();
            // зерно, на котором одобряют
            int зерно = 0;
            while (зерно < 50 && Округа.Бросок(зерно, "займ:" + мфо.id, я.id, -2) >= мфо.одобрят)
                зерно++;
            с = new Сервисы(данные, зерно);
            double было = я.счёт, часов = я.time_left;
            var взял = с.Взять(я, мфо, -2, работают: true);
            if (!взял.да || Math.Abs(я.счёт - было - мфо.сумма) > 1e-9 || с.долги.Count != 1)
                плохо.Add($"микрозайм одобрен — а на карте {Текст.G(я.счёт - было)} (ждали {Текст.G(мфо.сумма)}), долгов {с.долги.Count}");
            if (Math.Abs(взял.часов - мфо.часов) > 1e-9 || Math.Abs(я.time_left - часов) > 1e-9)
                плохо.Add("заявка должна стоить часов, и проживает их зовущий, а не займ");
            var долг = с.долги[0];
            if (долг.Вернуть(долг.срок) <= долг.взял || долг.Вернуть(долг.срок) <= долг.Вернуть(долг.день + 1))
                плохо.Add("долг не растёт по дням");
            if (с.Нельзя(мфо, я, работают: true) is null)
                плохо.Add("второй микрозайм в ту же контору дают");
            // отказ: второй раз не подать
            int отказное = 0;
            while (отказное < 500 && Округа.Бросок(отказное, "займ:" + мфо.id, я.id, -2) < мфо.одобрят)
                отказное++;
            var с2 = new Сервисы(данные, отказное);
            double до_отказа = я.счёт;
            с2.Взять(я, мфо, -2, работают: true);
            if (Math.Abs(я.счёт - до_отказа) > 1e-9 || с2.долги.Count != 0 || с2.Нельзя(мфо, я, работают: true) is null)
                плохо.Add("отказали — а деньги пришли, долг появился или можно подать снова");
        }
        int одобрено = 0;
        {
            var (_, я, _, _) = Жизнь();
            for (int i = 0; i < 200; i++)
                if (Округа.Бросок(1000 + i, "займ:" + мфо.id, я.id, -2) < мфо.одобрят)
                    одобрено++;
            if (Math.Abs(одобрено / 200.0 - мфо.одобрят) > 0.08)
                плохо.Add($"микрозайм одобряют в {одобрено} из 200, а шанс в данных {Текст.G(мфо.одобрят)}");
        }

        // ---- 3. кредит в банке ----
        {
            var (h, я, _, _) = Жизнь();
            int да = 0;
            while (да < 50 && Округа.Бросок(да, "займ:" + банк.id, я.id, -2) >= банк.одобрят)
                да++;
            var с = new Сервисы(данные, да);
            double было = я.счёт;
            var заявка = с.Взять(я, банк, -2, работают: true);
            if (!заявка.да || Math.Abs(я.счёт - было) > 1e-9 || !с.Подана(банк.id))
                плохо.Add("банк: заявка подана — а деньги уже на карте (или заявки нет)");
            if (с.Утро(я, -2, банки: true).Count != 0 || Math.Abs(я.счёт - было) > 1e-9)
                плохо.Add("банк решил в тот же день — а должен к утру");
            var утро = с.Утро(я, -1, банки: true);
            if (Math.Abs(я.счёт - было - банк.сумма) > 1e-9 || с.долги.Count != 1 || утро.Count == 0)
                плохо.Add($"банк одобрил наутро — а на карте {Текст.G(я.счёт - было)}");
            // одобрили, а банки уже встали
            var с2 = new Сервисы(данные, да);
            с2.Взять(я, банк, -1, работают: true);
            double до = я.счёт;
            var поздно = с2.Утро(я, 0, банки: false);
            if (Math.Abs(я.счёт - до) > 1e-9 || с2.долги.Count != 0 || !поздно.Any(в => в.Contains("не работают", StringComparison.Ordinal)))
                плохо.Add("банк одобрил, когда банки уже встали, — а деньги пришли (или об этом молчат)");
        }

        // ---- 4. доставка ----
        string доставка_итог;
        {
            var (h, я, с, п) = Жизнь();
            я.счёт = 5.0;
            п.Сверить(h, я);            // шкаф — вещами, как на первом вопросе
            double Закон() => Math.Abs(п.Сумма(МестоЕды.ПОЛКА) - Продукты.Число(я, МестоЕды.ПОЛКА));
            if (Закон() > 1e-6)
                плохо.Add("закон полки не сошёлся ещё до доставки");
            double еды_было = я.stock.Взять("еда", 0.0);
            var пицца = Блюдо_("пицца");
            var газировка = Блюдо_("газировка");
            с.Заказать(h, я, пицца, работают: true, день: -2);
            с.Заказать(h, я, газировка, работают: true, день: -2);
            if (Math.Abs(я.счёт - (5.0 - пицца.цена - газировка.цена)) > 1e-9 || с.заказ?.еда.Count != 2)
                плохо.Add($"заказ: с карты ушло {Текст.G(5.0 - я.счёт)}, в пакете {с.заказ?.еда.Count ?? 0}");
            double к_часу = с.заказ!.к_часу;
            if (с.Привезти(я, к_часу - 0.1, дома: true, п) is not null)
                плохо.Add("привезли раньше, чем курьер доехал");
            if (с.Привезти(я, к_часу, дома: false, п) is not null || с.заказ is null)
                плохо.Add("героя нет дома — а пакет занесли на полку");
            var привезли = с.Привезти(я, к_часу + 0.5, дома: true, п);
            double порций = еда["пицца"].единиц + еда["газировка"].единиц;
            if (привезли?.Count != 2 || с.заказ is not null
                || Math.Abs(я.stock.Взять("еда", 0.0) - еды_было - порций) > 1e-9
                || !п.В(МестоЕды.ПОЛКА).Any(в => в.вид == "пицца"))
                плохо.Add($"дома — а привезли {привезли?.Count ?? 0}, еды в шкафу +{Текст.G(я.stock.Взять("еда", 0.0) - еды_было)} (ждали {Текст.G(порций)})");
            if (Закон() > 1e-6)
                плохо.Add($"после доставки закон полки разошёлся: вещей {Текст.G(п.Сумма(МестоЕды.ПОЛКА))}, в шкафу {Текст.G(Продукты.Число(я, МестоЕды.ПОЛКА))}");
            // газировку пьют от жажды — и сытому тоже
            я.satiety = 100;
            я.hydration = 40;
            var банка = п.В(МестоЕды.ПОЛКА).First(в => в.вид == "газировка");
            var выпил = п.Съесть(h, я, банка);
            if (я.hydration <= 40 + 1e-9 || выпил.единиц <= 0)
                плохо.Add($"газировку выпил — а жажда та же ({Текст.G(я.hydration)})");
            if (Закон() > 1e-6)
                плохо.Add("выпил газировку — закон полки разошёлся");
            доставка_итог = $"пицца и газировка — {Текст.G(пицца.цена + газировка.цена)} тыс., курьер к {ХодВремени.Часы(к_часу)}; "
                            + $"вода после газировки {Текст.G(Math.Round(я.hydration))}";
        }

        // ---- 5. метель ----
        {
            var (h, я, с, п) = Жизнь();
            if (с.Нельзя(мфо, я, работают: false) is null || с.Нельзя(Блюдо_("бургер"), h, я, работают: false) is null)
                плохо.Add("в метель займ ещё берут или еду ещё заказывают");
            я.счёт = 3.0;
            с.Заказать(h, я, Блюдо_("бургер"), работают: true, день: -1);
            if (с.Метель(я) is null || с.заказ is not null || Math.Abs(я.счёт - 3.0) > 1e-9)
                плохо.Add("пришла метель — а заказ всё едет (или деньги не вернулись)");
            int зерно = 0;
            while (зерно < 50 && Округа.Бросок(зерно, "займ:" + мфо.id, я.id, -2) >= мфо.одобрят)
                зерно++;
            var с2 = new Сервисы(данные, зерно);
            с2.Взять(я, мфо, -2, работают: true);
            int срок = с2.долги[0].срок;
            if (с2.Утро(я, срок - 1, false).Count != 0 || с2.Утро(я, срок, false).Count != 1 || с2.Утро(я, срок + 1, false).Count != 0)
                плохо.Add("напоминание о платеже — не ровно одно и не в день срока");
        }

        // ---- 6. сохранение ----
        {
            var (h, я, _, _) = Жизнь();
            int зерно = 0;
            while (зерно < 50 && Округа.Бросок(зерно, "займ:" + мфо.id, я.id, -2) >= мфо.одобрят)
                зерно++;
            var с = new Сервисы(данные, зерно);
            я.счёт = 60;
            с.Взять(я, мфо, -2, работают: true);
            с.Взять(я, банк, -2, работают: true);
            с.Заказать(h, я, Блюдо_("фри"), работают: true, день: -2);
            var о = System.Text.Json.Nodes.JsonNode.Parse(с.Сложить().ToJsonString())!.AsObject();
            var с2 = new Сервисы(данные, зерно);
            с2.Разложить(о);
            if (с2.долги.Count != 1 || !с2.Подана(банк.id) || с2.заказ?.еда.FirstOrDefault() != "фри")
                плохо.Add("после сейва забылись долг, заявка или заказ");
            var с3 = new Сервисы(данные, зерно);
            с3.Разложить(null);
            if (с3.долги.Count != 0 || с3.заказ is not null)
                плохо.Add("старый сейв без сервисов — а долги откуда-то есть");
        }

        w($"  займы: {string.Join("; ", данные.займы.Select(з => $"{з.имя} — {Текст.G(з.сумма)} тыс."))}; микрозайм одобрен в {одобрено} из 200");
        w($"  доставка: {доставка_итог}");
        return плохо;
    }
}
