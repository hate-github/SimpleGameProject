// Проверка портретов: лица соседей в окне разговора (`data/лица.json`,
// `Дом.Экран/Лица.cs`, картинки — `Дом.Годот/лица/NN.png`, окно —
// `ПортретUI` в `ВопросUI` и `ПоходUI`; просьба автора 01.10.2026).
//
//  1. **У каждого — своё лицо.** Каждый жилец дома и продавщица есть
//     в таблице; номер — ячейка сетки (от одного до шестнадцати), и одна
//     ячейка — одному человеку: два соседа с одним лицом путались бы.
//     Лишних в таблице нет — опечатка в имени оставила бы соседа без лица.
//  2. **Картинки лежат.** Все ячейки сетки нарезаны, и у каждого номера
//     из таблицы есть файл.
//  3. **Окна их показывают.** Вопрос с собеседником — лицом по `с_кем`;
//     беседы у двери, рассказ знатока и прилавок зовут окно с лицом.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Портреты_(Action<string> w)
    {
        var плохо = new List<string>();
        var лица = Лица.Прочитать(Пути.Данные);
        var h = new Прогон(Пути.Данные, seed: 1, days: 1, журнал: new Журнал(0, false, TextWriter.Null)).h;
        var кто = h.people.Ключи.Append("продавщица").ToList();

        // ---- 1. у каждого своё лицо ----
        foreach (var id in кто.Where(id => !лица.ContainsKey(id)))
            плохо.Add($"у «{id}» нет лица — окно разговора с ним будет без портрета");
        foreach (var id in лица.Keys.Where(id => !кто.Contains(id, StringComparer.Ordinal))
                                    .OrderBy(x => x, StringComparer.Ordinal))
            плохо.Add($"лицо есть у «{id}», а такого человека нет — опечатка в имени");
        foreach (var (id, номер) in лица.Where(п => п.Value < 1 || п.Value > Лица.ЯЧЕЕК))
            плохо.Add($"у «{id}» лицо №{номер}, а ячеек в сетке {Лица.ЯЧЕЕК}");
        foreach (var г in лица.GroupBy(п => п.Value).Where(г => г.Count() > 1))
            плохо.Add($"лицо №{г.Key} у двоих: {string.Join(" и ", г.Select(п => п.Key))}");

        // ---- 2. картинки лежат ----
        string папка = Path.Combine(Пути.Корень, "Дом.Годот", "лица");
        for (int n = 1; n <= Лица.ЯЧЕЕК; n++)
            if (!File.Exists(Path.Combine(папка, Лица.Файл(n))))
                плохо.Add($"ячейки {n} нет: лица/{Лица.Файл(n)} не нарезан");
        foreach (var (id, номер) in лица.Where(п => п.Value > Лица.ЯЧЕЕК))
            if (!File.Exists(Path.Combine(папка, Лица.Файл(номер))))
                плохо.Add($"у «{id}» лицо {Лица.Файл(номер)}, а файла нет");

        // ---- 3. окна их показывают ----
        string Код(string имя) => File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", имя + ".cs"));
        var узел = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            ["ВопросUI"] = Код("ВопросUI"),
            ["ПоходUI"] = Код("ПоходUI"),
            ["ДомУзел"] = Код("ДомУзел"),
        };
        foreach (var (где, текст, беда) in new (string, string, string)[]
        {
            ("ВопросUI", "_портрет.Показать(в.с_кем)", "вопрос соседа — без его лица"),
            ("ПоходUI", "Разговором(_портрет.Показать(лицо))", "окно с собеседником не становится разговором"),
            ("ДомУзел", "лицо: с.id);", "беседа у двери — без лица соседа"),
            ("ДомУзел", "лицо: с?.id);", "беседа в метель — без лица соседа"),
            ("ДомУзел", "лицо: р.кто);", "рассказ знатока — без его лица"),
            ("ДомУзел", "лицо: \"продавщица\");", "прилавок — без лица продавщицы"),
        })
            if (!узел[где].Contains(текст, StringComparison.Ordinal))
                плохо.Add($"{где}: {беда}");

        w($"  лиц в таблице {лица.Count} из {Лица.ЯЧЕЕК} ячеек; у {h.people.Count} жильцов и продавщицы — свои");
        return плохо;
    }
}
