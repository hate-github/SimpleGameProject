// Проверка продуктов (docs/ЕДА_ПЛАН.md, этап 1): еда героя — вещи,
// и в каждом месте — полка, ноша, карман — сумма вещей равна числу дома.
//
//  1. **Каталог.** Читается; у каждого продукта модель лежит в
//     `Дом.Годот/модели`; все пять «откуда» на месте.
//  2. **Сделать.** Целые — не больше заказанного, и недобор меньше самой
//     малой вещи; с куском — ровно столько.
//  3. **Сверка живой жизнью.** Герой живёт своим решающим пять дней,
//     и после каждого хода дома вещи сводятся с числами: закон держится
//     в трёх местах, дом ел — вещи снимались, запас «из дома» пришёл
//     первой сверкой.
//  4. **Ящик.** Еда из ящика — целые вещи на «еду» добычи, недобор
//     остался в кладовой; в сумку и в карман ложатся только целые,
//     каждая записана там, куда легло её число; не влезшее — в кладовой.
//  5. **Переезд.** Ноша разгрузилась у порога — на полке те же вещи,
//     по номерам, а не новые.
//  6. **Порча.** День дома на полке — день, в кармане — четверть;
//     хлеб за сроком в плесени; открытая банка портится своими днями.
//  7. **Съесть.** Сытость — порция × порции вещи; сытому не лезет;
//     больше, чем лезет, — банка початая; число места убыло ровно
//     на съеденное.
//  8. **Сохранение.** Сложить → разложить → сложить — то же.
//  9. **Дом без игрока.** У соседей вещей нет; петля без каталога
//     вещей не заводит.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Продукты_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var еда = КаталогЕды.Прочитать(Пути.Данные);
        const string КТО = "оксана";
        if (еда is null)
        {
            плохо.Add("нет data/еда.json — еда героя не вещи");
            return плохо;
        }

        (Прогон прогон, NPC я, Продукты п) Жизнь(long зерно = 5, int дней = 1)
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: дней,
                                    журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки, еда: еда).Слушать(прогон, КТО);
            var я = прогон.h.people[КТО];
            return (прогон, я, Продукты.У(я)!);
        }

        // закон: в каждом месте сумма вещей — число дома
        string? Закон(Продукты п, NPC я)
        {
            foreach (var м in Продукты.МЕСТА)
            {
                double вещей = п.Сумма(м), числом = Продукты.Число(я, м);
                if (Math.Abs(вещей - числом) > 1e-5)
                    return $"{м}: вещей на {Текст.Ф(вещей, 3)}, а у дома {Текст.Ф(числом, 3)}";
                if (п.В(м).Any(x => x.единиц <= 0))
                    return $"{м}: вещь в ноль порций";
            }
            return null;
        }

        // ---- 1. каталог ----
        string корень_движка = Path.Combine(Пути.Корень, "Дом.Годот");
        foreach (var в in еда.виды)
        {
            string файл = Path.Combine(корень_движка, в.модель.Replace("res://", "").Replace('/', Path.DirectorySeparatorChar));
            if (!File.Exists(файл))
                плохо.Add($"{в.имя}: модели {в.модель} нет");
            if (в.род == РодЕды.БАНКА && в.открытая_дней <= 0)
                плохо.Add($"{в.имя}: открытая банка живёт {в.открытая_дней} дней");
        }
        foreach (string о in Продукты.ОТКУДА)
            if (еда.Откуда(о).Count == 0)
                плохо.Add($"еда ниоткуда: «{о}» пуст");

        // ---- 2. сделать ----
        {
            var (_, _, п) = Жизнь();
            double малая = еда.виды.Min(в => в.единиц);
            foreach (double сколько in new[] { 0.3, 1.0, 2.6, 5.0, 7.3 })
                foreach (string о in Продукты.ОТКУДА)
                {
                    var целые = п.Сделать(о, сколько, целые_только: true);
                    double вышло = целые.Sum(x => x.единиц);
                    if (вышло > сколько + 1e-9 || сколько - вышло >= малая - 1e-9 && сколько >= малая)
                        плохо.Add($"«{о}», {Текст.G(сколько)}: целых на {Текст.Ф(вышло, 2)} — перебор или недобор больше малой вещи");
                    if (целые.Any(x => Math.Abs(x.единиц - п.Вид(x).единиц) > 1e-9))
                        плохо.Add($"«{о}»: среди целых — кусок");
                    var с_куском = п.Сделать(о, сколько, целые_только: false);
                    if (Math.Abs(с_куском.Sum(x => x.единиц) - сколько) > 1e-9)
                        плохо.Add($"«{о}», {Текст.G(сколько)}: с куском вышло {Текст.Ф(с_куском.Sum(x => x.единиц), 3)}");
                }
        }

        // ---- 3. сверка живой жизнью ----
        string жизнь_итог;
        {
            var (прогон, я, п) = Жизнь(зерно: 11, дней: 5);
            int сверок = 0, снимало = 0;
            string? первая_беда = null;
            double принесено = 0;
            void Свести(House h)
            {
                double до = Продукты.МЕСТА.Sum(м => п.Сумма(м));
                принесено += п.Сверить(h, я);
                сверок++;
                if (Продукты.МЕСТА.Sum(м => п.Сумма(м)) < до - 1e-9)
                    снимало++;
                if (первая_беда is null && Закон(п, я) is string беда)
                    первая_беда = $"день {h.day}: {беда}";
            }
            прогон.h.hooks.after_execute.Add((h, _, _, _, _, _) => Свести(h));
            прогон.h.hooks.on_day.Add(Свести);
            прогон.run();
            int было_вещей = п.В(МестоЕды.ПОЛКА).Count;
            if (первая_беда is not null)
                плохо.Add($"живая жизнь: закон разошёлся — {первая_беда}");
            if (снимало == 0)
                плохо.Add("за пять дней дом ни разу не снял вещей — ел ли герой? сверка не про что");
            if (принесено < 1.0)
                плохо.Add("запас «из дома» не пришёл вещами на первой сверке");
            жизнь_итог = $"{сверок} сверок за пять дней, вещи снимались {снимало} раз, "
                         + $"принесено домом {Текст.Ф(принесено, 1)} порций, на полке к концу {было_вещей} вещей";
        }

        // ---- 4. ящик ----
        string ящик_итог;
        {
            var большая = Тары.ВСЕ.OrderByDescending(т => т.мест(ручки)).First();
            int вещей = 0, не_влезло = 0;
            double недобор = 0;
            for (int раз = 0; раз < 20; раз++)
            {
                var (прогон, я, п) = Жизнь(зерно: 100 + раз);
                var h = прогон.h;
                var к = h.кладовые["гараж13"];
                к.stock.Очистить();
                к.stock["еда"] = 2.9 + раз * 0.37;
                к.stock["топливо"] = 2;
                п.Сверить(h, я);
                double всего = к.stock.Взять("еда", 0) + 0;
                var д = Обыск.коробка(h, я, к, 1, ручки);
                if (д.продукты is not { } найдено || найдено.Count == 0)
                {
                    плохо.Add($"ящик с едой {Текст.G(всего)} — а вещами ничего");
                    break;
                }
                double сумма = найдено.Sum(x => x.единиц);
                if (Math.Abs(сумма - д.вещи.Взять("еда", 0)) > 1e-9)
                    плохо.Add("вещи ящика не сходятся с его «едой»");
                if (найдено.Any(x => Math.Abs(x.единиц - п.Вид(x).единиц) > 1e-9))
                    плохо.Add("в ящике кусок, а не целая вещь");
                if (Math.Abs(к.stock.Взять("еда", 0) + сумма - всего) > 1e-9)
                    плохо.Add("недобор ящика пропал — а должен остаться в кладовой");
                недобор += к.stock.Взять("еда", 0);
                вещей += найдено.Count;
                // половина раз — в карман, половина — в сумку, заранее почти полную
                Тара? тара = раз % 2 == 0 ? null : большая;
                if (тара is Тара т)
                {
                    var почти = Словари.Числа();
                    почти["материалы"] = т.мест(ручки) - 1.5;
                    я.ноша!.Положить(т, почти, ручки);
                }
                double в_кладовой = к.stock.Взять("еда", 0);
                var взято = Обыск.унести(h, я, к, д, тара, ручки);
                if (Закон(п, я) is string беда)
                    плохо.Add($"после ящика {(тара is null ? "в карман" : "в сумку")}: {беда}");
                double легло = п.Сумма(тара is null ? МестоЕды.КАРМАН : МестоЕды.НОША);
                if (Math.Abs(легло - взято.Взять("еда", 0)) > 1e-9)
                    плохо.Add("унесено еды не столько, сколько легло вещей");
                if (Math.Abs(к.stock.Взять("еда", 0) - (в_кладовой + сумма - легло)) > 1e-9)
                    плохо.Add("не влезшая еда не вернулась в кладовую");
                if (легло < сумма - 1e-9)
                    не_влезло++;
            }
            if (не_влезло == 0)
                плохо.Add("ни разу не было, чтобы вещь не влезла, — путь «не влезло» не проверен");
            ящик_итог = $"20 ящиков: {вещей} вещей, недобор в кладовых {Текст.Ф(недобор, 2)}, не влезло в {не_влезло}";
        }

        // ---- 5. переезд ----
        {
            var (прогон, я, п) = Жизнь(зерно: 3);
            var h = прогон.h;
            п.Сверить(h, я);
            var к = h.кладовые["гараж13"];
            к.stock.Очистить();
            к.stock["еда"] = 4;
            var д = Обыск.коробка(h, я, к, 1, ручки);
            Обыск.унести(h, я, к, д, Тара.СУМКА, ручки);
            var номера = п.В(МестоЕды.НОША).Select(x => x.номер).OrderBy(x => x).ToList();
            я.ноша!.Разгрузить(я);
            п.Сверить(h, я);
            var на_полке = п.В(МестоЕды.ПОЛКА).Select(x => x.номер).ToHashSet();
            if (номера.Count == 0)
                плохо.Add("в сумке нет вещей — переезд не про что");
            else if (!номера.All(на_полке.Contains))
                плохо.Add("разгрузили сумку — а на полке не те банки, а новые");
            if (п.В(МестоЕды.НОША).Count > 0 || Закон(п, я) is not null)
                плохо.Add($"после разгрузки: {Закон(п, я) ?? "в ноше остались вещи"}");
        }

        // ---- 6. порча ----
        string порча_итог;
        {
            var (прогон, я, п) = Жизнь(зерно: 4);
            var h = прогон.h;
            я.stock["еда"] = 0;
            п.Сверить(h, я);
            var батон = еда.виды.First(в => в.род == РодЕды.ХЛЕБ);
            var банка = еда.виды.First(в => в.род == РодЕды.БАНКА);
            var хлеб = new Продукт(9001, батон.id, батон.единиц, 0);
            var в_кармане = new Продукт(9002, батон.id, батон.единиц, 0);
            var открытая = new Продукт(9003, банка.id, банка.единиц, 0, открыта: 0);
            п.Положить(МестоЕды.ПОЛКА, хлеб);
            п.Положить(МестоЕды.ПОЛКА, открытая);
            п.Положить(МестоЕды.КАРМАН, в_кармане);
            п.Состарить(h.day);
            int дней = (int)Math.Ceiling(батон.годна_дней) + 1;
            п.Состарить(h.day + дней);
            if (Math.Abs(хлеб.возраст - дней) > 1e-9 || Math.Abs(в_кармане.возраст - дней * еда.карман_время) > 1e-9)
                плохо.Add($"за {дней} дней хлеб на полке постарел на {Текст.G(хлеб.возраст)}, в кармане — на {Текст.G(в_кармане.возраст)}");
            if (п.Свежесть(хлеб) != Свежесть.ИСПОРЧЕНА)
                плохо.Add("хлеб за сроком — а не в плесени");
            if (п.Свежесть(в_кармане) != Свежесть.СВЕЖАЯ)
                плохо.Add("хлеб в кармане вне времени испортился так же быстро, как на полке");
            if (дней > банка.открытая_дней && п.Свежесть(открытая) != Свежесть.ИСПОРЧЕНА)
                плохо.Add("открытая банка стоит дольше своего — а не испорчена");
            var закрытая = new Продукт(9004, банка.id, банка.единиц, банка.годна_дней + 1);
            if (п.Свежесть(закрытая) != Свежесть.ПРОСРОЧЕНА)
                плохо.Add("закрытая банка старше срока — а не просрочена");
            порча_итог = $"{дней} дней: хлеб на полке {Текст.G(хлеб.возраст)} дн (плесень), в кармане {Текст.G(в_кармане.возраст)} дн (свежий)";
        }

        // ---- 7. съесть ----
        string съесть_итог;
        {
            var (прогон, я, п) = Жизнь(зерно: 6);
            var h = прогон.h;
            я.stock["еда"] = 0;
            п.Сверить(h, я);
            var банка = еда.виды.First(в => в.род == РодЕды.БАНКА && Math.Abs(в.единиц - 1.0) < 1e-9);
            var б = new Продукт(9101, банка.id, банка.единиц, 0);
            п.Положить(МестоЕды.ПОЛКА, б);
            я.stock["еда"] = банка.единиц;
            double порция = Действия.порция(h, я, h.B);
            // голодный: съедает целиком
            я.satiety = 10;
            var с1 = п.Съесть(h, я, б);
            if (с1.почему is not null || Math.Abs(с1.единиц - банка.единиц) > 1e-9
                || Math.Abs(я.satiety - (10 + порция * банка.единиц)) > 1e-6 && !с1.отравился)
                плохо.Add($"голодный съел {Текст.G(с1.единиц)} порций, сытость {Текст.Ф(я.satiety, 1)} — а должна {Текст.Ф(10 + порция * банка.единиц, 1)}");
            if (п.Где(б) is not null || я.stock.Взять("еда", 0) > 1e-9)
                плохо.Add("пустая банка осталась на полке или число не убыло");
            // почти сытый: половина лезет — банка початая
            var б2 = new Продукт(9102, банка.id, банка.единиц, 0);
            п.Положить(МестоЕды.ПОЛКА, б2);
            я.stock["еда"] = банка.единиц;
            я.satiety = 100 - порция * 0.5;
            var с2 = п.Съесть(h, я, б2);
            if (Math.Abs(с2.единиц - 0.5) > 1e-6 || !б2.открыт || Math.Abs(п.Доля(б2) - 0.5) > 1e-6)
                плохо.Add($"влезала половина — съедено {Текст.G(Текст.Округлить(с2.единиц, 3))}, банка {(б2.открыт ? "открыта" : "закрыта")}, доля {Текст.Ф(п.Доля(б2), 2)}");
            if (Закон(п, я) is string беда)
                плохо.Add($"после еды: {беда}");
            var с3 = п.Съесть(h, я, б2);
            if (с3.почему is null)
                плохо.Add("сытый съел ещё — «не лезет» не сработало");
            // испорченное: из ста — хоть раз отравился, и сытости тогда меньше
            int отравлений = 0;
            for (int i = 0; i < 100; i++)
            {
                var гниль = new Продукт(9200 + i, банка.id, банка.единиц, 0, открыта: банка.открытая_дней + 5);
                п.Положить(МестоЕды.ПОЛКА, гниль);
                я.stock["еда"] = я.stock.Взять("еда", 0) + банка.единиц;
                я.satiety = 0;
                if (п.Съесть(h, я, гниль).отравился)
                    отравлений++;
            }
            if (отравлений == 0 || отравлений == 100)
                плохо.Add($"испорченное: отравился {отравлений} раз из ста — шанса нет");
            съесть_итог = $"порция {Текст.G(порция)}; почти сытый — половина банки, банка початая; испорченное — отравился {отравлений} из 100";
        }

        // ---- 8. сохранение ----
        {
            var (прогон, я, п) = Жизнь(зерно: 8);
            п.Сверить(прогон.h, я);
            var снимок = п.Сложить().ToJsonString();
            var (прогон2, я2, п2) = Жизнь(зерно: 8);
            п2.Разложить(System.Text.Json.Nodes.JsonNode.Parse(снимок)!.AsObject());
            if (п2.Сложить().ToJsonString() != снимок)
                плохо.Add("продукты после сохранения другие");
            // и генератор продолжает ту же ленту
            var а = п.Сделать("гараж", 3.0, true).Select(x => x.вид);
            var б = п2.Сделать("гараж", 3.0, true).Select(x => x.вид);
            if (!а.SequenceEqual(б))
                плохо.Add("после сохранения ящики дают другие вещи — генератор не сохранён");
        }

        // ---- 9. дом без игрока ----
        {
            var (прогон, я, _) = Жизнь(зерно: 9);
            if (прогон.h.people.Значения.Any(p => p.id != я.id && Продукты.У(p) is not null))
                плохо.Add("у соседа завелись вещи — еда у соседей должна остаться числом");
            var прогон2 = new Прогон(Пути.Данные, seed: 9, days: 1, журнал: new Журнал(0, false, TextWriter.Null));
            new Дом.Ядро.Петля(new Наследие(), ручки).Слушать(прогон2, КТО);
            if (Продукты.У(прогон2.h.people[КТО]) is not null)
                плохо.Add("петля без каталога еды завела вещи");
        }

        w($"  жизнь: {жизнь_итог}");
        w($"  ящик: {ящик_итог}");
        w($"  порча: {порча_итог}");
        w($"  съесть: {съесть_итог}");
        return плохо;
    }
}
