// Проверка «без сознания» (`Дом.Экран/Беспамятство.cs`, движок —
// `ДомУзел.Беспамятство`): день для героя кончился — он не делает ничего сам,
// а дом отвечает за него молчанием.
//
//  1. **Полнота.** Каждый вопрос (`Вопрос`) — ровно в одном списке: день
//     и ночь, свои, «да или нет» с ответом молчания. Новый вопрос без
//     ответа краснеет, а не проскакивает мимо.
//  2. **Ответ — из тех, что есть.** Для каждого «да или нет» ответ молчания —
//     один из двух, которые ядро предлагает (сверка с исходником ядра).
//  3. **Выбор варианта** — по ключу, а не по месту: варианты идут по весу,
//     и «через дверь» бывает и первым, и вторым; не открыл, сдался, ночью
//     спал; день — не отвечать, а прожить шаг; своё — лучшим.
//  4. **Узел.** Ответ дому с клавиш и из телефона начинается с отказа без
//     сознания, карман без сознания не открывается, промотка зовётся каждый кадр.

using System.Text.RegularExpressions;
using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Беспамятство_(Action<string> w)
    {
        var плохо = new List<string>();

        // ---- 1. полнота ----
        foreach (var вопрос in Enum.GetValues<Вопрос>())
        {
            int где = (Беспамятство.ДЕНЬ_И_НОЧЬ.Contains(вопрос) ? 1 : 0)
                      + (Беспамятство.СВОИ.Contains(вопрос) ? 1 : 0)
                      + (Беспамятство.ТИХО.ContainsKey(вопрос) ? 1 : 0);
            if (где != 1)
                плохо.Add(где == 0
                    ? $"вопрос {вопрос}: без сознания на него ответа нет"
                    : $"вопрос {вопрос}: стоит в двух списках разом");
        }

        // ---- 2. ответ — из тех, что предлагает ядро ----
        var ядро = string.Join("\n", Directory.GetFiles(Path.Combine(Пути.Корень, "Дом.Ядро"), "*.cs",
                                                         SearchOption.AllDirectories)
                                              .Select(File.ReadAllText));
        int сверено = 0;
        foreach (var (вопрос, ответ) in Беспамятство.ТИХО)
        {
            var пары = Regex.Matches(ядро, @"Вопрос\." + вопрос + @"\b\s*,\s*""([^""]*)""\s*,\s*""([^""]*)""")
                            .Select(м => (м.Groups[1].Value, м.Groups[2].Value)).ToList();
            if (пары.Count == 0)
            {
                плохо.Add($"вопрос {вопрос}: ядро его «да или нет» не задаёт — откуда ответ «{ответ}»?");
                continue;
            }
            сверено++;
            foreach (var (да, нет) in пары.Distinct())
                if (ответ != да && ответ != нет)
                    плохо.Add($"вопрос {вопрос}: без сознания «{ответ}», а ядро спрашивает «{да}» или «{нет}»");
        }

        // ---- 3. выбор варианта ----
        ВопросИгроку В(Вопрос вопрос, params (string ключ, double вес)[] варианты)
            => new(1, Герой.ID, вопрос, "",
                   варианты.Select(v => new ВариантИгроку(v.ключ, v.вес, v.ключ)).ToList(), null, null);
        string Ключ(ВопросИгроку в) => Беспамятство.Ответ(в) is var i and >= 0 ? в.варианты[i].ключ : "(шаг дня)";
        var случаи = new (ВопросИгроку в, string ждём)[]
        {
            (В(Вопрос.ОТКРЫТЬ_ДВЕРЬ, ("открыть", 1.0), ("через дверь", 0.0)), "через дверь"),
            (В(Вопрос.ОТКРЫТЬ_ДВЕРЬ, ("через дверь", 1.0), ("открыть", 0.0)), "через дверь"),
            (В(Вопрос.ВПУСТИТЬ_МЕДИКА, ("впустить", 2.0), ("не впустить", 0.0)), "не впустить"),
            (В(Вопрос.СДАТЬСЯ, ("драться", 1.0), ("сдаться", 0.0)), "сдаться"),
            (В(Вопрос.КРИЧАТЬ, ("кричать", 3.0), ("молчать", 0.0)), "молчать"),
            (В(Вопрос.НОЧЬ, ("дежурить", 2.0), ("спать", 1.0), ("уйти", 0.5)), "спать"),
            (В(Вопрос.ЧТО_ДЕЛАТЬ, ("лечить", 5.0), ("поесть", 3.0)), "(шаг дня)"),
            (В(Вопрос.ЗА_ЧТО_ВЗЯТЬСЯ, ("а", 1.0), ("б", 4.0), ("в", 2.0)), "б"),
        };
        foreach (var (в, ждём) in случаи)
            if (Ключ(в) != ждём)
                плохо.Add($"без сознания на {в.вопрос} ({string.Join(", ", в.варианты.Select(v => v.ключ))}) — «{Ключ(в)}», а надо «{ждём}»");

        // ---- 4. узел ----
        string узел = File.ReadAllText(Path.Combine(Пути.Корень, "Дом.Годот", "ДомУзел.cs"));
        var ответить = Regex.Match(узел, @"private void Ответить\(int номер, bool играть\)\s*\{\s*([^\n]*)");
        if (!ответить.Success || !ответить.Groups[1].Value.Contains("Без_сознания_молчит()", StringComparison.Ordinal))
            плохо.Add("ДомУзел.Ответить начинается не с отказа без сознания — с клавиш герой ответит дому");
        var карман = Regex.Match(узел, @"Клавиши\.КАРМАН\)\)\s*return \(\) =>\s*\{\s*([^\n]*)");
        if (!карман.Success || !карман.Groups[1].Value.Contains("Без_сознания_молчит()", StringComparison.Ordinal))
            плохо.Add("карман по клавише открывается и без сознания — съесть можно, не приходя в себя");
        if (!узел.Contains("Беспамятство_кадр();", StringComparison.Ordinal))
            плохо.Add("промотка без сознания не зовётся — день стоит, пока герой лежит");

        // ---- 5. день без сознания в живом доме ----
        // избит до беспамятства: за героя отвечает молчание, как в узле, —
        // день идёт шагами, ночью спит, наутро приходит в себя
        string день_итог = "—";
        {
            var ручки = РучкиПетли.Прочитать(Пути.Данные);
            var прогон = new Прогон(Пути.Данные, seed: 31, days: 3);
            using var партия = new Партия(прогон, "лида");
            var h = прогон.h;
            var я = партия.сеанс.я;
            партия.Начать();
            var в = партия.Дождаться();
            while (в is { вопрос: not Вопрос.ЧТО_ДЕЛАТЬ })
            {
                партия.Ответить(0);
                в = партия.Дождаться();
            }
            int день0 = в?.день ?? 0;
            я.без_сознания = день0;
            я.health = Math.Max(я.health, 60);
            int шагов = 0, ночью_спал = 0;
            var спросили = new SortedSet<string>(StringComparer.Ordinal);
            bool очнулся = false;
            while (в is not null && шагов < 800)
            {
                if (Положения.Героя(h, я, ручки) != Положение.БЕЗ_СОЗНАНИЯ)
                {
                    очнулся = в.день > день0;
                    if (!очнулся)
                        плохо.Add($"очнулся в тот же день ({в.день}), а день для него кончился");
                    break;
                }
                int номер = Беспамятство.Ответ(в);
                if (номер < 0)
                {
                    ХодВремени.Прожить(я, Math.Min(0.5, я.time_left));
                    if (!партия.Пропустить())
                    {
                        плохо.Add("без сознания: партия не пропустила вопрос дня");
                        break;
                    }
                }
                else
                {
                    спросили.Add($"{в.вопрос}→{в.варианты[номер].ключ}");
                    if (в.вопрос == Вопрос.НОЧЬ && в.варианты[номер].ключ == "спать")
                        ночью_спал++;
                    партия.Ответить(номер);
                }
                шагов++;
                в = партия.Дождаться();
            }
            if (!очнулся)
                плохо.Add($"без сознания {шагов} шагов, а утро так и не пришло");
            if (ночью_спал == 0)
                плохо.Add("без сознания ночь прошла не во сне");
            while (в is not null)
            {
                партия.Ответить(0);
                в = партия.Дождаться();
            }
            партия.Досидеть();
            день_итог = $"день {день0}: {шагов} шагов до утра, ночью спал {ночью_спал}; "
                        + $"спрашивали: {(спросили.Count == 0 ? "ничего, кроме ночи" : string.Join(", ", спросили))}";
        }

        w($"  вопросов {Enum.GetValues<Вопрос>().Length}: день и ночь {Беспамятство.ДЕНЬ_И_НОЧЬ.Count}, "
          + $"свои {Беспамятство.СВОИ.Count}, молчанием {Беспамятство.ТИХО.Count} (сверено с ядром {сверено}); "
          + $"случаев выбора {случаи.Length}");
        w($"  {день_итог}");
        return плохо;
    }
}
