// Проверка хода времени (`Дом.Ядро/Петля/ХодВремени.cs`, задание автора,
// пп. 24–25): время идёт само, а дом по-прежнему считает ходами.
//
//  1. **Темпы.** Обычно — минута дня за секунду (ГДД 3), в разговоре —
//     как в жизни, но не стоит; в кармане и меню — стоит; дело своё время
//     считает само и в долг не идёт. Накопленное отдаётся шагами.
//  2. **Дело.** Полтора часа дела — десять секунд шкалы (пример задания),
//     и дело дробится: молотком пять кусков, болторезом два, обыск одним.
//  3. **Стоя, герой проживает день.** Через партию: на каждом вопросе дня
//     герой проживает шаг, ничего не делая, и дом пропускает его ход.
//     Часы героя растут ровно на шаг, соседи между шагами ходят, и день
//     кончается ночью — от одного стояния, как в ГДД: «день без действий».
//  4. **Взлом кусками.** Шанс куска выбран так, чтобы стук за всё дело
//     слышали столько же, сколько при одном броске; но спускаются посреди
//     дела — на втором, третьем куске, — и часов тогда ушло меньше целого.
//  5. **Между кусками соседи живут.** Через партию: кусок — в дом, дом
//     пропускает ход героя, и соседи делают своё, пока шкала ждёт.

using Дом.Ядро;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> Время_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);

        // ---- 1. темпы ----
        string темпы_итог;
        {
            var ход = new ХодВремени(ручки);
            ход.Кадр(60.0, Темп.ОБЫЧНО);
            double обычно = ход.долг;
            ход.Кадр(60.0, Темп.РАЗГОВОР);
            double разговор = ход.долг - обычно;
            ход.Кадр(60.0, Темп.СТОИТ);
            double стоит = ход.долг - обычно - разговор;
            ход.Кадр(60.0, Темп.ДЕЛО);
            double дело = ход.долг - обычно - разговор - стоит;
            if (Math.Abs(обычно - 1.0) > 1e-9)
                плохо.Add($"минута стояния дала {Текст.Ф(обычно, 3)} ч дня, а по ГДД — час "
                          + "(минута дня за секунду)");
            if (разговор <= 0.0)
                плохо.Add("в разговоре время стоит — а должно идти медленно (задание, п. 24)");
            if (разговор >= обычно)
                плохо.Add($"в разговоре время идёт не медленнее обычного: {Текст.Ф(разговор, 4)} "
                          + $"против {Текст.Ф(обычно, 4)}");
            if (стоит != 0.0)
                плохо.Add($"в кармане и меню время идёт ({Текст.Ф(стоит, 4)} ч) — по ГДД 9 оно стоит");
            if (дело != 0.0)
                плохо.Add($"время дела ушло в долг ({Текст.Ф(дело, 4)} ч) — дело отдаёт часы кусками само");
            int шагов = 0;
            double всего = ход.долг;
            while (ход.Шаг() is double ш)
            {
                шагов++;
                if (Math.Abs(ш - ход.шаг) > 1e-12)
                    плохо.Add($"шаг отдал {ш} ч, а шаг — {ход.шаг}");
                if (шагов > 1000)
                    break;
            }
            int ждать = (int)Math.Floor(всего / ход.шаг + 1e-9);
            if (шагов != ждать)
                плохо.Add($"из {Текст.Ф(всего, 3)} ч отдано {шагов} шагов, а должно {ждать}");
            if (ход.долг < 0 || ход.долг >= ход.шаг)
                плохо.Add($"после шагов в долгу {Текст.Ф(ход.долг, 4)} ч — не остаток от шага");
            темпы_итог = $"минута: обычно {Текст.Ф(обычно * 60, 0)} мин дня, разговор "
                         + $"{Текст.Ф(разговор * 60, 1)} мин, карман 0; шаг {Текст.G(ход.шаг)} ч";
        }

        // ---- 2. дело ----
        string дело_итог;
        {
            double с = ХодВремени.Секунд_дела(ручки, 1.5);
            if (Math.Abs(с - 10.0) > 0.01)
                плохо.Add($"полтора часа дела — {Текст.Ф(с, 2)} с шкалы, а в примере задания 10");
            var к = new[] { (1.5, 5), (0.45, 2), (0.35, 1), (0.1, 1), (6.0, 5) };
            foreach (var (часы, надо) in к)
                if (ХодВремени.Кусков(ручки, часы) != надо)
                    плохо.Add($"дело в {Текст.G(часы)} ч дробится на {ХодВремени.Кусков(ручки, часы)} "
                              + $"кусков, а должно на {надо}");
            double быстрее = (1.5 / с) / new ХодВремени(ручки).Скорость(Темп.ОБЫЧНО);
            if (быстрее <= 1.0)
                плохо.Add("в деле время идёт не быстрее обычного — дело не ускоряет время");
            if (ХодВремени.Часы(14.0 + 5.0 / 60.0) != "14:05" || ХодВремени.Часы(24.5) != "00:30")
                плохо.Add($"часы пишутся «{ХодВремени.Часы(14.0 + 5.0 / 60.0)}» и "
                          + $"«{ХодВремени.Часы(24.5)}», а не «14:05» и «00:30»");
            дело_итог = $"полтора часа — {Текст.Ф(с, 1)} с, в {Текст.Ф(быстрее, 0)} раз быстрее "
                        + "обычного; кусков: молоток 5, болторез 2, обыск 1";
        }

        // ---- 3. стоя, герой проживает день ----
        string стоя_итог = "—";
        {
            var прогон = new Прогон(Пути.Данные, seed: 31, days: 2);
            using var партия = new Дом.Экран.Партия(прогон, "лида");
            var ход = new ХодВремени(ручки);
            var h = прогон.h;
            var я = партия.сеанс.я;
            партия.Начать();
            var в = партия.Дождаться();
            int день0 = -1, шагов = 0, с_соседями = 0, ходов = 0;
            bool день_кончился = false;
            while (в is not null && шагов < 400)
            {
                if (в.вопрос != Вопрос.ЧТО_ДЕЛАТЬ)
                {
                    партия.Ответить(0);           // окно — отвечаем первым, как игрок щелчком
                    в = партия.Дождаться();
                    continue;
                }
                if (день0 < 0)
                    день0 = в.день;
                if (в.день != день0)
                {
                    день_кончился = true;
                    break;
                }
                ход.Кадр(ход.шаг / ход.Скорость(Темп.ОБЫЧНО), Темп.ОБЫЧНО);
                if (ход.Шаг() is not double шаг)
                {
                    плохо.Add("за время шага долг не набрался на шаг");
                    break;
                }
                double ч0 = я.час(), т0 = я.time_left;
                int было = партия.сеанс.хроника.Подряд(в.день).Count;
                double прожито = ХодВремени.Прожить(я, шаг);
                if (Math.Abs(прожито - Math.Min(шаг, т0)) > 1e-12)
                    плохо.Add($"шаг прожил {прожито} ч из {шаг} при {т0} до ночи");
                if (!партия.Пропустить())
                {
                    плохо.Add("партия не пропустила ход на вопросе дня");
                    break;
                }
                шагов++;
                в = партия.Дождаться();
                int стало = партия.сеанс.хроника.Подряд(день0).Count;
                if (стало > было)
                {
                    с_соседями++;
                    ходов += стало - было;
                }
                if (в is { вопрос: Вопрос.ЧТО_ДЕЛАТЬ } && в.день == день0
                    && Math.Abs(я.час() - (ч0 + прожито)) > 1e-9)
                    плохо.Add($"после шага часы героя {Текст.Ф(я.час(), 2)}, "
                              + $"а должны {Текст.Ф(ч0 + прожито, 2)}");
            }
            if (!день_кончился)
                плохо.Add($"герой простоял {шагов} шагов, а день так и не кончился");
            if (с_соседями == 0)
                плохо.Add("пока герой стоял, соседи не сделали ни хода — время не шло");
            while (в is not null)
            {
                партия.Ответить(0);
                в = партия.Дождаться();
            }
            партия.Досидеть();
            стоя_итог = $"стоя, день кончился за {шагов} шагов; соседи ходили между "
                        + $"{с_соседями} из них ({ходов} ходов)";
        }

        // ---- 4. взлом кусками ----
        string куски_итог;
        {
            const int СЕРИЯ = 400;
            var молоток = Инструменты.Прочитать(Пути.Данные).все["молоток"];
            var приём = молоток.Берёт("навесной")!;
            static House Дом_(long зерно)
                => new Прогон(Пути.Данные, seed: зерно, days: 1,
                              журнал: new Журнал(1, false, TextWriter.Null)).h;
            (int ушей, int застали, int посреди, double часов_посреди) Серия(int кусков)
            {
                int ушей = 0, застали = 0, посреди = 0;
                double часов_посреди = 0.0;
                for (int i = 0; i < СЕРИЯ; i++)
                {
                    var h = Дом_(700 + i);
                    var я = h.people["оксана"];
                    var к = h.кладовые["погреб1"];
                    я.time_left = 16.0;
                    double всего = Взлом.часы(h, приём);
                    var слышали = new HashSet<string>(StringComparer.Ordinal);
                    for (int номер = 1; номер <= кусков; номер++)
                    {
                        var п = Взлом.кусок(h, я, к, ручки, молоток, приём, номер, кусков);
                        слышали.UnionWith(п.слышали ?? Array.Empty<string>());
                        if (Math.Abs(п.часы - всего / кусков) > 1e-9)
                            плохо.Add($"кусок {номер} из {кусков} занял {п.часы} ч, а должен {всего / кусков}");
                        if (п.идёт && номер == кусков)
                            плохо.Add("последний кусок сказал «идёт» — дело не кончилось бы никогда");
                        if (п.идёт && (п.удалась || п.травма is not null))
                            плохо.Add($"кусок {номер} из {кусков} уже решил замок — рано");
                        if (п.идёт && к.вскрыта)
                            плохо.Add($"замок сорван на {номер}-м куске из {кусков}");
                        if (!п.идёт)
                        {
                            ушей += слышали.Count;
                            if (п.застал is not null)
                            {
                                застали++;
                                if (номер < кусков)
                                {
                                    посреди++;
                                    часов_посреди += 16.0 - я.time_left;
                                    if (16.0 - я.time_left >= всего - 1e-9)
                                        плохо.Add("застали посреди дела, а часов ушло как за всё дело");
                                }
                            }
                            break;
                        }
                    }
                }
                return (ушей, застали, посреди, посреди == 0 ? 0.0 : часов_посреди / посреди);
            }
            var целиком = Серия(1);
            var кусками = Серия(ХодВремени.Кусков(ручки, 1.5));
            if (кусками.посреди == 0)
                плохо.Add($"за {СЕРИЯ} взломов кусками ни разу не спустились посреди дела — "
                          + "сосед ждёт конца полутора часов (задание, п. 24)");
            // Стук за всё дело слышат те же уши — шанс куска так и выбран
            // (посреди дела, правда, слушать перестают: застали — стучать
            // некому). И ловят так же часто: куски одного дела — один стук,
            // дом настораживается от дела к делу. Разница — только когда:
            // посреди дела, а не после всех полутора часов
            if (кусками.ушей > целиком.ушей * 1.15 + 20)
                плохо.Add($"кусками стук услышали {кусками.ушей} ушей на {СЕРИЯ} взломов, "
                          + $"целиком — {целиком.ушей}: шанс куска не поделён на куски");
            if (Math.Abs(кусками.застали - целиком.застали)
                > Math.Max(30, 0.25 * Math.Max(кусками.застали, целиком.застали)))
                плохо.Add($"кусками застали {кусками.застали} раз из {СЕРИЯ}, одним броском "
                          + $"{целиком.застали}: дробление дела само сменило, как часто ловят");
            куски_итог = $"ушей: целиком {целиком.ушей} на {СЕРИЯ}, кусками {кусками.ушей}; "
                         + $"застали {целиком.застали} и {кусками.застали}, из них посреди дела "
                         + $"{кусками.посреди} (в среднем через {Текст.Ф(кусками.часов_посреди, 1)} ч)";
        }

        // ---- 5. между кусками соседи живут ----
        string партия_итог = "—";
        {
            var прогон = new Прогон(Пути.Данные, seed: 23, days: 1);
            using var партия = new Дом.Экран.Партия(прогон, "оксана");
            var каталог = Инструменты.Прочитать(Пути.Данные);
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог).Слушать(прогон, "оксана");
            var h = прогон.h;
            var я = партия.сеанс.я;
            партия.Начать();
            var в = партия.Дождаться();
            while (в is not null && в.вопрос != Вопрос.ЧТО_ДЕЛАТЬ)
            {
                партия.Ответить(0);
                в = партия.Дождаться();
            }
            if (в is null)
                плохо.Add("за день партия ни разу не спросила, что делать");
            else
            {
                я.снаряжение!.Взять("молоток");
                var к = h.кладовые.Значения.First(x => x.вид == ВидКладовой.ПОГРЕБ
                                                         && !h.есть_ключ(я, x));
                var (и, п) = Взлом.чем(я, к, каталог)!.Value;
                int кусков = ХодВремени.Кусков(ручки, Взлом.часы(h, п));
                int отдано = 0, с_соседями = 0;
                string конец = "дело не кончилось";
                for (int номер = 1; номер <= кусков && в is { вопрос: Вопрос.ЧТО_ДЕЛАТЬ }; номер++)
                {
                    int день = в.день;
                    int было = партия.сеанс.хроника.Подряд(день).Count;
                    double ч0 = я.час();
                    var кусок = Взлом.кусок(h, я, к, ручки, и, п, номер, кусков);
                    отдано++;
                    if (!партия.Пропустить())
                    {
                        плохо.Add("кусок взлома — а партия не пропустила ход");
                        break;
                    }
                    в = партия.Дождаться();
                    if (партия.сеанс.хроника.Подряд(день).Count > было)
                        с_соседями++;
                    if (кусок.застал is not null)
                    {
                        конец = $"застали на {номер}-м куске";
                        break;
                    }
                    if (!кусок.идёт)
                    {
                        конец = кусок.удалась ? "замок сорван" : "замок не поддался";
                        break;
                    }
                    // между кусками дом может спросить своё — ответ, и дело ждёт
                    while (в is not null && в.вопрос != Вопрос.ЧТО_ДЕЛАТЬ && в.день == день)
                    {
                        партия.Ответить(0);
                        в = партия.Дождаться();
                    }
                    if (в is { вопрос: Вопрос.ЧТО_ДЕЛАТЬ } && в.день == день
                        && я.час() < ч0 + кусок.часы - 1e-9)
                        плохо.Add($"после куска часы героя {Текст.Ф(я.час(), 2)}, а кусок стоил "
                                  + $"{Текст.Ф(кусок.часы, 2)} ч с {Текст.Ф(ч0, 2)}");
                }
                if (с_соседями == 0)
                    плохо.Add($"за {отдано} кусков взлома соседи не сделали ни хода — "
                              + "дом не жил, пока герой возился с замком");
                партия_итог = $"{отдано} кусков из {кусков}, соседи ходили после {с_соседями}; {конец}";
            }
            while (в is not null)
            {
                партия.Ответить(0);
                в = партия.Дождаться();
            }
            партия.Досидеть();
        }

        w($"  темпы: {темпы_итог}");
        w($"  дело: {дело_итог}");
        w($"  стоя: {стоя_итог}");
        w($"  взлом кусками: {куски_итог}");
        w($"  через партию: {партия_итог}");
        return плохо;
    }
}
