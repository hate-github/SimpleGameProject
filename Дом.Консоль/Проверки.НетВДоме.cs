// Проверка «нет в доме» (замечание автора: «нажал жить по распорядку
// у койки в участке — и меня позвали на рейд, хотя сосед физически
// не мог со мной поговорить; они вообще обо мне могут забыть дню к 10
// и просто взломать дверь, потому что она пустует»; `NPC.нет_в_доме`,
// `Округа.Пустая_квартира`).
//
//  1. **Кого нет в доме, того не спрашивают.** Дома — зовут в налёт, к чужой
//     двери на помощь, на собрание; ночью есть из чего выбрать. В участке
//     или во дворе — ни одного такого вопроса, а ночью — только «спать».
//     Его квартиру не осаждают; вор, у которого не вышло, никого
//     не будит; пропажу он замечает, вернувшись. Ход героя не делает его
//     «дома», а ночь снимает «не в подъезде».
//  2. **Пустая квартира.** Ночует не дома «дней» ночей подряд — квартиру
//     вскрывают: доля шкафа у вора, замок сорван, пропажа ждёт героя;
//     раньше срока — нет; вернулся к дому — счёт заново; боятся — не лезут.
//     Сейв помнит.

using Дом.Ядро;
using Дом.Экран;

namespace Дом.Консоль;

public static partial class Проверки
{
    public static List<string> НетВДоме_(Action<string> w)
    {
        var плохо = new List<string>();
        var ручки = РучкиПетли.Прочитать(Пути.Данные);
        var каталог = Дом.Ядро.Инструменты.Прочитать(Пути.Данные);
        var л = Летопись.Прочитать(Пути.Данные);
        var профиль = new ПрофильГероя("Андрей");
        var спросили = new List<ВопросИгроку>();
        (House h, NPC я, Округа о) Жизнь(long зерно = 7)
        {
            var прогон = new Прогон(Пути.Данные, seed: зерно, days: 40,
                                    журнал: new Журнал(0, false, TextWriter.Null),
                                    жильцы: npcs => Герой.Заселить(npcs, профиль, Пути.Данные));
            new Дом.Ядро.Петля(new Наследие(), ручки, инструменты: каталог, летопись: л).Слушать(прогон, Герой.ID);
            прогон.h.day = 3;
            var я = прогон.h.people[Герой.ID];
            // «человек» отвечает первым вариантом и записывает, о чём спросили
            я.решающий = new Человек(в =>
            {
                спросили.Add(в);
                return 0;
            });
            return (прогон.h, я, Округа.У(прогон.h)!);
        }
        int Спросили(Вопрос в) => спросили.Count(x => x.вопрос == в);
        // три положения героя: дома, во дворе (движок: не в подъезде), в участке (приют)
        var где = new (string имя, Action<House, NPC, Округа> поставить)[]
        {
            ("дома", (_, я, _) => { я.вне_дома = false; я.приют = null; }),
            ("во дворе", (_, я, _) => { я.вне_дома = true; я.приют = null; }),
            ("в участке", (_, я, о) => { я.вне_дома = false; о.участок!.Пришёл(я); }),
        };

        // ---- 1. кого нет в доме, того не спрашивают ----
        var итоги = new List<string>();
        foreach (var (имя, поставить) in где)
        {
            var (h, я, о) = Жизнь();
            поставить(h, я, о);
            bool дома = имя == "дома";
            var чужие = h.others(я).Where(p => p.здесь()).OrderBy(p => p.id, StringComparer.Ordinal).ToList();
            var вожак = чужие[0];
            var жертва = чужие[1];
            // герою есть причина идти и выходить: зол на жертву и дружен с ней же — пусть решает сам
            я.hate[жертва.id] = 100;
            // налёт
            спросили.Clear();
            var (crew, отказали) = Конфликт.recruit(h, вожак, жертва);
            int в_налёт = Спросили(Вопрос.ПОЙТИ_В_НАЛЁТ);
            if (дома && в_налёт == 0)
                плохо.Add("дома, злой на жертву — а в налёт не позвали (проверка ни о чём)");
            if (!дома && (в_налёт > 0 || crew.Contains(я) || отказали.Contains(я)))
                плохо.Add($"{имя}: позвали в налёт — хотя поговорить с ним некому");
            // на помощь к чужой двери
            спросили.Clear();
            Конфликт.defenders_of(h, жертва, new HashSet<string>(StringComparer.Ordinal) { вожак.id });
            int к_двери = Спросили(Вопрос.ВЫЙТИ_К_ДВЕРИ);
            if (дома && к_двери == 0)
                плохо.Add("дома — а выйти на помощь к чужой двери не спросили (проверка ни о чём)");
            if (!дома && к_двери > 0)
                плохо.Add($"{имя}: позвали выйти к чужой двери на помощь");
            // собрание
            спросили.Clear();
            Площадка.провести(h, вожак);
            int на_собрание = Спросили(Вопрос.ВЫЙТИ_НА_СОБРАНИЕ) + Спросили(Вопрос.ГОЛОС_НА_СОБРАНИИ);
            if (дома && на_собрание == 0)
                плохо.Add("дома — а на собрание не позвали (проверка ни о чём)");
            if (!дома && на_собрание > 0)
                плохо.Add($"{имя}: позвали на собрание на площадке");
            // ночь: дома — есть из чего выбрать, не дома — только спать
            if (имя != "во дворе")          // ночью «во дворе» не бывает: ночь снимает его сама
            {
                спросили.Clear();
                я.panic = 100;               // дежурить есть зачем,
                я.normalcy = 0.0;            // и жизнь уже не похожа на прежнюю
                Ночью.решение(h, я);
                var ночь = спросили.LastOrDefault(x => x.вопрос == Вопрос.НОЧЬ);
                if (дома && (ночь is null || ночь.варианты.Count < 2))
                    плохо.Add("дома, в панике — а ночью выбирать не из чего (проверка ни о чём): "
                              + string.Join(", ", ночь?.варианты.Select(x => x.ключ) ?? Array.Empty<string>()));
                if (!дома && ночь is not null && ночь.варианты.Any(x => x.ключ != "спать"))
                    плохо.Add($"{имя}: ночью предлагают не только спать: {string.Join(", ", ночь.варианты.Select(x => x.ключ))}");
            }
            итоги.Add($"{имя}: в налёт {в_налёт}, к двери {к_двери}, на собрание {на_собрание}");
        }

        // квартиру отсутствующего не осаждают
        {
            var (h, я, о) = Жизнь();
            var налётчик = h.others(я).Where(p => p.здесь()).OrderBy(p => p.id, StringComparer.Ordinal).First();
            налётчик.normalcy = 0;
            налётчик.panic = 100;
            налётчик.stock["еда"] = 0;
            foreach (var t in h.others(налётчик))
            {
                налётчик.hate[t.id] = 0;
                Социальное.adjust(налётчик, t.id, aware: -100);
            }
            налётчик.hate[я.id] = 100;
            Социальное.adjust(налётчик, я.id, aware: 100);
            я.stock["еда"] = 40;
            var цель_дома = Ночью.consider_raid(h, налётчик);
            о.участок!.Пришёл(я);
            var цель_без = Ночью.consider_raid(h, налётчик);
            if (!ReferenceEquals(цель_дома, я))
                плохо.Add($"налётчик зол на героя и голоден — а идёт не к нему ({цель_дома?.id ?? "никуда"}) (проверка ни о чём)");
            if (ReferenceEquals(цель_без, я))
                плохо.Add("герой в участке — а налёт собираются вести к его двери, за которой никого");
        }

        // вор у пустой квартиры никого не будит; пропажу хозяин заметит, вернувшись
        {
            var (h, я, о) = Жизнь();
            о.участок!.Пришёл(я);
            var вор = h.others(я).Where(p => p.здесь()).OrderBy(p => p.id, StringComparer.Ordinal).First();
            я.shelter["дверь"] = 3;
            я.weapon = Оружие.ПИСТОЛЕТ;
            я.stock["патроны"] = 5;
            int сорвалось = 0;
            спросили.Clear();
            for (int i = 0; i < 60; i++)
            {
                var (исход, _) = Конфликт.steal(h, вор, я);
                if (исход == Конфликт.ИсходКражи.СОРВАЛОСЬ)
                    сорвалось++;
                else if (исход != Конфликт.ИсходКражи.УСПЕХ)
                    плохо.Add($"вор у квартиры, где никого, — исход «{исход}»: его кто-то застал");
            }
            if (Спросили(Вопрос.ВЫЙТИ_СО_СТВОЛОМ) + Спросили(Вопрос.ДРАТЬСЯ_С_ВОРОМ) > 0)
                плохо.Add("герой в участке — а его спросили, выйти ли на вора у себя дома");
            if (сорвалось == 0)
                плохо.Add("шестьдесят краж у крепкой двери — и ни одна не сорвалась (ветка не пройдена)");
            h.ожидает.пропажи.Clear();
            h.ожидает.пропажи.Add((вор.id, я.id));
            Обнаружения.пропажи(h);
            if (!h.ожидает.пропажи.Contains((вор.id, я.id)))
                плохо.Add("герой в участке — а пропажу дома он «заметил» этим же утром");
            о.участок.Ушёл(я);
            Обнаружения.пропажи(h);
            if (h.ожидает.пропажи.Contains((вор.id, я.id)))
                плохо.Add("вернулся домой — а пропажа всё ждёт");
        }

        // утро не делает отсутствующего «дома» (замечание автора: «сплю
        // по распорядку в участке — а Марина стучит в мою дверь просить воды»):
        // утренний сброс `away` у всех, и до первого хода героя соседи,
        // вставшие раньше, считали его дома
        foreach (var (имя, в_участке) in new[] { ("дома", false), ("в участке", true) })
        {
            var (h, я, о) = Жизнь();
            if (в_участке)
                о.участок!.Пришёл(я);
            foreach (var p in h.alive())
                p.новый_день(h.B);              // утро — как в `Прогон._morning`
            int к_нему = 0;
            foreach (var сосед in h.others(я).Where(p => p.здесь()))
                к_нему += Действия.gather(h, сосед).варианты
                    .Count(в => ReferenceEquals(в.что.target, я) && в.что.key != "кража_днём");
            if (!в_участке && к_нему == 0)
                плохо.Add("утром дома — а к нему никто и не собирается (проверка ни о чём)");
            if (в_участке && (к_нему > 0 || !я.away))
                плохо.Add($"утро: герой в участке, а соседи собираются к его двери ({к_нему} мыслей; away — {я.away})");
            итоги.Add($"утром {имя}: мыслей соседей к его двери {к_нему}");
        }

        // ход героя не делает его «дома»; ночь снимает «не в подъезде»
        {
            var (h, я, _) = Жизнь();
            я.вне_дома = true;
            // на шаге времени движок отвечает «сам» — ход без дела дома;
            // первая мысль могла бы оказаться вылазкой, а та сама делает
            // «не дома» — и проверка шла бы ни о чём (порча это показала)
            я.решающий = new Человек(в => в.вопрос == Вопрос.ЧТО_ДЕЛАТЬ ? ВопросИгроку.САМ : 0);
            Действия.choose_and_do(h, я);
            if (!я.away)
                плохо.Add("герой во дворе сделал ход — и дом снова считает его дома");
            Ночью.ночь(h);
            if (я.вне_дома)
                плохо.Add("ночь пришла — а герой всё «не в подъезде»: ночью спят дома");
        }

        // ---- 2. пустая квартира ----
        string пустая_итог;
        var п = л.пустая_квартира;
        if (п is null)
        {
            плохо.Add("в мир.json нет «пустая_квартира»");
            пустая_итог = "—";
        }
        else
        {
            var (h, я, о) = Жизнь();
            о.участок!.Пришёл(я);
            foreach (var с in h.others(я))
                с.stock["еда"] = 0;                    // голодные — идут охотнее
            я.stock["еда"] = 20;
            я.stock["вода"] = 10;
            double еды = я.stock["еда"];
            int ночь = 3, вскрыли = -1;
            for (; ночь < 3 + п.дней + 10 && вскрыли < 0; ночь++)
            {
                h.day = ночь;
                о.Пустая_квартира(h, я);
                if (я.stock["еда"] < еды - 1e-9)
                    вскрыли = ночь;
            }
            if (вскрыли < 0)
                плохо.Add($"героя нет дома {п.дней + 10} ночей, соседи голодные — а квартиру так и не вскрыли");
            else if (вскрыли - 3 < п.дней)
                плохо.Add($"квартиру вскрыли на {вскрыли - 3}-ю ночь — раньше, чем через {п.дней}");
            var вынесли = о.Вынесли();
            if (вскрыли >= 0)
            {
                if (!h.where(я).открыта || !h.события.Any(с => с.вид == ВидСобытия.КРАЖА && с.кому == я.id && с.где == я.apt)
                    || Math.Abs(вынесли.Взять("еда", 0.0) - (еды - я.stock["еда"])) > 1e-9
                    || !h.ожидает.пропажи.Any(x => x.жертва == я.id))
                    плохо.Add("вскрыли — а замок цел, события нет, пропажа не ждёт героя или о вынесенном молчат");
                if (о.Вынесли().Count != 0)
                    плохо.Add("о вынесенном сказано дважды");
            }
            // вернулся к дому — счёт заново
            var у_дома = new Поход("проба", "проба", "участок", 1.0, "участок", null);
            о.Вернулся(h, я, у_дома);
            if (о.нет_с_дня is not null)
                плохо.Add("вернулся к дому — а соседи всё считают квартиру ничьей");
            // боятся героя — не лезут
            var (h2, я2, о2) = Жизнь(11);
            о2.участок!.Пришёл(я2);
            foreach (var с in h2.others(я2))
            {
                с.stock["еда"] = 0;
                с.страх[я2.id] = 100;
            }
            я2.stock["еда"] = 20;
            for (int д = 3; д < 3 + п.дней + 10; д++)
            {
                h2.day = д;
                о2.Пустая_квартира(h2, я2);
            }
            if (я2.stock["еда"] < 20 - 1e-9)
                плохо.Add("героя боятся все до смерти — а его квартиру всё равно вскрыли");
            // сейв помнит, с какой ночи его нет
            var (h3, я3, о3) = Жизнь(13);
            о3.участок!.Пришёл(я3);
            о3.Пустая_квартира(h3, я3);
            var сейв = System.Text.Json.Nodes.JsonNode.Parse(о3.Сложить().ToJsonString())!.AsObject();
            var (_, я4, о4) = Жизнь(13);
            о4.Разложить(сейв, я4);
            if (о4.нет_с_дня != о3.нет_с_дня)
                плохо.Add("после сейва забылось, с какой ночи героя нет дома");
            пустая_итог = вскрыли < 0 ? "не вскрыли"
                : $"вскрыли на {вскрыли - 3}-ю ночь без героя: вынесли {string.Join(", ", вынесли.Ключи.Select(к => $"{к} {Текст.G(вынесли[к])}"))}";
        }

        foreach (var с in итоги)
            w($"  {с}");
        w($"  пустая квартира: {пустая_итог}");
        return плохо;
    }
}
