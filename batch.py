# -*- coding: utf-8 -*-
"""Прогон многих жизней подряд — чтобы видеть не историю, а закономерность.

    python batch.py                    — 40 прогонов по 30 дней
    python batch.py --прогонов 200
    python batch.py --потоков 1        — в один поток (для отладки)

Одна история ничего не доказывает. Но и сто историй ничего не доказывают, если
смотреть на голое среднее, поэтому рядом с каждым числом стоит «±» — половина
95%-интервала. Если две настройки отличаются меньше чем на этот размах,
они не отличаются вовсе; чтобы сравнить их честно, есть `python ab.py`.
"""
import argparse
import sys
from collections import Counter

from house.runner import many, метрика, сводка, доля, впервые, причины


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--прогонов", type=int, default=40)
    ap.add_argument("--дней", type=int, default=30)
    ap.add_argument("--от", type=int, default=1)
    ap.add_argument("--потоков", type=int, default=None)
    ap.add_argument("--подробно", action="store_true")
    args = ap.parse_args()

    out = sys.stdout
    try:
        out.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

    runs = many(range(args.от, args.от + args.прогонов), days=args.дней, jobs=args.потоков)
    n = len(runs)

    print(f"ПРОГОНОВ: {n} по {args.дней} дней   (± — половина 95%-интервала)")
    print()

    surv = Counter(r["выжило"] for r in runs)
    m, ci = сводка(r["выжило"] for r in runs)
    print("Выжило человек из 6:")
    for k in range(7):
        print(f"  {k}: {surv.get(k, 0):>3}  " + "█" * surv.get(k, 0))
    print(f"  в среднем {m:.2f} ± {ci:.2f}")
    # ушедший не выжил и не погиб: дом не знает, дошёл он или замёрз
    mu, ciu = сводка(r.get("ушло", 0) for r in runs)
    print(f"  и ушли к пункту обогрева {mu:.2f} ± {ciu:.2f} — их нет ни в одной из двух колонок")
    print()

    who = Counter()
    for r in runs:
        for name in r["имена"]:
            who[name] += 1
    print("Кто доживает чаще (из 6 жильцов):")
    for name, c in who.most_common():
        print(f"  {name:<8} {100 * c / n:>5.0f}%")
    print()

    print("Судьба каждого (доля прогонов, где дожил / средний день смерти):")
    for name in runs[0]["судьбы"]:
        days = [r["судьбы"][name][0] for r in runs if r["судьбы"][name][0]]
        alive_share = 100.0 * (n - len(days)) / n
        cause = Counter(r["судьбы"][name][1] for r in runs if r["судьбы"][name][0]).most_common(1)
        хвост = ""
        if days:
            dm, dci = сводка(days)
            хвост = f", если нет — день {dm:.1f} ± {dci:.1f}, чаще всего «{cause[0][0]}»"
        print(f"  {name:<8} дожил {alive_share:>3.0f}%{хвост}")
    print()

    c = причины(runs)
    всего = max(1, sum(c.values()))
    print("Причины смерти:")
    for k, v in c.most_common():
        print(f"  {k:<28} {v:>4}  ({100 * v / всего:.0f}%)")
    print()

    print("Что рождает система (доля прогонов, где случилось хоть раз):")
    for key, label in [("краж", "кража"), ("налётов", "осада"), ("убийств", "убийство"),
                       ("союзов_заключено", "союз"), ("изгнаний", "изгнание"),
                       ("отъёмов", "отъём на лестнице"),
                       ("ложных_обвинений", "ложное обвинение"), ("детей_брошено", "ребёнок брошен"),
                       ("предательств", "предательство союзника"), ("переездов", "переезд к соседу"),
                       ("людоедство", "дошли до тела"), ("раскрытых_людоедов", "дом узнал"),
                       ("тел_вынесено", "тело вынесли во двор"),
               ("ушедших", "ушёл к пункту обогрева"),
               ("возвратов_с_полпути", "повернул с полпути"),
               ("смертей_от_угара", "угорел во сне"),
               ("тел_найдено", "нашёл тело соседа"),
               ("подозрений_в_убийстве", "не поверил известию о смерти")]:
        m, ci = сводка(метрика(runs, key))
        print(f"  {label:<24} {доля(runs, key):>5.0f}%   за прогон {m:.1f} ± {ci:.1f}")
    print()

    print("Когда это случается впервые:")
    for key, label in [("первая_кража_день", "первая кража"), ("первый_налёт_день", "первая осада"),
                       ("первая_смерть_день", "первая смерть"), ("первый_союз_день", "первый союз"),
                       ("первая_попытка_уйти", "первая попытка уйти")]:
        (m, ci), сколько = впервые(runs, key)
        if m is None:
            print(f"  {label:<16} не случается")
        else:
            print(f"  {label:<16} день {m:.1f} ± {ci:.1f}   (в {100 * сколько / n:.0f}% прогонов)")
    print()

    print("Чем кончаются осады (GDD 16 называет шесть исходов):")
    осад = sum(метрика(runs, "налётов"))
    for k in ("откупился", "переубедил", "отбился", "ограблен", "сбежал", "изгнан", "убит"):
        v = sum(метрика(runs, "исход_" + k))
        метка = "" if k != "переубедил" else "   (этого исхода в GDD нет — нашёлся сам)"
        print(f"  {k:<12} {v:>4}  ({100 * v / max(1, осад):>3.0f}%){метка}")
    print()

    print("Экономика:")
    for res in ("еда", "топливо", "материалы"):
        m, ci = сводка(метрика(runs, "принесено_" + res))
        u, _ = сводка(метрика(runs, "израсходовано_" + res))
        print(f"  {res:<10} принесено {m:>5.1f} ± {ci:<4.1f}  израсходовано {u:>5.1f}")
    m, ci = сводка(r["богатство"] for r in runs)
    print(f"  богатство района в конце {m:.2f} ± {ci:.2f} (стартовало с 1.00)")
    m, ci = сводка(r["паника"] for r in runs)
    print(f"  средняя паника выживших  {m:.0f} ± {ci:.0f}")

    нарушений = sum(len(r["нарушения"]) for r in runs)
    if нарушений:
        print()
        print(f"⚠ нарушений инвариантов: {нарушений} — запустите python check.py")

    if args.подробно:
        print()
        for r in runs:
            print(f"  зерно {r['зерно']:>4}: выжило {r['выжило']} ({', '.join(r['имена']) or '—'}), "
                  f"осад {r['stats'].get('налётов', 0)}, краж {r['stats'].get('краж', 0)}")


if __name__ == "__main__":
    main()
